#include <字元分類.h>

/* Single-byte C/POSIX locale; these are not Unicode character classifiers. */
int 檢查是否大寫字母(int 字元值) { return 字元值 >= 'A' && 字元值 <= 'Z'; }
int 檢查是否小寫字母(int 字元值) { return 字元值 >= 'a' && 字元值 <= 'z'; }
int 檢查是否字母(int 字元值) { return 檢查是否大寫字母(字元值) || 檢查是否小寫字母(字元值); }
int 檢查是否十進數字(int 字元值) { return 字元值 >= '0' && 字元值 <= '9'; }
int 檢查是否字母或數字(int 字元值) { return 檢查是否字母(字元值) || 檢查是否十進數字(字元值); }
int 檢查是否水平空白(int 字元值) { return 字元值 == ' ' || 字元值 == '\t'; }
int 檢查是否空白字元(int 字元值) { return 字元值 == ' ' || (字元值 >= '\t' && 字元值 <= '\r'); }
int 檢查是否控制字元(int 字元值) { return (字元值 >= 0 && 字元值 < 32) || 字元值 == 127; }
int 檢查是否可印字元(int 字元值) { return 字元值 >= 32 && 字元值 <= 126; }
int 檢查是否非空白可印字元(int 字元值) { return 字元值 >= 33 && 字元值 <= 126; }
int 檢查是否標點符號(int 字元值) { return 檢查是否非空白可印字元(字元值) && !檢查是否字母或數字(字元值); }
int 檢查是否十六進數字(int 字元值) { return 檢查是否十進數字(字元值) || (字元值 >= 'a' && 字元值 <= 'f') || (字元值 >= 'A' && 字元值 <= 'F'); }
int 轉換為小寫(int 字元值) { return 檢查是否大寫字母(字元值) ? 字元值 + ('a' - 'A') : 字元值; }
int 轉換為大寫(int 字元值) { return 檢查是否小寫字母(字元值) ? 字元值 - ('a' - 'A') : 字元值; }
