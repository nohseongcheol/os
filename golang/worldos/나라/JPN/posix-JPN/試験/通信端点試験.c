#include <通信番地/八桁組順序.h>
#include <誤り番号.h>
#include <体系/通信端点.h>
#include <入出力と実行.h>

static unsigned int 文字列長を得る(const char *検査資料)
{
    unsigned int 呼出種類 = 0;
    while (検査資料[呼出種類] != 0) 呼出種類++;
    return 呼出種類;
}

static void 電文を書く(const char *検査資料) { (void)書く(標準出力番号, 検査資料, 文字列長を得る(検査資料)); }

static void 結果を報告(const char *名前, int 検査合格)
{
    電文を書く(検査合格 ? "NTEST:PASS:" : "NTEST:FAIL:");
    電文を書く(名前);
    電文を書く("\n");
}

int main(void)
{
    struct 相互接続網端点番地 応答端点番地 = {0};
    struct 相互接続網端点番地 読出元 = {0};
    番地長型 送信元番地長 = sizeof(読出元);
    char 資料緩衝領域[8] = {0};
    int 応答端点 = 通信端点を作る(相互接続網番地系統, 資料電文端点, 利用者資料電文規約);
    int 要求端点 = 通信端点を作る(相互接続網番地系統, 資料電文端点, 0);

    結果を報告("socket-server", 応答端点 >= 3);
    結果を報告("socket-client", 要求端点 >= 3 && 要求端点 != 応答端点);
    応答端点番地.接続網番地系統 = 相互接続網番地系統;
    応答端点番地.通信窓口番号 = 通信網順に16桁を変える(32345);
    応答端点番地.接続網番地内容.番地値 = 通信網順に32桁を変える(自己折返し番地);
    結果を報告("bind", 局所番地を結ぶ(応答端点, (const struct 通信端点番地 *)&応答端点番地,
                        sizeof(応答端点番地)) == 0);
    結果を報告("connect", 相手端点につなぐ(要求端点, (const struct 通信端点番地 *)&応答端点番地,
                              sizeof(応答端点番地)) == 0);
    結果を報告("send", 送る(要求端点, "ping", 4, 0) == 4);
    結果を報告("recvfrom", 送信元と共に受け取る(応答端点, 資料緩衝領域, sizeof(資料緩衝領域), 0,
                                (struct 通信端点番地 *)&読出元, &送信元番地長) == 4 &&
                       資料緩衝領域[0] == 'p' && 資料緩衝領域[3] == 'g' && 送信元番地長 == 16);
    誤り番号 = 0;
    結果を報告("empty-eagain", 受け取る(応答端点, 資料緩衝領域, sizeof(資料緩衝領域), 0) == -1 && 誤り番号 == 誤り一時利用不可);
    結果を報告("getsockname", 局所端点の番地を得る(応答端点, (struct 通信端点番地 *)&読出元,
                                      &送信元番地長) == 0 && 読出元.通信窓口番号 == 通信網順に16桁を変える(32345));
    誤り番号 = 0;
    結果を報告("udp-listen-not-supported", 接続要求に備える(応答端点, 1) == -1 && 誤り番号 == 誤り操作非対応);
    結果を報告("close-client", 閉じる(要求端点) == 0);
    結果を報告("close-server", 閉じる(応答端点) == 0);
    電文を書く("NTEST:DONE\n");
    return 0;
}
