enum { вместимость_строки_ввода = 512, максимальное_число_аргументов = 16, максимальная_вложенность_командных_файлов = 4 };
static int глубина_вложенности_командных_файлов;
struct поток_ввода {
    int дескриптор_ввода;
    char буфер_передачи_2[256];
    size_t позиция;
    size_t длина;
};

static size_t длина_текста_в_байтах(const char *текст)
{
    size_t длина = 0;
    while (текст[длина] != '\0')
        длина++;
    return длина;
}

static int тексты_равны(const char *слева, const char *справа)
{
    size_t позиция = 0;
    while (слева[позиция] == справа[позиция]) {
        if (слева[позиция] == '\0')
            return 1;
        позиция++;
    }
    return 0;
}

static void вывести_текст(const char *текст)
{
    size_t длина = длина_текста_в_байтах(текст);
    while (длина > 0U) {
        ssize_t число_записанных_байтов = писать(STDOUT_FILENO, текст, длина);
        if (число_записанных_байтов <= 0)
            return;
        текст += число_записанных_байтов;
        длина -= (size_t)число_записанных_байтов;
    }
}

static void вывести_целое_число(int значение)
{
    char символы_цифр[16];
    unsigned int число_цифр;
    unsigned int модуль_без_знака;

    if (значение < 0) {
        вывести_текст("-");
        модуль_без_знака = (unsigned int)(-(значение + 1)) + 1U;
    } else {
        модуль_без_знака = (unsigned int)значение;
    }
    число_цифр = 0;
    do {
        символы_цифр[число_цифр++] = (char)('0' + модуль_без_знака % 10U);
        модуль_без_знака /= 10U;
    } while (модуль_без_знака != 0U);
    while (число_цифр > 0U) {
        число_цифр--;
        (void)писать(STDOUT_FILENO, &символы_цифр[число_цифр], 1);
    }
}

static void сообщить_об_ошибке(const char *операция)
{
    вывести_текст("error: ");
    вывести_текст(операция);
    вывести_текст(" errno=");
    вывести_целое_число(errno);
    вывести_текст("\n");
}

static int прочитать_строку_ввода(struct поток_ввода *ввод, char *строка_ввода, size_t вместимость)
{
    size_t позиция = 0;
    int недопустимая_строка_ввода = 0;
    char символ;
    ssize_t прочитанные_байты;
    if (вместимость < 2U)
        return -2;
    for (;;) {
        if (ввод->позиция == ввод->длина) {
            прочитанные_байты = читать(ввод->дескриптор_ввода, ввод->буфер_передачи_2, sizeof(ввод->буфер_передачи_2));
            if (прочитанные_байты < 0) {
                if (errno == EINTR)
                    continue;
                return -1;
            }
            if (прочитанные_байты == 0) {
                if (позиция == 0 && !недопустимая_строка_ввода)
                    return -1;
                break;
            }
            ввод->длина = (size_t)прочитанные_байты;
            ввод->позиция = 0;
        }
        символ = ввод->буфер_передачи_2[ввод->позиция++];
        if (символ == '\n')
            break;
        if (ввод->дескриптор_ввода == STDIN_FILENO && символ == 4) {
            if (позиция == 0 && !недопустимая_строка_ввода)
                return -1;
            break;
        }
        if (ввод->дескриптор_ввода == STDIN_FILENO && (символ == 8 || символ == 127)) {
            if (позиция > 0) {
                do {
                    позиция--;
                } while (позиция > 0 && ((unsigned char)строка_ввода[позиция] & 0xc0U) == 0x80U);
            }
            continue;
        }
        if (символ == '\r')
            continue;
        if (символ == '\0') {
            недопустимая_строка_ввода = 1; /* Reject binary input; do not execute its prefix. */
            continue;
        }
        if (позиция + 1U < вместимость)
            строка_ввода[позиция++] = символ;
        else
            недопустимая_строка_ввода = 1;
    }
    строка_ввода[позиция] = '\0';
    return недопустимая_строка_ввода ? -2 : (int)позиция;
}

static int разделить_аргументы(char *строка_ввода, char **аргументы)
{
    int число_аргументов = 0;
    char *текущая_позиция = строка_ввода;
    char *позиция_вывода = строка_ввода;

    while (*текущая_позиция != '\0') {
        char кавычка = '\0';
        while (*текущая_позиция == ' ' || *текущая_позиция == '\t')
            текущая_позиция++;
        if (*текущая_позиция == '\0' || *текущая_позиция == '#')
            break;
        if (число_аргументов == максимальное_число_аргументов - 1)
            return -1;
        аргументы[число_аргументов++] = позиция_вывода;
        while (*текущая_позиция != '\0') {
            char символ = *текущая_позиция++;
            if (кавычка == '\0' && (символ == ' ' || символ == '\t'))
                break;
            if (символ == '\\' && кавычка != '\'') {
                if (*текущая_позиция == '\0')
                    return -1;
                *позиция_вывода++ = *текущая_позиция++;
            } else if (символ == '\'' || символ == '"') {
                if (кавычка == '\0')
                    кавычка = символ;
                else if (кавычка == символ)
                    кавычка = '\0';
                else
                    *позиция_вывода++ = символ;
            } else {
                *позиция_вывода++ = символ;
            }
        }
        if (кавычка != '\0')
            return -1;
        *позиция_вывода++ = '\0';
    }
    аргументы[число_аргументов] = (char *)0;
    return число_аргументов;
}

static void показать_справку(void)
{
    size_t позиция;
    вывести_текст(
        "WorldOS command interpreter commands:\n"
        "  help                 show this help\n"
        "  echo TEXT            print text\n"
        "  pwd                  show current directory\n"
        "  cd PATH              change directory\n"
        "  cat FILE             print a FAT file\n"
        "  stat FILE            show file size\n"
        "  pid                  show process identifiers\n"
        "  uname                show operating-system identity\n"
        "  run FILE [ARGS...]   execute a user ELF program\n"
        "  udp [TEXT]           call POSIX UDP and loop back TEXT\n"
        "  source FILE          interpret a UTF-8 command file\n"
        "  exit                 leave the shell\n");
    вывести_текст("Native command proposals (ASCII aliases remain available):\n");
    for (позиция = 0; позиция < sizeof(основные_команды) / sizeof(основные_команды[0]); позиция++) {
        вывести_текст(местные_имена_команд[позиция]);
        вывести_текст(" = ");
        вывести_текст(основные_команды[позиция]);
        вывести_текст("\n");
    }
}

static int команда_совпадает(const char *текст, const char *команда)
{
    size_t позиция;
    if (тексты_равны(текст, команда))
        return 1;
    for (позиция = 0; позиция < sizeof(основные_команды) / sizeof(основные_команды[0]); позиция++)
        if (тексты_равны(команда, основные_команды[позиция]))
            return тексты_равны(текст, местные_имена_команд[позиция]);
    return 0;
}

