static int исполнить_командный_файл(const char *имя_файла)
{
    int дескриптор_файла_2;
    int состояние;
    if (глубина_вложенности_командных_файлов >= максимальная_вложенность_командных_файлов) {
        вывести_текст("source: nesting limit\n");
        return 0;
    }
    дескриптор_файла_2 = открыть(имя_файла, O_RDONLY);
    if (дескриптор_файла_2 < 0) {
        сообщить_об_ошибке(имя_файла);
        return 0;
    }
    глубина_вложенности_командных_файлов++;
    состояние = разобрать_ввод(дескриптор_файла_2);
    глубина_вложенности_командных_файлов--;
    (void)закрыть(дескриптор_файла_2);
    return состояние;
}

static void вывести_аргументы(int число_аргументов, char **аргументы)
{
    int позиция;
    for (позиция = 1; позиция < число_аргументов; позиция++) {
        if (позиция != 1)
            вывести_текст(" ");
        вывести_текст(аргументы[позиция]);
    }
    вывести_текст("\n");
}

static void показать_текущий_каталог(void)
{
    char путь[128];
    if (получить_путь_рабочего_каталога(путь, sizeof(путь)) == (char *)0) {
        сообщить_об_ошибке("pwd");
        return;
    }
    вывести_текст(путь);
    вывести_текст("\n");
}

static void показать_содержимое_файла(const char *имя_файла)
{
    char буфер_передачи_2[128];
    int дескриптор_файла_2 = открыть(имя_файла, O_RDONLY);
    ssize_t прочитанные_байты;

    if (дескриптор_файла_2 < 0) {
        сообщить_об_ошибке("cat");
        return;
    }
    while ((прочитанные_байты = читать(дескриптор_файла_2, буфер_передачи_2, sizeof(буфер_передачи_2))) > 0)
        (void)писать(STDOUT_FILENO, буфер_передачи_2, (size_t)прочитанные_байты);
    if (прочитанные_байты < 0)
        сообщить_об_ошибке("cat/read");
    (void)закрыть(дескриптор_файла_2);
    вывести_текст("\n");
}

static void показать_сведения_о_файле(const char *имя_файла)
{
    struct состояние_файла состояние;
    if (состояние_файла(имя_файла, &состояние) < 0) {
        сообщить_об_ошибке("stat");
        return;
    }
    вывести_текст("size=");
    вывести_целое_число((int)состояние.st_size);
    вывести_текст(S_ISDIR(состояние.st_mode) ? " type=directory\n" : " type=file\n");
}

