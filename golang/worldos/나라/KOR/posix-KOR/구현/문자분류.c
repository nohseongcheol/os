#include <문자분류.h>

/* Single-byte C/POSIX locale; these are not Unicode character classifiers. */
int 대문자인지확인하기(int 문자값) { return 문자값 >= 'A' && 문자값 <= 'Z'; }
int 소문자인지확인하기(int 문자값) { return 문자값 >= 'a' && 문자값 <= 'z'; }
int 영문자인지확인하기(int 문자값) { return 대문자인지확인하기(문자값) || 소문자인지확인하기(문자값); }
int 십진숫자인지확인하기(int 문자값) { return 문자값 >= '0' && 문자값 <= '9'; }
int 영문자나숫자인지확인하기(int 문자값) { return 영문자인지확인하기(문자값) || 십진숫자인지확인하기(문자값); }
int 수평공백인지확인하기(int 문자값) { return 문자값 == ' ' || 문자값 == '\t'; }
int 공백문자인지확인하기(int 문자값) { return 문자값 == ' ' || (문자값 >= '\t' && 문자값 <= '\r'); }
int 제어문자인지확인하기(int 문자값) { return (문자값 >= 0 && 문자값 < 32) || 문자값 == 127; }
int 인쇄문자인지확인하기(int 문자값) { return 문자값 >= 32 && 문자값 <= 126; }
int 공백아닌인쇄문자인지확인하기(int 문자값) { return 문자값 >= 33 && 문자값 <= 126; }
int 문장기호인지확인하기(int 문자값) { return 공백아닌인쇄문자인지확인하기(문자값) && !영문자나숫자인지확인하기(문자값); }
int 십육진숫자인지확인하기(int 문자값) { return 십진숫자인지확인하기(문자값) || (문자값 >= 'a' && 문자값 <= 'f') || (문자값 >= 'A' && 문자값 <= 'F'); }
int 소문자로바꾸기(int 문자값) { return 대문자인지확인하기(문자값) ? 문자값 + ('a' - 'A') : 문자값; }
int 대문자로바꾸기(int 문자값) { return 소문자인지확인하기(문자값) ? 문자값 - ('a' - 'A') : 문자값; }
