#include <체계/자식대기.h>
#include <자료철제어.h>
#include <입출력과실행.h>

static void 전문쓰기(const char *문자열, unsigned int 크기)
{
    (void)쓰기(표준출력번호, 문자열, 크기);
}

int main(void)
{
    int 끝난상태;
    실행과정번호형 부모과정 = 실행과정번호얻기();
    실행과정번호형 자식자리;
    실행과정번호형 기다린과정;
    volatile int 과정전용값 = 10;
    int 자료철서술번호;
    char 여덟자리묶음값;
    int 반복차례;

    전문쓰기("\nPOSIX-FORK:START\n", 18);
    자식자리 = 실행과정갈라내기();
    if (자식자리 == 0) {
        과정전용값 = 20;
        if (부모실행과정번호얻기() != 부모과정 || 과정전용값 != 20)
            즉시끝내기(90);
        즉시끝내기(23);
    }
    if (자식자리 < 0) {
        전문쓰기("PTEST:FAIL:fork-return\n", 23);
        즉시끝내기(1);
    }
    전문쓰기("PTEST:PASS:fork-return\n", 23);
    기다린과정 = 지정자식기다리기(자식자리, &끝난상태, 0);
    if (기다린과정 == 자식자리 && 정상종료인지확인(끝난상태) && 종료값꺼내기(끝난상태) == 23 &&
        과정전용값 == 10) {
        전문쓰기("PTEST:PASS:fork-wait-exit\n", 26);
    } else {
        전문쓰기("PTEST:FAIL:fork-wait-exit\n", 26);
        즉시끝내기(1);
    }

    자식자리 = 실행과정갈라내기();
    if (자식자리 == 0)
        즉시끝내기(29);
    기다린과정 = 자식기다리기(&끝난상태);
    if (기다린과정 == 자식자리 && 정상종료인지확인(끝난상태) && 종료값꺼내기(끝난상태) == 29)
        전문쓰기("PTEST:PASS:blocking-wait\n", 25);
    else {
        전문쓰기("PTEST:FAIL:blocking-wait\n", 25);
        즉시끝내기(1);
    }

    자료철서술번호 = 열기("/USER2", 읽기전용열기);
    자식자리 = 실행과정갈라내기();
    if (자식자리 == 0) {
        (void)닫기(자료철서술번호);
        즉시끝내기(0);
    }
    기다린과정 = 지정자식기다리기(자식자리, &끝난상태, 0);
    if (자료철서술번호 >= 0 && 기다린과정 == 자식자리 && 읽기(자료철서술번호, &여덟자리묶음값, 1) == 1 &&
        (unsigned char)여덟자리묶음값 == 0x7f)
        전문쓰기("PTEST:PASS:fork-fd-isolation\n", 29);
    else {
        전문쓰기("PTEST:FAIL:fork-fd-isolation\n", 29);
        즉시끝내기(1);
    }
    (void)닫기(자료철서술번호);

    for (반복차례 = 0; 반복차례 < 2; 반복차례++) {
        자식자리 = 실행과정갈라내기();
        if (자식자리 == 0)
            즉시끝내기(반복차례);
        if (자식자리 < 0 || 지정자식기다리기(자식자리, &끝난상태, 0) != 자식자리 ||
            !정상종료인지확인(끝난상태) || 종료값꺼내기(끝난상태) != 반복차례) {
            전문쓰기("PTEST:FAIL:fork-stress\n", 23);
            즉시끝내기(1);
        }
    }
    전문쓰기("PTEST:PASS:fork-stress\n", 23);
    전문쓰기("POSIX-FORK:PASS\n", 16);
    즉시끝내기(0);
}
