enum { سعة_سطر_الإدخال = 512, الحد_الأقصى_لعدد_المعاملات = 16, الحد_الأقصى_لتداخل_ملفات_الأوامر = 4 };
static int عمق_تداخل_ملفات_الأوامر;
struct تدفق_الإدخال {
    int واصف_الإدخال;
    char مخزن_النقل_المؤقت_2[256];
    size_t الموضع;
    size_t الطول;
};

static size_t طول_النص_بالبايت(const char *النص)
{
    size_t الطول = 0;
    while (النص[الطول] != '\0')
        الطول++;
    return الطول;
}

static int تساوي_النصين(const char *اليسار, const char *اليمين)
{
    size_t الموضع = 0;
    while (اليسار[الموضع] == اليمين[الموضع]) {
        if (اليسار[الموضع] == '\0')
            return 1;
        الموضع++;
    }
    return 0;
}

static void كتابة_النص(const char *النص)
{
    size_t الطول = طول_النص_بالبايت(النص);
    while (الطول > 0U) {
        ssize_t عدد_البايتات_المكتوبة = كتابة(STDOUT_FILENO, النص, الطول);
        if (عدد_البايتات_المكتوبة <= 0)
            return;
        النص += عدد_البايتات_المكتوبة;
        الطول -= (size_t)عدد_البايتات_المكتوبة;
    }
}

static void كتابة_عدد_صحيح(int القيمة)
{
    char محارف_الأرقام[16];
    unsigned int عدد_الخانات;
    unsigned int المقدار_بلا_إشارة;

    if (القيمة < 0) {
        كتابة_النص("-");
        المقدار_بلا_إشارة = (unsigned int)(-(القيمة + 1)) + 1U;
    } else {
        المقدار_بلا_إشارة = (unsigned int)القيمة;
    }
    عدد_الخانات = 0;
    do {
        محارف_الأرقام[عدد_الخانات++] = (char)('0' + المقدار_بلا_إشارة % 10U);
        المقدار_بلا_إشارة /= 10U;
    } while (المقدار_بلا_إشارة != 0U);
    while (عدد_الخانات > 0U) {
        عدد_الخانات--;
        (void)كتابة(STDOUT_FILENO, &محارف_الأرقام[عدد_الخانات], 1);
    }
}

static void الإبلاغ_عن_خطأ(const char *العملية)
{
    كتابة_النص("error: ");
    كتابة_النص(العملية);
    كتابة_النص(" errno=");
    كتابة_عدد_صحيح(errno);
    كتابة_النص("\n");
}

static int قراءة_سطر_الإدخال(struct تدفق_الإدخال *الإدخال, char *سطر_الإدخال, size_t السعة)
{
    size_t الموضع = 0;
    int سطر_إدخال_غير_صالح = 0;
    char المحرف;
    ssize_t البايتات_المقروءة;
    if (السعة < 2U)
        return -2;
    for (;;) {
        if (الإدخال->الموضع == الإدخال->الطول) {
            البايتات_المقروءة = قراءة(الإدخال->واصف_الإدخال, الإدخال->مخزن_النقل_المؤقت_2, sizeof(الإدخال->مخزن_النقل_المؤقت_2));
            if (البايتات_المقروءة < 0) {
                if (errno == EINTR)
                    continue;
                return -1;
            }
            if (البايتات_المقروءة == 0) {
                if (الموضع == 0 && !سطر_إدخال_غير_صالح)
                    return -1;
                break;
            }
            الإدخال->الطول = (size_t)البايتات_المقروءة;
            الإدخال->الموضع = 0;
        }
        المحرف = الإدخال->مخزن_النقل_المؤقت_2[الإدخال->الموضع++];
        if (المحرف == '\n')
            break;
        if (الإدخال->واصف_الإدخال == STDIN_FILENO && المحرف == 4) {
            if (الموضع == 0 && !سطر_إدخال_غير_صالح)
                return -1;
            break;
        }
        if (الإدخال->واصف_الإدخال == STDIN_FILENO && (المحرف == 8 || المحرف == 127)) {
            if (الموضع > 0) {
                do {
                    الموضع--;
                } while (الموضع > 0 && ((unsigned char)سطر_الإدخال[الموضع] & 0xc0U) == 0x80U);
            }
            continue;
        }
        if (المحرف == '\r')
            continue;
        if (المحرف == '\0') {
            سطر_إدخال_غير_صالح = 1; /* Reject binary input; do not execute its prefix. */
            continue;
        }
        if (الموضع + 1U < السعة)
            سطر_الإدخال[الموضع++] = المحرف;
        else
            سطر_إدخال_غير_صالح = 1;
    }
    سطر_الإدخال[الموضع] = '\0';
    return سطر_إدخال_غير_صالح ? -2 : (int)الموضع;
}

static int فصل_المعاملات(char *سطر_الإدخال, char **المعاملات)
{
    int عدد_المعاملات = 0;
    char *الموضع_الحالي = سطر_الإدخال;
    char *موضع_الإخراج = سطر_الإدخال;

    while (*الموضع_الحالي != '\0') {
        char علامة_الاقتباس = '\0';
        while (*الموضع_الحالي == ' ' || *الموضع_الحالي == '\t')
            الموضع_الحالي++;
        if (*الموضع_الحالي == '\0' || *الموضع_الحالي == '#')
            break;
        if (عدد_المعاملات == الحد_الأقصى_لعدد_المعاملات - 1)
            return -1;
        المعاملات[عدد_المعاملات++] = موضع_الإخراج;
        while (*الموضع_الحالي != '\0') {
            char المحرف = *الموضع_الحالي++;
            if (علامة_الاقتباس == '\0' && (المحرف == ' ' || المحرف == '\t'))
                break;
            if (المحرف == '\\' && علامة_الاقتباس != '\'') {
                if (*الموضع_الحالي == '\0')
                    return -1;
                *موضع_الإخراج++ = *الموضع_الحالي++;
            } else if (المحرف == '\'' || المحرف == '"') {
                if (علامة_الاقتباس == '\0')
                    علامة_الاقتباس = المحرف;
                else if (علامة_الاقتباس == المحرف)
                    علامة_الاقتباس = '\0';
                else
                    *موضع_الإخراج++ = المحرف;
            } else {
                *موضع_الإخراج++ = المحرف;
            }
        }
        if (علامة_الاقتباس != '\0')
            return -1;
        *موضع_الإخراج++ = '\0';
    }
    المعاملات[عدد_المعاملات] = (char *)0;
    return عدد_المعاملات;
}

static void عرض_المساعدة(void)
{
    size_t الموضع;
    كتابة_النص(
        "WorldOS command interpreter commands:\n"
        "  help                 show this help\n"
        "  echo TEXT            print text\n"
        "  pwd                  show current directory\n"
        "  cd PATH              change directory\n"
        "  cat FILE             print a FAT file\n"
        "  stat FILE            show file size\n"
        "  pid                  show process identifiers\n"
        "  uname                show operating-system identity\n"
        "  run FILE [ARGS...]   execute a user ELF program\n"
        "  udp [TEXT]           call POSIX UDP and loop back TEXT\n"
        "  source FILE          interpret a UTF-8 command file\n"
        "  exit                 leave the shell\n");
    كتابة_النص("Native command proposals (ASCII aliases remain available):\n");
    for (الموضع = 0; الموضع < sizeof(الأوامر_المرجعية) / sizeof(الأوامر_المرجعية[0]); الموضع++) {
        كتابة_النص(أسماء_الأوامر_المحلية[الموضع]);
        كتابة_النص(" = ");
        كتابة_النص(الأوامر_المرجعية[الموضع]);
        كتابة_النص("\n");
    }
}

static int مطابقة_الأمر(const char *النص, const char *الأمر)
{
    size_t الموضع;
    if (تساوي_النصين(النص, الأمر))
        return 1;
    for (الموضع = 0; الموضع < sizeof(الأوامر_المرجعية) / sizeof(الأوامر_المرجعية[0]); الموضع++)
        if (تساوي_النصين(الأمر, الأوامر_المرجعية[الموضع]))
            return تساوي_النصين(النص, أسماء_الأوامر_المحلية[الموضع]);
    return 0;
}

