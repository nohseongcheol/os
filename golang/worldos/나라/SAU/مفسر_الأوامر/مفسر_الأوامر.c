static int تفسير_ملف_الأوامر(const char *اسم_الملف)
{
    int واصف_الملف_2;
    int الحالة;
    if (عمق_تداخل_ملفات_الأوامر >= الحد_الأقصى_لتداخل_ملفات_الأوامر) {
        كتابة_النص("source: nesting limit\n");
        return 0;
    }
    واصف_الملف_2 = فتح(اسم_الملف, O_RDONLY);
    if (واصف_الملف_2 < 0) {
        الإبلاغ_عن_خطأ(اسم_الملف);
        return 0;
    }
    عمق_تداخل_ملفات_الأوامر++;
    الحالة = تفسير_الإدخال(واصف_الملف_2);
    عمق_تداخل_ملفات_الأوامر--;
    (void)إغلاق(واصف_الملف_2);
    return الحالة;
}

static void عرض_المعاملات(int عدد_المعاملات, char **المعاملات)
{
    int الموضع;
    for (الموضع = 1; الموضع < عدد_المعاملات; الموضع++) {
        if (الموضع != 1)
            كتابة_النص(" ");
        كتابة_النص(المعاملات[الموضع]);
    }
    كتابة_النص("\n");
}

static void عرض_المجلد_الحالي(void)
{
    char المسار[128];
    if (جلب_مسار_دليل_العمل(المسار, sizeof(المسار)) == (char *)0) {
        الإبلاغ_عن_خطأ("pwd");
        return;
    }
    كتابة_النص(المسار);
    كتابة_النص("\n");
}

static void عرض_محتوى_الملف(const char *اسم_الملف)
{
    char مخزن_النقل_المؤقت_2[128];
    int واصف_الملف_2 = فتح(اسم_الملف, O_RDONLY);
    ssize_t البايتات_المقروءة;

    if (واصف_الملف_2 < 0) {
        الإبلاغ_عن_خطأ("cat");
        return;
    }
    while ((البايتات_المقروءة = قراءة(واصف_الملف_2, مخزن_النقل_المؤقت_2, sizeof(مخزن_النقل_المؤقت_2))) > 0)
        (void)كتابة(STDOUT_FILENO, مخزن_النقل_المؤقت_2, (size_t)البايتات_المقروءة);
    if (البايتات_المقروءة < 0)
        الإبلاغ_عن_خطأ("cat/read");
    (void)إغلاق(واصف_الملف_2);
    كتابة_النص("\n");
}

static void عرض_معلومات_الملف(const char *اسم_الملف)
{
    struct حالة_الملف الحالة;
    if (حالة_الملف(اسم_الملف, &الحالة) < 0) {
        الإبلاغ_عن_خطأ("stat");
        return;
    }
    كتابة_النص("size=");
    كتابة_عدد_صحيح((int)الحالة.st_size);
    كتابة_النص(S_ISDIR(الحالة.st_mode) ? " type=directory\n" : " type=file\n");
}

