static void تشغيل_البرنامج(int عدد_المعاملات, char **المعاملات)
{
    pid_t معرف_العملية_الفرعية;
    int حالة_انتهاء_العملية_الفرعية = 0;

    if (عدد_المعاملات < 2) {
        كتابة_النص("usage: run FILE [ARGS...]\n");
        return;
    }
    معرف_العملية_الفرعية = إنشاء_عملية_فرعية();
    if (معرف_العملية_الفرعية < 0) {
        الإبلاغ_عن_خطأ("fork");
        return;
    }
    if (معرف_العملية_الفرعية == 0) {
        استبدال_البرنامج_الجاري(المعاملات[1], &المعاملات[1], (char *const *)0);
        الإبلاغ_عن_خطأ("execve");
        إنهاء_فوري(127);
    }
    if (انتظار_العملية_الفرعية_المحددة(معرف_العملية_الفرعية, &حالة_انتهاء_العملية_الفرعية, 0) < 0) {
        الإبلاغ_عن_خطأ("waitpid");
        return;
    }
    كتابة_النص("exit-status=");
    كتابة_عدد_صحيح(WEXITSTATUS(حالة_انتهاء_العملية_الفرعية));
    كتابة_النص("\n");
}

static void اختبار_إرجاع_حزمة_البيانات(const char *الرسالة)
{
    struct عنوان_نقطة_اتصال_الشبكات_المترابطة عنوان_الاستقبال = {0};
    struct عنوان_نقطة_اتصال_الشبكات_المترابطة عنوان_المرسل = {0};
    نوع_طول_العنوان طول_عنوان_المرسل = sizeof(عنوان_المرسل);
    char البيانات_المستلمة[96];
    size_t طول_الرسالة_بالبايت = طول_النص_بالبايت(الرسالة);
    int نقطة_اتصال_الاستقبال = -1;
    int نقطة_اتصال_الإرسال = -1;
    ssize_t عدد_البايتات_المستلمة;

    if (طول_الرسالة_بالبايت >= sizeof(البيانات_المستلمة)) {
        كتابة_النص("udp: message exceeds 95 bytes\n");
        return;
    }
    نقطة_اتصال_الاستقبال = إنشاء_نقطة_اتصال(رمز_عائلة_عناوين_الشبكات_المترابطة, نقطة_رزم_البيانات, بروتوكول_رزم_المستخدم);
    نقطة_اتصال_الإرسال = إنشاء_نقطة_اتصال(رمز_عائلة_عناوين_الشبكات_المترابطة, نقطة_رزم_البيانات, بروتوكول_رزم_المستخدم);
    if (نقطة_اتصال_الاستقبال < 0 || نقطة_اتصال_الإرسال < 0) {
        الإبلاغ_عن_خطأ("socket");
        goto إغلاق_نقاط_الاتصال;
    }
    عنوان_الاستقبال.عائلة_عناوين_الشبكات_المترابطة = رمز_عائلة_عناوين_الشبكات_المترابطة;
    عنوان_الاستقبال.رقم_منفذ_الاتصال = تحويل_16_خانة_إلى_ترتيب_الشبكة(40404);
    عنوان_الاستقبال.محتوى_عنوان_الشبكات_المترابطة.قيمة_العنوان = تحويل_32_خانة_إلى_ترتيب_الشبكة(عنوان_الحلقة_المحلية);
    if (ربط_عنوان_محلي(نقطة_اتصال_الاستقبال, (const struct عنوان_نقطة_الاتصال *)&عنوان_الاستقبال, sizeof(عنوان_الاستقبال)) < 0) {
        الإبلاغ_عن_خطأ("bind");
        goto إغلاق_نقاط_الاتصال;
    }
    if (الاتصال_بالطرف_المقابل(نقطة_اتصال_الإرسال, (const struct عنوان_نقطة_الاتصال *)&عنوان_الاستقبال, sizeof(عنوان_الاستقبال)) < 0) {
        الإبلاغ_عن_خطأ("connect");
        goto إغلاق_نقاط_الاتصال;
    }
    if (إرسال(نقطة_اتصال_الإرسال, الرسالة, طول_الرسالة_بالبايت, 0) != (ssize_t)طول_الرسالة_بالبايت) {
        الإبلاغ_عن_خطأ("send");
        goto إغلاق_نقاط_الاتصال;
    }
    عدد_البايتات_المستلمة = استقبال_مع_عنوان_المصدر(نقطة_اتصال_الاستقبال, البيانات_المستلمة, sizeof(البيانات_المستلمة) - 1U, 0,
                         (struct عنوان_نقطة_الاتصال *)&عنوان_المرسل, &طول_عنوان_المرسل);
    if (عدد_البايتات_المستلمة < 0) {
        الإبلاغ_عن_خطأ("recvfrom");
        goto إغلاق_نقاط_الاتصال;
    }
    البيانات_المستلمة[عدد_البايتات_المستلمة] = '\0';
    كتابة_النص("udp-received: ");
    كتابة_النص(البيانات_المستلمة);
    كتابة_النص("\n");

إغلاق_نقاط_الاتصال:
    if (نقطة_اتصال_الإرسال >= 0)
        (void)إغلاق(نقطة_اتصال_الإرسال);
    if (نقطة_اتصال_الاستقبال >= 0)
        (void)إغلاق(نقطة_اتصال_الاستقبال);
}

static int تفسير_الإدخال(int واصف_الإدخال)
{
    char سطر_الإدخال[سعة_سطر_الإدخال];
    char *المعاملات[الحد_الأقصى_لعدد_المعاملات];
    struct تدفق_الإدخال الإدخال = {0};
    الإدخال.واصف_الإدخال = واصف_الإدخال;

    for (;;) {
        int عدد_المعاملات;
        int الحالة;
        if (واصف_الإدخال == STDIN_FILENO)
            كتابة_النص("worldos$ ");
        الحالة = قراءة_سطر_الإدخال(&الإدخال, سطر_الإدخال, sizeof(سطر_الإدخال));
        if (الحالة == -1)
            return 0;
        if (الحالة == -2) {
            كتابة_النص("input rejected: overlong or binary line\n");
            continue;
        }
        عدد_المعاملات = فصل_المعاملات(سطر_الإدخال, المعاملات);
        if (عدد_المعاملات < 0) {
            كتابة_النص("syntax error: quote, escape or argument limit\n");
            continue;
        }
        if (عدد_المعاملات == 0)
            continue;
        if (مطابقة_الأمر(المعاملات[0], "help"))
            عرض_المساعدة();
        else if (مطابقة_الأمر(المعاملات[0], "echo"))
            عرض_المعاملات(عدد_المعاملات, المعاملات);
        else if (مطابقة_الأمر(المعاملات[0], "pwd"))
            عرض_المجلد_الحالي();
        else if (مطابقة_الأمر(المعاملات[0], "cd")) {
            if (عدد_المعاملات < 2)
                كتابة_النص("usage: cd PATH\n");
            else if (تغيير_دليل_العمل(المعاملات[1]) < 0)
                الإبلاغ_عن_خطأ("cd");
        } else if (مطابقة_الأمر(المعاملات[0], "cat")) {
            if (عدد_المعاملات < 2)
                كتابة_النص("usage: cat FILE\n");
            else
                عرض_محتوى_الملف(المعاملات[1]);
        } else if (مطابقة_الأمر(المعاملات[0], "stat")) {
            if (عدد_المعاملات < 2)
                كتابة_النص("usage: stat FILE\n");
            else
                عرض_معلومات_الملف(المعاملات[1]);
        } else if (مطابقة_الأمر(المعاملات[0], "pid"))
            عرض_معرفات_العمليات();
        else if (مطابقة_الأمر(المعاملات[0], "uname"))
            عرض_هوية_النظام();
        else if (مطابقة_الأمر(المعاملات[0], "run"))
            تشغيل_البرنامج(عدد_المعاملات, المعاملات);
        else if (مطابقة_الأمر(المعاملات[0], "udp"))
            اختبار_إرجاع_حزمة_البيانات(عدد_المعاملات >= 2 ? المعاملات[1] : "ping");
        else if (مطابقة_الأمر(المعاملات[0], "source")) {
            if (عدد_المعاملات < 2)
                كتابة_النص("usage: source FILE\n");
            else if (تفسير_ملف_الأوامر(المعاملات[1]))
                return 1;
        } else if (مطابقة_الأمر(المعاملات[0], "exit"))
            return 1;
        else
            كتابة_النص("unknown command; type help\n");
    }
}

int main(void)
{
    كتابة_النص("WORLDOS-SHELL:READY\n");
    (void)تفسير_الإدخال(STDIN_FILENO);
    كتابة_النص("WORLDOS-SHELL:EXIT\n");
    return 0;
}
