package виконуваний_і_компонований_формат

import . "unsafe"
import . "консоль"

import mem "памятьmanager"

type Посилання struct {
	Динамічно	uintptr
	Previous	*Посилання
	Наступне	*Посилання
}
type Посиланняmap struct {
	First	*Посилання
	Останнє	*Посилання

	Розмір_2	int

	mem	*mem.TПамятьmanager
}

func (поточний *Посиланняmap) Init(mem *mem.TПамятьmanager) {
	поточний.mem = mem
}
func (поточний *Посиланняmap) Clone() Посиланняmap {
	var посиланняmap Посиланняmap

	посиланняmap.Init(поточний.mem)

	Посилання := поточний.First

	for ; Посилання != nil; Посилання = Посилання.Наступне {
		посиланняmap.Додати_в_кінець_списку(Посилання.Динамічно)
	}
	return посиланняmap
}
func (поточний *Посиланняmap) Додати_на_початок_списку(Динамічно uintptr) {
	новийПосилання := (*Посилання)(поточний.mem.Виділити_памʼять(uint32(Sizeof(Посилання{}))))
	новийПосилання.Динамічно = Динамічно
	новийПосилання.Наступне = поточний.First
	поточний.First = новийПосилання
	поточний.Розмір_2++

	if поточний.First.Наступне == nil {
		поточний.Останнє = поточний.First
	}
}
func (поточний *Посиланняmap) Додати_в_кінець_списку(Динамічно uintptr) {
	if Динамічно == 0 {
		return
	}

	if поточний.Розмір_2 == 0 {
		поточний.Додати_на_початок_списку(Динамічно)
	} else {
		новийПосилання := (*Посилання)(поточний.mem.Виділити_памʼять(uint32(Sizeof(Посилання{}))))
		новийПосилання.Динамічно = Динамічно
		новийПосилання.Наступне = nil
		поточний.Останнє.Наступне = новийПосилання
		поточний.Останнє = новийПосилання
		поточний.Розмір_2++
	}
}
func (поточний *Посиланняmap) Друк(x uint16, y uint16) {
	Посилання := поточний.First
	консоль_2 := TКонсоль{}
	консоль_2.MДрукxy("linkmap : ", x, y)
	for ; Посилання != nil; Посилання = Посилання.Наступне {
		консоль_2.MUnsignedinteger32Друк(uint32(Посилання.Динамічно))
		консоль_2.MДрук("+")

	}
}
