enum { місткість_рядка_введення = 512, максимальна_кількість_аргументів = 16, максимальна_вкладеність_командних_файлів = 4 };
static int глибина_вкладеності_командних_файлів;
struct потік_введення {
    int дескриптор_введення;
    char буфер_передавання_2[256];
    size_t позиція;
    size_t довжина;
};

static size_t довжина_тексту_в_байтах(const char *текст)
{
    size_t довжина = 0;
    while (текст[довжина] != '\0')
        довжина++;
    return довжина;
}

static int тексти_однакові(const char *ліворуч, const char *праворуч)
{
    size_t позиція = 0;
    while (ліворуч[позиція] == праворуч[позиція]) {
        if (ліворуч[позиція] == '\0')
            return 1;
        позиція++;
    }
    return 0;
}

static void вивести_текст(const char *текст)
{
    size_t довжина = довжина_тексту_в_байтах(текст);
    while (довжина > 0U) {
        ssize_t кількість_записаних_байтів = Запис(STDOUT_FILENO, текст, довжина);
        if (кількість_записаних_байтів <= 0)
            return;
        текст += кількість_записаних_байтів;
        довжина -= (size_t)кількість_записаних_байтів;
    }
}

static void вивести_ціле_число(int значення)
{
    char символи_цифр[16];
    unsigned int кількість_цифр;
    unsigned int модуль_без_знака;

    if (значення < 0) {
        вивести_текст("-");
        модуль_без_знака = (unsigned int)(-(значення + 1)) + 1U;
    } else {
        модуль_без_знака = (unsigned int)значення;
    }
    кількість_цифр = 0;
    do {
        символи_цифр[кількість_цифр++] = (char)('0' + модуль_без_знака % 10U);
        модуль_без_знака /= 10U;
    } while (модуль_без_знака != 0U);
    while (кількість_цифр > 0U) {
        кількість_цифр--;
        (void)Запис(STDOUT_FILENO, &символи_цифр[кількість_цифр], 1);
    }
}

static void повідомити_про_помилку(const char *операція)
{
    вивести_текст("error: ");
    вивести_текст(операція);
    вивести_текст(" errno=");
    вивести_ціле_число(errno);
    вивести_текст("\n");
}

static int прочитати_рядок_введення(struct потік_введення *введення, char *рядок_введення, size_t місткість)
{
    size_t позиція = 0;
    int неприпустимий_рядок_введення = 0;
    char символ;
    ssize_t прочитані_байти;
    if (місткість < 2U)
        return -2;
    for (;;) {
        if (введення->позиція == введення->довжина) {
            прочитані_байти = Читання(введення->дескриптор_введення, введення->буфер_передавання_2, sizeof(введення->буфер_передавання_2));
            if (прочитані_байти < 0) {
                if (errno == EINTR)
                    continue;
                return -1;
            }
            if (прочитані_байти == 0) {
                if (позиція == 0 && !неприпустимий_рядок_введення)
                    return -1;
                break;
            }
            введення->довжина = (size_t)прочитані_байти;
            введення->позиція = 0;
        }
        символ = введення->буфер_передавання_2[введення->позиція++];
        if (символ == '\n')
            break;
        if (введення->дескриптор_введення == STDIN_FILENO && символ == 4) {
            if (позиція == 0 && !неприпустимий_рядок_введення)
                return -1;
            break;
        }
        if (введення->дескриптор_введення == STDIN_FILENO && (символ == 8 || символ == 127)) {
            if (позиція > 0) {
                do {
                    позиція--;
                } while (позиція > 0 && ((unsigned char)рядок_введення[позиція] & 0xc0U) == 0x80U);
            }
            continue;
        }
        if (символ == '\r')
            continue;
        if (символ == '\0') {
            неприпустимий_рядок_введення = 1; /* Reject binary input; do not execute its prefix. */
            continue;
        }
        if (позиція + 1U < місткість)
            рядок_введення[позиція++] = символ;
        else
            неприпустимий_рядок_введення = 1;
    }
    рядок_введення[позиція] = '\0';
    return неприпустимий_рядок_введення ? -2 : (int)позиція;
}

static int розділити_аргументи(char *рядок_введення, char **аргументи)
{
    int кількість_аргументів = 0;
    char *поточна_позиція = рядок_введення;
    char *позиція_виведення = рядок_введення;

    while (*поточна_позиція != '\0') {
        char лапки = '\0';
        while (*поточна_позиція == ' ' || *поточна_позиція == '\t')
            поточна_позиція++;
        if (*поточна_позиція == '\0' || *поточна_позиція == '#')
            break;
        if (кількість_аргументів == максимальна_кількість_аргументів - 1)
            return -1;
        аргументи[кількість_аргументів++] = позиція_виведення;
        while (*поточна_позиція != '\0') {
            char символ = *поточна_позиція++;
            if (лапки == '\0' && (символ == ' ' || символ == '\t'))
                break;
            if (символ == '\\' && лапки != '\'') {
                if (*поточна_позиція == '\0')
                    return -1;
                *позиція_виведення++ = *поточна_позиція++;
            } else if (символ == '\'' || символ == '"') {
                if (лапки == '\0')
                    лапки = символ;
                else if (лапки == символ)
                    лапки = '\0';
                else
                    *позиція_виведення++ = символ;
            } else {
                *позиція_виведення++ = символ;
            }
        }
        if (лапки != '\0')
            return -1;
        *позиція_виведення++ = '\0';
    }
    аргументи[кількість_аргументів] = (char *)0;
    return кількість_аргументів;
}

static void показати_довідку(void)
{
    size_t позиція;
    вивести_текст(
        "WorldOS command interpreter commands:\n"
        "  help                 show this help\n"
        "  echo TEXT            print text\n"
        "  pwd                  show current directory\n"
        "  cd PATH              change directory\n"
        "  cat FILE             print a FAT file\n"
        "  stat FILE            show file size\n"
        "  pid                  show process identifiers\n"
        "  uname                show operating-system identity\n"
        "  run FILE [ARGS...]   execute a user ELF program\n"
        "  udp [TEXT]           call POSIX UDP and loop back TEXT\n"
        "  source FILE          interpret a UTF-8 command file\n"
        "  exit                 leave the shell\n");
    вивести_текст("Native command proposals (ASCII aliases remain available):\n");
    for (позиція = 0; позиція < sizeof(основні_команди) / sizeof(основні_команди[0]); позиція++) {
        вивести_текст(місцеві_назви_команд[позиція]);
        вивести_текст(" = ");
        вивести_текст(основні_команди[позиція]);
        вивести_текст("\n");
    }
}

static int команда_збігається(const char *текст, const char *команда)
{
    size_t позиція;
    if (тексти_однакові(текст, команда))
        return 1;
    for (позиція = 0; позиція < sizeof(основні_команди) / sizeof(основні_команди[0]); позиція++)
        if (тексти_однакові(команда, основні_команди[позиція]))
            return тексти_однакові(текст, місцеві_назви_команд[позиція]);
    return 0;
}

