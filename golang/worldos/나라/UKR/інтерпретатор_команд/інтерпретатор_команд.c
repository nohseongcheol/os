static int виконати_командний_файл(const char *ім_я_файла)
{
    int дескриптор_файла_2;
    int стан;
    if (глибина_вкладеності_командних_файлів >= максимальна_вкладеність_командних_файлів) {
        вивести_текст("source: nesting limit\n");
        return 0;
    }
    дескриптор_файла_2 = Відкрити(ім_я_файла, O_RDONLY);
    if (дескриптор_файла_2 < 0) {
        повідомити_про_помилку(ім_я_файла);
        return 0;
    }
    глибина_вкладеності_командних_файлів++;
    стан = розібрати_введення(дескриптор_файла_2);
    глибина_вкладеності_командних_файлів--;
    (void)Закрити(дескриптор_файла_2);
    return стан;
}

static void вивести_аргументи(int кількість_аргументів, char **аргументи)
{
    int позиція;
    for (позиція = 1; позиція < кількість_аргументів; позиція++) {
        if (позиція != 1)
            вивести_текст(" ");
        вивести_текст(аргументи[позиція]);
    }
    вивести_текст("\n");
}

static void показати_поточний_каталог(void)
{
    char шлях[128];
    if (getcwd(шлях, sizeof(шлях)) == (char *)0) {
        повідомити_про_помилку("pwd");
        return;
    }
    вивести_текст(шлях);
    вивести_текст("\n");
}

static void показати_вміст_файла(const char *ім_я_файла)
{
    char буфер_передавання_2[128];
    int дескриптор_файла_2 = Відкрити(ім_я_файла, O_RDONLY);
    ssize_t прочитані_байти;

    if (дескриптор_файла_2 < 0) {
        повідомити_про_помилку("cat");
        return;
    }
    while ((прочитані_байти = Читання(дескриптор_файла_2, буфер_передавання_2, sizeof(буфер_передавання_2))) > 0)
        (void)Запис(STDOUT_FILENO, буфер_передавання_2, (size_t)прочитані_байти);
    if (прочитані_байти < 0)
        повідомити_про_помилку("cat/read");
    (void)Закрити(дескриптор_файла_2);
    вивести_текст("\n");
}

static void показати_відомості_про_файл(const char *ім_я_файла)
{
    struct stat стан;
    if (stat(ім_я_файла, &стан) < 0) {
        повідомити_про_помилку("stat");
        return;
    }
    вивести_текст("size=");
    вивести_ціле_число((int)стан.st_size);
    вивести_текст(S_ISDIR(стан.st_mode) ? " type=directory\n" : " type=file\n");
}

static void показати_номери_процесів(void)
{
    вивести_текст("pid=");
    вивести_ціле_число((int)getpid());
    вивести_текст(" ppid=");
    вивести_ціле_число((int)getppid());
    вивести_текст("\n");
}

static void показати_відомості_про_систему(void)
{
    struct utsname відомості_про_систему;
    if (uname(&відомості_про_систему) < 0) {
        повідомити_про_помилку("uname");
        return;
    }
    вивести_текст(відомості_про_систему.sysname);
    вивести_текст(" ");
    вивести_текст(відомості_про_систему.release);
    вивести_текст(" ");
    вивести_текст(відомості_про_систему.machine);
    вивести_текст("\n");
}

static void запустити_програму(int кількість_аргументів, char **аргументи)
{
    pid_t номер_дочірнього_процесу;
    int стан_завершення_дочірнього_процесу = 0;

    if (кількість_аргументів < 2) {
        вивести_текст("usage: run FILE [ARGS...]\n");
        return;
    }
    номер_дочірнього_процесу = fork();
    if (номер_дочірнього_процесу < 0) {
        повідомити_про_помилку("fork");
        return;
    }
    if (номер_дочірнього_процесу == 0) {
        execve(аргументи[1], &аргументи[1], (char *const *)0);
        повідомити_про_помилку("execve");
        _exit(127);
    }
    if (waitpid(номер_дочірнього_процесу, &стан_завершення_дочірнього_процесу, 0) < 0) {
        повідомити_про_помилку("waitpid");
        return;
    }
    вивести_текст("exit-status=");
    вивести_ціле_число(WEXITSTATUS(стан_завершення_дочірнього_процесу));
    вивести_текст("\n");
}

static void перевірити_повернення_датаграми(const char *повідомлення)
{
    struct sockaddr_in адреса_отримувача = {0};
    struct sockaddr_in адреса_відправника = {0};
    socklen_t довжина_адреси_відправника = sizeof(адреса_відправника);
    char отримані_дані[96];
    size_t довжина_повідомлення_в_байтах = довжина_тексту_в_байтах(повідомлення);
    int приймальна_кінцева_точка = -1;
    int передавальна_кінцева_точка = -1;
    ssize_t кількість_отриманих_байтів;

    if (довжина_повідомлення_в_байтах >= sizeof(отримані_дані)) {
        вивести_текст("udp: message exceeds 95 bytes\n");
        return;
    }
    приймальна_кінцева_точка = socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP);
    передавальна_кінцева_точка = socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP);
    if (приймальна_кінцева_точка < 0 || передавальна_кінцева_точка < 0) {
        повідомити_про_помилку("socket");
        goto закрити_кінцеві_точки;
    }
    адреса_отримувача.sin_family = AF_INET;
    адреса_отримувача.sin_port = htons(40404);
    адреса_отримувача.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    if (bind(приймальна_кінцева_точка, (const struct sockaddr *)&адреса_отримувача, sizeof(адреса_отримувача)) < 0) {
        повідомити_про_помилку("bind");
        goto закрити_кінцеві_точки;
    }
    if (connect(передавальна_кінцева_точка, (const struct sockaddr *)&адреса_отримувача, sizeof(адреса_отримувача)) < 0) {
        повідомити_про_помилку("connect");
        goto закрити_кінцеві_точки;
    }
    if (send(передавальна_кінцева_точка, повідомлення, довжина_повідомлення_в_байтах, 0) != (ssize_t)довжина_повідомлення_в_байтах) {
        повідомити_про_помилку("send");
        goto закрити_кінцеві_точки;
    }
    кількість_отриманих_байтів = recvfrom(приймальна_кінцева_точка, отримані_дані, sizeof(отримані_дані) - 1U, 0,
                         (struct sockaddr *)&адреса_відправника, &довжина_адреси_відправника);
    if (кількість_отриманих_байтів < 0) {
        повідомити_про_помилку("recvfrom");
        goto закрити_кінцеві_точки;
    }
    отримані_дані[кількість_отриманих_байтів] = '\0';
    вивести_текст("udp-received: ");
    вивести_текст(отримані_дані);
    вивести_текст("\n");

закрити_кінцеві_точки:
    if (передавальна_кінцева_точка >= 0)
        (void)Закрити(передавальна_кінцева_точка);
    if (приймальна_кінцева_точка >= 0)
        (void)Закрити(приймальна_кінцева_точка);
}

static int розібрати_введення(int дескриптор_введення)
{
    char рядок_введення[місткість_рядка_введення];
    char *аргументи[максимальна_кількість_аргументів];
    struct потік_введення введення = {0};
    введення.дескриптор_введення = дескриптор_введення;

    for (;;) {
        int кількість_аргументів;
        int стан;
        if (дескриптор_введення == STDIN_FILENO)
            вивести_текст("worldos$ ");
        стан = прочитати_рядок_введення(&введення, рядок_введення, sizeof(рядок_введення));
        if (стан == -1)
            return 0;
        if (стан == -2) {
            вивести_текст("input rejected: overlong or binary line\n");
            continue;
        }
        кількість_аргументів = розділити_аргументи(рядок_введення, аргументи);
        if (кількість_аргументів < 0) {
            вивести_текст("syntax error: quote, escape or argument limit\n");
            continue;
        }
        if (кількість_аргументів == 0)
            continue;
        if (команда_збігається(аргументи[0], "help"))
            показати_довідку();
        else if (команда_збігається(аргументи[0], "echo"))
            вивести_аргументи(кількість_аргументів, аргументи);
        else if (команда_збігається(аргументи[0], "pwd"))
            показати_поточний_каталог();
        else if (команда_збігається(аргументи[0], "cd")) {
            if (кількість_аргументів < 2)
                вивести_текст("usage: cd PATH\n");
            else if (chdir(аргументи[1]) < 0)
                повідомити_про_помилку("cd");
        } else if (команда_збігається(аргументи[0], "cat")) {
            if (кількість_аргументів < 2)
                вивести_текст("usage: cat FILE\n");
            else
                показати_вміст_файла(аргументи[1]);
        } else if (команда_збігається(аргументи[0], "stat")) {
            if (кількість_аргументів < 2)
                вивести_текст("usage: stat FILE\n");
            else
                показати_відомості_про_файл(аргументи[1]);
        } else if (команда_збігається(аргументи[0], "pid"))
            показати_номери_процесів();
        else if (команда_збігається(аргументи[0], "uname"))
            показати_відомості_про_систему();
        else if (команда_збігається(аргументи[0], "run"))
            запустити_програму(кількість_аргументів, аргументи);
        else if (команда_збігається(аргументи[0], "udp"))
            перевірити_повернення_датаграми(кількість_аргументів >= 2 ? аргументи[1] : "ping");
        else if (команда_збігається(аргументи[0], "source")) {
            if (кількість_аргументів < 2)
                вивести_текст("usage: source FILE\n");
            else if (виконати_командний_файл(аргументи[1]))
                return 1;
        } else if (команда_збігається(аргументи[0], "exit"))
            return 1;
        else
            вивести_текст("unknown command; type help\n");
    }
}

int main(void)
{
    вивести_текст("WORLDOS-SHELL:READY\n");
    (void)розібрати_введення(STDIN_FILENO);
    вивести_текст("WORLDOS-SHELL:EXIT\n");
    return 0;
}
