#include <にゅうしゅつりょくとじっこう.h>

static void でんぶんをかく(const char *もじれつ, unsigned int おおきさ)
{
    (void)かく(ひょうじゅんしゅつりょくばんごう, もじれつ, おおきさ);
}

int main(void)
{
    char にゅうりょくいち[4];
    ふごうつきおおきさがた すうりょう;

    でんぶんをかく("\nPOSIX-STDIN:READY\n", 19);
    すうりょう = よむ(ひょうじゅんにゅうりょくばんごう, にゅうりょくいち, sizeof(にゅうりょくいち));
    if (すうりょう == 2 && にゅうりょくいち[0] == 'a' && にゅうりょくいち[1] == '\n') {
        でんぶんをかく("POSIX-STDIN:PASS\n", 17);
        ただちにしゅうりょうする(0);
    }
    でんぶんをかく("POSIX-STDIN:FAIL\n", 17);
    ただちにしゅうりょうする(1);
}
