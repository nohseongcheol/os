    /* USER2 is the ELF fixture installed by the boot harness, not user data. */
    int ブンショキジュツバンゴウ = ヒラク("/USER2", ヨミトリセンヨウデヒラク);
    struct ブンショジョウタイ ジョウタイシリョウ;
