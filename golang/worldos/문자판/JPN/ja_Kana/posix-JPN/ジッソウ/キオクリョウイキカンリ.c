/* Single-thread runtime. Reuse and coalesce freed blocks; do not shrink brk.
 * A block header and every returned address are 16-byte aligned on i386.
 * Callers must not move brk backwards across live allocations. */
struct キオククカク {
    オオキサガタ ヨウリョウ;
    struct キオククカク *ツギノクカク;
    int リヨウカノウハンテイ;
    unsigned int セイレツウメコミチョウ;
};
static struct キオククカク *サイショノクカク;

void *キオクリョウイキヲカクホスル(オオキサガタ オオキサ)
{
    struct キオククカク *シンコウイチ = サイショノクカク, *サイゴノクカク = カラバンチ, *カクホモトバンチ;
    オオキサガタ ゼンタイチョウ, セイレツウメコミチョウ;
    void *バンチ;
    if (!オオキサ) オオキサ = 1;
    if (オオキサ > (オオキサガタ)セイスウサイダイチ - 2 * sizeof(struct キオククカク)) { アヤマリバンゴウ = アヤマリキオクブソク; return カラバンチ; }
    オオキサ = (オオキサ + 15U) & ~15U;
    while (シンコウイチ) {
        if (シンコウイチ->リヨウカノウハンテイ && シンコウイチ->ヨウリョウ >= オオキサ) {
            if (シンコウイチ->ヨウリョウ - オオキサ >= sizeof(struct キオククカク) + 16U) {
                カクホモトバンチ = (struct キオククカク *)((unsigned char *)(シンコウイチ + 1) + オオキサ);
                カクホモトバンチ->ヨウリョウ = シンコウイチ->ヨウリョウ - オオキサ - sizeof(*カクホモトバンチ);
                カクホモトバンチ->ツギノクカク = シンコウイチ->ツギノクカク;
                カクホモトバンチ->リヨウカノウハンテイ = 1;
                シンコウイチ->ツギノクカク = カクホモトバンチ;
                シンコウイチ->ヨウリョウ = オオキサ;
            }
            シンコウイチ->リヨウカノウハンテイ = 0;
            return シンコウイチ + 1;
        }
        サイゴノクカク = シンコウイチ; シンコウイチ = シンコウイチ->ツギノクカク;
    }
    バンチ = ドウテキキオクノシュウタンヲウツス(0);
    if (バンチ == (void *)-1) return カラバンチ;
    セイレツウメコミチョウ = (0U - (バンチハバフゴウナシセイスウ)バンチ) & 15U;
    ゼンタイチョウ = セイレツウメコミチョウ + sizeof(struct キオククカク) + オオキサ;
    if ((バンチハバフゴウナシセイスウ)バンチ > (バンチハバフゴウナシセイスウ)セイスウサイダイチ - ゼンタイチョウ) { アヤマリバンゴウ = アヤマリキオクブソク; return カラバンチ; }
    バンチ = ドウテキキオクノシュウタンヲウツス((int)ゼンタイチョウ);
    if (バンチ == (void *)-1) return カラバンチ;
    カクホモトバンチ = (struct キオククカク *)((unsigned char *)バンチ + セイレツウメコミチョウ);
    カクホモトバンチ->ヨウリョウ = オオキサ; カクホモトバンチ->ツギノクカク = カラバンチ; カクホモトバンチ->リヨウカノウハンテイ = 0;
    if (サイゴノクカク) サイゴノクカク->ツギノクカク = カクホモトバンチ;
    else サイショノクカク = カクホモトバンチ;
    return カクホモトバンチ + 1;
}

void キオクリョウイキヲカエス(void *バンチ)
{
    struct キオククカク *シンコウイチ;
    if (!バンチ) return;
    ((struct キオククカク *)バンチ - 1)->リヨウカノウハンテイ = 1;
    シンコウイチ = サイショノクカク;
    while (シンコウイチ && シンコウイチ->ツギノクカク) {
        struct キオククカク *ツギノクカク = シンコウイチ->ツギノクカク;
        if (シンコウイチ->リヨウカノウハンテイ && ツギノクカク->リヨウカノウハンテイ &&
            (unsigned char *)(シンコウイチ + 1) + シンコウイチ->ヨウリョウ == (unsigned char *)ツギノクカク) {
            シンコウイチ->ヨウリョウ += sizeof(*ツギノクカク) + ツギノクカク->ヨウリョウ;
            シンコウイチ->ツギノクカク = ツギノクカク->ツギノクカク;
        } else シンコウイチ = ツギノクカク;
    }
}

void *レイデミタシタハイレツリョウイキヲカクホスル(オオキサガタ スウリョウ, オオキサガタ ヨウソノオオキサ)
{
    void *バンチ;
    if (ヨウソノオオキサ && スウリョウ > (オオキサガタ)-1 / ヨウソノオオキサ) { アヤマリバンゴウ = アヤマリキオクブソク; return カラバンチ; }
    バンチ = キオクリョウイキヲカクホスル(スウリョウ * ヨウソノオオキサ);
    if (バンチ) キオクリョウイキヲアタイデミタス(バンチ, 0, スウリョウ * ヨウソノオオキサ);
    return バンチ;
}

void *キオクリョウイキノオオキサヲカエル(void *バンチ, オオキサガタ オオキサ)
{
    void *カキコミサキ;
    struct キオククカク *シンコウイチ;
    if (!バンチ) return キオクリョウイキヲカクホスル(オオキサ);
    /* Documented zero-size choice: retain a valid, freeable minimum block. */
    if (!オオキサ) オオキサ = 1;
    シンコウイチ = (struct キオククカク *)バンチ - 1;
    if (オオキサ <= シンコウイチ->ヨウリョウ) return バンチ;
    カキコミサキ = キオクリョウイキヲカクホスル(オオキサ);
    if (!カキコミサキ) return カラバンチ;
    キオクナイヨウヲフクシャスル(カキコミサキ, バンチ, シンコウイチ->ヨウリョウ);
    キオクリョウイキヲカエス(バンチ);
    return カキコミサキ;
}
