int スイヘイクウハクカシラベル(int モジチ) { return モジチ == ' ' || モジチ == '\t'; }
int クウハクモジカシラベル(int モジチ) { return モジチ == ' ' || (モジチ >= '\t' && モジチ <= '\r'); }
int セイギョモジカシラベル(int モジチ) { return (モジチ >= 0 && モジチ < 32) || モジチ == 127; }
