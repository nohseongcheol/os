int コモジニカエル(int モジチ) { return オオモジカシラベル(モジチ) ? モジチ + ('a' - 'A') : モジチ; }
int オオモジニカエル(int モジチ) { return コモジカシラベル(モジチ) ? モジチ - ('a' - 'A') : モジチ; }
