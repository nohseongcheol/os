#include <錯誤編號.h>
#include <檔案控制.h>
#include <系統/檔案狀態.h>
#include <系統/系統身分.h>
#include <系統/子行程等待.h>
#include <輸入輸出與執行.h>

int 宣告編譯試驗(void)
{
    char 工作目錄[8];
    struct 檔案狀態 狀態資料;
    struct 系統身分資訊 系統資料;
    int 檔案描述編號 = 開啟("/USER1", 唯讀開啟);
    int 複製值 = 檔案描述編號 >= 0 ? 複製開啟檔案參照(檔案描述編號) : -1;
    if (複製值 >= 0) 關閉(複製值);
    if (檔案描述編號 >= 0) {
        取得開啟檔案狀態(檔案描述編號, &狀態資料);
        移動讀寫位置(檔案描述編號, 0, 從起點定位);
        關閉(檔案描述編號);
    }
    檔案狀態("/", &狀態資料);
    取得系統資訊(&系統資料);
    取得工作目錄路徑(工作目錄, sizeof(工作目錄));
    return 錯誤編號 + 取得行程編號() + 取得父行程編號();
}
