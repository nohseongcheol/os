#define 检查条件(值) do { if (!(值)) return __LINE__; } while (0)

static int 比较整数(const void *左值, const void *右值)
{
    int 结果 = *(const int *)左值, 值 = *(const int *)右值;
    return (结果 > 值) - (结果 < 值);
}

int 测试函数集行为(void)
{
    char 数据缓冲区域[64], 来源位置[64], *转换末端地址, *保存进度状态, *地址, *目标位置;
    const char *字符串 = "abca", *输入位置 = " 	-0x80rest";
    int 元素数组[257], 索引, 值;
    大小类型 长度;
    整数除法结果类型 结果;
    长整数除法结果类型 解码值;
    char **保存环境列表 = 环境变量列表;
    char *环境列表[] = {"ONE=first", "ONE_MORE=second", "EMPTY=", 空地址};

    检查条件(用值填充内存区域(数据缓冲区域, 0xab, sizeof(数据缓冲区域)) == 数据缓冲区域);
    检查条件((unsigned char)数据缓冲区域[63] == 0xab);
    检查条件(复制内存内容(数据缓冲区域, "abcdef", 7) == 数据缓冲区域);
    检查条件(允许重叠移动内存内容(数据缓冲区域 + 2, 数据缓冲区域, 5) == 数据缓冲区域 + 2);
    检查条件(比较内存内容(数据缓冲区域, "ababcde", 7) == 0);
    检查条件(允许重叠移动内存内容(数据缓冲区域, 数据缓冲区域 + 2, 5) == 数据缓冲区域);
    检查条件(比较内存内容(数据缓冲区域, "abcde", 5) == 0);
    检查条件(允许重叠移动内存内容(数据缓冲区域, 数据缓冲区域, 0) == 数据缓冲区域);
    检查条件(比较内存内容("\x80", "\x7f", 1) > 0);
    检查条件(比较内存内容(数据缓冲区域, 来源位置, 0) == 0);
    检查条件(在内存中查找值(字符串, 'c', 4) == 字符串 + 2);
    检查条件(在内存中查找值(字符串, 0, 5) == 字符串 + 4);
    检查条件(在内存中查找值(字符串, 'z', 4) == 空地址);
    检查条件(取得字符串字节数("한국어") == 9 && 取得限长字符串字节数("한국어", 4) == 4);
    检查条件(取得限长字符串字节数("", 3) == 0 && 取得限长字符串字节数("abc", 0) == 0);
    检查条件(复制字符串(数据缓冲区域, 字符串) == 数据缓冲区域 && 比较字符串(数据缓冲区域, 字符串) == 0);
    检查条件(复制字符串并取得末端(数据缓冲区域, "xy") == 数据缓冲区域 + 2 && 数据缓冲区域[2] == 0);
    用值填充内存区域(数据缓冲区域, 7, sizeof(数据缓冲区域));
    检查条件(定长填充复制字符串(数据缓冲区域, "xy", 5) == 数据缓冲区域);
    检查条件(!比较内存内容(数据缓冲区域, "xy\0\0\0", 5) && 数据缓冲区域[5] == 7);
    检查条件(定长填充复制并取得末端(数据缓冲区域, "abcdef", 3) == 数据缓冲区域 + 3 && 数据缓冲区域[3] == 0);
    检查条件(定长填充复制并取得末端(数据缓冲区域, "a", 4) == 数据缓冲区域 + 1 && 数据缓冲区域[3] == 0);
    检查条件(定长填充复制字符串(数据缓冲区域, "z", 0) == 数据缓冲区域 && 数据缓冲区域[0] == 'a');
    复制字符串(数据缓冲区域, "a");
    检查条件(追加字符串(数据缓冲区域, "bc") == 数据缓冲区域 && !比较字符串(数据缓冲区域, "abc"));
    检查条件(限长追加字符串(数据缓冲区域, "def", 2) == 数据缓冲区域 && !比较字符串(数据缓冲区域, "abcde"));
    检查条件(限长追加字符串(数据缓冲区域, "xyz", 0) == 数据缓冲区域 && !比较字符串(数据缓冲区域, "abcde"));
    检查条件(比较字符串("", "a") < 0 && 比较字符串("\xff", "\x7f") > 0);
    检查条件(限长比较字符串("abc", "abd", 2) == 0 && 限长比较字符串("abc", "abd", 3) < 0);
    检查条件(限长比较字符串("a", "b", 0) == 0 && 按排序规则比较字符串("a", "b") < 0);
    检查条件(生成字符串排序键(空地址, "abc", 0) == 3);
    检查条件(生成字符串排序键(数据缓冲区域, "abc", 4) == 3 && !比较字符串(数据缓冲区域, "abc"));
    检查条件(查找字符串首个值(字符串, 'a') == 字符串 && 查找字符串最后值(字符串, 'a') == 字符串 + 3);
    检查条件(查找字符串首个值(字符串, 0) == 字符串 + 4 && 查找字符串最后值(字符串, 0) == 字符串 + 4);
    检查条件(查找字符串首个值(字符串, 'z') == 空地址 && 查找字符串最后值(字符串, 'z') == 空地址);
    检查条件(查找子字符串(字符串, "bc") == 字符串 + 1 && 查找子字符串(字符串, "") == 字符串);
    检查条件(查找子字符串(字符串, "abcaa") == 空地址 && 查找子字符串(字符串, "z") == 空地址);
    检查条件(取得允许值前缀长度("aaabbz", "ab") == 5 && 取得允许值前缀长度("abc", "") == 0);
    检查条件(取得无排除值前缀长度("aaabbz", "bz") == 3 && 取得无排除值前缀长度("abc", "") == 3);
    检查条件(查找字符串中的集合值(字符串, "cz") == 字符串 + 2 && 查找字符串中的集合值(字符串, "z") == 空地址);
    复制字符串(数据缓冲区域, ",,one;two,,");
    检查条件(!比较字符串(指定状态分割字符串词段(数据缓冲区域, ",;", &保存进度状态), "one"));
    复制字符串(来源位置, "x:y");
    检查条件(!比较字符串(分割字符串词段(来源位置, ":"), "x"));
    检查条件(!比较字符串(指定状态分割字符串词段(空地址, ",;", &保存进度状态), "two"));
    检查条件(指定状态分割字符串词段(空地址, ",;", &保存进度状态) == 空地址);
    检查条件(!比较字符串(分割字符串词段(空地址, ":"), "y") && 分割字符串词段(空地址, ":") == 空地址);
    复制字符串(来源位置, "x,y");
    检查条件(!比较字符串(指定状态分割字符串词段(来源位置, "", &保存进度状态), "x,y"));
    检查条件(指定状态分割字符串词段(空地址, "", &保存进度状态) == 空地址);
    检查条件(忽略大小写比较字符串("aBc", "AbC") == 0 && 忽略大小写比较字符串("a", "B") < 0);
    检查条件(限长忽略大小写比较字符串("aBcX", "AbCy", 3) == 0 && 限长忽略大小写比较字符串("a", "B", 1) < 0);

    for (值 = -1; 值 <= 255; ++值) {
        int 下界 = 值 >= 'a' && 值 <= 'z', 上界 = 值 >= 'A' && 值 <= 'Z';
        int 数字值 = 值 >= '0' && 值 <= '9';
        检查条件(!!检查是否字母(值) == (下界 || 上界));
        检查条件(!!检查是否字母或数字(值) == (下界 || 上界 || 数字值));
        检查条件(!!检查是否十进数字(值) == 数字值);
        检查条件(!!检查是否小写字母(值) == 下界 && !!检查是否大写字母(值) == 上界);
        检查条件(!!检查是否水平空白(值) == (值 == ' ' || 值 == '\t'));
        检查条件(!!检查是否空白字符(值) == (值 == ' ' || (值 >= 9 && 值 <= 13)));
        检查条件(!!检查是否控制字符(值) == ((值 >= 0 && 值 < 32) || 值 == 127));
        检查条件(!!检查是否可印字符(值) == (值 >= 32 && 值 <= 126));
        检查条件(!!检查是否非空白可印字符(值) == (值 >= 33 && 值 <= 126));
        检查条件(!!检查是否标点符号(值) == (值 >= 33 && 值 <= 126 && !下界 && !上界 && !数字值));
        检查条件(!!检查是否十六进数字(值) == (数字值 || (值 >= 'a' && 值 <= 'f') || (值 >= 'A' && 值 <= 'F')));
        检查条件(转换为小写(值) == (上界 ? 值 + 32 : 值));
        检查条件(转换为大写(值) == (下界 ? 值 - 32 : 值));
    }
    错误编号 = 错误输入输出失败;
    检查条件(将字符串读为长整数(输入位置, &转换末端地址, 0) == -128 && !比较字符串(转换末端地址, "rest") && 错误编号 == 错误输入输出失败);
    检查条件(将字符串读为长整数("2147483647", 空地址, 10) == 长整数最大值);
    检查条件(将字符串读为长整数("-2147483648", 空地址, 10) == 长整数最小值);
    错误编号 = 0;
    检查条件(将字符串读为长整数("2147483648xxx", &转换末端地址, 10) == 长整数最大值 && 错误编号 == 错误数值超出范围 && *转换末端地址 == 'x');
    错误编号 = 0;
    检查条件(将字符串读为长整数("-99999999999999999z", &转换末端地址, 10) == 长整数最小值 && 错误编号 == 错误数值超出范围 && *转换末端地址 == 'z');
    检查条件(将字符串读为长整数("077", 空地址, 0) == 63 && 将字符串读为长整数("0Xff", 空地址, 16) == 255);
    字符串 = "-0x";
    检查条件(将字符串读为长整数(字符串, &转换末端地址, 0) == 0 && 转换末端地址 == 字符串 + 2);
    字符串 = "  +z";
    检查条件(将字符串读为长整数(字符串, &转换末端地址, 10) == 0 && 转换末端地址 == 字符串);
    错误编号 = 0;
    检查条件(将字符串读为长整数(字符串, &转换末端地址, 1) == 0 && 错误编号 == 错误参数无效 && 转换末端地址 == 字符串);
    检查条件(将字符串读为长整数("z", 空地址, 36) == 35 && 将字符串读为长整数("101", 空地址, 2) == 5);
    错误编号 = 错误输入输出失败;
    检查条件(将字符串读为无符号长整数("4294967295", 空地址, 10) == 无符号长整数最大值 && 错误编号 == 错误输入输出失败);
    检查条件(将字符串读为无符号长整数("-1", 空地址, 10) == 无符号长整数最大值 && 错误编号 == 错误输入输出失败);
    错误编号 = 错误数值超出范围;
    检查条件(将字符串读为无符号长整数("-2", 空地址, 10) == 无符号长整数最大值 - 1 && 错误编号 == 错误数值超出范围);
    错误编号 = 0;
    检查条件(将字符串读为无符号长整数("-4294967296x", &转换末端地址, 10) == 无符号长整数最大值 && 错误编号 == 错误数值超出范围 && *转换末端地址 == 'x');
    检查条件(将十进字符串读为整数(" -123tail") == -123 && 将十进字符串读为长整数("+456") == 456);
    检查条件(取得整数绝对值(-4) == 4 && 取得整数绝对值(0) == 0 && 取得长整数绝对值(-99L) == 99L);
    结果 = 取得整数商余数(-7, 3); 解码值 = 取得长整数商余数(7L, -3L);
    检查条件(结果.商值 == -2 && 结果.余数 == -1 && 解码值.商值 == -2 && 解码值.余数 == 1);

    for (长度 = 0; 长度 <= 257; ++长度) {
        for (索引 = 0; 索引 < (int)长度; ++索引) 元素数组[索引] = ((索引 * 37 + (int)长度) % 19) - 9;
        按比较规则排序(元素数组, 长度, sizeof(int), 比较整数);
        for (索引 = 1; 索引 < (int)长度; ++索引) 检查条件(元素数组[索引 - 1] <= 元素数组[索引]);
        for (索引 = 0; 索引 < (int)长度; ++索引) {
            int *找到位置 = 在有序数组中二分查找(&元素数组[索引], 元素数组, 长度, sizeof(int), 比较整数);
            检查条件(找到位置 && *找到位置 == 元素数组[索引]);
        }
        值 = 100;
        检查条件(在有序数组中二分查找(&值, 元素数组, 长度, sizeof(int), 比较整数) == 空地址);
    }
    环境变量列表 = 环境列表;
    检查条件(!比较字符串(取得环境变量值("ONE"), "first") && !比较字符串(取得环境变量值("EMPTY"), ""));
    检查条件(取得环境变量值("ON") == 空地址 && 取得环境变量值("") == 空地址 && 取得环境变量值("ONE=first") == 空地址);
    环境变量列表 = 保存环境列表;

    错误编号 = 错误输入输出失败;
    释放内存空间(空地址);
    检查条件(错误编号 == 错误输入输出失败);
    地址 = 分配内存空间(17);
    检查条件(地址 && ((地址宽度无符号整数)地址 & 15U) == 0);
    用值填充内存区域(地址, 0x59, 17);
    目标位置 = 调整内存空间大小(地址, 100);
    检查条件(目标位置);
    for (索引 = 0; 索引 < 17; ++索引) 检查条件(目标位置[索引] == 0x59);
    错误编号 = 0;
    检查条件(调整内存空间大小(目标位置, (大小类型)-1) == 空地址 && 错误编号 == 错误内存不足);
    检查条件(目标位置[0] == 0x59);
    地址 = 调整内存空间大小(目标位置, 3);
    检查条件(地址 == 目标位置 && 地址[0] == 0x59);
    地址 = 调整内存空间大小(目标位置, 0);
    检查条件(地址 && 地址[0] == 0x59);
    错误编号 = 错误输入输出失败;
    释放内存空间(地址);
    检查条件(错误编号 == 错误输入输出失败);
    错误编号 = 0;
    检查条件(分配清零数组空间((大小类型)-1, 2) == 空地址 && 错误编号 == 错误内存不足);
    检查条件(分配内存空间((大小类型)-1) == 空地址 && 错误编号 == 错误内存不足);
    地址 = 分配清零数组空间(19, 3);
    检查条件(地址);
    for (索引 = 0; 索引 < 57; ++索引) 检查条件(地址[索引] == 0);
    释放内存空间(地址);
    地址 = 分配内存空间(0); 检查条件(地址); 释放内存空间(地址);
    地址 = 调整内存空间大小(空地址, 11); 检查条件(地址); 释放内存空间(地址);
    地址 = 在新空间复制字符串("자료"); 检查条件(地址 && !比较字符串(地址, "자료")); 释放内存空间(地址);
    地址 = 限长在新空间复制字符串("abcdef", 3); 检查条件(地址 && !比较字符串(地址, "abc")); 释放内存空间(地址);
    地址 = 限长在新空间复制字符串("abc", 0); 检查条件(地址 && !比较字符串(地址, "")); 释放内存空间(地址);
    /* Repeated use must reuse freed storage instead of growing brk each time. */
    地址 = 分配内存空间(4096); 检查条件(地址); 释放内存空间(地址);
    目标位置 = 移动动态存储末端(0);
    for (索引 = 0; 索引 < 100; ++索引) {
        地址 = 分配内存空间(1024); 检查条件(地址); 用值填充内存区域(地址, 索引, 1024); 释放内存空间(地址);
    }
    检查条件(移动动态存储末端(0) == 目标位置);
    return 0;
}
