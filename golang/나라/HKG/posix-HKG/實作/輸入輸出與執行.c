int 檢查是否終端(int 檔案描述編號)
{
    struct 檔案狀態 狀態資料;
    if (取得開啟檔案狀態(檔案描述編號, &狀態資料) < 0)
        return 0;
    if (!檢查字元裝置模式(狀態資料.檔案類型與權限)) {
        錯誤編號 = 錯誤裝置不適用操作;
        return 0;
    }
    return 1;
}

int 設定動態記憶末端(void *位址)
{
    long 結果 = 單引數系統呼叫(系統呼叫_設定動態記憶末端, 位址);
    if (結果 != (long)位址) {
        錯誤編號 = 錯誤記憶體不足;
        return -1;
    }
    return 0;
}

void *移動動態記憶末端(int 增量)
{
    long 目前末端 = 單引數系統呼叫(系統呼叫_設定動態記憶末端, 0);
    long 要求末端 = 目前末端 + 增量;
    if (增量 != 0 && 設定動態記憶末端((void *)要求末端) < 0)
        return (void *)-1;
    return (void *)目前末端;
}

行程編號型別 等待指定子行程(行程編號型別 行程編號, int *結束狀態, int 選項)
{
    long 結果;
    do {
        結果 = 三引數系統呼叫(7, 行程編號, 結束狀態, 選項);
    } while (結果 == -錯誤暫時無法使用 && (選項 & 未就緒則不等待) == 0);
    return (行程編號型別)__syscall_result(結果);
}

行程編號型別 等待子行程(int *結束狀態)
{
    return 等待指定子行程(-1, 結束狀態, 0);
}
