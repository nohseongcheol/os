#define 檢查條件(值) do { if (!(值)) return __LINE__; } while (0)

static int 比較整數(const void *左值, const void *右值)
{
    int 結果 = *(const int *)左值, 值 = *(const int *)右值;
    return (結果 > 值) - (結果 < 值);
}

int 測試函式集行為(void)
{
    char 資料緩衝區域[64], 來源位置[64], *轉換末端位址, *保存進度狀態, *位址, *目標位置;
    const char *字串 = "abca", *輸入位置 = " 	-0x80rest";
    int 元素陣列[257], 索引, 值;
    大小型別 長度;
    整數除法結果型別 結果;
    長整數除法結果型別 解碼值;
    char **保存環境列表 = 環境變數列表;
    char *環境列表[] = {"ONE=first", "ONE_MORE=second", "EMPTY=", 空位址};

    檢查條件(以值填滿記憶區域(資料緩衝區域, 0xab, sizeof(資料緩衝區域)) == 資料緩衝區域);
    檢查條件((unsigned char)資料緩衝區域[63] == 0xab);
    檢查條件(複製記憶內容(資料緩衝區域, "abcdef", 7) == 資料緩衝區域);
    檢查條件(允許重疊移動記憶內容(資料緩衝區域 + 2, 資料緩衝區域, 5) == 資料緩衝區域 + 2);
    檢查條件(比較記憶內容(資料緩衝區域, "ababcde", 7) == 0);
    檢查條件(允許重疊移動記憶內容(資料緩衝區域, 資料緩衝區域 + 2, 5) == 資料緩衝區域);
    檢查條件(比較記憶內容(資料緩衝區域, "abcde", 5) == 0);
    檢查條件(允許重疊移動記憶內容(資料緩衝區域, 資料緩衝區域, 0) == 資料緩衝區域);
    檢查條件(比較記憶內容("\x80", "\x7f", 1) > 0);
    檢查條件(比較記憶內容(資料緩衝區域, 來源位置, 0) == 0);
    檢查條件(在記憶中尋找值(字串, 'c', 4) == 字串 + 2);
    檢查條件(在記憶中尋找值(字串, 0, 5) == 字串 + 4);
    檢查條件(在記憶中尋找值(字串, 'z', 4) == 空位址);
    檢查條件(取得字串位元組數("한국어") == 9 && 取得限長字串位元組數("한국어", 4) == 4);
    檢查條件(取得限長字串位元組數("", 3) == 0 && 取得限長字串位元組數("abc", 0) == 0);
    檢查條件(複製字串(資料緩衝區域, 字串) == 資料緩衝區域 && 比較字串(資料緩衝區域, 字串) == 0);
    檢查條件(複製字串並取得末端(資料緩衝區域, "xy") == 資料緩衝區域 + 2 && 資料緩衝區域[2] == 0);
    以值填滿記憶區域(資料緩衝區域, 7, sizeof(資料緩衝區域));
    檢查條件(定長填補複製字串(資料緩衝區域, "xy", 5) == 資料緩衝區域);
    檢查條件(!比較記憶內容(資料緩衝區域, "xy\0\0\0", 5) && 資料緩衝區域[5] == 7);
    檢查條件(定長填補複製並取得末端(資料緩衝區域, "abcdef", 3) == 資料緩衝區域 + 3 && 資料緩衝區域[3] == 0);
    檢查條件(定長填補複製並取得末端(資料緩衝區域, "a", 4) == 資料緩衝區域 + 1 && 資料緩衝區域[3] == 0);
    檢查條件(定長填補複製字串(資料緩衝區域, "z", 0) == 資料緩衝區域 && 資料緩衝區域[0] == 'a');
    複製字串(資料緩衝區域, "a");
    檢查條件(附加字串(資料緩衝區域, "bc") == 資料緩衝區域 && !比較字串(資料緩衝區域, "abc"));
    檢查條件(限長附加字串(資料緩衝區域, "def", 2) == 資料緩衝區域 && !比較字串(資料緩衝區域, "abcde"));
    檢查條件(限長附加字串(資料緩衝區域, "xyz", 0) == 資料緩衝區域 && !比較字串(資料緩衝區域, "abcde"));
    檢查條件(比較字串("", "a") < 0 && 比較字串("\xff", "\x7f") > 0);
    檢查條件(限長比較字串("abc", "abd", 2) == 0 && 限長比較字串("abc", "abd", 3) < 0);
    檢查條件(限長比較字串("a", "b", 0) == 0 && 依排序規則比較字串("a", "b") < 0);
    檢查條件(產生字串排序鍵(空位址, "abc", 0) == 3);
    檢查條件(產生字串排序鍵(資料緩衝區域, "abc", 4) == 3 && !比較字串(資料緩衝區域, "abc"));
    檢查條件(尋找字串首個值(字串, 'a') == 字串 && 尋找字串最後值(字串, 'a') == 字串 + 3);
    檢查條件(尋找字串首個值(字串, 0) == 字串 + 4 && 尋找字串最後值(字串, 0) == 字串 + 4);
    檢查條件(尋找字串首個值(字串, 'z') == 空位址 && 尋找字串最後值(字串, 'z') == 空位址);
    檢查條件(尋找子字串(字串, "bc") == 字串 + 1 && 尋找子字串(字串, "") == 字串);
    檢查條件(尋找子字串(字串, "abcaa") == 空位址 && 尋找子字串(字串, "z") == 空位址);
    檢查條件(取得允許值前綴長度("aaabbz", "ab") == 5 && 取得允許值前綴長度("abc", "") == 0);
    檢查條件(取得無排除值前綴長度("aaabbz", "bz") == 3 && 取得無排除值前綴長度("abc", "") == 3);
    檢查條件(尋找字串中的集合值(字串, "cz") == 字串 + 2 && 尋找字串中的集合值(字串, "z") == 空位址);
    複製字串(資料緩衝區域, ",,one;two,,");
    檢查條件(!比較字串(指定狀態分割字串詞段(資料緩衝區域, ",;", &保存進度狀態), "one"));
    複製字串(來源位置, "x:y");
    檢查條件(!比較字串(分割字串詞段(來源位置, ":"), "x"));
    檢查條件(!比較字串(指定狀態分割字串詞段(空位址, ",;", &保存進度狀態), "two"));
    檢查條件(指定狀態分割字串詞段(空位址, ",;", &保存進度狀態) == 空位址);
    檢查條件(!比較字串(分割字串詞段(空位址, ":"), "y") && 分割字串詞段(空位址, ":") == 空位址);
    複製字串(來源位置, "x,y");
    檢查條件(!比較字串(指定狀態分割字串詞段(來源位置, "", &保存進度狀態), "x,y"));
    檢查條件(指定狀態分割字串詞段(空位址, "", &保存進度狀態) == 空位址);
    檢查條件(忽略大小寫比較字串("aBc", "AbC") == 0 && 忽略大小寫比較字串("a", "B") < 0);
    檢查條件(限長忽略大小寫比較字串("aBcX", "AbCy", 3) == 0 && 限長忽略大小寫比較字串("a", "B", 1) < 0);

    for (值 = -1; 值 <= 255; ++值) {
        int 下界 = 值 >= 'a' && 值 <= 'z', 上界 = 值 >= 'A' && 值 <= 'Z';
        int 數字值 = 值 >= '0' && 值 <= '9';
        檢查條件(!!檢查是否字母(值) == (下界 || 上界));
        檢查條件(!!檢查是否字母或數字(值) == (下界 || 上界 || 數字值));
        檢查條件(!!檢查是否十進數字(值) == 數字值);
        檢查條件(!!檢查是否小寫字母(值) == 下界 && !!檢查是否大寫字母(值) == 上界);
        檢查條件(!!檢查是否水平空白(值) == (值 == ' ' || 值 == '\t'));
        檢查條件(!!檢查是否空白字元(值) == (值 == ' ' || (值 >= 9 && 值 <= 13)));
        檢查條件(!!檢查是否控制字元(值) == ((值 >= 0 && 值 < 32) || 值 == 127));
        檢查條件(!!檢查是否可印字元(值) == (值 >= 32 && 值 <= 126));
        檢查條件(!!檢查是否非空白可印字元(值) == (值 >= 33 && 值 <= 126));
        檢查條件(!!檢查是否標點符號(值) == (值 >= 33 && 值 <= 126 && !下界 && !上界 && !數字值));
        檢查條件(!!檢查是否十六進數字(值) == (數字值 || (值 >= 'a' && 值 <= 'f') || (值 >= 'A' && 值 <= 'F')));
        檢查條件(轉換為小寫(值) == (上界 ? 值 + 32 : 值));
        檢查條件(轉換為大寫(值) == (下界 ? 值 - 32 : 值));
    }
    錯誤編號 = 錯誤輸入輸出失敗;
    檢查條件(將字串讀為長整數(輸入位置, &轉換末端位址, 0) == -128 && !比較字串(轉換末端位址, "rest") && 錯誤編號 == 錯誤輸入輸出失敗);
    檢查條件(將字串讀為長整數("2147483647", 空位址, 10) == 長整數最大值);
    檢查條件(將字串讀為長整數("-2147483648", 空位址, 10) == 長整數最小值);
    錯誤編號 = 0;
    檢查條件(將字串讀為長整數("2147483648xxx", &轉換末端位址, 10) == 長整數最大值 && 錯誤編號 == 錯誤數值超出範圍 && *轉換末端位址 == 'x');
    錯誤編號 = 0;
    檢查條件(將字串讀為長整數("-99999999999999999z", &轉換末端位址, 10) == 長整數最小值 && 錯誤編號 == 錯誤數值超出範圍 && *轉換末端位址 == 'z');
    檢查條件(將字串讀為長整數("077", 空位址, 0) == 63 && 將字串讀為長整數("0Xff", 空位址, 16) == 255);
    字串 = "-0x";
    檢查條件(將字串讀為長整數(字串, &轉換末端位址, 0) == 0 && 轉換末端位址 == 字串 + 2);
    字串 = "  +z";
    檢查條件(將字串讀為長整數(字串, &轉換末端位址, 10) == 0 && 轉換末端位址 == 字串);
    錯誤編號 = 0;
    檢查條件(將字串讀為長整數(字串, &轉換末端位址, 1) == 0 && 錯誤編號 == 錯誤引數無效 && 轉換末端位址 == 字串);
    檢查條件(將字串讀為長整數("z", 空位址, 36) == 35 && 將字串讀為長整數("101", 空位址, 2) == 5);
    錯誤編號 = 錯誤輸入輸出失敗;
    檢查條件(將字串讀為無號長整數("4294967295", 空位址, 10) == 無號長整數最大值 && 錯誤編號 == 錯誤輸入輸出失敗);
    檢查條件(將字串讀為無號長整數("-1", 空位址, 10) == 無號長整數最大值 && 錯誤編號 == 錯誤輸入輸出失敗);
    錯誤編號 = 錯誤數值超出範圍;
    檢查條件(將字串讀為無號長整數("-2", 空位址, 10) == 無號長整數最大值 - 1 && 錯誤編號 == 錯誤數值超出範圍);
    錯誤編號 = 0;
    檢查條件(將字串讀為無號長整數("-4294967296x", &轉換末端位址, 10) == 無號長整數最大值 && 錯誤編號 == 錯誤數值超出範圍 && *轉換末端位址 == 'x');
    檢查條件(將十進字串讀為整數(" -123tail") == -123 && 將十進字串讀為長整數("+456") == 456);
    檢查條件(取得整數絕對值(-4) == 4 && 取得整數絕對值(0) == 0 && 取得長整數絕對值(-99L) == 99L);
    結果 = 取得整數商餘數(-7, 3); 解碼值 = 取得長整數商餘數(7L, -3L);
    檢查條件(結果.商值 == -2 && 結果.餘數 == -1 && 解碼值.商值 == -2 && 解碼值.餘數 == 1);

    for (長度 = 0; 長度 <= 257; ++長度) {
        for (索引 = 0; 索引 < (int)長度; ++索引) 元素陣列[索引] = ((索引 * 37 + (int)長度) % 19) - 9;
        依比較規則排序(元素陣列, 長度, sizeof(int), 比較整數);
        for (索引 = 1; 索引 < (int)長度; ++索引) 檢查條件(元素陣列[索引 - 1] <= 元素陣列[索引]);
        for (索引 = 0; 索引 < (int)長度; ++索引) {
            int *找到位置 = 在有序陣列中二分搜尋(&元素陣列[索引], 元素陣列, 長度, sizeof(int), 比較整數);
            檢查條件(找到位置 && *找到位置 == 元素陣列[索引]);
        }
        值 = 100;
        檢查條件(在有序陣列中二分搜尋(&值, 元素陣列, 長度, sizeof(int), 比較整數) == 空位址);
    }
    環境變數列表 = 環境列表;
    檢查條件(!比較字串(取得環境變數值("ONE"), "first") && !比較字串(取得環境變數值("EMPTY"), ""));
    檢查條件(取得環境變數值("ON") == 空位址 && 取得環境變數值("") == 空位址 && 取得環境變數值("ONE=first") == 空位址);
    環境變數列表 = 保存環境列表;

    錯誤編號 = 錯誤輸入輸出失敗;
    釋放記憶空間(空位址);
    檢查條件(錯誤編號 == 錯誤輸入輸出失敗);
    位址 = 配置記憶空間(17);
    檢查條件(位址 && ((位址寬度無號整數)位址 & 15U) == 0);
    以值填滿記憶區域(位址, 0x59, 17);
    目標位置 = 調整記憶空間大小(位址, 100);
    檢查條件(目標位置);
    for (索引 = 0; 索引 < 17; ++索引) 檢查條件(目標位置[索引] == 0x59);
    錯誤編號 = 0;
    檢查條件(調整記憶空間大小(目標位置, (大小型別)-1) == 空位址 && 錯誤編號 == 錯誤記憶體不足);
    檢查條件(目標位置[0] == 0x59);
    位址 = 調整記憶空間大小(目標位置, 3);
    檢查條件(位址 == 目標位置 && 位址[0] == 0x59);
    位址 = 調整記憶空間大小(目標位置, 0);
    檢查條件(位址 && 位址[0] == 0x59);
    錯誤編號 = 錯誤輸入輸出失敗;
    釋放記憶空間(位址);
    檢查條件(錯誤編號 == 錯誤輸入輸出失敗);
    錯誤編號 = 0;
    檢查條件(配置清零陣列空間((大小型別)-1, 2) == 空位址 && 錯誤編號 == 錯誤記憶體不足);
    檢查條件(配置記憶空間((大小型別)-1) == 空位址 && 錯誤編號 == 錯誤記憶體不足);
    位址 = 配置清零陣列空間(19, 3);
    檢查條件(位址);
    for (索引 = 0; 索引 < 57; ++索引) 檢查條件(位址[索引] == 0);
    釋放記憶空間(位址);
    位址 = 配置記憶空間(0); 檢查條件(位址); 釋放記憶空間(位址);
    位址 = 調整記憶空間大小(空位址, 11); 檢查條件(位址); 釋放記憶空間(位址);
    位址 = 在新空間複製字串("자료"); 檢查條件(位址 && !比較字串(位址, "자료")); 釋放記憶空間(位址);
    位址 = 限長在新空間複製字串("abcdef", 3); 檢查條件(位址 && !比較字串(位址, "abc")); 釋放記憶空間(位址);
    位址 = 限長在新空間複製字串("abc", 0); 檢查條件(位址 && !比較字串(位址, "")); 釋放記憶空間(位址);
    /* Repeated use must reuse freed storage instead of growing brk each time. */
    位址 = 配置記憶空間(4096); 檢查條件(位址); 釋放記憶空間(位址);
    目標位置 = 移動動態記憶末端(0);
    for (索引 = 0; 索引 < 100; ++索引) {
        位址 = 配置記憶空間(1024); 檢查條件(位址); 以值填滿記憶區域(位址, 索引, 1024); 釋放記憶空間(位址);
    }
    檢查條件(移動動態記憶末端(0) == 目標位置);
    return 0;
}
