static int 檢查次數;
static int 失敗次數;

static unsigned int 文字位元組長度(const char *字串)
{
    unsigned int 長度 = 0;
    while (字串[長度] != 0)
        長度++;
    return 長度;
}

static int 檢查文字相等(const char *左值, const char *右值)
{
    unsigned int 項目索引 = 0;
    while (左值[項目索引] != 0 && 右值[項目索引] != 0) {
        if (左值[項目索引] != 右值[項目索引])
            return 0;
        項目索引++;
    }
    return 左值[項目索引] == 右值[項目索引];
}

static void 寫出訊息(const char *字串)
{
    (void)寫入(標準輸出編號, 字串, 文字位元組長度(字串));
}

static void 報告結果(const char *系統資料, int 通過旗標)
{
    檢查次數++;
    if (通過旗標) {
        寫出訊息("PTEST:PASS:");
    } else {
        失敗次數++;
        寫出訊息("PTEST:FAIL:");
    }
    寫出訊息(系統資料);
    寫出訊息("\n");
}

static int 檢查是否指定錯誤(int 結果, int 預期錯誤編號)
{
    return 結果 == -1 && 錯誤編號 == 預期錯誤編號;
}

static 行程編號型別 不等待回收子行程(行程編號型別 子項位置, int *結束狀態)
{
    unsigned int 迴圈次數;
    行程編號型別 結果;

    for (迴圈次數 = 0; 迴圈次數 < 2000000U; 迴圈次數++) {
        結果 = 等待指定子行程(子項位置, 結束狀態, 未就緒則不等待);
        if (結果 != 0)
            return 結果;
    }
    return 0;
}

