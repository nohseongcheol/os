static int 数字値を得る(unsigned char 文字値)
{
    if (十進数字か調べる(文字値)) return 文字値 - '0';
    if (英字か調べる(文字値)) return 小文字に変える(文字値) - 'a' + 10;
    return 36;
}

static unsigned long 符号なし数を解釈する(const char *文字列, char **変換終端番地,
                                    int 基数, int 符号なし判定, int *負数判定, int *範囲超過判定)
{
    const char *進行位置 = 文字列, *最初の一致位置;
    unsigned long 大きさの値 = 0, 最大値;
    int 数字値;
    if (変換終端番地) *変換終端番地 = (char *)文字列;
    *負数判定 = 0;
    *範囲超過判定 = 0;
    if (基数 && (基数 < 2 || 基数 > 36)) { 誤り番号 = 誤り引数不正; return 0; }
    while (空白文字か調べる((unsigned char)*進行位置)) ++進行位置;
    if (*進行位置 == '+' || *進行位置 == '-') { *負数判定 = *進行位置 == '-'; ++進行位置; }
    if ((基数 == 0 || 基数 == 16) && 進行位置[0] == '0' &&
        (進行位置[1] == 'x' || 進行位置[1] == 'X') && 数字値を得る((unsigned char)進行位置[2]) < 16) {
        進行位置 += 2; 基数 = 16;
    }
    if (!基数) 基数 = *進行位置 == '0' ? 8 : 10;
    最大値 = 符号なし判定 ? 符号なし長整数最大値 : (unsigned long)長整数最大値 + (unsigned long)*負数判定;
    最初の一致位置 = 進行位置;
    while ((数字値 = 数字値を得る((unsigned char)*進行位置)) < 基数) {
        if (大きさの値 > (最大値 - (unsigned long)数字値) / (unsigned long)基数)
            *範囲超過判定 = 1;
        else if (!*範囲超過判定)
            大きさの値 = 大きさの値 * (unsigned long)基数 + (unsigned long)数字値;
        ++進行位置;
    }
    if (進行位置 == 最初の一致位置) return 0;
    if (変換終端番地) *変換終端番地 = (char *)進行位置;
    if (*範囲超過判定) { 誤り番号 = 誤り値範囲外; return 最大値; }
    return 大きさの値;
}

long 文字列を長整数として読む(const char *文字列, char **変換終端番地, int 基数)
{
    int 負数判定, 範囲超過判定;
    unsigned long 大きさの値 = 符号なし数を解釈する(文字列, 変換終端番地, 基数, 0, &負数判定, &範囲超過判定);
    if (!負数判定) return (long)大きさの値;
    return 大きさの値 == (unsigned long)長整数最大値 + 1UL ? 長整数最小値 : -(long)大きさの値;
}

unsigned long 文字列を符号なし長整数として読む(const char *文字列, char **変換終端番地, int 基数)
{
    int 負数判定, 範囲超過判定;
    unsigned long 大きさの値 = 符号なし数を解釈する(文字列, 変換終端番地, 基数, 1, &負数判定, &範囲超過判定);
    if (範囲超過判定) return 符号なし長整数最大値;
    return 負数判定 ? 0UL - 大きさの値 : 大きさの値;
}

