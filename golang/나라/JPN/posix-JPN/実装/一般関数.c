static void 要素を交換する(unsigned char *左の値, unsigned char *右の値, 大きさ型 要素の大きさ)
{
    while (要素の大きさ--) { unsigned char 一時値 = *左の値; *左の値++ = *右の値; *右の値++ = 一時値; }
}

static void 下方へ整列を直す(unsigned char *要素配列, 大きさ型 降下位置, 大きさ型 数量,
                      大きさ型 要素の大きさ, int (*比較関数)(const void *, const void *))
{
    while (降下位置 < 数量 / 2) {
        大きさ型 子の位置 = 降下位置 * 2 + 1;
        if (子の位置 + 1 < 数量 && 比較関数(要素配列 + 子の位置 * 要素の大きさ, 要素配列 + (子の位置 + 1) * 要素の大きさ) < 0)
            ++子の位置;
        if (比較関数(要素配列 + 降下位置 * 要素の大きさ, 要素配列 + 子の位置 * 要素の大きさ) >= 0) return;
        要素を交換する(要素配列 + 降下位置 * 要素の大きさ, 要素配列 + 子の位置 * 要素の大きさ, 要素の大きさ);
        降下位置 = 子の位置;
    }
}

void 比較基準で整列する(void *要素配列, 大きさ型 数量, 大きさ型 要素の大きさ,
           int (*比較関数)(const void *, const void *))
{
    unsigned char *進行位置 = 要素配列;
    大きさ型 添字;
    if (数量 < 2 || !要素の大きさ || 数量 > (大きさ型)-1 / 要素の大きさ) return;
    /* Heap sort: bounded stack, O(n log n), comparator receives array elements. */
    for (添字 = 数量 / 2; 添字; ) 下方へ整列を直す(進行位置, --添字, 数量, 要素の大きさ, 比較関数);
    for (添字 = 数量 - 1; 添字; --添字) {
        要素を交換する(進行位置, 進行位置 + 添字 * 要素の大きさ, 要素の大きさ);
        下方へ整列を直す(進行位置, 0, 添字, 要素の大きさ, 比較関数);
    }
}

void *整列済み配列を二分探索する(const void *読出元, const void *要素配列, 大きさ型 数量,
              大きさ型 要素の大きさ, int (*比較関数)(const void *, const void *))
{
    大きさ型 下境界 = 0, 上境界 = 数量;
    const unsigned char *進行位置 = 要素配列;
    if (!要素の大きさ || 数量 > (大きさ型)-1 / 要素の大きさ) return 空番地;
    while (下境界 < 上境界) {
        大きさ型 中央位置 = 下境界 + (上境界 - 下境界) / 2;
        int 結果 = 比較関数(読出元, 進行位置 + 中央位置 * 要素の大きさ);
        if (!結果) return (void *)(進行位置 + 中央位置 * 要素の大きさ);
        if (結果 < 0) 上境界 = 中央位置;
        else 下境界 = 中央位置 + 1;
    }
    return 空番地;
}

char *環境変数の値を得る(const char *名前)
{
    大きさ型 長さ = 文字列の八桁組数を得る(名前);
    char **進行位置 = 環境変数一覧;
    if (!長さ || 文字列から最初の値を探す(名前, '=') || !進行位置) return 空番地;
    while (*進行位置) {
        if (!上限内で文字列を比較する(*進行位置, 名前, 長さ) && (*進行位置)[長さ] == '=') return *進行位置 + 長さ + 1;
        ++進行位置;
    }
    return 空番地;
}
