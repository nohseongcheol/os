int 端末か調べる(int 文書記述番号)
{
    struct 文書状態 状態資料;
    if (開いた文書の状態を得る(文書記述番号, &状態資料) < 0)
        return 0;
    if (!文字装置方式判定(状態資料.文書種類と権限)) {
        誤り番号 = 誤り装置不適合操作;
        return 0;
    }
    return 1;
}

int 動的記憶の終端を定める(void *番地)
{
    long 結果 = 引数一つ体系呼出し(体系呼出_動的記憶の終端を定める, 番地);
    if (結果 != (long)番地) {
        誤り番号 = 誤り記憶不足;
        return -1;
    }
    return 0;
}

void *動的記憶の終端を移す(int 増分)
{
    long 現在終端 = 引数一つ体系呼出し(体系呼出_動的記憶の終端を定める, 0);
    long 要求終端 = 現在終端 + 増分;
    if (増分 != 0 && 動的記憶の終端を定める((void *)要求終端) < 0)
        return (void *)-1;
    return (void *)現在終端;
}

実行過程番号型 指定した子を待つ(実行過程番号型 実行過程番号, int *終了状態, int 選択事項)
{
    long 結果;
    do {
        結果 = 引数三つ体系呼出し(7, 実行過程番号, 終了状態, 選択事項);
    } while (結果 == -誤り一時利用不可 && (選択事項 & 未準備なら待たない) == 0);
    return (実行過程番号型)__syscall_result(結果);
}

