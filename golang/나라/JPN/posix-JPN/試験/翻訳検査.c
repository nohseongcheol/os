#include <誤り番号.h>
#include <文書制御.h>
#include <体系/文書状態.h>
#include <体系/体系情報.h>
#include <体系/子の待機.h>
#include <入出力と実行.h>

int 宣言翻訳試験(void)
{
    char 作業目録[8];
    struct 文書状態 状態資料;
    struct 体系情報 名前;
    int 文書記述番号 = 開く("/USER1", 読取専用で開く);
    int 複写値 = 文書記述番号 >= 0 ? 開いた文書の参照を複製する(文書記述番号) : -1;
    if (複写値 >= 0) 閉じる(複写値);
    if (文書記述番号 >= 0) {
        開いた文書の状態を得る(文書記述番号, &状態資料);
        読み書き位置を移す(文書記述番号, 0, 先頭基準位置);
        閉じる(文書記述番号);
    }
    文書状態("/", &状態資料);
    体系情報を得る(&名前);
    作業目録の経路を得る(作業目録, sizeof(作業目録));
    return 誤り番号 + 実行過程番号を得る() + 親実行過程番号を得る();
}
