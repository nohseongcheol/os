#include <errno.h>
#include <fcntl.h>
#include <система/stat.h>
#include <система/сведения_о_системе.h>
#include <система/ожидание_потомков.h>
#include <unistd.h>

int posix_compile_test(void)
{
    char cwd[8];
    struct состояние_файла st;
    struct utsname сведения_о_системе;
    int дескриптор_файла = открыть("/USER1", O_RDONLY);
    int copy = дескриптор_файла >= 0 ? дублировать_ссылку_на_открытый_файл(дескриптор_файла) : -1;
    if (copy >= 0) закрыть(copy);
    if (дескриптор_файла >= 0) {
        получить_состояние_открытого_файла(дескриптор_файла, &st);
        переместить_позицию_файла(дескриптор_файла, 0, SEEK_SET);
        закрыть(дескриптор_файла);
    }
    состояние_файла("/", &st);
    получить_сведения_о_системе(&сведения_о_системе);
    получить_путь_рабочего_каталога(cwd, sizeof(cwd));
    return errno + получить_номер_процесса() + получить_номер_родительского_процесса();
}
