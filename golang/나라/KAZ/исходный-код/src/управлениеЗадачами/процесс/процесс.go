func (текущий *Процесс) Init(mem *mem.TПамятьдиспетчер) {
	текущий.Потоксписок = Linkedсписок{}
	текущий.Threads = &текущий.Потоксписок
	текущий.Threads.Init(mem)
}

type Процессhelper struct {
	процессы			Linkedсписок
	mem				*mem.TПамятьдиспетчер
	ядространицакаталогзапись	uintptr
}

func (текущий *Процессhelper) Init(mem *mem.TПамятьдиспетчер, ядространицакаталогзапись uintptr) {
	текущий.mem = mem
	текущий.процессы = Linkedсписок{}
	текущий.процессы.Init(текущий.mem)
	текущий.ядространицакаталогзапись = ядространицакаталогзапись
}

func (текущий *Процессhelper) Создать(записьpoint func(), потокhelper *TПотокhelper, Страницакаталогзапись uint32, isядро bool) Процесс {
	процесс := (*Процесс)(текущий.mem.Выделить_память(uint32(Sizeof(Процесс{}))))
	if процесс == nil {
		return Процесс{}
	}
	процесс.Init(текущий.mem)
	процесс.иДЕНТИФИКАТОР = Allocatepid()
	процесс.Страницакаталогзапись = uintptr(Страницакаталогзапись)
	главныйпоток := потокhelper.СоздатьУказателиfromФункция(записьpoint, Страницакаталогзапись, isядро)
	if главныйпоток != nil {
		главныйпоток.Pid = процесс.иДЕНТИФИКАТОР
		главныйпоток.Родительpid = 0
		процесс.Threads.Добавить_в_конец_списка(uintptr(Pointer(главныйпоток)))
	}

	текущий.процессы.Добавить_в_конец_списка(uintptr(Pointer(процесс)))

	return *процесс
}

func (текущий *Процессhelper) Spawn(записьpoint func(), потокhelper *TПотокhelper, планировщик *Планировщик, Страницакаталогзапись uint32, isядро bool) Процесс {
	процесс := текущий.Создать(записьpoint, потокhelper, Страницакаталогзапись, isядро)
	if процесс.Threads != nil && процесс.Threads.Размер_2 > 0 {
		поток := (*TПоток)(процесс.Threads.Getat(0))
		if поток != nil && планировщик != nil {
			планировщик.Добавитьпоток(поток)
		}
	}
	return процесс
}

