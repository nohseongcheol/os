#include <오류번호.h>
#include <자료철제어.h>
#include <체계/자료철상태.h>
#include <체계/체제정보.h>
#include <체계/자식대기.h>
#include <입출력과실행.h>

int 선언번역시험(void)
{
    char 작업목록[8];
    struct 자료철상태 상태자료;
    struct 체제정보 이름;
    int 자료철서술번호 = 열기("/USER1", 읽기전용열기);
    int 복사값 = 자료철서술번호 >= 0 ? 열린자료참조복제하기(자료철서술번호) : -1;
    if (복사값 >= 0) 닫기(복사값);
    if (자료철서술번호 >= 0) {
        열린자료철상태얻기(자료철서술번호, &상태자료);
        자료위치옮기기(자료철서술번호, 0, 처음기준위치);
        닫기(자료철서술번호);
    }
    자료철상태("/", &상태자료);
    체제정보얻기(&이름);
    작업목록경로얻기(작업목록, sizeof(작업목록));
    return 오류번호 + 실행과정번호얻기() + 부모실행과정번호얻기();
}
