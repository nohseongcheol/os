const Proc사용자동적기억공간크기 = 1 * 1024 * 1024

type T실행과정 struct {
	식별자		uint32
	체계호출번호	int
	Is사용자공간		bool
	인자들		*[]byte

	T실행흐름목록	T연결목록
	V실행흐름목록	*T연결목록
	F파일이름	[]byte

	P기억쪽상위표항목	uintptr
}

func (자신 *T실행과정) F관문초기화(기억관리 *기억관리.T기억공간관리자) {
	자신.T실행흐름목록 = T연결목록{}
	자신.V실행흐름목록 = &자신.T실행흐름목록
	자신.V실행흐름목록.F관문초기화(기억관리)
}

type T실행과정도우미 struct {
	실행과정_2	T연결목록
	기억관리	*기억관리.T기억공간관리자
	핵심기억쪽상위표항목	uintptr
}

func (자신 *T실행과정도우미) F관문초기화(기억관리 *기억관리.T기억공간관리자, 핵심기억쪽상위표항목 uintptr) {
	자신.기억관리 = 기억관리
	자신.실행과정_2 = T연결목록{}
	자신.실행과정_2.F관문초기화(자신.기억관리)
	자신.핵심기억쪽상위표항목 = 핵심기억쪽상위표항목
}

func (자신 *T실행과정도우미) M실행과정생성(진입함수 func(), 실행흐름도우미 *T실행흐름도우미, P기억쪽상위표항목 uint32, 핵심영역여부 bool) T실행과정 {
	실행과정 := (*T실행과정)(자신.기억관리.M기억공간할당(uint32(Sizeof(T실행과정{}))))
	if 실행과정 == nil {
		return T실행과정{}
	}
	실행과정.F관문초기화(자신.기억관리)
	실행과정.식별자 = F과정식별자할당()
	실행과정.P기억쪽상위표항목 = uintptr(P기억쪽상위표항목)
	주요실행흐름 := 실행흐름도우미.M함수에서실행흐름주소생성(진입함수, P기억쪽상위표항목, 핵심영역여부)
	if 주요실행흐름 != nil {
		주요실행흐름.P과정식별자 = 실행과정.식별자
		주요실행흐름.P부모과정식별자 = 0
		실행과정.V실행흐름목록.M맨뒤에추가(uintptr(Pointer(주요실행흐름)))
	}

	자신.실행과정_2.M맨뒤에추가(uintptr(Pointer(실행과정)))

	return *실행과정
}

func (자신 *T실행과정도우미) M실행과정생성후등록(진입함수 func(), 실행흐름도우미 *T실행흐름도우미, 작업배정기 *T작업배정기, P기억쪽상위표항목 uint32, 핵심영역여부 bool) T실행과정 {
	실행과정 := 자신.M실행과정생성(진입함수, 실행흐름도우미, P기억쪽상위표항목, 핵심영역여부)
	if 실행과정.V실행흐름목록 != nil && 실행과정.V실행흐름목록.S크기_2 > 0 {
		실행흐름 := (*T실행흐름)(실행과정.V실행흐름목록.M지정위치자료가져오기(0))
		if 실행흐름 != nil && 작업배정기 != nil {
			작업배정기.M실행흐름추가(실행흐름)
		}
	}
	return 실행과정
}

func (자신 *T실행과정도우미) 복사기억쪽상위표(출발지항목 uintptr, 목적지항목 uintptr) {
	출발지_2 := F주소에서정수32배열참조(출발지항목, 1024, 1024)
	목적지_2 := F주소에서정수32배열참조(목적지항목, 1024, 1024)

	for i := uint32(0); i < 1024; i++ {
		목적지_2[i] = 출발지_2[i]
	}
}
