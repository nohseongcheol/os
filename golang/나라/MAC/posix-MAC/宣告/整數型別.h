#ifndef _宣告_整數型別
#define _宣告_整數型別

typedef signed char 有號8位整數;
typedef unsigned char 無號8位整數;
typedef signed short 有號16位整數;
typedef unsigned short 無號16位整數;
typedef signed int 有號32位整數;
typedef unsigned int 無號32位整數;
typedef signed long long 有號64位整數;
typedef unsigned long long 無號64位整數;
typedef unsigned int 位址寬度無號整數;
typedef int 位址寬度有號整數;

#endif
