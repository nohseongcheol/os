int 단말인지확인하기(int 자료철서술번호)
{
    struct 자료철상태 상태자료;
    if (열린자료철상태얻기(자료철서술번호, &상태자료) < 0)
        return 0;
    if (!문자장치방식인지확인(상태자료.자료철종류와권한)) {
        오류번호 = 오류장치에맞지않는동작;
        return 0;
    }
    return 1;
}

int 동적기억끝정하기(void *주소)
{
    long 결과 = 인수하나체계호출(체계호출_동적기억끝정하기, 주소);
    if (결과 != (long)주소) {
        오류번호 = 오류기억공간부족;
        return -1;
    }
    return 0;
}

void *동적기억끝옮기기(int 증가량)
{
    long 현재끝 = 인수하나체계호출(체계호출_동적기억끝정하기, 0);
    long 요청끝 = 현재끝 + 증가량;
    if (증가량 != 0 && 동적기억끝정하기((void *)요청끝) < 0)
        return (void *)-1;
    return (void *)현재끝;
}

실행과정번호형 지정자식기다리기(실행과정번호형 실행과정번호, int *끝난상태, int 선택사항)
{
    long 결과;
    do {
        결과 = 인수셋체계호출(7, 실행과정번호, 끝난상태, 선택사항);
    } while (결과 == -오류잠시사용불가 && (선택사항 & 준비안되면기다리지않기) == 0);
    return (실행과정번호형)__syscall_result(결과);
}

