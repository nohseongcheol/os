#include <통신주소/여덟자리묶음순서.h>
#include <오류번호.h>
#include <체계/통신끝점.h>
#include <입출력과실행.h>

static unsigned int 문자열길이구하기(const char *검사자료)
{
    unsigned int 호출종류 = 0;
    while (검사자료[호출종류] != 0) 호출종류++;
    return 호출종류;
}

static void 전문쓰기(const char *검사자료) { (void)쓰기(표준출력번호, 검사자료, 문자열길이구하기(검사자료)); }

static void 결과알리기(const char *이름, int 검사통과)
{
    전문쓰기(검사통과 ? "NTEST:PASS:" : "NTEST:FAIL:");
    전문쓰기(이름);
    전문쓰기("\n");
}

int main(void)
{
    struct 상호연결망끝점주소 응답끝점주소 = {0};
    struct 상호연결망끝점주소 원본 = {0};
    주소길이형 출발주소크기 = sizeof(원본);
    char 자료완충영역[8] = {0};
    int 응답끝점 = 통신끝점만들기(상호연결망주소계열, 자료전문끝점, 사용자자료전문규약);
    int 요청끝점 = 통신끝점만들기(상호연결망주소계열, 자료전문끝점, 0);

    결과알리기("socket-server", 응답끝점 >= 3);
    결과알리기("socket-client", 요청끝점 >= 3 && 요청끝점 != 응답끝점);
    응답끝점주소.연결망주소계열 = 상호연결망주소계열;
    응답끝점주소.통신창구번호 = 통신망순서로16자리바꾸기(32345);
    응답끝점주소.연결망주소내용.주소값 = 통신망순서로32자리바꾸기(자기되돌림주소);
    결과알리기("bind", 지역주소맺기(응답끝점, (const struct 통신끝점주소 *)&응답끝점주소,
                        sizeof(응답끝점주소)) == 0);
    결과알리기("connect", 상대끝점잇기(요청끝점, (const struct 통신끝점주소 *)&응답끝점주소,
                              sizeof(응답끝점주소)) == 0);
    결과알리기("send", 보내기(요청끝점, "ping", 4, 0) == 4);
    결과알리기("recvfrom", 보낸곳과함께받기(응답끝점, 자료완충영역, sizeof(자료완충영역), 0,
                                (struct 통신끝점주소 *)&원본, &출발주소크기) == 4 &&
                       자료완충영역[0] == 'p' && 자료완충영역[3] == 'g' && 출발주소크기 == 16);
    오류번호 = 0;
    결과알리기("empty-eagain", 받기(응답끝점, 자료완충영역, sizeof(자료완충영역), 0) == -1 && 오류번호 == 오류잠시사용불가);
    결과알리기("getsockname", 지역끝점주소얻기(응답끝점, (struct 통신끝점주소 *)&원본,
                                      &출발주소크기) == 0 && 원본.통신창구번호 == 통신망순서로16자리바꾸기(32345));
    오류번호 = 0;
    결과알리기("udp-listen-not-supported", 연결요청받을준비하기(응답끝점, 1) == -1 && 오류번호 == 오류동작지원안함);
    결과알리기("close-client", 닫기(요청끝점) == 0);
    결과알리기("close-server", 닫기(응답끝점) == 0);
    전문쓰기("NTEST:DONE\n");
    return 0;
}
