func (자신 *T저장장치접속기) F관문초기화(주 bool, 접속기준 uint16) {
	자신.주 = 주
	자신.자료접속.F관문초기화(접속기준)
	자신.오류접속.F관문초기화(접속기준 + 0x1)
	자신.저장구역개수접속.F관문초기화(접속기준 + 0x2)
	자신.논리구역주소하위접속.F관문초기화(접속기준 + 0x3)
	자신.논리구역주소중간접속.F관문초기화(접속기준 + 0x4)
	자신.논리구역주소상위접속.F관문초기화(접속기준 + 0x5)
	자신.장치접속.F관문초기화(접속기준 + 0x6)
	자신.명령접속.F관문초기화(접속기준 + 0x7)
	자신.제어접속.F관문초기화(접속기준 + 0x8)

}

func (자신 *T저장장치접속기) M저장장치식별정보읽기() {

	var 단말_3 = T단말{}

	if 자신.주 {
		자신.장치접속.M쓰기(0xA0)
	} else {
		자신.장치접속.M쓰기(0xB0)
	}
	자신.제어접속.M쓰기(0)
	자신.장치접속.M쓰기(0xA0)

	var 상태 uint8 = 자신.명령접속.M읽기()
	if 상태 == 0xFF {
		단말_3.M출력(([]byte)("Invalid Status"))
		return
	}

	if 자신.주 {
		자신.장치접속.M쓰기(0xA0)
	} else {
		자신.장치접속.M쓰기(0xB0)
	}
	자신.저장구역개수접속.M쓰기(0)
	자신.논리구역주소하위접속.M쓰기(0)
	자신.논리구역주소중간접속.M쓰기(0)
	자신.논리구역주소상위접속.M쓰기(0)
	자신.명령접속.M쓰기(0xEC)

	상태 = 자신.명령접속.M읽기()
	if 상태 == 0x00 {
		단말_3.M출력(([]byte)("HDD Does not exist, ignoreign "))
		return
	}
	for (상태&0x80) == 0x80 && (상태&0x01) != 0x01 {
		상태 = 자신.명령접속.M읽기()
	}

	if (상태 & 0x01) != 0 {
		단말_3.M출력(([]byte)("error reading ATA"))
		return
	}

	for i := 0; i < 256; i++ {
		var 자료 = 자신.자료접속.M읽기()
		텍스트 := []byte("  ")
		텍스트[0] = uint8((자료 >> 8) & 0xFF)
		텍스트[1] = uint8(자료 & 0xFF)

	}
	단말_3.M지정좌표에출력(([]byte)("ata ok"), 10, 22)

}
func (자신 *T저장장치접속기) M논리구역28비트주소로읽기(저장구역 uint32, 자료 *[]byte, 개수 int) {
	var 단말_3 = T단말{}
	if (저장구역 & 0xF0000000) != 0 {
		단말_3.M출력(([]byte)("ata read error "))
		return
	}
	if 개수 > C저장구역당바이트수 {
		단말_3.M출력(([]byte)("ata read error "))
		return
	}

	if 자신.주 {
		자신.장치접속.M쓰기(uint8(0xE0 | uint8((저장구역&0x0F000000)>>24)))
	} else {
		자신.장치접속.M쓰기(uint8(0xF0 | uint8((저장구역&0x0F000000)>>24)))
	}
	자신.오류접속.M쓰기(0)
	자신.저장구역개수접속.M쓰기(1)

	자신.논리구역주소하위접속.M쓰기(uint8(저장구역 & 0x000000FF))
	자신.논리구역주소중간접속.M쓰기(uint8((저장구역 & 0x0000FF00) >> 8))
	자신.논리구역주소상위접속.M쓰기(uint8((저장구역 & 0x00FF0000) >> 16))
	자신.명령접속.M쓰기(0x20)

	var 상태 uint8 = 자신.명령접속.M읽기()
	for ((상태 & 0x80) == 0x80) && ((상태 & 0x01) != 0x01) {
		상태 = 자신.명령접속.M읽기()
	}

	if (상태 & 0x01) != 0 {
		단말_3.M출력(([]byte)("ata read error "))
		return
	}

	단말_3.M지정좌표에출력(([]byte)("Reading ATA Drive:"), 1, 24)

	var i int = 0
	for ; i < 개수; i += 2 {
		var wdata uint16 = 자신.자료접속.M읽기()

		(*자료)[i] = uint8(wdata & 0x00FF)
		if i+1 < 개수 {

			(*자료)[i+1] = uint8((wdata >> 8) & 0x00FF)
		}
	}

	for i := (개수 + (개수 % 2)); i < C저장구역당바이트수; i += 2 {
		자신.자료접속.M읽기()
	}
}
func (자신 *T저장장치접속기) M논리구역28비트주소로쓰기(저장구역번호 uint32, 자료 []byte, 개수 uint32) {

	if 저장구역번호 > 0x0FFFFFFF {
		return
	}

	if 개수 > 512 {
		return
	}

	if 자신.주 {
		자신.장치접속.M쓰기(uint8(0xE0 | uint8((저장구역번호&0x0F000000)>>24)))
	} else {
		자신.장치접속.M쓰기(uint8(0xF0 | uint8((저장구역번호&0x0F000000)>>24)))
	}

	자신.오류접속.M쓰기(0)
	자신.저장구역개수접속.M쓰기(1)
	자신.논리구역주소하위접속.M쓰기(uint8(저장구역번호 & 0x000000FF))
	자신.논리구역주소중간접속.M쓰기(uint8((저장구역번호 & 0x0000FF00) >> 8))
	자신.논리구역주소상위접속.M쓰기(uint8((저장구역번호 & 0x00FF0000) >> 16))
	자신.명령접속.M쓰기(0x30)

	var 단말_3 = T단말{}
	단말_3.M출력(([]byte)("Writing to ATA Drive:"))

	for i := uint32(0); i < 개수; i += 2 {

		var wdata uint16 = uint16(자료[i])

		if i+1 < 개수 {
			wdata = wdata | (uint16(자료[i+1]) << 8)
		}

		자신.자료접속.M쓰기(wdata)

		텍스트 := []byte("  ")
		텍스트[0] = uint8((wdata >> 8) & 0xFF)
		텍스트[1] = uint8(wdata & 0xFF)

		단말_3.M출력(텍스트)
	}

	for i := (개수 + (개수 % 2)); i < 512; i += 2 {
		자신.자료접속.M쓰기(0x0000)
	}

}

func (자신 *T저장장치접속기) M저장장치쓰기완료대기() {
	if 자신.주 {
		자신.장치접속.M쓰기(0xE0)
	} else {
		자신.장치접속.M쓰기(0xF0)
	}
	자신.명령접속.M쓰기(0xE7)

	var 단말_3 = T단말{}

	var 상태 uint8 = 자신.명령접속.M읽기()
	if 상태 == 0x00 {
		return
	}

	for ((상태 & 0x80) == 0x80) && ((상태 & 0x01) != 0x01) {
		상태 = 자신.명령접속.M읽기()
	}
	if (상태 & 0x01) != 0 {
		단말_3.M출력(([]byte)(" ata flush error"))
		return
	}

}
