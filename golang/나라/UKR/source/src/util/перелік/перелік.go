import mem "памятьmanager"

type TВузол_списку struct {
	посилання_на_адресу	uintptr
	previous	*TВузол_списку
	наступне	*TВузол_списку
}

type LinkedПерелік struct {
	head		*TВузол_списку
	tail		*TВузол_списку
	Розмір_2	int

	mem	*mem.TПамятьmanager
}

func (поточний *LinkedПерелік) Init(mem *mem.TПамятьmanager) {
	поточний.head = nil
	поточний.tail = nil
	поточний.Розмір_2 = 0

	поточний.mem = mem
}
func (поточний *LinkedПерелік) Додати_на_початок_списку(посилання_на_адресу uintptr) {
	новийВузол := (*TВузол_списку)(поточний.mem.Виділити_памʼять(uint32(Sizeof(TВузол_списку{}))))
	if новийВузол == nil {
		return
	}
	новийВузол.посилання_на_адресу = посилання_на_адресу
	новийВузол.previous = nil
	новийВузол.наступне = поточний.head
	if поточний.head != nil {
		поточний.head.previous = новийВузол
	}
	поточний.head = новийВузол
	поточний.Розмір_2++

	if поточний.head.наступне == nil {
		поточний.tail = поточний.head
	}

}
func (поточний *LinkedПерелік) Додати_в_кінець_списку(посилання_на_адресу uintptr) {
	if поточний.Розмір_2 == 0 {
		поточний.Додати_на_початок_списку(посилання_на_адресу)
	} else {
		новийВузол := (*TВузол_списку)(поточний.mem.Виділити_памʼять(uint32(Sizeof(TВузол_списку{}))))
		if новийВузол == nil {
			return
		}
		новийВузол.посилання_на_адресу = посилання_на_адресу
		новийВузол.previous = поточний.tail
		новийВузол.наступне = nil
		поточний.tail.наступне = новийВузол
		поточний.tail = новийВузол
		поточний.Розмір_2++
	}
}
func (поточний *LinkedПерелік) Вставити_за_індексом(індекс int, посилання_на_адресу uintptr) {
	if індекс == 0 {
		поточний.Додати_на_початок_списку(посилання_на_адресу)
	} else {
		previousВузол := поточний.GetВузолat(індекс - 1)
		наступнеВузол := previousВузол.наступне
		новийВузол := (*TВузол_списку)(поточний.mem.Виділити_памʼять(uint32(Sizeof(TВузол_списку{}))))
		if новийВузол == nil {
			return
		}
		новийВузол.посилання_на_адресу = посилання_на_адресу

		previousВузол.наступне = новийВузол
		новийВузол.previous = previousВузол
		новийВузол.наступне = наступнеВузол
		if наступнеВузол != nil {
			наступнеВузол.previous = новийВузол
		}

		поточний.Розмір_2++

		if новийВузол.наступне == nil {
			поточний.tail = новийВузол
		}
	}
}
func (поточний *LinkedПерелік) GetВузолat(індекс int) *TВузол_списку {
	if індекс < 0 || індекс >= поточний.Розмір_2 {
		return nil
	}
	var x *TВузол_списку = поточний.head
	for i := 0; i < індекс; i++ {
		x = x.наступне
	}
	return x
}

func (поточний *LinkedПерелік) МножинаВузолat(індекс int, посилання_на_адресу uintptr) {
	var x *TВузол_списку = поточний.head
	for i := 0; i < індекс; i++ {
		x = x.наступне
	}
	if x != nil {
		x.посилання_на_адресу = посилання_на_адресу
	}
}
func (поточний *LinkedПерелік) Getat(індекс int) Pointer {
	вузол_списку := поточний.GetВузолat(індекс)
	if вузол_списку == nil {
		return nil
	}
	var посилання_на_адресу uintptr = вузол_списку.посилання_на_адресу
	return Pointer(посилання_на_адресу)
}
func (поточний *LinkedПерелік) Індексз(посилання_на_адресу uintptr) int {
	var n *TВузол_списку = поточний.head
	i := 0
	for ; i < поточний.Розмір_2; i++ {
		if посилання_на_адресу == n.посилання_на_адресу {
			return i
		}
		n = n.наступне
	}
	return -1
}
func (поточний *LinkedПерелік) Вилучити_2(посилання_на_адресу uintptr) {
	індекс := поточний.Індексз(посилання_на_адресу)
	if індекс < 0 {
		return
	}
	поточний.Вилучитиat(індекс)
}
func (поточний *LinkedПерелік) Вилучитиat(індекс int) {
	if індекс < 0 || індекс >= поточний.Розмір_2 {
		return
	}
	вузол_списку := поточний.GetВузолat(індекс)
	if вузол_списку == nil {
		return
	}
	if вузол_списку.previous != nil {
		вузол_списку.previous.наступне = вузол_списку.наступне
	} else {
		поточний.head = вузол_списку.наступне
	}
	if вузол_списку.наступне != nil {
		вузол_списку.наступне.previous = вузол_списку.previous
	} else {
		поточний.tail = вузол_списку.previous
	}
	поточний.Розмір_2 = поточний.Розмір_2 - 1

	if поточний.mem != nil {
		поточний.mem.Вільно(Pointer(вузол_списку))
	}
}

