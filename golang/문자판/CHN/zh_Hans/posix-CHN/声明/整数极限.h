#ifndef _声明_整数极限
#define _声明_整数极限
/* This package's compiler ABI is i386 ILP32 with signed plain char. */
#define 每字节位数 8
#define 有符号字符整数最小值 (-128)
#define 有符号字符整数最大值 127
#define 无符号字符整数最大值 255
#define 字符整数最小值 有符号字符整数最小值
#define 字符整数最大值 有符号字符整数最大值
#define 短整数最小值 (-32767-1)
#define 短整数最大值 32767
#define 无符号短整数最大值 65535
#define 整数最小值 (-2147483647-1)
#define 整数最大值 2147483647
#define 无符号整数最大值 4294967295U
#define 长整数最小值 (-2147483647L-1L)
#define 长整数最大值 2147483647L
#define 无符号长整数最大值 4294967295UL
#define 长长整数最小值 (-9223372036854775807LL-1LL)
#define 长长整数最大值 9223372036854775807LL
#define 无符号长长整数最大值 18446744073709551615ULL
#endif
