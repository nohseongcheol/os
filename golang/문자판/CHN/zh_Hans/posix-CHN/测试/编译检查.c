#include <错误编号.h>
#include <文件控制.h>
#include <系统/文件状态.h>
#include <系统/系统身份.h>
#include <系统/子进程等待.h>
#include <输入输出与执行.h>

int 声明编译试验(void)
{
    char 工作目录[8];
    struct 文件状态 状态资料;
    struct 系统身份信息 系统资料;
    int 文件描述编号 = 打开("/USER1", 只读打开);
    int 复制值 = 文件描述编号 >= 0 ? 复制打开文件引用(文件描述编号) : -1;
    if (复制值 >= 0) 关闭(复制值);
    if (文件描述编号 >= 0) {
        取得打开文件状态(文件描述编号, &状态资料);
        移动读写位置(文件描述编号, 0, 从起点定位);
        关闭(文件描述编号);
    }
    文件状态("/", &状态资料);
    取得系统信息(&系统资料);
    取得工作目录路径(工作目录, sizeof(工作目录));
    return 错误编号 + 取得进程编号() + 取得父进程编号();
}
