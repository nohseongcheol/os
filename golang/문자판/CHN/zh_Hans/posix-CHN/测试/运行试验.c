static int 检查次数;
static int 失败次数;

static unsigned int 文本字节长度(const char *字符串)
{
    unsigned int 长度 = 0;
    while (字符串[长度] != 0)
        长度++;
    return 长度;
}

static int 检查文本相等(const char *左值, const char *右值)
{
    unsigned int 项目索引 = 0;
    while (左值[项目索引] != 0 && 右值[项目索引] != 0) {
        if (左值[项目索引] != 右值[项目索引])
            return 0;
        项目索引++;
    }
    return 左值[项目索引] == 右值[项目索引];
}

static void 写出报文(const char *字符串)
{
    (void)写入(标准输出编号, 字符串, 文本字节长度(字符串));
}

static void 报告结果(const char *系统资料, int 通过标志)
{
    检查次数++;
    if (通过标志) {
        写出报文("PTEST:PASS:");
    } else {
        失败次数++;
        写出报文("PTEST:FAIL:");
    }
    写出报文(系统资料);
    写出报文("\n");
}

static int 检查是否指定错误(int 结果, int 预期错误编号)
{
    return 结果 == -1 && 错误编号 == 预期错误编号;
}

static 进程编号类型 不等待回收子进程(进程编号类型 子项位置, int *结束状态)
{
    unsigned int 循环次数;
    进程编号类型 结果;

    for (循环次数 = 0; 循环次数 < 2000000U; 循环次数++) {
        结果 = 等待指定子进程(子项位置, 结束状态, 未就绪则不等待);
        if (结果 != 0)
            return 结果;
    }
    return 0;
}

