int 检查是否终端(int 文件描述编号)
{
    struct 文件状态 状态资料;
    if (取得打开文件状态(文件描述编号, &状态资料) < 0)
        return 0;
    if (!检查字符设备模式(状态资料.文件类型与权限)) {
        错误编号 = 错误设备不适用操作;
        return 0;
    }
    return 1;
}

int 设定动态存储末端(void *地址)
{
    long 结果 = 单参数系统调用(系统调用_设定动态存储末端, 地址);
    if (结果 != (long)地址) {
        错误编号 = 错误内存不足;
        return -1;
    }
    return 0;
}

void *移动动态存储末端(int 增量)
{
    long 当前末端 = 单参数系统调用(系统调用_设定动态存储末端, 0);
    long 请求末端 = 当前末端 + 增量;
    if (增量 != 0 && 设定动态存储末端((void *)请求末端) < 0)
        return (void *)-1;
    return (void *)当前末端;
}

