enum { নিবেশ_পঙ্‌ক্তির_ধারণক্ষমতা = 512, আর্গুমেন্টের_সর্বোচ্চ_সংখ্যা = 16, আদেশ_নথির_সর্বোচ্চ_অন্তর্ভুক্তি = 4 };
static int আদেশ_নথির_অন্তর্ভুক্তির_গভীরতা;
struct নিবেশের_প্রবাহ {
    int নিবেশ_নির্দেশক;
    char স্থানান্তরের_অস্থায়ী_ভান্ডার_2[256];
    size_t অবস্থান;
    size_t দৈর্ঘ্য;
};

static size_t পাঠের_বাইট_দৈর্ঘ্য(const char *পাঠ)
{
    size_t দৈর্ঘ্য = 0;
    while (পাঠ[দৈর্ঘ্য] != '\0')
        দৈর্ঘ্য++;
    return দৈর্ঘ্য;
}

static int পাঠ_সমান(const char *বাঁদিক, const char *ডানদিক)
{
    size_t অবস্থান = 0;
    while (বাঁদিক[অবস্থান] == ডানদিক[অবস্থান]) {
        if (বাঁদিক[অবস্থান] == '\0')
            return 1;
        অবস্থান++;
    }
    return 0;
}

static void পাঠ_লেখা(const char *পাঠ)
{
    size_t দৈর্ঘ্য = পাঠের_বাইট_দৈর্ঘ্য(পাঠ);
    while (দৈর্ঘ্য > 0U) {
        ssize_t লিখিত_বাইটের_সংখ্যা = লেখা(STDOUT_FILENO, পাঠ, দৈর্ঘ্য);
        if (লিখিত_বাইটের_সংখ্যা <= 0)
            return;
        পাঠ += লিখিত_বাইটের_সংখ্যা;
        দৈর্ঘ্য -= (size_t)লিখিত_বাইটের_সংখ্যা;
    }
}

static void পূর্ণসংখ্যা_লেখা(int মান)
{
    char অঙ্কের_অক্ষর[16];
    unsigned int অঙ্কের_সংখ্যা;
    unsigned int চিহ্নবিহীন_পরিমাণ;

    if (মান < 0) {
        পাঠ_লেখা("-");
        চিহ্নবিহীন_পরিমাণ = (unsigned int)(-(মান + 1)) + 1U;
    } else {
        চিহ্নবিহীন_পরিমাণ = (unsigned int)মান;
    }
    অঙ্কের_সংখ্যা = 0;
    do {
        অঙ্কের_অক্ষর[অঙ্কের_সংখ্যা++] = (char)('0' + চিহ্নবিহীন_পরিমাণ % 10U);
        চিহ্নবিহীন_পরিমাণ /= 10U;
    } while (চিহ্নবিহীন_পরিমাণ != 0U);
    while (অঙ্কের_সংখ্যা > 0U) {
        অঙ্কের_সংখ্যা--;
        (void)লেখা(STDOUT_FILENO, &অঙ্কের_অক্ষর[অঙ্কের_সংখ্যা], 1);
    }
}

static void ত্রুটি_জানানো(const char *ক্রিয়া)
{
    পাঠ_লেখা("error: ");
    পাঠ_লেখা(ক্রিয়া);
    পাঠ_লেখা(" errno=");
    পূর্ণসংখ্যা_লেখা(errno);
    পাঠ_লেখা("\n");
}

static int নিবেশের_পঙ্‌ক্তি_পড়া(struct নিবেশের_প্রবাহ *নিবেশ, char *নিবেশের_পঙ্‌ক্তি, size_t ধারণক্ষমতা)
{
    size_t অবস্থান = 0;
    int অবৈধ_নিবেশ_পঙ্‌ক্তি = 0;
    char অক্ষর;
    ssize_t পঠিত_বাইট;
    if (ধারণক্ষমতা < 2U)
        return -2;
    for (;;) {
        if (নিবেশ->অবস্থান == নিবেশ->দৈর্ঘ্য) {
            পঠিত_বাইট = পড়া(নিবেশ->নিবেশ_নির্দেশক, নিবেশ->স্থানান্তরের_অস্থায়ী_ভান্ডার_2, sizeof(নিবেশ->স্থানান্তরের_অস্থায়ী_ভান্ডার_2));
            if (পঠিত_বাইট < 0) {
                if (errno == EINTR)
                    continue;
                return -1;
            }
            if (পঠিত_বাইট == 0) {
                if (অবস্থান == 0 && !অবৈধ_নিবেশ_পঙ্‌ক্তি)
                    return -1;
                break;
            }
            নিবেশ->দৈর্ঘ্য = (size_t)পঠিত_বাইট;
            নিবেশ->অবস্থান = 0;
        }
        অক্ষর = নিবেশ->স্থানান্তরের_অস্থায়ী_ভান্ডার_2[নিবেশ->অবস্থান++];
        if (অক্ষর == '\n')
            break;
        if (নিবেশ->নিবেশ_নির্দেশক == STDIN_FILENO && অক্ষর == 4) {
            if (অবস্থান == 0 && !অবৈধ_নিবেশ_পঙ্‌ক্তি)
                return -1;
            break;
        }
        if (নিবেশ->নিবেশ_নির্দেশক == STDIN_FILENO && (অক্ষর == 8 || অক্ষর == 127)) {
            if (অবস্থান > 0) {
                do {
                    অবস্থান--;
                } while (অবস্থান > 0 && ((unsigned char)নিবেশের_পঙ্‌ক্তি[অবস্থান] & 0xc0U) == 0x80U);
            }
            continue;
        }
        if (অক্ষর == '\r')
            continue;
        if (অক্ষর == '\0') {
            অবৈধ_নিবেশ_পঙ্‌ক্তি = 1; /* Reject binary input; do not execute its prefix. */
            continue;
        }
        if (অবস্থান + 1U < ধারণক্ষমতা)
            নিবেশের_পঙ্‌ক্তি[অবস্থান++] = অক্ষর;
        else
            অবৈধ_নিবেশ_পঙ্‌ক্তি = 1;
    }
    নিবেশের_পঙ্‌ক্তি[অবস্থান] = '\0';
    return অবৈধ_নিবেশ_পঙ্‌ক্তি ? -2 : (int)অবস্থান;
}

static int আর্গুমেন্ট_আলাদা_করা(char *নিবেশের_পঙ্‌ক্তি, char **আর্গুমেন্ট_তালিকা)
{
    int আর্গুমেন্ট_সংখ্যা = 0;
    char *বর্তমান_অবস্থান = নিবেশের_পঙ্‌ক্তি;
    char *নির্গমের_অবস্থান = নিবেশের_পঙ্‌ক্তি;

    while (*বর্তমান_অবস্থান != '\0') {
        char উদ্ধৃতি_চিহ্ন = '\0';
        while (*বর্তমান_অবস্থান == ' ' || *বর্তমান_অবস্থান == '\t')
            বর্তমান_অবস্থান++;
        if (*বর্তমান_অবস্থান == '\0' || *বর্তমান_অবস্থান == '#')
            break;
        if (আর্গুমেন্ট_সংখ্যা == আর্গুমেন্টের_সর্বোচ্চ_সংখ্যা - 1)
            return -1;
        আর্গুমেন্ট_তালিকা[আর্গুমেন্ট_সংখ্যা++] = নির্গমের_অবস্থান;
        while (*বর্তমান_অবস্থান != '\0') {
            char অক্ষর = *বর্তমান_অবস্থান++;
            if (উদ্ধৃতি_চিহ্ন == '\0' && (অক্ষর == ' ' || অক্ষর == '\t'))
                break;
            if (অক্ষর == '\\' && উদ্ধৃতি_চিহ্ন != '\'') {
                if (*বর্তমান_অবস্থান == '\0')
                    return -1;
                *নির্গমের_অবস্থান++ = *বর্তমান_অবস্থান++;
            } else if (অক্ষর == '\'' || অক্ষর == '"') {
                if (উদ্ধৃতি_চিহ্ন == '\0')
                    উদ্ধৃতি_চিহ্ন = অক্ষর;
                else if (উদ্ধৃতি_চিহ্ন == অক্ষর)
                    উদ্ধৃতি_চিহ্ন = '\0';
                else
                    *নির্গমের_অবস্থান++ = অক্ষর;
            } else {
                *নির্গমের_অবস্থান++ = অক্ষর;
            }
        }
        if (উদ্ধৃতি_চিহ্ন != '\0')
            return -1;
        *নির্গমের_অবস্থান++ = '\0';
    }
    আর্গুমেন্ট_তালিকা[আর্গুমেন্ট_সংখ্যা] = (char *)0;
    return আর্গুমেন্ট_সংখ্যা;
}

