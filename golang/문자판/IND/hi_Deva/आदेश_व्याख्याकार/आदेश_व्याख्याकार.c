struct निवेश_धारा {
    int निवेश_विवरणक;
    char स्थानांतरण_का_अस्थायी_भंडार_2[256];
    size_t स्थान;
    size_t लंबाई;
};

static size_t पाठ_की_बाइट_लंबाई(const char *पाठ)
{
    size_t लंबाई = 0;
    while (पाठ[लंबाई] != '\0')
        लंबाई++;
    return लंबाई;
}

static int पाठ_समान_हैं(const char *बायाँ, const char *दायाँ)
{
    size_t स्थान = 0;
    while (बायाँ[स्थान] == दायाँ[स्थान]) {
        if (बायाँ[स्थान] == '\0')
            return 1;
        स्थान++;
    }
    return 0;
}

static void पाठ_लिखना(const char *पाठ)
{
    size_t लंबाई = पाठ_की_बाइट_लंबाई(पाठ);
    while (लंबाई > 0U) {
        ssize_t लिखे_गए_बाइटों_की_संख्या = लिखना(STDOUT_FILENO, पाठ, लंबाई);
        if (लिखे_गए_बाइटों_की_संख्या <= 0)
            return;
        पाठ += लिखे_गए_बाइटों_की_संख्या;
        लंबाई -= (size_t)लिखे_गए_बाइटों_की_संख्या;
    }
}

static void पूर्णांक_लिखना(int मान)
{
    char अंकों_के_वर्ण[16];
    unsigned int अंकों_की_संख्या;
    unsigned int चिह्न_रहित_परिमाण;

    if (मान < 0) {
        पाठ_लिखना("-");
        चिह्न_रहित_परिमाण = (unsigned int)(-(मान + 1)) + 1U;
    } else {
        चिह्न_रहित_परिमाण = (unsigned int)मान;
    }
    अंकों_की_संख्या = 0;
    do {
        अंकों_के_वर्ण[अंकों_की_संख्या++] = (char)('0' + चिह्न_रहित_परिमाण % 10U);
        चिह्न_रहित_परिमाण /= 10U;
    } while (चिह्न_रहित_परिमाण != 0U);
    while (अंकों_की_संख्या > 0U) {
        अंकों_की_संख्या--;
        (void)लिखना(STDOUT_FILENO, &अंकों_के_वर्ण[अंकों_की_संख्या], 1);
    }
}

static void त्रुटि_बताना(const char *क्रिया)
{
    पाठ_लिखना("error: ");
    पाठ_लिखना(क्रिया);
    पाठ_लिखना(" errno=");
    पूर्णांक_लिखना(errno);
    पाठ_लिखना("\n");
}

static int निवेश_पंक्ति_पढ़ना(struct निवेश_धारा *निवेश, char *निवेश_पंक्ति, size_t क्षमता)
{
    size_t स्थान = 0;
    int अमान्य_निवेश_पंक्ति = 0;
    char वर्ण;
    ssize_t पढ़े_गए_बाइट;
    if (क्षमता < 2U)
        return -2;
    for (;;) {
        if (निवेश->स्थान == निवेश->लंबाई) {
            पढ़े_गए_बाइट = पढ़ना(निवेश->निवेश_विवरणक, निवेश->स्थानांतरण_का_अस्थायी_भंडार_2, sizeof(निवेश->स्थानांतरण_का_अस्थायी_भंडार_2));
            if (पढ़े_गए_बाइट < 0) {
                if (errno == EINTR)
                    continue;
                return -1;
            }
            if (पढ़े_गए_बाइट == 0) {
                if (स्थान == 0 && !अमान्य_निवेश_पंक्ति)
                    return -1;
                break;
            }
            निवेश->लंबाई = (size_t)पढ़े_गए_बाइट;
            निवेश->स्थान = 0;
        }
        वर्ण = निवेश->स्थानांतरण_का_अस्थायी_भंडार_2[निवेश->स्थान++];
        if (वर्ण == '\n')
            break;
        if (निवेश->निवेश_विवरणक == STDIN_FILENO && वर्ण == 4) {
            if (स्थान == 0 && !अमान्य_निवेश_पंक्ति)
                return -1;
            break;
        }
        if (निवेश->निवेश_विवरणक == STDIN_FILENO && (वर्ण == 8 || वर्ण == 127)) {
            if (स्थान > 0) {
                do {
                    स्थान--;
                } while (स्थान > 0 && ((unsigned char)निवेश_पंक्ति[स्थान] & 0xc0U) == 0x80U);
            }
            continue;
        }
        if (वर्ण == '\r')
            continue;
        if (वर्ण == '\0') {
            अमान्य_निवेश_पंक्ति = 1; /* Reject binary input; do not execute its prefix. */
            continue;
        }
        if (स्थान + 1U < क्षमता)
            निवेश_पंक्ति[स्थान++] = वर्ण;
        else
            अमान्य_निवेश_पंक्ति = 1;
    }
    निवेश_पंक्ति[स्थान] = '\0';
    return अमान्य_निवेश_पंक्ति ? -2 : (int)स्थान;
}

static int तर्क_अलग_करना(char *निवेश_पंक्ति, char **तर्क_सूची)
{
    int तर्कों_की_संख्या = 0;
    char *वर्तमान_स्थान = निवेश_पंक्ति;
    char *निर्गम_स्थान = निवेश_पंक्ति;

    while (*वर्तमान_स्थान != '\0') {
        char उद्धरण_चिह्न = '\0';
        while (*वर्तमान_स्थान == ' ' || *वर्तमान_स्थान == '\t')
            वर्तमान_स्थान++;
        if (*वर्तमान_स्थान == '\0' || *वर्तमान_स्थान == '#')
            break;
        if (तर्कों_की_संख्या == तर्कों_की_अधिकतम_संख्या - 1)
            return -1;
        तर्क_सूची[तर्कों_की_संख्या++] = निर्गम_स्थान;
        while (*वर्तमान_स्थान != '\0') {
            char वर्ण = *वर्तमान_स्थान++;
            if (उद्धरण_चिह्न == '\0' && (वर्ण == ' ' || वर्ण == '\t'))
                break;
            if (वर्ण == '\\' && उद्धरण_चिह्न != '\'') {
                if (*वर्तमान_स्थान == '\0')
                    return -1;
                *निर्गम_स्थान++ = *वर्तमान_स्थान++;
            } else if (वर्ण == '\'' || वर्ण == '"') {
                if (उद्धरण_चिह्न == '\0')
                    उद्धरण_चिह्न = वर्ण;
                else if (उद्धरण_चिह्न == वर्ण)
                    उद्धरण_चिह्न = '\0';
                else
                    *निर्गम_स्थान++ = वर्ण;
            } else {
                *निर्गम_स्थान++ = वर्ण;
            }
        }
        if (उद्धरण_चिह्न != '\0')
            return -1;
        *निर्गम_स्थान++ = '\0';
    }
    तर्क_सूची[तर्कों_की_संख्या] = (char *)0;
    return तर्कों_की_संख्या;
}

