static int حکم_ملتا_ہے(const char *متن, const char *حکم)
{
    size_t مقام;
    if (متن_برابر_ہیں(متن, حکم))
        return 1;
    for (مقام = 0; مقام < sizeof(بنیادی_احکامات) / sizeof(بنیادی_احکامات[0]); مقام++)
        if (متن_برابر_ہیں(حکم, بنیادی_احکامات[مقام]))
            return متن_برابر_ہیں(متن, احکامات_کے_مقامی_نام[مقام]);
    return 0;
}

static int اندراج_کی_تشریح_کرنا(int اندراج_کا_وصف_کنندہ);

static int احکامات_کی_فائل_کی_تشریح_کرنا(const char *فائل_کا_نام)
{
    int فائل_کا_وصف_کنندہ_2;
    int حالت;
    if (احکامات_کی_فائلوں_کی_تہہ_کی_گہرائی >= احکامات_کی_فائلوں_کی_زیادہ_سے_زیادہ_تہیں) {
        متن_لکھنا("source: nesting limit\n");
        return 0;
    }
    فائل_کا_وصف_کنندہ_2 = open(فائل_کا_نام, O_RDONLY);
    if (فائل_کا_وصف_کنندہ_2 < 0) {
        خرابی_بتانا(فائل_کا_نام);
        return 0;
    }
    احکامات_کی_فائلوں_کی_تہہ_کی_گہرائی++;
    حالت = اندراج_کی_تشریح_کرنا(فائل_کا_وصف_کنندہ_2);
    احکامات_کی_فائلوں_کی_تہہ_کی_گہرائی--;
    (void)close(فائل_کا_وصف_کنندہ_2);
    return حالت;
}

static void دلائل_دکھانا(int دلائل_کی_تعداد, char **دلائل)
{
    int مقام;
    for (مقام = 1; مقام < دلائل_کی_تعداد; مقام++) {
        if (مقام != 1)
            متن_لکھنا(" ");
        متن_لکھنا(دلائل[مقام]);
    }
    متن_لکھنا("\n");
}

static void موجودہ_فہرست_دکھانا(void)
{
    char راستہ[128];
    if (getcwd(راستہ, sizeof(راستہ)) == (char *)0) {
        خرابی_بتانا("pwd");
        return;
    }
    متن_لکھنا(راستہ);
    متن_لکھنا("\n");
}

static void فائل_کا_مواد_دکھانا(const char *فائل_کا_نام)
{
    char منتقلی_کا_عارضی_ذخیرہ_2[128];
    int فائل_کا_وصف_کنندہ_2 = open(فائل_کا_نام, O_RDONLY);
    ssize_t پڑھے_گئے_بائٹ;

    if (فائل_کا_وصف_کنندہ_2 < 0) {
        خرابی_بتانا("cat");
        return;
    }
    while ((پڑھے_گئے_بائٹ = پڑھنا(فائل_کا_وصف_کنندہ_2, منتقلی_کا_عارضی_ذخیرہ_2, sizeof(منتقلی_کا_عارضی_ذخیرہ_2))) > 0)
        (void)لکھنا(STDOUT_FILENO, منتقلی_کا_عارضی_ذخیرہ_2, (size_t)پڑھے_گئے_بائٹ);
    if (پڑھے_گئے_بائٹ < 0)
        خرابی_بتانا("cat/read");
    (void)close(فائل_کا_وصف_کنندہ_2);
    متن_لکھنا("\n");
}

static void فائل_کی_معلومات_دکھانا(const char *فائل_کا_نام)
{
    struct stat حالت;
    if (stat(فائل_کا_نام, &حالت) < 0) {
        خرابی_بتانا("stat");
        return;
    }
    متن_لکھنا("size=");
    صحیح_عدد_لکھنا((int)حالت.st_size);
    متن_لکھنا(S_ISDIR(حالت.st_mode) ? " type=directory\n" : " type=file\n");
}

