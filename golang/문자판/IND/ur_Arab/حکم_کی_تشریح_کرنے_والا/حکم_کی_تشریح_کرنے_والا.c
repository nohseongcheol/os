enum { اندراج_کی_سطر_کی_گنجائش = 512, دلائل_کی_زیادہ_سے_زیادہ_تعداد = 16, احکامات_کی_فائلوں_کی_زیادہ_سے_زیادہ_تہیں = 4 };
static int احکامات_کی_فائلوں_کی_تہہ_کی_گہرائی;
struct اندراج_کا_بہاؤ {
    int اندراج_کا_وصف_کنندہ;
    char منتقلی_کا_عارضی_ذخیرہ_2[256];
    size_t مقام;
    size_t لمبائی;
};

static size_t متن_کی_بائٹ_لمبائی(const char *متن)
{
    size_t لمبائی = 0;
    while (متن[لمبائی] != '\0')
        لمبائی++;
    return لمبائی;
}

static int متن_برابر_ہیں(const char *بایاں, const char *دایاں)
{
    size_t مقام = 0;
    while (بایاں[مقام] == دایاں[مقام]) {
        if (بایاں[مقام] == '\0')
            return 1;
        مقام++;
    }
    return 0;
}

static void متن_لکھنا(const char *متن)
{
    size_t لمبائی = متن_کی_بائٹ_لمبائی(متن);
    while (لمبائی > 0U) {
        ssize_t لکھے_گئے_بائٹ_کی_تعداد = لکھنا(STDOUT_FILENO, متن, لمبائی);
        if (لکھے_گئے_بائٹ_کی_تعداد <= 0)
            return;
        متن += لکھے_گئے_بائٹ_کی_تعداد;
        لمبائی -= (size_t)لکھے_گئے_بائٹ_کی_تعداد;
    }
}

static void صحیح_عدد_لکھنا(int قدر)
{
    char ہندسوں_کے_حروف[16];
    unsigned int ہندسوں_کی_تعداد;
    unsigned int بغیر_علامت_مقدار;

    if (قدر < 0) {
        متن_لکھنا("-");
        بغیر_علامت_مقدار = (unsigned int)(-(قدر + 1)) + 1U;
    } else {
        بغیر_علامت_مقدار = (unsigned int)قدر;
    }
    ہندسوں_کی_تعداد = 0;
    do {
        ہندسوں_کے_حروف[ہندسوں_کی_تعداد++] = (char)('0' + بغیر_علامت_مقدار % 10U);
        بغیر_علامت_مقدار /= 10U;
    } while (بغیر_علامت_مقدار != 0U);
    while (ہندسوں_کی_تعداد > 0U) {
        ہندسوں_کی_تعداد--;
        (void)لکھنا(STDOUT_FILENO, &ہندسوں_کے_حروف[ہندسوں_کی_تعداد], 1);
    }
}

static void خرابی_بتانا(const char *عمل)
{
    متن_لکھنا("error: ");
    متن_لکھنا(عمل);
    متن_لکھنا(" errno=");
    صحیح_عدد_لکھنا(errno);
    متن_لکھنا("\n");
}

static int اندراج_کی_سطر_پڑھنا(struct اندراج_کا_بہاؤ *اندراج, char *اندراج_کی_سطر, size_t گنجائش)
{
    size_t مقام = 0;
    int غلط_اندراج_کی_سطر = 0;
    char حرف;
    ssize_t پڑھے_گئے_بائٹ;
    if (گنجائش < 2U)
        return -2;
    for (;;) {
        if (اندراج->مقام == اندراج->لمبائی) {
            پڑھے_گئے_بائٹ = پڑھنا(اندراج->اندراج_کا_وصف_کنندہ, اندراج->منتقلی_کا_عارضی_ذخیرہ_2, sizeof(اندراج->منتقلی_کا_عارضی_ذخیرہ_2));
            if (پڑھے_گئے_بائٹ < 0) {
                if (errno == EINTR)
                    continue;
                return -1;
            }
            if (پڑھے_گئے_بائٹ == 0) {
                if (مقام == 0 && !غلط_اندراج_کی_سطر)
                    return -1;
                break;
            }
            اندراج->لمبائی = (size_t)پڑھے_گئے_بائٹ;
            اندراج->مقام = 0;
        }
        حرف = اندراج->منتقلی_کا_عارضی_ذخیرہ_2[اندراج->مقام++];
        if (حرف == '\n')
            break;
        if (اندراج->اندراج_کا_وصف_کنندہ == STDIN_FILENO && حرف == 4) {
            if (مقام == 0 && !غلط_اندراج_کی_سطر)
                return -1;
            break;
        }
        if (اندراج->اندراج_کا_وصف_کنندہ == STDIN_FILENO && (حرف == 8 || حرف == 127)) {
            if (مقام > 0) {
                do {
                    مقام--;
                } while (مقام > 0 && ((unsigned char)اندراج_کی_سطر[مقام] & 0xc0U) == 0x80U);
            }
            continue;
        }
        if (حرف == '\r')
            continue;
        if (حرف == '\0') {
            غلط_اندراج_کی_سطر = 1; /* Reject binary input; do not execute its prefix. */
            continue;
        }
        if (مقام + 1U < گنجائش)
            اندراج_کی_سطر[مقام++] = حرف;
        else
            غلط_اندراج_کی_سطر = 1;
    }
    اندراج_کی_سطر[مقام] = '\0';
    return غلط_اندراج_کی_سطر ? -2 : (int)مقام;
}

static int دلائل_الگ_کرنا(char *اندراج_کی_سطر, char **دلائل)
{
    int دلائل_کی_تعداد = 0;
    char *موجودہ_مقام = اندراج_کی_سطر;
    char *اخراج_کا_مقام = اندراج_کی_سطر;

    while (*موجودہ_مقام != '\0') {
        char اقتباس_کی_علامت = '\0';
        while (*موجودہ_مقام == ' ' || *موجودہ_مقام == '\t')
            موجودہ_مقام++;
        if (*موجودہ_مقام == '\0' || *موجودہ_مقام == '#')
            break;
        if (دلائل_کی_تعداد == دلائل_کی_زیادہ_سے_زیادہ_تعداد - 1)
            return -1;
        دلائل[دلائل_کی_تعداد++] = اخراج_کا_مقام;
        while (*موجودہ_مقام != '\0') {
            char حرف = *موجودہ_مقام++;
            if (اقتباس_کی_علامت == '\0' && (حرف == ' ' || حرف == '\t'))
                break;
            if (حرف == '\\' && اقتباس_کی_علامت != '\'') {
                if (*موجودہ_مقام == '\0')
                    return -1;
                *اخراج_کا_مقام++ = *موجودہ_مقام++;
            } else if (حرف == '\'' || حرف == '"') {
                if (اقتباس_کی_علامت == '\0')
                    اقتباس_کی_علامت = حرف;
                else if (اقتباس_کی_علامت == حرف)
                    اقتباس_کی_علامت = '\0';
                else
                    *اخراج_کا_مقام++ = حرف;
            } else {
                *اخراج_کا_مقام++ = حرف;
            }
        }
        if (اقتباس_کی_علامت != '\0')
            return -1;
        *اخراج_کا_مقام++ = '\0';
    }
    دلائل[دلائل_کی_تعداد] = (char *)0;
    return دلائل_کی_تعداد;
}

