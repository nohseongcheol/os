static int もじれついっちはんてい(const char *ひだりのあたい, const char *みぎのあたい)
{
    unsigned int こうのそえじ = 0;
    while (ひだりのあたい[こうのそえじ] != 0 && みぎのあたい[こうのそえじ] != 0) {
        if (ひだりのあたい[こうのそえじ] != みぎのあたい[こうのそえじ])
            return 0;
        こうのそえじ++;
    }
    return ひだりのあたい[こうのそえじ] == みぎのあたい[こうのそえじ];
}

