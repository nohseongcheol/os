static void かほうへせいれつをなおす(unsigned char *ようそはいれつ, おおきさがた こうかいち, おおきさがた すうりょう,
                      おおきさがた ようそのおおきさ, int (*ひかくかんすう)(const void *, const void *))
{
    while (こうかいち < すうりょう / 2) {
        おおきさがた このいち = こうかいち * 2 + 1;
        if (このいち + 1 < すうりょう && ひかくかんすう(ようそはいれつ + このいち * ようそのおおきさ, ようそはいれつ + (このいち + 1) * ようそのおおきさ) < 0)
            ++このいち;
        if (ひかくかんすう(ようそはいれつ + こうかいち * ようそのおおきさ, ようそはいれつ + このいち * ようそのおおきさ) >= 0) return;
        ようそをこうかんする(ようそはいれつ + こうかいち * ようそのおおきさ, ようそはいれつ + このいち * ようそのおおきさ, ようそのおおきさ);
        こうかいち = このいち;
    }
}

void ひかくきじゅんでせいれつする(void *ようそはいれつ, おおきさがた すうりょう, おおきさがた ようそのおおきさ,
           int (*ひかくかんすう)(const void *, const void *))
{
    unsigned char *しんこういち = ようそはいれつ;
    おおきさがた そえじ;
    if (すうりょう < 2 || !ようそのおおきさ || すうりょう > (おおきさがた)-1 / ようそのおおきさ) return;
    /* Heap sort: bounded stack, O(n log n), comparator receives array elements. */
    for (そえじ = すうりょう / 2; そえじ; ) かほうへせいれつをなおす(しんこういち, --そえじ, すうりょう, ようそのおおきさ, ひかくかんすう);
    for (そえじ = すうりょう - 1; そえじ; --そえじ) {
        ようそをこうかんする(しんこういち, しんこういち + そえじ * ようそのおおきさ, ようそのおおきさ);
        かほうへせいれつをなおす(しんこういち, 0, そえじ, ようそのおおきさ, ひかくかんすう);
    }
}

