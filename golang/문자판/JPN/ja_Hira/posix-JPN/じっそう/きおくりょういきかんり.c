/* Single-thread runtime. Reuse and coalesce freed blocks; do not shrink brk.
 * A block header and every returned address are 16-byte aligned on i386.
 * Callers must not move brk backwards across live allocations. */
struct きおくくかく {
    おおきさがた ようりょう;
    struct きおくくかく *つぎのくかく;
    int りようかのうはんてい;
    unsigned int せいれつうめこみちょう;
};
static struct きおくくかく *さいしょのくかく;

void *きおくりょういきをかくほする(おおきさがた おおきさ)
{
    struct きおくくかく *しんこういち = さいしょのくかく, *さいごのくかく = からばんち, *かくほもとばんち;
    おおきさがた ぜんたいちょう, せいれつうめこみちょう;
    void *ばんち;
    if (!おおきさ) おおきさ = 1;
    if (おおきさ > (おおきさがた)せいすうさいだいち - 2 * sizeof(struct きおくくかく)) { あやまりばんごう = あやまりきおくぶそく; return からばんち; }
    おおきさ = (おおきさ + 15U) & ~15U;
    while (しんこういち) {
        if (しんこういち->りようかのうはんてい && しんこういち->ようりょう >= おおきさ) {
            if (しんこういち->ようりょう - おおきさ >= sizeof(struct きおくくかく) + 16U) {
                かくほもとばんち = (struct きおくくかく *)((unsigned char *)(しんこういち + 1) + おおきさ);
                かくほもとばんち->ようりょう = しんこういち->ようりょう - おおきさ - sizeof(*かくほもとばんち);
                かくほもとばんち->つぎのくかく = しんこういち->つぎのくかく;
                かくほもとばんち->りようかのうはんてい = 1;
                しんこういち->つぎのくかく = かくほもとばんち;
                しんこういち->ようりょう = おおきさ;
            }
            しんこういち->りようかのうはんてい = 0;
            return しんこういち + 1;
        }
        さいごのくかく = しんこういち; しんこういち = しんこういち->つぎのくかく;
    }
    ばんち = どうてききおくのしゅうたんをうつす(0);
    if (ばんち == (void *)-1) return からばんち;
    せいれつうめこみちょう = (0U - (ばんちはばふごうなしせいすう)ばんち) & 15U;
    ぜんたいちょう = せいれつうめこみちょう + sizeof(struct きおくくかく) + おおきさ;
    if ((ばんちはばふごうなしせいすう)ばんち > (ばんちはばふごうなしせいすう)せいすうさいだいち - ぜんたいちょう) { あやまりばんごう = あやまりきおくぶそく; return からばんち; }
    ばんち = どうてききおくのしゅうたんをうつす((int)ぜんたいちょう);
    if (ばんち == (void *)-1) return からばんち;
    かくほもとばんち = (struct きおくくかく *)((unsigned char *)ばんち + せいれつうめこみちょう);
    かくほもとばんち->ようりょう = おおきさ; かくほもとばんち->つぎのくかく = からばんち; かくほもとばんち->りようかのうはんてい = 0;
    if (さいごのくかく) さいごのくかく->つぎのくかく = かくほもとばんち;
    else さいしょのくかく = かくほもとばんち;
    return かくほもとばんち + 1;
}

void きおくりょういきをかえす(void *ばんち)
{
    struct きおくくかく *しんこういち;
    if (!ばんち) return;
    ((struct きおくくかく *)ばんち - 1)->りようかのうはんてい = 1;
    しんこういち = さいしょのくかく;
    while (しんこういち && しんこういち->つぎのくかく) {
        struct きおくくかく *つぎのくかく = しんこういち->つぎのくかく;
        if (しんこういち->りようかのうはんてい && つぎのくかく->りようかのうはんてい &&
            (unsigned char *)(しんこういち + 1) + しんこういち->ようりょう == (unsigned char *)つぎのくかく) {
            しんこういち->ようりょう += sizeof(*つぎのくかく) + つぎのくかく->ようりょう;
            しんこういち->つぎのくかく = つぎのくかく->つぎのくかく;
        } else しんこういち = つぎのくかく;
    }
}

void *れいでみたしたはいれつりょういきをかくほする(おおきさがた すうりょう, おおきさがた ようそのおおきさ)
{
    void *ばんち;
    if (ようそのおおきさ && すうりょう > (おおきさがた)-1 / ようそのおおきさ) { あやまりばんごう = あやまりきおくぶそく; return からばんち; }
    ばんち = きおくりょういきをかくほする(すうりょう * ようそのおおきさ);
    if (ばんち) きおくりょういきをあたいでみたす(ばんち, 0, すうりょう * ようそのおおきさ);
    return ばんち;
}

void *きおくりょういきのおおきさをかえる(void *ばんち, おおきさがた おおきさ)
{
    void *かきこみさき;
    struct きおくくかく *しんこういち;
    if (!ばんち) return きおくりょういきをかくほする(おおきさ);
    /* Documented zero-size choice: retain a valid, freeable minimum block. */
    if (!おおきさ) おおきさ = 1;
    しんこういち = (struct きおくくかく *)ばんち - 1;
    if (おおきさ <= しんこういち->ようりょう) return ばんち;
    かきこみさき = きおくりょういきをかくほする(おおきさ);
    if (!かきこみさき) return からばんち;
    きおくないようをふくしゃする(かきこみさき, ばんち, しんこういち->ようりょう);
    きおくりょういきをかえす(ばんち);
    return かきこみさき;
}
