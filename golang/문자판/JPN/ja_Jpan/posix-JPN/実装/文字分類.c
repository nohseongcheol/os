#include <文字分類.h>

/* Single-byte C/POSIX locale; these are not Unicode character classifiers. */
int 大文字か調べる(int 文字値) { return 文字値 >= 'A' && 文字値 <= 'Z'; }
int 小文字か調べる(int 文字値) { return 文字値 >= 'a' && 文字値 <= 'z'; }
int 英字か調べる(int 文字値) { return 大文字か調べる(文字値) || 小文字か調べる(文字値); }
int 十進数字か調べる(int 文字値) { return 文字値 >= '0' && 文字値 <= '9'; }
int 英字か数字か調べる(int 文字値) { return 英字か調べる(文字値) || 十進数字か調べる(文字値); }
int 水平空白か調べる(int 文字値) { return 文字値 == ' ' || 文字値 == '\t'; }
int 空白文字か調べる(int 文字値) { return 文字値 == ' ' || (文字値 >= '\t' && 文字値 <= '\r'); }
int 制御文字か調べる(int 文字値) { return (文字値 >= 0 && 文字値 < 32) || 文字値 == 127; }
int 印字文字か調べる(int 文字値) { return 文字値 >= 32 && 文字値 <= 126; }
int 空白以外の印字文字か調べる(int 文字値) { return 文字値 >= 33 && 文字値 <= 126; }
int 句読記号か調べる(int 文字値) { return 空白以外の印字文字か調べる(文字値) && !英字か数字か調べる(文字値); }
int 十六進数字か調べる(int 文字値) { return 十進数字か調べる(文字値) || (文字値 >= 'a' && 文字値 <= 'f') || (文字値 >= 'A' && 文字値 <= 'F'); }
int 小文字に変える(int 文字値) { return 大文字か調べる(文字値) ? 文字値 + ('a' - 'A') : 文字値; }
int 大文字に変える(int 文字値) { return 小文字か調べる(文字値) ? 文字値 - ('a' - 'A') : 文字値; }
