#include <体系/子の待機.h>
#include <文書制御.h>
#include <入出力と実行.h>

static void 電文を書く(const char *文字列, unsigned int 大きさ)
{
    (void)書く(標準出力番号, 文字列, 大きさ);
}

int main(void)
{
    int 終了状態;
    実行過程番号型 親過程 = 実行過程番号を得る();
    実行過程番号型 子の位置;
    実行過程番号型 待った過程;
    volatile int 過程専用値 = 10;
    int 文書記述番号;
    char 八桁組値;
    int 反復回数;

    電文を書く("\nPOSIX-FORK:START\n", 18);
    子の位置 = 実行過程を分岐する();
    if (子の位置 == 0) {
        過程専用値 = 20;
        if (親実行過程番号を得る() != 親過程 || 過程専用値 != 20)
            直ちに終了する(90);
        直ちに終了する(23);
    }
    if (子の位置 < 0) {
        電文を書く("PTEST:FAIL:fork-return\n", 23);
        直ちに終了する(1);
    }
    電文を書く("PTEST:PASS:fork-return\n", 23);
    待った過程 = 指定した子を待つ(子の位置, &終了状態, 0);
    if (待った過程 == 子の位置 && 正常終了判定(終了状態) && 終了値取出し(終了状態) == 23 &&
        過程専用値 == 10) {
        電文を書く("PTEST:PASS:fork-wait-exit\n", 26);
    } else {
        電文を書く("PTEST:FAIL:fork-wait-exit\n", 26);
        直ちに終了する(1);
    }

    子の位置 = 実行過程を分岐する();
    if (子の位置 == 0)
        直ちに終了する(29);
    待った過程 = 子を待つ(&終了状態);
    if (待った過程 == 子の位置 && 正常終了判定(終了状態) && 終了値取出し(終了状態) == 29)
        電文を書く("PTEST:PASS:blocking-wait\n", 25);
    else {
        電文を書く("PTEST:FAIL:blocking-wait\n", 25);
        直ちに終了する(1);
    }

    文書記述番号 = 開く("/USER2", 読取専用で開く);
    子の位置 = 実行過程を分岐する();
    if (子の位置 == 0) {
        (void)閉じる(文書記述番号);
        直ちに終了する(0);
    }
    待った過程 = 指定した子を待つ(子の位置, &終了状態, 0);
    if (文書記述番号 >= 0 && 待った過程 == 子の位置 && 読む(文書記述番号, &八桁組値, 1) == 1 &&
        (unsigned char)八桁組値 == 0x7f)
        電文を書く("PTEST:PASS:fork-fd-isolation\n", 29);
    else {
        電文を書く("PTEST:FAIL:fork-fd-isolation\n", 29);
        直ちに終了する(1);
    }
    (void)閉じる(文書記述番号);

    for (反復回数 = 0; 反復回数 < 2; 反復回数++) {
        子の位置 = 実行過程を分岐する();
        if (子の位置 == 0)
            直ちに終了する(反復回数);
        if (子の位置 < 0 || 指定した子を待つ(子の位置, &終了状態, 0) != 子の位置 ||
            !正常終了判定(終了状態) || 終了値取出し(終了状態) != 反復回数) {
            電文を書く("PTEST:FAIL:fork-stress\n", 23);
            直ちに終了する(1);
        }
    }
    電文を書く("PTEST:PASS:fork-stress\n", 23);
    電文を書く("POSIX-FORK:PASS\n", 16);
    直ちに終了する(0);
}
