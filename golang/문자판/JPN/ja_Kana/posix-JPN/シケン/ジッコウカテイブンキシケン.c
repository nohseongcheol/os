#include <タイケイ/コノタイキ.h>
#include <ブンショセイギョ.h>
#include <ニュウシュツリョクトジッコウ.h>

static void デンブンヲカク(const char *モジレツ, unsigned int オオキサ)
{
    (void)カク(ヒョウジュンシュツリョクバンゴウ, モジレツ, オオキサ);
}

int main(void)
{
    int シュウリョウジョウタイ;
    ジッコウカテイバンゴウガタ オヤカテイ = ジッコウカテイバンゴウヲエル();
    ジッコウカテイバンゴウガタ コノイチ;
    ジッコウカテイバンゴウガタ マッタカテイ;
    volatile int カテイセンヨウチ = 10;
    int ブンショキジュツバンゴウ;
    char ハチケタグミチ;
    int ハンプクカイスウ;

    デンブンヲカク("\nPOSIX-FORK:START\n", 18);
    コノイチ = ジッコウカテイヲブンキスル();
    if (コノイチ == 0) {
        カテイセンヨウチ = 20;
        if (オヤジッコウカテイバンゴウヲエル() != オヤカテイ || カテイセンヨウチ != 20)
            タダチニシュウリョウスル(90);
        タダチニシュウリョウスル(23);
    }
    if (コノイチ < 0) {
        デンブンヲカク("PTEST:FAIL:fork-return\n", 23);
        タダチニシュウリョウスル(1);
    }
    デンブンヲカク("PTEST:PASS:fork-return\n", 23);
    マッタカテイ = シテイシタコヲマツ(コノイチ, &シュウリョウジョウタイ, 0);
    if (マッタカテイ == コノイチ && セイジョウシュウリョウハンテイ(シュウリョウジョウタイ) && シュウリョウチトリダシ(シュウリョウジョウタイ) == 23 &&
        カテイセンヨウチ == 10) {
        デンブンヲカク("PTEST:PASS:fork-wait-exit\n", 26);
    } else {
        デンブンヲカク("PTEST:FAIL:fork-wait-exit\n", 26);
        タダチニシュウリョウスル(1);
    }

    コノイチ = ジッコウカテイヲブンキスル();
    if (コノイチ == 0)
        タダチニシュウリョウスル(29);
    マッタカテイ = コヲマツ(&シュウリョウジョウタイ);
    if (マッタカテイ == コノイチ && セイジョウシュウリョウハンテイ(シュウリョウジョウタイ) && シュウリョウチトリダシ(シュウリョウジョウタイ) == 29)
        デンブンヲカク("PTEST:PASS:blocking-wait\n", 25);
    else {
        デンブンヲカク("PTEST:FAIL:blocking-wait\n", 25);
        タダチニシュウリョウスル(1);
    }

    ブンショキジュツバンゴウ = ヒラク("/USER2", ヨミトリセンヨウデヒラク);
    コノイチ = ジッコウカテイヲブンキスル();
    if (コノイチ == 0) {
        (void)トジル(ブンショキジュツバンゴウ);
        タダチニシュウリョウスル(0);
    }
    マッタカテイ = シテイシタコヲマツ(コノイチ, &シュウリョウジョウタイ, 0);
    if (ブンショキジュツバンゴウ >= 0 && マッタカテイ == コノイチ && ヨム(ブンショキジュツバンゴウ, &ハチケタグミチ, 1) == 1 &&
        (unsigned char)ハチケタグミチ == 0x7f)
        デンブンヲカク("PTEST:PASS:fork-fd-isolation\n", 29);
    else {
        デンブンヲカク("PTEST:FAIL:fork-fd-isolation\n", 29);
        タダチニシュウリョウスル(1);
    }
    (void)トジル(ブンショキジュツバンゴウ);

    for (ハンプクカイスウ = 0; ハンプクカイスウ < 2; ハンプクカイスウ++) {
        コノイチ = ジッコウカテイヲブンキスル();
        if (コノイチ == 0)
            タダチニシュウリョウスル(ハンプクカイスウ);
        if (コノイチ < 0 || シテイシタコヲマツ(コノイチ, &シュウリョウジョウタイ, 0) != コノイチ ||
            !セイジョウシュウリョウハンテイ(シュウリョウジョウタイ) || シュウリョウチトリダシ(シュウリョウジョウタイ) != ハンプクカイスウ) {
            デンブンヲカク("PTEST:FAIL:fork-stress\n", 23);
            タダチニシュウリョウスル(1);
        }
    }
    デンブンヲカク("PTEST:PASS:fork-stress\n", 23);
    デンブンヲカク("POSIX-FORK:PASS\n", 16);
    タダチニシュウリョウスル(0);
}
