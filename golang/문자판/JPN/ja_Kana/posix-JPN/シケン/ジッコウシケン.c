static int ケンサスウ;
static int シッパイスウ;

static unsigned int モジレツクミチョウ(const char *モジレツ)
{
    unsigned int ナガサ = 0;
    while (モジレツ[ナガサ] != 0)
        ナガサ++;
    return ナガサ;
}

static int モジレツイッチハンテイ(const char *ヒダリノアタイ, const char *ミギノアタイ)
{
    unsigned int コウノソエジ = 0;
    while (ヒダリノアタイ[コウノソエジ] != 0 && ミギノアタイ[コウノソエジ] != 0) {
        if (ヒダリノアタイ[コウノソエジ] != ミギノアタイ[コウノソエジ])
            return 0;
        コウノソエジ++;
    }
    return ヒダリノアタイ[コウノソエジ] == ミギノアタイ[コウノソエジ];
}

static void デンブンヲカク(const char *モジレツ)
{
    (void)カク(ヒョウジュンシュツリョクバンゴウ, モジレツ, モジレツクミチョウ(モジレツ));
}

static void ケッカヲホウコク(const char *ナマエ, int ゴウカクハンテイ)
{
    ケンサスウ++;
    if (ゴウカクハンテイ) {
        デンブンヲカク("PTEST:PASS:");
    } else {
        シッパイスウ++;
        デンブンヲカク("PTEST:FAIL:");
    }
    デンブンヲカク(ナマエ);
    デンブンヲカク("\n");
}

static int シテイアヤマリニヨルシッパイハンテイ(int ケッカ, int キタイアヤマリバンゴウ)
{
    return ケッカ == -1 && アヤマリバンゴウ == キタイアヤマリバンゴウ;
}

static ジッコウカテイバンゴウガタ マタズニコヲカイシュウ(ジッコウカテイバンゴウガタ コノイチ, int *シュウリョウジョウタイ)
{
    unsigned int カイテンスウ;
    ジッコウカテイバンゴウガタ ケッカ;

    for (カイテンスウ = 0; カイテンスウ < 2000000U; カイテンスウ++) {
        ケッカ = シテイシタコヲマツ(コノイチ, シュウリョウジョウタイ, ミジュンビナラマタナイ);
        if (ケッカ != 0)
            return ケッカ;
    }
    return 0;
}

