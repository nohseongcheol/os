        アヤマリバンゴウ = 0;
        ケッカヲホウコク("fstat-efault", シテイアヤマリニヨルシッパイハンテイ(ヒライタブンショノジョウタイヲエル(ブンショキジュツバンゴウ, (struct ブンショジョウタイ *)0), アヤマリキオクバンチフセイ));
