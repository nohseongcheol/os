#include <ツウシンバンチ/ハチケタグミジュンジョ.h>
#include <アヤマリバンゴウ.h>
#include <タイケイ/ツウシンタンテン.h>
#include <ニュウシュツリョクトジッコウ.h>

static unsigned int モジレツチョウヲエル(const char *ケンサシリョウ)
{
    unsigned int ヨビダシシュルイ = 0;
    while (ケンサシリョウ[ヨビダシシュルイ] != 0) ヨビダシシュルイ++;
    return ヨビダシシュルイ;
}

static void デンブンヲカク(const char *ケンサシリョウ) { (void)カク(ヒョウジュンシュツリョクバンゴウ, ケンサシリョウ, モジレツチョウヲエル(ケンサシリョウ)); }

static void ケッカヲホウコク(const char *ナマエ, int ケンサゴウカク)
{
    デンブンヲカク(ケンサゴウカク ? "NTEST:PASS:" : "NTEST:FAIL:");
    デンブンヲカク(ナマエ);
    デンブンヲカク("\n");
}

int main(void)
{
    struct ソウゴセツゾクモウタンテンバンチ オウトウタンテンバンチ = {0};
    struct ソウゴセツゾクモウタンテンバンチ ヨミダシモト = {0};
    バンチチョウガタ ソウシンモトバンチチョウ = sizeof(ヨミダシモト);
    char シリョウカンショウリョウイキ[8] = {0};
    int オウトウタンテン = ツウシンタンテンヲツクル(ソウゴセツゾクモウバンチケイトウ, シリョウデンブンタンテン, リヨウシャシリョウデンブンキヤク);
    int ヨウキュウタンテン = ツウシンタンテンヲツクル(ソウゴセツゾクモウバンチケイトウ, シリョウデンブンタンテン, 0);

    ケッカヲホウコク("socket-server", オウトウタンテン >= 3);
    ケッカヲホウコク("socket-client", ヨウキュウタンテン >= 3 && ヨウキュウタンテン != オウトウタンテン);
    オウトウタンテンバンチ.セツゾクモウバンチケイトウ = ソウゴセツゾクモウバンチケイトウ;
    オウトウタンテンバンチ.ツウシンマドグチバンゴウ = ツウシンモウジュンニ16ケタヲカエル(32345);
    オウトウタンテンバンチ.セツゾクモウバンチナイヨウ.バンチチ = ツウシンモウジュンニ32ケタヲカエル(ジコオリカエシバンチ);
    ケッカヲホウコク("bind", キョクショバンチヲムスブ(オウトウタンテン, (const struct ツウシンタンテンバンチ *)&オウトウタンテンバンチ,
                        sizeof(オウトウタンテンバンチ)) == 0);
    ケッカヲホウコク("connect", アイテタンテンニツナグ(ヨウキュウタンテン, (const struct ツウシンタンテンバンチ *)&オウトウタンテンバンチ,
                              sizeof(オウトウタンテンバンチ)) == 0);
    ケッカヲホウコク("send", オクル(ヨウキュウタンテン, "ping", 4, 0) == 4);
    ケッカヲホウコク("recvfrom", ソウシンモトトトモニウケトル(オウトウタンテン, シリョウカンショウリョウイキ, sizeof(シリョウカンショウリョウイキ), 0,
                                (struct ツウシンタンテンバンチ *)&ヨミダシモト, &ソウシンモトバンチチョウ) == 4 &&
                       シリョウカンショウリョウイキ[0] == 'p' && シリョウカンショウリョウイキ[3] == 'g' && ソウシンモトバンチチョウ == 16);
    アヤマリバンゴウ = 0;
    ケッカヲホウコク("empty-eagain", ウケトル(オウトウタンテン, シリョウカンショウリョウイキ, sizeof(シリョウカンショウリョウイキ), 0) == -1 && アヤマリバンゴウ == アヤマリイチジリヨウフカ);
    ケッカヲホウコク("getsockname", キョクショタンテンノバンチヲエル(オウトウタンテン, (struct ツウシンタンテンバンチ *)&ヨミダシモト,
                                      &ソウシンモトバンチチョウ) == 0 && ヨミダシモト.ツウシンマドグチバンゴウ == ツウシンモウジュンニ16ケタヲカエル(32345));
    アヤマリバンゴウ = 0;
    ケッカヲホウコク("udp-listen-not-supported", セツゾクヨウキュウニソナエル(オウトウタンテン, 1) == -1 && アヤマリバンゴウ == アヤマリソウサヒタイオウ);
    ケッカヲホウコク("close-client", トジル(ヨウキュウタンテン) == 0);
    ケッカヲホウコク("close-server", トジル(オウトウタンテン) == 0);
    デンブンヲカク("NTEST:DONE\n");
    return 0;
}
