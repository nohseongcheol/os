#include <アヤマリバンゴウ.h>
#include <ブンショセイギョ.h>
#include <タイケイ/ブンショジョウタイ.h>
#include <タイケイ/タイケイジョウホウ.h>
#include <タイケイ/コノタイキ.h>
#include <ニュウシュツリョクトジッコウ.h>

int センゲンホンヤクシケン(void)
{
    char サギョウモクロク[8];
    struct ブンショジョウタイ ジョウタイシリョウ;
    struct タイケイジョウホウ ナマエ;
    int ブンショキジュツバンゴウ = ヒラク("/USER1", ヨミトリセンヨウデヒラク);
    int フクシャチ = ブンショキジュツバンゴウ >= 0 ? ヒライタブンショノサンショウヲフクセイスル(ブンショキジュツバンゴウ) : -1;
    if (フクシャチ >= 0) トジル(フクシャチ);
    if (ブンショキジュツバンゴウ >= 0) {
        ヒライタブンショノジョウタイヲエル(ブンショキジュツバンゴウ, &ジョウタイシリョウ);
        ヨミカキイチヲウツス(ブンショキジュツバンゴウ, 0, セントウキジュンイチ);
        トジル(ブンショキジュツバンゴウ);
    }
    ブンショジョウタイ("/", &ジョウタイシリョウ);
    タイケイジョウホウヲエル(&ナマエ);
    サギョウモクロクノケイロヲエル(サギョウモクロク, sizeof(サギョウモクロク));
    return アヤマリバンゴウ + ジッコウカテイバンゴウヲエル() + オヤジッコウカテイバンゴウヲエル();
}
