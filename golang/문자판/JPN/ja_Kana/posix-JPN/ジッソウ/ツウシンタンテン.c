static long ツウシンタンテンヲヨビダス(long ツウシンヨビダシバンゴウ, unsigned long *ウケワタシヒキスウイチラン)
{
    return __syscall_result(
        __syscall6(ツウシンタンテンタイケイヨビダシバンゴウ, ツウシンヨビダシバンゴウ, (long)ウケワタシヒキスウイチラン, 0, 0, 0, 0));
}

