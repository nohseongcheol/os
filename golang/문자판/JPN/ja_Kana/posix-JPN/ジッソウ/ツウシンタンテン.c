フゴウナシ16ニシンケタセイスウ キカイジュンニ16ケタヲカエル(フゴウナシ16ニシンケタセイスウ アタイ) { return ツウシンモウジュンニ16ケタヲカエル(アタイ); }
フゴウナシ32ニシンケタセイスウ ツウシンモウジュンニ32ケタヲカエル(フゴウナシ32ニシンケタセイスウ アタイ)
{
    return ((アタイ & 0x000000ffU) << 24) | ((アタイ & 0x0000ff00U) << 8) |
           ((アタイ & 0x00ff0000U) >> 8) | ((アタイ & 0xff000000U) >> 24);
}
