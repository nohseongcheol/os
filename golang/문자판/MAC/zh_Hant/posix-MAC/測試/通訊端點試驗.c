#include <通訊位址/位元組順序.h>
#include <錯誤編號.h>
#include <系統/通訊端點.h>
#include <輸入輸出與執行.h>

static unsigned int 取得文字長度(const char *受檢資料)
{
    unsigned int 呼叫種類 = 0;
    while (受檢資料[呼叫種類] != 0) 呼叫種類++;
    return 呼叫種類;
}

static void 寫出訊息(const char *受檢資料) { (void)寫入(標準輸出編號, 受檢資料, 取得文字長度(受檢資料)); }

static void 報告結果(const char *系統資料, int 檢查通過)
{
    寫出訊息(檢查通過 ? "NTEST:PASS:" : "NTEST:FAIL:");
    寫出訊息(系統資料);
    寫出訊息("\n");
}

int main(void)
{
    struct 互聯網路端點位址 回應端點位址 = {0};
    struct 互聯網路端點位址 來源位置 = {0};
    位址長度型別 來源位址大小 = sizeof(來源位置);
    char 資料緩衝區域[8] = {0};
    int 回應端點 = 建立通訊端點(互聯網路位址族, 資料報端點, 使用者資料報協定);
    int 請求端點 = 建立通訊端點(互聯網路位址族, 資料報端點, 0);

    報告結果("socket-server", 回應端點 >= 3);
    報告結果("socket-client", 請求端點 >= 3 && 請求端點 != 回應端點);
    回應端點位址.互聯位址族 = 互聯網路位址族;
    回應端點位址.通訊埠編號 = 轉為網路次序16位(32345);
    回應端點位址.互聯位址內容.位址值 = 轉為網路次序32位(本機迴送位址);
    報告結果("bind", 繫結本地位址(回應端點, (const struct 通訊端點位址 *)&回應端點位址,
                        sizeof(回應端點位址)) == 0);
    報告結果("connect", 連接對端(請求端點, (const struct 通訊端點位址 *)&回應端點位址,
                              sizeof(回應端點位址)) == 0);
    報告結果("send", 傳送(請求端點, "ping", 4, 0) == 4);
    報告結果("recvfrom", 接收並取得來源位址(回應端點, 資料緩衝區域, sizeof(資料緩衝區域), 0,
                                (struct 通訊端點位址 *)&來源位置, &來源位址大小) == 4 &&
                       資料緩衝區域[0] == 'p' && 資料緩衝區域[3] == 'g' && 來源位址大小 == 16);
    錯誤編號 = 0;
    報告結果("empty-eagain", 接收(回應端點, 資料緩衝區域, sizeof(資料緩衝區域), 0) == -1 && 錯誤編號 == 錯誤暫時無法使用);
    報告結果("getsockname", 取得本地端點位址(回應端點, (struct 通訊端點位址 *)&來源位置,
                                      &來源位址大小) == 0 && 來源位置.通訊埠編號 == 轉為網路次序16位(32345));
    錯誤編號 = 0;
    報告結果("udp-listen-not-supported", 準備接收連線(回應端點, 1) == -1 && 錯誤編號 == 錯誤不支援操作);
    報告結果("close-client", 關閉(請求端點) == 0);
    報告結果("close-server", 關閉(回應端點) == 0);
    寫出訊息("NTEST:DONE\n");
    return 0;
}
