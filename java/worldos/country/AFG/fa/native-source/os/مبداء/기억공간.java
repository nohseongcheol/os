/** 부팅 اطلاعات_سیستم 조회와 4KiB 고정 اندازه 작업 قسمت_مقدار اختصاص_دادن_حافظه_تلفن/بازگرداندن_سنجش. 일반 물리 صفحه_مقدار 관리자는 아니다. */
public final class 기억공간 {
    static int[] قسمت_مقدار = new int[8192];
    static int[] 사용 = new int[8];

    static int تفسیر_عدد_صحیح(int آدرس) {
        return دستگاه_مقدار.기억읽기(آدرس) | (دستگاه_مقدار.기억읽기(آدرس + 1) << 8)
            | (دستگاه_مقدار.기억읽기(آدرس + 2) << 16) | (دستگاه_مقدار.기억읽기(آدرس + 3) << 24);
    }

    static int 위쪽기억크기() {
        int اطلاعات_سیستم = دستگاه_مقدار.부팅정보();
        if (دستگاه_مقدار.부팅표식() != 0x2badb002 || اطلاعات_سیستم == 0 || (تفسیر_عدد_صحیح(اطلاعات_سیستم) & 1) == 0) return -1;
        return تفسیر_عدد_صحیح(اطلاعات_سیستم + 8);
    }

    static int اختصاص_دادن_حافظه_تلفن() {
        for (int فهرست = 0; فهرست < 사용.length; فهرست++) {
            if (사용[فهرست] == 0) {
                사용[فهرست] = 1;
                for (int شکاف_ورودی = 0; شکاف_ورودی < 1024; شکاف_ورودی++) قسمت_مقدار[فهرست * 1024 + شکاف_ورودی] = 0;
                return فهرست;
            }
        }
        return -1;
    }

    static boolean بازگرداندن_سنجش(int فهرست) {
        if (فهرست < 0 || فهرست >= 사용.length || 사용[فهرست] == 0) return false;
        사용[فهرست] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int فهرست = 0; فهرست < 사용.length; فهرست++) 개수 += 사용[فهرست];
        return 개수;
    }
}
