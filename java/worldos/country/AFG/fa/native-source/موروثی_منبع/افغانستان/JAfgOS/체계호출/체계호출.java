    public int اجرا_فرمان(فرآیند_مقدار 현재과정, byte[] 실행파일, String[] پارامتر_آرگومان, String[] 환경) {
        실행파일적재기.عکس عکس_مقدار;
        try {
            عکس_مقدار = 적재기.검사(실행파일);
        } catch (IllegalArgumentException خطا) {
            return -8;
        }
        if (پارامتر_آرگومان == null || 환경 == null || پارامتر_آرگومان.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.قسمت_مقدار قسمت_مقدار : عکس_مقدار.구역들()) {
            if ((قسمت_مقدار.پرچم_مقدار() & 2) == 0 || قسمت_مقدار.اندازه() == 0) {
                continue;
            }
            int 첫쪽 = قسمت_مقدار.آدرس() / صفحه_مدیر.اندازه_صفحه;
            int 끝쪽 = (قسمت_مقدار.آدرس() + قسمت_مقدار.اندازه() + صفحه_مدیر.اندازه_صفحه - 1) / صفحه_مدیر.اندازه_صفحه;
            for (int فهرست = 첫쪽; فهرست < 끝쪽; فهرست++) {
                int آدرس = فهرست * صفحه_مدیر.اندازه_صفحه;
                try {
                    쪽관리.바이트읽기(현재과정.آدرس_فضا(), آدرس);
                    쪽관리.범위개인쓰기(현재과정.آدرس_فضا(), آدرس, صفحه_مدیر.اندازه_صفحه);
                } catch (IllegalStateException خطا) {
                    쪽관리.نگاشت_صفحه(현재과정.آدرس_فضا(), آدرس, true);
                }
            }
            for (int فهرست = 0; فهرست < قسمت_مقدار.اندازه(); فهرست++) {
                byte مقدار = قسمت_مقدار.종류() == 8 ? 0 : 실행파일[قسمت_مقدار.فایل_مرتب_کردن() + فهرست];
                쪽관리.نوشتن_بایت_مقدار(현재과정.آدرس_فضا(), قسمت_مقدار.آدرس() + فهرست, مقدار);
            }
        }
        현재과정.실행문맥설정(عکس_مقدار.شروع_آدرس(), پارامتر_آرگومان, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

