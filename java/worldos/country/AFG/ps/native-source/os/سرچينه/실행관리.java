/** لوستل 전용 실행 묶음의 ELF32 검증, 인수 전달, 한 번에 한 کارن 과정 실행. */
public final class 실행관리 {
    static final int پيل_کارن_کاريال = 0x04000000;
    static final int کارن_پاى = 0x04400000;
    static final int انځور_پاى_پته = 0x04200000;
    static final int ارزښتوړى_پيل = 0x04300000;
    static int 인수수 = 0;
    static int[] ارزښتوړى_پته = new int[16];

    static boolean ټوټه(int پته, int اوږدوالى_ارزښت) {
        return پته >= پيل_کارن_کاريال && پته < کارن_پاى && اوږدوالى_ارزښت >= 0 && اوږدوالى_ارزښت <= کارن_پاى - پته;
    }

    static int 수(int پته) { return 기억공간.تجزیه_صحيح_عدد(پته); }
    static int 짧은수(int پته) { return وزله_ارزښت.기억읽기(پته) | وزله_ارزښت.기억읽기(پته + 1) << 8; }
    static void 수쓰기(int پته, int ارزښت) {
        for (int لړیال = 0; لړیال < 4; لړیال++) وزله_ارزښت.기억쓰기(پته + لړیال, ارزښت >>> (لړیال * 8));
    }

    static int 묶음개수() {
        int پته = وزله_ارزښت.실행묶음();
        int کچ = وزله_ارزښت.실행묶음크기();
        if (کچ < 8 || 수(پته) != 0x50414b4a) return 0;
        int 개수 = 수(پته + 4);
        return 개수 >= 0 && 개수 <= 32 && 개수 <= (کچ - 8) / 24 ? 개수 : 0;
    }

    static void 목록() {
        for (int لړیال = 0; لړیال < 묶음개수(); لړیال++) {
            int ننوت_ارزښت = وزله_ارزښت.실행묶음() + 8 + لړیال * 24;
            for (int لوښه_ارزښت = 0; لوښه_ارزښت < 16 && وزله_ارزښت.기억읽기(ننوت_ارزښت + لوښه_ارزښت) != 0; لوښه_ارزښت++)
                문자단말.문자(وزله_ارزښت.기억읽기(ننوت_ارزښت + لوښه_ارزښت));
            문자단말.لوستل_2("\n");
        }
    }

    static int 찾기(int[] 입력, int ځغلول, int اوږدوالى_ارزښت) {
        if (اوږدوالى_ارزښت <= 0 || اوږدوالى_ارزښت >= 16) return 0;
        for (int لړیال = 0; لړیال < 묶음개수(); لړیال++) {
            int ننوت_ارزښت = وزله_ارزښت.실행묶음() + 8 + لړیال * 24;
            boolean 같음 = وزله_ارزښت.기억읽기(ننوت_ارزښت + اوږدوالى_ارزښت) == 0;
            for (int لوښه_ارزښت = 0; لوښه_ارزښت < اوږدوالى_ارزښت; لوښه_ارزښت++)
                if (입력[ځغلول + لوښه_ارزښت] != وزله_ارزښت.기억읽기(ننوت_ارزښت + لوښه_ارزښت)) 같음 = false;
            if (같음) return ننوت_ارزښت;
        }
        return 0;
    }

    static int 검증(int دوتنه, int اوږدوالى_ارزښت) {
        if (اوږدوالى_ارزښت < 52 || 수(دوتنه) != 0x464c457f || وزله_ارزښت.기억읽기(دوتنه + 4) != 1
            || وزله_ارزښت.기억읽기(دوتنه + 5) != 1 || وزله_ارزښت.기억읽기(دوتنه + 6) != 1
            || 짧은수(دوتنه + 16) != 2 || 짧은수(دوتنه + 18) != 3 || 수(دوتنه + 20) != 1
            || 짧은수(دوتنه + 40) != 52 || 짧은수(دوتنه + 42) != 32) return -8;
        int ننوت_ټکى_ارزښت = 수(دوتنه + 24);
        int 표위치 = 수(دوتنه + 28);
        int 개수 = 짧은수(دوتنه + 44);
        if (개수 == 0 || 개수 > 16 || 표위치 < 52 || 표위치 > اوږدوالى_ارزښت - 개수 * 32) return -8;
        boolean 실행가능 = false;
        for (int لړیال = 0; لړیال < 개수; لړیال++) {
            int 표 = دوتنه + 표위치 + لړیال * 32;
            int 종류 = 수(표);
            if (종류 == 2 || 종류 == 3) return -8; // 동적 نښلېدل/해석기 미지원
            if (종류 != 1) continue;
            int ځای = 수(표 + 4), پته = 수(표 + 8), 파일크기 = 수(표 + 16), 기억크기 = 수(표 + 20);
            int پرليکول_ارزښت = 수(표 + 28);
            if (پته < پيل_کارن_کاريال || پته >= انځور_پاى_پته || 기억크기 < 0 || 기억크기 > انځور_پاى_پته - پته
                || 파일크기 < 0 || 파일크기 > 기억크기 || ځای < 0 || (파일크기 > 0 && ځای > اوږدوالى_ارزښت - 파일크기)
                || (پرليکول_ارزښت != 0 && (پرليکول_ارزښت < 0 || (پرليکول_ارزښت & (پرليکول_ارزښت - 1)) != 0
                    || ((پته - ځای) & (پرليکول_ارزښت - 1)) != 0))) return -8;
            for (int 앞 = 0; 앞 < لړیال; 앞++) {
                int 이전 = دوتنه + 표위치 + 앞 * 32;
                if (수(이전) == 1 && 기억크기 > 0 && 수(이전 + 20) > 0
                    && پته < 수(이전 + 8) + 수(이전 + 20) && 수(이전 + 8) < پته + 기억크기) return -8;
            }
            if ((수(표 + 24) & 1) != 0 && ننوت_ټکى_ارزښت >= پته && ننوت_ټکى_ارزښت - پته < 파일크기) 실행가능 = true;
        }
        return 실행가능 ? ننوت_ټکى_ارزښت : -8;
    }

    static int 실행(int[] 입력, int ځغلول, int اوږدوالى_ارزښت) {
        while (ځغلول < اوږدوالى_ارزښت && 입력[ځغلول] == ' ') ځغلول++;
        int 끝 = ځغلول;
        while (끝 < اوږدوالى_ارزښت && 입력[끝] != ' ') 끝++;
        int ننوت_ارزښت = 찾기(입력, ځغلول, 끝 - ځغلول);
        if (ننوت_ارزښت == 0) return -2;
        int ځای = 수(ننوت_ارزښت + 16), کچ = 수(ننوت_ارزښت + 20);
        if (ځای < 8 + 묶음개수() * 24 || کچ < 52 || ځای > وزله_ارزښت.실행묶음크기() - کچ) return -8;
        int دوتنه = وزله_ارزښت.실행묶음() + ځای;
        int ننوت_ټکى_ارزښت = 검증(دوتنه, کچ);
        if (ننوت_ټکى_ارزښت < 0) return ننوت_ټکى_ارزښت;
        وزله_ارزښت.کارن_پاک_منځپانګې();
        int 표위치 = 수(دوتنه + 28), 개수 = 짧은수(دوتنه + 44);
        for (int لړیال = 0; لړیال < 개수; لړیال++) {
            int 표 = دوتنه + 표위치 + لړیال * 32;
            if (수(표) != 1) continue;
            int 원본 = دوتنه + 수(표 + 4), موخه_ارزښت = 수(표 + 8), 파일크기 = 수(표 + 16);
            for (int بايټ_ارزښت = 0; بايټ_ارزښت < 파일크기; بايټ_ارزښت++) وزله_ارزښت.기억쓰기(موخه_ارزښت + بايټ_ارزښت, وزله_ارزښت.기억읽기(원본 + بايټ_ارزښت));
        }
        인수수 = 0;
        int 저장 = ارزښتوړى_پيل;
        while (끝 < اوږدوالى_ارزښت) {
            while (끝 < اوږدوالى_ارزښت && 입력[끝] == ' ') 끝++;
            if (끝 == اوږدوالى_ارزښت) break;
            if (인수수 == ارزښتوړى_پته.length) return -22;
            ځغلول = 끝;
            while (끝 < اوږدوالى_ارزښت && 입력[끝] != ' ') 끝++;
            ارزښتوړى_پته[인수수++] = 저장;
            수쓰기(저장, 끝 - ځغلول);
            for (int لوښه_ارزښت = ځغلول; لوښه_ارزښت < 끝; لوښه_ارزښت++) 수쓰기(저장 + 4 + (لوښه_ارزښت - ځغلول) * 4, 입력[لوښه_ارزښت]);
            저장 += 4 + (끝 - ځغلول) * 4;
        }
        통신망.과정정리();
        파일서술자관리.과정시작();
        int 결과 = وزله_ارزښت.사용자실행(ننوت_ټکى_ارزښت, کارن_پاى - 16);
        파일서술자관리.과정정리();
        통신망.과정정리();
        return 결과;
    }
}
