#!/usr/bin/env python3
"""اعلامیه 고유번호와 UTF-8 بایت_مقدار 위치로 بومی C 이름을 옮기는 일회성 이행 ابزارها.

외부 구조체의 멤버, رشته_مقدار_6ca8363c, C 표준 عملکرد_مقدار, 이식 규약은 보존한다.
입력은 تغییر_مقدار 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

نمایش_دادن_جذر = Path(__file__).resolve().parents[1]

def اجرا_فرمان():
    분석 = json.loads((نمایش_دادن_جذر/'build/한국어화/시언어분석.json').read_text())
    if 분석['خطا']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    نام_جدول = json.loads((نمایش_دادن_جذر/'명명/시언어이름.json').read_text())
    کیفیت_استاندارد = set(json.loads((نمایش_دادن_جذر/'명명/규격이름.json').read_text()))
    اعلامیه_جدول = 분석['اعلامیه']
    바꿀선언 = {고유:نام_جدول[ورودی_مقدار['نام']] for 고유,ورودی_مقدار in اعلامیه_جدول.items()
                if ورودی_مقدار['نام'] in نام_جدول and ورودی_مقدار['نام'] not in کیفیت_استاندارد}
    اتصال_جدول = {ورودی_مقدار['نام']:نام_جدول[ورودی_مقدار['نام']] for ورودی_مقدار in اعلامیه_جدول.values()
              if ورودی_مقدار.get('اتصال')==4 and ورودی_مقدار['종류'] in (8,9)
              and ورودی_مقدار['نام'] in نام_جدول and ورودی_مقدار['نام'] not in کیفیت_استاندارد}
    # ایجاد AOT C·어셈블리·공개 SDK가 공유하는 바이너리 اتصال 이름만 유지한다.
    머리 = ['/* فارسی منبع_درخت 이름과 기존 دستگاه اتصال شغل_مقدار. 자동 ایجاد: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(اتصال_جدول.items())]
    머리 += ['#endif','']
    (نمایش_دادن_جذر/'명명/기계연결이름.h').write_text('\n'.join(머리))
    تغییرها_لیست = defaultdict(dict)
    for پرونده,جابجایی_لایه_ای_مقدار,نام,고유 in 분석['مرجع']:
        if 고유 in 바꿀선언:
            تغییرها_لیست[پرونده][جابجایی_لایه_ای_مقدار] = (نام,바꿀선언[고유])
    واقعه_نگار_ردیف = ['پرونده\t원래바이트위치\t이전이름\t한국어이름']
    نادیده_گرفتن_مقدار = []
    for پرونده,تغییر_مقدار in تغییرها_لیست.items():
        مسیر = Path(پرونده); 원본 = مسیر.read_bytes(); داده_ها = 원본
        for جابجایی_لایه_ای_مقدار,(옛이름,새이름) in sorted(تغییر_مقدار.items(),reverse=True):
            끝 = جابجایی_لایه_ای_مقدار+len(옛이름.encode())
            if 원본[جابجایی_لایه_ای_مقدار:끝] != 옛이름.encode():
                نادیده_گرفتن_مقدار.append((str(مسیر.relative_to(نمایش_دادن_جذر)),جابجایی_لایه_ای_مقدار,옛이름));continue
            داده_ها = داده_ها[:جابجایی_لایه_ای_مقدار]+새이름.encode()+داده_ها[끝:]
            واقعه_نگار_ردیف.append('{}\t{}\t{}\t{}'.format(مسیر.relative_to(نمایش_دادن_جذر),جابجایی_لایه_ای_مقدار,옛이름,새이름))
        مسیر.write_bytes(داده_ها)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ماکرو_مقدار = {ورودی_مقدار['نام']:نام_جدول[ورودی_مقدار['نام']] for ورودی_مقدار in اعلامیه_جدول.values()
              if ورودی_مقدار['종류']==501 and ورودی_مقدار['نام'] in نام_جدول and ورودی_مقدار['نام'] not in کیفیت_استاندارد}
    for مسیر in sorted({Path(ورودی_مقدار['پرونده']) for ورودی_مقدار in اعلامیه_جدول.values()}):
        خط_لیست = مسیر.read_text().splitlines(True); 이어짐 = False
        for فهرست,خط in enumerate(خط_لیست):
            전처리 = 이어짐 or bool(re.match(r'\s*#',خط))
            이어짐 = 전처리 and خط.rstrip().endswith('\\')
            if 전처리:
                جستجو_جدول = نام_جدول if re.match(r'\s*#\s*define\b',خط) or 이어짐 else ماکرو_مقدار
                خط_لیست[فهرست] = 낱말.sub(lambda 맞음: جستجو_جدول.get(맞음[0],맞음[0]) if 맞음[0] not in کیفیت_استاندارد else 맞음[0],خط)
        مسیر.write_text(''.join(خط_لیست))
    # 각 بومی تبدیل_منبع 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for مسیر in sorted({Path(ورودی_مقدار['پرونده']) for ورودی_مقدار in اعلامیه_جدول.values()}):
        if مسیر.suffix not in ('.c','.cpp'):continue
        مشابه_مقدار = '../' * len(مسیر.relative_to(نمایش_دادن_جذر).parts[:-1]) + '명명/기계연결이름.h'
        مسیر.write_text('#include "'+مشابه_مقدار+'"\n'+مسیر.read_text())
    (نمایش_دادن_جذر/'명명/시언어이름대응.tsv').write_text('\n'.join(واقعه_نگار_ردیف)+'\n')
    (نمایش_دادن_جذر/'build/한국어화/전처리참조.json').write_text(json.dumps(نادیده_گرفتن_مقدار,ensure_ascii=False,indent=2)+'\n')
    print('تغییر_مقدار',len(واقعه_نگار_ردیف)-1,'전처리 재검토',len(نادیده_گرفتن_مقدار),'دستگاه اتصال',len(اتصال_جدول))

if __name__=='__main__': اجرا_فرمان()
