        return فهرست >= 0 && فهرست < 파일수 && مرتب_کردن_فهرست >= 0 && مرتب_کردن_فهرست < 이름길이[فهرست] ? نام[فهرست * 64 + مرتب_کردن_فهرست] : -22;
