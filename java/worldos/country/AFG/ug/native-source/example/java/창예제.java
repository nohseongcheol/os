import 한국어.자체.كۆزنەك;
import 한국어.자체.ئەن;
import 한국어.자체.تېكىست_بۆلىكى;
import 한국어.자체.كۇنۇپكا;
import 한국어.자체.ھادىسە_تەرتىپ;
import 한국어.자체.چىقار;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing كۆزنەك: ug 입력 → كۇنۇپكا → چۈشەندۈرۈش_ھۆججىتى_eb81d7d9 تېكىست يېڭىلىماق. */
public class 창예제 implements 실행할일, 동작받이 {
    private كۆزنەك 인사창;
    private تېكىست_بۆلىكى نامى_بۆلەك;
    private ئەن 인사말;
    private int 인사횟수;

    public void قۇرۇش_كۆزنەك() {
        인사창 = new كۆزنەك("ug Swing", 460, 300);
        인사창.قوشماق_ئېلېمېنت(new ئەن("ug", 20, 20, 420, 28));
        نامى_بۆلەك = new تېكىست_بۆلىكى("ug", 20, 64, 420, 30);
        인사말 = new ئەن("ug", 20, 152, 420, 28);
        인사창.قوشماق_ئېلېمېنت(نامى_بۆلەك);
        인사창.قوشماق_ئېلېمېنت(new كۇنۇپكا("인사하기", 20, 108, 180, 32, this));
        인사창.قوشماق_ئېلېمېنت(인사말);
        인사창.قوشماق_ئېلېمېنت(new ئەن("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.كۆرسەتمەك_كۆزنەك();
        چىقار.يازماق_قۇر("GUI 예제 تەييارلىماق: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.يازماق_تېكست("ug, " + نامى_بۆلەك.글읽기() + "님! (" + 인사횟수 + ")");
        چىقار.يازماق_قۇر("GUI 인사: " + 인사말.글읽기());
    }

    public void ئىجرا_قىل() { قۇرۇش_كۆزنەك(); }
    public void 동작받기(동작알림 알림) {
        چىقار.يازماق_قۇر("مەشغۇلات 알림: " + 알림.بۇيرۇق_تېكست());
        인사하기();
    }
    public static void ئىجرا_قىل_2() {
        ھادىسە_تەرتىپ.나중에실행(new 창예제());
    }
}
