/** 부팅 سىستېما_ئۇچۇرى 조회와 4KiB 고정 چوڭلۇقى 작업 بۆلۈم_قىممىتى تەقسىملەش_بوشلۇق/قايتۇرۇپ_بېرىش_ئۆلچەم. 일반 물리 بەت_قىممىتى 관리자는 아니다. */
public final class 기억공간 {
    static int[] بۆلۈم_قىممىتى = new int[8192];
    static int[] 사용 = new int[8];

    static int 정수읽기(int ئادرېس) {
        return كۆچمە_قىممىتى.기억읽기(ئادرېس) | (كۆچمە_قىممىتى.기억읽기(ئادرېس + 1) << 8)
            | (كۆچمە_قىممىتى.기억읽기(ئادرېس + 2) << 16) | (كۆچمە_قىممىتى.기억읽기(ئادرېس + 3) << 24);
    }

    static int 위쪽기억크기() {
        int سىستېما_ئۇچۇرى = كۆچمە_قىممىتى.부팅정보();
        if (كۆچمە_قىممىتى.부팅표식() != 0x2badb002 || سىستېما_ئۇچۇرى == 0 || (정수읽기(سىستېما_ئۇچۇرى) & 1) == 0) return -1;
        return 정수읽기(سىستېما_ئۇچۇرى + 8);
    }

    static int تەقسىملەش_بوشلۇق() {
        for (int ئىندېكس = 0; ئىندېكس < 사용.length; ئىندېكس++) {
            if (사용[ئىندېكس] == 0) {
                사용[ئىندېكس] = 1;
                for (int ئوقۇر_كىرگۈزۈش = 0; ئوقۇر_كىرگۈزۈش < 1024; ئوقۇر_كىرگۈزۈش++) بۆلۈم_قىممىتى[ئىندېكس * 1024 + ئوقۇر_كىرگۈزۈش] = 0;
                return ئىندېكس;
            }
        }
        return -1;
    }

    static boolean قايتۇرۇپ_بېرىش_ئۆلچەم(int ئىندېكس) {
        if (ئىندېكس < 0 || ئىندېكس >= 사용.length || 사용[ئىندېكس] == 0) return false;
        사용[ئىندېكس] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int ئىندېكس = 0; ئىندېكس < 사용.length; ئىندېكس++) 개수 += 사용[ئىندېكس];
        return 개수;
    }
}
