package ئافغانىستان.JAfgOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB بەت_قىممىتى 연결과 ياز 시 복사를 제공한다. */
public final class بەت_باشقۇرغۇچى {
    public static final int بەت_ھەجىمى = 4096;

    private static final class بەت_قىممىتى {
        private byte[] مەلۇمات = new byte[بەت_ھەجىمى];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class ئادرېس_بوشلۇق {
        private final Map<Integer, بەت_قىممىتى> بەت_جەدۋەل = new HashMap<Integer, بەت_قىممىتى>();
    }

    public ئادرېس_بوشلۇق 새주소공간() {
        return new ئادرېس_بوشلۇق();
    }

    public void خەرىتىدىن_كۆرسەتمەك_بەت(ئادرېس_بوشلۇق 공간, int مەۋھۇم_ئادرېس, boolean 쓰기가능) {
        int ئىندېكس = 쪽번호(مەۋھۇم_ئادرېس);
        بەت_قىممىتى 새쪽 = new بەت_قىممىتى();
        새쪽.쓰기가능 = 쓰기가능;
        공간.بەت_جەدۋەل.put(Integer.valueOf(ئىندېكس), 새쪽);
    }

    public ئادرېس_بوشلۇق 쓰기시복사복제(ئادرېس_بوشلۇق 원본) {
        ئادرېس_بوشلۇق 복제본 = new ئادرېس_بوشلۇق();
        for (Map.Entry<Integer, بەت_قىممىتى> كىرگۈزۈش_قىممىتى : 원본.بەت_جەدۋەل.entrySet()) {
            بەت_قىممىتى 공유쪽 = كىرگۈزۈش_قىممىتى.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.بەت_جەدۋەل.put(كىرگۈزۈش_قىممىتى.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(ئادرېس_بوشلۇق 공간, int مەۋھۇم_ئادرېس) {
        بەت_قىممىتى نىشان = ئىزدەش_بەت(공간, مەۋھۇم_ئادرېس);
        return نىشان.مەلۇمات[Math.floorMod(مەۋھۇم_ئادرېس, بەت_ھەجىمى)];
    }

    public void يازماق_بايت_قىممىتى(ئادرېس_بوشلۇق 공간, int مەۋھۇم_ئادرېس, byte قىممىتى) {
        int ئىندېكس = 쪽번호(مەۋھۇم_ئادرېس);
        بەت_قىممىتى نىشان = ئىزدەش_بەت(공간, مەۋھۇم_ئادرېس);
        if (!نىشان.쓰기가능) {
            if (!نىشان.쓰기시복사) {
                throw new IllegalStateException("ئوقۇ 전용 쪽입니다.");
            }
            نىشان = قۇرۇش_خۇسۇسىي_بەت(공간, ئىندېكس, نىشان);
        }
        نىشان.مەلۇمات[Math.floorMod(مەۋھۇم_ئادرېس, بەت_ھەجىمى)] = قىممىتى;
    }

    public void 범위개인쓰기(ئادرېس_بوشلۇق 공간, int باشلاش_ئادرېس, int چوڭلۇقى) {
        if (چوڭلۇقى < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int تاماملىماق_ئادرېس = Math.addExact(باشلاش_ئادرېس, چوڭلۇقى);
        for (int ئادرېس = باشلاش_ئادرېس; ئادرېس < تاماملىماق_ئادرېس; ئادرېس = (쪽번호(ئادرېس) + 1) * بەت_ھەجىمى) {
            int ئىندېكس = 쪽번호(ئادرېس);
            بەت_قىممىتى نىشان = ئىزدەش_بەت(공간, ئادرېس);
            if (نىشان.쓰기시복사) {
                قۇرۇش_خۇسۇسىي_بەت(공간, ئىندېكس, نىشان);
            } else {
                نىشان.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(ئادرېس_بوشلۇق 공간, int باشلاش_ئادرېس, byte[] مەلۇمات) {
        for (int ئىندېكس = 0; ئىندېكس < مەلۇمات.length; ئىندېكس++) {
            يازماق_بايت_قىممىتى(공간, باشلاش_ئادرېس + ئىندېكس, مەلۇمات[ئىندېكس]);
        }
    }

    private بەت_قىممىتى قۇرۇش_خۇسۇسىي_بەت(ئادرېس_بوشلۇق 공간, int ئىندېكس, بەت_قىممىتى 공유쪽) {
        بەت_قىممىتى خۇسۇسىي_بەت = new بەت_قىممىتى();
        خۇسۇسىي_بەت.مەلۇمات = Arrays.copyOf(공유쪽.مەلۇمات, 공유쪽.مەلۇمات.length);
        خۇسۇسىي_بەت.쓰기가능 = true;
        خۇسۇسىي_بەت.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.بەت_جەدۋەل.put(Integer.valueOf(ئىندېكس), خۇسۇسىي_بەت);
        return خۇسۇسىي_بەت;
    }

    private بەت_قىممىتى ئىزدەش_بەت(ئادرېس_بوشلۇق 공간, int ئادرېس) {
        بەت_قىممىتى نىشان = 공간.بەت_جەدۋەل.get(Integer.valueOf(쪽번호(ئادرېس)));
        if (نىشان == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return نىشان;
    }

    private int 쪽번호(int ئادرېس) {
        if (ئادرېس < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return ئادرېس / بەت_ھەجىمى;
    }
}

