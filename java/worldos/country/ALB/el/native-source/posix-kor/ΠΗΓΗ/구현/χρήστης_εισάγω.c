#include "καλώ_όριο.h"
extern int main(int 인수개수, char **όρισμα_Λίστα);
static char όρισμα_Μνήμη[2048];
static char *όρισμα_Λίστα[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* τρέχων_στοιχείο 커널의 argv는 εκτελώ_εντολή 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    όρισμα_Λίστα[0] = "jkoros-app";
    int Θέση = 0;
    for (int Ευρετήριο = 0; Ευρετήριο < 개수; Ευρετήριο++) {
        const int *원본 = (const int *)jkoros_syscall(3, Ευρετήριο, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        όρισμα_Λίστα[Ευρετήριο + 1] = όρισμα_Μνήμη + Θέση;
        for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 원본[0]; υποδοχή_καταχώρηση++) {
            if (Θέση >= 2047) return 126;
            όρισμα_Μνήμη[Θέση++] = 원본[υποδοχή_καταχώρηση + 1];
        }
        όρισμα_Μνήμη[Θέση++] = 0;
    }
    όρισμα_Λίστα[개수 + 1] = 0;
    return main(개수 + 1, όρισμα_Λίστα);
}
