/** 자체 커널의 Swing прозорец: mk 입력 → копче → информации_пред_употреба_eb81d7d9 Текст освежи. */
public class 창예제 implements 실행할일, 동작받이 {
    private прозорец 인사창;
    private СМС_поле име_поле;
    private Ознака 인사말;
    private int 인사횟수;

    public void отвори_прозорец() {
        인사창 = new прозорец("mk Swing", 460, 300);
        인사창.додавање_елемент(new Ознака("mk", 20, 20, 420, 28));
        име_поле = new СМС_поле("mk", 20, 64, 420, 30);
        인사말 = new Ознака("mk", 20, 152, 420, 28);
        인사창.додавање_елемент(име_поле);
        인사창.додавање_елемент(new копче("인사하기", 20, 108, 180, 32, this));
        인사창.додавање_елемент(인사말);
        인사창.додавање_елемент(new Ознака("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.прикажи_прозорец();
        출력.запиши_ред("GUI 예제 Подготви: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.запиши_СМС("mk, " + име_поле.글읽기() + "님! (" + 인사횟수 + ")");
        출력.запиши_ред("GUI 인사: " + 인사말.글읽기());
    }

    public void Изврши() { отвори_прозорец(); }
    public void 동작받기(동작알림 알림) {
        출력.запиши_ред("Дејство 알림: " + 알림.наредба_СМС());
        인사하기();
    }
    public static void Изврши_2() {
        настан_ред_на_чекање.나중에실행(new 창예제());
    }
}
