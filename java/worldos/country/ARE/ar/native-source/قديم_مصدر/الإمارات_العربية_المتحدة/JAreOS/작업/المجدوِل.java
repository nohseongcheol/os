package الإمارات_العربية_المتحدة.JAreOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import الإمارات_العربية_المتحدة.JAreOS.ذاكرة_منطقة.صفحة_مدير;
import الإمارات_العربية_المتحدة.JAreOS.نظام_الملفات.파일서술자표;

/** عملية_قيمة 식별자와 라운드로빈 إعداد 대기열을 관리한다. */
public final class المجدوِل {
    private final صفحة_مدير 쪽관리;
    private final Map<Integer, عملية_قيمة> قائمة_عمليات = new HashMap<Integer, عملية_قيمة>();
    private final Queue<عملية_قيمة> 준비대기열 = new ArrayDeque<عملية_قيمة>();
    private int التالي_معرف = 1;

    public المجدوِل(صفحة_مدير 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public عملية_قيمة 첫과정(파일서술자표 파일서술자) {
        عملية_قيمة 새과정 = new عملية_قيمة(يخصص_معرف(), 0, 쪽관리.새주소공간(), 파일서술자);
        قائمة_عمليات.put(Integer.valueOf(새과정.معرف_قيمة()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public عملية_قيمة نسخة_قيمة(عملية_قيمة أصل_قيمة) {
        عملية_قيمة طفل_قيمة = new عملية_قيمة(
                يخصص_معرف(),
                أصل_قيمة.معرف_قيمة(),
                쪽관리.نسخة_نسخ_الكتابة(أصل_قيمة.عنوان_مساحة()),
                أصل_قيمة.파일서술자().نسخة_قيمة());
        طفل_قيمة.مجموعة_تطبيق_توقف(أصل_قيمة.تطبيق_توقف());
        قائمة_عمليات.put(Integer.valueOf(طفل_قيمة.معرف_قيمة()), طفل_قيمة);
        준비대기열.offer(طفل_قيمة);
        return طفل_قيمة;
    }

    public عملية_قيمة التالي_عملية() {
        int 검사수 = 준비대기열.size();
        for (int فهرس = 0; فهرس < 검사수; فهرس++) {
            عملية_قيمة التالي_عنصر = 준비대기열.poll();
            if (التالي_عنصر != null && (التالي_عنصر.حالة_قيمة() == عملية_حالة.إعداد || التالي_عنصر.حالة_قيمة() == عملية_حالة.ينفذ_أمر)) {
                التالي_عنصر.مجموعة_حالة(عملية_حالة.ينفذ_أمر);
                준비대기열.offer(التالي_عنصر);
                return التالي_عنصر;
            }
        }
        return null;
    }

    public int 자식기다리기(عملية_قيمة أصل_قيمة, int طفل_معرف, boolean 기다리지않음) {
        for (عملية_قيمة 후보 : قائمة_عمليات.values()) {
            if (후보.أصل_معرف() != أصل_قيمة.معرف_قيمة()) {
                continue;
            }
            if (طفل_معرف > 0 && 후보.معرف_قيمة() != طفل_معرف) {
                continue;
            }
            if (후보.حالة_قيمة() == عملية_حالة.خروج_تطبيق) {
                int نتيجة = (후보.التعليمة_البرمجية_للخروج() & 0xff) << 8;
                قائمة_عمليات.remove(Integer.valueOf(후보.معرف_قيمة()));
                return نتيجة;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public عملية_قيمة بحث_عملية(int معرف_قيمة) {
        return قائمة_عمليات.get(Integer.valueOf(معرف_قيمة));
    }

    private int يخصص_معرف() {
        return التالي_معرف++;
    }
}
