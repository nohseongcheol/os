/** بومی 커널의 Swing پنجره: fa 입력 → دکمه → مرا_بخوان_eb81d7d9 متن تازه_کردن. */
public class نمونهپنجره implements 실행할일, 동작받이 {
    private پنجره 인사창;
    private متن_فیلد نام_فیلد;
    private برچسب 인사말;
    private int 인사횟수;

    public void ایجاد_پنجره() {
        인사창 = new پنجره("fa Swing", 460, 300);
        인사창.افزودن_عنصر(new برچسب("سلام", 20, 20, 420, 28));
        نام_فیلد = new متن_فیلد("fa", 20, 64, 420, 30);
        인사말 = new برچسب("سلام", 20, 152, 420, 28);
        인사창.افزودن_عنصر(نام_فیلد);
        인사창.افزودن_عنصر(new دکمه("인사하기", 20, 108, 180, 32, this));
        인사창.افزودن_عنصر(인사말);
        인사창.افزودن_عنصر(new برچسب("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.نمایش_پنجره();
        خروجی.نوشتن_خط("GUI 예제 آماده_کردن: نمونهپنجره");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.نوشتن_متن("سلام, " + نام_فیلد.글읽기() + "님! (" + 인사횟수 + ")");
        خروجی.نوشتن_خط("GUI 인사: " + 인사말.글읽기());
    }

    public void اجرا() { ایجاد_پنجره(); }
    public void 동작받기(동작알림 알림) {
        خروجی.نوشتن_خط("کنش 알림: " + 알림.فرمان_متن());
        인사하기();
    }
    public static void اجرا_2() {
        رویداد_صف.나중에실행(new نمونهپنجره());
    }
}
