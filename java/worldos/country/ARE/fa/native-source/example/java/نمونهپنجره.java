import فارسی.بومی.پنجره;
import فارسی.بومی.برچسب;
import فارسی.بومی.متن_فیلد;
import فارسی.بومی.دکمه;
import فارسی.بومی.رویداد_صف;
import فارسی.بومی.خروجی;
import فارسی.بومی.실행할일;
