    시언어번역기만들기(വർഗ്ഗമൂലം_പാത, കലവറ_പാത, 시언어번역기, 연결편집기, കോണ്_ഫിഗറേഷന്_ബാക്_ഗ്രൗണ്ട്_ഇന്റലിജന്റ്_ട്രാൻസ്_ഫർ_സർവീസ്, നടപ്പാക്കുക_കമാന്_ഡ്)
