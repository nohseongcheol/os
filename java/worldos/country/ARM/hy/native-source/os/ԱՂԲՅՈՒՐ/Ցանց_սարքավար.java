/** PCI RTL8139 (10ec:8139), 단일 ուղարկել_արժեք 버퍼와 8KiB 수신 օղակում_արժեք. 인터럽트 대신 폴링한다. */
public final class Ցանց_սարքավար {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] սարք_հասցե = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int Դիրք) {
        սարք_արժեք.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | Դիրք);
        return սարք_արժեք.입출력정수읽기(0xcfc);
    }

    static boolean Պատրաստել() {
        int 장치번호 = -1;
        for (int դասիչ = 0; դասիչ < 32; դասիչ++) {
            if (설정읽기(դասիչ, 0) == 0x813910ec) { 장치번호 = դասիչ; break; }
        }
        if (장치번호 < 0) return false;
        int սկզբնադիր_արժեք = 설정읽기(장치번호, 0x10);
        if ((սկզբնադիր_արժեք & 1) == 0 || (սկզբնադիր_արժեք & 0xfffffffc) < 0x100 || (սկզբնադիր_արժեք & 0xfffffffc) > 65535) return false;
        입출력기준주소 = սկզբնադիր_արժեք & 0xfffc;
        int Հրահանգ = 설정읽기(장치번호, 4);
        սարք_արժեք.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        սարք_արժեք.입출력짧은수쓰기(0xcfc, Հրահանգ | 5); // I/O 및 bus master Թույլատրել_արժեք, PCI վիճակ_արժեք 비트는 건드리지 않음
        սարք_արժեք.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!վերակայել_արժեք()) { 입출력기준주소 = 0; return false; }
        for (int դասիչ = 0; դասիչ < 6; դասիչ++) սարք_հասցե[դասիչ] = սարք_արժեք.입출력바이트읽기(입출력기준주소 + դասիչ);
        return true;
    }

    static boolean վերակայել_արժեք() {
        սարք_արժեք.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int Գործարկել = սարք_արժեք.밀리초();
        while ((սարք_արժեք.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (սարք_արժեք.밀리초() - Գործարկել > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        սարք_արժեք.입출력정수쓰기(입출력기준주소 + 0x30, սարք_արժեք.Ցանց_Հիշողություն());
        for (int դասիչ = 0; դասիչ < 4; դասիչ++) սարք_արժեք.입출력정수쓰기(입출력기준주소 + 0x20 + դասիչ * 4, սարք_արժեք.Ցանց_Հիշողություն() + 12288);
        սարք_արժեք.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        սարք_արժեք.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        սարք_արժեք.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        սարք_արժեք.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/հեռարձակում_արժեք, wrap 연속 պահեստավորել_արժեք, 8KiB
        սարք_արժեք.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int ուղարկել(int[] տվյալ, int տեւողություն_արժեք) {
        if (입출력기준주소 == 0) return -19;
        if (տեւողություն_արժեք < 14 || տեւողություն_արժեք > 1514) return -90;
        int վիճակ_միացք = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int Գործարկել = սարք_արժեք.밀리초();
        while ((սարք_արժեք.입출력정수읽기(վիճակ_միացք) & 0x2000) == 0)
            if (սարք_արժեք.밀리초() - Գործարկել > 100) return -110;
        int Չափս = տեւողություն_արժեք < 60 ? 60 : տեւողություն_արժեք;
        for (int դասիչ = 0; դասիչ < Չափս; դասիչ++)
            սարք_արժեք.գրել_Հիշողություն(սարք_արժեք.Ցանց_Հիշողություն() + 12288 + դասիչ, դասիչ < տեւողություն_արժեք ? տվյալ[դասիչ] : 0);
        սարք_արժեք.입출력정수쓰기(վիճակ_միացք, Չափս | 0x00080000);
        Գործարկել = սարք_արժեք.밀리초();
        while ((սարք_արժեք.입출력정수읽기(վիճակ_միացք) & 0xe0008000) == 0)
            if (սարք_արժեք.밀리초() - Գործարկել > 100) return -110;
        if ((սարք_արժեք.입출력정수읽기(վիճակ_միացք) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return տեւողություն_արժեք;
    }

    static int 받기(int[] տվյալ) {
        if (입출력기준주소 == 0) return 0;
        if ((սարք_արժեք.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!վերակայել_արժեք()) 입출력기준주소 = 0;
            return 0;
        }
        if ((սարք_արժեք.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = սարք_արժեք.Ցանց_Հիշողություն() + 수신위치;
        int վիճակ_արժեք = 실행관리.짧은수(머리), Չափս = 실행관리.짧은수(머리 + 2);
        if (Չափս == 0xfff0) return 0; // DMA 진행 중
        if (Չափս < 4 || Չափս > 1518) {
            오류수++;
            if (!վերակայել_արժեք()) 입출력기준주소 = 0;
            return 0;
        }
        int տեւողություն_արժեք = Չափս - 4;
        if ((վիճակ_արժեք & 1) != 0) {
            for (int դասիչ = 0; դասիչ < տեւողություն_արժեք; դասիչ++) տվյալ[դասիչ] = սարք_արժեք.기억읽기(머리 + 4 + դասիչ);
            수신수++;
        } else { տեւողություն_արժեք = 0; 오류수++; }
        수신위치 = (수신위치 + Չափս + 4 + 3) & ~3;
        수신위치 &= 8191;
        սարք_արժեք.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        սարք_արժեք.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return տեւողություն_արժեք;
    }
}
