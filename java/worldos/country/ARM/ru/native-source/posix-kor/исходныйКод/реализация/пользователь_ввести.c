#include "вызов_граница.h"
extern int main(int 인수개수, char **аргумент_Список);
static char аргумент_Память[2048];
static char *аргумент_Список[18];
int jkoros_main(void) {
    int товар_СЧЁТ = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (товар_СЧЁТ < 0 || товар_СЧЁТ > 16) return 126;
    /* текущий_товар 커널의 argv는 실행 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    аргумент_Список[0] = "jkoros-app";
    int позиция = 0;
    for (int ИНДЕКС = 0; ИНДЕКС < товар_СЧЁТ; ИНДЕКС++) {
        const int *원본 = (const int *)jkoros_syscall(3, ИНДЕКС, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        аргумент_Список[ИНДЕКС + 1] = аргумент_Память + позиция;
        for (int слот_ввод = 0; слот_ввод < 원본[0]; слот_ввод++) {
            if (позиция >= 2047) return 126;
            аргумент_Память[позиция++] = 원본[слот_ввод + 1];
        }
        аргумент_Память[позиция++] = 0;
    }
    аргумент_Список[товар_СЧЁТ + 1] = 0;
    return main(товар_СЧЁТ + 1, аргумент_Список);
}
