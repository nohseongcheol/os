import 한국어.자체.պատուհան;
import 한국어.자체.Պիտակ;
import 한국어.자체.գրվածքի_դաշտ;
import 한국어.자체.կոճակ;
import 한국어.자체.միջոցառում_հերթ;
import 한국어.자체.Ելք;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing պատուհան: Armenian 입력 → կոճակ → ԿԱՐԴԱ_ԻՆՁ_eb81d7d9 Տեքստ թարմացնել. */
public class 창예제 implements 실행할일, 동작받이 {
    private պատուհան 인사창;
    private գրվածքի_դաշտ անուն_դաշտ;
    private Պիտակ 인사말;
    private int 인사횟수;

    public void բացել_պատուհան() {
        인사창 = new պատուհան("Armenian Swing", 460, 300);
        인사창.հավելել_տարր(new Պիտակ("Բարեւ", 20, 20, 420, 28));
        անուն_դաշտ = new գրվածքի_դաշտ("Armenian", 20, 64, 420, 30);
        인사말 = new Պիտակ("Բարեւ", 20, 152, 420, 28);
        인사창.հավելել_տարր(անուն_դաշտ);
        인사창.հավելել_տարր(new կոճակ("인사하기", 20, 108, 180, 32, this));
        인사창.հավելել_տարր(인사말);
        인사창.հավելել_տարր(new Պիտակ("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.ցուցադրել_պատուհան();
        Ելք.գրել_կապ("GUI 예제 Պատրաստել: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.գրել_Գրվածք("Բարեւ, " + անուն_դաշտ.글읽기() + "님! (" + 인사횟수 + ")");
        Ելք.գրել_կապ("GUI 인사: " + 인사말.글읽기());
    }

    public void Կատարել() { բացել_պատուհան(); }
    public void 동작받기(동작알림 알림) {
        Ելք.գրել_կապ("Գործողություն 알림: " + 알림.հրաման_Գրվածք());
        인사하기();
    }
    public static void Գործարկել() {
        միջոցառում_հերթ.나중에실행(new 창예제());
    }
}
