/** 최대 Չափս/홀수 տեւողություն_արժեք 데이터그램으로 իրական_տվյալ RTL8139 수신 օղակում_արժեք 순환을 시험한다. */
public final class Ցանց_օղակում {
    public static int Գործարկել() {
        if (օգտվող.인수개수() != 1) { օգտվող.Գրել("Usage: run stress PORT\n"); return 2; }
        String Տեքստ = օգտվող.인수(0);
        int միացք_արժեք = 0;
        for (int դասիչ = 0; դասիչ < Տեքստ.length(); դասիչ++) {
            if (Տեքստ.charAt(դասիչ) < '0' || Տեքստ.charAt(դասիչ) > '9' || միացք_արժեք > 6553) return 2;
            միացք_արժեք = միացք_արժեք * 10 + Տեքստ.charAt(դասիչ) - '0';
        }
        if (միացք_արժեք < 1 || միացք_արժեք > 65535) return 2;
        int բռնակ_արժեք = օգտվող.բացել_Ցանց(0);
        if (բռնակ_արժեք < 0) return 3;
        int[] տվյալ = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int տեւողություն_արժեք = 1024 - (회차 & 1);
            for (int դասիչ = 0; դասիչ < տեւողություն_արժեք; դասիչ++) տվյալ[դասիչ] = (դասիչ + 회차) & 255;
            if (օգտվող.ուղարկել_տվյալ(բռնակ_արժեք, 0x0a000202, միացք_արժեք, տվյալ, տեւողություն_արժեք) != տեւողություն_արժեք) return 4;
            if (օգտվող.자료받기(բռնակ_արժեք, տվյալ, 300) != տեւողություն_արժեք) return 5;
            for (int դասիչ = 0; դասիչ < տեւողություն_արժեք; դասիչ++) if (տվյալ[դասիչ] != ((դասիչ + 회차) & 255)) return 6;
        }
        օգտվող.փակել_Ցանց(բռնակ_արժեք);
        օգտվող.Գրել("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
