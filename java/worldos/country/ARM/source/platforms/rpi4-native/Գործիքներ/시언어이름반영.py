#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 բայթ_արժեք 위치로 자체 C 이름을 옮기는 일회성 이행 Գործիքներ.

외부 구조체의 멤버, տող_արժեք_6ca8363c, C 표준 ՖՈՒՆԿՑԻԱ_արժեք, 이식 규약은 보존한다.
입력은 փոխել_արժեք 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

արձակել_արմատ = Path(__file__).resolve().parents[1]

def կատարել_հրաման():
    분석 = json.loads((արձակել_արմատ/'build/한국어화/시언어분석.json').read_text())
    if 분석['Սխալ']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    անուն_աղյուսակ = json.loads((արձակել_արմատ/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((արձակել_արմատ/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:անուն_աղյուսակ[մուտքագրում_արժեք['Անուն']] for 고유,մուտքագրում_արժեք in 선언표.items()
                if մուտքագրում_արժեք['Անուն'] in անուն_աղյուսակ and մուտքագրում_արժեք['Անուն'] not in 규격}
    կապ_աղյուսակ = {մուտքագրում_արժեք['Անուն']:անուն_աղյուսակ[մուտքագրում_արժեք['Անուն']] for մուտքագրում_արժեք in 선언표.values()
              if մուտքագրում_արժեք.get('Միացնել')==4 and մուտքագրում_արժեք['종류'] in (8,9)
              and մուտքագրում_արժեք['Անուն'] in անուն_աղյուսակ and մուտքագրում_արժեք['Անուն'] not in 규격}
    # արտադրել AOT C·어셈블리·공개 SDK가 공유하는 바이너리 Միացնել 이름만 유지한다.
    머리 = ['/* 한국어 աղբյուր_ծառ 이름과 기존 մեքենա Միացնել գործ_արժեք. 자동 արտադրել: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(կապ_աղյուսակ.items())]
    머리 += ['#endif','']
    (արձակել_արմատ/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Փոփոխություններ_Ցուցակ = defaultdict(dict)
    for Ֆայլ,Տեղաշարժում_արժեք,Անուն,고유 in 분석['Տեղեկատուներ']:
        if 고유 in 바꿀선언:
            Փոփոխություններ_Ցուցակ[Ֆայլ][Տեղաշարժում_արժեք] = (Անուն,바꿀선언[고유])
    մատյան_տող = ['Ֆայլ\t원래바이트위치\t이전이름\t한국어이름']
    անտեսել_արժեք = []
    for Ֆայլ,փոխել_արժեք in Փոփոխություններ_Ցուցակ.items():
        Ճանապարհ = Path(Ֆայլ); 원본 = Ճանապարհ.read_bytes(); տվյալ = 원본
        for Տեղաշարժում_արժեք,(옛이름,새이름) in sorted(փոխել_արժեք.items(),reverse=True):
            끝 = Տեղաշարժում_արժեք+len(옛이름.encode())
            if 원본[Տեղաշարժում_արժեք:끝] != 옛이름.encode():
                անտեսել_արժեք.append((str(Ճանապարհ.relative_to(արձակել_արմատ)),Տեղաշարժում_արժեք,옛이름));continue
            տվյալ = տվյալ[:Տեղաշարժում_արժեք]+새이름.encode()+տվյալ[끝:]
            մատյան_տող.append('{}\t{}\t{}\t{}'.format(Ճանապարհ.relative_to(արձակել_արմատ),Տեղաշարժում_արժեք,옛이름,새이름))
        Ճանապարհ.write_bytes(տվյալ)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    մակրո_արժեք = {մուտքագրում_արժեք['Անուն']:անուն_աղյուսակ[մուտքագրում_արժեք['Անուն']] for մուտքագրում_արժեք in 선언표.values()
              if մուտքագրում_արժեք['종류']==501 and մուտքագրում_արժեք['Անուն'] in անուն_աղյուսակ and մուտքագրում_արժեք['Անուն'] not in 규격}
    for Ճանապարհ in sorted({Path(մուտքագրում_արժեք['Ֆայլ']) for մուտքագրում_արժեք in 선언표.values()}):
        կապ_Ցուցակ = Ճանապարհ.read_text().splitlines(True); 이어짐 = False
        for դասիչ,կապ in enumerate(կապ_Ցուցակ):
            전처리 = 이어짐 or bool(re.match(r'\s*#',կապ))
            이어짐 = 전처리 and կապ.rstrip().endswith('\\')
            if 전처리:
                Փնտրում_աղյուսակ = անուն_աղյուսակ if re.match(r'\s*#\s*define\b',կապ) or 이어짐 else մակրո_արժեք
                կապ_Ցուցակ[դասիչ] = 낱말.sub(lambda 맞음: Փնտրում_աղյուսակ.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],կապ)
        Ճանապարհ.write_text(''.join(կապ_Ցուցակ))
    # 각 자체 Թարգմանել_աղբյուր 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for Ճանապարհ in sorted({Path(մուտքագրում_արժեք['Ֆայլ']) for մուտքագրում_արժեք in 선언표.values()}):
        if Ճանապարհ.suffix not in ('.c','.cpp'):continue
        հավասարազոր_սարք_արժեք = '../' * len(Ճանապարհ.relative_to(արձակել_արմատ).parts[:-1]) + '명명/기계연결이름.h'
        Ճանապարհ.write_text('#include "'+հավասարազոր_սարք_արժեք+'"\n'+Ճանապարհ.read_text())
    (արձակել_արմատ/'명명/시언어이름대응.tsv').write_text('\n'.join(մատյան_տող)+'\n')
    (արձակել_արմատ/'build/한국어화/전처리참조.json').write_text(json.dumps(անտեսել_արժեք,ensure_ascii=False,indent=2)+'\n')
    print('փոխել_արժեք',len(մատյան_տող)-1,'전처리 재검토',len(անտեսել_արժեք),'մեքենա Միացնել',len(կապ_աղյուսակ))

if __name__=='__main__': կատարել_հրաման()
