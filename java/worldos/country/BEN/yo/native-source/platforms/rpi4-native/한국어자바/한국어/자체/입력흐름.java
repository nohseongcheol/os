package 한국어.자체;

/** 입력(入力)과 Stream_iye: 순서대로 들어오는 바이트를 읽는 òpónà_ìgbéwọlé. */
public final class 입력흐름 {
    private final java.io.InputStream 표준흐름;
    입력흐름(java.io.InputStream 표준흐름) { this.표준흐름 = 표준흐름; }
    public int Kàá() throws 입출력예외 {
        try { return 표준흐름.read();
        } catch (java.io.IOException àṣìṣe) { throw 예외변환.I_O(àṣìṣe); }
        catch (RuntimeException àṣìṣe) { throw 예외변환.ṣiṣẹ́_àṣẹ(àṣìṣe); }
    }
    public int Kàá(byte[] détà) throws 입출력예외 {
        try { return 표준흐름.read(détà);
        } catch (java.io.IOException àṣìṣe) { throw 예외변환.I_O(àṣìṣe); }
        catch (RuntimeException àṣìṣe) { throw 예외변환.ṣiṣẹ́_àṣẹ(àṣìṣe); }
    }
    public int Kàá(byte[] détà, int Rọ́ọ̀nù, int gígùn_iye) throws 입출력예외 {
        try { return 표준흐름.read(détà, Rọ́ọ̀nù, gígùn_iye);
        } catch (java.io.IOException àṣìṣe) { throw 예외변환.I_O(àṣìṣe); }
        catch (RuntimeException àṣìṣe) { throw 예외변환.ṣiṣẹ́_àṣẹ(àṣìṣe); }
    }
    public void Ti() throws 입출력예외 {
        try { 표준흐름.close();
        } catch (java.io.IOException àṣìṣe) { throw 예외변환.I_O(àṣìṣe); }
        catch (RuntimeException àṣìṣe) { throw 예외변환.ṣiṣẹ́_àṣẹ(àṣìṣe); }
    }
}
