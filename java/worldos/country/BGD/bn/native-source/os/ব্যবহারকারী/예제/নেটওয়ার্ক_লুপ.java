/** 최대 আকার/홀수 দৈর্ঘ্য_মান 데이터그램으로 প্রকৃত_ডাটা RTL8139 수신 লুপ_মান 순환을 시험한다. */
public final class নেটওয়ার্ক_লুপ {
    public static int চালনা() {
        if (ব্যবহারকারী.인수개수() != 1) { ব্যবহারকারী.লেখা("Usage: run stress PORT\n"); return 2; }
        String পাঠ = ব্যবহারকারী.আর্গুমেন্ট_তালিকা(0);
        int পোর্ট_মান = 0;
        for (int সূচি = 0; সূচি < পাঠ.length(); সূচি++) {
            if (পাঠ.charAt(সূচি) < '0' || পাঠ.charAt(সূচি) > '9' || পোর্ট_মান > 6553) return 2;
            পোর্ট_মান = পোর্ট_মান * 10 + পাঠ.charAt(সূচি) - '0';
        }
        if (পোর্ট_মান < 1 || পোর্ট_মান > 65535) return 2;
        int হাতল_মান = ব্যবহারকারী.খোলা_নেটওয়ার্ক(0);
        if (হাতল_মান < 0) return 3;
        int[] ডাটা = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int দৈর্ঘ্য_মান = 1024 - (회차 & 1);
            for (int সূচি = 0; সূচি < দৈর্ঘ্য_মান; সূচি++) ডাটা[সূচি] = (সূচি + 회차) & 255;
            if (ব্যবহারকারী.পাঠান_ডাটা(হাতল_মান, 0x0a000202, পোর্ট_মান, ডাটা, দৈর্ঘ্য_মান) != দৈর্ঘ্য_মান) return 4;
            if (ব্যবহারকারী.자료받기(হাতল_মান, ডাটা, 300) != দৈর্ঘ্য_মান) return 5;
            for (int সূচি = 0; সূচি < দৈর্ঘ্য_মান; সূচি++) if (ডাটা[সূচি] != ((সূচি + 회차) & 255)) return 6;
        }
        ব্যবহারকারী.বন্ধ_নেটওয়ার্ক(হাতল_মান);
        ব্যবহারকারী.লেখা("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
