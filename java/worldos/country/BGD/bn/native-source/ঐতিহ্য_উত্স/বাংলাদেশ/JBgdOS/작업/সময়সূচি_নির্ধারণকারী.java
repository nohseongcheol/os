package বাংলাদেশ.JBgdOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import বাংলাদেশ.JBgdOS.기억공간.পৃষ্ঠা_ব্যবস্থাপক;
import বাংলাদেশ.JBgdOS.ফাইল_পদ্ধতি.파일서술자표;

/** প্রসেসর_মান 식별자와 라운드로빈 প্রস্তুত_করুন 대기열을 관리한다. */
public final class সময়সূচি_নির্ধারণকারী {
    private final পৃষ্ঠা_ব্যবস্থাপক 쪽관리;
    private final Map<Integer, প্রসেসর_মান> প্রক্রিয়া_তালিকা = new HashMap<Integer, প্রসেসর_মান>();
    private final Queue<প্রসেসর_মান> 준비대기열 = new ArrayDeque<প্রসেসর_মান>();
    private int পরবর্তী_সনাক্তকারী = 1;

    public সময়সূচি_নির্ধারণকারী(পৃষ্ঠা_ব্যবস্থাপক 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public প্রসেসর_মান 첫과정(파일서술자표 파일서술자) {
        প্রসেসর_মান 새과정 = new প্রসেসর_মান(বন্টন_করা_সনাক্তকারী(), 0, 쪽관리.새주소공간(), 파일서술자);
        প্রক্রিয়া_তালিকা.put(Integer.valueOf(새과정.সনাক্তকারী_মান()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public প্রসেসর_মান 복제(প্রসেসর_মান 부모) {
        প্রসেসর_মান শিশু_মান = new প্রসেসর_মান(
                বন্টন_করা_সনাক্তকারী(),
                부모.সনাক্তকারী_মান(),
                쪽관리.쓰기시복사복제(부모.ইমেইল_স্পেস()),
                부모.파일서술자().복제());
        শিশু_মান.সেট_অ্যাপ_বিরতি(부모.অ্যাপ_বিরতি());
        প্রক্রিয়া_তালিকা.put(Integer.valueOf(শিশু_মান.সনাক্তকারী_মান()), শিশু_মান);
        준비대기열.offer(শিশু_মান);
        return শিশু_মান;
    }

    public প্রসেসর_মান পরবর্তী_প্রসেসর() {
        int 검사수 = 준비대기열.size();
        for (int সূচি = 0; সূচি < 검사수; সূচি++) {
            প্রসেসর_মান পরবর্তী_দফা = 준비대기열.poll();
            if (পরবর্তী_দফা != null && (পরবর্তী_দফা.অবস্হা_মান() == প্রসেসর_অবস্হা.প্রস্তুত_করুন || পরবর্তী_দফা.অবস্হা_মান() == প্রসেসর_অবস্হা.কার্যকর_করুন_আদেশ)) {
                পরবর্তী_দফা.সেট_অবস্হা(প্রসেসর_অবস্হা.কার্যকর_করুন_আদেশ);
                준비대기열.offer(পরবর্তী_দফা);
                return পরবর্তী_দফা;
            }
        }
        return null;
    }

    public int 자식기다리기(প্রসেসর_মান 부모, int শিশু_সনাক্তকারী, boolean 기다리지않음) {
        for (প্রসেসর_মান 후보 : প্রক্রিয়া_তালিকা.values()) {
            if (후보.부모식별자() != 부모.সনাক্তকারী_মান()) {
                continue;
            }
            if (শিশু_সনাক্তকারী > 0 && 후보.সনাক্তকারী_মান() != শিশু_সনাক্তকারী) {
                continue;
            }
            if (후보.অবস্হা_মান() == প্রসেসর_অবস্হা.প্রস্থান_অ্যাপ) {
                int পরিমাপ = (후보.প্রস্থান_কোড() & 0xff) << 8;
                প্রক্রিয়া_তালিকা.remove(Integer.valueOf(후보.সনাক্তকারী_মান()));
                return পরিমাপ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public প্রসেসর_মান খোঁজা_প্রসেসর(int সনাক্তকারী_মান) {
        return প্রক্রিয়া_তালিকা.get(Integer.valueOf(সনাক্তকারী_মান));
    }

    private int বন্টন_করা_সনাক্তকারী() {
        return পরবর্তী_সনাক্তকারী++;
    }
}
