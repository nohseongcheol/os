import မြန်မာ.ကိုယ်ပိုင်.စစ်ဆေးချက်;
import မြန်မာ.ကိုယ်ပိုင်.ဝင်စီးကြောင်း;
import မြန်မာ.ကိုယ်ပိုင်.အဝင်အထွက်ခြွင်းချက်;

public class ကွန်ရက်ဥပမာ {
    public static void လုပ်ဆောင်() throws အဝင်အထွက်ခြွင်းချက် {
        // အိမ်ရှင်တွင် လုပ်ဆောင်ရန်: python3 ကိရိယာစု/ဥပမာပြန်ပို့.py --tcp-port 9000 --udp-port 9001
        ဆက်သွယ်လမ်းကြောင်း ချိတ်ဆက် = ဆက်သွယ်လမ်းကြောင်း.ဖွင့်("10.0.2.2", အက္ခရာ.ကိန်းပြည့်သဒ္ဒါခွဲခြမ်း(လုပ်ဆောင်အချက်များ.စာသား(0)));
        try {
            ချိတ်ဆက်.စောင့်ချိန်(700);
            byte[] ပို့မည့်စာ = အက္ခရာ.ကုဒ်သွင်း("JAVA TCP my\n");
            ချိတ်ဆက်.အထွက်().ရေး(ပို့မည့်စာ);
            ဝင်စီးကြောင်း ဝင်ဒေတာ = ချိတ်ဆက်.ဝင်ဒေတာ();
            for (int ကိန်းတန်ဖိုး = 0; ကိန်းတန်ဖိုး < အက္ခရာ.ဘိုက်အရေအတွက်(ပို့မည့်စာ); ကိန်းတန်ဖိုး++) {
                စစ်ဆေးချက်.မှန်ကြောင်းစစ်(ဝင်ဒေတာ.ဖတ်() == (ပို့မည့်စာ[ကိန်းတန်ဖိုး] & 255), "TCP အကြောင်းပြန်ချက် 불일치");
            }
        } finally { ချိတ်ဆက်.ပိတ်(); }
        ဒေတာပို့လမ်း ဆုံးမှတ် = ဒေတာပို့လမ်း.ဖွင့်(0);
        try {
            ဆုံးမှတ်.စောင့်ချိန်(700);
            ဆုံးမှတ်.ပို့("10.0.2.2", အက္ခရာ.ကိန်းပြည့်သဒ္ဒါခွဲခြမ်း(လုပ်ဆောင်အချက်များ.စာသား(1)), "JAVA UDP my");
            စစ်ဆေးချက်.မှန်ကြောင်းစစ်(အက္ခရာ.ညီစာသား(ဆုံးမှတ်.လက်ခံ(), "JAVA UDP my"), "UDP အကြောင်းပြန်ချက် 불일치");
        } finally { ဆုံးမှတ်.ပိတ်(); }
        အထွက်.စာကြောင်းထုတ်("JAVA ကွန်ရက်ဆက် အတည်ပြု: TCP UDP my");
    }
}
