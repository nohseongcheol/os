            for (int နေရာကွက်အချက် = 0; နေရာကွက်အချက် < ဖိုင်အရွယ်; နေရာကွက်အချက်++) တည်းဖြတ်တန်ဖိုး[နေရာကွက်အချက်] = ကိရိယာ.မှတ်ဉာဏ်ဖတ်(အုပ်စုတန်ဖိုး + နေရာ + နေရာကွက်အချက်);
            if (သိုလှောင်တန်ဖိုး(အမည်, အလျား, တည်းဖြတ်တန်ဖိုး, ဖိုင်အရွယ်) < 0) { စာသားစက်.ရေး("Java 파일을 가져오지 못했습니다\n"); return; }
