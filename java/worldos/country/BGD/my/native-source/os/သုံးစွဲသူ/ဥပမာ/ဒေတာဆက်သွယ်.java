public final class ဒေတာဆက်သွယ် {
    static int ဂဏန်းတန်ဖိုး(String စာသား) {
        if (စာသား == null || စာသား.length() == 0) return -1;
        int ရလဒ် = 0;
        for (int နံပါတ် = 0; နံပါတ် < စာသား.length(); နံပါတ်++) {
            int တန်ဖိုး = စာသား.charAt(နံပါတ်) - '0';
            if (တန်ဖိုး < 0 || တန်ဖိုး > 9 || ရလဒ် > 6553) return -1;
            ရလဒ် = ရလဒ် * 10 + တန်ဖိုး;
            if (ရလဒ် > 65535) return -1;
        }
        return ရလဒ်;
    }
    static int လိပ်စာ(String စာသား) {
        if (စာသား == null) return 0;
        int တန်ဖိုး = 0, ရလဒ် = 0, အစိတ်အပိုင်းတန်ဖိုး = 0, ဂဏန်းများ = 0;
        for (int နံပါတ် = 0; နံပါတ် <= စာသား.length(); နံပါတ်++) {
            int အက္ခရာ = နံပါတ် == စာသား.length() ? '.' : စာသား.charAt(နံပါတ်);
            if (အက္ခရာ == '.') {
                if (ဂဏန်းများ == 0 || အစိတ်အပိုင်းတန်ဖိုး == 4) return 0;
                ရလဒ် = (ရလဒ် << 8) | တန်ဖိုး; အစိတ်အပိုင်းတန်ဖိုး++; တန်ဖိုး = 0; ဂဏန်းများ = 0;
            } else {
                if (အက္ခရာ < '0' || အက္ခရာ > '9') return 0;
                တန်ဖိုး = တန်ဖိုး * 10 + အက္ခရာ - '0';
                if (++ဂဏန်းများ > 3 || တန်ဖိုး > 255) return 0;
            }
        }
        return အစိတ်အပိုင်းတန်ဖိုး == 4 ? ရလဒ် : 0;
    }
    public static int လုပ်ဆောင်() {
        if (သုံးစွဲသူ.ပေးအချက်များအရေအတွက်() != 3) { သုံးစွဲသူ.ရေး("Usage: run udp IP PORT TEXT\n"); return 2; }
        int လိပ်စာ = လိပ်စာ(သုံးစွဲသူ.အချက်များ(0)), ဆက်သွယ်ပေါက်တန်ဖိုး = ဂဏန်းတန်ဖိုး(သုံးစွဲသူ.အချက်များ(1));
        String အကြောင်းအရာတန်ဖိုး = သုံးစွဲသူ.အချက်များ(2);
        if (လိပ်စာ == 0 || ဆက်သွယ်ပေါက်တန်ဖိုး < 1 || အကြောင်းအရာတန်ဖိုး.length() > 1024) { သုံးစွဲသူ.ရေး("Bad destination\n"); return 2; }
        int ကိုင်တွယ်ရာတန်ဖိုး = သုံးစွဲသူ.ကွန်ရက်ဖွင့်(0);
        if (ကိုင်တွယ်ရာတန်ဖိုး < 0) { သုံးစွဲသူ.ရေး("UDP OPEN FAILED (network unavailable)\n"); return 3; }
        int[] ဒေတာ = new int[1024];
        for (int နံပါတ် = 0; နံပါတ် < အကြောင်းအရာတန်ဖိုး.length(); နံပါတ်++) ဒေတာ[နံပါတ်] = အကြောင်းအရာတန်ဖိုး.charAt(နံပါတ်);
        if (သုံးစွဲသူ.ဒေတာပို့(ကိုင်တွယ်ရာတန်ဖိုး, လိပ်စာ, ဆက်သွယ်ပေါက်တန်ဖိုး, ဒေတာ, အကြောင်းအရာတန်ဖိုး.length()) < 0) {
            သုံးစွဲသူ.ရေး("UDP SEND FAILED\n"); သုံးစွဲသူ.ကွန်ရက်ပိတ်(ကိုင်တွယ်ရာတန်ဖိုး); return 4;
        }
        သုံးစွဲသူ.ရေး("UDP SENT\n");
        int ရရှိအရှည် = သုံးစွဲသူ.ဒေတာလက်ခံရယူ(ကိုင်တွယ်ရာတန်ဖိုး, ဒေတာ, 1500);
        boolean ညီစာသား = ရရှိအရှည် == အကြောင်းအရာတန်ဖိုး.length() && သုံးစွဲသူ.ပို့ပြီးလိပ်စာ(ကိုင်တွယ်ရာတန်ဖိုး) == လိပ်စာ && သုံးစွဲသူ.ပို့ပြီးဆက်သွယ်ပေါက်(ကိုင်တွယ်ရာတန်ဖိုး) == ဆက်သွယ်ပေါက်တန်ဖိုး;
        if (ညီစာသား) for (int နံပါတ် = 0; နံပါတ် < ရရှိအရှည်; နံပါတ်++) if (ဒေတာ[နံပါတ်] != အကြောင်းအရာတန်ဖိုး.charAt(နံပါတ်)) ညီစာသား = false;
        သုံးစွဲသူ.ကွန်ရက်ပိတ်(ကိုင်တွယ်ရာတန်ဖိုး);
        if (ရရှိအရှည် < 0) { သုံးစွဲသူ.ရေး("UDP RECEIVE TIMEOUT/ERROR\n"); return 5; }
        သုံးစွဲသူ.ရေး(ညီစာသား ? "UDP ECHO PASS\n" : "UDP REPLY MISMATCH\n");
        return ညီစာသား ? 0 : 6;
    }
}
