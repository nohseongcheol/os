#!/usr/bin/env python3
"""ကြေညာချက် 고유번호와 UTF-8 ဘိုက်တန်ဖိုး 위치로 ကိုယ်ပိုင် C 이름을 옮기는 일회성 이행 ကိရိယာစု.

ပြင်ပတန်ဖိုး 구조체의 멤버, အက္ခရာစဉ်, C 표준 လုပ်ဆောင်ချက်, 이식 규약은 보존한다.
입력은 တန်ဖိုးပြောင်း 전 소스에 대한 Cအမည်များခွဲခြမ်းစိတ်ဖြာ.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

စီမံကိန်းအမြစ် = Path(__file__).resolve().parents[1]

def စက်မောင်း():
    တန်ဖိုးခွဲခြမ်းစိတ်ဖြာ = json.loads((စီမံကိန်းအမြစ်/'build/한국어화/시언어분석.json').read_text())
    if တန်ဖိုးခွဲခြမ်းစိတ်ဖြာ['အမှား']: raise SystemExit('တန်ဖိုးခွဲခြမ်းစိတ်ဖြာ 오류를 먼저 해결해야 합니다.')
    အမည်ဇယား = json.loads((စီမံကိန်းအမြစ်/'명명/Cအမည်များ.json').read_text())
    규격 = set(json.loads((စီမံကိန်းအမြစ်/'명명/စံအမည်များ.json').read_text()))
    ကြေညာချက်ဇယား = တန်ဖိုးခွဲခြမ်းစိတ်ဖြာ['ကြေညာချက်']
    바꿀선언 = {고유:အမည်ဇယား[အချက်တန်ဖိုး['အမည်']] for 고유,အချက်တန်ဖိုး in ကြေညာချက်ဇယား.items()
                if အချက်တန်ဖိုး['အမည်'] in အမည်ဇယား and အချက်တန်ဖိုး['အမည်'] not in 규격}
    ချိတ်ဆက်မှုဇယား = {အချက်တန်ဖိုး['အမည်']:အမည်ဇယား[အချက်တန်ဖိုး['အမည်']] for အချက်တန်ဖိုး in ကြေညာချက်ဇယား.values()
              if အချက်တန်ဖိုး.get('ချိတ်ဆက်')==4 and အချက်တန်ဖိုး['အမျိုးအစားတန်ဖိုး'] in (8,9)
              and အချက်တန်ဖိုး['အမည်'] in အမည်ဇယား and အချက်တန်ဖိုး['အမည်'] not in 규격}
    # ထုတ်လုပ် AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ချိတ်ဆက် 이름만 유지한다.
    ဦးခေါင်းတန်ဖိုး = ['/* မြန်မာ မူရင်းကုဒ်အပင်ဖွဲ့စည်းပုံ 이름과 기존 စက် ချိတ်ဆက် သဘောတူစည်းမျဉ်းတန်ဖိုး. 자동 ထုတ်လုပ်: 명명/Cအမည်များ.json */',
           '#ifndef ကိုယ်ပိုင်စက်ချိတ်အမည်များခေါင်းစီး', '#define ကိုယ်ပိုင်စက်ချိတ်အမည်များခေါင်းစီး']
    ဦးခေါင်းတန်ဖိုး += ['#define '+အသစ်အမည်+' '+အဟောင်းအမည် for အဟောင်းအမည်,အသစ်အမည် in sorted(ချိတ်ဆက်မှုဇယား.items())]
    ဦးခေါင်းတန်ဖိုး += ['#endif','']
    (စီမံကိန်းအမြစ်/'명명/စက်ချိတ်အမည်များ.h').write_text('\n'.join(ဦးခေါင်းတန်ဖိုး))
    변경들 = defaultdict(dict)
    for ဖိုင်,အရွေ့တန်ဖိုး,အမည်,고유 in တန်ဖိုးခွဲခြမ်းစိတ်ဖြာ['ကိုးကားချက်']:
        if 고유 in 바꿀선언:
            변경들[ဖိုင်][အရွေ့တန်ဖိုး] = (အမည်,바꿀선언[고유])
    မှတ်တမ်းမှတ်တမ်းတစ်ခု = ['ဖိုင်\t원래바이트위치\t이전이름\t한국어이름']
    무시 = []
    for ဖိုင်,တန်ဖိုးပြောင်း in 변경들.items():
        လမ်း = Path(ဖိုင်); မူရင်း = လမ်း.read_bytes(); ဒေတာ = မူရင်း
        for အရွေ့တန်ဖိုး,(အဟောင်းအမည်,အသစ်အမည်) in sorted(တန်ဖိုးပြောင်း.items(),reverse=True):
            အဆုံး = အရွေ့တန်ဖိုး+len(အဟောင်းအမည်.encode())
            if မူရင်း[အရွေ့တန်ဖိုး:အဆုံး] != အဟောင်းအမည်.encode():
                무시.append((str(လမ်း.relative_to(စီမံကိန်းအမြစ်)),အရွေ့တန်ဖိုး,အဟောင်းအမည်));continue
            ဒေတာ = ဒေတာ[:အရွေ့တန်ဖိုး]+အသစ်အမည်.encode()+ဒေတာ[အဆုံး:]
            မှတ်တမ်းမှတ်တမ်းတစ်ခု.append('{}\t{}\t{}\t{}'.format(လမ်း.relative_to(စီမံကိန်းအမြစ်),အရွေ့တန်ဖိုး,အဟောင်းအမည်,အသစ်အမည်))
        လမ်း.write_bytes(ဒေတာ)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    ဝေါဟာရ = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    매크로 = {အချက်တန်ဖိုး['အမည်']:အမည်ဇယား[အချက်တန်ဖိုး['အမည်']] for အချက်တန်ဖိုး in ကြေညာချက်ဇယား.values()
              if အချက်တန်ဖိုး['အမျိုးအစားတန်ဖိုး']==501 and အချက်တန်ဖိုး['အမည်'] in အမည်ဇယား and အချက်တန်ဖိုး['အမည်'] not in 규격}
    for လမ်း in sorted({Path(အချက်တန်ဖိုး['ဖိုင်']) for အချက်တန်ဖိုး in ကြေညာချက်ဇယား.values()}):
        စာကြောင်းစာရင်း = လမ်း.read_text().splitlines(True); 이어짐 = False
        for နံပါတ်,စာကြောင်း in enumerate(စာကြောင်းစာရင်း):
            전처리 = 이어짐 or bool(re.match(r'\s*#',စာကြောင်း))
            이어짐 = 전처리 and စာကြောင်း.rstrip().endswith('\\')
            if 전처리:
                ဇယား = အမည်ဇယား if re.match(r'\s*#\s*define\b',စာကြောင်း) or 이어짐 else 매크로
                စာကြောင်းစာရင်း[နံပါတ်] = ဝေါဟာရ.sub(lambda 맞음: ဇယား.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],စာကြောင်း)
        လမ်း.write_text(''.join(စာကြောင်းစာရင်း))
    # 각 ကိုယ်ပိုင် မူရင်းကုဒ်ဘာသာပြန်ဆို 단위에만 연결표를 넣는다. ပြင်ပတန်ဖိုး 배포본에는 전파하지 않는다.
    for လမ်း in sorted({Path(အချက်တန်ဖိုး['ဖိုင်']) for အချက်တန်ဖိုး in ကြေညာချက်ဇယား.values()}):
        if လမ်း.suffix not in ('.c','.cpp'):continue
        တစ်ဖက်တန်ဖိုး = '../' * len(လမ်း.relative_to(စီမံကိန်းအမြစ်).parts[:-1]) + '명명/စက်ချိတ်အမည်များ.h'
        လမ်း.write_text('#include "'+တစ်ဖက်တန်ဖိုး+'"\n'+လမ်း.read_text())
    (စီမံကိန်းအမြစ်/'명명/Cအမည်ချိတ်ဆက်ပုံ.tsv').write_text('\n'.join(မှတ်တမ်းမှတ်တမ်းတစ်ခု)+'\n')
    (စီမံကိန်းအမြစ်/'build/한국어화/전처리참조.json').write_text(json.dumps(무시,ensure_ascii=False,indent=2)+'\n')
    print('တန်ဖိုးပြောင်း',len(မှတ်တမ်းမှတ်တမ်းတစ်ခု)-1,'전처리 재검토',len(무시),'စက် ချိတ်ဆက်',len(ချိတ်ဆက်မှုဇယား))

if __name__=='__main__': စက်မောင်း()
