#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from အလုပ်မျက်နှာပြင်ရှုမြင်ရာ import လက်ကွက်


class ဟန်ဂုအဝင်စမ်းသပ်(unittest.TestCase):
    def setUp(자신):
        자신.စာသားကြားခံ = ''
        def ပို့(ဒေတာ):
            for အက္ခရာဒေတာ in ဒေတာ.decode('utf-8'):
                if အက္ခရာဒေတာ == '\x7f': 자신.စာသားကြားခံ = 자신.စာသားကြားခံ[:-1]
                else: 자신.စာသားကြားခံ += အက္ခရာဒေတာ
        자신.လက်ကွက်အချက် = လက်ကွက်(ပို့)

    def 글쇠누르기(자신, သင်္ကေတတန်ဖိုး):
        자신.လက်ကွက်အချက်.누름값(True, သင်္ကေတတန်ဖိုး)
        자신.လက်ကွက်အချက်.누름값(False, သင်္ကေတတန်ဖိုး)

    def ပုံစံအမျိုးအစား(자신, 누름열):
        for 누름값 in 누름열: 자신.글쇠누르기(ord(누름값))

    def စကားလုံးများစမ်းသပ်(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.글쇠누르기(0xffc6); 자신.ပုံစံအမျိုးအစား(누름열)
                자신.assertEqual(자신.စာသားကြားခံ, 예상결과)

    def test_앞글자지우기(자신):
        자신.글쇠누르기(0xff31); 자신.ပုံစံအမျိုးအစား('dlfr')
        자신.assertEqual(자신.စာသားကြားခံ,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.글쇠누르기(0xff08); 자신.assertEqual(자신.စာသားကြားခံ,예상결과)
        자신.ပုံစံအမျိုးအစား('gksk'); 자신.assertEqual(자신.စာသားကြားခံ,'တစ်တန်ဖိုး')
        자신.글쇠누르기(0xff08); 자신.assertEqual(자신.စာသားကြားခံ,'하ㄴ')

    def test_전환반복확정(자신):
        자신.ပုံစံအမျိုးအစား('echo ')
        자신.လက်ကွက်အချက်.누름값(True,0xffe1)
        자신.လက်ကွက်အချက်.누름값(True,32); 자신.လက်ကွက်အချက်.누름값(True,32)
        자신.လက်ကွက်အချက်.누름값(False,32); 자신.လက်ကွက်အချက်.누름값(False,0xffe1)
        자신.assertTrue(자신.လက်ကွက်အချက်.한글여부)
        자신.ပုံစံအမျိုးအစား('gksrmf'); 자신.글쇠누르기(0xff31); 자신.ပုံစံအမျိုးအစား(' English')
        자신.assertEqual(자신.စာသားကြားခံ,'echo 한글 English')
        자신.assertFalse(자신.လက်ကွက်အချက်.한글여부)
        자신.글쇠누르기(0xffc6); 자신.ပုံစံအမျိုးအစား('rk'); 자신.글쇠누르기(0xff51)
        자신.ပုံစံအမျိုးအစား('sk'); 자신.assertTrue(자신.စာသားကြားခံ.endswith('ပထမတွက်ချက်ခံ\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.글쇠누르기(0xffc6); 자신.ပုံစံအမျိုးအစား('rk')
        자신.လက်ကွက်အချက်.붙임판='붙여넣기'.encode()
        자신.လက်ကွက်အချက်.누름값(True,0xffe3); 자신.လက်ကွက်အချက်.누름값(True,0xffe1)
        자신.글쇠누르기(ord('v'))
        자신.လက်ကွက်အချက်.누름값(False,0xffe1); 자신.လက်ကွက်အချက်.누름값(False,0xffe3)
        자신.글쇠누르기(0x0100d55c); 자신.ပုံစံအမျိုးအစား('sk')
        자신.assertEqual(자신.စာသားကြားခံ,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
