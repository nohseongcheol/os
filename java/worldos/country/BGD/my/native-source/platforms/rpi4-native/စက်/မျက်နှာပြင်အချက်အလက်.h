#ifndef ကိုယ်ပိုင်မျက်နှာပြင်အချက်အလက်ခေါင်းစီး
#define ကိုယ်ပိုင်မျက်နှာပြင်အချက်အလက်ခေါင်းစီး
#include <stdint.h>
/* 초기화가 끝난 တကယ့်ဒေတာ RGB32 မျက်နှာပြင် အရွယ်. 준비되지 않았으면 0이다. */
uintptr_t ဆားကစ်ပြားမျက်နှာပြင်အနံ(void);
uintptr_t ဆားကစ်ပြားမျက်နှာပြင်အမြင့်(void);
/* 0: 숨김, 1: 화살표, 2: 좌상↔우하, 3: 우상↔좌하. */
void ဆားကစ်ပြားညွှန်တံ(int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ, unsigned ပုံသဏ္ဌာန်တန်ဖိုး);
/* 한 번에 32줄을 완성한 နောက်တန်ဖိုး, 달라진 화소만 တကယ့်ဒေတာ 화면에 옮긴다. */
void ဆားကစ်ပြားပြင်ဆင်ပုံရေးဆွဲမှု(volatile uint32_t *ဒေတာ, unsigned အကျယ်အဝန်း, unsigned အလျား, unsigned 줄간격);
int 보드그림범위(int *အလျားတည်နေရာ, int *ဒေါင်လိုက်တည်နေရာ, int *အကျယ်အဝန်း, int *အလျား);
int ဆားကစ်ပြားစတင်ပုံရေးဆွဲမှု(int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ, int အကျယ်အဝန်း, int အလျား);
void ဆားကစ်ပြားပြီးဆုံးပုံရေးဆွဲမှု(void);
void ဆားကစ်ပြားစတုဂံဖြည့်(int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ, int အကျယ်အဝန်း, int အလျား, uint32_t အရောင်တန်ဖိုး);
/* တကယ့်ဒေတာ တန်ဖိုးပြသ 메모리에 기록한 ပုံမှတ် ကိန်းတန်ဖိုး. ညွှန်တံ 갱신은 제외한다. */
uint64_t ဆားကစ်ပြားပုံရေးဆွဲမှုအရေအတွက်(void);
uint32_t ဆားကစ်ပြားဖတ်မျက်နှာပြင်(unsigned အလျားတည်နေရာ, unsigned ဒေါင်လိုက်တည်နေရာ);
#endif
