import မြန်မာ.ကိုယ်ပိုင်.*;
public class မြန်မာအလုပ်ကြိုးစမ်းသပ် implements လုပ်ဆောင်ရန်အလုပ် {
    private int အကုန်စုစုပေါင်းတန်ဖိုး;
    public void အလုပ်လုပ်ဆောင်() {
        for (int အစဉ်လိုက်တန်ဖိုး = 0; အစဉ်လိုက်တန်ဖိုး < 100; အစဉ်လိုက်တန်ဖိုး++) { အကုန်စုစုပေါင်းတန်ဖိုး++; အလုပ်သမား.အလုပ်အလှည့်ပေး(); }
    }
    public static void လုပ်ဆောင်() throws စောင့်ဆိုင်းပြတ်ခြွင်းချက် {
        မြန်မာအလုပ်ကြိုးစမ်းသပ် အလုပ်လုပ်ဆောင်ချက် = new မြန်မာအလုပ်ကြိုးစမ်းသပ်();
        အလုပ်သမား အလုပ်ကြိုးတန်ဖိုး = new အလုပ်သမား(အလုပ်လုပ်ဆောင်ချက်);
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(!အလုပ်ကြိုးတန်ဖိုး.လည်ပတ်ဆဲလား(), "လုပ်ဆောင် 전 အခြေအနေတန်ဖိုး");
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(!((Object)အလုပ်ကြိုးတန်ဖိုး instanceof Thread), "표준 가닥과 독립된 ပုံစံတန်ဖိုး");
        အလုပ်ကြိုးတန်ဖိုး.အလုပ်စတင်(); အလုပ်ကြိုးတန်ဖိုး.စောင့်();
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(အလုပ်လုပ်ဆောင်ချက်.အကုန်စုစုပေါင်းတန်ဖိုး == 100 && !အလုပ်ကြိုးတန်ဖိုး.လည်ပတ်ဆဲလား(), "한글 အလုပ်ကြိုးတန်ဖိုး 실행과 အခြေအနေစောင့်");
        try { အလုပ်ကြိုးတန်ဖိုး.အလုပ်စတင်(); စစ်ဆေးချက်.မှန်ကြောင်းစစ်(false, "중복 လုပ်ဆောင် တန်ဖိုးငြင်းပယ်"); }
        catch (အလုပ်ကြိုးအခြေအနေခြွင်းချက် အမှား) { အထွက်.စာကြောင်းထုတ်("မြန်မာ အလုပ်ကြိုးတန်ဖိုး 중복 လုပ်ဆောင် တန်ဖိုးငြင်းပယ်"); }
        အလုပ်သမား နောက်တစ်ခုအလုပ်ကြိုး = အလုပ်.လုပ်ဆောင်(အလုပ်လုပ်ဆောင်ချက်); အလုပ်.စောင့်(နောက်တစ်ခုအလုပ်ကြိုး);
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(အလုပ်လုပ်ဆောင်ချက်.အကုန်စုစုပေါင်းတန်ဖိုး == 200 && !အလုပ်.လည်ပတ်ဆဲလား(နောက်တစ်ခုအလုပ်ကြိုး), "မြန်မာ အလုပ် 편의 လုပ်ဆောင်ချက်");
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(လုပ်ဆောင်အချက်များ.အရေအတွက်() == 0, "빈 စက်မောင်း အချက်များ");
        try { လုပ်ဆောင်အချက်များ.စာသား(0); စစ်ဆေးချက်.မှန်ကြောင်းစစ်(false, "အချက်များ ဖြတ်နယ်ပယ် စစ်ဆေးချက်"); }
        catch (နယ်နိမိတ်ခြွင်းချက် အမှား) { အထွက်.စာကြောင်းထုတ်("မြန်မာ အချက်များ ဖြတ်နယ်ပယ် တန်ဖိုးငြင်းပယ်"); }
        အထွက်.စာကြောင်းထုတ်("မြန်မာ 직접 အလုပ်ကြိုးတန်ဖိုး အောင်တန်ဖိုး");
    }
}
