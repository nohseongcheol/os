public final class အဆုံးသုံးစက် {
    static void အက္ခရာ(int တန်ဖိုး) {
        if (တန်ဖိုး < 0x80) ဆားကစ်ပြား.အစဉ်ဆက်ရေး(တန်ဖိုး);
        else if (တန်ဖိုး < 0x800) {
            ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0xc0 | (တန်ဖိုး >> 6)); ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0x80 | (တန်ဖိုး & 63));
        } else if (တန်ဖိုး < 0x10000) {
            ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0xe0 | (တန်ဖိုး >> 12)); ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0x80 | ((တန်ဖိုး >> 6) & 63)); ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0x80 | (တန်ဖိုး & 63));
        } else {
            ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0xf0 | (တန်ဖိုး >> 18)); ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0x80 | ((တန်ဖိုး >> 12) & 63));
            ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0x80 | ((တန်ဖိုး >> 6) & 63)); ဆားကစ်ပြား.အစဉ်ဆက်ရေး(0x80 | (တန်ဖိုး & 63));
        }
    }
    static void ရေး(String စာသား) {
        for (int နံပါတ် = 0; နံပါတ် < စာသား.length(); နံပါတ်++) {
            int တန်ဖိုး = စာသား.charAt(နံပါတ်);
            if (တန်ဖိုး >= 0xd800 && တန်ဖိုး <= 0xdbff && နံပါတ် + 1 < စာသား.length()) {
                int အောက်ဆုံးတန်ဖိုး = စာသား.charAt(နံပါတ် + 1);
                if (အောက်ဆုံးတန်ဖိုး >= 0xdc00 && အောက်ဆုံးတန်ဖိုး <= 0xdfff) {
                    တန်ဖိုး = 0x10000 + ((တန်ဖိုး - 0xd800) << 10) + အောက်ဆုံးတန်ဖိုး - 0xdc00; နံပါတ်++;
                }
            }
            if (တန်ဖိုး >= 0xd800 && တန်ဖိုး <= 0xdfff) တန်ဖိုး = 0xfffd;
            အက္ခရာ(တန်ဖိုး);
        }
    }
    static void ကိန်းတန်ဖိုး(int တန်ဖိုး) {
        if (တန်ဖိုး < 0) အက္ခရာ('-'); else တန်ဖိုး = -တန်ဖိုး;
        int နေရာအညွှန်းကိန်း = 1000000000;
        boolean လုပ်ဆောင် = false;
        while (နေရာအညွှန်းကိန်း > 0) {
            int ဂဏန်းတန်ဖိုး = -(တန်ဖိုး / နေရာအညွှန်းကိန်း);
            if (ဂဏန်းတန်ဖိုး != 0 || လုပ်ဆောင် || နေရာအညွှန်းကိန်း == 1) { အက္ခရာ('0' + ဂဏန်းတန်ဖိုး); လုပ်ဆောင် = true; }
            တန်ဖိုး %= နေရာအညွှန်းကိန်း; နေရာအညွှန်းကိန်း /= 10;
        }
    }
}
