/** ပိုက်များကို 16 KiB စီ အစဉ်လိုက် လုပ်ဆောင်သည်။ လုပ်ငန်းစဉ်များနှင့် တစ်ပြိုင်နက် ပိုက်များကို အတုမပြုပါ။ */
public final class အမိန့်ဝင်းဝင်ထွက် {
    static int[] အဝင်ဒေတာ = new int[16384], အထွက်ဒေတာ = new int[16384];
    static int အဝင်အလျား, အဝင်နေရာ, အထွက်အလျား, အဝင်ဖိုင် = -1, အထွက်ဖိုင် = -1;
    static boolean ပိုက်အဝင်, ပိုက်အထွက်;
    static int မအောင်မြင်မှု;
    static boolean အပြန်အလှန်ခွင့်ပြု = true;
    public static int ဖြစ်သောအပြန်အလှန်() { return အပြန်အလှန်ခွင့်ပြု && အဝင်ဖိုင် < 3 && အထွက်ဖိုင် < 3 && !ပိုက်အဝင် && !ပိုက်အထွက် ? 1 : 0; }
    public static int အထွက်(int ချန်နယ်တန်ဖိုး, int တန်ဖိုး) {
        if (ချန်နယ်တန်ဖိုး != 1) return 0;
        if (အထွက်ဖိုင် >= 3) { int ကိုင်တွယ်ပြီးတန်ဖိုး = မှတ်ဉာဏ်ဖိုင်.ရေး(အထွက်ဖိုင်, တန်ဖိုး); if (ကိုင်တွယ်ပြီးတန်ဖိုး < 0) မအောင်မြင်မှု = ကိုင်တွယ်ပြီးတန်ဖိုး; return 1; }
        if (!ပိုက်အထွက်) return 0;
        if (အထွက်အလျား == အထွက်ဒေတာ.length) မအောင်မြင်မှု = -28;
        else အထွက်ဒေတာ[အထွက်အလျား++] = တန်ဖိုး;
        return 1;
    }
    public static int ဝင်ဒေတာ() {
        if (အဝင်ဖိုင် >= 3) { int ကိုင်တွယ်ပြီးတန်ဖိုး = မှတ်ဉာဏ်ဖိုင်.ဖတ်(အဝင်ဖိုင်); return ကိုင်တွယ်ပြီးတန်ဖိုး == 256 ? -2 : ကိုင်တွယ်ပြီးတန်ဖိုး; }
        if (ပိုက်အဝင်) return အဝင်နေရာ < အဝင်အလျား ? အဝင်ဒေတာ[အဝင်နေရာ++] : -2;
        return -3; // UART သို့ ပို့သည်။
    }
    static void လုပ်ဆောင်(boolean ရှေ့ပိုက်, boolean နောက်ပိုက်) {
        ပိုက်အဝင် = ရှေ့ပိုက်; ပိုက်အထွက် = နောက်ပိုက်;
        အဝင်နေရာ = 0; အထွက်အလျား = 0; အဝင်ဖိုင် = -1; အထွက်ဖိုင် = -1; မအောင်မြင်မှု = 0;
    }
    static void အဆုံး() {
        ဆားကစ်ပြား.အလှည့်ပြောင်းအဝင်အထွက်(0);
        if (အဝင်ဖိုင် >= 3) မှတ်ဉာဏ်ဖိုင်.ပိတ်(အဝင်ဖိုင်);
        if (အထွက်ဖိုင် >= 3) မှတ်ဉာဏ်ဖိုင်.ပိတ်(အထွက်ဖိုင်);
        if (ပိုက်အထွက်) { အဝင်အလျား = အထွက်အလျား; for (int ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း = 0; ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း < အထွက်အလျား; ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း++) အဝင်ဒေတာ[ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း] = အထွက်ဒေတာ[ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း]; }
        အဝင်ဖိုင် = -1; အထွက်ဖိုင် = -1; ပိုက်အဝင် = false; ပိုက်အထွက် = false;
    }
}
