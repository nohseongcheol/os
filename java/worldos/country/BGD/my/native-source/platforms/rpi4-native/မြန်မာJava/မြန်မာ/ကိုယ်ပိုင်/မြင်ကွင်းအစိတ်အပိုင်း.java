package မြန်မာ.ကိုယ်ပိုင်;
/** မြန်မာ မျက်နှာပြင်အစိတ်အပိုင်းများ ဖန်တီးရန် အဆင်ပြေလုပ်ဆောင်နည်းများ။ */
public final class မြင်ကွင်းအစိတ်အပိုင်း {
    private မြင်ကွင်းအစိတ်အပိုင်း() {}
    public static void နောက်မှလုပ်ဆောင်(လုပ်ဆောင်ရန်အလုပ် အလုပ်လုပ်ဆောင်ချက်) { ဖြစ်ရပ်တန်းစီရာ.နောက်မှလုပ်ဆောင်(အလုပ်လုပ်ဆောင်ချက်); }
    public static အညွှန်းစာ တံဆိပ်တန်ဖိုး(String စာသား, int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ, int အကျယ်အဝန်း, int အမြင့်တန်ဖိုး) {
        return new အညွှန်းစာ(စာသား, အလျားတည်နေရာ, ဒေါင်လိုက်တည်နေရာ, အကျယ်အဝန်း, အမြင့်တန်ဖိုး);
    }
    public static ခလုတ် ခလုတ်(String စာသား, int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ, int အကျယ်အဝန်း, int အမြင့်တန်ဖိုး, လှုပ်ရှားမှုလက်ခံသူ လက်ခံသူတန်ဖိုး) {
        return new ခလုတ်(စာသား, အလျားတည်နေရာ, ဒေါင်လိုက်တည်နေရာ, အကျယ်အဝန်း, အမြင့်တန်ဖိုး, လက်ခံသူတန်ဖိုး);
    }
    public static စာသားအကွက် စာသားအကွက်(String စာသား, int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ, int အကျယ်အဝန်း, int အမြင့်တန်ဖိုး) {
        return new စာသားအကွက်(စာသား, အလျားတည်နေရာ, ဒေါင်လိုက်တည်နေရာ, အကျယ်အဝန်း, အမြင့်တန်ဖိုး);
    }
}
