package မြန်မာ.ကိုယ်ပိုင်;
/** အလုပ်ကြိုးသည် လုပ်ဆောင်မှုစီးကြောင်းတစ်ခုဖြစ်သည်။ ကိုယ်ပိုင် JVM တွင် အမိန့်အရေအတွက်အလိုက် အလှည့်ကျ လုပ်ဆောင်သည်။ */
public final class အလုပ် {
    private အလုပ်() {}
    public static အလုပ်သမား လုပ်ဆောင်(လုပ်ဆောင်ရန်အလုပ် အလုပ်လုပ်ဆောင်ချက်) { အလုပ်သမား အလုပ်ကြိုးတန်ဖိုး = new အလုပ်သမား(အလုပ်လုပ်ဆောင်ချက်); အလုပ်ကြိုးတန်ဖိုး.အလုပ်စတင်(); return အလုပ်ကြိုးတန်ဖိုး; }
    public static void စောင့်(အလုပ်သမား အလုပ်ကြိုးတန်ဖိုး) throws စောင့်ဆိုင်းပြတ်ခြွင်းချက် { အလုပ်ကြိုးတန်ဖိုး.စောင့်(); }
    public static boolean လည်ပတ်ဆဲလား(အလုပ်သမား အလုပ်ကြိုးတန်ဖိုး) { return အလုပ်ကြိုးတန်ဖိုး.လည်ပတ်ဆဲလား(); }
    public static void အလုပ်အလှည့်ပေး() { အလုပ်သမား.အလုပ်အလှည့်ပေး(); }
}
