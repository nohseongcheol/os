package ဘင်္ဂလားဒေ့ရှ်.JBgdOS.မျက်နှာပြင်;

import java.util.Arrays;

/** VGA စာသားနည်းနှင့် တူညီသော 80x25 စာသားမျက်နှာပြင်ပုံစံ။ */
public final class စာသားမျက်နှာပြင် {
    public static final int အနံတန်ဖိုး = 80;
    public static final int အမြင့်တန်ဖိုး = 25;
    private final char[] အက္ခရာတန်ဖိုးများ = new char[အနံတန်ဖိုး * အမြင့်တန်ဖိုး];
    private int အလျားတည်နေရာ;
    private int ဒေါင်လိုက်တည်နေရာ;

    public စာသားမျက်နှာပြင်() {
        အချက်ဖျက်();
    }

    public void အထွက်(String အကြောင်းအရာတန်ဖိုး) {
        for (int နံပါတ် = 0; နံပါတ် < အကြောင်းအရာတန်ဖိုး.length(); နံပါတ်++) {
            char အက္ခရာ = အကြောင်းအရာတန်ဖိုး.charAt(နံပါတ်);
            if (အက္ခရာ == '\n') {
                အလျားတည်နေရာ = 0;
                ဒေါင်လိုက်တည်နေရာ++;
            } else {
                အက္ခရာထုတ်(အလျားတည်နေရာ++, ဒေါင်လိုက်တည်နေရာ, အက္ခရာ);
            }
            if (အလျားတည်နေရာ >= အနံတန်ဖိုး) {
                အလျားတည်နေရာ = 0;
                ဒေါင်လိုက်တည်နေရာ++;
            }
            if (ဒေါင်လိုက်တည်နေရာ >= အမြင့်တန်ဖိုး) {
                လှိမ့်အပေါ်();
            }
        }
    }

    public char အက္ခရာ(int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ) {
        နေရာအတည်ပြု(အလျားတည်နေရာ, ဒေါင်လိုက်တည်နေရာ);
        return အက္ခရာတန်ဖိုးများ[ဒေါင်လိုက်တည်နေရာ * အနံတန်ဖိုး + အလျားတည်နေရာ];
    }

    public void အချက်ဖျက်() {
        Arrays.fill(အက္ခရာတန်ဖိုးများ, ' ');
        အလျားတည်နေရာ = 0;
        ဒေါင်လိုက်တည်နေရာ = 0;
    }

    private void အက္ခရာထုတ်(int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ, char အက္ခရာ) {
        နေရာအတည်ပြု(အလျားတည်နေရာ, ဒေါင်လိုက်တည်နေရာ);
        အက္ခရာတန်ဖိုးများ[ဒေါင်လိုက်တည်နေရာ * အနံတန်ဖိုး + အလျားတည်နေရာ] = အက္ခရာ;
    }

    private void လှိမ့်အပေါ်() {
        System.arraycopy(အက္ခရာတန်ဖိုးများ, အနံတန်ဖိုး, အက္ခရာတန်ဖိုးများ, 0, အနံတန်ဖိုး * (အမြင့်တန်ဖိုး - 1));
        Arrays.fill(အက္ခရာတန်ဖိုးများ, အနံတန်ဖိုး * (အမြင့်တန်ဖိုး - 1), အက္ခရာတန်ဖိုးများ.length, ' ');
        ဒေါင်လိုက်တည်နေရာ = အမြင့်တန်ဖိုး - 1;
    }

    private void နေရာအတည်ပြု(int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ) {
        if (အလျားတည်နေရာ < 0 || အလျားတည်နေရာ >= အနံတန်ဖိုး || ဒေါင်လိုက်တည်နေရာ < 0 || ဒေါင်လိုက်တည်နေရာ >= အမြင့်တန်ဖိုး) {
            throw new IllegalArgumentException("မျက်နှာပြင် 위치가 올바르지 않습니다.");
        }
    }
}

