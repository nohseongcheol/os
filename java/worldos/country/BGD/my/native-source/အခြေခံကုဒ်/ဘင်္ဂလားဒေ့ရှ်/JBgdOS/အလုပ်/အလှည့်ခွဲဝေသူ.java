package ဘင်္ဂလားဒေ့ရှ်.JBgdOS.အလုပ်;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import ဘင်္ဂလားဒေ့ရှ်.JBgdOS.မှတ်ဉာဏ်နယ်ပယ်.စာမျက်နှာစီမံသူ;
import ဘင်္ဂလားဒေ့ရှ်.JBgdOS.ဖိုင်စနစ်.ဖိုင်အညွှန်းဇယား;

/** လုပ်ငန်းစဉ်အမှတ်များနှင့် အလှည့်ကျ အသင့်တန်းစီရာကို စီမံသည်။ */
public final class အလှည့်ခွဲဝေသူ {
    private final စာမျက်နှာစီမံသူ စာမျက်နှာစီမံမှု;
    private final Map<Integer, လုပ်ငန်းစဉ်> လုပ်ငန်းစဉ်စာရင်း = new HashMap<Integer, လုပ်ငန်းစဉ်>();
    private final Queue<လုပ်ငန်းစဉ်> အသင့်တန်းစီရာ = new ArrayDeque<လုပ်ငန်းစဉ်>();
    private int နောက်တစ်ခုသတ်မှတ်နံပါတ် = 1;

    public အလှည့်ခွဲဝေသူ(စာမျက်နှာစီမံသူ စာမျက်နှာစီမံမှု) {
        this.စာမျက်နှာစီမံမှု = စာမျက်နှာစီမံမှု;
    }

    public လုပ်ငန်းစဉ် ပထမလုပ်ငန်းစဉ်(ဖိုင်အညွှန်းဇယား ဖိုင်အညွှန်း) {
        လုပ်ငန်းစဉ် အသစ်လုပ်ငန်းစဉ် = new လုပ်ငန်းစဉ်(သတ်မှတ်နံပါတ်ခွဲဝေ(), 0, စာမျက်နှာစီမံမှု.အသစ်လိပ်စာနေရာလပ်(), ဖိုင်အညွှန်း);
        လုပ်ငန်းစဉ်စာရင်း.put(Integer.valueOf(အသစ်လုပ်ငန်းစဉ်.သတ်မှတ်နံပါတ်တန်ဖိုး()), အသစ်လုပ်ငန်းစဉ်);
        အသင့်တန်းစီရာ.offer(အသစ်လုပ်ငန်းစဉ်);
        return အသစ်လုပ်ငန်းစဉ်;
    }

    public လုပ်ငန်းစဉ် ပုံတူပွားတန်ဖိုး(လုပ်ငန်းစဉ် မိဘတန်ဖိုး) {
        လုပ်ငန်းစဉ် သားသမီးတန်ဖိုး = new လုပ်ငန်းစဉ်(
                သတ်မှတ်နံပါတ်ခွဲဝေ(),
                မိဘတန်ဖိုး.သတ်မှတ်နံပါတ်တန်ဖိုး(),
                စာမျက်နှာစီမံမှု.ရေးချိန်ကူးပွား(မိဘတန်ဖိုး.လိပ်စာနယ်ပယ်()),
                မိဘတန်ဖိုး.ဖိုင်အညွှန်း().ပုံတူပွားတန်ဖိုး());
        သားသမီးတန်ဖိုး.ပရိုဂရမ်ဖြတ်သတ်မှတ်(မိဘတန်ဖိုး.ပရိုဂရမ်ဖြတ်());
        လုပ်ငန်းစဉ်စာရင်း.put(Integer.valueOf(သားသမီးတန်ဖိုး.သတ်မှတ်နံပါတ်တန်ဖိုး()), သားသမီးတန်ဖိုး);
        အသင့်တန်းစီရာ.offer(သားသမီးတန်ဖိုး);
        return သားသမီးတန်ဖိုး;
    }

    public လုပ်ငန်းစဉ် နောက်တစ်ခုလုပ်ငန်းစဉ်() {
        int အရေအတွက်စစ် = အသင့်တန်းစီရာ.size();
        for (int နံပါတ် = 0; နံပါတ် < အရေအတွက်စစ်; နံပါတ်++) {
            လုပ်ငန်းစဉ် နောက်တစ်ခုအချက်အလက်တစ်ခု = အသင့်တန်းစီရာ.poll();
            if (နောက်တစ်ခုအချက်အလက်တစ်ခု != null && (နောက်တစ်ခုအချက်အလက်တစ်ခု.အခြေအနေတန်ဖိုး() == လုပ်ငန်းစဉ်အခြေအနေ.ပြင်ဆင် || နောက်တစ်ခုအချက်အလက်တစ်ခု.အခြေအနေတန်ဖိုး() == လုပ်ငန်းစဉ်အခြေအနေ.စက်မောင်း)) {
                နောက်တစ်ခုအချက်အလက်တစ်ခု.အခြေအနေသတ်မှတ်(လုပ်ငန်းစဉ်အခြေအနေ.စက်မောင်း);
                အသင့်တန်းစီရာ.offer(နောက်တစ်ခုအချက်အလက်တစ်ခု);
                return နောက်တစ်ခုအချက်အလက်တစ်ခု;
            }
        }
        return null;
    }

    public int သားလုပ်ငန်းစဉ်စောင့်(လုပ်ငန်းစဉ် မိဘတန်ဖိုး, int သားသမီးသတ်မှတ်နံပါတ်, boolean ပိတ်ဆို့မစောင့်) {
        for (လုပ်ငန်းစဉ် အဆိုပြုချက် : လုပ်ငန်းစဉ်စာရင်း.values()) {
            if (အဆိုပြုချက်.မိဘသတ်မှတ်နံပါတ်() != မိဘတန်ဖိုး.သတ်မှတ်နံပါတ်တန်ဖိုး()) {
                continue;
            }
            if (သားသမီးသတ်မှတ်နံပါတ် > 0 && အဆိုပြုချက်.သတ်မှတ်နံပါတ်တန်ဖိုး() != သားသမီးသတ်မှတ်နံပါတ်) {
                continue;
            }
            if (အဆိုပြုချက်.အခြေအနေတန်ဖိုး() == လုပ်ငန်းစဉ်အခြေအနေ.ထွက်ပရိုဂရမ်) {
                int ရလဒ် = (အဆိုပြုချက်.ထွက်ကုဒ်() & 0xff) << 8;
                လုပ်ငန်းစဉ်စာရင်း.remove(Integer.valueOf(အဆိုပြုချက်.သတ်မှတ်နံပါတ်တန်ဖိုး()));
                return ရလဒ်;
            }
            return ပိတ်ဆို့မစောင့် ? 0 : -11;
        }
        return -10;
    }

    public လုပ်ငန်းစဉ် လုပ်ငန်းစဉ်ရှာ(int သတ်မှတ်နံပါတ်တန်ဖိုး) {
        return လုပ်ငန်းစဉ်စာရင်း.get(Integer.valueOf(သတ်မှတ်နံပါတ်တန်ဖိုး));
    }

    private int သတ်မှတ်နံပါတ်ခွဲဝေ() {
        return နောက်တစ်ခုသတ်မှတ်နံပါတ်++;
    }
}
