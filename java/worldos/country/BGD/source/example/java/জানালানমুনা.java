import বাংলা.নিজ.উইন্ডো;
import বাংলা.নিজ.লেবেল;
import বাংলা.নিজ.পাঠ্য_ক্ষেত্র;
import বাংলা.নিজ.বোতাম;
import বাংলা.নিজ.ঘটনা_সারিবদ্ধ;
import বাংলা.নিজ.নির্গম;
import বাংলা.নিজ.실행할일;
import বাংলা.নিজ.동작받이;
import বাংলা.নিজ.동작알림;

/** নিজ 커널의 Swing উইন্ডো: বাংলা 입력 → বোতাম → স্বনিবন্ধ_eb81d7d9 পাঠ রিফ্রেশ. */
public class জানালানমুনা implements 실행할일, 동작받이 {
    private উইন্ডো 인사창;
    private পাঠ্য_ক্ষেত্র নাম_ক্ষেত্র;
    private লেবেল 인사말;
    private int 인사횟수;

    public void খোলা_উইন্ডো() {
        인사창 = new উইন্ডো("বাংলা Swing", 460, 300);
        인사창.যোগ_করা_উপাদান(new লেবেল("নমস্কার", 20, 20, 420, 28));
        নাম_ক্ষেত্র = new পাঠ্য_ক্ষেত্র("বাংলা", 20, 64, 420, 30);
        인사말 = new লেবেল("নমস্কার", 20, 152, 420, 28);
        인사창.যোগ_করা_উপাদান(নাম_ক্ষেত্র);
        인사창.যোগ_করা_উপাদান(new বোতাম("인사하기", 20, 108, 180, 32, this));
        인사창.যোগ_করা_উপাদান(인사말);
        인사창.যোগ_করা_উপাদান(new লেবেল("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.শো_উইন্ডো();
        নির্গম.লেখা_লাইন("GUI 예제 প্রস্তুত_করুন: জানালানমুনা");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.লেখা_পাঠ("নমস্কার, " + নাম_ক্ষেত্র.글읽기() + "님! (" + 인사횟수 + ")");
        নির্গম.লেখা_লাইন("GUI 인사: " + 인사말.글읽기());
    }

    public void চালানো() { খোলা_উইন্ডো(); }
    public void 동작받기(동작알림 알림) {
        নির্গম.লেখা_লাইন("কাজ 알림: " + 알림.আদেশ_পাঠ());
        인사하기();
    }
    public static void চালনা() {
        ঘটনা_সারিবদ্ধ.나중에실행(new জানালানমুনা());
    }
}
