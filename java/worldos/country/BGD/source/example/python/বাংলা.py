"""নিজ 커널의 নথির_নাম·통신·화면 호출과 বাংলা ব্যতিক্রম. 표준 이름은 이 연결부에서만 쓴다."""
import jkoros as অপারেটিং_সিস্টেম
import sys as সাধারণ_ভাষা_রানটাইম

def নির্গম(*মান, বিভাজক=" ", 끝="\n", **기존인수):
    # 기존 print의 sep/end 인수도 연결부에서 호환한다.
    if "sep" not in 기존인수: 기존인수["sep"] = বিভাজক
    if "end" not in 기존인수: 기존인수["end"] = 끝
    print(*মান, **기존인수)

পূর্ণসংখ্যা = int
명령인수 = সাধারণ_ভাষা_রানটাইম.argv
다시시도오류 = 11

class সিস্টেম_ত্রুটি(OSError):
    def __init__(자신, সূচি, 설명="অপারেটিং_সিস্টেম 작업에 실패했습니다."):
        super().__init__(সূচি, 설명)
        자신.সূচি = সূচি
        자신.설명 = 설명

def 운영호출(ফাংশন_মান, *আর্গুমেন্ট_তালিকা):
    try:
        return ফাংশন_মান(*আর্গুমেন্ট_তালিকা)
    except OSError as ত্রুটি:
        সূচি = ত্রুটি.args[0] if ত্রুটি.args else 0
        raise সিস্টেম_ত্রুটি(সূচি)

def 글부호화(পাঠ):
    return পাঠ.encode("utf-8")

def 글해독(ডাটা):
    return ডাটা.decode("utf-8")

def 파일읽기(নাম):
    return 운영호출(অপারেটিং_সিস্টেম.read, নাম)

def লেখা_ফাইল(নাম, ডাটা):
    return 운영호출(অপারেটিং_সিস্টেম.write, নাম, ডাটা)

def সরানো_ফাইল(নাম):
    return 운영호출(অপারেটিং_সিস্টেম.remove, নাম)

def 전문통신열기(পোর্ট_নম্বর):
    return 운영호출(অপারেটিং_সিস্টেম.udp_open, পোর্ট_নম্বর)

def 전문보내기(종단, পোর্ট_নম্বর, ডাটা):
    return 운영호출(অপারেটিং_সিস্টেম.udp_send, 종단, পোর্ট_নম্বর, ডাটা)

def 바깥전문보내기(종단, ইমেইল, পোর্ট_নম্বর, ডাটা):
    return 운영호출(অপারেটিং_সিস্টেম.udp_sendto, 종단, ইমেইল, পোর্ট_নম্বর, ডাটা)

def 전문받기(종단):
    return 운영호출(অপারেটিং_সিস্টেম.udp_recv, 종단)

def বন্ধ_নেটওয়ার্ক(종단):
    return 운영호출(অপারেটিং_সিস্টেম.udp_close, 종단)

def 네모그리기(*আর্গুমেন্ট_তালিকা):
    return 운영호출(অপারেটিং_সিস্টেম.rect, *আর্গুমেন্ট_তালিকা)

def 화면크기():
    return 운영호출(অপারেটিং_সিস্টেম.screen_size)

