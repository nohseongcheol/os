#!/usr/bin/env python3
"""ঘোষণা 고유번호와 UTF-8 বাইট_মান 위치로 নিজ C 이름을 옮기는 일회성 이행 সরঞ্জামগুলি.

외부 구조체의 멤버, স্ট্রিং_মান, C 표준 ফাংশন_মান, 이식 규약은 보존한다.
입력은 পরিবর্তন_করা_মান 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

প্রকল্প_মূল = Path(__file__).resolve().parents[1]

def কার্যকর_করুন_আদেশ():
    분석 = json.loads((প্রকল্প_মূল/'build/한국어화/시언어분석.json').read_text())
    if 분석['ত্রুটি']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    নাম_সারণি = json.loads((প্রকল্প_মূল/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((প্রকল্প_মূল/'명명/규격이름.json').read_text()))
    ঘোষণা_সারণি = 분석['ঘোষণা']
    바꿀선언 = {고유:নাম_সারণি[ভুক্তি_মান['নাম']] for 고유,ভুক্তি_মান in ঘোষণা_সারণি.items()
                if ভুক্তি_মান['নাম'] in নাম_সারণি and ভুক্তি_মান['নাম'] not in 규격}
    সংযোগ_সারণি = {ভুক্তি_মান['নাম']:নাম_সারণি[ভুক্তি_মান['নাম']] for ভুক্তি_মান in ঘোষণা_সারণি.values()
              if ভুক্তি_মান.get('সংযোগ_স্থাপনা')==4 and ভুক্তি_মান['종류'] in (8,9)
              and ভুক্তি_মান['নাম'] in নাম_সারণি and ভুক্তি_মান['নাম'] not in 규격}
    # সৃষ্টি_করুন AOT C·어셈블리·공개 SDK가 공유하는 바이너리 সংযোগ_স্থাপনা 이름만 유지한다.
    머리 = ['/* বাংলা উত্স_ট্রী 이름과 기존 মেশিন সংযোগ_স্থাপনা কাজ_মান. 자동 সৃষ্টি_করুন: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(সংযোগ_সারণি.items())]
    머리 += ['#endif','']
    (প্রকল্প_মূল/'명명/기계연결이름.h').write_text('\n'.join(머리))
    পরিবর্তনগুলো_তালিকা = defaultdict(dict)
    for নথির_নাম,অফসেট_মান,নাম,고유 in 분석['প্রসঙ্গ']:
        if 고유 in 바꿀선언:
            পরিবর্তনগুলো_তালিকা[নথির_নাম][অফসেট_মান] = (নাম,바꿀선언[고유])
    লগ_সারি = ['নথির_নাম\t원래바이트위치\t이전이름\t한국어이름']
    অগ্রাহ্য_করা_মান = []
    for নথির_নাম,পরিবর্তন_করা_মান in পরিবর্তনগুলো_তালিকা.items():
        পথ_2 = Path(নথির_নাম); 원본 = পথ_2.read_bytes(); ডাটা = 원본
        for অফসেট_মান,(옛이름,새이름) in sorted(পরিবর্তন_করা_মান.items(),reverse=True):
            끝 = অফসেট_মান+len(옛이름.encode())
            if 원본[অফসেট_মান:끝] != 옛이름.encode():
                অগ্রাহ্য_করা_মান.append((str(পথ_2.relative_to(প্রকল্প_মূল)),অফসেট_মান,옛이름));continue
            ডাটা = ডাটা[:অফসেট_মান]+새이름.encode()+ডাটা[끝:]
            লগ_সারি.append('{}\t{}\t{}\t{}'.format(পথ_2.relative_to(প্রকল্প_মূল),অফসেট_মান,옛이름,새이름))
        পথ_2.write_bytes(ডাটা)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ম্যাক্রো_মান = {ভুক্তি_মান['নাম']:নাম_সারণি[ভুক্তি_মান['নাম']] for ভুক্তি_মান in ঘোষণা_সারণি.values()
              if ভুক্তি_মান['종류']==501 and ভুক্তি_মান['নাম'] in নাম_সারণি and ভুক্তি_মান['নাম'] not in 규격}
    for পথ_2 in sorted({Path(ভুক্তি_মান['নথির_নাম']) for ভুক্তি_মান in ঘোষণা_সারণি.values()}):
        লাইন_তালিকা = পথ_2.read_text().splitlines(True); 이어짐 = False
        for সূচি,নিবেশের_পঙ্_ক্তি in enumerate(লাইন_তালিকা):
            전처리 = 이어짐 or bool(re.match(r'\s*#',নিবেশের_পঙ্_ক্তি))
            이어짐 = 전처리 and নিবেশের_পঙ্_ক্তি.rstrip().endswith('\\')
            if 전처리:
                লুকআপ_সারণি = নাম_সারণি if re.match(r'\s*#\s*define\b',নিবেশের_পঙ্_ক্তি) or 이어짐 else ম্যাক্রো_মান
                লাইন_তালিকা[সূচি] = 낱말.sub(lambda 맞음: লুকআপ_সারণি.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],নিবেশের_পঙ্_ক্তি)
        পথ_2.write_text(''.join(লাইন_তালিকা))
    # 각 নিজ অনুবাদ_করুন_উত্স 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for পথ_2 in sorted({Path(ভুক্তি_মান['নথির_নাম']) for ভুক্তি_মান in ঘোষণা_সারণি.values()}):
        if পথ_2.suffix not in ('.c','.cpp'):continue
        পিয়ার_মান = '../' * len(পথ_2.relative_to(প্রকল্প_মূল).parts[:-1]) + '명명/기계연결이름.h'
        পথ_2.write_text('#include "'+পিয়ার_মান+'"\n'+পথ_2.read_text())
    (প্রকল্প_মূল/'명명/시언어이름대응.tsv').write_text('\n'.join(লগ_সারি)+'\n')
    (প্রকল্প_মূল/'build/한국어화/전처리참조.json').write_text(json.dumps(অগ্রাহ্য_করা_মান,ensure_ascii=False,indent=2)+'\n')
    print('পরিবর্তন_করা_মান',len(লগ_সারি)-1,'전처리 재검토',len(অগ্রাহ্য_করা_মান),'মেশিন সংযোগ_স্থাপনা',len(সংযোগ_সারণি))

if __name__=='__main__': কার্যকর_করুন_আদেশ()
