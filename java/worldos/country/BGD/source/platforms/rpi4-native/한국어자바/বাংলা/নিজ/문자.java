    public static String লেপন_করা_পাঠ(String সম্মুখ_মান, String ফিরে_যান_মান) { return সম্মুখ_মান.concat(ফিরে_যান_মান); }
    public static String কাট_মান(String পাঠ, int চালনা, int 끝) { return পাঠ.substring(চালনা, 끝); }
