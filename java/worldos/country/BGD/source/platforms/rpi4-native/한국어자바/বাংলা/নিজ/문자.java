    public static String লেখা_পূর্ণসংখ্যা_মান(int 수) { return Integer.toString(수); }
    public static int 코드포인트수(String পাঠ) {
        int 수 = 0;
        for (int লুপ_সূচি = 0; লুপ_সূচি < পাঠ.length(); লুপ_সূচি++, 수++) {
            int অক্ষর_কোড = পাঠ.charAt(লুপ_সূচি);
            if (অক্ষর_কোড >= 0xd800 && অক্ষর_কোড <= 0xdbff && লুপ_সূচি + 1 < পাঠ.length() && পাঠ.charAt(লুপ_সূচি + 1) >= 0xdc00 && পাঠ.charAt(লুপ_সূচি + 1) <= 0xdfff) লুপ_সূচি++;
        }
        return 수;
    }
    public static byte[] 부호화(String পাঠ) {
        byte[] 임시 = new byte[পাঠ.length() * 3]; int 쓴수 = 0;
        for (int লুপ_সূচি = 0; লুপ_সূচি < পাঠ.length(); লুপ_সূচি++) {
            int অক্ষর_কোড = পাঠ.charAt(লুপ_সূচি);
            if (অক্ষর_কোড >= 0xd800 && অক্ষর_কোড <= 0xdbff && লুপ_সূচি + 1 < পাঠ.length() && পাঠ.charAt(লুপ_সূচি + 1) >= 0xdc00 && পাঠ.charAt(লুপ_সূচি + 1) <= 0xdfff) অক্ষর_কোড = 0x10000 + ((অক্ষর_কোড - 0xd800) << 10) + পাঠ.charAt(++লুপ_সূচি) - 0xdc00;
            else if (অক্ষর_কোড >= 0xd800 && অক্ষর_কোড <= 0xdfff) অক্ষর_কোড = '?';
            if (অক্ষর_কোড < 128) 임시[쓴수++] = (byte)অক্ষর_কোড;
            else if (অক্ষর_কোড < 2048) { 임시[쓴수++] = (byte)(192 | অক্ষর_কোড >> 6); 임시[쓴수++] = (byte)(128 | অক্ষর_কোড & 63); }
            else if (অক্ষর_কোড < 65536) { 임시[쓴수++] = (byte)(224 | অক্ষর_কোড >> 12); 임시[쓴수++] = (byte)(128 | অক্ষর_কোড >> 6 & 63); 임시[쓴수++] = (byte)(128 | অক্ষর_কোড & 63); }
            else { 임시[쓴수++] = (byte)(240 | অক্ষর_কোড >> 18); 임시[쓴수++] = (byte)(128 | অক্ষর_কোড >> 12 & 63); 임시[쓴수++] = (byte)(128 | অক্ষর_কোড >> 6 & 63); 임시[쓴수++] = (byte)(128 | অক্ষর_কোড & 63); }
        }
        byte[] পরিমাপ = new byte[쓴수]; System.arraycopy(임시, 0, পরিমাপ, 0, 쓴수); return পরিমাপ;
    }
    /** 잘못된 UTF-8은 잘못된인수예외으로 거부한다. */
    public static String ডিক্রিপ্ট_ডাটা(byte[] বাইট_মান) {
        StringBuilder পরিমাপ = new StringBuilder();
        for (int লুপ_সূচি = 0; লুপ_সূচি < বাইট_মান.length;) {
            int অক্ষর_কোড = বাইট_মান[লুপ_সূচি++] & 255, 수 = অক্ষর_কোড < 128 ? 0 : অক্ষর_কোড >= 194 && অক্ষর_কোড < 224 ? 1 : অক্ষর_কোড >= 224 && অক্ষর_কোড < 240 ? 2 : অক্ষর_কোড >= 240 && অক্ষর_কোড <= 244 ? 3 : -1;
            if (수 < 0 || বাইট_মান.length - লুপ_সূচি < 수) throw new অবৈধ_যুক্তি_ব্যতিক্রম("잘못된 UTF-8");
            int 최소 = 수 == 1 ? 128 : 수 == 2 ? 2048 : 수 == 3 ? 65536 : 0;
            if (수 > 0) অক্ষর_কোড &= (1 << (6 - 수)) - 1;
            for (int অন্তর_জোড়_পদ = 0; অন্তর_জোড়_পদ < 수; অন্তর_জোড়_পদ++) { int ফিরে_যান_মান = বাইট_মান[লুপ_সূচি++] & 255; if ((ফিরে_যান_মান & 192) != 128) throw new অবৈধ_যুক্তি_ব্যতিক্রম("잘못된 UTF-8"); অক্ষর_কোড = অক্ষর_কোড << 6 | ফিরে_যান_মান & 63; }
            if (অক্ষর_কোড < 최소 || অক্ষর_কোড > 0x10ffff || অক্ষর_কোড >= 0xd800 && অক্ষর_কোড <= 0xdfff) throw new অবৈধ_যুক্তি_ব্যতিক্রম("잘못된 UTF-8");
            if (অক্ষর_কোড < 65536) পরিমাপ.append((char)অক্ষর_কোড);
            else { অক্ষর_কোড -= 65536; পরিমাপ.append((char)(0xd800 | অক্ষর_কোড >> 10)); পরিমাপ.append((char)(0xdc00 | অক্ষর_কোড & 1023)); }
        }
        return পরিমাপ.toString();
    }
