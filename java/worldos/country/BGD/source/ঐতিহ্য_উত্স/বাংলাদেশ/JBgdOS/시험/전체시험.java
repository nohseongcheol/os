    private static void 파일과과정시험(কারনেল কারনেল_মান) {
        byte[] সামগ্রি_মান = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        কারনেল_মান.ফাইল_পদ্ধতি().파일추가("시험", সামগ্রি_মান);
        প্রসেসর_মান 부모 = কারনেল_মান.첫과정();
        체계호출 호출 = কারনেল_মান.체계호출();
        int 서술자 = 호출.খুলুন(부모, "/시험", 체계호출.কেবল_পাঠযোগ্য_নিশান);
        যাচাই_করা(서술자 >= 3, "নথির_নাম খুলুন");

        byte[] 받을곳 = new byte[সামগ্রি_মান.length];
        যাচাই_করা(호출.পড়া(부모, 서술자, 받을곳, 받을곳.length) == সামগ্রি_মান.length, "নথির_নাম পড়া");
        যাচাই_করা(Arrays.equals(সামগ্রি_মান, 받을곳), "নথির_নাম সামগ্রি_মান");
        যাচাই_করা(호출.অপসারণ_করা_পদ(부모, 서술자, 0, 체계호출.দেখুন_শুরু) == 0, "নথির_নাম অবস্থান অপসারণ_করা_মান");

        int 복제서술자 = 호출.서술자복제(부모, 서술자);
        যাচাই_করা(복제서술자 >= 0, "서술자 복제");
        প্রসেসর_মান শিশু_মান = 호출.과정복제(부모);
        যাচাই_করা(শিশু_মান.সনাক্তকারী_মান() != 부모.সনাক্তকারী_মান(), "প্রসেসর_মান সনাক্তকারী_মান 분리");
        যাচাই_করা(শিশু_মান.부모식별자() == 부모.সনাক্তকারী_মান(), "부모 প্রসেসর_মান সনাক্তকারী_মান");
        যাচাই_করা(호출.বন্ধ_করুন(শিশু_মান, 서술자) == 0 && 부모.파일서술자().তথ্য_প্রযুক্তি_খোলা(서술자), "শিশু_মান বন্ধ_করুন 격리");

        int 이전끝 = 호출.프로그램끝늘리기(부모, 8192);
        যাচাই_করা(이전끝 == 0x06000000, "অ্যাপ_f5044b9b 끝 늘리기");
        যাচাই_করা(부모.অ্যাপ_বিরতি() == 0x06002000, "অ্যাপ_f5044b9b 끝 반영");
        যাচাই_করা(শিশু_মান.অ্যাপ_বিরতি() == 0x06000000, "과정별 অ্যাপ_f5044b9b 끝 격리");

        শিশু_মান.প্রস্থান_অ্যাপ(7);
        যাচাই_করা(호출.자식기다리기(부모, শিশু_মান.সনাক্তকারী_মান(), false) == (7 << 8), "শিশু_মান প্রস্থান_অ্যাপ 기다리기");
        যাচাই_করা(호출.접근가능("시험", 1) == -13, "কার্যকর_করুন_আদেশ অনুমতি_মান প্রত্যাখ্যান_মান");
        যাচাই_করা(호출.ব্যবহারকারী_সনাক্তকারী() == 0 && 호출.দল_সনাক্তকারী() == 0, "사용자와 무리 সনাক্তকারী_মান");
        যাচাই_করা("/".equals(호출.현재작업목록(2)) && 호출.সুইচ_কার্যতালিকা("/") == 0, "현재 작업 ভুক্তি_তালিকা");
        যাচাই_করা(호출.তথ্য_প্রযুক্তি_টার্মিনাল(부모, 1), "표준 নির্গম 단말");
        যাচাই_করা("JBgdOS".equals(호출.체계정보().সিস্টেম_নাম()), "অপারেটিং_সিস্টেম_মান সিসটেম_তথ্য");
    }

