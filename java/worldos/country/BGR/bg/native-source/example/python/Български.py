class система_грешка(OSError):
    def __init__(자신, индекс, 설명="операционна_система 작업에 실패했습니다."):
        super().__init__(индекс, 설명)
        자신.индекс = индекс
        자신.설명 = 설명

def 운영호출(функция_стойност, *Параметри):
    try:
        return функция_стойност(*Параметри)
    except OSError as ГРЕШКА:
        индекс = ГРЕШКА.args[0] if ГРЕШКА.args else 0
        raise система_грешка(индекс)

