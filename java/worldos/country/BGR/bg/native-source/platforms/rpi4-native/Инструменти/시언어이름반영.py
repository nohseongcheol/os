#!/usr/bin/env python3
"""декларация 고유번호와 UTF-8 байт_стойност 위치로 자체 C 이름을 옮기는 일회성 이행 Инструменти.

външен_стойност 구조체의 멤버, низ_стойност, C 표준 функция_стойност, 이식 규약은 보존한다.
입력은 променям_стойност 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

проект_корен = Path(__file__).resolve().parents[1]

def изпълнявам_команда():
    Анализ_стойност = json.loads((проект_корен/'build/한국어화/시언어분석.json').read_text())
    if Анализ_стойност['ГРЕШКА']: raise SystemExit('Анализ_стойност 오류를 먼저 해결해야 합니다.')
    препратка_към_клетка_таблица = json.loads((проект_корен/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((проект_корен/'명명/규격이름.json').read_text()))
    декларация_таблица = Анализ_стойност['декларация']
    바꿀선언 = {고유:препратка_към_клетка_таблица[запис_стойност['Име']] for 고유,запис_стойност in декларация_таблица.items()
                if запис_стойност['Име'] in препратка_към_клетка_таблица and запис_стойност['Име'] not in 규격}
    връзка_таблица = {запис_стойност['Име']:препратка_към_клетка_таблица[запис_стойност['Име']] for запис_стойност in декларация_таблица.values()
              if запис_стойност.get('Свързване')==4 and запис_стойност['종류'] in (8,9)
              and запис_стойност['Име'] in препратка_към_клетка_таблица and запис_стойност['Име'] not in 규격}
    # генерирам AOT C·어셈블리·공개 SDK가 공유하는 바이너리 Свързване 이름만 유지한다.
    머리 = ['/* Български източник_дърво 이름과 기존 машина Свързване случай_стойност. 자동 генерирам: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(връзка_таблица.items())]
    머리 += ['#endif','']
    (проект_корен/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Промени_Списък = defaultdict(dict)
    for Файл,Изместване_стойност,Име,고유 in Анализ_стойност['препратка']:
        if 고유 in 바꿀선언:
            Промени_Списък[Файл][Изместване_стойност] = (Име,바꿀선언[고유])
    регистрирам_запис = ['Файл\t원래바이트위치\t이전이름\t한국어이름']
    игнорирай_стойност = []
    for Файл,променям_стойност in Промени_Списък.items():
        ПЪТ = Path(Файл); 원본 = ПЪТ.read_bytes(); данни = 원본
        for Изместване_стойност,(옛이름,새이름) in sorted(променям_стойност.items(),reverse=True):
            끝 = Изместване_стойност+len(옛이름.encode())
            if 원본[Изместване_стойност:끝] != 옛이름.encode():
                игнорирай_стойност.append((str(ПЪТ.relative_to(проект_корен)),Изместване_стойност,옛이름));continue
            данни = данни[:Изместване_стойност]+새이름.encode()+данни[끝:]
            регистрирам_запис.append('{}\t{}\t{}\t{}'.format(ПЪТ.relative_to(проект_корен),Изместване_стойност,옛이름,새이름))
        ПЪТ.write_bytes(данни)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макрос_стойност = {запис_стойност['Име']:препратка_към_клетка_таблица[запис_стойност['Име']] for запис_стойност in декларация_таблица.values()
              if запис_стойност['종류']==501 and запис_стойност['Име'] in препратка_към_клетка_таблица and запис_стойност['Име'] not in 규격}
    for ПЪТ in sorted({Path(запис_стойност['Файл']) for запис_стойност in декларация_таблица.values()}):
        ред_Списък_701073a1 = ПЪТ.read_text().splitlines(True); 이어짐 = False
        for индекс,ред in enumerate(ред_Списък_701073a1):
            전처리 = 이어짐 or bool(re.match(r'\s*#',ред))
            이어짐 = 전처리 and ред.rstrip().endswith('\\')
            if 전처리:
                таблица_за_справка = препратка_към_клетка_таблица if re.match(r'\s*#\s*define\b',ред) or 이어짐 else макрос_стойност
                ред_Списък_701073a1[индекс] = 낱말.sub(lambda 맞음: таблица_за_справка.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],ред)
        ПЪТ.write_text(''.join(ред_Списък_701073a1))
    # 각 자체 Превод_източник 단위에만 연결표를 넣는다. външен_стойност 배포본에는 전파하지 않는다.
    for ПЪТ in sorted({Path(запис_стойност['Файл']) for запис_стойност in декларация_таблица.values()}):
        if ПЪТ.suffix not in ('.c','.cpp'):continue
        крайно_устройство_стойност = '../' * len(ПЪТ.relative_to(проект_корен).parts[:-1]) + '명명/기계연결이름.h'
        ПЪТ.write_text('#include "'+крайно_устройство_стойност+'"\n'+ПЪТ.read_text())
    (проект_корен/'명명/시언어이름대응.tsv').write_text('\n'.join(регистрирам_запис)+'\n')
    (проект_корен/'build/한국어화/전처리참조.json').write_text(json.dumps(игнорирай_стойност,ensure_ascii=False,indent=2)+'\n')
    print('променям_стойност',len(регистрирам_запис)-1,'전처리 재검토',len(игнорирай_стойност),'машина Свързване',len(връзка_таблица))

if __name__=='__main__': изпълнявам_команда()
