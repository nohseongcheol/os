public final class 문자 {
    public static int 바이트수(byte[] данни) { return данни.length; }
    private 문자() {}
    public static int 길이(String Текст) { return Текст.length(); }
    public static boolean 같음(String предна_стойност, String НАЗАД_стойност) { return предна_стойност == null ? НАЗАД_стойност == null : предна_стойност.equals(НАЗАД_стойност); }
    public static String поставям_Текст(String предна_стойност, String НАЗАД_стойност) { return предна_стойност.concat(НАЗАД_стойност); }
    public static String изрязвам_стойност(String Текст, int Стартиране, int 끝) { return Текст.substring(Стартиране, 끝); }
    public static int анализирам_цяло_число(String Текст) { try { return Integer.parseInt(Текст); } catch (NumberFormatException ГРЕШКА) { throw new 숫자형식예외("숫자의 형식이나 범위를 확인하십시오."); } }
    public static String записване_цяло_число_стойност(int 수) { return Integer.toString(수); }
    public static int 코드포인트수(String Текст) {
        int 수 = 0;
        for (int цикъл_индекс = 0; цикъл_индекс < Текст.length(); цикъл_индекс++, 수++) {
            int знаков_код = Текст.charAt(цикъл_индекс);
            if (знаков_код >= 0xd800 && знаков_код <= 0xdbff && цикъл_индекс + 1 < Текст.length() && Текст.charAt(цикъл_индекс + 1) >= 0xdc00 && Текст.charAt(цикъл_индекс + 1) <= 0xdfff) цикъл_индекс++;
        }
        return 수;
    }
    public static byte[] кодирам(String Текст) {
        byte[] 임시 = new byte[Текст.length() * 3]; int 쓴수 = 0;
        for (int цикъл_индекс = 0; цикъл_индекс < Текст.length(); цикъл_индекс++) {
            int знаков_код = Текст.charAt(цикъл_индекс);
            if (знаков_код >= 0xd800 && знаков_код <= 0xdbff && цикъл_индекс + 1 < Текст.length() && Текст.charAt(цикъл_индекс + 1) >= 0xdc00 && Текст.charAt(цикъл_индекс + 1) <= 0xdfff) знаков_код = 0x10000 + ((знаков_код - 0xd800) << 10) + Текст.charAt(++цикъл_индекс) - 0xdc00;
            else if (знаков_код >= 0xd800 && знаков_код <= 0xdfff) знаков_код = '?';
            if (знаков_код < 128) 임시[쓴수++] = (byte)знаков_код;
            else if (знаков_код < 2048) { 임시[쓴수++] = (byte)(192 | знаков_код >> 6); 임시[쓴수++] = (byte)(128 | знаков_код & 63); }
            else if (знаков_код < 65536) { 임시[쓴수++] = (byte)(224 | знаков_код >> 12); 임시[쓴수++] = (byte)(128 | знаков_код >> 6 & 63); 임시[쓴수++] = (byte)(128 | знаков_код & 63); }
            else { 임시[쓴수++] = (byte)(240 | знаков_код >> 18); 임시[쓴수++] = (byte)(128 | знаков_код >> 12 & 63); 임시[쓴수++] = (byte)(128 | знаков_код >> 6 & 63); 임시[쓴수++] = (byte)(128 | знаков_код & 63); }
        }
        byte[] РЕЗУЛТАТ = new byte[쓴수]; System.arraycopy(임시, 0, РЕЗУЛТАТ, 0, 쓴수); return РЕЗУЛТАТ;
    }
    /** 잘못된 UTF-8은 잘못된인수예외으로 거부한다. */
    public static String дешифрирам_данни(byte[] байт_стойност) {
        StringBuilder РЕЗУЛТАТ = new StringBuilder();
        for (int цикъл_индекс = 0; цикъл_индекс < байт_стойност.length;) {
            int знаков_код = байт_стойност[цикъл_индекс++] & 255, 수 = знаков_код < 128 ? 0 : знаков_код >= 194 && знаков_код < 224 ? 1 : знаков_код >= 224 && знаков_код < 240 ? 2 : знаков_код >= 240 && знаков_код <= 244 ? 3 : -1;
            if (수 < 0 || байт_стойност.length - цикъл_индекс < 수) throw new невалиден_аргумент_изключение("잘못된 UTF-8");
            int 최소 = 수 == 1 ? 128 : 수 == 2 ? 2048 : 수 == 3 ? 65536 : 0;
            if (수 > 0) знаков_код &= (1 << (6 - 수)) - 1;
            for (int вътрешно_позиция = 0; вътрешно_позиция < 수; вътрешно_позиция++) { int НАЗАД_стойност = байт_стойност[цикъл_индекс++] & 255; if ((НАЗАД_стойност & 192) != 128) throw new невалиден_аргумент_изключение("잘못된 UTF-8"); знаков_код = знаков_код << 6 | НАЗАД_стойност & 63; }
            if (знаков_код < 최소 || знаков_код > 0x10ffff || знаков_код >= 0xd800 && знаков_код <= 0xdfff) throw new невалиден_аргумент_изключение("잘못된 UTF-8");
            if (знаков_код < 65536) РЕЗУЛТАТ.append((char)знаков_код);
            else { знаков_код -= 65536; РЕЗУЛТАТ.append((char)(0xd800 | знаков_код >> 10)); РЕЗУЛТАТ.append((char)(0xdc00 | знаков_код & 1023)); }
        }
        return РЕЗУЛТАТ.toString();
    }
}
