package Български.자체;
/** 화면(畫面): 부팅 때 선택한 크기의 자체 ядро_стойност RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int стойност = ядро_стойност.화면너비(); if (стойност < 0) throw new Състояние_изключение("프레임버퍼 없음"); return стойност; }
    public static int 높이() { int стойност = ядро_стойност.화면높이(); if (стойност < 0) throw new Състояние_изключение("프레임버퍼 없음"); return стойност; }
    public static void правоъгълник(int 가로, int вертикал_позиция, int 폭, int 높이, int 색) {
        if (가로 < 0 || вертикал_позиция < 0 || 폭 < 0 || 높이 < 0 || 가로 > 너비() || вертикал_позиция > 높이() || 폭 > 너비() - 가로 || 높이 > 높이() - вертикал_позиция) throw new невалиден_аргумент_изключение("화면 клип");
        if (ядро_стойност.правоъгълник(가로, вертикал_позиция, 폭, 높이, 색) < 0) throw new Състояние_изключение("프레임버퍼 없음");
    }
    public static void изтривам_запис(int 색) { правоъгълник(0, 0, 너비(), 높이(), 색); }
    public static void 기다리기() { if (ядро_стойност.그림대기() < 0) throw new Състояние_изключение("대화형 입력 필요"); }
}
