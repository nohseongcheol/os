import Български.자체.Прозорец;
import Български.자체.Етикет;
import Български.자체.текстово_поле;
import Български.자체.бутон;
import Български.자체.събитие_опашка;
import Български.자체.Изход;
import Български.자체.실행할일;
import Български.자체.동작받이;
import Български.자체.проект_предупреждение;

/** 자체 커널의 Swing Прозорец: Български 입력 → бутон → 안내 Текст обновявам. */
public class 창예제 implements 실행할일, 동작받이 {
    private Прозорец 인사창;
    private текстово_поле препратка_към_клетка_поле;
    private Етикет 인사말;
    private int 인사횟수;

    public void отварям_прозорец() {
        인사창 = new Прозорец("Български Swing", 460, 300);
        인사창.добавям_елемент(new Етикет("Български", 20, 20, 420, 28));
        препратка_към_клетка_поле = new текстово_поле("Български", 20, 64, 420, 30);
        인사말 = new Етикет("Български", 20, 152, 420, 28);
        인사창.добавям_елемент(препратка_към_клетка_поле);
        인사창.добавям_елемент(new бутон("인사하기", 20, 108, 180, 32, this));
        인사창.добавям_елемент(인사말);
        인사창.добавям_елемент(new Етикет("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.показвам_прозорец();
        Изход.записване_ред("GUI 예제 Подготвяне: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.записване_Текст("Български, " + препратка_към_клетка_поле.글읽기() + "님! (" + 인사횟수 + ")");
        Изход.записване_ред("GUI 인사: " + 인사말.글읽기());
    }

    public void Изпълнение() { отварям_прозорец(); }
    public void получавам_проект(проект_предупреждение предупреждение) {
        Изход.записване_ред("Операция предупреждение: " + предупреждение.команда_Текст());
        인사하기();
    }
    public static void Стартиране() {
        събитие_опашка.나중에실행(new 창예제());
    }
}
