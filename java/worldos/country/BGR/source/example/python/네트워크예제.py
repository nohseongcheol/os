from Български import Изход, отварям_дейтаграма, изпращам_външен_дейтаграма, получавам_дейтаграма, затварям_мрежа, 밀리초
from Български import система_грешка, 다시시도오류, кодирам_Текст, 명령인수, цяло_число
участник = отварям_дейтаграма(0)
try:
    дейтаграма = кодирам_Текст("PYTHON UDP Български")
    изпращам_външен_дейтаграма(участник, "10.0.2.2", цяло_число(명령인수[1]), дейтаграма)
    Стартиране = 밀리초()
    while True:
        try:
            отговор, порт_стойност = получавам_дейтаграма(участник)
            break
        except система_грешка as ГРЕШКА:
            if ГРЕШКА.индекс != 다시시도오류 or 밀리초() - Стартиране >= 700:
                raise
    assert отговор == дейтаграма
    Изход("PYTHON 네트워크 проверявам: UDP Български")
finally:
    затварям_мрежа(участник)
