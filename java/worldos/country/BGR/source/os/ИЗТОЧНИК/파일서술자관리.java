        int РЕЗУЛТАТ = проверявам_адрес(адрес, 길이);
        if (РЕЗУЛТАТ < 0) return РЕЗУЛТАТ;
        if (мрежа_манипулатор[기술] != 0) return -22;
        int мрежов_идентификатор = адрес_32(адрес + 4);
