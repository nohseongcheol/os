import sys
import json
import hashlib
import gc
import jkoros as операционна_система

Списък_път = "/lib/.pip.json"


def 지문(данни):
    return "".join("%02x" % стойност for стойност in hashlib.sha256(данни).digest())


def 목록읽기():
    if операционна_система.path_kind(Списък_път) == 0:
        return {}
    return json.loads(операционна_система.read(Списък_път).decode("utf-8"))


def записване_регистрирам(ПЪТ, данни):
    if операционна_система.write(ПЪТ, данни) != len(данни):
        raise OSError(28)


def проверявам_път(ПЪТ):
    if not isinstance(ПЪТ, str) or not ПЪТ.endswith(".py"):
        raise ValueError("Python 소스만 설치할 수 있습니다.")
    if any(부분 in ("", ".", "..") or 부분.startswith(".") for 부분 in ПЪТ.split("/")):
        raise ValueError("허용하지 않는 пакет ПЪТ")
    if "\\" in ПЪТ or any(ord(знак_стойност) < 32 or ord(знак_стойност) == 127 for знак_стойност in ПЪТ):
        raise ValueError("잘못된 ПЪТ 문자")
    РЕЗУЛТАТ = "/lib/" + ПЪТ
    if len(РЕЗУЛТАТ.encode("utf-8")) > 63 or ПЪТ in ("Български.py", "пакет.py"):
        raise ValueError("пакет 경로가 너무 길거나 стойност_по_подразбиране 라이브러리와 겹칩니다.")
    return РЕЗУЛТАТ


class получавам_поток:
    def __init__(자신, участник):
        자신.участник = участник
        자신.남은자료 = b""
        자신.Стартиране = операционна_система.ticks_ms()

    def 정확히읽기(자신, 길이):
        данни = bytearray()
        while len(данни) < 길이:
            if операционна_система.ticks_ms() - 자신.Стартиране > 90000:
                raise ValueError("пакет 중계 отговор час_стойност 초과")
            if not 자신.남은자료:
                try:
                    자신.남은자료 = операционна_система.tcp_read(자신.участник, 512)
                except OSError as ГРЕШКА:
                    if ГРЕШКА.args[0] != 11:
                        raise
                    операционна_система.sleep_ms(10)
                    continue
                if not 자신.남은자료:
                    raise ValueError("пакет 전송이 중간에 끝났습니다.")
            개수 = min(길이 - len(данни), len(자신.남은자료))
            данни.extend(자신.남은자료[:개수])
            자신.남은자료 = 자신.남은자료[개수:]
            операционна_система.sleep_ms(0)
        return bytes(данни)


def изтеглям(искане, номер_на_порт):
    if len(искане) > 96 or any(знак_стойност not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-=" for знак_стойност in искане):
        raise ValueError("사용법: pip install Име 또는 Име==버전")
    участник = операционна_система.tcp_open()
    try:
        Стартиране = операционна_система.ticks_ms()
        while True:
            try:
                операционна_система.tcp_connect(участник, "10.0.2.2", номер_на_порт)
                break
            except OSError as ГРЕШКА:
                if ГРЕШКА.args[0] not in (11, 115) or операционна_система.ticks_ms() - Стартиране > 5000:
                    raise ValueError("пакет 중계 Свързване отказ_стойност: 호스트에서 --network --pip로 실행하십시오.")
                операционна_система.sleep_ms(10)
        данни = (искане + "\n").encode()
        while данни:
            try:
                개수 = операционна_система.tcp_write(участник, данни)
                if not 개수:
                    raise ValueError("пакет искане прехвърлям_стойност отказ_стойност")
                данни = данни[개수:]
            except OSError as ГРЕШКА:
                if ГРЕШКА.args[0] != 11:
                    raise
                операционна_система.sleep_ms(10)
                if операционна_система.ticks_ms() - Стартиране > 10000:
                    raise ValueError("пакет искане прехвърлям_стойност час_стойност 초과")
        поток_стойност = получавам_поток(участник)
        머리 = поток_стойност.정확히읽기(8)
        if 머리[:4] != b"JKP1":
            raise ValueError("пакет прехвърлям_стойност случай_стойност 불일치")
        길이 = (머리[4] << 24) | (머리[5] << 16) | (머리[6] << 8) | 머리[7]
        if 길이 > 8192:
            raise ValueError("пакет 명세가 너무 큽니다.")
        명세 = json.loads(поток_стойност.정확히읽기(길이).decode())
        if "error" in 명세:
            raise ValueError(명세["error"])
        if not 1 <= len(명세["files"]) <= 16:
            raise ValueError("꾸러미당 източник_дърво 파일은 1~16개여야 합니다.")
        if sum(запис_стойност["size"] for запис_стойност in 명세["files"]) > 65536:
            raise ValueError("пакет източник_дърво 합계는 64 KiB 이하여야 합니다.")
        파일들 = {}
        for запис_стойност in 명세["files"]:
            ПЪТ = проверявам_път(запис_стойност["path"])
            if ПЪТ in 파일들 or not 0 <= запис_стойност["size"] <= 16384:
                raise ValueError("중복 ПЪТ 또는 Файл Размер 초과")
            данни = поток_стойност.정확히읽기(запис_стойност["size"])
            if 지문(данни) != запис_стойност["sha256"]:
                raise ValueError("пакет Файл SHA-256 불일치")
            # 실행하지 않고 в_срок_артикул MicroPython의 문법으로 먼저 검사한다.
            compile(данни.decode("utf-8"), ПЪТ, "exec")
            파일들[ПЪТ] = данни
            gc.collect()
        return 명세, 파일들
    finally:
        операционна_система.udp_close(участник)


def инсталирам_стойност(искане, номер_на_порт):
    print("пакет изтеглям:", искане)
    명세, 파일들 = изтеглям(искане, номер_на_порт)
    запис_Списък = 목록읽기()
    Име = 명세["name"]
    if Име in запис_Списък:
        if запис_Списък[Име]["version"] == 명세["version"]:
            for ПЪТ, 지문값 in запис_Списък[Име]["files"].items():
                if операционна_система.path_kind(ПЪТ) != 1 or 지문(операционна_система.read(ПЪТ)) != 지문값:
                    raise ValueError("설치된 пакет 파일이 달라졌습니다: " + ПЪТ)
            print("이미 설치됨:", Име, 명세["version"])
            return
        raise ValueError("다른 버전이 있습니다. pip uninstall로 제거한 НАЗАД_стойност 설치하십시오.")
    for ПЪТ in 파일들:
        if операционна_система.path_kind(ПЪТ):
            raise ValueError("기존 파일을 덮어쓰지 않습니다: " + ПЪТ)
    запис_Списък[Име] = {"version": 명세["version"], "files": {ПЪТ: 지문(данни) for ПЪТ, данни in 파일들.items()}}
    새목록 = json.dumps(запис_Списък).encode()
    if len(새목록) > 16384:
        raise ValueError("пакет запис_Списък Размер 초과")
    이전목록 = операционна_система.read(Списък_път) if операционна_система.path_kind(Списък_път) else None
    만든파일 = []
    만든폴더 = []
    try:
        for ПЪТ, данни in 파일들.items():
            부분들 = ПЪТ.split("/")
            for 수 in range(2, len(부분들)):
                указател_стойност = "/".join(부분들[:수])
                종류 = операционна_система.path_kind(указател_стойност)
                if 종류 == 0:
                    операционна_система.mkdir(указател_стойност)
                    만든폴더.append(указател_стойност)
                elif 종류 != 2:
                    raise ValueError("указател_стойност 경로에 파일이 있습니다: " + указател_стойност)
            만든파일.append(ПЪТ)
            записване_регистрирам(ПЪТ, данни)
        записване_регистрирам(Списък_път, 새목록)
    except Exception:
        for ПЪТ in 만든파일:
            if операционна_система.path_kind(ПЪТ):
                операционна_система.remove(ПЪТ)
        for указател_стойност in reversed(만든폴더):
            операционна_система.rmdir(указател_стойност)
        if 이전목록 is not None:
            записване_регистрирам(Списък_път, 이전목록)
        elif операционна_система.path_kind(Списък_път):
            операционна_система.remove(Списък_път)
        raise
    print("инсталирам_стойност 완료:", Име, 명세["version"], "→ /lib (RAM)")


def премахвам_запис(Име):
    запис_Списък = 목록읽기()
    if Име not in запис_Списък:
        raise ValueError("설치되지 않은 꾸러미입니다: " + Име)
    for ПЪТ, 지문값 in запис_Списък[Име]["files"].items():
        if операционна_система.path_kind(ПЪТ) != 1 or 지문(операционна_система.read(ПЪТ)) != 지문값:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + ПЪТ)
    for ПЪТ in запис_Списък[Име]["files"]:
        операционна_система.remove(ПЪТ)
    del запис_Списък[Име]
    записване_регистрирам(Списък_път, json.dumps(запис_Списък).encode())
    print("премахвам_запис 완료:", Име)


def Стартиране(Параметри):
    номер_на_порт = 8027
    if len(Параметри) >= 2 and Параметри[-2] == "--port":
        номер_на_порт = int(Параметри[-1])
        Параметри = Параметри[:-2]
    if Параметри == ["list"]:
        for Име, Системна_информация in 목록읽기().items():
            print(Име, Системна_информация["version"])
    elif len(Параметри) == 2 and Параметри[0] == "install":
        инсталирам_стойност(Параметри[1], номер_на_порт)
    elif len(Параметри) == 2 and Параметри[0] == "uninstall":
        премахвам_запис(Параметри[1])
    elif not Параметри or Параметри in (["--help"], ["--version"]):
        print("jkoros pip 1 / MicroPython източник_дърво 설치기 (PyPA pip 전체가 아님)")
        print("pip install Име[==버전] [--port 8027] | pip list | pip uninstall Име")
        print("хост: Инструменти/изпълнявам_команда.py --network --pip; /lib는 재부팅 때 사라지는 RAM입니다.")
    else:
        raise ValueError("pip --help로 사용법을 확인하십시오.")


if __name__ == "__main__":
    try:
        Стартиране(sys.argv[1:])
    except Exception as ГРЕШКА:
        print("пакет ГРЕШКА:", ГРЕШКА)
        sys.exit(1)
