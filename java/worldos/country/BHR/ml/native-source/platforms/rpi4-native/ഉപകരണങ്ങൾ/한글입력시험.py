#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from ഡെസ്ക്ടോപ്പ്_കാഴ്ച import കീബോര്_ഡ്


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.ലിഖിതം_ബഫര് = ''
        def അയയ്ക്കുക(ഡാറ്റാ):
            for പ്രതീക_ഡാറ്റ in ഡാറ്റാ.decode('utf-8'):
                if പ്രതീക_ഡാറ്റ == '\x7f': 자신.ലിഖിതം_ബഫര് = 자신.ലിഖിതം_ബഫര്[:-1]
                else: 자신.ലിഖിതം_ബഫര് += പ്രതീക_ഡാറ്റ
        자신.കീബോര്_ഡ്_എന്_ട്രി = കീബോര്_ഡ്(അയയ്ക്കുക)

    def 글쇠누르기(자신, nbsp_ചിഹ്നം_മൂല്യം):
        자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(True, nbsp_ചിഹ്നം_മൂല്യം)
        자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(False, nbsp_ചിഹ്നം_മൂല്യം)

    def ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്(자신, 누름열):
        for 누름값 in 누름열: 자신.글쇠누르기(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.글쇠누르기(0xffc6); 자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്(누름열)
                자신.assertEqual(자신.ലിഖിതം_ബഫര്, 예상결과)

    def test_앞글자지우기(자신):
        자신.글쇠누르기(0xff31); 자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്('dlfr')
        자신.assertEqual(자신.ലിഖിതം_ബഫര്,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.글쇠누르기(0xff08); 자신.assertEqual(자신.ലിഖിതം_ബഫര്,예상결과)
        자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്('gksk'); 자신.assertEqual(자신.ലിഖിതം_ബഫര്,'하나')
        자신.글쇠누르기(0xff08); 자신.assertEqual(자신.ലിഖിതം_ബഫര്,'하ㄴ')

    def test_전환반복확정(자신):
        자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്('echo ')
        자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(True,0xffe1)
        자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(True,32); 자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(True,32)
        자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(False,32); 자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(False,0xffe1)
        자신.assertTrue(자신.കീബോര്_ഡ്_എന്_ട്രി.한글여부)
        자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്('gksrmf'); 자신.글쇠누르기(0xff31); 자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്(' English')
        자신.assertEqual(자신.ലിഖിതം_ബഫര്,'echo 한글 English')
        자신.assertFalse(자신.കീബോര്_ഡ്_എന്_ട്രി.한글여부)
        자신.글쇠누르기(0xffc6); 자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്('rk'); 자신.글쇠누르기(0xff51)
        자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്('sk'); 자신.assertTrue(자신.ലിഖിതം_ബഫര്.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.글쇠누르기(0xffc6); 자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്('rk')
        자신.കീബോര്_ഡ്_എന്_ട്രി.പകര്_പ്പിടം_മൂല്യം='ഒട്ടിക്കുക_മൂല്യം'.encode()
        자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(True,0xffe3); 자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(True,0xffe1)
        자신.글쇠누르기(ord('v'))
        자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(False,0xffe1); 자신.കീബോര്_ഡ്_എന്_ട്രി.누름값(False,0xffe3)
        자신.글쇠누르기(0x0100d55c); 자신.ടൈപ്പ്_ചെയ്യുക_വകുപ്പ്('sk')
        자신.assertEqual(자신.ലിഖിതം_ബഫര്,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
