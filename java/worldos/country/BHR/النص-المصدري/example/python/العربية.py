def مخرجات(*قيمة, فاصل=" ", 끝="\n", **기존인수):
    # 기존 print의 sep/end 인수도 연결부에서 호환한다.
    if "sep" not in 기존인수: 기존인수["sep"] = فاصل
    if "end" not in 기존인수: 기존인수["end"] = 끝
    print(*قيمة, **기존인수)

