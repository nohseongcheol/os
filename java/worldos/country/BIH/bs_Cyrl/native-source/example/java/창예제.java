import 한국어.자체.прозор;
import 한국어.자체.ознака;
import 한국어.자체.текст_поље;
import 한국어.자체.дугме;
import 한국어.자체.догађај_редослијед;
import 한국어.자체.출력;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing прозор: bs_Cyrl 입력 → дугме → Прочитај_ме_eb81d7d9 текст освјежити. */
public class 창예제 implements 실행할일, 동작받이 {
    private прозор 인사창;
    private текст_поље назив_поље;
    private ознака 인사말;
    private int 인사횟수;

    public void отворити_прозор() {
        인사창 = new прозор("bs_Cyrl Swing", 460, 300);
        인사창.додати_елемент(new ознака("bs_Cyrl", 20, 20, 420, 28));
        назив_поље = new текст_поље("bs_Cyrl", 20, 64, 420, 30);
        인사말 = new ознака("bs_Cyrl", 20, 152, 420, 28);
        인사창.додати_елемент(назив_поље);
        인사창.додати_елемент(new дугме("인사하기", 20, 108, 180, 32, this));
        인사창.додати_елемент(인사말);
        인사창.додати_елемент(new ознака("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.приказати_прозор();
        출력.писати_редак("GUI 예제 Припремити: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.писати_текст("bs_Cyrl, " + назив_поље.글읽기() + "님! (" + 인사횟수 + ")");
        출력.писати_редак("GUI 인사: " + 인사말.글읽기());
    }

    public void 실행하기() { отворити_прозор(); }
    public void 동작받기(동작알림 알림) {
        출력.писати_редак("радња 알림: " + 알림.команда_текст());
        인사하기();
    }
    public static void 시작() {
        догађај_редослијед.나중에실행(new 창예제());
    }
}
