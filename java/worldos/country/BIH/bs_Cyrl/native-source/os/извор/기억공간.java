/** 부팅 систем_информација 조회와 4KiB 고정 подесити_величину 작업 секција_вриједност 할당/반환. 일반 물리 страница_вриједност 관리자는 아니다. */
public final class 기억공간 {
    static int[] секција_вриједност = new int[8192];
    static int[] 사용 = new int[8];

    static int рашчлањивати_цијели_број(int адреса) {
        return уређај_вриједност.기억읽기(адреса) | (уређај_вриједност.기억읽기(адреса + 1) << 8)
            | (уређај_вриједност.기억읽기(адреса + 2) << 16) | (уређај_вриједност.기억읽기(адреса + 3) << 24);
    }

    static int 위쪽기억크기() {
        int систем_информација = уређај_вриједност.부팅정보();
        if (уређај_вриједност.부팅표식() != 0x2badb002 || систем_информација == 0 || (рашчлањивати_цијели_број(систем_информација) & 1) == 0) return -1;
        return рашчлањивати_цијели_број(систем_информација + 8);
    }

    static int 할당() {
        for (int индекс = 0; индекс < 사용.length; индекс++) {
            if (사용[индекс] == 0) {
                사용[индекс] = 1;
                for (int 칸 = 0; 칸 < 1024; 칸++) секција_вриједност[индекс * 1024 + 칸] = 0;
                return индекс;
            }
        }
        return -1;
    }

    static boolean 반환(int индекс) {
        if (индекс < 0 || индекс >= 사용.length || 사용[индекс] == 0) return false;
        사용[индекс] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int индекс = 0; индекс < 사용.length; индекс++) 개수 += 사용[индекс];
        return 개수;
    }
}
