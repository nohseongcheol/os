#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 бајт_вриједност 위치로 자체 C 이름을 옮기는 일회성 이행 도구.

외부 구조체의 멤버, стринг_вриједност, C 표준 функција_вриједност, 이식 규약은 보존한다.
입력은 промијенити_вриједност 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def 실행():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['грешка']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    назив_табела = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:назив_табела[унос_вриједност['назив']] for 고유,унос_вриједност in 선언표.items()
                if унос_вриједност['назив'] in назив_табела and унос_вриједност['назив'] not in 규격}
    веза_табела = {унос_вриједност['назив']:назив_табела[унос_вриједност['назив']] for унос_вриједност in 선언표.values()
              if унос_вриједност.get('повезати')==4 and унос_вриједност['종류'] in (8,9)
              and унос_вриједност['назив'] in назив_табела and унос_вриједност['назив'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 повезати 이름만 유지한다.
    머리 = ['/* 한국어 извор_стабло 이름과 기존 기계 повезати Уговор_вриједност. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(веза_табела.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    변경들 = defaultdict(dict)
    for фајл,변위,назив,고유 in 분석['참조']:
        if 고유 in 바꿀선언:
            변경들[фајл][변위] = (назив,바꿀선언[고유])
    дневник_рада_ред = ['фајл\t원래바이트위치\t이전이름\t한국어이름']
    игнорирати_вриједност = []
    for фајл,промијенити_вриједност in 변경들.items():
        пут = Path(фајл); 원본 = пут.read_bytes(); подаци = 원본
        for 변위,(옛이름,새이름) in sorted(промијенити_вриједност.items(),reverse=True):
            끝 = 변위+len(옛이름.encode())
            if 원본[변위:끝] != 옛이름.encode():
                игнорирати_вриједност.append((str(пут.relative_to(기준)),변위,옛이름));continue
            подаци = подаци[:변위]+새이름.encode()+подаци[끝:]
            дневник_рада_ред.append('{}\t{}\t{}\t{}'.format(пут.relative_to(기준),변위,옛이름,새이름))
        пут.write_bytes(подаци)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макронаредба_вриједност = {унос_вриједност['назив']:назив_табела[унос_вриједност['назив']] for унос_вриједност in 선언표.values()
              if унос_вриједност['종류']==501 and унос_вриједност['назив'] in назив_табела and унос_вриједност['назив'] not in 규격}
    for пут in sorted({Path(унос_вриједност['фајл']) for унос_вриједност in 선언표.values()}):
        редак_списак = пут.read_text().splitlines(True); 이어짐 = False
        for индекс,редак in enumerate(редак_списак):
            전처리 = 이어짐 or bool(re.match(r'\s*#',редак))
            이어짐 = 전처리 and редак.rstrip().endswith('\\')
            if 전처리:
                표 = назив_табела if re.match(r'\s*#\s*define\b',редак) or 이어짐 else макронаредба_вриједност
                редак_списак[индекс] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],редак)
        пут.write_text(''.join(редак_списак))
    # 각 자체 번역 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for пут in sorted({Path(унос_вриједност['фајл']) for унос_вриједност in 선언표.values()}):
        if пут.suffix not in ('.c','.cpp'):continue
        peer_вриједност = '../' * len(пут.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        пут.write_text('#include "'+peer_вриједност+'"\n'+пут.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(дневник_рада_ред)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(игнорирати_вриједност,ensure_ascii=False,indent=2)+'\n')
    print('промијенити_вриједност',len(дневник_рада_ред)-1,'전처리 재검토',len(игнорирати_вриједност),'기계 повезати',len(веза_табела))

if __name__=='__main__': 실행()
