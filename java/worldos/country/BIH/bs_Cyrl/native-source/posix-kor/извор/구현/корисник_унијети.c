#include "호출경계.h"
extern int main(int 인수개수, char **аргумент_списак);
static char аргумент_меморија[2048];
static char *аргумент_списак[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 실행 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    аргумент_списак[0] = "jkoros-app";
    int 위치 = 0;
    for (int индекс = 0; индекс < 개수; индекс++) {
        const int *원본 = (const int *)jkoros_syscall(3, индекс, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        аргумент_списак[индекс + 1] = аргумент_меморија + 위치;
        for (int 칸 = 0; 칸 < 원본[0]; 칸++) {
            if (위치 >= 2047) return 126;
            аргумент_меморија[위치++] = 원본[칸 + 1];
        }
        аргумент_меморија[위치++] = 0;
    }
    аргумент_списак[개수 + 1] = 0;
    return main(개수 + 1, аргумент_списак);
}
