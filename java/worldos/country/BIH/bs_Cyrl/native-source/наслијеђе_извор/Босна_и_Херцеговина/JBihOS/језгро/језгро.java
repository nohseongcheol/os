package Босна_и_Херцеговина.JBihOS.језгро;

import Босна_и_Херцеговина.JBihOS.기억공간.меморија_менаџер;
import Босна_и_Херцеговина.JBihOS.기억공간.страница_менаџер;
import Босна_и_Херцеговина.JBihOS.입력.입력관리자;
import Босна_и_Херцеговина.JBihOS.작업.процес_вриједност;
import Босна_и_Херцеговина.JBihOS.작업.배정기;
import Босна_и_Херцеговина.JBihOS.체계호출.체계호출;
import Босна_и_Херцеговина.JBihOS.фајл_систем.파일서술자표;
import Босна_и_Херцеговина.JBihOS.фајл_систем.фајл_систем;

/** Java 관리 커널의 조립과 시작을 담당한다. */
public final class језгро {
    private final 하드웨어 уређај_вриједност;
    private final меморија_менаџер 기억공간 = new меморија_менаџер(32 * 1024 * 1024);
    private final страница_менаџер 쪽관리 = new страница_менаџер();
    private final фајл_систем фајл_систем = new фајл_систем();
    private final 배정기 배정기 = new 배정기(쪽관리);
    private final 입력관리자 입력관리 = new 입력관리자(256);
    private final процес_вриједност 첫과정;
    private final 체계호출 체계호출;

    public језгро(하드웨어 уређај_вриједност) {
        this.уређај_вриједност = уређај_вриједност;
        첫과정 = 배정기.첫과정(new 파일서술자표(фајл_систем));
        체계호출 = new 체계호출(фајл_систем, 쪽관리, 배정기, уређај_вриједност, 입력관리);
    }

    public void 시작() {
        уређај_вриједност.직렬출력("=== JBihOS 관리 језгро_вриједност ===\n");
    }

    public void 한단계실행() {
        уређај_вриједност.중앙처리장치멈춤();
    }

    public меморија_менаџер 기억공간() {
        return 기억공간;
    }

    public страница_менаџер 쪽관리() {
        return 쪽관리;
    }

    public фајл_систем фајл_систем() {
        return фајл_систем;
    }

    public 배정기 배정기() {
        return 배정기;
    }

    public 입력관리자 입력관리() {
        return 입력관리;
    }

    public процес_вриједност 첫과정() {
        return 첫과정;
    }

    public 체계호출 체계호출() {
        return 체계호출;
    }
}
