package Босна_и_Херцеговина.JBihOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Босна_и_Херцеговина.JBihOS.기억공간.страница_менаџер;
import Босна_и_Херцеговина.JBihOS.фајл_систем.파일서술자표;

/** процес_вриједност 식별자와 라운드로빈 Припремити 대기열을 관리한다. */
public final class 배정기 {
    private final страница_менаџер 쪽관리;
    private final Map<Integer, процес_вриједност> процес_списак = new HashMap<Integer, процес_вриједност>();
    private final Queue<процес_вриједност> 준비대기열 = new ArrayDeque<процес_вриједност>();
    private int 다음식별자 = 1;

    public 배정기(страница_менаџер 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public процес_вриједност 첫과정(파일서술자표 파일서술자) {
        процес_вриједност 새과정 = new процес_вриједност(식별자할당(), 0, 쪽관리.새주소공간(), 파일서술자);
        процес_списак.put(Integer.valueOf(새과정.식별자()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public процес_вриједност 복제(процес_вриједност 부모) {
        процес_вриједност дијете_вриједност = new процес_вриједност(
                식별자할당(),
                부모.식별자(),
                쪽관리.쓰기시복사복제(부모.адреса_простор()),
                부모.파일서술자().복제());
        дијете_вриједност.프로그램끝설정(부모.프로그램끝());
        процес_списак.put(Integer.valueOf(дијете_вриједност.식별자()), дијете_вриједност);
        준비대기열.offer(дијете_вриједност);
        return дијете_вриједност;
    }

    public процес_вриједност 다음과정() {
        int 검사수 = 준비대기열.size();
        for (int индекс = 0; индекс < 검사수; индекс++) {
            процес_вриједност 다음 = 준비대기열.poll();
            if (다음 != null && (다음.стање_вриједност() == процес_стање.Припремити || 다음.стање_вриједност() == процес_стање.실행)) {
                다음.именовани_скуп_стање(процес_стање.실행);
                준비대기열.offer(다음);
                return 다음;
            }
        }
        return null;
    }

    public int 자식기다리기(процес_вриједност 부모, int 자식식별자, boolean 기다리지않음) {
        for (процес_вриједност 후보 : процес_списак.values()) {
            if (후보.부모식별자() != 부모.식별자()) {
                continue;
            }
            if (자식식별자 > 0 && 후보.식별자() != 자식식별자) {
                continue;
            }
            if (후보.стање_вриједност() == процес_стање.изаћи_програм) {
                int 결과 = (후보.종료값() & 0xff) << 8;
                процес_списак.remove(Integer.valueOf(후보.식별자()));
                return 결과;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public процес_вриједност наћи_процес(int 식별자) {
        return процес_списак.get(Integer.valueOf(식별자));
    }

    private int 식별자할당() {
        return 다음식별자++;
    }
}
