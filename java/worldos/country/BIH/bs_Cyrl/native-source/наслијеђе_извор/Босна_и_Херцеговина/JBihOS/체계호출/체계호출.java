    public int фајл_контрола(процес_вриједност 현재과정, int 서술자, int команда, int 인자) {
        if (команда == 0) {
            return 현재과정.파일서술자().복제서술자(서술자, 인자);
        }
        if (команда == 1) {
            return 현재과정.파일서술자().실행시닫기값(서술자);
        }
        if (команда == 2) {
            return 현재과정.파일서술자().실행시닫기설정(서술자, (인자 & 1) != 0);
        }
        if (команда == 3) {
            return 현재과정.파일서술자().систем_информација(서술자) == null ? -9 : само_за_читање_заставица;
        }
        if (команда == 4) {
            return 인자 == само_за_читање_заставица ? 0 : -30;
        }
        return -22;
    }

