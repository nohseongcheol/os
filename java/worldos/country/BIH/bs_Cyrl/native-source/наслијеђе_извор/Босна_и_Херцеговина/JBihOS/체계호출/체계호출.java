    public int 프로그램끝(процес_вриједност 현재과정, int 새끝) {
        int 이전끝 = 현재과정.프로그램끝();
        if (새끝 == 0) {
            return 이전끝;
        }
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            return -12;
        }
        int 첫쪽 = 이전끝 / страница_менаџер.величина_странице;
        int 끝쪽 = (새끝 + страница_менаџер.величина_странице - 1) / страница_менаџер.величина_странице;
        if (새끝 > 이전끝) {
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int адреса = индекс * страница_менаџер.величина_странице;
                try {
                    쪽관리.바이트읽기(현재과정.адреса_простор(), адреса);
                } catch (IllegalStateException грешка) {
                    쪽관리.쪽연결(현재과정.адреса_простор(), адреса, true);
                }
            }
        }
        현재과정.프로그램끝설정(새끝);
        return 새끝;
    }

    public int 프로그램끝늘리기(процес_вриједност 현재과정, int 증가량) {
        int 이전끝 = 현재과정.프로그램끝();
        int 결과 = 프로그램끝(현재과정, 이전끝 + 증가량);
        return 결과 < 0 ? 결과 : 이전끝;
    }

