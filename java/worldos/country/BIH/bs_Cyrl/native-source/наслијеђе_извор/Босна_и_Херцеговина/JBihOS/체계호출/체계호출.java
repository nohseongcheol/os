    public int 실행(процес_вриједност 현재과정, byte[] 실행파일, String[] 인자, String[] 환경) {
        실행파일적재기.слика слика_вриједност;
        try {
            слика_вриједност = 적재기.검사(실행파일);
        } catch (IllegalArgumentException грешка) {
            return -8;
        }
        if (인자 == null || 환경 == null || 인자.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.секција_вриједност секција_вриједност : слика_вриједност.구역들()) {
            if ((секција_вриједност.заставица_вриједност() & 2) == 0 || секција_вриједност.подесити_величину() == 0) {
                continue;
            }
            int 첫쪽 = секција_вриједност.адреса() / страница_менаџер.величина_странице;
            int 끝쪽 = (секција_вриједност.адреса() + секција_вриједност.подесити_величину() + страница_менаџер.величина_странице - 1) / страница_менаџер.величина_странице;
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int адреса = индекс * страница_менаџер.величина_странице;
                try {
                    쪽관리.바이트읽기(현재과정.адреса_простор(), адреса);
                    쪽관리.범위개인쓰기(현재과정.адреса_простор(), адреса, страница_менаџер.величина_странице);
                } catch (IllegalStateException грешка) {
                    쪽관리.쪽연결(현재과정.адреса_простор(), адреса, true);
                }
            }
            for (int индекс = 0; индекс < секција_вриједност.подесити_величину(); индекс++) {
                byte вриједност = секција_вриједност.종류() == 8 ? 0 : 실행파일[секција_вриједност.파일위치() + индекс];
                쪽관리.писати_бајт_вриједност(현재과정.адреса_простор(), секција_вриједност.адреса() + индекс, вриједност);
            }
        }
        현재과정.실행문맥설정(слика_вриједност.почети_адреса(), 인자, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

