/** PCI RTL8139 (10ec:8139), 단일 послати_вриједност 버퍼와 8KiB 수신 петља_вриједност. 인터럽트 대신 폴링한다. */
public final class Мрежа_драјвер_уређаја {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] уређај_адреса = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int 위치) {
        уређај_вриједност.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | 위치);
        return уређај_вриједност.입출력정수읽기(0xcfc);
    }

    static boolean Припремити() {
        int 장치번호 = -1;
        for (int индекс = 0; индекс < 32; индекс++) {
            if (설정읽기(индекс, 0) == 0x813910ec) { 장치번호 = индекс; break; }
        }
        if (장치번호 < 0) return false;
        int задана_вриједност = 설정읽기(장치번호, 0x10);
        if ((задана_вриједност & 1) == 0 || (задана_вриједност & 0xfffffffc) < 0x100 || (задана_вриједност & 0xfffffffc) > 65535) return false;
        입출력기준주소 = задана_вриједност & 0xfffc;
        int команда = 설정읽기(장치번호, 4);
        уређај_вриједност.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        уређај_вриједност.입출력짧은수쓰기(0xcfc, команда | 5); // I/O 및 bus master Дозволити_вриједност, PCI стање_вриједност 비트는 건드리지 않음
        уређај_вриједност.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!ресетовати_вриједност()) { 입출력기준주소 = 0; return false; }
        for (int индекс = 0; индекс < 6; индекс++) уређај_адреса[индекс] = уређај_вриједност.입출력바이트읽기(입출력기준주소 + индекс);
        return true;
    }

    static boolean ресетовати_вриједност() {
        уређај_вриједност.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int 시작 = уређај_вриједност.밀리초();
        while ((уређај_вриједност.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (уређај_вриједност.밀리초() - 시작 > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        уређај_вриједност.입출력정수쓰기(입출력기준주소 + 0x30, уређај_вриједност.Мрежа_меморија());
        for (int индекс = 0; индекс < 4; индекс++) уређај_вриједност.입출력정수쓰기(입출력기준주소 + 0x20 + индекс * 4, уређај_вриједност.Мрежа_меморија() + 12288);
        уређај_вриједност.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        уређај_вриједност.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        уређај_вриједност.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        уређај_вриједност.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/방송, wrap 연속 похранити_вриједност, 8KiB
        уређај_вриједност.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int послати(int[] подаци, int дужина_вриједност) {
        if (입출력기준주소 == 0) return -19;
        if (дужина_вриједност < 14 || дужина_вриједност > 1514) return -90;
        int стање_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int 시작 = уређај_вриједност.밀리초();
        while ((уређај_вриједност.입출력정수읽기(стање_порт) & 0x2000) == 0)
            if (уређај_вриједност.밀리초() - 시작 > 100) return -110;
        int подесити_величину = дужина_вриједност < 60 ? 60 : дужина_вриједност;
        for (int индекс = 0; индекс < подесити_величину; индекс++)
            уређај_вриједност.писати_меморија(уређај_вриједност.Мрежа_меморија() + 12288 + индекс, индекс < дужина_вриједност ? подаци[индекс] : 0);
        уређај_вриједност.입출력정수쓰기(стање_порт, подесити_величину | 0x00080000);
        시작 = уређај_вриједност.밀리초();
        while ((уређај_вриједност.입출력정수읽기(стање_порт) & 0xe0008000) == 0)
            if (уређај_вриједност.밀리초() - 시작 > 100) return -110;
        if ((уређај_вриједност.입출력정수읽기(стање_порт) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return дужина_вриједност;
    }

    static int 받기(int[] подаци) {
        if (입출력기준주소 == 0) return 0;
        if ((уређај_вриједност.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!ресетовати_вриједност()) 입출력기준주소 = 0;
            return 0;
        }
        if ((уређај_вриједност.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = уређај_вриједност.Мрежа_меморија() + 수신위치;
        int стање_вриједност = 실행관리.짧은수(머리), подесити_величину = 실행관리.짧은수(머리 + 2);
        if (подесити_величину == 0xfff0) return 0; // DMA 진행 중
        if (подесити_величину < 4 || подесити_величину > 1518) {
            오류수++;
            if (!ресетовати_вриједност()) 입출력기준주소 = 0;
            return 0;
        }
        int дужина_вриједност = подесити_величину - 4;
        if ((стање_вриједност & 1) != 0) {
            for (int индекс = 0; индекс < дужина_вриједност; индекс++) подаци[индекс] = уређај_вриједност.기억읽기(머리 + 4 + индекс);
            수신수++;
        } else { дужина_вриједност = 0; 오류수++; }
        수신위치 = (수신위치 + подесити_величину + 4 + 3) & ~3;
        수신위치 &= 8191;
        уређај_вриједност.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        уређај_вриједност.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return дужина_вриједност;
    }
}
