/** 부팅 Сістэмная_інфармацыя 조회와 4KiB 고정 Памер 작업 секцыя_значэнне вылучыць_Сховішча/반환. 일반 물리 старонка_значэнне 관리자는 아니다. */
public final class 기억공간 {
    static int[] секцыя_значэнне = new int[8192];
    static int[] 사용 = new int[8];

    static int 정수읽기(int адрас) {
        return прылада_значэнне.기억읽기(адрас) | (прылада_значэнне.기억읽기(адрас + 1) << 8)
            | (прылада_значэнне.기억읽기(адрас + 2) << 16) | (прылада_значэнне.기억읽기(адрас + 3) << 24);
    }

    static int 위쪽기억크기() {
        int Сістэмная_інфармацыя = прылада_значэнне.부팅정보();
        if (прылада_значэнне.부팅표식() != 0x2badb002 || Сістэмная_інфармацыя == 0 || (정수읽기(Сістэмная_інфармацыя) & 1) == 0) return -1;
        return 정수읽기(Сістэмная_інфармацыя + 8);
    }

    static int вылучыць_Сховішча() {
        for (int індэкс = 0; індэкс < 사용.length; індэкс++) {
            if (사용[індэкс] == 0) {
                사용[індэкс] = 1;
                for (int слот_увядзенне = 0; слот_увядзенне < 1024; слот_увядзенне++) секцыя_значэнне[індэкс * 1024 + слот_увядзенне] = 0;
                return індэкс;
            }
        }
        return -1;
    }

    static boolean 반환(int індэкс) {
        if (індэкс < 0 || індэкс >= 사용.length || 사용[індэкс] == 0) return false;
        사용[індэкс] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int індэкс = 0; індэкс < 사용.length; індэкс++) 개수 += 사용[індэкс];
        return 개수;
    }
}
