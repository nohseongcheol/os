    public static int 코드포인트수(String Тэкст) {
        int 수 = 0;
        for (int цыкл_індэкс = 0; цыкл_індэкс < Тэкст.length(); цыкл_індэкс++, 수++) {
            int код_сімвала = Тэкст.charAt(цыкл_індэкс);
            if (код_сімвала >= 0xd800 && код_сімвала <= 0xdbff && цыкл_індэкс + 1 < Тэкст.length() && Тэкст.charAt(цыкл_індэкс + 1) >= 0xdc00 && Тэкст.charAt(цыкл_індэкс + 1) <= 0xdfff) цыкл_індэкс++;
        }
        return 수;
    }
    public static byte[] 부호화(String Тэкст) {
        byte[] 임시 = new byte[Тэкст.length() * 3]; int 쓴수 = 0;
        for (int цыкл_індэкс = 0; цыкл_індэкс < Тэкст.length(); цыкл_індэкс++) {
            int код_сімвала = Тэкст.charAt(цыкл_індэкс);
            if (код_сімвала >= 0xd800 && код_сімвала <= 0xdbff && цыкл_індэкс + 1 < Тэкст.length() && Тэкст.charAt(цыкл_індэкс + 1) >= 0xdc00 && Тэкст.charAt(цыкл_індэкс + 1) <= 0xdfff) код_сімвала = 0x10000 + ((код_сімвала - 0xd800) << 10) + Тэкст.charAt(++цыкл_індэкс) - 0xdc00;
            else if (код_сімвала >= 0xd800 && код_сімвала <= 0xdfff) код_сімвала = '?';
            if (код_сімвала < 128) 임시[쓴수++] = (byte)код_сімвала;
            else if (код_сімвала < 2048) { 임시[쓴수++] = (byte)(192 | код_сімвала >> 6); 임시[쓴수++] = (byte)(128 | код_сімвала & 63); }
            else if (код_сімвала < 65536) { 임시[쓴수++] = (byte)(224 | код_сімвала >> 12); 임시[쓴수++] = (byte)(128 | код_сімвала >> 6 & 63); 임시[쓴수++] = (byte)(128 | код_сімвала & 63); }
            else { 임시[쓴수++] = (byte)(240 | код_сімвала >> 18); 임시[쓴수++] = (byte)(128 | код_сімвала >> 12 & 63); 임시[쓴수++] = (byte)(128 | код_сімвала >> 6 & 63); 임시[쓴수++] = (byte)(128 | код_сімвала & 63); }
        }
        byte[] 결과 = new byte[쓴수]; System.arraycopy(임시, 0, 결과, 0, 쓴수); return 결과;
    }
    /** 잘못된 UTF-8은 잘못된인수예외으로 거부한다. */
    public static String расшыфраваць_дадзеныя(byte[] байт_значэнне) {
        StringBuilder 결과 = new StringBuilder();
        for (int цыкл_індэкс = 0; цыкл_індэкс < байт_значэнне.length;) {
            int код_сімвала = байт_значэнне[цыкл_індэкс++] & 255, 수 = код_сімвала < 128 ? 0 : код_сімвала >= 194 && код_сімвала < 224 ? 1 : код_сімвала >= 224 && код_сімвала < 240 ? 2 : код_сімвала >= 240 && код_сімвала <= 244 ? 3 : -1;
            if (수 < 0 || байт_значэнне.length - цыкл_індэкс < 수) throw new памылковы_аргумент_выключэнне("잘못된 UTF-8");
            int 최소 = 수 == 1 ? 128 : 수 == 2 ? 2048 : 수 == 3 ? 65536 : 0;
            if (수 > 0) код_сімвала &= (1 << (6 - 수)) - 1;
            for (int 안쪽자리 = 0; 안쪽자리 < 수; 안쪽자리++) { int Назад_значэнне = байт_значэнне[цыкл_індэкс++] & 255; if ((Назад_значэнне & 192) != 128) throw new памылковы_аргумент_выключэнне("잘못된 UTF-8"); код_сімвала = код_сімвала << 6 | Назад_значэнне & 63; }
            if (код_сімвала < 최소 || код_сімвала > 0x10ffff || код_сімвала >= 0xd800 && код_сімвала <= 0xdfff) throw new памылковы_аргумент_выключэнне("잘못된 UTF-8");
            if (код_сімвала < 65536) 결과.append((char)код_сімвала);
            else { код_сімвала -= 65536; 결과.append((char)(0xd800 | код_сімвала >> 10)); 결과.append((char)(0xdc00 | код_сімвала & 1023)); }
        }
        return 결과.toString();
    }
