import 한국어.자체.акно;
import 한국어.자체.Адмеціна;
import 한국어.자체.Тэкст_поле;
import 한국어.자체.кнопка;
import 한국어.자체.падзея_чарга;
import 한국어.자체.Выхад;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing акно: Belarusian 입력 → кнопка → файл_звестак_eb81d7d9 Тэкст абнавіць. */
public class 창예제 implements 실행할일, 동작받이 {
    private акно 인사창;
    private Тэкст_поле імя_поле;
    private Адмеціна 인사말;
    private int 인사횟수;

    public void адкрыць_акно() {
        인사창 = new акно("Belarusian Swing", 460, 300);
        인사창.дадаць_элемент(new Адмеціна("Belarusian", 20, 20, 420, 28));
        імя_поле = new Тэкст_поле("Belarusian", 20, 64, 420, 30);
        인사말 = new Адмеціна("Belarusian", 20, 152, 420, 28);
        인사창.дадаць_элемент(імя_поле);
        인사창.дадаць_элемент(new кнопка("인사하기", 20, 108, 180, 32, this));
        인사창.дадаць_элемент(인사말);
        인사창.дадаць_элемент(new Адмеціна("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.паказаць_акно();
        Выхад.напісаць_лінія("GUI 예제 Падрыхтаваць: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.напісаць_Тэкст("Belarusian, " + імя_поле.글읽기() + "님! (" + 인사횟수 + ")");
        Выхад.напісаць_лінія("GUI 인사: " + 인사말.글읽기());
    }

    public void Выкананне() { адкрыць_акно(); }
    public void 동작받기(동작알림 알림) {
        Выхад.напісаць_лінія("Дзеянне 알림: " + 알림.каманда_Тэкст());
        인사하기();
    }
    public static void Выканаць() {
        падзея_чарга.나중에실행(new 창예제());
    }
}
