#!/usr/bin/env python3
"""абвяшчэнне 고유번호와 UTF-8 байт_значэнне 위치로 자체 C 이름을 옮기는 일회성 이행 Інструменты.

외부 구조체의 멤버, радок_значэнне, C 표준 функцыя_значэнне, 이식 규약은 보존한다.
입력은 змяніць_значэнне 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def выканаць_каманда():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['ПАМЫЛКА']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    імя_табліца = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    абвяшчэнне_табліца = 분석['абвяшчэнне']
    바꿀선언 = {고유:імя_табліца[увядзенне_значэнне['Назва']] for 고유,увядзенне_значэнне in абвяшчэнне_табліца.items()
                if увядзенне_значэнне['Назва'] in імя_табліца and увядзенне_значэнне['Назва'] not in 규격}
    кантакт_табліца = {увядзенне_значэнне['Назва']:імя_табліца[увядзенне_значэнне['Назва']] for увядзенне_значэнне in абвяшчэнне_табліца.values()
              if увядзенне_значэнне.get('Злучыцца')==4 and увядзенне_значэнне['종류'] in (8,9)
              and увядзенне_значэнне['Назва'] in імя_табліца and увядзенне_значэнне['Назва'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 Злучыцца 이름만 유지한다.
    머리 = ['/* 한국어 крыніца_дрэва 이름과 기존 камп_ютар Злучыцца зварот_значэнне. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(кантакт_табліца.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Змяненні_Спіс = defaultdict(dict)
    for Файл,Зрух_значэнне,Назва,고유 in 분석['Даведачныя_матэрыялы']:
        if 고유 in 바꿀선언:
            Змяненні_Спіс[Файл][Зрух_значэнне] = (Назва,바꿀선언[고유])
    журнал_запіс = ['Файл\t원래바이트위치\t이전이름\t한국어이름']
    адбой_значэнне = []
    for Файл,змяніць_значэнне in Змяненні_Спіс.items():
        ШЛЯХ = Path(Файл); 원본 = ШЛЯХ.read_bytes(); дадзеныя = 원본
        for Зрух_значэнне,(옛이름,새이름) in sorted(змяніць_значэнне.items(),reverse=True):
            끝 = Зрух_значэнне+len(옛이름.encode())
            if 원본[Зрух_значэнне:끝] != 옛이름.encode():
                адбой_значэнне.append((str(ШЛЯХ.relative_to(기준)),Зрух_значэнне,옛이름));continue
            дадзеныя = дадзеныя[:Зрух_значэнне]+새이름.encode()+дадзеныя[끝:]
            журнал_запіс.append('{}\t{}\t{}\t{}'.format(ШЛЯХ.relative_to(기준),Зрух_значэнне,옛이름,새이름))
        ШЛЯХ.write_bytes(дадзеныя)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макрас_значэнне = {увядзенне_значэнне['Назва']:імя_табліца[увядзенне_значэнне['Назва']] for увядзенне_значэнне in абвяшчэнне_табліца.values()
              if увядзенне_значэнне['종류']==501 and увядзенне_значэнне['Назва'] in імя_табліца and увядзенне_значэнне['Назва'] not in 규격}
    for ШЛЯХ in sorted({Path(увядзенне_значэнне['Файл']) for увядзенне_значэнне in абвяшчэнне_табліца.values()}):
        лінія_Спіс = ШЛЯХ.read_text().splitlines(True); 이어짐 = False
        for індэкс,лінія in enumerate(лінія_Спіс):
            전처리 = 이어짐 or bool(re.match(r'\s*#',лінія))
            이어짐 = 전처리 and лінія.rstrip().endswith('\\')
            if 전처리:
                표 = імя_табліца if re.match(r'\s*#\s*define\b',лінія) or 이어짐 else макрас_значэнне
                лінія_Спіс[індэкс] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],лінія)
        ШЛЯХ.write_text(''.join(лінія_Спіс))
    # 각 자체 Пераклад_крыніца 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ШЛЯХ in sorted({Path(увядзенне_значэнне['Файл']) for увядзенне_значэнне in абвяшчэнне_табліца.values()}):
        if ШЛЯХ.suffix not in ('.c','.cpp'):continue
        аднарангавы_значэнне = '../' * len(ШЛЯХ.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        ШЛЯХ.write_text('#include "'+аднарангавы_значэнне+'"\n'+ШЛЯХ.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(журнал_запіс)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(адбой_значэнне,ensure_ascii=False,indent=2)+'\n')
    print('змяніць_значэнне',len(журнал_запіс)-1,'전처리 재검토',len(адбой_значэнне),'камп_ютар Злучыцца',len(кантакт_табліца))

if __name__=='__main__': выканаць_каманда()
