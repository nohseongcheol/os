def чэк_шлях(ШЛЯХ):
    if not isinstance(ШЛЯХ, str) or not ШЛЯХ.endswith(".py"):
        raise ValueError("Python 소스만 설치할 수 있습니다.")
    if any(부분 in ("", ".", "..") or 부분.startswith(".") for 부분 in ШЛЯХ.split("/")):
        raise ValueError("허용하지 않는 пакет ШЛЯХ")
    if "\\" in ШЛЯХ or any(ord(сімвал_значэнне_068c2631) < 32 or ord(сімвал_значэнне_068c2631) == 127 for сімвал_значэнне_068c2631 in ШЛЯХ):
        raise ValueError("잘못된 ШЛЯХ 문자")
    결과 = "/lib/" + ШЛЯХ
    if len(결과.encode("utf-8")) > 63 or ШЛЯХ in ("한국어.py", "пакет.py"):
        raise ValueError("пакет 경로가 너무 길거나 значэнне_па_змаўчанні 라이브러리와 겹칩니다.")
    return 결과


class 수신흐름:
    def __init__(자신, 종단):
        자신.종단 = 종단
        자신.남은자료 = b""
        자신.Выканаць = аперацыйная_сістэма.ticks_ms()

    def 정확히읽기(자신, даўжыня_значэнне):
        дадзеныя = bytearray()
        while len(дадзеныя) < даўжыня_значэнне:
            if аперацыйная_сістэма.ticks_ms() - 자신.Выканаць > 90000:
                raise ValueError("пакет 중계 адказаць час_значэнне 초과")
            if not 자신.남은자료:
                try:
                    자신.남은자료 = аперацыйная_сістэма.tcp_read(자신.종단, 512)
                except OSError as ПАМЫЛКА:
                    if ПАМЫЛКА.args[0] != 11:
                        raise
                    аперацыйная_сістэма.sleep_ms(10)
                    continue
                if not 자신.남은자료:
                    raise ValueError("пакет 전송이 중간에 끝났습니다.")
            개수 = min(даўжыня_значэнне - len(дадзеныя), len(자신.남은자료))
            дадзеныя.extend(자신.남은자료[:개수])
            자신.남은자료 = 자신.남은자료[개수:]
            аперацыйная_сістэма.sleep_ms(0)
        return bytes(дадзеныя)


def спампоўка(요청, нумар_порта):
    if len(요청) > 96 or any(сімвал_значэнне_068c2631 not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-=" for сімвал_значэнне_068c2631 in 요청):
        raise ValueError("사용법: pip install Назва 또는 Назва==버전")
    종단 = аперацыйная_сістэма.tcp_open()
    try:
        Выканаць = аперацыйная_сістэма.ticks_ms()
        while True:
            try:
                аперацыйная_сістэма.tcp_connect(종단, "10.0.2.2", нумар_порта)
                break
            except OSError as ПАМЫЛКА:
                if ПАМЫЛКА.args[0] not in (11, 115) or аперацыйная_сістэма.ticks_ms() - Выканаць > 5000:
                    raise ValueError("пакет 중계 Злучыцца няўдача_значэнне: 호스트에서 --network --pip로 실행하십시오.")
                аперацыйная_сістэма.sleep_ms(10)
        дадзеныя = (요청 + "\n").encode()
        while дадзеныя:
            try:
                개수 = аперацыйная_сістэма.tcp_write(종단, дадзеныя)
                if not 개수:
                    raise ValueError("пакет 요청 перанос_значэнне няўдача_значэнне")
                дадзеныя = дадзеныя[개수:]
            except OSError as ПАМЫЛКА:
                if ПАМЫЛКА.args[0] != 11:
                    raise
                аперацыйная_сістэма.sleep_ms(10)
                if аперацыйная_сістэма.ticks_ms() - Выканаць > 10000:
                    raise ValueError("пакет 요청 перанос_значэнне час_значэнне 초과")
        паток_значэнне = 수신흐름(종단)
        머리 = паток_значэнне.정확히읽기(8)
        if 머리[:4] != b"JKP1":
            raise ValueError("пакет перанос_значэнне зварот_значэнне 불일치")
        даўжыня_значэнне = (머리[4] << 24) | (머리[5] << 16) | (머리[6] << 8) | 머리[7]
        if даўжыня_значэнне > 8192:
            raise ValueError("пакет 명세가 너무 큽니다.")
        명세 = json.loads(паток_значэнне.정확히읽기(даўжыня_значэнне).decode())
        if "error" in 명세:
            raise ValueError(명세["error"])
        if not 1 <= len(명세["files"]) <= 16:
            raise ValueError("꾸러미당 крыніца_дрэва 파일은 1~16개여야 합니다.")
        if sum(увядзенне_значэнне["size"] for увядзенне_значэнне in 명세["files"]) > 65536:
            raise ValueError("пакет крыніца_дрэва 합계는 64 KiB 이하여야 합니다.")
        파일들 = {}
        for увядзенне_значэнне in 명세["files"]:
            ШЛЯХ = чэк_шлях(увядзенне_значэнне["path"])
            if ШЛЯХ in 파일들 or not 0 <= увядзенне_значэнне["size"] <= 16384:
                raise ValueError("중복 ШЛЯХ 또는 Файл Памер 초과")
            дадзеныя = паток_значэнне.정확히읽기(увядзенне_значэнне["size"])
            if 지문(дадзеныя) != увядзенне_значэнне["sha256"]:
                raise ValueError("пакет Файл SHA-256 불일치")
            # 실행하지 않고 현재 MicroPython의 문법으로 먼저 검사한다.
            compile(дадзеныя.decode("utf-8"), ШЛЯХ, "exec")
            파일들[ШЛЯХ] = дадзеныя
            gc.collect()
        return 명세, 파일들
    finally:
        аперацыйная_сістэма.udp_close(종단)


def усталяваць_значэнне(요청, нумар_порта):
    print("пакет спампоўка:", 요청)
    명세, 파일들 = спампоўка(요청, нумар_порта)
    увядзенне_Спіс = 목록읽기()
    Назва = 명세["name"]
    if Назва in увядзенне_Спіс:
        if увядзенне_Спіс[Назва]["version"] == 명세["version"]:
            for ШЛЯХ, 지문값 in увядзенне_Спіс[Назва]["files"].items():
                if аперацыйная_сістэма.path_kind(ШЛЯХ) != 1 or 지문(аперацыйная_сістэма.read(ШЛЯХ)) != 지문값:
                    raise ValueError("설치된 пакет 파일이 달라졌습니다: " + ШЛЯХ)
            print("이미 설치됨:", Назва, 명세["version"])
            return
        raise ValueError("다른 버전이 있습니다. pip uninstall로 제거한 Назад_значэнне 설치하십시오.")
    for ШЛЯХ in 파일들:
        if аперацыйная_сістэма.path_kind(ШЛЯХ):
            raise ValueError("기존 파일을 덮어쓰지 않습니다: " + ШЛЯХ)
    увядзенне_Спіс[Назва] = {"version": 명세["version"], "files": {ШЛЯХ: 지문(дадзеныя) for ШЛЯХ, дадзеныя in 파일들.items()}}
    새목록 = json.dumps(увядзенне_Спіс).encode()
    if len(새목록) > 16384:
        raise ValueError("пакет увядзенне_Спіс Памер 초과")
    이전목록 = аперацыйная_сістэма.read(Спіс_шлях) if аперацыйная_сістэма.path_kind(Спіс_шлях) else None
    만든파일 = []
    만든폴더 = []
    try:
        for ШЛЯХ, дадзеныя in 파일들.items():
            부분들 = ШЛЯХ.split("/")
            for 수 in range(2, len(부분들)):
                каталог_значэнне = "/".join(부분들[:수])
                종류 = аперацыйная_сістэма.path_kind(каталог_значэнне)
                if 종류 == 0:
                    аперацыйная_сістэма.mkdir(каталог_значэнне)
                    만든폴더.append(каталог_значэнне)
                elif 종류 != 2:
                    raise ValueError("каталог_значэнне 경로에 파일이 있습니다: " + каталог_значэнне)
            만든파일.append(ШЛЯХ)
            напісаць_журнал(ШЛЯХ, дадзеныя)
        напісаць_журнал(Спіс_шлях, 새목록)
    except Exception:
        for ШЛЯХ in 만든파일:
            if аперацыйная_сістэма.path_kind(ШЛЯХ):
                аперацыйная_сістэма.remove(ШЛЯХ)
        for каталог_значэнне in reversed(만든폴더):
            аперацыйная_сістэма.rmdir(каталог_значэнне)
        if 이전목록 is not None:
            напісаць_журнал(Спіс_шлях, 이전목록)
        elif аперацыйная_сістэма.path_kind(Спіс_шлях):
            аперацыйная_сістэма.remove(Спіс_шлях)
        raise
    print("усталяваць_значэнне 완료:", Назва, 명세["version"], "→ /lib (RAM)")


def выдаліць_увядзенне(Назва):
    увядзенне_Спіс = 목록읽기()
    if Назва not in увядзенне_Спіс:
        raise ValueError("설치되지 않은 꾸러미입니다: " + Назва)
    for ШЛЯХ, 지문값 in увядзенне_Спіс[Назва]["files"].items():
        if аперацыйная_сістэма.path_kind(ШЛЯХ) != 1 or 지문(аперацыйная_сістэма.read(ШЛЯХ)) != 지문값:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + ШЛЯХ)
    for ШЛЯХ in увядзенне_Спіс[Назва]["files"]:
        аперацыйная_сістэма.remove(ШЛЯХ)
    del увядзенне_Спіс[Назва]
    напісаць_журнал(Спіс_шлях, json.dumps(увядзенне_Спіс).encode())
    print("выдаліць_увядзенне 완료:", Назва)


