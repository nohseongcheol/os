#include "호출경계.h"
extern int main(int 인수개수, char **аргумент_Спіс);
static char аргумент_памяць[2048];
static char *аргумент_Спіс[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 выканаць_каманда 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    аргумент_Спіс[0] = "jkoros-app";
    int Пазіцыя = 0;
    for (int індэкс = 0; індэкс < 개수; індэкс++) {
        const int *원본 = (const int *)jkoros_syscall(3, індэкс, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        аргумент_Спіс[індэкс + 1] = аргумент_памяць + Пазіцыя;
        for (int слот_увядзенне = 0; слот_увядзенне < 원본[0]; слот_увядзенне++) {
            if (Пазіцыя >= 2047) return 126;
            аргумент_памяць[Пазіцыя++] = 원본[слот_увядзенне + 1];
        }
        аргумент_памяць[Пазіцыя++] = 0;
    }
    аргумент_Спіс[개수 + 1] = 0;
    return main(개수 + 1, аргумент_Спіс);
}
