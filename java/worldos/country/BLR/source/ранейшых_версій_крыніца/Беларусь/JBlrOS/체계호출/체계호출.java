    public int 프로그램끝(Працэс_значэнне 현재과정, int 새끝) {
        int 이전끝 = 현재과정.프로그램끝();
        if (새끝 == 0) {
            return 이전끝;
        }
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            return -12;
        }
        int 첫쪽 = 이전끝 / старонка_менеджар.памер_старонкі;
        int 끝쪽 = (새끝 + старонка_менеджар.памер_старонкі - 1) / старонка_менеджар.памер_старонкі;
        if (새끝 > 이전끝) {
            for (int індэкс = 첫쪽; індэкс < 끝쪽; індэкс++) {
                int адрас = індэкс * старонка_менеджар.памер_старонкі;
                try {
                    쪽관리.바이트읽기(현재과정.адрас_ПРАБЕЛ(), адрас);
                } catch (IllegalStateException ПАМЫЛКА) {
                    쪽관리.супастаўляць_старонка(현재과정.адрас_ПРАБЕЛ(), адрас, true);
                }
            }
        }
        현재과정.프로그램끝설정(새끝);
        return 새끝;
    }

    public int 프로그램끝늘리기(Працэс_значэнне 현재과정, int 증가량) {
        int 이전끝 = 현재과정.프로그램끝();
        int 결과 = 프로그램끝(현재과정, 이전끝 + 증가량);
        return 결과 < 0 ? 결과 : 이전끝;
    }

