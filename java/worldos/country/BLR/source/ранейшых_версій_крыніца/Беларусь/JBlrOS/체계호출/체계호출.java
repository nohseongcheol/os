    public boolean 단말인가(Працэс_значэнне 현재과정, int 서술자) {
        файл_звесткі Сістэмная_інфармацыя = 현재과정.파일서술자().Сістэмная_інфармацыя(서술자);
        return Сістэмная_інфармацыя != null && (Сістэмная_інфармацыя.형태() & 0170000) == 0020000;
    }

    public int файл_кіраванне(Працэс_значэнне 현재과정, int 서술자, int Загад, int параметр_аргумент) {
        if (Загад == 0) {
            return 현재과정.파일서술자().복제서술자(서술자, параметр_аргумент);
        }
        if (Загад == 1) {
            return 현재과정.파일서술자().실행시닫기값(서술자);
        }
        if (Загад == 2) {
            return 현재과정.파일서술자().실행시닫기설정(서술자, (параметр_аргумент & 1) != 0);
        }
        if (Загад == 3) {
            return 현재과정.파일서술자().Сістэмная_інфармацыя(서술자) == null ? -9 : толькі_для_чытання_пазнака;
        }
        if (Загад == 4) {
            return параметр_аргумент == толькі_для_чытання_пазнака ? 0 : -30;
        }
        return -22;
    }

