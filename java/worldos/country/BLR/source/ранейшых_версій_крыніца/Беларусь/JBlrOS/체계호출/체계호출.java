    public int 접근가능(String Назва, int спосаб_рэжым) {
        файл_звесткі Сістэмная_інфармацыя = файлавая_сістэма.Сістэмная_інфармацыя(Назва);
        if (Сістэмная_інфармацыя == null) {
            return -2;
        }
        if ((спосаб_рэжым & 1) != 0 && (Сістэмная_інфармацыя.형태() & 0111) == 0) {
            return -13;
        }
        if ((спосаб_рэжым & 2) != 0) {
            return -30;
        }
        return 0;
    }

