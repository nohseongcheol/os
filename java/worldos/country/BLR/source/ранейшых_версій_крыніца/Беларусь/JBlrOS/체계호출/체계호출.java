    public int выканаць_каманда(Працэс_значэнне 현재과정, byte[] 실행파일, String[] параметр_аргумент, String[] 환경) {
        실행파일적재기.выява выява_значэнне;
        try {
            выява_значэнне = 적재기.검사(실행파일);
        } catch (IllegalArgumentException ПАМЫЛКА) {
            return -8;
        }
        if (параметр_аргумент == null || 환경 == null || параметр_аргумент.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.секцыя_значэнне секцыя_значэнне : выява_значэнне.구역들()) {
            if ((секцыя_значэнне.пазнака_значэнне() & 2) == 0 || секцыя_значэнне.Памер() == 0) {
                continue;
            }
            int 첫쪽 = секцыя_значэнне.адрас() / старонка_менеджар.памер_старонкі;
            int 끝쪽 = (секцыя_значэнне.адрас() + секцыя_значэнне.Памер() + старонка_менеджар.памер_старонкі - 1) / старонка_менеджар.памер_старонкі;
            for (int індэкс = 첫쪽; індэкс < 끝쪽; індэкс++) {
                int адрас = індэкс * старонка_менеджар.памер_старонкі;
                try {
                    쪽관리.바이트읽기(현재과정.адрас_ПРАБЕЛ(), адрас);
                    쪽관리.범위개인쓰기(현재과정.адрас_ПРАБЕЛ(), адрас, старонка_менеджар.памер_старонкі);
                } catch (IllegalStateException ПАМЫЛКА) {
                    쪽관리.супастаўляць_старонка(현재과정.адрас_ПРАБЕЛ(), адрас, true);
                }
            }
            for (int індэкс = 0; індэкс < секцыя_значэнне.Памер(); індэкс++) {
                byte значэнне = секцыя_значэнне.종류() == 8 ? 0 : 실행파일[секцыя_значэнне.파일위치() + індэкс];
                쪽관리.напісаць_байт_значэнне(현재과정.адрас_ПРАБЕЛ(), секцыя_значэнне.адрас() + індэкс, значэнне);
            }
        }
        현재과정.실행문맥설정(выява_значэнне.Пуск_адрас(), параметр_аргумент, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

