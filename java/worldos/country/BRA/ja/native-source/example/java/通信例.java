import 日本語.内蔵.接続経路;
import 日本語.内蔵.実行引数;
import 日本語.内蔵.データグラムチャネル;
import 日本語.内蔵.文字;
import 日本語.内蔵.出力;
import 日本語.内蔵.検査項目;
import 日本語.内蔵.入力ストリーム;
import 日本語.内蔵.入力出力例外;

public class 通信例 {
    public static void 起動処理() throws 入力出力例外 {
        // ホスト: python3 道具/用例復唱.py --tcp-port 9000 --udp-port 9001
        接続経路 接続 = 接続経路.開放("10.0.2.2", 文字.整数値解析(実行引数.文(0)));
        try {
            接続.待機期限(700);
            byte[] メッセージ = 文字.符号化("JAVA TCP ja\n");
            接続.出力().書込(メッセージ);
            入力ストリーム 入力値 = 接続.入力値();
            for (int 数 = 0; 数 < 文字.バイト個数(メッセージ); 数++) {
                検査項目.真偽確認(入力値.読取() == (メッセージ[数] & 255), "TCP 返答 불일치");
            }
        } finally { 接続.閉鎖(); }
        データグラムチャネル 通信端点 = データグラムチャネル.開放(0);
        try {
            通信端点.待機期限(700);
            通信端点.送信("10.0.2.2", 文字.整数値解析(実行引数.文(1)), "JAVA UDP ja");
            検査項目.真偽確認(文字.等価本文(通信端点.受取(), "JAVA UDP ja"), "UDP 返答 불일치");
        } finally { 通信端点.閉鎖(); }
        出力.行書込("JAVA 네트워크 検証: TCP UDP ja");
    }
}
