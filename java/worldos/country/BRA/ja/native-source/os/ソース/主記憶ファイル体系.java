/** セッション中保持する8個のファイル。ソース編集やコンパイルの失敗時は既存ファイルを保つ。 */
public final class 主記憶ファイル体系 {
    static final int 最大容量 = 16384;
    static int[] 名前一覧一覧 = new int[8 * 64];
    static int[] 容量列 = new int[8];
    static int[] 個数開放 = new int[8], 許可許可一覧 = new int[8];
    static int[] 名前 = new int[64];
    static int[] 編集値 = new int[最大容量];
    static boolean 判定編集中 = false;
    static boolean 桁あふれ値 = false;
    static int 編集容量 = 0;

    static boolean 名前検査(int[] 文字値, int 長さ) {
        if (長さ < 1 || 長さ > 63) return false;
        for (int 数 = 0; 数 < 長さ; 数++) {
            int 値 = 文字値[数];
            if (!(値 >= 'a' && 値 <= 'z') && !(値 >= 'A' && 値 <= 'Z')
                && !(値 >= '0' && 値 <= '9') && 値 != '_' && 値 != '-' && 値 != '.') return false;
        }
        return 文字値[0] != '.';
    }

    static int 入口探索(int[] 文字値, int 長さ) {
        if (!名前検査(文字値, 長さ)) return -22;
        for (int 数 = 0; 数 < 8; 数++) {
            boolean 等価本文 = 名前一覧一覧[数 * 64 + 長さ] == 0;
            for (int 槽入口 = 0; 槽入口 < 長さ; 槽入口++) if (名前一覧一覧[数 * 64 + 槽入口] != 文字値[槽入口]) 等価本文 = false;
            if (等価本文) return 数;
        }
        return -2;
    }

    static int 格納値(int[] 文字値, int 長さ, int[] データ, int 容量) {
        if (!名前検査(文字値, 長さ) || 容量 < 0 || 容量 > データ.length) return -22;
        if (容量 > 最大容量) return -90;
        int 番号 = 入口探索(文字値, 長さ);
        if (番号 == -2) {
            for (int 数 = 0; 数 < 8 && 番号 < 0; 数++) if (名前一覧一覧[数 * 64] == 0 && 個数開放[数] == 0) 番号 = 数;
            if (番号 >= 0) 許可許可一覧[番号] = 438;
        }
        if (番号 < 0) return -28;
        int 番地 = 装置.ファイル記憶() + 番号 * 最大容量;
        for (int 数 = 0; 数 < 容量; 数++) 装置.記憶書込(番地 + 数, データ[数]);
        for (int 数 = 0; 数 < 64; 数++) 名前一覧一覧[番号 * 64 + 数] = 数 < 長さ ? 文字値[数] : 0;
        容量列[番号] = 容量;
        return 容量;
    }

    static void 入口一覧() {
        for (int 数 = 0; 数 < 8; 数++) if (名前一覧一覧[数 * 64] != 0) {
            for (int 槽入口 = 0; 槽入口 < 64 && 名前一覧一覧[数 * 64 + 槽入口] != 0; 槽入口++) 文字端末.文字(名前一覧一覧[数 * 64 + 槽入口]);
            文字端末.書込("  "); 文字端末.番号書込(容量列[数]); 文字端末.書込("バイト値\n");
        }
        文字端末.書込(記憶装置接続.判定利用可能 ? "ファイル 8칸, 파일당 16384바이트; sync로 格納値 장치에 보존\n"
            : "一時値 ファイル 8칸, 파일당 16384바이트; 再試行処理値 시작하면 사라짐\n");
    }

    static void 命令(int[] 入力値, int 起動処理, int 長さ, int 動作) {
        while (起動処理 < 長さ && 入力値[起動処理] == ' ') 起動処理++;
        int 終端 = 長さ;
        while (終端 > 起動処理 && 入力値[終端 - 1] == ' ') 終端--;
        int 数 = 終端 - 起動処理;
        if (数 < 1 || 数 > 63) { 文字端末.書込("올바르지 않은 ファイル 名前\n"); return; }
        for (int 槽入口 = 0; 槽入口 < 64; 槽入口++) 名前[槽入口] = 槽入口 < 数 ? 入力値[起動処理 + 槽入口] : 0;
        int 番号 = 入口探索(名前, 数);
        if (番号 == -22) { 文字端末.書込("올바르지 않은 ファイル 名前\n"); return; }
        if (動作 == 0) {
            判定編集中 = true; 編集容量 = 0; 桁あふれ値 = false;
            文字端末.書込("원문을 입력하세요. .save는 보존, .cancel은 취소합니다.\n");
        } else if (番号 < 0) 文字端末.書込("파일을 찾을 数 없습니다\n");
        else if (動作 == 1) {
            int 番地 = 装置.ファイル記憶() + 番号 * 最大容量;
            for (int 槽入口 = 0; 槽入口 < 容量列[番号]; 槽入口++) 文字端末.文字(装置.記憶読取(番地 + 槽入口));
            文字端末.文字(10);
        } else { 名前一覧一覧[番号 * 64] = 0; 容量列[番号] = 0; 文字端末.書込("파일을 지웠습니다\n"); }
    }

    static boolean 判定厳密(int[] 入力値, int 長さ, String 句値) {
        if (長さ != 句値.length()) return false;
        for (int 槽入口 = 0; 槽入口 < 長さ; 槽入口++) if (入力値[槽入口] != 句値.charAt(槽入口)) return false;
        return true;
    }

    static void 編集済み行(int[] 入力値, int 長さ, boolean 行桁あふれ) {
        if (判定厳密(入力値, 長さ, ".cancel")) {
            判定編集中 = false; 文字端末.書込("취소했습니다. 원래 파일은 그대로입니다\n");
        } else if (判定厳密(入力値, 長さ, ".save")) {
            判定編集中 = false;
            if (桁あふれ値) { 文字端末.書込("입력이 너무 깁니다. 원래 파일은 그대로입니다\n"); return; }
            int 数 = 0;
            while (数 < 64 && 名前[数] != 0) 数++;
            int 結果 = 格納値(名前, 数, 編集値, 編集容量);
            文字端末.書込(結果 >= 0 ? "보존한 バイト値 数: " : "보존 失敗値: ");
            文字端末.番号書込(結果); 文字端末.文字(10);
        } else if (行桁あふれ || 長さ + 1 > 最大容量 - 編集容量) 桁あふれ値 = true;
        else {
            for (int 数 = 0; 数 < 長さ; 数++) 編集値[編集容量++] = 入力値[数];
            編集値[編集容量++] = 10;
        }
    }

    static void 用例(String ファイル, String 内容物値) {
        for (int 数 = 0; 数 < 64; 数++) 名前[数] = 数 < ファイル.length() ? ファイル.charAt(数) : 0;
        for (int 数 = 0; 数 < 内容物値.length(); 数++) 編集値[数] = 内容物値.charAt(数);
        格納値(名前, ファイル.length(), 編集値, 内容物値.length());
    }

    static void 用意() {
        用例("Hello.java", "public class Hello {\n public static void main(String[] args) {\n  System.out.println(\"Hello from jkoros JVM!\");\n  int sum = 0;\n  for (int i = 1; i <= 10; i++) { sum = sum + i; }\n  System.out.println(sum);\n }\n}\n");
        int 集合値 = 装置.Javaファイル束(), 容量 = 装置.Javaファイル束容量();
        if (容量 < 8 || 実行管理.数(集合値) != 0x464a4b4a) { 文字端末.書込("올바르지 않은 Java ファイル 集合値\n"); return; }
        int 項目個数 = 実行管理.数(集合値 + 4);
        if (項目個数 < 0 || 項目個数 > 8 || 項目個数 > (容量 - 8) / 72) { 文字端末.書込("올바르지 않은 Java ファイル 入口一覧\n"); return; }
        for (int 数 = 0; 数 < 項目個数; 数++) {
            int 入口値 = 集合値 + 8 + 数 * 72, 長さ = 0;
            for (int 槽入口 = 0; 槽入口 < 64; 槽入口++) 名前[槽入口] = 装置.記憶読取(入口値 + 槽入口);
            while (長さ < 64 && 名前[長さ] != 0) 長さ++;
            int 位置 = 実行管理.数(入口値 + 64), ファイル容量 = 実行管理.数(入口値 + 68);
            if (!名前検査(名前, 長さ) || ファイル容量 < 0 || ファイル容量 > 最大容量 || 位置 < 8 + 項目個数 * 72 || 位置 > 容量 - ファイル容量) {
                文字端末.書込("올바르지 않은 Java ファイル 入口値\n"); return;
            }
            for (int 槽入口 = 0; 槽入口 < ファイル容量; 槽入口++) 編集値[槽入口] = 装置.記憶読取(集合値 + 位置 + 槽入口);
            if (格納値(名前, 長さ, 編集値, ファイル容量) < 0) { 文字端末.書込("Java 파일을 가져오지 못했습니다\n"); return; }
        }
    }
}
