#include "通信網ABI.h"

int 利用者プログラム開始処理(int 引数) {
    (void)引数;
    struct インターネットソケット番地 番地 = {0};
    番地.番地体系 = インターネット体系;
    番地.ポート番号 = 通信網短整数(9260);
    番地.インターネット番地.番地値 = 通信網整数値(折返し番地);
    int サーバー値 = 通信端点作成(インターネット体系, ストリーム通信網, ストリーム輸送通信規約);
    if (サーバー値 < 0 || 番地結合(サーバー値, (struct ソケット番地 *)&番地, sizeof(番地)) < 0 ||
        対象通信網接続状態待合(サーバー値, 4) < 0) return 1;
    if (通信網接続状態受理(サーバー値, 0, 0) != -1 || エラー番号 != 11) return 2;
    int ゲスト値 = 通信端点作成(インターネット体系, ストリーム通信網, ストリーム輸送通信規約);
    if (ゲスト値 < 0 || 通信網接続(ゲスト値, (struct ソケット番地 *)&番地, sizeof(番地)) < 0) return 3;
    int 接続 = 通信網接続状態受理(サーバー値, 0, 0);
    if (接続 < 0) return 4;
    unsigned char 項目到達先送信[1500], 受信済み項目[1500];
    for (int 数 = 0; 数 < 1500; 数++) 項目到達先送信[数] = (unsigned char)数;
    int 送信済み個数 = 0;
    while (送信済み個数 < 1024) {
        int 長さ = ファイルデータ書込(ゲスト値, 項目到達先送信 + 送信済み個数, sizeof(項目到達先送信) - 送信済み個数);
        if (長さ <= 0) return 5;
        送信済み個数 += 長さ;
    }
    if (ファイルデータ書込(ゲスト値, 項目到達先送信, 1) != -1 || エラー番号 != 11) return 6;
    /* 상대가 닫아도 이미 도착한 자료를 全体構築 읽은 後端値 EOF가 된다. */
    ファイル閉鎖(ゲスト値);
    int 受信済み個数 = 0;
    while (受信済み個数 < 送信済み個数) {
        int 長さ = ファイルデータ読取(接続, 受信済み項目 + 受信済み個数, sizeof(受信済み項目) - 受信済み個数);
        if (長さ <= 0) return 7;
        受信済み個数 += 長さ;
    }
    for (int 数 = 0; 数 < 受信済み個数; 数++) if (受信済み項目[数] != 項目到達先送信[数]) return 8;
    if (ファイルデータ読取(接続, 受信済み項目, 1) != 0) return 9;
    if (ファイルデータ書込(接続, 項目到達先送信, 1) != -1 || エラー番号 != 32) return 10;
    ファイル閉鎖(接続); ファイル閉鎖(サーバー値);
    const char 結果[] = "C posix-kor 연결형 通信 PASS\n";
    ファイルデータ書込(1, 結果, sizeof(結果) - 1);
    return 0;
}
