#include "ファイルABI.h"
class 文書管理器 {
    int 番号;
public:
    文書管理器(const char *名前) : 番号(ファイル開放(名前, 読取書込 | 作成条件未存在 | 切詰め内容, 0600)) {}
    ~文書管理器() { if (番号 >= 0) ファイル閉鎖(番号); }
    入出力結果型 書込(const char *データ, バイト個数型 容量) { return ファイルデータ書込(番号, データ, 容量); }
};
extern "C" int 利用者プログラム開始処理(int 引数) {
    (void)引数;
    const char 挨拶文[] = "C++에서 한글 클래스와 posix-kor 呼出\n";
    文書管理器 文書("C++挨拶例.txt");
    ファイルデータ書込(1, 挨拶文, sizeof(挨拶文) - 1);
    return 文書.書込(挨拶文, sizeof(挨拶文) - 1) == sizeof(挨拶文) - 1 ? 0 : 1;
}
