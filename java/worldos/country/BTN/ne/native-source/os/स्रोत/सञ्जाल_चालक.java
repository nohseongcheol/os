/** PCI RTL8139 (10ec:8139), 단일 पठाउनुहोस्_मान 버퍼와 8KiB 수신 लुप_मान. 인터럽트 대신 폴링한다. */
public final class सञ्जाल_चालक {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] मोबाइल_ठेगाना = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int स्थिति) {
        मोबाइल_मान.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | स्थिति);
        return मोबाइल_मान.입출력정수읽기(0xcfc);
    }

    static boolean तयार_गर्नुहोस्() {
        int 장치번호 = -1;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 32; अनुक्रमणिका++) {
            if (설정읽기(अनुक्रमणिका, 0) == 0x813910ec) { 장치번호 = अनुक्रमणिका; break; }
        }
        if (장치번호 < 0) return false;
        int पूर्वनिर्धारित_मान = 설정읽기(장치번호, 0x10);
        if ((पूर्वनिर्धारित_मान & 1) == 0 || (पूर्वनिर्धारित_मान & 0xfffffffc) < 0x100 || (पूर्वनिर्धारित_मान & 0xfffffffc) > 65535) return false;
        입출력기준주소 = पूर्वनिर्धारित_मान & 0xfffc;
        int आदेश = 설정읽기(장치번호, 4);
        मोबाइल_मान.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        मोबाइल_मान.입출력짧은수쓰기(0xcfc, आदेश | 5); // I/O 및 bus master अनुमति_दिनुहोस्_मान, PCI स्थिति_मान 비트는 건드리지 않음
        मोबाइल_मान.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!रिसेट_गर्नुहोस्_मान()) { 입출력기준주소 = 0; return false; }
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 6; अनुक्रमणिका++) मोबाइल_ठेगाना[अनुक्रमणिका] = मोबाइल_मान.입출력바이트읽기(입출력기준주소 + अनुक्रमणिका);
        return true;
    }

    static boolean रिसेट_गर्नुहोस्_मान() {
        मोबाइल_मान.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int चलाउनुहोस् = मोबाइल_मान.밀리초();
        while ((मोबाइल_मान.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (मोबाइल_मान.밀리초() - चलाउनुहोस् > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        मोबाइल_मान.입출력정수쓰기(입출력기준주소 + 0x30, मोबाइल_मान.सञ्जाल_मेमोरी());
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 4; अनुक्रमणिका++) मोबाइल_मान.입출력정수쓰기(입출력기준주소 + 0x20 + अनुक्रमणिका * 4, मोबाइल_मान.सञ्जाल_मेमोरी() + 12288);
        मोबाइल_मान.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        मोबाइल_मान.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        मोबाइल_मान.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        मोबाइल_मान.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/ब्रोडकास्ट_मान, wrap 연속 भण्डार_गर्नुहोस्_मान, 8KiB
        मोबाइल_मान.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int पठाउनुहोस्(int[] लगत, int लम्बाइ_मान) {
        if (입출력기준주소 == 0) return -19;
        if (लम्बाइ_मान < 14 || लम्बाइ_मान > 1514) return -90;
        int स्थिति_पोर्ट = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int चलाउनुहोस् = मोबाइल_मान.밀리초();
        while ((मोबाइल_मान.입출력정수읽기(स्थिति_पोर्ट) & 0x2000) == 0)
            if (मोबाइल_मान.밀리초() - चलाउनुहोस् > 100) return -110;
        int आकार = लम्बाइ_मान < 60 ? 60 : लम्बाइ_मान;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < आकार; अनुक्रमणिका++)
            मोबाइल_मान.लेख्नुहोस्_मेमोरी(मोबाइल_मान.सञ्जाल_मेमोरी() + 12288 + अनुक्रमणिका, अनुक्रमणिका < लम्बाइ_मान ? लगत[अनुक्रमणिका] : 0);
        मोबाइल_मान.입출력정수쓰기(स्थिति_पोर्ट, आकार | 0x00080000);
        चलाउनुहोस् = मोबाइल_मान.밀리초();
        while ((मोबाइल_मान.입출력정수읽기(स्थिति_पोर्ट) & 0xe0008000) == 0)
            if (मोबाइल_मान.밀리초() - चलाउनुहोस् > 100) return -110;
        if ((मोबाइल_मान.입출력정수읽기(स्थिति_पोर्ट) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return लम्बाइ_मान;
    }

    static int 받기(int[] लगत) {
        if (입출력기준주소 == 0) return 0;
        if ((मोबाइल_मान.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!रिसेट_गर्नुहोस्_मान()) 입출력기준주소 = 0;
            return 0;
        }
        if ((मोबाइल_मान.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = मोबाइल_मान.सञ्जाल_मेमोरी() + 수신위치;
        int स्थिति_मान = 실행관리.짧은수(머리), आकार = 실행관리.짧은수(머리 + 2);
        if (आकार == 0xfff0) return 0; // DMA 진행 중
        if (आकार < 4 || आकार > 1518) {
            오류수++;
            if (!रिसेट_गर्नुहोस्_मान()) 입출력기준주소 = 0;
            return 0;
        }
        int लम्बाइ_मान = आकार - 4;
        if ((स्थिति_मान & 1) != 0) {
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < लम्बाइ_मान; अनुक्रमणिका++) लगत[अनुक्रमणिका] = मोबाइल_मान.기억읽기(머리 + 4 + अनुक्रमणिका);
            수신수++;
        } else { लम्बाइ_मान = 0; 오류수++; }
        수신위치 = (수신위치 + आकार + 4 + 3) & ~3;
        수신위치 &= 8191;
        मोबाइल_मान.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        मोबाइल_मान.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return लम्बाइ_मान;
    }
}
