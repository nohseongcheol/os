    private static void 기억공간시험(कर्णेल कर्णेल_मान) {
        मेमोरी_प्रबन्धक प्रबन्धक_मान = कर्णेल_मान.기억공간();
        int 첫주소 = प्रबन्धक_मान.정렬할당(100, 64);
        रुजू_गर्नुहोस्((첫주소 & 63) == 0, "पङ्_क्तिबद्ध_गर्नुहोस्_मान निर्धारण_गर्नुहोस्_भण्डारण");
        प्रबन्धक_मान.लेख्नुहोस्_बाइट_मान(첫주소, (byte) 0x5a);
        रुजू_गर्नुहोस्(प्रबन्धक_मान.바이트읽기(첫주소) == (byte) 0x5a, "물리 기억공간 읽고 लेख्नुहोस्");
        int 사용전 = प्रबन्धक_मान.사용크기();
        प्रबन्धक_मान.जारी_भण्डारण(첫주소);
        रुजू_गर्नुहोस्(प्रबन्धक_मान.사용크기() < 사용전, "기억공간 जारी_भण्डारण");
    }

    private static void 쪽관리시험(कर्णेल कर्णेल_मान) {
        पृष्ठ_प्रबन्धक प्रबन्धक_मान = कर्णेल_मान.쪽관리();
        पृष्ठ_प्रबन्धक.ठेगाना_स्थान 부모공간 = प्रबन्धक_मान.새주소공간();
        प्रबन्धक_मान.मानचित्र_पृष्ठ(부모공간, 0x1000, true);
        प्रबन्धक_मान.लेख्नुहोस्_बाइट_मान(부모공간, 0x1010, (byte) 7);
        पृष्ठ_प्रबन्धक.ठेगाना_स्थान बच्चा_स्थान = प्रबन्धक_मान.쓰기시복사복제(부모공간);
        प्रबन्धक_मान.लेख्नुहोस्_बाइट_मान(बच्चा_स्थान, 0x1010, (byte) 9);
        रुजू_गर्नुहोस्(प्रबन्धक_मान.바이트읽기(부모공간, 0x1010) == 7, "लेख्नुहोस् 시 उद्धरण_मान_37b3d3b1 부모 격리");
        रुजू_गर्नुहोस्(प्रबन्धक_मान.바이트읽기(बच्चा_स्थान, 0x1010) == 9, "लेख्नुहोस् 시 उद्धरण_मान_37b3d3b1 बच्चा_मान लेख्नुहोस्");
    }

    private static void 파일과과정시험(कर्णेल कर्णेल_मान) {
        byte[] सामग्री_मान = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        कर्णेल_मान.फाइल_प्रणाली().파일추가("시험", सामग्री_मान);
        प्रक्रिया_मान 부모 = कर्णेल_मान.첫과정();
        체계호출 호출 = कर्णेल_मान.체계호출();
        int 서술자 = 호출.खोल्नुहोस्(부모, "/시험", 체계호출.पढ्न_मात्र_झन्डा);
        रुजू_गर्नुहोस्(서술자 >= 3, "फाइल खोल्नुहोस्");

        byte[] 받을곳 = new byte[सामग्री_मान.length];
        रुजू_गर्नुहोस्(호출.पढनुहोस्(부모, 서술자, 받을곳, 받을곳.length) == सामग्री_मान.length, "फाइल पढनुहोस्");
        रुजू_गर्नुहोस्(Arrays.equals(सामग्री_मान, 받을곳), "फाइल सामग्री_मान");
        रुजू_गर्नुहोस्(호출.लैजानुहोस्_राख्नुहोस्(부모, 서술자, 0, 체계호출.खोज_सुरु) == 0, "फाइल स्थिति लैजानुहोस्_मान");

        int 복제서술자 = 호출.서술자복제(부모, 서술자);
        रुजू_गर्नुहोस्(복제서술자 >= 0, "서술자 복제");
        प्रक्रिया_मान बच्चा_मान = 호출.과정복제(부모);
        रुजू_गर्नुहोस्(बच्चा_मान.परिचायक_मान() != 부모.परिचायक_मान(), "प्रक्रिया_मान परिचायक_मान 분리");
        रुजू_गर्नुहोस्(बच्चा_मान.부모식별자() == 부모.परिचायक_मान(), "부모 प्रक्रिया_मान परिचायक_मान");
        रुजू_गर्नुहोस्(호출.बन्दगर्नुहोस्(बच्चा_मान, 서술자) == 0 && 부모.파일서술자().열려있음(서술자), "बच्चा_मान बन्दगर्नुहोस् 격리");

        int 이전끝 = 호출.프로그램끝늘리기(부모, 8192);
        रुजू_गर्नुहोस्(이전끝 == 0x06000000, "अनुप्रयोग_f5044b9b 끝 늘리기");
        रुजू_गर्नुहोस्(부모.프로그램끝() == 0x06002000, "अनुप्रयोग_f5044b9b 끝 반영");
        रुजू_गर्नुहोस्(बच्चा_मान.프로그램끝() == 0x06000000, "과정별 अनुप्रयोग_f5044b9b 끝 격리");

        बच्चा_मान.बाहिर_जानुहोस्_अनुप्रयोग(7);
        रुजू_गर्नुहोस्(호출.자식기다리기(부모, बच्चा_मान.परिचायक_मान(), false) == (7 << 8), "बच्चा_मान बाहिर_जानुहोस्_अनुप्रयोग 기다리기");
        रुजू_गर्नुहोस्(호출.접근가능("시험", 1) == -13, "कार्यान्वयन_गर्नुहोस्_आदेश अनुमति_मान 거부");
        रुजू_गर्नुहोस्(호출.प्रयोगकर्ता_परिचायक() == 0 && 호출.समूह_परिचायक() == 0, "사용자와 무리 परिचायक_मान");
        रुजू_गर्नुहोस्("/".equals(호출.현재작업목록(2)) && 호출.परिवर्तन_कार्यसूची("/") == 0, "현재 작업 प्रविष्टि_सूची");
        रुजू_गर्नुहोस्(호출.단말인가(부모, 1), "표준 출력 단말");
        रुजू_गर्नुहोस्("JBtnOS".equals(호출.체계정보().प्रणाली_नाम()), "सञ्चालनप्रणाली_मान प्रणाली_जानकारी");
    }

