        int 서술자 = कर्णेल_मान.체계호출().खोल्नुहोस्(कर्णेल_मान.첫과정(), "시험", 체계호출.पढ्न_मात्र_झन्डा);
        रुजू_गर्नुहोस्(कर्णेल_मान.체계호출().फाइल_नियन्त्रण(कर्णेल_मान.첫과정(), 서술자, 2, 1) == 0, "कार्यान्वयन_गर्नुहोस्_आदेश 시 बन्दगर्नुहोस् सेटिङ");
