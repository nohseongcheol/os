                    if (문자값 == '`' && 따옴표 != 39 || 문자값 == '$' && 따옴표 != 39 && 현재자리 + 1 < 항목수 && 원문[기준자리 + 현재자리 + 1] == '(') { 오류("명령 결과 치환은 지원하지 않습니다"); return -1; }
