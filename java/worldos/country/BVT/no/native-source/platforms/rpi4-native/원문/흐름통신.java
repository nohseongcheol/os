/** 커널 안의 연결형 바이트 흐름. Ethernet/TCP 패킷 스택이 아닌 루프백 socket 계층. */
public final class 흐름통신 {
    static int[] 상태 = new int[16], 창구 = new int[16], 짝 = new int[16], 상대창구 = new int[16], 대기 = new int[16], 묶임 = new int[16];
    static int[] 앞 = new int[16], 수 = new int[16], 자료 = new int[16 * 1024];
    static int 다음 = 50000;
    static int 확인(int 열린파일번호) { return 열린파일번호 >= 40 && 열린파일번호 < 56 && 상태[열린파일번호 - 40] != 0 ? 열린파일번호 - 40 : -1; }
    static boolean 사용중(int 접속번호) { for (int 반복자리 = 0; 반복자리 < 16; 반복자리++) if (상태[반복자리] != 0 && 묶임[반복자리] != 0 && 창구[반복자리] == 접속번호) return true; return false; }
    public static int 만들기() {
        for (int 반복자리 = 0; 반복자리 < 16; 반복자리++) if (상태[반복자리] == 0) { 상태[반복자리] = 1; 상대창구[반복자리] = 창구[반복자리] = 앞[반복자리] = 수[반복자리] = 대기[반복자리] = 묶임[반복자리] = 0; 짝[반복자리] = -1; return 반복자리 + 40; }
        return -24;
    }
    public static int 묶기(int 열린파일번호, int 통신주소, int 접속번호) {
        int 반복자리 = 확인(열린파일번호); if (반복자리 < 0) return -9;
        if (통신주소 != 0 && 통신주소 != 0x7f000001) return -99;
        if (상태[반복자리] != 1 || 접속번호 < 0 || 접속번호 > 65535) return -22;
        if (접속번호 == 0) { do { 접속번호 = 다음++; if (다음 > 65535) 다음 = 50000; } while (사용중(접속번호)); }
        if (사용중(접속번호)) return -98; 창구[반복자리] = 접속번호; 묶임[반복자리] = 1; 상태[반복자리] = 2; return 0;
    }
    public static int 듣기(int 열린파일번호, int 연결대기한도) { int 반복자리 = 확인(열린파일번호); if (반복자리 < 0) return -9; if (상태[반복자리] != 2 || 연결대기한도 < 1) return -22; 상태[반복자리] = 3; return 0; }
    public static int 연결(int 열린파일번호, int 통신주소, int 접속번호) {
        int 반복자리 = 확인(열린파일번호); if (반복자리 < 0) return -9; if (통신주소 != 0x7f000001) return -101;
        if (접속번호 < 1 || 접속번호 > 65535 || 상태[반복자리] > 2) return -22;
        int 수신쪽 = -1; for (int 안쪽자리 = 0; 안쪽자리 < 16; 안쪽자리++) if (상태[안쪽자리] == 3 && 창구[안쪽자리] == 접속번호) 수신쪽 = 안쪽자리;
        if (수신쪽 < 0) return -111;
        int 대기여부 = 0; for (int 안쪽자리 = 0; 안쪽자리 < 16; 안쪽자리++) if (대기[안쪽자리] == 수신쪽 + 1) 대기여부++;
        if (대기여부 >= 4) return -11;
        if (상태[반복자리] == 1) { int 처리값 = 묶기(열린파일번호, 0x7f000001, 0); if (처리값 < 0) return 처리값; }
        int 다른번호 = 만들기(); if (다른번호 < 0) return 다른번호; 다른번호 -= 40;
        상태[반복자리] = 상태[다른번호] = 4; 짝[반복자리] = 다른번호; 짝[다른번호] = 반복자리; 창구[다른번호] = 접속번호; 상대창구[반복자리] = 접속번호; 상대창구[다른번호] = 창구[반복자리]; 대기[다른번호] = 수신쪽 + 1; return 0;
    }
    public static int 받음(int 열린파일번호) { int 반복자리 = 확인(열린파일번호); if (반복자리 < 0) return -9; if (상태[반복자리] != 3) return -22; for (int 안쪽자리 = 0; 안쪽자리 < 16; 안쪽자리++) if (상태[안쪽자리] != 0 && 대기[안쪽자리] == 반복자리 + 1) { 대기[안쪽자리] = 0; return 안쪽자리 + 40; } return -11; }
    public static int 쓰기(int 열린파일번호, int 항목수) {
        int 반복자리 = 확인(열린파일번호); if (반복자리 < 0) return -9; if (상태[반복자리] != 4) return -107;
        if (항목수 < 0 || 항목수 > 512) return -22; if (항목수 == 0) return 0;
        int 안쪽자리 = 짝[반복자리]; if (안쪽자리 < 0) return -32; int 총수 = 1024 - 수[안쪽자리]; if (총수 == 0) return -11; if (총수 > 항목수) 총수 = 항목수;
        for (int 비교자리 = 0; 비교자리 < 총수; 비교자리++) 자료[안쪽자리 * 1024 + (앞[안쪽자리] + 수[안쪽자리] + 비교자리) % 1024] = 되돌림망.전달[비교자리]; 수[안쪽자리] += 총수; return 총수;
    }
    public static int 읽기(int 열린파일번호, int 항목수) {
        int 반복자리 = 확인(열린파일번호); if (반복자리 < 0) return -9; if (상태[반복자리] != 4) return -107; if (항목수 < 0 || 항목수 > 512) return -22;
        if (항목수 == 0) return 0; if (수[반복자리] == 0) return 짝[반복자리] < 0 ? 0 : -11; if (항목수 > 수[반복자리]) 항목수 = 수[반복자리];
        for (int 비교자리 = 0; 비교자리 < 항목수; 비교자리++) 되돌림망.전달[비교자리] = 자료[반복자리 * 1024 + (앞[반복자리] + 비교자리) % 1024]; 앞[반복자리] = (앞[반복자리] + 항목수) % 1024; 수[반복자리] -= 항목수; return 항목수;
    }
    public static int 창구읽기(int 열린파일번호) { int 반복자리 = 확인(열린파일번호); return 반복자리 < 0 ? -9 : 창구[반복자리]; }
    public static int 상대창구읽기(int 열린파일번호) { int 반복자리 = 확인(열린파일번호); return 반복자리 < 0 ? -9 : 상대창구[반복자리]; }
    public static int Lukk(int 열린파일번호) {
        int 반복자리 = 확인(열린파일번호); if (반복자리 < 0) return -9;
        if (상태[반복자리] == 3) for (int 안쪽자리 = 0; 안쪽자리 < 16; 안쪽자리++) if (대기[안쪽자리] == 반복자리 + 1) { if (짝[안쪽자리] >= 0) 짝[짝[안쪽자리]] = -1; 상태[안쪽자리] = 대기[안쪽자리] = 묶임[안쪽자리] = 0; }
        if (짝[반복자리] >= 0) 짝[짝[반복자리]] = -1; 상태[반복자리] = 묶임[반복자리] = 수[반복자리] = 대기[반복자리] = 0; return 0;
    }
}
