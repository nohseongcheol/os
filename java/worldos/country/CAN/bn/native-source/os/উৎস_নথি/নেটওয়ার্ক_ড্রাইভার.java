/** PCI RTL8139 (10ec:8139), 단일 পাঠান_মান 버퍼와 8KiB 수신 লুপ_মান. 인터럽트 대신 폴링한다. */
public final class নেটওয়ার্ক_ড্রাইভার {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] ডিভাইস_ইমেইল = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int অবস্থান) {
        ডিভাইস_মান.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | অবস্থান);
        return ডিভাইস_মান.입출력정수읽기(0xcfc);
    }

    static boolean প্রস্তুত_করুন() {
        int 장치번호 = -1;
        for (int সূচি = 0; সূচি < 32; সূচি++) {
            if (설정읽기(সূচি, 0) == 0x813910ec) { 장치번호 = সূচি; break; }
        }
        if (장치번호 < 0) return false;
        int অমনোনীত_মান = 설정읽기(장치번호, 0x10);
        if ((অমনোনীত_মান & 1) == 0 || (অমনোনীত_মান & 0xfffffffc) < 0x100 || (অমনোনীত_মান & 0xfffffffc) > 65535) return false;
        입출력기준주소 = অমনোনীত_মান & 0xfffc;
        int আদেশ = 설정읽기(장치번호, 4);
        ডিভাইস_মান.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        ডিভাইস_মান.입출력짧은수쓰기(0xcfc, আদেশ | 5); // I/O 및 bus master সম্মতি_মান, PCI অবস্হা_মান 비트는 건드리지 않음
        ডিভাইস_মান.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!রিসেট_করা_মান()) { 입출력기준주소 = 0; return false; }
        for (int সূচি = 0; সূচি < 6; সূচি++) ডিভাইস_ইমেইল[সূচি] = ডিভাইস_মান.입출력바이트읽기(입출력기준주소 + সূচি);
        return true;
    }

    static boolean রিসেট_করা_মান() {
        ডিভাইস_মান.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int চালনা = ডিভাইস_মান.밀리초();
        while ((ডিভাইস_মান.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (ডিভাইস_মান.밀리초() - চালনা > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        ডিভাইস_মান.입출력정수쓰기(입출력기준주소 + 0x30, ডিভাইস_মান.নেটওয়ার্ক_মেমরি());
        for (int সূচি = 0; সূচি < 4; সূচি++) ডিভাইস_মান.입출력정수쓰기(입출력기준주소 + 0x20 + সূচি * 4, ডিভাইস_মান.নেটওয়ার্ক_মেমরি() + 12288);
        ডিভাইস_মান.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        ডিভাইস_মান.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        ডিভাইস_মান.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        ডিভাইস_মান.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/সম্প্রচার_মান, wrap 연속 ভাণ্ডার_মান, 8KiB
        ডিভাইস_মান.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int পাঠান(int[] ডাটা, int দৈর্ঘ্য_মান) {
        if (입출력기준주소 == 0) return -19;
        if (দৈর্ঘ্য_মান < 14 || দৈর্ঘ্য_মান > 1514) return -90;
        int অবস্থা_পোর্ট = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int চালনা = ডিভাইস_মান.밀리초();
        while ((ডিভাইস_মান.입출력정수읽기(অবস্থা_পোর্ট) & 0x2000) == 0)
            if (ডিভাইস_মান.밀리초() - চালনা > 100) return -110;
        int আকার = দৈর্ঘ্য_মান < 60 ? 60 : দৈর্ঘ্য_মান;
        for (int সূচি = 0; সূচি < আকার; সূচি++)
            ডিভাইস_মান.লেখা_মেমরি(ডিভাইস_মান.নেটওয়ার্ক_মেমরি() + 12288 + সূচি, সূচি < দৈর্ঘ্য_মান ? ডাটা[সূচি] : 0);
        ডিভাইস_মান.입출력정수쓰기(অবস্থা_পোর্ট, আকার | 0x00080000);
        চালনা = ডিভাইস_মান.밀리초();
        while ((ডিভাইস_মান.입출력정수읽기(অবস্থা_পোর্ট) & 0xe0008000) == 0)
            if (ডিভাইস_মান.밀리초() - চালনা > 100) return -110;
        if ((ডিভাইস_মান.입출력정수읽기(অবস্থা_পোর্ট) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return দৈর্ঘ্য_মান;
    }

    static int 받기(int[] ডাটা) {
        if (입출력기준주소 == 0) return 0;
        if ((ডিভাইস_মান.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!রিসেট_করা_মান()) 입출력기준주소 = 0;
            return 0;
        }
        if ((ডিভাইস_মান.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = ডিভাইস_মান.নেটওয়ার্ক_মেমরি() + 수신위치;
        int অবস্হা_মান = 실행관리.짧은수(머리), আকার = 실행관리.짧은수(머리 + 2);
        if (আকার == 0xfff0) return 0; // DMA 진행 중
        if (আকার < 4 || আকার > 1518) {
            오류수++;
            if (!রিসেট_করা_মান()) 입출력기준주소 = 0;
            return 0;
        }
        int দৈর্ঘ্য_মান = আকার - 4;
        if ((অবস্হা_মান & 1) != 0) {
            for (int সূচি = 0; সূচি < দৈর্ঘ্য_মান; সূচি++) ডাটা[সূচি] = ডিভাইস_মান.기억읽기(머리 + 4 + সূচি);
            수신수++;
        } else { দৈর্ঘ্য_মান = 0; 오류수++; }
        수신위치 = (수신위치 + আকার + 4 + 3) & ~3;
        수신위치 &= 8191;
        ডিভাইস_মান.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        ডিভাইস_মান.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return দৈর্ঘ্য_মান;
    }
}
