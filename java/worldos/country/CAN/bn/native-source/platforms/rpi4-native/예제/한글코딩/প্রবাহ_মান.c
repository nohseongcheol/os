#include "통신규약.h"

int শুরু_ব্যবহারকারী_অ্যাপ(int আর্গুমেন্ট_তালিকা) {
    (void)আর্গুমেন্ট_তালিকা;
    struct 인터넷통신주소 ইমেইল = {0};
    ইমেইল.ইমেইল_পরিবার = ক্লাউড_পরিবার;
    ইমেইল.পোর্ট_নম্বর = 망차례짧은수(9260);
    ইমেইল.ইন্টারনেট_ঠিকানা.ইমেইল_মান = নেটওয়ার্ক_পূর্ণসংখ্যা(되돌림주소);
    int সার্ভার_মান = 통신종단점만들기(ক্লাউড_পরিবার, প্রবাহ_নেটওয়ার্ক, 흐름전송규약);
    if (সার্ভার_মান < 0 || বন্ধন_করা_ইমেইল(সার্ভার_মান, (struct 통신주소 *)&ইমেইল, sizeof(ইমেইল)) < 0 ||
        통신연결기다리기(সার্ভার_মান, 4) < 0) return 1;
    if (স্বীকার_করুন_নেটওয়ার্ক_সংযোগ(সার্ভার_মান, 0, 0) != -1 || 오류번호 != 11) return 2;
    int অতিথি_মান = 통신종단점만들기(ক্লাউড_পরিবার, প্রবাহ_নেটওয়ার্ক, 흐름전송규약);
    if (অতিথি_মান < 0 || সংযোগ_নেটওয়ার্ক(অতিথি_মান, (struct 통신주소 *)&ইমেইল, sizeof(ইমেইল)) < 0) return 3;
    int সংযোগ_স্থাপনা = স্বীকার_করুন_নেটওয়ার্ক_সংযোগ(সার্ভার_মান, 0, 0);
    if (সংযোগ_স্থাপনা < 0) return 4;
    unsigned char 보낼것[1500], 받은것[1500];
    for (int 수 = 0; 수 < 1500; 수++) 보낼것[수] = (unsigned char)수;
    int 보낸수 = 0;
    while (보낸수 < 1024) {
        int দৈর্ঘ্য_মান = লেখা_ফাইল_ডাটা(অতিথি_মান, 보낼것 + 보낸수, sizeof(보낼것) - 보낸수);
        if (দৈর্ঘ্য_মান <= 0) return 5;
        보낸수 += দৈর্ঘ্য_মান;
    }
    if (লেখা_ফাইল_ডাটা(অতিথি_মান, 보낼것, 1) != -1 || 오류번호 != 11) return 6;
    /* 상대가 닫아도 이미 도착한 자료를 모두 읽은 ফিরে_যান_মান EOF가 된다. */
    বন্ধ_ফাইল(অতিথি_মান);
    int 받은수 = 0;
    while (받은수 < 보낸수) {
        int দৈর্ঘ্য_মান = 파일자료읽기(সংযোগ_স্থাপনা, 받은것 + 받은수, sizeof(받은것) - 받은수);
        if (দৈর্ঘ্য_মান <= 0) return 7;
        받은수 += দৈর্ঘ্য_মান;
    }
    for (int 수 = 0; 수 < 받은수; 수++) if (받은것[수] != 보낼것[수]) return 8;
    if (파일자료읽기(সংযোগ_স্থাপনা, 받은것, 1) != 0) return 9;
    if (লেখা_ফাইল_ডাটা(সংযোগ_স্থাপনা, 보낼것, 1) != -1 || 오류번호 != 32) return 10;
    বন্ধ_ফাইল(সংযোগ_স্থাপনা); বন্ধ_ফাইল(সার্ভার_মান);
    const char পরিমাপ[] = "C posix-kor 연결형 통신 PASS\n";
    লেখা_ফাইল_ডাটা(1, পরিমাপ, sizeof(পরিমাপ) - 1);
    return 0;
}
