Λίστα_διαδρομή = "/lib/.pip.json"


def 지문(δεδομένα):
    return "".join("%02x" % τιμή for τιμή in hashlib.sha256(δεδομένα).digest())


def 목록읽기():
    if λειτουργικό_σύστημα.path_kind(Λίστα_διαδρομή) == 0:
        return {}
    return json.loads(λειτουργικό_σύστημα.read(Λίστα_διαδρομή).decode("utf-8"))


def εγγράφω_καταγράφω(ΔΙΑΔΡΟΜΗ, δεδομένα):
    if λειτουργικό_σύστημα.write(ΔΙΑΔΡΟΜΗ, δεδομένα) != len(δεδομένα):
        raise OSError(28)


def ελέγχω_διαδρομή(ΔΙΑΔΡΟΜΗ):
    if not isinstance(ΔΙΑΔΡΟΜΗ, str) or not ΔΙΑΔΡΟΜΗ.endswith(".py"):
        raise ValueError("Python 소스만 설치할 수 있습니다.")
    if any(부분 in ("", ".", "..") or 부분.startswith(".") for 부분 in ΔΙΑΔΡΟΜΗ.split("/")):
        raise ValueError("허용하지 않는 πακέτο ΔΙΑΔΡΟΜΗ")
    if "\\" in ΔΙΑΔΡΟΜΗ or any(ord(χαρακτήρας_τιμή) < 32 or ord(χαρακτήρας_τιμή) == 127 for χαρακτήρας_τιμή in ΔΙΑΔΡΟΜΗ):
        raise ValueError("잘못된 ΔΙΑΔΡΟΜΗ 문자")
    μέτρηση = "/lib/" + ΔΙΑΔΡΟΜΗ
    if len(μέτρηση.encode("utf-8")) > 63 or ΔΙΑΔΡΟΜΗ in ("ελληνικά.py", "πακέτο.py"):
        raise ValueError("πακέτο 경로가 너무 길거나 προεπιλεγμένη_τιμή 라이브러리와 겹칩니다.")
    return μέτρηση


class λαμβάνω_ροή:
    def __init__(자신, τελικό_σημείο):
        자신.τελικό_σημείο = τελικό_σημείο
        자신.남은자료 = b""
        자신.Εκτέλεση_2 = λειτουργικό_σύστημα.ticks_ms()

    def 정확히읽기(자신, διάρκεια_τιμή):
        δεδομένα = bytearray()
        while len(δεδομένα) < διάρκεια_τιμή:
            if λειτουργικό_σύστημα.ticks_ms() - 자신.Εκτέλεση_2 > 90000:
                raise ValueError("πακέτο 중계 απαντώ τιμή_ώρας 초과")
            if not 자신.남은자료:
                try:
                    자신.남은자료 = λειτουργικό_σύστημα.tcp_read(자신.τελικό_σημείο, 512)
                except OSError as ΣΦΑΛΜΑ:
                    if ΣΦΑΛΜΑ.args[0] != 11:
                        raise
                    λειτουργικό_σύστημα.sleep_ms(10)
                    continue
                if not 자신.남은자료:
                    raise ValueError("πακέτο 전송이 중간에 끝났습니다.")
            개수 = min(διάρκεια_τιμή - len(δεδομένα), len(자신.남은자료))
            δεδομένα.extend(자신.남은자료[:개수])
            자신.남은자료 = 자신.남은자료[개수:]
            λειτουργικό_σύστημα.sleep_ms(0)
        return bytes(δεδομένα)


def λήψη(αίτηση, αριθμός_θύρας):
    if len(αίτηση) > 96 or any(χαρακτήρας_τιμή not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-=" for χαρακτήρας_τιμή in αίτηση):
        raise ValueError("사용법: pip install Όνομα 또는 Όνομα==버전")
    τελικό_σημείο = λειτουργικό_σύστημα.tcp_open()
    try:
        Εκτέλεση_2 = λειτουργικό_σύστημα.ticks_ms()
        while True:
            try:
                λειτουργικό_σύστημα.tcp_connect(τελικό_σημείο, "10.0.2.2", αριθμός_θύρας)
                break
            except OSError as ΣΦΑΛΜΑ:
                if ΣΦΑΛΜΑ.args[0] not in (11, 115) or λειτουργικό_σύστημα.ticks_ms() - Εκτέλεση_2 > 5000:
                    raise ValueError("πακέτο 중계 Σύνδεση αποτυχία_τιμή: 호스트에서 --network --pip로 실행하십시오.")
                λειτουργικό_σύστημα.sleep_ms(10)
        δεδομένα = (αίτηση + "\n").encode()
        while δεδομένα:
            try:
                개수 = λειτουργικό_σύστημα.tcp_write(τελικό_σημείο, δεδομένα)
                if not 개수:
                    raise ValueError("πακέτο αίτηση Μεταφορά_τιμή αποτυχία_τιμή")
                δεδομένα = δεδομένα[개수:]
            except OSError as ΣΦΑΛΜΑ:
                if ΣΦΑΛΜΑ.args[0] != 11:
                    raise
                λειτουργικό_σύστημα.sleep_ms(10)
                if λειτουργικό_σύστημα.ticks_ms() - Εκτέλεση_2 > 10000:
                    raise ValueError("πακέτο αίτηση Μεταφορά_τιμή τιμή_ώρας 초과")
        ροή_τιμή = λαμβάνω_ροή(τελικό_σημείο)
        머리 = ροή_τιμή.정확히읽기(8)
        if 머리[:4] != b"JKP1":
            raise ValueError("πακέτο Μεταφορά_τιμή εργασία_τιμή 불일치")
        διάρκεια_τιμή = (머리[4] << 24) | (머리[5] << 16) | (머리[6] << 8) | 머리[7]
        if διάρκεια_τιμή > 8192:
            raise ValueError("πακέτο 명세가 너무 큽니다.")
        명세 = json.loads(ροή_τιμή.정확히읽기(διάρκεια_τιμή).decode())
        if "error" in 명세:
            raise ValueError(명세["error"])
        if not 1 <= len(명세["files"]) <= 16:
            raise ValueError("꾸러미당 προέλευση_δέντρο 파일은 1~16개여야 합니다.")
        if sum(καταχώρηση_τιμή["size"] for καταχώρηση_τιμή in 명세["files"]) > 65536:
            raise ValueError("πακέτο προέλευση_δέντρο 합계는 64 KiB 이하여야 합니다.")
        파일들 = {}
        for καταχώρηση_τιμή in 명세["files"]:
            ΔΙΑΔΡΟΜΗ = ελέγχω_διαδρομή(καταχώρηση_τιμή["path"])
            if ΔΙΑΔΡΟΜΗ in 파일들 or not 0 <= καταχώρηση_τιμή["size"] <= 16384:
                raise ValueError("중복 ΔΙΑΔΡΟΜΗ 또는 Αρχείο Μέγεθος 초과")
            δεδομένα = ροή_τιμή.정확히읽기(καταχώρηση_τιμή["size"])
            if 지문(δεδομένα) != καταχώρηση_τιμή["sha256"]:
                raise ValueError("πακέτο Αρχείο SHA-256 불일치")
            # 실행하지 않고 τρέχων_στοιχείο MicroPython의 문법으로 먼저 검사한다.
            compile(δεδομένα.decode("utf-8"), ΔΙΑΔΡΟΜΗ, "exec")
            파일들[ΔΙΑΔΡΟΜΗ] = δεδομένα
            gc.collect()
        return 명세, 파일들
    finally:
        λειτουργικό_σύστημα.udp_close(τελικό_σημείο)


def εγκαθιστώ_τιμή(αίτηση, αριθμός_θύρας):
    print("πακέτο λήψη:", αίτηση)
    명세, 파일들 = λήψη(αίτηση, αριθμός_θύρας)
    καταχώρηση_Λίστα = 목록읽기()
    Όνομα = 명세["name"]
    if Όνομα in καταχώρηση_Λίστα:
        if καταχώρηση_Λίστα[Όνομα]["version"] == 명세["version"]:
            for ΔΙΑΔΡΟΜΗ, 지문값 in καταχώρηση_Λίστα[Όνομα]["files"].items():
                if λειτουργικό_σύστημα.path_kind(ΔΙΑΔΡΟΜΗ) != 1 or 지문(λειτουργικό_σύστημα.read(ΔΙΑΔΡΟΜΗ)) != 지문값:
                    raise ValueError("설치된 πακέτο 파일이 달라졌습니다: " + ΔΙΑΔΡΟΜΗ)
            print("이미 설치됨:", Όνομα, 명세["version"])
            return
        raise ValueError("다른 버전이 있습니다. pip uninstall로 제거한 Πίσω_τιμή 설치하십시오.")
    for ΔΙΑΔΡΟΜΗ in 파일들:
        if λειτουργικό_σύστημα.path_kind(ΔΙΑΔΡΟΜΗ):
            raise ValueError("기존 파일을 덮어쓰지 않습니다: " + ΔΙΑΔΡΟΜΗ)
    καταχώρηση_Λίστα[Όνομα] = {"version": 명세["version"], "files": {ΔΙΑΔΡΟΜΗ: 지문(δεδομένα) for ΔΙΑΔΡΟΜΗ, δεδομένα in 파일들.items()}}
    새목록 = json.dumps(καταχώρηση_Λίστα).encode()
    if len(새목록) > 16384:
        raise ValueError("πακέτο καταχώρηση_Λίστα Μέγεθος 초과")
    이전목록 = λειτουργικό_σύστημα.read(Λίστα_διαδρομή) if λειτουργικό_σύστημα.path_kind(Λίστα_διαδρομή) else None
    만든파일 = []
    만든폴더 = []
    try:
        for ΔΙΑΔΡΟΜΗ, δεδομένα in 파일들.items():
            부분들 = ΔΙΑΔΡΟΜΗ.split("/")
            for 수 in range(2, len(부분들)):
                Κατάλογος_τιμή = "/".join(부분들[:수])
                종류 = λειτουργικό_σύστημα.path_kind(Κατάλογος_τιμή)
                if 종류 == 0:
                    λειτουργικό_σύστημα.mkdir(Κατάλογος_τιμή)
                    만든폴더.append(Κατάλογος_τιμή)
                elif 종류 != 2:
                    raise ValueError("Κατάλογος_τιμή 경로에 파일이 있습니다: " + Κατάλογος_τιμή)
            만든파일.append(ΔΙΑΔΡΟΜΗ)
            εγγράφω_καταγράφω(ΔΙΑΔΡΟΜΗ, δεδομένα)
        εγγράφω_καταγράφω(Λίστα_διαδρομή, 새목록)
    except Exception:
        for ΔΙΑΔΡΟΜΗ in 만든파일:
            if λειτουργικό_σύστημα.path_kind(ΔΙΑΔΡΟΜΗ):
                λειτουργικό_σύστημα.remove(ΔΙΑΔΡΟΜΗ)
        for Κατάλογος_τιμή in reversed(만든폴더):
            λειτουργικό_σύστημα.rmdir(Κατάλογος_τιμή)
        if 이전목록 is not None:
            εγγράφω_καταγράφω(Λίστα_διαδρομή, 이전목록)
        elif λειτουργικό_σύστημα.path_kind(Λίστα_διαδρομή):
            λειτουργικό_σύστημα.remove(Λίστα_διαδρομή)
        raise
    print("εγκαθιστώ_τιμή 완료:", Όνομα, 명세["version"], "→ /lib (RAM)")


def καταργώ_καταχώρηση(Όνομα):
    καταχώρηση_Λίστα = 목록읽기()
    if Όνομα not in καταχώρηση_Λίστα:
        raise ValueError("설치되지 않은 꾸러미입니다: " + Όνομα)
    for ΔΙΑΔΡΟΜΗ, 지문값 in καταχώρηση_Λίστα[Όνομα]["files"].items():
        if λειτουργικό_σύστημα.path_kind(ΔΙΑΔΡΟΜΗ) != 1 or 지문(λειτουργικό_σύστημα.read(ΔΙΑΔΡΟΜΗ)) != 지문값:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + ΔΙΑΔΡΟΜΗ)
    for ΔΙΑΔΡΟΜΗ in καταχώρηση_Λίστα[Όνομα]["files"]:
        λειτουργικό_σύστημα.remove(ΔΙΑΔΡΟΜΗ)
    del καταχώρηση_Λίστα[Όνομα]
    εγγράφω_καταγράφω(Λίστα_διαδρομή, json.dumps(καταχώρηση_Λίστα).encode())
    print("καταργώ_καταχώρηση 완료:", Όνομα)


