package Καναδάς.JCanOS.Μνήμη_περιοχή;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB σελίδα_τιμή 연결과 Εγγραφή 시 복사를 제공한다. */
public final class σελίδα_Υπεύθυνος {
    public static final int μέγεθος_σελίδας = 4096;

    private static final class σελίδα_τιμή {
        private byte[] δεδομένα = new byte[μέγεθος_σελίδας];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class χώρος_διευθύνσεων {
        private final Map<Integer, σελίδα_τιμή> σελίδα_πίνακας = new HashMap<Integer, σελίδα_τιμή>();
    }

    public χώρος_διευθύνσεων 새주소공간() {
        return new χώρος_διευθύνσεων();
    }

    public void χάρτης_σελίδα(χώρος_διευθύνσεων διεύθυνση_περιοχή, int εικονική_διεύθυνση, boolean 쓰기가능) {
        int Ευρετήριο = 쪽번호(εικονική_διεύθυνση);
        σελίδα_τιμή 새쪽 = new σελίδα_τιμή();
        새쪽.쓰기가능 = 쓰기가능;
        διεύθυνση_περιοχή.σελίδα_πίνακας.put(Integer.valueOf(Ευρετήριο), 새쪽);
    }

    public χώρος_διευθύνσεων 쓰기시복사복제(χώρος_διευθύνσεων 원본) {
        χώρος_διευθύνσεων 복제본 = new χώρος_διευθύνσεων();
        for (Map.Entry<Integer, σελίδα_τιμή> καταχώρηση_τιμή : 원본.σελίδα_πίνακας.entrySet()) {
            σελίδα_τιμή 공유쪽 = καταχώρηση_τιμή.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.σελίδα_πίνακας.put(καταχώρηση_τιμή.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(χώρος_διευθύνσεων διεύθυνση_περιοχή, int εικονική_διεύθυνση) {
        σελίδα_τιμή τιμή_στόχος = Βρες_σελίδα(διεύθυνση_περιοχή, εικονική_διεύθυνση);
        return τιμή_στόχος.δεδομένα[Math.floorMod(εικονική_διεύθυνση, μέγεθος_σελίδας)];
    }

    public void 바이트쓰기(χώρος_διευθύνσεων διεύθυνση_περιοχή, int εικονική_διεύθυνση, byte τιμή) {
        int Ευρετήριο = 쪽번호(εικονική_διεύθυνση);
        σελίδα_τιμή τιμή_στόχος = Βρες_σελίδα(διεύθυνση_περιοχή, εικονική_διεύθυνση);
        if (!τιμή_στόχος.쓰기가능) {
            if (!τιμή_στόχος.쓰기시복사) {
                throw new IllegalStateException("Ανάγνωση 전용 쪽입니다.");
            }
            τιμή_στόχος = ανοίγω_Απόκρυψη_σελίδα(διεύθυνση_περιοχή, Ευρετήριο, τιμή_στόχος);
        }
        τιμή_στόχος.δεδομένα[Math.floorMod(εικονική_διεύθυνση, μέγεθος_σελίδας)] = τιμή;
    }

    public void Απόκρυψη_εύρος_εγγράφω(χώρος_διευθύνσεων διεύθυνση_περιοχή, int αρχή_διεύθυνση, int Μέγεθος) {
        if (Μέγεθος < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int Τελική_οντότητα_διεύθυνση = Math.addExact(αρχή_διεύθυνση, Μέγεθος);
        for (int διεύθυνση = αρχή_διεύθυνση; διεύθυνση < Τελική_οντότητα_διεύθυνση; διεύθυνση = (쪽번호(διεύθυνση) + 1) * μέγεθος_σελίδας) {
            int Ευρετήριο = 쪽번호(διεύθυνση);
            σελίδα_τιμή τιμή_στόχος = Βρες_σελίδα(διεύθυνση_περιοχή, διεύθυνση);
            if (τιμή_στόχος.쓰기시복사) {
                ανοίγω_Απόκρυψη_σελίδα(διεύθυνση_περιοχή, Ευρετήριο, τιμή_στόχος);
            } else {
                τιμή_στόχος.쓰기가능 = true;
            }
        }
    }

    public void εύρος_εγγράφω(χώρος_διευθύνσεων διεύθυνση_περιοχή, int αρχή_διεύθυνση, byte[] δεδομένα) {
        for (int Ευρετήριο = 0; Ευρετήριο < δεδομένα.length; Ευρετήριο++) {
            바이트쓰기(διεύθυνση_περιοχή, αρχή_διεύθυνση + Ευρετήριο, δεδομένα[Ευρετήριο]);
        }
    }

    private σελίδα_τιμή ανοίγω_Απόκρυψη_σελίδα(χώρος_διευθύνσεων διεύθυνση_περιοχή, int Ευρετήριο, σελίδα_τιμή 공유쪽) {
        σελίδα_τιμή Απόκρυψη_σελίδα = new σελίδα_τιμή();
        Απόκρυψη_σελίδα.δεδομένα = Arrays.copyOf(공유쪽.δεδομένα, 공유쪽.δεδομένα.length);
        Απόκρυψη_σελίδα.쓰기가능 = true;
        Απόκρυψη_σελίδα.쓰기시복사 = false;
        공유쪽.참조수--;
        διεύθυνση_περιοχή.σελίδα_πίνακας.put(Integer.valueOf(Ευρετήριο), Απόκρυψη_σελίδα);
        return Απόκρυψη_σελίδα;
    }

    private σελίδα_τιμή Βρες_σελίδα(χώρος_διευθύνσεων διεύθυνση_περιοχή, int διεύθυνση) {
        σελίδα_τιμή τιμή_στόχος = διεύθυνση_περιοχή.σελίδα_πίνακας.get(Integer.valueOf(쪽번호(διεύθυνση)));
        if (τιμή_στόχος == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return τιμή_στόχος;
    }

    private int 쪽번호(int διεύθυνση) {
        if (διεύθυνση < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return διεύθυνση / μέγεθος_σελίδας;
    }
}

