package Καναδάς.JCanOS.πυρήνας;

import Καναδάς.JCanOS.Μνήμη_περιοχή.Μνήμη_Υπεύθυνος;
import Καναδάς.JCanOS.Μνήμη_περιοχή.σελίδα_Υπεύθυνος;
import Καναδάς.JCanOS.είσοδος_τιμή.είσοδος_Υπεύθυνος;
import Καναδάς.JCanOS.작업.διεργασία_τιμή;
import Καναδάς.JCanOS.작업.Χρονοδιάγραμμα;
import Καναδάς.JCanOS.체계호출.체계호출;
import Καναδάς.JCanOS.σύστημα_αρχείων.파일서술자표;
import Καναδάς.JCanOS.σύστημα_αρχείων.σύστημα_αρχείων;

/** Java 관리 커널의 조립과 시작을 담당한다. */
public final class πυρήνας {
    private final υλικό_τιμή συσκευή_τιμή;
    private final Μνήμη_Υπεύθυνος Μνήμη_περιοχή = new Μνήμη_Υπεύθυνος(32 * 1024 * 1024);
    private final σελίδα_Υπεύθυνος 쪽관리 = new σελίδα_Υπεύθυνος();
    private final σύστημα_αρχείων σύστημα_αρχείων = new σύστημα_αρχείων();
    private final Χρονοδιάγραμμα Χρονοδιάγραμμα = new Χρονοδιάγραμμα(쪽관리);
    private final είσοδος_Υπεύθυνος 입력관리 = new είσοδος_Υπεύθυνος(256);
    private final διεργασία_τιμή 첫과정;
    private final 체계호출 체계호출;

    public πυρήνας(υλικό_τιμή συσκευή_τιμή) {
        this.συσκευή_τιμή = συσκευή_τιμή;
        첫과정 = Χρονοδιάγραμμα.첫과정(new 파일서술자표(σύστημα_αρχείων));
        체계호출 = new 체계호출(σύστημα_αρχείων, 쪽관리, Χρονοδιάγραμμα, συσκευή_τιμή, 입력관리);
    }

    public void Εκτέλεση_2() {
        συσκευή_τιμή.직렬출력("=== JCanOS 관리 πυρήνας_τιμή ===\n");
    }

    public void εκτελώ_βήμα() {
        συσκευή_τιμή.중앙처리장치멈춤();
    }

    public Μνήμη_Υπεύθυνος Μνήμη_περιοχή() {
        return Μνήμη_περιοχή;
    }

    public σελίδα_Υπεύθυνος 쪽관리() {
        return 쪽관리;
    }

    public σύστημα_αρχείων σύστημα_αρχείων() {
        return σύστημα_αρχείων;
    }

    public Χρονοδιάγραμμα Χρονοδιάγραμμα() {
        return Χρονοδιάγραμμα;
    }

    public είσοδος_Υπεύθυνος 입력관리() {
        return 입력관리;
    }

    public διεργασία_τιμή 첫과정() {
        return 첫과정;
    }

    public 체계호출 체계호출() {
        return 체계호출;
    }
}
