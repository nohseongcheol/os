package Καναδάς.JCanOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Καναδάς.JCanOS.Μνήμη_περιοχή.σελίδα_Υπεύθυνος;
import Καναδάς.JCanOS.σύστημα_αρχείων.파일서술자표;

/** διεργασία_τιμή 식별자와 라운드로빈 Προετοίμασε 대기열을 관리한다. */
public final class Χρονοδιάγραμμα {
    private final σελίδα_Υπεύθυνος 쪽관리;
    private final Map<Integer, διεργασία_τιμή> Λίστα_διαδικασίας = new HashMap<Integer, διεργασία_τιμή>();
    private final Queue<διεργασία_τιμή> 준비대기열 = new ArrayDeque<διεργασία_τιμή>();
    private int Επόμενο_αναγνωριστικό = 1;

    public Χρονοδιάγραμμα(σελίδα_Υπεύθυνος 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public διεργασία_τιμή 첫과정(파일서술자표 파일서술자) {
        διεργασία_τιμή 새과정 = new διεργασία_τιμή(εκχωρώ_αναγνωριστικό(), 0, 쪽관리.새주소공간(), 파일서술자);
        Λίστα_διαδικασίας.put(Integer.valueOf(새과정.αναγνωριστικό_τιμή()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public διεργασία_τιμή κλώνος_τιμή(διεργασία_τιμή γονικός_τιμή) {
        διεργασία_τιμή παιδί_τιμή = new διεργασία_τιμή(
                εκχωρώ_αναγνωριστικό(),
                γονικός_τιμή.αναγνωριστικό_τιμή(),
                쪽관리.쓰기시복사복제(γονικός_τιμή.χώρος_διευθύνσεων()),
                γονικός_τιμή.파일서술자().κλώνος_τιμή());
        παιδί_τιμή.σύνολο_εφαρμογή_διακόπτω(γονικός_τιμή.εφαρμογή_διακόπτω());
        Λίστα_διαδικασίας.put(Integer.valueOf(παιδί_τιμή.αναγνωριστικό_τιμή()), παιδί_τιμή);
        준비대기열.offer(παιδί_τιμή);
        return παιδί_τιμή;
    }

    public διεργασία_τιμή Επόμενο_διεργασία() {
        int 검사수 = 준비대기열.size();
        for (int Ευρετήριο = 0; Ευρετήριο < 검사수; Ευρετήριο++) {
            διεργασία_τιμή Επόμενο_στοιχείο = 준비대기열.poll();
            if (Επόμενο_στοιχείο != null && (Επόμενο_στοιχείο.Κατάσταση_τιμή() == διεργασία_Κατάσταση.Προετοίμασε || Επόμενο_στοιχείο.Κατάσταση_τιμή() == διεργασία_Κατάσταση.εκτελώ_εντολή)) {
                Επόμενο_στοιχείο.σύνολο_Κατάσταση(διεργασία_Κατάσταση.εκτελώ_εντολή);
                준비대기열.offer(Επόμενο_στοιχείο);
                return Επόμενο_στοιχείο;
            }
        }
        return null;
    }

    public int 자식기다리기(διεργασία_τιμή γονικός_τιμή, int παιδί_αναγνωριστικό, boolean 기다리지않음) {
        for (διεργασία_τιμή 후보 : Λίστα_διαδικασίας.values()) {
            if (후보.γονικός_αναγνωριστικό() != γονικός_τιμή.αναγνωριστικό_τιμή()) {
                continue;
            }
            if (παιδί_αναγνωριστικό > 0 && 후보.αναγνωριστικό_τιμή() != παιδί_αναγνωριστικό) {
                continue;
            }
            if (후보.Κατάσταση_τιμή() == διεργασία_Κατάσταση.Έξοδος_εφαρμογή) {
                int μέτρηση = (후보.κωδικός_εξόδου() & 0xff) << 8;
                Λίστα_διαδικασίας.remove(Integer.valueOf(후보.αναγνωριστικό_τιμή()));
                return μέτρηση;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public διεργασία_τιμή Βρες_διεργασία(int αναγνωριστικό_τιμή) {
        return Λίστα_διαδικασίας.get(Integer.valueOf(αναγνωριστικό_τιμή));
    }

    private int εκχωρώ_αναγνωριστικό() {
        return Επόμενο_αναγνωριστικό++;
    }
}
