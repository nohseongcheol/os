import فارسی.بومی.문자;
import فارسی.بومی.پرونده;
import فارسی.بومی.ورودی_لیست;
import فارسی.بومی.لغت_نامه;
import فارسی.بومی.خروجی;
public class 한글시험 {
    public static void main(String[] a) throws Exception {
        String 인사 = "안녕하세요 · 日本語 · العربية · 😀";
        خروجی.نوشتن_خط(문자.رمزگشایی_داده_ها(문자.부호화(인사))); خروجی.수쓰기(문자.코드포인트수("한글😀"));
        پرونده.نوشتن("한글자료.txt", 인사); خروجی.نوشتن_خط(پرونده.خواندن("한글자료.txt"));
        ورودی_لیست 이름들 = new ورودی_لیست(); 이름들.더하기("가람"); 이름들.더하기("누리"); خروجی.نوشتن_خط(이름들.خواندن(1));
        لغت_نامه 뜻 = new لغت_نامه(); 뜻.넣기("가람", "강"); System.gc(); خروجی.نوشتن_خط(뜻.کشف_ورودی("가람"));
        try { 문자.رمزگشایی_داده_ها(new byte[] {(byte)0xc0, (byte)0xaf}); } catch (IllegalArgumentException e) { خروجی.نوشتن_خط("UTF-8 خطا رد_کردن_مقدار"); }
        خروجی.نوشتن_خط("فارسی کتابخانه 완료");
    }
}
