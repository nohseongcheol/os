            int સ્થાન = 수(લુકઅપ_કોષ્ટક + 4), સરનામું = 수(લુકઅપ_કોષ્ટક + 8), ફાઇલ_આકાર = 수(લુકઅપ_કોષ્ટક + 16), મેમરી_આકાર = 수(લુકઅપ_કોષ્ટક + 20);
