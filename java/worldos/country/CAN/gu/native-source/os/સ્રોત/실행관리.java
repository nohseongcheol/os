        while (끝 < લંબાઈ_મૂલ્ય && 입력[끝] != ' ') 끝++;
        int પ્રવેશ_મૂલ્ય = શોધો_પ્રવેશ(입력, ચલાવો_2, 끝 - ચલાવો_2);
