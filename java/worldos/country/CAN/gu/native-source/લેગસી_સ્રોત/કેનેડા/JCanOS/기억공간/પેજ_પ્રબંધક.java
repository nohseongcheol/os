package કેનેડા.JCanOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB પેજ_મૂલ્ય 연결과 લખો 시 복사를 제공한다. */
public final class પેજ_પ્રબંધક {
    public static final int પેજ_આકાર = 4096;

    private static final class પેજ_મૂલ્ય {
        private byte[] ડેટા = new byte[પેજ_આકાર];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class સરનામું_જગ્યા {
        private final Map<Integer, પેજ_મૂલ્ય> પેજ_કોષ્ટક = new HashMap<Integer, પેજ_મૂલ્ય>();
    }

    public સરનામું_જગ્યા 새주소공간() {
        return new સરનામું_જગ્યા();
    }

    public void મૅપ_કરો_પેજ(સરનામું_જગ્યા 공간, int વર્ચુઅલ_સરનામું, boolean 쓰기가능) {
        int અનુક્રમણિકા = 쪽번호(વર્ચુઅલ_સરનામું);
        પેજ_મૂલ્ય 새쪽 = new પેજ_મૂલ્ય();
        새쪽.쓰기가능 = 쓰기가능;
        공간.પેજ_કોષ્ટક.put(Integer.valueOf(અનુક્રમણિકા), 새쪽);
    }

    public સરનામું_જગ્યા 쓰기시복사복제(સરનામું_જગ્યા 원본) {
        સરનામું_જગ્યા 복제본 = new સરનામું_જગ્યા();
        for (Map.Entry<Integer, પેજ_મૂલ્ય> પ્રવેશ_મૂલ્ય : 원본.પેજ_કોષ્ટક.entrySet()) {
            પેજ_મૂલ્ય 공유쪽 = પ્રવેશ_મૂલ્ય.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.પેજ_કોષ્ટક.put(પ્રવેશ_મૂલ્ય.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(સરનામું_જગ્યા 공간, int વર્ચુઅલ_સરનામું) {
        પેજ_મૂલ્ય લક્ષ્ય = શોધો_પેજ(공간, વર્ચુઅલ_સરનામું);
        return લક્ષ્ય.ડેટા[Math.floorMod(વર્ચુઅલ_સરનામું, પેજ_આકાર)];
    }

    public void લખો_બાઇટ_મૂલ્ય(સરનામું_જગ્યા 공간, int વર્ચુઅલ_સરનામું, byte મૂલ્ય) {
        int અનુક્રમણિકા = 쪽번호(વર્ચુઅલ_સરનામું);
        પેજ_મૂલ્ય લક્ષ્ય = શોધો_પેજ(공간, વર્ચુઅલ_સરનામું);
        if (!લક્ષ્ય.쓰기가능) {
            if (!લક્ષ્ય.쓰기시복사) {
                throw new IllegalStateException("વાંચો 전용 쪽입니다.");
            }
            લક્ષ્ય = બનાવો_ખાનગી_પેજ(공간, અનુક્રમણિકા, લક્ષ્ય);
        }
        લક્ષ્ય.ડેટા[Math.floorMod(વર્ચુઅલ_સરનામું, પેજ_આકાર)] = મૂલ્ય;
    }

    public void 범위개인쓰기(સરનામું_જગ્યા 공간, int પ્રારંભ_સરનામું, int માપ) {
        if (માપ < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int અંત_કરો_સરનામું = Math.addExact(પ્રારંભ_સરનામું, માપ);
        for (int સરનામું = પ્રારંભ_સરનામું; સરનામું < અંત_કરો_સરનામું; સરનામું = (쪽번호(સરનામું) + 1) * પેજ_આકાર) {
            int અનુક્રમણિકા = 쪽번호(સરનામું);
            પેજ_મૂલ્ય લક્ષ્ય = શોધો_પેજ(공간, સરનામું);
            if (લક્ષ્ય.쓰기시복사) {
                બનાવો_ખાનગી_પેજ(공간, અનુક્રમણિકા, લક્ષ્ય);
            } else {
                લક્ષ્ય.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(સરનામું_જગ્યા 공간, int પ્રારંભ_સરનામું, byte[] ડેટા) {
        for (int અનુક્રમણિકા = 0; અનુક્રમણિકા < ડેટા.length; અનુક્રમણિકા++) {
            લખો_બાઇટ_મૂલ્ય(공간, પ્રારંભ_સરનામું + અનુક્રમણિકા, ડેટા[અનુક્રમણિકા]);
        }
    }

    private પેજ_મૂલ્ય બનાવો_ખાનગી_પેજ(સરનામું_જગ્યા 공간, int અનુક્રમણિકા, પેજ_મૂલ્ય 공유쪽) {
        પેજ_મૂલ્ય ખાનગી_પેજ = new પેજ_મૂલ્ય();
        ખાનગી_પેજ.ડેટા = Arrays.copyOf(공유쪽.ડેટા, 공유쪽.ડેટા.length);
        ખાનગી_પેજ.쓰기가능 = true;
        ખાનગી_પેજ.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.પેજ_કોષ્ટક.put(Integer.valueOf(અનુક્રમણિકા), ખાનગી_પેજ);
        return ખાનગી_પેજ;
    }

    private પેજ_મૂલ્ય શોધો_પેજ(સરનામું_જગ્યા 공간, int સરનામું) {
        પેજ_મૂલ્ય લક્ષ્ય = 공간.પેજ_કોષ્ટક.get(Integer.valueOf(쪽번호(સરનામું)));
        if (લક્ષ્ય == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return લક્ષ્ય;
    }

    private int 쪽번호(int સરનામું) {
        if (સરનામું < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return સરનામું / પેજ_આકાર;
    }
}

