    static int 자료전문보내기(int 서술자, int डेटा_पता, int 길이, int विन्यास, int 요청주소) {
        int 기술 = 종단점기술(서술자);
        if (기술 < 0) return 기술;
        if (विन्यास != 0) return -95;
        if (길이 < 0 || 길이 > 1024) return -90;
        if (길이 != 0 && !실행관리.क्लिप(डेटा_पता, 길이)) return -14;
        if (!실행관리.क्लिप(요청주소, 8)) return -14;
        int पता = 실행관리.수(요청주소);
        int परिणाम = जाँचें_पता(पता, 실행관리.수(요청주소 + 4));
        if (परिणाम < 0) return परिणाम;
        int पोर्ट_संख्या = उपकरण_मान.पढें_मेमोरी(पता + 2) << 8 | उपकरण_मान.पढें_मेमोरी(पता + 3);
        if (पोर्ट_संख्या == 0) return -22;
        परिणाम = स्वतः_बाइंड_करें(기술);
        if (परिणाम < 0) return परिणाम;
        for (int इंडेक्स = 0; इंडेक्स < 길이; इंडेक्स++) हस्तांतरण_डेटा[इंडेक्स] = उपकरण_मान.पढें_मेमोरी(डेटा_पता + इंडेक्स);
        return नेटवर्क_स्टैक.भेजें(नेटवर्क_हैंडल[기술], पता_32(पता + 4), पोर्ट_संख्या, हस्तांतरण_डेटा, 길이);
    }
    static void लिखना_पता(int पता, int 길이, int नेटवर्क_पता, int पोर्ट_संख्या) {
        for (int इंडेक्स = 0; इंडेक्स < 길이 && इंडेक्स < 16; इंडेक्स++) {
            int मान = 0;
            if (इंडेक्स == 0) मान = 2;
            if (इंडेक्स == 2) मान = पोर्ट_संख्या >>> 8;
            if (इंडेक्स == 3) मान = पोर्ट_संख्या;
            if (इंडेक्स >= 4 && इंडेक्स < 8) मान = नेटवर्क_पता >>> (56 - इंडेक्स * 8);
            उपकरण_मान.लिखना_मेमोरी(पता + इंडेक्स, मान & 255);
        }
    }
    static int 자료전문받기(int 서술자, int डेटा_पता, int 길이, int विन्यास, int 요청주소) {
        int 기술 = 종단점기술(서술자);
        if (기술 < 0) return 기술;
        if ((विन्यास & ~64) != 0) return -95;
        if (길이 < 0) return -22;
        if (길이 != 0 && !실행관리.क्लिप(डेटा_पता, 길이)) return -14;
        int पता = 0, 주소길이주소 = 0, 주소길이 = 0;
        if (요청주소 != 0) {
            if (!실행관리.क्लिप(요청주소, 8)) return -14;
            पता = 실행관리.수(요청주소); 주소길이주소 = 실행관리.수(요청주소 + 4);
            if (पता != 0) {
                if (!실행관리.क्लिप(주소길이주소, 4)) return -14;
                주소길이 = 실행관리.수(주소길이주소);
                if (주소길이 < 0) return -22;
                if (!실행관리.क्लिप(पता, 주소길이 < 16 ? 주소길이 : 16)) return -14;
            }
        }
        int परिणाम = स्वतः_बाइंड_करें(기술);
        if (परिणाम < 0) return परिणाम;
        int चलाएँ = उपकरण_मान.밀리초();
        while (true) {
            परिणाम = नेटवर्क_स्टैक.받기(नेटवर्क_हैंडल[기술], हस्तांतरण_डेटा, 1024, 0);
            if (परिणाम != -11) break;
            if ((विन्यास & 64) != 0 || (जारी_सेटिंग[기술] & 기다리지않기) != 0) return -11;
            if (수신대기밀리초[기술] > 0 && उपकरण_मान.밀리초() - चलाएँ >= 수신대기밀리초[기술]) return -11;
            if (उपकरण_मान.사용자남은밀리초() <= 10) return -11;
            उपकरण_मान.잠시양보();
        }
        if (परिणाम < 0) return परिणाम;
        if (परिणाम > 길이) परिणाम = 길이;
        for (int इंडेक्स = 0; इंडेक्स < परिणाम; इंडेक्स++) उपकरण_मान.लिखना_मेमोरी(डेटा_पता + इंडेक्स, हस्तांतरण_डेटा[इंडेक्स]);
        if (पता != 0) {
            लिखना_पता(पता, 주소길이, नेटवर्क_स्टैक.पीअर_पता(नेटवर्क_हैंडल[기술]), नेटवर्क_स्टैक.पीअर_पोर्ट_संख्या(नेटवर्क_हैंडल[기술]));
            실행관리.수쓰기(주소길이주소, 16);
        }
        return परिणाम;
    }
