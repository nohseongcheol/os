        for (int इंडेक्स = आकार; इंडेक्स < स्थान; इंडेक्स++) उपकरण_मान.लिखना_मेमोरी(गंतव्य_पता + इंडेक्स, 0);
        for (int इंडेक्स = 0; इंडेक्स < 길이; इंडेक्स++) उपकरण_मान.लिखना_मेमोरी(गंतव्य_पता + स्थान + इंडेक्स, उपकरण_मान.पढें_मेमोरी(डेटा_पता + इंडेक्स));
