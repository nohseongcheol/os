        종류[기술] = 파일종류; लक्ष्य[기술] = फ़ाइल_लक्ष्य; 참조수[기술] = 1;
        जारी_सेटिंग[기술] = विन्यास & (3 | 이어쓰기 | 기다리지않기); फ़ाइल_पद[기술] = 0;
        नेटवर्क_हैंडल[기술] = 0; 수신대기밀리초[기술] = 0;
