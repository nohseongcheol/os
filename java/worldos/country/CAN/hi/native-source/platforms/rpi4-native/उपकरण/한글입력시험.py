#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from डेस्कटॉप_दृश्य import कीबोर्ड


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.पाठ_बफ़र = ''
        def भेजें(आँकड़े):
            for वर्ण_डेटा in आँकड़े.decode('utf-8'):
                if वर्ण_डेटा == '\x7f': 자신.पाठ_बफ़र = 자신.पाठ_बफ़र[:-1]
                else: 자신.पाठ_बफ़र += वर्ण_डेटा
        자신.कीबोर्ड_एन्ट्री = कीबोर्ड(भेजें)

    def दबाएँ_कुंजी(자신, प्रतीक_मान):
        자신.कीबोर्ड_एन्ट्री.누름값(True, प्रतीक_मान)
        자신.कीबोर्ड_एन्ट्री.누름값(False, प्रतीक_मान)

    def लिखें_श्रेणी(자신, 누름열):
        for 누름값 in 누름열: 자신.दबाएँ_कुंजी(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.दबाएँ_कुंजी(0xffc6); 자신.लिखें_श्रेणी(누름열)
                자신.assertEqual(자신.पाठ_बफ़र, 예상결과)

    def test_앞글자지우기(자신):
        자신.दबाएँ_कुंजी(0xff31); 자신.लिखें_श्रेणी('dlfr')
        자신.assertEqual(자신.पाठ_बफ़र,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.दबाएँ_कुंजी(0xff08); 자신.assertEqual(자신.पाठ_बफ़र,예상결과)
        자신.लिखें_श्रेणी('gksk'); 자신.assertEqual(자신.पाठ_बफ़र,'하나')
        자신.दबाएँ_कुंजी(0xff08); 자신.assertEqual(자신.पाठ_बफ़र,'하ㄴ')

    def test_전환반복확정(자신):
        자신.लिखें_श्रेणी('echo ')
        자신.कीबोर्ड_एन्ट्री.누름값(True,0xffe1)
        자신.कीबोर्ड_एन्ट्री.누름값(True,32); 자신.कीबोर्ड_एन्ट्री.누름값(True,32)
        자신.कीबोर्ड_एन्ट्री.누름값(False,32); 자신.कीबोर्ड_एन्ट्री.누름값(False,0xffe1)
        자신.assertTrue(자신.कीबोर्ड_एन्ट्री.한글여부)
        자신.लिखें_श्रेणी('gksrmf'); 자신.दबाएँ_कुंजी(0xff31); 자신.लिखें_श्रेणी(' English')
        자신.assertEqual(자신.पाठ_बफ़र,'echo 한글 English')
        자신.assertFalse(자신.कीबोर्ड_एन्ट्री.한글여부)
        자신.दबाएँ_कुंजी(0xffc6); 자신.लिखें_श्रेणी('rk'); 자신.दबाएँ_कुंजी(0xff51)
        자신.लिखें_श्रेणी('sk'); 자신.assertTrue(자신.पाठ_बफ़र.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.दबाएँ_कुंजी(0xffc6); 자신.लिखें_श्रेणी('rk')
        자신.कीबोर्ड_एन्ट्री.क्लिपबोर्ड_मान='चिपकाएँ_मान'.encode()
        자신.कीबोर्ड_एन्ट्री.누름값(True,0xffe3); 자신.कीबोर्ड_एन्ट्री.누름값(True,0xffe1)
        자신.दबाएँ_कुंजी(ord('v'))
        자신.कीबोर्ड_एन्ट्री.누름값(False,0xffe1); 자신.कीबोर्ड_एन्ट्री.누름값(False,0xffe3)
        자신.दबाएँ_कुंजी(0x0100d55c); 자신.लिखें_श्रेणी('sk')
        자신.assertEqual(자신.पाठ_बफ़र,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
