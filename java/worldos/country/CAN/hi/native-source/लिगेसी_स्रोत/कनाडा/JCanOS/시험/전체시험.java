        लिखना_पूर्णांक_मान(आँकड़े, 64, 0x04002000);
        लिखना_पूर्णांक_मान(आँकड़े, 72, 64);

        निष्पादन_योग्य_फ़ाइल_लोडर.छवि छवि_मान = new निष्पादन_योग्य_फ़ाइल_लोडर().검사(आँकड़े);
        सत्यापित_करें(छवि_मान.प्रारंभ_पता() == 0x04001000, "ELF चलाएँ पता");
        सत्यापित_करें(छवि_मान.구역들().size() == 1 && छवि_मान.구역들().get(0).종류() == 8, "ELF 빈 आँकड़े खंड_मान");
        int 서술자 = कर्नेल_मान.체계호출().खोलें(कर्नेल_मान.첫과정(), "시험", 체계호출.केवल_पढ़ने_के_लिए_ध्वज);
        सत्यापित_करें(कर्नेल_मान.체계호출().फ़ाइल_नियंत्रण(कर्नेल_मान.첫과정(), 서술자, 2, 1) == 0, "निष्पादित_करें_आदेश 시 बंदकरें विन्यास");
        सत्यापित_करें(कर्नेल_मान.체계호출().निष्पादित_करें_आदेश(कर्नेल_मान.첫과정(), आँकड़े, new String[] {"시험", "값"}, new String[] {"भाषा=हिंदी"}) == 0, "ELF निष्पादित_करें_आदेश छवि_मान 적재");
        सत्यापित_करें(कर्नेल_मान.첫과정().실행시작주소() == 0x04001000, "निष्पादित_करें_आदेश चलाएँ पता 반영");
        सत्यापित_करें(कर्नेल_मान.첫과정().실행인자().length == 2 && कर्नेल_मान.첫과정().환경값().length == 1, "निष्पादित_करें_आदेश 인자와 환경");
        सत्यापित_करें(!कर्नेल_मान.첫과정().파일서술자().सूचना_प्रौद्योगिकी_जारी(서술자), "निष्पादित_करें_आदेश 시 서술자 बंदकरें");
        सत्यापित_करें(कर्नेल_मान.쪽관리().पढें_बाइट_मान(कर्नेल_मान.첫과정().पता_स्थान(), 0x04002000) == 0, "빈 आँकड़े खंड_मान शून्य_ऑपरेंड आरंभ");
