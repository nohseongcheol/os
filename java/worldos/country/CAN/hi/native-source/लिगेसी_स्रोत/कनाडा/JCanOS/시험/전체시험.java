        आँकड़े[4] = 1;
        आँकड़े[5] = 1;
        लिखना_पूर्णांक_मान(आँकड़े, 24, 0x04001000);
        लिखना_पूर्णांक_मान(आँकड़े, 32, 52);
        짧은정수쓰기(आँकड़े, 46, 40);
