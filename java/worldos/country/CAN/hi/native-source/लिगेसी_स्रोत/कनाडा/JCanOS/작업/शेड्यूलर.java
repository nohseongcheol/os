package कनाडा.JCanOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import कनाडा.JCanOS.मेमोरी_क्षेत्र.पेज_प्रबंधक;
import कनाडा.JCanOS.फ़ाइल_सिस्टम.파일서술자표;

/** प्रक्रिया_मान 식별자와 라운드로빈 준비 대기열을 관리한다. */
public final class शेड्यूलर {
    private final पेज_प्रबंधक 쪽관리;
    private final Map<Integer, प्रक्रिया_मान> प्रक्रिया_सूची = new HashMap<Integer, प्रक्रिया_मान>();
    private final Queue<प्रक्रिया_मान> 준비대기열 = new ArrayDeque<प्रक्रिया_मान>();
    private int अगला_पहचानकर्ता = 1;

    public शेड्यूलर(पेज_प्रबंधक 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public प्रक्रिया_मान 첫과정(파일서술자표 파일서술자) {
        प्रक्रिया_मान 새과정 = new प्रक्रिया_मान(आवंटित_करें_पहचानकर्ता(), 0, 쪽관리.새주소공간(), 파일서술자);
        प्रक्रिया_सूची.put(Integer.valueOf(새과정.पहचानकर्ता_मान()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public प्रक्रिया_मान क्लोन_मान(प्रक्रिया_मान पैरेंट_मान) {
        प्रक्रिया_मान बच्चा_मान = new प्रक्रिया_मान(
                आवंटित_करें_पहचानकर्ता(),
                पैरेंट_मान.पहचानकर्ता_मान(),
                쪽관리.쓰기시복사복제(पैरेंट_मान.पता_स्थान()),
                पैरेंट_मान.파일서술자().क्लोन_मान());
        बच्चा_मान.सेट_ऐप_विराम(पैरेंट_मान.ऐप_विराम());
        प्रक्रिया_सूची.put(Integer.valueOf(बच्चा_मान.पहचानकर्ता_मान()), बच्चा_मान);
        준비대기열.offer(बच्चा_मान);
        return बच्चा_मान;
    }

    public प्रक्रिया_मान अगला_प्रक्रिया() {
        int 검사수 = 준비대기열.size();
        for (int इंडेक्स = 0; इंडेक्स < 검사수; इंडेक्स++) {
            प्रक्रिया_मान अगला_आइटम = 준비대기열.poll();
            if (अगला_आइटम != null && (अगला_आइटम.अवस्था_मान() == प्रक्रिया_अवस्था.준비 || अगला_आइटम.अवस्था_मान() == प्रक्रिया_अवस्था.निष्पादित_करें_आदेश)) {
                अगला_आइटम.सेट_अवस्था(प्रक्रिया_अवस्था.निष्पादित_करें_आदेश);
                준비대기열.offer(अगला_आइटम);
                return अगला_आइटम;
            }
        }
        return null;
    }

    public int 자식기다리기(प्रक्रिया_मान पैरेंट_मान, int बच्चा_पहचानकर्ता, boolean 기다리지않음) {
        for (प्रक्रिया_मान 후보 : प्रक्रिया_सूची.values()) {
            if (후보.पैरेंट_पहचानकर्ता() != पैरेंट_मान.पहचानकर्ता_मान()) {
                continue;
            }
            if (बच्चा_पहचानकर्ता > 0 && 후보.पहचानकर्ता_मान() != बच्चा_पहचानकर्ता) {
                continue;
            }
            if (후보.अवस्था_मान() == प्रक्रिया_अवस्था.निर्गमन_ऐप) {
                int परिणाम = (후보.निर्गमन_कोड() & 0xff) << 8;
                प्रक्रिया_सूची.remove(Integer.valueOf(후보.पहचानकर्ता_मान()));
                return परिणाम;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public प्रक्रिया_मान खोजें_प्रक्रिया(int पहचानकर्ता_मान) {
        return प्रक्रिया_सूची.get(Integer.valueOf(पहचानकर्ता_मान));
    }

    private int आवंटित_करें_पहचानकर्ता() {
        return अगला_पहचानकर्ता++;
    }
}
