/** 読取り専用の実行束の ELF32 を検証し、引数を渡し、一度に一つの利用者プロセスを実行する。 */
public final class 実行管理 {
    static final int 利用者プログラム開始処理 = 0x04000000;
    static final int 利用者終端位置 = 0x04400000;
    static final int イメージ終端位置番地 = 0x04200000;
    static final int 引数開始処理 = 0x04300000;
    static int 引数個数 = 0;
    static int[] 引数番地 = new int[16];

    static boolean 切抜き(int 番地, int 長さ) {
        return 番地 >= 利用者プログラム開始処理 && 番地 < 利用者終端位置 && 長さ >= 0 && 長さ <= 利用者終端位置 - 番地;
    }

    static int 数(int 番地) { return 記憶領域.整数値解析(番地); }
    static int 短整数値(int 番地) { return 装置.記憶読取(番地) | 装置.記憶読取(番地 + 1) << 8; }
    static void 番号書込(int 番地, int 値) {
        for (int 番号 = 0; 番号 < 4; 番号++) 装置.記憶書込(番地 + 番号, 値 >>> (番号 * 8));
    }

    static int 集合個数() {
        int 番地 = 装置.実行形式束();
        int 容量 = 装置.実行形式束容量();
        if (容量 < 8 || 数(番地) != 0x50414b4a) return 0;
        int 項目個数 = 数(番地 + 4);
        return 項目個数 >= 0 && 項目個数 <= 32 && 項目個数 <= (容量 - 8) / 24 ? 項目個数 : 0;
    }

    static void 入口一覧() {
        for (int 番号 = 0; 番号 < 集合個数(); 番号++) {
            int 入口値 = 装置.実行形式束() + 8 + 番号 * 24;
            for (int 文字値 = 0; 文字値 < 16 && 装置.記憶読取(入口値 + 文字値) != 0; 文字値++)
                文字端末.文字(装置.記憶読取(入口値 + 文字値));
            文字端末.書込("\n");
        }
    }

    static int 入口探索(int[] 入力値, int 起動処理, int 長さ) {
        if (長さ <= 0 || 長さ >= 16) return 0;
        for (int 番号 = 0; 番号 < 集合個数(); 番号++) {
            int 入口値 = 装置.実行形式束() + 8 + 番号 * 24;
            boolean 等価本文 = 装置.記憶読取(入口値 + 長さ) == 0;
            for (int 文字値 = 0; 文字値 < 長さ; 文字値++)
                if (入力値[起動処理 + 文字値] != 装置.記憶読取(入口値 + 文字値)) 等価本文 = false;
            if (等価本文) return 入口値;
        }
        return 0;
    }

    static int 妥当性検査(int ファイル, int 長さ) {
        if (長さ < 52 || 数(ファイル) != 0x464c457f || 装置.記憶読取(ファイル + 4) != 1
            || 装置.記憶読取(ファイル + 5) != 1 || 装置.記憶読取(ファイル + 6) != 1
            || 短整数値(ファイル + 16) != 2 || 短整数値(ファイル + 18) != 3 || 数(ファイル + 20) != 1
            || 短整数値(ファイル + 40) != 52 || 短整数値(ファイル + 42) != 32) return -8;
        int 入口点値 = 数(ファイル + 24);
        int 表位置 = 数(ファイル + 28);
        int 項目個数 = 短整数値(ファイル + 44);
        if (項目個数 == 0 || 項目個数 > 16 || 表位置 < 52 || 表位置 > 長さ - 項目個数 * 32) return -8;
        boolean 判定実行形式 = false;
        for (int 番号 = 0; 番号 < 項目個数; 番号++) {
            int 表 = ファイル + 表位置 + 番号 * 32;
            int 種別値 = 数(表);
            if (種別値 == 2 || 種別値 == 3) return -8; // 動的リンクとインタープリターには対応しない。
            if (種別値 != 1) continue;
            int 位置 = 数(表 + 4), 番地 = 数(表 + 8), ファイル容量 = 数(表 + 16), 記憶容量 = 数(表 + 20);
            int 整列値 = 数(表 + 28);
            if (番地 < 利用者プログラム開始処理 || 番地 >= イメージ終端位置番地 || 記憶容量 < 0 || 記憶容量 > イメージ終端位置番地 - 番地
                || ファイル容量 < 0 || ファイル容量 > 記憶容量 || 位置 < 0 || (ファイル容量 > 0 && 位置 > 長さ - ファイル容量)
                || (整列値 != 0 && (整列値 < 0 || (整列値 & (整列値 - 1)) != 0
                    || ((番地 - 位置) & (整列値 - 1)) != 0))) return -8;
            for (int 前面値 = 0; 前面値 < 番号; 前面値++) {
                int 前回項目 = ファイル + 表位置 + 前面値 * 32;
                if (数(前回項目) == 1 && 記憶容量 > 0 && 数(前回項目 + 20) > 0
                    && 番地 < 数(前回項目 + 8) + 数(前回項目 + 20) && 数(前回項目 + 8) < 番地 + 記憶容量) return -8;
            }
            if ((数(表 + 24) & 1) != 0 && 入口点値 >= 番地 && 入口点値 - 番地 < ファイル容量) 判定実行形式 = true;
        }
        return 判定実行形式 ? 入口点値 : -8;
    }

    static int 命令実行(int[] 入力値, int 起動処理, int 長さ) {
        while (起動処理 < 長さ && 入力値[起動処理] == ' ') 起動処理++;
        int 終端 = 起動処理;
        while (終端 < 長さ && 入力値[終端] != ' ') 終端++;
        int 入口値 = 入口探索(入力値, 起動処理, 終端 - 起動処理);
        if (入口値 == 0) return -2;
        int 位置 = 数(入口値 + 16), 容量 = 数(入口値 + 20);
        if (位置 < 8 + 集合個数() * 24 || 容量 < 52 || 位置 > 装置.実行形式束容量() - 容量) return -8;
        int ファイル = 装置.実行形式束() + 位置;
        int 入口点値 = 妥当性検査(ファイル, 容量);
        if (入口点値 < 0) return 入口点値;
        装置.利用者消去内容();
        int 表位置 = 数(ファイル + 28), 項目個数 = 短整数値(ファイル + 44);
        for (int 番号 = 0; 番号 < 項目個数; 番号++) {
            int 表 = ファイル + 表位置 + 番号 * 32;
            if (数(表) != 1) continue;
            int 原本 = ファイル + 数(表 + 4), 宛先値 = 数(表 + 8), ファイル容量 = 数(表 + 16);
            for (int バイト値 = 0; バイト値 < ファイル容量; バイト値++) 装置.記憶書込(宛先値 + バイト値, 装置.記憶読取(原本 + バイト値));
        }
        引数個数 = 0;
        int 格納値 = 引数開始処理;
        while (終端 < 長さ) {
            while (終端 < 長さ && 入力値[終端] == ' ') 終端++;
            if (終端 == 長さ) break;
            if (引数個数 == 引数番地.length) return -22;
            起動処理 = 終端;
            while (終端 < 長さ && 入力値[終端] != ' ') 終端++;
            引数番地[引数個数++] = 格納値;
            番号書込(格納値, 終端 - 起動処理);
            for (int 文字値 = 起動処理; 文字値 < 終端; 文字値++) 番号書込(格納値 + 4 + (文字値 - 起動処理) * 4, 入力値[文字値]);
            格納値 += 4 + (終端 - 起動処理) * 4;
        }
        通信網.清掃プロセス();
        ファイル記述子管理.プロセス開始処理();
        int 結果 = 装置.利用者プログラム起動処理(入口点値, 利用者終端位置 - 16);
        ファイル記述子管理.清掃プロセス();
        通信網.清掃プロセス();
        return 結果;
    }
}
