/** 最初の IDE 装置の512バイト論理セクター。この層では書式設定や任意装置の消去を行わない。 */
public final class 記憶装置接続 {
    static boolean 判定利用可能 = false;
    static int[] 区画データ = new int[512];
    static void 短時間だけ待合() {
        for (int 番号 = 0; 番号 < 4; 番号++) 装置.入出力バイト読取(0x3f6);
    }
    static int 到達待ち準備済み待合(boolean データ必須) {
        int 起動処理 = 装置.ミリ秒();
        while (装置.ミリ秒() - 起動処理 < 500) {
            int 状況値 = 装置.入出力バイト読取(0x1f7);
            if (状況値 == 0 || 状況値 == 255) return -19;
            if ((状況値 & 128) == 0) {
                if ((状況値 & 33) != 0) return -5;
                if (!データ必須 || (状況値 & 8) != 0) return 0;
            }
            装置.短時間だけ実行権譲渡();
        }
        return -110;
    }
    static int 要求(int 区画値, int 命令) {
        if (区画値 < 0 || 区画値 >= 2048) return -22;
        装置.入出力バイト書込(0x3f6, 2); // ポーリングを使い、IDE IRQ は使わない。
        装置.入出力バイト書込(0x1f6, 0xe0); 短時間だけ待合();
        int 結果 = 到達待ち準備済み待合(false);
        if (結果 < 0) return 結果;
        装置.入出力バイト書込(0x1f2, 1);
        装置.入出力バイト書込(0x1f3, 区画値 & 255);
        装置.入出力バイト書込(0x1f4, (区画値 >>> 8) & 255);
        装置.入出力バイト書込(0x1f5, 0);
        装置.入出力バイト書込(0x1f7, 命令); 短時間だけ待合();
        return 到達待ち準備済み待合(true);
    }
    static int 読取(int 区画値) {
        int 結果 = 要求(区画値, 0x20);
        if (結果 < 0) return 結果;
        for (int 番号 = 0; 番号 < 256; 番号++) {
            int 値 = 装置.入出力短整数読取(0x1f0);
            区画データ[番号 * 2] = 値 & 255; 区画データ[番号 * 2 + 1] = 値 >>> 8;
        }
        短時間だけ待合(); return 到達待ち準備済み待合(false);
    }
    static int 書込(int 区画値) {
        if (!判定利用可能 || 区画値 < 1 || 区画値 > 518) return -19;
        int 結果 = 要求(区画値, 0x30);
        if (結果 < 0) return 結果;
        for (int 番号 = 0; 番号 < 256; 番号++)
            装置.入出力短整数書込(0x1f0, 区画データ[番号 * 2] | 区画データ[番号 * 2 + 1] << 8);
        短時間だけ待合(); return 到達待ち準備済み待合(false);
    }
    static int 排出出力() {
        if (!判定利用可能) return -19;
        装置.入出力バイト書込(0x1f7, 0xe7); 短時間だけ待合();
        return 到達待ち準備済み待合(false);
    }
    static int 整数値解析(int 位置) {
        return 区画データ[位置] | 区画データ[位置 + 1] << 8 | 区画データ[位置 + 2] << 16 | 区画データ[位置 + 3] << 24;
    }
    static void 整数値値書込(int 位置, int 値) {
        for (int 番号 = 0; 番号 < 4; 番号++) 区画データ[位置 + 番号] = (値 >>> (番号 * 8)) & 255;
    }
}
