/** PCI RTL8139（10ec:8139）。送信バッファー一つと8 KiB受信リング。割込みの代わりにポーリングする。 */
public final class 通信装置駆動器 {
    static int 入出力基底番地 = 0;
    static int 位置受取 = 0, 伝送槽 = 0;
    static int[] 装置番地 = new int[6];
    static int 伝送個数 = 0, 個数受取 = 0, エラー個数 = 0;

    static int 設定値読取(int 装置番号, int 位置) {
        装置.入出力整数値書込(0xcf8, 0x80000000 | (装置番号 << 11) | 位置);
        return 装置.入出力整数値読取(0xcfc);
    }

    static boolean 用意() {
        int 装置番号 = -1;
        for (int 番号 = 0; 番号 < 32; 番号++) {
            if (設定値読取(番号, 0) == 0x813910ec) { 装置番号 = 番号; break; }
        }
        if (装置番号 < 0) return false;
        int 既定値 = 設定値読取(装置番号, 0x10);
        if ((既定値 & 1) == 0 || (既定値 & 0xfffffffc) < 0x100 || (既定値 & 0xfffffffc) > 65535) return false;
        入出力基底番地 = 既定値 & 0xfffc;
        int 命令 = 設定値読取(装置番号, 4);
        装置.入出力整数値書込(0xcf8, 0x80000004 | (装置番号 << 11));
        装置.入出力短整数書込(0xcfc, 命令 | 5); // I/O とバスマスターを有効にし、PCI 状態ビットは変更しない。
        装置.入出力バイト書込(入出力基底番地 + 0x52, 0);
        if (!値初期復帰()) { 入出力基底番地 = 0; return false; }
        for (int 番号 = 0; 番号 < 6; 番号++) 装置番地[番号] = 装置.入出力バイト読取(入出力基底番地 + 番号);
        return true;
    }

    static boolean 値初期復帰() {
        装置.入出力バイト書込(入出力基底番地 + 0x37, 0x10);
        int 起動処理 = 装置.ミリ秒();
        while ((装置.入出力バイト読取(入出力基底番地 + 0x37) & 0x10) != 0)
            if (装置.ミリ秒() - 起動処理 > 100) return false;
        位置受取 = 0; 伝送槽 = 0;
        装置.入出力整数値書込(入出力基底番地 + 0x30, 装置.通信網記憶());
        for (int 番号 = 0; 番号 < 4; 番号++) 装置.入出力整数値書込(入出力基底番地 + 0x20 + 番号 * 4, 装置.通信網記憶() + 12288);
        装置.入出力短整数書込(入出力基底番地 + 0x3c, 0);
        装置.入出力短整数書込(入出力基底番地 + 0x3e, 0xffff);
        装置.入出力バイト書込(入出力基底番地 + 0x37, 0x0c);
        装置.入出力整数値書込(入出力基底番地 + 0x44, 0x0000e78a); // 自局宛と同報を受信し、折返しを連続格納する。8 KiB。
        装置.入出力整数値書込(入出力基底番地 + 0x40, 0x03000600);
        return true;
    }

    static int 送信(int[] データ, int 長さ) {
        if (入出力基底番地 == 0) return -19;
        if (長さ < 14 || 長さ > 1514) return -90;
        int 状態ポート = 入出力基底番地 + 0x10 + 伝送槽 * 4;
        int 起動処理 = 装置.ミリ秒();
        while ((装置.入出力整数値読取(状態ポート) & 0x2000) == 0)
            if (装置.ミリ秒() - 起動処理 > 100) return -110;
        int 容量 = 長さ < 60 ? 60 : 長さ;
        for (int 番号 = 0; 番号 < 容量; 番号++)
            装置.記憶書込(装置.通信網記憶() + 12288 + 番号, 番号 < 長さ ? データ[番号] : 0);
        装置.入出力整数値書込(状態ポート, 容量 | 0x00080000);
        起動処理 = 装置.ミリ秒();
        while ((装置.入出力整数値読取(状態ポート) & 0xe0008000) == 0)
            if (装置.ミリ秒() - 起動処理 > 100) return -110;
        if ((装置.入出力整数値読取(状態ポート) & 0x8000) == 0) { エラー個数++; return -5; }
        伝送槽 = (伝送槽 + 1) & 3;
        伝送個数++;
        return 長さ;
    }

    static int 受取(int[] データ) {
        if (入出力基底番地 == 0) return 0;
        if ((装置.入出力バイト読取(入出力基底番地 + 0x3e) & 0x50) != 0) {
            エラー個数++;
            if (!値初期復帰()) 入出力基底番地 = 0;
            return 0;
        }
        if ((装置.入出力バイト読取(入出力基底番地 + 0x37) & 1) != 0) return 0;
        int 先頭部値 = 装置.通信網記憶() + 位置受取;
        int 状況値 = 実行管理.短整数値(先頭部値), 容量 = 実行管理.短整数値(先頭部値 + 2);
        if (容量 == 0xfff0) return 0; // DMA 転送中。
        if (容量 < 4 || 容量 > 1518) {
            エラー個数++;
            if (!値初期復帰()) 入出力基底番地 = 0;
            return 0;
        }
        int 長さ = 容量 - 4;
        if ((状況値 & 1) != 0) {
            for (int 番号 = 0; 番号 < 長さ; 番号++) データ[番号] = 装置.記憶読取(先頭部値 + 4 + 番号);
            個数受取++;
        } else { 長さ = 0; エラー個数++; }
        位置受取 = (位置受取 + 容量 + 4 + 3) & ~3;
        位置受取 &= 8191;
        装置.入出力短整数書込(入出力基底番地 + 0x38, (位置受取 - 16) & 65535);
        装置.入出力短整数書込(入出力基底番地 + 0x3e, 0x000f);
        return 長さ;
    }
}
