/** 描画範囲の切取り、帯領域の合成、ポインターの下地を管理する。実際の画面記憶域へのアクセスはボードが担う。 */
public final class 描画領域組立器 {
    static int 幅値, 高さ値, 判定組立中, 左境界位置値, 上限側境界位置, 右境界位置値, 下限側境界位置値;
    static int ポインタ横, ポインタ縦, ポインタ形状;
    static int 計数器下位, 計数器上位;
    static int[] 合成済み画素列 = new int[32 * 1920];
    static int[] ポインタ背景 = new int[21 * 21];
    static int[] 切抜き済み境界 = new int[4];
    public static void 用意(int 幅跨域, int 長さ) {
        幅値 = 幅跨域; 高さ値 = 長さ; 判定組立中 = 0; ポインタ形状 = 0;
        計数器下位 = 0; 計数器上位 = 0;
    }
    public static int 幅取得() { return 幅値; }
    public static int 高さ取得() { return 高さ値; }
    public static int 計数器下位取得() { return 計数器下位; }
    public static int 計数器上位取得() { return 計数器上位; }
    public static int 切抜き値(int 序数添字) { return 切抜き済み境界[序数添字]; }
    static int 正数長さ追加(int 値開始処理, int 長さ) {
        if (値開始処理 > 2147483647 - 長さ) return 2147483647;
        return 値開始処理 + 長さ;
    }
    public static int 切抜き(int 水平位置, int 垂直位置, int 幅跨域, int 長さ) {
        if (幅値 == 0 || 幅跨域 <= 0 || 長さ <= 0) return 0;
        int 右 = 正数長さ追加(水平位置, 幅跨域), 下限側側面 = 正数長さ追加(垂直位置, 長さ);
        int 左側面 = 判定組立中 != 0 ? 左境界位置値 : 0, 上限側側面 = 判定組立中 != 0 ? 上限側境界位置 : 0;
        int 最大水平位置 = 判定組立中 != 0 ? 右境界位置値 : 幅値, 最大垂直位置 = 判定組立中 != 0 ? 下限側境界位置値 : 高さ値;
        if (水平位置 < 左側面) 水平位置 = 左側面;
        if (垂直位置 < 上限側側面) 垂直位置 = 上限側側面;
        if (右 > 最大水平位置) 右 = 最大水平位置;
        if (下限側側面 > 最大垂直位置) 下限側側面 = 最大垂直位置;
        if (右 <= 水平位置 || 下限側側面 <= 垂直位置) return 0;
        切抜き済み境界[0] = 水平位置; 切抜き済み境界[1] = 垂直位置;
        切抜き済み境界[2] = 右 - 水平位置; 切抜き済み境界[3] = 下限側側面 - 垂直位置;
        return 1;
    }
    public static int 起動処理(int 水平位置, int 垂直位置, int 幅跨域, int 長さ) {
        if (判定組立中 != 0 || 長さ > 32 || 切抜き(水平位置, 垂直位置, 幅跨域, 長さ) == 0) return 0;
        左境界位置値 = 切抜き済み境界[0]; 上限側境界位置 = 切抜き済み境界[1];
        右境界位置値 = 左境界位置値 + 切抜き済み境界[2]; 下限側境界位置値 = 上限側境界位置 + 切抜き済み境界[3];
        判定組立中 = 1; return 1;
    }
    static boolean ポインタビット(int 水平位置, int 垂直位置, int 形状値) {
        if (形状値 == 1) return 水平位置 >= 0 && 水平位置 <= 垂直位置 / 2 && 垂直位置 < 16;
        if (形状値 == 3) 水平位置 = 20 - 水平位置;
        int 差分値 = 水平位置 - 垂直位置; if (差分値 < 0) 差分値 = -差分値;
        return (差分値 <= 1 && 水平位置 >= 3 && 水平位置 <= 17) ||
            (水平位置 >= 2 && 水平位置 <= 8 && 垂直位置 >= 2 && 垂直位置 <= 8 && (水平位置 <= 3 || 垂直位置 <= 3)) ||
            (水平位置 >= 12 && 水平位置 <= 18 && 垂直位置 >= 12 && 垂直位置 <= 18 && (水平位置 >= 17 || 垂直位置 >= 17));
    }
    static int ポインタ画素(int 水平位置, int 垂直位置) {
        if (ポインタビット(水平位置, 垂直位置, ポインタ形状)) return 2;
        for (int 行 = -1; 行 <= 1; 行++) for (int 槽入口 = -1; 槽入口 <= 1; 槽入口++)
            if (ポインタビット(水平位置 + 槽入口, 垂直位置 + 行, ポインタ形状)) return 1;
        return 0;
    }
    static void 表示処理画素(int 水平位置, int 垂直位置, int 色値) {
        int 槽入口 = 水平位置 - ポインタ横, 行 = 垂直位置 - ポインタ縦;
        if (ポインタ形状 != 0 && 槽入口 >= 0 && 行 >= 0 && 槽入口 < 21 && 行 < 21) {
            ポインタ背景[行 * 21 + 槽入口] = 色値;
            int 点値 = ポインタ画素(槽入口, 行); if (点値 != 0) 色値 = 点値 == 2 ? 0xffffff : 0x101010;
        }
        if (基板.表示処理画素読取(水平位置, 垂直位置) != 色値) {
            基板.表示処理画素書込(水平位置, 垂直位置, 色値);
            計数器下位++; if (計数器下位 == 0) 計数器上位++;
        }
    }
    public static void 終了処理() {
        if (判定組立中 == 0) return;
        for (int 行 = 上限側境界位置; 行 < 下限側境界位置値; 行++) for (int 槽入口 = 左境界位置値; 槽入口 < 右境界位置値; 槽入口++)
            表示処理画素(槽入口, 行, 合成済み画素列[(行 - 上限側境界位置) * 1920 + 槽入口]);
        判定組立中 = 0;
    }
    public static int 画素(int 水平位置, int 垂直位置, int 色値) {
        if (水平位置 < 0 || 垂直位置 < 0 || 水平位置 >= 幅値 || 垂直位置 >= 高さ値) return 0;
        if (判定組立中 != 0) {
            if (水平位置 >= 左境界位置値 && 水平位置 < 右境界位置値 && 垂直位置 >= 上限側境界位置 && 垂直位置 < 下限側境界位置値)
                合成済み画素列[(垂直位置 - 上限側境界位置) * 1920 + 水平位置] = 色値;
        } else 表示処理画素(水平位置, 垂直位置, 色値);
        return 0;
    }
    public static void 矩形塗潰し(int 水平位置, int 垂直位置, int 幅跨域, int 長さ, int 色値) {
        if (切抜き(水平位置, 垂直位置, 幅跨域, 長さ) == 0) return;
        水平位置 = 切抜き済み境界[0]; 垂直位置 = 切抜き済み境界[1]; 幅跨域 = 切抜き済み境界[2]; 長さ = 切抜き済み境界[3];
        for (int 行 = 垂直位置; 行 < 垂直位置 + 長さ; 行++) for (int 槽入口 = 水平位置; 槽入口 < 水平位置 + 幅跨域; 槽入口++) {
            if (判定組立中 != 0) 合成済み画素列[(行 - 上限側境界位置) * 1920 + 槽入口] = 色値;
            else 表示処理画素(槽入口, 行, 色値);
        }
    }
    public static void ポインタ(int 水平位置, int 垂直位置, int 形状値) {
        if (幅値 == 0) return;
        int 新規水平位置 = 水平位置 - (形状値 >= 2 ? 10 : 0), 新規垂直位置 = 垂直位置 - (形状値 >= 2 ? 10 : 0);
        if (ポインタ形状 == 形状値 && ポインタ横 == 新規水平位置 && ポインタ縦 == 新規垂直位置) return;
        if (ポインタ形状 != 0) for (int 行 = 0; 行 < 21; 行++) for (int 槽入口 = 0; 槽入口 < 21; 槽入口++) {
            int 先頭位置被演算子 = ポインタ横 + 槽入口, 三値 = ポインタ縦 + 行;
            if (先頭位置被演算子 >= 0 && 三値 >= 0 && 先頭位置被演算子 < 幅値 && 三値 < 高さ値) 基板.表示処理画素書込(先頭位置被演算子, 三値, ポインタ背景[行 * 21 + 槽入口]);
        }
        ポインタ形状 = 形状値; ポインタ横 = 新規水平位置; ポインタ縦 = 新規垂直位置;
        if (形状値 != 0) for (int 行 = 0; 行 < 21; 行++) for (int 槽入口 = 0; 槽入口 < 21; 槽入口++) {
            int 先頭位置被演算子 = ポインタ横 + 槽入口, 三値 = ポインタ縦 + 行;
            if (先頭位置被演算子 >= 0 && 三値 >= 0 && 先頭位置被演算子 < 幅値 && 三値 < 高さ値) {
                ポインタ背景[行 * 21 + 槽入口] = 基板.表示処理画素読取(先頭位置被演算子, 三値);
                int 点値 = ポインタ画素(槽入口, 行); if (点値 != 0) 基板.表示処理画素書込(先頭位置被演算子, 三値, 点値 == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
