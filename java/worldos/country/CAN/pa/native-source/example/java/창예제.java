import ਪੰਜਾਬੀ.자체.ਵਿੰਡੋ;
import ਪੰਜਾਬੀ.자체.ਲੇਬਲ;
import ਪੰਜਾਬੀ.자체.ਟੈਕਸਟ_ਖੇਤਰ;
import ਪੰਜਾਬੀ.자체.ਬਟਨ;
import ਪੰਜਾਬੀ.자체.ਇਵੈਂਟ_ਕਤਾਰ;
import ਪੰਜਾਬੀ.자체.ਆਉਟਪੁੱਟ;
import ਪੰਜਾਬੀ.자체.실행할일;
import ਪੰਜਾਬੀ.자체.동작받이;
import ਪੰਜਾਬੀ.자체.동작알림;

/** 자체 커널의 Swing ਵਿੰਡੋ: pa 입력 → ਬਟਨ → ਫਈਲ_ਮੈਨੂੰ_ਪੜਨ_ਦਿਉ_eb81d7d9 ਟੈਕਸਟ ਤਾਜ਼ਾ_ਕਰੋ. */
public class 창예제 implements 실행할일, 동작받이 {
    private ਵਿੰਡੋ 인사창;
    private ਟੈਕਸਟ_ਖੇਤਰ ਨਾਮ_ਫਿਲਡ;
    private ਲੇਬਲ 인사말;
    private int 인사횟수;

    public void ਖੋਲੋ_ਵਿੰਡੋ() {
        인사창 = new ਵਿੰਡੋ("pa Swing", 460, 300);
        인사창.ਜੋੜਨਾ_ਤੱਤ(new ਲੇਬਲ("pa", 20, 20, 420, 28));
        ਨਾਮ_ਫਿਲਡ = new ਟੈਕਸਟ_ਖੇਤਰ("pa", 20, 64, 420, 30);
        인사말 = new ਲੇਬਲ("pa", 20, 152, 420, 28);
        인사창.ਜੋੜਨਾ_ਤੱਤ(ਨਾਮ_ਫਿਲਡ);
        인사창.ਜੋੜਨਾ_ਤੱਤ(new ਬਟਨ("인사하기", 20, 108, 180, 32, this));
        인사창.ਜੋੜਨਾ_ਤੱਤ(인사말);
        인사창.ਜੋੜਨਾ_ਤੱਤ(new ਲੇਬਲ("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.ਸ਼ੋਅ_ਵਿੰਡੋ();
        ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ("GUI 예제 ਤਿਆਰ_ਕਰੋ: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.ਲਿੱਖੋ_ਪਾਠ("pa, " + ਨਾਮ_ਫਿਲਡ.글읽기() + "님! (" + 인사횟수 + ")");
        ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ("GUI 인사: " + 인사말.글읽기());
    }

    public void ਚਲਾਓ() { ਖੋਲੋ_ਵਿੰਡੋ(); }
    public void 동작받기(동작알림 알림) {
        ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ("ਐਕਸ਼ਨ 알림: " + 알림.ਆਦੇਸ਼_ਪਾਠ());
        인사하기();
    }
    public static void ਚਲਾਓ_2() {
        ਇਵੈਂਟ_ਕਤਾਰ.나중에실행(new 창예제());
    }
}
