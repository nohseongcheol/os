/** COM1 직렬 출력과 VGA 80x25 문자 화면. 한글은 직렬 단말에 UTF-8로 출력한다. */
public final class ਪਾਠ_ਟਰਮੀਨਲ {
    static int ਸਲੌਟ_ਦਾਖਲਾ = 0;
    static int 색 = 7;

    static void ਤਿਆਰ_ਕਰੋ() {
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3f9, 0);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3fb, 0x80);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3f8, 1);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3f9, 0);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3fb, 3);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3fa, 0xc7);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3fc, 0x0b);
        지우기();
    }

    static void 직렬바이트(int ਕੀਮਤ) {
        int 횟수 = 100000;
        while ((ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트읽기(0x3fd) & 0x20) == 0 && 횟수 > 0) 횟수--;
        if (횟수 > 0) ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3f8, ਕੀਮਤ);
    }

    static void 지우기() {
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 2000; ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
            ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(0xb8000 + ਅਨੁਕ੍ਰਮਣਿਕਾ * 2, 32);
            ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(0xb8001 + ਅਨੁਕ੍ਰਮਣਿਕਾ * 2, 색);
        }
        ਸਲੌਟ_ਦਾਖਲਾ = 0;
        ਕਰਸਰ_ਕੀਮਤ();
    }

    static void ਕਰਸਰ_ਕੀਮਤ() {
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3d4, 14);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3d5, ਸਲੌਟ_ਦਾਖਲਾ >> 8);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3d4, 15);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(0x3d5, ਸਲੌਟ_ਦਾਖਲਾ & 255);
    }

    static void 화면문자(int ਕੀਮਤ) {
        if (ਕੀਮਤ == 13) return;
        if (ਕੀਮਤ == 10) {
            ਸਲੌਟ_ਦਾਖਲਾ = (ਸਲੌਟ_ਦਾਖਲਾ / 80 + 1) * 80;
        } else if (ਕੀਮਤ == 8) {
            if (ਸਲੌਟ_ਦਾਖਲਾ > 0) {
                ਸਲੌਟ_ਦਾਖਲਾ--;
                ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(0xb8000 + ਸਲੌਟ_ਦਾਖਲਾ * 2, 32);
            }
        } else {
            ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(0xb8000 + ਸਲੌਟ_ਦਾਖਲਾ * 2, ਕੀਮਤ < 128 ? ਕੀਮਤ : '?');
            ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(0xb8001 + ਸਲੌਟ_ਦਾਖਲਾ * 2, 색);
            ਸਲੌਟ_ਦਾਖਲਾ++;
        }
        if (ਸਲੌਟ_ਦਾਖਲਾ >= 2000) {
            for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 3840; ਅਨੁਕ੍ਰਮਣਿਕਾ++)
                ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(0xb8000 + ਅਨੁਕ੍ਰਮਣਿਕਾ, ਤਜਵੀਜ_ਕੀਮਤ.기억읽기(0xb80a0 + ਅਨੁਕ੍ਰਮਣਿਕਾ));
            for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 1920; ਅਨੁਕ੍ਰਮਣਿਕਾ < 2000; ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
                ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(0xb8000 + ਅਨੁਕ੍ਰਮਣਿਕਾ * 2, 32);
                ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(0xb8001 + ਅਨੁਕ੍ਰਮਣਿਕਾ * 2, 색);
            }
            ਸਲੌਟ_ਦਾਖਲਾ = 1920;
        }
        ਕਰਸਰ_ਕੀਮਤ();
    }

    static void 문자(int ਕੀਮਤ) {
        if (ਕੀਮਤ < 128) {
            if (ਕੀਮਤ == 10) 직렬바이트(13);
            직렬바이트(ਕੀਮਤ);
        } else if (ਕੀਮਤ < 2048) {
            직렬바이트(0xc0 | (ਕੀਮਤ >> 6));
            직렬바이트(0x80 | (ਕੀਮਤ & 63));
        } else {
            직렬바이트(0xe0 | (ਕੀਮਤ >> 12));
            직렬바이트(0x80 | ((ਕੀਮਤ >> 6) & 63));
            직렬바이트(0x80 | (ਕੀਮਤ & 63));
        }
        화면문자(ਕੀਮਤ);
    }

    static void ਲਿਖਣ(String ਤਤਕਰਾ_ਕੀਮਤ) {
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < ਤਤਕਰਾ_ਕੀਮਤ.length(); ਅਨੁਕ੍ਰਮਣਿਕਾ++) 문자(ਤਤਕਰਾ_ਕੀਮਤ.charAt(ਅਨੁਕ੍ਰਮਣਿਕਾ));
    }

    static void 수쓰기(int ਕੀਮਤ) {
        // 양수로 바꾸지 않으므로 Integer.MIN_VALUE도 안전하다.
        if (ਕੀਮਤ < 0) 문자('-');
        else ਕੀਮਤ = -ਕੀਮਤ;
        int ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ = 1000000000;
        boolean ਚਲਾਓ_2 = false;
        while (ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ > 0) {
            int ਅੰਕ_ਕੀਮਤ = -(ਕੀਮਤ / ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ);
            if (ਅੰਕ_ਕੀਮਤ != 0 || ਚਲਾਓ_2 || ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ == 1) {
                문자('0' + ਅੰਕ_ਕੀਮਤ);
                ਚਲਾਓ_2 = true;
            }
            ਕੀਮਤ %= ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ;
            ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ /= 10;
        }
    }

    static int 직렬읽기() {
        if ((ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트읽기(0x3fd) & 1) != 0) return ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트읽기(0x3f8);
        return -1;
    }
}
