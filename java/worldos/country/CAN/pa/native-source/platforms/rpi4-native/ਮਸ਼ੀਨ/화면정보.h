#ifndef 자체화면정보머리
#define 자체화면정보머리
#include <stdint.h>
/* 초기화가 끝난 ਅਸਲ_ਸਮੱਗਰੀ RGB32 화면 ਆਕਾਰ. 준비되지 않았으면 0이다. */
uintptr_t 보드화면너비(void);
uintptr_t 보드화면높이(void);
/* 0: ਲੁਕਿਆ_ਹੋਇਆ_ਕੀਮਤ, 1: 화살표, 2: 좌상↔우하, 3: 우상↔좌하. */
void ਬੋਰਡ_ਪੌਇੰਟਰ(int 가로, int ਲੰਬਵਤ_ਸਥਿਤੀ_ਬਦਲੋ, unsigned ਆਕ੍ਰਿਤੀ_ਕੀਮਤ);
/* 한 번에 32줄을 완성한 ਪਿਛਲਾ_ਕੀਮਤ, 달라진 화소만 ਅਸਲ_ਸਮੱਗਰੀ 화면에 옮긴다. */
void ਬੋਰਡ_ਤਿਆਰ_ਕਰੋ_ਚਿੱਤਰ_ਬਨਾਉਣਾ(volatile uint32_t *ਸਮੱਗਰੀ, unsigned 폭, unsigned ਲੰਬਾਈ_ਕੀਮਤ, unsigned ਲੀਡਿੰਗ_ਕੀਮਤ);
int 보드그림범위(int *가로, int *ਲੰਬਵਤ_ਸਥਿਤੀ_ਬਦਲੋ, int *폭, int *ਲੰਬਾਈ_ਕੀਮਤ);
int ਬੋਰਡ_ਸੁਰੂ_ਚਿੱਤਰ_ਬਨਾਉਣਾ(int 가로, int ਲੰਬਵਤ_ਸਥਿਤੀ_ਬਦਲੋ, int 폭, int ਲੰਬਾਈ_ਕੀਮਤ);
void ਬੋਰਡ_ਖਤਮ_ਕਰਨਾ_ਚਿੱਤਰ_ਬਨਾਉਣਾ(void);
void 보드사각그림(int 가로, int ਲੰਬਵਤ_ਸਥਿਤੀ_ਬਦਲੋ, int 폭, int ਲੰਬਾਈ_ਕੀਮਤ, uint32_t 색);
/* ਅਸਲ_ਸਮੱਗਰੀ ਸ਼ੋਅ_ਕੀਮਤ 메모리에 기록한 ਬਿੰਦੂ 수. ਪੌਇੰਟਰ 갱신은 제외한다. */
uint64_t 보드그림기록수(void);
uint32_t 보드화면읽기(unsigned 가로, unsigned ਲੰਬਵਤ_ਸਥਿਤੀ_ਬਦਲੋ);
#endif
