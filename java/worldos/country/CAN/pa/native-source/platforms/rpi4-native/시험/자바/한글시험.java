public class 한글시험 {
    public static void main(String[] a) throws Exception {
        String 인사 = "안녕하세요 · 日本語 · العربية · 😀";
        ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ(문자.ਬਦਲਾਵ_ਕਰੋ_ਸਮੱਗਰੀ(문자.부호화(인사))); ਆਉਟਪੁੱਟ.수쓰기(문자.코드포인트수("한글😀"));
        ਫਾਇਲ.ਲਿਖਣ("한글자료.txt", 인사); ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ(ਫਾਇਲ.ਪੜ੍ਹਨ("한글자료.txt"));
        ਦਾਖਲਾ_ਸੂਚੀ 이름들 = new ਦਾਖਲਾ_ਸੂਚੀ(); 이름들.더하기("가람"); 이름들.더하기("누리"); ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ(이름들.ਪੜ੍ਹਨ(1));
        ਸ਼ਬਦਕੋਸ਼ 뜻 = new ਸ਼ਬਦਕੋਸ਼(); 뜻.넣기("가람", "강"); System.gc(); ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ(뜻.ਲੱਭੋ_ਦਾਖਲਾ("가람"));
        try { 문자.ਬਦਲਾਵ_ਕਰੋ_ਸਮੱਗਰੀ(new byte[] {(byte)0xc0, (byte)0xaf}); } catch (IllegalArgumentException e) { ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ("UTF-8 ਗਲਤੀ 거부"); }
        ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ("ਪੰਜਾਬੀ ਪੁਸਤਕਾਲਾ 완료");
    }
}
