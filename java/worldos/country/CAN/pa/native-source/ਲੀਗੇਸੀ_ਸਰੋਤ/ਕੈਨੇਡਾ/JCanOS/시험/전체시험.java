    private static void 파일과과정시험(ਪੱਕੇ_ਹੋਣਾ ਪੱਕੇ_ਹੋਣਾ_ਕੀਮਤ) {
        byte[] ਤਤਕਰਾ_ਕੀਮਤ = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        ਪੱਕੇ_ਹੋਣਾ_ਕੀਮਤ.ਫਾਈਲ_ਸਿਸਟਮ().파일추가("시험", ਤਤਕਰਾ_ਕੀਮਤ);
        ਕਾਰਵਾਈ_ਕੀਮਤ 부모 = ਪੱਕੇ_ਹੋਣਾ_ਕੀਮਤ.첫과정();
        체계호출 호출 = ਪੱਕੇ_ਹੋਣਾ_ਕੀਮਤ.체계호출();
        int 서술자 = 호출.ਖੋਲ੍ਹੋ(부모, "/시험", 체계호출.ਸਿਰਫ਼_ਪੜ੍ਹੋ_ਨਿਸ਼ਾਨ);
        ਤਸਦੀਕ(서술자 >= 3, "ਫਾਇਲ ਖੋਲ੍ਹੋ");

        byte[] 받을곳 = new byte[ਤਤਕਰਾ_ਕੀਮਤ.length];
        ਤਸਦੀਕ(호출.ਪੜ੍ਹਨ(부모, 서술자, 받을곳, 받을곳.length) == ਤਤਕਰਾ_ਕੀਮਤ.length, "ਫਾਇਲ ਪੜ੍ਹਨ");
        ਤਸਦੀਕ(Arrays.equals(ਤਤਕਰਾ_ਕੀਮਤ, 받을곳), "ਫਾਇਲ ਤਤਕਰਾ_ਕੀਮਤ");
        ਤਸਦੀਕ(호출.ਖਿਸਕਾਉਣਾ_ਸਥਿਤੀ_ਬਦਲੋ(부모, 서술자, 0, 체계호출.ਖੋਜ_ਸੁਰੂ) == 0, "ਫਾਇਲ ਸਥਿਤੀ ਖਿਸਕਾਉਣਾ_ਕੀਮਤ");

        int 복제서술자 = 호출.서술자복제(부모, 서술자);
        ਤਸਦੀਕ(복제서술자 >= 0, "서술자 복제");
        ਕਾਰਵਾਈ_ਕੀਮਤ ਚਾਈਲਡ_ਕੀਮਤ = 호출.과정복제(부모);
        ਤਸਦੀਕ(ਚਾਈਲਡ_ਕੀਮਤ.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ() != 부모.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ(), "ਕਾਰਵਾਈ_ਕੀਮਤ ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ 분리");
        ਤਸਦੀਕ(ਚਾਈਲਡ_ਕੀਮਤ.부모식별자() == 부모.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ(), "부모 ਕਾਰਵਾਈ_ਕੀਮਤ ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ");
        ਤਸਦੀਕ(호출.ਬੰਦ_ਕਰੋ(ਚਾਈਲਡ_ਕੀਮਤ, 서술자) == 0 && 부모.파일서술자().열려있음(서술자), "ਚਾਈਲਡ_ਕੀਮਤ ਬੰਦ_ਕਰੋ 격리");

        int 이전끝 = 호출.프로그램끝늘리기(부모, 8192);
        ਤਸਦੀਕ(이전끝 == 0x06000000, "ਐਪਲੀਕੇਸ਼_f5044b9b 끝 늘리기");
        ਤਸਦੀਕ(부모.프로그램끝() == 0x06002000, "ਐਪਲੀਕੇਸ਼_f5044b9b 끝 반영");
        ਤਸਦੀਕ(ਚਾਈਲਡ_ਕੀਮਤ.프로그램끝() == 0x06000000, "과정별 ਐਪਲੀਕੇਸ਼_f5044b9b 끝 격리");

        ਚਾਈਲਡ_ਕੀਮਤ.ਨਿਕਾਸ_ਐਪਲੀਕੇਸ਼(7);
        ਤਸਦੀਕ(호출.자식기다리기(부모, ਚਾਈਲਡ_ਕੀਮਤ.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ(), false) == (7 << 8), "ਚਾਈਲਡ_ਕੀਮਤ ਨਿਕਾਸ_ਐਪਲੀਕੇਸ਼ 기다리기");
        ਤਸਦੀਕ(호출.접근가능("시험", 1) == -13, "ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼ ਆਗਿਆ_ਕੀਮਤ 거부");
        ਤਸਦੀਕ(호출.ਉਪਭੋਗਤਾ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ() == 0 && 호출.ਸਮੂਹ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ() == 0, "사용자와 무리 ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ");
        ਤਸਦੀਕ("/".equals(호출.현재작업목록(2)) && 호출.ਸਵਿੱਚ_ਕਾਰਜ_ਸੂਚੀ("/") == 0, "현재 작업 ਦਾਖਲਾ_ਸੂਚੀ");
        ਤਸਦੀਕ(호출.단말인가(부모, 1), "표준 ਆਉਟਪੁੱਟ 단말");
        ਤਸਦੀਕ("JCanOS".equals(호출.체계정보().ਪਰਬੰਧ_ਨਾਮ()), "ਸਿਸਟਮ_ਚਲਾਉਣਾ_ਕੀਮਤ ਸਿਸਟਮ_ਜਾਣਕਾਰੀ");
    }

