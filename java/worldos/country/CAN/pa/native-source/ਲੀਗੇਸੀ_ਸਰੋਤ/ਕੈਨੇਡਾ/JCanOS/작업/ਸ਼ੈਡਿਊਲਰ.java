package ਕੈਨੇਡਾ.JCanOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import ਕੈਨੇਡਾ.JCanOS.기억공간.ਪੰਨਾ_ਪ੍ਰਬੰਧਕ;
import ਕੈਨੇਡਾ.JCanOS.ਫਾਈਲ_ਸਿਸਟਮ.파일서술자표;

/** ਕਾਰਵਾਈ_ਕੀਮਤ 식별자와 라운드로빈 ਤਿਆਰ_ਕਰੋ 대기열을 관리한다. */
public final class ਸ਼ੈਡਿਊਲਰ {
    private final ਪੰਨਾ_ਪ੍ਰਬੰਧਕ 쪽관리;
    private final Map<Integer, ਕਾਰਵਾਈ_ਕੀਮਤ> ਪ੍ਰਕਿਰਿਆ_ਸੂਚੀ = new HashMap<Integer, ਕਾਰਵਾਈ_ਕੀਮਤ>();
    private final Queue<ਕਾਰਵਾਈ_ਕੀਮਤ> 준비대기열 = new ArrayDeque<ਕਾਰਵਾਈ_ਕੀਮਤ>();
    private int ਅਗਲਾ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ = 1;

    public ਸ਼ੈਡਿਊਲਰ(ਪੰਨਾ_ਪ੍ਰਬੰਧਕ 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public ਕਾਰਵਾਈ_ਕੀਮਤ 첫과정(파일서술자표 파일서술자) {
        ਕਾਰਵਾਈ_ਕੀਮਤ 새과정 = new ਕਾਰਵਾਈ_ਕੀਮਤ(ਨਿਰਧਾਰਿਤ_ਕਰੋ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ(), 0, 쪽관리.새주소공간(), 파일서술자);
        ਪ੍ਰਕਿਰਿਆ_ਸੂਚੀ.put(Integer.valueOf(새과정.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public ਕਾਰਵਾਈ_ਕੀਮਤ 복제(ਕਾਰਵਾਈ_ਕੀਮਤ 부모) {
        ਕਾਰਵਾਈ_ਕੀਮਤ ਚਾਈਲਡ_ਕੀਮਤ = new ਕਾਰਵਾਈ_ਕੀਮਤ(
                ਨਿਰਧਾਰਿਤ_ਕਰੋ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ(),
                부모.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ(),
                쪽관리.쓰기시복사복제(부모.ਪਤਾ_ਥਾਂ()),
                부모.파일서술자().복제());
        ਚਾਈਲਡ_ਕੀਮਤ.프로그램끝설정(부모.프로그램끝());
        ਪ੍ਰਕਿਰਿਆ_ਸੂਚੀ.put(Integer.valueOf(ਚਾਈਲਡ_ਕੀਮਤ.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ()), ਚਾਈਲਡ_ਕੀਮਤ);
        준비대기열.offer(ਚਾਈਲਡ_ਕੀਮਤ);
        return ਚਾਈਲਡ_ਕੀਮਤ;
    }

    public ਕਾਰਵਾਈ_ਕੀਮਤ ਅਗਲਾ_ਕਾਰਵਾਈ() {
        int 검사수 = 준비대기열.size();
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 검사수; ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
            ਕਾਰਵਾਈ_ਕੀਮਤ ਅਗਲਾ_ਆਇਟਮ = 준비대기열.poll();
            if (ਅਗਲਾ_ਆਇਟਮ != null && (ਅਗਲਾ_ਆਇਟਮ.ਸਥਿਤੀ_ਕੀਮਤ() == ਕਾਰਵਾਈ_ਸਥਿਤੀ.ਤਿਆਰ_ਕਰੋ || ਅਗਲਾ_ਆਇਟਮ.ਸਥਿਤੀ_ਕੀਮਤ() == ਕਾਰਵਾਈ_ਸਥਿਤੀ.ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼)) {
                ਅਗਲਾ_ਆਇਟਮ.ਸੈਟ_ਸਥਿਤੀ(ਕਾਰਵਾਈ_ਸਥਿਤੀ.ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼);
                준비대기열.offer(ਅਗਲਾ_ਆਇਟਮ);
                return ਅਗਲਾ_ਆਇਟਮ;
            }
        }
        return null;
    }

    public int 자식기다리기(ਕਾਰਵਾਈ_ਕੀਮਤ 부모, int ਚਾਈਲਡ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ, boolean 기다리지않음) {
        for (ਕਾਰਵਾਈ_ਕੀਮਤ 후보 : ਪ੍ਰਕਿਰਿਆ_ਸੂਚੀ.values()) {
            if (후보.부모식별자() != 부모.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ()) {
                continue;
            }
            if (ਚਾਈਲਡ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ > 0 && 후보.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ() != ਚਾਈਲਡ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ) {
                continue;
            }
            if (후보.ਸਥਿਤੀ_ਕੀਮਤ() == ਕਾਰਵਾਈ_ਸਥਿਤੀ.ਨਿਕਾਸ_ਐਪਲੀਕੇਸ਼) {
                int ਮਾਪ = (후보.종료값() & 0xff) << 8;
                ਪ੍ਰਕਿਰਿਆ_ਸੂਚੀ.remove(Integer.valueOf(후보.ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ()));
                return ਮਾਪ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public ਕਾਰਵਾਈ_ਕੀਮਤ ਲੱਭੋ_ਕਾਰਵਾਈ(int ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ) {
        return ਪ੍ਰਕਿਰਿਆ_ਸੂਚੀ.get(Integer.valueOf(ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ_ਕੀਮਤ));
    }

    private int ਨਿਰਧਾਰਿਤ_ਕਰੋ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ() {
        return ਅਗਲਾ_ਤਫ਼ਤੀਸ਼_ਕਰਨ_ਵਾਲਾ++;
    }
}
