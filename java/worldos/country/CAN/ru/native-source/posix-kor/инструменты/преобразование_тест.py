#!/usr/bin/env python3
"""сборка 변환이 русский строка_ЗНАЧЕН, 주석, 헤더 경로를 바꾸지 않는지 검사한다."""
from идентификатор_преобразование import ПРЕОБР_ЗНАЧЕН

исходныйКод = '''#include <файл_ABI.h>
#include "сеть_ABI.h"
// открыть_файл 라는 주석
/* 자료이름 */
const char *файл_ввод_имя = "한글 \\" строка_ЗНАЧЕН";
char знак_ЗНАЧЕН = '가';
int 파일열기_횟수 = 1;
'''
текстовыйВывод = ПРЕОБР_ЗНАЧЕН(исходныйКод)
assert '#include <файл_ABI.h>' in текстовыйВывод
assert '#include "сеть_ABI.h"' in текстовыйВывод
assert '// открыть_файл 라는 주석' in текстовыйВывод
assert '/* 자료이름 */' in текстовыйВывод
assert '"한글 \\" строка_ЗНАЧЕН"' in текстовыйВывод
assert "'가'" in текстовыйВывод
assert '\\ud30c\\uc77c\\uc774\\ub984' in текстовыйВывод
assert '파일열기_횟수' not in текстовыйВывод
assert ПРЕОБР_ЗНАЧЕН(текстовыйВывод) == текстовыйВывод
print('PASS: русский идентификатор_ЗНАЧЕН ПРЕОБР_ЗНАЧЕН/строка_ЗНАЧЕН·주석·путь 보존')
