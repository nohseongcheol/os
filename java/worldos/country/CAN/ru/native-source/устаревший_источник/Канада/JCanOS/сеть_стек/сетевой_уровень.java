package Канада.JCanOS.сеть_стек;

import java.util.HashMap;
import java.util.Map;

/** Ethernet, ARP, IPv4, ICMP, UDP, TCP получить_ЗНАЧЕН 분배를 한곳에서 관리한다. */
public final class сетевой_уровень {
    @FunctionalInterface
    public interface данные_обработчик {
        void Процесс_ЗНАЧЕН_ввод(byte[] данные, int запустить, int длина_ЗНАЧЕН);
    }

    private final Map<Integer, данные_обработчик> Ethernet_обработчик = new HashMap<Integer, данные_обработчик>();
    private final Map<Integer, данные_обработчик> протокол_IP_обработчик = new HashMap<Integer, данные_обработчик>();
    private final Map<Integer, данные_обработчик> пользователь_данные_урок_обработчик = new HashMap<Integer, данные_обработчик>();
    private final Map<Integer, данные_обработчик> передача_управление_обработчик = new HashMap<Integer, данные_обработчик>();

    public void регистр_Ethernet(int Вид_ЗНАЧЕН, данные_обработчик обработчик) {
        Ethernet_обработчик.put(Integer.valueOf(Вид_ЗНАЧЕН & 0xffff), обработчик);
    }

    public void регистр_протокол_IP(int сумма_контракта, данные_обработчик обработчик) {
        протокол_IP_обработчик.put(Integer.valueOf(сумма_контракта & 0xff), обработчик);
    }

    public void регистр_пользователь_данные_урок(int аппаратный_порт, данные_обработчик обработчик) {
        пользователь_данные_урок_обработчик.put(Integer.valueOf(аппаратный_порт & 0xffff), обработчик);
    }

    public void регистр_передача_управление(int аппаратный_порт, данные_обработчик обработчик) {
        передача_управление_обработчик.put(Integer.valueOf(аппаратный_порт & 0xffff), обработчик);
    }

    public boolean получить_Ethernet(byte[] кадр_ИНДЕКС) {
        if (!сеть_Инструменты.ИТ_службы_Ethernet_кадр(кадр_ИНДЕКС)) {
            return false;
        }
        int Вид_ЗНАЧЕН = сеть_Инструменты.Ethernet_ПРОПИСН_протокол(кадр_ИНДЕКС);
        данные_обработчик 직접처리기 = Ethernet_обработчик.get(Integer.valueOf(Вид_ЗНАЧЕН));
        if (직접처리기 != null) {
            직접처리기.Процесс_ЗНАЧЕН_ввод(кадр_ИНДЕКС, 14, кадр_ИНДЕКС.length - 14);
            return true;
        }
        return Вид_ЗНАЧЕН == 0x0800 && получить_облако_пакет(кадр_ИНДЕКС, 14);
    }

    private boolean получить_облако_пакет(byte[] данные, int запустить) {
        if (!сеть_Инструменты.ИТ_службы_вакцина_полиовируса_4_протокол(данные, запустить)) {
            return false;
        }
        int Заголовок_длина = (данные[запустить] & 0x0f) * 4;
        int итог_длина = сеть_Инструменты.큰순서짧은정수(данные, запустить + 2);
        if (итог_длина < Заголовок_длина || запустить + итог_длина > данные.length) {
            return false;
        }
        int сумма_контракта = данные[запустить + 9] & 0xff;
        int контент_Пуск = запустить + Заголовок_длина;
        int контент_длина = итог_длина - Заголовок_длина;
        данные_обработчик 직접처리기 = протокол_IP_обработчик.get(Integer.valueOf(сумма_контракта));
        if (직접처리기 != null) {
            직접처리기.Процесс_ЗНАЧЕН_ввод(данные, контент_Пуск, контент_длина);
            return true;
        }
        if (контент_длина < 4) {
            return false;
        }
        int цель_номер_порта = сеть_Инструменты.큰순서짧은정수(данные, контент_Пуск + 2);
        Map<Integer, данные_обработчик> порт_таблица = сумма_контракта == 17 ? пользователь_данные_урок_обработчик : сумма_контракта == 6 ? передача_управление_обработчик : null;
        if (порт_таблица == null) {
            return false;
        }
        данные_обработчик порт_обработчик = порт_таблица.get(Integer.valueOf(цель_номер_порта));
        if (порт_обработчик == null) {
            return false;
        }
        порт_обработчик.Процесс_ЗНАЧЕН_ввод(данные, контент_Пуск, контент_длина);
        return true;
    }
}

