    private static void 기억공간시험(Ядро ядро_значення) {
        기억공간관리자 관리자 = ядро_значення.Пам_ять_область();
        int 첫주소 = 관리자.정렬할당(100, 64);
        перевіряти((첫주소 & 63) == 0, "вирівняти_значення виділяти_місце");
        관리자.записування_байт_значення(첫주소, (byte) 0x5a);
        перевіряти(관리자.바이트읽기(첫주소) == (byte) 0x5a, "물리 Пам_ять_область 읽고 Запис");
        int 사용전 = 관리자.사용크기();
        관리자.випуск_місце(첫주소);
        перевіряти(관리자.사용크기() < 사용전, "Пам_ять_область випуск_місце");
    }

    private static void 쪽관리시험(Ядро ядро_значення) {
        쪽관리자 관리자 = ядро_значення.쪽관리();
        쪽관리자.адреса_ПРОБІЛ батьківський_ПРОБІЛ = 관리자.새주소공간();
        관리자.карта_сторінка(батьківський_ПРОБІЛ, 0x1000, true);
        관리자.записування_байт_значення(батьківський_ПРОБІЛ, 0x1010, (byte) 7);
        쪽관리자.адреса_ПРОБІЛ дитина_ПРОБІЛ = 관리자.쓰기시복사복제(батьківський_ПРОБІЛ);
        관리자.записування_байт_значення(дитина_ПРОБІЛ, 0x1010, (byte) 9);
        перевіряти(관리자.바이트읽기(батьківський_ПРОБІЛ, 0x1010) == 7, "Запис 시 екземпляр_значення батьківський_значення 격리");
        перевіряти(관리자.바이트읽기(дитина_ПРОБІЛ, 0x1010) == 9, "Запис 시 екземпляр_значення дитина_значення Запис");
    }

    private static void 파일과과정시험(Ядро ядро_значення) {
        byte[] Вміст_значення = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        ядро_значення.файлова_система().додавати_Файл("випробування", Вміст_значення);
        процес_значення батьківський_значення = ядро_значення.첫과정();
        системний_виклик 호출 = ядро_значення.системний_виклик();
        int 서술자 = 호출.Відкрити(батьківський_значення, "/випробування", системний_виклик.лише_для_читання_позначка);
        перевіряти(서술자 >= 3, "файл Відкрити");

        byte[] отримувати_місце = new byte[Вміст_значення.length];
        перевіряти(호출.Читання(батьківський_значення, 서술자, отримувати_місце, отримувати_місце.length) == Вміст_значення.length, "файл Читання");
        перевіряти(Arrays.equals(Вміст_значення, отримувати_місце), "файл Вміст_значення");
        перевіряти(호출.переміщати_посада(батьківський_значення, 서술자, 0, системний_виклик.Пошук_ПУСК) == 0, "файл позиція переміщати_значення");

        int 복제서술자 = 호출.서술자복제(батьківський_значення, 서술자);
        перевіряти(복제서술자 >= 0, "서술자 клонувати_значення");
        процес_значення дитина_значення = 호출.клонувати_процес(батьківський_значення);
        перевіряти(дитина_значення.ідентифікатор_значення() != батьківський_значення.ідентифікатор_значення(), "процес_значення ідентифікатор_значення 분리");
        перевіряти(дитина_значення.батьківський_ідентифікатор() == батьківський_значення.ідентифікатор_значення(), "батьківський_значення процес_значення ідентифікатор_значення");
        перевіряти(호출.Закрити(дитина_значення, 서술자) == 0 && батьківський_значення.파일서술자().ІТ_відділ_відкрито(서술자), "дитина_значення Закрити 격리");

        int 이전끝 = 호출.프로그램끝늘리기(батьківський_значення, 8192);
        перевіряти(이전끝 == 0x06000000, "програма_f5044b9b 끝 늘리기");
        перевіряти(батьківський_значення.програма_перерва() == 0x06002000, "програма_f5044b9b 끝 반영");
        перевіряти(дитина_значення.програма_перерва() == 0x06000000, "과정별 програма_f5044b9b 끝 격리");

        дитина_значення.Вийти_програма(7);
        перевіряти(호출.자식기다리기(батьківський_значення, дитина_значення.ідентифікатор_значення(), false) == (7 << 8), "дитина_значення Вийти_програма 기다리기");
        перевіряти(호출.접근가능("випробування", 1) == -13, "Виконати_команда дозвіл_значення відхилити_значення");
        перевіряти(호출.ідентифікатор_користувача() == 0 && 호출.Група_ідентифікатор() == 0, "사용자와 무리 ідентифікатор_значення");
        перевіряти("/".equals(호출.чинний_список_завдань(2)) && 호출.перехід_список_завдань("/") == 0, "чинний_елемент 작업 запис_список");
        перевіряти(호출.ІТ_відділ_Термінал(батьківський_значення, 1), "표준 Вивід 단말");
        перевіряти("JCanOS".equals(호출.Система_Відомості().Система_ім_я()), "операційна_система_ОС_значення Відомості_про_систему");
    }

    private static void 실행파일시험(Ядро ядро_значення) {
        byte[] дані = new byte[92];
        дані[0] = 0x7f;
        дані[1] = 'E';
        дані[2] = 'L';
        дані[3] = 'F';
        дані[4] = 1;
        дані[5] = 1;
        записування_ціле_число_значення(дані, 24, 0x04001000);
        записування_ціле_число_значення(дані, 32, 52);
        짧은정수쓰기(дані, 46, 40);
        짧은정수쓰기(дані, 48, 1);
        записування_ціле_число_значення(дані, 56, 8);
        записування_ціле_число_значення(дані, 60, 2);
        записування_ціле_число_значення(дані, 64, 0x04002000);
        записування_ціле_число_значення(дані, 72, 64);

        실행파일적재기.фото фото_значення = new 실행파일적재기().검사(дані);
        перевіряти(фото_значення.ПУСК_адреса() == 0x04001000, "ELF запустити Адреса");
        перевіряти(фото_значення.구역들().size() == 1 && фото_значення.구역들().get(0).종류() == 8, "ELF 빈 дані розділ_значення_366e0bfa");
        int 서술자 = ядро_значення.системний_виклик().Відкрити(ядро_значення.첫과정(), "випробування", системний_виклик.лише_для_читання_позначка);
        перевіряти(ядро_значення.системний_виклик().керування_файлом(ядро_значення.첫과정(), 서술자, 2, 1) == 0, "Виконати_команда 시 Закрити Налаштування");
        перевіряти(ядро_значення.системний_виклик().Виконати_команда(ядро_значення.첫과정(), дані, new String[] {"випробування", "값"}, new String[] {"Мови=українська"}) == 0, "ELF Виконати_команда фото_значення 적재");
        перевіряти(ядро_значення.첫과정().실행시작주소() == 0x04001000, "Виконати_команда запустити Адреса 반영");
        перевіряти(ядро_значення.첫과정().실행인자().length == 2 && ядро_значення.첫과정().середовище_значення().length == 1, "Виконати_команда 인자와 середовище");
        перевіряти(!ядро_значення.첫과정().파일서술자().ІТ_відділ_відкрито(서술자), "Виконати_команда 시 서술자 Закрити");
        перевіряти(ядро_значення.쪽관리().바이트읽기(ядро_значення.첫과정().адреса_ПРОБІЛ(), 0x04002000) == 0, "빈 дані розділ_значення_366e0bfa нуль_операнд ініціалізувати");
    }

