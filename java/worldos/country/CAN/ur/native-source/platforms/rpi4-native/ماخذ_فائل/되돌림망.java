/** 첫 네트워크 پرت_قدر: 단일 کرنیل_قدر 안의 IPv4/UDP 루프백 منتقلی_قدر.
 * 외부 IP는 ENETUNREACH. Ethernet/IP 패킷 드라이버를 대신한다고 표시하지 않는다.
 * اختتام_نقطہ 8개, 끝점당 전문 4개, 전문당 512바이트. 모든 호출은 비차단이다.
 */
public final class 되돌림망 {
    static int[] 사용 = new int[8];
    static int[] پورٹ_قدر = new int[8];
    static int[] پتہ = new int[8];
    static int[] 앞 = new int[8];
    static int[] 개수 = new int[8];
    static int[] 받은창구 = new int[8];
    static int[] لمبا_ئی_قدر = new int[32];
    static int[] 보낸창구 = new int[32];
    static int[] کوائف = new int[32 * 512];
    static int[] فارورڈ_قدر = new int[512];
    static int 다음창구 = 49152;
    static int تصدیق_کریں(int اشاریہ) { return اشاریہ >= 32 && اشاریہ < 40 && 사용[اشاریہ - 32] != 0 ? اشاریہ - 32 : -1; }
    static boolean 겹침(int اشاریہ) {
        for (int سلاٹ_اندراج = 0; سلاٹ_اندراج < 8; سلاٹ_اندراج++) if (사용[سلاٹ_اندراج] != 0 && پورٹ_قدر[سلاٹ_اندراج] == اشاریہ) return true;
        return false;
    }
    static int 임시창구() {
        for (int 시도 = 0; 시도 < 16; 시도++) {
            int 후보 = 다음창구++;
            if (다음창구 > 65535) 다음창구 = 49152;
            if (!겹침(후보)) return 후보;
        }
        return -98;
    }
    public static int بنائیں_اندراج(int 영역, int 종류, int جاب_قدر) {
        if (영역 != 2) return -97;
        if (종류 != 2 || (جاب_قدر != 0 && جاب_قدر != 17)) return -93;
        for (int سلاٹ_اندراج = 0; سلاٹ_اندراج < 8; سلاٹ_اندراج++) if (사용[سلاٹ_اندراج] == 0) {
            사용[سلاٹ_اندراج] = 1; پورٹ_قدر[سلاٹ_اندراج] = 0; پتہ[سلاٹ_اندراج] = 0; 앞[سلاٹ_اندراج] = 0; 개수[سلاٹ_اندراج] = 0; 받은창구[سلاٹ_اندراج] = 0;
            return سلاٹ_اندراج + 32;
        }
        return -24;
    }
    public static int 묶기(int اشاریہ, int نیٹ_ورک_پتہ, int 창구번호) {
        int سلاٹ_اندراج = تصدیق_کریں(اشاریہ);
        if (سلاٹ_اندراج < 0) return -9;
        if (نیٹ_ورک_پتہ != 0 && نیٹ_ورک_پتہ != 0x7f000001) return -99;
        if (پورٹ_قدر[سلاٹ_اندراج] != 0 || 창구번호 < 0 || 창구번호 > 65535) return -22;
        if (창구번호 == 0) 창구번호 = 임시창구();
        if (창구번호 < 0) return 창구번호;
        if (겹침(창구번호)) return -98;
        پورٹ_قدر[سلاٹ_اندراج] = 창구번호; پتہ[سلاٹ_اندراج] = نیٹ_ورک_پتہ; return 0;
    }
    public static int 자료넣기(int اشاریہ, int قدر) {
        if (اشاریہ < 0 || اشاریہ >= 512) return -22;
        فارورڈ_قدر[اشاریہ] = قدر & 255; return 0;
    }
    public static int 자료읽기(int اشاریہ) { return اشاریہ >= 0 && اشاریہ < 512 ? فارورڈ_قدر[اشاریہ] : -22; }
    public static int بھیجیں(int اشاریہ, int نیٹ_ورک_پتہ, int 창구번호, int حجم) {
        int سلاٹ_اندراج = تصدیق_کریں(اشاریہ);
        if (سلاٹ_اندراج < 0) return -9;
        if (نیٹ_ورک_پتہ != 0x7f000001) return -101;
        if (창구번호 < 1 || 창구번호 > 65535) return -22;
        if (حجم < 0 || حجم > 512) return -90;
        if (پورٹ_قدر[سلاٹ_اندراج] == 0) {
            int پیمائش = 묶기(اشاریہ, 0x7f000001, 0);
            if (پیمائش < 0) return پیمائش;
        }
        int منزل_مقصود_قدر = -1;
        for (int 후보 = 0; 후보 < 8; 후보++) if (사용[후보] != 0 && پورٹ_قدر[후보] == 창구번호) منزل_مقصود_قدر = 후보;
        if (منزل_مقصود_قدر < 0) return -111;
        if (개수[منزل_مقصود_قدر] == 4) return -11;
        int پوزیشن_ٹھیک_کریں_اشاریہ = منزل_مقصود_قدر * 4 + (앞[منزل_مقصود_قدر] + 개수[منزل_مقصود_قدر]) % 4;
        for (int بائٹ_قدر = 0; بائٹ_قدر < حجم; بائٹ_قدر++) کوائف[پوزیشن_ٹھیک_کریں_اشاریہ * 512 + بائٹ_قدر] = فارورڈ_قدر[بائٹ_قدر];
        لمبا_ئی_قدر[پوزیشن_ٹھیک_کریں_اشاریہ] = حجم; 보낸창구[پوزیشن_ٹھیک_کریں_اشاریہ] = پورٹ_قدر[سلاٹ_اندراج]; 개수[منزل_مقصود_قدر]++;
        return حجم;
    }
    public static int 받기(int اشاریہ, int 용량) {
        int سلاٹ_اندراج = تصدیق_کریں(اشاریہ);
        if (سلاٹ_اندراج < 0) return -9;
        if (용량 < 0 || 용량 > 512) return -22;
        if (개수[سلاٹ_اندراج] == 0) return -11;
        int پوزیشن_ٹھیک_کریں_اشاریہ = سلاٹ_اندراج * 4 + 앞[سلاٹ_اندراج];
        int حجم = لمبا_ئی_قدر[پوزیشن_ٹھیک_کریں_اشاریہ] < 용량 ? لمبا_ئی_قدر[پوزیشن_ٹھیک_کریں_اشاریہ] : 용량;
        for (int بائٹ_قدر = 0; بائٹ_قدر < حجم; بائٹ_قدر++) فارورڈ_قدر[بائٹ_قدر] = کوائف[پوزیشن_ٹھیک_کریں_اشاریہ * 512 + بائٹ_قدر];
        받은창구[سلاٹ_اندراج] = 보낸창구[پوزیشن_ٹھیک_کریں_اشاریہ]; 앞[سلاٹ_اندراج] = (앞[سلاٹ_اندراج] + 1) % 4; 개수[سلاٹ_اندراج]--;
        return حجم;
    }
    public static int 창구읽기(int اشاریہ) { int سلاٹ_اندراج = تصدیق_کریں(اشاریہ); return سلاٹ_اندراج < 0 ? -9 : پورٹ_قدر[سلاٹ_اندراج]; }
    public static int 주소읽기(int اشاریہ) { int سلاٹ_اندراج = تصدیق_کریں(اشاریہ); return سلاٹ_اندراج < 0 ? -9 : پتہ[سلاٹ_اندراج]; }
    public static int 보낸곳(int اشاریہ) { int سلاٹ_اندراج = تصدیق_کریں(اشاریہ); return سلاٹ_اندراج < 0 ? -9 : 받은창구[سلاٹ_اندراج]; }
    public static int بند_کریں(int اشاریہ) {
        int سلاٹ_اندراج = تصدیق_کریں(اشاریہ); if (سلاٹ_اندراج < 0) return -9;
        사용[سلاٹ_اندراج] = 0; 개수[سلاٹ_اندراج] = 0; پورٹ_قدر[سلاٹ_اندراج] = 0; return 0;
    }
}
