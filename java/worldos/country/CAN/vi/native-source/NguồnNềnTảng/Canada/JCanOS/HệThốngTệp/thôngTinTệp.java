package Canada.JCanOS.HệThốngTệp;

public final class thôngTinTệp {
    private final int cỡ;
    private final int loạiHình;

    public thôngTinTệp(int cỡ, int loạiHình) {
        this.cỡ = cỡ;
        this.loạiHình = loạiHình;
    }

    public int cỡ() {
        return cỡ;
    }

    public int loạiHình() {
        return loạiHình;
    }
}

