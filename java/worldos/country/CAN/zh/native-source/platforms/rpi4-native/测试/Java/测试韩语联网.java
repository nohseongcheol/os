import 中文.内置.*;

/** 在 OpenJDK 和自研 JVM 上运行相同字节码的通信契约测试。 */
public class 测试韩语联网 {
    public static void main(String[] 实参) throws 输入输出异常 {
        接收端口 端口值 = 连接状态传输.打开接收者(0);
        连接通道 客户机值 = 连接状态传输.打开("127.0.0.1", 端口值.端口编号());
        连接通道 所有者标识符 = 端口值.接收();
        客户机值.超时(200); 所有者标识符.超时(200);
        检查项.确认真值(客户机值.已连接() && !客户机值.是否已关闭(), "连接 状态值");
        检查项.确认真值(所有者标识符.端口编号() == 客户机值.局部端口编号(), "对端值 端口编号");
        检查项.确认真值(客户机值.端口编号() == 所有者标识符.局部端口编号(), "局部作用域 端口编号");
        输入流 输入值 = 所有者标识符.输入值(); 输出流 输出页 = 客户机值.输出();
        byte[] 消息 = 字符.编码("한글 流值");
        输出页.写入(消息, 0, 消息.length); 输出页.发射值();
        byte[] 已接收文本 = new byte[消息.length];
        int 读取个数 = 0;
        while (读取个数 < 已接收文本.length) {
            int 附加读取 = 输入值.读取(已接收文本, 读取个数, 已接收文本.length - 读取个数);
            检查项.确认真值(附加读取 > 0, "예상하지 않은 文件 结尾"); 读取个数 += 附加读取;
        }
        检查项.确认真值(字符.相等文本(字符.解密数据(已接收文本), "한글 流值"), "子部分值 읽기와 写入");
        输出页.写入(new byte[] {17, 18});
        byte[] 读取短整数 = new byte[2];
        int 首位读取 = 输入值.读取(读取短整数);
        检查项.确认真值(首位读取 > 0 && 读取短整数[0] == 17, "数组值 读取");
        if (首位读取 == 1) 读取短整数[1] = (byte)输入值.读取();
        检查项.确认真值(读取短整数[1] == 18, "余数值 读取");
        所有者标识符.输出().写入(255);
        检查项.确认真值(客户机值.输入值().读取() == 255, "编码状态值 없는 한 字节值");
        输出页.关闭();
        检查项.确认真值(客户机值.是否已关闭() && 输入值.读取() == -1, "닫기와 文件 结尾");
        输入值.关闭(); 检查项.确认真值(所有者标识符.是否已关闭(), "输入值 流值 关闭");
        客户机值.关闭(); 所有者标识符.关闭();
        端口值.超时(15);
        boolean 执行状态超时 = false;
        try { 端口值.接收(); } catch (等待状态超时异常 预期错误) { 执行状态超时 = true; }
        检查项.确认真值(执行状态超时, "接收值 超时");
        端口值.关闭(); 检查项.确认真值(端口值.是否已关闭(), "接收端口 关闭");
        数据报信道 接收者端点 = 数据报信道.打开(0), 发送中端点 = 数据报信道.打开(0);
        接收者端点.超时(200);
        发送中端点.发送("127.0.0.1", 接收者端点.端口编号(), "数据报 한글");
        检查项.确认真值(字符.相等文本(接收者端点.接收(), "数据报 한글"), "数据报 송수신");
        发送中端点.关闭(); 接收者端点.关闭();
        检查项.确认真值(发送中端点.是否已关闭() && 接收者端点.是否已关闭(), "数据报 关闭");
        输出.写入行("中文 通信 验证: 连接 数据报 流值 执行状态超时 关闭");
    }
}
