/** 管理裁剪、条带合成和指针下方的背景；实际帧缓冲访问由板级代码负责。 */
public final class 帧缓冲组合器 {
    static int 宽度值, 高度值, 是否组合中, 左边界位置值, 上位侧边界位置, 右边界位置值, 下位侧边界位置值;
    static int 指针横坐标, 指针Y_按钮, 指针形状;
    static int 计数器低位, 计数器高位;
    static int[] 已合成像素列 = new int[32 * 1920];
    static int[] 指针背景 = new int[21 * 21];
    static int[] 已裁剪边界 = new int[4];
    public static void 准备(int 宽度跨度, int 长度) {
        宽度值 = 宽度跨度; 高度值 = 长度; 是否组合中 = 0; 指针形状 = 0;
        计数器低位 = 0; 计数器高位 = 0;
    }
    public static int 获取宽度() { return 宽度值; }
    public static int 获取高度() { return 高度值; }
    public static int 获取计数器低位() { return 计数器低位; }
    public static int 获取计数器高位() { return 计数器高位; }
    public static int 裁剪值(int 序数索引) { return 已裁剪边界[序数索引]; }
    static int 添加正数长度(int 开始值, int 长度) {
        if (开始值 > 2147483647 - 长度) return 2147483647;
        return 开始值 + 长度;
    }
    public static int 裁剪(int 水平位置, int 垂直位置, int 宽度跨度, int 长度) {
        if (宽度值 == 0 || 宽度跨度 <= 0 || 长度 <= 0) return 0;
        int 右 = 添加正数长度(水平位置, 宽度跨度), 下位侧侧 = 添加正数长度(垂直位置, 长度);
        int 左侧 = 是否组合中 != 0 ? 左边界位置值 : 0, 上位侧侧 = 是否组合中 != 0 ? 上位侧边界位置 : 0;
        int 最大水平位置 = 是否组合中 != 0 ? 右边界位置值 : 宽度值, 最大垂直位置 = 是否组合中 != 0 ? 下位侧边界位置值 : 高度值;
        if (水平位置 < 左侧) 水平位置 = 左侧;
        if (垂直位置 < 上位侧侧) 垂直位置 = 上位侧侧;
        if (右 > 最大水平位置) 右 = 最大水平位置;
        if (下位侧侧 > 最大垂直位置) 下位侧侧 = 最大垂直位置;
        if (右 <= 水平位置 || 下位侧侧 <= 垂直位置) return 0;
        已裁剪边界[0] = 水平位置; 已裁剪边界[1] = 垂直位置;
        已裁剪边界[2] = 右 - 水平位置; 已裁剪边界[3] = 下位侧侧 - 垂直位置;
        return 1;
    }
    public static int 运行(int 水平位置, int 垂直位置, int 宽度跨度, int 长度) {
        if (是否组合中 != 0 || 长度 > 32 || 裁剪(水平位置, 垂直位置, 宽度跨度, 长度) == 0) return 0;
        左边界位置值 = 已裁剪边界[0]; 上位侧边界位置 = 已裁剪边界[1];
        右边界位置值 = 左边界位置值 + 已裁剪边界[2]; 下位侧边界位置值 = 上位侧边界位置 + 已裁剪边界[3];
        是否组合中 = 1; return 1;
    }
    static boolean 指针位(int 水平位置, int 垂直位置, int 形状值) {
        if (形状值 == 1) return 水平位置 >= 0 && 水平位置 <= 垂直位置 / 2 && 垂直位置 < 16;
        if (形状值 == 3) 水平位置 = 20 - 水平位置;
        int 差异值 = 水平位置 - 垂直位置; if (差异值 < 0) 差异值 = -差异值;
        return (差异值 <= 1 && 水平位置 >= 3 && 水平位置 <= 17) ||
            (水平位置 >= 2 && 水平位置 <= 8 && 垂直位置 >= 2 && 垂直位置 <= 8 && (水平位置 <= 3 || 垂直位置 <= 3)) ||
            (水平位置 >= 12 && 水平位置 <= 18 && 垂直位置 >= 12 && 垂直位置 <= 18 && (水平位置 >= 17 || 垂直位置 >= 17));
    }
    static int 指针像素(int 水平位置, int 垂直位置) {
        if (指针位(水平位置, 垂直位置, 指针形状)) return 2;
        for (int 行 = -1; 行 <= 1; 行++) for (int 槽条目 = -1; 槽条目 <= 1; 槽条目++)
            if (指针位(水平位置 + 槽条目, 垂直位置 + 行, 指针形状)) return 1;
        return 0;
    }
    static void 显示操作像素(int 水平位置, int 垂直位置, int 颜色值) {
        int 槽条目 = 水平位置 - 指针横坐标, 行 = 垂直位置 - 指针Y_按钮;
        if (指针形状 != 0 && 槽条目 >= 0 && 行 >= 0 && 槽条目 < 21 && 行 < 21) {
            指针背景[行 * 21 + 槽条目] = 颜色值;
            int 分值 = 指针像素(槽条目, 行); if (分值 != 0) 颜色值 = 分值 == 2 ? 0xffffff : 0x101010;
        }
        if (板.读取显示操作像素(水平位置, 垂直位置) != 颜色值) {
            板.写入显示操作像素(水平位置, 垂直位置, 颜色值);
            计数器低位++; if (计数器低位 == 0) 计数器高位++;
        }
    }
    public static void 结束操作() {
        if (是否组合中 == 0) return;
        for (int 行 = 上位侧边界位置; 行 < 下位侧边界位置值; 行++) for (int 槽条目 = 左边界位置值; 槽条目 < 右边界位置值; 槽条目++)
            显示操作像素(槽条目, 行, 已合成像素列[(行 - 上位侧边界位置) * 1920 + 槽条目]);
        是否组合中 = 0;
    }
    public static int 像素(int 水平位置, int 垂直位置, int 颜色值) {
        if (水平位置 < 0 || 垂直位置 < 0 || 水平位置 >= 宽度值 || 垂直位置 >= 高度值) return 0;
        if (是否组合中 != 0) {
            if (水平位置 >= 左边界位置值 && 水平位置 < 右边界位置值 && 垂直位置 >= 上位侧边界位置 && 垂直位置 < 下位侧边界位置值)
                已合成像素列[(垂直位置 - 上位侧边界位置) * 1920 + 水平位置] = 颜色值;
        } else 显示操作像素(水平位置, 垂直位置, 颜色值);
        return 0;
    }
    public static void 矩形填充(int 水平位置, int 垂直位置, int 宽度跨度, int 长度, int 颜色值) {
        if (裁剪(水平位置, 垂直位置, 宽度跨度, 长度) == 0) return;
        水平位置 = 已裁剪边界[0]; 垂直位置 = 已裁剪边界[1]; 宽度跨度 = 已裁剪边界[2]; 长度 = 已裁剪边界[3];
        for (int 行 = 垂直位置; 行 < 垂直位置 + 长度; 行++) for (int 槽条目 = 水平位置; 槽条目 < 水平位置 + 宽度跨度; 槽条目++) {
            if (是否组合中 != 0) 已合成像素列[(行 - 上位侧边界位置) * 1920 + 槽条目] = 颜色值;
            else 显示操作像素(槽条目, 行, 颜色值);
        }
    }
    public static void 指针(int 水平位置, int 垂直位置, int 形状值) {
        if (宽度值 == 0) return;
        int 新建水平位置 = 水平位置 - (形状值 >= 2 ? 10 : 0), 新建垂直位置 = 垂直位置 - (形状值 >= 2 ? 10 : 0);
        if (指针形状 == 形状值 && 指针横坐标 == 新建水平位置 && 指针Y_按钮 == 新建垂直位置) return;
        if (指针形状 != 0) for (int 行 = 0; 行 < 21; 行++) for (int 槽条目 = 0; 槽条目 < 21; 槽条目++) {
            int 首位操作数 = 指针横坐标 + 槽条目, 三值 = 指针Y_按钮 + 行;
            if (首位操作数 >= 0 && 三值 >= 0 && 首位操作数 < 宽度值 && 三值 < 高度值) 板.写入显示操作像素(首位操作数, 三值, 指针背景[行 * 21 + 槽条目]);
        }
        指针形状 = 形状值; 指针横坐标 = 新建水平位置; 指针Y_按钮 = 新建垂直位置;
        if (形状值 != 0) for (int 行 = 0; 行 < 21; 行++) for (int 槽条目 = 0; 槽条目 < 21; 槽条目++) {
            int 首位操作数 = 指针横坐标 + 槽条目, 三值 = 指针Y_按钮 + 行;
            if (首位操作数 >= 0 && 三值 >= 0 && 首位操作数 < 宽度值 && 三值 < 高度值) {
                指针背景[行 * 21 + 槽条目] = 板.读取显示操作像素(首位操作数, 三值);
                int 分值 = 指针像素(槽条目, 行); if (分值 != 0) 板.写入显示操作像素(首位操作数, 三值, 分值 == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
