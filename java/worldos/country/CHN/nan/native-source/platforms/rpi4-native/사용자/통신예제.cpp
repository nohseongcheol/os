#include "통신규약.h"
static 인터넷통신주소 주소(unsigned 창구) {
    인터넷통신주소 값 = {}; 값.주소갈래 = 인터넷주소갈래;
    값.접속번호 = 망차례짧은수(창구); 값.인터넷주소.주소값 = 망차례정수(되돌림주소); return 값;
}
extern "C" int 사용자시작(int) {
    int 보내는곳 = 통신종단점만들기(인터넷주소갈래, 전문통신, 0);
    int 받는곳 = 통신종단점만들기(인터넷주소갈래, 전문통신, 전문전송규약);
    if (보내는곳 < 0 || 받는곳 < 0) return 1;
    인터넷통신주소 도착 = 주소(7777), 출발 = 주소(7778), 보낸주소 = {};
    통신주소길이형 주소길이 = sizeof(보낸주소);
    if (통신주소묶기(받는곳, (통신주소 *)&도착, sizeof(도착))) return 2;
    if (통신주소묶기(보내는곳, (통신주소 *)&도착, sizeof(도착)) != -1 || 오류번호 != 98) return 3;
    if (통신주소묶기(보내는곳, (통신주소 *)&출발, sizeof(출발))) return 4;
    static const char 내용[] = "한글 UDP loopback 😀";
    char 받은값[64] = {};
    if (자료전문보내기(보내는곳, 내용, sizeof(내용), 0, (통신주소 *)&도착, sizeof(도착)) != sizeof(내용)) return 5;
    if (자료전문받기(받는곳, (void *)내용, sizeof(내용), 0, 0, 0) != -1 || 오류번호 != 14) return 6;
    if (자료전문받기(받는곳, 받은값, sizeof(받은값), 0, (통신주소 *)&보낸주소, &주소길이) != sizeof(내용)) return 7;
    if (주소길이 != sizeof(보낸주소) || 장치차례짧은수(보낸주소.접속번호) != 7778 || 장치차례정수(보낸주소.인터넷주소.주소값) != 되돌림주소) return 8;
    for (unsigned 순번 = 0; 순번 < sizeof(내용); 순번++) if (받은값[순번] != 내용[순번]) return 9;
    if (자료전문받기(받는곳, 받은값, sizeof(받은값), 0, 0, 0) != -1 || 오류번호 != 11) return 10;
    if (자료전문보내기(받는곳, 받은값, sizeof(내용), 0, (통신주소 *)&보낸주소, sizeof(보낸주소)) != sizeof(내용)) return 11;
    if (자료전문받기(보내는곳, 받은값, 4, 0, 0, 0) != 4) return 12;
    if (자료전문받기(보내는곳, 받은값, 4, 0, 0, 0) != -1 || 오류번호 != 11) return 13;
    for (int 순번 = 0; 순번 < 4; 순번++) if (자료전문보내기(보내는곳, 내용, sizeof(내용), 0, (통신주소 *)&도착, sizeof(도착)) != sizeof(내용)) return 14;
    if (자료전문보내기(보내는곳, 내용, sizeof(내용), 0, (통신주소 *)&도착, sizeof(도착)) != -1 || 오류번호 != 11) return 15;
    for (int 순번 = 0; 순번 < 4; 순번++) if (자료전문받기(받는곳, 받은값, sizeof(받은값), 0, 0, 0) != sizeof(내용)) return 16;
    if (자료전문보내기(보내는곳, 0, 0, 0, (통신주소 *)&도착, sizeof(도착)) != 0 ||
        자료전문받기(받는곳, 0, 0, 0, 0, 0) != 0) return 21;
    도착.인터넷주소.주소값 = 망차례정수(0x08080808);
    if (자료전문보내기(보내는곳, 내용, sizeof(내용), 0, (통신주소 *)&도착, sizeof(도착)) != -1 || 오류번호 != 101) return 17;
    if (통신종단점만들기(인터넷주소갈래, 흐름통신, 전문전송규약) != -1 || 오류번호 != 93) return 18;
    주소길이 = sizeof(보낸주소);
    if (통신주소읽기(받는곳, (통신주소 *)&보낸주소, &주소길이) || 장치차례짧은수(보낸주소.접속번호) != 7777) return 19;
    if (파일닫기(받는곳) || 파일닫기(받는곳) != -1 || 오류번호 != 9) return 20;
    // 보내는곳은 열어 둔다: 종료 시 프로세스별 socket 정리를 검사한다.
    static const char 완료[] = "EL0 UDP LOOPBACK PASS (external network unavailable)\n";
    파일자료쓰기(1, 완료, sizeof(완료) - 1);
    return 0;
}
