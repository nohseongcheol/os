#!/usr/bin/env python3
"""декларация 고유번호와 UTF-8 байт_ЗНАЧЕН 위치로 свой C 이름을 옮기는 일회성 이행 инструменты.

внешний_ЗНАЧЕН 구조체의 멤버, строка_ЗНАЧЕН, C 표준 ФУНКЦИЯ_ЗНАЧЕН, 이식 규약은 보존한다.
입력은 изменить_ЗНАЧЕН 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

задача_корень = Path(__file__).resolve().parents[1]

def 실행():
    анализ_ЗНАЧЕН = json.loads((задача_корень/'build/한국어화/시언어분석.json').read_text())
    if анализ_ЗНАЧЕН['ошибка']: raise SystemExit('анализ_ЗНАЧЕН 오류를 먼저 해결해야 합니다.')
    имя_таблица = json.loads((задача_корень/'명명/시언어이름.json').read_text())
    SD = set(json.loads((задача_корень/'명명/규격이름.json').read_text()))
    декларация_таблица = анализ_ЗНАЧЕН['декларация']
    바꿀선언 = {УНИК_ЗНАЧЕН:имя_таблица[ввод_ЗНАЧЕН['Название']] for УНИК_ЗНАЧЕН,ввод_ЗНАЧЕН in декларация_таблица.items()
                if ввод_ЗНАЧЕН['Название'] in имя_таблица and ввод_ЗНАЧЕН['Название'] not in SD}
    контакт_таблица = {ввод_ЗНАЧЕН['Название']:имя_таблица[ввод_ЗНАЧЕН['Название']] for ввод_ЗНАЧЕН in декларация_таблица.values()
              if ввод_ЗНАЧЕН.get('Подключить')==4 and ввод_ЗНАЧЕН['Вид_ЗНАЧЕН'] in (8,9)
              and ввод_ЗНАЧЕН['Название'] in имя_таблица and ввод_ЗНАЧЕН['Название'] not in SD}
    # генерировать AOT C·어셈블리·공개 SDK가 공유하는 바이너리 Подключить 이름만 유지한다.
    HEAD_ЗНАЧЕН = ['/* русский источник_дерево 이름과 기존 компьютер_5eb260fa Подключить сумма_контракта. 자동 генерировать: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    HEAD_ЗНАЧЕН += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(контакт_таблица.items())]
    HEAD_ЗНАЧЕН += ['#endif','']
    (задача_корень/'명명/기계연결이름.h').write_text('\n'.join(HEAD_ЗНАЧЕН))
    Изменения_Список = defaultdict(dict)
    for файл,СМЕЩ_ЗНАЧЕН,Название,УНИК_ЗНАЧЕН in анализ_ЗНАЧЕН['ссылка']:
        if УНИК_ЗНАЧЕН in 바꿀선언:
            Изменения_Список[файл][СМЕЩ_ЗНАЧЕН] = (Название,바꿀선언[УНИК_ЗНАЧЕН])
    LOG_ЗАПИСЬ = ['файл\t원래바이트위치\t이전이름\t한국어이름']
    отклонить_ЗНАЧЕН_3c26be06 = []
    for файл,изменить_ЗНАЧЕН in Изменения_Список.items():
        путь = Path(файл); 원본 = путь.read_bytes(); данные = 원본
        for СМЕЩ_ЗНАЧЕН,(옛이름,새이름) in sorted(изменить_ЗНАЧЕН.items(),reverse=True):
            끝 = СМЕЩ_ЗНАЧЕН+len(옛이름.encode())
            if 원본[СМЕЩ_ЗНАЧЕН:끝] != 옛이름.encode():
                отклонить_ЗНАЧЕН_3c26be06.append((str(путь.relative_to(задача_корень)),СМЕЩ_ЗНАЧЕН,옛이름));continue
            данные = данные[:СМЕЩ_ЗНАЧЕН]+새이름.encode()+данные[끝:]
            LOG_ЗАПИСЬ.append('{}\t{}\t{}\t{}'.format(путь.relative_to(задача_корень),СМЕЩ_ЗНАЧЕН,옛이름,새이름))
        путь.write_bytes(данные)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макрос_ЗНАЧЕН = {ввод_ЗНАЧЕН['Название']:имя_таблица[ввод_ЗНАЧЕН['Название']] for ввод_ЗНАЧЕН in декларация_таблица.values()
              if ввод_ЗНАЧЕН['Вид_ЗНАЧЕН']==501 and ввод_ЗНАЧЕН['Название'] in имя_таблица and ввод_ЗНАЧЕН['Название'] not in SD}
    for путь in sorted({Path(ввод_ЗНАЧЕН['файл']) for ввод_ЗНАЧЕН in декларация_таблица.values()}):
        линия_Список = путь.read_text().splitlines(True); 이어짐 = False
        for ИНДЕКС,строка_ввода in enumerate(линия_Список):
            전처리 = 이어짐 or bool(re.match(r'\s*#',строка_ввода))
            이어짐 = 전처리 and строка_ввода.rstrip().endswith('\\')
            if 전처리:
                таблица_подстановки = имя_таблица if re.match(r'\s*#\s*define\b',строка_ввода) or 이어짐 else макрос_ЗНАЧЕН
                линия_Список[ИНДЕКС] = 낱말.sub(lambda 맞음: таблица_подстановки.get(맞음[0],맞음[0]) if 맞음[0] not in SD else 맞음[0],строка_ввода)
        путь.write_text(''.join(линия_Список))
    # 각 свой ПЕРЕВОД_источник 단위에만 연결표를 넣는다. внешний_ЗНАЧЕН 배포본에는 전파하지 않는다.
    for путь in sorted({Path(ввод_ЗНАЧЕН['файл']) for ввод_ЗНАЧЕН in декларация_таблица.values()}):
        if путь.suffix not in ('.c','.cpp'):continue
        одноранговый_ЗНАЧЕН = '../' * len(путь.relative_to(задача_корень).parts[:-1]) + '명명/기계연결이름.h'
        путь.write_text('#include "'+одноранговый_ЗНАЧЕН+'"\n'+путь.read_text())
    (задача_корень/'명명/C_имя_сопоставление.tsv').write_text('\n'.join(LOG_ЗАПИСЬ)+'\n')
    (задача_корень/'build/한국어화/전처리참조.json').write_text(json.dumps(отклонить_ЗНАЧЕН_3c26be06,ensure_ascii=False,indent=2)+'\n')
    print('изменить_ЗНАЧЕН',len(LOG_ЗАПИСЬ)-1,'전처리 재검토',len(отклонить_ЗНАЧЕН_3c26be06),'компьютер_5eb260fa Подключить',len(контакт_таблица))

if __name__=='__main__': 실행()
