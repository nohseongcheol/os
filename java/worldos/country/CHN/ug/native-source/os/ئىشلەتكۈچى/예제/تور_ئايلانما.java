/** 최대 چوڭلۇقى/홀수 ئۇزۇنلۇق_قىممىتى 데이터그램으로 ھەقىقىي_مەلۇمات RTL8139 수신 ئايلانما_قىممىتى 순환을 시험한다. */
public final class تور_ئايلانما {
    public static int ئىجرا_قىل_2() {
        if (ئىشلەتكۈچى.인수개수() != 1) { ئىشلەتكۈچى.ياز("Usage: run stress PORT\n"); return 2; }
        String تېكىست = ئىشلەتكۈچى.ئۆزگەرگۈچىلەر(0);
        int ئېغىز_قىممىتى = 0;
        for (int ئىندېكس = 0; ئىندېكس < تېكىست.length(); ئىندېكس++) {
            if (تېكىست.charAt(ئىندېكس) < '0' || تېكىست.charAt(ئىندېكس) > '9' || ئېغىز_قىممىتى > 6553) return 2;
            ئېغىز_قىممىتى = ئېغىز_قىممىتى * 10 + تېكىست.charAt(ئىندېكس) - '0';
        }
        if (ئېغىز_قىممىتى < 1 || ئېغىز_قىممىتى > 65535) return 2;
        int تۇتقۇچ_قىممىتى = ئىشلەتكۈچى.قۇرۇش_تور(0);
        if (تۇتقۇچ_قىممىتى < 0) return 3;
        int[] مەلۇمات = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int ئۇزۇنلۇق_قىممىتى = 1024 - (회차 & 1);
            for (int ئىندېكس = 0; ئىندېكس < ئۇزۇنلۇق_قىممىتى; ئىندېكس++) مەلۇمات[ئىندېكس] = (ئىندېكس + 회차) & 255;
            if (ئىشلەتكۈچى.ئەۋەتمەك_مەلۇمات(تۇتقۇچ_قىممىتى, 0x0a000202, ئېغىز_قىممىتى, مەلۇمات, ئۇزۇنلۇق_قىممىتى) != ئۇزۇنلۇق_قىممىتى) return 4;
            if (ئىشلەتكۈچى.자료받기(تۇتقۇچ_قىممىتى, مەلۇمات, 300) != ئۇزۇنلۇق_قىممىتى) return 5;
            for (int ئىندېكس = 0; ئىندېكس < ئۇزۇنلۇق_قىممىتى; ئىندېكس++) if (مەلۇمات[ئىندېكس] != ((ئىندېكس + 회차) & 255)) return 6;
        }
        ئىشلەتكۈچى.ئاياغ_تور(تۇتقۇچ_قىممىتى);
        ئىشلەتكۈچى.ياز("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
