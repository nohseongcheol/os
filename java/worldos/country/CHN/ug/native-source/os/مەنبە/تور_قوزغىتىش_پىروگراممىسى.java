/** PCI RTL8139 (10ec:8139), 단일 ئەۋەتمەك_قىممىتى 버퍼와 8KiB 수신 ئايلانما_قىممىتى. 인터럽트 대신 폴링한다. */
public final class تور_قوزغىتىش_پىروگراممىسى {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] كۆچمە_ئادرېس = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int ئورۇن) {
        كۆچمە_قىممىتى.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | ئورۇن);
        return كۆچمە_قىممىتى.입출력정수읽기(0xcfc);
    }

    static boolean تەييارلىماق() {
        int 장치번호 = -1;
        for (int ئىندېكس = 0; ئىندېكس < 32; ئىندېكس++) {
            if (설정읽기(ئىندېكس, 0) == 0x813910ec) { 장치번호 = ئىندېكس; break; }
        }
        if (장치번호 < 0) return false;
        int سۈكۈتتىكى_قىممەت = 설정읽기(장치번호, 0x10);
        if ((سۈكۈتتىكى_قىممەت & 1) == 0 || (سۈكۈتتىكى_قىممەت & 0xfffffffc) < 0x100 || (سۈكۈتتىكى_قىممەت & 0xfffffffc) > 65535) return false;
        입출력기준주소 = سۈكۈتتىكى_قىممەت & 0xfffc;
        int بۇيرۇق = 설정읽기(장치번호, 4);
        كۆچمە_قىممىتى.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        كۆچمە_قىممىتى.입출력짧은수쓰기(0xcfc, بۇيرۇق | 5); // I/O 및 bus master رۇخسەتنامە_قىممىتى, PCI ھالەت_قىممىتى 비트는 건드리지 않음
        كۆچمە_قىممىتى.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!قايتا_تەڭشەش_قىممىتى()) { 입출력기준주소 = 0; return false; }
        for (int ئىندېكس = 0; ئىندېكس < 6; ئىندېكس++) كۆچمە_ئادرېس[ئىندېكس] = كۆچمە_قىممىتى.입출력바이트읽기(입출력기준주소 + ئىندېكس);
        return true;
    }

    static boolean قايتا_تەڭشەش_قىممىتى() {
        كۆچمە_قىممىتى.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int ئىجرا_قىل_2 = كۆچمە_قىممىتى.밀리초();
        while ((كۆچمە_قىممىتى.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (كۆچمە_قىممىتى.밀리초() - ئىجرا_قىل_2 > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        كۆچمە_قىممىتى.입출력정수쓰기(입출력기준주소 + 0x30, كۆچمە_قىممىتى.تور_ساقلىغۇچ());
        for (int ئىندېكس = 0; ئىندېكس < 4; ئىندېكس++) كۆچمە_قىممىتى.입출력정수쓰기(입출력기준주소 + 0x20 + ئىندېكس * 4, كۆچمە_قىممىتى.تور_ساقلىغۇچ() + 12288);
        كۆچمە_قىممىتى.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        كۆچمە_قىممىتى.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        كۆچمە_قىممىتى.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        كۆچمە_قىممىتى.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/تارقىتىش_قىممىتى, wrap 연속 ساقلىماق_قىممىتى, 8KiB
        كۆچمە_قىممىتى.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int ئەۋەتمەك(int[] مەلۇمات, int ئۇزۇنلۇق_قىممىتى) {
        if (입출력기준주소 == 0) return -19;
        if (ئۇزۇنلۇق_قىممىتى < 14 || ئۇزۇنلۇق_قىممىتى > 1514) return -90;
        int بىكار_ئېغىز = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int ئىجرا_قىل_2 = كۆچمە_قىممىتى.밀리초();
        while ((كۆچمە_قىممىتى.입출력정수읽기(بىكار_ئېغىز) & 0x2000) == 0)
            if (كۆچمە_قىممىتى.밀리초() - ئىجرا_قىل_2 > 100) return -110;
        int چوڭلۇقى = ئۇزۇنلۇق_قىممىتى < 60 ? 60 : ئۇزۇنلۇق_قىممىتى;
        for (int ئىندېكس = 0; ئىندېكس < چوڭلۇقى; ئىندېكس++)
            كۆچمە_قىممىتى.يازماق_ساقلىغۇچ(كۆچمە_قىممىتى.تور_ساقلىغۇچ() + 12288 + ئىندېكس, ئىندېكس < ئۇزۇنلۇق_قىممىتى ? مەلۇمات[ئىندېكس] : 0);
        كۆچمە_قىممىتى.입출력정수쓰기(بىكار_ئېغىز, چوڭلۇقى | 0x00080000);
        ئىجرا_قىل_2 = كۆچمە_قىممىتى.밀리초();
        while ((كۆچمە_قىممىتى.입출력정수읽기(بىكار_ئېغىز) & 0xe0008000) == 0)
            if (كۆچمە_قىممىتى.밀리초() - ئىجرا_قىل_2 > 100) return -110;
        if ((كۆچمە_قىممىتى.입출력정수읽기(بىكار_ئېغىز) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return ئۇزۇنلۇق_قىممىتى;
    }

    static int 받기(int[] مەلۇمات) {
        if (입출력기준주소 == 0) return 0;
        if ((كۆچمە_قىممىتى.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!قايتا_تەڭشەش_قىممىتى()) 입출력기준주소 = 0;
            return 0;
        }
        if ((كۆچمە_قىممىتى.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = كۆچمە_قىممىتى.تور_ساقلىغۇچ() + 수신위치;
        int ھالەت_قىممىتى = 실행관리.짧은수(머리), چوڭلۇقى = 실행관리.짧은수(머리 + 2);
        if (چوڭلۇقى == 0xfff0) return 0; // DMA 진행 중
        if (چوڭلۇقى < 4 || چوڭلۇقى > 1518) {
            오류수++;
            if (!قايتا_تەڭشەش_قىممىتى()) 입출력기준주소 = 0;
            return 0;
        }
        int ئۇزۇنلۇق_قىممىتى = چوڭلۇقى - 4;
        if ((ھالەت_قىممىتى & 1) != 0) {
            for (int ئىندېكس = 0; ئىندېكس < ئۇزۇنلۇق_قىممىتى; ئىندېكس++) مەلۇمات[ئىندېكس] = كۆچمە_قىممىتى.기억읽기(머리 + 4 + ئىندېكس);
            수신수++;
        } else { ئۇزۇنلۇق_قىممىتى = 0; 오류수++; }
        수신위치 = (수신위치 + چوڭلۇقى + 4 + 3) & ~3;
        수신위치 &= 8191;
        كۆچمە_قىممىتى.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        كۆچمە_قىممىتى.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return ئۇزۇنلۇق_قىممىتى;
    }
}
