#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 بايت_قىممىتى 위치로 자체 C 이름을 옮기는 일회성 이행 قوراللار.

외부 구조체의 멤버, ھەرپ_تىزمىسى_قىممىتى, C 표준 فۇنكسىيە_قىممىتى, 이식 규약은 보존한다.
입력은 ئۆزگەرتمەك_قىممىتى 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

كۆرسىتىش_يىلتىز = Path(__file__).resolve().parents[1]

def ئىجرا_قىلىش_بۇيرۇق():
    ئانالىز_قىلماق_قىممىتى = json.loads((كۆرسىتىش_يىلتىز/'build/한국어화/시언어분석.json').read_text())
    if ئانالىز_قىلماق_قىممىتى['خاتالىق']: raise SystemExit('ئانالىز_قىلماق_قىممىتى 오류를 먼저 해결해야 합니다.')
    نامى_جەدۋەل = json.loads((كۆرسىتىش_يىلتىز/'명명/시언어이름.json').read_text())
    ئۆلچەملىك_SD = set(json.loads((كۆرسىتىش_يىلتىز/'명명/규격이름.json').read_text()))
    선언표 = ئانالىز_قىلماق_قىممىتى['선언']
    바꿀선언 = {고유:نامى_جەدۋەل[كىرگۈزۈش_قىممىتى['ئاتى']] for 고유,كىرگۈزۈش_قىممىتى in 선언표.items()
                if كىرگۈزۈش_قىممىتى['ئاتى'] in نامى_جەدۋەل and كىرگۈزۈش_قىممىتى['ئاتى'] not in ئۆلچەملىك_SD}
    ئۇلىنىش_جەدۋەل = {كىرگۈزۈش_قىممىتى['ئاتى']:نامى_جەدۋەل[كىرگۈزۈش_قىممىتى['ئاتى']] for كىرگۈزۈش_قىممىتى in 선언표.values()
              if كىرگۈزۈش_قىممىتى.get('ئۇلا')==4 and كىرگۈزۈش_قىممىتى['종류'] in (8,9)
              and كىرگۈزۈش_قىممىتى['ئاتى'] in نامى_جەدۋەل and كىرگۈزۈش_قىممىتى['ئاتى'] not in ئۆلچەملىك_SD}
    # ھاسىل_قىلىش AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ئۇلا 이름만 유지한다.
    머리 = ['/* 한국어 مەنبە_دەرەخ 이름과 기존 ماشىنا ئۇلا خىزمەت_قىممىتى. 자동 ھاسىل_قىلىش: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(ئۇلىنىش_جەدۋەل.items())]
    머리 += ['#endif','']
    (كۆرسىتىش_يىلتىز/'명명/기계연결이름.h').write_text('\n'.join(머리))
    ئۆزگەرتىش_تىزىم = defaultdict(dict)
    for ھۆججەت,ئاغما_قىممىتى,ئاتى,고유 in ئانالىز_قىلماق_قىممىتى['پايدىلانما']:
        if 고유 in 바꿀선언:
            ئۆزگەرتىش_تىزىم[ھۆججەت][ئاغما_قىممىتى] = (ئاتى,바꿀선언[고유])
    خاتىرە_قۇر = ['ھۆججەت\t원래바이트위치\t이전이름\t한국어이름']
    پەرۋا_قىلماسلىق_قىممىتى = []
    for ھۆججەت,ئۆزگەرتمەك_قىممىتى in ئۆزگەرتىش_تىزىم.items():
        يول = Path(ھۆججەت); 원본 = يول.read_bytes(); مەلۇمات = 원본
        for ئاغما_قىممىتى,(옛이름,새이름) in sorted(ئۆزگەرتمەك_قىممىتى.items(),reverse=True):
            끝 = ئاغما_قىممىتى+len(옛이름.encode())
            if 원본[ئاغما_قىممىتى:끝] != 옛이름.encode():
                پەرۋا_قىلماسلىق_قىممىتى.append((str(يول.relative_to(كۆرسىتىش_يىلتىز)),ئاغما_قىممىتى,옛이름));continue
            مەلۇمات = مەلۇمات[:ئاغما_قىممىتى]+새이름.encode()+مەلۇمات[끝:]
            خاتىرە_قۇر.append('{}\t{}\t{}\t{}'.format(يول.relative_to(كۆرسىتىش_يىلتىز),ئاغما_قىممىتى,옛이름,새이름))
        يول.write_bytes(مەلۇمات)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    بۇيرۇق_توپى_قىممىتى = {كىرگۈزۈش_قىممىتى['ئاتى']:نامى_جەدۋەل[كىرگۈزۈش_قىممىتى['ئاتى']] for كىرگۈزۈش_قىممىتى in 선언표.values()
              if كىرگۈزۈش_قىممىتى['종류']==501 and كىرگۈزۈش_قىممىتى['ئاتى'] in نامى_جەدۋەل and كىرگۈزۈش_قىممىتى['ئاتى'] not in ئۆلچەملىك_SD}
    for يول in sorted({Path(كىرگۈزۈش_قىممىتى['ھۆججەت']) for كىرگۈزۈش_قىممىتى in 선언표.values()}):
        قۇر_تىزىم = يول.read_text().splitlines(True); 이어짐 = False
        for ئىندېكس,قۇر in enumerate(قۇر_تىزىم):
            전처리 = 이어짐 or bool(re.match(r'\s*#',قۇر))
            이어짐 = 전처리 and قۇر.rstrip().endswith('\\')
            if 전처리:
                ئىزدەش_جەدۋەل = نامى_جەدۋەل if re.match(r'\s*#\s*define\b',قۇر) or 이어짐 else بۇيرۇق_توپى_قىممىتى
                قۇر_تىزىم[ئىندېكس] = 낱말.sub(lambda 맞음: ئىزدەش_جەدۋەل.get(맞음[0],맞음[0]) if 맞음[0] not in ئۆلچەملىك_SD else 맞음[0],قۇر)
        يول.write_text(''.join(قۇر_تىزىم))
    # 각 자체 تەرجىمە_مەنبە 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for يول in sorted({Path(كىرگۈزۈش_قىممىتى['ھۆججەت']) for كىرگۈزۈش_قىممىتى in 선언표.values()}):
        if يول.suffix not in ('.c','.cpp'):continue
        باراۋەرلىك_قىممىتى = '../' * len(يول.relative_to(كۆرسىتىش_يىلتىز).parts[:-1]) + '명명/기계연결이름.h'
        يول.write_text('#include "'+باراۋەرلىك_قىممىتى+'"\n'+يول.read_text())
    (كۆرسىتىش_يىلتىز/'명명/시언어이름대응.tsv').write_text('\n'.join(خاتىرە_قۇر)+'\n')
    (كۆرسىتىش_يىلتىز/'build/한국어화/전처리참조.json').write_text(json.dumps(پەرۋا_قىلماسلىق_قىممىتى,ensure_ascii=False,indent=2)+'\n')
    print('ئۆزگەرتمەك_قىممىتى',len(خاتىرە_قۇر)-1,'전처리 재검토',len(پەرۋا_قىلماسلىق_قىممىتى),'ماشىنا ئۇلا',len(ئۇلىنىش_جەدۋەل))

if __name__=='__main__': ئىجرا_قىلىش_بۇيرۇق()
