        دەلىللىمەك(호출.ياپ(بالا_قىممىتى, 서술자) == 0 && 부모.파일서술자().열려있음(서술자), "بالا_قىممىتى ياپ 격리");

        int 이전끝 = 호출.프로그램끝늘리기(부모, 8192);
        دەلىللىمەك(이전끝 == 0x06000000, "ئەپ_f5044b9b 끝 늘리기");
        دەلىللىمەك(부모.프로그램끝() == 0x06002000, "ئەپ_f5044b9b 끝 반영");
        دەلىللىمەك(بالا_قىممىتى.프로그램끝() == 0x06000000, "과정별 ئەپ_f5044b9b 끝 격리");

        بالا_قىممىتى.چىقىش_ئەپ(7);
        دەلىللىمەك(호출.자식기다리기(부모, بالا_قىممىتى.پەرقلەندۈرگۈچ_قىممىتى(), false) == (7 << 8), "بالا_قىممىتى چىقىش_ئەپ 기다리기");
        دەلىللىمەك(호출.접근가능("시험", 1) == -13, "ئىجرا_قىلىش_بۇيرۇق ئىجازەت_قىممىتى 거부");
        دەلىللىمەك(호출.ئىشلەتكۈچى_پەرقلەندۈرگۈچ() == 0 && 호출.توپ_پەرقلەندۈرگۈچ() == 0, "사용자와 무리 پەرقلەندۈرگۈچ_قىممىتى");
        دەلىللىمەك("/".equals(호출.현재작업목록(2)) && 호출.ئۆزگەرتمەك_ۋەزىپە_تىزىملىكى("/") == 0, "현재 작업 كىرگۈزۈش_تىزىم");
        دەلىللىمەك(호출.단말인가(부모, 1), "표준 چىقار 단말");
        دەلىللىمەك("JChnOS".equals(호출.체계정보().سىستېما_نامى()), "مەشغۇلات_سىستېمىسى_قىممىتى سىستېما_ئۇچۇرى");
