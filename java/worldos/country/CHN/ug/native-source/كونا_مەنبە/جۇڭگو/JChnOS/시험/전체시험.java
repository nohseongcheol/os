        دەلىللىمەك(서술자 >= 3, "ھۆججەت ئاچ");

        byte[] 받을곳 = new byte[مەزمۇن_قىممىتى.length];
        دەلىللىمەك(호출.ئوقۇ(부모, 서술자, 받을곳, 받을곳.length) == مەزمۇن_قىممىتى.length, "ھۆججەت ئوقۇ");
        دەلىللىمەك(Arrays.equals(مەزمۇن_قىممىتى, 받을곳), "ھۆججەت مەزمۇن_قىممىتى");
        دەلىللىمەك(호출.يۆتكىمەك_ئورۇنلاشتۇرۇش(부모, 서술자, 0, 체계호출.ئىزدەش_باشلاش) == 0, "ھۆججەت ئورۇن يۆتكىمەك_قىممىتى");

        int 복제서술자 = 호출.서술자복제(부모, 서술자);
        دەلىللىمەك(복제서술자 >= 0, "서술자 복제");
        جەريان_قىممىتى بالا_قىممىتى = 호출.과정복제(부모);
        دەلىللىمەك(بالا_قىممىتى.پەرقلەندۈرگۈچ_قىممىتى() != 부모.پەرقلەندۈرگۈچ_قىممىتى(), "جەريان_قىممىتى پەرقلەندۈرگۈچ_قىممىتى 분리");
