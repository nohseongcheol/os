/** 由 int 0x80 门调用；访问前检查所有用户指针和长度。 */
public final class 系统调用 {
    static int[] 临时缓冲 = new int[1024];

    static int 数组长度(int 地址) {
        if (!执行管理.裁剪(地址, 4)) return -14;
        int 长度 = 执行管理.数(地址);
        if (长度 < 0 || 长度 > (执行管理.用户结束 - 地址 - 4) / 4) return -14;
        return 长度;
    }

    public static int 进程值条目(int 编号, int 首位操作数, int 第二操作数, int 第三操作数, int 第四操作数, int 第五操作数) {
        if (编号 == 30) return 文件描述符管理.打开文件(首位操作数, 第二操作数, 第三操作数);
        if (编号 == 31) return 文件描述符管理.读取文件(首位操作数, 第二操作数, 第三操作数);
        if (编号 == 32) return 文件描述符管理.写入文件(首位操作数, 第二操作数, 第三操作数);
        if (编号 == 33) return 文件描述符管理.关闭文件(首位操作数);
        if (编号 == 34) return 文件描述符管理.寻道文件(首位操作数, 第二操作数, 第三操作数);
        if (编号 == 35) return 文件描述符管理.复制副本描述符(首位操作数, 0, false, 0);
        if (编号 == 36) return 文件描述符管理.复制副本描述符(首位操作数, 第二操作数, true, 0);
        if (编号 == 37) return 文件描述符管理.读取文件运行状态(首位操作数, 第二操作数);
        if (编号 == 38) return 文件描述符管理.移除文件条目名称(首位操作数);
        if (编号 == 39) return 文件描述符管理.设定文件长度(首位操作数, 第二操作数);
        if (编号 == 40) return 文件描述符管理.控制描述符(首位操作数, 第二操作数, 第三操作数);
        if (编号 == 41) return 文件描述符管理.创建端点(首位操作数, 第二操作数, 第三操作数);
        if (编号 == 42) return 文件描述符管理.绑定地址(首位操作数, 第二操作数, 第三操作数);
        if (编号 == 43) return 文件描述符管理.发送数据报数据(首位操作数, 第二操作数, 第三操作数, 第四操作数, 第五操作数);
        if (编号 == 44) return 文件描述符管理.接收数据报数据(首位操作数, 第二操作数, 第三操作数, 第四操作数, 第五操作数);
        if (编号 == 45) return 文件描述符管理.读取套接字地址(首位操作数, 第二操作数, 第三操作数);
        if (编号 == 46) return 文件描述符管理.设定接收超时(首位操作数, 第二操作数);
        if (编号 == 47) {
            int 描述符值 = 文件描述符管理.查找描述符(首位操作数);
            if (描述符值 < 0) return -9;
            if (文件描述符管理.种类值[描述符值] != 2) return -22;
            return 文件持久化.同步化();
        }
        if (编号 == 1) {
            int 长度 = 数组长度(首位操作数);
            if (长度 < 0) return 长度;
            if (长度 > 4096) return -90;
            for (int 字符值 = 0; 字符值 < 长度; 字符值++) 字符终端.字符(执行管理.数(首位操作数 + 4 + 字符值 * 4) & 65535);
            return 长度;
        }
        if (编号 == 2) return 执行管理.参数个数;
        if (编号 == 3) return 首位操作数 >= 0 && 首位操作数 < 执行管理.参数个数 ? 执行管理.参数地址[首位操作数] : 0;
        if (编号 == 10) return 通信网络.打开(首位操作数);
        if (编号 == 11) {
            int 长度 = 数组长度(第四操作数);
            if (长度 < 0) return 长度;
            if (第五操作数 < 0 || 第五操作数 > 长度 || 第五操作数 > 1024) return -90;
            for (int 位置 = 0; 位置 < 第五操作数; 位置++) 临时缓冲[位置] = 执行管理.数(第四操作数 + 4 + 位置 * 4) & 255;
            return 通信网络.发送(首位操作数, 第二操作数, 第三操作数, 临时缓冲, 第五操作数);
        }
        if (编号 == 12) {
            int 长度 = 数组长度(第二操作数);
            if (长度 < 0) return 长度;
            if (第三操作数 < 0 || 第三操作数 > 2000) return -22;
            int 结果 = 通信网络.接收(首位操作数, 临时缓冲, 长度 < 1024 ? 长度 : 1024, 第三操作数);
            if (结果 >= 0) for (int 位置 = 0; 位置 < 结果; 位置++) 执行管理.写入编号(第二操作数 + 4 + 位置 * 4, 临时缓冲[位置]);
            return 结果;
        }
        if (编号 == 13) return 通信网络.关闭(首位操作数);
        if (编号 == 14) return 通信网络.自有对象地址;
        if (编号 == 15) return 通信网络.对端地址(首位操作数);
        if (编号 == 16) return 通信网络.对端端口编号(首位操作数);
        if (编号 == 22) {
            if (首位操作数 < 0 || 首位操作数 > 65535) return -22;
            字符终端.字符(首位操作数); return 1;
        }
        if (编号 == 20 || 编号 == 21) {
            int 名称大小 = 数组长度(首位操作数), 数据大小 = 数组长度(第二操作数);
            if (名称大小 < 0 || 数据大小 < 0) return -14;
            if (名称大小 < 1 || 名称大小 > 64) return -22;
            int 长度 = 0;
            while (长度 < 名称大小 && 执行管理.数(首位操作数 + 4 + 长度 * 4) != 0) {
                主存文件系统.名称[长度] = 执行管理.数(首位操作数 + 4 + 长度 * 4);
                长度++;
            }
            if (!主存文件系统.检查名称(主存文件系统.名称, 长度)) return -22;
            if (编号 == 20) {
                int 文件 = 主存文件系统.查找条目(主存文件系统.名称, 长度);
                if (文件 < 0) return 文件;
                int 大小 = 主存文件系统.大小列表[文件];
                if (大小 > 数据大小) return -90;
                int 地址 = 设备.文件内存() + 文件 * 主存文件系统.最大大小;
                for (int 数 = 0; 数 < 大小; 数++) 执行管理.写入编号(第二操作数 + 4 + 数 * 4, 设备.读取内存(地址 + 数));
                return 大小;
            }
            if (第三操作数 < 0 || 第三操作数 > 数据大小) return -22;
            if (第三操作数 > 主存文件系统.最大大小) return -90;
            for (int 数 = 0; 数 < 第三操作数; 数++) 主存文件系统.编辑值[数] = 执行管理.数(第二操作数 + 4 + 数 * 4) & 255;
            return 主存文件系统.存储值(主存文件系统.名称, 长度, 主存文件系统.编辑值, 第三操作数);
        }
        return -38;
    }
}
