#include "网络ABI.h"
static 互联网套接字地址 地址(unsigned 端口值) {
    互联网套接字地址 值 = {}; 值.地址族 = 互联网族;
    值.端口编号 = 网络短整数(端口值); 值.互联网地址.地址值 = 网络整数(环回地址); return 值;
}
extern "C" int 开始用户程序(int) {
    int 发送中端点 = 创建端点(互联网族, 数据报套接字, 0);
    int 接收者端点 = 创建端点(互联网族, 数据报套接字, 数据报协议);
    if (发送中端点 < 0 || 接收者端点 < 0) return 1;
    互联网套接字地址 到达值 = 地址(7777), 出发值 = 地址(7778), 已发送地址 = {};
    套接字地址长度类型 地址长度 = sizeof(已发送地址);
    if (绑定地址(接收者端点, (套接字地址 *)&到达值, sizeof(到达值))) return 2;
    if (绑定地址(发送中端点, (套接字地址 *)&到达值, sizeof(到达值)) != -1 || 错误编号 != 98) return 3;
    if (绑定地址(发送中端点, (套接字地址 *)&出发值, sizeof(出发值))) return 4;
    static const char 内容值[] = "한글 UDP loopback 😀";
    char 已接收值[64] = {};
    if (发送数据报数据(发送中端点, 内容值, sizeof(内容值), 0, (套接字地址 *)&到达值, sizeof(到达值)) != sizeof(内容值)) return 5;
    if (接收数据报数据(接收者端点, (void *)内容值, sizeof(内容值), 0, 0, 0) != -1 || 错误编号 != 14) return 6;
    if (接收数据报数据(接收者端点, 已接收值, sizeof(已接收值), 0, (套接字地址 *)&已发送地址, &地址长度) != sizeof(内容值)) return 7;
    if (地址长度 != sizeof(已发送地址) || 设备排序短整数(已发送地址.端口编号) != 7778 || 设备排序整数(已发送地址.互联网地址.地址值) != 环回地址) return 8;
    for (unsigned 序数索引 = 0; 序数索引 < sizeof(内容值); 序数索引++) if (已接收值[序数索引] != 内容值[序数索引]) return 9;
    if (接收数据报数据(接收者端点, 已接收值, sizeof(已接收值), 0, 0, 0) != -1 || 错误编号 != 11) return 10;
    if (发送数据报数据(接收者端点, 已接收值, sizeof(内容值), 0, (套接字地址 *)&已发送地址, sizeof(已发送地址)) != sizeof(内容值)) return 11;
    if (接收数据报数据(发送中端点, 已接收值, 4, 0, 0, 0) != 4) return 12;
    if (接收数据报数据(发送中端点, 已接收值, 4, 0, 0, 0) != -1 || 错误编号 != 11) return 13;
    for (int 序数索引 = 0; 序数索引 < 4; 序数索引++) if (发送数据报数据(发送中端点, 内容值, sizeof(内容值), 0, (套接字地址 *)&到达值, sizeof(到达值)) != sizeof(内容值)) return 14;
    if (发送数据报数据(发送中端点, 内容值, sizeof(内容值), 0, (套接字地址 *)&到达值, sizeof(到达值)) != -1 || 错误编号 != 11) return 15;
    for (int 序数索引 = 0; 序数索引 < 4; 序数索引++) if (接收数据报数据(接收者端点, 已接收值, sizeof(已接收值), 0, 0, 0) != sizeof(内容值)) return 16;
    if (发送数据报数据(发送中端点, 0, 0, 0, (套接字地址 *)&到达值, sizeof(到达值)) != 0 ||
        接收数据报数据(接收者端点, 0, 0, 0, 0, 0) != 0) return 21;
    到达值.互联网地址.地址值 = 网络整数(0x08080808);
    if (发送数据报数据(发送中端点, 内容值, sizeof(内容值), 0, (套接字地址 *)&到达值, sizeof(到达值)) != -1 || 错误编号 != 101) return 17;
    if (创建端点(互联网族, 流网络, 数据报协议) != -1 || 错误编号 != 93) return 18;
    地址长度 = sizeof(已发送地址);
    if (读取套接字地址(接收者端点, (套接字地址 *)&已发送地址, &地址长度) || 设备排序短整数(已发送地址.端口编号) != 7777) return 19;
    if (关闭文件(接收者端点) || 关闭文件(接收者端点) != -1 || 错误编号 != 9) return 20;
    // 보내는곳은 열어 둔다: 退出程序 시 프로세스별 socket 정리를 검사한다.
    static const char 是否完成[] = "EL0 UDP LOOPBACK PASS (external network unavailable)\n";
    写入文件数据(1, 是否完成, sizeof(是否完成) - 1);
    return 0;
}
