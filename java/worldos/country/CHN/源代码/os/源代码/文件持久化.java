/** 采用校验和及双副本的小型专用存储格式，只在 fsync/sync 时持久化。 */
public final class 文件持久化 {
    static int 当前已保留复制 = -1, 代次编号 = 0;
    static int[] 文件表 = new int[1024];
    static int 哈希字节列(int 值, int 数据) { return (值 ^ 数据) * 16777619; }
    static void 清空数据() {
        for (int 编号 = 0; 编号 < 512; 编号++) 存储设备连接.区段数据[编号] = 0;
    }
    static int 表整数(int 位置) {
        return 文件表[位置] | 文件表[位置 + 1] << 8 | 文件表[位置 + 2] << 16 | 文件表[位置 + 3] << 24;
    }
    static void 写入表整数(int 位置, int 值) {
        for (int 编号 = 0; 编号 < 4; 编号++) 文件表[位置 + 编号] = (值 >>> (编号 * 8)) & 255;
    }
    static boolean 检查表() {
        for (int 文件 = 0; 文件 < 8; 文件++) {
            int 长度 = 0;
            for (int 槽条目 = 0; 槽条目 < 64; 槽条目++) 主存文件系统.名称[槽条目] = 文件表[文件 * 72 + 槽条目];
            while (长度 < 64 && 主存文件系统.名称[长度] != 0) 长度++;
            if (长度 == 0) continue;
            if (!主存文件系统.检查名称(主存文件系统.名称, 长度)
                || 表整数(文件 * 72 + 64) < 0 || 表整数(文件 * 72 + 64) > 16384) return false;
            for (int 前端值 = 0; 前端值 < 文件; 前端值++) {
                boolean 相等文本 = 文件表[前端值 * 72 + 长度] == 0;
                for (int 槽条目 = 0; 槽条目 < 长度; 槽条目++) if (文件表[前端值 * 72 + 槽条目] != 主存文件系统.名称[槽条目]) 相等文本 = false;
                if (相等文本) return false;
            }
        }
        return true;
    }
    static int 检查已保留复制(int 已保留复制) {
        int 开始区段 = 1 + 已保留复制 * 259;
        if (存储设备连接.读取(开始区段) < 0 || 存储设备连接.解析整数(0) != 0x4a4b534e) return -1;
        int 代次值 = 存储设备连接.解析整数(4), 校验和 = 存储设备连接.解析整数(8);
        if (代次值 < 1 || 存储设备连接.解析整数(12) != (代次值 ^ 校验和 ^ 0x4a4b534e)) return -1;
        int 哈希文件 = 0x811c9dc5;
        for (int 区段值 = 0; 区段值 < 258; 区段值++) {
            if (存储设备连接.读取(开始区段 + 1 + 区段值) < 0) return -1;
            for (int 槽条目 = 0; 槽条目 < 512; 槽条目++) {
                int 值 = 存储设备连接.区段数据[槽条目];
                哈希文件 = 哈希字节列(哈希文件, 值);
                if (区段值 < 2) 文件表[区段值 * 512 + 槽条目] = 值;
            }
        }
        return 哈希文件 == 校验和 && 检查表() ? 代次值 : -1;
    }
    static int 加载(int 已保留复制) {
        int 开始区段 = 1 + 已保留复制 * 259;
        for (int 区段值 = 0; 区段值 < 2; 区段值++) {
            if (存储设备连接.读取(开始区段 + 1 + 区段值) < 0) return -5;
            for (int 槽条目 = 0; 槽条目 < 512; 槽条目++) 文件表[区段值 * 512 + 槽条目] = 存储设备连接.区段数据[槽条目];
        }
        for (int 文件 = 0; 文件 < 8; 文件++) {
            for (int 槽条目 = 0; 槽条目 < 64; 槽条目++) 主存文件系统.名称列列表[文件 * 64 + 槽条目] = 文件表[文件 * 72 + 槽条目];
            主存文件系统.大小列表[文件] = 文件表[文件 * 72] == 0 ? 0 : 表整数(文件 * 72 + 64);
            主存文件系统.权限授权列[文件] = 表整数(文件 * 72 + 68) & 511;
            for (int 区段值 = 0; 区段值 < 32; 区段值++) {
                if (存储设备连接.读取(开始区段 + 3 + 文件 * 32 + 区段值) < 0) return -5;
                int 地址 = 设备.文件内存() + 文件 * 16384 + 区段值 * 512;
                for (int 槽条目 = 0; 槽条目 < 512; 槽条目++) 设备.写入内存(地址 + 槽条目, 存储设备连接.区段数据[槽条目]);
            }
        }
        return 0;
    }
    static void 准备() {
        if (存储设备连接.读取(0) < 0 || 存储设备连接.解析整数(0) != 0x54534b4a
            || 存储设备连接.解析整数(4) != 0x3145524f || 存储设备连接.解析整数(8) != 2048
            || 存储设备连接.解析整数(12) != 0x3153464a) {
            字符终端.写入("STORE RAM only (no JKSTORE1 disk)\n"); return;
        }
        存储设备连接.是否可用 = true;
        int 首位序数 = 检查已保留复制(0), 第二序数 = 检查已保留复制(1);
        if (首位序数 < 0 && 第二序数 < 0) { 字符终端.写入("STORE ready; no valid snapshot\n"); return; }
        当前已保留复制 = 首位序数 >= 第二序数 ? 0 : 1; 代次编号 = 首位序数 >= 第二序数 ? 首位序数 : 第二序数;
        if (加载(当前已保留复制) < 0) {
            字符终端.写入("STORE read failed; halted to preserve files\n"); 设备.停机执行状态();
        }
        字符终端.写入("STORE restored generation "); 字符终端.写入编号(代次编号); 字符终端.字符(10);
    }
    static int 同步化() {
        if (!存储设备连接.是否可用) return -19;
        if (代次编号 == 2147483647) return -75;
        int 下一项目 = 当前已保留复制 == 0 ? 1 : 0, 开始区段 = 1 + 下一项目 * 259;
        // 写新正文前，先使旧 commit 失效并刷新设备缓存。
        清空数据();
        if (存储设备连接.写入(开始区段) < 0 || 存储设备连接.冲刷输出() < 0) return -5;
        for (int 槽条目 = 0; 槽条目 < 1024; 槽条目++) 文件表[槽条目] = 0;
        for (int 文件 = 0; 文件 < 8; 文件++) if (主存文件系统.名称列列表[文件 * 64] != 0) {
            for (int 槽条目 = 0; 槽条目 < 64; 槽条目++) 文件表[文件 * 72 + 槽条目] = 主存文件系统.名称列列表[文件 * 64 + 槽条目];
            写入表整数(文件 * 72 + 64, 主存文件系统.大小列表[文件]);
            写入表整数(文件 * 72 + 68, 主存文件系统.权限授权列[文件]);
        }
        int 哈希文件 = 0x811c9dc5;
        for (int 区段值 = 0; 区段值 < 258; 区段值++) {
            for (int 槽条目 = 0; 槽条目 < 512; 槽条目++) {
                int 值 = 0;
                if (区段值 < 2) 值 = 文件表[区段值 * 512 + 槽条目];
                else {
                    int 文件 = (区段值 - 2) / 32, 位置 = (区段值 - 2) % 32 * 512 + 槽条目;
                    if (文件表[文件 * 72] != 0 && 位置 < 主存文件系统.大小列表[文件])
                        值 = 设备.读取内存(设备.文件内存() + 文件 * 16384 + 位置);
                }
                存储设备连接.区段数据[槽条目] = 值; 哈希文件 = 哈希字节列(哈希文件, 值);
            }
            if (存储设备连接.写入(开始区段 + 1 + 区段值) < 0) return -5;
        }
        if (存储设备连接.冲刷输出() < 0) return -5;
        清空数据(); 存储设备连接.写入整数值(0, 0x4a4b534e);
        存储设备连接.写入整数值(4, 代次编号 + 1); 存储设备连接.写入整数值(8, 哈希文件);
        存储设备连接.写入整数值(12, (代次编号 + 1) ^ 哈希文件 ^ 0x4a4b534e);
        if (存储设备连接.写入(开始区段) < 0 || 存储设备连接.冲刷输出() < 0) return -5;
        当前已保留复制 = 下一项目; 代次编号++;
        return 0;
    }
}
