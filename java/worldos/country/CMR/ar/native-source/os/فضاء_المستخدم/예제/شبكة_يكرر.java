/** 최대 حجم/홀수 길이 데이터그램으로 الفعلي_بيانات RTL8139 يستلم_قيمة يكرر_قيمة 순환을 시험한다. */
public final class شبكة_يكرر {
    public static int تشغيل() {
        if (فضاء_المستخدم.인수개수() != 1) { فضاء_المستخدم.كتابة("Usage: run stress PORT\n"); return 2; }
        String نص = فضاء_المستخدم.وسائط(0);
        int منفذ_قيمة = 0;
        for (int فهرس = 0; فهرس < نص.length(); فهرس++) {
            if (نص.charAt(فهرس) < '0' || نص.charAt(فهرس) > '9' || منفذ_قيمة > 6553) return 2;
            منفذ_قيمة = منفذ_قيمة * 10 + نص.charAt(فهرس) - '0';
        }
        if (منفذ_قيمة < 1 || منفذ_قيمة > 65535) return 2;
        int مؤشر_قيمة = فضاء_المستخدم.فتح_شبكة(0);
        if (مؤشر_قيمة < 0) return 3;
        int[] بيانات = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int 길이 = 1024 - (회차 & 1);
            for (int فهرس = 0; فهرس < 길이; فهرس++) بيانات[فهرس] = (فهرس + 회차) & 255;
            if (فضاء_المستخدم.يرسل_بيانات(مؤشر_قيمة, 0x0a000202, منفذ_قيمة, بيانات, 길이) != 길이) return 4;
            if (فضاء_المستخدم.يستلم_بيانات(مؤشر_قيمة, بيانات, 300) != 길이) return 5;
            for (int فهرس = 0; فهرس < 길이; فهرس++) if (بيانات[فهرس] != ((فهرس + 회차) & 255)) return 6;
        }
        فضاء_المستخدم.يغلق_شبكة(مؤشر_قيمة);
        فضاء_المستخدم.كتابة("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
