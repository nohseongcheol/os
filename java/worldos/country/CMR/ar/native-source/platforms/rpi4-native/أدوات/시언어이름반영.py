#!/usr/bin/env python3
"""إعلان 고유번호와 UTF-8 بايت_قيمة 위치로 ذاتي C 이름을 옮기는 일회성 이행 أدوات.

خارجي_قيمة 구조체의 멤버, سلسلة_قيمة, C 표준 دالة_قيمة, 이식 규약은 보존한다.
입력은 يغيّر_قيمة 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

يعرض_جذر = Path(__file__).resolve().parents[1]

def ينفذ_أمر():
    تحليل_قيمة = json.loads((يعرض_جذر/'build/한국어화/시언어분석.json').read_text())
    if تحليل_قيمة['خطأ']: raise SystemExit('تحليل_قيمة 오류를 먼저 해결해야 합니다.')
    اسم_جدول = json.loads((يعرض_جذر/'명명/시언어이름.json').read_text())
    قياسي_تعريف = set(json.loads((يعرض_جذر/'명명/규격이름.json').read_text()))
    إعلان_جدول = تحليل_قيمة['إعلان']
    바꿀선언 = {고유:اسم_جدول[إدخال_قيمة_962f286b['اسم']] for 고유,إدخال_قيمة_962f286b in إعلان_جدول.items()
                if إدخال_قيمة_962f286b['اسم'] in اسم_جدول and إدخال_قيمة_962f286b['اسم'] not in قياسي_تعريف}
    صديق_جدول = {إدخال_قيمة_962f286b['اسم']:اسم_جدول[إدخال_قيمة_962f286b['اسم']] for إدخال_قيمة_962f286b in إعلان_جدول.values()
              if إدخال_قيمة_962f286b.get('اتصال')==4 and إدخال_قيمة_962f286b['종류'] in (8,9)
              and إدخال_قيمة_962f286b['اسم'] in اسم_جدول and إدخال_قيمة_962f286b['اسم'] not in قياسي_تعريف}
    # إنشاء AOT C·어셈블리·공개 SDK가 공유하는 바이너리 اتصال 이름만 유지한다.
    رأس_قيمة = ['/* العربية مصدر_شجرة 이름과 기존 جهاز اتصال قيمة_العقد. 자동 إنشاء: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    رأس_قيمة += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(صديق_جدول.items())]
    رأس_قيمة += ['#endif','']
    (يعرض_جذر/'명명/기계연결이름.h').write_text('\n'.join(رأس_قيمة))
    التغييرات_قائمة = defaultdict(dict)
    for ملف,إزاحة_قيمة,اسم,고유 in تحليل_قيمة['مرجع']:
        if 고유 in 바꿀선언:
            التغييرات_قائمة[ملف][إزاحة_قيمة] = (اسم,바꿀선언[고유])
    سجل_سجل = ['ملف\t원래바이트위치\t이전이름\t한국어이름']
    تجاهل_قيمة_3c26be06 = []
    for ملف,يغيّر_قيمة in التغييرات_قائمة.items():
        مسار = Path(ملف); 원본 = مسار.read_bytes(); بيانات = 원본
        for إزاحة_قيمة,(옛이름,새이름) in sorted(يغيّر_قيمة.items(),reverse=True):
            끝 = إزاحة_قيمة+len(옛이름.encode())
            if 원본[إزاحة_قيمة:끝] != 옛이름.encode():
                تجاهل_قيمة_3c26be06.append((str(مسار.relative_to(يعرض_جذر)),إزاحة_قيمة,옛이름));continue
            بيانات = بيانات[:إزاحة_قيمة]+새이름.encode()+بيانات[끝:]
            سجل_سجل.append('{}\t{}\t{}\t{}'.format(مسار.relative_to(يعرض_جذر),إزاحة_قيمة,옛이름,새이름))
        مسار.write_bytes(بيانات)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ماكرو_قيمة = {إدخال_قيمة_962f286b['اسم']:اسم_جدول[إدخال_قيمة_962f286b['اسم']] for إدخال_قيمة_962f286b in إعلان_جدول.values()
              if إدخال_قيمة_962f286b['종류']==501 and إدخال_قيمة_962f286b['اسم'] in اسم_جدول and إدخال_قيمة_962f286b['اسم'] not in قياسي_تعريف}
    for مسار in sorted({Path(إدخال_قيمة_962f286b['ملف']) for إدخال_قيمة_962f286b in إعلان_جدول.values()}):
        خط_قائمة = مسار.read_text().splitlines(True); 이어짐 = False
        for فهرس,سطر in enumerate(خط_قائمة):
            전처리 = 이어짐 or bool(re.match(r'\s*#',سطر))
            이어짐 = 전처리 and سطر.rstrip().endswith('\\')
            if 전처리:
                جدول_البحث = اسم_جدول if re.match(r'\s*#\s*define\b',سطر) or 이어짐 else ماكرو_قيمة
                خط_قائمة[فهرس] = 낱말.sub(lambda 맞음: جدول_البحث.get(맞음[0],맞음[0]) if 맞음[0] not in قياسي_تعريف else 맞음[0],سطر)
        مسار.write_text(''.join(خط_قائمة))
    # 각 ذاتي تحويل_مصدر 단위에만 연결표를 넣는다. خارجي_قيمة 배포본에는 전파하지 않는다.
    for مسار in sorted({Path(إدخال_قيمة_962f286b['ملف']) for إدخال_قيمة_962f286b in إعلان_جدول.values()}):
        if مسار.suffix not in ('.c','.cpp'):continue
        نظير_قيمة = '../' * len(مسار.relative_to(يعرض_جذر).parts[:-1]) + '명명/기계연결이름.h'
        مسار.write_text('#include "'+نظير_قيمة+'"\n'+مسار.read_text())
    (يعرض_جذر/'명명/시언어이름대응.tsv').write_text('\n'.join(سجل_سجل)+'\n')
    (يعرض_جذر/'build/한국어화/전처리참조.json').write_text(json.dumps(تجاهل_قيمة_3c26be06,ensure_ascii=False,indent=2)+'\n')
    print('يغيّر_قيمة',len(سجل_سجل)-1,'전처리 재검토',len(تجاهل_قيمة_3c26be06),'جهاز اتصال',len(صديق_جدول))

if __name__=='__main__': ينفذ_أمر()
