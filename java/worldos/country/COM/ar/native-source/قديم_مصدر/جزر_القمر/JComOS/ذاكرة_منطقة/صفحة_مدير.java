package جزر_القمر.JComOS.ذاكرة_منطقة;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB صفحة_قيمة 연결과 كتابة 시 복사를 제공한다. */
public final class صفحة_مدير {
    public static final int حجم_الورقة = 4096;

    private static final class صفحة_قيمة {
        private byte[] بيانات = new byte[حجم_الورقة];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean نسخ_الكتابة;
    }

    public static final class عنوان_مساحة {
        private final Map<Integer, صفحة_قيمة> صفحة_جدول = new HashMap<Integer, صفحة_قيمة>();
    }

    public عنوان_مساحة 새주소공간() {
        return new عنوان_مساحة();
    }

    public void مخطط_صفحة(عنوان_مساحة عنوان_منطقة, int العنوان_الظاهري, boolean 쓰기가능) {
        int فهرس = صفحة_رقم(العنوان_الظاهري);
        صفحة_قيمة 새쪽 = new صفحة_قيمة();
        새쪽.쓰기가능 = 쓰기가능;
        عنوان_منطقة.صفحة_جدول.put(Integer.valueOf(فهرس), 새쪽);
    }

    public عنوان_مساحة نسخة_نسخ_الكتابة(عنوان_مساحة 원본) {
        عنوان_مساحة 복제본 = new عنوان_مساحة();
        for (Map.Entry<Integer, صفحة_قيمة> إدخال_قيمة_962f286b : 원본.صفحة_جدول.entrySet()) {
            صفحة_قيمة 공유쪽 = إدخال_قيمة_962f286b.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.نسخ_الكتابة = true;
            }
            복제본.صفحة_جدول.put(إدخال_قيمة_962f286b.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte يقرأ_بايت_قيمة(عنوان_مساحة عنوان_منطقة, int العنوان_الظاهري) {
        صفحة_قيمة الهدف = بحث_صفحة(عنوان_منطقة, العنوان_الظاهري);
        return الهدف.بيانات[Math.floorMod(العنوان_الظاهري, حجم_الورقة)];
    }

    public void كتابة_بايت_قيمة(عنوان_مساحة عنوان_منطقة, int العنوان_الظاهري, byte قيمة) {
        int فهرس = صفحة_رقم(العنوان_الظاهري);
        صفحة_قيمة الهدف = بحث_صفحة(عنوان_منطقة, العنوان_الظاهري);
        if (!الهدف.쓰기가능) {
            if (!الهدف.نسخ_الكتابة) {
                throw new IllegalStateException("قراءة 전용 쪽입니다.");
            }
            الهدف = فتح_خاص_صفحة(عنوان_منطقة, فهرس, الهدف);
        }
        الهدف.بيانات[Math.floorMod(العنوان_الظاهري, حجم_الورقة)] = قيمة;
    }

    public void خاص_نطاق_كتابة(عنوان_مساحة عنوان_منطقة, int بدء_عنوان, int حجم) {
        if (حجم < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int العنوان_الأخير = Math.addExact(بدء_عنوان, حجم);
        for (int عنوان = بدء_عنوان; عنوان < العنوان_الأخير; عنوان = (صفحة_رقم(عنوان) + 1) * حجم_الورقة) {
            int فهرس = صفحة_رقم(عنوان);
            صفحة_قيمة الهدف = بحث_صفحة(عنوان_منطقة, عنوان);
            if (الهدف.نسخ_الكتابة) {
                فتح_خاص_صفحة(عنوان_منطقة, فهرس, الهدف);
            } else {
                الهدف.쓰기가능 = true;
            }
        }
    }

    public void نطاق_كتابة(عنوان_مساحة عنوان_منطقة, int بدء_عنوان, byte[] بيانات) {
        for (int فهرس = 0; فهرس < بيانات.length; فهرس++) {
            كتابة_بايت_قيمة(عنوان_منطقة, بدء_عنوان + فهرس, بيانات[فهرس]);
        }
    }

    private صفحة_قيمة فتح_خاص_صفحة(عنوان_مساحة عنوان_منطقة, int فهرس, صفحة_قيمة 공유쪽) {
        صفحة_قيمة خاص_صفحة = new صفحة_قيمة();
        خاص_صفحة.بيانات = Arrays.copyOf(공유쪽.بيانات, 공유쪽.بيانات.length);
        خاص_صفحة.쓰기가능 = true;
        خاص_صفحة.نسخ_الكتابة = false;
        공유쪽.참조수--;
        عنوان_منطقة.صفحة_جدول.put(Integer.valueOf(فهرس), خاص_صفحة);
        return خاص_صفحة;
    }

    private صفحة_قيمة بحث_صفحة(عنوان_مساحة عنوان_منطقة, int عنوان) {
        صفحة_قيمة الهدف = عنوان_منطقة.صفحة_جدول.get(Integer.valueOf(صفحة_رقم(عنوان)));
        if (الهدف == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return الهدف;
    }

    private int صفحة_رقم(int عنوان) {
        if (عنوان < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return عنوان / حجم_الورقة;
    }
}

