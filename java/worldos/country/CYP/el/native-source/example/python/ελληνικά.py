class σφάλμα_συστήματος(OSError):
    def __init__(자신, Ευρετήριο, 설명="λειτουργικό_σύστημα 작업에 실패했습니다."):
        super().__init__(Ευρετήριο, 설명)
        자신.Ευρετήριο = Ευρετήριο
        자신.설명 = 설명

def 운영호출(συνάρτηση_τιμή, *Παράμετροι):
    try:
        return συνάρτηση_τιμή(*Παράμετροι)
    except OSError as ΣΦΑΛΜΑ:
        Ευρετήριο = ΣΦΑΛΜΑ.args[0] if ΣΦΑΛΜΑ.args else 0
        raise σφάλμα_συστήματος(Ευρετήριο)

