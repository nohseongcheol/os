/** 디스크 Εγγραφή 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] είσοδος_τιμή = new int[128];
    static int διάρκεια_τιμή = 0;
    static boolean 앞줄복귀 = false;
    static boolean γραμμή_Υπερχείλιση = false;

    static boolean Εντολή(String Όνομα) {
        if (διάρκεια_τιμή < Όνομα.length()) return false;
        for (int Ευρετήριο = 0; Ευρετήριο < Όνομα.length(); Ευρετήριο++)
            if (είσοδος_τιμή[Ευρετήριο] != Όνομα.charAt(Ευρετήριο)) return false;
        return διάρκεια_τιμή == Όνομα.length() || είσοδος_τιμή[Όνομα.length()] == ' ';
    }

    static void εμφανίζω_βοήθεια() {
        μήνυμα_Τερματικό.Εγγραφή("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        μήνυμα_Τερματικό.Εγγραφή("apps | run NAME [ARGS] | net\n");
        μήνυμα_Τερματικό.Εγγραφή("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        μήνυμα_Τερματικό.Εγγραφή("sync (연결된 JKSTORE1 αποθηκεύω_τιμή 장치에 Αρχείο 보존)\n");
    }

    static void διεργασία_τιμή_καταχώρηση() {
        if (διάρκεια_τιμή == 0) return;
        if (Εντολή("help")) εμφανίζω_βοήθεια();
        else if (Εντολή("sync")) {
            int μέτρηση = 파일보존.συγχρονίζω();
            μήνυμα_Τερματικό.Εγγραφή("Sync: "); μήνυμα_Τερματικό.수쓰기(μέτρηση); μήνυμα_Τερματικό.문자(10);
        }
        else if (Εντολή("ls")) Μνήμη_σύστημα_αρχείων.καταχώρηση_Λίστα();
        else if (Εντολή("edit")) Μνήμη_σύστημα_αρχείων.Εντολή(είσοδος_τιμή, 4, διάρκεια_τιμή, 0);
        else if (Εντολή("cat")) Μνήμη_σύστημα_αρχείων.Εντολή(είσοδος_τιμή, 3, διάρκεια_τιμή, 1);
        else if (Εντολή("rm")) Μνήμη_σύστημα_αρχείων.Εντολή(είσοδος_τιμή, 2, διάρκεια_τιμή, 2);
        else if (Εντολή("java") || Εντολή("javac")) {
            int μέτρηση = εκτέλεση_Υπεύθυνος.εκτελώ_εντολή(είσοδος_τιμή, 0, διάρκεια_τιμή);
            μήνυμα_Τερματικό.Εγγραφή("Exit: "); μήνυμα_Τερματικό.수쓰기(μέτρηση); μήνυμα_Τερματικό.문자(10);
        }
        else if (Εντολή("apps")) εκτέλεση_Υπεύθυνος.καταχώρηση_Λίστα();
        else if (Εντολή("net")) δίκτυο_δέσμη.Κατάσταση_τιμή();
        else if (Εντολή("run")) {
            int μέτρηση = εκτέλεση_Υπεύθυνος.εκτελώ_εντολή(είσοδος_τιμή, 3, διάρκεια_τιμή);
            μήνυμα_Τερματικό.Εγγραφή("Exit: "); μήνυμα_Τερματικό.수쓰기(μέτρηση); μήνυμα_Τερματικό.Εγγραφή("\n");
        } else if (Εντολή("info")) {
            μήνυμα_Τερματικό.Εγγραφή("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (Εντολή("mem")) {
            μήνυμα_Τερματικό.Εγγραφή("위쪽 Μνήμη_τιμή διεύθυνση_περιοχή(KiB): "); μήνυμα_Τερματικό.수쓰기(Μνήμη_περιοχή.위쪽기억크기());
            μήνυμα_Τερματικό.Εγγραφή("\n배열 동적 Μνήμη_τιμή διεύθυνση_περιοχή(바이트): "); μήνυμα_Τερματικό.수쓰기(συσκευή_τιμή.πίνακας_χρήση());
            μήνυμα_Τερματικό.Εγγραφή(" / 262144\n작업 διεύθυνση_περιοχή ενότητα_τιμή: "); μήνυμα_Τερματικό.수쓰기(Μνήμη_περιοχή.사용개수());
            μήνυμα_Τερματικό.Εγγραφή(" / 8 (각 4096바이트)\n");
        } else if (Εντολή("alloc")) {
            int Ευρετήριο = Μνήμη_περιοχή.εκχωρώ_Χώρος_αποθήκευσης();
            μήνυμα_Τερματικό.Εγγραφή("ενότητα_τιμή Ευρετήριο: "); μήνυμα_Τερματικό.수쓰기(Ευρετήριο); μήνυμα_Τερματικό.Εγγραφή("\n");
        } else if (Εντολή("free")) {
            if (διάρκεια_τιμή == 6 && είσοδος_τιμή[4] == ' ' && είσοδος_τιμή[5] >= '0' && είσοδος_τιμή[5] <= '7') {
                μήνυμα_Τερματικό.Εγγραφή(Μνήμη_περιοχή.επιστρέφω_μέτρηση(είσοδος_τιμή[5] - '0') ? "반환됨\n" : "할당되지 않은 ενότητα_τιμή\n");
            } else μήνυμα_Τερματικό.Εγγραφή("사용법: free 0..7\n");
        } else if (Εντολή("echo")) {
            for (int Ευρετήριο = 5; Ευρετήριο < διάρκεια_τιμή; Ευρετήριο++) μήνυμα_Τερματικό.문자(είσοδος_τιμή[Ευρετήριο]);
            μήνυμα_Τερματικό.문자(10);
        } else if (Εντολή("clear")) μήνυμα_Τερματικό.διαγράφω_καταχώρηση();
        else if (Εντολή("test")) πυρήνας.시험();
        else if (Εντολή("halt")) {
            μήνυμα_Τερματικό.Εγγραφή("HALTED\n");
            συσκευή_τιμή.정지();
        } else μήνυμα_Τερματικό.Εγγραφή("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void αποδέχομαι_λογικό_ΚΑΙ_εγγράφω(int τιμή) {
        if (τιμή == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = τιμή == 13;
        if (τιμή == 10 || τιμή == 13) {
            μήνυμα_Τερματικό.문자(10);
            if (Μνήμη_σύστημα_αρχείων.편집중) Μνήμη_σύστημα_αρχείων.Επεξεργασμένα_γραμμή(είσοδος_τιμή, διάρκεια_τιμή, γραμμή_Υπερχείλιση);
            else διεργασία_τιμή_καταχώρηση();
            διάρκεια_τιμή = 0;
            γραμμή_Υπερχείλιση = false;
            μήνυμα_Τερματικό.Εγγραφή(Μνήμη_σύστημα_αρχείων.편집중 ? "...> " : "jkoros> ");
        } else if (τιμή == 8 || τιμή == 127) {
            if (διάρκεια_τιμή > 0) {
                διάρκεια_τιμή--;
                μήνυμα_Τερματικό.직렬바이트(8); μήνυμα_Τερματικό.직렬바이트(32); μήνυμα_Τερματικό.직렬바이트(8);
                μήνυμα_Τερματικό.화면문자(8);
            }
        } else if (τιμή >= 32 && τιμή < 127 && διάρκεια_τιμή < είσοδος_τιμή.length) {
            είσοδος_τιμή[διάρκεια_τιμή++] = τιμή;
            μήνυμα_Τερματικό.문자(τιμή);
        } else if (τιμή >= 32 && τιμή < 127) γραμμή_Υπερχείλιση = true;
    }

    static void Εκτέλεση_2() {
        εμφανίζω_βοήθεια();
        μήνυμα_Τερματικό.Εγγραφή("READY\njkoros> ");
        while (true) {
            int τιμή = μήνυμα_Τερματικό.직렬읽기();
            if (τιμή < 0) τιμή = πληκτρολόγιο.Ανάγνωση();
            if (τιμή >= 0) αποδέχομαι_λογικό_ΚΑΙ_εγγράφω(τιμή);
            else { δίκτυο_δέσμη.επαληθεύω(); συσκευή_τιμή.잠시양보(); }
        }
    }
}
