package Կիպրոս.JCypOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Կիպրոս.JCypOS.기억공간.էջ_կառավարիչ;
import Կիպրոս.JCypOS.նիշքային_համակարգ.파일서술자표;

/** Ընթացք_արժեք 식별자와 라운드로빈 Պատրաստել 대기열을 관리한다. */
public final class Ծրագրող {
    private final էջ_կառավարիչ 쪽관리;
    private final Map<Integer, Ընթացք_արժեք> Ընթացքների_ցուցակ = new HashMap<Integer, Ընթացք_արժեք>();
    private final Queue<Ընթացք_արժեք> 준비대기열 = new ArrayDeque<Ընթացք_արժեք>();
    private int Հաջորդը_նույնացուցիչ = 1;

    public Ծրագրող(էջ_կառավարիչ 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public Ընթացք_արժեք 첫과정(파일서술자표 파일서술자) {
        Ընթացք_արժեք 새과정 = new Ընթացք_արժեք(հատկացնել_նույնացուցիչ(), 0, 쪽관리.새주소공간(), 파일서술자);
        Ընթացքների_ցուցակ.put(Integer.valueOf(새과정.նույնացուցիչ_արժեք()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public Ընթացք_արժեք 복제(Ընթացք_արժեք 부모) {
        Ընթացք_արժեք երեխա_արժեք = new Ընթացք_արժեք(
                հատկացնել_նույնացուցիչ(),
                부모.նույնացուցիչ_արժեք(),
                쪽관리.쓰기시복사복제(부모.հասցե_տեղ()),
                부모.파일서술자().복제());
        երեխա_արժեք.프로그램끝설정(부모.프로그램끝());
        Ընթացքների_ցուցակ.put(Integer.valueOf(երեխա_արժեք.նույնացուցիչ_արժեք()), երեխա_արժեք);
        준비대기열.offer(երեխա_արժեք);
        return երեխա_արժեք;
    }

    public Ընթացք_արժեք Հաջորդը_Ընթացք() {
        int 검사수 = 준비대기열.size();
        for (int դասիչ = 0; դասիչ < 검사수; դասիչ++) {
            Ընթացք_արժեք Հաջորդը_միավոր = 준비대기열.poll();
            if (Հաջորդը_միավոր != null && (Հաջորդը_միավոր.վիճակ_արժեք() == Ընթացք_վիճակ.Պատրաստել || Հաջորդը_միավոր.վիճակ_արժեք() == Ընթացք_վիճակ.կատարել_հրաման)) {
                Հաջորդը_միավոր.կազմ_վիճակ(Ընթացք_վիճակ.կատարել_հրաման);
                준비대기열.offer(Հաջորդը_միավոր);
                return Հաջորդը_միավոր;
            }
        }
        return null;
    }

    public int 자식기다리기(Ընթացք_արժեք 부모, int երեխա_նույնացուցիչ, boolean 기다리지않음) {
        for (Ընթացք_արժեք 후보 : Ընթացքների_ցուցակ.values()) {
            if (후보.부모식별자() != 부모.նույնացուցիչ_արժեք()) {
                continue;
            }
            if (երեխա_նույնացուցիչ > 0 && 후보.նույնացուցիչ_արժեք() != երեխա_նույնացուցիչ) {
                continue;
            }
            if (후보.վիճակ_արժեք() == Ընթացք_վիճակ.Ելք_ծրագիր) {
                int չափ = (후보.Ելք_կոդ() & 0xff) << 8;
                Ընթացքների_ցուցակ.remove(Integer.valueOf(후보.նույնացուցիչ_արժեք()));
                return չափ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public Ընթացք_արժեք գտնել_Ընթացք(int նույնացուցիչ_արժեք) {
        return Ընթացքների_ցուցակ.get(Integer.valueOf(նույնացուցիչ_արժեք));
    }

    private int հատկացնել_նույնացուցիչ() {
        return Հաջորդը_նույնացուցիչ++;
    }
}
