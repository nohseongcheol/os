"""свой 커널용 제한형 pip. PyPI의 작은 순수 Python 소스를 узел 중계로 설치한다."""
import sys
import json
import hashlib
import gc
import jkoros as операционная_система

Список_путь = "/lib/.pip.json"


def отпечаток_ЗНАЧЕН(данные):
    return "".join("%02x" % ЗНАЧЕН for ЗНАЧЕН in hashlib.sha256(данные).digest())


def чтение_Список():
    if операционная_система.path_kind(Список_путь) == 0:
        return {}
    return json.loads(операционная_система.read(Список_путь).decode("utf-8"))


def запись_LOG(путь, данные):
    if операционная_система.write(путь, данные) != len(данные):
        raise OSError(28)


def чек_путь(путь):
    if not isinstance(путь, str) or not путь.endswith(".py"):
        raise ValueError("Python 소스만 설치할 수 있습니다.")
    if any(부분 in ("", ".", "..") or 부분.startswith(".") for 부분 in путь.split("/")):
        raise ValueError("허용하지 않는 пакет путь")
    if "\\" in путь or any(ord(знак_ЗНАЧЕН) < 32 or ord(знак_ЗНАЧЕН) == 127 for знак_ЗНАЧЕН in путь):
        raise ValueError("잘못된 путь 문자")
    результат = "/lib/" + путь
    if len(результат.encode("utf-8")) > 63 or путь in ("русский.py", "пакет.py"):
        raise ValueError("пакет 경로가 너무 길거나 значение_по_умолчанию 라이브러리와 겹칩니다.")
    return результат


class получить_поток:
    def __init__(자신, участник):
        자신.участник = участник
        자신.남은자료 = b""
        자신.запустить = операционная_система.ticks_ms()

    def 정확히읽기(자신, длина_ЗНАЧЕН):
        данные = bytearray()
        while len(данные) < длина_ЗНАЧЕН:
            if операционная_система.ticks_ms() - 자신.запустить > 90000:
                raise ValueError("пакет Ретрансляция_ЗНАЧЕН ответ значение_времени 초과")
            if not 자신.남은자료:
                try:
                    자신.남은자료 = операционная_система.tcp_read(자신.участник, 512)
                except OSError as ошибка:
                    if ошибка.args[0] != 11:
                        raise
                    операционная_система.sleep_ms(10)
                    continue
                if not 자신.남은자료:
                    raise ValueError("пакет 전송이 중간에 끝났습니다.")
            товар_СЧЁТ = min(длина_ЗНАЧЕН - len(данные), len(자신.남은자료))
            данные.extend(자신.남은자료[:товар_СЧЁТ])
            자신.남은자료 = 자신.남은자료[товар_СЧЁТ:]
            операционная_система.sleep_ms(0)
        return bytes(данные)


def скачать(запрос, номер_порта):
    if len(запрос) > 96 or any(знак_ЗНАЧЕН not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-=" for знак_ЗНАЧЕН in запрос):
        raise ValueError("사용법: pip install Название 또는 Название==버전")
    участник = операционная_система.tcp_open()
    try:
        запустить = операционная_система.ticks_ms()
        while True:
            try:
                операционная_система.tcp_connect(участник, "10.0.2.2", номер_порта)
                break
            except OSError as ошибка:
                if ошибка.args[0] not in (11, 115) or операционная_система.ticks_ms() - запустить > 5000:
                    raise ValueError("пакет Ретрансляция_ЗНАЧЕН Подключить сбой_ЗНАЧЕН: 호스트에서 --network --pip로 실행하십시오.")
                операционная_система.sleep_ms(10)
        данные = (запрос + "\n").encode()
        while данные:
            try:
                товар_СЧЁТ = операционная_система.tcp_write(участник, данные)
                if not товар_СЧЁТ:
                    raise ValueError("пакет запрос передать_ЗНАЧЕН_630ba093 сбой_ЗНАЧЕН")
                данные = данные[товар_СЧЁТ:]
            except OSError as ошибка:
                if ошибка.args[0] != 11:
                    raise
                операционная_система.sleep_ms(10)
                if операционная_система.ticks_ms() - запустить > 10000:
                    raise ValueError("пакет запрос передать_ЗНАЧЕН_630ba093 значение_времени 초과")
        поток_ЗНАЧЕН = получить_поток(участник)
        HEAD_ЗНАЧЕН = поток_ЗНАЧЕН.정확히읽기(8)
        if HEAD_ЗНАЧЕН[:4] != b"JKP1":
            raise ValueError("пакет передать_ЗНАЧЕН_630ba093 сумма_контракта 불일치")
        длина_ЗНАЧЕН = (HEAD_ЗНАЧЕН[4] << 24) | (HEAD_ЗНАЧЕН[5] << 16) | (HEAD_ЗНАЧЕН[6] << 8) | HEAD_ЗНАЧЕН[7]
        if длина_ЗНАЧЕН > 8192:
            raise ValueError("пакет 명세가 너무 큽니다.")
        спецификация = json.loads(поток_ЗНАЧЕН.정확히읽기(длина_ЗНАЧЕН).decode())
        if "error" in спецификация:
            raise ValueError(спецификация["error"])
        if not 1 <= len(спецификация["files"]) <= 16:
            raise ValueError("꾸러미당 источник_дерево 파일은 1~16개여야 합니다.")
        if sum(ввод_ЗНАЧЕН["size"] for ввод_ЗНАЧЕН in спецификация["files"]) > 65536:
            raise ValueError("пакет источник_дерево 합계는 64 KiB 이하여야 합니다.")
        파일들 = {}
        for ввод_ЗНАЧЕН in спецификация["files"]:
            путь = чек_путь(ввод_ЗНАЧЕН["path"])
            if путь in 파일들 or not 0 <= ввод_ЗНАЧЕН["size"] <= 16384:
                raise ValueError("중복 путь 또는 файл Размер 초과")
            данные = поток_ЗНАЧЕН.정확히읽기(ввод_ЗНАЧЕН["size"])
            if отпечаток_ЗНАЧЕН(данные) != ввод_ЗНАЧЕН["sha256"]:
                raise ValueError("пакет файл SHA-256 불일치")
            # 실행하지 않고 текущий_товар MicroPython의 문법으로 먼저 검사한다.
            compile(данные.decode("utf-8"), путь, "exec")
            파일들[путь] = данные
            gc.collect()
        return спецификация, 파일들
    finally:
        операционная_система.udp_close(участник)


def установить_ЗНАЧЕН(запрос, номер_порта):
    print("пакет скачать:", запрос)
    спецификация, 파일들 = скачать(запрос, номер_порта)
    ввод_Список = чтение_Список()
    Название = спецификация["name"]
    if Название in ввод_Список:
        if ввод_Список[Название]["version"] == спецификация["version"]:
            for путь, отпечаток_данные in ввод_Список[Название]["files"].items():
                if операционная_система.path_kind(путь) != 1 or отпечаток_ЗНАЧЕН(операционная_система.read(путь)) != отпечаток_данные:
                    raise ValueError("설치된 пакет 파일이 달라졌습니다: " + путь)
            print("이미 설치됨:", Название, спецификация["version"])
            return
        raise ValueError("다른 버전이 있습니다. pip uninstall로 제거한 BACK_ЗНАЧЕН 설치하십시오.")
    for путь in 파일들:
        if операционная_система.path_kind(путь):
            raise ValueError("기존 파일을 덮어쓰지 않습니다: " + путь)
    ввод_Список[Название] = {"version": спецификация["version"], "files": {путь: отпечаток_ЗНАЧЕН(данные) for путь, данные in 파일들.items()}}
    새목록 = json.dumps(ввод_Список).encode()
    if len(새목록) > 16384:
        raise ValueError("пакет ввод_Список Размер 초과")
    Назад_Список = операционная_система.read(Список_путь) if операционная_система.path_kind(Список_путь) else None
    만든파일 = []
    만든폴더 = []
    try:
        for путь, данные in 파일들.items():
            부분들 = путь.split("/")
            for 수 in range(2, len(부분들)):
                Каталог_ЗНАЧЕН = "/".join(부분들[:수])
                Вид_ЗНАЧЕН = операционная_система.path_kind(Каталог_ЗНАЧЕН)
                if Вид_ЗНАЧЕН == 0:
                    операционная_система.mkdir(Каталог_ЗНАЧЕН)
                    만든폴더.append(Каталог_ЗНАЧЕН)
                elif Вид_ЗНАЧЕН != 2:
                    raise ValueError("Каталог_ЗНАЧЕН 경로에 파일이 있습니다: " + Каталог_ЗНАЧЕН)
            만든파일.append(путь)
            запись_LOG(путь, данные)
        запись_LOG(Список_путь, 새목록)
    except Exception:
        for путь in 만든파일:
            if операционная_система.path_kind(путь):
                операционная_система.remove(путь)
        for Каталог_ЗНАЧЕН in reversed(만든폴더):
            операционная_система.rmdir(Каталог_ЗНАЧЕН)
        if Назад_Список is not None:
            запись_LOG(Список_путь, Назад_Список)
        elif операционная_система.path_kind(Список_путь):
            операционная_система.remove(Список_путь)
        raise
    print("установить_ЗНАЧЕН 완료:", Название, спецификация["version"], "→ /lib (RAM)")


def удалить_ввод(Название):
    ввод_Список = чтение_Список()
    if Название not in ввод_Список:
        raise ValueError("설치되지 않은 꾸러미입니다: " + Название)
    for путь, отпечаток_данные in ввод_Список[Название]["files"].items():
        if операционная_система.path_kind(путь) != 1 or отпечаток_ЗНАЧЕН(операционная_система.read(путь)) != отпечаток_данные:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + путь)
    for путь in ввод_Список[Название]["files"]:
        операционная_система.remove(путь)
    del ввод_Список[Название]
    запись_LOG(Список_путь, json.dumps(ввод_Список).encode())
    print("удалить_ввод 완료:", Название)


def запустить(аргументы):
    номер_порта = 8027
    if len(аргументы) >= 2 and аргументы[-2] == "--port":
        номер_порта = int(аргументы[-1])
        аргументы = аргументы[:-2]
    if аргументы == ["list"]:
        for Название, msinfo32_exe in чтение_Список().items():
            print(Название, msinfo32_exe["version"])
    elif len(аргументы) == 2 and аргументы[0] == "install":
        установить_ЗНАЧЕН(аргументы[1], номер_порта)
    elif len(аргументы) == 2 and аргументы[0] == "uninstall":
        удалить_ввод(аргументы[1])
    elif not аргументы or аргументы in (["--help"], ["--version"]):
        print("jkoros pip 1 / MicroPython источник_дерево 설치기 (PyPA pip 전체가 아님)")
        print("pip install Название[==버전] [--port 8027] | pip list | pip uninstall Название")
        print("узел: инструменты/실행.py --network --pip; /lib는 재부팅 때 사라지는 RAM입니다.")
    else:
        raise ValueError("pip --help로 사용법을 확인하십시오.")


if __name__ == "__main__":
    try:
        запустить(sys.argv[1:])
    except Exception as ошибка:
        print("пакет ошибка:", ошибка)
        sys.exit(1)
