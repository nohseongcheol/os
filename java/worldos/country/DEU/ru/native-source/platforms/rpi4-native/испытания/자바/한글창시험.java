import русский.свой.Окно;
import русский.свой.элемент_экрана;
import русский.свой.*;

public class 한글창시험 implements 실행할일, 동작받이 {
    Окно экран;
    Метка файл_сведений_eb81d7d9;
    текстовое_поле входные_данные_ЗНАЧЕН;
    public void Выполнить() {
        검사.참인지(Событие_Очередь.사건처리중인가(), "русский экран 작업 큐");
        экран = new Окно("русский библиотека Окно", 400, 280);
        файл_сведений_eb81d7d9 = элемент_экрана.тег_ЗНАЧЕН("한글로 Java 코딩", 20, 20, 340, 30);
        входные_данные_ЗНАЧЕН = элемент_экрана.текстовое_поле("Название", 20, 65, 340, 30);
        экран.добавить_элемент(файл_сведений_eb81d7d9);
        экран.добавить_элемент(входные_данные_ЗНАЧЕН);
        экран.добавить_элемент(элемент_экрана.кнопка("인사하기", 20, 110, 180, 32, this));
        экран.выпуск_окно();
        текстовыйВывод.запись_линия("KOREAN SWING READY");
    }
    public void получить_задача(задача_уведомление Событие) {
        검사.참인지(Событие_Очередь.사건처리중인가(), "русский Действие 되부름");
        검사.참인지(Событие.ИНДЕКС() == 1001 && Событие.источник_события() instanceof кнопка, "русский Событие 객체와 origin_ЗНАЧЕН");
        검사.참인지(!((Object)Событие.источник_события() instanceof javax.swing.JButton), "표준 단추와 독립된 формат_ЗНАЧЕН");
        검사.참인지(!((Object)Событие instanceof java.awt.event.ActionEvent), "표준 사건과 독립된 формат_ЗНАЧЕН");
        файл_сведений_eb81d7d9.запись_SMS("안녕하세요 " + входные_данные_ЗНАЧЕН.чтение_SMS());
        текстовыйВывод.запись_линия("KOREAN SWING CLICK " + входные_данные_ЗНАЧЕН.чтение_SMS());
    }
    public static void main(String[] аргументы) {
        Событие_Очередь.나중에실행(new 한글창시험());
    }
}
