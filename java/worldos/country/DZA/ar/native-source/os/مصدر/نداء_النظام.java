/** int 0x80 게이트가 호출한다. 모든 فضاء_المستخدم مؤشر/길이는 يصل_إدخال 전에 검사한다. */
public final class نداء_النظام {
    static int[] 임시자료 = new int[1024];

    static int 배열길이(int عنوان) {
        if (!실행관리.يقص(عنوان, 4)) return -14;
        int 길이 = 실행관리.رقم(عنوان);
        if (길이 < 0 || 길이 > (실행관리.مستخدم_إنهاء_مكالمة - عنوان - 4) / 4) return -14;
        return 길이;
    }

    public static int عملية_قيمة_إدخال(int فهرس, int 가, int 나, int 다, int 라, int 마) {
        if (فهرس == 30) return 파일서술자관리.فتح_ملف(가, 나, 다);
        if (فهرس == 31) return 파일서술자관리.يقرأ_ملف(가, 나, 다);
        if (فهرس == 32) return 파일서술자관리.كتابة_ملف(가, 나, 다);
        if (فهرس == 33) return 파일서술자관리.يغلق_ملف(가);
        if (فهرس == 34) return 파일서술자관리.يبحث_ملف(가, 나, 다);
        if (فهرس == 35) return 파일서술자관리.서술자복제(가, 0, false, 0);
        if (فهرس == 36) return 파일서술자관리.서술자복제(가, 나, true, 0);
        if (فهرس == 37) return 파일서술자관리.يقرأ_ملف_توفر(가, 나);
        if (فهرس == 38) return 파일서술자관리.يزيل_ملف_إدخال_اسم(가);
        if (فهرس == 39) return 파일서술자관리.파일길이정하기(가, 나);
        if (فهرس == 40) return 파일서술자관리.서술자제어(가, 나, 다);
        if (فهرس == 41) return 파일서술자관리.فتح_المشارك(가, 나, 다);
        if (فهرس == 42) return 파일서술자관리.يربط_عنوان(가, 나, 다);
        if (فهرس == 43) return 파일서술자관리.يرسل_مخطط_بيانات_بيانات(가, 나, 다, 라, 마);
        if (فهرس == 44) return 파일서술자관리.يستلم_مخطط_بيانات_بيانات(가, 나, 다, 라, 마);
        if (فهرس == 45) return 파일서술자관리.يقرأ_مأخذ_التوصيل_عنوان(가, 나, 다);
        if (فهرس == 46) return 파일서술자관리.수신대기정하기(가, 나);
        if (فهرس == 47) {
            int 기술 = 파일서술자관리.기술찾기(가);
            if (기술 < 0) return -9;
            if (파일서술자관리.종류[기술] != 2) return -22;
            return 파일보존.تزامن();
        }
        if (فهرس == 1) {
            int 길이 = 배열길이(가);
            if (길이 < 0) return 길이;
            if (길이 > 4096) return -90;
            for (int حرف_قيمة = 0; حرف_قيمة < 길이; حرف_قيمة++) نص_الوحدة_الطرفية.문자(실행관리.رقم(가 + 4 + حرف_قيمة * 4) & 65535);
            return 길이;
        }
        if (فهرس == 2) return 실행관리.인수수;
        if (فهرس == 3) return 가 >= 0 && 가 < 실행관리.인수수 ? 실행관리.وسيطة_عنوان[가] : 0;
        if (فهرس == 10) return شبكة_رمز.فتح(가);
        if (فهرس == 11) {
            int 길이 = 배열길이(라);
            if (길이 < 0) return 길이;
            if (마 < 0 || 마 > 길이 || 마 > 1024) return -90;
            for (int موضع = 0; موضع < 마; موضع++) 임시자료[موضع] = 실행관리.رقم(라 + 4 + موضع * 4) & 255;
            return شبكة_رمز.يرسل(가, 나, 다, 임시자료, 마);
        }
        if (فهرس == 12) {
            int 길이 = 배열길이(나);
            if (길이 < 0) return 길이;
            if (다 < 0 || 다 > 2000) return -22;
            int نتيجة = شبكة_رمز.يستلم(가, 임시자료, 길이 < 1024 ? 길이 : 1024, 다);
            if (نتيجة >= 0) for (int موضع = 0; موضع < نتيجة; موضع++) 실행관리.كتابة_رقم(나 + 4 + موضع * 4, 임시자료[موضع]);
            return نتيجة;
        }
        if (فهرس == 13) return شبكة_رمز.إغلاق(가);
        if (فهرس == 14) return شبكة_رمز.내주소;
        if (فهرس == 15) return شبكة_رمز.نظير_عنوان(가);
        if (فهرس == 16) return شبكة_رمز.نظير_رقم_المنفذ(가);
        if (فهرس == 22) {
            if (가 < 0 || 가 > 65535) return -22;
            نص_الوحدة_الطرفية.문자(가); return 1;
        }
        if (فهرس == 20 || فهرس == 21) {
            int اسم_يغير_الحجم = 배열길이(가), بيانات_يغير_الحجم = 배열길이(나);
            if (اسم_يغير_الحجم < 0 || بيانات_يغير_الحجم < 0) return -14;
            if (اسم_يغير_الحجم < 1 || اسم_يغير_الحجم > 64) return -22;
            int 길이 = 0;
            while (길이 < اسم_يغير_الحجم && 실행관리.رقم(가 + 4 + 길이 * 4) != 0) {
                ذاكرة_نظام_الملفات.اسم[길이] = 실행관리.رقم(가 + 4 + 길이 * 4);
                길이++;
            }
            if (!ذاكرة_نظام_الملفات.شيك_اسم(ذاكرة_نظام_الملفات.اسم, 길이)) return -22;
            if (فهرس == 20) {
                int ملف = ذاكرة_نظام_الملفات.بحث_إدخال(ذاكرة_نظام_الملفات.اسم, 길이);
                if (ملف < 0) return ملف;
                int حجم = ذاكرة_نظام_الملفات.يغير_الحجم_قائمة[ملف];
                if (حجم > بيانات_يغير_الحجم) return -90;
                int عنوان = جهاز_قيمة.ملف_ذاكرة() + ملف * ذاكرة_نظام_الملفات.최대크기;
                for (int رقم = 0; رقم < حجم; رقم++) 실행관리.كتابة_رقم(나 + 4 + رقم * 4, جهاز_قيمة.يقرأ_ذاكرة(عنوان + رقم));
                return حجم;
            }
            if (다 < 0 || 다 > بيانات_يغير_الحجم) return -22;
            if (다 > ذاكرة_نظام_الملفات.최대크기) return -90;
            for (int رقم = 0; رقم < 다; رقم++) ذاكرة_نظام_الملفات.يحرر_قيمة[رقم] = 실행관리.رقم(나 + 4 + رقم * 4) & 255;
            return ذاكرة_نظام_الملفات.مخزن_قيمة(ذاكرة_نظام_الملفات.اسم, 길이, ذاكرة_نظام_الملفات.يحرر_قيمة, 다);
        }
        return -38;
    }
}
