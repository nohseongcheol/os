from العربية import مخرجات, فتح_مخطط_بيانات, يرسل_خارجي_مخطط_بيانات, يستلم_مخطط_بيانات, يغلق_شبكة, 밀리초
from العربية import فشل_النظام, 다시시도오류, يرمّز_نص, 명령인수, عدد_صحيح
المشارك = فتح_مخطط_بيانات(0)
try:
    رزمةمستقلة = يرمّز_نص("PYTHON UDP العربية")
    يرسل_خارجي_مخطط_بيانات(المشارك, "10.0.2.2", عدد_صحيح(명령인수[1]), رزمةمستقلة)
    تشغيل = 밀리초()
    while True:
        try:
            رد, منفذ_قيمة = يستلم_مخطط_بيانات(المشارك)
            break
        except فشل_النظام as خطأ:
            if خطأ.فهرس != 다시시도오류 or 밀리초() - تشغيل >= 700:
                raise
    assert رد == رزمةمستقلة
    مخرجات("PYTHON 네트워크 يتحقق: UDP العربية")
finally:
    يغلق_شبكة(المشارك)
