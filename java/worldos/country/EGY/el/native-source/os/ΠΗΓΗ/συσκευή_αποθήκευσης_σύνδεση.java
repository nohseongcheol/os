/** 첫 IDE 장치의 512바이트 논리 ενότητα_τιμή. 이 계층은 포맷을 만들거나 임의 장치를 지우지 않는다. */
public final class συσκευή_αποθήκευσης_σύνδεση {
    static boolean πληροφοριακά_συστήματα_Ενεργός_ή = false;
    static int[] ενότητα_δεδομένα = new int[512];
    static void 잠깐기다리기() {
        for (int Ευρετήριο = 0; Ευρετήριο < 4; Ευρετήριο++) συσκευή_τιμή.입출력바이트읽기(0x3f6);
    }
    static int 준비기다리기(boolean 자료필요) {
        int Εκτέλεση_2 = συσκευή_τιμή.밀리초();
        while (συσκευή_τιμή.밀리초() - Εκτέλεση_2 < 500) {
            int Κατάσταση_τιμή = συσκευή_τιμή.입출력바이트읽기(0x1f7);
            if (Κατάσταση_τιμή == 0 || Κατάσταση_τιμή == 255) return -19;
            if ((Κατάσταση_τιμή & 128) == 0) {
                if ((Κατάσταση_τιμή & 33) != 0) return -5;
                if (!자료필요 || (Κατάσταση_τιμή & 8) != 0) return 0;
            }
            συσκευή_τιμή.잠시양보();
        }
        return -110;
    }
    static int αίτηση(int ενότητα_τιμή, int Εντολή) {
        if (ενότητα_τιμή < 0 || ενότητα_τιμή >= 2048) return -22;
        συσκευή_τιμή.입출력바이트쓰기(0x3f6, 2); // polling; IDE IRQ χρήση_τιμή 안 함
        συσκευή_τιμή.입출력바이트쓰기(0x1f6, 0xe0); 잠깐기다리기();
        int μέτρηση = 준비기다리기(false);
        if (μέτρηση < 0) return μέτρηση;
        συσκευή_τιμή.입출력바이트쓰기(0x1f2, 1);
        συσκευή_τιμή.입출력바이트쓰기(0x1f3, ενότητα_τιμή & 255);
        συσκευή_τιμή.입출력바이트쓰기(0x1f4, (ενότητα_τιμή >>> 8) & 255);
        συσκευή_τιμή.입출력바이트쓰기(0x1f5, 0);
        συσκευή_τιμή.입출력바이트쓰기(0x1f7, Εντολή); 잠깐기다리기();
        return 준비기다리기(true);
    }
    static int Ανάγνωση(int ενότητα_τιμή) {
        int μέτρηση = αίτηση(ενότητα_τιμή, 0x20);
        if (μέτρηση < 0) return μέτρηση;
        for (int Ευρετήριο = 0; Ευρετήριο < 256; Ευρετήριο++) {
            int τιμή = συσκευή_τιμή.입출력짧은수읽기(0x1f0);
            ενότητα_δεδομένα[Ευρετήριο * 2] = τιμή & 255; ενότητα_δεδομένα[Ευρετήριο * 2 + 1] = τιμή >>> 8;
        }
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int Εγγραφή(int ενότητα_τιμή) {
        if (!πληροφοριακά_συστήματα_Ενεργός_ή || ενότητα_τιμή < 1 || ενότητα_τιμή > 518) return -19;
        int μέτρηση = αίτηση(ενότητα_τιμή, 0x30);
        if (μέτρηση < 0) return μέτρηση;
        for (int Ευρετήριο = 0; Ευρετήριο < 256; Ευρετήριο++)
            συσκευή_τιμή.입출력짧은수쓰기(0x1f0, ενότητα_δεδομένα[Ευρετήριο * 2] | ενότητα_δεδομένα[Ευρετήριο * 2 + 1] << 8);
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int 밀어쓰기() {
        if (!πληροφοριακά_συστήματα_Ενεργός_ή) return -19;
        συσκευή_τιμή.입출력바이트쓰기(0x1f7, 0xe7); 잠깐기다리기();
        return 준비기다리기(false);
    }
    static int ανάλυση_ακέραιος(int Θέση) {
        return ενότητα_δεδομένα[Θέση] | ενότητα_δεδομένα[Θέση + 1] << 8 | ενότητα_δεδομένα[Θέση + 2] << 16 | ενότητα_δεδομένα[Θέση + 3] << 24;
    }
    static void εγγράφω_ακέραιος_τιμή(int Θέση, int τιμή) {
        for (int Ευρετήριο = 0; Ευρετήριο < 4; Ευρετήριο++) ενότητα_δεδομένα[Θέση + Ευρετήριο] = (τιμή >>> (Ευρετήριο * 8)) & 255;
    }
}
