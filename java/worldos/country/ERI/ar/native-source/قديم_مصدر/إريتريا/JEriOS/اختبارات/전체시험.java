    private static void يختبر_ذاكرة(نواة نواة_قيمة) {
        ذاكرة_مدير مدير_قيمة = نواة_قيمة.ذاكرة_منطقة();
        int 첫주소 = مدير_قيمة.정렬할당(100, 64);
        يتحقق((첫주소 & 63) == 0, "يحاذي_قيمة يخصص_تخزين");
        مدير_قيمة.كتابة_بايت_قيمة(첫주소, (byte) 0x5a);
        يتحقق(مدير_قيمة.يقرأ_بايت_قيمة(첫주소) == (byte) 0x5a, "물리 ذاكرة_منطقة 읽고 كتابة");
        int 사용전 = مدير_قيمة.사용크기();
        مدير_قيمة.إصدار_تخزين(첫주소);
        يتحقق(مدير_قيمة.사용크기() < 사용전, "ذاكرة_منطقة إصدار_تخزين");
    }

    private static void 쪽관리시험(نواة نواة_قيمة) {
        صفحة_مدير مدير_قيمة = نواة_قيمة.쪽관리();
        صفحة_مدير.عنوان_مساحة أصل_مساحة = مدير_قيمة.새주소공간();
        مدير_قيمة.مخطط_صفحة(أصل_مساحة, 0x1000, true);
        مدير_قيمة.كتابة_بايت_قيمة(أصل_مساحة, 0x1010, (byte) 7);
        صفحة_مدير.عنوان_مساحة طفل_مساحة = مدير_قيمة.نسخة_نسخ_الكتابة(أصل_مساحة);
        مدير_قيمة.كتابة_بايت_قيمة(طفل_مساحة, 0x1010, (byte) 9);
        يتحقق(مدير_قيمة.يقرأ_بايت_قيمة(أصل_مساحة, 0x1010) == 7, "كتابة 시 مثيل_قيمة أصل_قيمة 격리");
        يتحقق(مدير_قيمة.يقرأ_بايت_قيمة(طفل_مساحة, 0x1010) == 9, "كتابة 시 مثيل_قيمة طفل_قيمة كتابة");
    }

    private static void 파일과과정시험(نواة نواة_قيمة) {
        byte[] محتوى_قيمة = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        نواة_قيمة.نظام_الملفات().إلحاق_ملف("اختبارات", محتوى_قيمة);
        عملية_قيمة أصل_قيمة = نواة_قيمة.첫과정();
        نداء_النظام 호출 = نواة_قيمة.نداء_النظام();
        int 서술자 = 호출.فتح(أصل_قيمة, "/اختبارات", نداء_النظام.للقراءة_فقط_إشارة);
        يتحقق(서술자 >= 3, "ملف فتح");

        byte[] يستلم_وجهة = new byte[محتوى_قيمة.length];
        يتحقق(호출.قراءة(أصل_قيمة, 서술자, يستلم_وجهة, يستلم_وجهة.length) == محتوى_قيمة.length, "ملف قراءة");
        يتحقق(Arrays.equals(محتوى_قيمة, يستلم_وجهة), "ملف محتوى_قيمة");
        يتحقق(호출.نقل_منصب(أصل_قيمة, 서술자, 0, نداء_النظام.بحث_بدء) == 0, "ملف موضع نقل_قيمة");

        int 복제서술자 = 호출.서술자복제(أصل_قيمة, 서술자);
        يتحقق(복제서술자 >= 0, "서술자 نسخة_قيمة");
        عملية_قيمة طفل_قيمة = 호출.نسخة_عملية(أصل_قيمة);
        يتحقق(طفل_قيمة.معرف_قيمة() != أصل_قيمة.معرف_قيمة(), "عملية_قيمة معرف_قيمة 분리");
        يتحقق(طفل_قيمة.أصل_معرف() == أصل_قيمة.معرف_قيمة(), "أصل_قيمة عملية_قيمة معرف_قيمة");
        يتحقق(호출.إغلاق(طفل_قيمة, 서술자) == 0 && أصل_قيمة.파일서술자().أنظمة_المعلومات_فتح(서술자), "طفل_قيمة إغلاق 격리");

        int 이전끝 = 호출.프로그램끝늘리기(أصل_قيمة, 8192);
        يتحقق(이전끝 == 0x06000000, "تطبيق_f5044b9b 끝 늘리기");
        يتحقق(أصل_قيمة.تطبيق_توقف() == 0x06002000, "تطبيق_f5044b9b 끝 반영");
        يتحقق(طفل_قيمة.تطبيق_توقف() == 0x06000000, "과정별 تطبيق_f5044b9b 끝 격리");

        طفل_قيمة.خروج_تطبيق(7);
        يتحقق(호출.자식기다리기(أصل_قيمة, طفل_قيمة.معرف_قيمة(), false) == (7 << 8), "طفل_قيمة خروج_تطبيق 기다리기");
        يتحقق(호출.접근가능("اختبارات", 1) == -13, "ينفذ_أمر إذن_قيمة يرفض_قيمة");
        يتحقق(호출.معرف_المستخدم() == 0 && 호출.يجمع_معرف() == 0, "사용자와 무리 معرف_قيمة");
        يتحقق("/".equals(호출.حديث_قائمة_المهام(2)) && 호출.تبديل_قائمة_المهام("/") == 0, "حديث_عنصر 작업 إدخال_قائمة_f07b3200");
        يتحقق(호출.أنظمة_المعلومات_الوحدة_الطرفية(أصل_قيمة, 1), "표준 مخرجات 단말");
        يتحقق("JEriOS".equals(호출.نظام_التفاصيل().نظام_اسم()), "نظام_تشغيل_قيمة معلومات_النظام");
    }

