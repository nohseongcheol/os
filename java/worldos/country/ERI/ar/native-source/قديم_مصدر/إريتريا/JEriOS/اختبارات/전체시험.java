    private static void كتابة_عدد_صحيح_قيمة(byte[] بيانات, int موضع, int قيمة) {
        بيانات[موضع] = (byte) قيمة;
        بيانات[موضع + 1] = (byte) (قيمة >>> 8);
        بيانات[موضع + 2] = (byte) (قيمة >>> 16);
        بيانات[موضع + 3] = (byte) (قيمة >>> 24);
    }

    private static void 짧은정수쓰기(byte[] بيانات, int موضع, int قيمة) {
        بيانات[موضع] = (byte) قيمة;
        بيانات[موضع + 1] = (byte) (قيمة >>> 8);
    }

