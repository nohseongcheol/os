import ትግርኛ.자체.መስኮት;
import ትግርኛ.자체.ገላጺ;
import ትግርኛ.자체.ጽሑፍ_ሜዳ;
import ትግርኛ.자체.መጠወቒ;
import ትግርኛ.자체.ፍጻመ_ሪጋ;
import ትግርኛ.자체.출력;
import ትግርኛ.자체.실행할일;
import ትግርኛ.자체.동작받이;
import ትግርኛ.자체.동작알림;

/** 자체 커널의 Swing መስኮት: ትግርኛ 입력 → መጠወቒ → ኣንብበኒ_eb81d7d9 ጽሑፍ ኣሐድስ. */
public class 창예제 implements 실행할일, 동작받이 {
    private መስኮት 인사창;
    private ጽሑፍ_ሜዳ ሽም_ሜዳ;
    private ገላጺ 인사말;
    private int 인사횟수;

    public void ክፈት_መስኮት() {
        인사창 = new መስኮት("ትግርኛ Swing", 460, 300);
        인사창.ወስኽ_ንጥረ_ነገር(new ገላጺ("ሰላም", 20, 20, 420, 28));
        ሽም_ሜዳ = new ጽሑፍ_ሜዳ("ትግርኛ", 20, 64, 420, 30);
        인사말 = new ገላጺ("ሰላም", 20, 152, 420, 28);
        인사창.ወስኽ_ንጥረ_ነገር(ሽም_ሜዳ);
        인사창.ወስኽ_ንጥረ_ነገር(new መጠወቒ("인사하기", 20, 108, 180, 32, this));
        인사창.ወስኽ_ንጥረ_ነገር(인사말);
        인사창.ወስኽ_ንጥረ_ነገር(new ገላጺ("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.ኣርእይ_መስኮት();
        출력.ጸሓፍ_መስመር("GUI 예제 ኣዳልው: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.ጸሓፍ_ጽሑፍ("ሰላም, " + ሽም_ሜዳ.글읽기() + "님! (" + 인사횟수 + ")");
        출력.ጸሓፍ_መስመር("GUI 인사: " + 인사말.글읽기());
    }

    public void ተግብር_ዕማም() { ክፈት_መስኮት(); }
    public void 동작받기(동작알림 알림) {
        출력.ጸሓፍ_መስመር("ስጉምቲ 알림: " + 알림.ትእዛዝ_ጽሑፍ());
        인사하기();
    }
    public static void ኣኺድ() {
        ፍጻመ_ሪጋ.나중에실행(new 창예제());
    }
}
