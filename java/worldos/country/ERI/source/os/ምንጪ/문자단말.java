/** COM1 직렬 출력과 VGA 80x25 문자 화면. 한글은 직렬 단말에 UTF-8로 출력한다. */
public final class 문자단말 {
    static int መሰኩዒ_ምእታው = 0;
    static int 색 = 7;

    static void ኣዳልው() {
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3f9, 0);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3fb, 0x80);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3f8, 1);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3f9, 0);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3fb, 3);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3fa, 0xc7);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3fc, 0x0b);
        지우기();
    }

    static void 직렬바이트(int ዋጋ) {
        int 횟수 = 100000;
        while ((መሳርሒ_ዋጋ.입출력바이트읽기(0x3fd) & 0x20) == 0 && 횟수 > 0) 횟수--;
        if (횟수 > 0) መሳርሒ_ዋጋ.입출력바이트쓰기(0x3f8, ዋጋ);
    }

    static void 지우기() {
        for (int መሐበሪ = 0; መሐበሪ < 2000; መሐበሪ++) {
            መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(0xb8000 + መሐበሪ * 2, 32);
            መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(0xb8001 + መሐበሪ * 2, 색);
        }
        መሰኩዒ_ምእታው = 0;
        ኣመልካቲ_ዋጋ();
    }

    static void ኣመልካቲ_ዋጋ() {
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3d4, 14);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3d5, መሰኩዒ_ምእታው >> 8);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3d4, 15);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3d5, መሰኩዒ_ምእታው & 255);
    }

    static void 화면문자(int ዋጋ) {
        if (ዋጋ == 13) return;
        if (ዋጋ == 10) {
            መሰኩዒ_ምእታው = (መሰኩዒ_ምእታው / 80 + 1) * 80;
        } else if (ዋጋ == 8) {
            if (መሰኩዒ_ምእታው > 0) {
                መሰኩዒ_ምእታው--;
                መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(0xb8000 + መሰኩዒ_ምእታው * 2, 32);
            }
        } else {
            መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(0xb8000 + መሰኩዒ_ምእታው * 2, ዋጋ < 128 ? ዋጋ : '?');
            መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(0xb8001 + መሰኩዒ_ምእታው * 2, 색);
            መሰኩዒ_ምእታው++;
        }
        if (መሰኩዒ_ምእታው >= 2000) {
            for (int መሐበሪ = 0; መሐበሪ < 3840; መሐበሪ++)
                መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(0xb8000 + መሐበሪ, መሳርሒ_ዋጋ.기억읽기(0xb80a0 + መሐበሪ));
            for (int መሐበሪ = 1920; መሐበሪ < 2000; መሐበሪ++) {
                መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(0xb8000 + መሐበሪ * 2, 32);
                መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(0xb8001 + መሐበሪ * 2, 색);
            }
            መሰኩዒ_ምእታው = 1920;
        }
        ኣመልካቲ_ዋጋ();
    }

    static void 문자(int ዋጋ) {
        if (ዋጋ < 128) {
            if (ዋጋ == 10) 직렬바이트(13);
            직렬바이트(ዋጋ);
        } else if (ዋጋ < 2048) {
            직렬바이트(0xc0 | (ዋጋ >> 6));
            직렬바이트(0x80 | (ዋጋ & 63));
        } else {
            직렬바이트(0xe0 | (ዋጋ >> 12));
            직렬바이트(0x80 | ((ዋጋ >> 6) & 63));
            직렬바이트(0x80 | (ዋጋ & 63));
        }
        화면문자(ዋጋ);
    }

    static void ጸሓፍ(String ትሕዝቶ_ዋጋ) {
        for (int መሐበሪ = 0; መሐበሪ < ትሕዝቶ_ዋጋ.length(); መሐበሪ++) 문자(ትሕዝቶ_ዋጋ.charAt(መሐበሪ));
    }

    static void 수쓰기(int ዋጋ) {
        // 양수로 바꾸지 않으므로 Integer.MIN_VALUE도 안전하다.
        if (ዋጋ < 0) 문자('-');
        else ዋጋ = -ዋጋ;
        int 자리 = 1000000000;
        boolean ኣኺድ = false;
        while (자리 > 0) {
            int ኣሃዝ_ዋጋ = -(ዋጋ / 자리);
            if (ኣሃዝ_ዋጋ != 0 || ኣኺድ || 자리 == 1) {
                문자('0' + ኣሃዝ_ዋጋ);
                ኣኺድ = true;
            }
            ዋጋ %= 자리;
            자리 /= 10;
        }
    }

    static int 직렬읽기() {
        if ((መሳርሒ_ዋጋ.입출력바이트읽기(0x3fd) & 1) != 0) return መሳርሒ_ዋጋ.입출력바이트읽기(0x3f8);
        return -1;
    }
}
