/** 화면 ቁረጽ_ዋጋ·띠 합성·ኣመልካቲ 밑그림을 관리한다. ትኽክለኛ_ሓበሬታ 화면 ማህደር_ዝኽረት_ሓበሬታ 접근은 보드가 담당한다. */
public final class 화면합성 {
    static int 너비, 높이, 합성중, 왼경계, 위경계, 오른경계, 아래경계;
    static int 포인터가로, 포인터세로, ኣመልካቲ_ቅርጺ;
    static int 기록아래낱말, 기록위낱말;
    static int[] 완성그림 = new int[32 * 1920];
    static int[] ኣመልካቲ_ድሕረባይታ = new int[21 * 21];
    static int[] 잘린범위 = new int[4];
    public static void ኣዳልው(int 폭, int ንውሓት_ዋጋ) {
        너비 = 폭; 높이 = ንውሓት_ዋጋ; 합성중 = 0; ኣመልካቲ_ቅርጺ = 0;
        기록아래낱말 = 0; 기록위낱말 = 0;
    }
    public static int 너비얻기() { return 너비; }
    public static int 높이얻기() { return 높이; }
    public static int 기록아래얻기() { return 기록아래낱말; }
    public static int 기록위얻기() { return 기록위낱말; }
    public static int ቅንጣብ_ዋጋ(int 순번) { return 잘린범위[순번]; }
    static int 양의길이더하기(int ጀምር_ዋጋ, int ንውሓት_ዋጋ) {
        if (ጀምር_ዋጋ > 2147483647 - ንውሓት_ዋጋ) return 2147483647;
        return ጀምር_ዋጋ + ንውሓት_ዋጋ;
    }
    public static int ቅንጣብ(int 가로, int 세로, int 폭, int ንውሓት_ዋጋ) {
        if (너비 == 0 || 폭 <= 0 || ንውሓት_ዋጋ <= 0) return 0;
        int 오른쪽 = 양의길이더하기(가로, 폭), 아래쪽 = 양의길이더하기(세로, ንውሓት_ዋጋ);
        int 왼쪽 = 합성중 != 0 ? 왼경계 : 0, 위쪽 = 합성중 != 0 ? 위경계 : 0;
        int 최대가로 = 합성중 != 0 ? 오른경계 : 너비, 최대세로 = 합성중 != 0 ? 아래경계 : 높이;
        if (가로 < 왼쪽) 가로 = 왼쪽;
        if (세로 < 위쪽) 세로 = 위쪽;
        if (오른쪽 > 최대가로) 오른쪽 = 최대가로;
        if (아래쪽 > 최대세로) 아래쪽 = 최대세로;
        if (오른쪽 <= 가로 || 아래쪽 <= 세로) return 0;
        잘린범위[0] = 가로; 잘린범위[1] = 세로;
        잘린범위[2] = 오른쪽 - 가로; 잘린범위[3] = 아래쪽 - 세로;
        return 1;
    }
    public static int ኣኺድ(int 가로, int 세로, int 폭, int ንውሓት_ዋጋ) {
        if (합성중 != 0 || ንውሓት_ዋጋ > 32 || ቅንጣብ(가로, 세로, 폭, ንውሓት_ዋጋ) == 0) return 0;
        왼경계 = 잘린범위[0]; 위경계 = 잘린범위[1];
        오른경계 = 왼경계 + 잘린범위[2]; 아래경계 = 위경계 + 잘린범위[3];
        합성중 = 1; return 1;
    }
    static boolean ኣመልካቲ_ቢት(int 가로, int 세로, int ቅርጺ_ዋጋ) {
        if (ቅርጺ_ዋጋ == 1) return 가로 >= 0 && 가로 <= 세로 / 2 && 세로 < 16;
        if (ቅርጺ_ዋጋ == 3) 가로 = 20 - 가로;
        int 차이 = 가로 - 세로; if (차이 < 0) 차이 = -차이;
        return (차이 <= 1 && 가로 >= 3 && 가로 <= 17) ||
            (가로 >= 2 && 가로 <= 8 && 세로 >= 2 && 세로 <= 8 && (가로 <= 3 || 세로 <= 3)) ||
            (가로 >= 12 && 가로 <= 18 && 세로 >= 12 && 세로 <= 18 && (가로 >= 17 || 세로 >= 17));
    }
    static int ኣመልካቲ_ንጣብ(int 가로, int 세로) {
        if (ኣመልካቲ_ቢት(가로, 세로, ኣመልካቲ_ቅርጺ)) return 2;
        for (int መስመር = -1; መስመር <= 1; መስመር++) for (int መሰኩዒ_ምእታው = -1; መሰኩዒ_ምእታው <= 1; መሰኩዒ_ምእታው++)
            if (ኣመልካቲ_ቢት(가로 + መሰኩዒ_ምእታው, 세로 + መስመር, ኣመልካቲ_ቅርጺ)) return 1;
        return 0;
    }
    static void መርኣዪ_ንጣብ(int 가로, int 세로, int 색) {
        int መሰኩዒ_ምእታው = 가로 - 포인터가로, መስመር = 세로 - 포인터세로;
        if (ኣመልካቲ_ቅርጺ != 0 && መሰኩዒ_ምእታው >= 0 && መስመር >= 0 && መሰኩዒ_ምእታው < 21 && መስመር < 21) {
            ኣመልካቲ_ድሕረባይታ[መስመር * 21 + መሰኩዒ_ምእታው] = 색;
            int ነጥቢ_ዋጋ = ኣመልካቲ_ንጣብ(መሰኩዒ_ምእታው, መስመር); if (ነጥቢ_ዋጋ != 0) 색 = ነጥቢ_ዋጋ == 2 ? 0xffffff : 0x101010;
        }
        if (보드.표시화소읽기(가로, 세로) != 색) {
            보드.ጸሓፍ_መርኣዪ_ንጣብ(가로, 세로, 색);
            기록아래낱말++; if (기록아래낱말 == 0) 기록위낱말++;
        }
    }
    public static void ጨርስ() {
        if (합성중 == 0) return;
        for (int መስመር = 위경계; መስመር < 아래경계; መስመር++) for (int መሰኩዒ_ምእታው = 왼경계; መሰኩዒ_ምእታው < 오른경계; መሰኩዒ_ምእታው++)
            መርኣዪ_ንጣብ(መሰኩዒ_ምእታው, መስመር, 완성그림[(መስመር - 위경계) * 1920 + መሰኩዒ_ምእታው]);
        합성중 = 0;
    }
    public static int ንጣብ(int 가로, int 세로, int 색) {
        if (가로 < 0 || 세로 < 0 || 가로 >= 너비 || 세로 >= 높이) return 0;
        if (합성중 != 0) {
            if (가로 >= 왼경계 && 가로 < 오른경계 && 세로 >= 위경계 && 세로 < 아래경계)
                완성그림[(세로 - 위경계) * 1920 + 가로] = 색;
        } else መርኣዪ_ንጣብ(가로, 세로, 색);
        return 0;
    }
    public static void 사각그림(int 가로, int 세로, int 폭, int ንውሓት_ዋጋ, int 색) {
        if (ቅንጣብ(가로, 세로, 폭, ንውሓት_ዋጋ) == 0) return;
        가로 = 잘린범위[0]; 세로 = 잘린범위[1]; 폭 = 잘린범위[2]; ንውሓት_ዋጋ = 잘린범위[3];
        for (int መስመር = 세로; መስመር < 세로 + ንውሓት_ዋጋ; መስመር++) for (int መሰኩዒ_ምእታው = 가로; መሰኩዒ_ምእታው < 가로 + 폭; መሰኩዒ_ምእታው++) {
            if (합성중 != 0) 완성그림[(መስመር - 위경계) * 1920 + መሰኩዒ_ምእታው] = 색;
            else መርኣዪ_ንጣብ(መሰኩዒ_ምእታው, መስመር, 색);
        }
    }
    public static void ኣመልካቲ(int 가로, int 세로, int ቅርጺ_ዋጋ) {
        if (너비 == 0) return;
        int 새가로 = 가로 - (ቅርጺ_ዋጋ >= 2 ? 10 : 0), 새세로 = 세로 - (ቅርጺ_ዋጋ >= 2 ? 10 : 0);
        if (ኣመልካቲ_ቅርጺ == ቅርጺ_ዋጋ && 포인터가로 == 새가로 && 포인터세로 == 새세로) return;
        if (ኣመልካቲ_ቅርጺ != 0) for (int መስመር = 0; መስመር < 21; መስመር++) for (int መሰኩዒ_ምእታው = 0; መሰኩዒ_ምእታው < 21; መሰኩዒ_ምእታው++) {
            int 가 = 포인터가로 + መሰኩዒ_ምእታው, 세 = 포인터세로 + መስመር;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) 보드.ጸሓፍ_መርኣዪ_ንጣብ(가, 세, ኣመልካቲ_ድሕረባይታ[መስመር * 21 + መሰኩዒ_ምእታው]);
        }
        ኣመልካቲ_ቅርጺ = ቅርጺ_ዋጋ; 포인터가로 = 새가로; 포인터세로 = 새세로;
        if (ቅርጺ_ዋጋ != 0) for (int መስመር = 0; መስመር < 21; መስመር++) for (int መሰኩዒ_ምእታው = 0; መሰኩዒ_ምእታው < 21; መሰኩዒ_ምእታው++) {
            int 가 = 포인터가로 + መሰኩዒ_ምእታው, 세 = 포인터세로 + መስመር;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) {
                ኣመልካቲ_ድሕረባይታ[መስመር * 21 + መሰኩዒ_ምእታው] = 보드.표시화소읽기(가, 세);
                int ነጥቢ_ዋጋ = ኣመልካቲ_ንጣብ(መሰኩዒ_ምእታው, መስመር); if (ነጥቢ_ዋጋ != 0) 보드.ጸሓፍ_መርኣዪ_ንጣብ(가, 세, ነጥቢ_ዋጋ == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
