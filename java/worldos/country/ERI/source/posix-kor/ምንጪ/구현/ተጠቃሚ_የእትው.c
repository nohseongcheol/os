#include "호출경계.h"
extern int main(int 인수개수, char **ሓባሪ_ቁጽሪ_ዝርዝር);
static char ሓባሪ_ቁጽሪ_ማህደር_ዝኽረት[2048];
static char *ሓባሪ_ቁጽሪ_ዝርዝር[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 ተግብር_ትእዛዝ 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    ሓባሪ_ቁጽሪ_ዝርዝር[0] = "jkoros-app";
    int 위치 = 0;
    for (int መሐበሪ = 0; መሐበሪ < 개수; መሐበሪ++) {
        const int *원본 = (const int *)jkoros_syscall(3, መሐበሪ, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        ሓባሪ_ቁጽሪ_ዝርዝር[መሐበሪ + 1] = ሓባሪ_ቁጽሪ_ማህደር_ዝኽረት + 위치;
        for (int መሰኩዒ_ምእታው = 0; መሰኩዒ_ምእታው < 원본[0]; መሰኩዒ_ምእታው++) {
            if (위치 >= 2047) return 126;
            ሓባሪ_ቁጽሪ_ማህደር_ዝኽረት[위치++] = 원본[መሰኩዒ_ምእታው + 1];
        }
        ሓባሪ_ቁጽሪ_ማህደር_ዝኽረት[위치++] = 0;
    }
    ሓባሪ_ቁጽሪ_ዝርዝር[개수 + 1] = 0;
    return main(개수 + 1, ሓባሪ_ቁጽሪ_ዝርዝር);
}
