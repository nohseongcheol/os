/** 디스크 ጸሓፍ 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int ንውሓት_ዋጋ = 0;
    static boolean 앞줄복귀 = false;
    static boolean መስመር_ፍሳስ = false;

    static boolean ትእዛዝ(String ሽም) {
        if (ንውሓት_ዋጋ < ሽም.length()) return false;
        for (int መሐበሪ = 0; መሐበሪ < ሽም.length(); መሐበሪ++)
            if (입력[መሐበሪ] != ሽም.charAt(መሐበሪ)) return false;
        return ንውሓት_ዋጋ == ሽም.length() || 입력[ሽም.length()] == ' ';
    }

    static void ኣርእይ_ሓገዝ() {
        문자단말.ጸሓፍ("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        문자단말.ጸሓፍ("apps | run NAME [ARGS] | net\n");
        문자단말.ጸሓፍ("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        문자단말.ጸሓፍ("sync (연결된 JKSTORE1 ከዝን_ዋጋ 장치에 ፋይል 보존)\n");
    }

    static void መስርሕ_ዋጋ_ምእታው() {
        if (ንውሓት_ዋጋ == 0) return;
        if (ትእዛዝ("help")) ኣርእይ_ሓገዝ();
        else if (ትእዛዝ("sync")) {
            int 결과 = 파일보존.ኣሳንይ();
            문자단말.ጸሓፍ("Sync: "); 문자단말.수쓰기(결과); 문자단말.문자(10);
        }
        else if (ትእዛዝ("ls")) ማህደር_ዝኽረት_ናይ_ፋይል_ስርዓት.ምእታው_ዝርዝር();
        else if (ትእዛዝ("edit")) ማህደር_ዝኽረት_ናይ_ፋይል_ስርዓት.ትእዛዝ(입력, 4, ንውሓት_ዋጋ, 0);
        else if (ትእዛዝ("cat")) ማህደር_ዝኽረት_ናይ_ፋይል_ስርዓት.ትእዛዝ(입력, 3, ንውሓት_ዋጋ, 1);
        else if (ትእዛዝ("rm")) ማህደር_ዝኽረት_ናይ_ፋይል_ስርዓት.ትእዛዝ(입력, 2, ንውሓት_ዋጋ, 2);
        else if (ትእዛዝ("java") || ትእዛዝ("javac")) {
            int 결과 = 실행관리.ተግብር_ትእዛዝ(입력, 0, ንውሓት_ዋጋ);
            문자단말.ጸሓፍ("Exit: "); 문자단말.수쓰기(결과); 문자단말.문자(10);
        }
        else if (ትእዛዝ("apps")) 실행관리.ምእታው_ዝርዝር();
        else if (ትእዛዝ("net")) ማሕበራዊ_ኔትወርክ_ድርደራ.ደረጃ_ዋጋ();
        else if (ትእዛዝ("run")) {
            int 결과 = 실행관리.ተግብር_ትእዛዝ(입력, 3, ንውሓት_ዋጋ);
            문자단말.ጸሓፍ("Exit: "); 문자단말.수쓰기(결과); 문자단말.ጸሓፍ("\n");
        } else if (ትእዛዝ("info")) {
            문자단말.ጸሓፍ("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (ትእዛዝ("mem")) {
            문자단말.ጸሓፍ("위쪽 ማህደር_ዝኽረት_ዋጋ 공간(KiB): "); 문자단말.수쓰기(기억공간.위쪽기억크기());
            문자단말.ጸሓፍ("\n배열 동적 ማህደር_ዝኽረት_ዋጋ 공간(ባይት_ዋጋ): "); 문자단말.수쓰기(መሳርሒ_ዋጋ.배열사용량());
            문자단말.ጸሓፍ(" / 262144\n작업 공간 ክፋል_ዋጋ: "); 문자단말.수쓰기(기억공간.사용개수());
            문자단말.ጸሓፍ(" / 8 (각 4096바이트)\n");
        } else if (ትእዛዝ("alloc")) {
            int መሐበሪ = 기억공간.ምምዳብ_መኽዘን();
            문자단말.ጸሓፍ("ክፋል_ዋጋ መሐበሪ: "); 문자단말.수쓰기(መሐበሪ); 문자단말.ጸሓፍ("\n");
        } else if (ትእዛዝ("free")) {
            if (ንውሓት_ዋጋ == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                문자단말.ጸሓፍ(기억공간.반환(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 ክፋል_ዋጋ\n");
            } else 문자단말.ጸሓፍ("사용법: free 0..7\n");
        } else if (ትእዛዝ("echo")) {
            for (int መሐበሪ = 5; መሐበሪ < ንውሓት_ዋጋ; መሐበሪ++) 문자단말.문자(입력[መሐበሪ]);
            문자단말.문자(10);
        } else if (ትእዛዝ("clear")) 문자단말.지우기();
        else if (ትእዛዝ("test")) ፍረ.시험();
        else if (ትእዛዝ("halt")) {
            문자단말.ጸሓፍ("HALTED\n");
            መሳርሒ_ዋጋ.정지();
        } else 문자단말.ጸሓፍ("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int ዋጋ) {
        if (ዋጋ == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = ዋጋ == 13;
        if (ዋጋ == 10 || ዋጋ == 13) {
            문자단말.문자(10);
            if (ማህደር_ዝኽረት_ናይ_ፋይል_ስርዓት.편집중) ማህደር_ዝኽረት_ናይ_ፋይል_ስርዓት.편집줄(입력, ንውሓት_ዋጋ, መስመር_ፍሳስ);
            else መስርሕ_ዋጋ_ምእታው();
            ንውሓት_ዋጋ = 0;
            መስመር_ፍሳስ = false;
            문자단말.ጸሓፍ(ማህደር_ዝኽረት_ናይ_ፋይል_ስርዓት.편집중 ? "...> " : "jkoros> ");
        } else if (ዋጋ == 8 || ዋጋ == 127) {
            if (ንውሓት_ዋጋ > 0) {
                ንውሓት_ዋጋ--;
                문자단말.직렬바이트(8); 문자단말.직렬바이트(32); 문자단말.직렬바이트(8);
                문자단말.화면문자(8);
            }
        } else if (ዋጋ >= 32 && ዋጋ < 127 && ንውሓት_ዋጋ < 입력.length) {
            입력[ንውሓት_ዋጋ++] = ዋጋ;
            문자단말.문자(ዋጋ);
        } else if (ዋጋ >= 32 && ዋጋ < 127) መስመር_ፍሳስ = true;
    }

    static void ኣኺድ() {
        ኣርእይ_ሓገዝ();
        문자단말.ጸሓፍ("READY\njkoros> ");
        while (true) {
            int ዋጋ = 문자단말.직렬읽기();
            if (ዋጋ < 0) ዋጋ = ናይ_መፍትሕ_ሰሌዳ.읽기();
            if (ዋጋ >= 0) 받아쓰기(ዋጋ);
            else { ማሕበራዊ_ኔትወርክ_ድርደራ.ኣረጋግጽ(); መሳርሒ_ዋጋ.잠시양보(); }
        }
    }
}
