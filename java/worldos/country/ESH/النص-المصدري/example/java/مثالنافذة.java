import العربية.ذاتي.نافذة;
import العربية.ذاتي.تسمية;
import العربية.ذاتي.حقل_نصي;
import العربية.ذاتي.زر;
import العربية.ذاتي.حدث_يدرج;
import العربية.ذاتي.مخرجات;
import العربية.ذاتي.실행할일;
import العربية.ذاتي.동작받이;
import العربية.ذاتي.إجراء_إشعار;

/** ذاتي 커널의 Swing نافذة: العربية إدخال_قيمة → زر → 안내 نص يحدث. */
public class مثالنافذة implements 실행할일, 동작받이 {
    private نافذة 인사창;
    private حقل_نصي اسم_حقل;
    private تسمية 인사말;
    private int 인사횟수;

    public void فتح_نافذة() {
        인사창 = new نافذة("العربية Swing", 460, 300);
        인사창.يضيف_عنصر(new تسمية("مرحبا", 20, 20, 420, 28));
        اسم_حقل = new حقل_نصي("العربية", 20, 64, 420, 30);
        인사말 = new تسمية("مرحبا", 20, 152, 420, 28);
        인사창.يضيف_عنصر(اسم_حقل);
        인사창.يضيف_عنصر(new زر("인사하기", 20, 108, 180, 32, this));
        인사창.يضيف_عنصر(인사말);
        인사창.يضيف_عنصر(new تسمية("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.عرض_نافذة();
        مخرجات.كتابة_خط("GUI 예제 إعداد: مثالنافذة");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.كتابة_نص("مرحبا, " + اسم_حقل.يقرأ_نص() + "님! (" + 인사횟수 + ")");
        مخرجات.كتابة_خط("GUI 인사: " + 인사말.يقرأ_نص());
    }

    public void تنفيذ() { فتح_نافذة(); }
    public void يستلم_إجراء(إجراء_إشعار إشعار) {
        مخرجات.كتابة_خط("إجراء إشعار: " + إشعار.أمر_نص());
        인사하기();
    }
    public static void تشغيل() {
        حدث_يدرج.나중에실행(new مثالنافذة());
    }
}
