"""Two-set Hangul composition for the native VNC-to-UART input bridge.

The pending character is visible in the guest editor. Replacing it uses that
editor's UTF-8 Backspace, so commit before cursor motion, shortcuts or a click.
No host input-method daemon or third-party Python package is required.
"""

첫소리목록 = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
가운뎃소리목록 = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
끝소리목록 = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'
Ключ_Макет = dict(zip('rRseEfaqQtTdwWczxvgkoiOjpuPhynbml',
                'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎㅏㅐㅑㅒㅓㅔㅕㅖㅗㅛㅜㅠㅡㅣ'))
겹가운뎃소리 = {('ㅗ','ㅏ'):'ㅘ',('ㅗ','ㅐ'):'ㅙ',('ㅗ','ㅣ'):'ㅚ',
          ('ㅜ','ㅓ'):'ㅝ',('ㅜ','ㅔ'):'ㅞ',('ㅜ','ㅣ'):'ㅟ',('ㅡ','ㅣ'):'ㅢ'}
겹끝소리 = {('ㄱ','ㅅ'):'ㄳ',('ㄴ','ㅈ'):'ㄵ',('ㄴ','ㅎ'):'ㄶ',
          ('ㄹ','ㄱ'):'ㄺ',('ㄹ','ㅁ'):'ㄻ',('ㄹ','ㅂ'):'ㄼ',('ㄹ','ㅅ'):'ㄽ',
          ('ㄹ','ㅌ'):'ㄾ',('ㄹ','ㅍ'):'ㄿ',('ㄹ','ㅎ'):'ㅀ',('ㅂ','ㅅ'):'ㅄ'}
끝소리가르기 = {ЗНАЧЕН: 한쌍 for 한쌍,ЗНАЧЕН in 겹끝소리.items()}


class 한글조합:
    def __init__(자신, написать):
        자신.написать = написать
        자신.фиксация_состав()

    def фиксация_состав(자신):
        자신.код_состояния = ('','','')
        자신.журнал = []

    def текст(자신):
        첫소리,가운뎃소리,끝소리 = 자신.код_состояния
        if 첫소리 and 가운뎃소리:
            return chr(0xac00 + (첫소리목록.index(첫소리)*21 + 가운뎃소리목록.index(가운뎃소리))*28
                       + (끝소리목록.index(끝소리) if 끝소리 else 0))
        return 첫소리 or 가운뎃소리

    def 앞글자지우기(자신):
        if not 자신.журнал:
            return False
        자신.код_состояния = 자신.журнал.pop()
        자신.написать(b'\x7f' + 자신.текст().encode('utf-8'))
        return True

    def канал_Ключ(자신, 누름값):
        символьные_данные = Ключ_Макет.get(누름값, Ключ_Макет.get(누름값.lower()))
        if символьные_данные is None:
            return False
        Назад_товар = 자신.текст()
        첫소리,가운뎃소리,끝소리 = 자신.код_состояния
        журнал = 자신.журнал + [자신.код_состояния]
        확정글 = ''
        if символьные_данные in 첫소리목록:
            if 첫소리 and 가운뎃소리 and not 끝소리 and символьные_данные in 끝소리목록:
                끝소리 = символьные_данные
            elif 끝소리 and (끝소리,символьные_данные) in 겹끝소리:
                끝소리 = 겹끝소리[끝소리,символьные_данные]
            else:
                확정글 = Назад_товар
                첫소리,가운뎃소리,끝소리 = символьные_данные,'',''
                журнал = [('','','')]
        elif 끝소리:
            왼쪽,право = 끝소리가르기.get(끝소리, ('',끝소리))
            자신.код_состояния = 첫소리,가운뎃소리,왼쪽
            확정글 = 자신.текст()
            첫소리,가운뎃소리,끝소리 = право,символьные_данные,''
            журнал = [('','',''),(право,'','')]
        elif 가운뎃소리:
            if (가운뎃소리,символьные_данные) in 겹가운뎃소리:
                가운뎃소리 = 겹가운뎃소리[가운뎃소리,символьные_данные]
            else:
                확정글 = Назад_товар
                첫소리,가운뎃소리,끝소리 = '',символьные_данные,''
                журнал = [('','','')]
        else:
            가운뎃소리 = символьные_данные
        자신.код_состояния = 첫소리,가운뎃소리,끝소리
        자신.журнал = журнал
        자신.написать((b'\x7f' if Назад_товар else b'') + (확정글+자신.текст()).encode('utf-8'))
        return True
