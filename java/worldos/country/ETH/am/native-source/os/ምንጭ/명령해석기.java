/** 디스크 መጻፊያ 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int ርዝመት_እሴት = 0;
    static boolean 앞줄복귀 = false;
    static boolean መስመር_መትረፍ = false;

    static boolean ትእዛዝ(String ስም) {
        if (ርዝመት_እሴት < ስም.length()) return false;
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < ስም.length(); መረጃ_ጠቆመ++)
            if (입력[መረጃ_ጠቆመ] != ስም.charAt(መረጃ_ጠቆመ)) return false;
        return ርዝመት_እሴት == ስም.length() || 입력[ስም.length()] == ' ';
    }

    static void አሳይ_እገዛ() {
        ጽሁፍ_ተርሚናል.መጻፊያ("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        ጽሁፍ_ተርሚናል.መጻፊያ("apps | run NAME [ARGS] | net\n");
        ጽሁፍ_ተርሚናል.መጻፊያ("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        ጽሁፍ_ተርሚናል.መጻፊያ("sync (연결된 JKSTORE1 ማከማቻ_እሴት 장치에 ፋይል 보존)\n");
    }

    static void ሂደት_እሴት_ምዝግብ() {
        if (ርዝመት_እሴት == 0) return;
        if (ትእዛዝ("help")) አሳይ_እገዛ();
        else if (ትእዛዝ("sync")) {
            int ልኬት = 파일보존.አመሳስል();
            ጽሁፍ_ተርሚናል.መጻፊያ("Sync: "); ጽሁፍ_ተርሚናል.수쓰기(ልኬት); ጽሁፍ_ተርሚናል.문자(10);
        }
        else if (ትእዛዝ("ls")) ማስቀመጫ_የፋይል_ስርዓት.ምዝግብ_ዝርዝር();
        else if (ትእዛዝ("edit")) ማስቀመጫ_የፋይል_ስርዓት.ትእዛዝ(입력, 4, ርዝመት_እሴት, 0);
        else if (ትእዛዝ("cat")) ማስቀመጫ_የፋይል_ስርዓት.ትእዛዝ(입력, 3, ርዝመት_እሴት, 1);
        else if (ትእዛዝ("rm")) ማስቀመጫ_የፋይል_ስርዓት.ትእዛዝ(입력, 2, ርዝመት_እሴት, 2);
        else if (ትእዛዝ("java") || ትእዛዝ("javac")) {
            int ልኬት = 실행관리.ፈጽም_ትእዛዝ(입력, 0, ርዝመት_እሴት);
            ጽሁፍ_ተርሚናል.መጻፊያ("Exit: "); ጽሁፍ_ተርሚናል.수쓰기(ልኬት); ጽሁፍ_ተርሚናል.문자(10);
        }
        else if (ትእዛዝ("apps")) 실행관리.ምዝግብ_ዝርዝር();
        else if (ትእዛዝ("net")) መረብ_ክምር.ዞን_እሴት();
        else if (ትእዛዝ("run")) {
            int ልኬት = 실행관리.ፈጽም_ትእዛዝ(입력, 3, ርዝመት_እሴት);
            ጽሁፍ_ተርሚናል.መጻፊያ("Exit: "); ጽሁፍ_ተርሚናል.수쓰기(ልኬት); ጽሁፍ_ተርሚናል.መጻፊያ("\n");
        } else if (ትእዛዝ("info")) {
            ጽሁፍ_ተርሚናል.መጻፊያ("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (ትእዛዝ("mem")) {
            ጽሁፍ_ተርሚናል.መጻፊያ("위쪽 ማስቀመጫ_እሴት 공간(KiB): "); ጽሁፍ_ተርሚናል.수쓰기(기억공간.위쪽기억크기());
            ጽሁፍ_ተርሚናል.መጻፊያ("\n배열 동적 ማስቀመጫ_እሴት 공간(ባይት_እሴት): "); ጽሁፍ_ተርሚናል.수쓰기(መሳሪያ_እሴት.ድርድር_ጥቅም_ላይ_የዋለ());
            ጽሁፍ_ተርሚናል.መጻፊያ(" / 262144\n작업 공간 ክፍል_እሴት: "); ጽሁፍ_ተርሚናል.수쓰기(기억공간.사용개수());
            ጽሁፍ_ተርሚናል.መጻፊያ(" / 8 (각 4096바이트)\n");
        } else if (ትእዛዝ("alloc")) {
            int መረጃ_ጠቆመ = 기억공간.መደብ_ማከማቻ();
            ጽሁፍ_ተርሚናል.መጻፊያ("ክፍል_እሴት መረጃ_ጠቆመ: "); ጽሁፍ_ተርሚናል.수쓰기(መረጃ_ጠቆመ); ጽሁፍ_ተርሚናል.መጻፊያ("\n");
        } else if (ትእዛዝ("free")) {
            if (ርዝመት_እሴት == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                ጽሁፍ_ተርሚናል.መጻፊያ(기억공간.반환(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 ክፍል_እሴት\n");
            } else ጽሁፍ_ተርሚናል.መጻፊያ("사용법: free 0..7\n");
        } else if (ትእዛዝ("echo")) {
            for (int መረጃ_ጠቆመ = 5; መረጃ_ጠቆመ < ርዝመት_እሴት; መረጃ_ጠቆመ++) ጽሁፍ_ተርሚናል.문자(입력[መረጃ_ጠቆመ]);
            ጽሁፍ_ተርሚናል.문자(10);
        } else if (ትእዛዝ("clear")) ጽሁፍ_ተርሚናል.አስወግድ_ምዝግብ_c8dbc399();
        else if (ትእዛዝ("test")) ዓንኳር.시험();
        else if (ትእዛዝ("halt")) {
            ጽሁፍ_ተርሚናል.መጻፊያ("HALTED\n");
            መሳሪያ_እሴት.정지();
        } else ጽሁፍ_ተርሚናል.መጻፊያ("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int እሴት) {
        if (እሴት == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = እሴት == 13;
        if (እሴት == 10 || እሴት == 13) {
            ጽሁፍ_ተርሚናል.문자(10);
            if (ማስቀመጫ_የፋይል_ስርዓት.편집중) ማስቀመጫ_የፋይል_ስርዓት.편집줄(입력, ርዝመት_እሴት, መስመር_መትረፍ);
            else ሂደት_እሴት_ምዝግብ();
            ርዝመት_እሴት = 0;
            መስመር_መትረፍ = false;
            ጽሁፍ_ተርሚናል.መጻፊያ(ማስቀመጫ_የፋይል_ስርዓት.편집중 ? "...> " : "jkoros> ");
        } else if (እሴት == 8 || እሴት == 127) {
            if (ርዝመት_እሴት > 0) {
                ርዝመት_እሴት--;
                ጽሁፍ_ተርሚናል.직렬바이트(8); ጽሁፍ_ተርሚናል.직렬바이트(32); ጽሁፍ_ተርሚናል.직렬바이트(8);
                ጽሁፍ_ተርሚናል.화면문자(8);
            }
        } else if (እሴት >= 32 && እሴት < 127 && ርዝመት_እሴት < 입력.length) {
            입력[ርዝመት_እሴት++] = እሴት;
            ጽሁፍ_ተርሚናል.문자(እሴት);
        } else if (እሴት >= 32 && እሴት < 127) መስመር_መትረፍ = true;
    }

    static void ማስኬጃ() {
        አሳይ_እገዛ();
        ጽሁፍ_ተርሚናል.መጻፊያ("READY\njkoros> ");
        while (true) {
            int እሴት = ጽሁፍ_ተርሚናል.직렬읽기();
            if (እሴት < 0) እሴት = የቁልፍ_ሰሌዳ.ማንበቢያ();
            if (እሴት >= 0) 받아쓰기(እሴት);
            else { መረብ_ክምር.አረጋግጥ(); መሳሪያ_እሴት.잠시양보(); }
        }
    }
}
