        if (가로 < 왼쪽) 가로 = 왼쪽;
        if (ቋሚ_በቦታ_አስቀመጠ < 위쪽) ቋሚ_በቦታ_አስቀመጠ = 위쪽;
        if (오른쪽 > 최대가로) 오른쪽 = 최대가로;
        if (아래쪽 > 최대세로) 아래쪽 = 최대세로;
        if (오른쪽 <= 가로 || 아래쪽 <= ቋሚ_በቦታ_አስቀመጠ) return 0;
        잘린범위[0] = 가로; 잘린범위[1] = ቋሚ_በቦታ_አስቀመጠ;
        잘린범위[2] = 오른쪽 - 가로; 잘린범위[3] = 아래쪽 - ቋሚ_በቦታ_አስቀመጠ;
