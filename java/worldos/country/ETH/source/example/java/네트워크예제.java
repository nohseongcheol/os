import አማርኛ.자체.ግንኙነት;
import አማርኛ.자체.실행인수;
import አማርኛ.자체.전문통로;
import አማርኛ.자체.문자;
import አማርኛ.자체.ውጤት;
import አማርኛ.자체.검사;
import አማርኛ.자체.입력흐름;
import አማርኛ.자체.ግቤት_ውጤት_ልዩነት;

public class 네트워크예제 {
    public static void ማስኬጃ() throws ግቤት_ውጤት_ልዩነት {
        // አዘጋጅ_b78e430d: python3 መሳሪያዎች/예제되돌림.py --tcp-port 9000 --udp-port 9001
        ግንኙነት መገናኛ = ግንኙነት.መክፈቻ("10.0.2.2", 문자.ተንትን_ኢንተጀር(실행인수.ጽሁፍ(0)));
        try {
            መገናኛ.대기시간(700);
            byte[] ኢሜይል = 문자.부호화("JAVA TCP አማርኛ\n");
            መገናኛ.ውጤት().መጻፊያ(ኢሜይል);
            입력흐름 입력 = መገናኛ.입력();
            for (int 수 = 0; 수 < 문자.바이트수(ኢሜይል); 수++) {
                검사.참인지(입력.ማንበቢያ() == (ኢሜይል[수] & 255), "TCP መልስ 불일치");
            }
        } finally { መገናኛ.መዝጊያ(); }
        전문통로 종단 = 전문통로.መክፈቻ(0);
        try {
            종단.대기시간(700);
            종단.ላክ("10.0.2.2", 문자.ተንትን_ኢንተጀር(실행인수.ጽሁፍ(1)), "JAVA UDP አማርኛ");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP አማርኛ"), "UDP መልስ 불일치");
        } finally { 종단.መዝጊያ(); }
        ውጤት.ጻፍ_መስመር("JAVA 네트워크 አረጋግጥ: TCP UDP አማርኛ");
    }
}
