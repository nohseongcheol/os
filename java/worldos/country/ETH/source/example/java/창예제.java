import አማርኛ.자체.መስኮት;
import አማርኛ.자체.ምልክት;
import አማርኛ.자체.ጽሁፍ_መስክ;
import አማርኛ.자체.አዝራር;
import አማርኛ.자체.ፍጻሜ_ሰልፍ;
import አማርኛ.자체.ውጤት;
import አማርኛ.자체.실행할일;
import አማርኛ.자체.동작받이;
import አማርኛ.자체.동작알림;

/** 자체 커널의 Swing መስኮት: አማርኛ 입력 → አዝራር → አንበኝ_eb81d7d9 ጽሁፍ አድስ. */
public class 창예제 implements 실행할일, 동작받이 {
    private መስኮት 인사창;
    private ጽሁፍ_መስክ ስም_መስክ;
    private ምልክት 인사말;
    private int 인사횟수;

    public void ክፈት_መስኮት() {
        인사창 = new መስኮት("አማርኛ Swing", 460, 300);
        인사창.አክል_አባል(new ምልክት("ሰላም", 20, 20, 420, 28));
        ስም_መስክ = new ጽሁፍ_መስክ("አማርኛ", 20, 64, 420, 30);
        인사말 = new ምልክት("ሰላም", 20, 152, 420, 28);
        인사창.አክል_አባል(ስም_መስክ);
        인사창.አክል_አባል(new አዝራር("인사하기", 20, 108, 180, 32, this));
        인사창.አክል_አባል(인사말);
        인사창.አክል_አባል(new ምልክት("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.አሳይ_መስኮት();
        ውጤት.ጻፍ_መስመር("GUI 예제 አዘጋጅ_9ce364fc: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.ጻፍ_ጽሁፍ("ሰላም, " + ስም_መስክ.글읽기() + "님! (" + 인사횟수 + ")");
        ውጤት.ጻፍ_መስመር("GUI 인사: " + 인사말.글읽기());
    }

    public void መፈጸሚያ() { ክፈት_መስኮት(); }
    public void 동작받기(동작알림 알림) {
        ውጤት.ጻፍ_መስመር("ተግባር 알림: " + 알림.ትእዛዝ_ጽሁፍ());
        인사하기();
    }
    public static void ማስኬጃ() {
        ፍጻሜ_ሰልፍ.나중에실행(new 창예제());
    }
}
