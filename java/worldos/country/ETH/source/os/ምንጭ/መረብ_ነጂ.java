/** PCI RTL8139 (10ec:8139), 단일 ላክ_እሴት 버퍼와 8KiB 수신 ድግግሞሽ_እሴት. 인터럽트 대신 폴링한다. */
public final class መረብ_ነጂ {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] መሳሪያ_አድራሻ = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int አካባቢ) {
        መሳሪያ_እሴት.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | አካባቢ);
        return መሳሪያ_እሴት.입출력정수읽기(0xcfc);
    }

    static boolean አዘጋጅ_9ce364fc() {
        int 장치번호 = -1;
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < 32; መረጃ_ጠቆመ++) {
            if (설정읽기(መረጃ_ጠቆመ, 0) == 0x813910ec) { 장치번호 = መረጃ_ጠቆመ; break; }
        }
        if (장치번호 < 0) return false;
        int ነባሪ_እሴት = 설정읽기(장치번호, 0x10);
        if ((ነባሪ_እሴት & 1) == 0 || (ነባሪ_እሴት & 0xfffffffc) < 0x100 || (ነባሪ_እሴት & 0xfffffffc) > 65535) return false;
        입출력기준주소 = ነባሪ_እሴት & 0xfffc;
        int ትእዛዝ = 설정읽기(장치번호, 4);
        መሳሪያ_እሴት.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        መሳሪያ_እሴት.입출력짧은수쓰기(0xcfc, ትእዛዝ | 5); // I/O 및 bus master ፍቀድ_እሴት, PCI ዞን_እሴት 비트는 건드리지 않음
        መሳሪያ_እሴት.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!ያዘጋጁ_እሴት()) { 입출력기준주소 = 0; return false; }
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < 6; መረጃ_ጠቆመ++) መሳሪያ_አድራሻ[መረጃ_ጠቆመ] = መሳሪያ_እሴት.입출력바이트읽기(입출력기준주소 + መረጃ_ጠቆመ);
        return true;
    }

    static boolean ያዘጋጁ_እሴት() {
        መሳሪያ_እሴት.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int ማስኬጃ = መሳሪያ_እሴት.밀리초();
        while ((መሳሪያ_እሴት.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (መሳሪያ_እሴት.밀리초() - ማስኬጃ > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        መሳሪያ_እሴት.입출력정수쓰기(입출력기준주소 + 0x30, መሳሪያ_እሴት.መረብ_ማስቀመጫ());
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < 4; መረጃ_ጠቆመ++) መሳሪያ_እሴት.입출력정수쓰기(입출력기준주소 + 0x20 + መረጃ_ጠቆመ * 4, መሳሪያ_እሴት.መረብ_ማስቀመጫ() + 12288);
        መሳሪያ_እሴት.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        መሳሪያ_እሴት.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        መሳሪያ_እሴት.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        መሳሪያ_እሴት.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/ስርጭት_እሴት, wrap 연속 ማከማቻ_እሴት, 8KiB
        መሳሪያ_እሴት.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int ላክ(int[] ውሂብ, int ርዝመት_እሴት) {
        if (입출력기준주소 == 0) return -19;
        if (ርዝመት_እሴት < 14 || ርዝመት_እሴት > 1514) return -90;
        int ዞን_ወደብ = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int ማስኬጃ = መሳሪያ_እሴት.밀리초();
        while ((መሳሪያ_እሴት.입출력정수읽기(ዞን_ወደብ) & 0x2000) == 0)
            if (መሳሪያ_እሴት.밀리초() - ማስኬጃ > 100) return -110;
        int መጠን = ርዝመት_እሴት < 60 ? 60 : ርዝመት_እሴት;
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < መጠን; መረጃ_ጠቆመ++)
            መሳሪያ_እሴት.ጻፍ_ማስቀመጫ(መሳሪያ_እሴት.መረብ_ማስቀመጫ() + 12288 + መረጃ_ጠቆመ, መረጃ_ጠቆመ < ርዝመት_እሴት ? ውሂብ[መረጃ_ጠቆመ] : 0);
        መሳሪያ_እሴት.입출력정수쓰기(ዞን_ወደብ, መጠን | 0x00080000);
        ማስኬጃ = መሳሪያ_እሴት.밀리초();
        while ((መሳሪያ_እሴት.입출력정수읽기(ዞን_ወደብ) & 0xe0008000) == 0)
            if (መሳሪያ_እሴት.밀리초() - ማስኬጃ > 100) return -110;
        if ((መሳሪያ_እሴት.입출력정수읽기(ዞን_ወደብ) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return ርዝመት_እሴት;
    }

    static int 받기(int[] ውሂብ) {
        if (입출력기준주소 == 0) return 0;
        if ((መሳሪያ_እሴት.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!ያዘጋጁ_እሴት()) 입출력기준주소 = 0;
            return 0;
        }
        if ((መሳሪያ_እሴት.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = መሳሪያ_እሴት.መረብ_ማስቀመጫ() + 수신위치;
        int ዞን_እሴት = 실행관리.짧은수(머리), መጠን = 실행관리.짧은수(머리 + 2);
        if (መጠን == 0xfff0) return 0; // DMA 진행 중
        if (መጠን < 4 || መጠን > 1518) {
            오류수++;
            if (!ያዘጋጁ_እሴት()) 입출력기준주소 = 0;
            return 0;
        }
        int ርዝመት_እሴት = መጠን - 4;
        if ((ዞን_እሴት & 1) != 0) {
            for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < ርዝመት_እሴት; መረጃ_ጠቆመ++) ውሂብ[መረጃ_ጠቆመ] = መሳሪያ_እሴት.기억읽기(머리 + 4 + መረጃ_ጠቆመ);
            수신수++;
        } else { ርዝመት_እሴት = 0; 오류수++; }
        수신위치 = (수신위치 + መጠን + 4 + 3) & ~3;
        수신위치 &= 8191;
        መሳሪያ_እሴት.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        መሳሪያ_እሴት.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return ርዝመት_እሴት;
    }
}
