/** 부팅 የስርዓት_መረጃ 조회와 4KiB 고정 መጠን 작업 ክፍል_እሴት መደብ_ማከማቻ/반환. 일반 물리 ገጽ_እሴት 관리자는 아니다. */
public final class 기억공간 {
    static int[] ክፍል_እሴት = new int[8192];
    static int[] 사용 = new int[8];

    static int ተንትን_ኢንተጀር(int አድራሻ) {
        return መሳሪያ_እሴት.기억읽기(አድራሻ) | (መሳሪያ_እሴት.기억읽기(አድራሻ + 1) << 8)
            | (መሳሪያ_እሴት.기억읽기(አድራሻ + 2) << 16) | (መሳሪያ_እሴት.기억읽기(አድራሻ + 3) << 24);
    }

    static int 위쪽기억크기() {
        int የስርዓት_መረጃ = መሳሪያ_እሴት.부팅정보();
        if (መሳሪያ_እሴት.부팅표식() != 0x2badb002 || የስርዓት_መረጃ == 0 || (ተንትን_ኢንተጀር(የስርዓት_መረጃ) & 1) == 0) return -1;
        return ተንትን_ኢንተጀር(የስርዓት_መረጃ + 8);
    }

    static int መደብ_ማከማቻ() {
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < 사용.length; መረጃ_ጠቆመ++) {
            if (사용[መረጃ_ጠቆመ] == 0) {
                사용[መረጃ_ጠቆመ] = 1;
                for (int ማስገቢያ_ቀዳዳ_ምዝግብ = 0; ማስገቢያ_ቀዳዳ_ምዝግብ < 1024; ማስገቢያ_ቀዳዳ_ምዝግብ++) ክፍል_እሴት[መረጃ_ጠቆመ * 1024 + ማስገቢያ_ቀዳዳ_ምዝግብ] = 0;
                return መረጃ_ጠቆመ;
            }
        }
        return -1;
    }

    static boolean 반환(int መረጃ_ጠቆመ) {
        if (መረጃ_ጠቆመ < 0 || መረጃ_ጠቆመ >= 사용.length || 사용[መረጃ_ጠቆመ] == 0) return false;
        사용[መረጃ_ጠቆመ] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < 사용.length; መረጃ_ጠቆመ++) 개수 += 사용[መረጃ_ጠቆመ];
        return 개수;
    }
}
