/** 최대 መጠን/홀수 ርዝመት_እሴት 데이터그램으로 ትክክለኛ_ውሂብ RTL8139 수신 ድግግሞሽ_እሴት 순환을 시험한다. */
public final class መረብ_ድግግሞሽ {
    public static int ማስኬጃ() {
        if (ተጠቃሚ.인수개수() != 1) { ተጠቃሚ.መጻፊያ("Usage: run stress PORT\n"); return 2; }
        String ጽሁፍ = ተጠቃሚ.인수(0);
        int ወደብ_እሴት = 0;
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < ጽሁፍ.length(); መረጃ_ጠቆመ++) {
            if (ጽሁፍ.charAt(መረጃ_ጠቆመ) < '0' || ጽሁፍ.charAt(መረጃ_ጠቆመ) > '9' || ወደብ_እሴት > 6553) return 2;
            ወደብ_እሴት = ወደብ_እሴት * 10 + ጽሁፍ.charAt(መረጃ_ጠቆመ) - '0';
        }
        if (ወደብ_እሴት < 1 || ወደብ_እሴት > 65535) return 2;
        int እጀታ_እሴት = ተጠቃሚ.ክፈት_መረብ(0);
        if (እጀታ_እሴት < 0) return 3;
        int[] ውሂብ = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int ርዝመት_እሴት = 1024 - (회차 & 1);
            for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < ርዝመት_እሴት; መረጃ_ጠቆመ++) ውሂብ[መረጃ_ጠቆመ] = (መረጃ_ጠቆመ + 회차) & 255;
            if (ተጠቃሚ.ላክ_ውሂብ(እጀታ_እሴት, 0x0a000202, ወደብ_እሴት, ውሂብ, ርዝመት_እሴት) != ርዝመት_እሴት) return 4;
            if (ተጠቃሚ.자료받기(እጀታ_እሴት, ውሂብ, 300) != ርዝመት_እሴት) return 5;
            for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < ርዝመት_እሴት; መረጃ_ጠቆመ++) if (ውሂብ[መረጃ_ጠቆመ] != ((መረጃ_ጠቆመ + 회차) & 255)) return 6;
        }
        ተጠቃሚ.ዝጋ_መረብ(እጀታ_እሴት);
        ተጠቃሚ.መጻፊያ("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
