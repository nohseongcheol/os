public final class Память_регион {
    static int[] раздел_ЗНАЧЕН_366e0bfa = new int[8192];
    static int[] использовать_ЗНАЧЕН = new int[8];

    static int анализировать_целое_число(int АДРЕС) {
        return устройство_ЗНАЧЕН.чтение_Память(АДРЕС) | (устройство_ЗНАЧЕН.чтение_Память(АДРЕС + 1) << 8)
            | (устройство_ЗНАЧЕН.чтение_Память(АДРЕС + 2) << 16) | (устройство_ЗНАЧЕН.чтение_Память(АДРЕС + 3) << 24);
    }

    static int ПРОПИСН_Память_изменить_размер() {
        int msinfo32_exe = устройство_ЗНАЧЕН.부팅정보();
        if (устройство_ЗНАЧЕН.부팅표식() != 0x2badb002 || msinfo32_exe == 0 || (анализировать_целое_число(msinfo32_exe) & 1) == 0) return -1;
        return анализировать_целое_число(msinfo32_exe + 8);
    }

    static int выделить_Память() {
        for (int ИНДЕКС = 0; ИНДЕКС < использовать_ЗНАЧЕН.length; ИНДЕКС++) {
            if (использовать_ЗНАЧЕН[ИНДЕКС] == 0) {
                использовать_ЗНАЧЕН[ИНДЕКС] = 1;
                for (int слот_ввод = 0; слот_ввод < 1024; слот_ввод++) раздел_ЗНАЧЕН_366e0bfa[ИНДЕКС * 1024 + слот_ввод] = 0;
                return ИНДЕКС;
            }
        }
        return -1;
    }

    static boolean Возврат_KR(int ИНДЕКС) {
        if (ИНДЕКС < 0 || ИНДЕКС >= использовать_ЗНАЧЕН.length || использовать_ЗНАЧЕН[ИНДЕКС] == 0) return false;
        использовать_ЗНАЧЕН[ИНДЕКС] = 0;
        return true;
    }

    static int 사용개수() {
        int товар_СЧЁТ = 0;
        for (int ИНДЕКС = 0; ИНДЕКС < использовать_ЗНАЧЕН.length; ИНДЕКС++) товар_СЧЁТ += использовать_ЗНАЧЕН[ИНДЕКС];
        return товар_СЧЁТ;
    }
}
