/** 최대 आकार/홀수 길이 데이터그램으로 वास्तविक_डेटा RTL8139 수신 लूप_मान 순환을 시험한다. */
public final class नेटवर्क_लूप {
    public static int चलाएँ() {
        if (उपयोगकर्ता.인수개수() != 1) { उपयोगकर्ता.लिखें("Usage: run stress PORT\n"); return 2; }
        String पाठ = उपयोगकर्ता.तर्क(0);
        int पोर्ट_मान = 0;
        for (int इंडेक्स = 0; इंडेक्स < पाठ.length(); इंडेक्स++) {
            if (पाठ.charAt(इंडेक्स) < '0' || पाठ.charAt(इंडेक्स) > '9' || पोर्ट_मान > 6553) return 2;
            पोर्ट_मान = पोर्ट_मान * 10 + पाठ.charAt(इंडेक्स) - '0';
        }
        if (पोर्ट_मान < 1 || पोर्ट_मान > 65535) return 2;
        int हैंडल_मान = उपयोगकर्ता.जारी_नेटवर्क(0);
        if (हैंडल_मान < 0) return 3;
        int[] आँकड़े = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int 길이 = 1024 - (회차 & 1);
            for (int इंडेक्स = 0; इंडेक्स < 길이; इंडेक्स++) आँकड़े[इंडेक्स] = (इंडेक्स + 회차) & 255;
            if (उपयोगकर्ता.भेजें_डेटा(हैंडल_मान, 0x0a000202, पोर्ट_मान, आँकड़े, 길이) != 길이) return 4;
            if (उपयोगकर्ता.자료받기(हैंडल_मान, आँकड़े, 300) != 길이) return 5;
            for (int इंडेक्स = 0; इंडेक्स < 길이; इंडेक्स++) if (आँकड़े[इंडेक्स] != ((इंडेक्स + 회차) & 255)) return 6;
        }
        उपयोगकर्ता.बंद_नेटवर्क(हैंडल_मान);
        उपयोगकर्ता.लिखें("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
