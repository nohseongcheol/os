/** 디스크 लिखें 없이 동작하는 작은 직렬/PS2 आदेश_व्याख्याकार. */
public final class आदेश_व्याख्याकार {
    static int[] 입력 = new int[128];
    static int 길이 = 0;
    static boolean 앞줄복귀 = false;
    static boolean लाइन_ओवरफ्लो = false;

    static boolean आदेश(String नाम) {
        if (길이 < नाम.length()) return false;
        for (int इंडेक्स = 0; इंडेक्स < नाम.length(); इंडेक्स++)
            if (입력[इंडेक्स] != नाम.charAt(इंडेक्स)) return false;
        return 길이 == नाम.length() || 입력[नाम.length()] == ' ';
    }

    static void सहायता_दिखाना() {
        पाठ_टर्मिनल.लिखें("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        पाठ_टर्मिनल.लिखें("apps | run NAME [ARGS] | net\n");
        पाठ_टर्मिनल.लिखें("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        पाठ_टर्मिनल.लिखें("sync (연결된 JKSTORE1 स्टोर_मान 장치에 संचिका 보존)\n");
    }

    static void प्रक्रिया_मान_एन्ट्री() {
        if (길이 == 0) return;
        if (आदेश("help")) सहायता_दिखाना();
        else if (आदेश("sync")) {
            int परिणाम = 파일보존.सिंक्रनाइज़_करें();
            पाठ_टर्मिनल.लिखें("Sync: "); पाठ_टर्मिनल.수쓰기(परिणाम); पाठ_टर्मिनल.문자(10);
        }
        else if (आदेश("ls")) मेमोरी_फ़ाइल_सिस्टम.एन्ट्री_सूची();
        else if (आदेश("edit")) मेमोरी_फ़ाइल_सिस्टम.आदेश(입력, 4, 길이, 0);
        else if (आदेश("cat")) मेमोरी_फ़ाइल_सिस्टम.आदेश(입력, 3, 길이, 1);
        else if (आदेश("rm")) मेमोरी_फ़ाइल_सिस्टम.आदेश(입력, 2, 길이, 2);
        else if (आदेश("java") || आदेश("javac")) {
            int परिणाम = 실행관리.निष्पादित_करें_आदेश(입력, 0, 길이);
            पाठ_टर्मिनल.लिखें("Exit: "); पाठ_टर्मिनल.수쓰기(परिणाम); पाठ_टर्मिनल.문자(10);
        }
        else if (आदेश("apps")) 실행관리.एन्ट्री_सूची();
        else if (आदेश("net")) नेटवर्क_स्टैक.अवस्था_मान();
        else if (आदेश("run")) {
            int परिणाम = 실행관리.निष्पादित_करें_आदेश(입력, 3, 길이);
            पाठ_टर्मिनल.लिखें("Exit: "); पाठ_टर्मिनल.수쓰기(परिणाम); पाठ_टर्मिनल.लिखें("\n");
        } else if (आदेश("info")) {
            पाठ_टर्मिनल.लिखें("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (आदेश("mem")) {
            पाठ_टर्मिनल.लिखें("위쪽 मेमोरी_मान पता_क्षेत्र(KiB): "); पाठ_टर्मिनल.수쓰기(मेमोरी_क्षेत्र.위쪽기억크기());
            पाठ_टर्मिनल.लिखें("\n배열 동적 मेमोरी_मान पता_क्षेत्र(बाइट_मान): "); पाठ_टर्मिनल.수쓰기(उपकरण_मान.배열사용량());
            पाठ_टर्मिनल.लिखें(" / 262144\n작업 पता_क्षेत्र खंड_मान: "); पाठ_टर्मिनल.수쓰기(मेमोरी_क्षेत्र.사용개수());
            पाठ_टर्मिनल.लिखें(" / 8 (각 4096바이트)\n");
        } else if (आदेश("alloc")) {
            int इंडेक्स = मेमोरी_क्षेत्र.आवंटित_करें_संग्रहण();
            पाठ_टर्मिनल.लिखें("खंड_मान इंडेक्स: "); पाठ_टर्मिनल.수쓰기(इंडेक्स); पाठ_टर्मिनल.लिखें("\n");
        } else if (आदेश("free")) {
            if (길이 == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                पाठ_टर्मिनल.लिखें(मेमोरी_क्षेत्र.वापस_करें_परिणाम(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 खंड_मान\n");
            } else पाठ_टर्मिनल.लिखें("사용법: free 0..7\n");
        } else if (आदेश("echo")) {
            for (int इंडेक्स = 5; इंडेक्स < 길이; इंडेक्स++) पाठ_टर्मिनल.문자(입력[इंडेक्स]);
            पाठ_टर्मिनल.문자(10);
        } else if (आदेश("clear")) पाठ_टर्मिनल.मिटाएँ_एन्ट्री();
        else if (आदेश("test")) कर्नेल.시험();
        else if (आदेश("halt")) {
            पाठ_टर्मिनल.लिखें("HALTED\n");
            उपकरण_मान.정지();
        } else पाठ_टर्मिनल.लिखें("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int मान) {
        if (मान == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = मान == 13;
        if (मान == 10 || मान == 13) {
            पाठ_टर्मिनल.문자(10);
            if (मेमोरी_फ़ाइल_सिस्टम.편집중) मेमोरी_फ़ाइल_सिस्टम.संपादित_लाइन(입력, 길이, लाइन_ओवरफ्लो);
            else प्रक्रिया_मान_एन्ट्री();
            길이 = 0;
            लाइन_ओवरफ्लो = false;
            पाठ_टर्मिनल.लिखें(मेमोरी_फ़ाइल_सिस्टम.편집중 ? "...> " : "jkoros> ");
        } else if (मान == 8 || मान == 127) {
            if (길이 > 0) {
                길이--;
                पाठ_टर्मिनल.직렬바이트(8); पाठ_टर्मिनल.직렬바이트(32); पाठ_टर्मिनल.직렬바이트(8);
                पाठ_टर्मिनल.화면문자(8);
            }
        } else if (मान >= 32 && मान < 127 && 길이 < 입력.length) {
            입력[길이++] = मान;
            पाठ_टर्मिनल.문자(मान);
        } else if (मान >= 32 && मान < 127) लाइन_ओवरफ्लो = true;
    }

    static void चलाएँ() {
        सहायता_दिखाना();
        पाठ_टर्मिनल.लिखें("READY\njkoros> ");
        while (true) {
            int मान = पाठ_टर्मिनल.직렬읽기();
            if (मान < 0) मान = कीबोर्ड.पढ़ें();
            if (मान >= 0) 받아쓰기(मान);
            else { नेटवर्क_स्टैक.सत्यापित_करें(); उपकरण_मान.잠시양보(); }
        }
    }
}
