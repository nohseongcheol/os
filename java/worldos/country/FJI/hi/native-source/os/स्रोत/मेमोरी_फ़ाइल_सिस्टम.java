/** 세션 동안 유지되는 8개 संचिका. 원본 संपादन_मान/कंपाइल_स्रोत विफलता_मान 시 기존 파일을 보존한다. */
public final class मेमोरी_फ़ाइल_सिस्टम {
    static final int 최대크기 = 16384;
    static int[] 이름들 = new int[8 * 64];
    static int[] आकार_सूची = new int[8];
    static int[] 열림수 = new int[8], 허가들 = new int[8];
    static int[] नाम = new int[64];
    static int[] संपादन_मान = new int[최대크기];
    static boolean 편집중 = false;
    static boolean ओवरफ्लो_मान = false;
    static int संपादन_आकार = 0;

    static boolean जाँचें_नाम(int[] कैरेक्टर_मान, int 길이) {
        if (길이 < 1 || 길이 > 63) return false;
        for (int 수 = 0; 수 < 길이; 수++) {
            int मान = कैरेक्टर_मान[수];
            if (!(मान >= 'a' && मान <= 'z') && !(मान >= 'A' && मान <= 'Z')
                && !(मान >= '0' && मान <= '9') && मान != '_' && मान != '-' && मान != '.') return false;
        }
        return कैरेक्टर_मान[0] != '.';
    }

    static int खोजें_एन्ट्री(int[] कैरेक्टर_मान, int 길이) {
        if (!जाँचें_नाम(कैरेक्टर_मान, 길이)) return -22;
        for (int 수 = 0; 수 < 8; 수++) {
            boolean 같음 = 이름들[수 * 64 + 길이] == 0;
            for (int 칸 = 0; 칸 < 길이; 칸++) if (이름들[수 * 64 + 칸] != कैरेक्टर_मान[칸]) 같음 = false;
            if (같음) return 수;
        }
        return -2;
    }

    static int स्टोर_मान(int[] कैरेक्टर_मान, int 길이, int[] आँकड़े, int आकार) {
        if (!जाँचें_नाम(कैरेक्टर_मान, 길이) || आकार < 0 || आकार > आँकड़े.length) return -22;
        if (आकार > 최대크기) return -90;
        int इंडेक्स = खोजें_एन्ट्री(कैरेक्टर_मान, 길이);
        if (इंडेक्स == -2) {
            for (int 수 = 0; 수 < 8 && इंडेक्स < 0; 수++) if (이름들[수 * 64] == 0 && 열림수[수] == 0) इंडेक्स = 수;
            if (इंडेक्स >= 0) 허가들[इंडेक्स] = 438;
        }
        if (इंडेक्स < 0) return -28;
        int पता = उपकरण_मान.फ़ाइल_मेमोरी() + इंडेक्स * 최대크기;
        for (int 수 = 0; 수 < आकार; 수++) उपकरण_मान.लिखना_मेमोरी(पता + 수, आँकड़े[수]);
        for (int 수 = 0; 수 < 64; 수++) 이름들[इंडेक्स * 64 + 수] = 수 < 길이 ? कैरेक्टर_मान[수] : 0;
        आकार_सूची[इंडेक्स] = आकार;
        return आकार;
    }

    static void एन्ट्री_सूची() {
        for (int 수 = 0; 수 < 8; 수++) if (이름들[수 * 64] != 0) {
            for (int 칸 = 0; 칸 < 64 && 이름들[수 * 64 + 칸] != 0; 칸++) पाठ_टर्मिनल.문자(이름들[수 * 64 + 칸]);
            पाठ_टर्मिनल.लिखें("  "); पाठ_टर्मिनल.수쓰기(आकार_सूची[수]); पाठ_टर्मिनल.लिखें("बाइट_मान\n");
        }
        पाठ_टर्मिनल.लिखें(संग्रहण_उपकरण_कनेक्शन.सूचना_प्रौद्योगिकी_उपलब्ध ? "संचिका 8칸, 파일당 16384바이트; sync로 स्टोर_मान 장치에 보존\n"
            : "임시 संचिका 8칸, 파일당 16384바이트; 다시 시작하면 사라짐\n");
    }

    static void आदेश(int[] 입력, int चलाएँ, int 길이, int क्रिया) {
        while (चलाएँ < 길이 && 입력[चलाएँ] == ' ') चलाएँ++;
        int 끝 = 길이;
        while (끝 > चलाएँ && 입력[끝 - 1] == ' ') 끝--;
        int 수 = 끝 - चलाएँ;
        if (수 < 1 || 수 > 63) { पाठ_टर्मिनल.लिखें("올바르지 않은 संचिका नाम\n"); return; }
        for (int 칸 = 0; 칸 < 64; 칸++) नाम[칸] = 칸 < 수 ? 입력[चलाएँ + 칸] : 0;
        int इंडेक्स = खोजें_एन्ट्री(नाम, 수);
        if (इंडेक्स == -22) { पाठ_टर्मिनल.लिखें("올바르지 않은 संचिका नाम\n"); return; }
        if (क्रिया == 0) {
            편집중 = true; संपादन_आकार = 0; ओवरफ्लो_मान = false;
            पाठ_टर्मिनल.लिखें("원문을 입력하세요. .save는 보존, .cancel은 취소합니다.\n");
        } else if (इंडेक्स < 0) पाठ_टर्मिनल.लिखें("파일을 찾을 수 없습니다\n");
        else if (क्रिया == 1) {
            int पता = उपकरण_मान.फ़ाइल_मेमोरी() + इंडेक्स * 최대크기;
            for (int 칸 = 0; 칸 < आकार_सूची[इंडेक्स]; 칸++) पाठ_टर्मिनल.문자(उपकरण_मान.पढें_मेमोरी(पता + 칸));
            पाठ_टर्मिनल.문자(10);
        } else { 이름들[इंडेक्स * 64] = 0; आकार_सूची[इंडेक्स] = 0; पाठ_टर्मिनल.लिखें("파일을 지웠습니다\n"); }
    }

    static boolean 정확(int[] 입력, int 길이, String 문구) {
        if (길이 != 문구.length()) return false;
        for (int 칸 = 0; 칸 < 길이; 칸++) if (입력[칸] != 문구.charAt(칸)) return false;
        return true;
    }

    static void संपादित_लाइन(int[] 입력, int 길이, boolean लाइन_ओवरफ्लो) {
        if (정확(입력, 길이, ".cancel")) {
            편집중 = false; पाठ_टर्मिनल.लिखें("취소했습니다. 원래 파일은 그대로입니다\n");
        } else if (정확(입력, 길이, ".save")) {
            편집중 = false;
            if (ओवरफ्लो_मान) { पाठ_टर्मिनल.लिखें("입력이 너무 깁니다. 원래 파일은 그대로입니다\n"); return; }
            int 수 = 0;
            while (수 < 64 && नाम[수] != 0) 수++;
            int परिणाम = स्टोर_मान(नाम, 수, संपादन_मान, संपादन_आकार);
            पाठ_टर्मिनल.लिखें(परिणाम >= 0 ? "보존한 बाइट_मान 수: " : "보존 विफलता_मान: ");
            पाठ_टर्मिनल.수쓰기(परिणाम); पाठ_टर्मिनल.문자(10);
        } else if (लाइन_ओवरफ्लो || 길이 + 1 > 최대크기 - संपादन_आकार) ओवरफ्लो_मान = true;
        else {
            for (int 수 = 0; 수 < 길이; 수++) संपादन_मान[संपादन_आकार++] = 입력[수];
            संपादन_मान[संपादन_आकार++] = 10;
        }
    }

    static void 예제(String संचिका, String सामग्री_मान) {
        for (int 수 = 0; 수 < 64; 수++) नाम[수] = 수 < संचिका.length() ? संचिका.charAt(수) : 0;
        for (int 수 = 0; 수 < सामग्री_मान.length(); 수++) संपादन_मान[수] = सामग्री_मान.charAt(수);
        स्टोर_मान(नाम, संचिका.length(), संपादन_मान, सामग्री_मान.length());
    }

    static void 준비() {
        예제("Hello.java", "public class Hello {\n public static void main(String[] args) {\n  System.out.println(\"Hello from jkoros JVM!\");\n  int sum = 0;\n  for (int i = 1; i <= 10; i++) { sum = sum + i; }\n  System.out.println(sum);\n }\n}\n");
        int समूह_मान = उपकरण_मान.자바파일묶음(), आकार = उपकरण_मान.자바파일묶음크기();
        if (आकार < 8 || 실행관리.수(समूह_मान) != 0x464a4b4a) { पाठ_टर्मिनल.लिखें("올바르지 않은 Java संचिका समूह_मान\n"); return; }
        int 개수 = 실행관리.수(समूह_मान + 4);
        if (개수 < 0 || 개수 > 8 || 개수 > (आकार - 8) / 72) { पाठ_टर्मिनल.लिखें("올바르지 않은 Java संचिका एन्ट्री_सूची\n"); return; }
        for (int 수 = 0; 수 < 개수; 수++) {
            int एन्ट्री_मान = समूह_मान + 8 + 수 * 72, 길이 = 0;
            for (int 칸 = 0; 칸 < 64; 칸++) नाम[칸] = उपकरण_मान.पढें_मेमोरी(एन्ट्री_मान + 칸);
            while (길이 < 64 && नाम[길이] != 0) 길이++;
            int स्थान = 실행관리.수(एन्ट्री_मान + 64), फ़ाइल_आकार = 실행관리.수(एन्ट्री_मान + 68);
            if (!जाँचें_नाम(नाम, 길이) || फ़ाइल_आकार < 0 || फ़ाइल_आकार > 최대크기 || स्थान < 8 + 개수 * 72 || स्थान > आकार - फ़ाइल_आकार) {
                पाठ_टर्मिनल.लिखें("올바르지 않은 Java संचिका एन्ट्री_मान\n"); return;
            }
            for (int 칸 = 0; 칸 < फ़ाइल_आकार; 칸++) संपादन_मान[칸] = उपकरण_मान.पढें_मेमोरी(समूह_मान + स्थान + 칸);
            if (स्टोर_मान(नाम, 길이, संपादन_मान, फ़ाइल_आकार) < 0) { पाठ_टर्मिनल.लिखें("Java 파일을 가져오지 못했습니다\n"); return; }
        }
    }
}
