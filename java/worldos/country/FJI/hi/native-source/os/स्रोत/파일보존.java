/** 검사합과 두 보존본을 사용하는 작은 전용 स्टोर_मान फॉर्मैट_मान. fsync/sync에서만 영구 반영한다. */
public final class 파일보존 {
    static int 현재보존본 = -1, 세대번호 = 0;
    static int[] फ़ाइल_तालिका = new int[1024];
    static int 바이트해시(int मान, int आँकड़े) { return (मान ^ आँकड़े) * 16777619; }
    static void साफ_करें_डेटा() {
        for (int इंडेक्स = 0; इंडेक्स < 512; इंडेक्स++) संग्रहण_उपकरण_कनेक्शन.खंड_डेटा[इंडेक्स] = 0;
    }
    static int तालिका_पूर्णांक(int स्थान) {
        return फ़ाइल_तालिका[स्थान] | फ़ाइल_तालिका[स्थान + 1] << 8 | फ़ाइल_तालिका[स्थान + 2] << 16 | फ़ाइल_तालिका[स्थान + 3] << 24;
    }
    static void लिखना_तालिका_पूर्णांक(int स्थान, int मान) {
        for (int इंडेक्स = 0; इंडेक्स < 4; इंडेक्स++) फ़ाइल_तालिका[स्थान + इंडेक्स] = (मान >>> (इंडेक्स * 8)) & 255;
    }
    static boolean जाँचें_तालिका() {
        for (int संचिका = 0; संचिका < 8; संचिका++) {
            int 길이 = 0;
            for (int 칸 = 0; 칸 < 64; 칸++) मेमोरी_फ़ाइल_सिस्टम.नाम[칸] = फ़ाइल_तालिका[संचिका * 72 + 칸];
            while (길이 < 64 && मेमोरी_फ़ाइल_सिस्टम.नाम[길이] != 0) 길이++;
            if (길이 == 0) continue;
            if (!मेमोरी_फ़ाइल_सिस्टम.जाँचें_नाम(मेमोरी_फ़ाइल_सिस्टम.नाम, 길이)
                || तालिका_पूर्णांक(संचिका * 72 + 64) < 0 || तालिका_पूर्णांक(संचिका * 72 + 64) > 16384) return false;
            for (int सामने_मान = 0; सामने_मान < संचिका; सामने_मान++) {
                boolean 같음 = फ़ाइल_तालिका[सामने_मान * 72 + 길이] == 0;
                for (int 칸 = 0; 칸 < 길이; 칸++) if (फ़ाइल_तालिका[सामने_मान * 72 + 칸] != मेमोरी_फ़ाइल_सिस्टम.नाम[칸]) 같음 = false;
                if (같음) return false;
            }
        }
        return true;
    }
    static int 보존본검사(int 보존본) {
        int प्रारंभ_खंड = 1 + 보존본 * 259;
        if (संग्रहण_उपकरण_कनेक्शन.पढ़ें(प्रारंभ_खंड) < 0 || संग्रहण_उपकरण_कनेक्शन.पार्स_करें_पूर्णांक(0) != 0x4a4b534e) return -1;
        int 세대 = संग्रहण_उपकरण_कनेक्शन.पार्स_करें_पूर्णांक(4), योगफल_की_जाँच = संग्रहण_उपकरण_कनेक्शन.पार्स_करें_पूर्णांक(8);
        if (세대 < 1 || संग्रहण_उपकरण_कनेक्शन.पार्स_करें_पूर्णांक(12) != (세대 ^ योगफल_की_जाँच ^ 0x4a4b534e)) return -1;
        int हैश_फ़ाइल = 0x811c9dc5;
        for (int खंड_मान = 0; खंड_मान < 258; खंड_मान++) {
            if (संग्रहण_उपकरण_कनेक्शन.पढ़ें(प्रारंभ_खंड + 1 + खंड_मान) < 0) return -1;
            for (int 칸 = 0; 칸 < 512; 칸++) {
                int मान = संग्रहण_उपकरण_कनेक्शन.खंड_डेटा[칸];
                हैश_फ़ाइल = 바이트해시(हैश_फ़ाइल, मान);
                if (खंड_मान < 2) फ़ाइल_तालिका[खंड_मान * 512 + 칸] = मान;
            }
        }
        return हैश_फ़ाइल == योगफल_की_जाँच && जाँचें_तालिका() ? 세대 : -1;
    }
    static int लोडकरें(int 보존본) {
        int प्रारंभ_खंड = 1 + 보존본 * 259;
        for (int खंड_मान = 0; खंड_मान < 2; खंड_मान++) {
            if (संग्रहण_उपकरण_कनेक्शन.पढ़ें(प्रारंभ_खंड + 1 + खंड_मान) < 0) return -5;
            for (int 칸 = 0; 칸 < 512; 칸++) फ़ाइल_तालिका[खंड_मान * 512 + 칸] = संग्रहण_उपकरण_कनेक्शन.खंड_डेटा[칸];
        }
        for (int संचिका = 0; संचिका < 8; संचिका++) {
            for (int 칸 = 0; 칸 < 64; 칸++) मेमोरी_फ़ाइल_सिस्टम.이름들[संचिका * 64 + 칸] = फ़ाइल_तालिका[संचिका * 72 + 칸];
            मेमोरी_फ़ाइल_सिस्टम.आकार_सूची[संचिका] = फ़ाइल_तालिका[संचिका * 72] == 0 ? 0 : तालिका_पूर्णांक(संचिका * 72 + 64);
            मेमोरी_फ़ाइल_सिस्टम.허가들[संचिका] = तालिका_पूर्णांक(संचिका * 72 + 68) & 511;
            for (int खंड_मान = 0; खंड_मान < 32; खंड_मान++) {
                if (संग्रहण_उपकरण_कनेक्शन.पढ़ें(प्रारंभ_खंड + 3 + संचिका * 32 + खंड_मान) < 0) return -5;
                int पता = उपकरण_मान.फ़ाइल_मेमोरी() + संचिका * 16384 + खंड_मान * 512;
                for (int 칸 = 0; 칸 < 512; 칸++) उपकरण_मान.लिखना_मेमोरी(पता + 칸, संग्रहण_उपकरण_कनेक्शन.खंड_डेटा[칸]);
            }
        }
        return 0;
    }
    static void 준비() {
        if (संग्रहण_उपकरण_कनेक्शन.पढ़ें(0) < 0 || संग्रहण_उपकरण_कनेक्शन.पार्स_करें_पूर्णांक(0) != 0x54534b4a
            || संग्रहण_उपकरण_कनेक्शन.पार्स_करें_पूर्णांक(4) != 0x3145524f || संग्रहण_उपकरण_कनेक्शन.पार्स_करें_पूर्णांक(8) != 2048
            || संग्रहण_उपकरण_कनेक्शन.पार्स_करें_पूर्णांक(12) != 0x3153464a) {
            पाठ_टर्मिनल.लिखें("STORE RAM only (no JKSTORE1 disk)\n"); return;
        }
        संग्रहण_उपकरण_कनेक्शन.सूचना_प्रौद्योगिकी_उपलब्ध = true;
        int 첫째 = 보존본검사(0), 둘째 = 보존본검사(1);
        if (첫째 < 0 && 둘째 < 0) { पाठ_टर्मिनल.लिखें("STORE ready; no valid snapshot\n"); return; }
        현재보존본 = 첫째 >= 둘째 ? 0 : 1; 세대번호 = 첫째 >= 둘째 ? 첫째 : 둘째;
        if (लोडकरें(현재보존본) < 0) {
            पाठ_टर्मिनल.लिखें("STORE read failed; halted to preserve files\n"); उपकरण_मान.정지();
        }
        पाठ_टर्मिनल.लिखें("STORE restored generation "); पाठ_टर्मिनल.수쓰기(세대번호); पाठ_टर्मिनल.문자(10);
    }
    static int सिंक्रनाइज़_करें() {
        if (!संग्रहण_उपकरण_कनेक्शन.सूचना_प्रौद्योगिकी_उपलब्ध) return -19;
        if (세대번호 == 2147483647) return -75;
        int अगला_आइटम = 현재보존본 == 0 ? 1 : 0, प्रारंभ_खंड = 1 + अगला_आइटम * 259;
        // 새 본문보다 먼저 이전 commit을 무효화하고 उपकरण_मान 캐시를 비운다.
        साफ_करें_डेटा();
        if (संग्रहण_उपकरण_कनेक्शन.लिखें(प्रारंभ_खंड) < 0 || संग्रहण_उपकरण_कनेक्शन.밀어쓰기() < 0) return -5;
        for (int 칸 = 0; 칸 < 1024; 칸++) फ़ाइल_तालिका[칸] = 0;
        for (int संचिका = 0; संचिका < 8; संचिका++) if (मेमोरी_फ़ाइल_सिस्टम.이름들[संचिका * 64] != 0) {
            for (int 칸 = 0; 칸 < 64; 칸++) फ़ाइल_तालिका[संचिका * 72 + 칸] = मेमोरी_फ़ाइल_सिस्टम.이름들[संचिका * 64 + 칸];
            लिखना_तालिका_पूर्णांक(संचिका * 72 + 64, मेमोरी_फ़ाइल_सिस्टम.आकार_सूची[संचिका]);
            लिखना_तालिका_पूर्णांक(संचिका * 72 + 68, मेमोरी_फ़ाइल_सिस्टम.허가들[संचिका]);
        }
        int हैश_फ़ाइल = 0x811c9dc5;
        for (int खंड_मान = 0; खंड_मान < 258; खंड_मान++) {
            for (int 칸 = 0; 칸 < 512; 칸++) {
                int मान = 0;
                if (खंड_मान < 2) मान = फ़ाइल_तालिका[खंड_मान * 512 + 칸];
                else {
                    int संचिका = (खंड_मान - 2) / 32, स्थान = (खंड_मान - 2) % 32 * 512 + 칸;
                    if (फ़ाइल_तालिका[संचिका * 72] != 0 && स्थान < मेमोरी_फ़ाइल_सिस्टम.आकार_सूची[संचिका])
                        मान = उपकरण_मान.पढें_मेमोरी(उपकरण_मान.फ़ाइल_मेमोरी() + संचिका * 16384 + स्थान);
                }
                संग्रहण_उपकरण_कनेक्शन.खंड_डेटा[칸] = मान; हैश_फ़ाइल = 바이트해시(हैश_फ़ाइल, मान);
            }
            if (संग्रहण_उपकरण_कनेक्शन.लिखें(प्रारंभ_खंड + 1 + खंड_मान) < 0) return -5;
        }
        if (संग्रहण_उपकरण_कनेक्शन.밀어쓰기() < 0) return -5;
        साफ_करें_डेटा(); संग्रहण_उपकरण_कनेक्शन.लिखना_पूर्णांक_मान(0, 0x4a4b534e);
        संग्रहण_उपकरण_कनेक्शन.लिखना_पूर्णांक_मान(4, 세대번호 + 1); संग्रहण_उपकरण_कनेक्शन.लिखना_पूर्णांक_मान(8, हैश_फ़ाइल);
        संग्रहण_उपकरण_कनेक्शन.लिखना_पूर्णांक_मान(12, (세대번호 + 1) ^ हैश_फ़ाइल ^ 0x4a4b534e);
        if (संग्रहण_उपकरण_कनेक्शन.लिखें(प्रारंभ_खंड) < 0 || संग्रहण_उपकरण_कनेक्शन.밀어쓰기() < 0) return -5;
        현재보존본 = अगला_आइटम; 세대번호++;
        return 0;
    }
}
