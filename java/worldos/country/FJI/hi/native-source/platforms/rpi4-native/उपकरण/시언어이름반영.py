#!/usr/bin/env python3
"""घोषणा 고유번호와 UTF-8 बाइट_मान 위치로 निज C 이름을 옮기는 일회성 이행 उपकरण.

बाहरी_मान 구조체의 멤버, स्ट्रिंग_मान, C 표준 फ़ंक्_शन_मान, 이식 규약은 보존한다.
입력은 परिवर्तित_करें_मान 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

प्रोजेक्ट_करें_मूल = Path(__file__).resolve().parents[1]

def निष्पादित_करें_आदेश():
    विश्लेषण_मान = json.loads((प्रोजेक्ट_करें_मूल/'build/한국어화/시언어분석.json').read_text())
    if विश्लेषण_मान['त्रुटि']: raise SystemExit('विश्लेषण_मान 오류를 먼저 해결해야 합니다.')
    नाम_तालिका = json.loads((प्रोजेक्ट_करें_मूल/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((प्रोजेक्ट_करें_मूल/'명명/규격이름.json').read_text()))
    घोषणा_तालिका = विश्लेषण_मान['घोषणा']
    바꿀선언 = {고유:नाम_तालिका[एन्ट्री_मान['नाम']] for 고유,एन्ट्री_मान in घोषणा_तालिका.items()
                if एन्ट्री_मान['नाम'] in नाम_तालिका and एन्ट्री_मान['नाम'] not in 규격}
    कनेक्शन_तालिका = {एन्ट्री_मान['नाम']:नाम_तालिका[एन्ट्री_मान['नाम']] for एन्ट्री_मान in घोषणा_तालिका.values()
              if एन्ट्री_मान.get('जोड़ना')==4 and एन्ट्री_मान['종류'] in (8,9)
              and एन्ट्री_मान['नाम'] in नाम_तालिका and एन्ट्री_मान['नाम'] not in 규격}
    # जनरेट_करें AOT C·어셈블리·공개 SDK가 공유하는 바이너리 जोड़ना 이름만 유지한다.
    머리 = ['/* हिंदी स्रोत_ट्री 이름과 기존 यंत्र जोड़ना मामला_मान. 자동 जनरेट_करें: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(कनेक्शन_तालिका.items())]
    머리 += ['#endif','']
    (प्रोजेक्ट_करें_मूल/'명명/기계연결이름.h').write_text('\n'.join(머리))
    नए_बदलाव_सूची = defaultdict(dict)
    for संचिका,ऑफ़सेट_मान,नाम,고유 in विश्लेषण_मान['संदर्भ']:
        if 고유 in 바꿀선언:
            नए_बदलाव_सूची[संचिका][ऑफ़सेट_मान] = (नाम,바꿀선언[고유])
    लॉग_रिकॉर्ड = ['संचिका\t원래바이트위치\t이전이름\t한국어이름']
    ध्यान_न_दें_मान = []
    for संचिका,परिवर्तित_करें_मान in नए_बदलाव_सूची.items():
        पथ = Path(संचिका); 원본 = पथ.read_bytes(); आँकड़े = 원본
        for ऑफ़सेट_मान,(옛이름,새이름) in sorted(परिवर्तित_करें_मान.items(),reverse=True):
            끝 = ऑफ़सेट_मान+len(옛이름.encode())
            if 원본[ऑफ़सेट_मान:끝] != 옛이름.encode():
                ध्यान_न_दें_मान.append((str(पथ.relative_to(प्रोजेक्ट_करें_मूल)),ऑफ़सेट_मान,옛이름));continue
            आँकड़े = आँकड़े[:ऑफ़सेट_मान]+새이름.encode()+आँकड़े[끝:]
            लॉग_रिकॉर्ड.append('{}\t{}\t{}\t{}'.format(पथ.relative_to(प्रोजेक्ट_करें_मूल),ऑफ़सेट_मान,옛이름,새이름))
        पथ.write_bytes(आँकड़े)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    मैक्रो_मान = {एन्ट्री_मान['नाम']:नाम_तालिका[एन्ट्री_मान['नाम']] for एन्ट्री_मान in घोषणा_तालिका.values()
              if एन्ट्री_मान['종류']==501 and एन्ट्री_मान['नाम'] in नाम_तालिका and एन्ट्री_मान['नाम'] not in 규격}
    for पथ in sorted({Path(एन्ट्री_मान['संचिका']) for एन्ट्री_मान in घोषणा_तालिका.values()}):
        लाइन_सूची = पथ.read_text().splitlines(True); 이어짐 = False
        for इंडेक्स,पंक्ति in enumerate(लाइन_सूची):
            전처리 = 이어짐 or bool(re.match(r'\s*#',पंक्ति))
            이어짐 = 전처리 and पंक्ति.rstrip().endswith('\\')
            if 전처리:
                लुकअप_तालिका = नाम_तालिका if re.match(r'\s*#\s*define\b',पंक्ति) or 이어짐 else मैक्रो_मान
                लाइन_सूची[इंडेक्स] = 낱말.sub(lambda 맞음: लुकअप_तालिका.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],पंक्ति)
        पथ.write_text(''.join(लाइन_सूची))
    # 각 निज अनुवाद_स्रोत 단위에만 연결표를 넣는다. बाहरी_मान 배포본에는 전파하지 않는다.
    for पथ in sorted({Path(एन्ट्री_मान['संचिका']) for एन्ट्री_मान in घोषणा_तालिका.values()}):
        if पथ.suffix not in ('.c','.cpp'):continue
        पीअर_मान = '../' * len(पथ.relative_to(प्रोजेक्ट_करें_मूल).parts[:-1]) + '명명/기계연결이름.h'
        पथ.write_text('#include "'+पीअर_मान+'"\n'+पथ.read_text())
    (प्रोजेक्ट_करें_मूल/'명명/시언어이름대응.tsv').write_text('\n'.join(लॉग_रिकॉर्ड)+'\n')
    (प्रोजेक्ट_करें_मूल/'build/한국어화/전처리참조.json').write_text(json.dumps(ध्यान_न_दें_मान,ensure_ascii=False,indent=2)+'\n')
    print('परिवर्तित_करें_मान',len(लॉग_रिकॉर्ड)-1,'전처리 재검토',len(ध्यान_न_दें_मान),'यंत्र जोड़ना',len(कनेक्शन_तालिका))

if __name__=='__main__': निष्पादित_करें_आदेश()
