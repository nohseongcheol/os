/** 화면 자르기·띠 합성·포인터 밑그림을 관리한다. 실제 화면 메모리 접근은 보드가 담당한다. */
public final class 화면합성 {
    static int 너비, 높이, 합성중, 왼경계, 위경계, 오른경계, 아래경계;
    static int 포인터가로, 포인터세로, 포인터모양;
    static int 기록아래낱말, 기록위낱말;
    static int[] 완성그림 = new int[32 * 1920];
    static int[] 포인터밑그림 = new int[21 * 21];
    static int[] 잘린범위 = new int[4];
    public static void 준비(int 폭, int 길이) {
        너비 = 폭; 높이 = 길이; 합성중 = 0; 포인터모양 = 0;
        기록아래낱말 = 0; 기록위낱말 = 0;
    }
    public static int 너비얻기() { return 너비; }
    public static int 높이얻기() { return 높이; }
    public static int 기록아래얻기() { return 기록아래낱말; }
    public static int 기록위얻기() { return 기록위낱말; }
    public static int 범위값(int 순번) { return 잘린범위[순번]; }
    static int 양의길이더하기(int 시작값, int 길이) {
        if (시작값 > 2147483647 - 길이) return 2147483647;
        return 시작값 + 길이;
    }
    public static int 범위(int 가로, int 세로, int 폭, int 길이) {
        if (너비 == 0 || 폭 <= 0 || 길이 <= 0) return 0;
        int 오른쪽 = 양의길이더하기(가로, 폭), 아래쪽 = 양의길이더하기(세로, 길이);
        int 왼쪽 = 합성중 != 0 ? 왼경계 : 0, 위쪽 = 합성중 != 0 ? 위경계 : 0;
        int 최대가로 = 합성중 != 0 ? 오른경계 : 너비, 최대세로 = 합성중 != 0 ? 아래경계 : 높이;
        if (가로 < 왼쪽) 가로 = 왼쪽;
        if (세로 < 위쪽) 세로 = 위쪽;
        if (오른쪽 > 최대가로) 오른쪽 = 최대가로;
        if (아래쪽 > 최대세로) 아래쪽 = 최대세로;
        if (오른쪽 <= 가로 || 아래쪽 <= 세로) return 0;
        잘린범위[0] = 가로; 잘린범위[1] = 세로;
        잘린범위[2] = 오른쪽 - 가로; 잘린범위[3] = 아래쪽 - 세로;
        return 1;
    }
    public static int Seveniñ_2(int 가로, int 세로, int 폭, int 길이) {
        if (합성중 != 0 || 길이 > 32 || 범위(가로, 세로, 폭, 길이) == 0) return 0;
        왼경계 = 잘린범위[0]; 위경계 = 잘린범위[1];
        오른경계 = 왼경계 + 잘린범위[2]; 아래경계 = 위경계 + 잘린범위[3];
        합성중 = 1; return 1;
    }
    static boolean 포인터비트(int 가로, int 세로, int 모양) {
        if (모양 == 1) return 가로 >= 0 && 가로 <= 세로 / 2 && 세로 < 16;
        if (모양 == 3) 가로 = 20 - 가로;
        int 차이 = 가로 - 세로; if (차이 < 0) 차이 = -차이;
        return (차이 <= 1 && 가로 >= 3 && 가로 <= 17) ||
            (가로 >= 2 && 가로 <= 8 && 세로 >= 2 && 세로 <= 8 && (가로 <= 3 || 세로 <= 3)) ||
            (가로 >= 12 && 가로 <= 18 && 세로 >= 12 && 세로 <= 18 && (가로 >= 17 || 세로 >= 17));
    }
    static int 포인터화소(int 가로, int 세로) {
        if (포인터비트(가로, 세로, 포인터모양)) return 2;
        for (int 줄 = -1; 줄 <= 1; 줄++) for (int 칸 = -1; 칸 <= 1; 칸++)
            if (포인터비트(가로 + 칸, 세로 + 줄, 포인터모양)) return 1;
        return 0;
    }
    static void 표시화소(int 가로, int 세로, int 색) {
        int 칸 = 가로 - 포인터가로, 줄 = 세로 - 포인터세로;
        if (포인터모양 != 0 && 칸 >= 0 && 줄 >= 0 && 칸 < 21 && 줄 < 21) {
            포인터밑그림[줄 * 21 + 칸] = 색;
            int 점 = 포인터화소(칸, 줄); if (점 != 0) 색 = 점 == 2 ? 0xffffff : 0x101010;
        }
        if (보드.표시화소읽기(가로, 세로) != 색) {
            보드.표시화소쓰기(가로, 세로, 색);
            기록아래낱말++; if (기록아래낱말 == 0) 기록위낱말++;
        }
    }
    public static void 마침() {
        if (합성중 == 0) return;
        for (int 줄 = 위경계; 줄 < 아래경계; 줄++) for (int 칸 = 왼경계; 칸 < 오른경계; 칸++)
            표시화소(칸, 줄, 완성그림[(줄 - 위경계) * 1920 + 칸]);
        합성중 = 0;
    }
    public static int 화소(int 가로, int 세로, int 색) {
        if (가로 < 0 || 세로 < 0 || 가로 >= 너비 || 세로 >= 높이) return 0;
        if (합성중 != 0) {
            if (가로 >= 왼경계 && 가로 < 오른경계 && 세로 >= 위경계 && 세로 < 아래경계)
                완성그림[(세로 - 위경계) * 1920 + 가로] = 색;
        } else 표시화소(가로, 세로, 색);
        return 0;
    }
    public static void 사각그림(int 가로, int 세로, int 폭, int 길이, int 색) {
        if (범위(가로, 세로, 폭, 길이) == 0) return;
        가로 = 잘린범위[0]; 세로 = 잘린범위[1]; 폭 = 잘린범위[2]; 길이 = 잘린범위[3];
        for (int 줄 = 세로; 줄 < 세로 + 길이; 줄++) for (int 칸 = 가로; 칸 < 가로 + 폭; 칸++) {
            if (합성중 != 0) 완성그림[(줄 - 위경계) * 1920 + 칸] = 색;
            else 표시화소(칸, 줄, 색);
        }
    }
    public static void 포인터(int 가로, int 세로, int 모양) {
        if (너비 == 0) return;
        int 새가로 = 가로 - (모양 >= 2 ? 10 : 0), 새세로 = 세로 - (모양 >= 2 ? 10 : 0);
        if (포인터모양 == 모양 && 포인터가로 == 새가로 && 포인터세로 == 새세로) return;
        if (포인터모양 != 0) for (int 줄 = 0; 줄 < 21; 줄++) for (int 칸 = 0; 칸 < 21; 칸++) {
            int 가 = 포인터가로 + 칸, 세 = 포인터세로 + 줄;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) 보드.표시화소쓰기(가, 세, 포인터밑그림[줄 * 21 + 칸]);
        }
        포인터모양 = 모양; 포인터가로 = 새가로; 포인터세로 = 새세로;
        if (모양 != 0) for (int 줄 = 0; 줄 < 21; 줄++) for (int 칸 = 0; 칸 < 21; 칸++) {
            int 가 = 포인터가로 + 칸, 세 = 포인터세로 + 줄;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) {
                포인터밑그림[줄 * 21 + 칸] = 보드.표시화소읽기(가, 세);
                int 점 = 포인터화소(칸, 줄); if (점 != 0) 보드.표시화소쓰기(가, 세, 점 == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
