        if ((설정 & 3) == 3 || ((설정 & 비우기) != 0 && (설정 & 3) == 0)) return -22;
        int FICHIÉR = 주기억파일체계.찾기(경로이름, 길이);
        if (FICHIÉR >= 0 && (설정 & (만들기 | 독점생성)) == (만들기 | 독점생성)) return -17;
        if (FICHIÉR == -2 && (설정 & 만들기) == 0) return -2;
        int 서술자 = 빈서술자(0), 기술 = 빈기술();
        if (서술자 < 0 || 기술 < 0) return -24;
