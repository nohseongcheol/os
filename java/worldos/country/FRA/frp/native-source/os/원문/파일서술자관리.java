    static int 파일닫기(int 서술자) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0) return -9;
        열린기술[서술자] = 0; 서술자설정[서술자] = 0;
        참조수[기술]--;
        if (참조수[기술] == 0) {
            if (종류[기술] == 2) 주기억파일체계.열림수[대상[기술]]--;
            if (종류[기술] == 3 && 통신손잡이[기술] != 0) 통신망.닫기(통신손잡이[기술]);
            종류[기술] = 0;
        }
        return 0;
    }
