        int দল_মান = ডিভাইস_মান.자바파일묶음(), আকার = ডিভাইস_মান.자바파일묶음크기();
        if (আকার < 8 || 실행관리.수(দল_মান) != 0x464a4b4a) { পাঠ_টার্মিনাল.লেখা("올바르지 않은 Java নথির_নাম দল_মান\n"); return; }
