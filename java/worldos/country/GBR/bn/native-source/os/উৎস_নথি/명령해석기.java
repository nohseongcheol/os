/** 디스크 লেখা 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int দৈর্ঘ্য_মান = 0;
    static boolean 앞줄복귀 = false;
    static boolean লাইন_উপচানো = false;

    static boolean আদেশ(String নাম) {
        if (দৈর্ঘ্য_মান < নাম.length()) return false;
        for (int সূচি = 0; সূচি < নাম.length(); সূচি++)
            if (입력[সূচি] != নাম.charAt(সূচি)) return false;
        return দৈর্ঘ্য_মান == নাম.length() || 입력[নাম.length()] == ' ';
    }

    static void সহায়তা_দেখানো() {
        পাঠ_টার্মিনাল.লেখা("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        পাঠ_টার্মিনাল.লেখা("apps | run NAME [ARGS] | net\n");
        পাঠ_টার্মিনাল.লেখা("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        পাঠ_টার্মিনাল.লেখা("sync (연결된 JKSTORE1 ভাণ্ডার_মান 장치에 নথির_নাম 보존)\n");
    }

    static void প্রসেসর_মান_ভুক্তি() {
        if (দৈর্ঘ্য_মান == 0) return;
        if (আদেশ("help")) সহায়তা_দেখানো();
        else if (আদেশ("sync")) {
            int পরিমাপ = 파일보존.সমলয়_করা();
            পাঠ_টার্মিনাল.লেখা("Sync: "); পাঠ_টার্মিনাল.수쓰기(পরিমাপ); পাঠ_টার্মিনাল.문자(10);
        }
        else if (আদেশ("ls")) মেমরি_ফাইল_পদ্ধতি.ভুক্তি_তালিকা();
        else if (আদেশ("edit")) মেমরি_ফাইল_পদ্ধতি.আদেশ(입력, 4, দৈর্ঘ্য_মান, 0);
        else if (আদেশ("cat")) মেমরি_ফাইল_পদ্ধতি.আদেশ(입력, 3, দৈর্ঘ্য_মান, 1);
        else if (আদেশ("rm")) মেমরি_ফাইল_পদ্ধতি.আদেশ(입력, 2, দৈর্ঘ্য_মান, 2);
        else if (আদেশ("java") || আদেশ("javac")) {
            int পরিমাপ = 실행관리.কার্যকর_করুন_আদেশ(입력, 0, দৈর্ঘ্য_মান);
            পাঠ_টার্মিনাল.লেখা("Exit: "); পাঠ_টার্মিনাল.수쓰기(পরিমাপ); পাঠ_টার্মিনাল.문자(10);
        }
        else if (আদেশ("apps")) 실행관리.ভুক্তি_তালিকা();
        else if (আদেশ("net")) নেটওয়ার্ক_গাদা.অবস্হা_মান();
        else if (আদেশ("run")) {
            int পরিমাপ = 실행관리.কার্যকর_করুন_আদেশ(입력, 3, দৈর্ঘ্য_মান);
            পাঠ_টার্মিনাল.লেখা("Exit: "); পাঠ_টার্মিনাল.수쓰기(পরিমাপ); পাঠ_টার্মিনাল.লেখা("\n");
        } else if (আদেশ("info")) {
            পাঠ_টার্মিনাল.লেখা("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (আদেশ("mem")) {
            পাঠ_টার্মিনাল.লেখা("위쪽 মেমরি_মান 공간(KiB): "); পাঠ_টার্মিনাল.수쓰기(기억공간.위쪽기억크기());
            পাঠ_টার্মিনাল.লেখা("\n배열 동적 মেমরি_মান 공간(বাইট_মান): "); পাঠ_টার্মিনাল.수쓰기(ডিভাইস_মান.অ্যারে_ব্যবহার());
            পাঠ_টার্মিনাল.লেখা(" / 262144\n작업 공간 শাখা_মান_366e0bfa: "); পাঠ_টার্মিনাল.수쓰기(기억공간.사용개수());
            পাঠ_টার্মিনাল.লেখা(" / 8 (각 4096바이트)\n");
        } else if (আদেশ("alloc")) {
            int সূচি = 기억공간.বন্টন_করা_স্টোরেজ();
            পাঠ_টার্মিনাল.লেখা("শাখা_মান_366e0bfa সূচি: "); পাঠ_টার্মিনাল.수쓰기(সূচি); পাঠ_টার্মিনাল.লেখা("\n");
        } else if (আদেশ("free")) {
            if (দৈর্ঘ্য_মান == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                পাঠ_টার্মিনাল.লেখা(기억공간.반환(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 শাখা_মান_366e0bfa\n");
            } else পাঠ_টার্মিনাল.লেখা("사용법: free 0..7\n");
        } else if (আদেশ("echo")) {
            for (int সূচি = 5; সূচি < দৈর্ঘ্য_মান; সূচি++) পাঠ_টার্মিনাল.문자(입력[সূচি]);
            পাঠ_টার্মিনাল.문자(10);
        } else if (আদেশ("clear")) পাঠ_টার্মিনাল.মুছুন_ভুক্তি();
        else if (আদেশ("test")) কারনেল.시험();
        else if (আদেশ("halt")) {
            পাঠ_টার্মিনাল.লেখা("HALTED\n");
            ডিভাইস_মান.정지();
        } else পাঠ_টার্মিনাল.লেখা("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int মান) {
        if (মান == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = মান == 13;
        if (মান == 10 || মান == 13) {
            পাঠ_টার্মিনাল.문자(10);
            if (মেমরি_ফাইল_পদ্ধতি.편집중) মেমরি_ফাইল_পদ্ধতি.편집줄(입력, দৈর্ঘ্য_মান, লাইন_উপচানো);
            else প্রসেসর_মান_ভুক্তি();
            দৈর্ঘ্য_মান = 0;
            লাইন_উপচানো = false;
            পাঠ_টার্মিনাল.লেখা(মেমরি_ফাইল_পদ্ধতি.편집중 ? "...> " : "jkoros> ");
        } else if (মান == 8 || মান == 127) {
            if (দৈর্ঘ্য_মান > 0) {
                দৈর্ঘ্য_মান--;
                পাঠ_টার্মিনাল.직렬바이트(8); পাঠ_টার্মিনাল.직렬바이트(32); পাঠ_টার্মিনাল.직렬바이트(8);
                পাঠ_টার্মিনাল.화면문자(8);
            }
        } else if (মান >= 32 && মান < 127 && দৈর্ঘ্য_মান < 입력.length) {
            입력[দৈর্ঘ্য_মান++] = মান;
            পাঠ_টার্মিনাল.문자(মান);
        } else if (মান >= 32 && মান < 127) লাইন_উপচানো = true;
    }

    static void চালনা() {
        সহায়তা_দেখানো();
        পাঠ_টার্মিনাল.লেখা("READY\njkoros> ");
        while (true) {
            int মান = পাঠ_টার্মিনাল.직렬읽기();
            if (মান < 0) মান = কীবোর্ড.পড়া();
            if (মান >= 0) 받아쓰기(মান);
            else { নেটওয়ার্ক_গাদা.যাচাই_করা(); ডিভাইস_মান.잠시양보(); }
        }
    }
}
