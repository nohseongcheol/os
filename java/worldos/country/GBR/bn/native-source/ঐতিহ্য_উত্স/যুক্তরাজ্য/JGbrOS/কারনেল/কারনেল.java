package যুক্তরাজ্য.JGbrOS.কারনেল;

import যুক্তরাজ্য.JGbrOS.기억공간.মেমরি_ব্যবস্থাপক;
import যুক্তরাজ্য.JGbrOS.기억공간.পৃষ্ঠা_ব্যবস্থাপক;
import যুক্তরাজ্য.JGbrOS.입력.입력관리자;
import যুক্তরাজ্য.JGbrOS.작업.প্রসেসর_মান;
import যুক্তরাজ্য.JGbrOS.작업.সময়সূচি_নির্ধারণকারী;
import যুক্তরাজ্য.JGbrOS.체계호출.체계호출;
import যুক্তরাজ্য.JGbrOS.ফাইল_পদ্ধতি.파일서술자표;
import যুক্তরাজ্য.JGbrOS.ফাইল_পদ্ধতি.ফাইল_পদ্ধতি;

/** Java 관리 커널의 조립과 시작을 담당한다. */
public final class কারনেল {
    private final হার্ডওয়্যার_মান ডিভাইস_মান;
    private final মেমরি_ব্যবস্থাপক 기억공간 = new মেমরি_ব্যবস্থাপক(32 * 1024 * 1024);
    private final পৃষ্ঠা_ব্যবস্থাপক 쪽관리 = new পৃষ্ঠা_ব্যবস্থাপক();
    private final ফাইল_পদ্ধতি ফাইল_পদ্ধতি = new ফাইল_পদ্ধতি();
    private final সময়সূচি_নির্ধারণকারী সময়সূচি_নির্ধারণকারী = new সময়সূচি_নির্ধারণকারী(쪽관리);
    private final 입력관리자 입력관리 = new 입력관리자(256);
    private final প্রসেসর_মান 첫과정;
    private final 체계호출 체계호출;

    public কারনেল(হার্ডওয়্যার_মান ডিভাইস_মান) {
        this.ডিভাইস_মান = ডিভাইস_মান;
        첫과정 = সময়সূচি_নির্ধারণকারী.첫과정(new 파일서술자표(ফাইল_পদ্ধতি));
        체계호출 = new 체계호출(ফাইল_পদ্ধতি, 쪽관리, সময়সূচি_নির্ধারণকারী, ডিভাইস_মান, 입력관리);
    }

    public void চালনা() {
        ডিভাইস_মান.직렬출력("=== JGbrOS 관리 কারনেল_মান ===\n");
    }

    public void 한단계실행() {
        ডিভাইস_মান.중앙처리장치멈춤();
    }

    public মেমরি_ব্যবস্থাপক 기억공간() {
        return 기억공간;
    }

    public পৃষ্ঠা_ব্যবস্থাপক 쪽관리() {
        return 쪽관리;
    }

    public ফাইল_পদ্ধতি ফাইল_পদ্ধতি() {
        return ফাইল_পদ্ধতি;
    }

    public সময়সূচি_নির্ধারণকারী সময়সূচি_নির্ধারণকারী() {
        return সময়সূচি_নির্ধারণকারী;
    }

    public 입력관리자 입력관리() {
        return 입력관리;
    }

    public প্রসেসর_মান 첫과정() {
        return 첫과정;
    }

    public 체계호출 체계호출() {
        return 체계호출;
    }
}
