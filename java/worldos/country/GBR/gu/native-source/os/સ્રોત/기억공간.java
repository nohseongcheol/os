/** 부팅 સિસ્ટમ_માહિતી 조회와 4KiB 고정 માપ 작업 અનુભાગ_મૂલ્ય ફાળવો_સંગ્રહ/반환. 일반 물리 પેજ_મૂલ્ય 관리자는 아니다. */
public final class 기억공간 {
    static int[] અનુભાગ_મૂલ્ય = new int[8192];
    static int[] 사용 = new int[8];

    static int પાર્સ_કરો_પૂર્ણાંક(int સરનામું) {
        return ડિવાઇસ_મૂલ્ય.기억읽기(સરનામું) | (ડિવાઇસ_મૂલ્ય.기억읽기(સરનામું + 1) << 8)
            | (ડિવાઇસ_મૂલ્ય.기억읽기(સરનામું + 2) << 16) | (ડિવાઇસ_મૂલ્ય.기억읽기(સરનામું + 3) << 24);
    }

    static int 위쪽기억크기() {
        int સિસ્ટમ_માહિતી = ડિવાઇસ_મૂલ્ય.부팅정보();
        if (ડિવાઇસ_મૂલ્ય.부팅표식() != 0x2badb002 || સિસ્ટમ_માહિતી == 0 || (પાર્સ_કરો_પૂર્ણાંક(સિસ્ટમ_માહિતી) & 1) == 0) return -1;
        return પાર્સ_કરો_પૂર્ણાંક(સિસ્ટમ_માહિતી + 8);
    }

    static int ફાળવો_સંગ્રહ() {
        for (int અનુક્રમણિકા = 0; અનુક્રમણિકા < 사용.length; અનુક્રમણિકા++) {
            if (사용[અનુક્રમણિકા] == 0) {
                사용[અનુક્રમણિકા] = 1;
                for (int સ્લૉટ_પ્રવેશ = 0; સ્લૉટ_પ્રવેશ < 1024; સ્લૉટ_પ્રવેશ++) અનુભાગ_મૂલ્ય[અનુક્રમણિકા * 1024 + સ્લૉટ_પ્રવેશ] = 0;
                return અનુક્રમણિકા;
            }
        }
        return -1;
    }

    static boolean 반환(int અનુક્રમણિકા) {
        if (અનુક્રમણિકા < 0 || અનુક્રમણિકા >= 사용.length || 사용[અનુક્રમણિકા] == 0) return false;
        사용[અનુક્રમણિકા] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int અનુક્રમણિકા = 0; અનુક્રમણિકા < 사용.length; અનુક્રમણિકા++) 개수 += 사용[અનુક્રમણિકા];
        return 개수;
    }
}
