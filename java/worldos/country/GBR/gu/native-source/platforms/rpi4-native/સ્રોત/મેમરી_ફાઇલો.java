    static int 자료읽기(int ફાઈલ, int સ્થિતિ_અનુક્રમણિકા) { return (સામગ્રી_મૂલ્ય[ફાઈલ * 4096 + સ્થિતિ_અનુક્રમણિકા / 4] >>> ((સ્થિતિ_અનુક્રમણિકા & 3) * 8)) & 255; }
    static void લખો_ડેટા(int ફાઈલ, int સ્થિતિ_અનુક્રમણિકા, int મૂલ્ય) {
        int સ્લૉટ_પ્રવેશ = ફાઈલ * 4096 + સ્થિતિ_અનુક્રમણિકા / 4, ખસેડવું_મૂલ્ય = (સ્થિતિ_અનુક્રમણિકા & 3) * 8;
        સામગ્રી_મૂલ્ય[સ્લૉટ_પ્રવેશ] = (સામગ્રી_મૂલ્ય[સ્લૉટ_પ્રવેશ] & ~(255 << ખસેડવું_મૂલ્ય)) | ((મૂલ્ય & 255) << ખસેડવું_મૂલ્ય);
    }

    public static int પાથ_પ્રારંભ(int માપ) {
        પાથ_લંબાઈ = 0;
        if (માપ < 1 || માપ > 63) return -36;
        પાથ_લંબાઈ = માપ;
        for (int લૂપ_અનુક્રમણિકા = 0; લૂપ_અનુક્રમણિકા < માપ; લૂપ_અનુક્રમણિકા++) પથ[લૂપ_અનુક્રમણિકા] = 0;
        return 0;
    }
