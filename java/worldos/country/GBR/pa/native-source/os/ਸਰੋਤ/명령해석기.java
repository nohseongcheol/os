    static int[] 입력 = new int[128];
    static int ਲੰਬਾਈ_ਕੀਮਤ = 0;
    static boolean 앞줄복귀 = false;
    static boolean ਕਤਾਰ_ਓਵਰਫ਼ਲੋ = false;

    static boolean ਕਮਾਂਡ(String ਨਾਂ) {
        if (ਲੰਬਾਈ_ਕੀਮਤ < ਨਾਂ.length()) return false;
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < ਨਾਂ.length(); ਅਨੁਕ੍ਰਮਣਿਕਾ++)
            if (입력[ਅਨੁਕ੍ਰਮਣਿਕਾ] != ਨਾਂ.charAt(ਅਨੁਕ੍ਰਮਣਿਕਾ)) return false;
        return ਲੰਬਾਈ_ਕੀਮਤ == ਨਾਂ.length() || 입력[ਨਾਂ.length()] == ' ';
    }

    static void ਸ਼ੋਅ_ਮਦਦ() {
        ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("apps | run NAME [ARGS] | net\n");
        ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("sync (연결된 JKSTORE1 ਸੰਭਾਲੋ_ਕੀਮਤ 장치에 ਫਾਇਲ 보존)\n");
    }

    static void ਕਾਰਵਾਈ_ਕੀਮਤ_ਦਾਖਲਾ() {
        if (ਲੰਬਾਈ_ਕੀਮਤ == 0) return;
        if (ਕਮਾਂਡ("help")) ਸ਼ੋਅ_ਮਦਦ();
        else if (ਕਮਾਂਡ("sync")) {
            int ਮਾਪ = 파일보존.ਸਿੰਕ_ਕਰੋ();
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("Sync: "); ਪਾਠ_ਟਰਮੀਨਲ.수쓰기(ਮਾਪ); ਪਾਠ_ਟਰਮੀਨਲ.문자(10);
        }
        else if (ਕਮਾਂਡ("ls")) ਮੈਮਰੀ_ਫਾਈਲ_ਸਿਸਟਮ.ਦਾਖਲਾ_ਸੂਚੀ();
        else if (ਕਮਾਂਡ("edit")) ਮੈਮਰੀ_ਫਾਈਲ_ਸਿਸਟਮ.ਕਮਾਂਡ(입력, 4, ਲੰਬਾਈ_ਕੀਮਤ, 0);
        else if (ਕਮਾਂਡ("cat")) ਮੈਮਰੀ_ਫਾਈਲ_ਸਿਸਟਮ.ਕਮਾਂਡ(입력, 3, ਲੰਬਾਈ_ਕੀਮਤ, 1);
        else if (ਕਮਾਂਡ("rm")) ਮੈਮਰੀ_ਫਾਈਲ_ਸਿਸਟਮ.ਕਮਾਂਡ(입력, 2, ਲੰਬਾਈ_ਕੀਮਤ, 2);
        else if (ਕਮਾਂਡ("java") || ਕਮਾਂਡ("javac")) {
            int ਮਾਪ = 실행관리.ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼(입력, 0, ਲੰਬਾਈ_ਕੀਮਤ);
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("Exit: "); ਪਾਠ_ਟਰਮੀਨਲ.수쓰기(ਮਾਪ); ਪਾਠ_ਟਰਮੀਨਲ.문자(10);
        }
        else if (ਕਮਾਂਡ("apps")) 실행관리.ਦਾਖਲਾ_ਸੂਚੀ();
        else if (ਕਮਾਂਡ("net")) ਨੈਟਵਰਕ_ਸਟੈਕ.ਸਥਿਤੀ_ਕੀਮਤ();
        else if (ਕਮਾਂਡ("run")) {
            int ਮਾਪ = 실행관리.ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼(입력, 3, ਲੰਬਾਈ_ਕੀਮਤ);
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("Exit: "); ਪਾਠ_ਟਰਮੀਨਲ.수쓰기(ਮਾਪ); ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("\n");
        } else if (ਕਮਾਂਡ("info")) {
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (ਕਮਾਂਡ("mem")) {
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("위쪽 ਮੈਮਰੀ_ਕੀਮਤ 공간(KiB): "); ਪਾਠ_ਟਰਮੀਨਲ.수쓰기(기억공간.위쪽기억크기());
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("\n배열 동적 ਮੈਮਰੀ_ਕੀਮਤ 공간(ਬਾਈਟ_ਕੀਮਤ): "); ਪਾਠ_ਟਰਮੀਨਲ.수쓰기(ਤਜਵੀਜ_ਕੀਮਤ.ਤਰਤੀਬ_ਦੇਣਾ_ਵਰਤੋਂ());
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ(" / 262144\n작업 공간 ਵਿਭਾਗ_ਕੀਮਤ: "); ਪਾਠ_ਟਰਮੀਨਲ.수쓰기(기억공간.사용개수());
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ(" / 8 (각 4096바이트)\n");
        } else if (ਕਮਾਂਡ("alloc")) {
            int ਅਨੁਕ੍ਰਮਣਿਕਾ = 기억공간.ਨਿਰਧਾਰਿਤ_ਕਰੋ_ਸਟੋਰੇਜ();
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("ਵਿਭਾਗ_ਕੀਮਤ ਅਨੁਕ੍ਰਮਣਿਕਾ: "); ਪਾਠ_ਟਰਮੀਨਲ.수쓰기(ਅਨੁਕ੍ਰਮਣਿਕਾ); ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("\n");
        } else if (ਕਮਾਂਡ("free")) {
            if (ਲੰਬਾਈ_ਕੀਮਤ == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ(기억공간.반환(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 ਵਿਭਾਗ_ਕੀਮਤ\n");
            } else ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("사용법: free 0..7\n");
        } else if (ਕਮਾਂਡ("echo")) {
            for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 5; ਅਨੁਕ੍ਰਮਣਿਕਾ < ਲੰਬਾਈ_ਕੀਮਤ; ਅਨੁਕ੍ਰਮਣਿਕਾ++) ਪਾਠ_ਟਰਮੀਨਲ.문자(입력[ਅਨੁਕ੍ਰਮਣਿਕਾ]);
            ਪਾਠ_ਟਰਮੀਨਲ.문자(10);
        } else if (ਕਮਾਂਡ("clear")) ਪਾਠ_ਟਰਮੀਨਲ.지우기();
        else if (ਕਮਾਂਡ("test")) ਪੱਕੇ_ਹੋਣਾ.시험();
        else if (ਕਮਾਂਡ("halt")) {
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("HALTED\n");
            ਤਜਵੀਜ_ਕੀਮਤ.정지();
        } else ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int ਕੀਮਤ) {
        if (ਕੀਮਤ == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = ਕੀਮਤ == 13;
        if (ਕੀਮਤ == 10 || ਕੀਮਤ == 13) {
            ਪਾਠ_ਟਰਮੀਨਲ.문자(10);
            if (ਮੈਮਰੀ_ਫਾਈਲ_ਸਿਸਟਮ.편집중) ਮੈਮਰੀ_ਫਾਈਲ_ਸਿਸਟਮ.편집줄(입력, ਲੰਬਾਈ_ਕੀਮਤ, ਕਤਾਰ_ਓਵਰਫ਼ਲੋ);
            else ਕਾਰਵਾਈ_ਕੀਮਤ_ਦਾਖਲਾ();
            ਲੰਬਾਈ_ਕੀਮਤ = 0;
            ਕਤਾਰ_ਓਵਰਫ਼ਲੋ = false;
            ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ(ਮੈਮਰੀ_ਫਾਈਲ_ਸਿਸਟਮ.편집중 ? "...> " : "jkoros> ");
        } else if (ਕੀਮਤ == 8 || ਕੀਮਤ == 127) {
            if (ਲੰਬਾਈ_ਕੀਮਤ > 0) {
                ਲੰਬਾਈ_ਕੀਮਤ--;
                ਪਾਠ_ਟਰਮੀਨਲ.직렬바이트(8); ਪਾਠ_ਟਰਮੀਨਲ.직렬바이트(32); ਪਾਠ_ਟਰਮੀਨਲ.직렬바이트(8);
                ਪਾਠ_ਟਰਮੀਨਲ.화면문자(8);
            }
        } else if (ਕੀਮਤ >= 32 && ਕੀਮਤ < 127 && ਲੰਬਾਈ_ਕੀਮਤ < 입력.length) {
            입력[ਲੰਬਾਈ_ਕੀਮਤ++] = ਕੀਮਤ;
            ਪਾਠ_ਟਰਮੀਨਲ.문자(ਕੀਮਤ);
        } else if (ਕੀਮਤ >= 32 && ਕੀਮਤ < 127) ਕਤਾਰ_ਓਵਰਫ਼ਲੋ = true;
    }

    static void ਚਲਾਓ_2() {
        ਸ਼ੋਅ_ਮਦਦ();
        ਪਾਠ_ਟਰਮੀਨਲ.ਲਿਖਣ("READY\njkoros> ");
        while (true) {
            int ਕੀਮਤ = ਪਾਠ_ਟਰਮੀਨਲ.직렬읽기();
            if (ਕੀਮਤ < 0) ਕੀਮਤ = ਕੀਬੋਰਡ.ਪੜ੍ਹਨ();
            if (ਕੀਮਤ >= 0) 받아쓰기(ਕੀਮਤ);
            else { ਨੈਟਵਰਕ_ਸਟੈਕ.ਤਸਦੀਕ(); ਤਜਵੀਜ_ਕੀਮਤ.잠시양보(); }
        }
    }
