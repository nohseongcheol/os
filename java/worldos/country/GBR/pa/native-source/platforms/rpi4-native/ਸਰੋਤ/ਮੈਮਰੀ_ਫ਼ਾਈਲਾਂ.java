    static void ਲਿੱਖੋ_ਸਮੱਗਰੀ(int ਫਾਇਲ, int ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ, int ਕੀਮਤ) {
        int ਸਲੌਟ_ਦਾਖਲਾ = ਫਾਇਲ * 4096 + ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ / 4, ਖਿਸਕਾਉਣਾ_ਕੀਮਤ = (ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ & 3) * 8;
        ਤਤਕਰਾ_ਕੀਮਤ[ਸਲੌਟ_ਦਾਖਲਾ] = (ਤਤਕਰਾ_ਕੀਮਤ[ਸਲੌਟ_ਦਾਖਲਾ] & ~(255 << ਖਿਸਕਾਉਣਾ_ਕੀਮਤ)) | ((ਕੀਮਤ & 255) << ਖਿਸਕਾਉਣਾ_ਕੀਮਤ);
    }

    public static int ਰਸਤਾ_ਸੁਰੂ(int ਆਕਾਰ) {
        ਰਸਤਾ_ਲੰਬਾਈ = 0;
        if (ਆਕਾਰ < 1 || ਆਕਾਰ > 63) return -36;
        ਰਸਤਾ_ਲੰਬਾਈ = ਆਕਾਰ;
        for (int ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ < ਆਕਾਰ; ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ++) ਮਾਰਗ[ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ] = 0;
        return 0;
    }
