public class 한글소스 {
    public static void main(String[] ਆਰਗੂਮੈਂਟ) throws ਪੰਜਾਬੀ.자체.입출력예외 {
        ਪੰਜਾਬੀ.자체.ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ("자체 컴파일러와 ਪੰਜਾਬੀ ਪੁਸਤਕਾਲਾ");
        int 글자수 = ਪੰਜਾਬੀ.자체.문자.코드포인트수("한글😀");
        ਪੰਜਾਬੀ.자체.ਆਉਟਪੁੱਟ.수쓰기(글자수);
        ਪੰਜਾਬੀ.자체.ਫਾਇਲ.ਲਿਖਣ("한글자료.txt", "자체 ਪੱਕੇ_ਹੋਣਾ_ਕੀਮਤ 안에서 저장한 한글😀");
        ਪੰਜਾਬੀ.자체.ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ(ਪੰਜਾਬੀ.자체.ਫਾਇਲ.ਪੜ੍ਹਨ("한글자료.txt"));
    }
}
