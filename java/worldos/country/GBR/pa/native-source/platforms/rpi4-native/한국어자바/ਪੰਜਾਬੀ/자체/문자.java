    public static int ਪਦ_ਵਿਆਖਿਆ_ਕਰੋ_ਪੂਰਣ_ਅੰਕ(String ਟੈਕਸਟ) { try { return Integer.parseInt(ਟੈਕਸਟ); } catch (NumberFormatException ਗਲਤੀ) { throw new 숫자형식예외("숫자의 형식이나 범위를 확인하십시오."); } }
    public static String ਲਿੱਖੋ_ਪੂਰਣ_ਅੰਕ_ਕੀਮਤ(int 수) { return Integer.toString(수); }
    public static int 코드포인트수(String ਟੈਕਸਟ) {
        int 수 = 0;
        for (int ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ < ਟੈਕਸਟ.length(); ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ++, 수++) {
            int ਵਰਣ_ਕੋਡ = ਟੈਕਸਟ.charAt(ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ);
            if (ਵਰਣ_ਕੋਡ >= 0xd800 && ਵਰਣ_ਕੋਡ <= 0xdbff && ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ + 1 < ਟੈਕਸਟ.length() && ਟੈਕਸਟ.charAt(ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ + 1) >= 0xdc00 && ਟੈਕਸਟ.charAt(ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ + 1) <= 0xdfff) ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ++;
        }
        return 수;
    }
    public static byte[] 부호화(String ਟੈਕਸਟ) {
        byte[] 임시 = new byte[ਟੈਕਸਟ.length() * 3]; int 쓴수 = 0;
        for (int ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ < ਟੈਕਸਟ.length(); ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
            int ਵਰਣ_ਕੋਡ = ਟੈਕਸਟ.charAt(ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ);
            if (ਵਰਣ_ਕੋਡ >= 0xd800 && ਵਰਣ_ਕੋਡ <= 0xdbff && ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ + 1 < ਟੈਕਸਟ.length() && ਟੈਕਸਟ.charAt(ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ + 1) >= 0xdc00 && ਟੈਕਸਟ.charAt(ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ + 1) <= 0xdfff) ਵਰਣ_ਕੋਡ = 0x10000 + ((ਵਰਣ_ਕੋਡ - 0xd800) << 10) + ਟੈਕਸਟ.charAt(++ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ) - 0xdc00;
            else if (ਵਰਣ_ਕੋਡ >= 0xd800 && ਵਰਣ_ਕੋਡ <= 0xdfff) ਵਰਣ_ਕੋਡ = '?';
            if (ਵਰਣ_ਕੋਡ < 128) 임시[쓴수++] = (byte)ਵਰਣ_ਕੋਡ;
            else if (ਵਰਣ_ਕੋਡ < 2048) { 임시[쓴수++] = (byte)(192 | ਵਰਣ_ਕੋਡ >> 6); 임시[쓴수++] = (byte)(128 | ਵਰਣ_ਕੋਡ & 63); }
            else if (ਵਰਣ_ਕੋਡ < 65536) { 임시[쓴수++] = (byte)(224 | ਵਰਣ_ਕੋਡ >> 12); 임시[쓴수++] = (byte)(128 | ਵਰਣ_ਕੋਡ >> 6 & 63); 임시[쓴수++] = (byte)(128 | ਵਰਣ_ਕੋਡ & 63); }
            else { 임시[쓴수++] = (byte)(240 | ਵਰਣ_ਕੋਡ >> 18); 임시[쓴수++] = (byte)(128 | ਵਰਣ_ਕੋਡ >> 12 & 63); 임시[쓴수++] = (byte)(128 | ਵਰਣ_ਕੋਡ >> 6 & 63); 임시[쓴수++] = (byte)(128 | ਵਰਣ_ਕੋਡ & 63); }
        }
        byte[] ਮਾਪ = new byte[쓴수]; System.arraycopy(임시, 0, ਮਾਪ, 0, 쓴수); return ਮਾਪ;
    }
    /** 잘못된 UTF-8은 잘못된인수예외으로 거부한다. */
    public static String ਬਦਲਾਵ_ਕਰੋ_ਸਮੱਗਰੀ(byte[] ਬਾਈਟ_ਕੀਮਤ) {
        StringBuilder ਮਾਪ = new StringBuilder();
        for (int ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ < ਬਾਈਟ_ਕੀਮਤ.length;) {
            int ਵਰਣ_ਕੋਡ = ਬਾਈਟ_ਕੀਮਤ[ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ++] & 255, 수 = ਵਰਣ_ਕੋਡ < 128 ? 0 : ਵਰਣ_ਕੋਡ >= 194 && ਵਰਣ_ਕੋਡ < 224 ? 1 : ਵਰਣ_ਕੋਡ >= 224 && ਵਰਣ_ਕੋਡ < 240 ? 2 : ਵਰਣ_ਕੋਡ >= 240 && ਵਰਣ_ਕੋਡ <= 244 ? 3 : -1;
            if (수 < 0 || ਬਾਈਟ_ਕੀਮਤ.length - ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ < 수) throw new 잘못된인수예외("잘못된 UTF-8");
            int 최소 = 수 == 1 ? 128 : 수 == 2 ? 2048 : 수 == 3 ? 65536 : 0;
            if (수 > 0) ਵਰਣ_ਕੋਡ &= (1 << (6 - 수)) - 1;
            for (int ਅੰਦਰੂਨੀ_ਜੋੜ_ਸਥਿਤੀ_ਬਦਲੋ = 0; ਅੰਦਰੂਨੀ_ਜੋੜ_ਸਥਿਤੀ_ਬਦਲੋ < 수; ਅੰਦਰੂਨੀ_ਜੋੜ_ਸਥਿਤੀ_ਬਦਲੋ++) { int ਪਿਛਲਾ_ਕੀਮਤ = ਬਾਈਟ_ਕੀਮਤ[ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ++] & 255; if ((ਪਿਛਲਾ_ਕੀਮਤ & 192) != 128) throw new 잘못된인수예외("잘못된 UTF-8"); ਵਰਣ_ਕੋਡ = ਵਰਣ_ਕੋਡ << 6 | ਪਿਛਲਾ_ਕੀਮਤ & 63; }
            if (ਵਰਣ_ਕੋਡ < 최소 || ਵਰਣ_ਕੋਡ > 0x10ffff || ਵਰਣ_ਕੋਡ >= 0xd800 && ਵਰਣ_ਕੋਡ <= 0xdfff) throw new 잘못된인수예외("잘못된 UTF-8");
            if (ਵਰਣ_ਕੋਡ < 65536) ਮਾਪ.append((char)ਵਰਣ_ਕੋਡ);
            else { ਵਰਣ_ਕੋਡ -= 65536; ਮਾਪ.append((char)(0xd800 | ਵਰਣ_ਕੋਡ >> 10)); ਮਾਪ.append((char)(0xdc00 | ਵਰਣ_ਕੋਡ & 1023)); }
        }
        return ਮਾਪ.toString();
    }
