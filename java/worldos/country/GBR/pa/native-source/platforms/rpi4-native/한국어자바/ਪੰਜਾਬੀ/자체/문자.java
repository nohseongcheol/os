    public static int ਲੰਬਾਈ_ਕੀਮਤ(String ਟੈਕਸਟ) { return ਟੈਕਸਟ.length(); }
    public static boolean 같음(String 앞, String ਪਿਛਲਾ_ਕੀਮਤ) { return 앞 == null ? ਪਿਛਲਾ_ਕੀਮਤ == null : 앞.equals(ਪਿਛਲਾ_ਕੀਮਤ); }
    public static String ਚਿਪਕਾਊਣਾ_ਪਾਠ(String 앞, String ਪਿਛਲਾ_ਕੀਮਤ) { return 앞.concat(ਪਿਛਲਾ_ਕੀਮਤ); }
