        பிரிவு_பாதை = Path(작업경로)
        இயக்கு_கட்டளை(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', பிரிவு_பாதை, '-sourcepath', பிரிவு_பாதை, '-d', பிரிவு_பாதை] +
            [தரவு_நிலை for தரவு_நிலை in sorted((தொகுபதிவகம்_பாதை / 'os/பயனர்/자바').glob('*.java')) if தரவு_நிலை.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
