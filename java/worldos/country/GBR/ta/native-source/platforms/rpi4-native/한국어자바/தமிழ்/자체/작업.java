/** 작업 தொடரிழை_மதிப்பு: 하나의 இயக்கு_கட்டளை தொடரோடி_மதிப்பு. 자체 JVM 안에서 கட்டளை 수를 기준으로 번갈아 실행한다. */
public final class 작업 {
    private 작업() {}
    public static 작업가닥 செயல்படுத்துக(실행할일 பணி_செயல்) { 작업가닥 தொடரிழை_மதிப்பு = new 작업가닥(பணி_செயல்); தொடரிழை_மதிப்பு.தொடங்கு_பணி(); return தொடரிழை_மதிப்பு; }
    public static void 기다리기(작업가닥 தொடரிழை_மதிப்பு) throws 대기중단예외 { தொடரிழை_மதிப்பு.기다리기(); }
    public static boolean 살아있는가(작업가닥 தொடரிழை_மதிப்பு) { return தொடரிழை_மதிப்பு.살아있는가(); }
    public static void இடைநீக்கம்_செய்யப்பட்டது_பணி() { 작업가닥.இடைநீக்கம்_செய்யப்பட்டது_பணி(); }
}
