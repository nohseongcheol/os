/** 첫 IDE 장치의 512바이트 논리 صیغہ_قدر. 이 계층은 포맷을 만들거나 임의 장치를 지우지 않는다. */
public final class ذخیرہ_آلہ_رابطہ {
    static boolean معلومات_ٹیکنالوجی_دستیاب = false;
    static int[] صیغہ_کوائف = new int[512];
    static void 잠깐기다리기() {
        for (int اشاریہ = 0; اشاریہ < 4; اشاریہ++) آلہ_قدر.입출력바이트읽기(0x3f6);
    }
    static int 준비기다리기(boolean 자료필요) {
        int چلائیں = آلہ_قدر.밀리초();
        while (آلہ_قدر.밀리초() - چلائیں < 500) {
            int حالت_قدر = آلہ_قدر.입출력바이트읽기(0x1f7);
            if (حالت_قدر == 0 || حالت_قدر == 255) return -19;
            if ((حالت_قدر & 128) == 0) {
                if ((حالت_قدر & 33) != 0) return -5;
                if (!자료필요 || (حالت_قدر & 8) != 0) return 0;
            }
            آلہ_قدر.잠시양보();
        }
        return -110;
    }
    static int 요청(int صیغہ_قدر, int حکم) {
        if (صیغہ_قدر < 0 || صیغہ_قدر >= 2048) return -22;
        آلہ_قدر.입출력바이트쓰기(0x3f6, 2); // polling; IDE IRQ 사용 안 함
        آلہ_قدر.입출력바이트쓰기(0x1f6, 0xe0); 잠깐기다리기();
        int پیمائش = 준비기다리기(false);
        if (پیمائش < 0) return پیمائش;
        آلہ_قدر.입출력바이트쓰기(0x1f2, 1);
        آلہ_قدر.입출력바이트쓰기(0x1f3, صیغہ_قدر & 255);
        آلہ_قدر.입출력바이트쓰기(0x1f4, (صیغہ_قدر >>> 8) & 255);
        آلہ_قدر.입출력바이트쓰기(0x1f5, 0);
        آلہ_قدر.입출력바이트쓰기(0x1f7, حکم); 잠깐기다리기();
        return 준비기다리기(true);
    }
    static int پڑھیں(int صیغہ_قدر) {
        int پیمائش = 요청(صیغہ_قدر, 0x20);
        if (پیمائش < 0) return پیمائش;
        for (int اشاریہ = 0; اشاریہ < 256; اشاریہ++) {
            int قدر = آلہ_قدر.입출력짧은수읽기(0x1f0);
            صیغہ_کوائف[اشاریہ * 2] = قدر & 255; صیغہ_کوائف[اشاریہ * 2 + 1] = قدر >>> 8;
        }
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int لکھیں(int صیغہ_قدر) {
        if (!معلومات_ٹیکنالوجی_دستیاب || صیغہ_قدر < 1 || صیغہ_قدر > 518) return -19;
        int پیمائش = 요청(صیغہ_قدر, 0x30);
        if (پیمائش < 0) return پیمائش;
        for (int اشاریہ = 0; اشاریہ < 256; اشاریہ++)
            آلہ_قدر.입출력짧은수쓰기(0x1f0, صیغہ_کوائف[اشاریہ * 2] | صیغہ_کوائف[اشاریہ * 2 + 1] << 8);
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int 밀어쓰기() {
        if (!معلومات_ٹیکنالوجی_دستیاب) return -19;
        آلہ_قدر.입출력바이트쓰기(0x1f7, 0xe7); 잠깐기다리기();
        return 준비기다리기(false);
    }
    static int پارس_سالم_عدد(int مقام) {
        return صیغہ_کوائف[مقام] | صیغہ_کوائف[مقام + 1] << 8 | صیغہ_کوائف[مقام + 2] << 16 | صیغہ_کوائف[مقام + 3] << 24;
    }
    static void لکھیں_سالم_عدد_قدر(int مقام, int قدر) {
        for (int اشاریہ = 0; اشاریہ < 4; اشاریہ++) صیغہ_کوائف[مقام + اشاریہ] = (قدر >>> (اشاریہ * 8)) & 255;
    }
}
