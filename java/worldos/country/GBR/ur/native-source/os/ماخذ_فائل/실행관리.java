/** پڑھیں 전용 نفاذ_کریں_حکم 묶음의 ELF32 جواز_دہی_کریں, دلائل فارورڈ_قدر, 한 번에 한 صارف عمل_قدر نفاذ_کریں_حکم. */
public final class 실행관리 {
    static final int ابتدا_صارف_ایپ = 0x04000000;
    static final int صارف_اختتام = 0x04400000;
    static final int نقش_اختتام_پتہ = 0x04200000;
    static final int دلائل_ابتدا = 0x04300000;
    static int 인수수 = 0;
    static int[] دلائل_پتہ = new int[16];

    static boolean تراشہ(int پتہ, int لمبا_ئی_قدر) {
        return پتہ >= ابتدا_صارف_ایپ && پتہ < صارف_اختتام && لمبا_ئی_قدر >= 0 && لمبا_ئی_قدر <= صارف_اختتام - پتہ;
    }

    static int 수(int پتہ) { return 기억공간.پارس_سالم_عدد(پتہ); }
    static int 짧은수(int پتہ) { return آلہ_قدر.기억읽기(پتہ) | آلہ_قدر.기억읽기(پتہ + 1) << 8; }
    static void 수쓰기(int پتہ, int قدر) {
        for (int اشاریہ = 0; اشاریہ < 4; اشاریہ++) آلہ_قدر.لکھیں_میموری(پتہ + اشاریہ, قدر >>> (اشاریہ * 8));
    }

    static int 묶음개수() {
        int پتہ = آلہ_قدر.실행묶음();
        int حجم = آلہ_قدر.실행묶음크기();
        if (حجم < 8 || 수(پتہ) != 0x50414b4a) return 0;
        int 개수 = 수(پتہ + 4);
        return 개수 >= 0 && 개수 <= 32 && 개수 <= (حجم - 8) / 24 ? 개수 : 0;
    }

    static void اندراج_فہرست() {
        for (int اشاریہ = 0; اشاریہ < 묶음개수(); اشاریہ++) {
            int اندراج_قدر = آلہ_قدر.실행묶음() + 8 + اشاریہ * 24;
            for (int کریکٹر_قدر = 0; کریکٹر_قدر < 16 && آلہ_قدر.기억읽기(اندراج_قدر + کریکٹر_قدر) != 0; کریکٹر_قدر++)
                متن_ٹرمینل.문자(آلہ_قدر.기억읽기(اندراج_قدر + کریکٹر_قدر));
            متن_ٹرمینل.لکھیں("\n");
        }
    }

    static int ڈھونڈیں_اندراج(int[] 입력, int چلائیں, int لمبا_ئی_قدر) {
        if (لمبا_ئی_قدر <= 0 || لمبا_ئی_قدر >= 16) return 0;
        for (int اشاریہ = 0; اشاریہ < 묶음개수(); اشاریہ++) {
            int اندراج_قدر = آلہ_قدر.실행묶음() + 8 + اشاریہ * 24;
            boolean 같음 = آلہ_قدر.기억읽기(اندراج_قدر + لمبا_ئی_قدر) == 0;
            for (int کریکٹر_قدر = 0; کریکٹر_قدر < لمبا_ئی_قدر; کریکٹر_قدر++)
                if (입력[چلائیں + کریکٹر_قدر] != آلہ_قدر.기억읽기(اندراج_قدر + کریکٹر_قدر)) 같음 = false;
            if (같음) return اندراج_قدر;
        }
        return 0;
    }

    static int جواز_دہی_کریں(int فائل_کا_نام, int لمبا_ئی_قدر) {
        if (لمبا_ئی_قدر < 52 || 수(فائل_کا_نام) != 0x464c457f || آلہ_قدر.기억읽기(فائل_کا_نام + 4) != 1
            || آلہ_قدر.기억읽기(فائل_کا_نام + 5) != 1 || آلہ_قدر.기억읽기(فائل_کا_نام + 6) != 1
            || 짧은수(فائل_کا_نام + 16) != 2 || 짧은수(فائل_کا_نام + 18) != 3 || 수(فائل_کا_نام + 20) != 1
            || 짧은수(فائل_کا_نام + 40) != 52 || 짧은수(فائل_کا_نام + 42) != 32) return -8;
        int اندراج_نقطہ_قدر = 수(فائل_کا_نام + 24);
        int جدول_پوزیشن_ٹھیک_کریں = 수(فائل_کا_نام + 28);
        int 개수 = 짧은수(فائل_کا_نام + 44);
        if (개수 == 0 || 개수 > 16 || جدول_پوزیشن_ٹھیک_کریں < 52 || جدول_پوزیشن_ٹھیک_کریں > لمبا_ئی_قدر - 개수 * 32) return -8;
        boolean 실행가능 = false;
        for (int اشاریہ = 0; اشاریہ < 개수; اشاریہ++) {
            int لُک_اپ_جدول = فائل_کا_نام + جدول_پوزیشن_ٹھیک_کریں + اشاریہ * 32;
            int 종류 = 수(لُک_اپ_جدول);
            if (종류 == 2 || 종류 == 3) return -8; // 동적 متصل_ہوں/해석기 미지원
            if (종류 != 1) continue;
            int مقام = 수(لُک_اپ_جدول + 4), پتہ = 수(لُک_اپ_جدول + 8), فائل_سائز_دیں = 수(لُک_اپ_جدول + 16), میموری_سائز_دیں = 수(لُک_اپ_جدول + 20);
            int سیدھ_میں_لائیں_قدر = 수(لُک_اپ_جدول + 28);
            if (پتہ < ابتدا_صارف_ایپ || پتہ >= نقش_اختتام_پتہ || میموری_سائز_دیں < 0 || میموری_سائز_دیں > نقش_اختتام_پتہ - پتہ
                || فائل_سائز_دیں < 0 || فائل_سائز_دیں > میموری_سائز_دیں || مقام < 0 || (فائل_سائز_دیں > 0 && مقام > لمبا_ئی_قدر - فائل_سائز_دیں)
                || (سیدھ_میں_لائیں_قدر != 0 && (سیدھ_میں_لائیں_قدر < 0 || (سیدھ_میں_لائیں_قدر & (سیدھ_میں_لائیں_قدر - 1)) != 0
                    || ((پتہ - مقام) & (سیدھ_میں_لائیں_قدر - 1)) != 0))) return -8;
            for (int 앞 = 0; 앞 < اشاریہ; 앞++) {
                int 이전 = فائل_کا_نام + جدول_پوزیشن_ٹھیک_کریں + 앞 * 32;
                if (수(이전) == 1 && میموری_سائز_دیں > 0 && 수(이전 + 20) > 0
                    && پتہ < 수(이전 + 8) + 수(이전 + 20) && 수(이전 + 8) < پتہ + میموری_سائز_دیں) return -8;
            }
            if ((수(لُک_اپ_جدول + 24) & 1) != 0 && اندراج_نقطہ_قدر >= پتہ && اندراج_نقطہ_قدر - پتہ < فائل_سائز_دیں) 실행가능 = true;
        }
        return 실행가능 ? اندراج_نقطہ_قدر : -8;
    }

    static int نفاذ_کریں_حکم(int[] 입력, int چلائیں, int لمبا_ئی_قدر) {
        while (چلائیں < لمبا_ئی_قدر && 입력[چلائیں] == ' ') چلائیں++;
        int 끝 = چلائیں;
        while (끝 < لمبا_ئی_قدر && 입력[끝] != ' ') 끝++;
        int اندراج_قدر = ڈھونڈیں_اندراج(입력, چلائیں, 끝 - چلائیں);
        if (اندراج_قدر == 0) return -2;
        int مقام = 수(اندراج_قدر + 16), حجم = 수(اندراج_قدر + 20);
        if (مقام < 8 + 묶음개수() * 24 || حجم < 52 || مقام > آلہ_قدر.실행묶음크기() - حجم) return -8;
        int فائل_کا_نام = آلہ_قدر.실행묶음() + مقام;
        int اندراج_نقطہ_قدر = جواز_دہی_کریں(فائل_کا_نام, حجم);
        if (اندراج_نقطہ_قدر < 0) return اندراج_نقطہ_قدر;
        آلہ_قدر.صارف_صاف_مشمولات();
        int جدول_پوزیشن_ٹھیک_کریں = 수(فائل_کا_نام + 28), 개수 = 짧은수(فائل_کا_نام + 44);
        for (int اشاریہ = 0; اشاریہ < 개수; اشاریہ++) {
            int لُک_اپ_جدول = فائل_کا_نام + جدول_پوزیشن_ٹھیک_کریں + اشاریہ * 32;
            if (수(لُک_اپ_جدول) != 1) continue;
            int 원본 = فائل_کا_نام + 수(لُک_اپ_جدول + 4), منزل_مقصود_قدر = 수(لُک_اپ_جدول + 8), فائل_سائز_دیں = 수(لُک_اپ_جدول + 16);
            for (int بائٹ_قدر = 0; بائٹ_قدر < فائل_سائز_دیں; بائٹ_قدر++) آلہ_قدر.لکھیں_میموری(منزل_مقصود_قدر + بائٹ_قدر, آلہ_قدر.기억읽기(원본 + بائٹ_قدر));
        }
        인수수 = 0;
        int ذخیرہ_کریں_قدر = دلائل_ابتدا;
        while (끝 < لمبا_ئی_قدر) {
            while (끝 < لمبا_ئی_قدر && 입력[끝] == ' ') 끝++;
            if (끝 == لمبا_ئی_قدر) break;
            if (인수수 == دلائل_پتہ.length) return -22;
            چلائیں = 끝;
            while (끝 < لمبا_ئی_قدر && 입력[끝] != ' ') 끝++;
            دلائل_پتہ[인수수++] = ذخیرہ_کریں_قدر;
            수쓰기(ذخیرہ_کریں_قدر, 끝 - چلائیں);
            for (int کریکٹر_قدر = چلائیں; کریکٹر_قدر < 끝; کریکٹر_قدر++) 수쓰기(ذخیرہ_کریں_قدر + 4 + (کریکٹر_قدر - چلائیں) * 4, 입력[کریکٹر_قدر]);
            ذخیرہ_کریں_قدر += 4 + (끝 - چلائیں) * 4;
        }
        نیٹ_ورک_اسٹیک.صاف_عمل();
        파일서술자관리.ابتدا_عمل();
        int پیمائش = آلہ_قدر.چلائیں_صارف_ایپ(اندراج_نقطہ_قدر, صارف_اختتام - 16);
        파일서술자관리.صاف_عمل();
        نیٹ_ورک_اسٹیک.صاف_عمل();
        return پیمائش;
    }
}
