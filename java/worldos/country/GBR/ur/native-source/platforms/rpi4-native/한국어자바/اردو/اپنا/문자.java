            if (کریکٹر_ضابطہ < 최소 || کریکٹر_ضابطہ > 0x10ffff || کریکٹر_ضابطہ >= 0xd800 && کریکٹر_ضابطہ <= 0xdfff) throw new بے_جواز_دلائل_استثنا("잘못된 UTF-8");
