    private static void 기억공간시험(کرنیل کرنیل_قدر) {
        میموری_مینیجر مینیجر_قدر = کرنیل_قدر.기억공간();
        int 첫주소 = مینیجر_قدر.정렬할당(100, 64);
        تصدیق_کریں((첫주소 & 63) == 0, "سیدھ_میں_لائیں_قدر مختص_کریں_ذخیرہ");
        مینیجر_قدر.لکھیں_بائٹ_قدر(첫주소, (byte) 0x5a);
        تصدیق_کریں(مینیجر_قدر.바이트읽기(첫주소) == (byte) 0x5a, "물리 기억공간 읽고 لکھیں");
        int 사용전 = مینیجر_قدر.사용크기();
        مینیجر_قدر.ریلیز_ذخیرہ(첫주소);
        تصدیق_کریں(مینیجر_قدر.사용크기() < 사용전, "기억공간 ریلیز_ذخیرہ");
    }

    private static void 쪽관리시험(کرنیل کرنیل_قدر) {
        صفحہ_مینیجر مینیجر_قدر = کرنیل_قدر.쪽관리();
        صفحہ_مینیجر.پتہ_اسپیس 부모공간 = مینیجر_قدر.새주소공간();
        مینیجر_قدر.میپ_صفحہ(부모공간, 0x1000, true);
        مینیجر_قدر.لکھیں_بائٹ_قدر(부모공간, 0x1010, (byte) 7);
        صفحہ_مینیجر.پتہ_اسپیس بچہ_اسپیس = مینیجر_قدر.쓰기시복사복제(부모공간);
        مینیجر_قدر.لکھیں_بائٹ_قدر(بچہ_اسپیس, 0x1010, (byte) 9);
        تصدیق_کریں(مینیجر_قدر.바이트읽기(부모공간, 0x1010) == 7, "لکھیں 시 نقل_قدر 부모 격리");
        تصدیق_کریں(مینیجر_قدر.바이트읽기(بچہ_اسپیس, 0x1010) == 9, "لکھیں 시 نقل_قدر بچہ_قدر لکھیں");
    }

    private static void 파일과과정시험(کرنیل کرنیل_قدر) {
        byte[] مشمول_قدر = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        کرنیل_قدر.فائل_نظام().파일추가("시험", مشمول_قدر);
        عمل_قدر 부모 = کرنیل_قدر.첫과정();
        체계호출 호출 = کرنیل_قدر.체계호출();
        int 서술자 = 호출.کھولیں(부모, "/시험", 체계호출.فقط_مطالعہ_پرچم);
        تصدیق_کریں(서술자 >= 3, "فائل_کا_نام کھولیں");

        byte[] 받을곳 = new byte[مشمول_قدر.length];
        تصدیق_کریں(호출.پڑھیں(부모, 서술자, 받을곳, 받을곳.length) == مشمول_قدر.length, "فائل_کا_نام پڑھیں");
        تصدیق_کریں(Arrays.equals(مشمول_قدر, 받을곳), "فائل_کا_نام مشمول_قدر");
        تصدیق_کریں(호출.منتقل_کریں_پوزیشن_ٹھیک_کریں(부모, 서술자, 0, 체계호출.تلاش_ابتدا) == 0, "فائل_کا_نام مقام منتقل_کریں_قدر");

        int 복제서술자 = 호출.서술자복제(부모, 서술자);
        تصدیق_کریں(복제서술자 >= 0, "서술자 복제");
        عمل_قدر بچہ_قدر = 호출.과정복제(부모);
        تصدیق_کریں(بچہ_قدر.شناخت_کنندہ_قدر() != 부모.شناخت_کنندہ_قدر(), "عمل_قدر شناخت_کنندہ_قدر 분리");
        تصدیق_کریں(بچہ_قدر.부모식별자() == 부모.شناخت_کنندہ_قدر(), "부모 عمل_قدر شناخت_کنندہ_قدر");
        تصدیق_کریں(호출.بند_کریں(بچہ_قدر, 서술자) == 0 && 부모.파일서술자().معلومات_ٹیکنالوجی_بنائیں(서술자), "بچہ_قدر بند_کریں 격리");

        int 이전끝 = 호출.프로그램끝늘리기(부모, 8192);
        تصدیق_کریں(이전끝 == 0x06000000, "ایپ_f5044b9b 끝 늘리기");
        تصدیق_کریں(부모.프로그램끝() == 0x06002000, "ایپ_f5044b9b 끝 반영");
        تصدیق_کریں(بچہ_قدر.프로그램끝() == 0x06000000, "과정별 ایپ_f5044b9b 끝 격리");

        بچہ_قدر.خروج_ایپ(7);
        تصدیق_کریں(호출.자식기다리기(부모, بچہ_قدر.شناخت_کنندہ_قدر(), false) == (7 << 8), "بچہ_قدر خروج_ایپ 기다리기");
        تصدیق_کریں(호출.접근가능("시험", 1) == -13, "نفاذ_کریں_حکم اجازت_قدر رد_کریں_قدر");
        تصدیق_کریں(호출.صارف_شناخت_کنندہ() == 0 && 호출.گروپ_شناخت_کنندہ() == 0, "사용자와 무리 شناخت_کنندہ_قدر");
        تصدیق_کریں("/".equals(호출.현재작업목록(2)) && 호출.سوئچ_ٹاسک_فہرست("/") == 0, "현재 작업 اندراج_فہرست");
        تصدیق_کریں(호출.معلومات_ٹیکنالوجی_ٹرمینل(부모, 1), "표준 اخراج_کا_مقام 단말");
        تصدیق_کریں("JGbrOS".equals(호출.체계정보().نظام_نام()), "آپریٹنگ_سسٹم_قدر نظام_کی_معلومات");
    }

