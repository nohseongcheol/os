package سلطنت_متحدہ.JGbrOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import سلطنت_متحدہ.JGbrOS.기억공간.صفحہ_مینیجر;
import سلطنت_متحدہ.JGbrOS.فائل_نظام.파일서술자표;

/** عمل_قدر 식별자와 라운드로빈 تیار_کریں 대기열을 관리한다. */
public final class میقات_کار {
    private final صفحہ_مینیجر 쪽관리;
    private final Map<Integer, عمل_قدر> عمل_فہرست = new HashMap<Integer, عمل_قدر>();
    private final Queue<عمل_قدر> 준비대기열 = new ArrayDeque<عمل_قدر>();
    private int اگلا_شناخت_کنندہ = 1;

    public میقات_کار(صفحہ_مینیجر 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public عمل_قدر 첫과정(파일서술자표 파일서술자) {
        عمل_قدر 새과정 = new عمل_قدر(مختص_کریں_شناخت_کنندہ(), 0, 쪽관리.새주소공간(), 파일서술자);
        عمل_فہرست.put(Integer.valueOf(새과정.شناخت_کنندہ_قدر()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public عمل_قدر 복제(عمل_قدر 부모) {
        عمل_قدر بچہ_قدر = new عمل_قدر(
                مختص_کریں_شناخت_کنندہ(),
                부모.شناخت_کنندہ_قدر(),
                쪽관리.쓰기시복사복제(부모.پتہ_اسپیس()),
                부모.파일서술자().복제());
        بچہ_قدر.프로그램끝설정(부모.프로그램끝());
        عمل_فہرست.put(Integer.valueOf(بچہ_قدر.شناخت_کنندہ_قدر()), بچہ_قدر);
        준비대기열.offer(بچہ_قدر);
        return بچہ_قدر;
    }

    public عمل_قدر اگلا_عمل() {
        int 검사수 = 준비대기열.size();
        for (int اشاریہ = 0; اشاریہ < 검사수; اشاریہ++) {
            عمل_قدر اگلا_شے = 준비대기열.poll();
            if (اگلا_شے != null && (اگلا_شے.حالت_قدر() == عمل_حالت.تیار_کریں || اگلا_شے.حالت_قدر() == عمل_حالت.نفاذ_کریں_حکم)) {
                اگلا_شے.سیٹ_حالت(عمل_حالت.نفاذ_کریں_حکم);
                준비대기열.offer(اگلا_شے);
                return اگلا_شے;
            }
        }
        return null;
    }

    public int 자식기다리기(عمل_قدر 부모, int بچہ_شناخت_کنندہ, boolean 기다리지않음) {
        for (عمل_قدر 후보 : عمل_فہرست.values()) {
            if (후보.부모식별자() != 부모.شناخت_کنندہ_قدر()) {
                continue;
            }
            if (بچہ_شناخت_کنندہ > 0 && 후보.شناخت_کنندہ_قدر() != بچہ_شناخت_کنندہ) {
                continue;
            }
            if (후보.حالت_قدر() == عمل_حالت.خروج_ایپ) {
                int پیمائش = (후보.종료값() & 0xff) << 8;
                عمل_فہرست.remove(Integer.valueOf(후보.شناخت_کنندہ_قدر()));
                return پیمائش;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public عمل_قدر ڈھونڈیں_عمل(int شناخت_کنندہ_قدر) {
        return عمل_فہرست.get(Integer.valueOf(شناخت_کنندہ_قدر));
    }

    private int مختص_کریں_شناخت_کنندہ() {
        return اگلا_شناخت_کنندہ++;
    }
}
