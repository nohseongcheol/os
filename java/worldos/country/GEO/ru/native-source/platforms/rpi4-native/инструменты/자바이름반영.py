#!/usr/bin/env python3
"""свой Java локальный_Scope 이름을 바꾼다. строка_ЗНАЧЕН·주석·внешний_ЗНАЧЕН 멤버 이름은 보존한다."""
import json
import re
from pathlib import Path

задача_корень = Path(__file__).resolve().parents[1]
сопоставление_ЗНАЧЕН = json.loads((задача_корень / '명명/자바이름.json').read_text())
блок_выражение = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[\w$]+|[^\w\s]', re.UNICODE)
LOG_ЗАПИСЬ = []
for Каталог_ЗНАЧЕН in ('исходныйКод', 'пространство_пользователя/자바', '한국어자바'):
    for путь in sorted((задача_корень / Каталог_ЗНАЧЕН).rglob('*.java')):
        исходныйКод = путь.read_text()
        토막들 = list(блок_выражение.finditer(исходныйКод))
        사용이름 = {блок_ввод.group() for блок_ввод in 토막들 if re.search('[가-힣]', блок_ввод.group())}
        сопоставление_файлов = {}
        for Назад_товар, 이후 in сопоставление_ЗНАЧЕН.items():
            # A pre-existing Korean binding must never be shadowed by renaming.
            새이름 = 이후
            while 새이름 in 사용이름: 새이름 = 'локальный_Scope' + 새이름
            сопоставление_файлов[Назад_товар] = 새이름
        수정 = []
        Назад_блок = ''
        for блок_ввод in 토막들:
            낱말 = блок_ввод.group()
            if 낱말.startswith(('//', '/*', '"', "'")): continue
            if 낱말 in сопоставление_файлов and Назад_блок != '.':
                수정.append((блок_ввод.start(), блок_ввод.end(), сопоставление_файлов[낱말]))
                LOG_ЗАПИСЬ.append((str(путь.relative_to(задача_корень)), 낱말, сопоставление_файлов[낱말]))
            Назад_блок = 낱말
        for запустить, 끝, 새이름 in reversed(수정): исходныйКод = исходныйКод[:запустить] + 새이름 + исходныйКод[끝:]
        if 수정: путь.write_text(исходныйКод)
(задача_корень / '명명/자바이름대응.tsv').write_text('файл\t이전\t이후\n' + ''.join('\t'.join(ввод_ЗНАЧЕН)+'\n' for ввод_ЗНАЧЕН in sorted(set(LOG_ЗАПИСЬ))))
print('Java Название ссылка изменить_ЗНАЧЕН:', len(LOG_ЗАПИСЬ))
