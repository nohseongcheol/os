import 한국어.자체.ფანჯარა;
import 한국어.자체.სათაური;
import 한국어.자체.ტექსტური_ველი;
import 한국어.자체.ღილაკი;
import 한국어.자체.მოვლენა_რიგი;
import 한국어.자체.출력;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing ფანჯარა: Georgian 입력 → ღილაკი → წასაკითხი_ფაილი_eb81d7d9 ტექსტი განახლება. */
public class 창예제 implements 실행할일, 동작받이 {
    private ფანჯარა 인사창;
    private ტექსტური_ველი სახელი_ველი;
    private სათაური 인사말;
    private int 인사횟수;

    public void გახსნა_ფანჯარა() {
        인사창 = new ფანჯარა("Georgian Swing", 460, 300);
        인사창.დამატება_ელემენტი(new სათაური("გამარჯობა", 20, 20, 420, 28));
        სახელი_ველი = new ტექსტური_ველი("Georgian", 20, 64, 420, 30);
        인사말 = new სათაური("გამარჯობა", 20, 152, 420, 28);
        인사창.დამატება_ელემენტი(სახელი_ველი);
        인사창.დამატება_ელემენტი(new ღილაკი("인사하기", 20, 108, 180, 32, this));
        인사창.დამატება_ელემენტი(인사말);
        인사창.დამატება_ელემენტი(new სათაური("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.ჩვენება_ფანჯარა();
        출력.ჩაწერა_ხაზი("GUI 예제 მომზადება: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.ჩაწერა_ტექსტი("გამარჯობა, " + სახელი_ველი.글읽기() + "님! (" + 인사횟수 + ")");
        출력.ჩაწერა_ხაზი("GUI 인사: " + 인사말.글읽기());
    }

    public void შესრულება() { გახსნა_ფანჯარა(); }
    public void 동작받기(동작알림 알림) {
        출력.ჩაწერა_ხაზი("ქმედება 알림: " + 알림.ბრძანება_ტექსტი());
        인사하기();
    }
    public static void გაშვება() {
        მოვლენა_რიგი.나중에실행(new 창예제());
    }
}
