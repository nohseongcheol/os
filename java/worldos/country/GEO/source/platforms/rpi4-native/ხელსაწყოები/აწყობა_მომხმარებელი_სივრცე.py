"""독립된 자체 ABI ELF64와 로더 거부 시험 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from 파이썬빌드 import 파이썬만들기
from 자바라이브러리빌드 import 자바라이브러리만들기
from 시언어번역기빌드 import 시언어번역기만들기


def შექმნა_მომხმარებელი_სივრცე(ფესვი_მდებარეობა, 저장소경로, 시언어번역기, 시플플번역기, 연결편집기, არქივი_ხელსაწყო, 설정비트, შესრულება_ბრძანება):
    설정비트 = [პარამეტრები_მნიშვნელობა for პარამეტრები_მნიშვნელობა in 설정비트 if პარამეტრები_მნიშვნელობა != '-mgeneral-regs-only']
    აწყობა_მდებარეობა = ფესვი_მდებარეობა / 'build'
    출력결과 = აწყობა_მდებარეობა / 'user'
    출력결과.mkdir(exist_ok=True)
    원본자료 = ფესვი_მდებარეობა / 'მომხმარებელი'
    포직스경로 = 저장소경로 / 'posix-kor/arm64-native'
    포함경로 = ['-I', 원본자료, '-I', 포직스경로 / '포함', '-I', 출력결과]
    for 번역기, 추가영역, გეზი, სახელი in [
            (시언어번역기, [], 원본자료 / 'გაშვება.S', 'start.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'შესრულება_ბრძანება.c', 'runtime.o'),
            (시언어번역기, ['-std=c11'], 포직스경로 / 'მომხმარებელი_ხიდი.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '파일예제.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '통신예제.cpp', 'network.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / '보호시험.c', 'fault.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'რედაქტორი.c', 'vi.o')]:
        შესრულება_ბრძანება([번역기] + 설정비트 + 추가영역 + 포함경로 + ['-Wall', '-Wextra', '-Werror', '-c', გეზი, '-o', 출력결과 / სახელი])
    შესრულება_ბრძანება([არქივი_ხელსაწყო, 'rcs', აწყობა_მდებარეობა / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for სახელი in ('demo', 'fault', 'network', 'vi'):
        შესრულება_ბრძანება([연결편집기, '-T', 원본자료 / 'ბმული_განლაგება.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (სახელი + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (სახელი + '.o'), აწყობა_მდებარეობა / 'libposix-kor-user.a'])
    자바라이브러리만들기(ფესვი_მდებარეობა, შესრულება_ბრძანება)
    # 기존 자체 Java 컴파일러/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(აწყობა_მდებარეობა)) as 작업경로:
        კლასი_მდებარეობა = Path(작업경로)
        შესრულება_ბრძანება(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', კლასი_მდებარეობა, '-sourcepath', კლასი_მდებარეობა, '-d', კლასი_მდებარეობა] +
            [მონაცემები_პოზიცია for მონაცემები_პოზიცია in sorted((저장소경로 / 'os/მომხმარებელი/자바').glob('*.java')) if მონაცემები_პოზიცია.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        შესრულება_ბრძანება(['sh', 저장소경로 / 'compiler/미리번역.sh', '--entry', 'ხელსაწყო_შენატანი.გაშვება',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(კლასი_მდებარეობა.glob('*.class')))
    압축해제경로 = ფესვი_მდებარეობა / 'vendor/uzlib'
    for გეზი, სახელი in [(출력결과 / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'შეკვრა.c', 'jar.o')] + [(압축해제경로 / (სახელი + '.c'), სახელი + '.o') for სახელი in ('tinflate', 'crc32', 'adler32')]:
        შესრულება_ბრძანება([시언어번역기] + 설정비트 + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + 포함경로 + ['-c', გეზი, '-o', 출력결과 / სახელი])
    შესრულება_ბრძანება([연결편집기, '-T', 원본자료 / 'ბმული_განლაგება.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / სახელი for სახელი in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(ფესვი_მდებარეობა, 시언어번역기, 연결편집기)
    시언어번역기만들기(ფესვი_მდებარეობა, 저장소경로, 시언어번역기, 연결편집기, 설정비트, შესრულება_ბრძანება)
    유효함 = (출력결과 / 'demo.elf').read_bytes()
    აპი_ზედა_კოლონტიტული_ოფსეტი = struct.unpack_from('<Q', 유효함, 32)[0]
    ზედა_კოლონტიტული_სია = [აპი_ზედა_კოლონტიტული_ოფსეტი + 개수 * 56 for 개수 in range(struct.unpack_from('<H', 유효함, 56)[0])]
    적재구획 = [მონაცემები_პოზიცია for მონაცემები_პოზიცია in ზედა_კოლონტიტული_სია if struct.unpack_from('<I', 유효함, მონაცემები_პოზიცია)[0] == 1]
    ტექსტი, მონაცემები = 적재구획[:2]
    ბრძანება_მისამართი = struct.unpack_from('<Q', 유효함, ტექსტი + 16)[0]
    მონაცემები_მისამართი = struct.unpack_from('<Q', 유효함, მონაცემები + 16)[0]
    호출규약 = 유효함.index(b'JKOROS\0')
    시험사례 = [('empty', b''), ('short', 유효함[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', ბრძანება_მისამართი + 1), ('data-entry', 24, 'Q', მონაცემები_მისამართი),
               ('outside-file', ტექსტი + 32, 'Q', len(유효함) + 1), ('short-memory', ტექსტი + 40, 'Q', 1),
               ('kernel-address', ტექსტი + 16, 'Q', 0x80000), ('memory-overflow', ტექსტი + 40, 'Q', 2**64 - 1),
               ('writable-code', ტექსტი + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', ტექსტი, 'I', 2),
               ('unaligned-load', ტექსტი + 16, 'Q', ბრძანება_მისამართი + 8),
               ('overlap', მონაცემები + 16, 'Q', ბრძანება_მისამართი)]
    for სახელი, ოფსეტი_მნიშვნელობა, ფორმატი_932e03c8, მნიშვნელობა in 수정사항:
        바뀐자료 = bytearray(유효함); struct.pack_into('<' + ფორმატი_932e03c8, 바뀐자료, ოფსეტი_მნიშვნელობა, მნიშვნელობა)
        시험사례.append((სახელი, bytes(바뀐자료)))
    탑재덩이들 = [(სახელი.replace('-', '_'), 출력결과 / (სახელი + '.elf')) for სახელი in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for ძებნა_ინდექსი, (სახელი, დატვირთვა_მონაცემები) in enumerate(시험사례):
        გეზი = 출력결과 / ('invalid-{}.elf'.format(სახელი)); გეზი.write_bytes(დატვირთვა_მონაცემები)
        탑재덩이들.append(('invalid_{}'.format(ძებნა_ინდექსი), გეზი))
    어셈블리자료, ზედა_კოლონტიტული_მნიშვნელობა = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for სახელი, გეზი in 탑재덩이들:
        სიმბოლო_მნიშვნელობა = 'user_blob_' + სახელი
        크기목록[სახელი] = გეზი.stat().st_size
        # 생성한 კვანძი_მნიშვნელობა_6a3b6fa7 경로만 넣어 프로젝트 경로의 공백/ციტატა 영향을 피한다.
        어셈블리자료 += ['.balign 16', '.global ' + სიმბოლო_მნიშვნელობა, სიმბოლო_მნიშვნელობა + ':', '.incbin "{}"'.format(გეზი.relative_to(ფესვი_მდებარეობა))]
        ზედა_კოლონტიტული_მნიშვნელობა.append('extern const unsigned char {}[];'.format(სიმბოლო_მნიშვნელობა))
    어셈블리자료.append('.section .note.GNU-stack,"",%progbits')
    ზედა_კოლონტიტული_მნიშვნელობა += ['static const აპი 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    ზედა_კოლონტიტული_მნიშვნელობა += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    ზედა_კოლონტიტული_მნიშვნელობა += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    ზედა_კოლონტიტული_მნიშვნელობა += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], მეთოდი_რეჟიმი) for მეთოდი_რეჟიმი in (0, 1)]
    ზედა_კოლონტიტული_მნიშვნელობა += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    ზედა_კოლონტიტული_მნიშვნელობა += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    ზედა_კოლონტიტული_მნიშვნელობა += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    ზედა_კოლონტიტული_მნიშვნელობა += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    ზედა_კოლონტიტული_მნიშვნელობა += ['};', 'static const აპი 잘못된실행항목들[] = {']
    ზედა_კოლონტიტული_მნიშვნელობა += ['{user_blob_invalid_%d, %d, 0},' % (순번, len(დატვირთვა_მონაცემები)) for 순번, (_, დატვირთვა_მონაცემები) in enumerate(시험사례)]
    ზედა_კოლონტიტული_მნიშვნელობა += ['};']
    (აწყობა_მდებარეობა / 'programs.S').write_text('\n'.join(어셈블리자료) + '\n')
    (აწყობა_მდებარეობა / 'programs.h').write_text('\n'.join(ზედა_კოლონტიტული_მნიშვნელობა) + '\n')
    (출력결과 / 'invalid-cases.txt').write_text('\n'.join(სახელი for სახელი, _ in 시험사례) + '\n')
    შესრულება_ბრძანება([시언어번역기] + 설정비트 + ['-c', აწყობა_მდებარეობა / 'programs.S', '-o', აწყობა_მდებარეობა / 'programs.o'])
