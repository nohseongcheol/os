#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from სამუშაო_დაფა_ხედი import კლავიატურა


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.ტექსტი_ბუფერი = ''
        def გაგზავნა(მონაცემები):
            for სიმბოლო_მონაცემები_4d9f8719 in მონაცემები.decode('utf-8'):
                if სიმბოლო_მონაცემები_4d9f8719 == '\x7f': 자신.ტექსტი_ბუფერი = 자신.ტექსტი_ბუფერი[:-1]
                else: 자신.ტექსტი_ბუფერი += სიმბოლო_მონაცემები_4d9f8719
        자신.კლავიატურა_შენატანი = კლავიატურა(გაგზავნა)

    def დაჭერა_კლავიში(자신, სიმბოლო_მნიშვნელობა):
        자신.კლავიატურა_შენატანი.누름값(True, სიმბოლო_მნიშვნელობა)
        자신.კლავიატურა_შენატანი.누름값(False, სიმბოლო_მნიშვნელობა)

    def აკრეფა_კატეგორია(자신, 누름열):
        for 누름값 in 누름열: 자신.დაჭერა_კლავიში(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.დაჭერა_კლავიში(0xffc6); 자신.აკრეფა_კატეგორია(누름열)
                자신.assertEqual(자신.ტექსტი_ბუფერი, 예상결과)

    def test_앞글자지우기(자신):
        자신.დაჭერა_კლავიში(0xff31); 자신.აკრეფა_კატეგორია('dlfr')
        자신.assertEqual(자신.ტექსტი_ბუფერი,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.დაჭერა_კლავიში(0xff08); 자신.assertEqual(자신.ტექსტი_ბუფერი,예상결과)
        자신.აკრეფა_კატეგორია('gksk'); 자신.assertEqual(자신.ტექსტი_ბუფერი,'하나')
        자신.დაჭერა_კლავიში(0xff08); 자신.assertEqual(자신.ტექსტი_ბუფერი,'하ㄴ')

    def test_전환반복확정(자신):
        자신.აკრეფა_კატეგორია('echo ')
        자신.კლავიატურა_შენატანი.누름값(True,0xffe1)
        자신.კლავიატურა_შენატანი.누름값(True,32); 자신.კლავიატურა_შენატანი.누름값(True,32)
        자신.კლავიატურა_შენატანი.누름값(False,32); 자신.კლავიატურა_შენატანი.누름값(False,0xffe1)
        자신.assertTrue(자신.კლავიატურა_შენატანი.한글여부)
        자신.აკრეფა_კატეგორია('gksrmf'); 자신.დაჭერა_კლავიში(0xff31); 자신.აკრეფა_კატეგორია(' English')
        자신.assertEqual(자신.ტექსტი_ბუფერი,'echo 한글 English')
        자신.assertFalse(자신.კლავიატურა_შენატანი.한글여부)
        자신.დაჭერა_კლავიში(0xffc6); 자신.აკრეფა_კატეგორია('rk'); 자신.დაჭერა_კლავიში(0xff51)
        자신.აკრეფა_კატეგორია('sk'); 자신.assertTrue(자신.ტექსტი_ბუფერი.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.დაჭერა_კლავიში(0xffc6); 자신.აკრეფა_კატეგორია('rk')
        자신.კლავიატურა_შენატანი.გაცვლის_ბუფერი_მნიშვნელობა='ჩასმა_მნიშვნელობა'.encode()
        자신.კლავიატურა_შენატანი.누름값(True,0xffe3); 자신.კლავიატურა_შენატანი.누름값(True,0xffe1)
        자신.დაჭერა_კლავიში(ord('v'))
        자신.კლავიატურა_შენატანი.누름값(False,0xffe1); 자신.კლავიატურა_შენატანი.누름값(False,0xffe3)
        자신.დაჭერა_კლავიში(0x0100d55c); 자신.აკრეფა_კატეგორია('sk')
        자신.assertEqual(자신.ტექსტი_ბუფერი,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
