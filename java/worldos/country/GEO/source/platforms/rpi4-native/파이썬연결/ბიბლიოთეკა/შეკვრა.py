class 수신흐름:
    def __init__(자신, 종단):
        자신.종단 = 종단
        자신.남은자료 = b""
        자신.გაშვება = ოპერაციული_სისტემა.ticks_ms()

    def 정확히읽기(자신, სიგრძე_მნიშვნელობა):
        მონაცემები = bytearray()
        while len(მონაცემები) < სიგრძე_მნიშვნელობა:
            if ოპერაციული_სისტემა.ticks_ms() - 자신.გაშვება > 90000:
                raise ValueError("შეკვრა 중계 პასუხი დრო_მნიშვნელობა 초과")
            if not 자신.남은자료:
                try:
                    자신.남은자료 = ოპერაციული_სისტემა.tcp_read(자신.종단, 512)
                except OSError as შეცდომა:
                    if შეცდომა.args[0] != 11:
                        raise
                    ოპერაციული_სისტემა.sleep_ms(10)
                    continue
                if not 자신.남은자료:
                    raise ValueError("შეკვრა 전송이 중간에 끝났습니다.")
            개수 = min(სიგრძე_მნიშვნელობა - len(მონაცემები), len(자신.남은자료))
            მონაცემები.extend(자신.남은자료[:개수])
            자신.남은자료 = 자신.남은자료[개수:]
            ოპერაციული_სისტემა.sleep_ms(0)
        return bytes(მონაცემები)


