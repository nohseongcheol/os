def ამოშლა_შენატანი(სახელი):
    შენატანი_სია = 목록읽기()
    if სახელი not in შენატანი_სია:
        raise ValueError("설치되지 않은 꾸러미입니다: " + სახელი)
    for გეზი, 지문값 in შენატანი_სია[სახელი]["files"].items():
        if ოპერაციული_სისტემა.path_kind(გეზი) != 1 or 지문(ოპერაციული_სისტემა.read(გეზი)) != 지문값:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + გეზი)
    for გეზი in შენატანი_სია[სახელი]["files"]:
        ოპერაციული_სისტემა.remove(გეზი)
    del შენატანი_სია[სახელი]
    ჩაწერა_ჟურნალი(სია_მდებარეობა, json.dumps(შენატანი_სია).encode())
    print("ამოშლა_შენატანი 완료:", სახელი)


