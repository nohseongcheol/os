/** 부팅 Системна_информация 조회와 4KiB 고정 Размер 작업 раздел_стойност заделям_Памет/връщам_мярка. 일반 물리 страница_стойност 관리자는 아니다. */
public final class Памет_област {
    static int[] раздел_стойност = new int[8192];
    static int[] използвам_стойност = new int[8];

    static int анализирам_цяло_число(int адрес) {
        return устройство_стойност.기억읽기(адрес) | (устройство_стойност.기억읽기(адрес + 1) << 8)
            | (устройство_стойност.기억읽기(адрес + 2) << 16) | (устройство_стойност.기억읽기(адрес + 3) << 24);
    }

    static int 위쪽기억크기() {
        int Системна_информация = устройство_стойност.부팅정보();
        if (устройство_стойност.부팅표식() != 0x2badb002 || Системна_информация == 0 || (анализирам_цяло_число(Системна_информация) & 1) == 0) return -1;
        return анализирам_цяло_число(Системна_информация + 8);
    }

    static int заделям_Памет() {
        for (int индекс = 0; индекс < използвам_стойност.length; индекс++) {
            if (използвам_стойност[индекс] == 0) {
                използвам_стойност[индекс] = 1;
                for (int 칸 = 0; 칸 < 1024; 칸++) раздел_стойност[индекс * 1024 + 칸] = 0;
                return индекс;
            }
        }
        return -1;
    }

    static boolean връщам_мярка(int индекс) {
        if (индекс < 0 || индекс >= използвам_стойност.length || използвам_стойност[индекс] == 0) return false;
        използвам_стойност[индекс] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int индекс = 0; индекс < използвам_стойност.length; индекс++) 개수 += използвам_стойност[индекс];
        return 개수;
    }
}
