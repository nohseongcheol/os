public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int 길이 = 0;
    static boolean 앞줄복귀 = false;
    static boolean ред_Препълване = false;

    static boolean Команда(String Име) {
        if (길이 < Име.length()) return false;
        for (int индекс = 0; индекс < Име.length(); индекс++)
            if (입력[индекс] != Име.charAt(индекс)) return false;
        return 길이 == Име.length() || 입력[Име.length()] == ' ';
    }

    static void показвам_помощ() {
        Текст_Терминал.Писане("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        Текст_Терминал.Писане("apps | run NAME [ARGS] | net\n");
        Текст_Терминал.Писане("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        Текст_Терминал.Писане("sync (연결된 JKSTORE1 хранилище_стойност 장치에 Файл 보존)\n");
    }

    static void Процес_стойност_запис() {
        if (길이 == 0) return;
        if (Команда("help")) показвам_помощ();
        else if (Команда("sync")) {
            int РЕЗУЛТАТ = 파일보존.синхронизирам();
            Текст_Терминал.Писане("Sync: "); Текст_Терминал.수쓰기(РЕЗУЛТАТ); Текст_Терминал.문자(10);
        }
        else if (Команда("ls")) Памет_файлова_система.запис_Списък();
        else if (Команда("edit")) Памет_файлова_система.Команда(입력, 4, 길이, 0);
        else if (Команда("cat")) Памет_файлова_система.Команда(입력, 3, 길이, 1);
        else if (Команда("rm")) Памет_файлова_система.Команда(입력, 2, 길이, 2);
        else if (Команда("java") || Команда("javac")) {
            int РЕЗУЛТАТ = 실행관리.изпълнявам_команда(입력, 0, 길이);
            Текст_Терминал.Писане("Exit: "); Текст_Терминал.수쓰기(РЕЗУЛТАТ); Текст_Терминал.문자(10);
        }
        else if (Команда("apps")) 실행관리.запис_Списък();
        else if (Команда("net")) мрежа_стек.Състояние_стойност();
        else if (Команда("run")) {
            int РЕЗУЛТАТ = 실행관리.изпълнявам_команда(입력, 3, 길이);
            Текст_Терминал.Писане("Exit: "); Текст_Терминал.수쓰기(РЕЗУЛТАТ); Текст_Терминал.Писане("\n");
        } else if (Команда("info")) {
            Текст_Терминал.Писане("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (Команда("mem")) {
            Текст_Терминал.Писане("위쪽 Памет_стойност адрес_област(KiB): "); Текст_Терминал.수쓰기(Памет_област.위쪽기억크기());
            Текст_Терминал.Писане("\n배열 동적 Памет_стойност адрес_област(байт_стойност): "); Текст_Терминал.수쓰기(устройство_стойност.масив_употреба());
            Текст_Терминал.Писане(" / 262144\n작업 адрес_област раздел_стойност: "); Текст_Терминал.수쓰기(Памет_област.사용개수());
            Текст_Терминал.Писане(" / 8 (각 4096바이트)\n");
        } else if (Команда("alloc")) {
            int индекс = Памет_област.заделям_Памет();
            Текст_Терминал.Писане("раздел_стойност индекс: "); Текст_Терминал.수쓰기(индекс); Текст_Терминал.Писане("\n");
        } else if (Команда("free")) {
            if (길이 == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                Текст_Терминал.Писане(Памет_област.връщам_мярка(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 раздел_стойност\n");
            } else Текст_Терминал.Писане("사용법: free 0..7\n");
        } else if (Команда("echo")) {
            for (int индекс = 5; индекс < 길이; индекс++) Текст_Терминал.문자(입력[индекс]);
            Текст_Терминал.문자(10);
        } else if (Команда("clear")) Текст_Терминал.изтривам_запис();
        else if (Команда("test")) ядро.시험();
        else if (Команда("halt")) {
            Текст_Терминал.Писане("HALTED\n");
            устройство_стойност.정지();
        } else Текст_Терминал.Писане("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void приемам_И_записване(int стойност) {
        if (стойност == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = стойност == 13;
        if (стойност == 10 || стойност == 13) {
            Текст_Терминал.문자(10);
            if (Памет_файлова_система.편집중) Памет_файлова_система.Редактирани_ред(입력, 길이, ред_Препълване);
            else Процес_стойност_запис();
            길이 = 0;
            ред_Препълване = false;
            Текст_Терминал.Писане(Памет_файлова_система.편집중 ? "...> " : "jkoros> ");
        } else if (стойност == 8 || стойност == 127) {
            if (길이 > 0) {
                길이--;
                Текст_Терминал.직렬바이트(8); Текст_Терминал.직렬바이트(32); Текст_Терминал.직렬바이트(8);
                Текст_Терминал.화면문자(8);
            }
        } else if (стойност >= 32 && стойност < 127 && 길이 < 입력.length) {
            입력[길이++] = стойност;
            Текст_Терминал.문자(стойност);
        } else if (стойност >= 32 && стойност < 127) ред_Препълване = true;
    }

    static void Стартиране() {
        показвам_помощ();
        Текст_Терминал.Писане("READY\njkoros> ");
        while (true) {
            int стойност = Текст_Терминал.직렬읽기();
            if (стойност < 0) стойност = клавиатура.Четене();
            if (стойност >= 0) приемам_И_записване(стойност);
            else { мрежа_стек.проверявам(); устройство_стойност.잠시양보(); }
        }
    }
}
