    public int изпълнявам_команда(Процес_стойност в_срок_Процес, byte[] 실행파일, String[] параметър_аргумент, String[] 환경) {
        실행파일적재기.снимка снимка_стойност;
        try {
            снимка_стойност = зареждаща_служебна_програма.검사(실행파일);
        } catch (IllegalArgumentException ГРЕШКА) {
            return -8;
        }
        if (параметър_аргумент == null || 환경 == null || параметър_аргумент.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.раздел_стойност раздел_стойност : снимка_стойност.구역들()) {
            if ((раздел_стойност.флаг_стойност() & 2) == 0 || раздел_стойност.Размер() == 0) {
                continue;
            }
            int 첫쪽 = раздел_стойност.адрес() / 쪽관리자.размер_на_страница;
            int 끝쪽 = (раздел_стойност.адрес() + раздел_стойност.Размер() + 쪽관리자.размер_на_страница - 1) / 쪽관리자.размер_на_страница;
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int адрес = индекс * 쪽관리자.размер_на_страница;
                try {
                    쪽관리.바이트읽기(в_срок_Процес.адрес_ИНТЕРВАЛ(), адрес);
                    쪽관리.частен_обхват_записване(в_срок_Процес.адрес_ИНТЕРВАЛ(), адрес, 쪽관리자.размер_на_страница);
                } catch (IllegalStateException ГРЕШКА) {
                    쪽관리.нанасям_страница(в_срок_Процес.адрес_ИНТЕРВАЛ(), адрес, true);
                }
            }
            for (int индекс = 0; индекс < раздел_стойност.Размер(); индекс++) {
                byte стойност = раздел_стойност.종류() == 8 ? 0 : 실행파일[раздел_стойност.Файл_позиция() + индекс];
                쪽관리.записване_байт_стойност(в_срок_Процес.адрес_ИНТЕРВАЛ(), раздел_стойност.адрес() + индекс, стойност);
            }
        }
        в_срок_Процес.실행문맥설정(снимка_стойност.Старт_адрес(), параметър_аргумент, 환경);
        в_срок_Процес.파일서술자().실행시닫기();
        return 0;
    }

