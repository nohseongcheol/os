    public int програма_почивка(Процес_стойност в_срок_Процес, int 새끝) {
        int 이전끝 = в_срок_Процес.програма_почивка();
        if (새끝 == 0) {
            return 이전끝;
        }
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            return -12;
        }
        int 첫쪽 = 이전끝 / 쪽관리자.размер_на_страница;
        int 끝쪽 = (새끝 + 쪽관리자.размер_на_страница - 1) / 쪽관리자.размер_на_страница;
        if (새끝 > 이전끝) {
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int адрес = индекс * 쪽관리자.размер_на_страница;
                try {
                    쪽관리.바이트읽기(в_срок_Процес.адрес_ИНТЕРВАЛ(), адрес);
                } catch (IllegalStateException ГРЕШКА) {
                    쪽관리.нанасям_страница(в_срок_Процес.адрес_ИНТЕРВАЛ(), адрес, true);
                }
            }
        }
        в_срок_Процес.набор_програма_почивка(새끝);
        return 새끝;
    }

    public int увеличение_програма_почивка(Процес_стойност в_срок_Процес, int нарастване_количество) {
        int 이전끝 = в_срок_Процес.програма_почивка();
        int РЕЗУЛТАТ = програма_почивка(в_срок_Процес, 이전끝 + нарастване_количество);
        return РЕЗУЛТАТ < 0 ? РЕЗУЛТАТ : 이전끝;
    }

