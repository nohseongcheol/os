/** 검사합과 두 보존본을 사용하는 작은 전용 αποθηκεύω_τιμή μορφή_τιμή. fsync/sync에서만 영구 반영한다. */
public final class 파일보존 {
    static int 현재보존본 = -1, 세대번호 = 0;
    static int[] Αρχείο_πίνακας = new int[1024];
    static int 바이트해시(int τιμή, int δεδομένα) { return (τιμή ^ δεδομένα) * 16777619; }
    static void εκκαθαρίζω_δεδομένα() {
        for (int Ευρετήριο = 0; Ευρετήριο < 512; Ευρετήριο++) συσκευή_αποθήκευσης_σύνδεση.ενότητα_δεδομένα[Ευρετήριο] = 0;
    }
    static int πίνακας_ακέραιος(int Θέση) {
        return Αρχείο_πίνακας[Θέση] | Αρχείο_πίνακας[Θέση + 1] << 8 | Αρχείο_πίνακας[Θέση + 2] << 16 | Αρχείο_πίνακας[Θέση + 3] << 24;
    }
    static void εγγράφω_πίνακας_ακέραιος(int Θέση, int τιμή) {
        for (int Ευρετήριο = 0; Ευρετήριο < 4; Ευρετήριο++) Αρχείο_πίνακας[Θέση + Ευρετήριο] = (τιμή >>> (Ευρετήριο * 8)) & 255;
    }
    static boolean ελέγχω_πίνακας() {
        for (int Αρχείο = 0; Αρχείο < 8; Αρχείο++) {
            int διάρκεια_τιμή = 0;
            for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 64; υποδοχή_καταχώρηση++) Μνήμη_σύστημα_αρχείων.Όνομα[υποδοχή_καταχώρηση] = Αρχείο_πίνακας[Αρχείο * 72 + υποδοχή_καταχώρηση];
            while (διάρκεια_τιμή < 64 && Μνήμη_σύστημα_αρχείων.Όνομα[διάρκεια_τιμή] != 0) διάρκεια_τιμή++;
            if (διάρκεια_τιμή == 0) continue;
            if (!Μνήμη_σύστημα_αρχείων.ελέγχω_όνομα(Μνήμη_σύστημα_αρχείων.Όνομα, διάρκεια_τιμή)
                || πίνακας_ακέραιος(Αρχείο * 72 + 64) < 0 || πίνακας_ακέραιος(Αρχείο * 72 + 64) > 16384) return false;
            for (int μπροστινή_τιμή = 0; μπροστινή_τιμή < Αρχείο; μπροστινή_τιμή++) {
                boolean 같음 = Αρχείο_πίνακας[μπροστινή_τιμή * 72 + διάρκεια_τιμή] == 0;
                for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < διάρκεια_τιμή; υποδοχή_καταχώρηση++) if (Αρχείο_πίνακας[μπροστινή_τιμή * 72 + υποδοχή_καταχώρηση] != Μνήμη_σύστημα_αρχείων.Όνομα[υποδοχή_καταχώρηση]) 같음 = false;
                if (같음) return false;
            }
        }
        return true;
    }
    static int 보존본검사(int 보존본) {
        int αρχή_ενότητα = 1 + 보존본 * 259;
        if (συσκευή_αποθήκευσης_σύνδεση.Ανάγνωση(αρχή_ενότητα) < 0 || συσκευή_αποθήκευσης_σύνδεση.ανάλυση_ακέραιος(0) != 0x4a4b534e) return -1;
        int 세대 = συσκευή_αποθήκευσης_σύνδεση.ανάλυση_ακέραιος(4), άθροισμα_ελέγχου = συσκευή_αποθήκευσης_σύνδεση.ανάλυση_ακέραιος(8);
        if (세대 < 1 || συσκευή_αποθήκευσης_σύνδεση.ανάλυση_ακέραιος(12) != (세대 ^ άθροισμα_ελέγχου ^ 0x4a4b534e)) return -1;
        int κατακερματισμός_Αρχείο = 0x811c9dc5;
        for (int ενότητα_τιμή = 0; ενότητα_τιμή < 258; ενότητα_τιμή++) {
            if (συσκευή_αποθήκευσης_σύνδεση.Ανάγνωση(αρχή_ενότητα + 1 + ενότητα_τιμή) < 0) return -1;
            for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 512; υποδοχή_καταχώρηση++) {
                int τιμή = συσκευή_αποθήκευσης_σύνδεση.ενότητα_δεδομένα[υποδοχή_καταχώρηση];
                κατακερματισμός_Αρχείο = 바이트해시(κατακερματισμός_Αρχείο, τιμή);
                if (ενότητα_τιμή < 2) Αρχείο_πίνακας[ενότητα_τιμή * 512 + υποδοχή_καταχώρηση] = τιμή;
            }
        }
        return κατακερματισμός_Αρχείο == άθροισμα_ελέγχου && ελέγχω_πίνακας() ? 세대 : -1;
    }
    static int Φόρτος(int 보존본) {
        int αρχή_ενότητα = 1 + 보존본 * 259;
        for (int ενότητα_τιμή = 0; ενότητα_τιμή < 2; ενότητα_τιμή++) {
            if (συσκευή_αποθήκευσης_σύνδεση.Ανάγνωση(αρχή_ενότητα + 1 + ενότητα_τιμή) < 0) return -5;
            for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 512; υποδοχή_καταχώρηση++) Αρχείο_πίνακας[ενότητα_τιμή * 512 + υποδοχή_καταχώρηση] = συσκευή_αποθήκευσης_σύνδεση.ενότητα_δεδομένα[υποδοχή_καταχώρηση];
        }
        for (int Αρχείο = 0; Αρχείο < 8; Αρχείο++) {
            for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 64; υποδοχή_καταχώρηση++) Μνήμη_σύστημα_αρχείων.이름들[Αρχείο * 64 + υποδοχή_καταχώρηση] = Αρχείο_πίνακας[Αρχείο * 72 + υποδοχή_καταχώρηση];
            Μνήμη_σύστημα_αρχείων.αλλάζω_μέγεθος_Λίστα[Αρχείο] = Αρχείο_πίνακας[Αρχείο * 72] == 0 ? 0 : πίνακας_ακέραιος(Αρχείο * 72 + 64);
            Μνήμη_σύστημα_αρχείων.허가들[Αρχείο] = πίνακας_ακέραιος(Αρχείο * 72 + 68) & 511;
            for (int ενότητα_τιμή = 0; ενότητα_τιμή < 32; ενότητα_τιμή++) {
                if (συσκευή_αποθήκευσης_σύνδεση.Ανάγνωση(αρχή_ενότητα + 3 + Αρχείο * 32 + ενότητα_τιμή) < 0) return -5;
                int διεύθυνση = συσκευή_τιμή.Αρχείο_Μνήμη() + Αρχείο * 16384 + ενότητα_τιμή * 512;
                for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 512; υποδοχή_καταχώρηση++) συσκευή_τιμή.εγγράφω_Μνήμη(διεύθυνση + υποδοχή_καταχώρηση, συσκευή_αποθήκευσης_σύνδεση.ενότητα_δεδομένα[υποδοχή_καταχώρηση]);
            }
        }
        return 0;
    }
    static void Προετοίμασε() {
        if (συσκευή_αποθήκευσης_σύνδεση.Ανάγνωση(0) < 0 || συσκευή_αποθήκευσης_σύνδεση.ανάλυση_ακέραιος(0) != 0x54534b4a
            || συσκευή_αποθήκευσης_σύνδεση.ανάλυση_ακέραιος(4) != 0x3145524f || συσκευή_αποθήκευσης_σύνδεση.ανάλυση_ακέραιος(8) != 2048
            || συσκευή_αποθήκευσης_σύνδεση.ανάλυση_ακέραιος(12) != 0x3153464a) {
            μήνυμα_Τερματικό.Εγγραφή("STORE RAM only (no JKSTORE1 disk)\n"); return;
        }
        συσκευή_αποθήκευσης_σύνδεση.πληροφοριακά_συστήματα_Ενεργός_ή = true;
        int 첫째 = 보존본검사(0), 둘째 = 보존본검사(1);
        if (첫째 < 0 && 둘째 < 0) { μήνυμα_Τερματικό.Εγγραφή("STORE ready; no valid snapshot\n"); return; }
        현재보존본 = 첫째 >= 둘째 ? 0 : 1; 세대번호 = 첫째 >= 둘째 ? 첫째 : 둘째;
        if (Φόρτος(현재보존본) < 0) {
            μήνυμα_Τερματικό.Εγγραφή("STORE read failed; halted to preserve files\n"); συσκευή_τιμή.정지();
        }
        μήνυμα_Τερματικό.Εγγραφή("STORE restored generation "); μήνυμα_Τερματικό.수쓰기(세대번호); μήνυμα_Τερματικό.문자(10);
    }
    static int συγχρονίζω() {
        if (!συσκευή_αποθήκευσης_σύνδεση.πληροφοριακά_συστήματα_Ενεργός_ή) return -19;
        if (세대번호 == 2147483647) return -75;
        int Επόμενο_στοιχείο = 현재보존본 == 0 ? 1 : 0, αρχή_ενότητα = 1 + Επόμενο_στοιχείο * 259;
        // 새 본문보다 먼저 이전 commit을 무효화하고 συσκευή_τιμή 캐시를 비운다.
        εκκαθαρίζω_δεδομένα();
        if (συσκευή_αποθήκευσης_σύνδεση.Εγγραφή(αρχή_ενότητα) < 0 || συσκευή_αποθήκευσης_σύνδεση.밀어쓰기() < 0) return -5;
        for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 1024; υποδοχή_καταχώρηση++) Αρχείο_πίνακας[υποδοχή_καταχώρηση] = 0;
        for (int Αρχείο = 0; Αρχείο < 8; Αρχείο++) if (Μνήμη_σύστημα_αρχείων.이름들[Αρχείο * 64] != 0) {
            for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 64; υποδοχή_καταχώρηση++) Αρχείο_πίνακας[Αρχείο * 72 + υποδοχή_καταχώρηση] = Μνήμη_σύστημα_αρχείων.이름들[Αρχείο * 64 + υποδοχή_καταχώρηση];
            εγγράφω_πίνακας_ακέραιος(Αρχείο * 72 + 64, Μνήμη_σύστημα_αρχείων.αλλάζω_μέγεθος_Λίστα[Αρχείο]);
            εγγράφω_πίνακας_ακέραιος(Αρχείο * 72 + 68, Μνήμη_σύστημα_αρχείων.허가들[Αρχείο]);
        }
        int κατακερματισμός_Αρχείο = 0x811c9dc5;
        for (int ενότητα_τιμή = 0; ενότητα_τιμή < 258; ενότητα_τιμή++) {
            for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 512; υποδοχή_καταχώρηση++) {
                int τιμή = 0;
                if (ενότητα_τιμή < 2) τιμή = Αρχείο_πίνακας[ενότητα_τιμή * 512 + υποδοχή_καταχώρηση];
                else {
                    int Αρχείο = (ενότητα_τιμή - 2) / 32, Θέση = (ενότητα_τιμή - 2) % 32 * 512 + υποδοχή_καταχώρηση;
                    if (Αρχείο_πίνακας[Αρχείο * 72] != 0 && Θέση < Μνήμη_σύστημα_αρχείων.αλλάζω_μέγεθος_Λίστα[Αρχείο])
                        τιμή = συσκευή_τιμή.기억읽기(συσκευή_τιμή.Αρχείο_Μνήμη() + Αρχείο * 16384 + Θέση);
                }
                συσκευή_αποθήκευσης_σύνδεση.ενότητα_δεδομένα[υποδοχή_καταχώρηση] = τιμή; κατακερματισμός_Αρχείο = 바이트해시(κατακερματισμός_Αρχείο, τιμή);
            }
            if (συσκευή_αποθήκευσης_σύνδεση.Εγγραφή(αρχή_ενότητα + 1 + ενότητα_τιμή) < 0) return -5;
        }
        if (συσκευή_αποθήκευσης_σύνδεση.밀어쓰기() < 0) return -5;
        εκκαθαρίζω_δεδομένα(); συσκευή_αποθήκευσης_σύνδεση.εγγράφω_ακέραιος_τιμή(0, 0x4a4b534e);
        συσκευή_αποθήκευσης_σύνδεση.εγγράφω_ακέραιος_τιμή(4, 세대번호 + 1); συσκευή_αποθήκευσης_σύνδεση.εγγράφω_ακέραιος_τιμή(8, κατακερματισμός_Αρχείο);
        συσκευή_αποθήκευσης_σύνδεση.εγγράφω_ακέραιος_τιμή(12, (세대번호 + 1) ^ κατακερματισμός_Αρχείο ^ 0x4a4b534e);
        if (συσκευή_αποθήκευσης_σύνδεση.Εγγραφή(αρχή_ενότητα) < 0 || συσκευή_αποθήκευσης_σύνδεση.밀어쓰기() < 0) return -5;
        현재보존본 = Επόμενο_στοιχείο; 세대번호++;
        return 0;
    }
}
