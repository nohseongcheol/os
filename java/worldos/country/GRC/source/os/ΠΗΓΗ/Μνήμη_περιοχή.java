/** 부팅 Πληροφορίες_συστήματος 조회와 4KiB 고정 Μέγεθος 작업 ενότητα_τιμή εκχωρώ_Χώρος_αποθήκευσης/επιστρέφω_μέτρηση. 일반 물리 σελίδα_τιμή 관리자는 아니다. */
public final class Μνήμη_περιοχή {
    static int[] ενότητα_τιμή = new int[8192];
    static int[] χρήση_τιμή = new int[8];

    static int ανάλυση_ακέραιος(int διεύθυνση) {
        return συσκευή_τιμή.기억읽기(διεύθυνση) | (συσκευή_τιμή.기억읽기(διεύθυνση + 1) << 8)
            | (συσκευή_τιμή.기억읽기(διεύθυνση + 2) << 16) | (συσκευή_τιμή.기억읽기(διεύθυνση + 3) << 24);
    }

    static int 위쪽기억크기() {
        int Πληροφορίες_συστήματος = συσκευή_τιμή.부팅정보();
        if (συσκευή_τιμή.부팅표식() != 0x2badb002 || Πληροφορίες_συστήματος == 0 || (ανάλυση_ακέραιος(Πληροφορίες_συστήματος) & 1) == 0) return -1;
        return ανάλυση_ακέραιος(Πληροφορίες_συστήματος + 8);
    }

    static int εκχωρώ_Χώρος_αποθήκευσης() {
        for (int Ευρετήριο = 0; Ευρετήριο < χρήση_τιμή.length; Ευρετήριο++) {
            if (χρήση_τιμή[Ευρετήριο] == 0) {
                χρήση_τιμή[Ευρετήριο] = 1;
                for (int υποδοχή_καταχώρηση = 0; υποδοχή_καταχώρηση < 1024; υποδοχή_καταχώρηση++) ενότητα_τιμή[Ευρετήριο * 1024 + υποδοχή_καταχώρηση] = 0;
                return Ευρετήριο;
            }
        }
        return -1;
    }

    static boolean επιστρέφω_μέτρηση(int Ευρετήριο) {
        if (Ευρετήριο < 0 || Ευρετήριο >= χρήση_τιμή.length || χρήση_τιμή[Ευρετήριο] == 0) return false;
        χρήση_τιμή[Ευρετήριο] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int Ευρετήριο = 0; Ευρετήριο < χρήση_τιμή.length; Ευρετήριο++) 개수 += χρήση_τιμή[Ευρετήριο];
        return 개수;
    }
}
