"""Two-set Hangul composition for the native VNC-to-UART input bridge.

The pending character is visible in the guest editor. Replacing it uses that
editor's UTF-8 Backspace, so commit before cursor motion, shortcuts or a click.
No host input-method daemon or third-party Python package is required.
"""

初始字母構件表 = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
中聲字母構件表 = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
最終字母構件表 = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'
鍵導航 = dict(zip('rRseEfaqQtTdwWczxvgkoiOjpuPhynbml',
                'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎㅏㅐㅑㅒㅓㅔㅕㅖㅗㅛㅜㅠㅡㅣ'))
複合中聲字母構件 = {('ㅗ','ㅏ'):'ㅘ',('ㅗ','ㅐ'):'ㅙ',('ㅗ','ㅣ'):'ㅚ',
          ('ㅜ','ㅓ'):'ㅝ',('ㅜ','ㅔ'):'ㅞ',('ㅜ','ㅣ'):'ㅟ',('ㅡ','ㅣ'):'ㅢ'}
複合最終字母構件 = {('ㄱ','ㅅ'):'ㄳ',('ㄴ','ㅈ'):'ㄵ',('ㄴ','ㅎ'):'ㄶ',
          ('ㄹ','ㄱ'):'ㄺ',('ㄹ','ㅁ'):'ㄻ',('ㄹ','ㅂ'):'ㄼ',('ㄹ','ㅅ'):'ㄽ',
          ('ㄹ','ㅌ'):'ㄾ',('ㄹ','ㅍ'):'ㄿ',('ㄹ','ㅎ'):'ㅀ',('ㅂ','ㅅ'):'ㅄ'}
分割最終字母構件 = {值: 一一對 for 一一對,值 in 複合最終字母構件.items()}


class 合成韓文字母:
    def __init__(自身值, 發送):
        自身值.發送 = 發送
        自身值.提交合成狀態()

    def 提交合成狀態(自身值):
        自身值.狀態程式碼 = ('','','')
        自身值.歷史記錄 = []

    def 文本(自身值):
        初始字母構件,中聲字母構件,最終字母構件 = 自身值.狀態程式碼
        if 初始字母構件 and 中聲字母構件:
            return chr(0xac00 + (初始字母構件表.index(初始字母構件)*21 + 中聲字母構件表.index(中聲字母構件))*28
                       + (最終字母構件表.index(最終字母構件) if 最終字母構件 else 0))
        return 初始字母構件 or 中聲字母構件

    def 退格(自身值):
        if not 自身值.歷史記錄:
            return False
        自身值.狀態程式碼 = 自身值.歷史記錄.pop()
        自身值.發送(b'\x7f' + 自身值.文本().encode('utf-8'))
        return True

    def 供給鍵(自身值, 已按下值):
        字元資料 = 鍵導航.get(已按下值, 鍵導航.get(已按下值.lower()))
        if 字元資料 is None:
            return False
        上一個項目 = 自身值.文本()
        初始字母構件,中聲字母構件,最終字母構件 = 自身值.狀態程式碼
        歷史記錄 = 自身值.歷史記錄 + [自身值.狀態程式碼]
        已提交 = ''
        if 字元資料 in 初始字母構件表:
            if 初始字母構件 and 中聲字母構件 and not 最終字母構件 and 字元資料 in 最終字母構件表:
                最終字母構件 = 字元資料
            elif 最終字母構件 and (最終字母構件,字元資料) in 複合最終字母構件:
                最終字母構件 = 複合最終字母構件[最終字母構件,字元資料]
            else:
                已提交 = 上一個項目
                初始字母構件,中聲字母構件,最終字母構件 = 字元資料,'',''
                歷史記錄 = [('','','')]
        elif 最終字母構件:
            左側,右 = 分割最終字母構件.get(最終字母構件, ('',最終字母構件))
            自身值.狀態程式碼 = 初始字母構件,中聲字母構件,左側
            已提交 = 自身值.文本()
            初始字母構件,中聲字母構件,最終字母構件 = 右,字元資料,''
            歷史記錄 = [('','',''),(右,'','')]
        elif 中聲字母構件:
            if (中聲字母構件,字元資料) in 複合中聲字母構件:
                中聲字母構件 = 複合中聲字母構件[中聲字母構件,字元資料]
            else:
                已提交 = 上一個項目
                初始字母構件,中聲字母構件,最終字母構件 = '',字元資料,''
                歷史記錄 = [('','','')]
        else:
            中聲字母構件 = 字元資料
        自身值.狀態程式碼 = 初始字母構件,中聲字母構件,最終字母構件
        自身值.歷史記錄 = 歷史記錄
        自身值.發送((b'\x7f' if 上一個項目 else b'') + (已提交+自身值.文本()).encode('utf-8'))
        return True
