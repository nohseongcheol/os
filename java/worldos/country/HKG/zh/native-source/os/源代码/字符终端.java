/** COM1 串口输出和 VGA 80×25 字符屏幕；Unicode 文本以 UTF-8 发送至串口终端。 */
public final class 字符终端 {
    static int 槽条目 = 0;
    static int 颜色值 = 7;

    static void 准备() {
        设备.写入输入输出字节(0x3f9, 0);
        设备.写入输入输出字节(0x3fb, 0x80);
        设备.写入输入输出字节(0x3f8, 1);
        设备.写入输入输出字节(0x3f9, 0);
        设备.写入输入输出字节(0x3fb, 3);
        设备.写入输入输出字节(0x3fa, 0xc7);
        设备.写入输入输出字节(0x3fc, 0x0b);
        擦除条目();
    }

    static void 串行字节(int 值) {
        int 重复状态个数 = 100000;
        while ((设备.读取输入输出字节(0x3fd) & 0x20) == 0 && 重复状态个数 > 0) 重复状态个数--;
        if (重复状态个数 > 0) 设备.写入输入输出字节(0x3f8, 值);
    }

    static void 擦除条目() {
        for (int 编号 = 0; 编号 < 2000; 编号++) {
            设备.写入内存(0xb8000 + 编号 * 2, 32);
            设备.写入内存(0xb8001 + 编号 * 2, 颜色值);
        }
        槽条目 = 0;
        光标值();
    }

    static void 光标值() {
        设备.写入输入输出字节(0x3d4, 14);
        设备.写入输入输出字节(0x3d5, 槽条目 >> 8);
        设备.写入输入输出字节(0x3d4, 15);
        设备.写入输入输出字节(0x3d5, 槽条目 & 255);
    }

    static void 屏幕字符(int 值) {
        if (值 == 13) return;
        if (值 == 10) {
            槽条目 = (槽条目 / 80 + 1) * 80;
        } else if (值 == 8) {
            if (槽条目 > 0) {
                槽条目--;
                设备.写入内存(0xb8000 + 槽条目 * 2, 32);
            }
        } else {
            设备.写入内存(0xb8000 + 槽条目 * 2, 值 < 128 ? 值 : '?');
            设备.写入内存(0xb8001 + 槽条目 * 2, 颜色值);
            槽条目++;
        }
        if (槽条目 >= 2000) {
            for (int 编号 = 0; 编号 < 3840; 编号++)
                设备.写入内存(0xb8000 + 编号, 设备.读取内存(0xb80a0 + 编号));
            for (int 编号 = 1920; 编号 < 2000; 编号++) {
                设备.写入内存(0xb8000 + 编号 * 2, 32);
                设备.写入内存(0xb8001 + 编号 * 2, 颜色值);
            }
            槽条目 = 1920;
        }
        光标值();
    }

    static void 字符(int 值) {
        if (值 < 128) {
            if (值 == 10) 串行字节(13);
            串行字节(值);
        } else if (值 < 2048) {
            串行字节(0xc0 | (值 >> 6));
            串行字节(0x80 | (值 & 63));
        } else {
            串行字节(0xe0 | (值 >> 12));
            串行字节(0x80 | ((值 >> 6) & 63));
            串行字节(0x80 | (值 & 63));
        }
        屏幕字符(值);
    }

    static void 写入(String 内容值) {
        for (int 编号 = 0; 编号 < 内容值.length(); 编号++) 字符(内容值.charAt(编号));
    }

    static void 写入编号(int 值) {
        // 不转成正数，因此 Integer.MIN_VALUE 也安全。
        if (值 < 0) 字符('-');
        else 值 = -值;
        int 位置索引 = 1000000000;
        boolean 运行 = false;
        while (位置索引 > 0) {
            int 数字值 = -(值 / 位置索引);
            if (数字值 != 0 || 运行 || 位置索引 == 1) {
                字符('0' + 数字值);
                运行 = true;
            }
            值 %= 位置索引;
            位置索引 /= 10;
        }
    }

    static int 读取串行() {
        if ((设备.读取输入输出字节(0x3fd) & 1) != 0) return 设备.读取输入输出字节(0x3f8);
        return -1;
    }
}
