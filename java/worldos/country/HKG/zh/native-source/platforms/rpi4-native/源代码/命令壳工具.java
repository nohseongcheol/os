/** 共享 RAM VFS 和标准输入输出的 shell 内置工具。 */
public final class 命令壳工具 {
    static int[] 数据 = new int[16384];
    static int 输入文件 = -1;
    static int 打开文件(int 参数索引, int 进程模式) {
        int 已处理值 = 命令解释器.路径(参数索引); return 已处理值 < 0 ? 已处理值 : 内存文件集.打开(进程模式);
    }
    static boolean 准备输入(int 参数索引) {
        输入文件 = -1;
        if (参数索引 < 命令解释器.词元个数) {
            输入文件 = 打开文件(参数索引, 0);
            if (输入文件 < 0) { 命令解释器.错误(输入文件); return false; }
        }
        return true;
    }
    static int 读取() {
        if (输入文件 >= 3) return 内存文件集.读取(输入文件);
        while (true) {
            int 字节数据 = 板.读取串行(); if (字节数据 == -2 || 字节数据 == 4) return 256;
            if (字节数据 == 3) { 命令解释器.结果 = 130; return 256; }
            if (字节数据 >= 0) return 字节数据; 板.挂起处理器();
        }
    }
    static void 关闭() { if (输入文件 >= 3) 内存文件集.关闭(输入文件); 输入文件 = -1; }
    static void 视图值() {
        int 最后位置 = 命令解释器.词元个数 == 1 ? 2 : 命令解释器.词元个数;
        for (int 参数索引 = 1; 参数索引 < 最后位置; 参数索引++) {
            if (!准备输入(参数索引)) continue;
            int 字节数据; while ((字节数据 = 读取()) != 256 && 字节数据 >= 0) 板.写入串行(字节数据);
            if (字节数据 < 0) 命令解释器.错误(字节数据); 关闭();
        }
    }
    static void 文件作业(String 动作编号) {
        if (命令解释器.词元个数 != 2) { 命令解释器.结果 = 2; 终端输入输出.写入("사용법: mkdir/rmdir/touch 文件\n"); return; }
        int 已处理值 = 命令解释器.路径(1);
        if (已处理值 >= 0) {
            if (动作编号.charAt(0) == 'm') 已处理值 = 内存文件集.创建目录();
            else if (动作编号.charAt(0) == 'r') 已处理值 = 内存文件集.移除目录();
            else { 已处理值 = 内存文件集.打开(65); if (已处理值 >= 3) 已处理值 = 内存文件集.关闭(已处理值); }
        }
        if (已处理值 < 0) 命令解释器.错误(已处理值);
    }
    static void 复制值(boolean 拥有已移动) {
        if (命令解释器.词元个数 != 3) { 命令解释器.结果 = 2; 终端输入输出.写入("사용법: cp/mv 原始 目的地址端点 (文件)\n"); return; }
        int 已处理值 = 命令解释器.路径(1); if (已处理值 >= 0) 已处理值 = 内存文件集.正规化值();
        if (已处理值 < 0) { 命令解释器.错误(已处理值); return; }
        int 原始编号 = 内存文件集.查找条目(); if (原始编号 < 0) { 命令解释器.错误(-2); return; }
        int 条目个数 = 内存文件集.长度[原始编号]; for (int 循环索引 = 0; 循环索引 < 条目个数; 循环索引++) 数据[循环索引] = 内存文件集.读取数据(原始编号, 循环索引);
        已处理值 = 命令解释器.路径(2); if (已处理值 >= 0) 已处理值 = 内存文件集.正规化值();
        if (已处理值 < 0) { 命令解释器.错误(已处理值); return; }
        if (内存文件集.查找条目() == 原始编号) { if (!拥有已移动) 命令解释器.错误(-22); return; }
        if (拥有已移动) { 已处理值 = 内存文件集.重命名条目(原始编号); if (已处理值 < 0) 命令解释器.错误(已处理值); return; }
        int 已打开文件编号 = 内存文件集.打开(577); if (已打开文件编号 < 0) { 命令解释器.错误(已打开文件编号); return; }
        for (int 循环索引 = 0; 循环索引 < 条目个数; 循环索引++) { 已处理值 = 内存文件集.写入(已打开文件编号, 数据[循环索引]); if (已处理值 < 0) { 命令解释器.错误(已处理值); break; } }
        内存文件集.关闭(已打开文件编号);
    }
    static int 数字值(int 参数索引) {
        if (参数索引 >= 命令解释器.词元个数) return -1;
        int 条目个数 = 0; for (int 循环索引 = 0; 循环索引 < 命令解释器.长度[参数索引]; 循环索引++) { int 字符代码 = 命令解释器.词元值[命令解释器.起始分[参数索引] + 循环索引]; if (字符代码 < '0' || 字符代码 > '9' || 条目个数 > 10000) return -1; 条目个数 = 条目个数 * 10 + 字符代码 - '0'; } return 条目个数;
    }
    static void 计数中值() {
        int 参数索引 = 1, 选项 = 0;
        if (命令解释器.相等文本(1, "-c") || 命令解释器.相等文本(1, "-l") || 命令解释器.相等文本(1, "-w")) { 选项 = 命令解释器.相等文本(1, "-c") ? 1 : 命令解释器.相等文本(1, "-l") ? 2 : 3; 参数索引++; }
        if (命令解释器.词元个数 > 参数索引 + 1) { 命令解释器.结果 = 2; 终端输入输出.写入("사용법: wc [-c|-l|-w] [文件]\n"); return; }
        if (!准备输入(参数索引)) return;
        int 字节个数 = 0, 行数 = 0, 词法用机器字个数 = 0, 字节数据; boolean 词法用机器字 = false;
        while ((字节数据 = 读取()) >= 0 && 字节数据 != 256) { 字节个数++; if (字节数据 == 10) 行数++; boolean 空间 = 字节数据 == 32 || 字节数据 >= 9 && 字节数据 <= 13; if (!空间 && !词法用机器字) 词法用机器字个数++; 词法用机器字 = !空间; }
        关闭(); if (字节数据 < 0) { 命令解释器.错误(字节数据); return; }
        if (选项 != 0) 终端输入输出.数(选项 == 1 ? 字节个数 : 选项 == 2 ? 行数 : 词法用机器字个数);
        else { 终端输入输出.数(行数); 终端输入输出.字符(' '); 终端输入输出.数(词法用机器字个数); 终端输入输出.字符(' '); 终端输入输出.数(字节个数); } 终端输入输出.字符(10);
    }
    static void 查找条目() {
        if (命令解释器.词元个数 < 2 || 命令解释器.词元个数 > 3) { 命令解释器.结果 = 2; 终端输入输出.写入("사용법: grep 찾을문구 [文件]\n"); return; }
        if (!准备输入(2)) return;
        int 条目个数 = 0, 字节数据, 匹配数 = 0;
        while (true) {
            字节数据 = 读取();
            if (字节数据 == 10 || 字节数据 == 256 || 字节数据 < 0) {
                boolean 曾经已找到 = false;
                for (int 循环索引 = 0; 循环索引 <= 条目个数 - 命令解释器.长度[1]; 循环索引++) {
                    boolean 是否相同 = true; for (int 内部侧位置 = 0; 内部侧位置 < 命令解释器.长度[1]; 内部侧位置++) if (数据[循环索引 + 内部侧位置] != 命令解释器.词元值[命令解释器.起始分[1] + 内部侧位置]) 是否相同 = false;
                    if (是否相同) 曾经已找到 = true;
                }
                if (曾经已找到 && (条目个数 > 0 || 字节数据 == 10)) { for (int 循环索引 = 0; 循环索引 < 条目个数; 循环索引++) 板.写入串行(数据[循环索引]); 终端输入输出.字符(10); 匹配数++; }
                条目个数 = 0; if (字节数据 != 10) break;
            } else if (条目个数 < 数据.length) 数据[条目个数++] = 字节数据;
            else { 命令解释器.错误(-28); 关闭(); return; }
        }
        关闭(); if (字节数据 < 0) 命令解释器.错误(字节数据); else if (命令解释器.结果 == 0) 命令解释器.结果 = 匹配数 == 0 ? 1 : 0;
    }
    static void 头值(boolean 后方位置) {
        int 参数索引 = 1, 行数 = 10;
        if (命令解释器.相等文本(1, "-n")) { 行数 = 数字值(2); 参数索引 = 3; }
        if (行数 < 0 || 命令解释器.词元个数 > 参数索引 + 1) { 命令解释器.结果 = 2; 终端输入输出.写入("사용법: head/tail [-n 行数] [文件]\n"); return; }
        if (!准备输入(参数索引)) return;
        int 条目个数 = 0, 字节数据;
        while ((字节数据 = 读取()) != 256 && 字节数据 >= 0) { if (条目个数 == 数据.length) { 命令解释器.错误(-28); 关闭(); return; } 数据[条目个数++] = 字节数据; }
        关闭(); if (字节数据 < 0) { 命令解释器.错误(字节数据); return; }
        int 局部开始 = 0, 结束位置 = 条目个数;
        if (行数 == 0) return;
        if (后方位置) { int 总计个数 = 0; for (int 循环索引 = 条目个数 - 2; 循环索引 >= 0; 循环索引--) if (数据[循环索引] == 10 && ++总计个数 == 行数) { 局部开始 = 循环索引 + 1; break; } }
        else { int 总计个数 = 0; for (int 循环索引 = 0; 循环索引 < 条目个数; 循环索引++) if (数据[循环索引] == 10 && ++总计个数 == 行数) { 结束位置 = 循环索引 + 1; break; } }
        for (int 循环索引 = 局部开始; 循环索引 < 结束位置; 循环索引++) 板.写入串行(数据[循环索引]);
    }
    static void 写入共同() {
        boolean 追加 = 命令解释器.相等文本(1, "-a"); int 参数索引 = 追加 ? 2 : 1;
        if (命令解释器.词元个数 != 参数索引 + 1) { 命令解释器.结果 = 2; 终端输入输出.写入("사용법: tee [-a] 文件\n"); return; }
        int 已打开文件编号 = 打开文件(参数索引, 追加 ? 1089 : 577); if (已打开文件编号 < 0) { 命令解释器.错误(已打开文件编号); return; }
        输入文件 = -1; int 字节数据;
        while ((字节数据 = 读取()) != 256 && 字节数据 >= 0) { int 已处理值 = 内存文件集.写入(已打开文件编号, 字节数据); if (已处理值 < 0) { 命令解释器.错误(已处理值); break; } 板.写入串行(字节数据); }
        内存文件集.关闭(已打开文件编号);
    }
}
