        int 地址=地址值, 已发送个数=0, 已接收个数=0, 累积值=0, 最小限制=100000, 最大限制=0;
        终端输入输出.写入("PING ");写入地址(地址);终端输入输出.写入(" 32 ICMP bytes\n");
