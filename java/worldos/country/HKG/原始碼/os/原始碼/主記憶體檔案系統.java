/** 工作階段期間保留 8 個檔案；原始碼編輯或編譯失敗時保留原檔案。 */
public final class 主記憶體檔案系統 {
    static final int 最大大小 = 16384;
    static int[] 名稱列列表 = new int[8 * 64];
    static int[] 大小列表 = new int[8];
    static int[] 打開個數 = new int[8], 權限授權列 = new int[8];
    static int[] 名稱 = new int[64];
    static int[] 編輯值 = new int[最大大小];
    static boolean 是否編輯中 = false;
    static boolean 溢出值 = false;
    static int 編輯大小 = 0;

    static boolean 檢查名稱(int[] 字元值, int 長度) {
        if (長度 < 1 || 長度 > 63) return false;
        for (int 數 = 0; 數 < 長度; 數++) {
            int 值 = 字元值[數];
            if (!(值 >= 'a' && 值 <= 'z') && !(值 >= 'A' && 值 <= 'Z')
                && !(值 >= '0' && 值 <= '9') && 值 != '_' && 值 != '-' && 值 != '.') return false;
        }
        return 字元值[0] != '.';
    }

    static int 查找條目(int[] 字元值, int 長度) {
        if (!檢查名稱(字元值, 長度)) return -22;
        for (int 數 = 0; 數 < 8; 數++) {
            boolean 相等文本 = 名稱列列表[數 * 64 + 長度] == 0;
            for (int 槽條目 = 0; 槽條目 < 長度; 槽條目++) if (名稱列列表[數 * 64 + 槽條目] != 字元值[槽條目]) 相等文本 = false;
            if (相等文本) return 數;
        }
        return -2;
    }

    static int 存儲值(int[] 字元值, int 長度, int[] 資料, int 大小) {
        if (!檢查名稱(字元值, 長度) || 大小 < 0 || 大小 > 資料.length) return -22;
        if (大小 > 最大大小) return -90;
        int 編號 = 查找條目(字元值, 長度);
        if (編號 == -2) {
            for (int 數 = 0; 數 < 8 && 編號 < 0; 數++) if (名稱列列表[數 * 64] == 0 && 打開個數[數] == 0) 編號 = 數;
            if (編號 >= 0) 權限授權列[編號] = 438;
        }
        if (編號 < 0) return -28;
        int 地址 = 設備.檔案記憶體() + 編號 * 最大大小;
        for (int 數 = 0; 數 < 大小; 數++) 設備.寫入記憶體(地址 + 數, 資料[數]);
        for (int 數 = 0; 數 < 64; 數++) 名稱列列表[編號 * 64 + 數] = 數 < 長度 ? 字元值[數] : 0;
        大小列表[編號] = 大小;
        return 大小;
    }

    static void 條目列表() {
        for (int 數 = 0; 數 < 8; 數++) if (名稱列列表[數 * 64] != 0) {
            for (int 槽條目 = 0; 槽條目 < 64 && 名稱列列表[數 * 64 + 槽條目] != 0; 槽條目++) 字元終端.字元(名稱列列表[數 * 64 + 槽條目]);
            字元終端.寫入("  "); 字元終端.寫入編號(大小列表[數]); 字元終端.寫入("位元組值\n");
        }
        字元終端.寫入(存儲設備連接.是否可用 ? "檔案 8칸, 파일당 16384바이트; sync로 存儲值 장치에 보존\n"
            : "臨時值 檔案 8칸, 파일당 16384바이트; 重試值 시작하면 사라짐\n");
    }

    static void 命令(int[] 輸入值, int 運行, int 長度, int 動作) {
        while (運行 < 長度 && 輸入值[運行] == ' ') 運行++;
        int 結尾 = 長度;
        while (結尾 > 運行 && 輸入值[結尾 - 1] == ' ') 結尾--;
        int 數 = 結尾 - 運行;
        if (數 < 1 || 數 > 63) { 字元終端.寫入("올바르지 않은 檔案 名稱\n"); return; }
        for (int 槽條目 = 0; 槽條目 < 64; 槽條目++) 名稱[槽條目] = 槽條目 < 數 ? 輸入值[運行 + 槽條目] : 0;
        int 編號 = 查找條目(名稱, 數);
        if (編號 == -22) { 字元終端.寫入("올바르지 않은 檔案 名稱\n"); return; }
        if (動作 == 0) {
            是否編輯中 = true; 編輯大小 = 0; 溢出值 = false;
            字元終端.寫入("원문을 입력하세요. .save는 보존, .cancel은 취소합니다.\n");
        } else if (編號 < 0) 字元終端.寫入("파일을 찾을 數 없습니다\n");
        else if (動作 == 1) {
            int 地址 = 設備.檔案記憶體() + 編號 * 最大大小;
            for (int 槽條目 = 0; 槽條目 < 大小列表[編號]; 槽條目++) 字元終端.字元(設備.讀取記憶體(地址 + 槽條目));
            字元終端.字元(10);
        } else { 名稱列列表[編號 * 64] = 0; 大小列表[編號] = 0; 字元終端.寫入("파일을 지웠습니다\n"); }
    }

    static boolean 是否精確(int[] 輸入值, int 長度, String 短語值) {
        if (長度 != 短語值.length()) return false;
        for (int 槽條目 = 0; 槽條目 < 長度; 槽條目++) if (輸入值[槽條目] != 短語值.charAt(槽條目)) return false;
        return true;
    }

    static void 已編輯行(int[] 輸入值, int 長度, boolean 行溢出) {
        if (是否精確(輸入值, 長度, ".cancel")) {
            是否編輯中 = false; 字元終端.寫入("취소했습니다. 원래 파일은 그대로입니다\n");
        } else if (是否精確(輸入值, 長度, ".save")) {
            是否編輯中 = false;
            if (溢出值) { 字元終端.寫入("입력이 너무 깁니다. 원래 파일은 그대로입니다\n"); return; }
            int 數 = 0;
            while (數 < 64 && 名稱[數] != 0) 數++;
            int 結果 = 存儲值(名稱, 數, 編輯值, 編輯大小);
            字元終端.寫入(結果 >= 0 ? "보존한 位元組值 數: " : "보존 失敗值: ");
            字元終端.寫入編號(結果); 字元終端.字元(10);
        } else if (行溢出 || 長度 + 1 > 最大大小 - 編輯大小) 溢出值 = true;
        else {
            for (int 數 = 0; 數 < 長度; 數++) 編輯值[編輯大小++] = 輸入值[數];
            編輯值[編輯大小++] = 10;
        }
    }

    static void 範例(String 檔案, String 內容值) {
        for (int 數 = 0; 數 < 64; 數++) 名稱[數] = 數 < 檔案.length() ? 檔案.charAt(數) : 0;
        for (int 數 = 0; 數 < 內容值.length(); 數++) 編輯值[數] = 內容值.charAt(數);
        存儲值(名稱, 檔案.length(), 編輯值, 內容值.length());
    }

    static void 準備() {
        範例("Hello.java", "public class Hello {\n public static void main(String[] args) {\n  System.out.println(\"Hello from jkoros JVM!\");\n  int sum = 0;\n  for (int i = 1; i <= 10; i++) { sum = sum + i; }\n  System.out.println(sum);\n }\n}\n");
        int 組值 = 設備.Java檔案捆綁(), 大小 = 設備.Java檔案捆綁大小();
        if (大小 < 8 || 執行管理.數(組值) != 0x464a4b4a) { 字元終端.寫入("올바르지 않은 Java 檔案 組值\n"); return; }
        int 項目個數 = 執行管理.數(組值 + 4);
        if (項目個數 < 0 || 項目個數 > 8 || 項目個數 > (大小 - 8) / 72) { 字元終端.寫入("올바르지 않은 Java 檔案 條目列表\n"); return; }
        for (int 數 = 0; 數 < 項目個數; 數++) {
            int 條目值 = 組值 + 8 + 數 * 72, 長度 = 0;
            for (int 槽條目 = 0; 槽條目 < 64; 槽條目++) 名稱[槽條目] = 設備.讀取記憶體(條目值 + 槽條目);
            while (長度 < 64 && 名稱[長度] != 0) 長度++;
            int 位置 = 執行管理.數(條目值 + 64), 檔案大小 = 執行管理.數(條目值 + 68);
            if (!檢查名稱(名稱, 長度) || 檔案大小 < 0 || 檔案大小 > 最大大小 || 位置 < 8 + 項目個數 * 72 || 位置 > 大小 - 檔案大小) {
                字元終端.寫入("올바르지 않은 Java 檔案 條目值\n"); return;
            }
            for (int 槽條目 = 0; 槽條目 < 檔案大小; 槽條目++) 編輯值[槽條目] = 設備.讀取記憶體(組值 + 位置 + 槽條目);
            if (存儲值(名稱, 長度, 編輯值, 檔案大小) < 0) { 字元終端.寫入("Java 파일을 가져오지 못했습니다\n"); return; }
        }
    }
}
