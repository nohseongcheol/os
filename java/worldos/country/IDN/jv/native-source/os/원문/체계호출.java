/** int 0x80 게이트가 호출한다. 모든 사용자 포인터/길이는 접근 전에 검사한다. */
public final class 체계호출 {
    static int[] 임시자료 = new int[1024];

    static int 배열길이(int 주소) {
        if (!실행관리.범위(주소, 4)) return -14;
        int 길이 = 실행관리.수(주소);
        if (길이 < 0 || 길이 > (실행관리.사용자끝 - 주소 - 4) / 4) return -14;
        return 길이;
    }

    public static int 처리(int 번호, int 가, int 나, int 다, int 라, int 마) {
        if (번호 == 30) return 파일서술자관리.파일열기(가, 나, 다);
        if (번호 == 31) return 파일서술자관리.파일읽기(가, 나, 다);
        if (번호 == 32) return 파일서술자관리.파일쓰기(가, 나, 다);
        if (번호 == 33) return 파일서술자관리.파일닫기(가);
        if (번호 == 34) return 파일서술자관리.파일위치옮기기(가, 나, 다);
        if (번호 == 35) return 파일서술자관리.서술자복제(가, 0, false, 0);
        if (번호 == 36) return 파일서술자관리.서술자복제(가, 나, true, 0);
        if (번호 == 37) return 파일서술자관리.파일상태읽기(가, 나);
        if (번호 == 38) return 파일서술자관리.파일이름지우기(가);
        if (번호 == 39) return 파일서술자관리.파일길이정하기(가, 나);
        if (번호 == 40) return 파일서술자관리.서술자제어(가, 나, 다);
        if (번호 == 41) return 파일서술자관리.통신종단점만들기(가, 나, 다);
        if (번호 == 42) return 파일서술자관리.통신주소묶기(가, 나, 다);
        if (번호 == 43) return 파일서술자관리.자료전문보내기(가, 나, 다, 라, 마);
        if (번호 == 44) return 파일서술자관리.자료전문받기(가, 나, 다, 라, 마);
        if (번호 == 45) return 파일서술자관리.통신주소읽기(가, 나, 다);
        if (번호 == 46) return 파일서술자관리.수신대기정하기(가, 나);
        if (번호 == 47) {
            int 기술 = 파일서술자관리.기술찾기(가);
            if (기술 < 0) return -9;
            if (파일서술자관리.종류[기술] != 2) return -22;
            return 파일보존.동기화();
        }
        if (번호 == 1) {
            int 길이 = 배열길이(가);
            if (길이 < 0) return 길이;
            if (길이 > 4096) return -90;
            for (int 글자 = 0; 글자 < 길이; 글자++) 문자단말.문자(실행관리.수(가 + 4 + 글자 * 4) & 65535);
            return 길이;
        }
        if (번호 == 2) return 실행관리.인수수;
        if (번호 == 3) return 가 >= 0 && 가 < 실행관리.인수수 ? 실행관리.인수주소[가] : 0;
        if (번호 == 10) return 통신망.열기(가);
        if (번호 == 11) {
            int 길이 = 배열길이(라);
            if (길이 < 0) return 길이;
            if (마 < 0 || 마 > 길이 || 마 > 1024) return -90;
            for (int 위치 = 0; 위치 < 마; 위치++) 임시자료[위치] = 실행관리.수(라 + 4 + 위치 * 4) & 255;
            return 통신망.보내기(가, 나, 다, 임시자료, 마);
        }
        if (번호 == 12) {
            int 길이 = 배열길이(나);
            if (길이 < 0) return 길이;
            if (다 < 0 || 다 > 2000) return -22;
            int 결과 = 통신망.받기(가, 임시자료, 길이 < 1024 ? 길이 : 1024, 다);
            if (결과 >= 0) for (int 위치 = 0; 위치 < 결과; 위치++) 실행관리.수쓰기(나 + 4 + 위치 * 4, 임시자료[위치]);
            return 결과;
        }
        if (번호 == 13) return 통신망.Nutup(가);
        if (번호 == 14) return 통신망.내주소;
        if (번호 == 15) return 통신망.상대주소(가);
        if (번호 == 16) return 통신망.상대접속번호(가);
        if (번호 == 22) {
            if (가 < 0 || 가 > 65535) return -22;
            문자단말.문자(가); return 1;
        }
        if (번호 == 20 || 번호 == 21) {
            int 이름크기 = 배열길이(가), 자료크기 = 배열길이(나);
            if (이름크기 < 0 || 자료크기 < 0) return -14;
            if (이름크기 < 1 || 이름크기 > 64) return -22;
            int 길이 = 0;
            while (길이 < 이름크기 && 실행관리.수(가 + 4 + 길이 * 4) != 0) {
                주기억파일체계.이름[길이] = 실행관리.수(가 + 4 + 길이 * 4);
                길이++;
            }
            if (!주기억파일체계.이름검사(주기억파일체계.이름, 길이)) return -22;
            if (번호 == 20) {
                int 파일 = 주기억파일체계.찾기(주기억파일체계.이름, 길이);
                if (파일 < 0) return 파일;
                int 크기 = 주기억파일체계.크기들[파일];
                if (크기 > 자료크기) return -90;
                int 주소 = 장치.파일기억() + 파일 * 주기억파일체계.최대크기;
                for (int 수 = 0; 수 < 크기; 수++) 실행관리.수쓰기(나 + 4 + 수 * 4, 장치.기억읽기(주소 + 수));
                return 크기;
            }
            if (다 < 0 || 다 > 자료크기) return -22;
            if (다 > 주기억파일체계.최대크기) return -90;
            for (int 수 = 0; 수 < 다; 수++) 주기억파일체계.편집[수] = 실행관리.수(나 + 4 + 수 * 4) & 255;
            return 주기억파일체계.저장(주기억파일체계.이름, 길이, 주기억파일체계.편집, 다);
        }
        return -38;
    }
}
