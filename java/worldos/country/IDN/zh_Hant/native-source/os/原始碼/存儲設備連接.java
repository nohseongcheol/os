/** 第一個 IDE 裝置的 512 位元組邏輯磁區；此層不格式化或清除任意裝置。 */
public final class 存儲設備連接 {
    static boolean 是否可用 = false;
    static int[] 區段資料 = new int[512];
    static void 等待狀態短暫地() {
        for (int 編號 = 0; 編號 < 4; 編號++) 設備.讀取輸入輸出位元組(0x3f6);
    }
    static int 等待狀態直到就緒(boolean 資料必需) {
        int 運行 = 設備.毫秒();
        while (設備.毫秒() - 運行 < 500) {
            int 狀態值 = 設備.讀取輸入輸出位元組(0x1f7);
            if (狀態值 == 0 || 狀態值 == 255) return -19;
            if ((狀態值 & 128) == 0) {
                if ((狀態值 & 33) != 0) return -5;
                if (!資料必需 || (狀態值 & 8) != 0) return 0;
            }
            設備.掛起短暫地();
        }
        return -110;
    }
    static int 申請(int 區段值, int 命令) {
        if (區段值 < 0 || 區段值 >= 2048) return -22;
        設備.寫入輸入輸出位元組(0x3f6, 2); // 採用輪詢，不使用 IDE IRQ。
        設備.寫入輸入輸出位元組(0x1f6, 0xe0); 等待狀態短暫地();
        int 結果 = 等待狀態直到就緒(false);
        if (結果 < 0) return 結果;
        設備.寫入輸入輸出位元組(0x1f2, 1);
        設備.寫入輸入輸出位元組(0x1f3, 區段值 & 255);
        設備.寫入輸入輸出位元組(0x1f4, (區段值 >>> 8) & 255);
        設備.寫入輸入輸出位元組(0x1f5, 0);
        設備.寫入輸入輸出位元組(0x1f7, 命令); 等待狀態短暫地();
        return 等待狀態直到就緒(true);
    }
    static int 讀取(int 區段值) {
        int 結果 = 申請(區段值, 0x20);
        if (結果 < 0) return 結果;
        for (int 編號 = 0; 編號 < 256; 編號++) {
            int 值 = 設備.讀取輸入輸出短整數(0x1f0);
            區段資料[編號 * 2] = 值 & 255; 區段資料[編號 * 2 + 1] = 值 >>> 8;
        }
        等待狀態短暫地(); return 等待狀態直到就緒(false);
    }
    static int 寫入(int 區段值) {
        if (!是否可用 || 區段值 < 1 || 區段值 > 518) return -19;
        int 結果 = 申請(區段值, 0x30);
        if (結果 < 0) return 結果;
        for (int 編號 = 0; 編號 < 256; 編號++)
            設備.寫入輸入輸出短整數(0x1f0, 區段資料[編號 * 2] | 區段資料[編號 * 2 + 1] << 8);
        等待狀態短暫地(); return 等待狀態直到就緒(false);
    }
    static int 沖刷輸出() {
        if (!是否可用) return -19;
        設備.寫入輸入輸出位元組(0x1f7, 0xe7); 等待狀態短暫地();
        return 等待狀態直到就緒(false);
    }
    static int 解析整數(int 位置) {
        return 區段資料[位置] | 區段資料[位置 + 1] << 8 | 區段資料[位置 + 2] << 16 | 區段資料[位置 + 3] << 24;
    }
    static void 寫入整數值(int 位置, int 值) {
        for (int 編號 = 0; 編號 < 4; 編號++) 區段資料[位置 + 編號] = (值 >>> (編號 * 8)) & 255;
    }
}
