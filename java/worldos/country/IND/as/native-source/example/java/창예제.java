import 한국어.자체.উইণ্ড;
import 한국어.자체.লেবেল;
import 한국어.자체.পাঠৰ_ক্ষেত্ৰ;
import 한국어.자체.বুটাম;
import 한국어.자체.ইভেণ্ট_লানি;
import 한국어.자체.নিৰ্গম;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing উইণ্ড: as 입력 → বুটাম → ৰিডমি_ফাইল_eb81d7d9 টেক্সট সতেজ_কৰক. */
public class 창예제 implements 실행할일, 동작받이 {
    private উইণ্ড 인사창;
    private পাঠৰ_ক্ষেত্ৰ নাম_ফিল্ড;
    private লেবেল 인사말;
    private int 인사횟수;

    public void খোলক_উইণ্ড() {
        인사창 = new উইণ্ড("as Swing", 460, 300);
        인사창.যোগ_কৰক_উপাদান(new লেবেল("as", 20, 20, 420, 28));
        নাম_ফিল্ড = new পাঠৰ_ক্ষেত্ৰ("as", 20, 64, 420, 30);
        인사말 = new লেবেল("as", 20, 152, 420, 28);
        인사창.যোগ_কৰক_উপাদান(নাম_ফিল্ড);
        인사창.যোগ_কৰক_উপাদান(new বুটাম("인사하기", 20, 108, 180, 32, this));
        인사창.যোগ_কৰক_উপাদান(인사말);
        인사창.যোগ_কৰক_উপাদান(new লেবেল("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.শ্ব_উইণ্ড();
        নিৰ্গম.লিখক_লাইন("GUI 예제 প্ৰস্তুত_কৰক: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.লিখক_পাঠ("as, " + নাম_ফিল্ড.글읽기() + "님! (" + 인사횟수 + ")");
        নিৰ্গম.লিখক_লাইন("GUI 인사: " + 인사말.글읽기());
    }

    public void চলাওক() { খোলক_উইণ্ড(); }
    public void 동작받기(동작알림 알림) {
        নিৰ্গম.লিখক_লাইন("কাৰ্য্য 알림: " + 알림.আদেশ_পাঠ());
        인사하기();
    }
    public static void সঞ্চালন() {
        ইভেণ্ট_লানি.나중에실행(new 창예제());
    }
}
