#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 বাইট_মান 위치로 자체 C 이름을 옮기는 일회성 이행 সঁজুলিসমূহ.

외부 구조체의 멤버, ষ্ট্ৰিং_মান, C 표준 ফাংছন_মান, 이식 규약은 보존한다.
입력은 পৰিবৰ্তন_কৰক_মান 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def নিষ্পাদন_আদেশ():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['ত্ৰুটি']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    নাম_তালিকা = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:নাম_তালিকা[প্রবিষ্ট_মান['নাম']] for 고유,প্রবিষ্ট_মান in 선언표.items()
                if প্রবিষ্ট_মান['নাম'] in নাম_তালিকা and প্রবিষ্ট_মান['নাম'] not in 규격}
    সংযোগ_তালিকা = {প্রবিষ্ট_মান['নাম']:নাম_তালিকা[প্রবিষ্ট_মান['নাম']] for প্রবিষ্ট_মান in 선언표.values()
              if প্রবিষ্ট_মান.get('সংযোগ_স্থাপনা')==4 and প্রবিষ্ট_মান['종류'] in (8,9)
              and প্রবিষ্ট_মান['নাম'] in নাম_তালিকা and প্রবিষ্ট_মান['নাম'] not in 규격}
    # সৃষ্টি_কৰক AOT C·어셈블리·공개 SDK가 공유하는 바이너리 সংযোগ_স্থাপনা 이름만 유지한다.
    머리 = ['/* 한국어 উৎস_ট্ৰি 이름과 기존 মেচিন সংযোগ_স্থাপনা কেছ_মান. 자동 সৃষ্টি_কৰক: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(সংযোগ_তালিকা.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    পৰিৱৰ্তনসমূহ_সূচী = defaultdict(dict)
    for নথিপত্ৰ,অফছেট_মান,নাম,고유 in 분석['참조']:
        if 고유 in 바꿀선언:
            পৰিৱৰ্তনসমূহ_সূচী[নথিপত্ৰ][অফছেট_মান] = (নাম,바꿀선언[고유])
    লগ_শাৰী = ['নথিপত্ৰ\t원래바이트위치\t이전이름\t한국어이름']
    প্ৰত্যাখ্যান_কৰক_মান = []
    for নথিপত্ৰ,পৰিবৰ্তন_কৰক_মান in পৰিৱৰ্তনসমূহ_সূচী.items():
        পথ = Path(নথিপত্ৰ); 원본 = পথ.read_bytes(); ডাটা = 원본
        for অফছেট_মান,(옛이름,새이름) in sorted(পৰিবৰ্তন_কৰক_মান.items(),reverse=True):
            끝 = অফছেট_মান+len(옛이름.encode())
            if 원본[অফছেট_মান:끝] != 옛이름.encode():
                প্ৰত্যাখ্যান_কৰক_মান.append((str(পথ.relative_to(기준)),অফছেট_মান,옛이름));continue
            ডাটা = ডাটা[:অফছেট_মান]+새이름.encode()+ডাটা[끝:]
            লগ_শাৰী.append('{}\t{}\t{}\t{}'.format(পথ.relative_to(기준),অফছেট_মান,옛이름,새이름))
        পথ.write_bytes(ডাটা)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    মেক্ৰ_মান = {প্রবিষ্ট_মান['নাম']:নাম_তালিকা[প্রবিষ্ট_মান['নাম']] for প্রবিষ্ট_মান in 선언표.values()
              if প্রবিষ্ট_মান['종류']==501 and প্রবিষ্ট_মান['নাম'] in নাম_তালিকা and প্রবিষ্ট_মান['নাম'] not in 규격}
    for পথ in sorted({Path(প্রবিষ্ট_মান['নথিপত্ৰ']) for প্রবিষ্ট_মান in 선언표.values()}):
        লাইন_সূচী = পথ.read_text().splitlines(True); 이어짐 = False
        for ইনডেক্স,লাইন in enumerate(লাইন_সূচী):
            전처리 = 이어짐 or bool(re.match(r'\s*#',লাইন))
            이어짐 = 전처리 and লাইন.rstrip().endswith('\\')
            if 전처리:
                লুকআপ_তালিকা = নাম_তালিকা if re.match(r'\s*#\s*define\b',লাইন) or 이어짐 else মেক্ৰ_মান
                লাইন_সূচী[ইনডেক্স] = 낱말.sub(lambda 맞음: লুকআপ_তালিকা.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],লাইন)
        পথ.write_text(''.join(লাইন_সূচী))
    # 각 자체 অনুবাদ_উৎস 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for পথ in sorted({Path(প্রবিষ্ট_মান['নথিপত্ৰ']) for প্রবিষ্ট_মান in 선언표.values()}):
        if পথ.suffix not in ('.c','.cpp'):continue
        পীয়েৰ_মান = '../' * len(পথ.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        পথ.write_text('#include "'+পীয়েৰ_মান+'"\n'+পথ.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(লগ_শাৰী)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(প্ৰত্যাখ্যান_কৰক_মান,ensure_ascii=False,indent=2)+'\n')
    print('পৰিবৰ্তন_কৰক_মান',len(লগ_শাৰী)-1,'전처리 재검토',len(প্ৰত্যাখ্যান_কৰক_মান),'মেচিন সংযোগ_স্থাপনা',len(সংযোগ_তালিকা))

if __name__=='__main__': নিষ্পাদন_আদেশ()
