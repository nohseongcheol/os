#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from ডেস্কটপ_দর্শন import কীবোর্ড


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.পাঠ_বাফাৰ = ''
        def ই_মেইল_কৰক(ডাটা):
            for বৰ্ণ_ডাটা in ডাটা.decode('utf-8'):
                if বৰ্ণ_ডাটা == '\x7f': 자신.পাঠ_বাফাৰ = 자신.পাঠ_বাফাৰ[:-1]
                else: 자신.পাঠ_বাফাৰ += বৰ্ণ_ডাটা
        자신.কীবোর্ড_প্রবিষ্ট = কীবোর্ড(ই_মেইল_কৰক)

    def 글쇠누르기(자신, প্ৰতীক_মান):
        자신.কীবোর্ড_প্রবিষ্ট.누름값(True, প্ৰতীক_মান)
        자신.কীবোর্ড_প্রবিষ্ট.누름값(False, প্ৰতীক_মান)

    def প্ৰকাৰ_বর্গ(자신, 누름열):
        for 누름값 in 누름열: 자신.글쇠누르기(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.글쇠누르기(0xffc6); 자신.প্ৰকাৰ_বর্গ(누름열)
                자신.assertEqual(자신.পাঠ_বাফাৰ, 예상결과)

    def test_앞글자지우기(자신):
        자신.글쇠누르기(0xff31); 자신.প্ৰকাৰ_বর্গ('dlfr')
        자신.assertEqual(자신.পাঠ_বাফাৰ,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.글쇠누르기(0xff08); 자신.assertEqual(자신.পাঠ_বাফাৰ,예상결과)
        자신.প্ৰকাৰ_বর্গ('gksk'); 자신.assertEqual(자신.পাঠ_বাফাৰ,'하나')
        자신.글쇠누르기(0xff08); 자신.assertEqual(자신.পাঠ_বাফাৰ,'하ㄴ')

    def test_전환반복확정(자신):
        자신.প্ৰকাৰ_বর্গ('echo ')
        자신.কীবোর্ড_প্রবিষ্ট.누름값(True,0xffe1)
        자신.কীবোর্ড_প্রবিষ্ট.누름값(True,32); 자신.কীবোর্ড_প্রবিষ্ট.누름값(True,32)
        자신.কীবোর্ড_প্রবিষ্ট.누름값(False,32); 자신.কীবোর্ড_প্রবিষ্ট.누름값(False,0xffe1)
        자신.assertTrue(자신.কীবোর্ড_প্রবিষ্ট.한글여부)
        자신.প্ৰকাৰ_বর্গ('gksrmf'); 자신.글쇠누르기(0xff31); 자신.প্ৰকাৰ_বর্গ(' English')
        자신.assertEqual(자신.পাঠ_বাফাৰ,'echo 한글 English')
        자신.assertFalse(자신.কীবোর্ড_প্রবিষ্ট.한글여부)
        자신.글쇠누르기(0xffc6); 자신.প্ৰকাৰ_বর্গ('rk'); 자신.글쇠누르기(0xff51)
        자신.প্ৰকাৰ_বর্গ('sk'); 자신.assertTrue(자신.পাঠ_বাফাৰ.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.글쇠누르기(0xffc6); 자신.প্ৰকাৰ_বর্গ('rk')
        자신.কীবোর্ড_প্রবিষ্ট.ক্লিপ_বোৰ্ড_মান='লেপন_কৰক_মান'.encode()
        자신.কীবোর্ড_প্রবিষ্ট.누름값(True,0xffe3); 자신.কীবোর্ড_প্রবিষ্ট.누름값(True,0xffe1)
        자신.글쇠누르기(ord('v'))
        자신.কীবোর্ড_প্রবিষ্ট.누름값(False,0xffe1); 자신.কীবোর্ড_প্রবিষ্ট.누름값(False,0xffe3)
        자신.글쇠누르기(0x0100d55c); 자신.প্ৰকাৰ_বর্গ('sk')
        자신.assertEqual(자신.পাঠ_বাফাৰ,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
