#include "호출경계.h"
extern int main(int 인수개수, char **যুক্তি_সূচী);
static char যুক্তি_মেম_ৰি[2048];
static char *যুক্তি_সূচী[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 নিষ্পাদন_আদেশ 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    যুক্তি_সূচী[0] = "jkoros-app";
    int অৱস্থান = 0;
    for (int ইনডেক্স = 0; ইনডেক্স < 개수; ইনডেক্স++) {
        const int *원본 = (const int *)jkoros_syscall(3, ইনডেক্স, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        যুক্তি_সূচী[ইনডেক্স + 1] = যুক্তি_মেম_ৰি + অৱস্থান;
        for (int শ্লট_প্রবিষ্ট = 0; শ্লট_প্রবিষ্ট < 원본[0]; শ্লট_প্রবিষ্ট++) {
            if (অৱস্থান >= 2047) return 126;
            যুক্তি_মেম_ৰি[অৱস্থান++] = 원본[শ্লট_প্রবিষ্ট + 1];
        }
        যুক্তি_মেম_ৰি[অৱস্থান++] = 0;
    }
    যুক্তি_সূচী[개수 + 1] = 0;
    return main(개수 + 1, যুক্তি_সূচী);
}
