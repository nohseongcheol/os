import ভাৰত.JIndOS.ফাইল_ছিষ্টেম.파일서술자표;

/** প্ৰক্ৰিয়া_মান 식별자와 라운드로빈 প্ৰস্তুত_কৰক 대기열을 관리한다. */
public final class অনুসূচক {
    private final পৃষ্ঠা_মেনেজাৰ 쪽관리;
    private final Map<Integer, প্ৰক্ৰিয়া_মান> প্ৰক্ৰিয়া_সূচী = new HashMap<Integer, প্ৰক্ৰিয়া_মান>();
    private final Queue<প্ৰক্ৰিয়া_মান> 준비대기열 = new ArrayDeque<প্ৰক্ৰিয়া_মান>();
    private int পৰৱৰ্তী_চিনাক্তকাৰী = 1;

    public অনুসূচক(পৃষ্ঠা_মেনেজাৰ 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public প্ৰক্ৰিয়া_মান 첫과정(파일서술자표 파일서술자) {
        প্ৰক্ৰিয়া_মান 새과정 = new প্ৰক্ৰিয়া_মান(আৱণ্টন_চিনাক্তকাৰী(), 0, 쪽관리.새주소공간(), 파일서술자);
        প্ৰক্ৰিয়া_সূচী.put(Integer.valueOf(새과정.চিনাক্তকাৰী_মান()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public প্ৰক্ৰিয়া_মান 복제(প্ৰক্ৰিয়া_মান 부모) {
        প্ৰক্ৰিয়া_মান শিশু_মান = new প্ৰক্ৰিয়া_মান(
                আৱণ্টন_চিনাক্তকাৰী(),
                부모.চিনাক্তকাৰী_মান(),
                쪽관리.쓰기시복사복제(부모.ঠিকনা_স্থান()),
                부모.파일서술자().복제());
        শিশু_মান.프로그램끝설정(부모.프로그램끝());
        প্ৰক্ৰিয়া_সূচী.put(Integer.valueOf(শিশু_মান.চিনাক্তকাৰী_মান()), শিশু_মান);
        준비대기열.offer(শিশু_মান);
        return শিশু_মান;
    }

    public প্ৰক্ৰিয়া_মান পৰৱৰ্তী_প্ৰক্ৰিয়া() {
        int 검사수 = 준비대기열.size();
        for (int ইনডেক্স = 0; ইনডেক্স < 검사수; ইনডেক্স++) {
            প্ৰক্ৰিয়া_মান পৰৱৰ্তী_আইটেম = 준비대기열.poll();
            if (পৰৱৰ্তী_আইটেম != null && (পৰৱৰ্তী_আইটেম.অৱস্থা_মান() == প্ৰক্ৰিয়া_অৱস্থা.প্ৰস্তুত_কৰক || পৰৱৰ্তী_আইটেম.অৱস্থা_মান() == প্ৰক্ৰিয়া_অৱস্থা.নিষ্পাদন_আদেশ)) {
                পৰৱৰ্তী_আইটেম.ছেট_অৱস্থা(প্ৰক্ৰিয়া_অৱস্থা.নিষ্পাদন_আদেশ);
                준비대기열.offer(পৰৱৰ্তী_আইটেম);
                return পৰৱৰ্তী_আইটেম;
            }
        }
        return null;
    }

    public int 자식기다리기(প্ৰক্ৰিয়া_মান 부모, int শিশু_চিনাক্তকাৰী, boolean 기다리지않음) {
        for (প্ৰক্ৰিয়া_মান 후보 : প্ৰক্ৰিয়া_সূচী.values()) {
            if (후보.부모식별자() != 부모.চিনাক্তকাৰী_মান()) {
                continue;
            }
            if (শিশু_চিনাক্তকাৰী > 0 && 후보.চিনাক্তকাৰী_মান() != শিশু_চিনাক্তকাৰী) {
                continue;
            }
            if (후보.অৱস্থা_মান() == প্ৰক্ৰিয়া_অৱস্থা.প্ৰস্থান_এপ্প্) {
                int পৰিমাপ = (후보.종료값() & 0xff) << 8;
                প্ৰক্ৰিয়া_সূচী.remove(Integer.valueOf(후보.চিনাক্তকাৰী_মান()));
                return পৰিমাপ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public প্ৰক্ৰিয়া_মান বিচাৰক_প্ৰক্ৰিয়া(int চিনাক্তকাৰী_মান) {
        return প্ৰক্ৰিয়া_সূচী.get(Integer.valueOf(চিনাক্তকাৰী_মান));
    }

    private int আৱণ্টন_চিনাক্তকাৰী() {
        return পৰৱৰ্তী_চিনাক্তকাৰী++;
    }
}
