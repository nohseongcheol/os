import বাংলা.নিজ.সংযোগ;
import বাংলা.নিজ.실행인수;
import বাংলা.নিজ.전문통로;
import বাংলা.নিজ.문자;
import বাংলা.নিজ.নির্গম;
import বাংলা.নিজ.검사;
import বাংলা.নিজ.입력흐름;
import বাংলা.নিজ.ইনপুট_আউটপুট_ব্যতিক্রম;

public class নেটওয়ার্ক {
    public static void চালনা() throws ইনপুট_আউটপুট_ব্যতিক্রম {
        // হোস্ট: python3 সরঞ্জামগুলি/예제되돌림.py --tcp-port 9000 --udp-port 9001
        সংযোগ সংযোগ_স্থাপনা = সংযোগ.খুলুন("10.0.2.2", 문자.বিভাজন_করা_পূর্ণসংখ্যা(실행인수.পাঠ(0)));
        try {
            সংযোগ_স্থাপনা.টাইমআউট(700);
            byte[] ইমেইল_8c783e64 = 문자.부호화("JAVA TCP bn\n");
            সংযোগ_স্থাপনা.নির্গম().লেখা(ইমেইল_8c783e64);
            입력흐름 입력 = সংযোগ_স্থাপনা.입력();
            for (int 수 = 0; 수 < 문자.바이트수(ইমেইল_8c783e64); 수++) {
                검사.참인지(입력.পড়া() == (ইমেইল_8c783e64[수] & 255), "TCP উত্তর_দিন 불일치");
            }
        } finally { সংযোগ_স্থাপনা.বন্ধ_করুন(); }
        전문통로 종단 = 전문통로.খুলুন(0);
        try {
            종단.টাইমআউট(700);
            종단.পাঠান("10.0.2.2", 문자.বিভাজন_করা_পূর্ণসংখ্যা(실행인수.পাঠ(1)), "JAVA UDP bn");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP bn"), "UDP উত্তর_দিন 불일치");
        } finally { 종단.বন্ধ_করুন(); }
        নির্গম.লেখা_লাইন("JAVA 네트워크 যাচাই_করা: TCP UDP bn");
    }
}
