        for (int সূচি = আকার; সূচি < অবস্থান; সূচি++) ডিভাইস_মান.লেখা_মেমরি(গন্তব্য_ইমেইল + সূচি, 0);
        for (int সূচি = 0; সূচি < দৈর্ঘ্য_মান; সূচি++) ডিভাইস_মান.লেখা_মেমরি(গন্তব্য_ইমেইল + অবস্থান + সূচি, ডিভাইস_মান.기억읽기(ডাটা_ইমেইল + সূচি));
        ফাইল_পদ[기술] = অবস্থান + দৈর্ঘ্য_মান;
        if (অবস্থান + দৈর্ঘ্য_মান > আকার) মেমরি_ফাইল_পদ্ধতি.আয়তন_তালিকা[নথির_নাম] = অবস্থান + দৈর্ঘ্য_মান;
