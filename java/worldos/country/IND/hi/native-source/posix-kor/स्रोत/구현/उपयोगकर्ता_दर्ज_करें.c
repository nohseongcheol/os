#include "호출경계.h"
extern int main(int 인수개수, char **तर्क_सूची);
static char तर्क_मेमोरी[2048];
static char *तर्क_सूची[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* अद्यतित_आइटम 커널의 argv는 निष्पादित_करें_आदेश 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    तर्क_सूची[0] = "jkoros-app";
    int स्थान = 0;
    for (int इंडेक्स = 0; इंडेक्स < 개수; इंडेक्स++) {
        const int *원본 = (const int *)jkoros_syscall(3, इंडेक्स, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        तर्क_सूची[इंडेक्स + 1] = तर्क_मेमोरी + स्थान;
        for (int 칸 = 0; 칸 < 원본[0]; 칸++) {
            if (स्थान >= 2047) return 126;
            तर्क_मेमोरी[स्थान++] = 원본[칸 + 1];
        }
        तर्क_मेमोरी[स्थान++] = 0;
    }
    तर्क_सूची[개수 + 1] = 0;
    return main(개수 + 1, तर्क_सूची);
}
