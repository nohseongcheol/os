/** 부팅 ಸಿಸ್ಟಮ್_ಮಾಹಿತಿ 조회와 4KiB 고정 ಗಾತ್ರ 작업 ವಿಭಾಗ_ಮೌಲ್ಯ ವಿತರಿಸು_ಸಂಗ್ರಹ/반환. 일반 물리 ಪುಟ_ಮೌಲ್ಯ 관리자는 아니다. */
public final class 기억공간 {
    static int[] ವಿಭಾಗ_ಮೌಲ್ಯ = new int[8192];
    static int[] 사용 = new int[8];

    static int ಪಾರ್ಸ್_ಮಾಡಿ_ಪೂರ್ಣಸಂಖ್ಯೆ(int ಇಮೇಲ್) {
        return ಸಾಧನ_ಮೌಲ್ಯ.기억읽기(ಇಮೇಲ್) | (ಸಾಧನ_ಮೌಲ್ಯ.기억읽기(ಇಮೇಲ್ + 1) << 8)
            | (ಸಾಧನ_ಮೌಲ್ಯ.기억읽기(ಇಮೇಲ್ + 2) << 16) | (ಸಾಧನ_ಮೌಲ್ಯ.기억읽기(ಇಮೇಲ್ + 3) << 24);
    }

    static int 위쪽기억크기() {
        int ಸಿಸ್ಟಮ್_ಮಾಹಿತಿ = ಸಾಧನ_ಮೌಲ್ಯ.부팅정보();
        if (ಸಾಧನ_ಮೌಲ್ಯ.부팅표식() != 0x2badb002 || ಸಿಸ್ಟಮ್_ಮಾಹಿತಿ == 0 || (ಪಾರ್ಸ್_ಮಾಡಿ_ಪೂರ್ಣಸಂಖ್ಯೆ(ಸಿಸ್ಟಮ್_ಮಾಹಿತಿ) & 1) == 0) return -1;
        return ಪಾರ್ಸ್_ಮಾಡಿ_ಪೂರ್ಣಸಂಖ್ಯೆ(ಸಿಸ್ಟಮ್_ಮಾಹಿತಿ + 8);
    }

    static int ವಿತರಿಸು_ಸಂಗ್ರಹ() {
        for (int ಪದಸೂಚಿ = 0; ಪದಸೂಚಿ < 사용.length; ಪದಸೂಚಿ++) {
            if (사용[ಪದಸೂಚಿ] == 0) {
                사용[ಪದಸೂಚಿ] = 1;
                for (int ಸ್ಲಾಟ್_ನಮೂದು = 0; ಸ್ಲಾಟ್_ನಮೂದು < 1024; ಸ್ಲಾಟ್_ನಮೂದು++) ವಿಭಾಗ_ಮೌಲ್ಯ[ಪದಸೂಚಿ * 1024 + ಸ್ಲಾಟ್_ನಮೂದು] = 0;
                return ಪದಸೂಚಿ;
            }
        }
        return -1;
    }

    static boolean 반환(int ಪದಸೂಚಿ) {
        if (ಪದಸೂಚಿ < 0 || ಪದಸೂಚಿ >= 사용.length || 사용[ಪದಸೂಚಿ] == 0) return false;
        사용[ಪದಸೂಚಿ] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int ಪದಸೂಚಿ = 0; ಪದಸೂಚಿ < 사용.length; ಪದಸೂಚಿ++) 개수 += 사용[ಪದಸೂಚಿ];
        return 개수;
    }
}
