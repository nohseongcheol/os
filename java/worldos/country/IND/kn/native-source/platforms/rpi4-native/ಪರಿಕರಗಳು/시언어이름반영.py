#!/usr/bin/env python3
"""ದೃಢೀಕರಣ 고유번호와 UTF-8 ಬೈಟ್_ಮೌಲ್ಯ 위치로 자체 C 이름을 옮기는 일회성 이행 ಪರಿಕರಗಳು.

외부 구조체의 멤버, ಸ್ಟ್ರಿಂಗ್_ಮೌಲ್ಯ, C 표준 ಕಾರ್ಯ_ಮೌಲ್ಯ, 이식 규약은 보존한다.
입력은 ಬದಲಿಸು_ಮೌಲ್ಯ 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

ಬಿಂಬಿಸು_ಮೂಲ = Path(__file__).resolve().parents[1]

def ಪೂರೈಸು_ಆದೇಶ():
    분석 = json.loads((ಬಿಂಬಿಸು_ಮೂಲ/'build/한국어화/시언어분석.json').read_text())
    if 분석['ದೋಷ']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ಹೆಸರು_ಕೋಷ್ಟಕ = json.loads((ಬಿಂಬಿಸು_ಮೂಲ/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((ಬಿಂಬಿಸು_ಮೂಲ/'명명/규격이름.json').read_text()))
    ದೃಢೀಕರಣ_ಕೋಷ್ಟಕ = 분석['ದೃಢೀಕರಣ']
    바꿀선언 = {고유:ಹೆಸರು_ಕೋಷ್ಟಕ[ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು']] for 고유,ನಮೂದು_ಮೌಲ್ಯ in ದೃಢೀಕರಣ_ಕೋಷ್ಟಕ.items()
                if ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು'] in ಹೆಸರು_ಕೋಷ್ಟಕ and ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು'] not in 규격}
    ಸಂಪರ್ಕ_ಕೋಷ್ಟಕ = {ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು']:ಹೆಸರು_ಕೋಷ್ಟಕ[ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು']] for ನಮೂದು_ಮೌಲ್ಯ in ದೃಢೀಕರಣ_ಕೋಷ್ಟಕ.values()
              if ನಮೂದು_ಮೌಲ್ಯ.get('ಸಂಪರ್ಕ_ಕಲ್ಪಿಸು')==4 and ನಮೂದು_ಮೌಲ್ಯ['종류'] in (8,9)
              and ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು'] in ಹೆಸರು_ಕೋಷ್ಟಕ and ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು'] not in 규격}
    # ರಚಿಸಿ AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ಸಂಪರ್ಕ_ಕಲ್ಪಿಸು 이름만 유지한다.
    머리 = ['/* ಕನ್ನಡ ಮೂಲ_ವೃಕ್ಷ 이름과 기존 ಯಂತ್ರ ಸಂಪರ್ಕ_ಕಲ್ಪಿಸು ಕೆಲಸ_ಮೌಲ್ಯ. 자동 ರಚಿಸಿ: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(ಸಂಪರ್ಕ_ಕೋಷ್ಟಕ.items())]
    머리 += ['#endif','']
    (ಬಿಂಬಿಸು_ಮೂಲ/'명명/기계연결이름.h').write_text('\n'.join(머리))
    ಬದಲಾವಣೆಗಳು_ಪಟ್ಟಿ = defaultdict(dict)
    for ಕಡತ,ಆಫ್_ಸೆಟ್_ಮೌಲ್ಯ,ಹೆಸರು,고유 in 분석['ಉಲ್ಲೇಖ']:
        if 고유 in 바꿀선언:
            ಬದಲಾವಣೆಗಳು_ಪಟ್ಟಿ[ಕಡತ][ಆಫ್_ಸೆಟ್_ಮೌಲ್ಯ] = (ಹೆಸರು,바꿀선언[고유])
    ಲಾಗ್_ದಾಖಲೆ = ['ಕಡತ\t원래바이트위치\t이전이름\t한국어이름']
    ನಿರ್ಲಕ್ಷಿಸು_ಮೌಲ್ಯ = []
    for ಕಡತ,ಬದಲಿಸು_ಮೌಲ್ಯ in ಬದಲಾವಣೆಗಳು_ಪಟ್ಟಿ.items():
        ಮಾರ್ಗ = Path(ಕಡತ); 원본 = ಮಾರ್ಗ.read_bytes(); ಡೇಟಾ = 원본
        for ಆಫ್_ಸೆಟ್_ಮೌಲ್ಯ,(옛이름,새이름) in sorted(ಬದಲಿಸು_ಮೌಲ್ಯ.items(),reverse=True):
            끝 = ಆಫ್_ಸೆಟ್_ಮೌಲ್ಯ+len(옛이름.encode())
            if 원본[ಆಫ್_ಸೆಟ್_ಮೌಲ್ಯ:끝] != 옛이름.encode():
                ನಿರ್ಲಕ್ಷಿಸು_ಮೌಲ್ಯ.append((str(ಮಾರ್ಗ.relative_to(ಬಿಂಬಿಸು_ಮೂಲ)),ಆಫ್_ಸೆಟ್_ಮೌಲ್ಯ,옛이름));continue
            ಡೇಟಾ = ಡೇಟಾ[:ಆಫ್_ಸೆಟ್_ಮೌಲ್ಯ]+새이름.encode()+ಡೇಟಾ[끝:]
            ಲಾಗ್_ದಾಖಲೆ.append('{}\t{}\t{}\t{}'.format(ಮಾರ್ಗ.relative_to(ಬಿಂಬಿಸು_ಮೂಲ),ಆಫ್_ಸೆಟ್_ಮೌಲ್ಯ,옛이름,새이름))
        ಮಾರ್ಗ.write_bytes(ಡೇಟಾ)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ಮ್ಯಾಕ್ರೊ_ಮೌಲ್ಯ = {ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು']:ಹೆಸರು_ಕೋಷ್ಟಕ[ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು']] for ನಮೂದು_ಮೌಲ್ಯ in ದೃಢೀಕರಣ_ಕೋಷ್ಟಕ.values()
              if ನಮೂದು_ಮೌಲ್ಯ['종류']==501 and ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು'] in ಹೆಸರು_ಕೋಷ್ಟಕ and ನಮೂದು_ಮೌಲ್ಯ['ಹೆಸರು'] not in 규격}
    for ಮಾರ್ಗ in sorted({Path(ನಮೂದು_ಮೌಲ್ಯ['ಕಡತ']) for ನಮೂದು_ಮೌಲ್ಯ in ದೃಢೀಕರಣ_ಕೋಷ್ಟಕ.values()}):
        ಸಾಲು_ಪಟ್ಟಿ = ಮಾರ್ಗ.read_text().splitlines(True); 이어짐 = False
        for ಪದಸೂಚಿ,ಸಾಲು in enumerate(ಸಾಲು_ಪಟ್ಟಿ):
            전처리 = 이어짐 or bool(re.match(r'\s*#',ಸಾಲು))
            이어짐 = 전처리 and ಸಾಲು.rstrip().endswith('\\')
            if 전처리:
                ನೋಡುವ_ಕೋಷ್ಟಕ = ಹೆಸರು_ಕೋಷ್ಟಕ if re.match(r'\s*#\s*define\b',ಸಾಲು) or 이어짐 else ಮ್ಯಾಕ್ರೊ_ಮೌಲ್ಯ
                ಸಾಲು_ಪಟ್ಟಿ[ಪದಸೂಚಿ] = 낱말.sub(lambda 맞음: ನೋಡುವ_ಕೋಷ್ಟಕ.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],ಸಾಲು)
        ಮಾರ್ಗ.write_text(''.join(ಸಾಲು_ಪಟ್ಟಿ))
    # 각 자체 ಅನುವಾದಿಸು_ಮೂಲ 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ಮಾರ್ಗ in sorted({Path(ನಮೂದು_ಮೌಲ್ಯ['ಕಡತ']) for ನಮೂದು_ಮೌಲ್ಯ in ದೃಢೀಕರಣ_ಕೋಷ್ಟಕ.values()}):
        if ಮಾರ್ಗ.suffix not in ('.c','.cpp'):continue
        ಪೀರ್_ಮೌಲ್ಯ = '../' * len(ಮಾರ್ಗ.relative_to(ಬಿಂಬಿಸು_ಮೂಲ).parts[:-1]) + '명명/기계연결이름.h'
        ಮಾರ್ಗ.write_text('#include "'+ಪೀರ್_ಮೌಲ್ಯ+'"\n'+ಮಾರ್ಗ.read_text())
    (ಬಿಂಬಿಸು_ಮೂಲ/'명명/시언어이름대응.tsv').write_text('\n'.join(ಲಾಗ್_ದಾಖಲೆ)+'\n')
    (ಬಿಂಬಿಸು_ಮೂಲ/'build/한국어화/전처리참조.json').write_text(json.dumps(ನಿರ್ಲಕ್ಷಿಸು_ಮೌಲ್ಯ,ensure_ascii=False,indent=2)+'\n')
    print('ಬದಲಿಸು_ಮೌಲ್ಯ',len(ಲಾಗ್_ದಾಖಲೆ)-1,'전처리 재검토',len(ನಿರ್ಲಕ್ಷಿಸು_ಮೌಲ್ಯ),'ಯಂತ್ರ ಸಂಪರ್ಕ_ಕಲ್ಪಿಸು',len(ಸಂಪರ್ಕ_ಕೋಷ್ಟಕ))

if __name__=='__main__': ಪೂರೈಸು_ಆದೇಶ()
