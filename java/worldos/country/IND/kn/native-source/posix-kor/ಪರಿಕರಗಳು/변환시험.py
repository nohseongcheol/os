#!/usr/bin/env python3
"""ಬಿಲ್ಡ್_ಸಿಸ್ಟಂ 변환이 ಕನ್ನಡ ಸ್ಟ್ರಿಂಗ್_ಮೌಲ್ಯ, 주석, 헤더 경로를 바꾸지 않는지 검사한다."""
from ಗುರುತಿಸುವಿಕೆ_ಪರಿವರ್ತನೆ import 변환

ಮೂಲ = '''#include <파일규약.h>
#include "통신규약.h"
// ರಚಿಸು_ಫೈಲ್ 라는 주석
/* 자료이름 */
const char *ಫೈಲ್_ನಮೂದು_ಹೆಸರು = "한글 \\" ಸ್ಟ್ರಿಂಗ್_ಮೌಲ್ಯ";
char ಅಕ್ಷರ_ಮೌಲ್ಯ = '가';
int 파일열기_횟수 = 1;
'''
ಔಟ್_ಪುಟ್ = 변환(ಮೂಲ)
assert '#include <파일규약.h>' in ಔಟ್_ಪುಟ್
assert '#include "통신규약.h"' in ಔಟ್_ಪುಟ್
assert '// ರಚಿಸು_ಫೈಲ್ 라는 주석' in ಔಟ್_ಪುಟ್
assert '/* 자료이름 */' in ಔಟ್_ಪುಟ್
assert '"한글 \\" ಸ್ಟ್ರಿಂಗ್_ಮೌಲ್ಯ"' in ಔಟ್_ಪುಟ್
assert "'가'" in ಔಟ್_ಪುಟ್
assert '\\ud30c\\uc77c\\uc774\\ub984' in ಔಟ್_ಪುಟ್
assert '파일열기_횟수' not in ಔಟ್_ಪುಟ್
assert 변환(ಔಟ್_ಪುಟ್) == ಔಟ್_ಪುಟ್
print('PASS: ಕನ್ನಡ ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ 변환/ಸ್ಟ್ರಿಂಗ್_ಮೌಲ್ಯ·주석·ಮಾರ್ಗ 보존')
