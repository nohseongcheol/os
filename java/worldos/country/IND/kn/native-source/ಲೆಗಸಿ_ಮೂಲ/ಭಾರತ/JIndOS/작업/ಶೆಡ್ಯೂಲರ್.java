package ಭಾರತ.JIndOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import ಭಾರತ.JIndOS.기억공간.ಪುಟ_ವ್ಯವಸ್ಥಾಪಕ;
import ಭಾರತ.JIndOS.ಫೈಲ್_ಸಿಸ್ಟಂ.파일서술자표;

/** ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ 식별자와 라운드로빈 ಸಿದ್ಧಪಡಿಸು 대기열을 관리한다. */
public final class ಶೆಡ್ಯೂಲರ್ {
    private final ಪುಟ_ವ್ಯವಸ್ಥಾಪಕ 쪽관리;
    private final Map<Integer, ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ> ಪ್ರಕ್ರಿಯೆ_ಪಟ್ಟಿ = new HashMap<Integer, ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ>();
    private final Queue<ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ> 준비대기열 = new ArrayDeque<ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ>();
    private int ಮುಂದೆ_ಗುರುತಿಸುವಿಕೆ = 1;

    public ಶೆಡ್ಯೂಲರ್(ಪುಟ_ವ್ಯವಸ್ಥಾಪಕ 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ 첫과정(파일서술자표 파일서술자) {
        ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ 새과정 = new ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ(ವಿತರಿಸು_ಗುರುತಿಸುವಿಕೆ(), 0, 쪽관리.새주소공간(), 파일서술자);
        ಪ್ರಕ್ರಿಯೆ_ಪಟ್ಟಿ.put(Integer.valueOf(새과정.ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ 복제(ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ 부모) {
        ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ ಮಗು_ಮೌಲ್ಯ = new ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ(
                ವಿತರಿಸು_ಗುರುತಿಸುವಿಕೆ(),
                부모.ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ(),
                쪽관리.쓰기시복사복제(부모.ಇಮೇಲ್_ಸ್ಪೇಸ್()),
                부모.파일서술자().복제());
        ಮಗು_ಮೌಲ್ಯ.ಸೆಟ್_ಅಪ್ಲಿ_ವಿರಾಮ(부모.ಅಪ್ಲಿ_ವಿರಾಮ());
        ಪ್ರಕ್ರಿಯೆ_ಪಟ್ಟಿ.put(Integer.valueOf(ಮಗು_ಮೌಲ್ಯ.ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ()), ಮಗು_ಮೌಲ್ಯ);
        준비대기열.offer(ಮಗು_ಮೌಲ್ಯ);
        return ಮಗು_ಮೌಲ್ಯ;
    }

    public ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ ಮುಂದೆ_ಪ್ರಕ್ರಿಯೆ() {
        int 검사수 = 준비대기열.size();
        for (int ಪದಸೂಚಿ = 0; ಪದಸೂಚಿ < 검사수; ಪದಸೂಚಿ++) {
            ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ ಮುಂದೆ_ಅಂಶ = 준비대기열.poll();
            if (ಮುಂದೆ_ಅಂಶ != null && (ಮುಂದೆ_ಅಂಶ.ಸ್ಥಿತಿ_ಮೌಲ್ಯ() == ಪ್ರಕ್ರಿಯೆ_ಸ್ಥಿತಿ.ಸಿದ್ಧಪಡಿಸು || ಮುಂದೆ_ಅಂಶ.ಸ್ಥಿತಿ_ಮೌಲ್ಯ() == ಪ್ರಕ್ರಿಯೆ_ಸ್ಥಿತಿ.ಪೂರೈಸು_ಆದೇಶ)) {
                ಮುಂದೆ_ಅಂಶ.ಸೆಟ್_ಸ್ಥಿತಿ(ಪ್ರಕ್ರಿಯೆ_ಸ್ಥಿತಿ.ಪೂರೈಸು_ಆದೇಶ);
                준비대기열.offer(ಮುಂದೆ_ಅಂಶ);
                return ಮುಂದೆ_ಅಂಶ;
            }
        }
        return null;
    }

    public int 자식기다리기(ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ 부모, int ಮಗು_ಗುರುತಿಸುವಿಕೆ, boolean 기다리지않음) {
        for (ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ 후보 : ಪ್ರಕ್ರಿಯೆ_ಪಟ್ಟಿ.values()) {
            if (후보.부모식별자() != 부모.ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ()) {
                continue;
            }
            if (ಮಗು_ಗುರುತಿಸುವಿಕೆ > 0 && 후보.ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ() != ಮಗು_ಗುರುತಿಸುವಿಕೆ) {
                continue;
            }
            if (후보.ಸ್ಥಿತಿ_ಮೌಲ್ಯ() == ಪ್ರಕ್ರಿಯೆ_ಸ್ಥಿತಿ.ನಿರ್ಗಮನ_ಅಪ್ಲಿ) {
                int ಮಾಪನ = (후보.ನಿರ್ಗಮನ_ಕೋಡ್() & 0xff) << 8;
                ಪ್ರಕ್ರಿಯೆ_ಪಟ್ಟಿ.remove(Integer.valueOf(후보.ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ()));
                return ಮಾಪನ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public ಪ್ರಕ್ರಿಯೆ_ಮೌಲ್ಯ ಹುಡುಕಿ_ಪ್ರಕ್ರಿಯೆ(int ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ) {
        return ಪ್ರಕ್ರಿಯೆ_ಪಟ್ಟಿ.get(Integer.valueOf(ಗುರುತಿಸುವಿಕೆ_ಮೌಲ್ಯ));
    }

    private int ವಿತರಿಸು_ಗುರುತಿಸುವಿಕೆ() {
        return ಮುಂದೆ_ಗುರುತಿಸುವಿಕೆ++;
    }
}
