public class 창예제 implements 실행할일, 동작받이 {
    private विंडो 인사창;
    private लिखीत_मळ नांव_फिल्ड;
    private लेबल 인사말;
    private int 인사횟수;

    public void उगडचें_विंडो() {
        인사창 = new विंडो("kok Swing", 460, 300);
        인사창.संयोजन_करचें_मूलतत्व(new लेबल("kok", 20, 20, 420, 28));
        नांव_फिल्ड = new लिखीत_मळ("kok", 20, 64, 420, 30);
        인사말 = new लेबल("kok", 20, 152, 420, 28);
        인사창.संयोजन_करचें_मूलतत्व(नांव_फिल्ड);
        인사창.संयोजन_करचें_मूलतत्व(new बटन("인사하기", 20, 108, 180, 32, this));
        인사창.संयोजन_करचें_मूलतत्व(인사말);
        인사창.संयोजन_करचें_मूलतत्व(new लेबल("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.शो_विंडो();
        출력.बरोवचें_रेग("GUI 예제 तयार_करचें_9ce364fc: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.बरोवचें_SMS("kok, " + नांव_फिल्ड.글읽기() + "님! (" + 인사횟수 + ")");
        출력.बरोवचें_रेग("GUI 인사: " + 인사말.글읽기());
    }

    public void पाळो_दिवचो_कार्य() { उगडचें_विंडो(); }
    public void 동작받기(동작알림 알림) {
        출력.बरोवचें_रेग("कृती 알림: " + 알림.आदेश_SMS());
        인사하기();
    }
    public static void चलोवप() {
        प्रसंग_प्रतिक्षावळ.나중에실행(new 창예제());
    }
}
