/** PCI RTL8139 (10ec:8139), 단일 धाडचें_मोल 버퍼와 8KiB 수신 लूप_मोल. 인터럽트 대신 폴링한다. */
public final class नॅटवर्क_ड्रायव्हर {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] मोबायल_नामो = new int[6];
    static int 송신수 = 0, 수신수 = 0, चूक_COUNT = 0;

    static int 설정읽기(int 장치번호, int स्थिती) {
        मोबायल_मोल.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | स्थिती);
        return मोबायल_मोल.입출력정수읽기(0xcfc);
    }

    static boolean तयार_करचें_9ce364fc() {
        int 장치번호 = -1;
        for (int INDEX = 0; INDEX < 32; INDEX++) {
            if (설정읽기(INDEX, 0) == 0x813910ec) { 장치번호 = INDEX; break; }
        }
        if (장치번호 < 0) return false;
        int डिफॉल्ट_मोल = 설정읽기(장치번호, 0x10);
        if ((डिफॉल्ट_मोल & 1) == 0 || (डिफॉल्ट_मोल & 0xfffffffc) < 0x100 || (डिफॉल्ट_मोल & 0xfffffffc) > 65535) return false;
        입출력기준주소 = डिफॉल्ट_मोल & 0xfffc;
        int आदेश = 설정읽기(장치번호, 4);
        मोबायल_मोल.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        मोबायल_मोल.입출력짧은수쓰기(0xcfc, आदेश | 5); // I/O 및 bus master परवानगी_दिवची_मोल, PCI स्थिती_मोल_e10195a1 비트는 건드리지 않음
        मोबायल_मोल.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!रिसॅट_करचें_मोल()) { 입출력기준주소 = 0; return false; }
        for (int INDEX = 0; INDEX < 6; INDEX++) मोबायल_नामो[INDEX] = मोबायल_मोल.입출력바이트읽기(입출력기준주소 + INDEX);
        return true;
    }

    static boolean रिसॅट_करचें_मोल() {
        मोबायल_मोल.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int चलोवप = मोबायल_मोल.밀리초();
        while ((मोबायल_मोल.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (मोबायल_मोल.밀리초() - चलोवप > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        मोबायल_मोल.입출력정수쓰기(입출력기준주소 + 0x30, मोबायल_मोल.नॅटवर्क_मेमरी());
        for (int INDEX = 0; INDEX < 4; INDEX++) मोबायल_मोल.입출력정수쓰기(입출력기준주소 + 0x20 + INDEX * 4, मोबायल_मोल.नॅटवर्क_मेमरी() + 12288);
        मोबायल_मोल.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        मोबायल_मोल.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        मोबायल_मोल.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        मोबायल_मोल.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/प्रसारण_मोल, wrap 연속 Store_मोल, 8KiB
        मोबायल_मोल.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int धाडचें(int[] डेटा, int लांबाय_मोल) {
        if (입출력기준주소 == 0) return -19;
        if (लांबाय_मोल < 14 || लांबाय_मोल > 1514) return -90;
        int स्थिती_पोर्ट = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int चलोवप = मोबायल_मोल.밀리초();
        while ((मोबायल_मोल.입출력정수읽기(स्थिती_पोर्ट) & 0x2000) == 0)
            if (मोबायल_मोल.밀리초() - चलोवप > 100) return -110;
        int आवाठ = लांबाय_मोल < 60 ? 60 : लांबाय_मोल;
        for (int INDEX = 0; INDEX < आवाठ; INDEX++)
            मोबायल_मोल.बरोवचें_मेमरी(मोबायल_मोल.नॅटवर्क_मेमरी() + 12288 + INDEX, INDEX < लांबाय_मोल ? डेटा[INDEX] : 0);
        मोबायल_मोल.입출력정수쓰기(स्थिती_पोर्ट, आवाठ | 0x00080000);
        चलोवप = मोबायल_मोल.밀리초();
        while ((मोबायल_मोल.입출력정수읽기(स्थिती_पोर्ट) & 0xe0008000) == 0)
            if (मोबायल_मोल.밀리초() - चलोवप > 100) return -110;
        if ((मोबायल_मोल.입출력정수읽기(स्थिती_पोर्ट) & 0x8000) == 0) { चूक_COUNT++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return लांबाय_मोल;
    }

    static int 받기(int[] डेटा) {
        if (입출력기준주소 == 0) return 0;
        if ((मोबायल_मोल.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            चूक_COUNT++;
            if (!रिसॅट_करचें_मोल()) 입출력기준주소 = 0;
            return 0;
        }
        if ((मोबायल_मोल.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = मोबायल_मोल.नॅटवर्क_मेमरी() + 수신위치;
        int स्थिती_मोल_e10195a1 = 실행관리.짧은수(머리), आवाठ = 실행관리.짧은수(머리 + 2);
        if (आवाठ == 0xfff0) return 0; // DMA 진행 중
        if (आवाठ < 4 || आवाठ > 1518) {
            चूक_COUNT++;
            if (!रिसॅट_करचें_मोल()) 입출력기준주소 = 0;
            return 0;
        }
        int लांबाय_मोल = आवाठ - 4;
        if ((स्थिती_मोल_e10195a1 & 1) != 0) {
            for (int INDEX = 0; INDEX < लांबाय_मोल; INDEX++) डेटा[INDEX] = मोबायल_मोल.기억읽기(머리 + 4 + INDEX);
            수신수++;
        } else { लांबाय_मोल = 0; चूक_COUNT++; }
        수신위치 = (수신위치 + आवाठ + 4 + 3) & ~3;
        수신위치 &= 8191;
        मोबायल_मोल.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        मोबायल_मोल.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return लांबाय_मोल;
    }
}
