/** 디스크 बरोवचें 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int लांबाय_मोल = 0;
    static boolean 앞줄복귀 = false;
    static boolean रेग_ओवरफ्लो = false;

    static boolean आदेश(String नांव) {
        if (लांबाय_मोल < नांव.length()) return false;
        for (int INDEX = 0; INDEX < नांव.length(); INDEX++)
            if (입력[INDEX] != नांव.charAt(INDEX)) return false;
        return लांबाय_मोल == नांव.length() || 입력[नांव.length()] == ' ';
    }

    static void शो_आदार() {
        SMS_टर्मिनल.बरोवचें("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        SMS_टर्मिनल.बरोवचें("apps | run NAME [ARGS] | net\n");
        SMS_टर्मिनल.बरोवचें("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        SMS_टर्मिनल.बरोवचें("sync (연결된 JKSTORE1 Store_मोल 장치에 फायल 보존)\n");
    }

    static void प्रक्रिया_मोल_प्रवेश() {
        if (लांबाय_मोल == 0) return;
        if (आदेश("help")) शो_आदार();
        else if (आदेश("sync")) {
            int मेजप = 파일보존.सिंक्रोनायझ();
            SMS_टर्मिनल.बरोवचें("Sync: "); SMS_टर्मिनल.수쓰기(मेजप); SMS_टर्मिनल.문자(10);
        }
        else if (आदेश("ls")) मेमरी_फायल_प्रणाली.प्रवेश_सुची();
        else if (आदेश("edit")) मेमरी_फायल_प्रणाली.आदेश(입력, 4, लांबाय_मोल, 0);
        else if (आदेश("cat")) मेमरी_फायल_प्रणाली.आदेश(입력, 3, लांबाय_मोल, 1);
        else if (आदेश("rm")) मेमरी_फायल_प्रणाली.आदेश(입력, 2, लांबाय_मोल, 2);
        else if (आदेश("java") || आदेश("javac")) {
            int मेजप = 실행관리.पाळो_दिवचो_आदेश(입력, 0, लांबाय_मोल);
            SMS_टर्मिनल.बरोवचें("Exit: "); SMS_टर्मिनल.수쓰기(मेजप); SMS_टर्मिनल.문자(10);
        }
        else if (आदेश("apps")) 실행관리.प्रवेश_सुची();
        else if (आदेश("net")) नॅटवर्क_स्टॅक.स्थिती_मोल_e10195a1();
        else if (आदेश("run")) {
            int मेजप = 실행관리.पाळो_दिवचो_आदेश(입력, 3, लांबाय_मोल);
            SMS_टर्मिनल.बरोवचें("Exit: "); SMS_टर्मिनल.수쓰기(मेजप); SMS_टर्मिनल.बरोवचें("\n");
        } else if (आदेश("info")) {
            SMS_टर्मिनल.बरोवचें("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (आदेश("mem")) {
            SMS_टर्मिनल.बरोवचें("위쪽 मेमरी_मोल 공간(KiB): "); SMS_टर्मिनल.수쓰기(기억공간.UPPER_मेमरी_आवाठ());
            SMS_टर्मिनल.बरोवचें("\n배열 동적 मेमरी_मोल 공간(बायट_मोल): "); SMS_टर्मिनल.수쓰기(मोबायल_मोल.क्रम_पद्दत());
            SMS_टर्मिनल.बरोवचें(" / 262144\n작업 공간 विभाग_मोल: "); SMS_टर्मिनल.수쓰기(기억공간.사용개수());
            SMS_टर्मिनल.बरोवचें(" / 8 (각 4096바이트)\n");
        } else if (आदेश("alloc")) {
            int INDEX = 기억공간.नेमून_दिवचें_सांठवण();
            SMS_टर्मिनल.बरोवचें("विभाग_मोल INDEX: "); SMS_टर्मिनल.수쓰기(INDEX); SMS_टर्मिनल.बरोवचें("\n");
        } else if (आदेश("free")) {
            if (लांबाय_मोल == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                SMS_टर्मिनल.बरोवचें(기억공간.return_मेजप(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 विभाग_मोल\n");
            } else SMS_टर्मिनल.बरोवचें("사용법: free 0..7\n");
        } else if (आदेश("echo")) {
            for (int INDEX = 5; INDEX < लांबाय_मोल; INDEX++) SMS_टर्मिनल.문자(입력[INDEX]);
            SMS_टर्मिनल.문자(10);
        } else if (आदेश("clear")) SMS_टर्मिनल.지우기();
        else if (आदेश("test")) कर्नेल.시험();
        else if (आदेश("halt")) {
            SMS_टर्मिनल.बरोवचें("HALTED\n");
            मोबायल_मोल.정지();
        } else SMS_टर्मिनल.बरोवचें("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void स्विकारचें_AND_बरोवचें(int मोल) {
        if (मोल == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = मोल == 13;
        if (मोल == 10 || मोल == 13) {
            SMS_टर्मिनल.문자(10);
            if (मेमरी_फायल_प्रणाली.편집중) मेमरी_फायल_प्रणाली.편집줄(입력, लांबाय_मोल, रेग_ओवरफ्लो);
            else प्रक्रिया_मोल_प्रवेश();
            लांबाय_मोल = 0;
            रेग_ओवरफ्लो = false;
            SMS_टर्मिनल.बरोवचें(मेमरी_फायल_प्रणाली.편집중 ? "...> " : "jkoros> ");
        } else if (मोल == 8 || मोल == 127) {
            if (लांबाय_मोल > 0) {
                लांबाय_मोल--;
                SMS_टर्मिनल.직렬바이트(8); SMS_टर्मिनल.직렬바이트(32); SMS_टर्मिनल.직렬바이트(8);
                SMS_टर्मिनल.화면문자(8);
            }
        } else if (मोल >= 32 && मोल < 127 && लांबाय_मोल < 입력.length) {
            입력[लांबाय_मोल++] = मोल;
            SMS_टर्मिनल.문자(मोल);
        } else if (मोल >= 32 && मोल < 127) रेग_ओवरफ्लो = true;
    }

    static void चलोवप() {
        शो_आदार();
        SMS_टर्मिनल.बरोवचें("READY\njkoros> ");
        while (true) {
            int मोल = SMS_टर्मिनल.직렬읽기();
            if (मोल < 0) मोल = किबोर्ड.읽기();
            if (मोल >= 0) स्विकारचें_AND_बरोवचें(मोल);
            else { नॅटवर्क_स्टॅक.पुनर्तपासणी_करची(); मोबायल_मोल.잠시양보(); }
        }
    }
}
