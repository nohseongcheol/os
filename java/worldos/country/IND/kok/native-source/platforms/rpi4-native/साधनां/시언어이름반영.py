#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 बायट_मोल 위치로 자체 C 이름을 옮기는 일회성 이행 साधनां.

외부 구조체의 멤버, स्ट्रिंग_मोल, C 표준 फंक्शन_मोल, 이식 규약은 보존한다.
입력은 बदलचें_मोल 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

प्रॉजॅक्ट_रूट = Path(__file__).resolve().parents[1]

def पाळो_दिवचो_आदेश():
    분석 = json.loads((प्रॉजॅक्ट_रूट/'build/한국어화/시언어분석.json').read_text())
    if 분석['चूक']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    नांव_तकटो = json.loads((प्रॉजॅक्ट_रूट/'명명/시언어이름.json').read_text())
    SD = set(json.loads((प्रॉजॅक्ट_रूट/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {UNIQUE_मोल:नांव_तकटो[प्रवेश_मोल['नांव']] for UNIQUE_मोल,प्रवेश_मोल in 선언표.items()
                if प्रवेश_मोल['नांव'] in नांव_तकटो and प्रवेश_मोल['नांव'] not in SD}
    कनॅक्शन_तकटो = {प्रवेश_मोल['नांव']:नांव_तकटो[प्रवेश_मोल['नांव']] for प्रवेश_मोल in 선언표.values()
              if प्रवेश_मोल.get('कनॅक्ट')==4 and प्रवेश_मोल['종류'] in (8,9)
              and प्रवेश_मोल['नांव'] in नांव_तकटो and प्रवेश_मोल['नांव'] not in SD}
    # तयार_करचें AOT C·어셈블리·공개 SDK가 공유하는 바이너리 कनॅक्ट 이름만 유지한다.
    머리 = ['/* 한국어 स्त्रोत_ट्री 이름과 기존 यंत्र कनॅक्ट काम_मोल. 자동 तयार_करचें: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(कनॅक्शन_तकटो.items())]
    머리 += ['#endif','']
    (प्रॉजॅक्ट_रूट/'명명/기계연결이름.h').write_text('\n'.join(머리))
    बदल_सुची = defaultdict(dict)
    for फायल,ऑफसॅट_मोल,नांव,UNIQUE_मोल in 분석['संदर्भ']:
        if UNIQUE_मोल in 바꿀선언:
            बदल_सुची[फायल][ऑफसॅट_मोल] = (नांव,바꿀선언[UNIQUE_मोल])
    LOG_नोंद = ['फायल\t원래바이트위치\t이전이름\t한국어이름']
    दुर्लक्ष_करचें_मोल = []
    for फायल,बदलचें_मोल in बदल_सुची.items():
        पाथ = Path(फायल); 원본 = पाथ.read_bytes(); डेटा = 원본
        for ऑफसॅट_मोल,(옛이름,새이름) in sorted(बदलचें_मोल.items(),reverse=True):
            끝 = ऑफसॅट_मोल+len(옛이름.encode())
            if 원본[ऑफसॅट_मोल:끝] != 옛이름.encode():
                दुर्लक्ष_करचें_मोल.append((str(पाथ.relative_to(प्रॉजॅक्ट_रूट)),ऑफसॅट_मोल,옛이름));continue
            डेटा = डेटा[:ऑफसॅट_मोल]+새이름.encode()+डेटा[끝:]
            LOG_नोंद.append('{}\t{}\t{}\t{}'.format(पाथ.relative_to(प्रॉजॅक्ट_रूट),ऑफसॅट_मोल,옛이름,새이름))
        पाथ.write_bytes(डेटा)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    मॅक्रो_मोल = {प्रवेश_मोल['नांव']:नांव_तकटो[प्रवेश_मोल['नांव']] for प्रवेश_मोल in 선언표.values()
              if प्रवेश_मोल['종류']==501 and प्रवेश_मोल['नांव'] in नांव_तकटो and प्रवेश_मोल['नांव'] not in SD}
    for पाथ in sorted({Path(प्रवेश_मोल['फायल']) for प्रवेश_मोल in 선언표.values()}):
        रेग_सुची = पाथ.read_text().splitlines(True); 이어짐 = False
        for INDEX,रेग in enumerate(रेग_सुची):
            전처리 = 이어짐 or bool(re.match(r'\s*#',रेग))
            이어짐 = 전처리 and रेग.rstrip().endswith('\\')
            if 전처리:
                लूकअप_तकटो = नांव_तकटो if re.match(r'\s*#\s*define\b',रेग) or 이어짐 else मॅक्रो_मोल
                रेग_सुची[INDEX] = 낱말.sub(lambda 맞음: लूकअप_तकटो.get(맞음[0],맞음[0]) if 맞음[0] not in SD else 맞음[0],रेग)
        पाथ.write_text(''.join(रेग_सुची))
    # 각 자체 अणकारप_स्त्रोत 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for पाथ in sorted({Path(प्रवेश_मोल['फायल']) for प्रवेश_मोल in 선언표.values()}):
        if पाथ.suffix not in ('.c','.cpp'):continue
        पीयर_मोल = '../' * len(पाथ.relative_to(प्रॉजॅक्ट_रूट).parts[:-1]) + '명명/기계연결이름.h'
        पाथ.write_text('#include "'+पीयर_मोल+'"\n'+पाथ.read_text())
    (प्रॉजॅक्ट_रूट/'명명/시언어이름대응.tsv').write_text('\n'.join(LOG_नोंद)+'\n')
    (प्रॉजॅक्ट_रूट/'build/한국어화/전처리참조.json').write_text(json.dumps(दुर्लक्ष_करचें_मोल,ensure_ascii=False,indent=2)+'\n')
    print('बदलचें_मोल',len(LOG_नोंद)-1,'전처리 재검토',len(दुर्लक्ष_करचें_मोल),'यंत्र कनॅक्ट',len(कनॅक्शन_तकटो))

if __name__=='__main__': पाळो_दिवचो_आदेश()
