    private static void 파일과과정시험(कर्नेल कर्नेल_मोल) {
        byte[] अनुक्रमणिका_मोल = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        कर्नेल_मोल.फायल_प्रणाली().파일추가("시험", अनुक्रमणिका_मोल);
        प्रक्रिया_मोल 부모 = कर्नेल_मोल.첫과정();
        체계호출 호출 = कर्नेल_मोल.체계호출();
        int 서술자 = 호출.उगडचें(부모, "/시험", 체계호출.फकत_वाचचें_कुरवो);
        पुनर्तपासणी_करची(서술자 >= 3, "फायल उगडचें");

        byte[] 받을곳 = new byte[अनुक्रमणिका_मोल.length];
        पुनर्तपासणी_करची(호출.읽기(부모, 서술자, 받을곳, 받을곳.length) == अनुक्रमणिका_मोल.length, "फायल 읽기");
        पुनर्तपासणी_करची(Arrays.equals(अनुक्रमणिका_मोल, 받을곳), "फायल अनुक्रमणिका_मोल");
        पुनर्तपासणी_करची(호출.हालोवचें_स्थिती(부모, 서술자, 0, 체계호출.सोद_Start) == 0, "फायल स्थिती हालोवचें_मोल");

        int 복제서술자 = 호출.서술자복제(부모, 서술자);
        पुनर्तपासणी_करची(복제서술자 >= 0, "서술자 복제");
        प्रक्रिया_मोल भुरगें_मोल = 호출.과정복제(부모);
        पुनर्तपासणी_करची(भुरगें_मोल.वळखुपी_मोल() != 부모.वळखुपी_मोल(), "प्रक्रिया_मोल वळखुपी_मोल 분리");
        पुनर्तपासणी_करची(भुरगें_मोल.부모식별자() == 부모.वळखुपी_मोल(), "부모 प्रक्रिया_मोल वळखुपी_मोल");
        पुनर्तपासणी_करची(호출.शेवट(भुरगें_मोल, 서술자) == 0 && 부모.파일서술자().열려있음(서술자), "भुरगें_मोल शेवट 격리");

        int 이전끝 = 호출.프로그램끝늘리기(부모, 8192);
        पुनर्तपासणी_करची(이전끝 == 0x06000000, "एप्लिकेशन_f5044b9b 끝 늘리기");
        पुनर्तपासणी_करची(부모.프로그램끝() == 0x06002000, "एप्लिकेशन_f5044b9b 끝 반영");
        पुनर्तपासणी_करची(भुरगें_मोल.프로그램끝() == 0x06000000, "과정별 एप्लिकेशन_f5044b9b 끝 격리");

        भुरगें_मोल.प्रस्थान_करचें_एप्लिकेशन(7);
        पुनर्तपासणी_करची(호출.자식기다리기(부모, भुरगें_मोल.वळखुपी_मोल(), false) == (7 << 8), "भुरगें_मोल प्रस्थान_करचें_एप्लिकेशन 기다리기");
        पुनर्तपासणी_करची(호출.접근가능("시험", 1) == -13, "पाळो_दिवचो_आदेश अनुमती_मोल 거부");
        पुनर्तपासणी_करची(호출.उपेगकर्तो_वळखुपी() == 0 && 호출.गट_वळखुपी() == 0, "사용자와 무리 वळखुपी_मोल");
        पुनर्तपासणी_करची("/".equals(호출.현재작업목록(2)) && 호출.स्विच_कार्य_सुची("/") == 0, "현재 작업 प्रवेश_सुची");
        पुनर्तपासणी_करची(호출.단말인가(부모, 1), "표준 출력 단말");
        पुनर्तपासणी_करची("JIndOS".equals(호출.체계정보().प्रणाली_नांव()), "ऑपरेटिंग_प्रणाली_मोल msinfo32_exe");
    }

