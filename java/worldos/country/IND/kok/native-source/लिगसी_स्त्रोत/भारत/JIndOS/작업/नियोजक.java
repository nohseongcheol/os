package भारत.JIndOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import भारत.JIndOS.기억공간.पान_वेवस्थापक;
import भारत.JIndOS.फायल_प्रणाली.파일서술자표;

/** प्रक्रिया_मोल 식별자와 라운드로빈 तयार_करचें_9ce364fc 대기열을 관리한다. */
public final class नियोजक {
    private final पान_वेवस्थापक 쪽관리;
    private final Map<Integer, प्रक्रिया_मोल> प्रक्रिया_सुची = new HashMap<Integer, प्रक्रिया_मोल>();
    private final Queue<प्रक्रिया_मोल> 준비대기열 = new ArrayDeque<प्रक्रिया_मोल>();
    private int फुडलें_वळखुपी = 1;

    public नियोजक(पान_वेवस्थापक 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public प्रक्रिया_मोल 첫과정(파일서술자표 파일서술자) {
        प्रक्रिया_मोल 새과정 = new प्रक्रिया_मोल(नेमून_दिवचें_वळखुपी(), 0, 쪽관리.새주소공간(), 파일서술자);
        प्रक्रिया_सुची.put(Integer.valueOf(새과정.वळखुपी_मोल()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public प्रक्रिया_मोल 복제(प्रक्रिया_मोल 부모) {
        प्रक्रिया_मोल भुरगें_मोल = new प्रक्रिया_मोल(
                नेमून_दिवचें_वळखुपी(),
                부모.वळखुपी_मोल(),
                쪽관리.쓰기시복사복제(부모.नामो_SPACE()),
                부모.파일서술자().복제());
        भुरगें_मोल.프로그램끝설정(부모.프로그램끝());
        प्रक्रिया_सुची.put(Integer.valueOf(भुरगें_मोल.वळखुपी_मोल()), भुरगें_मोल);
        준비대기열.offer(भुरगें_मोल);
        return भुरगें_मोल;
    }

    public प्रक्रिया_मोल फुडलें_प्रक्रिया() {
        int तपासचें_COUNT = 준비대기열.size();
        for (int INDEX = 0; INDEX < तपासचें_COUNT; INDEX++) {
            प्रक्रिया_मोल फुडलें_आयटम = 준비대기열.poll();
            if (फुडलें_आयटम != null && (फुडलें_आयटम.स्थिती_मोल_e10195a1() == प्रक्रिया_स्थिती.तयार_करचें_9ce364fc || फुडलें_आयटम.स्थिती_मोल_e10195a1() == प्रक्रिया_स्थिती.पाळो_दिवचो_आदेश)) {
                फुडलें_आयटम.संच_स्थिती(प्रक्रिया_स्थिती.पाळो_दिवचो_आदेश);
                준비대기열.offer(फुडलें_आयटम);
                return फुडलें_आयटम;
            }
        }
        return null;
    }

    public int 자식기다리기(प्रक्रिया_मोल 부모, int भुरगें_वळखुपी, boolean 기다리지않음) {
        for (प्रक्रिया_मोल 후보 : प्रक्रिया_सुची.values()) {
            if (후보.부모식별자() != 부모.वळखुपी_मोल()) {
                continue;
            }
            if (भुरगें_वळखुपी > 0 && 후보.वळखुपी_मोल() != भुरगें_वळखुपी) {
                continue;
            }
            if (후보.स्थिती_मोल_e10195a1() == प्रक्रिया_स्थिती.प्रस्थान_करचें_एप्लिकेशन) {
                int मेजप = (후보.प्रस्थान_करचें_CODE() & 0xff) << 8;
                प्रक्रिया_सुची.remove(Integer.valueOf(후보.वळखुपी_मोल()));
                return मेजप;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public प्रक्रिया_मोल FIND_प्रक्रिया(int वळखुपी_मोल) {
        return प्रक्रिया_सुची.get(Integer.valueOf(वळखुपी_मोल));
    }

    private int नेमून_दिवचें_वळखुपी() {
        return फुडलें_वळखुपी++;
    }
}
