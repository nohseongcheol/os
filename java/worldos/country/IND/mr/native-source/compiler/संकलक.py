class संकलन_त्रुटी(Exception):
    pass


class डेटा_वाचा:
    def __init__(स्वतः, डेटा):
        स्वतः.डेटा = डेटा
        स्वतः.जागा = 0

    def वाचन(स्वतः, लांबी_मूल्य):
        if लांबी_मूल्य < 0 or स्वतः.जागा + लांबी_मूल्य > len(स्वतः.डेटा):
            raise संकलन_त्रुटी('कापलेले_मूल्य वर्ग_मूल्य 또는 आदेश डेटा')
        मोजमाप = स्वतः.डेटा[स्वतः.जागा:स्वतः.जागा + लांबी_मूल्य]
        स्वतः.जागा += लांबी_मूल्य
        return मोजमाप

    def संख्या(स्वतः, स्वरूप_मूल्य):
        return struct.unpack('>' + स्वरूप_मूल्य, स्वतः.वाचन(struct.calcsize('>' + स्वरूप_मूल्य)))[0]


def विसंकेतन_सुधारित_युनिकोडसंकेतन_8(डेटा):
    # CONSTANT_Utf8은 NUL 및 UTF-16 대리쌍을 사용하는 modified UTF-8이다.
    स्ट्रींग_मूल्य = डेटा.replace(b'\xc0\x80', b'\x00').decode('utf-8', 'surrogatepass')
    return स्ट्रींग_मूल्य.encode('utf-16-le', 'surrogatepass').decode('utf-16-le', 'surrogatepass')


class वर्ग_मूल्य:
    def __init__(स्वतः, मार्ग):
        स्वतः.मार्ग = मार्ग
        रीडर_मूल्य = डेटा_वाचा(मार्ग.read_bytes())
        if रीडर_मूल्य.संख्या('I') != 0xcafebabe:
            raise संकलन_त्रुटी('Java वर्ग_मूल्य 표식이 아님')
        रीडर_मूल्य.वाचन(4)
        आयटम_संख्या = रीडर_मूल्य.संख्या('H')
        स्वतः.स्थिरांक_मूल्य = [None] * आयटम_संख्या
        अनुक्रमणिका = 1
        while अनुक्रमणिका < आयटम_संख्या:
            प्रकार_मूल्य = रीडर_मूल्य.संख्या('B')
            if प्रकार_मूल्य == 1:
                मूल्य = विसंकेतन_सुधारित_युनिकोडसंकेतन_8(रीडर_मूल्य.वाचन(रीडर_मूल्य.संख्या('H')))
            elif प्रकार_मूल्य == 3:
                मूल्य = रीडर_मूल्य.संख्या('i')
            elif प्रकार_मूल्य == 4:
                मूल्य = रीडर_मूल्य.वाचन(4)
            elif प्रकार_मूल्य in (5, 6):
                मूल्य = रीडर_मूल्य.वाचन(8)
            elif प्रकार_मूल्य in (7, 8, 16):
                मूल्य = रीडर_मूल्य.संख्या('H')
            elif प्रकार_मूल्य in (9, 10, 11, 12, 18):
                मूल्य = (रीडर_मूल्य.संख्या('H'), रीडर_मूल्य.संख्या('H'))
            elif प्रकार_मूल्य == 15:
                मूल्य = (रीडर_मूल्य.संख्या('B'), रीडर_मूल्य.संख्या('H'))
            else:
                raise संकलन_त्रुटी('지원하지 않는 स्थिरांक_मूल्य प्रकार_मूल्य: {}'.format(प्रकार_मूल्य))
            स्वतः.स्थिरांक_मूल्य[अनुक्रमणिका] = (प्रकार_मूल्य, मूल्य)
            अनुक्रमणिका += 2 if प्रकार_मूल्य in (5, 6) else 1
        स्वतः.ऍक्सेस_प्रविष्टी = रीडर_मूल्य.संख्या('H')
        स्वतः.नाव = स्वतः.वर्ग_नाव(रीडर_मूल्य.संख्या('H'))
        जनक_मूल्य = रीडर_मूल्य.संख्या('H')
        if स्वतः.वर्ग_नाव(जनक_मूल्य) != 'java/lang/Object' or रीडर_मूल्य.संख्या('H') != 0:
            raise संकलन_त्रुटी(स्वतः.नाव + ': 상속 및 인터페이스는 아직 지원하지 않음')
        स्वतः.फील्ड_मूल्य = स्वतः.सदस्य_वाचा(रीडर_मूल्य)
        स्वतः.फलन_मूल्य = स्वतः.सदस्य_वाचा(रीडर_मूल्य)
        स्वतः.गुणधर्म_वाचा(रीडर_मूल्य)

    def वर्ण(स्वतः, अनुक्रमणिका):
        if स्वतः.स्थिरांक_मूल्य[अनुक्रमणिका][0] != 1:
            raise संकलन_त्रुटी('स्ट्रींग_मूल्य स्थिरांक_मूल्य स्वरूप_मूल्य त्रुटी')
        return स्वतः.स्थिरांक_मूल्य[अनुक्रमणिका][1]

    def वर्ग_नाव(स्वतः, अनुक्रमणिका):
        return स्वतः.वर्ण(स्वतः.स्थिरांक_मूल्य[अनुक्रमणिका][1])

    def संदर्भ(स्वतः, अनुक्रमणिका):
        मालक_मूल्य, नाव_स्वरूप = स्वतः.स्थिरांक_मूल्य[अनुक्रमणिका][1]
        नाव, स्वरूप_मूल्य = स्वतः.स्थिरांक_मूल्य[नाव_स्वरूप][1]
        return स्वतः.वर्ग_नाव(मालक_मूल्य), स्वतः.वर्ण(नाव), स्वतः.वर्ण(स्वरूप_मूल्य)

    def गुणधर्म_वाचा(स्वतः, रीडर_मूल्य):
        मोजमाप = {}
        for _ in range(रीडर_मूल्य.संख्या('H')):
            नाव = स्वतः.वर्ण(रीडर_मूल्य.संख्या('H'))
            मोजमाप[नाव] = रीडर_मूल्य.वाचन(रीडर_मूल्य.संख्या('I'))
        return मोजमाप

    def सदस्य_वाचा(स्वतः, रीडर_मूल्य):
        मोजमाप = []
        for _ in range(रीडर_मूल्य.संख्या('H')):
            ऍक्सेस_प्रविष्टी = रीडर_मूल्य.संख्या('H')
            नाव = स्वतः.वर्ण(रीडर_मूल्य.संख्या('H'))
            स्वरूप_मूल्य = स्वतः.वर्ण(रीडर_मूल्य.संख्या('H'))
            मोजमाप.append((ऍक्सेस_प्रविष्टी, नाव, स्वरूप_मूल्य, स्वतः.गुणधर्म_वाचा(रीडर_मूल्य)))
        return मोजमाप


def प्रकार_पार्स_करा(स्ट्रींग_मूल्य):
    मोजमाप = []
    जागा = 0
    while जागा < len(स्ट्रींग_मूल्य):
        for स्वरूप_मूल्य in ('Ljava/lang/String;', '[I', 'I', 'Z', 'B', 'C', 'S', 'V'):
            if स्ट्रींग_मूल्य.startswith(स्वरूप_मूल्य, जागा):
                मोजमाप.append(स्वरूप_मूल्य)
                जागा += len(स्वरूप_मूल्य)
                break
        else:
            raise संकलन_त्रुटी('지원하지 않는 डेटा_टाइप: ' + स्ट्रींग_मूल्य)
    return मोजमाप


def पद्धत_विवरणक(वर्णन_मूल्य):
    बाबी, परतकरा_मोजमाप = वर्णन_मूल्य[1:].split(')')
    बाबी = प्रकार_पार्स_करा(बाबी)
    परतकरा_टाइप_करा = प्रकार_पार्स_करा(परतकरा_मोजमाप)
    if 'V' in बाबी or len(परतकरा_टाइप_करा) != 1:
        raise संकलन_त्रुटी('फलन_मूल्य वर्णन_मूल्य स्वरूप_मूल्य त्रुटी: ' + वर्णन_मूल्य)
    return बाबी, परतकरा_मोजमाप


def चिन्ह(प्रकार_मूल्य, *उपभाग_मूल्य):
    स्रोत = '\x00'.join(उपभाग_मूल्य).encode('utf-8')
    return 'j_{}_{}'.format(प्रकार_मूल्य, hashlib.sha256(स्रोत).hexdigest()[:24])


# CPU 경계는 이 클래스와 정확한 फलन_मूल्य 서술에 대해서만 허용한다.
def आज्ञा_कार्यवाही_करा(बाबी=None):
    व्याकरणविश्लेषक_48ee4b1b = argparse.ArgumentParser(description='स्वकीय Java AOT, OpenJDK 앱 포장 또는 공식 OpenJDK स्रोत_ट्री सिस्टम_बांधणी')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--target', choices=['linux', 'kernel', 'user', 'openjdk', 'openjdk-build'], default='linux')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--classpath', action='append', default=[], help='openjdk 대상의 शेवटीजोडा_प्रविष्टी JAR/वर्ग_मूल्य 디렉터리')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--java-home', help='openjdk 앱의 सिस्टम_बांधणी JDK 또는 openjdk-build의 부트 JDK मार्ग')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--bundle-runtime', help='आज्ञा_कार्यवाही_करा 파일과 함께 제공할 같은 CPU/OS용 JDK/JRE 디렉터리')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--cc', default='cc', help='OpenJDK अनुप्रयोग_चालक/स्रोत_ट्री 빌드의 C संकलक')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--cxx', help='openjdk-build의 C++ संकलक')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--jobs', type=int, default=2, help='openjdk-build의 सिस्टम_बांधणी पारपाडा_कार्य संख्या')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--openjdk-target', help='공식 OpenJDK 교차 सिस्टम_बांधणी लक्ष्य (예: aarch64-linux-gnu)')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--sysroot', help='교차 सिस्टम_बांधणी 대상의 libc/헤더/लायब्ररी 루트')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--configure-arg', action='append', default=[], help='공식 configure에 전달할 옵션; --configure-arg=--옵션 स्वरूप_मूल्य')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--export', action='append', default=[], help='외부기호=वर्ग_मूल्य.फलन_मूल्य (स्वकीय संकार्य_स्टॅक ABI)')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('--entry', help='예: गणना.सुरू_करा (openjdk-build 이외 대상에서 आहे_आवश्यक)')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('-o', '--output', required=True, help='आज्ञा_कार्यवाही_करा ELF/.o आउटपुट; openjdk-build는 전용 सिस्टम_बांधणी 디렉터리')
    व्याकरणविश्लेषक_48ee4b1b.add_argument('sources', nargs='+')
    परिमापन_वितर्क = व्याकरणविश्लेषक_48ee4b1b.parse_args(बाबी)
    if परिमापन_वितर्क.target == 'openjdk-build':
        if len(परिमापन_वितर्क.sources) != 1 or not परिमापन_वितर्क.java_home or परिमापन_वितर्क.entry or परिमापन_वितर्क.export or परिमापन_वितर्क.classpath or परिमापन_वितर्क.bundle_runtime:
            raise संकलन_त्रुटी('openjdk-build: OpenJDK स्रोत_ट्री 디렉터리 하나와 --java-home 부트 JDK, -o सिस्टम_बांधणी 디렉터리를 지정하세요')
        from openjdk_build import build, BuildError
        try:
            build(परिमापन_वितर्क.sources[0], परिमापन_वितर्क.output, परिमापन_वितर्क.java_home, परिमापन_वितर्क.jobs, परिमापन_वितर्क.openjdk_target,
                  परिमापन_वितर्क.sysroot, None if परिमापन_वितर्क.cc == 'cc' else परिमापन_वितर्क.cc, परिमापन_वितर्क.cxx, परिमापन_वितर्क.configure_arg)
        except BuildError as त्रुटी:
            raise संकलन_त्रुटी(str(त्रुटी))
        return
    if not परिमापन_वितर्क.entry:
        व्याकरणविश्लेषक_48ee4b1b.error('--entry is required for this target')
    if परिमापन_वितर्क.cxx or परिमापन_वितर्क.openjdk_target or परिमापन_वितर्क.sysroot or परिमापन_वितर्क.configure_arg or परिमापन_वितर्क.jobs != 2:
        raise संकलन_त्रुटी('cxx/jobs/openjdk-target/sysroot/configure-arg 옵션은 openjdk-build लक्ष्य 전용')
    if परिमापन_वितर्क.target == 'openjdk':
        sys.modules.setdefault('संकलक', sys.modules[__name__])
        from निष्पादनीय_संचिका import प्रविष्टी_तयार_करा
        प्रविष्टी_तयार_करा(परिमापन_वितर्क)
        return
    if परिमापन_वितर्क.classpath or परिमापन_वितर्क.java_home or परिमापन_वितर्क.bundle_runtime or परिमापन_वितर्क.cc != 'cc':
        raise संकलन_त्रुटी('classpath/java-home/bundle-runtime/cc 옵션은 openjdk लक्ष्य 전용')
    जावा_आज्ञा = ['sh', str(Path(__file__).resolve().parent/'आगाऊ_संबंधित_वेळ.sh'),
                '--target', परिमापन_वितर्क.target, '--entry', परिमापन_वितर्क.entry, '-o', परिमापन_वितर्क.output]
    for नेमा_मूल्य in परिमापन_वितर्क.export: जावा_आज्ञा.extend(['--export', नेमा_मूल्य])
    subprocess.run(जावा_आज्ञा+परिमापन_वितर्क.sources, check=True)
    return


if __name__ == '__main__':
    try:
        आज्ञा_कार्यवाही_करा()
    except (संकलन_त्रुटी, OSError, ValueError, subprocess.CalledProcessError) as त्रुटी:
        print('स्रोत_बांधणी त्रुटी: ' + str(त्रुटी), file=sys.stderr)
        sys.exit(1)
