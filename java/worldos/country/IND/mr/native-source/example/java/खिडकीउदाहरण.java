import मराठी.स्वकीय.विंडो;
import मराठी.स्वकीय.लेबल;
import मराठी.स्वकीय.मजकूर_फील्_ड;
import मराठी.स्वकीय.बटण;
import मराठी.स्वकीय.इव्हेंट_रांग;
import मराठी.स्वकीय.आउटपुट;
import मराठी.स्वकीय.चालवण्यायोग्य_कार्य;
import मराठी.स्वकीय.क्रिया_ग्राहक;
import मराठी.स्वकीय.क्रिया_सूचना;

/** स्वतंत्र केंद्रकावरील Swing खिडकी: मराठी मजकूर लिहिणे, बटण दाबणे आणि सूचनामजकूर बदलणे. */
public class खिडकीउदाहरण implements चालवण्यायोग्य_कार्य, क्रिया_ग्राहक {
    private विंडो अभिवादन_विंडो;
    private मजकूर_फील्_ड नाव_फील्ड;
    private लेबल अभिवादन;
    private int अभिवादन_संख्या;

    public void विंडो_उघडा() {
        अभिवादन_विंडो = new विंडो("mr Swing", 460, 300);
        अभिवादन_विंडो.जोडा_घटक(new लेबल("mr", 20, 20, 420, 28));
        नाव_फील्ड = new मजकूर_फील्_ड("mr", 20, 64, 420, 30);
        अभिवादन = new लेबल("mr", 20, 152, 420, 28);
        अभिवादन_विंडो.जोडा_घटक(नाव_फील्ड);
        अभिवादन_विंडो.जोडा_घटक(new बटण("अभिवादनकरा", 20, 108, 180, 32, this));
        अभिवादन_विंडो.जोडा_घटक(अभिवादन);
        अभिवादन_विंडो.जोडा_घटक(new लेबल("F9 / Shift+Space | X", 20, 204, 420, 28));
        अभिवादन_विंडो.विंडो_शो();
        आउटपुट.ओळ_लिहा("GUI उदाहरणे तयार_करणे: खिडकीउदाहरण");
    }

    public void अभिवादनकरा() {
        अभिवादन_संख्या++;
        अभिवादन.मजकूर_लिहा("mr, " + नाव_फील्ड.मजकूर_वाचा() + "님! (" + अभिवादन_संख्या + ")");
        आउटपुट.ओळ_लिहा("GUI अभिवादन_ae353e94: " + अभिवादन.मजकूर_वाचा());
    }

    public void कार्यान्वित_करा() { विंडो_उघडा(); }
    public void क्रिया_स्वीकारा(क्रिया_सूचना सूचना) {
        आउटपुट.ओळ_लिहा("कृती सूचना: " + सूचना.आज्ञा_मजकूर());
        अभिवादनकरा();
    }
    public static void सुरू_करा() {
        इव्हेंट_रांग.नंतर_आवाहन(new खिडकीउदाहरण());
    }
}
