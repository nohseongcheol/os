import मराठी.स्वकीय.कनेक्शन;
import मराठी.स्वकीय.वितर्क;
import मराठी.स्वकीय.स्वतंत्रसंदेश_चॅनल;
import मराठी.स्वकीय.वर्ण;
import मराठी.स्वकीय.आउटपुट;
import मराठी.स्वकीय.पडताळण्या;
import मराठी.स्वकीय.आदान_प्रवाह;
import मराठी.स्वकीय.इनपुट_आउटपुट_अपवाद;

public class जाळेउदाहरण {
    public static void सुरू_करा() throws इनपुट_आउटपुट_अपवाद {
        // यजमान: python3 साधने/उदाहरण_प्रतिध्वनी_8ea2a692.py --tcp-port 9000 --udp-port 9001
        कनेक्शन जोडा = कनेक्शन.उघडा("10.0.2.2", वर्ण.पूर्णांक_पार्स_करा(वितर्क.पाठ्य(0)));
        try {
            जोडा.प्रतीक्षामर्यादा(700);
            byte[] संदेश = वर्ण.संकेतन("JAVA TCP mr\n");
            जोडा.आउटपुट().लेखन(संदेश);
            आदान_प्रवाह आदान_मूल्य = जोडा.आदान_मूल्य();
            for (int संख्या = 0; संख्या < वर्ण.बाइट_संख्या(संदेश); संख्या++) {
                पडताळण्या.आवश्यकतापडताळा(आदान_मूल्य.वाचन() == (संदेश[संख्या] & 255), "TCP प्रत्युत्तर_द्या 불일치");
            }
        } finally { जोडा.बंद_करा(); }
        स्वतंत्रसंदेश_चॅनल संचारटोक = स्वतंत्रसंदेश_चॅनल.उघडा(0);
        try {
            संचारटोक.प्रतीक्षामर्यादा(700);
            संचारटोक.पाठवा("10.0.2.2", वर्ण.पूर्णांक_पार्स_करा(वितर्क.पाठ्य(1)), "JAVA UDP mr");
            पडताळण्या.आवश्यकतापडताळा(वर्ण.समान_मजकूर(संचारटोक.स्वीकारा(), "JAVA UDP mr"), "UDP प्रत्युत्तर_द्या 불일치");
        } finally { संचारटोक.बंद_करा(); }
        आउटपुट.ओळ_लिहा("JAVA 네트워크 पडताळा: TCP UDP mr");
    }
}
