from मराठी import आउटपुट, स्वतंत्रसंदेश_उघडा, बाह्य_स्वतंत्रसंदेश_पाठवा, स्वतंत्रसंदेश_स्वीकारा, संचारजाळे_मिटवा, मिलिसेकंद
from मराठी import सिस्टम_त्रुटी, प्रयत्नकरा_पुन्हा_त्रुटी, संकेतन_मजकूर, आज्ञा_वितर्क, पूर्णांक
संचारटोक = स्वतंत्रसंदेश_उघडा(0)
try:
    स्वतंत्रसंदेश = संकेतन_मजकूर("PYTHON UDP mr")
    बाह्य_स्वतंत्रसंदेश_पाठवा(संचारटोक, "10.0.2.2", पूर्णांक(आज्ञा_वितर्क[1]), स्वतंत्रसंदेश)
    सुरू_करा = मिलिसेकंद()
    while True:
        try:
            प्रत्युत्तर_द्या, पॉर्ट_मूल्य = स्वतंत्रसंदेश_स्वीकारा(संचारटोक)
            break
        except सिस्टम_त्रुटी as त्रुटी:
            if त्रुटी.अनुक्रमणिका != प्रयत्नकरा_पुन्हा_त्रुटी or मिलिसेकंद() - सुरू_करा >= 700:
                raise
    assert प्रत्युत्तर_द्या == स्वतंत्रसंदेश
    आउटपुट("PYTHON 네트워크 पडताळा: UDP mr")
finally:
    संचारजाळे_मिटवा(संचारटोक)
