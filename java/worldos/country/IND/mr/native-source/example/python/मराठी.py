import jkoros as संचालनप्रणाली
import sys as सामान्य_भाषा_रनटाइम

def आउटपुट(*मूल्य, विभाजक=" ", शेवट="\n", **लेगसी_वितर्क):
    # 기존 print의 sep/end 인수도 연결부에서 호환한다.
    if "sep" not in लेगसी_वितर्क: लेगसी_वितर्क["sep"] = विभाजक
    if "end" not in लेगसी_वितर्क: लेगसी_वितर्क["end"] = शेवट
    print(*मूल्य, **लेगसी_वितर्क)

पूर्णांक = int
आज्ञा_वितर्क = सामान्य_भाषा_रनटाइम.argv
प्रयत्नकरा_पुन्हा_त्रुटी = 11

class सिस्टम_त्रुटी(OSError):
    def __init__(स्वतः, अनुक्रमणिका, वर्णन="संचालनप्रणाली 작업에 실패했습니다."):
        super().__init__(अनुक्रमणिका, वर्णन)
        स्वतः.अनुक्रमणिका = अनुक्रमणिका
        स्वतः.वर्णन = वर्णन

def सिस्टम_आवाहन(फलन_मूल्य, *बाबी):
    try:
        return फलन_मूल्य(*बाबी)
    except OSError as त्रुटी:
        अनुक्रमणिका = त्रुटी.args[0] if त्रुटी.args else 0
        raise सिस्टम_त्रुटी(अनुक्रमणिका)

def संकेतन_मजकूर(पाठ्य):
    return पाठ्य.encode("utf-8")

def विसंकेतन_मजकूर(डेटा):
    return डेटा.decode("utf-8")

def संचिका_वाचा(नाव):
    return सिस्टम_आवाहन(संचालनप्रणाली.read, नाव)

def संचिका_लिहा(नाव, डेटा):
    return सिस्टम_आवाहन(संचालनप्रणाली.write, नाव, डेटा)

def संचिका_काढणे(नाव):
    return सिस्टम_आवाहन(संचालनप्रणाली.remove, नाव)

def स्वतंत्रसंदेश_उघडा(पोर्ट_नंबर):
    return सिस्टम_आवाहन(संचालनप्रणाली.udp_open, पोर्ट_नंबर)

def स्वतंत्रसंदेश_पाठवा(संचारटोक, पोर्ट_नंबर, डेटा):
    return सिस्टम_आवाहन(संचालनप्रणाली.udp_send, संचारटोक, पोर्ट_नंबर, डेटा)

def बाह्य_स्वतंत्रसंदेश_पाठवा(संचारटोक, पत्ता, पोर्ट_नंबर, डेटा):
    return सिस्टम_आवाहन(संचालनप्रणाली.udp_sendto, संचारटोक, पत्ता, पोर्ट_नंबर, डेटा)

def स्वतंत्रसंदेश_स्वीकारा(संचारटोक):
    return सिस्टम_आवाहन(संचालनप्रणाली.udp_recv, संचारटोक)

def संचारजाळे_मिटवा(संचारटोक):
    return सिस्टम_आवाहन(संचालनप्रणाली.udp_close, संचारटोक)

def आयत_आरेखित_करा(*बाबी):
    return सिस्टम_आवाहन(संचालनप्रणाली.rect, *बाबी)

def पडदा_आकारा():
    return सिस्टम_आवाहन(संचालनप्रणाली.screen_size)

def प्रतीक्षा_करा_साठी_रेखांकन():
    return सिस्टम_आवाहन(संचालनप्रणाली.wait_key)

