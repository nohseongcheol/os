    static int अंक_मूल्य(String पाठ्य) {
        if (पाठ्य == null || पाठ्य.length() == 0) return -1;
        int मोजमाप = 0;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < पाठ्य.length(); अनुक्रमणिका++) {
            int मूल्य = पाठ्य.charAt(अनुक्रमणिका) - '0';
            if (मूल्य < 0 || मूल्य > 9 || मोजमाप > 6553) return -1;
            मोजमाप = मोजमाप * 10 + मूल्य;
            if (मोजमाप > 65535) return -1;
        }
        return मोजमाप;
    }
    static int पत्ता(String पाठ्य) {
        if (पाठ्य == null) return 0;
        int मूल्य = 0, मोजमाप = 0, उपभाग_मूल्य = 0, अंक_90a88624 = 0;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका <= पाठ्य.length(); अनुक्रमणिका++) {
            int वर्ण = अनुक्रमणिका == पाठ्य.length() ? '.' : पाठ्य.charAt(अनुक्रमणिका);
            if (वर्ण == '.') {
                if (अंक_90a88624 == 0 || उपभाग_मूल्य == 4) return 0;
                मोजमाप = (मोजमाप << 8) | मूल्य; उपभाग_मूल्य++; मूल्य = 0; अंक_90a88624 = 0;
            } else {
                if (वर्ण < '0' || वर्ण > '9') return 0;
                मूल्य = मूल्य * 10 + वर्ण - '0';
                if (++अंक_90a88624 > 3 || मूल्य > 255) return 0;
            }
        }
        return उपभाग_मूल्य == 4 ? मोजमाप : 0;
    }
