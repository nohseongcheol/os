/** कमाल आणि विषम लांबीच्या संदेशांनी प्रत्यक्ष RTL8139 स्वीकारवलयाचे चक्रीय वर्तन तपासते. */
public final class संचारजाळे_लूप {
    public static int सुरू_करा() {
        if (प्रयोक्ता.वितर्क_संख्या_e5e1cf1c() != 1) { प्रयोक्ता.लेखन("Usage: run stress PORT\n"); return 2; }
        String पाठ्य = प्रयोक्ता.बाबी(0);
        int पॉर्ट_मूल्य = 0;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < पाठ्य.length(); अनुक्रमणिका++) {
            if (पाठ्य.charAt(अनुक्रमणिका) < '0' || पाठ्य.charAt(अनुक्रमणिका) > '9' || पॉर्ट_मूल्य > 6553) return 2;
            पॉर्ट_मूल्य = पॉर्ट_मूल्य * 10 + पाठ्य.charAt(अनुक्रमणिका) - '0';
        }
        if (पॉर्ट_मूल्य < 1 || पॉर्ट_मूल्य > 65535) return 2;
        int हाताळा_मूल्य = प्रयोक्ता.संचारजाळे_उघडा(0);
        if (हाताळा_मूल्य < 0) return 3;
        int[] डेटा = new int[1024];
        for (int पुनरावृत्ती_क्रमांक = 0; पुनरावृत्ती_क्रमांक < 24; पुनरावृत्ती_क्रमांक++) {
            int लांबी_मूल्य = 1024 - (पुनरावृत्ती_क्रमांक & 1);
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < लांबी_मूल्य; अनुक्रमणिका++) डेटा[अनुक्रमणिका] = (अनुक्रमणिका + पुनरावृत्ती_क्रमांक) & 255;
            if (प्रयोक्ता.डेटा_पाठवा(हाताळा_मूल्य, 0x0a000202, पॉर्ट_मूल्य, डेटा, लांबी_मूल्य) != लांबी_मूल्य) return 4;
            if (प्रयोक्ता.डेटा_स्वीकारा(हाताळा_मूल्य, डेटा, 300) != लांबी_मूल्य) return 5;
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < लांबी_मूल्य; अनुक्रमणिका++) if (डेटा[अनुक्रमणिका] != ((अनुक्रमणिका + पुनरावृत्ती_क्रमांक) & 255)) return 6;
        }
        प्रयोक्ता.संचारजाळे_मिटवा(हाताळा_मूल्य);
        प्रयोक्ता.लेखन("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
