/** अतिथी साधनांचे समान निर्गत आणि ASCII संचिकानावांची हाताळणी. */
public final class जावा_साधने {
    /** UTF-8 बाइटमालिकेचे त्याच मालिकेत UTF-16 एककांत रूपांतर करते. चुकीचे आदान नाकारते. */
    static int विसंकेतन_स्रोत(int[] डेटा, int लांबी_मूल्य) {
        int वाचन = 0, लेखन = 0;
        if (लांबी_मूल्य >= 3 && डेटा[0] == 239 && डेटा[1] == 187 && डेटा[2] == 191) वाचन = 3;
        while (वाचन < लांबी_मूल्य) {
            int मूल्य = डेटा[वाचन++], संख्या = 0, किमान_मूल्य = 0;
            if (मूल्य >= 194 && मूल्य <= 223) { संख्या = 1; किमान_मूल्य = 128; मूल्य &= 31; }
            else if (मूल्य >= 224 && मूल्य <= 239) { संख्या = 2; किमान_मूल्य = 2048; मूल्य &= 15; }
            else if (मूल्य >= 240 && मूल्य <= 244) { संख्या = 3; किमान_मूल्य = 65536; मूल्य &= 7; }
            else if (मूल्य >= 128 || मूल्य < 0) return -1;
            if (संख्या > लांबी_मूल्य - वाचन) return -1;
            for (int i = 0; i < संख्या; i++) {
                int पुढील_आयटम = डेटा[वाचन++]; if ((पुढील_आयटम & 192) != 128) return -1;
                मूल्य = (मूल्य << 6) | (पुढील_आयटम & 63);
            }
            if (मूल्य < किमान_मूल्य || मूल्य > 0x10ffff || (मूल्य >= 0xd800 && मूल्य <= 0xdfff)) return -1;
            if (मूल्य >= 65536) { मूल्य -= 65536; डेटा[लेखन++] = 0xd800 | (मूल्य >> 10); डेटा[लेखन++] = 0xdc00 | (मूल्य & 1023); }
            else डेटा[लेखन++] = मूल्य;
        }
        return लेखन;
    }
    static void संख्या_लिहा(int मूल्य) {
        if (मूल्य < 0) प्रयोक्ता.वर्ण_मूल्य_लिहा('-'); else मूल्य = -मूल्य;
        int स्थान_अनुक्रमणिका = 1000000000;
        boolean सुरू_करा = false;
        while (स्थान_अनुक्रमणिका != 0) {
            int संख्या = -(मूल्य / स्थान_अनुक्रमणिका);
            if (संख्या != 0 || सुरू_करा || स्थान_अनुक्रमणिका == 1) { प्रयोक्ता.वर्ण_मूल्य_लिहा('0' + संख्या); सुरू_करा = true; }
            मूल्य %= स्थान_अनुक्रमणिका; स्थान_अनुक्रमणिका /= 10;
        }
    }
    static int नाव(int[] गंतव्यस्थान_मूल्य, String मूळ) {
        if (मूळ.length() >= गंतव्यस्थान_मूल्य.length) return -1;
        for (int संख्या = 0; संख्या < गंतव्यस्थान_मूल्य.length; संख्या++) गंतव्यस्थान_मूल्य[संख्या] = संख्या < मूळ.length() ? मूळ.charAt(संख्या) : 0;
        return मूळ.length();
    }
    static boolean समान_मजकूर(String पहिले_संकार्य, String दुसरे_संकार्य) {
        if (पहिले_संकार्य.length() != दुसरे_संकार्य.length()) return false;
        for (int संख्या = 0; संख्या < पहिले_संकार्य.length(); संख्या++) if (पहिले_संकार्य.charAt(संख्या) != दुसरे_संकार्य.charAt(संख्या)) return false;
        return true;
    }
}
