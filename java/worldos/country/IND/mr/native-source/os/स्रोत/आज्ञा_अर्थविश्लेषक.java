/** चकतीवर न लिहिणारा लहान अनुक्रमिक/PS2 आज्ञादुभाषक. */
public final class आज्ञा_अर्थविश्लेषक {
    static int[] आदान_मूल्य = new int[128];
    static int लांबी_मूल्य = 0;
    static boolean परतकरा_कडे_मागील_ओळ = false;
    static boolean ओळ_ओवरफ्लो = false;

    static boolean आदेश(String नाव) {
        if (लांबी_मूल्य < नाव.length()) return false;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < नाव.length(); अनुक्रमणिका++)
            if (आदान_मूल्य[अनुक्रमणिका] != नाव.charAt(अनुक्रमणिका)) return false;
        return लांबी_मूल्य == नाव.length() || आदान_मूल्य[नाव.length()] == ' ';
    }

    static void मदत_शो() {
        मजकूर_टर्मिनल.लेखन("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        मजकूर_टर्मिनल.लेखन("apps | run NAME [ARGS] | net\n");
        मजकूर_टर्मिनल.लेखन("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        मजकूर_टर्मिनल.लेखन("sync (연결된 JKSTORE1 साठवणे_मूल्य 장치에 फाइल 보존)\n");
    }

    static void प्रक्रिया_मूल्य_प्रविष्टी() {
        if (लांबी_मूल्य == 0) return;
        if (आदेश("help")) मदत_शो();
        else if (आदेश("sync")) {
            int मोजमाप = जतनकरा_संचिका.समन्वय_साधा();
            मजकूर_टर्मिनल.लेखन("Sync: "); मजकूर_टर्मिनल.संख्या_लिहा(मोजमाप); मजकूर_टर्मिनल.वर्ण(10);
        }
        else if (आदेश("ls")) स्मृती_फाइल_सिस्टम.प्रविष्टी_यादी();
        else if (आदेश("edit")) स्मृती_फाइल_सिस्टम.आदेश(आदान_मूल्य, 4, लांबी_मूल्य, 0);
        else if (आदेश("cat")) स्मृती_फाइल_सिस्टम.आदेश(आदान_मूल्य, 3, लांबी_मूल्य, 1);
        else if (आदेश("rm")) स्मृती_फाइल_सिस्टम.आदेश(आदान_मूल्य, 2, लांबी_मूल्य, 2);
        else if (आदेश("java") || आदेश("javac")) {
            int मोजमाप = निष्पादन_व्यवस्थापक.आज्ञा_कार्यवाही_करा(आदान_मूल्य, 0, लांबी_मूल्य);
            मजकूर_टर्मिनल.लेखन("Exit: "); मजकूर_टर्मिनल.संख्या_लिहा(मोजमाप); मजकूर_टर्मिनल.वर्ण(10);
        }
        else if (आदेश("apps")) निष्पादन_व्यवस्थापक.प्रविष्टी_यादी();
        else if (आदेश("net")) संचारजाळे_स्टॅक.राज्य_मूल्य();
        else if (आदेश("run")) {
            int मोजमाप = निष्पादन_व्यवस्थापक.आज्ञा_कार्यवाही_करा(आदान_मूल्य, 3, लांबी_मूल्य);
            मजकूर_टर्मिनल.लेखन("Exit: "); मजकूर_टर्मिनल.संख्या_लिहा(मोजमाप); मजकूर_टर्मिनल.लेखन("\n");
        } else if (आदेश("info")) {
            मजकूर_टर्मिनल.लेखन("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (आदेश("mem")) {
            मजकूर_टर्मिनल.लेखन("वरचे_बाजू स्मृती_मूल्य पत्ता_प्रदेश(KiB): "); मजकूर_टर्मिनल.संख्या_लिहा(स्मृती_प्रदेश.वरचे_स्मृती_आकारा());
            मजकूर_टर्मिनल.लेखन("\n배열 동적 स्मृती_मूल्य पत्ता_प्रदेश(बाइट_मूल्य): "); मजकूर_टर्मिनल.संख्या_लिहा(मोबाइल_मूल्य.ऍरे_वापर());
            मजकूर_टर्मिनल.लेखन(" / 262144\n작업 पत्ता_प्रदेश विभाग_मूल्य: "); मजकूर_टर्मिनल.संख्या_लिहा(स्मृती_प्रदेश.वापरलेले_प्रविष्टी_संख्या());
            मजकूर_टर्मिनल.लेखन(" / 8 (각 4096바이트)\n");
        } else if (आदेश("alloc")) {
            int अनुक्रमणिका = स्मृती_प्रदेश.संग्रह_वाटप_करा();
            मजकूर_टर्मिनल.लेखन("विभाग_मूल्य अनुक्रमणिका: "); मजकूर_टर्मिनल.संख्या_लिहा(अनुक्रमणिका); मजकूर_टर्मिनल.लेखन("\n");
        } else if (आदेश("free")) {
            if (लांबी_मूल्य == 6 && आदान_मूल्य[4] == ' ' && आदान_मूल्य[5] >= '0' && आदान_मूल्य[5] <= '7') {
                मजकूर_टर्मिनल.लेखन(स्मृती_प्रदेश.परतकरा_मोजमाप(आदान_मूल्य[5] - '0') ? "반환됨\n" : "할당되지 않은 विभाग_मूल्य\n");
            } else मजकूर_टर्मिनल.लेखन("사용법: free 0..7\n");
        } else if (आदेश("echo")) {
            for (int अनुक्रमणिका = 5; अनुक्रमणिका < लांबी_मूल्य; अनुक्रमणिका++) मजकूर_टर्मिनल.वर्ण(आदान_मूल्य[अनुक्रमणिका]);
            मजकूर_टर्मिनल.वर्ण(10);
        } else if (आदेश("clear")) मजकूर_टर्मिनल.पुसा_प्रविष्टी();
        else if (आदेश("test")) गाभा.चाचण्या();
        else if (आदेश("halt")) {
            मजकूर_टर्मिनल.लेखन("HALTED\n");
            मोबाइल_मूल्य.थांबवा_निष्पादन();
        } else मजकूर_टर्मिनल.लेखन("알 संख्या 없는 명령입니다. help를 입력하세요.\n");
    }

    static void स्वीकारा_आणि_लिहा(int मूल्य) {
        if (मूल्य == 10 && परतकरा_कडे_मागील_ओळ) { परतकरा_कडे_मागील_ओळ = false; return; }
        परतकरा_कडे_मागील_ओळ = मूल्य == 13;
        if (मूल्य == 10 || मूल्य == 13) {
            मजकूर_टर्मिनल.वर्ण(10);
            if (स्मृती_फाइल_सिस्टम.आहे_संपादन) स्मृती_फाइल_सिस्टम.संपादित_ओळ(आदान_मूल्य, लांबी_मूल्य, ओळ_ओवरफ्लो);
            else प्रक्रिया_मूल्य_प्रविष्टी();
            लांबी_मूल्य = 0;
            ओळ_ओवरफ्लो = false;
            मजकूर_टर्मिनल.लेखन(स्मृती_फाइल_सिस्टम.आहे_संपादन ? "...> " : "jkoros> ");
        } else if (मूल्य == 8 || मूल्य == 127) {
            if (लांबी_मूल्य > 0) {
                लांबी_मूल्य--;
                मजकूर_टर्मिनल.अनुक्रमिक_बाइट(8); मजकूर_टर्मिनल.अनुक्रमिक_बाइट(32); मजकूर_टर्मिनल.अनुक्रमिक_बाइट(8);
                मजकूर_टर्मिनल.पडदा_वर्ण(8);
            }
        } else if (मूल्य >= 32 && मूल्य < 127 && लांबी_मूल्य < आदान_मूल्य.length) {
            आदान_मूल्य[लांबी_मूल्य++] = मूल्य;
            मजकूर_टर्मिनल.वर्ण(मूल्य);
        } else if (मूल्य >= 32 && मूल्य < 127) ओळ_ओवरफ्लो = true;
    }

    static void सुरू_करा() {
        मदत_शो();
        मजकूर_टर्मिनल.लेखन("READY\njkoros> ");
        while (true) {
            int मूल्य = मजकूर_टर्मिनल.अनुक्रमिक_वाचा();
            if (मूल्य < 0) मूल्य = कीबोर्ड.वाचन();
            if (मूल्य >= 0) स्वीकारा_आणि_लिहा(मूल्य);
            else { संचारजाळे_स्टॅक.पडताळा(); मोबाइल_मूल्य.निलंबित_करा_क्षणभर(); }
        }
    }
}
