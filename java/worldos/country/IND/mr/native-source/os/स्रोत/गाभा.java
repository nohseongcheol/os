/** प्रत्यक्ष प्रारंभानंतर बोलावला जाणारा Java प्रवेशबिंदू; JVM किंवा यजमान कार्यप्रणालीवर अवलंबून नाही. */
public final class गाभा {
    static int एकूण_मूल्य(int शेवट) {
        int बेरीज_मूल्य = 0;
        for (int अनुक्रमणिका = 1; अनुक्रमणिका <= शेवट; अनुक्रमणिका++) बेरीज_मूल्य += अनुक्रमणिका;
        return बेरीज_मूल्य;
    }

    static boolean चाचण्या() {
        int[] मूल्ये = new int[4];
        मूल्ये[2] = एकूण_मूल्य(10);
        int ऋण_मूल्य = -7;
        int किमान_मूल्य = 0x80000000;
        int भागाकार_मोजमाप = -1;
        int अनुक्रमणिका = स्मृती_प्रदेश.संग्रह_वाटप_करा();
        boolean उत्तीर्ण_मूल्य = मूल्ये[0] == 0 && मूल्ये[2] == 55 && मूल्ये.length == 4
            && ऋण_मूल्य / 3 == -2 && ऋण_मूल्य % 3 == -1 && किमान_मूल्य / भागाकार_मोजमाप == किमान_मूल्य
            && किमान_मूल्य % भागाकार_मोजमाप == 0 && "한글".length() == 2 && "한글".charAt(1) == '글'
            && अनुक्रमणिका >= 0 && स्मृती_प्रदेश.परतकरा_मोजमाप(अनुक्रमणिका) && !स्मृती_प्रदेश.परतकरा_मोजमाप(अनुक्रमणिका);
        मजकूर_टर्मिनल.लेखन(उत्तीर्ण_मूल्य ? "JAVA SELFTEST PASS\n" : "JAVA SELFTEST FAIL\n");
        return उत्तीर्ण_मूल्य;
    }

    public static void सुरू_करा() {
        मजकूर_टर्मिनल.तयार_करणे();
        मजकूर_टर्मिनल.लेखन("JKOROS NATIVE JAVA\n");
        मजकूर_टर्मिनल.लेखन("जावा 기계어 गाभा_मूल्य सुरू_करा\n");
        if (मोबाइल_मूल्य.प्रणालीप्रारंभ_खूण() != 0x2badb002) {
            मजकूर_टर्मिनल.लेखन("BAD MULTIBOOT MAGIC\n");
            मोबाइल_मूल्य.थांबवा_निष्पादन();
        }
        if (!चाचण्या()) मोबाइल_मूल्य.थांबवा_निष्पादन();
        if (स्मृती_प्रदेश.वरचे_स्मृती_आकारा() < 15360) {
            मजकूर_टर्मिनल.लेखन("At least 16 MiB RAM required\n");
            मोबाइल_मूल्य.थांबवा_निष्पादन();
        }
        मोबाइल_मूल्य.तयार_करणे_प्रयोक्ता_अनुप्रयोग();
        मजकूर_टर्मिनल.लेखन("USER ELF: ring 3 / paging / int 0x80\n");
        संचारजाळे_ड्रायव्हर.तयार_करणे();
        संचारजाळे_स्टॅक.सुबक_प्रक्रिया();
        स्मृती_फाइल_सिस्टम.तयार_करणे();
        जतनकरा_संचिका.तयार_करणे();
        आज्ञा_अर्थविश्लेषक.सुरू_करा();
    }
}
