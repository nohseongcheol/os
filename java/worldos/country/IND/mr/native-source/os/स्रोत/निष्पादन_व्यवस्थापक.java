/** केवळ-वाचन कार्यसंचातील ELF32 तपासते, प्रचल देते आणि एका वेळी एक वापरकर्ता प्रक्रिया चालवते. */
public final class निष्पादन_व्यवस्थापक {
    static final int प्रारंभ_प्रयोक्ता_अनुप्रयोग = 0x04000000;
    static final int प्रयोक्ता_शेवट_करा = 0x04400000;
    static final int चित्र_शेवट_करा_पत्ता = 0x04200000;
    static final int वितर्क_प्रारंभ = 0x04300000;
    static int वितर्क_संख्या = 0;
    static int[] वितर्क_पत्ता = new int[16];

    static boolean क्लिप(int पत्ता, int लांबी_मूल्य) {
        return पत्ता >= प्रारंभ_प्रयोक्ता_अनुप्रयोग && पत्ता < प्रयोक्ता_शेवट_करा && लांबी_मूल्य >= 0 && लांबी_मूल्य <= प्रयोक्ता_शेवट_करा - पत्ता;
    }

    static int संख्या(int पत्ता) { return स्मृती_प्रदेश.पूर्णांक_पार्स_करा(पत्ता); }
    static int लघु_मूल्य(int पत्ता) { return मोबाइल_मूल्य.स्मृती_वाचा(पत्ता) | मोबाइल_मूल्य.स्मृती_वाचा(पत्ता + 1) << 8; }
    static void संख्या_लिहा(int पत्ता, int मूल्य) {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 4; अनुक्रमणिका++) मोबाइल_मूल्य.स्मृती_लिहा(पत्ता + अनुक्रमणिका, मूल्य >>> (अनुक्रमणिका * 8));
    }

    static int समूह_संख्या() {
        int पत्ता = मोबाइल_मूल्य.निष्पादनीय_बंडल();
        int आकार = मोबाइल_मूल्य.निष्पादनीय_बंडल_आकारा();
        if (आकार < 8 || संख्या(पत्ता) != 0x50414b4a) return 0;
        int आयटम_संख्या = संख्या(पत्ता + 4);
        return आयटम_संख्या >= 0 && आयटम_संख्या <= 32 && आयटम_संख्या <= (आकार - 8) / 24 ? आयटम_संख्या : 0;
    }

    static void प्रविष्टी_यादी() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < समूह_संख्या(); अनुक्रमणिका++) {
            int प्रविष्टी_मूल्य = मोबाइल_मूल्य.निष्पादनीय_बंडल() + 8 + अनुक्रमणिका * 24;
            for (int वर्ण_मूल्य = 0; वर्ण_मूल्य < 16 && मोबाइल_मूल्य.स्मृती_वाचा(प्रविष्टी_मूल्य + वर्ण_मूल्य) != 0; वर्ण_मूल्य++)
                मजकूर_टर्मिनल.वर्ण(मोबाइल_मूल्य.स्मृती_वाचा(प्रविष्टी_मूल्य + वर्ण_मूल्य));
            मजकूर_टर्मिनल.लेखन("\n");
        }
    }

    static int प्रविष्टी_शोधा(int[] आदान_मूल्य, int सुरू_करा, int लांबी_मूल्य) {
        if (लांबी_मूल्य <= 0 || लांबी_मूल्य >= 16) return 0;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < समूह_संख्या(); अनुक्रमणिका++) {
            int प्रविष्टी_मूल्य = मोबाइल_मूल्य.निष्पादनीय_बंडल() + 8 + अनुक्रमणिका * 24;
            boolean समान_मजकूर = मोबाइल_मूल्य.स्मृती_वाचा(प्रविष्टी_मूल्य + लांबी_मूल्य) == 0;
            for (int वर्ण_मूल्य = 0; वर्ण_मूल्य < लांबी_मूल्य; वर्ण_मूल्य++)
                if (आदान_मूल्य[सुरू_करा + वर्ण_मूल्य] != मोबाइल_मूल्य.स्मृती_वाचा(प्रविष्टी_मूल्य + वर्ण_मूल्य)) समान_मजकूर = false;
            if (समान_मजकूर) return प्रविष्टी_मूल्य;
        }
        return 0;
    }

    static int प्रमाणित(int फाइल, int लांबी_मूल्य) {
        if (लांबी_मूल्य < 52 || संख्या(फाइल) != 0x464c457f || मोबाइल_मूल्य.स्मृती_वाचा(फाइल + 4) != 1
            || मोबाइल_मूल्य.स्मृती_वाचा(फाइल + 5) != 1 || मोबाइल_मूल्य.स्मृती_वाचा(फाइल + 6) != 1
            || लघु_मूल्य(फाइल + 16) != 2 || लघु_मूल्य(फाइल + 18) != 3 || संख्या(फाइल + 20) != 1
            || लघु_मूल्य(फाइल + 40) != 52 || लघु_मूल्य(फाइल + 42) != 32) return -8;
        int प्रविष्टी_गुण_मूल्य = संख्या(फाइल + 24);
        int सारणी_स्थान = संख्या(फाइल + 28);
        int आयटम_संख्या = लघु_मूल्य(फाइल + 44);
        if (आयटम_संख्या == 0 || आयटम_संख्या > 16 || सारणी_स्थान < 52 || सारणी_स्थान > लांबी_मूल्य - आयटम_संख्या * 32) return -8;
        boolean आहे_निष्पादनीय = false;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < आयटम_संख्या; अनुक्रमणिका++) {
            int लुकअप_सारणी = फाइल + सारणी_स्थान + अनुक्रमणिका * 32;
            int प्रकार_मूल्य = संख्या(लुकअप_सारणी);
            if (प्रकार_मूल्य == 2 || प्रकार_मूल्य == 3) return -8; // गतिशील जोडणी किंवा दुभाषक उपलब्ध नाही.
            if (प्रकार_मूल्य != 1) continue;
            int जागा = संख्या(लुकअप_सारणी + 4), पत्ता = संख्या(लुकअप_सारणी + 8), संचिका_आकारा = संख्या(लुकअप_सारणी + 16), स्मृती_आकारा = संख्या(लुकअप_सारणी + 20);
            int संरेखन_करावे_मूल्य = संख्या(लुकअप_सारणी + 28);
            if (पत्ता < प्रारंभ_प्रयोक्ता_अनुप्रयोग || पत्ता >= चित्र_शेवट_करा_पत्ता || स्मृती_आकारा < 0 || स्मृती_आकारा > चित्र_शेवट_करा_पत्ता - पत्ता
                || संचिका_आकारा < 0 || संचिका_आकारा > स्मृती_आकारा || जागा < 0 || (संचिका_आकारा > 0 && जागा > लांबी_मूल्य - संचिका_आकारा)
                || (संरेखन_करावे_मूल्य != 0 && (संरेखन_करावे_मूल्य < 0 || (संरेखन_करावे_मूल्य & (संरेखन_करावे_मूल्य - 1)) != 0
                    || ((पत्ता - जागा) & (संरेखन_करावे_मूल्य - 1)) != 0))) return -8;
            for (int पुढील_मूल्य = 0; पुढील_मूल्य < अनुक्रमणिका; पुढील_मूल्य++) {
                int मागील_आयटम = फाइल + सारणी_स्थान + पुढील_मूल्य * 32;
                if (संख्या(मागील_आयटम) == 1 && स्मृती_आकारा > 0 && संख्या(मागील_आयटम + 20) > 0
                    && पत्ता < संख्या(मागील_आयटम + 8) + संख्या(मागील_आयटम + 20) && संख्या(मागील_आयटम + 8) < पत्ता + स्मृती_आकारा) return -8;
            }
            if ((संख्या(लुकअप_सारणी + 24) & 1) != 0 && प्रविष्टी_गुण_मूल्य >= पत्ता && प्रविष्टी_गुण_मूल्य - पत्ता < संचिका_आकारा) आहे_निष्पादनीय = true;
        }
        return आहे_निष्पादनीय ? प्रविष्टी_गुण_मूल्य : -8;
    }

    static int आज्ञा_कार्यवाही_करा(int[] आदान_मूल्य, int सुरू_करा, int लांबी_मूल्य) {
        while (सुरू_करा < लांबी_मूल्य && आदान_मूल्य[सुरू_करा] == ' ') सुरू_करा++;
        int शेवट = सुरू_करा;
        while (शेवट < लांबी_मूल्य && आदान_मूल्य[शेवट] != ' ') शेवट++;
        int प्रविष्टी_मूल्य = प्रविष्टी_शोधा(आदान_मूल्य, सुरू_करा, शेवट - सुरू_करा);
        if (प्रविष्टी_मूल्य == 0) return -2;
        int जागा = संख्या(प्रविष्टी_मूल्य + 16), आकार = संख्या(प्रविष्टी_मूल्य + 20);
        if (जागा < 8 + समूह_संख्या() * 24 || आकार < 52 || जागा > मोबाइल_मूल्य.निष्पादनीय_बंडल_आकारा() - आकार) return -8;
        int फाइल = मोबाइल_मूल्य.निष्पादनीय_बंडल() + जागा;
        int प्रविष्टी_गुण_मूल्य = प्रमाणित(फाइल, आकार);
        if (प्रविष्टी_गुण_मूल्य < 0) return प्रविष्टी_गुण_मूल्य;
        मोबाइल_मूल्य.प्रयोक्ता_साफ_करा_सामुग्री();
        int सारणी_स्थान = संख्या(फाइल + 28), आयटम_संख्या = लघु_मूल्य(फाइल + 44);
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < आयटम_संख्या; अनुक्रमणिका++) {
            int लुकअप_सारणी = फाइल + सारणी_स्थान + अनुक्रमणिका * 32;
            if (संख्या(लुकअप_सारणी) != 1) continue;
            int मूळ = फाइल + संख्या(लुकअप_सारणी + 4), गंतव्यस्थान_मूल्य = संख्या(लुकअप_सारणी + 8), संचिका_आकारा = संख्या(लुकअप_सारणी + 16);
            for (int बाइट_मूल्य = 0; बाइट_मूल्य < संचिका_आकारा; बाइट_मूल्य++) मोबाइल_मूल्य.स्मृती_लिहा(गंतव्यस्थान_मूल्य + बाइट_मूल्य, मोबाइल_मूल्य.स्मृती_वाचा(मूळ + बाइट_मूल्य));
        }
        वितर्क_संख्या = 0;
        int साठवणे_मूल्य = वितर्क_प्रारंभ;
        while (शेवट < लांबी_मूल्य) {
            while (शेवट < लांबी_मूल्य && आदान_मूल्य[शेवट] == ' ') शेवट++;
            if (शेवट == लांबी_मूल्य) break;
            if (वितर्क_संख्या == वितर्क_पत्ता.length) return -22;
            सुरू_करा = शेवट;
            while (शेवट < लांबी_मूल्य && आदान_मूल्य[शेवट] != ' ') शेवट++;
            वितर्क_पत्ता[वितर्क_संख्या++] = साठवणे_मूल्य;
            संख्या_लिहा(साठवणे_मूल्य, शेवट - सुरू_करा);
            for (int वर्ण_मूल्य = सुरू_करा; वर्ण_मूल्य < शेवट; वर्ण_मूल्य++) संख्या_लिहा(साठवणे_मूल्य + 4 + (वर्ण_मूल्य - सुरू_करा) * 4, आदान_मूल्य[वर्ण_मूल्य]);
            साठवणे_मूल्य += 4 + (शेवट - सुरू_करा) * 4;
        }
        संचारजाळे_स्टॅक.सुबक_प्रक्रिया();
        संचिका_विवरणक_व्यवस्थापक.प्रारंभ_प्रक्रिया();
        int मोजमाप = मोबाइल_मूल्य.रन_प्रयोक्ता_अनुप्रयोग(प्रविष्टी_गुण_मूल्य, प्रयोक्ता_शेवट_करा - 16);
        संचिका_विवरणक_व्यवस्थापक.सुबक_प्रक्रिया();
        संचारजाळे_स्टॅक.सुबक_प्रक्रिया();
        return मोजमाप;
    }
}
