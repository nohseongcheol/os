/** COM1 अनुक्रमिक निर्गत आणि VGA 80x25 अक्षरपडदा. Unicode मजकूर अनुक्रमिक अंतिमकाला UTF-8 मध्ये पाठवला जातो. */
public final class मजकूर_टर्मिनल {
    static int खाच_प्रविष्टी = 0;
    static int रंग_मूल्य = 7;

    static void तयार_करणे() {
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3f9, 0);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3fb, 0x80);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3f8, 1);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3f9, 0);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3fb, 3);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3fa, 0xc7);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3fc, 0x0b);
        पुसा_प्रविष्टी();
    }

    static void अनुक्रमिक_बाइट(int मूल्य) {
        int पुनरावृत्ती_संख्या = 100000;
        while ((मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(0x3fd) & 0x20) == 0 && पुनरावृत्ती_संख्या > 0) पुनरावृत्ती_संख्या--;
        if (पुनरावृत्ती_संख्या > 0) मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3f8, मूल्य);
    }

    static void पुसा_प्रविष्टी() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 2000; अनुक्रमणिका++) {
            मोबाइल_मूल्य.स्मृती_लिहा(0xb8000 + अनुक्रमणिका * 2, 32);
            मोबाइल_मूल्य.स्मृती_लिहा(0xb8001 + अनुक्रमणिका * 2, रंग_मूल्य);
        }
        खाच_प्रविष्टी = 0;
        कर्सर_मूल्य();
    }

    static void कर्सर_मूल्य() {
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3d4, 14);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3d5, खाच_प्रविष्टी >> 8);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3d4, 15);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3d5, खाच_प्रविष्टी & 255);
    }

    static void पडदा_वर्ण(int मूल्य) {
        if (मूल्य == 13) return;
        if (मूल्य == 10) {
            खाच_प्रविष्टी = (खाच_प्रविष्टी / 80 + 1) * 80;
        } else if (मूल्य == 8) {
            if (खाच_प्रविष्टी > 0) {
                खाच_प्रविष्टी--;
                मोबाइल_मूल्य.स्मृती_लिहा(0xb8000 + खाच_प्रविष्टी * 2, 32);
            }
        } else {
            मोबाइल_मूल्य.स्मृती_लिहा(0xb8000 + खाच_प्रविष्टी * 2, मूल्य < 128 ? मूल्य : '?');
            मोबाइल_मूल्य.स्मृती_लिहा(0xb8001 + खाच_प्रविष्टी * 2, रंग_मूल्य);
            खाच_प्रविष्टी++;
        }
        if (खाच_प्रविष्टी >= 2000) {
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < 3840; अनुक्रमणिका++)
                मोबाइल_मूल्य.स्मृती_लिहा(0xb8000 + अनुक्रमणिका, मोबाइल_मूल्य.स्मृती_वाचा(0xb80a0 + अनुक्रमणिका));
            for (int अनुक्रमणिका = 1920; अनुक्रमणिका < 2000; अनुक्रमणिका++) {
                मोबाइल_मूल्य.स्मृती_लिहा(0xb8000 + अनुक्रमणिका * 2, 32);
                मोबाइल_मूल्य.स्मृती_लिहा(0xb8001 + अनुक्रमणिका * 2, रंग_मूल्य);
            }
            खाच_प्रविष्टी = 1920;
        }
        कर्सर_मूल्य();
    }

    static void वर्ण(int मूल्य) {
        if (मूल्य < 128) {
            if (मूल्य == 10) अनुक्रमिक_बाइट(13);
            अनुक्रमिक_बाइट(मूल्य);
        } else if (मूल्य < 2048) {
            अनुक्रमिक_बाइट(0xc0 | (मूल्य >> 6));
            अनुक्रमिक_बाइट(0x80 | (मूल्य & 63));
        } else {
            अनुक्रमिक_बाइट(0xe0 | (मूल्य >> 12));
            अनुक्रमिक_बाइट(0x80 | ((मूल्य >> 6) & 63));
            अनुक्रमिक_बाइट(0x80 | (मूल्य & 63));
        }
        पडदा_वर्ण(मूल्य);
    }

    static void लेखन(String सामुग्री_मूल्य) {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < सामुग्री_मूल्य.length(); अनुक्रमणिका++) वर्ण(सामुग्री_मूल्य.charAt(अनुक्रमणिका));
    }

    static void संख्या_लिहा(int मूल्य) {
        // धन संख्येत बदलत नसल्याने Integer.MIN_VALUE सुद्धा सुरक्षित आहे.
        if (मूल्य < 0) वर्ण('-');
        else मूल्य = -मूल्य;
        int स्थान_अनुक्रमणिका = 1000000000;
        boolean सुरू_करा = false;
        while (स्थान_अनुक्रमणिका > 0) {
            int अंक_मूल्य = -(मूल्य / स्थान_अनुक्रमणिका);
            if (अंक_मूल्य != 0 || सुरू_करा || स्थान_अनुक्रमणिका == 1) {
                वर्ण('0' + अंक_मूल्य);
                सुरू_करा = true;
            }
            मूल्य %= स्थान_अनुक्रमणिका;
            स्थान_अनुक्रमणिका /= 10;
        }
    }

    static int अनुक्रमिक_वाचा() {
        if ((मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(0x3fd) & 1) != 0) return मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(0x3f8);
        return -1;
    }
}
