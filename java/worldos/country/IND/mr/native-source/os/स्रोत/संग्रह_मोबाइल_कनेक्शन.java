/** पहिल्या IDE साधनाचे 512 बाइट तार्किक क्षेत्र. हा स्तर कोणतेही मनमानी साधन स्वरूपित किंवा पुसत नाही. */
public final class संग्रह_मोबाइल_कनेक्शन {
    static boolean आहे_उपलब्ध = false;
    static int[] विभाग_डेटा = new int[512];
    static void प्रतीक्षा_करा_क्षणभर() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 4; अनुक्रमणिका++) मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(0x3f6);
    }
    static int प्रतीक्षा_करा_पर्यंत_सज्ज(boolean डेटा_आवश्यक) {
        int सुरू_करा = मोबाइल_मूल्य.मिलिसेकंद();
        while (मोबाइल_मूल्य.मिलिसेकंद() - सुरू_करा < 500) {
            int राज्य_मूल्य = मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(0x1f7);
            if (राज्य_मूल्य == 0 || राज्य_मूल्य == 255) return -19;
            if ((राज्य_मूल्य & 128) == 0) {
                if ((राज्य_मूल्य & 33) != 0) return -5;
                if (!डेटा_आवश्यक || (राज्य_मूल्य & 8) != 0) return 0;
            }
            मोबाइल_मूल्य.निलंबित_करा_क्षणभर();
        }
        return -110;
    }
    static int विनंती(int विभाग_मूल्य, int आदेश) {
        if (विभाग_मूल्य < 0 || विभाग_मूल्य >= 2048) return -22;
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x3f6, 2); // वारंवार स्थिती विचारली जाते; IDE IRQ वापरला जात नाही.
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x1f6, 0xe0); प्रतीक्षा_करा_क्षणभर();
        int मोजमाप = प्रतीक्षा_करा_पर्यंत_सज्ज(false);
        if (मोजमाप < 0) return मोजमाप;
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x1f2, 1);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x1f3, विभाग_मूल्य & 255);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x1f4, (विभाग_मूल्य >>> 8) & 255);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x1f5, 0);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x1f7, आदेश); प्रतीक्षा_करा_क्षणभर();
        return प्रतीक्षा_करा_पर्यंत_सज्ज(true);
    }
    static int वाचन(int विभाग_मूल्य) {
        int मोजमाप = विनंती(विभाग_मूल्य, 0x20);
        if (मोजमाप < 0) return मोजमाप;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 256; अनुक्रमणिका++) {
            int मूल्य = मोबाइल_मूल्य.आदानप्रदान_लघु_वाचा(0x1f0);
            विभाग_डेटा[अनुक्रमणिका * 2] = मूल्य & 255; विभाग_डेटा[अनुक्रमणिका * 2 + 1] = मूल्य >>> 8;
        }
        प्रतीक्षा_करा_क्षणभर(); return प्रतीक्षा_करा_पर्यंत_सज्ज(false);
    }
    static int लेखन(int विभाग_मूल्य) {
        if (!आहे_उपलब्ध || विभाग_मूल्य < 1 || विभाग_मूल्य > 518) return -19;
        int मोजमाप = विनंती(विभाग_मूल्य, 0x30);
        if (मोजमाप < 0) return मोजमाप;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 256; अनुक्रमणिका++)
            मोबाइल_मूल्य.आदानप्रदान_लघु_लिहा(0x1f0, विभाग_डेटा[अनुक्रमणिका * 2] | विभाग_डेटा[अनुक्रमणिका * 2 + 1] << 8);
        प्रतीक्षा_करा_क्षणभर(); return प्रतीक्षा_करा_पर्यंत_सज्ज(false);
    }
    static int संचितपाठवा_प्रदान() {
        if (!आहे_उपलब्ध) return -19;
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(0x1f7, 0xe7); प्रतीक्षा_करा_क्षणभर();
        return प्रतीक्षा_करा_पर्यंत_सज्ज(false);
    }
    static int पूर्णांक_पार्स_करा(int जागा) {
        return विभाग_डेटा[जागा] | विभाग_डेटा[जागा + 1] << 8 | विभाग_डेटा[जागा + 2] << 16 | विभाग_डेटा[जागा + 3] << 24;
    }
    static void पूर्णांक_मूल्य_लिहा(int जागा, int मूल्य) {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 4; अनुक्रमणिका++) विभाग_डेटा[जागा + अनुक्रमणिका] = (मूल्य >>> (अनुक्रमणिका * 8)) & 255;
    }
}
