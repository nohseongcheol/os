/** PCI RTL8139 (10ec:8139), एक प्रेषणसाठा आणि 8 KiB स्वीकारवलय. व्यत्ययांऐवजी वारंवार स्थिती विचारते. */
public final class संचारजाळे_ड्रायव्हर {
    static int आदानप्रदान_पाया_पत्ता = 0;
    static int स्थान_स्वीकारा = 0, प्रेषितकरा_खाच = 0;
    static int[] मोबाइल_पत्ता = new int[6];
    static int प्रेषितकरा_संख्या = 0, संख्या_स्वीकारा = 0, त्रुटी_संख्या_22e8e9c0 = 0;

    static int सेटिंग्ज_वाचा(int मोबाइल_संख्या, int जागा) {
        मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_लिहा(0xcf8, 0x80000000 | (मोबाइल_संख्या << 11) | जागा);
        return मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_वाचा(0xcfc);
    }

    static boolean तयार_करणे() {
        int मोबाइल_संख्या = -1;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 32; अनुक्रमणिका++) {
            if (सेटिंग्ज_वाचा(अनुक्रमणिका, 0) == 0x813910ec) { मोबाइल_संख्या = अनुक्रमणिका; break; }
        }
        if (मोबाइल_संख्या < 0) return false;
        int डिफॉल्ट_मूल्य = सेटिंग्ज_वाचा(मोबाइल_संख्या, 0x10);
        if ((डिफॉल्ट_मूल्य & 1) == 0 || (डिफॉल्ट_मूल्य & 0xfffffffc) < 0x100 || (डिफॉल्ट_मूल्य & 0xfffffffc) > 65535) return false;
        आदानप्रदान_पाया_पत्ता = डिफॉल्ट_मूल्य & 0xfffc;
        int आदेश = सेटिंग्ज_वाचा(मोबाइल_संख्या, 4);
        मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_लिहा(0xcf8, 0x80000004 | (मोबाइल_संख्या << 11));
        मोबाइल_मूल्य.आदानप्रदान_लघु_लिहा(0xcfc, आदेश | 5); // I/O आणि बस-नियंत्रण सक्षम करावे; PCI स्थितिबिट बदलू नयेत.
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(आदानप्रदान_पाया_पत्ता + 0x52, 0);
        if (!रीसेट_करा_मूल्य()) { आदानप्रदान_पाया_पत्ता = 0; return false; }
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 6; अनुक्रमणिका++) मोबाइल_पत्ता[अनुक्रमणिका] = मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(आदानप्रदान_पाया_पत्ता + अनुक्रमणिका);
        return true;
    }

    static boolean रीसेट_करा_मूल्य() {
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(आदानप्रदान_पाया_पत्ता + 0x37, 0x10);
        int सुरू_करा = मोबाइल_मूल्य.मिलिसेकंद();
        while ((मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(आदानप्रदान_पाया_पत्ता + 0x37) & 0x10) != 0)
            if (मोबाइल_मूल्य.मिलिसेकंद() - सुरू_करा > 100) return false;
        स्थान_स्वीकारा = 0; प्रेषितकरा_खाच = 0;
        मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_लिहा(आदानप्रदान_पाया_पत्ता + 0x30, मोबाइल_मूल्य.संचारजाळे_स्मृती());
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 4; अनुक्रमणिका++) मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_लिहा(आदानप्रदान_पाया_पत्ता + 0x20 + अनुक्रमणिका * 4, मोबाइल_मूल्य.संचारजाळे_स्मृती() + 12288);
        मोबाइल_मूल्य.आदानप्रदान_लघु_लिहा(आदानप्रदान_पाया_पत्ता + 0x3c, 0);
        मोबाइल_मूल्य.आदानप्रदान_लघु_लिहा(आदानप्रदान_पाया_पत्ता + 0x3e, 0xffff);
        मोबाइल_मूल्य.आदानप्रदान_बाइट_लिहा(आदानप्रदान_पाया_पत्ता + 0x37, 0x0c);
        मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_लिहा(आदानप्रदान_पाया_पत्ता + 0x44, 0x0000e78a); // स्वतःचा पत्ता आणि सर्वप्रसारण स्वीकारावे; वलय वळताना सलग साठवण, 8 KiB.
        मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_लिहा(आदानप्रदान_पाया_पत्ता + 0x40, 0x03000600);
        return true;
    }

    static int पाठवा(int[] डेटा, int लांबी_मूल्य) {
        if (आदानप्रदान_पाया_पत्ता == 0) return -19;
        if (लांबी_मूल्य < 14 || लांबी_मूल्य > 1514) return -90;
        int राज्य_पॉर्ट = आदानप्रदान_पाया_पत्ता + 0x10 + प्रेषितकरा_खाच * 4;
        int सुरू_करा = मोबाइल_मूल्य.मिलिसेकंद();
        while ((मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_वाचा(राज्य_पॉर्ट) & 0x2000) == 0)
            if (मोबाइल_मूल्य.मिलिसेकंद() - सुरू_करा > 100) return -110;
        int आकार = लांबी_मूल्य < 60 ? 60 : लांबी_मूल्य;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < आकार; अनुक्रमणिका++)
            मोबाइल_मूल्य.स्मृती_लिहा(मोबाइल_मूल्य.संचारजाळे_स्मृती() + 12288 + अनुक्रमणिका, अनुक्रमणिका < लांबी_मूल्य ? डेटा[अनुक्रमणिका] : 0);
        मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_लिहा(राज्य_पॉर्ट, आकार | 0x00080000);
        सुरू_करा = मोबाइल_मूल्य.मिलिसेकंद();
        while ((मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_वाचा(राज्य_पॉर्ट) & 0xe0008000) == 0)
            if (मोबाइल_मूल्य.मिलिसेकंद() - सुरू_करा > 100) return -110;
        if ((मोबाइल_मूल्य.आदानप्रदान_पूर्णांक_वाचा(राज्य_पॉर्ट) & 0x8000) == 0) { त्रुटी_संख्या_22e8e9c0++; return -5; }
        प्रेषितकरा_खाच = (प्रेषितकरा_खाच + 1) & 3;
        प्रेषितकरा_संख्या++;
        return लांबी_मूल्य;
    }

    static int स्वीकारा(int[] डेटा) {
        if (आदानप्रदान_पाया_पत्ता == 0) return 0;
        if ((मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(आदानप्रदान_पाया_पत्ता + 0x3e) & 0x50) != 0) {
            त्रुटी_संख्या_22e8e9c0++;
            if (!रीसेट_करा_मूल्य()) आदानप्रदान_पाया_पत्ता = 0;
            return 0;
        }
        if ((मोबाइल_मूल्य.आदानप्रदान_बाइट_वाचा(आदानप्रदान_पाया_पत्ता + 0x37) & 1) != 0) return 0;
        int शीर्ष_मूल्य = मोबाइल_मूल्य.संचारजाळे_स्मृती() + स्थान_स्वीकारा;
        int राज्य_मूल्य = निष्पादन_व्यवस्थापक.लघु_मूल्य(शीर्ष_मूल्य), आकार = निष्पादन_व्यवस्थापक.लघु_मूल्य(शीर्ष_मूल्य + 2);
        if (आकार == 0xfff0) return 0; // DMA चालू आहे.
        if (आकार < 4 || आकार > 1518) {
            त्रुटी_संख्या_22e8e9c0++;
            if (!रीसेट_करा_मूल्य()) आदानप्रदान_पाया_पत्ता = 0;
            return 0;
        }
        int लांबी_मूल्य = आकार - 4;
        if ((राज्य_मूल्य & 1) != 0) {
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < लांबी_मूल्य; अनुक्रमणिका++) डेटा[अनुक्रमणिका] = मोबाइल_मूल्य.स्मृती_वाचा(शीर्ष_मूल्य + 4 + अनुक्रमणिका);
            संख्या_स्वीकारा++;
        } else { लांबी_मूल्य = 0; त्रुटी_संख्या_22e8e9c0++; }
        स्थान_स्वीकारा = (स्थान_स्वीकारा + आकार + 4 + 3) & ~3;
        स्थान_स्वीकारा &= 8191;
        मोबाइल_मूल्य.आदानप्रदान_लघु_लिहा(आदानप्रदान_पाया_पत्ता + 0x38, (स्थान_स्वीकारा - 16) & 65535);
        मोबाइल_मूल्य.आदानप्रदान_लघु_लिहा(आदानप्रदान_पाया_पत्ता + 0x3e, 0x000f);
        return लांबी_मूल्य;
    }
}
