/** int 0x80 प्रवेशद्वारातून आवाहन होते. वापरण्यापूर्वी सर्व वापरकर्ता दर्शक आणि लांबी तपासाव्यात. */
public final class सिस्टम_कॉल_आवाहन {
    static int[] तात्पुरते_बफर = new int[1024];

    static int ऍरे_लांबी(int पत्ता) {
        if (!निष्पादन_व्यवस्थापक.क्लिप(पत्ता, 4)) return -14;
        int लांबी_मूल्य = निष्पादन_व्यवस्थापक.संख्या(पत्ता);
        if (लांबी_मूल्य < 0 || लांबी_मूल्य > (निष्पादन_व्यवस्थापक.प्रयोक्ता_शेवट_करा - पत्ता - 4) / 4) return -14;
        return लांबी_मूल्य;
    }

    public static int प्रक्रिया_मूल्य_प्रविष्टी(int अनुक्रमणिका, int पहिले_संकार्य, int दुसरे_संकार्य, int तिसरे_संकार्य, int चौथे_संकार्य, int पाचवे_संकार्य) {
        if (अनुक्रमणिका == 30) return संचिका_विवरणक_व्यवस्थापक.संचिका_उघडा(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य);
        if (अनुक्रमणिका == 31) return संचिका_विवरणक_व्यवस्थापक.संचिका_वाचा(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य);
        if (अनुक्रमणिका == 32) return संचिका_विवरणक_व्यवस्थापक.संचिका_लिहा(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य);
        if (अनुक्रमणिका == 33) return संचिका_विवरणक_व्यवस्थापक.संचिका_मिटवा(पहिले_संकार्य);
        if (अनुक्रमणिका == 34) return संचिका_विवरणक_व्यवस्थापक.शोधा_संचिका(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य);
        if (अनुक्रमणिका == 35) return संचिका_विवरणक_व्यवस्थापक.प्रतिरूप_विवरणक(पहिले_संकार्य, 0, false, 0);
        if (अनुक्रमणिका == 36) return संचिका_विवरणक_व्यवस्थापक.प्रतिरूप_विवरणक(पहिले_संकार्य, दुसरे_संकार्य, true, 0);
        if (अनुक्रमणिका == 37) return संचिका_विवरणक_व्यवस्थापक.संचिका_राज्य_वाचा(पहिले_संकार्य, दुसरे_संकार्य);
        if (अनुक्रमणिका == 38) return संचिका_विवरणक_व्यवस्थापक.संचिका_प्रविष्टी_नाव_काढणे(पहिले_संकार्य);
        if (अनुक्रमणिका == 39) return संचिका_विवरणक_व्यवस्थापक.संचिका_लांबी_संच(पहिले_संकार्य, दुसरे_संकार्य);
        if (अनुक्रमणिका == 40) return संचिका_विवरणक_व्यवस्थापक.नियंत्रण_विवरणक(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य);
        if (अनुक्रमणिका == 41) return संचिका_विवरणक_व्यवस्थापक.संचारटोक_तयार_करा(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य);
        if (अनुक्रमणिका == 42) return संचिका_विवरणक_व्यवस्थापक.बाइंड_करा_पत्ता(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य);
        if (अनुक्रमणिका == 43) return संचिका_विवरणक_व्यवस्थापक.स्वतंत्रसंदेश_डेटा_पाठवा(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य, चौथे_संकार्य, पाचवे_संकार्य);
        if (अनुक्रमणिका == 44) return संचिका_विवरणक_व्यवस्थापक.स्वतंत्रसंदेश_डेटा_स्वीकारा(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य, चौथे_संकार्य, पाचवे_संकार्य);
        if (अनुक्रमणिका == 45) return संचिका_विवरणक_व्यवस्थापक.संचारद्वार_पत्ता_वाचा(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य);
        if (अनुक्रमणिका == 46) return संचिका_विवरणक_व्यवस्थापक.स्वीकारा_प्रतीक्षामर्यादा_संच(पहिले_संकार्य, दुसरे_संकार्य);
        if (अनुक्रमणिका == 47) {
            int विवरणक_मूल्य = संचिका_विवरणक_व्यवस्थापक.विवरणक_शोधा(पहिले_संकार्य);
            if (विवरणक_मूल्य < 0) return -9;
            if (संचिका_विवरणक_व्यवस्थापक.प्रकार_मूल्य[विवरणक_मूल्य] != 2) return -22;
            return जतनकरा_संचिका.समन्वय_साधा();
        }
        if (अनुक्रमणिका == 1) {
            int लांबी_मूल्य = ऍरे_लांबी(पहिले_संकार्य);
            if (लांबी_मूल्य < 0) return लांबी_मूल्य;
            if (लांबी_मूल्य > 4096) return -90;
            for (int वर्ण_मूल्य = 0; वर्ण_मूल्य < लांबी_मूल्य; वर्ण_मूल्य++) मजकूर_टर्मिनल.वर्ण(निष्पादन_व्यवस्थापक.संख्या(पहिले_संकार्य + 4 + वर्ण_मूल्य * 4) & 65535);
            return लांबी_मूल्य;
        }
        if (अनुक्रमणिका == 2) return निष्पादन_व्यवस्थापक.वितर्क_संख्या;
        if (अनुक्रमणिका == 3) return पहिले_संकार्य >= 0 && पहिले_संकार्य < निष्पादन_व्यवस्थापक.वितर्क_संख्या ? निष्पादन_व्यवस्थापक.वितर्क_पत्ता[पहिले_संकार्य] : 0;
        if (अनुक्रमणिका == 10) return संचारजाळे_स्टॅक.उघडा(पहिले_संकार्य);
        if (अनुक्रमणिका == 11) {
            int लांबी_मूल्य = ऍरे_लांबी(चौथे_संकार्य);
            if (लांबी_मूल्य < 0) return लांबी_मूल्य;
            if (पाचवे_संकार्य < 0 || पाचवे_संकार्य > लांबी_मूल्य || पाचवे_संकार्य > 1024) return -90;
            for (int जागा = 0; जागा < पाचवे_संकार्य; जागा++) तात्पुरते_बफर[जागा] = निष्पादन_व्यवस्थापक.संख्या(चौथे_संकार्य + 4 + जागा * 4) & 255;
            return संचारजाळे_स्टॅक.पाठवा(पहिले_संकार्य, दुसरे_संकार्य, तिसरे_संकार्य, तात्पुरते_बफर, पाचवे_संकार्य);
        }
        if (अनुक्रमणिका == 12) {
            int लांबी_मूल्य = ऍरे_लांबी(दुसरे_संकार्य);
            if (लांबी_मूल्य < 0) return लांबी_मूल्य;
            if (तिसरे_संकार्य < 0 || तिसरे_संकार्य > 2000) return -22;
            int मोजमाप = संचारजाळे_स्टॅक.स्वीकारा(पहिले_संकार्य, तात्पुरते_बफर, लांबी_मूल्य < 1024 ? लांबी_मूल्य : 1024, तिसरे_संकार्य);
            if (मोजमाप >= 0) for (int जागा = 0; जागा < मोजमाप; जागा++) निष्पादन_व्यवस्थापक.संख्या_लिहा(दुसरे_संकार्य + 4 + जागा * 4, तात्पुरते_बफर[जागा]);
            return मोजमाप;
        }
        if (अनुक्रमणिका == 13) return संचारजाळे_स्टॅक.बंद_करा(पहिले_संकार्य);
        if (अनुक्रमणिका == 14) return संचारजाळे_स्टॅक.स्वकीय_पत्ता;
        if (अनुक्रमणिका == 15) return संचारजाळे_स्टॅक.समकक्ष_पत्ता(पहिले_संकार्य);
        if (अनुक्रमणिका == 16) return संचारजाळे_स्टॅक.समकक्ष_पोर्ट_नंबर(पहिले_संकार्य);
        if (अनुक्रमणिका == 22) {
            if (पहिले_संकार्य < 0 || पहिले_संकार्य > 65535) return -22;
            मजकूर_टर्मिनल.वर्ण(पहिले_संकार्य); return 1;
        }
        if (अनुक्रमणिका == 20 || अनुक्रमणिका == 21) {
            int नाव_आकारा = ऍरे_लांबी(पहिले_संकार्य), डेटा_आकारा = ऍरे_लांबी(दुसरे_संकार्य);
            if (नाव_आकारा < 0 || डेटा_आकारा < 0) return -14;
            if (नाव_आकारा < 1 || नाव_आकारा > 64) return -22;
            int लांबी_मूल्य = 0;
            while (लांबी_मूल्य < नाव_आकारा && निष्पादन_व्यवस्थापक.संख्या(पहिले_संकार्य + 4 + लांबी_मूल्य * 4) != 0) {
                स्मृती_फाइल_सिस्टम.नाव[लांबी_मूल्य] = निष्पादन_व्यवस्थापक.संख्या(पहिले_संकार्य + 4 + लांबी_मूल्य * 4);
                लांबी_मूल्य++;
            }
            if (!स्मृती_फाइल_सिस्टम.नाव_तपासा(स्मृती_फाइल_सिस्टम.नाव, लांबी_मूल्य)) return -22;
            if (अनुक्रमणिका == 20) {
                int फाइल = स्मृती_फाइल_सिस्टम.प्रविष्टी_शोधा(स्मृती_फाइल_सिस्टम.नाव, लांबी_मूल्य);
                if (फाइल < 0) return फाइल;
                int आकार = स्मृती_फाइल_सिस्टम.आकारा_यादी[फाइल];
                if (आकार > डेटा_आकारा) return -90;
                int पत्ता = मोबाइल_मूल्य.संचिका_स्मृती() + फाइल * स्मृती_फाइल_सिस्टम.कमाल_आकारा;
                for (int संख्या = 0; संख्या < आकार; संख्या++) निष्पादन_व्यवस्थापक.संख्या_लिहा(दुसरे_संकार्य + 4 + संख्या * 4, मोबाइल_मूल्य.स्मृती_वाचा(पत्ता + संख्या));
                return आकार;
            }
            if (तिसरे_संकार्य < 0 || तिसरे_संकार्य > डेटा_आकारा) return -22;
            if (तिसरे_संकार्य > स्मृती_फाइल_सिस्टम.कमाल_आकारा) return -90;
            for (int संख्या = 0; संख्या < तिसरे_संकार्य; संख्या++) स्मृती_फाइल_सिस्टम.संपादन_मूल्य[संख्या] = निष्पादन_व्यवस्थापक.संख्या(दुसरे_संकार्य + 4 + संख्या * 4) & 255;
            return स्मृती_फाइल_सिस्टम.साठवणे_मूल्य(स्मृती_फाइल_सिस्टम.नाव, लांबी_मूल्य, स्मृती_फाइल_सिस्टम.संपादन_मूल्य, तिसरे_संकार्य);
        }
        return -38;
    }
}
