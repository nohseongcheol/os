/** प्रारंभमाहिती वाचणे आणि निश्चित 4 KiB कार्यभाग देणे-परत घेणे; सामान्य भौतिक पान व्यवस्थापक नाही. */
public final class स्मृती_प्रदेश {
    static int[] विभाग_मूल्य = new int[8192];
    static int[] वापर_मूल्य = new int[8];

    static int पूर्णांक_पार्स_करा(int पत्ता) {
        return मोबाइल_मूल्य.स्मृती_वाचा(पत्ता) | (मोबाइल_मूल्य.स्मृती_वाचा(पत्ता + 1) << 8)
            | (मोबाइल_मूल्य.स्मृती_वाचा(पत्ता + 2) << 16) | (मोबाइल_मूल्य.स्मृती_वाचा(पत्ता + 3) << 24);
    }

    static int वरचे_स्मृती_आकारा() {
        int सिस्टम_माहिती = मोबाइल_मूल्य.प्रणालीप्रारंभ_माहिती();
        if (मोबाइल_मूल्य.प्रणालीप्रारंभ_खूण() != 0x2badb002 || सिस्टम_माहिती == 0 || (पूर्णांक_पार्स_करा(सिस्टम_माहिती) & 1) == 0) return -1;
        return पूर्णांक_पार्स_करा(सिस्टम_माहिती + 8);
    }

    static int संग्रह_वाटप_करा() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < वापर_मूल्य.length; अनुक्रमणिका++) {
            if (वापर_मूल्य[अनुक्रमणिका] == 0) {
                वापर_मूल्य[अनुक्रमणिका] = 1;
                for (int खाच_प्रविष्टी = 0; खाच_प्रविष्टी < 1024; खाच_प्रविष्टी++) विभाग_मूल्य[अनुक्रमणिका * 1024 + खाच_प्रविष्टी] = 0;
                return अनुक्रमणिका;
            }
        }
        return -1;
    }

    static boolean परतकरा_मोजमाप(int अनुक्रमणिका) {
        if (अनुक्रमणिका < 0 || अनुक्रमणिका >= वापर_मूल्य.length || वापर_मूल्य[अनुक्रमणिका] == 0) return false;
        वापर_मूल्य[अनुक्रमणिका] = 0;
        return true;
    }

    static int वापरलेले_प्रविष्टी_संख्या() {
        int आयटम_संख्या = 0;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < वापर_मूल्य.length; अनुक्रमणिका++) आयटम_संख्या += वापर_मूल्य[अनुक्रमणिका];
        return आयटम_संख्या;
    }
}
