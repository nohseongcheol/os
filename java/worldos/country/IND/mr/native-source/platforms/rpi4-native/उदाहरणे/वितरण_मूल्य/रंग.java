public class रंग {
    public static void main(String[] बाबी) throws Exception {
        int बेरीज_मूल्य = 0;
        int संख्या = 1;
        while (संख्या <= 10) {
            बेरीज_मूल्य = बेरीज_मूल्य + संख्या;
            संख्या = संख्या + 1;
        }
        मराठी.स्वकीय.आउटपुट.संख्या_लिहा(बेरीज_मूल्य);
        मराठी.स्वकीय.फाइल.लेखन("aot.txt", "한글 AOT फाइल 😀");
        मराठी.स्वकीय.आउटपुट.ओळ_लिहा(मराठी.स्वकीय.फाइल.वाचन("aot.txt"));
    }
}
