#include "संचिका_द्विमानजोडणी.h"
int प्रारंभ_प्रयोक्ता_अनुप्रयोग(int बाबी) {
    (void)बाबी;
    const char अभिवादन[] = "C에서 한글 이름과 posix-kor आवाहन\n";
    int मार्गदर्शिका = संचिका_उघडा("C인사.txt", वाचणे_लिहिणे | जर_अनुपस्थित_तयार_करा | छाटूनरिकामेकरा_सामुग्री, 0600);
    if (मार्गदर्शिका < 0) return 1;
    आदानप्रदान_मोजमाप_टाइप_करा नोंदवलेले_संख्या = संचिका_डेटा_लिहा(मार्गदर्शिका, अभिवादन, sizeof(अभिवादन) - 1);
    संचिका_मिटवा(मार्गदर्शिका);
    संचिका_डेटा_लिहा(1, अभिवादन, sizeof(अभिवादन) - 1);
    return नोंदवलेले_संख्या == sizeof(अभिवादन) - 1 ? 0 : 2;
}
