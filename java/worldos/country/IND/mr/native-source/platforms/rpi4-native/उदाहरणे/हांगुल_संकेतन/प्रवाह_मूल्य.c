#include "संचारजाळे_द्विमानजोडणी.h"

int प्रारंभ_प्रयोक्ता_अनुप्रयोग(int बाबी) {
    (void)बाबी;
    struct क्लाउड_संचारद्वार_पत्ता पत्ता = {0};
    पत्ता.पत्ता_कुटुंब = क्लाउड_कुटुंब;
    पत्ता.पोर्ट_नंबर = संचारजाळे_लघु(9260);
    पत्ता.इंटरनेट_पत्ता.पत्ता_मूल्य = संचारजाळे_पूर्णांक(स्वपरतावा_पत्ता);
    int सर्व्हर_मूल्य = संचारटोक_तयार_करा(क्लाउड_कुटुंब, प्रवाह_संचारजाळे, प्रवाह_वाहतूक_प्रोटोकॉल);
    if (सर्व्हर_मूल्य < 0 || बाइंड_करा_पत्ता(सर्व्हर_मूल्य, (struct संचारद्वार_पत्ता *)&पत्ता, sizeof(पत्ता)) < 0 ||
        प्रतीक्षा_करा_साठी_नेटवर्क_कनेक्शन(सर्व्हर_मूल्य, 4) < 0) return 1;
    if (स्वीकारा_नेटवर्क_कनेक्शन(सर्व्हर_मूल्य, 0, 0) != -1 || त्रुटी_संख्या != 11) return 2;
    int अतिथी_मूल्य = संचारटोक_तयार_करा(क्लाउड_कुटुंब, प्रवाह_संचारजाळे, प्रवाह_वाहतूक_प्रोटोकॉल);
    if (अतिथी_मूल्य < 0 || कनेक्ट_संचारजाळे(अतिथी_मूल्य, (struct संचारद्वार_पत्ता *)&पत्ता, sizeof(पत्ता)) < 0) return 3;
    int जोडा = स्वीकारा_नेटवर्क_कनेक्शन(सर्व्हर_मूल्य, 0, 0);
    if (जोडा < 0) return 4;
    unsigned char आयटम_कडे_पाठवा[1500], स्वीकारलेले_आयटम[1500];
    for (int संख्या = 0; संख्या < 1500; संख्या++) आयटम_कडे_पाठवा[संख्या] = (unsigned char)संख्या;
    int पाठवलेले_संख्या = 0;
    while (पाठवलेले_संख्या < 1024) {
        int लांबी_मूल्य = संचिका_डेटा_लिहा(अतिथी_मूल्य, आयटम_कडे_पाठवा + पाठवलेले_संख्या, sizeof(आयटम_कडे_पाठवा) - पाठवलेले_संख्या);
        if (लांबी_मूल्य <= 0) return 5;
        पाठवलेले_संख्या += लांबी_मूल्य;
    }
    if (संचिका_डेटा_लिहा(अतिथी_मूल्य, आयटम_कडे_पाठवा, 1) != -1 || त्रुटी_संख्या != 11) return 6;
    /* 상대가 닫아도 이미 도착한 자료를 सर्व_बांधणी 읽은 मागे_मूल्य EOF가 된다. */
    संचिका_मिटवा(अतिथी_मूल्य);
    int स्वीकारलेले_संख्या = 0;
    while (स्वीकारलेले_संख्या < पाठवलेले_संख्या) {
        int लांबी_मूल्य = संचिका_डेटा_वाचा(जोडा, स्वीकारलेले_आयटम + स्वीकारलेले_संख्या, sizeof(स्वीकारलेले_आयटम) - स्वीकारलेले_संख्या);
        if (लांबी_मूल्य <= 0) return 7;
        स्वीकारलेले_संख्या += लांबी_मूल्य;
    }
    for (int संख्या = 0; संख्या < स्वीकारलेले_संख्या; संख्या++) if (स्वीकारलेले_आयटम[संख्या] != आयटम_कडे_पाठवा[संख्या]) return 8;
    if (संचिका_डेटा_वाचा(जोडा, स्वीकारलेले_आयटम, 1) != 0) return 9;
    if (संचिका_डेटा_लिहा(जोडा, आयटम_कडे_पाठवा, 1) != -1 || त्रुटी_संख्या != 32) return 10;
    संचिका_मिटवा(जोडा); संचिका_मिटवा(सर्व्हर_मूल्य);
    const char मोजमाप[] = "C posix-kor 연결형 संचार PASS\n";
    संचिका_डेटा_लिहा(1, मोजमाप, sizeof(मोजमाप) - 1);
    return 0;
}
