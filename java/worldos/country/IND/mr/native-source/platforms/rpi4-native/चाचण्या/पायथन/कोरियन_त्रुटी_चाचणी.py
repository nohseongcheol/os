from मराठी import सिस्टम_त्रुटी, प्रयत्नकरा_पुन्हा_त्रुटी, स्वतंत्रसंदेश_उघडा, स्वतंत्रसंदेश_स्वीकारा, संचारजाळे_मिटवा, संचिका_वाचा, आउटपुट

संचारटोक = स्वतंत्रसंदेश_उघडा(0)
try:
    try:
        स्वतंत्रसंदेश_स्वीकारा(संचारटोक)
        raise AssertionError("비어 있는 स्वतंत्रसंदेश 대기에서 예외가 필요합니다.")
    except सिस्टम_त्रुटी as त्रुटी:
        assert त्रुटी.अनुक्रमणिका == प्रयत्नकरा_पुन्हा_त्रुटी
        assert त्रुटी.वर्णन == "संचालनप्रणाली 작업에 실패했습니다."
        आउटपुट("मराठी स्वतंत्रसंदेश अपवाद पडताळा")
finally:
    संचारजाळे_मिटवा(संचारटोक)
try:
    संचिका_वाचा("/없는파일")
except सिस्टम_त्रुटी as त्रुटी:
    assert त्रुटी.अनुक्रमणिका == 2
    आउटपुट("मराठी फाइल अपवाद पडताळा")
else:
    raise AssertionError("फाइल अनुपस्थित_पद्धत 예외가 필요합니다.")
