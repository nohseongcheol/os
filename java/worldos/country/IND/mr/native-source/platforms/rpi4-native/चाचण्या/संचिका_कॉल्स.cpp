// 표준 C++ लायब्ररी 없는 freestanding C++11 अनुप्रयोग_f5044b9b. 커널에 स्थिर_मूल्य 링크한다.
extern "C" uintptr_t सीप्लसप्लस_कार्यक्रम_चाचणी(void) {
    const char सामुग्री_मूल्य[] = "C++ → Java गाभा_मूल्य · 한글 😀";
    unsigned char मूल्य_वाचा[sizeof(सामुग्री_मूल्य)] = {};
    int फाइल = संचिका_उघडा("चाचण्या.txt", वाचणे_लिहिणे | जर_अनुपस्थित_तयार_करा | छाटूनरिकामेकरा_सामुग्री, 0600);
    if (फाइल < 0) return 1;
    if (संचिका_डेटा_लिहा(फाइल, सामुग्री_मूल्य, sizeof(सामुग्री_मूल्य)) != sizeof(सामुग्री_मूल्य)) return 2;
    if (शोधा_संचिका(फाइल, 0, पासून_आरंभ) != 0) return 3;
    if (संचिका_डेटा_वाचा(फाइल, मूल्य_वाचा, sizeof(मूल्य_वाचा)) != sizeof(मूल्य_वाचा)) return 4;
    for (size_t क्रमांक_अनुक्रमणिका = 0; क्रमांक_अनुक्रमणिका < sizeof(सामुग्री_मूल्य); क्रमांक_अनुक्रमणिका++) if (मूल्य_वाचा[क्रमांक_अनुक्रमणिका] != (unsigned char)सामुग्री_मूल्य[क्रमांक_अनुक्रमणिका]) return 5;
    if (संचिका_डेटा_वाचा(फाइल, मूल्य_वाचा, 1) != 0) return 6;
    if (स्थिरकरा_फाईल_संग्रहण(फाइल) != -1 || त्रुटी_संख्या != 38) return 7;
    if (संचिका_मिटवा(फाइल) || संचिका_मिटवा(फाइल) != -1 || त्रुटी_संख्या != 9) return 8;
    फाइल = संचिका_उघडा("चाचण्या.txt", केवळ_मूल्य_वाचा);
    if (फाइल < 0 || संचिका_डेटा_लिहा(फाइल, सामुग्री_मूल्य, 1) != -1 || त्रुटी_संख्या != 9) return 9;
    if (संचिका_मिटवा(फाइल)) return 10;
    फाइल = संचिका_उघडा("चाचण्या.txt", वाचणे_लिहिणे | शेवटीजोडा_येथे_शेवट_करा);
    if (फाइल < 0 || शोधा_संचिका(फाइल, 0, पासून_आरंभ) != 0 || संचिका_डेटा_लिहा(फाइल, "!", 1) != 1 || संचिका_आकारा(फाइल) != sizeof(सामुग्री_मूल्य) + 1) return 11;
    if (संचिका_लांबी_संच(फाइल, 2) || शोधा_संचिका(फाइल, 4, पासून_आरंभ) != 4) return 12;
    // append는 매 write 때 EOF를 사용한다.
    if (संचिका_डेटा_लिहा(फाइल, "x", 1) != 1 || संचिका_आकारा(फाइल) != 3 || संचिका_मिटवा(फाइल)) return 13;
    फाइल = संचिका_उघडा("구멍.bin", वाचणे_लिहिणे | जर_अनुपस्थित_तयार_करा | छाटूनरिकामेकरा_सामुग्री, 0600);
    if (फाइल < 0 || शोधा_संचिका(फाइल, 3, पासून_आरंभ) != 3 || संचिका_डेटा_लिहा(फाइल, "z", 1) != 1) return 14;
    if (शोधा_संचिका(फाइल, 0, पासून_आरंभ) != 0 || संचिका_डेटा_वाचा(फाइल, मूल्य_वाचा, 4) != 4 || मूल्य_वाचा[0] || मूल्य_वाचा[1] || मूल्य_वाचा[2] || मूल्य_वाचा[3] != 'z') return 15;
    if (संचिका_प्रविष्टी_नाव_काढणे("구멍.bin") || संचिका_आकारा(फाइल) != 4 || संचिका_मिटवा(फाइल)) return 16;
    if (संचिका_उघडा("구멍.bin", केवळ_मूल्य_वाचा) != -1 || त्रुटी_संख्या != 2) return 17;
    if (संचिका_उघडा("चाचण्या.txt", वाचणे_लिहिणे | नवे_संचिका_तयार_करा, 0600) != -1 || त्रुटी_संख्या != 17) return 18;
    if (संचिका_उघडा("../निषिद्ध_मूल्य", केवळ_मूल्य_वाचा) != -1) return 19;
    return 0;
}
