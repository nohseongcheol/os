"""स्वकीय 커널용 제한형 pip. PyPI의 작은 순수 Python 소스를 होस्ट 중계로 설치한다."""
import sys
import json
import hashlib
import gc
import jkoros as संचालनप्रणाली

यादी_पथ = "/lib/.pip.json"


def ओळखठसा_मूल्य(डेटा):
    return "".join("%02x" % मूल्य for मूल्य in hashlib.sha256(डेटा).digest())


def यादी_वाचा():
    if संचालनप्रणाली.path_kind(यादी_पथ) == 0:
        return {}
    return json.loads(संचालनप्रणाली.read(यादी_पथ).decode("utf-8"))


def लॉग_लिहा(मार्ग, डेटा):
    if संचालनप्रणाली.write(मार्ग, डेटा) != len(डेटा):
        raise OSError(28)


def पथ_तपासा(मार्ग):
    if not isinstance(मार्ग, str) or not मार्ग.endswith(".py"):
        raise ValueError("Python 소스만 설치할 संख्या 있습니다.")
    if any(उपभाग_मूल्य in ("", ".", "..") or उपभाग_मूल्य.startswith(".") for उपभाग_मूल्य in मार्ग.split("/")):
        raise ValueError("허용하지 않는 बंडल मार्ग")
    if "\\" in मार्ग or any(ord(वर्ण_मूल्य) < 32 or ord(वर्ण_मूल्य) == 127 for वर्ण_मूल्य in मार्ग):
        raise ValueError("잘못된 मार्ग वर्ण")
    मोजमाप = "/lib/" + मार्ग
    if len(मोजमाप.encode("utf-8")) > 63 or मार्ग in ("मराठी.py", "बंडल.py"):
        raise ValueError("बंडल 경로가 너무 길거나 डिफॉल्ट_मूल्य 라이브러리와 겹칩니다.")
    return मोजमाप


class प्रवाह_स्वीकारा:
    def __init__(स्वतः, संचारटोक):
        स्वतः.संचारटोक = संचारटोक
        स्वतः.उर्वरित_डेटा = b""
        स्वतः.सुरू_करा = संचालनप्रणाली.ticks_ms()

    def नेमके_वाचा(स्वतः, लांबी_मूल्य):
        डेटा = bytearray()
        while len(डेटा) < लांबी_मूल्य:
            if संचालनप्रणाली.ticks_ms() - स्वतः.सुरू_करा > 90000:
                raise ValueError("बंडल संदेशमध्यस्थ_मूल्य प्रत्युत्तर_द्या वेळ_मूल्य 초과")
            if not स्वतः.उर्वरित_डेटा:
                try:
                    स्वतः.उर्वरित_डेटा = संचालनप्रणाली.tcp_read(स्वतः.संचारटोक, 512)
                except OSError as त्रुटी:
                    if त्रुटी.args[0] != 11:
                        raise
                    संचालनप्रणाली.sleep_ms(10)
                    continue
                if not स्वतः.उर्वरित_डेटा:
                    raise ValueError("बंडल 전송이 중간에 끝났습니다.")
            आयटम_संख्या = min(लांबी_मूल्य - len(डेटा), len(स्वतः.उर्वरित_डेटा))
            डेटा.extend(स्वतः.उर्वरित_डेटा[:आयटम_संख्या])
            स्वतः.उर्वरित_डेटा = स्वतः.उर्वरित_डेटा[आयटम_संख्या:]
            संचालनप्रणाली.sleep_ms(0)
        return bytes(डेटा)


def डाउनलोड(विनंती, पोर्ट_नंबर):
    if len(विनंती) > 96 or any(वर्ण_मूल्य not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-=" for वर्ण_मूल्य in विनंती):
        raise ValueError("사용법: pip install नाव 또는 नाव==버전")
    संचारटोक = संचालनप्रणाली.tcp_open()
    try:
        सुरू_करा = संचालनप्रणाली.ticks_ms()
        while True:
            try:
                संचालनप्रणाली.tcp_connect(संचारटोक, "10.0.2.2", पोर्ट_नंबर)
                break
            except OSError as त्रुटी:
                if त्रुटी.args[0] not in (11, 115) or संचालनप्रणाली.ticks_ms() - सुरू_करा > 5000:
                    raise ValueError("बंडल संदेशमध्यस्थ_मूल्य जोडा बिघाड_मूल्य: 호스트에서 --network --pip로 실행하십시오.")
                संचालनप्रणाली.sleep_ms(10)
        डेटा = (विनंती + "\n").encode()
        while डेटा:
            try:
                आयटम_संख्या = संचालनप्रणाली.tcp_write(संचारटोक, डेटा)
                if not आयटम_संख्या:
                    raise ValueError("बंडल विनंती स्थानांतर_मूल्य बिघाड_मूल्य")
                डेटा = डेटा[आयटम_संख्या:]
            except OSError as त्रुटी:
                if त्रुटी.args[0] != 11:
                    raise
                संचालनप्रणाली.sleep_ms(10)
                if संचालनप्रणाली.ticks_ms() - सुरू_करा > 10000:
                    raise ValueError("बंडल विनंती स्थानांतर_मूल्य वेळ_मूल्य 초과")
        प्रवाह_मूल्य = प्रवाह_स्वीकारा(संचारटोक)
        शीर्ष_मूल्य = प्रवाह_मूल्य.नेमके_वाचा(8)
        if शीर्ष_मूल्य[:4] != b"JKP1":
            raise ValueError("बंडल स्थानांतर_मूल्य काम_मूल्य 불일치")
        लांबी_मूल्य = (शीर्ष_मूल्य[4] << 24) | (शीर्ष_मूल्य[5] << 16) | (शीर्ष_मूल्य[6] << 8) | शीर्ष_मूल्य[7]
        if लांबी_मूल्य > 8192:
            raise ValueError("बंडल 명세가 너무 큽니다.")
        विनिर्देश = json.loads(प्रवाह_मूल्य.नेमके_वाचा(लांबी_मूल्य).decode())
        if "error" in विनिर्देश:
            raise ValueError(विनिर्देश["error"])
        if not 1 <= len(विनिर्देश["files"]) <= 16:
            raise ValueError("꾸러미당 स्रोत_ट्री 파일은 1~16개여야 합니다.")
        if sum(प्रविष्टी_मूल्य["size"] for प्रविष्टी_मूल्य in विनिर्देश["files"]) > 65536:
            raise ValueError("बंडल स्रोत_ट्री 합계는 64 KiB 이하여야 합니다.")
        संचिका_नोंदी = {}
        for प्रविष्टी_मूल्य in विनिर्देश["files"]:
            मार्ग = पथ_तपासा(प्रविष्टी_मूल्य["path"])
            if मार्ग in संचिका_नोंदी or not 0 <= प्रविष्टी_मूल्य["size"] <= 16384:
                raise ValueError("중복 मार्ग 또는 फाइल आकार 초과")
            डेटा = प्रवाह_मूल्य.नेमके_वाचा(प्रविष्टी_मूल्य["size"])
            if ओळखठसा_मूल्य(डेटा) != प्रविष्टी_मूल्य["sha256"]:
                raise ValueError("बंडल फाइल SHA-256 불일치")
            # 실행하지 않고 सध्याचे_आयटम MicroPython의 문법으로 먼저 검사한다.
            compile(डेटा.decode("utf-8"), मार्ग, "exec")
            संचिका_नोंदी[मार्ग] = डेटा
            gc.collect()
        return विनिर्देश, संचिका_नोंदी
    finally:
        संचालनप्रणाली.udp_close(संचारटोक)


def स्थापित_करा_मूल्य(विनंती, पोर्ट_नंबर):
    print("बंडल डाउनलोड:", विनंती)
    विनिर्देश, संचिका_नोंदी = डाउनलोड(विनंती, पोर्ट_नंबर)
    प्रविष्टी_यादी = यादी_वाचा()
    नाव = विनिर्देश["name"]
    if नाव in प्रविष्टी_यादी:
        if प्रविष्टी_यादी[नाव]["version"] == विनिर्देश["version"]:
            for मार्ग, ओळखठसा_डेटा in प्रविष्टी_यादी[नाव]["files"].items():
                if संचालनप्रणाली.path_kind(मार्ग) != 1 or ओळखठसा_मूल्य(संचालनप्रणाली.read(मार्ग)) != ओळखठसा_डेटा:
                    raise ValueError("설치된 बंडल 파일이 달라졌습니다: " + मार्ग)
            print("이미 설치됨:", नाव, विनिर्देश["version"])
            return
        raise ValueError("다른 버전이 있습니다. pip uninstall로 제거한 मागे_मूल्य 설치하십시오.")
    for मार्ग in संचिका_नोंदी:
        if संचालनप्रणाली.path_kind(मार्ग):
            raise ValueError("기존 파일을 덮어쓰지 않습니다: " + मार्ग)
    प्रविष्टी_यादी[नाव] = {"version": विनिर्देश["version"], "files": {मार्ग: ओळखठसा_मूल्य(डेटा) for मार्ग, डेटा in संचिका_नोंदी.items()}}
    नवे_यादी = json.dumps(प्रविष्टी_यादी).encode()
    if len(नवे_यादी) > 16384:
        raise ValueError("बंडल प्रविष्टी_यादी आकार 초과")
    मागील_यादी = संचालनप्रणाली.read(यादी_पथ) if संचालनप्रणाली.path_kind(यादी_पथ) else None
    निर्मित_संचिका = []
    निर्मित_निर्देशिका = []
    try:
        for मार्ग, डेटा in संचिका_नोंदी.items():
            भाग = मार्ग.split("/")
            for संख्या in range(2, len(भाग)):
                निर्देशिका_मूल्य = "/".join(भाग[:संख्या])
                प्रकार_मूल्य = संचालनप्रणाली.path_kind(निर्देशिका_मूल्य)
                if प्रकार_मूल्य == 0:
                    संचालनप्रणाली.mkdir(निर्देशिका_मूल्य)
                    निर्मित_निर्देशिका.append(निर्देशिका_मूल्य)
                elif प्रकार_मूल्य != 2:
                    raise ValueError("निर्देशिका_मूल्य 경로에 파일이 있습니다: " + निर्देशिका_मूल्य)
            निर्मित_संचिका.append(मार्ग)
            लॉग_लिहा(मार्ग, डेटा)
        लॉग_लिहा(यादी_पथ, नवे_यादी)
    except Exception:
        for मार्ग in निर्मित_संचिका:
            if संचालनप्रणाली.path_kind(मार्ग):
                संचालनप्रणाली.remove(मार्ग)
        for निर्देशिका_मूल्य in reversed(निर्मित_निर्देशिका):
            संचालनप्रणाली.rmdir(निर्देशिका_मूल्य)
        if मागील_यादी is not None:
            लॉग_लिहा(यादी_पथ, मागील_यादी)
        elif संचालनप्रणाली.path_kind(यादी_पथ):
            संचालनप्रणाली.remove(यादी_पथ)
        raise
    print("स्थापित_करा_मूल्य आहे_पूर्ण:", नाव, विनिर्देश["version"], "→ /lib (RAM)")


def प्रविष्टी_काढणे(नाव):
    प्रविष्टी_यादी = यादी_वाचा()
    if नाव not in प्रविष्टी_यादी:
        raise ValueError("설치되지 않은 꾸러미입니다: " + नाव)
    for मार्ग, ओळखठसा_डेटा in प्रविष्टी_यादी[नाव]["files"].items():
        if संचालनप्रणाली.path_kind(मार्ग) != 1 or ओळखठसा_मूल्य(संचालनप्रणाली.read(मार्ग)) != ओळखठसा_डेटा:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + मार्ग)
    for मार्ग in प्रविष्टी_यादी[नाव]["files"]:
        संचालनप्रणाली.remove(मार्ग)
    del प्रविष्टी_यादी[नाव]
    लॉग_लिहा(यादी_पथ, json.dumps(प्रविष्टी_यादी).encode())
    print("प्रविष्टी_काढणे आहे_पूर्ण:", नाव)


def सुरू_करा(बाबी):
    पोर्ट_नंबर = 8027
    if len(बाबी) >= 2 and बाबी[-2] == "--port":
        पोर्ट_नंबर = int(बाबी[-1])
        बाबी = बाबी[:-2]
    if बाबी == ["list"]:
        for नाव, सिस्टम_माहिती in यादी_वाचा().items():
            print(नाव, सिस्टम_माहिती["version"])
    elif len(बाबी) == 2 and बाबी[0] == "install":
        स्थापित_करा_मूल्य(बाबी[1], पोर्ट_नंबर)
    elif len(बाबी) == 2 and बाबी[0] == "uninstall":
        प्रविष्टी_काढणे(बाबी[1])
    elif not बाबी or बाबी in (["--help"], ["--version"]):
        print("jkoros pip 1 / MicroPython स्रोत_ट्री 설치기 (PyPA pip 전체가 아님)")
        print("pip install नाव[==버전] [--port 8027] | pip list | pip uninstall नाव")
        print("होस्ट: साधने/आज्ञा_कार्यवाही_करा.py --network --pip; /lib는 재부팅 때 사라지는 RAM입니다.")
    else:
        raise ValueError("pip --help로 사용법을 확인하십시오.")


if __name__ == "__main__":
    try:
        सुरू_करा(sys.argv[1:])
    except Exception as त्रुटी:
        print("बंडल त्रुटी:", त्रुटी)
        sys.exit(1)
