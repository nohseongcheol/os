#ifndef स्वकीय_पडदा_माहिती_शीर्षलेख
#define स्वकीय_पडदा_माहिती_शीर्षलेख
#include <stdint.h>
/* 초기화가 끝난 वास्तविक_डेटा RGB32 पडदा आकार. 준비되지 않았으면 0이다. */
uintptr_t बोर्ड_पडदा_रुंदी(void);
uintptr_t बोर्ड_पडदा_उंची(void);
/* 0: लपलेले_मूल्य, 1: 화살표, 2: 좌상↔우하, 3: 우상↔좌하. */
void बोर्ड_निर्देशक(int आडवे_स्थान, int अनुलंब_स्थान, unsigned आकृती_मूल्य);
/* 한 번에 32줄을 완성한 मागे_मूल्य, 달라진 화소만 वास्तविक_डेटा 화면에 옮긴다. */
void बोर्ड_तयार_करणे_रेखांकन(volatile uint32_t *डेटा, unsigned रुंदी_विस्तार, unsigned लांबी_मूल्य, unsigned अग्रस्थान_मूल्य);
int बोर्ड_रेखांकन_सीमा(int *आडवे_स्थान, int *अनुलंब_स्थान, int *रुंदी_विस्तार, int *लांबी_मूल्य);
int बोर्ड_प्रारंभ_रेखांकन(int आडवे_स्थान, int अनुलंब_स्थान, int रुंदी_विस्तार, int लांबी_मूल्य);
void बोर्ड_समाप्त_रेखांकन(void);
void बोर्ड_आयत_भरणे(int आडवे_स्थान, int अनुलंब_स्थान, int रुंदी_विस्तार, int लांबी_मूल्य, uint32_t रंग_मूल्य);
/* वास्तविक_डेटा मूल्य_शो 메모리에 기록한 पिक्सेल संख्या. निर्देशक 갱신은 제외한다. */
uint64_t बोर्ड_रेखांकन_संख्या(void);
uint32_t बोर्ड_वाचा_पडदा(unsigned आडवे_स्थान, unsigned अनुलंब_स्थान);
#endif
