uintptr_t बोर्ड_प्रतिमास्मृती_वाचा(uintptr_t आडवे_स्थान,uintptr_t अनुलंब_स्थान){
    return चित्रबिंदू_यादी&&आडवे_स्थान<पडदा_रुंदी&&अनुलंब_स्थान<पडदा_उंची?चित्रबिंदू_यादी[अनुलंब_स्थान*पडदा_ओळ_शब्द_गणना+आडवे_स्थान]:0;
}
void बोर्ड_प्रतिमास्मृती_लिहा(uintptr_t आडवे_स्थान,uintptr_t अनुलंब_स्थान,uintptr_t रंग_मूल्य){
    if(चित्रबिंदू_यादी&&आडवे_स्थान<पडदा_रुंदी&&अनुलंब_स्थान<पडदा_उंची)चित्रबिंदू_यादी[अनुलंब_स्थान*पडदा_ओळ_शब्द_गणना+आडवे_स्थान]=(uint32_t)रंग_मूल्य;
}
void बोर्ड_तयार_करणे_रेखांकन(volatile uint32_t *डेटा,unsigned रुंदी_विस्तार,unsigned लांबी_मूल्य,unsigned अग्रस्थान_मूल्य){
    चित्रबिंदू_यादी=डेटा;पडदा_रुंदी=रुंदी_विस्तार;पडदा_उंची=लांबी_मूल्य;पडदा_ओळ_शब्द_गणना=अग्रस्थान_मूल्य/4;जावारेखाटन_तयार_करणे((int)रुंदी_विस्तार,(int)लांबी_मूल्य);
}
