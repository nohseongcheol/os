int बोर्ड_रेखांकन_सीमा(int *आडवे_स्थान,int *अनुलंब_स्थान,int *रुंदी_विस्तार,int *लांबी_मूल्य){
    if(!जावारेखाटन_क्लिप(*आडवे_स्थान,*अनुलंब_स्थान,*रुंदी_विस्तार,*लांबी_मूल्य))return 0;
    *आडवे_स्थान=जावारेखाटन_क्लिप_मूल्य(0);*अनुलंब_स्थान=जावारेखाटन_क्लिप_मूल्य(1);*रुंदी_विस्तार=जावारेखाटन_क्लिप_मूल्य(2);*लांबी_मूल्य=जावारेखाटन_क्लिप_मूल्य(3);return 1;
}
