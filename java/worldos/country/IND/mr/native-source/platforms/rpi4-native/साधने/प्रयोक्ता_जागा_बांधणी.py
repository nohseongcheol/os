"""독립된 स्वकीय ABI ELF64와 로더 अस्वीकृत_करा_मूल्य चाचण्या 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from पायथन_बांधणी import पायथन_तयार_करा
from जावा_लायब्ररी_बांधणी import जावा_लायब्ररी_तयार_करा
from सी_संकलक_बांधणी import सी_संकलक_तयार_करा


def प्रयोक्ता_जागा_तयार_करा(मूळ_पथ, भांडार_पथ, सी_संकलक, सीप्लसप्लस_संकलक, जोडणीकार_साधन, संग्रह_साधन, कॉन्फिगरेशन_द्व्यंक, आज्ञा_कार्यवाही_करा):
    कॉन्फिगरेशन_द्व्यंक = [सेटिंग्ज_मूल्य for सेटिंग्ज_मूल्य in कॉन्फिगरेशन_द्व्यंक if सेटिंग्ज_मूल्य != '-mgeneral-regs-only']
    पथ_बांधणी = मूळ_पथ / 'build'
    प्रदान = पथ_बांधणी / 'user'
    प्रदान.mkdir(exist_ok=True)
    मूळ_डेटा = मूळ_पथ / 'प्रयोक्ता'
    पॉझिक्स = भांडार_पथ / 'posix-kor/arm64-native'
    समाविष्टकरा_पथ = ['-I', मूळ_डेटा, '-I', पॉझिक्स / 'घोषणाशीर्षे', '-I', प्रदान]
    for संकलक_साधन, अतिरिक्त_प्रदेश, मार्ग, नाव in [
            (सी_संकलक, [], मूळ_डेटा / 'सुरू_करा.S', 'start.o'),
            (सी_संकलक, ['-std=c11'], मूळ_डेटा / 'आज्ञा_कार्यवाही_करा.c', 'runtime.o'),
            (सी_संकलक, ['-std=c11'], पॉझिक्स / 'प्रयोक्ता_ब्रिज.c', 'posix.o'),
            (सीप्लसप्लस_संकलक, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], मूळ_डेटा / 'संचिका_उदाहरण.cpp', 'demo.o'),
            (सीप्लसप्लस_संकलक, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], मूळ_डेटा / 'संचार_उदाहरण.cpp', 'network.o'),
            (सी_संकलक, ['-std=c11'], मूळ_डेटा / 'संरक्षण_चाचणी.c', 'fault.o'),
            (सी_संकलक, ['-std=c11'], मूळ_डेटा / 'संपादक.c', 'vi.o')]:
        आज्ञा_कार्यवाही_करा([संकलक_साधन] + कॉन्फिगरेशन_द्व्यंक + अतिरिक्त_प्रदेश + समाविष्टकरा_पथ + ['-Wall', '-Wextra', '-Werror', '-c', मार्ग, '-o', प्रदान / नाव])
    आज्ञा_कार्यवाही_करा([संग्रह_साधन, 'rcs', पथ_बांधणी / 'libposix-kor-user.a', प्रदान / 'posix.o'])
    for नाव in ('demo', 'fault', 'network', 'vi'):
        आज्ञा_कार्यवाही_करा([जोडणीकार_साधन, '-T', मूळ_डेटा / 'लिंक_लेआउट.ld', '-z', 'max-page-size=4096', '-o', प्रदान / (नाव + '.elf'),
             प्रदान / 'start.o', प्रदान / 'runtime.o', प्रदान / (नाव + '.o'), पथ_बांधणी / 'libposix-kor-user.a'])
    जावा_लायब्ररी_तयार_करा(मूळ_पथ, आज्ञा_कार्यवाही_करा)
    # 기존 स्वकीय Java संकलक/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(पथ_बांधणी)) as कार्यरत_पथ:
        वर्ग_पथ = Path(कार्यरत_पथ)
        आज्ञा_कार्यवाही_करा(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', वर्ग_पथ, '-sourcepath', वर्ग_पथ, '-d', वर्ग_पथ] +
            [डेटा_स्थान for डेटा_स्थान in sorted((भांडार_पथ / 'os/प्रयोक्ता/जावा').glob('*.java')) if डेटा_स्थान.name != 'जावा_मशीन.java'] + sorted((मूळ_डेटा / 'जावा').glob('*.java')))
        आज्ञा_कार्यवाही_करा(['sh', भांडार_पथ / 'compiler/आगाऊ_संबंधित_वेळ.sh', '--entry', 'साधन_प्रविष्टी.सुरू_करा',
             '--profile', 'user', '--heap-words', '1048576', '-o', प्रदान / 'java-tools.c'] + sorted(वर्ग_पथ.glob('*.class')))
    युझलिब = मूळ_पथ / 'vendor/uzlib'
    for मार्ग, नाव in [(प्रदान / 'java-tools.c', 'java-tools.o'), (मूळ_डेटा / 'जावा_ब्रिज.c', 'java-link.o'),
                       (मूळ_डेटा / 'बंडल.c', 'jar.o')] + [(युझलिब / (नाव + '.c'), नाव + '.o') for नाव in ('tinflate', 'crc32', 'adler32')]:
        आज्ञा_कार्यवाही_करा([सी_संकलक] + कॉन्फिगरेशन_द्व्यंक + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', युझलिब] + समाविष्टकरा_पथ + ['-c', मार्ग, '-o', प्रदान / नाव])
    आज्ञा_कार्यवाही_करा([जोडणीकार_साधन, '-T', मूळ_डेटा / 'लिंक_लेआउट.ld', '-z', 'max-page-size=4096', '-o', प्रदान / 'java-tools.elf'] +
        [प्रदान / नाव for नाव in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    पायथन_तयार_करा(मूळ_पथ, सी_संकलक, जोडणीकार_साधन)
    सी_संकलक_तयार_करा(मूळ_पथ, भांडार_पथ, सी_संकलक, जोडणीकार_साधन, कॉन्फिगरेशन_द्व्यंक, आज्ञा_कार्यवाही_करा)
    वैध = (प्रदान / 'demo.elf').read_bytes()
    अनुप्रयोग_शीर्षलेख_ऑफसेट = struct.unpack_from('<Q', वैध, 32)[0]
    शीर्षलेख_यादी = [अनुप्रयोग_शीर्षलेख_ऑफसेट + आयटम_संख्या * 56 for आयटम_संख्या in range(struct.unpack_from('<H', वैध, 56)[0])]
    भारणे = [डेटा_स्थान for डेटा_स्थान in शीर्षलेख_यादी if struct.unpack_from('<I', वैध, डेटा_स्थान)[0] == 1]
    पाठ्य, डेटा = भारणे[:2]
    आज्ञा_पत्ता = struct.unpack_from('<Q', वैध, पाठ्य + 16)[0]
    डेटा_पत्ता = struct.unpack_from('<Q', वैध, डेटा + 16)[0]
    कॉल_द्विमानजोडणी = वैध.index(b'JKOROS\0')
    काम_चाचणी = [('empty', b''), ('short', वैध[:63])]
    सुधारणा = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', आज्ञा_पत्ता + 1), ('data-entry', 24, 'Q', डेटा_पत्ता),
               ('outside-file', पाठ्य + 32, 'Q', len(वैध) + 1), ('short-memory', पाठ्य + 40, 'Q', 1),
               ('kernel-address', पाठ्य + 16, 'Q', 0x80000), ('memory-overflow', पाठ्य + 40, 'Q', 2**64 - 1),
               ('writable-code', पाठ्य + 4, 'I', 7), ('missing-abi', कॉल_द्विमानजोडणी, 'B', ord('X')),
               ('wrong-abi', कॉल_द्विमानजोडणी + 8, 'I', 2), ('dynamic', पाठ्य, 'I', 2),
               ('unaligned-load', पाठ्य + 16, 'Q', आज्ञा_पत्ता + 8),
               ('overlap', डेटा + 16, 'Q', आज्ञा_पत्ता)]
    for नाव, ऑफसेट_मूल्य, स्वरूप_932e03c8, मूल्य in सुधारणा:
        बदललेले = bytearray(वैध); struct.pack_into('<' + स्वरूप_932e03c8, बदललेले, ऑफसेट_मूल्य, मूल्य)
        काम_चाचणी.append((नाव, bytes(बदललेले)))
    द्विमानसंच = [(नाव.replace('-', '_'), प्रदान / (नाव + '.elf')) for नाव in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for लुकअप_अनुक्रमणिका, (नाव, पेलोड_डेटा) in enumerate(काम_चाचणी):
        मार्ग = प्रदान / ('invalid-{}.elf'.format(नाव)); मार्ग.write_bytes(पेलोड_डेटा)
        द्विमानसंच.append(('invalid_{}'.format(लुकअप_अनुक्रमणिका), मार्ग))
    यंत्रजोडणी, शीर्षलेख_मूल्य = ['.section .rodata.user,"a"'], []
    मापे = {}
    for नाव, मार्ग in द्विमानसंच:
        चिन्ह_मूल्य = 'user_blob_' + नाव
        मापे[नाव] = मार्ग.stat().st_size
        # 생성한 समकक्ष_मूल्य 경로만 넣어 프로젝트 경로의 공백/कोट 영향을 피한다.
        यंत्रजोडणी += ['.balign 16', '.global ' + चिन्ह_मूल्य, चिन्ह_मूल्य + ':', '.incbin "{}"'.format(मार्ग.relative_to(मूळ_पथ))]
        शीर्षलेख_मूल्य.append('extern const unsigned char {}[];'.format(चिन्ह_मूल्य))
    यंत्रजोडणी.append('.section .note.GNU-stack,"",%progbits')
    शीर्षलेख_मूल्य += ['static const अनुप्रयोग निष्पादनीय_नोंदी[] = {', '{user_blob_demo, %d, 0},' % मापे['demo']]
    शीर्षलेख_मूल्य += ['{user_blob_fault, %d, %d},' % (मापे['fault'], अग्रेषित_मूल्य) for अग्रेषित_मूल्य in range(8)]
    शीर्षलेख_मूल्य += ['{user_blob_network, %d, 0},' % मापे['network']]
    शीर्षलेख_मूल्य += ['{user_blob_java_tools, %d, %d},' % (मापे['java_tools'], पद्धत_मोड) for पद्धत_मोड in (0, 1)]
    शीर्षलेख_मूल्य += ['{user_blob_python, %d, 0},' % मापे['python'], '{user_blob_vi, %d, 0},' % मापे['vi']]
    शीर्षलेख_मूल्य += ['{user_blob_java_tools, %d, 2},' % मापे['java_tools']]
    शीर्षलेख_मूल्य += ['{user_blob_cc, %d, 0},' % मापे['cc']]
    शीर्षलेख_मूल्य += ['{user_blob_cc, %d, 1},' % मापे['cc']]
    शीर्षलेख_मूल्य += ['};', 'static const अनुप्रयोग अवैध_निष्पादनीयसंचिका[] = {']
    शीर्षलेख_मूल्य += ['{user_blob_invalid_%d, %d, 0},' % (क्रमांक_अनुक्रमणिका, len(पेलोड_डेटा)) for क्रमांक_अनुक्रमणिका, (_, पेलोड_डेटा) in enumerate(काम_चाचणी)]
    शीर्षलेख_मूल्य += ['};']
    (पथ_बांधणी / 'programs.S').write_text('\n'.join(यंत्रजोडणी) + '\n')
    (पथ_बांधणी / 'programs.h').write_text('\n'.join(शीर्षलेख_मूल्य) + '\n')
    (प्रदान / 'invalid-cases.txt').write_text('\n'.join(नाव for नाव, _ in काम_चाचणी) + '\n')
    आज्ञा_कार्यवाही_करा([सी_संकलक] + कॉन्फिगरेशन_द्व्यंक + ['-c', पथ_बांधणी / 'programs.S', '-o', पथ_बांधणी / 'programs.o'])
