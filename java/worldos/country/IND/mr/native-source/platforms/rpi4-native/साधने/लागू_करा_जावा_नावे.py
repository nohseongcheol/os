#!/usr/bin/env python3
"""स्वकीय Java स्थानिक_संधी 이름을 바꾼다. स्ट्रींग_मूल्य·주석·बाह्य_मूल्य 멤버 이름은 보존한다."""
import json
import re
from pathlib import Path

प्रोजेक्ट_मूळ = Path(__file__).resolve().parents[1]
प्रतिचित्रण_मूल्य = json.loads((प्रोजेक्ट_मूळ / 'नामकरण/जावा_नावे.json').read_text())
खंड_अभिव्यक्ती = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[\w$]+|[^\w\s]', re.UNICODE)
लॉग_नोंद = []
for निर्देशिका_मूल्य in ('स्रोत', 'प्रयोक्ता/जावा', 'स्वकीय_जावा'):
    for मार्ग in sorted((प्रोजेक्ट_मूळ / निर्देशिका_मूल्य).rglob('*.java')):
        स्रोत = मार्ग.read_text()
        खंड_यादी = list(खंड_अभिव्यक्ती.finditer(स्रोत))
        वापरलेले_नाव = {खंड_प्रविष्टी.group() for खंड_प्रविष्टी in खंड_यादी if re.search('[पहिले_संकार्य-힣]', खंड_प्रविष्टी.group())}
        संचिका_प्रतिचित्रण = {}
        for मागील_आयटम, नंतर_मूल्य_ee1d8655 in प्रतिचित्रण_मूल्य.items():
            # A pre-existing Korean binding must never be shadowed by renaming.
            नवे_नाव = नंतर_मूल्य_ee1d8655
            while नवे_नाव in वापरलेले_नाव: नवे_नाव = 'स्थानिक_संधी' + नवे_नाव
            संचिका_प्रतिचित्रण[मागील_आयटम] = नवे_नाव
        सुधारा_मूल्य = []
        मागील_खंड = ''
        for खंड_प्रविष्टी in खंड_यादी:
            शाब्दिक_शब्द = खंड_प्रविष्टी.group()
            if शाब्दिक_शब्द.startswith(('//', '/*', '"', "'")): continue
            if शाब्दिक_शब्द in संचिका_प्रतिचित्रण and मागील_खंड != '.':
                सुधारा_मूल्य.append((खंड_प्रविष्टी.start(), खंड_प्रविष्टी.end(), संचिका_प्रतिचित्रण[शाब्दिक_शब्द]))
                लॉग_नोंद.append((str(मार्ग.relative_to(प्रोजेक्ट_मूळ)), शाब्दिक_शब्द, संचिका_प्रतिचित्रण[शाब्दिक_शब्द]))
            मागील_खंड = शाब्दिक_शब्द
        for सुरू_करा, शेवट, नवे_नाव in reversed(सुधारा_मूल्य): स्रोत = स्रोत[:सुरू_करा] + नवे_नाव + स्रोत[शेवट:]
        if सुधारा_मूल्य: मार्ग.write_text(स्रोत)
(प्रोजेक्ट_मूळ / 'नामकरण/जावा_नाव_प्रतिचित्रण.tsv').write_text('फाइल\t이전\t이후\n' + ''.join('\t'.join(प्रविष्टी_मूल्य)+'\n' for प्रविष्टी_मूल्य in sorted(set(लॉग_नोंद))))
print('Java नाव संदर्भ बदल_करा_मूल्य:', len(लॉग_नोंद))
