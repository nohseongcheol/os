#!/usr/bin/env python3
"""घोषणा 고유번호와 UTF-8 बाइट_मूल्य 위치로 स्वकीय C 이름을 옮기는 일회성 이행 साधने.

बाह्य_मूल्य 구조체의 멤버, स्ट्रींग_मूल्य, C 표준 फलन_मूल्य, अनुकूलन 규약은 보존한다.
입력은 बदल_करा_मूल्य आधी_मूल्य 소스에 대한 विश्लेषणकरा_सी_नावे.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

प्रोजेक्ट_मूळ = Path(__file__).resolve().parents[1]

def आज्ञा_कार्यवाही_करा():
    विश्लेषणकरा_मूल्य = json.loads((प्रोजेक्ट_मूळ/'build/한국어화/시언어분석.json').read_text())
    if विश्लेषणकरा_मूल्य['त्रुटी']: raise SystemExit('विश्लेषणकरा_मूल्य 오류를 먼저 해결해야 합니다.')
    नाव_सारणी = json.loads((प्रोजेक्ट_मूळ/'नामकरण/सी_नावे.json').read_text())
    प्रमाणित_व्याख्या = set(json.loads((प्रोजेक्ट_मूळ/'नामकरण/प्रमाणित_नावे.json').read_text()))
    घोषणा_सारणी = विश्लेषणकरा_मूल्य['घोषणा']
    घोषणा_कडे_बदलावे = {अद्वितीय_मूल्य:नाव_सारणी[प्रविष्टी_मूल्य['नाव']] for अद्वितीय_मूल्य,प्रविष्टी_मूल्य in घोषणा_सारणी.items()
                if प्रविष्टी_मूल्य['नाव'] in नाव_सारणी and प्रविष्टी_मूल्य['नाव'] not in प्रमाणित_व्याख्या}
    कनेक्शन_सारणी = {प्रविष्टी_मूल्य['नाव']:नाव_सारणी[प्रविष्टी_मूल्य['नाव']] for प्रविष्टी_मूल्य in घोषणा_सारणी.values()
              if प्रविष्टी_मूल्य.get('जोडा')==4 and प्रविष्टी_मूल्य['प्रकार_मूल्य'] in (8,9)
              and प्रविष्टी_मूल्य['नाव'] in नाव_सारणी and प्रविष्टी_मूल्य['नाव'] not in प्रमाणित_व्याख्या}
    # तयार_करा AOT C·어셈블리·공개 SDK가 공유하는 바이너리 जोडा 이름만 유지한다.
    शीर्ष_मूल्य = ['/* मराठी स्रोत_ट्री 이름과 기존 मशीन जोडा काम_मूल्य. 자동 तयार_करा: नामकरण/सी_नावे.json */',
           '#ifndef स्वकीय_मशीन_लिंक_नावे_शीर्षलेख', '#define स्वकीय_मशीन_लिंक_नावे_शीर्षलेख']
    शीर्ष_मूल्य += ['#define '+नवे_नाव+' '+जुने_नाव for जुने_नाव,नवे_नाव in sorted(कनेक्शन_सारणी.items())]
    शीर्ष_मूल्य += ['#endif','']
    (प्रोजेक्ट_मूळ/'नामकरण/मशीन_लिंक_नावे.h').write_text('\n'.join(शीर्ष_मूल्य))
    बदल_यादी = defaultdict(dict)
    for फाइल,ऑफसेट_मूल्य,नाव,अद्वितीय_मूल्य in विश्लेषणकरा_मूल्य['संदर्भ']:
        if अद्वितीय_मूल्य in घोषणा_कडे_बदलावे:
            बदल_यादी[फाइल][ऑफसेट_मूल्य] = (नाव,घोषणा_कडे_बदलावे[अद्वितीय_मूल्य])
    लॉग_नोंद = ['फाइल\t원래바이트위치\t이전이름\t한국어이름']
    दुर्लक्ष_करा_मूल्य = []
    for फाइल,बदल_करा_मूल्य in बदल_यादी.items():
        मार्ग = Path(फाइल); मूळ = मार्ग.read_bytes(); डेटा = मूळ
        for ऑफसेट_मूल्य,(जुने_नाव,नवे_नाव) in sorted(बदल_करा_मूल्य.items(),reverse=True):
            शेवट = ऑफसेट_मूल्य+len(जुने_नाव.encode())
            if मूळ[ऑफसेट_मूल्य:शेवट] != जुने_नाव.encode():
                दुर्लक्ष_करा_मूल्य.append((str(मार्ग.relative_to(प्रोजेक्ट_मूळ)),ऑफसेट_मूल्य,जुने_नाव));continue
            डेटा = डेटा[:ऑफसेट_मूल्य]+नवे_नाव.encode()+डेटा[शेवट:]
            लॉग_नोंद.append('{}\t{}\t{}\t{}'.format(मार्ग.relative_to(प्रोजेक्ट_मूळ),ऑफसेट_मूल्य,जुने_नाव,नवे_नाव))
        मार्ग.write_bytes(डेटा)
    # पूर्वप्रक्रियाकरा_स्रोत 매개변수는 AST의 선언으로 나타나지 않는다. पूर्वप्रक्रियाकरा_स्रोत 줄만 보완한다.
    शाब्दिक_शब्द = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    मॅक्रो_मूल्य = {प्रविष्टी_मूल्य['नाव']:नाव_सारणी[प्रविष्टी_मूल्य['नाव']] for प्रविष्टी_मूल्य in घोषणा_सारणी.values()
              if प्रविष्टी_मूल्य['प्रकार_मूल्य']==501 and प्रविष्टी_मूल्य['नाव'] in नाव_सारणी and प्रविष्टी_मूल्य['नाव'] not in प्रमाणित_व्याख्या}
    for मार्ग in sorted({Path(प्रविष्टी_मूल्य['फाइल']) for प्रविष्टी_मूल्य in घोषणा_सारणी.values()}):
        ओळ_यादी = मार्ग.read_text().splitlines(True); आहे_पुढीलक्रम = False
        for अनुक्रमणिका,ओळ in enumerate(ओळ_यादी):
            पूर्वप्रक्रियाकरा_स्रोत = आहे_पुढीलक्रम or bool(re.match(r'\s*#',ओळ))
            आहे_पुढीलक्रम = पूर्वप्रक्रियाकरा_स्रोत and ओळ.rstrip().endswith('\\')
            if पूर्वप्रक्रियाकरा_स्रोत:
                लुकअप_सारणी = नाव_सारणी if re.match(r'\s*#\s*define\b',ओळ) or आहे_पुढीलक्रम else मॅक्रो_मूल्य
                ओळ_यादी[अनुक्रमणिका] = शाब्दिक_शब्द.sub(lambda आहे_जुळलेले: लुकअप_सारणी.get(आहे_जुळलेले[0],आहे_जुळलेले[0]) if आहे_जुळलेले[0] not in प्रमाणित_व्याख्या else आहे_जुळलेले[0],ओळ)
        मार्ग.write_text(''.join(ओळ_यादी))
    # 각 स्वकीय भाषांतर_करा_स्रोत 단위에만 연결표를 넣는다. बाह्य_मूल्य 배포본에는 전파하지 않는다.
    for मार्ग in sorted({Path(प्रविष्टी_मूल्य['फाइल']) for प्रविष्टी_मूल्य in घोषणा_सारणी.values()}):
        if मार्ग.suffix not in ('.c','.cpp'):continue
        समकक्ष_मूल्य = '../' * len(मार्ग.relative_to(प्रोजेक्ट_मूळ).parts[:-1]) + 'नामकरण/मशीन_लिंक_नावे.h'
        मार्ग.write_text('#include "'+समकक्ष_मूल्य+'"\n'+मार्ग.read_text())
    (प्रोजेक्ट_मूळ/'नामकरण/सी_नाव_प्रतिचित्रण.tsv').write_text('\n'.join(लॉग_नोंद)+'\n')
    (प्रोजेक्ट_मूळ/'build/한국어화/전처리참조.json').write_text(json.dumps(दुर्लक्ष_करा_मूल्य,ensure_ascii=False,indent=2)+'\n')
    print('बदल_करा_मूल्य',len(लॉग_नोंद)-1,'पूर्वप्रक्रियाकरा_स्रोत 재검토',len(दुर्लक्ष_करा_मूल्य),'मशीन जोडा',len(कनेक्शन_सारणी))

if __name__=='__main__': आज्ञा_कार्यवाही_करा()
