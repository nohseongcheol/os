"""Two-set Hangul composition for the native VNC-to-UART input bridge.

The pending character is visible in the guest editor. Replacing it uses that
editor's UTF-8 Backspace, so commit before cursor motion, shortcuts or a click.
No host input-method daemon or third-party Python package is required.
"""

प्रारंभिक_हांगुलवर्णघटक_सारणी = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
मध्यवर्ती_हांगुलवर्णघटक_सारणी = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
अंतिम_हांगुलवर्णघटक_सारणी = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'
कळ_लेआउट = dict(zip('rRseEfaqQtTdwWczxvgkoiOjpuPhynbml',
                'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎㅏㅐㅑㅒㅓㅔㅕㅖㅗㅛㅜㅠㅡㅣ'))
संयुक्त_मध्यवर्ती_हांगुलवर्णघटक = {('ㅗ','ㅏ'):'ㅘ',('ㅗ','ㅐ'):'ㅙ',('ㅗ','ㅣ'):'ㅚ',
          ('ㅜ','ㅓ'):'ㅝ',('ㅜ','ㅔ'):'ㅞ',('ㅜ','ㅣ'):'ㅟ',('ㅡ','ㅣ'):'ㅢ'}
संयुक्त_अंतिम_हांगुलवर्णघटक = {('ㄱ','ㅅ'):'ㄳ',('ㄴ','ㅈ'):'ㄵ',('ㄴ','ㅎ'):'ㄶ',
          ('ㄹ','ㄱ'):'ㄺ',('ㄹ','ㅁ'):'ㄻ',('ㄹ','ㅂ'):'ㄼ',('ㄹ','ㅅ'):'ㄽ',
          ('ㄹ','ㅌ'):'ㄾ',('ㄹ','ㅍ'):'ㄿ',('ㄹ','ㅎ'):'ㅀ',('ㅂ','ㅅ'):'ㅄ'}
विभाजन_अंतिम_हांगुलवर्णघटक = {मूल्य: एक_जोड for एक_जोड,मूल्य in संयुक्त_अंतिम_हांगुलवर्णघटक.items()}


class रचना_करा_हांगुल:
    def __init__(स्वतः, पाठवा):
        स्वतः.पाठवा = पाठवा
        स्वतः.स्थिरकरा_संयोजन()

    def स्थिरकरा_संयोजन(स्वतः):
        स्वतः.राज्य_संहिता = ('','','')
        स्वतः.इतिहास = []

    def पाठ्य(स्वतः):
        प्रारंभिक_हांगुलवर्णघटक,मध्यवर्ती_हांगुलवर्णघटक,अंतिम_हांगुलवर्णघटक = स्वतः.राज्य_संहिता
        if प्रारंभिक_हांगुलवर्णघटक and मध्यवर्ती_हांगुलवर्णघटक:
            return chr(0xac00 + (प्रारंभिक_हांगुलवर्णघटक_सारणी.index(प्रारंभिक_हांगुलवर्णघटक)*21 + मध्यवर्ती_हांगुलवर्णघटक_सारणी.index(मध्यवर्ती_हांगुलवर्णघटक))*28
                       + (अंतिम_हांगुलवर्णघटक_सारणी.index(अंतिम_हांगुलवर्णघटक) if अंतिम_हांगुलवर्णघटक else 0))
        return प्रारंभिक_हांगुलवर्णघटक or मध्यवर्ती_हांगुलवर्णघटक

    def मागीलवर्णपुसा(स्वतः):
        if not स्वतः.इतिहास:
            return False
        स्वतः.राज्य_संहिता = स्वतः.इतिहास.pop()
        स्वतः.पाठवा(b'\x7f' + स्वतः.पाठ्य().encode('utf-8'))
        return True

    def फीड_कळ(स्वतः, दाबलेले_मूल्य):
        वर्ण_डेटा = कळ_लेआउट.get(दाबलेले_मूल्य, कळ_लेआउट.get(दाबलेले_मूल्य.lower()))
        if वर्ण_डेटा is None:
            return False
        मागील_आयटम = स्वतः.पाठ्य()
        प्रारंभिक_हांगुलवर्णघटक,मध्यवर्ती_हांगुलवर्णघटक,अंतिम_हांगुलवर्णघटक = स्वतः.राज्य_संहिता
        इतिहास = स्वतः.इतिहास + [स्वतः.राज्य_संहिता]
        स्थिरकेलेले = ''
        if वर्ण_डेटा in प्रारंभिक_हांगुलवर्णघटक_सारणी:
            if प्रारंभिक_हांगुलवर्णघटक and मध्यवर्ती_हांगुलवर्णघटक and not अंतिम_हांगुलवर्णघटक and वर्ण_डेटा in अंतिम_हांगुलवर्णघटक_सारणी:
                अंतिम_हांगुलवर्णघटक = वर्ण_डेटा
            elif अंतिम_हांगुलवर्णघटक and (अंतिम_हांगुलवर्णघटक,वर्ण_डेटा) in संयुक्त_अंतिम_हांगुलवर्णघटक:
                अंतिम_हांगुलवर्णघटक = संयुक्त_अंतिम_हांगुलवर्णघटक[अंतिम_हांगुलवर्णघटक,वर्ण_डेटा]
            else:
                स्थिरकेलेले = मागील_आयटम
                प्रारंभिक_हांगुलवर्णघटक,मध्यवर्ती_हांगुलवर्णघटक,अंतिम_हांगुलवर्णघटक = वर्ण_डेटा,'',''
                इतिहास = [('','','')]
        elif अंतिम_हांगुलवर्णघटक:
            डावे_बाजू,उजवे = विभाजन_अंतिम_हांगुलवर्णघटक.get(अंतिम_हांगुलवर्णघटक, ('',अंतिम_हांगुलवर्णघटक))
            स्वतः.राज्य_संहिता = प्रारंभिक_हांगुलवर्णघटक,मध्यवर्ती_हांगुलवर्णघटक,डावे_बाजू
            स्थिरकेलेले = स्वतः.पाठ्य()
            प्रारंभिक_हांगुलवर्णघटक,मध्यवर्ती_हांगुलवर्णघटक,अंतिम_हांगुलवर्णघटक = उजवे,वर्ण_डेटा,''
            इतिहास = [('','',''),(उजवे,'','')]
        elif मध्यवर्ती_हांगुलवर्णघटक:
            if (मध्यवर्ती_हांगुलवर्णघटक,वर्ण_डेटा) in संयुक्त_मध्यवर्ती_हांगुलवर्णघटक:
                मध्यवर्ती_हांगुलवर्णघटक = संयुक्त_मध्यवर्ती_हांगुलवर्णघटक[मध्यवर्ती_हांगुलवर्णघटक,वर्ण_डेटा]
            else:
                स्थिरकेलेले = मागील_आयटम
                प्रारंभिक_हांगुलवर्णघटक,मध्यवर्ती_हांगुलवर्णघटक,अंतिम_हांगुलवर्णघटक = '',वर्ण_डेटा,''
                इतिहास = [('','','')]
        else:
            मध्यवर्ती_हांगुलवर्णघटक = वर्ण_डेटा
        स्वतः.राज्य_संहिता = प्रारंभिक_हांगुलवर्णघटक,मध्यवर्ती_हांगुलवर्णघटक,अंतिम_हांगुलवर्णघटक
        स्वतः.इतिहास = इतिहास
        स्वतः.पाठवा((b'\x7f' if मागील_आयटम else b'') + (स्थिरकेलेले+स्वतः.पाठ्य()).encode('utf-8'))
        return True
