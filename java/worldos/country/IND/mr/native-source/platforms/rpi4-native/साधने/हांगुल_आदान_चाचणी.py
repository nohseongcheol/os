#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from डेस्कटॉप_दृश्य import कीबोर्ड


class हांगुल_आदान_चाचणी(unittest.TestCase):
    def setUp(स्वतः):
        स्वतः.मजकूर_बफर = ''
        def पाठवा(डेटा):
            for वर्ण_डेटा in डेटा.decode('utf-8'):
                if वर्ण_डेटा == '\x7f': स्वतः.मजकूर_बफर = स्वतः.मजकूर_बफर[:-1]
                else: स्वतः.मजकूर_बफर += वर्ण_डेटा
        स्वतः.कीबोर्ड_प्रविष्टी = कीबोर्ड(पाठवा)

    def दाबा_कळ(स्वतः, चिन्ह_मूल्य):
        स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(True, चिन्ह_मूल्य)
        स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(False, चिन्ह_मूल्य)

    def टाइप_करा_वर्गवारी(स्वतः, दाबलेले_कळा):
        for दाबलेले_मूल्य in दाबलेले_कळा: स्वतः.दाबा_कळ(ord(दाबलेले_मूल्य))

    def शब्द_चाचणी(स्वतः):
        for दाबलेले_कळा,अपेक्षित in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with स्वतः.subTest(दाबलेले_कळा=दाबलेले_कळा):
                स्वतः.setUp(); स्वतः.दाबा_कळ(0xffc6); स्वतः.टाइप_करा_वर्गवारी(दाबलेले_कळा)
                स्वतः.assertEqual(स्वतः.मजकूर_बफर, अपेक्षित)

    def मागीलवर्णपुसा_चाचणी(स्वतः):
        स्वतः.दाबा_कळ(0xff31); स्वतः.टाइप_करा_वर्गवारी('dlfr')
        स्वतः.assertEqual(स्वतः.मजकूर_बफर,'읽')
        for अपेक्षित in ('일','이','ㅇ',''):
            स्वतः.दाबा_कळ(0xff08); स्वतः.assertEqual(स्वतः.मजकूर_बफर,अपेक्षित)
        स्वतः.टाइप_करा_वर्गवारी('gksk'); स्वतः.assertEqual(स्वतः.मजकूर_बफर,'एक_मूल्य')
        स्वतः.दाबा_कळ(0xff08); स्वतः.assertEqual(स्वतः.मजकूर_बफर,'하ㄴ')

    def पद्धती_आवर्तन_आणि_स्थिरकरा_चाचणी(स्वतः):
        स्वतः.टाइप_करा_वर्गवारी('echo ')
        स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(True,0xffe1)
        स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(True,32); स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(True,32)
        स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(False,32); स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(False,0xffe1)
        स्वतः.assertTrue(स्वतः.कीबोर्ड_प्रविष्टी.कोरियन)
        स्वतः.टाइप_करा_वर्गवारी('gksrmf'); स्वतः.दाबा_कळ(0xff31); स्वतः.टाइप_करा_वर्गवारी(' English')
        स्वतः.assertEqual(स्वतः.मजकूर_बफर,'echo 한글 English')
        स्वतः.assertFalse(स्वतः.कीबोर्ड_प्रविष्टी.कोरियन)
        स्वतः.दाबा_कळ(0xffc6); स्वतः.टाइप_करा_वर्गवारी('rk'); स्वतः.दाबा_कळ(0xff51)
        स्वतः.टाइप_करा_वर्गवारी('sk'); स्वतः.assertTrue(स्वतः.मजकूर_बफर.endswith('पहिले_संकार्य\x1b[D나'))

    def चिकटवा_आणि_युनिकोड_चाचणी(स्वतः):
        स्वतः.दाबा_कळ(0xffc6); स्वतः.टाइप_करा_वर्गवारी('rk')
        स्वतः.कीबोर्ड_प्रविष्टी.क्लिपबोर्ड_मूल्य='चिकटवा_मूल्य'.encode()
        स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(True,0xffe3); स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(True,0xffe1)
        स्वतः.दाबा_कळ(ord('v'))
        स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(False,0xffe1); स्वतः.कीबोर्ड_प्रविष्टी.दाबलेले_मूल्य(False,0xffe3)
        स्वतः.दाबा_कळ(0x0100d55c); स्वतः.टाइप_करा_वर्गवारी('sk')
        स्वतः.assertEqual(स्वतः.मजकूर_बफर,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
