    static int अंक_मूल्य(int वर्ण_मूल्य) { return वर्ण_मूल्य <= '9' ? वर्ण_मूल्य - '0' : वर्ण_मूल्य - 'A' + 10; }
    static void पाठ्य(int आडवे_स्थान, int अनुलंब_स्थान, String सामुग्री_मूल्य, int रंग_मूल्य) {
        for (int वर्ण_मूल्य = 0; वर्ण_मूल्य < सामुग्री_मूल्य.length(); वर्ण_मूल्य++) {
            int सापडलेले_मूल्य = -1;
            for (int उमेदवार = 0; उमेदवार < वर्ण_मूल्ये.length(); उमेदवार++) if (वर्ण_मूल्ये.charAt(उमेदवार) == सामुग्री_मूल्य.charAt(वर्ण_मूल्य)) सापडलेले_मूल्य = उमेदवार;
            if (सापडलेले_मूल्य < 0) continue;
            for (int ओळ_मूल्य = 0; ओळ_मूल्य < 7; ओळ_मूल्य++) {
                int जागा = सापडलेले_मूल्य * 14 + ओळ_मूल्य * 2;
                int बिट_मूल्य = अंक_मूल्य(आकार_यादी.charAt(जागा)) * 16 + अंक_मूल्य(आकार_यादी.charAt(जागा + 1));
                for (int स्तंभ_मूल्य = 0; स्तंभ_मूल्य < 5; स्तंभ_मूल्य++) if ((बिट_मूल्य & (16 >> स्तंभ_मूल्य)) != 0)
                    गाभा.आयत(आडवे_स्थान + वर्ण_मूल्य * 12 + स्तंभ_मूल्य * 2, अनुलंब_स्थान + ओळ_मूल्य * 2, 2, 2, रंग_मूल्य);
            }
        }
    }
    static void पेंट_पडदा(int निवड_मूल्य, String राज्य_मूल्य) {
        गाभा.आयत(0, 0, बोर्ड.पडदा_रुंदी(), बोर्ड.पडदा_उंची(), 0x302018);
        गाभा.आयत(32, 24, 576, 432, 0xefe8e2);
        गाभा.आयत(32, 24, 576, 48, 0x905020);
        पाठ्य(52, 40, "JKOROS PROGRAMS", 0xffffff);
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 5; अनुक्रमणिका++) {
            गाभा.आयत(64, 112 + अनुक्रमणिका * 52, 512, 40, अनुक्रमणिका == निवड_मूल्य ? 0xd0a040 : 0xd8d0c8);
            पाठ्य(84, 128 + अनुक्रमणिका * 52, अनुक्रमणिका == 0 ? "RUN C++ FILE PROGRAM" : अनुक्रमणिका == 1 ? "RUN UDP LOOPBACK" : अनुक्रमणिका == 2 ? "COMPILE AND RUN JAVA" : अनुक्रमणिका == 3 ? "RUN MICROPYTHON" : "OPEN TERMINAL", 0x201810);
        }
        पाठ्य(68, 384, राज्य_मूल्य, 0x205020);
        पाठ्य(52, 420, "TAB SELECT  ENTER RUN  Q EXIT", 0x302018);
    }
    public static void आज्ञा_कार्यवाही_करा() {
        if (बोर्ड.तयार_करणे_पडदा() == 0) { टर्मिनल_आदानप्रदान.लेखन("GUI unavailable\n"); return; }
        int निवड_मूल्य = 0;
        String राज्य_मूल्य = "READY";
        boolean मागील_ओळ = आज्ञा_अर्थविश्लेषक.मागील_ओळ;
        पेंट_पडदा(निवड_मूल्य, राज्य_मूल्य);
        टर्मिनल_आदानप्रदान.लेखन("GUI READY: UART TAB selects, ENTER runs, Q exits\n");
        while (true) {
            int आदान_मूल्य = बोर्ड.अनुक्रमिक_वाचा();
            if (आदान_मूल्य < 0) { बोर्ड.निलंबित_करा_प्रोसेसर(); continue; }
            if (आदान_मूल्य == 10 && मागील_ओळ) { मागील_ओळ = false; continue; }
            मागील_ओळ = आदान_मूल्य == 13;
            if (आदान_मूल्य >= '1' && आदान_मूल्य <= '5') { निवड_मूल्य = आदान_मूल्य - '1'; आदान_मूल्य = 13; }
            if (आदान_मूल्य == 't' || आदान_मूल्य == 'T') { आज्ञा_अर्थविश्लेषक.टर्मिनल(false); return; }
            if (आदान_मूल्य == 'q' || आदान_मूल्य == 'Q' || आदान_मूल्य == 27) break;
            if (आदान_मूल्य == 9 || आदान_मूल्य == 'j') {
                निवड_मूल्य = (निवड_मूल्य + 1) % 5; पेंट_पडदा(निवड_मूल्य, राज्य_मूल्य); टर्मिनल_आदानप्रदान.लेखन("GUI FOCUS "); टर्मिनल_आदानप्रदान.संख्या(निवड_मूल्य); टर्मिनल_आदानप्रदान.वर्ण(10);
            } else if (आदान_मूल्य == 13 || आदान_मूल्य == 10) {
                if (निवड_मूल्य == 4) { आज्ञा_अर्थविश्लेषक.टर्मिनल(false); return; }
                int मोजमाप;
                if (निवड_मूल्य < 2) मोजमाप = बोर्ड.रन_प्रयोक्ता_अनुप्रयोग(निवड_मूल्य == 0 ? 0 : 9);
                else if (निवड_मूल्य == 2) {
                    मोजमाप = आज्ञा_अर्थविश्लेषक.रन_उदाहरण(10, "Hello.java");
                    if (मोजमाप == 0) मोजमाप = आज्ञा_अर्थविश्लेषक.रन_उदाहरण(11, "Hello");
                } else मोजमाप = आज्ञा_अर्थविश्लेषक.रन_उदाहरण(12, "hello.py");
                राज्य_मूल्य = मोजमाप != 0 ? "PROGRAM FAILED" : निवड_मूल्य == 0 ? "C++ FILE OK" : निवड_मूल्य == 1 ? "UDP LOOPBACK OK" : निवड_मूल्य == 2 ? "JAVA OK" : "MICROPYTHON OK";
                पेंट_पडदा(निवड_मूल्य, राज्य_मूल्य);
                टर्मिनल_आदानप्रदान.लेखन("GUI ACTION "); टर्मिनल_आदानप्रदान.संख्या(निवड_मूल्य); टर्मिनल_आदानप्रदान.लेखन(" RESULT "); टर्मिनल_आदानप्रदान.संख्या(मोजमाप); टर्मिनल_आदानप्रदान.वर्ण(10);
            }
        }
        गाभा.पडदा();
        टर्मिनल_आदानप्रदान.लेखन("GUI EXIT\n");
    }
