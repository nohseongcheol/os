/** नलिका 16 KiB च्या तुकड्यांनी क्रमाने चालतात. प्रक्रिया किंवा समांतर नलिकांचे अनुकरण होत नाही. */
public final class शेल_आदानप्रदान {
    static int[] आदान_डेटा = new int[16384], प्रदान_डेटा = new int[16384];
    static int आदान_लांबी, आदान_स्थान, प्रदान_लांबी, आदान_संचिका = -1, आउटपुट_फाइल = -1;
    static boolean पाइप_आदान, पाइप_प्रदान;
    static int बिघाड_मूल्य;
    static boolean परवानगी_द्या_परस्परसंवादी = true;
    public static int आहे_परस्परसंवादी() { return परवानगी_द्या_परस्परसंवादी && आदान_संचिका < 3 && आउटपुट_फाइल < 3 && !पाइप_आदान && !पाइप_प्रदान ? 1 : 0; }
    public static int आउटपुट(int चॅनल_मूल्य, int मूल्य) {
        if (चॅनल_मूल्य != 1) return 0;
        if (आउटपुट_फाइल >= 3) { int प्रक्रियाकृत_मूल्य = स्मृती_संचिका.लेखन(आउटपुट_फाइल, मूल्य); if (प्रक्रियाकृत_मूल्य < 0) बिघाड_मूल्य = प्रक्रियाकृत_मूल्य; return 1; }
        if (!पाइप_प्रदान) return 0;
        if (प्रदान_लांबी == प्रदान_डेटा.length) बिघाड_मूल्य = -28;
        else प्रदान_डेटा[प्रदान_लांबी++] = मूल्य;
        return 1;
    }
    public static int आदान_मूल्य() {
        if (आदान_संचिका >= 3) { int प्रक्रियाकृत_मूल्य = स्मृती_संचिका.वाचन(आदान_संचिका); return प्रक्रियाकृत_मूल्य == 256 ? -2 : प्रक्रियाकृत_मूल्य; }
        if (पाइप_आदान) return आदान_स्थान < आदान_लांबी ? आदान_डेटा[आदान_स्थान++] : -2;
        return -3; // UART कडे पाठवावे.
    }
    static void सुरू_करा(boolean अग्रस्थान_पाइप, boolean शेवटचे_पाइप) {
        पाइप_आदान = अग्रस्थान_पाइप; पाइप_प्रदान = शेवटचे_पाइप;
        आदान_स्थान = 0; प्रदान_लांबी = 0; आदान_संचिका = -1; आउटपुट_फाइल = -1; बिघाड_मूल्य = 0;
    }
    static void शेवट() {
        बोर्ड.स्विच_आदानप्रदान(0);
        if (आदान_संचिका >= 3) स्मृती_संचिका.बंद_करा(आदान_संचिका);
        if (आउटपुट_फाइल >= 3) स्मृती_संचिका.बंद_करा(आउटपुट_फाइल);
        if (पाइप_प्रदान) { आदान_लांबी = प्रदान_लांबी; for (int लूप_अनुक्रमणिका = 0; लूप_अनुक्रमणिका < प्रदान_लांबी; लूप_अनुक्रमणिका++) आदान_डेटा[लूप_अनुक्रमणिका] = प्रदान_डेटा[लूप_अनुक्रमणिका]; }
        आदान_संचिका = -1; आउटपुट_फाइल = -1; पाइप_आदान = false; पाइप_प्रदान = false;
    }
}
