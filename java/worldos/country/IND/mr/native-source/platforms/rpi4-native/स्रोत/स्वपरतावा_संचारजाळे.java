/** प्रारंभिक जाळे स्तर: एकाच केंद्रकातील IPv4/UDP स्थानिक परतमार्ग. बाहेरील IP साठी ENETUNREACH मिळते; हा Ethernet/IP पाकीट चालकाचा पर्याय नाही. 8 टोकबिंदू, प्रत्येकाकडे 4 संदेश, प्रत्येक संदेश 512 बाइट. सर्व आवाहने न थांबवणारी आहेत. */
public final class स्वपरतावा_संचारजाळे {
    static int[] वापर_मूल्य = new int[8];
    static int[] पॉर्ट_मूल्य = new int[8];
    static int[] पत्ता = new int[8];
    static int[] पुढील_मूल्य = new int[8];
    static int[] आयटम_संख्या = new int[8];
    static int[] स्वीकारलेले_पॉर्ट = new int[8];
    static int[] लांबी_मूल्य = new int[32];
    static int[] पाठवलेले_पॉर्ट = new int[32];
    static int[] डेटा = new int[32 * 512];
    static int[] फॉरवर्ड_मूल्य = new int[512];
    static int पुढील_संचारटोक = 49152;
    static int पडताळा(int अनुक्रमणिका) { return अनुक्रमणिका >= 32 && अनुक्रमणिका < 40 && वापर_मूल्य[अनुक्रमणिका - 32] != 0 ? अनुक्रमणिका - 32 : -1; }
    static boolean आच्छादन(int अनुक्रमणिका) {
        for (int खाच_प्रविष्टी = 0; खाच_प्रविष्टी < 8; खाच_प्रविष्टी++) if (वापर_मूल्य[खाच_प्रविष्टी] != 0 && पॉर्ट_मूल्य[खाच_प्रविष्टी] == अनुक्रमणिका) return true;
        return false;
    }
    static int तात्पुरते_पॉर्ट() {
        for (int प्रयत्न_मूल्य = 0; प्रयत्न_मूल्य < 16; प्रयत्न_मूल्य++) {
            int उमेदवार = पुढील_संचारटोक++;
            if (पुढील_संचारटोक > 65535) पुढील_संचारटोक = 49152;
            if (!आच्छादन(उमेदवार)) return उमेदवार;
        }
        return -98;
    }
    public static int प्रविष्टी_तयार_करा(int प्रदेश_मूल्य, int प्रकार_मूल्य, int काम_मूल्य) {
        if (प्रदेश_मूल्य != 2) return -97;
        if (प्रकार_मूल्य != 2 || (काम_मूल्य != 0 && काम_मूल्य != 17)) return -93;
        for (int खाच_प्रविष्टी = 0; खाच_प्रविष्टी < 8; खाच_प्रविष्टी++) if (वापर_मूल्य[खाच_प्रविष्टी] == 0) {
            वापर_मूल्य[खाच_प्रविष्टी] = 1; पॉर्ट_मूल्य[खाच_प्रविष्टी] = 0; पत्ता[खाच_प्रविष्टी] = 0; पुढील_मूल्य[खाच_प्रविष्टी] = 0; आयटम_संख्या[खाच_प्रविष्टी] = 0; स्वीकारलेले_पॉर्ट[खाच_प्रविष्टी] = 0;
            return खाच_प्रविष्टी + 32;
        }
        return -24;
    }
    public static int बाइंड_करा_संचारटोक(int अनुक्रमणिका, int संचारजाळे_पत्ता, int संचारटोक_पोर्ट_नंबर) {
        int खाच_प्रविष्टी = पडताळा(अनुक्रमणिका);
        if (खाच_प्रविष्टी < 0) return -9;
        if (संचारजाळे_पत्ता != 0 && संचारजाळे_पत्ता != 0x7f000001) return -99;
        if (पॉर्ट_मूल्य[खाच_प्रविष्टी] != 0 || संचारटोक_पोर्ट_नंबर < 0 || संचारटोक_पोर्ट_नंबर > 65535) return -22;
        if (संचारटोक_पोर्ट_नंबर == 0) संचारटोक_पोर्ट_नंबर = तात्पुरते_पॉर्ट();
        if (संचारटोक_पोर्ट_नंबर < 0) return संचारटोक_पोर्ट_नंबर;
        if (आच्छादन(संचारटोक_पोर्ट_नंबर)) return -98;
        पॉर्ट_मूल्य[खाच_प्रविष्टी] = संचारटोक_पोर्ट_नंबर; पत्ता[खाच_प्रविष्टी] = संचारजाळे_पत्ता; return 0;
    }
    public static int ठेवा_डेटा(int अनुक्रमणिका, int मूल्य) {
        if (अनुक्रमणिका < 0 || अनुक्रमणिका >= 512) return -22;
        फॉरवर्ड_मूल्य[अनुक्रमणिका] = मूल्य & 255; return 0;
    }
    public static int डेटा_वाचा(int अनुक्रमणिका) { return अनुक्रमणिका >= 0 && अनुक्रमणिका < 512 ? फॉरवर्ड_मूल्य[अनुक्रमणिका] : -22; }
    public static int पाठवा(int अनुक्रमणिका, int संचारजाळे_पत्ता, int संचारटोक_पोर्ट_नंबर, int आकार) {
        int खाच_प्रविष्टी = पडताळा(अनुक्रमणिका);
        if (खाच_प्रविष्टी < 0) return -9;
        if (संचारजाळे_पत्ता != 0x7f000001) return -101;
        if (संचारटोक_पोर्ट_नंबर < 1 || संचारटोक_पोर्ट_नंबर > 65535) return -22;
        if (आकार < 0 || आकार > 512) return -90;
        if (पॉर्ट_मूल्य[खाच_प्रविष्टी] == 0) {
            int मोजमाप = बाइंड_करा_संचारटोक(अनुक्रमणिका, 0x7f000001, 0);
            if (मोजमाप < 0) return मोजमाप;
        }
        int गंतव्यस्थान_मूल्य = -1;
        for (int उमेदवार = 0; उमेदवार < 8; उमेदवार++) if (वापर_मूल्य[उमेदवार] != 0 && पॉर्ट_मूल्य[उमेदवार] == संचारटोक_पोर्ट_नंबर) गंतव्यस्थान_मूल्य = उमेदवार;
        if (गंतव्यस्थान_मूल्य < 0) return -111;
        if (आयटम_संख्या[गंतव्यस्थान_मूल्य] == 4) return -11;
        int स्थान_अनुक्रमणिका = गंतव्यस्थान_मूल्य * 4 + (पुढील_मूल्य[गंतव्यस्थान_मूल्य] + आयटम_संख्या[गंतव्यस्थान_मूल्य]) % 4;
        for (int बाइट_मूल्य = 0; बाइट_मूल्य < आकार; बाइट_मूल्य++) डेटा[स्थान_अनुक्रमणिका * 512 + बाइट_मूल्य] = फॉरवर्ड_मूल्य[बाइट_मूल्य];
        लांबी_मूल्य[स्थान_अनुक्रमणिका] = आकार; पाठवलेले_पॉर्ट[स्थान_अनुक्रमणिका] = पॉर्ट_मूल्य[खाच_प्रविष्टी]; आयटम_संख्या[गंतव्यस्थान_मूल्य]++;
        return आकार;
    }
    public static int स्वीकारा(int अनुक्रमणिका, int धारणक्षमता_मूल्य) {
        int खाच_प्रविष्टी = पडताळा(अनुक्रमणिका);
        if (खाच_प्रविष्टी < 0) return -9;
        if (धारणक्षमता_मूल्य < 0 || धारणक्षमता_मूल्य > 512) return -22;
        if (आयटम_संख्या[खाच_प्रविष्टी] == 0) return -11;
        int स्थान_अनुक्रमणिका = खाच_प्रविष्टी * 4 + पुढील_मूल्य[खाच_प्रविष्टी];
        int आकार = लांबी_मूल्य[स्थान_अनुक्रमणिका] < धारणक्षमता_मूल्य ? लांबी_मूल्य[स्थान_अनुक्रमणिका] : धारणक्षमता_मूल्य;
        for (int बाइट_मूल्य = 0; बाइट_मूल्य < आकार; बाइट_मूल्य++) फॉरवर्ड_मूल्य[बाइट_मूल्य] = डेटा[स्थान_अनुक्रमणिका * 512 + बाइट_मूल्य];
        स्वीकारलेले_पॉर्ट[खाच_प्रविष्टी] = पाठवलेले_पॉर्ट[स्थान_अनुक्रमणिका]; पुढील_मूल्य[खाच_प्रविष्टी] = (पुढील_मूल्य[खाच_प्रविष्टी] + 1) % 4; आयटम_संख्या[खाच_प्रविष्टी]--;
        return आकार;
    }
    public static int संचारटोक_पॉर्ट_वाचा(int अनुक्रमणिका) { int खाच_प्रविष्टी = पडताळा(अनुक्रमणिका); return खाच_प्रविष्टी < 0 ? -9 : पॉर्ट_मूल्य[खाच_प्रविष्टी]; }
    public static int पत्ता_वाचा(int अनुक्रमणिका) { int खाच_प्रविष्टी = पडताळा(अनुक्रमणिका); return खाच_प्रविष्टी < 0 ? -9 : पत्ता[खाच_प्रविष्टी]; }
    public static int प्रेषक_संचारटोक(int अनुक्रमणिका) { int खाच_प्रविष्टी = पडताळा(अनुक्रमणिका); return खाच_प्रविष्टी < 0 ? -9 : स्वीकारलेले_पॉर्ट[खाच_प्रविष्टी]; }
    public static int बंद_करा(int अनुक्रमणिका) {
        int खाच_प्रविष्टी = पडताळा(अनुक्रमणिका); if (खाच_प्रविष्टी < 0) return -9;
        वापर_मूल्य[खाच_प्रविष्टी] = 0; आयटम_संख्या[खाच_प्रविष्टी] = 0; पॉर्ट_मूल्य[खाच_प्रविष्टी] = 0; return 0;
    }
}
