package मराठी.स्वकीय;
/** स्वतंत्र केंद्रकाचा RGB32 चित्रचौकट साठा; आकार प्रारंभी निवडला जातो. */
public final class पडदा {
    private पडदा() {}
    public static int रुंदी_मूल्य() { int मूल्य = गाभा_मूल्य.पडदा_रुंदी(); if (मूल्य < 0) throw new राज्य_अपवाद("चित्रस्मृती उपलब्ध नाही"); return मूल्य; }
    public static int उंची_मूल्य() { int मूल्य = गाभा_मूल्य.पडदा_उंची(); if (मूल्य < 0) throw new राज्य_अपवाद("चित्रस्मृती उपलब्ध नाही"); return मूल्य; }
    public static void आयत(int आडवे_स्थान, int अनुलंब_स्थान, int रुंदी_विस्तार, int उंची_मूल्य, int रंग_मूल्य) {
        if (आडवे_स्थान < 0 || अनुलंब_स्थान < 0 || रुंदी_विस्तार < 0 || उंची_मूल्य < 0 || आडवे_स्थान > रुंदी_मूल्य() || अनुलंब_स्थान > उंची_मूल्य() || रुंदी_विस्तार > रुंदी_मूल्य() - आडवे_स्थान || उंची_मूल्य > उंची_मूल्य() - अनुलंब_स्थान) throw new अवैध_वितर्क_अपवाद("पडद्याची मर्यादा");
        if (गाभा_मूल्य.आयत(आडवे_स्थान, अनुलंब_स्थान, रुंदी_विस्तार, उंची_मूल्य, रंग_मूल्य) < 0) throw new राज्य_अपवाद("चित्रस्मृती उपलब्ध नाही");
    }
    public static void पुसा_प्रविष्टी(int रंग_मूल्य) { आयत(0, 0, रुंदी_मूल्य(), उंची_मूल्य(), रंग_मूल्य); }
    public static void प्रतीक्षाकरा() { if (गाभा_मूल्य.प्रतीक्षा_करा_साठी_चित्र() < 0) throw new राज्य_अपवाद("संवादी आदान आवश्यक आहे"); }
}
