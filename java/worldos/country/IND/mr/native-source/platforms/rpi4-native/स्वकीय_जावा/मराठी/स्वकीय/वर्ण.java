package मराठी.स्वकीय;
/** UTF-8 बाइट आणि UTF-16 अक्षरमाला यांचे रूपांतर. सामान्यीकरण आणि जोडाक्षर आदान स्वतंत्रपणे हाताळले जातात. */
public final class वर्ण {
    public static int बाइट_संख्या(byte[] डेटा) { return डेटा.length; }
    private वर्ण() {}
    public static int लांबी_मूल्य(String पाठ्य) { return पाठ्य.length(); }
    public static boolean समान_मजकूर(String पुढील_मूल्य, String मागे_मूल्य) { return पुढील_मूल्य == null ? मागे_मूल्य == null : पुढील_मूल्य.equals(मागे_मूल्य); }
    public static String चिकटवा_मजकूर(String पुढील_मूल्य, String मागे_मूल्य) { return पुढील_मूल्य.concat(मागे_मूल्य); }
    public static String कट_मूल्य(String पाठ्य, int सुरू_करा, int शेवट) { return पाठ्य.substring(सुरू_करा, शेवट); }
    public static int पूर्णांक_पार्स_करा(String पाठ्य) { try { return Integer.parseInt(पाठ्य); } catch (NumberFormatException त्रुटी) { throw new संख्या_स्वरूप_बिघाड("संख्येचे स्वरूप आणि मर्यादा तपासा."); } }
    public static String पूर्णांक_मूल्य_लिहा(int संख्या) { return Integer.toString(संख्या); }
    public static int वर्ण_कोड_संख्या(String पाठ्य) {
        int संख्या = 0;
        for (int लूप_अनुक्रमणिका = 0; लूप_अनुक्रमणिका < पाठ्य.length(); लूप_अनुक्रमणिका++, संख्या++) {
            int वर्ण_कोड = पाठ्य.charAt(लूप_अनुक्रमणिका);
            if (वर्ण_कोड >= 0xd800 && वर्ण_कोड <= 0xdbff && लूप_अनुक्रमणिका + 1 < पाठ्य.length() && पाठ्य.charAt(लूप_अनुक्रमणिका + 1) >= 0xdc00 && पाठ्य.charAt(लूप_अनुक्रमणिका + 1) <= 0xdfff) लूप_अनुक्रमणिका++;
        }
        return संख्या;
    }
    public static byte[] संकेतन(String पाठ्य) {
        byte[] तात्पुरते_मूल्य = new byte[पाठ्य.length() * 3]; int लिहिलेले = 0;
        for (int लूप_अनुक्रमणिका = 0; लूप_अनुक्रमणिका < पाठ्य.length(); लूप_अनुक्रमणिका++) {
            int वर्ण_कोड = पाठ्य.charAt(लूप_अनुक्रमणिका);
            if (वर्ण_कोड >= 0xd800 && वर्ण_कोड <= 0xdbff && लूप_अनुक्रमणिका + 1 < पाठ्य.length() && पाठ्य.charAt(लूप_अनुक्रमणिका + 1) >= 0xdc00 && पाठ्य.charAt(लूप_अनुक्रमणिका + 1) <= 0xdfff) वर्ण_कोड = 0x10000 + ((वर्ण_कोड - 0xd800) << 10) + पाठ्य.charAt(++लूप_अनुक्रमणिका) - 0xdc00;
            else if (वर्ण_कोड >= 0xd800 && वर्ण_कोड <= 0xdfff) वर्ण_कोड = '?';
            if (वर्ण_कोड < 128) तात्पुरते_मूल्य[लिहिलेले++] = (byte)वर्ण_कोड;
            else if (वर्ण_कोड < 2048) { तात्पुरते_मूल्य[लिहिलेले++] = (byte)(192 | वर्ण_कोड >> 6); तात्पुरते_मूल्य[लिहिलेले++] = (byte)(128 | वर्ण_कोड & 63); }
            else if (वर्ण_कोड < 65536) { तात्पुरते_मूल्य[लिहिलेले++] = (byte)(224 | वर्ण_कोड >> 12); तात्पुरते_मूल्य[लिहिलेले++] = (byte)(128 | वर्ण_कोड >> 6 & 63); तात्पुरते_मूल्य[लिहिलेले++] = (byte)(128 | वर्ण_कोड & 63); }
            else { तात्पुरते_मूल्य[लिहिलेले++] = (byte)(240 | वर्ण_कोड >> 18); तात्पुरते_मूल्य[लिहिलेले++] = (byte)(128 | वर्ण_कोड >> 12 & 63); तात्पुरते_मूल्य[लिहिलेले++] = (byte)(128 | वर्ण_कोड >> 6 & 63); तात्पुरते_मूल्य[लिहिलेले++] = (byte)(128 | वर्ण_कोड & 63); }
        }
        byte[] मोजमाप = new byte[लिहिलेले]; System.arraycopy(तात्पुरते_मूल्य, 0, मोजमाप, 0, लिहिलेले); return मोजमाप;
    }
    /** चुकीचे UTF-8 हे API मधील अवैध प्रचल अपवादाने नाकारते. */
    public static String डिक्रिप्ट_करा_डेटा(byte[] बाइट_मूल्य) {
        StringBuilder मोजमाप = new StringBuilder();
        for (int लूप_अनुक्रमणिका = 0; लूप_अनुक्रमणिका < बाइट_मूल्य.length;) {
            int वर्ण_कोड = बाइट_मूल्य[लूप_अनुक्रमणिका++] & 255, संख्या = वर्ण_कोड < 128 ? 0 : वर्ण_कोड >= 194 && वर्ण_कोड < 224 ? 1 : वर्ण_कोड >= 224 && वर्ण_कोड < 240 ? 2 : वर्ण_कोड >= 240 && वर्ण_कोड <= 244 ? 3 : -1;
            if (संख्या < 0 || बाइट_मूल्य.length - लूप_अनुक्रमणिका < संख्या) throw new अवैध_वितर्क_अपवाद("अवैध UTF-8");
            int किमान_मूल्य = संख्या == 1 ? 128 : संख्या == 2 ? 2048 : संख्या == 3 ? 65536 : 0;
            if (संख्या > 0) वर्ण_कोड &= (1 << (6 - संख्या)) - 1;
            for (int आंतरिक_संयोग_स्थान = 0; आंतरिक_संयोग_स्थान < संख्या; आंतरिक_संयोग_स्थान++) { int मागे_मूल्य = बाइट_मूल्य[लूप_अनुक्रमणिका++] & 255; if ((मागे_मूल्य & 192) != 128) throw new अवैध_वितर्क_अपवाद("अवैध UTF-8"); वर्ण_कोड = वर्ण_कोड << 6 | मागे_मूल्य & 63; }
            if (वर्ण_कोड < किमान_मूल्य || वर्ण_कोड > 0x10ffff || वर्ण_कोड >= 0xd800 && वर्ण_कोड <= 0xdfff) throw new अवैध_वितर्क_अपवाद("अवैध UTF-8");
            if (वर्ण_कोड < 65536) मोजमाप.append((char)वर्ण_कोड);
            else { वर्ण_कोड -= 65536; मोजमाप.append((char)(0xd800 | वर्ण_कोड >> 10)); मोजमाप.append((char)(0xdc00 | वर्ण_कोड & 1023)); }
        }
        return मोजमाप.toString();
    }
}
