package भारत.JIndOS.इंटरप्ट;

import java.util.Arrays;

/** IDT च्या Java-व्यवस्थापित हाताळकांची नोंदणी आणि वाटप करते. */
public final class इंटरप्ट_व्यवस्थापक {
    private final इंटरप्ट_हाताळक[] हाताळक_यादी = new इंटरप्ट_हाताळक[256];
    private boolean सक्रिय;

    public void रजिस्टर_प्रविष्टी(int अनुक्रमणिका, इंटरप्ट_हाताळक हाताळक) {
        संख्या_पडताळा(अनुक्रमणिका);
        हाताळक_यादी[अनुक्रमणिका] = हाताळक;
    }

    public void संग्रह_रिलीज(int अनुक्रमणिका) {
        संख्या_पडताळा(अनुक्रमणिका);
        हाताळक_यादी[अनुक्रमणिका] = null;
    }

    public int वितरीत_करा_मूल्य(int अनुक्रमणिका, int साठवलेले_स्टॅक_पत्ता) {
        संख्या_पडताळा(अनुक्रमणिका);
        if (!सक्रिय) {
            return साठवलेले_स्टॅक_पत्ता;
        }
        इंटरप्ट_हाताळक हाताळक = हाताळक_यादी[अनुक्रमणिका];
        return हाताळक == null ? साठवलेले_स्टॅक_पत्ता : हाताळक.प्रक्रिया_मूल्य_प्रविष्टी(साठवलेले_स्टॅक_पत्ता);
    }

    public void सक्षम() {
        सक्रिय = true;
    }

    public void निष्क्रिय_करा() {
        सक्रिय = false;
    }

    public boolean आहे_सक्रिय() {
        return सक्रिय;
    }

    public void सर्व_रिलीज() {
        Arrays.fill(हाताळक_यादी, null);
    }

    private void संख्या_पडताळा(int अनुक्रमणिका) {
        if (अनुक्रमणिका < 0 || अनुक्रमणिका >= हाताळक_यादी.length) {
            throw new IllegalArgumentException("इंटरप्ट 번호가 올바르지 않습니다.");
        }
    }
}

