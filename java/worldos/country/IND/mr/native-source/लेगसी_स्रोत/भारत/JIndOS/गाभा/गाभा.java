package भारत.JIndOS.गाभा;

import भारत.JIndOS.स्मृती_प्रदेश.स्मृती_व्यवस्थापक;
import भारत.JIndOS.स्मृती_प्रदेश.पृष्ठ_व्यवस्थापक;
import भारत.JIndOS.आदान_मूल्य.आदान_व्यवस्थापक;
import भारत.JIndOS.पारपाडा_कार्य.प्रक्रिया_मूल्य;
import भारत.JIndOS.पारपाडा_कार्य.शेड्यूलर;
import भारत.JIndOS.सिस्टम_कॉल_आवाहन.सिस्टम_कॉल_आवाहन;
import भारत.JIndOS.फाइल_सिस्टम.संचिका_विवरणक_सारणी;
import भारत.JIndOS.फाइल_सिस्टम.फाइल_सिस्टम;

/** Java-व्यवस्थापित केंद्रक जोडते आणि सुरू करते. */
public final class गाभा {
    private final हार्डवेअर_मूल्य मोबाइल_मूल्य;
    private final स्मृती_व्यवस्थापक स्मृती_प्रदेश = new स्मृती_व्यवस्थापक(32 * 1024 * 1024);
    private final पृष्ठ_व्यवस्थापक पृष्ठ_व्यवस्थापन = new पृष्ठ_व्यवस्थापक();
    private final फाइल_सिस्टम फाइल_सिस्टम = new फाइल_सिस्टम();
    private final शेड्यूलर शेड्यूलर = new शेड्यूलर(पृष्ठ_व्यवस्थापन);
    private final आदान_व्यवस्थापक आदान_व्यवस्थापन = new आदान_व्यवस्थापक(256);
    private final प्रक्रिया_मूल्य पहिले_प्रक्रिया;
    private final सिस्टम_कॉल_आवाहन सिस्टम_कॉल_आवाहन;

    public गाभा(हार्डवेअर_मूल्य मोबाइल_मूल्य) {
        this.मोबाइल_मूल्य = मोबाइल_मूल्य;
        पहिले_प्रक्रिया = शेड्यूलर.पहिले_प्रक्रिया(new संचिका_विवरणक_सारणी(फाइल_सिस्टम));
        सिस्टम_कॉल_आवाहन = new सिस्टम_कॉल_आवाहन(फाइल_सिस्टम, पृष्ठ_व्यवस्थापन, शेड्यूलर, मोबाइल_मूल्य, आदान_व्यवस्थापन);
    }

    public void सुरू_करा() {
        मोबाइल_मूल्य.अनुक्रमिक_प्रदान("=== JIndOS 관리 गाभा_मूल्य ===\n");
    }

    public void पायरी_कार्यवाही_करा() {
        मोबाइल_मूल्य.थांबवा_प्रोसेसर();
    }

    public स्मृती_व्यवस्थापक स्मृती_प्रदेश() {
        return स्मृती_प्रदेश;
    }

    public पृष्ठ_व्यवस्थापक पृष्ठ_व्यवस्थापन() {
        return पृष्ठ_व्यवस्थापन;
    }

    public फाइल_सिस्टम फाइल_सिस्टम() {
        return फाइल_सिस्टम;
    }

    public शेड्यूलर शेड्यूलर() {
        return शेड्यूलर;
    }

    public आदान_व्यवस्थापक आदान_व्यवस्थापन() {
        return आदान_व्यवस्थापन;
    }

    public प्रक्रिया_मूल्य पहिले_प्रक्रिया() {
        return पहिले_प्रक्रिया;
    }

    public सिस्टम_कॉल_आवाहन सिस्टम_कॉल_आवाहन() {
        return सिस्टम_कॉल_आवाहन;
    }
}
