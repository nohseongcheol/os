    private static void स्मृती_चाचणी(गाभा गाभा_मूल्य) {
        स्मृती_व्यवस्थापक व्यवस्थापक_मूल्य = गाभा_मूल्य.स्मृती_प्रदेश();
        int पहिले_पत्ता = व्यवस्थापक_मूल्य.संरेखित_वाटप_करा(100, 64);
        पडताळा((पहिले_पत्ता & 63) == 0, "संरेखन_करावे_मूल्य संग्रह_वाटप_करा");
        व्यवस्थापक_मूल्य.बाइट_मूल्य_लिहा(पहिले_पत्ता, (byte) 0x5a);
        पडताळा(व्यवस्थापक_मूल्य.बाइट_मूल्य_वाचा(पहिले_पत्ता) == (byte) 0x5a, "물리 स्मृती_प्रदेश 읽고 लेखन");
        int आधी_वापर = व्यवस्थापक_मूल्य.वापरलेले_आकारा();
        व्यवस्थापक_मूल्य.संग्रह_रिलीज(पहिले_पत्ता);
        पडताळा(व्यवस्थापक_मूल्य.वापरलेले_आकारा() < आधी_वापर, "स्मृती_प्रदेश संग्रह_रिलीज");
    }

    private static void पृष्ठ_व्यवस्थापन_चाचणी(गाभा गाभा_मूल्य) {
        पृष्ठ_व्यवस्थापक व्यवस्थापक_मूल्य = गाभा_मूल्य.पृष्ठ_व्यवस्थापन();
        पृष्ठ_व्यवस्थापक.पत्ता_जागा जनक_जागा = व्यवस्थापक_मूल्य.नवे_पत्ता_जागा();
        व्यवस्थापक_मूल्य.मॅप_करा_पृष्ठ(जनक_जागा, 0x1000, true);
        व्यवस्थापक_मूल्य.बाइट_मूल्य_लिहा(जनक_जागा, 0x1010, (byte) 7);
        पृष्ठ_व्यवस्थापक.पत्ता_जागा उपघटक_जागा = व्यवस्थापक_मूल्य.प्रतबनवा_इन्स्टन्स_चालू_लिहा(जनक_जागा);
        व्यवस्थापक_मूल्य.बाइट_मूल्य_लिहा(उपघटक_जागा, 0x1010, (byte) 9);
        पडताळा(व्यवस्थापक_मूल्य.बाइट_मूल्य_वाचा(जनक_जागा, 0x1010) == 7, "लेखन 시 इन्स्टन्स_मूल्य जनक_मूल्य 격리");
        पडताळा(व्यवस्थापक_मूल्य.बाइट_मूल्य_वाचा(उपघटक_जागा, 0x1010) == 9, "लेखन 시 इन्स्टन्स_मूल्य उपघटक_मूल्य लेखन");
    }

    private static void संचिका_आणि_प्रक्रिया_चाचणी(गाभा गाभा_मूल्य) {
        byte[] सामुग्री_मूल्य = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        गाभा_मूल्य.फाइल_सिस्टम().शेवटीजोडा_संचिका("चाचण्या", सामुग्री_मूल्य);
        प्रक्रिया_मूल्य जनक_मूल्य = गाभा_मूल्य.पहिले_प्रक्रिया();
        सिस्टम_कॉल_आवाहन आवाहन = गाभा_मूल्य.सिस्टम_कॉल_आवाहन();
        int विवरणक_प्रविष्टी = आवाहन.उघडा(जनक_मूल्य, "/चाचण्या", सिस्टम_कॉल_आवाहन.केवळ_ध्वजांकित_करा_वाचा);
        पडताळा(विवरणक_प्रविष्टी >= 3, "फाइल उघडा");

        byte[] गंतव्यस्थान_स्वीकारा = new byte[सामुग्री_मूल्य.length];
        पडताळा(आवाहन.वाचन(जनक_मूल्य, विवरणक_प्रविष्टी, गंतव्यस्थान_स्वीकारा, गंतव्यस्थान_स्वीकारा.length) == सामुग्री_मूल्य.length, "फाइल वाचन");
        पडताळा(Arrays.equals(सामुग्री_मूल्य, गंतव्यस्थान_स्वीकारा), "फाइल सामुग्री_मूल्य");
        पडताळा(आवाहन.हलवा_स्थान(जनक_मूल्य, विवरणक_प्रविष्टी, 0, सिस्टम_कॉल_आवाहन.शोध_प्रारंभ) == 0, "फाइल जागा हलवा_मूल्य");

        int प्रतिलिपित_विवरणक = आवाहन.प्रतिरूप_विवरणक(जनक_मूल्य, विवरणक_प्रविष्टी);
        पडताळा(प्रतिलिपित_विवरणक >= 0, "विवरणक_प्रविष्टी प्रतबनवा_मूल्य");
        प्रक्रिया_मूल्य उपघटक_मूल्य = आवाहन.प्रतबनवा_प्रक्रिया(जनक_मूल्य);
        पडताळा(उपघटक_मूल्य.आयडेंटिफायर_मूल्य() != जनक_मूल्य.आयडेंटिफायर_मूल्य(), "प्रक्रिया_मूल्य आयडेंटिफायर_मूल्य 분리");
        पडताळा(उपघटक_मूल्य.जनक_आयडेंटिफायर() == जनक_मूल्य.आयडेंटिफायर_मूल्य(), "जनक_मूल्य प्रक्रिया_मूल्य आयडेंटिफायर_मूल्य");
        पडताळा(आवाहन.बंद_करा(उपघटक_मूल्य, विवरणक_प्रविष्टी) == 0 && जनक_मूल्य.संचिका_विवरणक().आहे_उघडा(विवरणक_प्रविष्टी), "उपघटक_मूल्य बंद_करा 격리");

        int मागील_शेवट_करा = आवाहन.वाढवा_अनुप्रयोग_खंड(जनक_मूल्य, 8192);
        पडताळा(मागील_शेवट_करा == 0x06000000, "अनुप्रयोग_f5044b9b शेवट 늘리기");
        पडताळा(जनक_मूल्य.अनुप्रयोग_खंड() == 0x06002000, "अनुप्रयोग_f5044b9b शेवट 반영");
        पडताळा(उपघटक_मूल्य.अनुप्रयोग_खंड() == 0x06000000, "과정별 अनुप्रयोग_f5044b9b शेवट 격리");

        उपघटक_मूल्य.निर्गमन_करा_अनुप्रयोग(7);
        पडताळा(आवाहन.प्रतीक्षा_करा_साठी_उपघटक(जनक_मूल्य, उपघटक_मूल्य.आयडेंटिफायर_मूल्य(), false) == (7 << 8), "उपघटक_मूल्य निर्गमन_करा_अनुप्रयोग प्रतीक्षाकरा");
        पडताळा(आवाहन.आहे_प्रवेशयोग्य("चाचण्या", 1) == -13, "आज्ञा_कार्यवाही_करा परवानगी_मूल्य अस्वीकृत_करा_मूल्य");
        पडताळा(आवाहन.प्रयोक्ता_ID() == 0 && आवाहन.समूह_आयडेंटिफायर() == 0, "사용자와 무리 आयडेंटिफायर_मूल्य");
        पडताळा("/".equals(आवाहन.सध्याचे_कार्य_यादी(2)) && आवाहन.स्विच_कार्य_यादी("/") == 0, "सध्याचे_आयटम पारपाडा_कार्य प्रविष्टी_यादी");
        पडताळा(आवाहन.आहे_टर्मिनल(जनक_मूल्य, 1), "표준 आउटपुट टर्मिनल_आदानप्रदान");
        पडताळा("JIndOS".equals(आवाहन.सिस्टम_तपशील().सिस्टम_नाव()), "ऑपरेटिंग_सिस्टम_मूल्य सिस्टम_माहिती");
    }

    private static void ईएलएफ_चाचणी(गाभा गाभा_मूल्य) {
        byte[] डेटा = new byte[92];
        डेटा[0] = 0x7f;
        डेटा[1] = 'E';
        डेटा[2] = 'L';
        डेटा[3] = 'F';
        डेटा[4] = 1;
        डेटा[5] = 1;
        पूर्णांक_मूल्य_लिहा(डेटा, 24, 0x04001000);
        पूर्णांक_मूल्य_लिहा(डेटा, 32, 52);
        लघु_पूर्णांक_लिहा(डेटा, 46, 40);
        लघु_पूर्णांक_लिहा(डेटा, 48, 1);
        पूर्णांक_मूल्य_लिहा(डेटा, 56, 8);
        पूर्णांक_मूल्य_लिहा(डेटा, 60, 2);
        पूर्णांक_मूल्य_लिहा(डेटा, 64, 0x04002000);
        पूर्णांक_मूल्य_लिहा(डेटा, 72, 64);

        निष्पादनीय_भारक.चित्र चित्र_मूल्य = new निष्पादनीय_भारक().पडताळण्या(डेटा);
        पडताळा(चित्र_मूल्य.प्रारंभ_पत्ता() == 0x04001000, "ELF सुरू_करा पत्ता");
        पडताळा(चित्र_मूल्य.विभाग_यादी().size() == 1 && चित्र_मूल्य.विभाग_यादी().get(0).प्रकार_मूल्य() == 8, "ELF 빈 डेटा विभाग_मूल्य");
        int विवरणक_प्रविष्टी = गाभा_मूल्य.सिस्टम_कॉल_आवाहन().उघडा(गाभा_मूल्य.पहिले_प्रक्रिया(), "चाचण्या", सिस्टम_कॉल_आवाहन.केवळ_ध्वजांकित_करा_वाचा);
        पडताळा(गाभा_मूल्य.सिस्टम_कॉल_आवाहन().संचिका_नियंत्रण(गाभा_मूल्य.पहिले_प्रक्रिया(), विवरणक_प्रविष्टी, 2, 1) == 0, "आज्ञा_कार्यवाही_करा 시 बंद_करा संयोजना");
        पडताळा(गाभा_मूल्य.सिस्टम_कॉल_आवाहन().आज्ञा_कार्यवाही_करा(गाभा_मूल्य.पहिले_प्रक्रिया(), डेटा, new String[] {"चाचण्या", "값"}, new String[] {"भाषा=मराठी"}) == 0, "ELF आज्ञा_कार्यवाही_करा चित्र_मूल्य 적재");
        पडताळा(गाभा_मूल्य.पहिले_प्रक्रिया().निष्पादन_प्रारंभ_पत्ता() == 0x04001000, "आज्ञा_कार्यवाही_करा सुरू_करा पत्ता 반영");
        पडताळा(गाभा_मूल्य.पहिले_प्रक्रिया().निष्पादन_वितर्क().length == 2 && गाभा_मूल्य.पहिले_प्रक्रिया().पर्यावरण_मूल्य().length == 1, "आज्ञा_कार्यवाही_करा 인자와 पर्यावरण");
        पडताळा(!गाभा_मूल्य.पहिले_प्रक्रिया().संचिका_विवरणक().आहे_उघडा(विवरणक_प्रविष्टी), "आज्ञा_कार्यवाही_करा 시 विवरणक_प्रविष्टी बंद_करा");
        पडताळा(गाभा_मूल्य.पृष्ठ_व्यवस्थापन().बाइट_मूल्य_वाचा(गाभा_मूल्य.पहिले_प्रक्रिया().पत्ता_जागा(), 0x04002000) == 0, "빈 डेटा विभाग_मूल्य शून्य_संकार्य आरंभ_करा");
    }

    private static void आदान_चाचणी(गाभा गाभा_मूल्य) {
        गाभा_मूल्य.आदान_व्यवस्थापन().कळ_खाली('가');
        गाभा_मूल्य.आदान_व्यवस्थापन().माऊस_हालचाल(3, -2);
        आदान_इव्हेंट पहिले_इव्हेंट = गाभा_मूल्य.आदान_व्यवस्थापन().पुढील_इव्हेंट();
        आदान_इव्हेंट दुसरे_इव्हेंट = गाभा_मूल्य.आदान_व्यवस्थापन().पुढील_इव्हेंट();
        पडताळा(पहिले_इव्हेंट.इव्हेंट_प्रकार() == आदान_इव्हेंट.प्रकार_मूल्य.कळ_खाली, "자판 इव्हेंट");
        पडताळा(दुसरे_इव्हेंट.पहिले_मूल्य() == 3 && दुसरे_इव्हेंट.दुसरे_मूल्य() == -2, "쥐 हलवा_मूल्य इव्हेंट");
    }

