package भारत.JIndOS.पडदा;

import java.util.Arrays;

/** VGA मजकूर पद्धतीसारखे 80x25 अक्षरपडद्याचे प्रतिरूप. */
public final class वर्ण_प्रदर्शन {
    public static final int रुंदी_मूल्य = 80;
    public static final int उंची_मूल्य = 25;
    private final char[] वर्ण_मूल्ये = new char[रुंदी_मूल्य * उंची_मूल्य];
    private int आडवे_स्थान;
    private int अनुलंब_स्थान;

    public वर्ण_प्रदर्शन() {
        पुसा_प्रविष्टी();
    }

    public void आउटपुट(String सामुग्री_मूल्य) {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < सामुग्री_मूल्य.length(); अनुक्रमणिका++) {
            char वर्ण = सामुग्री_मूल्य.charAt(अनुक्रमणिका);
            if (वर्ण == '\n') {
                आडवे_स्थान = 0;
                अनुलंब_स्थान++;
            } else {
                वर्ण_छापा(आडवे_स्थान++, अनुलंब_स्थान, वर्ण);
            }
            if (आडवे_स्थान >= रुंदी_मूल्य) {
                आडवे_स्थान = 0;
                अनुलंब_स्थान++;
            }
            if (अनुलंब_स्थान >= उंची_मूल्य) {
                स्क्रोल_वर();
            }
        }
    }

    public char वर्ण(int आडवे_स्थान, int अनुलंब_स्थान) {
        स्थान_पडताळा(आडवे_स्थान, अनुलंब_स्थान);
        return वर्ण_मूल्ये[अनुलंब_स्थान * रुंदी_मूल्य + आडवे_स्थान];
    }

    public void पुसा_प्रविष्टी() {
        Arrays.fill(वर्ण_मूल्ये, ' ');
        आडवे_स्थान = 0;
        अनुलंब_स्थान = 0;
    }

    private void वर्ण_छापा(int आडवे_स्थान, int अनुलंब_स्थान, char वर्ण) {
        स्थान_पडताळा(आडवे_स्थान, अनुलंब_स्थान);
        वर्ण_मूल्ये[अनुलंब_स्थान * रुंदी_मूल्य + आडवे_स्थान] = वर्ण;
    }

    private void स्क्रोल_वर() {
        System.arraycopy(वर्ण_मूल्ये, रुंदी_मूल्य, वर्ण_मूल्ये, 0, रुंदी_मूल्य * (उंची_मूल्य - 1));
        Arrays.fill(वर्ण_मूल्ये, रुंदी_मूल्य * (उंची_मूल्य - 1), वर्ण_मूल्ये.length, ' ');
        अनुलंब_स्थान = उंची_मूल्य - 1;
    }

    private void स्थान_पडताळा(int आडवे_स्थान, int अनुलंब_स्थान) {
        if (आडवे_स्थान < 0 || आडवे_स्थान >= रुंदी_मूल्य || अनुलंब_स्थान < 0 || अनुलंब_स्थान >= उंची_मूल्य) {
            throw new IllegalArgumentException("पडदा 위치가 올바르지 않습니다.");
        }
    }
}

