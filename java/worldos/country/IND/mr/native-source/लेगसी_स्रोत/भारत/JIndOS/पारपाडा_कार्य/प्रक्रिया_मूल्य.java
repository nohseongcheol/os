package भारत.JIndOS.पारपाडा_कार्य;

import भारत.JIndOS.स्मृती_प्रदेश.पृष्ठ_व्यवस्थापक;
import भारत.JIndOS.फाइल_सिस्टम.संचिका_विवरणक_सारणी;

public final class प्रक्रिया_मूल्य {
    private final int आयडेंटिफायर_मूल्य;
    private final int जनक_आयडेंटिफायर;
    private final पृष्ठ_व्यवस्थापक.पत्ता_जागा पत्ता_जागा;
    private final संचिका_विवरणक_सारणी संचिका_विवरणक;
    private प्रक्रिया_राज्य राज्य_मूल्य = प्रक्रिया_राज्य.तयार_करणे;
    private int निर्गमन_करा_संहिता;
    private int अनुप्रयोग_खंड = 0x06000000;
    private int निष्पादन_प्रारंभ_पत्ता;
    private String[] निष्पादन_वितर्क = new String[0];
    private String[] पर्यावरण_मूल्य = new String[0];

    प्रक्रिया_मूल्य(int आयडेंटिफायर_मूल्य, int जनक_आयडेंटिफायर, पृष्ठ_व्यवस्थापक.पत्ता_जागा पत्ता_जागा, संचिका_विवरणक_सारणी संचिका_विवरणक) {
        this.आयडेंटिफायर_मूल्य = आयडेंटिफायर_मूल्य;
        this.जनक_आयडेंटिफायर = जनक_आयडेंटिफायर;
        this.पत्ता_जागा = पत्ता_जागा;
        this.संचिका_विवरणक = संचिका_विवरणक;
    }

    public int आयडेंटिफायर_मूल्य() {
        return आयडेंटिफायर_मूल्य;
    }

    public int जनक_आयडेंटिफायर() {
        return जनक_आयडेंटिफायर;
    }

    public पृष्ठ_व्यवस्थापक.पत्ता_जागा पत्ता_जागा() {
        return पत्ता_जागा;
    }

    public संचिका_विवरणक_सारणी संचिका_विवरणक() {
        return संचिका_विवरणक;
    }

    public प्रक्रिया_राज्य राज्य_मूल्य() {
        return राज्य_मूल्य;
    }

    public void राज्य_संच(प्रक्रिया_राज्य नवे_राज्य) {
        राज्य_मूल्य = नवे_राज्य;
    }

    public int निर्गमन_करा_संहिता() {
        return निर्गमन_करा_संहिता;
    }

    public void निर्गमन_करा_अनुप्रयोग(int मूल्य) {
        निर्गमन_करा_संहिता = मूल्य & 0xff;
        राज्य_मूल्य = प्रक्रिया_राज्य.निर्गमन_करा_अनुप्रयोग;
    }

    public int अनुप्रयोग_खंड() {
        return अनुप्रयोग_खंड;
    }

    public void अनुप्रयोग_खंड_संच(int नवे_शेवट_करा) {
        if (नवे_शेवट_करा < 0x06000000 || नवे_शेवट_करा > 0x07000000) {
            throw new IllegalArgumentException("अनुप्रयोग_f5044b9b शेवट 범위를 벗어났습니다.");
        }
        अनुप्रयोग_खंड = नवे_शेवट_करा;
    }

    public void निष्पादन_संदर्भ_संच(int प्रारंभ_पत्ता, String[] परिमापन_वितर्क, String[] पर्यावरण) {
        निष्पादन_प्रारंभ_पत्ता = प्रारंभ_पत्ता;
        निष्पादन_वितर्क = परिमापन_वितर्क.clone();
        पर्यावरण_मूल्य = पर्यावरण.clone();
    }

    public int निष्पादन_प्रारंभ_पत्ता() { return निष्पादन_प्रारंभ_पत्ता; }
    public String[] निष्पादन_वितर्क() { return निष्पादन_वितर्क.clone(); }
    public String[] पर्यावरण_मूल्य() { return पर्यावरण_मूल्य.clone(); }
}
