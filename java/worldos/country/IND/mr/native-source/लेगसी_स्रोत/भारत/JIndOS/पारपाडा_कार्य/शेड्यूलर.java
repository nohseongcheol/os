package भारत.JIndOS.पारपाडा_कार्य;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import भारत.JIndOS.स्मृती_प्रदेश.पृष्ठ_व्यवस्थापक;
import भारत.JIndOS.फाइल_सिस्टम.संचिका_विवरणक_सारणी;

/** प्रक्रिया ओळखचिन्हे आणि आळीपाळीची सज्ज रांग सांभाळते. */
public final class शेड्यूलर {
    private final पृष्ठ_व्यवस्थापक पृष्ठ_व्यवस्थापन;
    private final Map<Integer, प्रक्रिया_मूल्य> प्रक्रिया_यादी = new HashMap<Integer, प्रक्रिया_मूल्य>();
    private final Queue<प्रक्रिया_मूल्य> सज्ज_रांग = new ArrayDeque<प्रक्रिया_मूल्य>();
    private int पुढील_आयडेंटिफायर = 1;

    public शेड्यूलर(पृष्ठ_व्यवस्थापक पृष्ठ_व्यवस्थापन) {
        this.पृष्ठ_व्यवस्थापन = पृष्ठ_व्यवस्थापन;
    }

    public प्रक्रिया_मूल्य पहिले_प्रक्रिया(संचिका_विवरणक_सारणी संचिका_विवरणक) {
        प्रक्रिया_मूल्य नवे_प्रक्रिया = new प्रक्रिया_मूल्य(आयडेंटिफायर_वाटप_करा(), 0, पृष्ठ_व्यवस्थापन.नवे_पत्ता_जागा(), संचिका_विवरणक);
        प्रक्रिया_यादी.put(Integer.valueOf(नवे_प्रक्रिया.आयडेंटिफायर_मूल्य()), नवे_प्रक्रिया);
        सज्ज_रांग.offer(नवे_प्रक्रिया);
        return नवे_प्रक्रिया;
    }

    public प्रक्रिया_मूल्य प्रतबनवा_मूल्य(प्रक्रिया_मूल्य जनक_मूल्य) {
        प्रक्रिया_मूल्य उपघटक_मूल्य = new प्रक्रिया_मूल्य(
                आयडेंटिफायर_वाटप_करा(),
                जनक_मूल्य.आयडेंटिफायर_मूल्य(),
                पृष्ठ_व्यवस्थापन.प्रतबनवा_इन्स्टन्स_चालू_लिहा(जनक_मूल्य.पत्ता_जागा()),
                जनक_मूल्य.संचिका_विवरणक().प्रतबनवा_मूल्य());
        उपघटक_मूल्य.अनुप्रयोग_खंड_संच(जनक_मूल्य.अनुप्रयोग_खंड());
        प्रक्रिया_यादी.put(Integer.valueOf(उपघटक_मूल्य.आयडेंटिफायर_मूल्य()), उपघटक_मूल्य);
        सज्ज_रांग.offer(उपघटक_मूल्य);
        return उपघटक_मूल्य;
    }

    public प्रक्रिया_मूल्य पुढील_प्रक्रिया() {
        int संख्या_तपासा = सज्ज_रांग.size();
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < संख्या_तपासा; अनुक्रमणिका++) {
            प्रक्रिया_मूल्य पुढील_आयटम = सज्ज_रांग.poll();
            if (पुढील_आयटम != null && (पुढील_आयटम.राज्य_मूल्य() == प्रक्रिया_राज्य.तयार_करणे || पुढील_आयटम.राज्य_मूल्य() == प्रक्रिया_राज्य.आज्ञा_कार्यवाही_करा)) {
                पुढील_आयटम.राज्य_संच(प्रक्रिया_राज्य.आज्ञा_कार्यवाही_करा);
                सज्ज_रांग.offer(पुढील_आयटम);
                return पुढील_आयटम;
            }
        }
        return null;
    }

    public int प्रतीक्षा_करा_साठी_उपघटक(प्रक्रिया_मूल्य जनक_मूल्य, int उपघटक_आयडेंटिफायर, boolean अभाव_रोखणारे) {
        for (प्रक्रिया_मूल्य उमेदवार : प्रक्रिया_यादी.values()) {
            if (उमेदवार.जनक_आयडेंटिफायर() != जनक_मूल्य.आयडेंटिफायर_मूल्य()) {
                continue;
            }
            if (उपघटक_आयडेंटिफायर > 0 && उमेदवार.आयडेंटिफायर_मूल्य() != उपघटक_आयडेंटिफायर) {
                continue;
            }
            if (उमेदवार.राज्य_मूल्य() == प्रक्रिया_राज्य.निर्गमन_करा_अनुप्रयोग) {
                int मोजमाप = (उमेदवार.निर्गमन_करा_संहिता() & 0xff) << 8;
                प्रक्रिया_यादी.remove(Integer.valueOf(उमेदवार.आयडेंटिफायर_मूल्य()));
                return मोजमाप;
            }
            return अभाव_रोखणारे ? 0 : -11;
        }
        return -10;
    }

    public प्रक्रिया_मूल्य प्रक्रिया_शोधा(int आयडेंटिफायर_मूल्य) {
        return प्रक्रिया_यादी.get(Integer.valueOf(आयडेंटिफायर_मूल्य));
    }

    private int आयडेंटिफायर_वाटप_करा() {
        return पुढील_आयडेंटिफायर++;
    }
}
