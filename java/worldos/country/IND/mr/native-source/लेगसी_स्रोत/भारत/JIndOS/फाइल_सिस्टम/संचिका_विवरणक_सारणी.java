package भारत.JIndOS.फाइल_सिस्टम;

import java.util.HashMap;
import java.util.Map;

/** प्रत्येक प्रक्रियेसाठी स्वतंत्र वर्णक आणि सामायिक करता येणारी उघड्या संचिकांची वर्णने राखते. */
public final class संचिका_विवरणक_सारणी {
    private static final int कमाल_विवरणक = 32;

    private static final class विवरणक_प्रविष्टी {
        private final फाइल_सिस्टम.उघडलेले_संचिका उघडलेले_संचिका;
        private boolean चालू_निष्पादन_मिटवा;

        विवरणक_प्रविष्टी(फाइल_सिस्टम.उघडलेले_संचिका उघडलेले_संचिका) {
            this.उघडलेले_संचिका = उघडलेले_संचिका;
        }
    }

    private final फाइल_सिस्टम फाइल_सिस्टम;
    private final Map<Integer, विवरणक_प्रविष्टी> विवरणक_नोंदी = new HashMap<Integer, विवरणक_प्रविष्टी>();

    public संचिका_विवरणक_सारणी(फाइल_सिस्टम फाइल_सिस्टम) {
        this.फाइल_सिस्टम = फाइल_सिस्टम;
    }

    public int उघडा(String नाव) {
        फाइल_सिस्टम.उघडलेले_संचिका उघडलेले_संचिका = फाइल_सिस्टम.उघडा(नाव);
        if (उघडलेले_संचिका == null) {
            return -2;
        }
        int अनुक्रमणिका = रिक्त_अनुक्रमणिका(3);
        if (अनुक्रमणिका < 0) {
            return -24;
        }
        विवरणक_नोंदी.put(Integer.valueOf(अनुक्रमणिका), new विवरणक_प्रविष्टी(उघडलेले_संचिका));
        return अनुक्रमणिका;
    }

    public int वाचन(int अनुक्रमणिका, byte[] गंतव्यस्थान_स्वीकारा, int आकार) {
        विवरणक_प्रविष्टी प्रविष्टी_मूल्य = विवरणक_नोंदी.get(Integer.valueOf(अनुक्रमणिका));
        if (प्रविष्टी_मूल्य == null) {
            return -9;
        }
        if (आकार < 0 || आकार > गंतव्यस्थान_स्वीकारा.length) {
            return -22;
        }
        int बाकी_डेटा = प्रविष्टी_मूल्य.उघडलेले_संचिका.डेटा.length - प्रविष्टी_मूल्य.उघडलेले_संचिका.जागा;
        int आकारा_वाचा = Math.min(आकार, Math.max(बाकी_डेटा, 0));
        System.arraycopy(प्रविष्टी_मूल्य.उघडलेले_संचिका.डेटा, प्रविष्टी_मूल्य.उघडलेले_संचिका.जागा, गंतव्यस्थान_स्वीकारा, 0, आकारा_वाचा);
        प्रविष्टी_मूल्य.उघडलेले_संचिका.जागा += आकारा_वाचा;
        return आकारा_वाचा;
    }

    public int हलवा_स्थान(int अनुक्रमणिका, int अंतर_मूल्य, int प्रोजेक्ट_मूळ) {
        विवरणक_प्रविष्टी प्रविष्टी_मूल्य = विवरणक_नोंदी.get(Integer.valueOf(अनुक्रमणिका));
        if (प्रविष्टी_मूल्य == null) {
            return -9;
        }
        int वॉलपेपर_मूल्य;
        if (प्रोजेक्ट_मूळ == 0) {
            वॉलपेपर_मूल्य = 0;
        } else if (प्रोजेक्ट_मूळ == 1) {
            वॉलपेपर_मूल्य = प्रविष्टी_मूल्य.उघडलेले_संचिका.जागा;
        } else if (प्रोजेक्ट_मूळ == 2) {
            वॉलपेपर_मूल्य = प्रविष्टी_मूल्य.उघडलेले_संचिका.डेटा.length;
        } else {
            return -22;
        }
        int नवे_स्थान = वॉलपेपर_मूल्य + अंतर_मूल्य;
        if (नवे_स्थान < 0) {
            return -22;
        }
        प्रविष्टी_मूल्य.उघडलेले_संचिका.जागा = नवे_स्थान;
        return नवे_स्थान;
    }

    public int बंद_करा(int अनुक्रमणिका) {
        विवरणक_प्रविष्टी प्रविष्टी_मूल्य = विवरणक_नोंदी.remove(Integer.valueOf(अनुक्रमणिका));
        if (प्रविष्टी_मूल्य == null) {
            return -9;
        }
        प्रविष्टी_मूल्य.उघडलेले_संचिका.संदर्भ_संख्या--;
        return 0;
    }

    public int प्रतिलिपित_विवरणक(int अनुक्रमणिका, int किमान_संख्या) {
        विवरणक_प्रविष्टी प्रविष्टी_मूल्य = विवरणक_नोंदी.get(Integer.valueOf(अनुक्रमणिका));
        if (प्रविष्टी_मूल्य == null) {
            return -9;
        }
        int नवे_संख्या = रिक्त_अनुक्रमणिका(किमान_संख्या);
        if (नवे_संख्या < 0) {
            return -24;
        }
        प्रविष्टी_मूल्य.उघडलेले_संचिका.संदर्भ_संख्या++;
        विवरणक_नोंदी.put(Integer.valueOf(नवे_संख्या), new विवरणक_प्रविष्टी(प्रविष्टी_मूल्य.उघडलेले_संचिका));
        return नवे_संख्या;
    }

    public int प्रतिरूप_येथे(int अनुक्रमणिका, int नवे_संख्या) {
        if (अनुक्रमणिका == नवे_संख्या) {
            return विवरणक_नोंदी.containsKey(Integer.valueOf(अनुक्रमणिका)) ? अनुक्रमणिका : -9;
        }
        if (नवे_संख्या < 0 || नवे_संख्या >= कमाल_विवरणक) {
            return -9;
        }
        विवरणक_प्रविष्टी मूळ = विवरणक_नोंदी.get(Integer.valueOf(अनुक्रमणिका));
        if (मूळ == null) {
            return -9;
        }
        if (विवरणक_नोंदी.containsKey(Integer.valueOf(नवे_संख्या))) {
            बंद_करा(नवे_संख्या);
        }
        मूळ.उघडलेले_संचिका.संदर्भ_संख्या++;
        विवरणक_नोंदी.put(Integer.valueOf(नवे_संख्या), new विवरणक_प्रविष्टी(मूळ.उघडलेले_संचिका));
        return नवे_संख्या;
    }

    public int मिटवा_चालू_निष्पादन_संच(int अनुक्रमणिका, boolean मूल्य) {
        विवरणक_प्रविष्टी प्रविष्टी_मूल्य = विवरणक_नोंदी.get(Integer.valueOf(अनुक्रमणिका));
        if (प्रविष्टी_मूल्य == null) {
            return -9;
        }
        प्रविष्टी_मूल्य.चालू_निष्पादन_मिटवा = मूल्य;
        return 0;
    }

    public int चालू_निष्पादन_मूल्य_मिटवा(int अनुक्रमणिका) {
        विवरणक_प्रविष्टी प्रविष्टी_मूल्य = विवरणक_नोंदी.get(Integer.valueOf(अनुक्रमणिका));
        if (प्रविष्टी_मूल्य == null) {
            return -9;
        }
        return प्रविष्टी_मूल्य.चालू_निष्पादन_मिटवा ? 1 : 0;
    }

    public संचिका_माहिती सिस्टम_माहिती(int अनुक्रमणिका) {
        if (अनुक्रमणिका >= 0 && अनुक्रमणिका <= 2) {
            return new संचिका_माहिती(0, 0020666);
        }
        विवरणक_प्रविष्टी प्रविष्टी_मूल्य = विवरणक_नोंदी.get(Integer.valueOf(अनुक्रमणिका));
        if (प्रविष्टी_मूल्य == null) {
            return null;
        }
        return new संचिका_माहिती(प्रविष्टी_मूल्य.उघडलेले_संचिका.डेटा.length, 0100444);
    }

    public void चालू_निष्पादन_मिटवा() {
        Integer[] संख्या_यादी = विवरणक_नोंदी.keySet().toArray(new Integer[0]);
        for (Integer अनुक्रमणिका : संख्या_यादी) {
            विवरणक_प्रविष्टी प्रविष्टी_मूल्य = विवरणक_नोंदी.get(अनुक्रमणिका);
            if (प्रविष्टी_मूल्य != null && प्रविष्टी_मूल्य.चालू_निष्पादन_मिटवा) {
                बंद_करा(अनुक्रमणिका.intValue());
            }
        }
    }

    public boolean आहे_उघडा(int अनुक्रमणिका) {
        return विवरणक_नोंदी.containsKey(Integer.valueOf(अनुक्रमणिका));
    }

    public संचिका_विवरणक_सारणी प्रतबनवा_मूल्य() {
        संचिका_विवरणक_सारणी मोजमाप = new संचिका_विवरणक_सारणी(फाइल_सिस्टम);
        for (Map.Entry<Integer, विवरणक_प्रविष्टी> प्रविष्टी_मूल्य : विवरणक_नोंदी.entrySet()) {
            प्रविष्टी_मूल्य.getValue().उघडलेले_संचिका.संदर्भ_संख्या++;
            विवरणक_प्रविष्टी नवे_विवरणक = new विवरणक_प्रविष्टी(प्रविष्टी_मूल्य.getValue().उघडलेले_संचिका);
            नवे_विवरणक.चालू_निष्पादन_मिटवा = प्रविष्टी_मूल्य.getValue().चालू_निष्पादन_मिटवा;
            मोजमाप.विवरणक_नोंदी.put(प्रविष्टी_मूल्य.getKey(), नवे_विवरणक);
        }
        return मोजमाप;
    }

    private int रिक्त_अनुक्रमणिका(int किमान_संख्या) {
        for (int अनुक्रमणिका = Math.max(0, किमान_संख्या); अनुक्रमणिका < कमाल_विवरणक; अनुक्रमणिका++) {
            if (!विवरणक_नोंदी.containsKey(Integer.valueOf(अनुक्रमणिका))) {
                return अनुक्रमणिका;
            }
        }
        return -1;
    }
}
