package भारत.JIndOS.संचारजाळे_स्टॅक;

import java.util.HashMap;
import java.util.Map;

/** Ethernet, ARP, IPv4, ICMP, UDP आणि TCP स्वीकाराचे वाटप एकाच ठिकाणी सांभाळते. */
public final class संचारजाळे_थर {
    @FunctionalInterface
    public interface डेटा_हाताळक {
        void प्रक्रिया_मूल्य_प्रविष्टी(byte[] डेटा, int सुरू_करा, int लांबी_मूल्य);
    }

    private final Map<Integer, डेटा_हाताळक> इथरनेट_हाताळक = new HashMap<Integer, डेटा_हाताळक>();
    private final Map<Integer, डेटा_हाताळक> इंटरनेट_प्रोटोकॉल_हाताळक = new HashMap<Integer, डेटा_हाताळक>();
    private final Map<Integer, डेटा_हाताळक> प्रयोक्ता_डेटा_एकक_हाताळक = new HashMap<Integer, डेटा_हाताळक>();
    private final Map<Integer, डेटा_हाताळक> प्रसारण_नियंत्रण_हाताळक = new HashMap<Integer, डेटा_हाताळक>();

    public void रजिस्टर_इथरनेट(int प्रकार_मूल्य, डेटा_हाताळक हाताळक) {
        इथरनेट_हाताळक.put(Integer.valueOf(प्रकार_मूल्य & 0xffff), हाताळक);
    }

    public void रजिस्टर_इंटरनेट_प्रोटोकॉल(int काम_मूल्य, डेटा_हाताळक हाताळक) {
        इंटरनेट_प्रोटोकॉल_हाताळक.put(Integer.valueOf(काम_मूल्य & 0xff), हाताळक);
    }

    public void रजिस्टर_प्रयोक्ता_डेटा_एकक(int हार्डवेअर_पॉर्ट, डेटा_हाताळक हाताळक) {
        प्रयोक्ता_डेटा_एकक_हाताळक.put(Integer.valueOf(हार्डवेअर_पॉर्ट & 0xffff), हाताळक);
    }

    public void रजिस्टर_प्रसारण_नियंत्रण(int हार्डवेअर_पॉर्ट, डेटा_हाताळक हाताळक) {
        प्रसारण_नियंत्रण_हाताळक.put(Integer.valueOf(हार्डवेअर_पॉर्ट & 0xffff), हाताळक);
    }

    public boolean इथरनेट_स्वीकारा(byte[] फ्रेम_अनुक्रमणिका) {
        if (!संचारजाळे_साधने.आहे_इथरनेट_फ्रेम(फ्रेम_अनुक्रमणिका)) {
            return false;
        }
        int प्रकार_मूल्य = संचारजाळे_साधने.इथरनेट_वरचे_प्रोटोकॉल(फ्रेम_अनुक्रमणिका);
        डेटा_हाताळक थेट_हाताळक = इथरनेट_हाताळक.get(Integer.valueOf(प्रकार_मूल्य));
        if (थेट_हाताळक != null) {
            थेट_हाताळक.प्रक्रिया_मूल्य_प्रविष्टी(फ्रेम_अनुक्रमणिका, 14, फ्रेम_अनुक्रमणिका.length - 14);
            return true;
        }
        return प्रकार_मूल्य == 0x0800 && क्लाउड_पॅकेट_स्वीकारा(फ्रेम_अनुक्रमणिका, 14);
    }

    private boolean क्लाउड_पॅकेट_स्वीकारा(byte[] डेटा, int सुरू_करा) {
        if (!संचारजाळे_साधने.आहे_आयपीआवृत्ती_4_प्रोटोकॉल(डेटा, सुरू_करा)) {
            return false;
        }
        int शीर्षलेख_लांबी = (डेटा[सुरू_करा] & 0x0f) * 4;
        int एकूण_लांबी = संचारजाळे_साधने.मोठे_बाइटक्रम_लघु(डेटा, सुरू_करा + 2);
        if (एकूण_लांबी < शीर्षलेख_लांबी || सुरू_करा + एकूण_लांबी > डेटा.length) {
            return false;
        }
        int काम_मूल्य = डेटा[सुरू_करा + 9] & 0xff;
        int सामुग्री_प्रारंभ = सुरू_करा + शीर्षलेख_लांबी;
        int सामुग्री_लांबी = एकूण_लांबी - शीर्षलेख_लांबी;
        डेटा_हाताळक थेट_हाताळक = इंटरनेट_प्रोटोकॉल_हाताळक.get(Integer.valueOf(काम_मूल्य));
        if (थेट_हाताळक != null) {
            थेट_हाताळक.प्रक्रिया_मूल्य_प्रविष्टी(डेटा, सामुग्री_प्रारंभ, सामुग्री_लांबी);
            return true;
        }
        if (सामुग्री_लांबी < 4) {
            return false;
        }
        int गंतव्यस्थान_पोर्ट_नंबर = संचारजाळे_साधने.मोठे_बाइटक्रम_लघु(डेटा, सामुग्री_प्रारंभ + 2);
        Map<Integer, डेटा_हाताळक> पॉर्ट_सारणी = काम_मूल्य == 17 ? प्रयोक्ता_डेटा_एकक_हाताळक : काम_मूल्य == 6 ? प्रसारण_नियंत्रण_हाताळक : null;
        if (पॉर्ट_सारणी == null) {
            return false;
        }
        डेटा_हाताळक पॉर्ट_हाताळक = पॉर्ट_सारणी.get(Integer.valueOf(गंतव्यस्थान_पोर्ट_नंबर));
        if (पॉर्ट_हाताळक == null) {
            return false;
        }
        पॉर्ट_हाताळक.प्रक्रिया_मूल्य_प्रविष्टी(डेटा, सामुग्री_प्रारंभ, सामुग्री_लांबी);
        return true;
    }
}

