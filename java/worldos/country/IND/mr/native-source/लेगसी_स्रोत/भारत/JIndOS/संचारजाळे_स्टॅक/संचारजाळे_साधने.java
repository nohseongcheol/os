package भारत.JIndOS.संचारजाळे_स्टॅक;

/** Ethernet/ARP/IPv4/ICMP/UDP स्तरांसाठी समान बाइटक्रम आणि तपासबेरीज साधने. */
public final class संचारजाळे_साधने {
    private संचारजाळे_साधने() {
    }

    public static int मोठे_बाइटक्रम_लघु(byte[] डेटा, int जागा) {
        व्याप्ती_तपासा(डेटा, जागा, 2);
        return ((डेटा[जागा] & 0xff) << 8) | (डेटा[जागा + 1] & 0xff);
    }

    public static long मोठे_बाइटक्रम_पूर्णांक(byte[] डेटा, int जागा) {
        व्याप्ती_तपासा(डेटा, जागा, 4);
        return ((long) (डेटा[जागा] & 0xff) << 24)
                | ((long) (डेटा[जागा + 1] & 0xff) << 16)
                | ((long) (डेटा[जागा + 2] & 0xff) << 8)
                | (डेटा[जागा + 3] & 0xffL);
    }

    public static int क्लाउड_चेकसम(byte[] डेटा, int सुरू_करा, int लांबी_मूल्य) {
        व्याप्ती_तपासा(डेटा, सुरू_करा, लांबी_मूल्य);
        long बेरीज_मूल्य = 0;
        int शेवट = सुरू_करा + लांबी_मूल्य;
        int जागा = सुरू_करा;
        while (जागा + 1 < शेवट) {
            बेरीज_मूल्य += मोठे_बाइटक्रम_लघु(डेटा, जागा);
            जागा += 2;
        }
        if (जागा < शेवट) {
            बेरीज_मूल्य += (डेटा[जागा] & 0xff) << 8;
        }
        while ((बेरीज_मूल्य >>> 16) != 0) {
            बेरीज_मूल्य = (बेरीज_मूल्य & 0xffff) + (बेरीज_मूल्य >>> 16);
        }
        return (int) (~बेरीज_मूल्य) & 0xffff;
    }

    public static boolean आहे_इथरनेट_फ्रेम(byte[] डेटा) {
        return डेटा != null && डेटा.length >= 14;
    }

    public static int इथरनेट_वरचे_प्रोटोकॉल(byte[] डेटा) {
        if (!आहे_इथरनेट_फ्रेम(डेटा)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return मोठे_बाइटक्रम_लघु(डेटा, 12);
    }

    public static boolean आहे_आयपीआवृत्ती_4_प्रोटोकॉल(byte[] डेटा, int जागा) {
        if (डेटा == null || जागा < 0 || डेटा.length - जागा < 20) {
            return false;
        }
        int आवृत्ती_मूल्य = (डेटा[जागा] >>> 4) & 0xf;
        int शीर्षलेख_लांबी = (डेटा[जागा] & 0xf) * 4;
        return आवृत्ती_मूल्य == 4 && शीर्षलेख_लांबी >= 20 && डेटा.length - जागा >= शीर्षलेख_लांबी;
    }

    private static void व्याप्ती_तपासा(byte[] डेटा, int सुरू_करा, int लांबी_मूल्य) {
        if (डेटा == null || सुरू_करा < 0 || लांबी_मूल्य < 0 || सुरू_करा > डेटा.length - लांबी_मूल्य) {
            throw new IllegalArgumentException("संचारजाळे_स्टॅक डेटा 범위를 벗어났습니다.");
        }
    }
}

