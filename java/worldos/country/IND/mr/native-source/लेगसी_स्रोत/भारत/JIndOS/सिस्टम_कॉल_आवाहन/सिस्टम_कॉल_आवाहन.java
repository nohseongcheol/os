    public int अनुप्रयोग_खंड(प्रक्रिया_मूल्य सध्याचे_प्रक्रिया, int नवे_शेवट_करा) {
        int मागील_शेवट_करा = सध्याचे_प्रक्रिया.अनुप्रयोग_खंड();
        if (नवे_शेवट_करा == 0) {
            return मागील_शेवट_करा;
        }
        if (नवे_शेवट_करा < 0x06000000 || नवे_शेवट_करा > 0x07000000) {
            return -12;
        }
        int पहिले_पृष्ठ = मागील_शेवट_करा / पृष्ठ_व्यवस्थापक.पृष्ठ_आकार;
        int शेवटचे_पृष्ठ = (नवे_शेवट_करा + पृष्ठ_व्यवस्थापक.पृष्ठ_आकार - 1) / पृष्ठ_व्यवस्थापक.पृष्ठ_आकार;
        if (नवे_शेवट_करा > मागील_शेवट_करा) {
            for (int अनुक्रमणिका = पहिले_पृष्ठ; अनुक्रमणिका < शेवटचे_पृष्ठ; अनुक्रमणिका++) {
                int पत्ता = अनुक्रमणिका * पृष्ठ_व्यवस्थापक.पृष्ठ_आकार;
                try {
                    पृष्ठ_व्यवस्थापन.बाइट_मूल्य_वाचा(सध्याचे_प्रक्रिया.पत्ता_जागा(), पत्ता);
                } catch (IllegalStateException त्रुटी) {
                    पृष्ठ_व्यवस्थापन.मॅप_करा_पृष्ठ(सध्याचे_प्रक्रिया.पत्ता_जागा(), पत्ता, true);
                }
            }
        }
        सध्याचे_प्रक्रिया.अनुप्रयोग_खंड_संच(नवे_शेवट_करा);
        return नवे_शेवट_करा;
    }

    public int वाढवा_अनुप्रयोग_खंड(प्रक्रिया_मूल्य सध्याचे_प्रक्रिया, int वाढ_रक्कम) {
        int मागील_शेवट_करा = सध्याचे_प्रक्रिया.अनुप्रयोग_खंड();
        int मोजमाप = अनुप्रयोग_खंड(सध्याचे_प्रक्रिया, मागील_शेवट_करा + वाढ_रक्कम);
        return मोजमाप < 0 ? मोजमाप : मागील_शेवट_करा;
    }

    public int आज्ञा_कार्यवाही_करा(प्रक्रिया_मूल्य सध्याचे_प्रक्रिया, byte[] निष्पादनीय_संचिका) {
        return आज्ञा_कार्यवाही_करा(सध्याचे_प्रक्रिया, निष्पादनीय_संचिका, new String[0], new String[0]);
    }

    public int आज्ञा_कार्यवाही_करा(प्रक्रिया_मूल्य सध्याचे_प्रक्रिया, byte[] निष्पादनीय_संचिका, String[] परिमापन_वितर्क, String[] पर्यावरण) {
        निष्पादनीय_भारक.चित्र चित्र_मूल्य;
        try {
            चित्र_मूल्य = भारक.पडताळण्या(निष्पादनीय_संचिका);
        } catch (IllegalArgumentException त्रुटी) {
            return -8;
        }
        if (परिमापन_वितर्क == null || पर्यावरण == null || परिमापन_वितर्क.length > 16 || पर्यावरण.length > 16) {
            return -7;
        }
        for (निष्पादनीय_भारक.विभाग_मूल्य विभाग_मूल्य : चित्र_मूल्य.विभाग_यादी()) {
            if ((विभाग_मूल्य.ध्वजांकित_करा_मूल्य() & 2) == 0 || विभाग_मूल्य.आकार() == 0) {
                continue;
            }
            int पहिले_पृष्ठ = विभाग_मूल्य.पत्ता() / पृष्ठ_व्यवस्थापक.पृष्ठ_आकार;
            int शेवटचे_पृष्ठ = (विभाग_मूल्य.पत्ता() + विभाग_मूल्य.आकार() + पृष्ठ_व्यवस्थापक.पृष्ठ_आकार - 1) / पृष्ठ_व्यवस्थापक.पृष्ठ_आकार;
            for (int अनुक्रमणिका = पहिले_पृष्ठ; अनुक्रमणिका < शेवटचे_पृष्ठ; अनुक्रमणिका++) {
                int पत्ता = अनुक्रमणिका * पृष्ठ_व्यवस्थापक.पृष्ठ_आकार;
                try {
                    पृष्ठ_व्यवस्थापन.बाइट_मूल्य_वाचा(सध्याचे_प्रक्रिया.पत्ता_जागा(), पत्ता);
                    पृष्ठ_व्यवस्थापन.निजी_व्याप्ती_लिहा(सध्याचे_प्रक्रिया.पत्ता_जागा(), पत्ता, पृष्ठ_व्यवस्थापक.पृष्ठ_आकार);
                } catch (IllegalStateException त्रुटी) {
                    पृष्ठ_व्यवस्थापन.मॅप_करा_पृष्ठ(सध्याचे_प्रक्रिया.पत्ता_जागा(), पत्ता, true);
                }
            }
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < विभाग_मूल्य.आकार(); अनुक्रमणिका++) {
                byte मूल्य = विभाग_मूल्य.प्रकार_मूल्य() == 8 ? 0 : निष्पादनीय_संचिका[विभाग_मूल्य.संचिका_स्थान() + अनुक्रमणिका];
                पृष्ठ_व्यवस्थापन.बाइट_मूल्य_लिहा(सध्याचे_प्रक्रिया.पत्ता_जागा(), विभाग_मूल्य.पत्ता() + अनुक्रमणिका, मूल्य);
            }
        }
        सध्याचे_प्रक्रिया.निष्पादन_संदर्भ_संच(चित्र_मूल्य.प्रारंभ_पत्ता(), परिमापन_वितर्क, पर्यावरण);
        सध्याचे_प्रक्रिया.संचिका_विवरणक().चालू_निष्पादन_मिटवा();
        return 0;
    }

