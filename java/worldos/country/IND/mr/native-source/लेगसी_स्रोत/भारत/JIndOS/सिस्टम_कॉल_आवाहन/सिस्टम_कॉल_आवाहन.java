    public int वाचन(प्रक्रिया_मूल्य सध्याचे_प्रक्रिया, int विवरणक_प्रविष्टी, byte[] गंतव्यस्थान_स्वीकारा, int आकार) {
        if (विवरणक_प्रविष्टी == 0) {
            if (आकार <= 0 || गंतव्यस्थान_स्वीकारा.length == 0) {
                return 0;
            }
            आदान_इव्हेंट इव्हेंट = आदान_व्यवस्थापन.पुढील_इव्हेंट();
            if (इव्हेंट == null || इव्हेंट.इव्हेंट_प्रकार() != आदान_इव्हेंट.प्रकार_मूल्य.कळ_खाली) {
                return -11;
            }
            गंतव्यस्थान_स्वीकारा[0] = (byte) इव्हेंट.पहिले_मूल्य();
            return 1;
        }
        return सध्याचे_प्रक्रिया.संचिका_विवरणक().वाचन(विवरणक_प्रविष्टी, गंतव्यस्थान_स्वीकारा, आकार);
    }

    public int लेखन(प्रक्रिया_मूल्य सध्याचे_प्रक्रिया, int विवरणक_प्रविष्टी, byte[] डेटा, int आकार) {
        if (विवरणक_प्रविष्टी != 1 && विवरणक_प्रविष्टी != 2) {
            return सध्याचे_प्रक्रिया.संचिका_विवरणक().आहे_उघडा(विवरणक_प्रविष्टी) ? -30 : -9;
        }
        if (आकार < 0 || आकार > डेटा.length) {
            return -22;
        }
        मोबाइल_मूल्य.अनुक्रमिक_प्रदान(new String(डेटा, 0, आकार, java.nio.charset.StandardCharsets.UTF_8));
        return आकार;
    }

