package भारत.JIndOS.स्मृती_प्रदेश;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB पानांचे नकाशन आणि लिहिताना प्रत बनवण्याची सुविधा देते. */
public final class पृष्ठ_व्यवस्थापक {
    public static final int पृष्ठ_आकार = 4096;

    private static final class पृष्ठ_मूल्य {
        private byte[] डेटा = new byte[पृष्ठ_आकार];
        private int संदर्भ_संख्या = 1;
        private boolean शक्य_लिहा = true;
        private boolean इन्स्टन्स_चालू_लिहा;
    }

    public static final class पत्ता_जागा {
        private final Map<Integer, पृष्ठ_मूल्य> पृष्ठ_सारणी = new HashMap<Integer, पृष्ठ_मूल्य>();
    }

    public पत्ता_जागा नवे_पत्ता_जागा() {
        return new पत्ता_जागा();
    }

    public void मॅप_करा_पृष्ठ(पत्ता_जागा पत्ता_प्रदेश, int व्हर्च्युअल_पत्ता, boolean शक्य_लिहा) {
        int अनुक्रमणिका = पृष्ठ_संख्या(व्हर्च्युअल_पत्ता);
        पृष्ठ_मूल्य नवे_पृष्ठ = new पृष्ठ_मूल्य();
        नवे_पृष्ठ.शक्य_लिहा = शक्य_लिहा;
        पत्ता_प्रदेश.पृष्ठ_सारणी.put(Integer.valueOf(अनुक्रमणिका), नवे_पृष्ठ);
    }

    public पत्ता_जागा प्रतबनवा_इन्स्टन्स_चालू_लिहा(पत्ता_जागा मूळ) {
        पत्ता_जागा प्रतिलिपित_मूल्य_11f4b78c = new पत्ता_जागा();
        for (Map.Entry<Integer, पृष्ठ_मूल्य> प्रविष्टी_मूल्य : मूळ.पृष्ठ_सारणी.entrySet()) {
            पृष्ठ_मूल्य सामायिक_पृष्ठ = प्रविष्टी_मूल्य.getValue();
            सामायिक_पृष्ठ.संदर्भ_संख्या++;
            if (सामायिक_पृष्ठ.शक्य_लिहा) {
                सामायिक_पृष्ठ.शक्य_लिहा = false;
                सामायिक_पृष्ठ.इन्स्टन्स_चालू_लिहा = true;
            }
            प्रतिलिपित_मूल्य_11f4b78c.पृष्ठ_सारणी.put(प्रविष्टी_मूल्य.getKey(), सामायिक_पृष्ठ);
        }
        return प्रतिलिपित_मूल्य_11f4b78c;
    }

    public byte बाइट_मूल्य_वाचा(पत्ता_जागा पत्ता_प्रदेश, int व्हर्च्युअल_पत्ता) {
        पृष्ठ_मूल्य लक्ष्य = पृष्ठ_शोधा(पत्ता_प्रदेश, व्हर्च्युअल_पत्ता);
        return लक्ष्य.डेटा[Math.floorMod(व्हर्च्युअल_पत्ता, पृष्ठ_आकार)];
    }

    public void बाइट_मूल्य_लिहा(पत्ता_जागा पत्ता_प्रदेश, int व्हर्च्युअल_पत्ता, byte मूल्य) {
        int अनुक्रमणिका = पृष्ठ_संख्या(व्हर्च्युअल_पत्ता);
        पृष्ठ_मूल्य लक्ष्य = पृष्ठ_शोधा(पत्ता_प्रदेश, व्हर्च्युअल_पत्ता);
        if (!लक्ष्य.शक्य_लिहा) {
            if (!लक्ष्य.इन्स्टन्स_चालू_लिहा) {
                throw new IllegalStateException("वाचन 전용 쪽입니다.");
            }
            लक्ष्य = निजी_पृष्ठ_तयार_करा(पत्ता_प्रदेश, अनुक्रमणिका, लक्ष्य);
        }
        लक्ष्य.डेटा[Math.floorMod(व्हर्च्युअल_पत्ता, पृष्ठ_आकार)] = मूल्य;
    }

    public void निजी_व्याप्ती_लिहा(पत्ता_जागा पत्ता_प्रदेश, int प्रारंभ_पत्ता, int आकार) {
        if (आकार < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int शेवट_करा_पत्ता = Math.addExact(प्रारंभ_पत्ता, आकार);
        for (int पत्ता = प्रारंभ_पत्ता; पत्ता < शेवट_करा_पत्ता; पत्ता = (पृष्ठ_संख्या(पत्ता) + 1) * पृष्ठ_आकार) {
            int अनुक्रमणिका = पृष्ठ_संख्या(पत्ता);
            पृष्ठ_मूल्य लक्ष्य = पृष्ठ_शोधा(पत्ता_प्रदेश, पत्ता);
            if (लक्ष्य.इन्स्टन्स_चालू_लिहा) {
                निजी_पृष्ठ_तयार_करा(पत्ता_प्रदेश, अनुक्रमणिका, लक्ष्य);
            } else {
                लक्ष्य.शक्य_लिहा = true;
            }
        }
    }

    public void व्याप्ती_लिहा(पत्ता_जागा पत्ता_प्रदेश, int प्रारंभ_पत्ता, byte[] डेटा) {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < डेटा.length; अनुक्रमणिका++) {
            बाइट_मूल्य_लिहा(पत्ता_प्रदेश, प्रारंभ_पत्ता + अनुक्रमणिका, डेटा[अनुक्रमणिका]);
        }
    }

    private पृष्ठ_मूल्य निजी_पृष्ठ_तयार_करा(पत्ता_जागा पत्ता_प्रदेश, int अनुक्रमणिका, पृष्ठ_मूल्य सामायिक_पृष्ठ) {
        पृष्ठ_मूल्य निजी_पृष्ठ = new पृष्ठ_मूल्य();
        निजी_पृष्ठ.डेटा = Arrays.copyOf(सामायिक_पृष्ठ.डेटा, सामायिक_पृष्ठ.डेटा.length);
        निजी_पृष्ठ.शक्य_लिहा = true;
        निजी_पृष्ठ.इन्स्टन्स_चालू_लिहा = false;
        सामायिक_पृष्ठ.संदर्भ_संख्या--;
        पत्ता_प्रदेश.पृष्ठ_सारणी.put(Integer.valueOf(अनुक्रमणिका), निजी_पृष्ठ);
        return निजी_पृष्ठ;
    }

    private पृष्ठ_मूल्य पृष्ठ_शोधा(पत्ता_जागा पत्ता_प्रदेश, int पत्ता) {
        पृष्ठ_मूल्य लक्ष्य = पत्ता_प्रदेश.पृष्ठ_सारणी.get(Integer.valueOf(पृष्ठ_संख्या(पत्ता)));
        if (लक्ष्य == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return लक्ष्य;
    }

    private int पृष्ठ_संख्या(int पत्ता) {
        if (पत्ता < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return पत्ता / पृष्ठ_आकार;
    }
}

