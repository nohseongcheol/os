import नेपाली.निज.동작받이;
import नेपाली.निज.동작알림;

/** निज 커널의 Swing सन्झ्याल: ne 입력 → बटन → readme_फाइल_eb81d7d9 पाठ ताजा_गर्नुहोस्. */
public class झ्यालउदाहरण implements 실행할일, 동작받이 {
    private सन्झ्याल 인사창;
    private पाठ_क्षेत्र नाम_फाँट;
    private लेबुल 인사말;
    private int 인사횟수;

    public void सिर्जना_सन्झ्याल() {
        인사창 = new सन्झ्याल("ne Swing", 460, 300);
        인사창.थप्नुहोस्_तत्त्व(new लेबुल("नमस्ते", 20, 20, 420, 28));
        नाम_फाँट = new पाठ_क्षेत्र("ne", 20, 64, 420, 30);
        인사말 = new लेबुल("नमस्ते", 20, 152, 420, 28);
        인사창.थप्नुहोस्_तत्त्व(नाम_फाँट);
        인사창.थप्नुहोस्_तत्त्व(new बटन("인사하기", 20, 108, 180, 32, this));
        인사창.थप्नुहोस्_तत्त्व(인사말);
        인사창.थप्नुहोस्_तत्त्व(new लेबुल("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.शो_सन्झ्याल();
        출력.लेख्नुहोस्_रेखा("GUI 예제 तयार_गर्नुहोस्: झ्यालउदाहरण");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.लेख्नुहोस्_पाठ("नमस्ते, " + नाम_फाँट.글읽기() + "님! (" + 인사횟수 + ")");
        출력.लेख्नुहोस्_रेखा("GUI 인사: " + 인사말.글읽기());
    }

    public void कार्यान्वयन_गर्नुहोस्() { सिर्जना_सन्झ्याल(); }
    public void 동작받기(동작알림 알림) {
        출력.लेख्नुहोस्_रेखा("कार्य 알림: " + 알림.आदेश_पाठ());
        인사하기();
    }
    public static void चलाउनुहोस्() {
        घटना_लाइन.나중에실행(new झ्यालउदाहरण());
    }
}
