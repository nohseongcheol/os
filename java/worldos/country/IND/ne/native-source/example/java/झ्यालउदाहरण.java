import नेपाली.निज.सन्झ्याल;
import नेपाली.निज.लेबुल;
import नेपाली.निज.पाठ_क्षेत्र;
import नेपाली.निज.बटन;
import नेपाली.निज.घटना_लाइन;
import नेपाली.निज.출력;
