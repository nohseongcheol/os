/** 첫 IDE 장치의 512바이트 논리 सेक्सन_मान. 이 계층은 포맷을 만들거나 임의 장치를 지우지 않는다. */
public final class भण्डारण_मोबाइल_जडान {
    static boolean 사용가능 = false;
    static int[] सेक्सन_लगत = new int[512];
    static void 잠깐기다리기() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 4; अनुक्रमणिका++) मोबाइल_मान.입출력바이트읽기(0x3f6);
    }
    static int 준비기다리기(boolean 자료필요) {
        int चलाउनुहोस् = मोबाइल_मान.밀리초();
        while (मोबाइल_मान.밀리초() - चलाउनुहोस् < 500) {
            int स्थिति_मान = मोबाइल_मान.입출력바이트읽기(0x1f7);
            if (स्थिति_मान == 0 || स्थिति_मान == 255) return -19;
            if ((स्थिति_मान & 128) == 0) {
                if ((स्थिति_मान & 33) != 0) return -5;
                if (!자료필요 || (स्थिति_मान & 8) != 0) return 0;
            }
            मोबाइल_मान.잠시양보();
        }
        return -110;
    }
    static int 요청(int सेक्सन_मान, int आदेश) {
        if (सेक्सन_मान < 0 || सेक्सन_मान >= 2048) return -22;
        मोबाइल_मान.입출력바이트쓰기(0x3f6, 2); // polling; IDE IRQ 사용 안 함
        मोबाइल_मान.입출력바이트쓰기(0x1f6, 0xe0); 잠깐기다리기();
        int मापन = 준비기다리기(false);
        if (मापन < 0) return मापन;
        मोबाइल_मान.입출력바이트쓰기(0x1f2, 1);
        मोबाइल_मान.입출력바이트쓰기(0x1f3, सेक्सन_मान & 255);
        मोबाइल_मान.입출력바이트쓰기(0x1f4, (सेक्सन_मान >>> 8) & 255);
        मोबाइल_मान.입출력바이트쓰기(0x1f5, 0);
        मोबाइल_मान.입출력바이트쓰기(0x1f7, आदेश); 잠깐기다리기();
        return 준비기다리기(true);
    }
    static int पढनुहोस्(int सेक्सन_मान) {
        int मापन = 요청(सेक्सन_मान, 0x20);
        if (मापन < 0) return मापन;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 256; अनुक्रमणिका++) {
            int मान = मोबाइल_मान.입출력짧은수읽기(0x1f0);
            सेक्सन_लगत[अनुक्रमणिका * 2] = मान & 255; सेक्सन_लगत[अनुक्रमणिका * 2 + 1] = मान >>> 8;
        }
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int लेख्नुहोस्(int सेक्सन_मान) {
        if (!사용가능 || सेक्सन_मान < 1 || सेक्सन_मान > 518) return -19;
        int मापन = 요청(सेक्सन_मान, 0x30);
        if (मापन < 0) return मापन;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 256; अनुक्रमणिका++)
            मोबाइल_मान.입출력짧은수쓰기(0x1f0, सेक्सन_लगत[अनुक्रमणिका * 2] | सेक्सन_लगत[अनुक्रमणिका * 2 + 1] << 8);
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int 밀어쓰기() {
        if (!사용가능) return -19;
        मोबाइल_मान.입출력바이트쓰기(0x1f7, 0xe7); 잠깐기다리기();
        return 준비기다리기(false);
    }
    static int पदच्छेद_गर्नुहोस्_पूर्ण_सङ्ख्या(int स्थिति) {
        return सेक्सन_लगत[स्थिति] | सेक्सन_लगत[स्थिति + 1] << 8 | सेक्सन_लगत[स्थिति + 2] << 16 | सेक्सन_लगत[स्थिति + 3] << 24;
    }
    static void लेख्नुहोस्_पूर्ण_सङ्ख्या_मान(int स्थिति, int मान) {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 4; अनुक्रमणिका++) सेक्सन_लगत[स्थिति + अनुक्रमणिका] = (मान >>> (अनुक्रमणिका * 8)) & 255;
    }
}
