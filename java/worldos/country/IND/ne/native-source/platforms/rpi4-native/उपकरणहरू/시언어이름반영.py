#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 बाइट_मान 위치로 निज C 이름을 옮기는 일회성 이행 उपकरणहरू.

외부 구조체의 멤버, स्ट्रिङ_मान, C 표준 प्रकार्य_मान, 이식 규약은 보존한다.
입력은 परिवर्तन_मान 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

परियोजना_रूट = Path(__file__).resolve().parents[1]

def कार्यान्वयन_गर्नुहोस्_आदेश():
    분석 = json.loads((परियोजना_रूट/'build/한국어화/시언어분석.json').read_text())
    if 분석['त्रुटि']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    नाम_तालिका = json.loads((परियोजना_रूट/'명명/시언어이름.json').read_text())
    एसडि = set(json.loads((परियोजना_रूट/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:नाम_तालिका[प्रविष्टि_मान['नाम']] for 고유,प्रविष्टि_मान in 선언표.items()
                if प्रविष्टि_मान['नाम'] in नाम_तालिका and प्रविष्टि_मान['नाम'] not in एसडि}
    जडान_तालिका = {प्रविष्टि_मान['नाम']:नाम_तालिका[प्रविष्टि_मान['नाम']] for प्रविष्टि_मान in 선언표.values()
              if प्रविष्टि_मान.get('जडान')==4 and प्रविष्टि_मान['종류'] in (8,9)
              and प्रविष्टि_मान['नाम'] in नाम_तालिका and प्रविष्टि_मान['नाम'] not in एसडि}
    # सिर्जना_गर्नुहोस् AOT C·어셈블리·공개 SDK가 공유하는 바이너리 जडान 이름만 유지한다.
    머리 = ['/* नेपाली स्रोत_वृक्ष 이름과 기존 मेशिन जडान केस_मान. 자동 सिर्जना_गर्नुहोस्: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(जडान_तालिका.items())]
    머리 += ['#endif','']
    (परियोजना_रूट/'명명/기계연결이름.h').write_text('\n'.join(머리))
    परिवर्तनहरू_सूची = defaultdict(dict)
    for फाइल,अफसेट_मान,नाम,고유 in 분석['निर्देश']:
        if 고유 in 바꿀선언:
            परिवर्तनहरू_सूची[फाइल][अफसेट_मान] = (नाम,바꿀선언[고유])
    लग_रेकर्ड = ['फाइल\t원래바이트위치\t이전이름\t한국어이름']
    बेवास्ता_गर्नुहोस्_मान = []
    for फाइल,परिवर्तन_मान in परिवर्तनहरू_सूची.items():
        मार्ग = Path(फाइल); 원본 = मार्ग.read_bytes(); लगत = 원본
        for अफसेट_मान,(옛이름,새이름) in sorted(परिवर्तन_मान.items(),reverse=True):
            끝 = अफसेट_मान+len(옛이름.encode())
            if 원본[अफसेट_मान:끝] != 옛이름.encode():
                बेवास्ता_गर्नुहोस्_मान.append((str(मार्ग.relative_to(परियोजना_रूट)),अफसेट_मान,옛이름));continue
            लगत = लगत[:अफसेट_मान]+새이름.encode()+लगत[끝:]
            लग_रेकर्ड.append('{}\t{}\t{}\t{}'.format(मार्ग.relative_to(परियोजना_रूट),अफसेट_मान,옛이름,새이름))
        मार्ग.write_bytes(लगत)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    म्याक्रो_मान = {प्रविष्टि_मान['नाम']:नाम_तालिका[प्रविष्टि_मान['नाम']] for प्रविष्टि_मान in 선언표.values()
              if प्रविष्टि_मान['종류']==501 and प्रविष्टि_मान['नाम'] in नाम_तालिका and प्रविष्टि_मान['नाम'] not in एसडि}
    for मार्ग in sorted({Path(प्रविष्टि_मान['फाइल']) for प्रविष्टि_मान in 선언표.values()}):
        रेखा_सूची = मार्ग.read_text().splitlines(True); 이어짐 = False
        for अनुक्रमणिका,रेखा in enumerate(रेखा_सूची):
            전처리 = 이어짐 or bool(re.match(r'\s*#',रेखा))
            이어짐 = 전처리 and रेखा.rstrip().endswith('\\')
            if 전처리:
                विवरण_हेर्ने_सुविधा_तालिका = नाम_तालिका if re.match(r'\s*#\s*define\b',रेखा) or 이어짐 else म्याक्रो_मान
                रेखा_सूची[अनुक्रमणिका] = 낱말.sub(lambda 맞음: विवरण_हेर्ने_सुविधा_तालिका.get(맞음[0],맞음[0]) if 맞음[0] not in एसडि else 맞음[0],रेखा)
        मार्ग.write_text(''.join(रेखा_सूची))
    # 각 निज अनुवाद_स्रोत 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for मार्ग in sorted({Path(प्रविष्टि_मान['फाइल']) for प्रविष्टि_मान in 선언표.values()}):
        if मार्ग.suffix not in ('.c','.cpp'):continue
        समान_मान = '../' * len(मार्ग.relative_to(परियोजना_रूट).parts[:-1]) + '명명/기계연결이름.h'
        मार्ग.write_text('#include "'+समान_मान+'"\n'+मार्ग.read_text())
    (परियोजना_रूट/'명명/시언어이름대응.tsv').write_text('\n'.join(लग_रेकर्ड)+'\n')
    (परियोजना_रूट/'build/한국어화/전처리참조.json').write_text(json.dumps(बेवास्ता_गर्नुहोस्_मान,ensure_ascii=False,indent=2)+'\n')
    print('परिवर्तन_मान',len(लग_रेकर्ड)-1,'전처리 재검토',len(बेवास्ता_गर्नुहोस्_मान),'मेशिन जडान',len(जडान_तालिका))

if __name__=='__main__': कार्यान्वयन_गर्नुहोस्_आदेश()
