package भारत.JIndOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB पृष्ठ_मान 연결과 लेख्नुहोस् 시 복사를 제공한다. */
public final class पृष्ठ_प्रबन्धक {
    public static final int पृष्ठ_साइज = 4096;

    private static final class पृष्ठ_मान {
        private byte[] लगत = new byte[पृष्ठ_साइज];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class ठेगाना_स्थान {
        private final Map<Integer, पृष्ठ_मान> पृष्ठ_तालिका = new HashMap<Integer, पृष्ठ_मान>();
    }

    public ठेगाना_स्थान 새주소공간() {
        return new ठेगाना_स्थान();
    }

    public void मानचित्र_पृष्ठ(ठेगाना_स्थान 공간, int अवास्तविक_ठेगाना, boolean 쓰기가능) {
        int अनुक्रमणिका = 쪽번호(अवास्तविक_ठेगाना);
        पृष्ठ_मान 새쪽 = new पृष्ठ_मान();
        새쪽.쓰기가능 = 쓰기가능;
        공간.पृष्ठ_तालिका.put(Integer.valueOf(अनुक्रमणिका), 새쪽);
    }

    public ठेगाना_स्थान 쓰기시복사복제(ठेगाना_स्थान 원본) {
        ठेगाना_स्थान 복제본 = new ठेगाना_स्थान();
        for (Map.Entry<Integer, पृष्ठ_मान> प्रविष्टि_मान : 원본.पृष्ठ_तालिका.entrySet()) {
            पृष्ठ_मान 공유쪽 = प्रविष्टि_मान.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.पृष्ठ_तालिका.put(प्रविष्टि_मान.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(ठेगाना_स्थान 공간, int अवास्तविक_ठेगाना) {
        पृष्ठ_मान लक्ष्य = खोज_गर्नुहोस्_पृष्ठ(공간, अवास्तविक_ठेगाना);
        return लक्ष्य.लगत[Math.floorMod(अवास्तविक_ठेगाना, पृष्ठ_साइज)];
    }

    public void लेख्नुहोस्_बाइट_मान(ठेगाना_स्थान 공간, int अवास्तविक_ठेगाना, byte मान) {
        int अनुक्रमणिका = 쪽번호(अवास्तविक_ठेगाना);
        पृष्ठ_मान लक्ष्य = खोज_गर्नुहोस्_पृष्ठ(공간, अवास्तविक_ठेगाना);
        if (!लक्ष्य.쓰기가능) {
            if (!लक्ष्य.쓰기시복사) {
                throw new IllegalStateException("पढनुहोस् 전용 쪽입니다.");
            }
            लक्ष्य = सिर्जना_निजी_पृष्ठ(공간, अनुक्रमणिका, लक्ष्य);
        }
        लक्ष्य.लगत[Math.floorMod(अवास्तविक_ठेगाना, पृष्ठ_साइज)] = मान;
    }

    public void 범위개인쓰기(ठेगाना_स्थान 공간, int सुरु_ठेगाना, int आकार) {
        if (आकार < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int समाप्त_गर्नुहोस्_ठेगाना = Math.addExact(सुरु_ठेगाना, आकार);
        for (int ठेगाना = सुरु_ठेगाना; ठेगाना < समाप्त_गर्नुहोस्_ठेगाना; ठेगाना = (쪽번호(ठेगाना) + 1) * पृष्ठ_साइज) {
            int अनुक्रमणिका = 쪽번호(ठेगाना);
            पृष्ठ_मान लक्ष्य = खोज_गर्नुहोस्_पृष्ठ(공간, ठेगाना);
            if (लक्ष्य.쓰기시복사) {
                सिर्जना_निजी_पृष्ठ(공간, अनुक्रमणिका, लक्ष्य);
            } else {
                लक्ष्य.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(ठेगाना_स्थान 공간, int सुरु_ठेगाना, byte[] लगत) {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < लगत.length; अनुक्रमणिका++) {
            लेख्नुहोस्_बाइट_मान(공간, सुरु_ठेगाना + अनुक्रमणिका, लगत[अनुक्रमणिका]);
        }
    }

    private पृष्ठ_मान सिर्जना_निजी_पृष्ठ(ठेगाना_स्थान 공간, int अनुक्रमणिका, पृष्ठ_मान 공유쪽) {
        पृष्ठ_मान निजी_पृष्ठ = new पृष्ठ_मान();
        निजी_पृष्ठ.लगत = Arrays.copyOf(공유쪽.लगत, 공유쪽.लगत.length);
        निजी_पृष्ठ.쓰기가능 = true;
        निजी_पृष्ठ.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.पृष्ठ_तालिका.put(Integer.valueOf(अनुक्रमणिका), निजी_पृष्ठ);
        return निजी_पृष्ठ;
    }

    private पृष्ठ_मान खोज_गर्नुहोस्_पृष्ठ(ठेगाना_स्थान 공간, int ठेगाना) {
        पृष्ठ_मान लक्ष्य = 공간.पृष्ठ_तालिका.get(Integer.valueOf(쪽번호(ठेगाना)));
        if (लक्ष्य == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return लक्ष्य;
    }

    private int 쪽번호(int ठेगाना) {
        if (ठेगाना < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return ठेगाना / पृष्ठ_साइज;
    }
}

