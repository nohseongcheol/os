import 한국어.자체.ଓ୍ୱିଣ୍ଡୋ;
import 한국어.자체.ସୂଚକ;
import 한국어.자체.ପାଠ୍ୟ_କ୍ଷେତ୍ର;
import 한국어.자체.ବଟନ୍;
import 한국어.자체.ଘଟଣା_ପ୍ରତିଧାଡ଼ି;
import 한국어.자체.ନିର୍ଗମ;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing ଓ୍ୱିଣ୍ଡୋ: or 입력 → ବଟନ୍ → ମତେପଢନ୍ତୁ_eb81d7d9 ପାଠ୍ଯ ସତେଜ_କରନ୍ତୁ. */
public class 창예제 implements 실행할일, 동작받이 {
    private ଓ୍ୱିଣ୍ଡୋ 인사창;
    private ପାଠ୍ୟ_କ୍ଷେତ୍ର ନାମ_ଫିଲ୍ଡ;
    private ସୂଚକ 인사말;
    private int 인사횟수;

    public void ଖୋଲିବା_ଓ୍ୱିଣ୍ଡୋ() {
        인사창 = new ଓ୍ୱିଣ୍ଡୋ("or Swing", 460, 300);
        인사창.ଯୋଡ଼ିବା_ଉପାଦାନ(new ସୂଚକ("or", 20, 20, 420, 28));
        ନାମ_ଫିଲ୍ଡ = new ପାଠ୍ୟ_କ୍ଷେତ୍ର("or", 20, 64, 420, 30);
        인사말 = new ସୂଚକ("or", 20, 152, 420, 28);
        인사창.ଯୋଡ଼ିବା_ଉପାଦାନ(ନାମ_ଫିଲ୍ଡ);
        인사창.ଯୋଡ଼ିବା_ଉପାଦାନ(new ବଟନ୍("인사하기", 20, 108, 180, 32, this));
        인사창.ଯୋଡ଼ିବା_ଉପାଦାନ(인사말);
        인사창.ଯୋଡ଼ିବା_ଉପାଦାନ(new ସୂଚକ("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.ପ୍ରଦର୍ଶନ_କରିବା_ଓ୍ୱିଣ୍ଡୋ();
        ନିର୍ଗମ.ଲିଖନ_ରେଖା("GUI 예제 ପ୍ରସ୍ତୁତ: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.ଲିଖନ_ପାଠ("or, " + ନାମ_ଫିଲ୍ଡ.글읽기() + "님! (" + 인사횟수 + ")");
        ନିର୍ଗମ.ଲିଖନ_ରେଖା("GUI 인사: " + 인사말.글읽기());
    }

    public void ନିଷ୍ପାଦନ_କରନ୍ତୁ() { ଖୋଲିବା_ଓ୍ୱିଣ୍ଡୋ(); }
    public void 동작받기(동작알림 알림) {
        ନିର୍ଗମ.ଲିଖନ_ରେଖା("କାମ 알림: " + 알림.ନିର୍ଦ୍ଦେଶ_ପାଠ());
        인사하기();
    }
    public static void ଚଳାନ୍ତୁ() {
        ଘଟଣା_ପ୍ରତିଧାଡ଼ି.나중에실행(new 창예제());
    }
}
