/** COM1 직렬 출력과 VGA 80x25 문자 화면. 한글은 직렬 단말에 UTF-8로 출력한다. */
public final class ପାଠ_ଟର୍ମିନାଲ୍ {
    static int ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = 0;
    static int 색 = 7;

    static void ପ୍ରସ୍ତୁତ() {
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3f9, 0);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3fb, 0x80);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3f8, 1);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3f9, 0);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3fb, 3);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3fa, 0xc7);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3fc, 0x0b);
        지우기();
    }

    static void 직렬바이트(int ମୂଲ୍ୟ) {
        int 횟수 = 100000;
        while ((ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트읽기(0x3fd) & 0x20) == 0 && 횟수 > 0) 횟수--;
        if (횟수 > 0) ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3f8, ମୂଲ୍ୟ);
    }

    static void 지우기() {
        for (int ଅନୁକ୍ରମଣିକା = 0; ଅନୁକ୍ରମଣିକା < 2000; ଅନୁକ୍ରମଣିକା++) {
            ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(0xb8000 + ଅନୁକ୍ରମଣିକା * 2, 32);
            ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(0xb8001 + ଅନୁକ୍ରମଣିକା * 2, 색);
        }
        ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = 0;
        କରସର୍_ମୂଲ୍ୟ();
    }

    static void କରସର୍_ମୂଲ୍ୟ() {
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3d4, 14);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3d5, ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି >> 8);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3d4, 15);
        ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트쓰기(0x3d5, ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି & 255);
    }

    static void 화면문자(int ମୂଲ୍ୟ) {
        if (ମୂଲ୍ୟ == 13) return;
        if (ମୂଲ୍ୟ == 10) {
            ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = (ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି / 80 + 1) * 80;
        } else if (ମୂଲ୍ୟ == 8) {
            if (ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି > 0) {
                ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି--;
                ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(0xb8000 + ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି * 2, 32);
            }
        } else {
            ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(0xb8000 + ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି * 2, ମୂଲ୍ୟ < 128 ? ମୂଲ୍ୟ : '?');
            ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(0xb8001 + ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି * 2, 색);
            ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି++;
        }
        if (ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି >= 2000) {
            for (int ଅନୁକ୍ରମଣିକା = 0; ଅନୁକ୍ରମଣିକା < 3840; ଅନୁକ୍ରମଣିକା++)
                ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(0xb8000 + ଅନୁକ୍ରମଣିକା, ଡିଭାଇସ_ମୂଲ୍ୟ.기억읽기(0xb80a0 + ଅନୁକ୍ରମଣିକା));
            for (int ଅନୁକ୍ରମଣିକା = 1920; ଅନୁକ୍ରମଣିକା < 2000; ଅନୁକ୍ରମଣିକା++) {
                ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(0xb8000 + ଅନୁକ୍ରମଣିକା * 2, 32);
                ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(0xb8001 + ଅନୁକ୍ରମଣିକା * 2, 색);
            }
            ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = 1920;
        }
        କରସର୍_ମୂଲ୍ୟ();
    }

    static void 문자(int ମୂଲ୍ୟ) {
        if (ମୂଲ୍ୟ < 128) {
            if (ମୂଲ୍ୟ == 10) 직렬바이트(13);
            직렬바이트(ମୂଲ୍ୟ);
        } else if (ମୂଲ୍ୟ < 2048) {
            직렬바이트(0xc0 | (ମୂଲ୍ୟ >> 6));
            직렬바이트(0x80 | (ମୂଲ୍ୟ & 63));
        } else {
            직렬바이트(0xe0 | (ମୂଲ୍ୟ >> 12));
            직렬바이트(0x80 | ((ମୂଲ୍ୟ >> 6) & 63));
            직렬바이트(0x80 | (ମୂଲ୍ୟ & 63));
        }
        화면문자(ମୂଲ୍ୟ);
    }

    static void ଲେଖନ୍ତୁ(String ବିଷୟ_ମୂଲ୍ୟ) {
        for (int ଅନୁକ୍ରମଣିକା = 0; ଅନୁକ୍ରମଣିକା < ବିଷୟ_ମୂଲ୍ୟ.length(); ଅନୁକ୍ରମଣିକା++) 문자(ବିଷୟ_ମୂଲ୍ୟ.charAt(ଅନୁକ୍ରମଣିକା));
    }

    static void 수쓰기(int ମୂଲ୍ୟ) {
        // 양수로 바꾸지 않으므로 Integer.MIN_VALUE도 안전하다.
        if (ମୂଲ୍ୟ < 0) 문자('-');
        else ମୂଲ୍ୟ = -ମୂଲ୍ୟ;
        int ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା = 1000000000;
        boolean ଚଳାନ୍ତୁ = false;
        while (ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା > 0) {
            int ଅଙ୍କ_ମୂଲ୍ୟ = -(ମୂଲ୍ୟ / ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା);
            if (ଅଙ୍କ_ମୂଲ୍ୟ != 0 || ଚଳାନ୍ତୁ || ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା == 1) {
                문자('0' + ଅଙ୍କ_ମୂଲ୍ୟ);
                ଚଳାନ୍ତୁ = true;
            }
            ମୂଲ୍ୟ %= ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା;
            ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା /= 10;
        }
    }

    static int 직렬읽기() {
        if ((ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트읽기(0x3fd) & 1) != 0) return ଡିଭାଇସ_ମୂଲ୍ୟ.입출력바이트읽기(0x3f8);
        return -1;
    }
}
