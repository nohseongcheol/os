    static boolean ପରୀକ୍ଷିତ_ନାମ(int[] ବର୍ଣ୍ଣ_ମୂଲ୍ୟ, int ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ) {
        if (ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ < 1 || ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ > 63) return false;
        for (int 수 = 0; 수 < ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ; 수++) {
            int ମୂଲ୍ୟ = ବର୍ଣ୍ଣ_ମୂଲ୍ୟ[수];
            if (!(ମୂଲ୍ୟ >= 'a' && ମୂଲ୍ୟ <= 'z') && !(ମୂଲ୍ୟ >= 'A' && ମୂଲ୍ୟ <= 'Z')
                && !(ମୂଲ୍ୟ >= '0' && ମୂଲ୍ୟ <= '9') && ମୂଲ୍ୟ != '_' && ମୂଲ୍ୟ != '-' && ମୂଲ୍ୟ != '.') return false;
        }
        return ବର୍ଣ୍ଣ_ମୂଲ୍ୟ[0] != '.';
    }

    static int ଖୋଜିବା_ଏଣ୍ଟ୍ରି(int[] ବର୍ଣ୍ଣ_ମୂଲ୍ୟ, int ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ) {
        if (!ପରୀକ୍ଷିତ_ନାମ(ବର୍ଣ୍ଣ_ମୂଲ୍ୟ, ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ)) return -22;
        for (int 수 = 0; 수 < 8; 수++) {
            boolean 같음 = 이름들[수 * 64 + ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ] == 0;
            for (int ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = 0; ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି < ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ; ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି++) if (이름들[수 * 64 + ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] != ବର୍ଣ୍ଣ_ମୂଲ୍ୟ[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି]) 같음 = false;
            if (같음) return 수;
        }
        return -2;
    }

    static int ସଞ୍ଚୟ_କରିବା_ମୂଲ୍ୟ(int[] ବର୍ଣ୍ଣ_ମୂଲ୍ୟ, int ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ, int[] ଡାଟା, int ଆକାର) {
        if (!ପରୀକ୍ଷିତ_ନାମ(ବର୍ଣ୍ଣ_ମୂଲ୍ୟ, ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ) || ଆକାର < 0 || ଆକାର > ଡାଟା.length) return -22;
        if (ଆକାର > 최대크기) return -90;
        int ଅନୁକ୍ରମଣିକା = ଖୋଜିବା_ଏଣ୍ଟ୍ରି(ବର୍ଣ୍ଣ_ମୂଲ୍ୟ, ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ);
        if (ଅନୁକ୍ରମଣିକା == -2) {
            for (int 수 = 0; 수 < 8 && ଅନୁକ୍ରମଣିକା < 0; 수++) if (이름들[수 * 64] == 0 && 열림수[수] == 0) ଅନୁକ୍ରମଣିକା = 수;
            if (ଅନୁକ୍ରମଣିକା >= 0) 허가들[ଅନୁକ୍ରମଣିକା] = 438;
        }
        if (ଅନୁକ୍ରମଣିକା < 0) return -28;
        int ଠିକଣା = ଡିଭାଇସ_ମୂଲ୍ୟ.ଫାଇଲ୍_ମୋମରୀ() + ଅନୁକ୍ରମଣିକା * 최대크기;
        for (int 수 = 0; 수 < ଆକାର; 수++) ଡିଭାଇସ_ମୂଲ୍ୟ.ଲିଖନ_ମୋମରୀ(ଠିକଣା + 수, ଡାଟା[수]);
        for (int 수 = 0; 수 < 64; 수++) 이름들[ଅନୁକ୍ରମଣିକା * 64 + 수] = 수 < ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ ? ବର୍ଣ୍ଣ_ମୂଲ୍ୟ[수] : 0;
        ଅକାର_ତାଲିକା[ଅନୁକ୍ରମଣିକା] = ଆକାର;
        return ଆକାର;
    }

