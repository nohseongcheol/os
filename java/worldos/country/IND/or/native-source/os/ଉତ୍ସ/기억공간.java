/** 부팅 ସିଷ୍ଟମ୍_ସୂଚନା 조회와 4KiB 고정 ଆକାର 작업 ବିଭାଗ_ମୂଲ୍ୟ ବଣ୍ଟନ_ଷ୍ଟୋରେଜ୍/반환. 일반 물리 ପେଜ୍_ମୂଲ୍ୟ 관리자는 아니다. */
public final class 기억공간 {
    static int[] ବିଭାଗ_ମୂଲ୍ୟ = new int[8192];
    static int[] 사용 = new int[8];

    static int ପାର୍ସ_ଇଣ୍ଟିଜର(int ଠିକଣା) {
        return ଡିଭାଇସ_ମୂଲ୍ୟ.기억읽기(ଠିକଣା) | (ଡିଭାଇସ_ମୂଲ୍ୟ.기억읽기(ଠିକଣା + 1) << 8)
            | (ଡିଭାଇସ_ମୂଲ୍ୟ.기억읽기(ଠିକଣା + 2) << 16) | (ଡିଭାଇସ_ମୂଲ୍ୟ.기억읽기(ଠିକଣା + 3) << 24);
    }

    static int 위쪽기억크기() {
        int ସିଷ୍ଟମ୍_ସୂଚନା = ଡିଭାଇସ_ମୂଲ୍ୟ.부팅정보();
        if (ଡିଭାଇସ_ମୂଲ୍ୟ.부팅표식() != 0x2badb002 || ସିଷ୍ଟମ୍_ସୂଚନା == 0 || (ପାର୍ସ_ଇଣ୍ଟିଜର(ସିଷ୍ଟମ୍_ସୂଚନା) & 1) == 0) return -1;
        return ପାର୍ସ_ଇଣ୍ଟିଜର(ସିଷ୍ଟମ୍_ସୂଚନା + 8);
    }

    static int ବଣ୍ଟନ_ଷ୍ଟୋରେଜ୍() {
        for (int ଅନୁକ୍ରମଣିକା = 0; ଅନୁକ୍ରମଣିକା < 사용.length; ଅନୁକ୍ରମଣିକା++) {
            if (사용[ଅନୁକ୍ରମଣିକା] == 0) {
                사용[ଅନୁକ୍ରମଣିକା] = 1;
                for (int ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = 0; ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି < 1024; ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି++) ବିଭାଗ_ମୂଲ୍ୟ[ଅନୁକ୍ରମଣିକା * 1024 + ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 0;
                return ଅନୁକ୍ରମଣିକା;
            }
        }
        return -1;
    }

    static boolean 반환(int ଅନୁକ୍ରମଣିକା) {
        if (ଅନୁକ୍ରମଣିକା < 0 || ଅନୁକ୍ରମଣିକା >= 사용.length || 사용[ଅନୁକ୍ରମଣିକା] == 0) return false;
        사용[ଅନୁକ୍ରମଣିକା] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int ଅନୁକ୍ରମଣିକା = 0; ଅନୁକ୍ରମଣିକା < 사용.length; ଅନୁକ୍ରମଣିକା++) 개수 += 사용[ଅନୁକ୍ରମଣିକା];
        return 개수;
    }
}
