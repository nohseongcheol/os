    static int ସାରଣୀ_ଇଣ୍ଟିଜର(int ଅବସ୍ଥାନ) {
        return ଫାଇଲ୍_ସାରଣୀ[ଅବସ୍ଥାନ] | ଫାଇଲ୍_ସାରଣୀ[ଅବସ୍ଥାନ + 1] << 8 | ଫାଇଲ୍_ସାରଣୀ[ଅବସ୍ଥାନ + 2] << 16 | ଫାଇଲ୍_ସାରଣୀ[ଅବସ୍ଥାନ + 3] << 24;
    }
