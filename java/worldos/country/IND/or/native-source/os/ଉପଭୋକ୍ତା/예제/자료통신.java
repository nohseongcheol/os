        int[] ଡାଟା = new int[1024];
        for (int ଅନୁକ୍ରମଣିକା = 0; ଅନୁକ୍ରମଣିକା < ବିଷୟ_ମୂଲ୍ୟ.length(); ଅନୁକ୍ରମଣିକା++) ଡାଟା[ଅନୁକ୍ରମଣିକା] = ବିଷୟ_ମୂଲ୍ୟ.charAt(ଅନୁକ୍ରମଣିକା);
        if (ଉପଭୋକ୍ତା.ପଠାନ୍ତୁ_ଡାଟା(ହାଣ୍ଡେଲ୍_ମୂଲ୍ୟ, ଠିକଣା, ପୋର୍ଟ_ମୂଲ୍ୟ, ଡାଟା, ବିଷୟ_ମୂଲ୍ୟ.length()) < 0) {
            ଉପଭୋକ୍ତା.ଲେଖନ୍ତୁ("UDP SEND FAILED\n"); ଉପଭୋକ୍ତା.ବନ୍ଦ_ନେଟ୍_ୱାର୍କ୍(ହାଣ୍ଡେଲ୍_ମୂଲ୍ୟ); return 4;
        }
        ଉପଭୋକ୍ତା.ଲେଖନ୍ତୁ("UDP SENT\n");
        int 받은길이 = ଉପଭୋକ୍ତା.자료받기(ହାଣ୍ଡେଲ୍_ମୂଲ୍ୟ, ଡାଟା, 1500);
