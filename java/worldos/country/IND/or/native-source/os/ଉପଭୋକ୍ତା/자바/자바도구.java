/** 게스트 ଉପକରଣସମୂହ 공통 ନିର୍ଗମ 및 ASCII ଫାଇଲ ନାମ ପ୍ରୋସେସ୍_ମୂଲ୍ୟ_ଏଣ୍ଟ୍ରି. */
public final class 자바도구 {
    /** UTF-8 ବାଇଟ୍_ମୂଲ୍ୟ 배열을 같은 배열의 UTF-16 단위로 바꾼다. 잘못된 입력은 ପ୍ରତ୍ୟାକ୍ଷାନ_ମୂଲ୍ୟ. */
    static int 원문해독(int[] ଡାଟା, int ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ) {
        int ପଢନ୍ତୁ = 0, ଲେଖନ୍ତୁ = 0;
        if (ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ >= 3 && ଡାଟା[0] == 239 && ଡାଟା[1] == 187 && ଡାଟା[2] == 191) ପଢନ୍ତୁ = 3;
        while (ପଢନ୍ତୁ < ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ) {
            int ମୂଲ୍ୟ = ଡାଟା[ପଢନ୍ତୁ++], 수 = 0, 최소 = 0;
            if (ମୂଲ୍ୟ >= 194 && ମୂଲ୍ୟ <= 223) { 수 = 1; 최소 = 128; ମୂଲ୍ୟ &= 31; }
            else if (ମୂଲ୍ୟ >= 224 && ମୂଲ୍ୟ <= 239) { 수 = 2; 최소 = 2048; ମୂଲ୍ୟ &= 15; }
            else if (ମୂଲ୍ୟ >= 240 && ମୂଲ୍ୟ <= 244) { 수 = 3; 최소 = 65536; ମୂଲ୍ୟ &= 7; }
            else if (ମୂଲ୍ୟ >= 128 || ମୂଲ୍ୟ < 0) return -1;
            if (수 > ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ - ପଢନ୍ତୁ) return -1;
            for (int i = 0; i < 수; i++) {
                int ପରବର୍ତ୍ତୀ_ଆଇଟମ୍ = ଡାଟା[ପଢନ୍ତୁ++]; if ((ପରବର୍ତ୍ତୀ_ଆଇଟମ୍ & 192) != 128) return -1;
                ମୂଲ୍ୟ = (ମୂଲ୍ୟ << 6) | (ପରବର୍ତ୍ତୀ_ଆଇଟମ୍ & 63);
            }
            if (ମୂଲ୍ୟ < 최소 || ମୂଲ୍ୟ > 0x10ffff || (ମୂଲ୍ୟ >= 0xd800 && ମୂଲ୍ୟ <= 0xdfff)) return -1;
            if (ମୂଲ୍ୟ >= 65536) { ମୂଲ୍ୟ -= 65536; ଡାଟା[ଲେଖନ୍ତୁ++] = 0xd800 | (ମୂଲ୍ୟ >> 10); ଡାଟା[ଲେଖନ୍ତୁ++] = 0xdc00 | (ମୂଲ୍ୟ & 1023); }
            else ଡାଟା[ଲେଖନ୍ତୁ++] = ମୂଲ୍ୟ;
        }
        return ଲେଖନ୍ତୁ;
    }
    static void 수쓰기(int ମୂଲ୍ୟ) {
        if (ମୂଲ୍ୟ < 0) ଉପଭୋକ୍ତା.ଲିଖନ_ବର୍ଣ୍ଣ_ମୂଲ୍ୟ('-'); else ମୂଲ୍ୟ = -ମୂଲ୍ୟ;
        int ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା = 1000000000;
        boolean ଚଳାନ୍ତୁ = false;
        while (ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା != 0) {
            int 수 = -(ମୂଲ୍ୟ / ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା);
            if (수 != 0 || ଚଳାନ୍ତୁ || ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା == 1) { ଉପଭୋକ୍ତା.ଲିଖନ_ବର୍ଣ୍ଣ_ମୂଲ୍ୟ('0' + 수); ଚଳାନ୍ତୁ = true; }
            ମୂଲ୍ୟ %= ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା; ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା /= 10;
        }
    }
    static int ନାମ(int[] ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ, String 원본) {
        if (원본.length() >= ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ.length) return -1;
        for (int 수 = 0; 수 < ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ.length; 수++) ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ[수] = 수 < 원본.length() ? 원본.charAt(수) : 0;
        return 원본.length();
    }
    static boolean 같음(String 가, String 나) {
        if (가.length() != 나.length()) return false;
        for (int 수 = 0; 수 < 가.length(); 수++) if (가.charAt(수) != 나.charAt(수)) return false;
        return true;
    }
}
