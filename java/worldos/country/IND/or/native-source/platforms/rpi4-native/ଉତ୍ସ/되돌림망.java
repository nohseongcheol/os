    static int ଯାଞ୍ଚ୍_କରିବା(int ଅନୁକ୍ରମଣିକା) { return ଅନୁକ୍ରମଣିକା >= 32 && ଅନୁକ୍ରମଣିକା < 40 && 사용[ଅନୁକ୍ରମଣିକା - 32] != 0 ? ଅନୁକ୍ରମଣିକା - 32 : -1; }
    static boolean 겹침(int ଅନୁକ୍ରମଣିକା) {
        for (int ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = 0; ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି < 8; ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି++) if (사용[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] != 0 && ପୋର୍ଟ_ମୂଲ୍ୟ[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] == ଅନୁକ୍ରମଣିକା) return true;
        return false;
    }
    static int 임시창구() {
        for (int 시도 = 0; 시도 < 16; 시도++) {
            int 후보 = 다음창구++;
            if (다음창구 > 65535) 다음창구 = 49152;
            if (!겹침(후보)) return 후보;
        }
        return -98;
    }
    public static int ସୃଷ୍ଟି_ଏଣ୍ଟ୍ରି(int 영역, int 종류, int କର୍ମ_ମୂଲ୍ୟ) {
        if (영역 != 2) return -97;
        if (종류 != 2 || (କର୍ମ_ମୂଲ୍ୟ != 0 && କର୍ମ_ମୂଲ୍ୟ != 17)) return -93;
        for (int ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = 0; ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି < 8; ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି++) if (사용[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] == 0) {
            사용[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 1; ପୋର୍ଟ_ମୂଲ୍ୟ[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 0; ଠିକଣା[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 0; 앞[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 0; 개수[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 0; 받은창구[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 0;
            return ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି + 32;
        }
        return -24;
    }
    public static int 묶기(int ଅନୁକ୍ରମଣିକା, int ନେଟ୍_ୱାର୍କ୍_ଠିକଣା, int 창구번호) {
        int ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = ଯାଞ୍ଚ୍_କରିବା(ଅନୁକ୍ରମଣିକା);
        if (ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି < 0) return -9;
        if (ନେଟ୍_ୱାର୍କ୍_ଠିକଣା != 0 && ନେଟ୍_ୱାର୍କ୍_ଠିକଣା != 0x7f000001) return -99;
        if (ପୋର୍ଟ_ମୂଲ୍ୟ[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] != 0 || 창구번호 < 0 || 창구번호 > 65535) return -22;
        if (창구번호 == 0) 창구번호 = 임시창구();
        if (창구번호 < 0) return 창구번호;
        if (겹침(창구번호)) return -98;
        ପୋର୍ଟ_ମୂଲ୍ୟ[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 창구번호; ଠିକଣା[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = ନେଟ୍_ୱାର୍କ୍_ଠିକଣା; return 0;
    }
    public static int 자료넣기(int ଅନୁକ୍ରମଣିକା, int ମୂଲ୍ୟ) {
        if (ଅନୁକ୍ରମଣିକା < 0 || ଅନୁକ୍ରମଣିକା >= 512) return -22;
        ଅଗ୍ରଗାମୀ_ମୂଲ୍ୟ[ଅନୁକ୍ରମଣିକା] = ମୂଲ୍ୟ & 255; return 0;
    }
    public static int 자료읽기(int ଅନୁକ୍ରମଣିକା) { return ଅନୁକ୍ରମଣିକା >= 0 && ଅନୁକ୍ରମଣିକା < 512 ? ଅଗ୍ରଗାମୀ_ମୂଲ୍ୟ[ଅନୁକ୍ରମଣିକା] : -22; }
    public static int ପଠାନ୍ତୁ(int ଅନୁକ୍ରମଣିକା, int ନେଟ୍_ୱାର୍କ୍_ଠିକଣା, int 창구번호, int ଆକାର) {
        int ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = ଯାଞ୍ଚ୍_କରିବା(ଅନୁକ୍ରମଣିକା);
        if (ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି < 0) return -9;
        if (ନେଟ୍_ୱାର୍କ୍_ଠିକଣା != 0x7f000001) return -101;
        if (창구번호 < 1 || 창구번호 > 65535) return -22;
        if (ଆକାର < 0 || ଆକାର > 512) return -90;
        if (ପୋର୍ଟ_ମୂଲ୍ୟ[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] == 0) {
            int ମାପ = 묶기(ଅନୁକ୍ରମଣିକା, 0x7f000001, 0);
            if (ମାପ < 0) return ମାପ;
        }
        int ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ = -1;
        for (int 후보 = 0; 후보 < 8; 후보++) if (사용[후보] != 0 && ପୋର୍ଟ_ମୂଲ୍ୟ[후보] == 창구번호) ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ = 후보;
        if (ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ < 0) return -111;
        if (개수[ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ] == 4) return -11;
        int ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା = ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ * 4 + (앞[ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ] + 개수[ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ]) % 4;
        for (int ବାଇଟ୍_ମୂଲ୍ୟ = 0; ବାଇଟ୍_ମୂଲ୍ୟ < ଆକାର; ବାଇଟ୍_ମୂଲ୍ୟ++) ଡାଟା[ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା * 512 + ବାଇଟ୍_ମୂଲ୍ୟ] = ଅଗ୍ରଗାମୀ_ମୂଲ୍ୟ[ବାଇଟ୍_ମୂଲ୍ୟ];
        ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ[ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା] = ଆକାର; 보낸창구[ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା] = ପୋର୍ଟ_ମୂଲ୍ୟ[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି]; 개수[ଲକ୍ଷସ୍ଥଳ_ମୂଲ୍ୟ]++;
        return ଆକାର;
    }
    public static int 받기(int ଅନୁକ୍ରମଣିକା, int 용량) {
        int ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି = ଯାଞ୍ଚ୍_କରିବା(ଅନୁକ୍ରମଣିକା);
        if (ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି < 0) return -9;
        if (용량 < 0 || 용량 > 512) return -22;
        if (개수[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] == 0) return -11;
        int ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା = ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି * 4 + 앞[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି];
        int ଆକାର = ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ[ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା] < 용량 ? ଦୈର୍ଘ୍ୟ_ମୂଲ୍ୟ[ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା] : 용량;
        for (int ବାଇଟ୍_ମୂଲ୍ୟ = 0; ବାଇଟ୍_ମୂଲ୍ୟ < ଆକାର; ବାଇଟ୍_ମୂଲ୍ୟ++) ଅଗ୍ରଗାମୀ_ମୂଲ୍ୟ[ବାଇଟ୍_ମୂଲ୍ୟ] = ଡାଟା[ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା * 512 + ବାଇଟ୍_ମୂଲ୍ୟ];
        받은창구[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = 보낸창구[ସ୍ଥିତି_ଅନୁକ୍ରମଣିକା]; 앞[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] = (앞[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି] + 1) % 4; 개수[ସ୍ଲଟ୍_ଏଣ୍ଟ୍ରି]--;
        return ଆକାର;
    }
