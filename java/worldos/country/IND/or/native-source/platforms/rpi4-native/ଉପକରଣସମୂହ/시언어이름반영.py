#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 ବାଇଟ୍_ମୂଲ୍ୟ 위치로 자체 C 이름을 옮기는 일회성 이행 ଉପକରଣସମୂହ.

외부 구조체의 멤버, ଷ୍ଟ୍ରିଂ_ମୂଲ୍ୟ, C 표준 Excel_ଟେବଲ୍_ମୂଲ୍ୟ, 이식 규약은 보존한다.
입력은 ପରିବର୍ତ୍ତନ_ମୂଲ୍ୟ 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍ = Path(__file__).resolve().parents[1]

def ନିର୍ବାହ_କରିବା_ନିର୍ଦ୍ଦେଶ():
    분석 = json.loads((ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍/'build/한국어화/시언어분석.json').read_text())
    if 분석['ତ୍ରୁଟି']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ନାମ_ସାରଣୀ = json.loads((ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:ନାମ_ସାରଣୀ[ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ']] for 고유,ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ in 선언표.items()
                if ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ'] in ନାମ_ସାରଣୀ and ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ'] not in 규격}
    ସଂଯୋଗ_ସାରଣୀ = {ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ']:ନାମ_ସାରଣୀ[ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ']] for ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ in 선언표.values()
              if ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ.get('ସଂଯୋଗ_କରନ୍ତୁ')==4 and ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['종류'] in (8,9)
              and ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ'] in ନାମ_ସାରଣୀ and ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ'] not in 규격}
    # ସୃଷ୍ଟି_କରିବା AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ସଂଯୋଗ_କରନ୍ତୁ 이름만 유지한다.
    머리 = ['/* 한국어 ଉତ୍ସ_ବୃକ୍ଷ 이름과 기존 ମେସିନ୍ ସଂଯୋଗ_କରନ୍ତୁ କର୍ମ_ମୂଲ୍ୟ. 자동 ସୃଷ୍ଟି_କରିବା: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(ସଂଯୋଗ_ସାରଣୀ.items())]
    머리 += ['#endif','']
    (ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍/'명명/기계연결이름.h').write_text('\n'.join(머리))
    ପରିବର୍ତ୍ତନଗୁଡିକ_ତାଲିକା = defaultdict(dict)
    for ଫାଇଲ,ଅଫ୍_ସେଟ୍_ମୂଲ୍ୟ,ନାମ,고유 in 분석['ପ୍ରସଙ୍ଗ']:
        if 고유 in 바꿀선언:
            ପରିବର୍ତ୍ତନଗୁଡିକ_ତାଲିକା[ଫାଇଲ][ଅଫ୍_ସେଟ୍_ମୂଲ୍ୟ] = (ନାମ,바꿀선언[고유])
    ଲଗ୍_ଧାଡ଼ି = ['ଫାଇଲ\t원래바이트위치\t이전이름\t한국어이름']
    ଉପେକ୍ଷା_ମୂଲ୍ୟ = []
    for ଫାଇଲ,ପରିବର୍ତ୍ତନ_ମୂଲ୍ୟ in ପରିବର୍ତ୍ତନଗୁଡିକ_ତାଲିକା.items():
        ପଥ = Path(ଫାଇଲ); 원본 = ପଥ.read_bytes(); ଡାଟା = 원본
        for ଅଫ୍_ସେଟ୍_ମୂଲ୍ୟ,(옛이름,새이름) in sorted(ପରିବର୍ତ୍ତନ_ମୂଲ୍ୟ.items(),reverse=True):
            끝 = ଅଫ୍_ସେଟ୍_ମୂଲ୍ୟ+len(옛이름.encode())
            if 원본[ଅଫ୍_ସେଟ୍_ମୂଲ୍ୟ:끝] != 옛이름.encode():
                ଉପେକ୍ଷା_ମୂଲ୍ୟ.append((str(ପଥ.relative_to(ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍)),ଅଫ୍_ସେଟ୍_ମୂଲ୍ୟ,옛이름));continue
            ଡାଟା = ଡାଟା[:ଅଫ୍_ସେଟ୍_ମୂଲ୍ୟ]+새이름.encode()+ଡାଟା[끝:]
            ଲଗ୍_ଧାଡ଼ି.append('{}\t{}\t{}\t{}'.format(ପଥ.relative_to(ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍),ଅଫ୍_ସେଟ୍_ମୂଲ୍ୟ,옛이름,새이름))
        ପଥ.write_bytes(ଡାଟା)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ମାକ୍ରୋ_ମୂଲ୍ୟ = {ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ']:ନାମ_ସାରଣୀ[ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ']] for ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ in 선언표.values()
              if ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['종류']==501 and ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ'] in ନାମ_ସାରଣୀ and ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ନାମ'] not in 규격}
    for ପଥ in sorted({Path(ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ଫାଇଲ']) for ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ in 선언표.values()}):
        ରେଖା_ତାଲିକା = ପଥ.read_text().splitlines(True); 이어짐 = False
        for ଅନୁକ୍ରମଣିକା,ରେଖା in enumerate(ରେଖା_ତାଲିକା):
            전처리 = 이어짐 or bool(re.match(r'\s*#',ରେଖା))
            이어짐 = 전처리 and ରେଖା.rstrip().endswith('\\')
            if 전처리:
                ଦୃଷ୍ଟିପାତ_ସାରଣୀ = ନାମ_ସାରଣୀ if re.match(r'\s*#\s*define\b',ରେଖା) or 이어짐 else ମାକ୍ରୋ_ମୂଲ୍ୟ
                ରେଖା_ତାଲିକା[ଅନୁକ୍ରମଣିକା] = 낱말.sub(lambda 맞음: ଦୃଷ୍ଟିପାତ_ସାରଣୀ.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],ରେଖା)
        ପଥ.write_text(''.join(ରେଖା_ତାଲିକା))
    # 각 자체 ଅନୁବାଦ_ଉତ୍ସ 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ପଥ in sorted({Path(ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ['ଫାଇଲ']) for ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ in 선언표.values()}):
        if ପଥ.suffix not in ('.c','.cpp'):continue
        ସମକକ୍ଷ_ମୂଲ୍ୟ = '../' * len(ପଥ.relative_to(ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍).parts[:-1]) + '명명/기계연결이름.h'
        ପଥ.write_text('#include "'+ସମକକ୍ଷ_ମୂଲ୍ୟ+'"\n'+ପଥ.read_text())
    (ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍/'명명/시언어이름대응.tsv').write_text('\n'.join(ଲଗ୍_ଧାଡ଼ି)+'\n')
    (ପ୍ରୋଜେକ୍ଟ୍_ରୁଟ୍/'build/한국어화/전처리참조.json').write_text(json.dumps(ଉପେକ୍ଷା_ମୂଲ୍ୟ,ensure_ascii=False,indent=2)+'\n')
    print('ପରିବର୍ତ୍ତନ_ମୂଲ୍ୟ',len(ଲଗ୍_ଧାଡ଼ି)-1,'전처리 재검토',len(ଉପେକ୍ଷା_ମୂଲ୍ୟ),'ମେସିନ୍ ସଂଯୋଗ_କରନ୍ତୁ',len(ସଂଯୋଗ_ସାରଣୀ))

if __name__=='__main__': ନିର୍ବାହ_କରିବା_ନିର୍ଦ୍ଦେଶ()
