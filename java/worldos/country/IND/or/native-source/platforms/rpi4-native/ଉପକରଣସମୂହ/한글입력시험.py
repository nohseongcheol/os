#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from ଡେସ୍କଟପ୍_ଭିୟୁ import କୀବୋର୍ଡ୍


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.ପାଠ_ବଫର୍ = ''
        def ପଠାନ୍ତୁ(ଡାଟା):
            for ବର୍ଣ୍ଣ_ଡାଟା in ଡାଟା.decode('utf-8'):
                if ବର୍ଣ୍ଣ_ଡାଟା == '\x7f': 자신.ପାଠ_ବଫର୍ = 자신.ପାଠ_ବଫର୍[:-1]
                else: 자신.ପାଠ_ବଫର୍ += ବର୍ଣ୍ଣ_ଡାଟା
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି = କୀବୋର୍ଡ୍(ପଠାନ୍ତୁ)

    def 글쇠누르기(자신, ସଙ୍କେତ_ମୂଲ୍ୟ):
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(True, ସଙ୍କେତ_ମୂଲ୍ୟ)
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(False, ସଙ୍କେତ_ମୂଲ୍ୟ)

    def ଟାଇପ୍_କରିବା_ବର୍ଗ(자신, 누름열):
        for 누름값 in 누름열: 자신.글쇠누르기(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.글쇠누르기(0xffc6); 자신.ଟାଇପ୍_କରିବା_ବର୍ଗ(누름열)
                자신.assertEqual(자신.ପାଠ_ବଫର୍, 예상결과)

    def test_앞글자지우기(자신):
        자신.글쇠누르기(0xff31); 자신.ଟାଇପ୍_କରିବା_ବର୍ଗ('dlfr')
        자신.assertEqual(자신.ପାଠ_ବଫର୍,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.글쇠누르기(0xff08); 자신.assertEqual(자신.ପାଠ_ବଫର୍,예상결과)
        자신.ଟାଇପ୍_କରିବା_ବର୍ଗ('gksk'); 자신.assertEqual(자신.ପାଠ_ବଫର୍,'하나')
        자신.글쇠누르기(0xff08); 자신.assertEqual(자신.ପାଠ_ବଫର୍,'하ㄴ')

    def test_전환반복확정(자신):
        자신.ଟାଇପ୍_କରିବା_ବର୍ଗ('echo ')
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(True,0xffe1)
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(True,32); 자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(True,32)
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(False,32); 자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(False,0xffe1)
        자신.assertTrue(자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.한글여부)
        자신.ଟାଇପ୍_କରିବା_ବର୍ଗ('gksrmf'); 자신.글쇠누르기(0xff31); 자신.ଟାଇପ୍_କରିବା_ବର୍ଗ(' English')
        자신.assertEqual(자신.ପାଠ_ବଫର୍,'echo 한글 English')
        자신.assertFalse(자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.한글여부)
        자신.글쇠누르기(0xffc6); 자신.ଟାଇପ୍_କରିବା_ବର୍ଗ('rk'); 자신.글쇠누르기(0xff51)
        자신.ଟାଇପ୍_କରିବା_ବର୍ଗ('sk'); 자신.assertTrue(자신.ପାଠ_ବଫର୍.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.글쇠누르기(0xffc6); 자신.ଟାଇପ୍_କରିବା_ବର୍ଗ('rk')
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.କ୍ଲିପ୍_ବୋର୍ଡ଼_ମୂଲ୍ୟ='ଲେପନ_କରିବା_ମୂଲ୍ୟ'.encode()
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(True,0xffe3); 자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(True,0xffe1)
        자신.글쇠누르기(ord('v'))
        자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(False,0xffe1); 자신.କୀବୋର୍ଡ୍_ଏଣ୍ଟ୍ରି.누름값(False,0xffe3)
        자신.글쇠누르기(0x0100d55c); 자신.ଟାଇପ୍_କରିବା_ବର୍ଗ('sk')
        자신.assertEqual(자신.ପାଠ_ବଫର୍,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
