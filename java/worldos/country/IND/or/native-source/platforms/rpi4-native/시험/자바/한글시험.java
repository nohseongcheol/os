import 한국어.자체.문자;
import 한국어.자체.ଫାଇଲ;
import 한국어.자체.ଏଣ୍ଟ୍ରି_ତାଲିକା;
import 한국어.자체.ଅଭିଧାନ;
import 한국어.자체.ନିର୍ଗମ;
public class 한글시험 {
    public static void main(String[] a) throws Exception {
        String 인사 = "안녕하세요 · 日本語 · العربية · 😀";
        ନିର୍ଗମ.ଲିଖନ_ରେଖା(문자.ଡିକ୍ରିପ୍ଟ_ଡାଟା(문자.부호화(인사))); ନିର୍ଗମ.수쓰기(문자.코드포인트수("한글😀"));
        ଫାଇଲ.ଲେଖନ୍ତୁ("한글자료.txt", 인사); ନିର୍ଗମ.ଲିଖନ_ରେଖା(ଫାଇଲ.ପଢନ୍ତୁ("한글자료.txt"));
        ଏଣ୍ଟ୍ରି_ତାଲିକା 이름들 = new ଏଣ୍ଟ୍ରି_ତାଲିକା(); 이름들.더하기("가람"); 이름들.더하기("누리"); ନିର୍ଗମ.ଲିଖନ_ରେଖା(이름들.ପଢନ୍ତୁ(1));
        ଅଭିଧାନ 뜻 = new ଅଭିଧାନ(); 뜻.넣기("가람", "강"); System.gc(); ନିର୍ଗମ.ଲିଖନ_ରେଖା(뜻.ଖୋଜିବା_ଏଣ୍ଟ୍ରି("가람"));
        try { 문자.ଡିକ୍ରିପ୍ଟ_ଡାଟା(new byte[] {(byte)0xc0, (byte)0xaf}); } catch (IllegalArgumentException e) { ନିର୍ଗମ.ଲିଖନ_ରେଖା("UTF-8 ତ୍ରୁଟି ପ୍ରତ୍ୟାକ୍ଷାନ_ମୂଲ୍ୟ"); }
        ନିର୍ଗମ.ଲିଖନ_ରେଖା("한국어 ଲାଇବ୍ରେରୀ 완료");
    }
}
