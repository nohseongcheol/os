package 한국어.자체;
/** 화면(畫面): 부팅 때 선택한 크기의 자체 କେନ୍ଦ୍ରିକ_ମୂଲ୍ୟ RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int ମୂଲ୍ୟ = କେନ୍ଦ୍ରିକ_ମୂଲ୍ୟ.화면너비(); if (ମୂଲ୍ୟ < 0) throw new ସ୍ଥିତି_ବ୍ୟତିକ୍ରମ("프레임버퍼 없음"); return ମୂଲ୍ୟ; }
    public static int 높이() { int ମୂଲ୍ୟ = କେନ୍ଦ୍ରିକ_ମୂଲ୍ୟ.화면높이(); if (ମୂଲ୍ୟ < 0) throw new ସ୍ଥିତି_ବ୍ୟତିକ୍ରମ("프레임버퍼 없음"); return ମୂଲ୍ୟ; }
    public static void 사각형(int 가로, int ଅନୁଲମ୍ବ_ସ୍ଥିତି, int 폭, int 높이, int 색) {
        if (가로 < 0 || ଅନୁଲମ୍ବ_ସ୍ଥିତି < 0 || 폭 < 0 || 높이 < 0 || 가로 > 너비() || ଅନୁଲମ୍ବ_ସ୍ଥିତି > 높이() || 폭 > 너비() - 가로 || 높이 > 높이() - ଅନୁଲମ୍ବ_ସ୍ଥିତି) throw new ଅବୈଧ_ଯୁକ୍ତି_ବ୍ୟତିକ୍ରମ("화면 କ୍ଲିପ୍");
        if (କେନ୍ଦ୍ରିକ_ମୂଲ୍ୟ.사각형(가로, ଅନୁଲମ୍ବ_ସ୍ଥିତି, 폭, 높이, 색) < 0) throw new ସ୍ଥିତି_ବ୍ୟତିକ୍ରମ("프레임버퍼 없음");
    }
    public static void 지우기(int 색) { 사각형(0, 0, 너비(), 높이(), 색); }
    public static void 기다리기() { if (କେନ୍ଦ୍ରିକ_ମୂଲ୍ୟ.그림대기() < 0) throw new ସ୍ଥିତି_ବ୍ୟତିକ୍ରମ("ଆଦାନ_ପ୍ରଦାନ_ଯୋଗ୍ୟ 입력 필요"); }
}
