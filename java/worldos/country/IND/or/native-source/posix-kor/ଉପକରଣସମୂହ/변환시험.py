#!/usr/bin/env python3
"""ବିଲ୍ଡ୍_ସିଷ୍ଟମ 변환이 한국어 ଷ୍ଟ୍ରିଂ_ମୂଲ୍ୟ, 주석, 헤더 경로를 바꾸지 않는지 검사한다."""
from ପରିଚାୟକ_ପରିବର୍ତ୍ତନ import 변환

ଉତ୍ସ = '''#include <파일규약.h>
#include "통신규약.h"
// ଖୋଲିବା_ଫାଇଲ୍ 라는 주석
/* 자료이름 */
const char *ଫାଇଲ୍_ଏଣ୍ଟ୍ରି_ନାମ = "한글 \\" ଷ୍ଟ୍ରିଂ_ମୂଲ୍ୟ";
char ବର୍ଣ୍ଣ_ମୂଲ୍ୟ = '가';
int 파일열기_횟수 = 1;
'''
ନିର୍ଗମ = 변환(ଉତ୍ସ)
assert '#include <파일규약.h>' in ନିର୍ଗମ
assert '#include "통신규약.h"' in ନିର୍ଗମ
assert '// ଖୋଲିବା_ଫାଇଲ୍ 라는 주석' in ନିର୍ଗମ
assert '/* 자료이름 */' in ନିର୍ଗମ
assert '"한글 \\" ଷ୍ଟ୍ରିଂ_ମୂଲ୍ୟ"' in ନିର୍ଗମ
assert "'가'" in ନିର୍ଗମ
assert '\\ud30c\\uc77c\\uc774\\ub984' in ନିର୍ଗମ
assert '파일열기_횟수' not in ନିର୍ଗମ
assert 변환(ନିର୍ଗମ) == ନିର୍ଗମ
print('PASS: 한국어 ପରିଚାୟକ_ମୂଲ୍ୟ 변환/ଷ୍ଟ୍ରିଂ_ମୂଲ୍ୟ·주석·ପଥ 보존')
