package ଭାରତ.JIndOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB ପେଜ୍_ମୂଲ୍ୟ 연결과 ଲେଖନ୍ତୁ 시 복사를 제공한다. */
public final class ପେଜ୍_ପରିଚାଳକ {
    public static final int ପୃଷ୍ଠା_ଆକାର = 4096;

    private static final class ପେଜ୍_ମୂଲ୍ୟ {
        private byte[] ଡାଟା = new byte[ପୃଷ୍ଠା_ଆକାର];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class ଠିକଣା_ସ୍ଥାନ {
        private final Map<Integer, ପେଜ୍_ମୂଲ୍ୟ> ପେଜ୍_ସାରଣୀ = new HashMap<Integer, ପେଜ୍_ମୂଲ୍ୟ>();
    }

    public ଠିକଣା_ସ୍ଥାନ 새주소공간() {
        return new ଠିକଣା_ସ୍ଥାନ();
    }

    public void ମ୍ୟାପ୍_କରିବା_ପେଜ୍(ଠିକଣା_ସ୍ଥାନ 공간, int ବାସ୍ତବ_ଠିକଣା, boolean 쓰기가능) {
        int ଅନୁକ୍ରମଣିକା = 쪽번호(ବାସ୍ତବ_ଠିକଣା);
        ପେଜ୍_ମୂଲ୍ୟ 새쪽 = new ପେଜ୍_ମୂଲ୍ୟ();
        새쪽.쓰기가능 = 쓰기가능;
        공간.ପେଜ୍_ସାରଣୀ.put(Integer.valueOf(ଅନୁକ୍ରମଣିକା), 새쪽);
    }

    public ଠିକଣା_ସ୍ଥାନ 쓰기시복사복제(ଠିକଣା_ସ୍ଥାନ 원본) {
        ଠିକଣା_ସ୍ଥାନ 복제본 = new ଠିକଣା_ସ୍ଥାନ();
        for (Map.Entry<Integer, ପେଜ୍_ମୂଲ୍ୟ> ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ : 원본.ପେଜ୍_ସାରଣୀ.entrySet()) {
            ପେଜ୍_ମୂଲ୍ୟ 공유쪽 = ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.ପେଜ୍_ସାରଣୀ.put(ଏଣ୍ଟ୍ରି_ମୂଲ୍ୟ.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(ଠିକଣା_ସ୍ଥାନ 공간, int ବାସ୍ତବ_ଠିକଣା) {
        ପେଜ୍_ମୂଲ୍ୟ ଲକ୍ଷ୍ୟସ୍ଥଳ = ଖୋଜିବା_ପେଜ୍(공간, ବାସ୍ତବ_ଠିକଣା);
        return ଲକ୍ଷ୍ୟସ୍ଥଳ.ଡାଟା[Math.floorMod(ବାସ୍ତବ_ଠିକଣା, ପୃଷ୍ଠା_ଆକାର)];
    }

    public void ଲିଖନ_ବାଇଟ୍_ମୂଲ୍ୟ(ଠିକଣା_ସ୍ଥାନ 공간, int ବାସ୍ତବ_ଠିକଣା, byte ମୂଲ୍ୟ) {
        int ଅନୁକ୍ରମଣିକା = 쪽번호(ବାସ୍ତବ_ଠିକଣା);
        ପେଜ୍_ମୂଲ୍ୟ ଲକ୍ଷ୍ୟସ୍ଥଳ = ଖୋଜିବା_ପେଜ୍(공간, ବାସ୍ତବ_ଠିକଣା);
        if (!ଲକ୍ଷ୍ୟସ୍ଥଳ.쓰기가능) {
            if (!ଲକ୍ଷ୍ୟସ୍ଥଳ.쓰기시복사) {
                throw new IllegalStateException("ପଢନ୍ତୁ 전용 쪽입니다.");
            }
            ଲକ୍ଷ୍ୟସ୍ଥଳ = ସୃଷ୍ଟି_ନିଜସ୍ୱ_ପେଜ୍(공간, ଅନୁକ୍ରମଣିକା, ଲକ୍ଷ୍ୟସ୍ଥଳ);
        }
        ଲକ୍ଷ୍ୟସ୍ଥଳ.ଡାଟା[Math.floorMod(ବାସ୍ତବ_ଠିକଣା, ପୃଷ୍ଠା_ଆକାର)] = ମୂଲ୍ୟ;
    }

    public void 범위개인쓰기(ଠିକଣା_ସ୍ଥାନ 공간, int ଆରମ୍ଭ_ଠିକଣା, int ଆକାର) {
        if (ଆକାର < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int ଶେଷ_କରନ୍ତୁ_ଠିକଣା = Math.addExact(ଆରମ୍ଭ_ଠିକଣା, ଆକାର);
        for (int ଠିକଣା = ଆରମ୍ଭ_ଠିକଣା; ଠିକଣା < ଶେଷ_କରନ୍ତୁ_ଠିକଣା; ଠିକଣା = (쪽번호(ଠିକଣା) + 1) * ପୃଷ୍ଠା_ଆକାର) {
            int ଅନୁକ୍ରମଣିକା = 쪽번호(ଠିକଣା);
            ପେଜ୍_ମୂଲ୍ୟ ଲକ୍ଷ୍ୟସ୍ଥଳ = ଖୋଜିବା_ପେଜ୍(공간, ଠିକଣା);
            if (ଲକ୍ଷ୍ୟସ୍ଥଳ.쓰기시복사) {
                ସୃଷ୍ଟି_ନିଜସ୍ୱ_ପେଜ୍(공간, ଅନୁକ୍ରମଣିକା, ଲକ୍ଷ୍ୟସ୍ଥଳ);
            } else {
                ଲକ୍ଷ୍ୟସ୍ଥଳ.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(ଠିକଣା_ସ୍ଥାନ 공간, int ଆରମ୍ଭ_ଠିକଣା, byte[] ଡାଟା) {
        for (int ଅନୁକ୍ରମଣିକା = 0; ଅନୁକ୍ରମଣିକା < ଡାଟା.length; ଅନୁକ୍ରମଣିକା++) {
            ଲିଖନ_ବାଇଟ୍_ମୂଲ୍ୟ(공간, ଆରମ୍ଭ_ଠିକଣା + ଅନୁକ୍ରମଣିକା, ଡାଟା[ଅନୁକ୍ରମଣିକା]);
        }
    }

    private ପେଜ୍_ମୂଲ୍ୟ ସୃଷ୍ଟି_ନିଜସ୍ୱ_ପେଜ୍(ଠିକଣା_ସ୍ଥାନ 공간, int ଅନୁକ୍ରମଣିକା, ପେଜ୍_ମୂଲ୍ୟ 공유쪽) {
        ପେଜ୍_ମୂଲ୍ୟ ନିଜସ୍ୱ_ପେଜ୍ = new ପେଜ୍_ମୂଲ୍ୟ();
        ନିଜସ୍ୱ_ପେଜ୍.ଡାଟା = Arrays.copyOf(공유쪽.ଡାଟା, 공유쪽.ଡାଟା.length);
        ନିଜସ୍ୱ_ପେଜ୍.쓰기가능 = true;
        ନିଜସ୍ୱ_ପେଜ୍.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.ପେଜ୍_ସାରଣୀ.put(Integer.valueOf(ଅନୁକ୍ରମଣିକା), ନିଜସ୍ୱ_ପେଜ୍);
        return ନିଜସ୍ୱ_ପେଜ୍;
    }

    private ପେଜ୍_ମୂଲ୍ୟ ଖୋଜିବା_ପେଜ୍(ଠିକଣା_ସ୍ଥାନ 공간, int ଠିକଣା) {
        ପେଜ୍_ମୂଲ୍ୟ ଲକ୍ଷ୍ୟସ୍ଥଳ = 공간.ପେଜ୍_ସାରଣୀ.get(Integer.valueOf(쪽번호(ଠିକଣା)));
        if (ଲକ୍ଷ୍ୟସ୍ଥଳ == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return ଲକ୍ଷ୍ୟସ୍ଥଳ;
    }

    private int 쪽번호(int ଠିକଣା) {
        if (ଠିକଣା < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return ଠିକଣା / ପୃଷ୍ଠା_ଆକାର;
    }
}

