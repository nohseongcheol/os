        ପେଜ୍_ପରିଚାଳକ.ଠିକଣା_ସ୍ଥାନ ଶିଶୁ_ସ୍ଥାନ = ପରିଚାଳକ_ମୂଲ୍ୟ.쓰기시복사복제(부모공간);
