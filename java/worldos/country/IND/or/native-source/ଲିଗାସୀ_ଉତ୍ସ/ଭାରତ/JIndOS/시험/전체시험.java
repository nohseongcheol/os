        ଲିଖନ_ଇଣ୍ଟିଜର_ମୂଲ୍ୟ(ଡାଟା, 32, 52);
        짧은정수쓰기(ଡାଟା, 46, 40);
        짧은정수쓰기(ଡାଟା, 48, 1);
        ଲିଖନ_ଇଣ୍ଟିଜର_ମୂଲ୍ୟ(ଡାଟା, 56, 8);
        ଲିଖନ_ଇଣ୍ଟିଜର_ମୂଲ୍ୟ(ଡାଟା, 60, 2);
        ଲିଖନ_ଇଣ୍ଟିଜର_ମୂଲ୍ୟ(ଡାଟା, 64, 0x04002000);
        ଲିଖନ_ଇଣ୍ଟିଜର_ମୂଲ୍ୟ(ଡାଟା, 72, 64);

        실행파일적재기.ଚିତ୍ର ଚିତ୍ର_ମୂଲ୍ୟ = new 실행파일적재기().검사(ଡାଟା);
