        ଯାଞ୍ଚ୍_କରିବା(ପରିଚାଳକ_ମୂଲ୍ୟ.바이트읽기(ଶିଶୁ_ସ୍ଥାନ, 0x1010) == 9, "ଲେଖନ୍ତୁ 시 କପି_ମୂଲ୍ୟ ଶିଶୁ_ମୂଲ୍ୟ ଲେଖନ୍ତୁ");
