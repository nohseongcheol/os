package ଭାରତ.JIndOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import ଭାରତ.JIndOS.기억공간.ପେଜ୍_ପରିଚାଳକ;
import ଭାରତ.JIndOS.ଫାଇଲ୍_ସିଷ୍ଟମ୍.파일서술자표;

/** ପ୍ରୋସେସ୍_ମୂଲ୍ୟ 식별자와 라운드로빈 ପ୍ରସ୍ତୁତ 대기열을 관리한다. */
public final class ସିଡ୍ୟୁଲର୍ {
    private final ପେଜ୍_ପରିଚାଳକ 쪽관리;
    private final Map<Integer, ପ୍ରୋସେସ୍_ମୂଲ୍ୟ> ପ୍ରକ୍ରିୟା_ତାଲିକା = new HashMap<Integer, ପ୍ରୋସେସ୍_ମୂଲ୍ୟ>();
    private final Queue<ପ୍ରୋସେସ୍_ମୂଲ୍ୟ> 준비대기열 = new ArrayDeque<ପ୍ରୋସେସ୍_ମୂଲ୍ୟ>();
    private int ପରବର୍ତ୍ତୀ_ପରିଚାୟକ = 1;

    public ସିଡ୍ୟୁଲର୍(ପେଜ୍_ପରିଚାଳକ 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public ପ୍ରୋସେସ୍_ମୂଲ୍ୟ 첫과정(파일서술자표 파일서술자) {
        ପ୍ରୋସେସ୍_ମୂଲ୍ୟ 새과정 = new ପ୍ରୋସେସ୍_ମୂଲ୍ୟ(ବଣ୍ଟନ_ପରିଚାୟକ(), 0, 쪽관리.새주소공간(), 파일서술자);
        ପ୍ରକ୍ରିୟା_ତାଲିକା.put(Integer.valueOf(새과정.ପରିଚାୟକ_ମୂଲ୍ୟ()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public ପ୍ରୋସେସ୍_ମୂଲ୍ୟ 복제(ପ୍ରୋସେସ୍_ମୂଲ୍ୟ 부모) {
        ପ୍ରୋସେସ୍_ମୂଲ୍ୟ ଶିଶୁ_ମୂଲ୍ୟ = new ପ୍ରୋସେସ୍_ମୂଲ୍ୟ(
                ବଣ୍ଟନ_ପରିଚାୟକ(),
                부모.ପରିଚାୟକ_ମୂଲ୍ୟ(),
                쪽관리.쓰기시복사복제(부모.ଠିକଣା_ସ୍ଥାନ()),
                부모.파일서술자().복제());
        ଶିଶୁ_ମୂଲ୍ୟ.프로그램끝설정(부모.프로그램끝());
        ପ୍ରକ୍ରିୟା_ତାଲିକା.put(Integer.valueOf(ଶିଶୁ_ମୂଲ୍ୟ.ପରିଚାୟକ_ମୂଲ୍ୟ()), ଶିଶୁ_ମୂଲ୍ୟ);
        준비대기열.offer(ଶିଶୁ_ମୂଲ୍ୟ);
        return ଶିଶୁ_ମୂଲ୍ୟ;
    }

    public ପ୍ରୋସେସ୍_ମୂଲ୍ୟ ପରବର୍ତ୍ତୀ_ପ୍ରୋସେସ୍() {
        int 검사수 = 준비대기열.size();
        for (int ଅନୁକ୍ରମଣିକା = 0; ଅନୁକ୍ରମଣିକା < 검사수; ଅନୁକ୍ରମଣିକା++) {
            ପ୍ରୋସେସ୍_ମୂଲ୍ୟ ପରବର୍ତ୍ତୀ_ଆଇଟମ୍ = 준비대기열.poll();
            if (ପରବର୍ତ୍ତୀ_ଆଇଟମ୍ != null && (ପରବର୍ତ୍ତୀ_ଆଇଟମ୍.ସ୍ଥିତି_ମୂଲ୍ୟ_e10195a1() == ପ୍ରୋସେସ୍_ସ୍ଥିତି.ପ୍ରସ୍ତୁତ || ପରବର୍ତ୍ତୀ_ଆଇଟମ୍.ସ୍ଥିତି_ମୂଲ୍ୟ_e10195a1() == ପ୍ରୋସେସ୍_ସ୍ଥିତି.ନିର୍ବାହ_କରିବା_ନିର୍ଦ୍ଦେଶ)) {
                ପରବର୍ତ୍ତୀ_ଆଇଟମ୍.ସେଟ୍_ସ୍ଥିତି(ପ୍ରୋସେସ୍_ସ୍ଥିତି.ନିର୍ବାହ_କରିବା_ନିର୍ଦ୍ଦେଶ);
                준비대기열.offer(ପରବର୍ତ୍ତୀ_ଆଇଟମ୍);
                return ପରବର୍ତ୍ତୀ_ଆଇଟମ୍;
            }
        }
        return null;
    }

    public int 자식기다리기(ପ୍ରୋସେସ୍_ମୂଲ୍ୟ 부모, int ଶିଶୁ_ପରିଚାୟକ, boolean 기다리지않음) {
        for (ପ୍ରୋସେସ୍_ମୂଲ୍ୟ 후보 : ପ୍ରକ୍ରିୟା_ତାଲିକା.values()) {
            if (후보.부모식별자() != 부모.ପରିଚାୟକ_ମୂଲ୍ୟ()) {
                continue;
            }
            if (ଶିଶୁ_ପରିଚାୟକ > 0 && 후보.ପରିଚାୟକ_ମୂଲ୍ୟ() != ଶିଶୁ_ପରିଚାୟକ) {
                continue;
            }
            if (후보.ସ୍ଥିତି_ମୂଲ୍ୟ_e10195a1() == ପ୍ରୋସେସ୍_ସ୍ଥିତି.ପ୍ରସ୍ଥାନ_ଅନୁପ୍ରୟୋଗ) {
                int ମାପ = (후보.종료값() & 0xff) << 8;
                ପ୍ରକ୍ରିୟା_ତାଲିକା.remove(Integer.valueOf(후보.ପରିଚାୟକ_ମୂଲ୍ୟ()));
                return ମାପ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public ପ୍ରୋସେସ୍_ମୂଲ୍ୟ ଖୋଜିବା_ପ୍ରୋସେସ୍(int ପରିଚାୟକ_ମୂଲ୍ୟ) {
        return ପ୍ରକ୍ରିୟା_ତାଲିକା.get(Integer.valueOf(ପରିଚାୟକ_ମୂଲ୍ୟ));
    }

    private int ବଣ୍ଟନ_ପରିଚାୟକ() {
        return ପରବର୍ତ୍ତୀ_ପରିଚାୟକ++;
    }
}
