import ਪੰਜਾਬੀ.자체.ਸਬੰਧ;
import ਪੰਜਾਬੀ.자체.실행인수;
import ਪੰਜਾਬੀ.자체.전문통로;
import ਪੰਜਾਬੀ.자체.문자;
import ਪੰਜਾਬੀ.자체.ਆਉਟਪੁੱਟ;
import ਪੰਜਾਬੀ.자체.검사;
import ਪੰਜਾਬੀ.자체.입력흐름;
import ਪੰਜਾਬੀ.자체.입출력예외;

public class 네트워크예제 {
    public static void ਚਲਾਓ_2() throws 입출력예외 {
        // ਹੋਸਟ: python3 ਸਾਧਨ/예제되돌림.py --tcp-port 9000 --udp-port 9001
        ਸਬੰਧ ਕੁਨੈਕਸ਼ਨ_ਕਰੋ = ਸਬੰਧ.ਖੋਲ੍ਹੋ("10.0.2.2", 문자.ਪਦ_ਵਿਆਖਿਆ_ਕਰੋ_ਪੂਰਣ_ਅੰਕ(실행인수.ਟੈਕਸਟ(0)));
        try {
            ਕੁਨੈਕਸ਼ਨ_ਕਰੋ.ਸਮਾਂ_ਸਮਾਪਤ(700);
            byte[] ਸੁਨੇਹਾ = 문자.부호화("JAVA TCP pa\n");
            ਕੁਨੈਕਸ਼ਨ_ਕਰੋ.ਆਉਟਪੁੱਟ().ਲਿਖਣ(ਸੁਨੇਹਾ);
            입력흐름 입력 = ਕੁਨੈਕਸ਼ਨ_ਕਰੋ.입력();
            for (int 수 = 0; 수 < 문자.바이트수(ਸੁਨੇਹਾ); 수++) {
                검사.참인지(입력.ਪੜ੍ਹਨ() == (ਸੁਨੇਹਾ[수] & 255), "TCP ਜਵਾਬ_ਦਿਓ 불일치");
            }
        } finally { ਕੁਨੈਕਸ਼ਨ_ਕਰੋ.ਬੰਦ_ਕਰੋ(); }
        전문통로 종단 = 전문통로.ਖੋਲ੍ਹੋ(0);
        try {
            종단.ਸਮਾਂ_ਸਮਾਪਤ(700);
            종단.ਈਮੇਲ("10.0.2.2", 문자.ਪਦ_ਵਿਆਖਿਆ_ਕਰੋ_ਪੂਰਣ_ਅੰਕ(실행인수.ਟੈਕਸਟ(1)), "JAVA UDP pa");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP pa"), "UDP ਜਵਾਬ_ਦਿਓ 불일치");
        } finally { 종단.ਬੰਦ_ਕਰੋ(); }
        ਆਉਟਪੁੱਟ.ਲਿੱਖੋ_ਕਤਾਰ("JAVA 네트워크 ਤਸਦੀਕ: TCP UDP pa");
    }
}
