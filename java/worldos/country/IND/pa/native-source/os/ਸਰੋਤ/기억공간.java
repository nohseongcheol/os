/** 부팅 ਸਿਸਟਮ_ਜਾਣਕਾਰੀ 조회와 4KiB 고정 ਆਕਾਰ 작업 ਵਿਭਾਗ_ਕੀਮਤ ਨਿਰਧਾਰਿਤ_ਕਰੋ_ਸਟੋਰੇਜ/반환. 일반 물리 ਪੰਨਾ_ਕੀਮਤ 관리자는 아니다. */
public final class 기억공간 {
    static int[] ਵਿਭਾਗ_ਕੀਮਤ = new int[8192];
    static int[] 사용 = new int[8];

    static int ਪਦ_ਵਿਆਖਿਆ_ਕਰੋ_ਪੂਰਣ_ਅੰਕ(int ਪਤਾ) {
        return ਤਜਵੀਜ_ਕੀਮਤ.기억읽기(ਪਤਾ) | (ਤਜਵੀਜ_ਕੀਮਤ.기억읽기(ਪਤਾ + 1) << 8)
            | (ਤਜਵੀਜ_ਕੀਮਤ.기억읽기(ਪਤਾ + 2) << 16) | (ਤਜਵੀਜ_ਕੀਮਤ.기억읽기(ਪਤਾ + 3) << 24);
    }

    static int 위쪽기억크기() {
        int ਸਿਸਟਮ_ਜਾਣਕਾਰੀ = ਤਜਵੀਜ_ਕੀਮਤ.부팅정보();
        if (ਤਜਵੀਜ_ਕੀਮਤ.부팅표식() != 0x2badb002 || ਸਿਸਟਮ_ਜਾਣਕਾਰੀ == 0 || (ਪਦ_ਵਿਆਖਿਆ_ਕਰੋ_ਪੂਰਣ_ਅੰਕ(ਸਿਸਟਮ_ਜਾਣਕਾਰੀ) & 1) == 0) return -1;
        return ਪਦ_ਵਿਆਖਿਆ_ਕਰੋ_ਪੂਰਣ_ਅੰਕ(ਸਿਸਟਮ_ਜਾਣਕਾਰੀ + 8);
    }

    static int ਨਿਰਧਾਰਿਤ_ਕਰੋ_ਸਟੋਰੇਜ() {
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 사용.length; ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
            if (사용[ਅਨੁਕ੍ਰਮਣਿਕਾ] == 0) {
                사용[ਅਨੁਕ੍ਰਮਣਿਕਾ] = 1;
                for (int ਸਲੌਟ_ਦਾਖਲਾ = 0; ਸਲੌਟ_ਦਾਖਲਾ < 1024; ਸਲੌਟ_ਦਾਖਲਾ++) ਵਿਭਾਗ_ਕੀਮਤ[ਅਨੁਕ੍ਰਮਣਿਕਾ * 1024 + ਸਲੌਟ_ਦਾਖਲਾ] = 0;
                return ਅਨੁਕ੍ਰਮਣਿਕਾ;
            }
        }
        return -1;
    }

    static boolean 반환(int ਅਨੁਕ੍ਰਮਣਿਕਾ) {
        if (ਅਨੁਕ੍ਰਮਣਿਕਾ < 0 || ਅਨੁਕ੍ਰਮਣਿਕਾ >= 사용.length || 사용[ਅਨੁਕ੍ਰਮਣਿਕਾ] == 0) return false;
        사용[ਅਨੁਕ੍ਰਮਣਿਕਾ] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 사용.length; ਅਨੁਕ੍ਰਮਣਿਕਾ++) 개수 += 사용[ਅਨੁਕ੍ਰਮਣਿਕਾ];
        return 개수;
    }
}
