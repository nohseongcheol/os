/** 최대 سائيز/홀수 لمبائي_قدر 데이터그램으로 اصلي_ڪوائف RTL8139 수신 لوپ_قدر 순환을 시험한다. */
public final class نيٽ_ورڪ_لوپ {
    public static int هلائڻ() {
        if (صارف.인수개수() != 1) { صارف.لکو("Usage: run stress PORT\n"); return 2; }
        String متن = صارف.인수(0);
        int پورٽ_قدر = 0;
        for (int ابتدائي = 0; ابتدائي < متن.length(); ابتدائي++) {
            if (متن.charAt(ابتدائي) < '0' || متن.charAt(ابتدائي) > '9' || پورٽ_قدر > 6553) return 2;
            پورٽ_قدر = پورٽ_قدر * 10 + متن.charAt(ابتدائي) - '0';
        }
        if (پورٽ_قدر < 1 || پورٽ_قدر > 65535) return 2;
        int منهن_ڏيڻ_قدر = صارف.ٺاھيو_نيٽ_ورڪ(0);
        if (منهن_ڏيڻ_قدر < 0) return 3;
        int[] ڪوائف = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int لمبائي_قدر = 1024 - (회차 & 1);
            for (int ابتدائي = 0; ابتدائي < لمبائي_قدر; ابتدائي++) ڪوائف[ابتدائي] = (ابتدائي + 회차) & 255;
            if (صارف.اي_ميل_ڪوائف(منهن_ڏيڻ_قدر, 0x0a000202, پورٽ_قدر, ڪوائف, لمبائي_قدر) != لمبائي_قدر) return 4;
            if (صارف.자료받기(منهن_ڏيڻ_قدر, ڪوائف, 300) != لمبائي_قدر) return 5;
            for (int ابتدائي = 0; ابتدائي < لمبائي_قدر; ابتدائي++) if (ڪوائف[ابتدائي] != ((ابتدائي + 회차) & 255)) return 6;
        }
        صارف.بند_ڪرڻ_نيٽ_ورڪ(منهن_ڏيڻ_قدر);
        صارف.لکو("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
