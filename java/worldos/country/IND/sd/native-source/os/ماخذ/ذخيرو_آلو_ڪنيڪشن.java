/** 첫 IDE 장치의 512바이트 논리 سيڪشن_قدر. 이 계층은 포맷을 만들거나 임의 장치를 지우지 않는다. */
public final class ذخيرو_آلو_ڪنيڪشن {
    static boolean 사용가능 = false;
    static int[] سيڪشن_ڪوائف = new int[512];
    static void 잠깐기다리기() {
        for (int ابتدائي = 0; ابتدائي < 4; ابتدائي++) آلو_قدر.입출력바이트읽기(0x3f6);
    }
    static int 준비기다리기(boolean 자료필요) {
        int هلائڻ = آلو_قدر.밀리초();
        while (آلو_قدر.밀리초() - هلائڻ < 500) {
            int حالت_قدر = آلو_قدر.입출력바이트읽기(0x1f7);
            if (حالت_قدر == 0 || حالت_قدر == 255) return -19;
            if ((حالت_قدر & 128) == 0) {
                if ((حالت_قدر & 33) != 0) return -5;
                if (!자료필요 || (حالت_قدر & 8) != 0) return 0;
            }
            آلو_قدر.잠시양보();
        }
        return -110;
    }
    static int 요청(int سيڪشن_قدر, int حڪم) {
        if (سيڪشن_قدر < 0 || سيڪشن_قدر >= 2048) return -22;
        آلو_قدر.입출력바이트쓰기(0x3f6, 2); // polling; IDE IRQ 사용 안 함
        آلو_قدر.입출력바이트쓰기(0x1f6, 0xe0); 잠깐기다리기();
        int 결과 = 준비기다리기(false);
        if (결과 < 0) return 결과;
        آلو_قدر.입출력바이트쓰기(0x1f2, 1);
        آلو_قدر.입출력바이트쓰기(0x1f3, سيڪشن_قدر & 255);
        آلو_قدر.입출력바이트쓰기(0x1f4, (سيڪشن_قدر >>> 8) & 255);
        آلو_قدر.입출력바이트쓰기(0x1f5, 0);
        آلو_قدر.입출력바이트쓰기(0x1f7, حڪم); 잠깐기다리기();
        return 준비기다리기(true);
    }
    static int 읽기(int سيڪشن_قدر) {
        int 결과 = 요청(سيڪشن_قدر, 0x20);
        if (결과 < 0) return 결과;
        for (int ابتدائي = 0; ابتدائي < 256; ابتدائي++) {
            int قدر = آلو_قدر.입출력짧은수읽기(0x1f0);
            سيڪشن_ڪوائف[ابتدائي * 2] = قدر & 255; سيڪشن_ڪوائف[ابتدائي * 2 + 1] = قدر >>> 8;
        }
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int لکو(int سيڪشن_قدر) {
        if (!사용가능 || سيڪشن_قدر < 1 || سيڪشن_قدر > 518) return -19;
        int 결과 = 요청(سيڪشن_قدر, 0x30);
        if (결과 < 0) return 결과;
        for (int ابتدائي = 0; ابتدائي < 256; ابتدائي++)
            آلو_قدر.입출력짧은수쓰기(0x1f0, سيڪشن_ڪوائف[ابتدائي * 2] | سيڪشن_ڪوائف[ابتدائي * 2 + 1] << 8);
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int 밀어쓰기() {
        if (!사용가능) return -19;
        آلو_قدر.입출력바이트쓰기(0x1f7, 0xe7); 잠깐기다리기();
        return 준비기다리기(false);
    }
    static int 정수읽기(int 위치) {
        return سيڪشن_ڪوائف[위치] | سيڪشن_ڪوائف[위치 + 1] << 8 | سيڪشن_ڪوائف[위치 + 2] << 16 | سيڪشن_ڪوائف[위치 + 3] << 24;
    }
    static void لکو_عدد_صحيح_قدر(int 위치, int قدر) {
        for (int ابتدائي = 0; ابتدائي < 4; ابتدائي++) سيڪشن_ڪوائف[위치 + ابتدائي] = (قدر >>> (ابتدائي * 8)) & 255;
    }
}
