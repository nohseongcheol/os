        if (항목수 <= 시작자리) return -1;
        for (int لوپ_ابتدائي = 시작자리; لوپ_ابتدائي < 항목수; لوپ_ابتدائي++) if (ڪوائف_ترتيب[시작점 + لوپ_ابتدائي] == '/') return -1;
