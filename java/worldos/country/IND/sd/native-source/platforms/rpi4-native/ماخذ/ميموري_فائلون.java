            if (ڊائريڪٽري_لمبائي[لوپ_ابتدائي] > 정규길이 && 접두(ڊائريڪٽري_نالو, لوپ_ابتدائي * 64, ڊائريڪٽري_لمبائي[لوپ_ابتدائي], 정규, 정규길이) && ڊائريڪٽري_نالو[لوپ_ابتدائي * 64 + 정규길이] == '/') return -39;
