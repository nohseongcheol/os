    public int تعميل_ڪرڻ_حڪم(عمل_قدر 현재과정, byte[] 실행파일, String[] 인자, String[] 환경) {
        실행파일적재기.نقش نقش_قدر;
        try {
            نقش_قدر = 적재기.검사(실행파일);
        } catch (IllegalArgumentException نقص) {
            return -8;
        }
        if (인자 == null || 환경 == null || 인자.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.سيڪشن_قدر سيڪشن_قدر : نقش_قدر.구역들()) {
            if ((سيڪشن_قدر.جهنڊو_قدر() & 2) == 0 || سيڪشن_قدر.سائيز() == 0) {
                continue;
            }
            int 첫쪽 = سيڪشن_قدر.پتو() / صفحو_مئنيجر.صفحي_جي_ماپ;
            int 끝쪽 = (سيڪشن_قدر.پتو() + سيڪشن_قدر.سائيز() + صفحو_مئنيجر.صفحي_جي_ماپ - 1) / صفحو_مئنيجر.صفحي_جي_ماپ;
            for (int ابتدائي = 첫쪽; ابتدائي < 끝쪽; ابتدائي++) {
                int پتو = ابتدائي * صفحو_مئنيجر.صفحي_جي_ماپ;
                try {
                    쪽관리.바이트읽기(현재과정.پتو_جڳهه(), پتو);
                    쪽관리.범위개인쓰기(현재과정.پتو_جڳهه(), پتو, صفحو_مئنيجر.صفحي_جي_ماپ);
                } catch (IllegalStateException نقص) {
                    쪽관리.نقشو_صفحو(현재과정.پتو_جڳهه(), پتو, true);
                }
            }
            for (int ابتدائي = 0; ابتدائي < سيڪشن_قدر.سائيز(); ابتدائي++) {
                byte قدر = سيڪشن_قدر.종류() == 8 ? 0 : 실행파일[سيڪشن_قدر.파일위치() + ابتدائي];
                쪽관리.لکو_بائٽ_قدر(현재과정.پتو_جڳهه(), سيڪشن_قدر.پتو() + ابتدائي, قدر);
            }
        }
        현재과정.실행문맥설정(نقش_قدر.شروع_پتو(), 인자, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

