#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from డెస్క్_టాప్_వీక్షణ import కీబోర్డు


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.పాఠం_బఫర్ = ''
        def పంపు(డేటా):
            for అక్షరం_డేటా in డేటా.decode('utf-8'):
                if అక్షరం_డేటా == '\x7f': 자신.పాఠం_బఫర్ = 자신.పాఠం_బఫర్[:-1]
                else: 자신.పాఠం_బఫర్ += అక్షరం_డేటా
        자신.కీబోర్డు_ప్రవేశం = కీబోర్డు(పంపు)

    def 글쇠누르기(자신, చిహ్నం_మూల్యం):
        자신.కీబోర్డు_ప్రవేశం.누름값(True, చిహ్నం_మూల్యం)
        자신.కీబోర్డు_ప్రవేశం.누름값(False, చిహ్నం_మూల్యం)

    def టైప్_చేయండి_వర్గం(자신, 누름열):
        for 누름값 in 누름열: 자신.글쇠누르기(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.글쇠누르기(0xffc6); 자신.టైప్_చేయండి_వర్గం(누름열)
                자신.assertEqual(자신.పాఠం_బఫర్, 예상결과)

    def test_앞글자지우기(자신):
        자신.글쇠누르기(0xff31); 자신.టైప్_చేయండి_వర్గం('dlfr')
        자신.assertEqual(자신.పాఠం_బఫర్,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.글쇠누르기(0xff08); 자신.assertEqual(자신.పాఠం_బఫర్,예상결과)
        자신.టైప్_చేయండి_వర్గం('gksk'); 자신.assertEqual(자신.పాఠం_బఫర్,'하나')
        자신.글쇠누르기(0xff08); 자신.assertEqual(자신.పాఠం_బఫర్,'하ㄴ')

    def test_전환반복확정(자신):
        자신.టైప్_చేయండి_వర్గం('echo ')
        자신.కీబోర్డు_ప్రవేశం.누름값(True,0xffe1)
        자신.కీబోర్డు_ప్రవేశం.누름값(True,32); 자신.కీబోర్డు_ప్రవేశం.누름값(True,32)
        자신.కీబోర్డు_ప్రవేశం.누름값(False,32); 자신.కీబోర్డు_ప్రవేశం.누름값(False,0xffe1)
        자신.assertTrue(자신.కీబోర్డు_ప్రవేశం.한글여부)
        자신.టైప్_చేయండి_వర్గం('gksrmf'); 자신.글쇠누르기(0xff31); 자신.టైప్_చేయండి_వర్గం(' English')
        자신.assertEqual(자신.పాఠం_బఫర్,'echo 한글 English')
        자신.assertFalse(자신.కీబోర్డు_ప్రవేశం.한글여부)
        자신.글쇠누르기(0xffc6); 자신.టైప్_చేయండి_వర్గం('rk'); 자신.글쇠누르기(0xff51)
        자신.టైప్_చేయండి_వర్గం('sk'); 자신.assertTrue(자신.పాఠం_బఫర్.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.글쇠누르기(0xffc6); 자신.టైప్_చేయండి_వర్గం('rk')
        자신.కీబోర్డు_ప్రవేశం.క్లిప్_బోర్డ్_మూల్యం='అతికించు_మూల్యం'.encode()
        자신.కీబోర్డు_ప్రవేశం.누름값(True,0xffe3); 자신.కీబోర్డు_ప్రవేశం.누름값(True,0xffe1)
        자신.글쇠누르기(ord('v'))
        자신.కీబోర్డు_ప్రవేశం.누름값(False,0xffe1); 자신.కీబోర్డు_ప్రవేశం.누름값(False,0xffe3)
        자신.글쇠누르기(0x0100d55c); 자신.టైప్_చేయండి_వర్గం('sk')
        자신.assertEqual(자신.పాఠం_బఫర్,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
