class نظام_نقص(OSError):
    def __init__(자신, اشاریہ, 설명="آپریٹنگ_سسٹم 작업에 실패했습니다."):
        super().__init__(اشاریہ, 설명)
        자신.اشاریہ = اشاریہ
        자신.설명 = 설명

def 운영호출(فعل_قدر, *دلائل):
    try:
        return فعل_قدر(*دلائل)
    except OSError as غلطی:
        اشاریہ = غلطی.args[0] if غلطی.args else 0
        raise نظام_نقص(اشاریہ)

