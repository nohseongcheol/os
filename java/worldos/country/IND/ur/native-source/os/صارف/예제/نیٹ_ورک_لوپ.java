/** 최대 حجم/홀수 لمبا_ئی_قدر 데이터그램으로 اصل_کوائف RTL8139 수신 لوپ_قدر 순환을 시험한다. */
public final class نیٹ_ورک_لوپ {
    public static int چلائیں() {
        if (صارف.인수개수() != 1) { صارف.لکھیں("Usage: run stress PORT\n"); return 2; }
        String متن = صارف.دلائل(0);
        int پورٹ_قدر = 0;
        for (int اشاریہ = 0; اشاریہ < متن.length(); اشاریہ++) {
            if (متن.charAt(اشاریہ) < '0' || متن.charAt(اشاریہ) > '9' || پورٹ_قدر > 6553) return 2;
            پورٹ_قدر = پورٹ_قدر * 10 + متن.charAt(اشاریہ) - '0';
        }
        if (پورٹ_قدر < 1 || پورٹ_قدر > 65535) return 2;
        int ہینڈل_قدر = صارف.بنائیں_نیٹ_ورک(0);
        if (ہینڈل_قدر < 0) return 3;
        int[] کوائف = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int لمبا_ئی_قدر = 1024 - (회차 & 1);
            for (int اشاریہ = 0; اشاریہ < لمبا_ئی_قدر; اشاریہ++) کوائف[اشاریہ] = (اشاریہ + 회차) & 255;
            if (صارف.بھیجیں_کوائف(ہینڈل_قدر, 0x0a000202, پورٹ_قدر, کوائف, لمبا_ئی_قدر) != لمبا_ئی_قدر) return 4;
            if (صارف.자료받기(ہینڈل_قدر, کوائف, 300) != لمبا_ئی_قدر) return 5;
            for (int اشاریہ = 0; اشاریہ < لمبا_ئی_قدر; اشاریہ++) if (کوائف[اشاریہ] != ((اشاریہ + 회차) & 255)) return 6;
        }
        صارف.بند_نیٹ_ورک(ہینڈل_قدر);
        صارف.لکھیں("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
