/** 디스크 لکھیں 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int لمبا_ئی_قدر = 0;
    static boolean 앞줄복귀 = false;
    static boolean لائن_اوور_فلو = false;

    static boolean حکم(String نام) {
        if (لمبا_ئی_قدر < نام.length()) return false;
        for (int اشاریہ = 0; اشاریہ < نام.length(); اشاریہ++)
            if (입력[اشاریہ] != نام.charAt(اشاریہ)) return false;
        return لمبا_ئی_قدر == نام.length() || 입력[نام.length()] == ' ';
    }

    static void مدد_دکھانا() {
        متن_ٹرمینل.لکھیں("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        متن_ٹرمینل.لکھیں("apps | run NAME [ARGS] | net\n");
        متن_ٹرمینل.لکھیں("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        متن_ٹرمینل.لکھیں("sync (연결된 JKSTORE1 ذخیرہ_کریں_قدر 장치에 فائل_کا_نام 보존)\n");
    }

    static void عمل_قدر_اندراج() {
        if (لمبا_ئی_قدر == 0) return;
        if (حکم("help")) مدد_دکھانا();
        else if (حکم("sync")) {
            int پیمائش = 파일보존.ہم_وقت_ساز();
            متن_ٹرمینل.لکھیں("Sync: "); متن_ٹرمینل.수쓰기(پیمائش); متن_ٹرمینل.문자(10);
        }
        else if (حکم("ls")) میموری_فائل_نظام.اندراج_فہرست();
        else if (حکم("edit")) میموری_فائل_نظام.حکم(입력, 4, لمبا_ئی_قدر, 0);
        else if (حکم("cat")) میموری_فائل_نظام.حکم(입력, 3, لمبا_ئی_قدر, 1);
        else if (حکم("rm")) میموری_فائل_نظام.حکم(입력, 2, لمبا_ئی_قدر, 2);
        else if (حکم("java") || حکم("javac")) {
            int پیمائش = 실행관리.نفاذ_کریں_حکم(입력, 0, لمبا_ئی_قدر);
            متن_ٹرمینل.لکھیں("Exit: "); متن_ٹرمینل.수쓰기(پیمائش); متن_ٹرمینل.문자(10);
        }
        else if (حکم("apps")) 실행관리.اندراج_فہرست();
        else if (حکم("net")) نیٹ_ورک_اسٹیک.حالت_قدر();
        else if (حکم("run")) {
            int پیمائش = 실행관리.نفاذ_کریں_حکم(입력, 3, لمبا_ئی_قدر);
            متن_ٹرمینل.لکھیں("Exit: "); متن_ٹرمینل.수쓰기(پیمائش); متن_ٹرمینل.لکھیں("\n");
        } else if (حکم("info")) {
            متن_ٹرمینل.لکھیں("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (حکم("mem")) {
            متن_ٹرمینل.لکھیں("위쪽 میموری_قدر 공간(KiB): "); متن_ٹرمینل.수쓰기(기억공간.위쪽기억크기());
            متن_ٹرمینل.لکھیں("\n배열 동적 میموری_قدر 공간(بائٹ_قدر): "); متن_ٹرمینل.수쓰기(آلہ_قدر.لڑی_استعمال());
            متن_ٹرمینل.لکھیں(" / 262144\n작업 공간 صیغہ_قدر: "); متن_ٹرمینل.수쓰기(기억공간.사용개수());
            متن_ٹرمینل.لکھیں(" / 8 (각 4096바이트)\n");
        } else if (حکم("alloc")) {
            int اشاریہ = 기억공간.مختص_کریں_ذخیرہ();
            متن_ٹرمینل.لکھیں("صیغہ_قدر اشاریہ: "); متن_ٹرمینل.수쓰기(اشاریہ); متن_ٹرمینل.لکھیں("\n");
        } else if (حکم("free")) {
            if (لمبا_ئی_قدر == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                متن_ٹرمینل.لکھیں(기억공간.반환(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 صیغہ_قدر\n");
            } else متن_ٹرمینل.لکھیں("사용법: free 0..7\n");
        } else if (حکم("echo")) {
            for (int اشاریہ = 5; اشاریہ < لمبا_ئی_قدر; اشاریہ++) متن_ٹرمینل.문자(입력[اشاریہ]);
            متن_ٹرمینل.문자(10);
        } else if (حکم("clear")) متن_ٹرمینل.지우기();
        else if (حکم("test")) کرنیل.시험();
        else if (حکم("halt")) {
            متن_ٹرمینل.لکھیں("HALTED\n");
            آلہ_قدر.정지();
        } else متن_ٹرمینل.لکھیں("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int قدر) {
        if (قدر == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = قدر == 13;
        if (قدر == 10 || قدر == 13) {
            متن_ٹرمینل.문자(10);
            if (میموری_فائل_نظام.편집중) میموری_فائل_نظام.편집줄(입력, لمبا_ئی_قدر, لائن_اوور_فلو);
            else عمل_قدر_اندراج();
            لمبا_ئی_قدر = 0;
            لائن_اوور_فلو = false;
            متن_ٹرمینل.لکھیں(میموری_فائل_نظام.편집중 ? "...> " : "jkoros> ");
        } else if (قدر == 8 || قدر == 127) {
            if (لمبا_ئی_قدر > 0) {
                لمبا_ئی_قدر--;
                متن_ٹرمینل.직렬바이트(8); متن_ٹرمینل.직렬바이트(32); متن_ٹرمینل.직렬바이트(8);
                متن_ٹرمینل.화면문자(8);
            }
        } else if (قدر >= 32 && قدر < 127 && لمبا_ئی_قدر < 입력.length) {
            입력[لمبا_ئی_قدر++] = قدر;
            متن_ٹرمینل.문자(قدر);
        } else if (قدر >= 32 && قدر < 127) لائن_اوور_فلو = true;
    }

    static void چلائیں() {
        مدد_دکھانا();
        متن_ٹرمینل.لکھیں("READY\njkoros> ");
        while (true) {
            int قدر = متن_ٹرمینل.직렬읽기();
            if (قدر < 0) قدر = کی_بورڈ.پڑھیں();
            if (قدر >= 0) 받아쓰기(قدر);
            else { نیٹ_ورک_اسٹیک.تصدیق_کریں(); آلہ_قدر.잠시양보(); }
        }
    }
}
