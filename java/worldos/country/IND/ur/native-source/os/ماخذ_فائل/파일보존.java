            لکھیں_جدول_سالم_عدد(فائل_کا_نام * 72 + 64, میموری_فائل_نظام.سائز_دیں_فہرست[فائل_کا_نام]);
            لکھیں_جدول_سالم_عدد(فائل_کا_نام * 72 + 68, میموری_فائل_نظام.허가들[فائل_کا_نام]);
