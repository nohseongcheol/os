                for (int سلاٹ_اندراج = 0; سلاٹ_اندراج < لمبا_ئی_قدر; سلاٹ_اندراج++) if (فائل_جدول[앞 * 72 + سلاٹ_اندراج] != میموری_فائل_نظام.نام[سلاٹ_اندراج]) 같음 = false;
