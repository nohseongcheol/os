        int 세대 = ذخیرہ_آلہ_رابطہ.پارس_سالم_عدد(4), میزان_کی_جانچ_کرنا = ذخیرہ_آلہ_رابطہ.پارس_سالم_عدد(8);
        if (세대 < 1 || ذخیرہ_آلہ_رابطہ.پارس_سالم_عدد(12) != (세대 ^ میزان_کی_جانچ_کرنا ^ 0x4a4b534e)) return -1;
