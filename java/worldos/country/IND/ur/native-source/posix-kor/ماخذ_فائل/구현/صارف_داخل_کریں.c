#include "호출경계.h"
extern int main(int 인수개수, char **دلائل_فہرست);
static char دلائل_میموری[2048];
static char *دلائل_فہرست[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 نفاذ_کریں_حکم 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    دلائل_فہرست[0] = "jkoros-app";
    int مقام = 0;
    for (int اشاریہ = 0; اشاریہ < 개수; اشاریہ++) {
        const int *원본 = (const int *)jkoros_syscall(3, اشاریہ, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        دلائل_فہرست[اشاریہ + 1] = دلائل_میموری + مقام;
        for (int سلاٹ_اندراج = 0; سلاٹ_اندراج < 원본[0]; سلاٹ_اندراج++) {
            if (مقام >= 2047) return 126;
            دلائل_میموری[مقام++] = 원본[سلاٹ_اندراج + 1];
        }
        دلائل_میموری[مقام++] = 0;
    }
    دلائل_فہرست[개수 + 1] = 0;
    return main(개수 + 1, دلائل_فہرست);
}
