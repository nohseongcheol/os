import हिंदी.निज.कनेक्शन;
import हिंदी.निज.실행인수;
import हिंदी.निज.전문통로;
import हिंदी.निज.문자;
import हिंदी.निज.निर्गम;
import हिंदी.निज.검사;
import हिंदी.निज.इनपुट_प्रवाह;
import हिंदी.निज.इनपुट_आउटपुट_अपवाद;

public class जालउदाहरण {
    public static void चलाएँ() throws इनपुट_आउटपुट_अपवाद {
        // आयोजक: python3 उपकरण/예제되돌림.py --tcp-port 9000 --udp-port 9001
        कनेक्शन जोड़ना = कनेक्शन.खोलें("10.0.2.2", 문자.पार्स_करें_पूर्णांक(실행인수.पाठ(0)));
        try {
            जोड़ना.대기시간(700);
            byte[] ईमेल = 문자.부호화("JAVA TCP हिंदी\n");
            जोड़ना.निर्गम().लिखें(ईमेल);
            इनपुट_प्रवाह 입력 = जोड़ना.입력();
            for (int 수 = 0; 수 < 문자.바이트수(ईमेल); 수++) {
                검사.참인지(입력.पढ़ें() == (ईमेल[수] & 255), "TCP उत्तर 불일치");
            }
        } finally { जोड़ना.बंदकरें(); }
        전문통로 एंडपॉइंट = 전문통로.खोलें(0);
        try {
            एंडपॉइंट.대기시간(700);
            एंडपॉइंट.भेजें("10.0.2.2", 문자.पार्स_करें_पूर्णांक(실행인수.पाठ(1)), "JAVA UDP हिंदी");
            검사.참인지(문자.같음(एंडपॉइंट.받기(), "JAVA UDP हिंदी"), "UDP उत्तर 불일치");
        } finally { एंडपॉइंट.बंदकरें(); }
        निर्गम.लिखना_लाइन("JAVA 네트워크 सत्यापित_करें: TCP UDP हिंदी");
    }
}
