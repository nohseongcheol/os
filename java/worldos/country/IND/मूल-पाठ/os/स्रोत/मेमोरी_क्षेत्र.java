/** 부팅 सिस्टम_जानकारी 조회와 4KiB 고정 आकार 작업 खंड_मान आवंटित_करें_संग्रहण/वापस_करें_परिणाम. 일반 물리 पेज_मान 관리자는 아니다. */
public final class मेमोरी_क्षेत्र {
    static int[] खंड_मान = new int[8192];
    static int[] 사용 = new int[8];

    static int पार्स_करें_पूर्णांक(int पता) {
        return उपकरण_मान.पढें_मेमोरी(पता) | (उपकरण_मान.पढें_मेमोरी(पता + 1) << 8)
            | (उपकरण_मान.पढें_मेमोरी(पता + 2) << 16) | (उपकरण_मान.पढें_मेमोरी(पता + 3) << 24);
    }

    static int 위쪽기억크기() {
        int सिस्टम_जानकारी = उपकरण_मान.부팅정보();
        if (उपकरण_मान.부팅표식() != 0x2badb002 || सिस्टम_जानकारी == 0 || (पार्स_करें_पूर्णांक(सिस्टम_जानकारी) & 1) == 0) return -1;
        return पार्स_करें_पूर्णांक(सिस्टम_जानकारी + 8);
    }

    static int आवंटित_करें_संग्रहण() {
        for (int इंडेक्स = 0; इंडेक्स < 사용.length; इंडेक्स++) {
            if (사용[इंडेक्स] == 0) {
                사용[इंडेक्स] = 1;
                for (int 칸 = 0; 칸 < 1024; 칸++) खंड_मान[इंडेक्स * 1024 + 칸] = 0;
                return इंडेक्स;
            }
        }
        return -1;
    }

    static boolean वापस_करें_परिणाम(int इंडेक्स) {
        if (इंडेक्स < 0 || इंडेक्स >= 사용.length || 사용[इंडेक्स] == 0) return false;
        사용[इंडेक्स] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int इंडेक्स = 0; इंडेक्स < 사용.length; इंडेक्स++) 개수 += 사용[इंडेक्स];
        return 개수;
    }
}
