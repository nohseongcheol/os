import 한국어.자체.پەنجەرە;
import 한국어.자체.نیشانە;
import 한국어.자체.دەق_خانە;
import 한국어.자체.دوگمه;
import 한국어.자체.پێشهات_ڕیز;
import 한국어.자체.출력;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing پەنجەرە: ckb 입력 → دوگمه → رێخۆشکەر_eb81d7d9 دەق تازە_کردنەوە. */
public class 창예제 implements 실행할일, 동작받이 {
    private پەنجەرە 인사창;
    private دەق_خانە ناو_خانە;
    private نیشانە 인사말;
    private int 인사횟수;

    public void کردنەوە_پەنجەرە() {
        인사창 = new پەنجەرە("ckb Swing", 460, 300);
        인사창.زێدە_کردن_هێمان(new نیشانە("ckb", 20, 20, 420, 28));
        ناو_خانە = new دەق_خانە("ckb", 20, 64, 420, 30);
        인사말 = new نیشانە("ckb", 20, 152, 420, 28);
        인사창.زێدە_کردن_هێمان(ناو_خانە);
        인사창.زێدە_کردن_هێمان(new دوگمه("인사하기", 20, 108, 180, 32, this));
        인사창.زێدە_کردن_هێمان(인사말);
        인사창.زێدە_کردن_هێمان(new نیشانە("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.نیشاندان_پەنجەرە();
        출력.ڕایت_کردن_دێڕ("GUI 예제 ئامادە_کردن_9ce364fc: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.ڕایت_کردن_دەق("ckb, " + ناو_خانە.글읽기() + "님! (" + 인사횟수 + ")");
        출력.ڕایت_کردن_دێڕ("GUI 인사: " + 인사말.글읽기());
    }

    public void جێبەجێکردن_ئەرک() { کردنەوە_پەنجەرە(); }
    public void 동작받기(동작알림 알림) {
        출력.ڕایت_کردن_دێڕ("ئاکشن 알림: " + 알림.فەرمان_دەق());
        인사하기();
    }
    public static void ڕادان() {
        پێشهات_ڕیز.나중에실행(new 창예제());
    }
}
