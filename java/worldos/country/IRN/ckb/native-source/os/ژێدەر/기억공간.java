/** 부팅 msinfo32_exe 조회와 4KiB 고정 گۆڕینی_ئەندازە 작업 بەش_نرخ تەرخانکردن_هەمارگە/반환. 일반 물리 لاپەڕە_نرخ 관리자는 아니다. */
public final class 기억공간 {
    static int[] بەش_نرخ = new int[8192];
    static int[] 사용 = new int[8];

    static int 정수읽기(int ناونیشان) {
        return ئامێر_نرخ.기억읽기(ناونیشان) | (ئامێر_نرخ.기억읽기(ناونیشان + 1) << 8)
            | (ئامێر_نرخ.기억읽기(ناونیشان + 2) << 16) | (ئامێر_نرخ.기억읽기(ناونیشان + 3) << 24);
    }

    static int 위쪽기억크기() {
        int msinfo32_exe = ئامێر_نرخ.부팅정보();
        if (ئامێر_نرخ.부팅표식() != 0x2badb002 || msinfo32_exe == 0 || (정수읽기(msinfo32_exe) & 1) == 0) return -1;
        return 정수읽기(msinfo32_exe + 8);
    }

    static int تەرخانکردن_هەمارگە() {
        for (int پێرست = 0; پێرست < 사용.length; پێرست++) {
            if (사용[پێرست] == 0) {
                사용[پێرست] = 1;
                for (int کەلێن_بۆ_نووسین_یان_رەمز_تێنووسین = 0; کەلێن_بۆ_نووسین_یان_رەمز_تێنووسین < 1024; کەلێن_بۆ_نووسین_یان_رەمز_تێنووسین++) بەش_نرخ[پێرست * 1024 + کەلێن_بۆ_نووسین_یان_رەمز_تێنووسین] = 0;
                return پێرست;
            }
        }
        return -1;
    }

    static boolean 반환(int پێرست) {
        if (پێرست < 0 || پێرست >= 사용.length || 사용[پێرست] == 0) return false;
        사용[پێرست] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int پێرست = 0; پێرست < 사용.length; پێرست++) 개수 += 사용[پێرست];
        return 개수;
    }
}
