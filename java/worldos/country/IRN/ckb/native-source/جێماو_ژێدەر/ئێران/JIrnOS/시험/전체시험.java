    private static void 파일과과정시험(کوورەک کوورەک_نرخ) {
        byte[] ناوەرۆک_نرخ = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        کوورەک_نرخ.سیستمی_فایل().파일추가("시험", ناوەرۆک_نرخ);
        پرۆسە_نرخ 부모 = کوورەک_نرخ.첫과정();
        체계호출 호출 = کوورەک_نرخ.체계호출();
        int 서술자 = 호출.کردنەوە(부모, "/시험", 체계호출.تەنیا_دەخوێنرێتەوە_نیشان);
        سەلماندن(서술자 >= 3, "فایل کردنەوە");

        byte[] 받을곳 = new byte[ناوەرۆک_نرخ.length];
        سەلماندن(호출.읽기(부모, 서술자, 받을곳, 받을곳.length) == ناوەرۆک_نرخ.length, "فایل 읽기");
        سەلماندن(Arrays.equals(ناوەرۆک_نرخ, 받을곳), "فایل ناوەرۆک_نرخ");
        سەلماندن(호출.위치옮기기(부모, 서술자, 0, 체계호출.گەڕان_دەستپێك) == 0, "فایل 위치 گواستنەوە_نرخ");

        int 복제서술자 = 호출.서술자복제(부모, 서술자);
        سەلماندن(복제서술자 >= 0, "서술자 복제");
        پرۆسە_نرخ منداڵ_نرخ = 호출.과정복제(부모);
        سەلماندن(منداڵ_نرخ.ناسێنەر_نرخ() != 부모.ناسێنەر_نرخ(), "پرۆسە_نرخ ناسێنەر_نرخ 분리");
        سەلماندن(منداڵ_نرخ.부모식별자() == 부모.ناسێنەر_نرخ(), "부모 پرۆسە_نرخ ناسێنەر_نرخ");
        سەلماندن(호출.داخستن(منداڵ_نرخ, 서술자) == 0 && 부모.파일서술자().열려있음(서술자), "منداڵ_نرخ داخستن 격리");

        int 이전끝 = 호출.프로그램끝늘리기(부모, 8192);
        سەلماندن(이전끝 == 0x06000000, "بەرنامە_f5044b9b 끝 늘리기");
        سەلماندن(부모.프로그램끝() == 0x06002000, "بەرنامە_f5044b9b 끝 반영");
        سەلماندن(منداڵ_نرخ.프로그램끝() == 0x06000000, "과정별 بەرنامە_f5044b9b 끝 격리");

        منداڵ_نرخ.بزربوون_بەرنامە(7);
        سەلماندن(호출.자식기다리기(부모, منداڵ_نرخ.ناسێنەر_نرخ(), false) == (7 << 8), "منداڵ_نرخ بزربوون_بەرنامە 기다리기");
        سەلماندن(호출.접근가능("시험", 1) == -13, "جێبەجێکردن_فەرمان ڕێپێدان_نرخ 거부");
        سەلماندن(호출.بەکارهێنەر_ناسێنەر() == 0 && 호출.گروپ_ناسێنەر() == 0, "사용자와 무리 ناسێنەر_نرخ");
        سەلماندن("/".equals(호출.현재작업목록(2)) && 호출.گۆڕین_لیستی_ئەرکەکان("/") == 0, "현재 작업 تێنووسین_لیست");
        سەلماندن(호출.단말인가(부모, 1), "표준 출력 단말");
        سەلماندن("JIrnOS".equals(호출.체계정보().سیستم_ناو()), "سیستەمی_کارپێکردن_نرخ msinfo32_exe");
    }

