package ირანი.JIrnOS.ფაილური_სისტემა;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/** ELF32 little-endian შესრულება_ბრძანება 파일의 머리부와 적재 구역을 검증한다. */
public final class 실행파일적재기 {
    public static final class სექცია_მნიშვნელობა {
        private final int 종류;
        private final int დანიშვნა_მნიშვნელობა;
        private final int მისამართი;
        private final int ფაილი_პოზიცია;
        private final int ზომა;

        სექცია_მნიშვნელობა(int 종류, int დანიშვნა_მნიშვნელობა, int მისამართი, int ფაილი_პოზიცია, int ზომა) {
            this.종류 = 종류;
            this.დანიშვნა_მნიშვნელობა = დანიშვნა_მნიშვნელობა;
            this.მისამართი = მისამართი;
            this.ფაილი_პოზიცია = ფაილი_პოზიცია;
            this.ზომა = ზომა;
        }

        public int 종류() {
            return 종류;
        }

        public int დანიშვნა_მნიშვნელობა() {
            return დანიშვნა_მნიშვნელობა;
        }

        public int მისამართი() {
            return მისამართი;
        }

        public int ფაილი_პოზიცია() {
            return ფაილი_პოზიცია;
        }

        public int ზომა() {
            return ზომა;
        }
    }

    public static final class ნახატი {
        private final int დაწყება_მისამართი;
        private final List<სექცია_მნიშვნელობა> 구역들;

        ნახატი(int დაწყება_მისამართი, List<სექცია_მნიშვნელობა> 구역들) {
            this.დაწყება_მისამართი = დაწყება_მისამართი;
            this.구역들 = Collections.unmodifiableList(구역들);
        }

        public int დაწყება_მისამართი() {
            return დაწყება_მისამართი;
        }

        public List<სექცია_მნიშვნელობა> 구역들() {
            return 구역들;
        }
    }

    public ნახატი 검사(byte[] მონაცემები) {
        if (მონაცემები == null || მონაცემები.length < 52
                || მონაცემები[0] != 0x7f || მონაცემები[1] != 'E' || მონაცემები[2] != 'L' || მონაცემები[3] != 'F') {
            throw new IllegalArgumentException("ELF 마법값이 올바르지 않습니다.");
        }
        if (მონაცემები[4] != 1 || მონაცემები[5] != 1) {
            throw new IllegalArgumentException("ELF32 little-endian 형식이 아닙니다.");
        }
        int დაწყება_მისამართი = ანალიზი_მთელი_რიცხვი(მონაცემები, 24);
        int სექცია_ცხრილი_პოზიცია = ანალიზი_მთელი_რიცხვი(მონაცემები, 32);
        int სექცია_შენატანი_ზომის_შეცვლა = 짧은정수읽기(მონაცემები, 46);
        int 구역수 = 짧은정수읽기(მონაცემები, 48);
        if (სექცია_შენატანი_ზომის_შეცვლა < 40 || სექცია_ცხრილი_პოზიცია < 0
                || (long) სექცია_ცხრილი_პოზიცია + (long) სექცია_შენატანი_ზომის_შეცვლა * 구역수 > მონაცემები.length) {
            throw new IllegalArgumentException("ELF 구역표 범위가 올바르지 않습니다.");
        }
        List<სექცია_მნიშვნელობა> 구역들 = new ArrayList<სექცია_მნიშვნელობა>();
        for (int ინდექსი = 0; ინდექსი < 구역수; ინდექსი++) {
            int პოზიცია = სექცია_ცხრილი_პოზიცია + ინდექსი * სექცია_შენატანი_ზომის_შეცვლა;
            int 종류 = ანალიზი_მთელი_რიცხვი(მონაცემები, პოზიცია + 4);
            int დანიშვნა_მნიშვნელობა = ანალიზი_მთელი_რიცხვი(მონაცემები, პოზიცია + 8);
            int მისამართი = ანალიზი_მთელი_რიცხვი(მონაცემები, პოზიცია + 12);
            int ფაილი_პოზიცია = ანალიზი_მთელი_რიცხვი(მონაცემები, პოზიცია + 16);
            int ზომა = ანალიზი_მთელი_რიცხვი(მონაცემები, პოზიცია + 20);
            if (ზომა < 0 || (종류 != 8 && ((long) ფაილი_პოზიცია + ზომა > მონაცემები.length || ფაილი_პოზიცია < 0))) {
                throw new IllegalArgumentException("ELF სექცია_მნიშვნელობა მონაცემები 범위가 올바르지 않습니다.");
            }
            구역들.add(new სექცია_მნიშვნელობა(종류, დანიშვნა_მნიშვნელობა, მისამართი, ფაილი_პოზიცია, ზომა));
        }
        return new ნახატი(დაწყება_მისამართი, 구역들);
    }

    private int ანალიზი_მთელი_რიცხვი(byte[] მონაცემები, int პოზიცია) {
        if (პოზიცია < 0 || პოზიცია > მონაცემები.length - 4) {
            throw new IllegalArgumentException("ELF მთელი_რიცხვი 범위를 벗어났습니다.");
        }
        return (მონაცემები[პოზიცია] & 0xff)
                | ((მონაცემები[პოზიცია + 1] & 0xff) << 8)
                | ((მონაცემები[პოზიცია + 2] & 0xff) << 16)
                | ((მონაცემები[პოზიცია + 3] & 0xff) << 24);
    }

    private int 짧은정수읽기(byte[] მონაცემები, int პოზიცია) {
        if (პოზიცია < 0 || პოზიცია > მონაცემები.length - 2) {
            throw new IllegalArgumentException("ELF 짧은 მთელი_რიცხვი 범위를 벗어났습니다.");
        }
        return (მონაცემები[პოზიცია] & 0xff) | ((მონაცემები[პოზიცია + 1] & 0xff) << 8);
    }
}
