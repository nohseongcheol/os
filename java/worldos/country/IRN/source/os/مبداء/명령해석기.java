/** 디스크 نوشتن 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int طول_مقدار = 0;
    static boolean 앞줄복귀 = false;
    static boolean خط_سرریز = false;

    static boolean فرمان(String نام) {
        if (طول_مقدار < نام.length()) return false;
        for (int فهرست = 0; فهرست < نام.length(); فهرست++)
            if (입력[فهرست] != نام.charAt(فهرست)) return false;
        return طول_مقدار == نام.length() || 입력[نام.length()] == ' ';
    }

    static void نمایش_راهنما() {
        متن_پایانه.نوشتن("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        متن_پایانه.نوشتن("apps | run NAME [ARGS] | net\n");
        متن_پایانه.نوشتن("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        متن_پایانه.نوشتن("sync (연결된 JKSTORE1 ذخیره_مقدار 장치에 پرونده 보존)\n");
    }

    static void فرآیند_مقدار_ورودی() {
        if (طول_مقدار == 0) return;
        if (فرمان("help")) نمایش_راهنما();
        else if (فرمان("sync")) {
            int سنجش = 파일보존.همگام_سازی();
            متن_پایانه.نوشتن("Sync: "); متن_پایانه.수쓰기(سنجش); متن_پایانه.문자(10);
        }
        else if (فرمان("ls")) حافظه_سیستم_پرونده.ورودی_لیست();
        else if (فرمان("edit")) حافظه_سیستم_پرونده.فرمان(입력, 4, طول_مقدار, 0);
        else if (فرمان("cat")) حافظه_سیستم_پرونده.فرمان(입력, 3, طول_مقدار, 1);
        else if (فرمان("rm")) حافظه_سیستم_پرونده.فرمان(입력, 2, طول_مقدار, 2);
        else if (فرمان("java") || فرمان("javac")) {
            int سنجش = 실행관리.اجرا_فرمان(입력, 0, طول_مقدار);
            متن_پایانه.نوشتن("Exit: "); متن_پایانه.수쓰기(سنجش); متن_پایانه.문자(10);
        }
        else if (فرمان("apps")) 실행관리.ورودی_لیست();
        else if (فرمان("net")) شبکه_پشته.وضعیت_مقدار();
        else if (فرمان("run")) {
            int سنجش = 실행관리.اجرا_فرمان(입력, 3, طول_مقدار);
            متن_پایانه.نوشتن("Exit: "); متن_پایانه.수쓰기(سنجش); متن_پایانه.نوشتن("\n");
        } else if (فرمان("info")) {
            متن_پایانه.نوشتن("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (فرمان("mem")) {
            متن_پایانه.نوشتن("위쪽 حافظه_مقدار 공간(KiB): "); متن_پایانه.수쓰기(기억공간.위쪽기억크기());
            متن_پایانه.نوشتن("\n배열 동적 حافظه_مقدار 공간(بایت_مقدار): "); متن_پایانه.수쓰기(دستگاه_مقدار.آرايه_استفاده());
            متن_پایانه.نوشتن(" / 262144\n작업 공간 قسمت_مقدار: "); متن_پایانه.수쓰기(기억공간.사용개수());
            متن_پایانه.نوشتن(" / 8 (각 4096바이트)\n");
        } else if (فرمان("alloc")) {
            int فهرست = 기억공간.اختصاص_دادن_حافظه_تلفن();
            متن_پایانه.نوشتن("قسمت_مقدار فهرست: "); متن_پایانه.수쓰기(فهرست); متن_پایانه.نوشتن("\n");
        } else if (فرمان("free")) {
            if (طول_مقدار == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                متن_پایانه.نوشتن(기억공간.بازگرداندن_سنجش(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 قسمت_مقدار\n");
            } else متن_پایانه.نوشتن("사용법: free 0..7\n");
        } else if (فرمان("echo")) {
            for (int فهرست = 5; فهرست < طول_مقدار; فهرست++) متن_پایانه.문자(입력[فهرست]);
            متن_پایانه.문자(10);
        } else if (فرمان("clear")) متن_پایانه.پاک_کردن_ورودی();
        else if (فرمان("test")) هسته.시험();
        else if (فرمان("halt")) {
            متن_پایانه.نوشتن("HALTED\n");
            دستگاه_مقدار.정지();
        } else متن_پایانه.نوشتن("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int مقدار) {
        if (مقدار == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = مقدار == 13;
        if (مقدار == 10 || مقدار == 13) {
            متن_پایانه.문자(10);
            if (حافظه_سیستم_پرونده.편집중) حافظه_سیستم_پرونده.편집줄(입력, طول_مقدار, خط_سرریز);
            else فرآیند_مقدار_ورودی();
            طول_مقدار = 0;
            خط_سرریز = false;
            متن_پایانه.نوشتن(حافظه_سیستم_پرونده.편집중 ? "...> " : "jkoros> ");
        } else if (مقدار == 8 || مقدار == 127) {
            if (طول_مقدار > 0) {
                طول_مقدار--;
                متن_پایانه.직렬바이트(8); متن_پایانه.직렬바이트(32); متن_پایانه.직렬바이트(8);
                متن_پایانه.화면문자(8);
            }
        } else if (مقدار >= 32 && مقدار < 127 && طول_مقدار < 입력.length) {
            입력[طول_مقدار++] = مقدار;
            متن_پایانه.문자(مقدار);
        } else if (مقدار >= 32 && مقدار < 127) خط_سرریز = true;
    }

    static void اجرا_2() {
        نمایش_راهنما();
        متن_پایانه.نوشتن("READY\njkoros> ");
        while (true) {
            int مقدار = متن_پایانه.직렬읽기();
            if (مقدار < 0) مقدار = صفحه_کلید.خواندن();
            if (مقدار >= 0) 받아쓰기(مقدار);
            else { شبکه_پشته.تأیید_صحت(); دستگاه_مقدار.잠시양보(); }
        }
    }
}
