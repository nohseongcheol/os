/** 최대 گۆڕینی_ئەندازە/홀수 درێژی_نرخ 데이터그램으로 ڕاستەکی_دەیتا RTL8139 수신 گێژەن_نرخ 순환을 시험한다. */
public final class تۆڕ_گێژەن {
    public static int ڕادان() {
        if (بەکارهێنەر.인수개수() != 1) { بەکارهێنەر.ڕایت_کردن("Usage: run stress PORT\n"); return 2; }
        String دەق = بەکارهێنەر.인수(0);
        int دەرگا_نرخ = 0;
        for (int پێرست = 0; پێرست < دەق.length(); پێرست++) {
            if (دەق.charAt(پێرست) < '0' || دەق.charAt(پێرست) > '9' || دەرگا_نرخ > 6553) return 2;
            دەرگا_نرخ = دەرگا_نرخ * 10 + دەق.charAt(پێرست) - '0';
        }
        if (دەرگا_نرخ < 1 || دەرگا_نرخ > 65535) return 2;
        int دەسک_نرخ = بەکارهێنەر.کردنەوە_تۆڕ(0);
        if (دەسک_نرخ < 0) return 3;
        int[] دەیتا = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int درێژی_نرخ = 1024 - (회차 & 1);
            for (int پێرست = 0; پێرست < درێژی_نرخ; پێرست++) دەیتا[پێرست] = (پێرست + 회차) & 255;
            if (بەکارهێنەر.ناردن_دەیتا(دەسک_نرخ, 0x0a000202, دەرگا_نرخ, دەیتا, درێژی_نرخ) != درێژی_نرخ) return 4;
            if (بەکارهێنەر.자료받기(دەسک_نرخ, دەیتا, 300) != درێژی_نرخ) return 5;
            for (int پێرست = 0; پێرست < درێژی_نرخ; پێرست++) if (دەیتا[پێرست] != ((پێرست + 회차) & 255)) return 6;
        }
        بەکارهێنەر.داخستن_تۆڕ(دەسک_نرخ);
        بەکارهێنەر.ڕایت_کردن("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
