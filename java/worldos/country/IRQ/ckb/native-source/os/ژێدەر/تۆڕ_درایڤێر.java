/** PCI RTL8139 (10ec:8139), 단일 ناردن_نرخ 버퍼와 8KiB 수신 گێژەن_نرخ. 인터럽트 대신 폴링한다. */
public final class تۆڕ_درایڤێر {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] ئامێر_ناونیشان = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int 위치) {
        ئامێر_نرخ.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | 위치);
        return ئامێر_نرخ.입출력정수읽기(0xcfc);
    }

    static boolean ئامادە_کردن_9ce364fc() {
        int 장치번호 = -1;
        for (int پێرست = 0; پێرست < 32; پێرست++) {
            if (설정읽기(پێرست, 0) == 0x813910ec) { 장치번호 = پێرست; break; }
        }
        if (장치번호 < 0) return false;
        int بەهای_گریمانە = 설정읽기(장치번호, 0x10);
        if ((بەهای_گریمانە & 1) == 0 || (بەهای_گریمانە & 0xfffffffc) < 0x100 || (بەهای_گریمانە & 0xfffffffc) > 65535) return false;
        입출력기준주소 = بەهای_گریمانە & 0xfffc;
        int فەرمان = 설정읽기(장치번호, 4);
        ئامێر_نرخ.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        ئامێر_نرخ.입출력짧은수쓰기(0xcfc, فەرمان | 5); // I/O 및 bus master ڕێپێدان_نرخ_688200c4, PCI دۆخ_نرخ 비트는 건드리지 않음
        ئامێر_نرخ.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!ڕێککردنەوە_نرخ()) { 입출력기준주소 = 0; return false; }
        for (int پێرست = 0; پێرست < 6; پێرست++) ئامێر_ناونیشان[پێرست] = ئامێر_نرخ.입출력바이트읽기(입출력기준주소 + پێرست);
        return true;
    }

    static boolean ڕێککردنەوە_نرخ() {
        ئامێر_نرخ.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int ڕادان = ئامێر_نرخ.밀리초();
        while ((ئامێر_نرخ.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (ئامێر_نرخ.밀리초() - ڕادان > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        ئامێر_نرخ.입출력정수쓰기(입출력기준주소 + 0x30, ئامێر_نرخ.تۆڕ_بیرگە());
        for (int پێرست = 0; پێرست < 4; پێرست++) ئامێر_نرخ.입출력정수쓰기(입출력기준주소 + 0x20 + پێرست * 4, ئامێر_نرخ.تۆڕ_بیرگە() + 12288);
        ئامێر_نرخ.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        ئامێر_نرخ.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        ئامێر_نرخ.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        ئامێر_نرخ.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/방송, wrap 연속 Store_نرخ, 8KiB
        ئامێر_نرخ.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int ناردن(int[] دەیتا, int درێژی_نرخ) {
        if (입출력기준주소 == 0) return -19;
        if (درێژی_نرخ < 14 || درێژی_نرخ > 1514) return -90;
        int دۆخ_دەرگا = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int ڕادان = ئامێر_نرخ.밀리초();
        while ((ئامێر_نرخ.입출력정수읽기(دۆخ_دەرگا) & 0x2000) == 0)
            if (ئامێر_نرخ.밀리초() - ڕادان > 100) return -110;
        int گۆڕینی_ئەندازە = درێژی_نرخ < 60 ? 60 : درێژی_نرخ;
        for (int پێرست = 0; پێرست < گۆڕینی_ئەندازە; پێرست++)
            ئامێر_نرخ.ڕایت_کردن_بیرگە(ئامێر_نرخ.تۆڕ_بیرگە() + 12288 + پێرست, پێرست < درێژی_نرخ ? دەیتا[پێرست] : 0);
        ئامێر_نرخ.입출력정수쓰기(دۆخ_دەرگا, گۆڕینی_ئەندازە | 0x00080000);
        ڕادان = ئامێر_نرخ.밀리초();
        while ((ئامێر_نرخ.입출력정수읽기(دۆخ_دەرگا) & 0xe0008000) == 0)
            if (ئامێر_نرخ.밀리초() - ڕادان > 100) return -110;
        if ((ئامێر_نرخ.입출력정수읽기(دۆخ_دەرگا) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return درێژی_نرخ;
    }

    static int 받기(int[] دەیتا) {
        if (입출력기준주소 == 0) return 0;
        if ((ئامێر_نرخ.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!ڕێککردنەوە_نرخ()) 입출력기준주소 = 0;
            return 0;
        }
        if ((ئامێر_نرخ.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = ئامێر_نرخ.تۆڕ_بیرگە() + 수신위치;
        int دۆخ_نرخ = 실행관리.짧은수(머리), گۆڕینی_ئەندازە = 실행관리.짧은수(머리 + 2);
        if (گۆڕینی_ئەندازە == 0xfff0) return 0; // DMA 진행 중
        if (گۆڕینی_ئەندازە < 4 || گۆڕینی_ئەندازە > 1518) {
            오류수++;
            if (!ڕێککردنەوە_نرخ()) 입출력기준주소 = 0;
            return 0;
        }
        int درێژی_نرخ = گۆڕینی_ئەندازە - 4;
        if ((دۆخ_نرخ & 1) != 0) {
            for (int پێرست = 0; پێرست < درێژی_نرخ; پێرست++) دەیتا[پێرست] = ئامێر_نرخ.기억읽기(머리 + 4 + پێرست);
            수신수++;
        } else { درێژی_نرخ = 0; 오류수++; }
        수신위치 = (수신위치 + گۆڕینی_ئەندازە + 4 + 3) & ~3;
        수신위치 &= 8191;
        ئامێر_نرخ.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        ئامێر_نرخ.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return درێژی_نرخ;
    }
}
