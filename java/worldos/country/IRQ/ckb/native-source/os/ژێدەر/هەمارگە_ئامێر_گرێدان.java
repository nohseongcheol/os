/** 첫 IDE 장치의 512바이트 논리 بەش_نرخ. 이 계층은 포맷을 만들거나 임의 장치를 지우지 않는다. */
public final class هەمارگە_ئامێر_گرێدان {
    static boolean 사용가능 = false;
    static int[] بەش_دەیتا = new int[512];
    static void 잠깐기다리기() {
        for (int پێرست = 0; پێرست < 4; پێرست++) ئامێر_نرخ.입출력바이트읽기(0x3f6);
    }
    static int 준비기다리기(boolean 자료필요) {
        int ڕادان = ئامێر_نرخ.밀리초();
        while (ئامێر_نرخ.밀리초() - ڕادان < 500) {
            int دۆخ_نرخ = ئامێر_نرخ.입출력바이트읽기(0x1f7);
            if (دۆخ_نرخ == 0 || دۆخ_نرخ == 255) return -19;
            if ((دۆخ_نرخ & 128) == 0) {
                if ((دۆخ_نرخ & 33) != 0) return -5;
                if (!자료필요 || (دۆخ_نرخ & 8) != 0) return 0;
            }
            ئامێر_نرخ.잠시양보();
        }
        return -110;
    }
    static int 요청(int بەش_نرخ, int فەرمان) {
        if (بەش_نرخ < 0 || بەش_نرخ >= 2048) return -22;
        ئامێر_نرخ.입출력바이트쓰기(0x3f6, 2); // polling; IDE IRQ 사용 안 함
        ئامێر_نرخ.입출력바이트쓰기(0x1f6, 0xe0); 잠깐기다리기();
        int 결과 = 준비기다리기(false);
        if (결과 < 0) return 결과;
        ئامێر_نرخ.입출력바이트쓰기(0x1f2, 1);
        ئامێر_نرخ.입출력바이트쓰기(0x1f3, بەش_نرخ & 255);
        ئامێر_نرخ.입출력바이트쓰기(0x1f4, (بەش_نرخ >>> 8) & 255);
        ئامێر_نرخ.입출력바이트쓰기(0x1f5, 0);
        ئامێر_نرخ.입출력바이트쓰기(0x1f7, فەرمان); 잠깐기다리기();
        return 준비기다리기(true);
    }
    static int 읽기(int بەش_نرخ) {
        int 결과 = 요청(بەش_نرخ, 0x20);
        if (결과 < 0) return 결과;
        for (int پێرست = 0; پێرست < 256; پێرست++) {
            int نرخ = ئامێر_نرخ.입출력짧은수읽기(0x1f0);
            بەش_دەیتا[پێرست * 2] = نرخ & 255; بەش_دەیتا[پێرست * 2 + 1] = نرخ >>> 8;
        }
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int ڕایت_کردن(int بەش_نرخ) {
        if (!사용가능 || بەش_نرخ < 1 || بەش_نرخ > 518) return -19;
        int 결과 = 요청(بەش_نرخ, 0x30);
        if (결과 < 0) return 결과;
        for (int پێرست = 0; پێرست < 256; پێرست++)
            ئامێر_نرخ.입출력짧은수쓰기(0x1f0, بەش_دەیتا[پێرست * 2] | بەش_دەیتا[پێرست * 2 + 1] << 8);
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int 밀어쓰기() {
        if (!사용가능) return -19;
        ئامێر_نرخ.입출력바이트쓰기(0x1f7, 0xe7); 잠깐기다리기();
        return 준비기다리기(false);
    }
    static int 정수읽기(int 위치) {
        return بەش_دەیتا[위치] | بەش_دەیتا[위치 + 1] << 8 | بەش_دەیتا[위치 + 2] << 16 | بەش_دەیتا[위치 + 3] << 24;
    }
    static void ڕایت_کردن_ژمارەی_سروشتی_نرخ(int 위치, int نرخ) {
        for (int پێرست = 0; پێرست < 4; پێرست++) بەش_دەیتا[위치 + پێرست] = (نرخ >>> (پێرست * 8)) & 255;
    }
}
