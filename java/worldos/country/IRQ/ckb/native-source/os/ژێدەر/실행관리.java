            ڕادان = 끝;
            while (끝 < درێژی_نرخ && 입력[끝] != ' ') 끝++;
            ئارگیومێنت_ناونیشان[인수수++] = Store_نرخ;
            수쓰기(Store_نرخ, 끝 - ڕادان);
