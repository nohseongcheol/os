#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 بایت_نرخ 위치로 자체 C 이름을 옮기는 일회성 이행 ئامرازەکان.

외부 구조체의 멤버, رست_نرخ, C 표준 کردار_نرخ, 이식 규약은 보존한다.
입력은 گۆڕین_نرخ 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def جێبەجێکردن_فەرمان():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['هەڵە']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ناو_خشتە = json.loads((기준/'명명/시언어이름.json').read_text())
    SD = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {بێهاوتا_نرخ:ناو_خشتە[تێنووسین_نرخ['ناو']] for بێهاوتا_نرخ,تێنووسین_نرخ in 선언표.items()
                if تێنووسین_نرخ['ناو'] in ناو_خشتە and تێنووسین_نرخ['ناو'] not in SD}
    گرێدان_خشتە = {تێنووسین_نرخ['ناو']:ناو_خشتە[تێنووسین_نرخ['ناو']] for تێنووسین_نرخ in 선언표.values()
              if تێنووسین_نرخ.get('لكاندن')==4 and تێنووسین_نرخ['종류'] in (8,9)
              and تێنووسین_نرخ['ناو'] in ناو_خشتە and تێنووسین_نرخ['ناو'] not in SD}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 لكاندن 이름만 유지한다.
    머리 = ['/* 한국어 ژێدەر_دار 이름과 기존 مەکینه لكاندن ئەرک_نرخ. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(گرێدان_خشتە.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    گۆڕانکاریه_کان_لیست = defaultdict(dict)
    for فایل,ئۆفسێت_نرخ,ناو,بێهاوتا_نرخ in 분석['سەرچاوە']:
        if بێهاوتا_نرخ in 바꿀선언:
            گۆڕانکاریه_کان_لیست[فایل][ئۆفسێت_نرخ] = (ناو,바꿀선언[بێهاوتا_نرخ])
    تۆمار_ڕزن = ['فایل\t원래바이트위치\t이전이름\t한국어이름']
    فڕێدان_نرخ = []
    for فایل,گۆڕین_نرخ in گۆڕانکاریه_کان_لیست.items():
        گوزەر = Path(فایل); 원본 = گوزەر.read_bytes(); دەیتا = 원본
        for ئۆفسێت_نرخ,(옛이름,새이름) in sorted(گۆڕین_نرخ.items(),reverse=True):
            끝 = ئۆفسێت_نرخ+len(옛이름.encode())
            if 원본[ئۆفسێت_نرخ:끝] != 옛이름.encode():
                فڕێدان_نرخ.append((str(گوزەر.relative_to(기준)),ئۆفسێت_نرخ,옛이름));continue
            دەیتا = دەیتا[:ئۆفسێت_نرخ]+새이름.encode()+دەیتا[끝:]
            تۆمار_ڕزن.append('{}\t{}\t{}\t{}'.format(گوزەر.relative_to(기준),ئۆفسێت_نرخ,옛이름,새이름))
        گوزەر.write_bytes(دەیتا)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ماکرۆ_نرخ = {تێنووسین_نرخ['ناو']:ناو_خشتە[تێنووسین_نرخ['ناو']] for تێنووسین_نرخ in 선언표.values()
              if تێنووسین_نرخ['종류']==501 and تێنووسین_نرخ['ناو'] in ناو_خشتە and تێنووسین_نرخ['ناو'] not in SD}
    for گوزەر in sorted({Path(تێنووسین_نرخ['فایل']) for تێنووسین_نرخ in 선언표.values()}):
        دێڕ_لیست = گوزەر.read_text().splitlines(True); 이어짐 = False
        for پێرست,دێڕ in enumerate(دێڕ_لیست):
            전처리 = 이어짐 or bool(re.match(r'\s*#',دێڕ))
            이어짐 = 전처리 and دێڕ.rstrip().endswith('\\')
            if 전처리:
                표 = ناو_خشتە if re.match(r'\s*#\s*define\b',دێڕ) or 이어짐 else ماکرۆ_نرخ
                دێڕ_لیست[پێرست] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in SD else 맞음[0],دێڕ)
        گوزەر.write_text(''.join(دێڕ_لیست))
    # 각 자체 وەرگێڕان_ژێدەر 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for گوزەر in sorted({Path(تێنووسین_نرخ['فایل']) for تێنووسین_نرخ in 선언표.values()}):
        if گوزەر.suffix not in ('.c','.cpp'):continue
        هاوتا_نرخ = '../' * len(گوزەر.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        گوزەر.write_text('#include "'+هاوتا_نرخ+'"\n'+گوزەر.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(تۆمار_ڕزن)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(فڕێدان_نرخ,ensure_ascii=False,indent=2)+'\n')
    print('گۆڕین_نرخ',len(تۆمار_ڕزن)-1,'전처리 재검토',len(فڕێدان_نرخ),'مەکینه لكاندن',len(گرێدان_خشتە))

if __name__=='__main__': جێبەجێکردن_فەرمان()
