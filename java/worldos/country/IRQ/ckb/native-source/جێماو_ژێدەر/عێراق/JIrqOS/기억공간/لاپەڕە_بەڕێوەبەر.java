package عێراق.JIrqOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB لاپەڕە_نرخ 연결과 ڕایت_کردن 시 복사를 제공한다. */
public final class لاپەڕە_بەڕێوەبەر {
    public static final int قەبارەی_لاپەڕە = 4096;

    private static final class لاپەڕە_نرخ {
        private byte[] دەیتا = new byte[قەبارەی_لاپەڕە];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class ناونیشان_مەودا {
        private final Map<Integer, لاپەڕە_نرخ> لاپەڕە_خشتە = new HashMap<Integer, لاپەڕە_نرخ>();
    }

    public ناونیشان_مەودا 새주소공간() {
        return new ناونیشان_مەودا();
    }

    public void پیشاندان_لەسەر_نەخشە_لاپەڕە(ناونیشان_مەودا 공간, int مەجازی_ناونیشان, boolean 쓰기가능) {
        int پێرست = 쪽번호(مەجازی_ناونیشان);
        لاپەڕە_نرخ 새쪽 = new لاپەڕە_نرخ();
        새쪽.쓰기가능 = 쓰기가능;
        공간.لاپەڕە_خشتە.put(Integer.valueOf(پێرست), 새쪽);
    }

    public ناونیشان_مەودا 쓰기시복사복제(ناونیشان_مەودا 원본) {
        ناونیشان_مەودا 복제본 = new ناونیشان_مەودا();
        for (Map.Entry<Integer, لاپەڕە_نرخ> تێنووسین_نرخ : 원본.لاپەڕە_خشتە.entrySet()) {
            لاپەڕە_نرخ 공유쪽 = تێنووسین_نرخ.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.لاپەڕە_خشتە.put(تێنووسین_نرخ.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(ناونیشان_مەودا 공간, int مەجازی_ناونیشان) {
        لاپەڕە_نرخ مەبەست = دۆزینەوە_لاپەڕە(공간, مەجازی_ناونیشان);
        return مەبەست.دەیتا[Math.floorMod(مەجازی_ناونیشان, قەبارەی_لاپەڕە)];
    }

    public void ڕایت_کردن_بایت_نرخ(ناونیشان_مەودا 공간, int مەجازی_ناونیشان, byte نرخ) {
        int پێرست = 쪽번호(مەجازی_ناونیشان);
        لاپەڕە_نرخ مەبەست = دۆزینەوە_لاپەڕە(공간, مەجازی_ناونیشان);
        if (!مەبەست.쓰기가능) {
            if (!مەبەست.쓰기시복사) {
                throw new IllegalStateException("읽기 전용 쪽입니다.");
            }
            مەبەست = دروستکردن_تایبەت_لاپەڕە(공간, پێرست, مەبەست);
        }
        مەبەست.دەیتا[Math.floorMod(مەجازی_ناونیشان, قەبارەی_لاپەڕە)] = نرخ;
    }

    public void 범위개인쓰기(ناونیشان_مەودا 공간, int دەستپێك_ناونیشان, int گۆڕینی_ئەندازە) {
        if (گۆڕینی_ئەندازە < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int دوایی_کردن_ناونیشان = Math.addExact(دەستپێك_ناونیشان, گۆڕینی_ئەندازە);
        for (int ناونیشان = دەستپێك_ناونیشان; ناونیشان < دوایی_کردن_ناونیشان; ناونیشان = (쪽번호(ناونیشان) + 1) * قەبارەی_لاپەڕە) {
            int پێرست = 쪽번호(ناونیشان);
            لاپەڕە_نرخ مەبەست = دۆزینەوە_لاپەڕە(공간, ناونیشان);
            if (مەبەست.쓰기시복사) {
                دروستکردن_تایبەت_لاپەڕە(공간, پێرست, مەبەست);
            } else {
                مەبەست.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(ناونیشان_مەودا 공간, int دەستپێك_ناونیشان, byte[] دەیتا) {
        for (int پێرست = 0; پێرست < دەیتا.length; پێرست++) {
            ڕایت_کردن_بایت_نرخ(공간, دەستپێك_ناونیشان + پێرست, دەیتا[پێرست]);
        }
    }

    private لاپەڕە_نرخ دروستکردن_تایبەت_لاپەڕە(ناونیشان_مەودا 공간, int پێرست, لاپەڕە_نرخ 공유쪽) {
        لاپەڕە_نرخ تایبەت_لاپەڕە = new لاپەڕە_نرخ();
        تایبەت_لاپەڕە.دەیتا = Arrays.copyOf(공유쪽.دەیتا, 공유쪽.دەیتا.length);
        تایبەت_لاپەڕە.쓰기가능 = true;
        تایبەت_لاپەڕە.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.لاپەڕە_خشتە.put(Integer.valueOf(پێرست), تایبەت_لاپەڕە);
        return تایبەت_لاپەڕە;
    }

    private لاپەڕە_نرخ دۆزینەوە_لاپەڕە(ناونیشان_مەودا 공간, int ناونیشان) {
        لاپەڕە_نرخ مەبەست = 공간.لاپەڕە_خشتە.get(Integer.valueOf(쪽번호(ناونیشان)));
        if (مەبەست == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return مەبەست;
    }

    private int 쪽번호(int ناونیشان) {
        if (ناونیشان < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return ناونیشان / قەبارەی_لاپەڕە;
    }
}

