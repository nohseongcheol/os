class سیستم_خطا(OSError):
    def __init__(자신, فهرست, 설명="سیستم_عامل 작업에 실패했습니다."):
        super().__init__(فهرست, 설명)
        자신.فهرست = فهرست
        자신.설명 = 설명

def 운영호출(عملکرد_مقدار, *نشانوندها):
    try:
        return عملکرد_مقدار(*نشانوندها)
    except OSError as خطا:
        فهرست = خطا.args[0] if خطا.args else 0
        raise سیستم_خطا(فهرست)

def 글부호화(متن):
    return متن.encode("utf-8")

def 글해독(داده_ها):
    return داده_ها.decode("utf-8")

def 파일읽기(نام):
    return 운영호출(سیستم_عامل.read, نام)

