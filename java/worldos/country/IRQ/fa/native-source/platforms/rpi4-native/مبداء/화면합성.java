/** 화면 برش_مقدار·띠 합성·اشاره_گر 밑그림을 관리한다. واقعی_داده_ها 화면 حافظه_داده_ها 접근은 보드가 담당한다. */
public final class 화면합성 {
    static int 너비, 높이, 합성중, 왼경계, 위경계, 오른경계, 아래경계;
    static int اشاره_گر_دکمه_X, اشاره_گر_دکمه_Y, اشاره_گر_شکل;
    static int 기록아래낱말, 기록위낱말;
    static int[] 완성그림 = new int[32 * 1920];
    static int[] اشاره_گر_زمینه = new int[21 * 21];
    static int[] 잘린범위 = new int[4];
    public static void آماده_کردن(int 폭, int طول_مقدار) {
        너비 = 폭; 높이 = طول_مقدار; 합성중 = 0; اشاره_گر_شکل = 0;
        기록아래낱말 = 0; 기록위낱말 = 0;
    }
    public static int 너비얻기() { return 너비; }
    public static int 높이얻기() { return 높이; }
    public static int 기록아래얻기() { return 기록아래낱말; }
    public static int 기록위얻기() { return 기록위낱말; }
    public static int کلیپ_مقدار(int 순번) { return 잘린범위[순번]; }
    static int 양의길이더하기(int شروع_مقدار, int طول_مقدار) {
        if (شروع_مقدار > 2147483647 - طول_مقدار) return 2147483647;
        return شروع_مقدار + طول_مقدار;
    }
    public static int کلیپ(int 가로, int عمودی_مرتب_کردن, int 폭, int طول_مقدار) {
        if (너비 == 0 || 폭 <= 0 || طول_مقدار <= 0) return 0;
        int 오른쪽 = 양의길이더하기(가로, 폭), 아래쪽 = 양의길이더하기(عمودی_مرتب_کردن, طول_مقدار);
        int 왼쪽 = 합성중 != 0 ? 왼경계 : 0, 위쪽 = 합성중 != 0 ? 위경계 : 0;
        int 최대가로 = 합성중 != 0 ? 오른경계 : 너비, 최대세로 = 합성중 != 0 ? 아래경계 : 높이;
        if (가로 < 왼쪽) 가로 = 왼쪽;
        if (عمودی_مرتب_کردن < 위쪽) عمودی_مرتب_کردن = 위쪽;
        if (오른쪽 > 최대가로) 오른쪽 = 최대가로;
        if (아래쪽 > 최대세로) 아래쪽 = 최대세로;
        if (오른쪽 <= 가로 || 아래쪽 <= عمودی_مرتب_کردن) return 0;
        잘린범위[0] = 가로; 잘린범위[1] = عمودی_مرتب_کردن;
        잘린범위[2] = 오른쪽 - 가로; 잘린범위[3] = 아래쪽 - عمودی_مرتب_کردن;
        return 1;
    }
    public static int اجرا_2(int 가로, int عمودی_مرتب_کردن, int 폭, int طول_مقدار) {
        if (합성중 != 0 || طول_مقدار > 32 || کلیپ(가로, عمودی_مرتب_کردن, 폭, طول_مقدار) == 0) return 0;
        왼경계 = 잘린범위[0]; 위경계 = 잘린범위[1];
        오른경계 = 왼경계 + 잘린범위[2]; 아래경계 = 위경계 + 잘린범위[3];
        합성중 = 1; return 1;
    }
    static boolean اشاره_گر_بیت(int 가로, int عمودی_مرتب_کردن, int شکل_مقدار) {
        if (شکل_مقدار == 1) return 가로 >= 0 && 가로 <= عمودی_مرتب_کردن / 2 && عمودی_مرتب_کردن < 16;
        if (شکل_مقدار == 3) 가로 = 20 - 가로;
        int 차이 = 가로 - عمودی_مرتب_کردن; if (차이 < 0) 차이 = -차이;
        return (차이 <= 1 && 가로 >= 3 && 가로 <= 17) ||
            (가로 >= 2 && 가로 <= 8 && عمودی_مرتب_کردن >= 2 && عمودی_مرتب_کردن <= 8 && (가로 <= 3 || عمودی_مرتب_کردن <= 3)) ||
            (가로 >= 12 && 가로 <= 18 && عمودی_مرتب_کردن >= 12 && عمودی_مرتب_کردن <= 18 && (가로 >= 17 || عمودی_مرتب_کردن >= 17));
    }
    static int اشاره_گر_پیکسل(int 가로, int عمودی_مرتب_کردن) {
        if (اشاره_گر_بیت(가로, عمودی_مرتب_کردن, اشاره_گر_شکل)) return 2;
        for (int خط = -1; خط <= 1; خط++) for (int شکاف_ورودی = -1; شکاف_ورودی <= 1; شکاف_ورودی++)
            if (اشاره_گر_بیت(가로 + شکاف_ورودی, عمودی_مرتب_کردن + خط, اشاره_گر_شکل)) return 1;
        return 0;
    }
    static void صفحه_نمایش_پیکسل(int 가로, int عمودی_مرتب_کردن, int 색) {
        int شکاف_ورودی = 가로 - اشاره_گر_دکمه_X, خط = عمودی_مرتب_کردن - اشاره_گر_دکمه_Y;
        if (اشاره_گر_شکل != 0 && شکاف_ورودی >= 0 && خط >= 0 && شکاف_ورودی < 21 && خط < 21) {
            اشاره_گر_زمینه[خط * 21 + شکاف_ورودی] = 색;
            int نقطه_مقدار = اشاره_گر_پیکسل(شکاف_ورودی, خط); if (نقطه_مقدار != 0) 색 = نقطه_مقدار == 2 ? 0xffffff : 0x101010;
        }
        if (تخته_ای.표시화소읽기(가로, عمودی_مرتب_کردن) != 색) {
            تخته_ای.نوشتن_صفحه_نمایش_پیکسل(가로, عمودی_مرتب_کردن, 색);
            기록아래낱말++; if (기록아래낱말 == 0) 기록위낱말++;
        }
    }
    public static void خاتمه() {
        if (합성중 == 0) return;
        for (int خط = 위경계; خط < 아래경계; خط++) for (int شکاف_ورودی = 왼경계; شکاف_ورودی < 오른경계; شکاف_ورودی++)
            صفحه_نمایش_پیکسل(شکاف_ورودی, خط, 완성그림[(خط - 위경계) * 1920 + شکاف_ورودی]);
        합성중 = 0;
    }
    public static int پیکسل(int 가로, int عمودی_مرتب_کردن, int 색) {
        if (가로 < 0 || عمودی_مرتب_کردن < 0 || 가로 >= 너비 || عمودی_مرتب_کردن >= 높이) return 0;
        if (합성중 != 0) {
            if (가로 >= 왼경계 && 가로 < 오른경계 && عمودی_مرتب_کردن >= 위경계 && عمودی_مرتب_کردن < 아래경계)
                완성그림[(عمودی_مرتب_کردن - 위경계) * 1920 + 가로] = 색;
        } else صفحه_نمایش_پیکسل(가로, عمودی_مرتب_کردن, 색);
        return 0;
    }
    public static void 사각그림(int 가로, int عمودی_مرتب_کردن, int 폭, int طول_مقدار, int 색) {
        if (کلیپ(가로, عمودی_مرتب_کردن, 폭, طول_مقدار) == 0) return;
        가로 = 잘린범위[0]; عمودی_مرتب_کردن = 잘린범위[1]; 폭 = 잘린범위[2]; طول_مقدار = 잘린범위[3];
        for (int خط = عمودی_مرتب_کردن; خط < عمودی_مرتب_کردن + طول_مقدار; خط++) for (int شکاف_ورودی = 가로; شکاف_ورودی < 가로 + 폭; شکاف_ورودی++) {
            if (합성중 != 0) 완성그림[(خط - 위경계) * 1920 + شکاف_ورودی] = 색;
            else صفحه_نمایش_پیکسل(شکاف_ورودی, خط, 색);
        }
    }
    public static void اشاره_گر(int 가로, int عمودی_مرتب_کردن, int شکل_مقدار) {
        if (너비 == 0) return;
        int 새가로 = 가로 - (شکل_مقدار >= 2 ? 10 : 0), 새세로 = عمودی_مرتب_کردن - (شکل_مقدار >= 2 ? 10 : 0);
        if (اشاره_گر_شکل == شکل_مقدار && اشاره_گر_دکمه_X == 새가로 && اشاره_گر_دکمه_Y == 새세로) return;
        if (اشاره_گر_شکل != 0) for (int خط = 0; خط < 21; خط++) for (int شکاف_ورودی = 0; شکاف_ورودی < 21; شکاف_ورودی++) {
            int 가 = اشاره_گر_دکمه_X + شکاف_ورودی, 세 = اشاره_گر_دکمه_Y + خط;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) تخته_ای.نوشتن_صفحه_نمایش_پیکسل(가, 세, اشاره_گر_زمینه[خط * 21 + شکاف_ورودی]);
        }
        اشاره_گر_شکل = شکل_مقدار; اشاره_گر_دکمه_X = 새가로; اشاره_گر_دکمه_Y = 새세로;
        if (شکل_مقدار != 0) for (int خط = 0; خط < 21; خط++) for (int شکاف_ورودی = 0; شکاف_ورودی < 21; شکاف_ورودی++) {
            int 가 = اشاره_گر_دکمه_X + شکاف_ورودی, 세 = اشاره_گر_دکمه_Y + خط;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) {
                اشاره_گر_زمینه[خط * 21 + شکاف_ورودی] = تخته_ای.표시화소읽기(가, 세);
                int نقطه_مقدار = اشاره_گر_پیکسل(شکاف_ورودی, خط); if (نقطه_مقدار != 0) تخته_ای.نوشتن_صفحه_نمایش_پیکسل(가, 세, نقطه_مقدار == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
