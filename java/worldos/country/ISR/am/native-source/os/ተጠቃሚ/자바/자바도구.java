/** 게스트 መሳሪያዎች 공통 ውጤት 및 ASCII ፋይል ስም ሂደት_እሴት_ምዝግብ. */
public final class 자바도구 {
    /** UTF-8 ባይት_እሴት 배열을 같은 배열의 UTF-16 단위로 바꾼다. 잘못된 입력은 አትቀበል_እሴት. */
    static int 원문해독(int[] ውሂብ, int ርዝመት_እሴት) {
        int ማንበቢያ = 0, መጻፊያ = 0;
        if (ርዝመት_እሴት >= 3 && ውሂብ[0] == 239 && ውሂብ[1] == 187 && ውሂብ[2] == 191) ማንበቢያ = 3;
        while (ማንበቢያ < ርዝመት_እሴት) {
            int እሴት = ውሂብ[ማንበቢያ++], 수 = 0, 최소 = 0;
            if (እሴት >= 194 && እሴት <= 223) { 수 = 1; 최소 = 128; እሴት &= 31; }
            else if (እሴት >= 224 && እሴት <= 239) { 수 = 2; 최소 = 2048; እሴት &= 15; }
            else if (እሴት >= 240 && እሴት <= 244) { 수 = 3; 최소 = 65536; እሴት &= 7; }
            else if (እሴት >= 128 || እሴት < 0) return -1;
            if (수 > ርዝመት_እሴት - ማንበቢያ) return -1;
            for (int i = 0; i < 수; i++) {
                int ቀጣይ_ንጥል_ነገር = ውሂብ[ማንበቢያ++]; if ((ቀጣይ_ንጥል_ነገር & 192) != 128) return -1;
                እሴት = (እሴት << 6) | (ቀጣይ_ንጥል_ነገር & 63);
            }
            if (እሴት < 최소 || እሴት > 0x10ffff || (እሴት >= 0xd800 && እሴት <= 0xdfff)) return -1;
            if (እሴት >= 65536) { እሴት -= 65536; ውሂብ[መጻፊያ++] = 0xd800 | (እሴት >> 10); ውሂብ[መጻፊያ++] = 0xdc00 | (እሴት & 1023); }
            else ውሂብ[መጻፊያ++] = እሴት;
        }
        return መጻፊያ;
    }
    static void 수쓰기(int እሴት) {
        if (እሴት < 0) ተጠቃሚ.ጻፍ_ቁምፊ_እሴት('-'); else እሴት = -እሴት;
        int በቦታ_አስቀመጠ_መረጃ_ጠቆመ = 1000000000;
        boolean ማስኬጃ = false;
        while (በቦታ_አስቀመጠ_መረጃ_ጠቆመ != 0) {
            int 수 = -(እሴት / በቦታ_አስቀመጠ_መረጃ_ጠቆመ);
            if (수 != 0 || ማስኬጃ || በቦታ_አስቀመጠ_መረጃ_ጠቆመ == 1) { ተጠቃሚ.ጻፍ_ቁምፊ_እሴት('0' + 수); ማስኬጃ = true; }
            እሴት %= በቦታ_አስቀመጠ_መረጃ_ጠቆመ; በቦታ_አስቀመጠ_መረጃ_ጠቆመ /= 10;
        }
    }
    static int ስም(int[] መድረሻ_እሴት, String 원본) {
        if (원본.length() >= መድረሻ_እሴት.length) return -1;
        for (int 수 = 0; 수 < መድረሻ_እሴት.length; 수++) መድረሻ_እሴት[수] = 수 < 원본.length() ? 원본.charAt(수) : 0;
        return 원본.length();
    }
    static boolean 같음(String 가, String 나) {
        if (가.length() != 나.length()) return false;
        for (int 수 = 0; 수 < 가.length(); 수++) if (가.charAt(수) != 나.charAt(수)) return false;
        return true;
    }
}
