public final class 단말 {
    static void 문자(int እሴት) {
        if (እሴት < 0x80) ቦርድ.직렬쓰기(እሴት);
        else if (እሴት < 0x800) {
            ቦርድ.직렬쓰기(0xc0 | (እሴት >> 6)); ቦርድ.직렬쓰기(0x80 | (እሴት & 63));
        } else if (እሴት < 0x10000) {
            ቦርድ.직렬쓰기(0xe0 | (እሴት >> 12)); ቦርድ.직렬쓰기(0x80 | ((እሴት >> 6) & 63)); ቦርድ.직렬쓰기(0x80 | (እሴት & 63));
        } else {
            ቦርድ.직렬쓰기(0xf0 | (እሴት >> 18)); ቦርድ.직렬쓰기(0x80 | ((እሴት >> 12) & 63));
            ቦርድ.직렬쓰기(0x80 | ((እሴት >> 6) & 63)); ቦርድ.직렬쓰기(0x80 | (እሴት & 63));
        }
    }
    static void መጻፊያ(String ጽሁፍ) {
        for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < ጽሁፍ.length(); መረጃ_ጠቆመ++) {
            int እሴት = ጽሁፍ.charAt(መረጃ_ጠቆመ);
            if (እሴት >= 0xd800 && እሴት <= 0xdbff && መረጃ_ጠቆመ + 1 < ጽሁፍ.length()) {
                int 아래 = ጽሁፍ.charAt(መረጃ_ጠቆመ + 1);
                if (아래 >= 0xdc00 && 아래 <= 0xdfff) {
                    እሴት = 0x10000 + ((እሴት - 0xd800) << 10) + 아래 - 0xdc00; መረጃ_ጠቆመ++;
                }
            }
            if (እሴት >= 0xd800 && እሴት <= 0xdfff) እሴት = 0xfffd;
            문자(እሴት);
        }
    }
    static void 수(int እሴት) {
        if (እሴት < 0) 문자('-'); else እሴት = -እሴት;
        int በቦታ_አስቀመጠ_መረጃ_ጠቆመ = 1000000000;
        boolean ማስኬጃ = false;
        while (በቦታ_አስቀመጠ_መረጃ_ጠቆመ > 0) {
            int 숫자 = -(እሴት / በቦታ_አስቀመጠ_መረጃ_ጠቆመ);
            if (숫자 != 0 || ማስኬጃ || በቦታ_አስቀመጠ_መረጃ_ጠቆመ == 1) { 문자('0' + 숫자); ማስኬጃ = true; }
            እሴት %= በቦታ_አስቀመጠ_መረጃ_ጠቆመ; በቦታ_አስቀመጠ_መረጃ_ጠቆመ /= 10;
        }
    }
}
