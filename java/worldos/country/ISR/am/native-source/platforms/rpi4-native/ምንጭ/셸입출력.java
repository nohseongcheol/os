/** 파이프는 16 KiB씩 순서대로 실행한다. 프로세스/동시 파이프를 흉내 내지 않는다. */
public final class 셸입출력 {
    static int[] 입력자료 = new int[16384], 출력자료 = new int[16384];
    static int 입력길이, 입력위치, 출력길이, 입력파일 = -1, የውጤት_ፋይል = -1;
    static boolean 파이프입력, 파이프출력;
    static int ተስኖት_እሴት;
    static boolean ፍቀድ_በይነተገናኝ = true;
    public static int የመረጃ_ቴክኖሎጂ_በይነተገናኝ() { return ፍቀድ_በይነተገናኝ && 입력파일 < 3 && የውጤት_ፋይል < 3 && !파이프입력 && !파이프출력 ? 1 : 0; }
    public static int ውጤት(int ሰርጥ_እሴት, int እሴት) {
        if (ሰርጥ_እሴት != 1) return 0;
        if (የውጤት_ፋይል >= 3) { int 처리값 = ማስቀመጫ_ፋይሎች.መጻፊያ(የውጤት_ፋይል, እሴት); if (처리값 < 0) ተስኖት_እሴት = 처리값; return 1; }
        if (!파이프출력) return 0;
        if (출력길이 == 출력자료.length) ተስኖት_እሴት = -28;
        else 출력자료[출력길이++] = እሴት;
        return 1;
    }
    public static int 입력() {
        if (입력파일 >= 3) { int 처리값 = ማስቀመጫ_ፋይሎች.ማንበቢያ(입력파일); return 처리값 == 256 ? -2 : 처리값; }
        if (파이프입력) return 입력위치 < 입력길이 ? 입력자료[입력위치++] : -2;
        return -3; // UART로 አሳልፍ_እሴት
    }
    static void ማስኬጃ(boolean መሪ_ፓይፕ, boolean 뒤파이프) {
        파이프입력 = መሪ_ፓይፕ; 파이프출력 = 뒤파이프;
        입력위치 = 0; 출력길이 = 0; 입력파일 = -1; የውጤት_ፋይል = -1; ተስኖት_እሴት = 0;
    }
    static void 끝() {
        ቦርድ.입출력전환(0);
        if (입력파일 >= 3) ማስቀመጫ_ፋይሎች.መዝጊያ(입력파일);
        if (የውጤት_ፋይል >= 3) ማስቀመጫ_ፋይሎች.መዝጊያ(የውጤት_ፋይል);
        if (파이프출력) { 입력길이 = 출력길이; for (int ድግግሞሽ_መረጃ_ጠቆመ = 0; ድግግሞሽ_መረጃ_ጠቆመ < 출력길이; ድግግሞሽ_መረጃ_ጠቆመ++) 입력자료[ድግግሞሽ_መረጃ_ጠቆመ] = 출력자료[ድግግሞሽ_መረጃ_ጠቆመ]; }
        입력파일 = -1; የውጤት_ፋይል = -1; 파이프입력 = false; 파이프출력 = false;
    }
}
