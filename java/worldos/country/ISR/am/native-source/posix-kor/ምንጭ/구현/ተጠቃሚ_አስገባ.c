#include "호출경계.h"
extern int main(int 인수개수, char **ነጋሪ_እሴት_ዝርዝር);
static char ነጋሪ_እሴት_ማስቀመጫ[2048];
static char *ነጋሪ_እሴት_ዝርዝር[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 ፈጽም_ትእዛዝ 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    ነጋሪ_እሴት_ዝርዝር[0] = "jkoros-app";
    int አካባቢ = 0;
    for (int መረጃ_ጠቆመ = 0; መረጃ_ጠቆመ < 개수; መረጃ_ጠቆመ++) {
        const int *원본 = (const int *)jkoros_syscall(3, መረጃ_ጠቆመ, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        ነጋሪ_እሴት_ዝርዝር[መረጃ_ጠቆመ + 1] = ነጋሪ_እሴት_ማስቀመጫ + አካባቢ;
        for (int ማስገቢያ_ቀዳዳ_ምዝግብ = 0; ማስገቢያ_ቀዳዳ_ምዝግብ < 원본[0]; ማስገቢያ_ቀዳዳ_ምዝግብ++) {
            if (አካባቢ >= 2047) return 126;
            ነጋሪ_እሴት_ማስቀመጫ[አካባቢ++] = 원본[ማስገቢያ_ቀዳዳ_ምዝግብ + 1];
        }
        ነጋሪ_እሴት_ማስቀመጫ[አካባቢ++] = 0;
    }
    ነጋሪ_እሴት_ዝርዝር[개수 + 1] = 0;
    return main(개수 + 1, ነጋሪ_እሴት_ዝርዝር);
}
