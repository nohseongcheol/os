import עברית.עצמי.חלון;
import עברית.עצמי.תווית;
import עברית.עצמי.שדה_טקסט;
import עברית.עצמי.לחצן;
import עברית.עצמי.אירוע_תור;
import עברית.עצמי.פלטטקסט;
import עברית.עצמי.실행할일;
import עברית.עצמי.동작받이;
import עברית.עצמי.המלצה_הודעה;

/** עצמי 커널의 Swing חלון: he קלט_ערך → לחצן → 안내 טקסט רענן. */
public class דוגמתחלון implements 실행할일, 동작받이 {
    private חלון 인사창;
    private שדה_טקסט שם_שדה;
    private תווית 인사말;
    private int 인사횟수;

    public void פתח_חלון() {
        인사창 = new חלון("he Swing", 460, 300);
        인사창.הוסף_רכיב(new תווית("שלום", 20, 20, 420, 28));
        שם_שדה = new שדה_טקסט("he", 20, 64, 420, 30);
        인사말 = new תווית("שלום", 20, 152, 420, 28);
        인사창.הוסף_רכיב(שם_שדה);
        인사창.הוסף_רכיב(new לחצן("인사하기", 20, 108, 180, 32, this));
        인사창.הוסף_רכיב(인사말);
        인사창.הוסף_רכיב(new תווית("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.הופעה_חלון();
        פלטטקסט.כתיבה_קו("GUI 예제 להכין: דוגמתחלון");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.כתיבה_טקסט("שלום, " + שם_שדה.글읽기() + "님! (" + 인사횟수 + ")");
        פלטטקסט.כתיבה_קו("GUI 인사: " + 인사말.글읽기());
    }

    public void בצע() { פתח_חלון(); }
    public void לקבל_המלצה(המלצה_הודעה הודעה) {
        פלטטקסט.כתיבה_קו("פעולה הודעה: " + הודעה.פקודה_טקסט());
        인사하기();
    }
    public static void הפעלה() {
        אירוע_תור.나중에실행(new דוגמתחלון());
    }
}
