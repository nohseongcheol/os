import עברית.עצמי.קשר;
import עברית.עצמי.실행인수;
import עברית.עצמי.יחידת_נתונים_ערוץ;
import עברית.עצמי.문자;
import עברית.עצמי.פלטטקסט;
import עברית.עצמי.검사;
import עברית.עצמי.זרימת_קלט;
import עברית.עצמי.קלט_פלט_חריגה;

public class דוגמתרשת {
    public static void הפעלה() throws קלט_פלט_חריגה {
        // ארח: python3 כלים/예제되돌림.py --tcp-port 9000 --udp-port 9001
        קשר חיבור = קשר.פתח("10.0.2.2", 문자.ניתוח_מבנה_טקסט_מספר_שלם(실행인수.טקסט(0)));
        try {
            חיבור.פסק_זמן(700);
            byte[] דואר = 문자.לקדד("JAVA TCP he\n");
            חיבור.פלטטקסט().כתוב(דואר);
            זרימת_קלט קלט_ערך = חיבור.קלט_ערך();
            for (int 수 = 0; 수 < 문자.바이트수(דואר); 수++) {
                검사.참인지(קלט_ערך.קרא() == (דואר[수] & 255), "TCP מענה 불일치");
            }
        } finally { חיבור.סגירה(); }
        יחידת_נתונים_ערוץ משתתף = יחידת_נתונים_ערוץ.פתח(0);
        try {
            משתתף.פסק_זמן(700);
            משתתף.שלח("10.0.2.2", 문자.ניתוח_מבנה_טקסט_מספר_שלם(실행인수.טקסט(1)), "JAVA UDP he");
            검사.참인지(문자.같음(משתתף.לקבל(), "JAVA UDP he"), "UDP מענה 불일치");
        } finally { משתתף.סגירה(); }
        פלטטקסט.כתיבה_קו("JAVA 네트워크 ודא_אמת: TCP UDP he");
    }
}
