#!/usr/bin/env python3
"""הצהרה 고유번호와 UTF-8 בית_ערך 위치로 עצמי C 이름을 옮기는 일회성 이행 כלים.

חיצוני_ערך 구조체의 멤버, מחרוזת_ערך, C 표준 פונקציה_ערך, 이식 규약은 보존한다.
입력은 שנה_ערך 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

לשקף_בסיס = Path(__file__).resolve().parents[1]

def לבצע_פקודה():
    לנתח_ערך = json.loads((לשקף_בסיס/'build/한국어화/시언어분석.json').read_text())
    if לנתח_ערך['שגיאה']: raise SystemExit('לנתח_ערך 오류를 먼저 해결해야 합니다.')
    שם_טבלה = json.loads((לשקף_בסיס/'명명/시언어이름.json').read_text())
    תקן_הגדרה = set(json.loads((לשקף_בסיס/'명명/규격이름.json').read_text()))
    הצהרה_טבלה = לנתח_ערך['הצהרה']
    바꿀선언 = {고유:שם_טבלה[ערך_ערך['שם']] for 고유,ערך_ערך in הצהרה_טבלה.items()
                if ערך_ערך['שם'] in שם_טבלה and ערך_ערך['שם'] not in תקן_הגדרה}
    קשר_טבלה = {ערך_ערך['שם']:שם_טבלה[ערך_ערך['שם']] for ערך_ערך in הצהרה_טבלה.values()
              if ערך_ערך.get('חיבור')==4 and ערך_ערך['종류'] in (8,9)
              and ערך_ערך['שם'] in שם_טבלה and ערך_ערך['שם'] not in תקן_הגדרה}
    # יצר AOT C·어셈블리·공개 SDK가 공유하는 바이너리 חיבור 이름만 유지한다.
    ראש_ערך = ['/* עברית מקור_עץ 이름과 기존 מחשב חיבור ערך_חוזה. 자동 יצר: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    ראש_ערך += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(קשר_טבלה.items())]
    ראש_ערך += ['#endif','']
    (לשקף_בסיס/'명명/기계연결이름.h').write_text('\n'.join(ראש_ערך))
    שינויים_רשימה = defaultdict(dict)
    for קובץ,היסט_ערך,שם,고유 in לנתח_ערך['הפנה']:
        if 고유 in 바꿀선언:
            שינויים_רשימה[קובץ][היסט_ערך] = (שם,바꿀선언[고유])
    לרשום_שיא = ['קובץ\t원래바이트위치\t이전이름\t한국어이름']
    התעלם_ערך = []
    for קובץ,שנה_ערך in שינויים_רשימה.items():
        נתיב = Path(קובץ); 원본 = נתיב.read_bytes(); נתונים = 원본
        for היסט_ערך,(옛이름,새이름) in sorted(שנה_ערך.items(),reverse=True):
            끝 = היסט_ערך+len(옛이름.encode())
            if 원본[היסט_ערך:끝] != 옛이름.encode():
                התעלם_ערך.append((str(נתיב.relative_to(לשקף_בסיס)),היסט_ערך,옛이름));continue
            נתונים = נתונים[:היסט_ערך]+새이름.encode()+נתונים[끝:]
            לרשום_שיא.append('{}\t{}\t{}\t{}'.format(נתיב.relative_to(לשקף_בסיס),היסט_ערך,옛이름,새이름))
        נתיב.write_bytes(נתונים)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    מאקרו_ערך = {ערך_ערך['שם']:שם_טבלה[ערך_ערך['שם']] for ערך_ערך in הצהרה_טבלה.values()
              if ערך_ערך['종류']==501 and ערך_ערך['שם'] in שם_טבלה and ערך_ערך['שם'] not in תקן_הגדרה}
    for נתיב in sorted({Path(ערך_ערך['קובץ']) for ערך_ערך in הצהרה_טבלה.values()}):
        קו_רשימה = נתיב.read_text().splitlines(True); 이어짐 = False
        for מדד,שורה in enumerate(קו_רשימה):
            전처리 = 이어짐 or bool(re.match(r'\s*#',שורה))
            이어짐 = 전처리 and שורה.rstrip().endswith('\\')
            if 전처리:
                טבלת_בדיקת_מידע = שם_טבלה if re.match(r'\s*#\s*define\b',שורה) or 이어짐 else מאקרו_ערך
                קו_רשימה[מדד] = 낱말.sub(lambda 맞음: טבלת_בדיקת_מידע.get(맞음[0],맞음[0]) if 맞음[0] not in תקן_הגדרה else 맞음[0],שורה)
        נתיב.write_text(''.join(קו_רשימה))
    # 각 עצמי תרגם_מקור 단위에만 연결표를 넣는다. חיצוני_ערך 배포본에는 전파하지 않는다.
    for נתיב in sorted({Path(ערך_ערך['קובץ']) for ערך_ערך in הצהרה_טבלה.values()}):
        if נתיב.suffix not in ('.c','.cpp'):continue
        עמית_ערך = '../' * len(נתיב.relative_to(לשקף_בסיס).parts[:-1]) + '명명/기계연결이름.h'
        נתיב.write_text('#include "'+עמית_ערך+'"\n'+נתיב.read_text())
    (לשקף_בסיס/'명명/시언어이름대응.tsv').write_text('\n'.join(לרשום_שיא)+'\n')
    (לשקף_בסיס/'build/한국어화/전처리참조.json').write_text(json.dumps(התעלם_ערך,ensure_ascii=False,indent=2)+'\n')
    print('שנה_ערך',len(לרשום_שיא)-1,'전처리 재검토',len(התעלם_ערך),'מחשב חיבור',len(קשר_טבלה))

if __name__=='__main__': לבצע_פקודה()
