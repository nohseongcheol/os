#!/usr/bin/env python3
"""בנייה 변환이 עברית מחרוזת_ערך, 주석, 헤더 경로를 바꾸지 않는지 검사한다."""
from מזהה_המרה import המר_ערך

קודמקור = '''#include <파일규약.h>
#include "통신규약.h"
// פתח_קובץ 라는 주석
/* 자료이름 */
const char *קובץ_ערך_שם = "한글 \\" מחרוזת_ערך";
char תו_ערך = '가';
int 파일열기_횟수 = 1;
'''
פלטטקסט = המר_ערך(קודמקור)
assert '#include <파일규약.h>' in פלטטקסט
assert '#include "통신규약.h"' in פלטטקסט
assert '// פתח_קובץ 라는 주석' in פלטטקסט
assert '/* 자료이름 */' in פלטטקסט
assert '"한글 \\" מחרוזת_ערך"' in פלטטקסט
assert "'가'" in פלטטקסט
assert '\\ud30c\\uc77c\\uc774\\ub984' in פלטטקסט
assert '파일열기_횟수' not in פלטטקסט
assert המר_ערך(פלטטקסט) == פלטטקסט
print('PASS: עברית מזהה_ערך המר_ערך/מחרוזת_ערך·주석·נתיב 보존')
