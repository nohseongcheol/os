import ትግርኛ.자체.ርክብ;
import ትግርኛ.자체.실행인수;
import ትግርኛ.자체.전문통로;
import ትግርኛ.자체.문자;
import ትግርኛ.자체.출력;
import ትግርኛ.자체.검사;
import ትግርኛ.자체.입력흐름;
import ትግርኛ.자체.입출력예외;

public class 네트워크예제 {
    public static void ኣኺድ() throws 입출력예외 {
        // አዐንግድ: python3 መሳርሒታት/예제되돌림.py --tcp-port 9000 --udp-port 9001
        ርክብ ኣላግብ = ርክብ.ክፈት("10.0.2.2", 문자.정수읽기(실행인수.ጽሑፍ(0)));
        try {
            ኣላግብ.대기시간(700);
            byte[] መልእኽቲ = 문자.부호화("JAVA TCP ti\n");
            ኣላግብ.출력().ጸሓፍ(መልእኽቲ);
            입력흐름 입력 = ኣላግብ.입력();
            for (int 수 = 0; 수 < 문자.바이트수(መልእኽቲ); 수++) {
                검사.참인지(입력.읽기() == (መልእኽቲ[수] & 255), "TCP መልስ 불일치");
            }
        } finally { ኣላግብ.ዕጸው(); }
        전문통로 종단 = 전문통로.ክፈት(0);
        try {
            종단.대기시간(700);
            종단.ለኣኽ("10.0.2.2", 문자.정수읽기(실행인수.ጽሑፍ(1)), "JAVA UDP ti");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP ti"), "UDP መልስ 불일치");
        } finally { 종단.ዕጸው(); }
        출력.ጸሓፍ_መስመር("JAVA 네트워크 ኣረጋግጽ: TCP UDP ti");
    }
}
