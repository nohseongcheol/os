/** 첫 IDE 장치의 512바이트 논리 ክፋል_ዋጋ. 이 계층은 포맷을 만들거나 임의 장치를 지우지 않는다. */
public final class መኽዘን_መሳርሒ_ርክብ {
    static boolean 사용가능 = false;
    static int[] ክፋል_ሓበሬታ = new int[512];
    static void 잠깐기다리기() {
        for (int መሐበሪ = 0; መሐበሪ < 4; መሐበሪ++) መሳርሒ_ዋጋ.입출력바이트읽기(0x3f6);
    }
    static int 준비기다리기(boolean 자료필요) {
        int ኣኺድ = መሳርሒ_ዋጋ.밀리초();
        while (መሳርሒ_ዋጋ.밀리초() - ኣኺድ < 500) {
            int ደረጃ_ዋጋ = መሳርሒ_ዋጋ.입출력바이트읽기(0x1f7);
            if (ደረጃ_ዋጋ == 0 || ደረጃ_ዋጋ == 255) return -19;
            if ((ደረጃ_ዋጋ & 128) == 0) {
                if ((ደረጃ_ዋጋ & 33) != 0) return -5;
                if (!자료필요 || (ደረጃ_ዋጋ & 8) != 0) return 0;
            }
            መሳርሒ_ዋጋ.잠시양보();
        }
        return -110;
    }
    static int 요청(int ክፋል_ዋጋ, int ትእዛዝ) {
        if (ክፋል_ዋጋ < 0 || ክፋል_ዋጋ >= 2048) return -22;
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x3f6, 2); // polling; IDE IRQ 사용 안 함
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x1f6, 0xe0); 잠깐기다리기();
        int 결과 = 준비기다리기(false);
        if (결과 < 0) return 결과;
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x1f2, 1);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x1f3, ክፋል_ዋጋ & 255);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x1f4, (ክፋል_ዋጋ >>> 8) & 255);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x1f5, 0);
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x1f7, ትእዛዝ); 잠깐기다리기();
        return 준비기다리기(true);
    }
    static int 읽기(int ክፋል_ዋጋ) {
        int 결과 = 요청(ክፋል_ዋጋ, 0x20);
        if (결과 < 0) return 결과;
        for (int መሐበሪ = 0; መሐበሪ < 256; መሐበሪ++) {
            int ዋጋ = መሳርሒ_ዋጋ.입출력짧은수읽기(0x1f0);
            ክፋል_ሓበሬታ[መሐበሪ * 2] = ዋጋ & 255; ክፋል_ሓበሬታ[መሐበሪ * 2 + 1] = ዋጋ >>> 8;
        }
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int ጸሓፍ(int ክፋል_ዋጋ) {
        if (!사용가능 || ክፋል_ዋጋ < 1 || ክፋል_ዋጋ > 518) return -19;
        int 결과 = 요청(ክፋል_ዋጋ, 0x30);
        if (결과 < 0) return 결과;
        for (int መሐበሪ = 0; መሐበሪ < 256; መሐበሪ++)
            መሳርሒ_ዋጋ.입출력짧은수쓰기(0x1f0, ክፋል_ሓበሬታ[መሐበሪ * 2] | ክፋል_ሓበሬታ[መሐበሪ * 2 + 1] << 8);
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int 밀어쓰기() {
        if (!사용가능) return -19;
        መሳርሒ_ዋጋ.입출력바이트쓰기(0x1f7, 0xe7); 잠깐기다리기();
        return 준비기다리기(false);
    }
    static int 정수읽기(int 위치) {
        return ክፋል_ሓበሬታ[위치] | ክፋል_ሓበሬታ[위치 + 1] << 8 | ክፋል_ሓበሬታ[위치 + 2] << 16 | ክፋል_ሓበሬታ[위치 + 3] << 24;
    }
    static void ጸሓፍ_ኢንቲጀር_ዋጋ(int 위치, int ዋጋ) {
        for (int መሐበሪ = 0; መሐበሪ < 4; መሐበሪ++) ክፋል_ሓበሬታ[위치 + መሐበሪ] = (ዋጋ >>> (መሐበሪ * 8)) & 255;
    }
}
