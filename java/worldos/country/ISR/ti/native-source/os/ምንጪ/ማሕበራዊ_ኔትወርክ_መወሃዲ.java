/** PCI RTL8139 (10ec:8139), 단일 ለኣኽ_ዋጋ 버퍼와 8KiB 수신 ደጋግም_ዋጋ. 인터럽트 대신 폴링한다. */
public final class ማሕበራዊ_ኔትወርክ_መወሃዲ {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] መሳርሒ_ኣድራሻ = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int 위치) {
        መሳርሒ_ዋጋ.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | 위치);
        return መሳርሒ_ዋጋ.입출력정수읽기(0xcfc);
    }

    static boolean ኣዳልው() {
        int 장치번호 = -1;
        for (int መሐበሪ = 0; መሐበሪ < 32; መሐበሪ++) {
            if (설정읽기(መሐበሪ, 0) == 0x813910ec) { 장치번호 = መሐበሪ; break; }
        }
        if (장치번호 < 0) return false;
        int ንቡር_ዋጋ = 설정읽기(장치번호, 0x10);
        if ((ንቡር_ዋጋ & 1) == 0 || (ንቡር_ዋጋ & 0xfffffffc) < 0x100 || (ንቡር_ዋጋ & 0xfffffffc) > 65535) return false;
        입출력기준주소 = ንቡር_ዋጋ & 0xfffc;
        int ትእዛዝ = 설정읽기(장치번호, 4);
        መሳርሒ_ዋጋ.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        መሳርሒ_ዋጋ.입출력짧은수쓰기(0xcfc, ትእዛዝ | 5); // I/O 및 bus master ፍቐድ_ዋጋ, PCI ደረጃ_ዋጋ 비트는 건드리지 않음
        መሳርሒ_ዋጋ.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!እንደገና_ኣዳልው_ዋጋ()) { 입출력기준주소 = 0; return false; }
        for (int መሐበሪ = 0; መሐበሪ < 6; መሐበሪ++) መሳርሒ_ኣድራሻ[መሐበሪ] = መሳርሒ_ዋጋ.입출력바이트읽기(입출력기준주소 + መሐበሪ);
        return true;
    }

    static boolean እንደገና_ኣዳልው_ዋጋ() {
        መሳርሒ_ዋጋ.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int ኣኺድ = መሳርሒ_ዋጋ.밀리초();
        while ((መሳርሒ_ዋጋ.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (መሳርሒ_ዋጋ.밀리초() - ኣኺድ > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        መሳርሒ_ዋጋ.입출력정수쓰기(입출력기준주소 + 0x30, መሳርሒ_ዋጋ.ማሕበራዊ_ኔትወርክ_ማህደር_ዝኽረት());
        for (int መሐበሪ = 0; መሐበሪ < 4; መሐበሪ++) መሳርሒ_ዋጋ.입출력정수쓰기(입출력기준주소 + 0x20 + መሐበሪ * 4, መሳርሒ_ዋጋ.ማሕበራዊ_ኔትወርክ_ማህደር_ዝኽረት() + 12288);
        መሳርሒ_ዋጋ.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        መሳርሒ_ዋጋ.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        መሳርሒ_ዋጋ.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        መሳርሒ_ዋጋ.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/방송, wrap 연속 ከዝን_ዋጋ, 8KiB
        መሳርሒ_ዋጋ.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int ለኣኽ(int[] ሓበሬታ, int ንውሓት_ዋጋ) {
        if (입출력기준주소 == 0) return -19;
        if (ንውሓት_ዋጋ < 14 || ንውሓት_ዋጋ > 1514) return -90;
        int ደረጃ_ወደብ = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int ኣኺድ = መሳርሒ_ዋጋ.밀리초();
        while ((መሳርሒ_ዋጋ.입출력정수읽기(ደረጃ_ወደብ) & 0x2000) == 0)
            if (መሳርሒ_ዋጋ.밀리초() - ኣኺድ > 100) return -110;
        int መጠን = ንውሓት_ዋጋ < 60 ? 60 : ንውሓት_ዋጋ;
        for (int መሐበሪ = 0; መሐበሪ < መጠን; መሐበሪ++)
            መሳርሒ_ዋጋ.ጸሓፍ_ማህደር_ዝኽረት(መሳርሒ_ዋጋ.ማሕበራዊ_ኔትወርክ_ማህደር_ዝኽረት() + 12288 + መሐበሪ, መሐበሪ < ንውሓት_ዋጋ ? ሓበሬታ[መሐበሪ] : 0);
        መሳርሒ_ዋጋ.입출력정수쓰기(ደረጃ_ወደብ, መጠን | 0x00080000);
        ኣኺድ = መሳርሒ_ዋጋ.밀리초();
        while ((መሳርሒ_ዋጋ.입출력정수읽기(ደረጃ_ወደብ) & 0xe0008000) == 0)
            if (መሳርሒ_ዋጋ.밀리초() - ኣኺድ > 100) return -110;
        if ((መሳርሒ_ዋጋ.입출력정수읽기(ደረጃ_ወደብ) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return ንውሓት_ዋጋ;
    }

    static int 받기(int[] ሓበሬታ) {
        if (입출력기준주소 == 0) return 0;
        if ((መሳርሒ_ዋጋ.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!እንደገና_ኣዳልው_ዋጋ()) 입출력기준주소 = 0;
            return 0;
        }
        if ((መሳርሒ_ዋጋ.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = መሳርሒ_ዋጋ.ማሕበራዊ_ኔትወርክ_ማህደር_ዝኽረት() + 수신위치;
        int ደረጃ_ዋጋ = 실행관리.짧은수(머리), መጠን = 실행관리.짧은수(머리 + 2);
        if (መጠን == 0xfff0) return 0; // DMA 진행 중
        if (መጠን < 4 || መጠን > 1518) {
            오류수++;
            if (!እንደገና_ኣዳልው_ዋጋ()) 입출력기준주소 = 0;
            return 0;
        }
        int ንውሓት_ዋጋ = መጠን - 4;
        if ((ደረጃ_ዋጋ & 1) != 0) {
            for (int መሐበሪ = 0; መሐበሪ < ንውሓት_ዋጋ; መሐበሪ++) ሓበሬታ[መሐበሪ] = መሳርሒ_ዋጋ.기억읽기(머리 + 4 + መሐበሪ);
            수신수++;
        } else { ንውሓት_ዋጋ = 0; 오류수++; }
        수신위치 = (수신위치 + መጠን + 4 + 3) & ~3;
        수신위치 &= 8191;
        መሳርሒ_ዋጋ.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        መሳርሒ_ዋጋ.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return ንውሓት_ዋጋ;
    }
}
