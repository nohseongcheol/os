/** ίδιο 커널의 Swing Παράθυρο: el είσοδος_τιμή → κουμπί → αρχείο_readme_eb81d7d9 Κείμενο ανανεώνω. */
public class ΠαράδειγμαΠαραθύρου implements 실행할일, 동작받이 {
    private Παράθυρο 인사창;
    private πεδίο_κειμένου όνομα_πεδίο;
    private Ετικέτα 인사말;
    private int 인사횟수;

    public void ανοίγω_Παράθυρο() {
        인사창 = new Παράθυρο("el Swing", 460, 300);
        인사창.Προσθήκη_στοιχείο(new Ετικέτα("Γεια σας", 20, 20, 420, 28));
        όνομα_πεδίο = new πεδίο_κειμένου("el", 20, 64, 420, 30);
        인사말 = new Ετικέτα("Γεια σας", 20, 152, 420, 28);
        인사창.Προσθήκη_στοιχείο(όνομα_πεδίο);
        인사창.Προσθήκη_στοιχείο(new κουμπί("인사하기", 20, 108, 180, 32, this));
        인사창.Προσθήκη_στοιχείο(인사말);
        인사창.Προσθήκη_στοιχείο(new Ετικέτα("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.εμφανίζω_Παράθυρο();
        Έξοδος.εγγράφω_γραμμή("GUI 예제 Προετοίμασε: ΠαράδειγμαΠαραθύρου");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.εγγράφω_μήνυμα("Γεια σας, " + όνομα_πεδίο.글읽기() + "님! (" + 인사횟수 + ")");
        Έξοδος.εγγράφω_γραμμή("GUI 인사: " + 인사말.글읽기());
    }

    public void Εκτέλεση() { ανοίγω_Παράθυρο(); }
    public void λαμβάνω_έργο(έργο_γνωστοποίηση γνωστοποίηση) {
        Έξοδος.εγγράφω_γραμμή("Ενέργεια γνωστοποίηση: " + γνωστοποίηση.εντολή_μήνυμα());
        인사하기();
    }
    public static void Εκτέλεση_2() {
        συμβάν_ουρά.나중에실행(new ΠαράδειγμαΠαραθύρου());
    }
}
