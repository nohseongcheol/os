#!/usr/bin/env python3
"""ίδιο Java τοπικός_Πεδίο 이름을 바꾼다. συμβολοσειρά_τιμή·주석·εξωτερικός_τιμή 멤버 이름은 보존한다."""
import json
import re
from pathlib import Path

έργο_ρίζα = Path(__file__).resolve().parents[1]
αντιστοίχιση_τιμή = json.loads((έργο_ρίζα / '명명/자바이름.json').read_text())
τμήμα_παράσταση = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[\w$]+|[^\w\s]', re.UNICODE)
καταγράφω_ρεκόρ = []
for Κατάλογος_τιμή in ('ΠΗΓΗ', 'χρήστης/자바', '한국어자바'):
    for ΔΙΑΔΡΟΜΗ in sorted((έργο_ρίζα / Κατάλογος_τιμή).rglob('*.java')):
        ΠΗΓΗ = ΔΙΑΔΡΟΜΗ.read_text()
        토막들 = list(τμήμα_παράσταση.finditer(ΠΗΓΗ))
        사용이름 = {τμήμα_καταχώρηση.group() for τμήμα_καταχώρηση in 토막들 if re.search('[가-힣]', τμήμα_καταχώρηση.group())}
        αντιστοίχιση_αρχείων = {}
        for 이전, 이후 in αντιστοίχιση_τιμή.items():
            # A pre-existing Korean binding must never be shadowed by renaming.
            새이름 = 이후
            while 새이름 in 사용이름: 새이름 = 'τοπικός_Πεδίο' + 새이름
            αντιστοίχιση_αρχείων[이전] = 새이름
        수정 = []
        이전토막 = ''
        for τμήμα_καταχώρηση in 토막들:
            낱말 = τμήμα_καταχώρηση.group()
            if 낱말.startswith(('//', '/*', '"', "'")): continue
            if 낱말 in αντιστοίχιση_αρχείων and 이전토막 != '.':
                수정.append((τμήμα_καταχώρηση.start(), τμήμα_καταχώρηση.end(), αντιστοίχιση_αρχείων[낱말]))
                καταγράφω_ρεκόρ.append((str(ΔΙΑΔΡΟΜΗ.relative_to(έργο_ρίζα)), 낱말, αντιστοίχιση_αρχείων[낱말]))
            이전토막 = 낱말
        for Εκτέλεση_2, 끝, 새이름 in reversed(수정): ΠΗΓΗ = ΠΗΓΗ[:Εκτέλεση_2] + 새이름 + ΠΗΓΗ[끝:]
        if 수정: ΔΙΑΔΡΟΜΗ.write_text(ΠΗΓΗ)
(έργο_ρίζα / '명명/자바이름대응.tsv').write_text('Αρχείο\t이전\t이후\n' + ''.join('\t'.join(καταχώρηση_τιμή)+'\n' for καταχώρηση_τιμή in sorted(set(καταγράφω_ρεκόρ))))
print('Java Όνομα Αναφορά αλλάζω_τιμή:', len(καταγράφω_ρεκόρ))
