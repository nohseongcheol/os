package Ιταλία.JItaOS.δίκτυο_δέσμη;

/** Ethernet/ARP/IPv4/ICMP/UDP 계층이 공유하는 바이트 순서와 άθροισμα_ελέγχου 도구다. */
public final class δίκτυο_Εργαλεία {
    private δίκτυο_Εργαλεία() {
    }

    public static int 큰순서짧은정수(byte[] δεδομένα, int Θέση) {
        ελέγχω_εύρος(δεδομένα, Θέση, 2);
        return ((δεδομένα[Θέση] & 0xff) << 8) | (δεδομένα[Θέση + 1] & 0xff);
    }

    public static long μεγακρικός_ακέραιος(byte[] δεδομένα, int Θέση) {
        ελέγχω_εύρος(δεδομένα, Θέση, 4);
        return ((long) (δεδομένα[Θέση] & 0xff) << 24)
                | ((long) (δεδομένα[Θέση + 1] & 0xff) << 16)
                | ((long) (δεδομένα[Θέση + 2] & 0xff) << 8)
                | (δεδομένα[Θέση + 3] & 0xffL);
    }

    public static int πλέγμα_άθροισμα_ελέγχου(byte[] δεδομένα, int Εκτέλεση_2, int διάρκεια_τιμή) {
        ελέγχω_εύρος(δεδομένα, Εκτέλεση_2, διάρκεια_τιμή);
        long Διαχείριση_ενημερώσεων_λογισμικού_τιμή = 0;
        int 끝 = Εκτέλεση_2 + διάρκεια_τιμή;
        int Θέση = Εκτέλεση_2;
        while (Θέση + 1 < 끝) {
            Διαχείριση_ενημερώσεων_λογισμικού_τιμή += 큰순서짧은정수(δεδομένα, Θέση);
            Θέση += 2;
        }
        if (Θέση < 끝) {
            Διαχείριση_ενημερώσεων_λογισμικού_τιμή += (δεδομένα[Θέση] & 0xff) << 8;
        }
        while ((Διαχείριση_ενημερώσεων_λογισμικού_τιμή >>> 16) != 0) {
            Διαχείριση_ενημερώσεων_λογισμικού_τιμή = (Διαχείριση_ενημερώσεων_λογισμικού_τιμή & 0xffff) + (Διαχείριση_ενημερώσεων_λογισμικού_τιμή >>> 16);
        }
        return (int) (~Διαχείριση_ενημερώσεων_λογισμικού_τιμή) & 0xffff;
    }

    public static boolean 이더넷틀인가(byte[] δεδομένα) {
        return δεδομένα != null && δεδομένα.length >= 14;
    }

    public static int 이더넷상위규약(byte[] δεδομένα) {
        if (!이더넷틀인가(δεδομένα)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return 큰순서짧은정수(δεδομένα, 12);
    }

    public static boolean πληροφοριακά_συστήματα_εμβόλιο_πολιομυελίτιδας_4_πρωτόκολλο(byte[] δεδομένα, int Θέση) {
        if (δεδομένα == null || Θέση < 0 || δεδομένα.length - Θέση < 20) {
            return false;
        }
        int έκδοση_τιμή = (δεδομένα[Θέση] >>> 4) & 0xf;
        int κεφαλίδα_διάρκεια = (δεδομένα[Θέση] & 0xf) * 4;
        return έκδοση_τιμή == 4 && κεφαλίδα_διάρκεια >= 20 && δεδομένα.length - Θέση >= κεφαλίδα_διάρκεια;
    }

    private static void ελέγχω_εύρος(byte[] δεδομένα, int Εκτέλεση_2, int διάρκεια_τιμή) {
        if (δεδομένα == null || Εκτέλεση_2 < 0 || διάρκεια_τιμή < 0 || Εκτέλεση_2 > δεδομένα.length - διάρκεια_τιμή) {
            throw new IllegalArgumentException("δίκτυο_δέσμη δεδομένα 범위를 벗어났습니다.");
        }
    }
}

