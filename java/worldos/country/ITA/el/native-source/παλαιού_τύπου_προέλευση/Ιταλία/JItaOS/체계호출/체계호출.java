            if ((ενότητα_τιμή.σημαία_τιμή() & 2) == 0 || ενότητα_τιμή.Μέγεθος() == 0) {
                continue;
            }
            int 첫쪽 = ενότητα_τιμή.διεύθυνση() / σελίδα_Υπεύθυνος.μέγεθος_σελίδας;
            int 끝쪽 = (ενότητα_τιμή.διεύθυνση() + ενότητα_τιμή.Μέγεθος() + σελίδα_Υπεύθυνος.μέγεθος_σελίδας - 1) / σελίδα_Υπεύθυνος.μέγεθος_σελίδας;
