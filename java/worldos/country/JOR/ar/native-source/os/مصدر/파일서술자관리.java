    static void كتابة_عنوان(int عنوان, int 길이, int معرف_الشبكة, int رقم_المنفذ) {
        for (int فهرس = 0; فهرس < 길이 && فهرس < 16; فهرس++) {
            int قيمة = 0;
            if (فهرس == 0) قيمة = 2;
            if (فهرس == 2) قيمة = رقم_المنفذ >>> 8;
            if (فهرس == 3) قيمة = رقم_المنفذ;
            if (فهرس >= 4 && فهرس < 8) قيمة = معرف_الشبكة >>> (56 - فهرس * 8);
            جهاز_قيمة.كتابة_ذاكرة(عنوان + فهرس, قيمة & 255);
        }
    }
