        int ملف = الهدف[기술], حجم = 종류[기술] == 2 ? ذاكرة_نظام_الملفات.يغير_الحجم_قائمة[ملف] : 0;
        int 허가 = 종류[기술] == 2 ? ذاكرة_نظام_الملفات.허가들[ملف] : 438;
