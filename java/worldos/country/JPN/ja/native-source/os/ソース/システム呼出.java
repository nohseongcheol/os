/** int 0x80 ゲートから呼ばれる。利用者ポインターと長さはすべてアクセス前に検査する。 */
public final class システム呼出 {
    static int[] 一時緩衝域 = new int[1024];

    static int 配列長さ(int 番地) {
        if (!実行管理.切抜き(番地, 4)) return -14;
        int 長さ = 実行管理.数(番地);
        if (長さ < 0 || 長さ > (実行管理.利用者終端位置 - 番地 - 4) / 4) return -14;
        return 長さ;
    }

    public static int プロセス値入口(int 番号, int 先頭位置被演算子, int 第二被演算子, int 第三被演算子, int 第四被演算子, int 第五被演算子) {
        if (番号 == 30) return ファイル記述子管理.ファイル開放(先頭位置被演算子, 第二被演算子, 第三被演算子);
        if (番号 == 31) return ファイル記述子管理.ファイル読取(先頭位置被演算子, 第二被演算子, 第三被演算子);
        if (番号 == 32) return ファイル記述子管理.ファイル書込(先頭位置被演算子, 第二被演算子, 第三被演算子);
        if (番号 == 33) return ファイル記述子管理.ファイル閉鎖(先頭位置被演算子);
        if (番号 == 34) return ファイル記述子管理.ファイル位置移動(先頭位置被演算子, 第二被演算子, 第三被演算子);
        if (番号 == 35) return ファイル記述子管理.複製記述子(先頭位置被演算子, 0, false, 0);
        if (番号 == 36) return ファイル記述子管理.複製記述子(先頭位置被演算子, 第二被演算子, true, 0);
        if (番号 == 37) return ファイル記述子管理.ファイル状態読取(先頭位置被演算子, 第二被演算子);
        if (番号 == 38) return ファイル記述子管理.ファイル入口名前除去(先頭位置被演算子);
        if (番号 == 39) return ファイル記述子管理.ファイル長さ設定(先頭位置被演算子, 第二被演算子);
        if (番号 == 40) return ファイル記述子管理.制御記述子(先頭位置被演算子, 第二被演算子, 第三被演算子);
        if (番号 == 41) return ファイル記述子管理.通信端点作成(先頭位置被演算子, 第二被演算子, 第三被演算子);
        if (番号 == 42) return ファイル記述子管理.番地結合(先頭位置被演算子, 第二被演算子, 第三被演算子);
        if (番号 == 43) return ファイル記述子管理.データグラムデータ送信(先頭位置被演算子, 第二被演算子, 第三被演算子, 第四被演算子, 第五被演算子);
        if (番号 == 44) return ファイル記述子管理.データグラムデータ受取(先頭位置被演算子, 第二被演算子, 第三被演算子, 第四被演算子, 第五被演算子);
        if (番号 == 45) return ファイル記述子管理.ソケット番地読取(先頭位置被演算子, 第二被演算子, 第三被演算子);
        if (番号 == 46) return ファイル記述子管理.受取待機期限設定(先頭位置被演算子, 第二被演算子);
        if (番号 == 47) {
            int 記述子値 = ファイル記述子管理.記述子探索(先頭位置被演算子);
            if (記述子値 < 0) return -9;
            if (ファイル記述子管理.種別値[記述子値] != 2) return -22;
            return ファイル永続化.同期化();
        }
        if (番号 == 1) {
            int 長さ = 配列長さ(先頭位置被演算子);
            if (長さ < 0) return 長さ;
            if (長さ > 4096) return -90;
            for (int 文字値 = 0; 文字値 < 長さ; 文字値++) 文字端末.文字(実行管理.数(先頭位置被演算子 + 4 + 文字値 * 4) & 65535);
            return 長さ;
        }
        if (番号 == 2) return 実行管理.引数個数;
        if (番号 == 3) return 先頭位置被演算子 >= 0 && 先頭位置被演算子 < 実行管理.引数個数 ? 実行管理.引数番地[先頭位置被演算子] : 0;
        if (番号 == 10) return 通信網.開放(先頭位置被演算子);
        if (番号 == 11) {
            int 長さ = 配列長さ(第四被演算子);
            if (長さ < 0) return 長さ;
            if (第五被演算子 < 0 || 第五被演算子 > 長さ || 第五被演算子 > 1024) return -90;
            for (int 位置 = 0; 位置 < 第五被演算子; 位置++) 一時緩衝域[位置] = 実行管理.数(第四被演算子 + 4 + 位置 * 4) & 255;
            return 通信網.送信(先頭位置被演算子, 第二被演算子, 第三被演算子, 一時緩衝域, 第五被演算子);
        }
        if (番号 == 12) {
            int 長さ = 配列長さ(第二被演算子);
            if (長さ < 0) return 長さ;
            if (第三被演算子 < 0 || 第三被演算子 > 2000) return -22;
            int 結果 = 通信網.受取(先頭位置被演算子, 一時緩衝域, 長さ < 1024 ? 長さ : 1024, 第三被演算子);
            if (結果 >= 0) for (int 位置 = 0; 位置 < 結果; 位置++) 実行管理.番号書込(第二被演算子 + 4 + 位置 * 4, 一時緩衝域[位置]);
            return 結果;
        }
        if (番号 == 13) return 通信網.閉鎖(先頭位置被演算子);
        if (番号 == 14) return 通信網.自前番地;
        if (番号 == 15) return 通信網.通信相手番地(先頭位置被演算子);
        if (番号 == 16) return 通信網.通信相手ポート番号(先頭位置被演算子);
        if (番号 == 22) {
            if (先頭位置被演算子 < 0 || 先頭位置被演算子 > 65535) return -22;
            文字端末.文字(先頭位置被演算子); return 1;
        }
        if (番号 == 20 || 番号 == 21) {
            int 名前容量 = 配列長さ(先頭位置被演算子), データ容量 = 配列長さ(第二被演算子);
            if (名前容量 < 0 || データ容量 < 0) return -14;
            if (名前容量 < 1 || 名前容量 > 64) return -22;
            int 長さ = 0;
            while (長さ < 名前容量 && 実行管理.数(先頭位置被演算子 + 4 + 長さ * 4) != 0) {
                主記憶ファイル体系.名前[長さ] = 実行管理.数(先頭位置被演算子 + 4 + 長さ * 4);
                長さ++;
            }
            if (!主記憶ファイル体系.名前検査(主記憶ファイル体系.名前, 長さ)) return -22;
            if (番号 == 20) {
                int ファイル = 主記憶ファイル体系.入口探索(主記憶ファイル体系.名前, 長さ);
                if (ファイル < 0) return ファイル;
                int 容量 = 主記憶ファイル体系.容量列[ファイル];
                if (容量 > データ容量) return -90;
                int 番地 = 装置.ファイル記憶() + ファイル * 主記憶ファイル体系.最大容量;
                for (int 数 = 0; 数 < 容量; 数++) 実行管理.番号書込(第二被演算子 + 4 + 数 * 4, 装置.記憶読取(番地 + 数));
                return 容量;
            }
            if (第三被演算子 < 0 || 第三被演算子 > データ容量) return -22;
            if (第三被演算子 > 主記憶ファイル体系.最大容量) return -90;
            for (int 数 = 0; 数 < 第三被演算子; 数++) 主記憶ファイル体系.編集値[数] = 実行管理.数(第二被演算子 + 4 + 数 * 4) & 255;
            return 主記憶ファイル体系.格納値(主記憶ファイル体系.名前, 長さ, 主記憶ファイル体系.編集値, 第三被演算子);
        }
        return -38;
    }
}
