/** 検査和と二つの保存本を用いる小さな専用保存形式。fsync/sync 時にだけ永続化する。 */
public final class ファイル永続化 {
    static int 現在保持済み複写 = -1, 世代番号 = 0;
    static int[] ファイル表 = new int[1024];
    static int ハッシュバイト列(int 値, int データ) { return (値 ^ データ) * 16777619; }
    static void データ消去() {
        for (int 番号 = 0; 番号 < 512; 番号++) 記憶装置接続.区画データ[番号] = 0;
    }
    static int 表整数値(int 位置) {
        return ファイル表[位置] | ファイル表[位置 + 1] << 8 | ファイル表[位置 + 2] << 16 | ファイル表[位置 + 3] << 24;
    }
    static void 表整数値書込(int 位置, int 値) {
        for (int 番号 = 0; 番号 < 4; 番号++) ファイル表[位置 + 番号] = (値 >>> (番号 * 8)) & 255;
    }
    static boolean 表検査() {
        for (int ファイル = 0; ファイル < 8; ファイル++) {
            int 長さ = 0;
            for (int 槽入口 = 0; 槽入口 < 64; 槽入口++) 主記憶ファイル体系.名前[槽入口] = ファイル表[ファイル * 72 + 槽入口];
            while (長さ < 64 && 主記憶ファイル体系.名前[長さ] != 0) 長さ++;
            if (長さ == 0) continue;
            if (!主記憶ファイル体系.名前検査(主記憶ファイル体系.名前, 長さ)
                || 表整数値(ファイル * 72 + 64) < 0 || 表整数値(ファイル * 72 + 64) > 16384) return false;
            for (int 前面値 = 0; 前面値 < ファイル; 前面値++) {
                boolean 等価本文 = ファイル表[前面値 * 72 + 長さ] == 0;
                for (int 槽入口 = 0; 槽入口 < 長さ; 槽入口++) if (ファイル表[前面値 * 72 + 槽入口] != 主記憶ファイル体系.名前[槽入口]) 等価本文 = false;
                if (等価本文) return false;
            }
        }
        return true;
    }
    static int 保持済み複写検査(int 保持済み複写) {
        int 区画開始処理 = 1 + 保持済み複写 * 259;
        if (記憶装置接続.読取(区画開始処理) < 0 || 記憶装置接続.整数値解析(0) != 0x4a4b534e) return -1;
        int 世代値 = 記憶装置接続.整数値解析(4), 検査和 = 記憶装置接続.整数値解析(8);
        if (世代値 < 1 || 記憶装置接続.整数値解析(12) != (世代値 ^ 検査和 ^ 0x4a4b534e)) return -1;
        int ハッシュファイル = 0x811c9dc5;
        for (int 区画値 = 0; 区画値 < 258; 区画値++) {
            if (記憶装置接続.読取(区画開始処理 + 1 + 区画値) < 0) return -1;
            for (int 槽入口 = 0; 槽入口 < 512; 槽入口++) {
                int 値 = 記憶装置接続.区画データ[槽入口];
                ハッシュファイル = ハッシュバイト列(ハッシュファイル, 値);
                if (区画値 < 2) ファイル表[区画値 * 512 + 槽入口] = 値;
            }
        }
        return ハッシュファイル == 検査和 && 表検査() ? 世代値 : -1;
    }
    static int 読込(int 保持済み複写) {
        int 区画開始処理 = 1 + 保持済み複写 * 259;
        for (int 区画値 = 0; 区画値 < 2; 区画値++) {
            if (記憶装置接続.読取(区画開始処理 + 1 + 区画値) < 0) return -5;
            for (int 槽入口 = 0; 槽入口 < 512; 槽入口++) ファイル表[区画値 * 512 + 槽入口] = 記憶装置接続.区画データ[槽入口];
        }
        for (int ファイル = 0; ファイル < 8; ファイル++) {
            for (int 槽入口 = 0; 槽入口 < 64; 槽入口++) 主記憶ファイル体系.名前一覧一覧[ファイル * 64 + 槽入口] = ファイル表[ファイル * 72 + 槽入口];
            主記憶ファイル体系.容量列[ファイル] = ファイル表[ファイル * 72] == 0 ? 0 : 表整数値(ファイル * 72 + 64);
            主記憶ファイル体系.許可許可一覧[ファイル] = 表整数値(ファイル * 72 + 68) & 511;
            for (int 区画値 = 0; 区画値 < 32; 区画値++) {
                if (記憶装置接続.読取(区画開始処理 + 3 + ファイル * 32 + 区画値) < 0) return -5;
                int 番地 = 装置.ファイル記憶() + ファイル * 16384 + 区画値 * 512;
                for (int 槽入口 = 0; 槽入口 < 512; 槽入口++) 装置.記憶書込(番地 + 槽入口, 記憶装置接続.区画データ[槽入口]);
            }
        }
        return 0;
    }
    static void 用意() {
        if (記憶装置接続.読取(0) < 0 || 記憶装置接続.整数値解析(0) != 0x54534b4a
            || 記憶装置接続.整数値解析(4) != 0x3145524f || 記憶装置接続.整数値解析(8) != 2048
            || 記憶装置接続.整数値解析(12) != 0x3153464a) {
            文字端末.書込("STORE RAM only (no JKSTORE1 disk)\n"); return;
        }
        記憶装置接続.判定利用可能 = true;
        int 先頭位置序数 = 保持済み複写検査(0), 第二序数 = 保持済み複写検査(1);
        if (先頭位置序数 < 0 && 第二序数 < 0) { 文字端末.書込("STORE ready; no valid snapshot\n"); return; }
        現在保持済み複写 = 先頭位置序数 >= 第二序数 ? 0 : 1; 世代番号 = 先頭位置序数 >= 第二序数 ? 先頭位置序数 : 第二序数;
        if (読込(現在保持済み複写) < 0) {
            文字端末.書込("STORE read failed; halted to preserve files\n"); 装置.機械停止実行状態();
        }
        文字端末.書込("STORE restored generation "); 文字端末.番号書込(世代番号); 文字端末.文字(10);
    }
    static int 同期化() {
        if (!記憶装置接続.判定利用可能) return -19;
        if (世代番号 == 2147483647) return -75;
        int 次回項目 = 現在保持済み複写 == 0 ? 1 : 0, 区画開始処理 = 1 + 次回項目 * 259;
        // 新しい本体を書く前に古い commit を無効にし、装置キャッシュを排出する。
        データ消去();
        if (記憶装置接続.書込(区画開始処理) < 0 || 記憶装置接続.排出出力() < 0) return -5;
        for (int 槽入口 = 0; 槽入口 < 1024; 槽入口++) ファイル表[槽入口] = 0;
        for (int ファイル = 0; ファイル < 8; ファイル++) if (主記憶ファイル体系.名前一覧一覧[ファイル * 64] != 0) {
            for (int 槽入口 = 0; 槽入口 < 64; 槽入口++) ファイル表[ファイル * 72 + 槽入口] = 主記憶ファイル体系.名前一覧一覧[ファイル * 64 + 槽入口];
            表整数値書込(ファイル * 72 + 64, 主記憶ファイル体系.容量列[ファイル]);
            表整数値書込(ファイル * 72 + 68, 主記憶ファイル体系.許可許可一覧[ファイル]);
        }
        int ハッシュファイル = 0x811c9dc5;
        for (int 区画値 = 0; 区画値 < 258; 区画値++) {
            for (int 槽入口 = 0; 槽入口 < 512; 槽入口++) {
                int 値 = 0;
                if (区画値 < 2) 値 = ファイル表[区画値 * 512 + 槽入口];
                else {
                    int ファイル = (区画値 - 2) / 32, 位置 = (区画値 - 2) % 32 * 512 + 槽入口;
                    if (ファイル表[ファイル * 72] != 0 && 位置 < 主記憶ファイル体系.容量列[ファイル])
                        値 = 装置.記憶読取(装置.ファイル記憶() + ファイル * 16384 + 位置);
                }
                記憶装置接続.区画データ[槽入口] = 値; ハッシュファイル = ハッシュバイト列(ハッシュファイル, 値);
            }
            if (記憶装置接続.書込(区画開始処理 + 1 + 区画値) < 0) return -5;
        }
        if (記憶装置接続.排出出力() < 0) return -5;
        データ消去(); 記憶装置接続.整数値値書込(0, 0x4a4b534e);
        記憶装置接続.整数値値書込(4, 世代番号 + 1); 記憶装置接続.整数値値書込(8, ハッシュファイル);
        記憶装置接続.整数値値書込(12, (世代番号 + 1) ^ ハッシュファイル ^ 0x4a4b534e);
        if (記憶装置接続.書込(区画開始処理) < 0 || 記憶装置接続.排出出力() < 0) return -5;
        現在保持済み複写 = 次回項目; 世代番号++;
        return 0;
    }
}
