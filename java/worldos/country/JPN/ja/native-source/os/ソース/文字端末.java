/** COM1 直列出力と VGA 80×25文字画面。Unicode 文字は直列端末へ UTF-8 で送る。 */
public final class 文字端末 {
    static int 槽入口 = 0;
    static int 色値 = 7;

    static void 用意() {
        装置.入出力バイト書込(0x3f9, 0);
        装置.入出力バイト書込(0x3fb, 0x80);
        装置.入出力バイト書込(0x3f8, 1);
        装置.入出力バイト書込(0x3f9, 0);
        装置.入出力バイト書込(0x3fb, 3);
        装置.入出力バイト書込(0x3fa, 0xc7);
        装置.入出力バイト書込(0x3fc, 0x0b);
        入口消去処理();
    }

    static void 直列バイト(int 値) {
        int 反復状態個数 = 100000;
        while ((装置.入出力バイト読取(0x3fd) & 0x20) == 0 && 反復状態個数 > 0) 反復状態個数--;
        if (反復状態個数 > 0) 装置.入出力バイト書込(0x3f8, 値);
    }

    static void 入口消去処理() {
        for (int 番号 = 0; 番号 < 2000; 番号++) {
            装置.記憶書込(0xb8000 + 番号 * 2, 32);
            装置.記憶書込(0xb8001 + 番号 * 2, 色値);
        }
        槽入口 = 0;
        カーソル値();
    }

    static void カーソル値() {
        装置.入出力バイト書込(0x3d4, 14);
        装置.入出力バイト書込(0x3d5, 槽入口 >> 8);
        装置.入出力バイト書込(0x3d4, 15);
        装置.入出力バイト書込(0x3d5, 槽入口 & 255);
    }

    static void 画面文字(int 値) {
        if (値 == 13) return;
        if (値 == 10) {
            槽入口 = (槽入口 / 80 + 1) * 80;
        } else if (値 == 8) {
            if (槽入口 > 0) {
                槽入口--;
                装置.記憶書込(0xb8000 + 槽入口 * 2, 32);
            }
        } else {
            装置.記憶書込(0xb8000 + 槽入口 * 2, 値 < 128 ? 値 : '?');
            装置.記憶書込(0xb8001 + 槽入口 * 2, 色値);
            槽入口++;
        }
        if (槽入口 >= 2000) {
            for (int 番号 = 0; 番号 < 3840; 番号++)
                装置.記憶書込(0xb8000 + 番号, 装置.記憶読取(0xb80a0 + 番号));
            for (int 番号 = 1920; 番号 < 2000; 番号++) {
                装置.記憶書込(0xb8000 + 番号 * 2, 32);
                装置.記憶書込(0xb8001 + 番号 * 2, 色値);
            }
            槽入口 = 1920;
        }
        カーソル値();
    }

    static void 文字(int 値) {
        if (値 < 128) {
            if (値 == 10) 直列バイト(13);
            直列バイト(値);
        } else if (値 < 2048) {
            直列バイト(0xc0 | (値 >> 6));
            直列バイト(0x80 | (値 & 63));
        } else {
            直列バイト(0xe0 | (値 >> 12));
            直列バイト(0x80 | ((値 >> 6) & 63));
            直列バイト(0x80 | (値 & 63));
        }
        画面文字(値);
    }

    static void 書込(String 内容物値) {
        for (int 番号 = 0; 番号 < 内容物値.length(); 番号++) 文字(内容物値.charAt(番号));
    }

    static void 番号書込(int 値) {
        // 正数へ反転しないため、Integer.MIN_VALUE でも安全。
        if (値 < 0) 文字('-');
        else 値 = -値;
        int 位置添字 = 1000000000;
        boolean 起動処理 = false;
        while (位置添字 > 0) {
            int 桁値 = -(値 / 位置添字);
            if (桁値 != 0 || 起動処理 || 位置添字 == 1) {
                文字('0' + 桁値);
                起動処理 = true;
            }
            値 %= 位置添字;
            位置添字 /= 10;
        }
    }

    static int 直列読取() {
        if ((装置.入出力バイト読取(0x3fd) & 1) != 0) return 装置.入出力バイト読取(0x3f8);
        return -1;
    }
}
