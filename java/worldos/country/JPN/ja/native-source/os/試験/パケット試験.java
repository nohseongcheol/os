import java.util.Arrays;

/** 実際の Java 規約処理器を JVM から呼び、境界と壊れた入力をすばやく検査する。 */
public final class パケット試験 {
    static int 反復状態個数 = 0;
    static void 検証(boolean 値) { if (!値) throw new AssertionError("case " + 反復状態個数); 反復状態個数++; }
    static int 検査和(int[] 値, int 起動処理, int 長さ, int 初期状況) {
        int 総和値 = 初期状況;
        for (int 番号 = 0; 番号 < 長さ; 番号++) 総和値 += 値[起動処理 + 番号] << ((番号 & 1) == 0 ? 8 : 0);
        総和値 = (総和値 & 65535) + (総和値 >>> 16);
        総和値 = (総和値 & 65535) + (総和値 >>> 16);
        return ~総和値 & 65535;
    }
    static void 用意(int 長さ) {
        通信網.清掃プロセス();
        検証(通信網.開放(5000) == 3);
        int[] 枠組添字 = 通信網.入力枠組;
        Arrays.fill(枠組添字, 0);
        for (int 番号 = 0; 番号 < 6; 番号++) 枠組添字[番号] = 通信装置駆動器.装置番地[番号];
        通信網.十六ビット格納(枠組添字, 12, 0x0800);
        枠組添字[14] = 0x45; 枠組添字[22] = 64; 枠組添字[23] = 17;
        通信網.十六ビット格納(枠組添字, 16, 28 + 長さ);
        通信網.三十二ビット格納(枠組添字, 26, 0x0a000202); 通信網.三十二ビット格納(枠組添字, 30, 通信網.自前番地);
        通信網.十六ビット格納(枠組添字, 34, 4321); 通信網.十六ビット格納(枠組添字, 36, 5000); 通信網.十六ビット格納(枠組添字, 38, 長さ + 8);
        for (int 番号 = 0; 番号 < 長さ; 番号++) 枠組添字[42 + 番号] = 番号 & 255;
        検査和設定(長さ);
    }
    static void 検査和設定(int 長さ) {
        int[] 枠組添字 = 通信網.入力枠組;
        通信網.十六ビット格納(枠組添字, 24, 0); 通信網.十六ビット格納(枠組添字, 40, 0);
        通信網.十六ビット格納(枠組添字, 24, 検査和(枠組添字, 14, 20, 0));
        int 初期状況 = 通信網.疑似ヘッダー検査和(通信網.整数値32(枠組添字, 26), 通信網.自前番地, 長さ + 8);
        int 総和値 = 検査和(枠組添字, 34, 長さ + 8, 初期状況);
        通信網.十六ビット格納(枠組添字, 40, 総和値 == 0 ? 65535 : 総和値);
    }
    static void 値却下(int 長さ) { 通信網.プロセス枠組(長さ); 検証(通信網.受信済み長さ[0] == -1); }
    public static void main(String[] 引数) {
        for (int 長さ : new int[]{0, 1, 2, 7, 1023, 1024}) {
            用意(長さ); 通信網.プロセス枠組(長さ + 42);
            検証(通信網.受信済み長さ[0] == 長さ);
            検証(通信網.受信済み番地[0] == 0x0a000202 && 通信網.受信済みポート番号[0] == 4321);
            for (int 番号 = 0; 番号 < 長さ; 番号++) 検証(通信網.受信済みデータ[番号] == (番号 & 255));
        }
        for (int 長さ = 0; 長さ < 42; 長さ++) { 用意(0); 値却下(長さ); }
        用意(1025); 値却下(1067);
        用意(2); 通信網.入力枠組[24] ^= 1; 値却下(44);
        用意(2); 通信網.入力枠組[42] ^= 1; 値却下(44);
        用意(2); 通信網.十六ビット格納(通信網.入力枠組, 38, 7); 値却下(44);
        用意(2); 通信網.十六ビット格納(通信網.入力枠組, 38, 65535); 値却下(44);
        用意(2); 通信網.入力枠組[14] = 0x4f; 値却下(44);
        用意(2); 通信網.入力枠組[14] = 0x44; 値却下(44);
        用意(2); 通信網.入力枠組[20] = 0x20; 検査和設定(2); 値却下(44);
        用意(2); 通信網.入力枠組[21] = 1; 検査和設定(2); 値却下(44);
        用意(2); 通信網.入力枠組[33] = 99; 検査和設定(2); 値却下(44);
        用意(2); 通信網.入力枠組[0] ^= 1; 値却下(44);
        用意(2); 通信網.入力枠組[23] = 6; 検査和設定(2); 値却下(44);
        用意(2); 通信網.十六ビット格納(通信網.入力枠組, 40, 0); 通信網.プロセス枠組(44); 検証(通信網.受信済み長さ[0] == 2);
        int[] 結果 = new int[4];
        検証(通信網.受取(3, 結果, 1, 0) == -90);
        検証(通信網.受取(3, 結果, 4, 0) == -11);
        用意(2); 通信網.プロセス枠組(44); int 値破棄 = 通信網.破棄済み個数;
        通信網.プロセス枠組(44); 検証(通信網.破棄済み個数 == 値破棄 + 1);
        通信網.清掃プロセス(); 検証(通信網.開放(5000) == 3);
        検証(通信網.開放(5000) == -98); 検証(通信網.開放(0) == 4);
        検証(通信網.開放(0) == 5); 検証(通信網.開放(0) == 6); 検証(通信網.開放(0) == -24);
        検証(通信網.閉鎖(4) == 0); 検証(通信網.閉鎖(4) == -9);
        通信網.発見結果番地 = 通信網.中継門値;
        検証(通信網.送信(3, 通信網.中継門値, 4321, new int[]{1, 2, 3}, 3) == 3);
        int[] 保有送信済み = 通信装置駆動器.直近値;
        検証(検査和(保有送信済み, 14, 20, 0) == 0);
        検証(検査和(保有送信済み, 34, 11, 通信網.疑似ヘッダー検査和(通信網.自前番地, 通信網.中継門値, 11)) == 0);
        検証(保有送信済み[42] == 1 && 保有送信済み[44] == 3);
        System.out.println("PACKET TEST PASS: " + 反復状態個数 + " assertions");
    }
}
