import 日本語.内蔵.*;

/** 同じバイトコードを OpenJDK と独自 JVM で実行する通信契約試験。 */
public class 韓国語通信機構試験 {
    public static void main(String[] 引数) throws 入力出力例外 {
        ポート受取 ポート値 = 接続状態輸送.受信先開放(0);
        接続経路 ゲスト値 = 接続状態輸送.開放("127.0.0.1", ポート値.ポート番号());
        接続経路 所有者識別子 = ポート値.受取();
        ゲスト値.待機期限(200); 所有者識別子.待機期限(200);
        検査項目.真偽確認(ゲスト値.接続済み() && !ゲスト値.判定閉鎖済み(), "接続 状況値");
        検査項目.真偽確認(所有者識別子.ポート番号() == ゲスト値.局所ポート番号(), "通信相手値 ポート番号");
        検査項目.真偽確認(ゲスト値.ポート番号() == 所有者識別子.局所ポート番号(), "局所有効範囲 ポート番号");
        入力ストリーム 入力値 = 所有者識別子.入力値(); 出力ストリーム 出力ページ = ゲスト値.出力();
        byte[] メッセージ = 文字.符号化("한글 ストリーム値");
        出力ページ.書込(メッセージ, 0, メッセージ.length); 出力ページ.値出力();
        byte[] 受信済み本文 = new byte[メッセージ.length];
        int 個数読取 = 0;
        while (個数読取 < 受信済み本文.length) {
            int 追加分読取 = 入力値.読取(受信済み本文, 個数読取, 受信済み本文.length - 個数読取);
            検査項目.真偽確認(追加分読取 > 0, "예상하지 않은 ファイル 終端"); 個数読取 += 追加分読取;
        }
        検査項目.真偽確認(文字.等価本文(文字.データ復号化(受信済み本文), "한글 ストリーム値"), "部分要素値 읽기와 書込");
        出力ページ.書込(new byte[] {17, 18});
        byte[] 短整数読取 = new byte[2];
        int 先頭位置読取 = 入力値.読取(短整数読取);
        検査項目.真偽確認(先頭位置読取 > 0 && 短整数読取[0] == 17, "配列値 読取");
        if (先頭位置読取 == 1) 短整数読取[1] = (byte)入力値.読取();
        検査項目.真偽確認(短整数読取[1] == 18, "剰余値 読取");
        所有者識別子.出力().書込(255);
        検査項目.真偽確認(ゲスト値.入力値().読取() == 255, "符号化状態値 없는 한 バイト値");
        出力ページ.閉鎖();
        検査項目.真偽確認(ゲスト値.判定閉鎖済み() && 入力値.読取() == -1, "닫기와 ファイル 終端");
        入力値.閉鎖(); 検査項目.真偽確認(所有者識別子.判定閉鎖済み(), "入力値 ストリーム値 閉鎖");
        ゲスト値.閉鎖(); 所有者識別子.閉鎖();
        ポート値.待機期限(15);
        boolean 実行状態待機期限 = false;
        try { ポート値.受取(); } catch (待合待機期限例外 期待エラー) { 実行状態待機期限 = true; }
        検査項目.真偽確認(実行状態待機期限, "値受取 待機期限");
        ポート値.閉鎖(); 検査項目.真偽確認(ポート値.判定閉鎖済み(), "ポート受取 閉鎖");
        データグラムチャネル 受信先通信端点 = データグラムチャネル.開放(0), 送信中通信端点 = データグラムチャネル.開放(0);
        受信先通信端点.待機期限(200);
        送信中通信端点.送信("127.0.0.1", 受信先通信端点.ポート番号(), "データグラム 한글");
        検査項目.真偽確認(文字.等価本文(受信先通信端点.受取(), "データグラム 한글"), "データグラム 송수신");
        送信中通信端点.閉鎖(); 受信先通信端点.閉鎖();
        検査項目.真偽確認(送信中通信端点.判定閉鎖済み() && 受信先通信端点.判定閉鎖済み(), "データグラム 閉鎖");
        出力.行書込("日本語 通信 検証: 接続 データグラム ストリーム値 実行状態待機期限 閉鎖");
    }
}
