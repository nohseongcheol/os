import 日本語.内蔵.窓;
import 日本語.内蔵.ラベル;
import 日本語.内蔵.本文フィールド;
import 日本語.内蔵.ボタン;
import 日本語.内蔵.イベント待ち行列;
import 日本語.内蔵.出力;
import 日本語.内蔵.実行可能処理作業;
import 日本語.内蔵.動作受信先;
import 日本語.内蔵.動作通知;

/** 独自カーネルの Swing 窓。日本語入力、ボタン操作、案内表示の更新をつなぐ。 */
public class 窓例 implements 実行可能処理作業, 動作受信先 {
    private 窓 挨拶文窓;
    private 本文フィールド 名前フィールド;
    private ラベル 挨拶文;
    private int 挨拶文個数;

    public void 窓開放() {
        挨拶文窓 = new 窓("日本語 Swing", 460, 300);
        挨拶文窓.要素追加(new ラベル("こんにちは", 20, 20, 420, 28));
        名前フィールド = new 本文フィールド("日本語", 20, 64, 420, 30);
        挨拶文 = new ラベル("こんにちは", 20, 152, 420, 28);
        挨拶文窓.要素追加(名前フィールド);
        挨拶文窓.要素追加(new ボタン("挨拶", 20, 108, 180, 32, this));
        挨拶文窓.要素追加(挨拶文);
        挨拶文窓.要素追加(new ラベル("F9 / Shift+Space | X", 20, 204, 420, 28));
        挨拶文窓.窓表示();
        出力.行書込("GUI 用例 用意: 窓例");
    }

    public void 挨拶() {
        挨拶文個数++;
        挨拶文.本文書込("こんにちは, " + 名前フィールド.本文読取() + "님! (" + 挨拶文個数 + ")");
        出力.行書込("GUI 挨拶例: " + 挨拶文.本文読取());
    }

    public void 作業実行() { 窓開放(); }
    public void 動作受取(動作通知 通知) {
        出力.行書込("動作 通知: " + 通知.命令本文());
        挨拶();
    }
    public static void 起動処理() {
        イベント待ち行列.後続呼出(new 窓例());
    }
}
