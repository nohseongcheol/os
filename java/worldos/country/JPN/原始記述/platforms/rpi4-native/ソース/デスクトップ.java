/** フレームバッファー上の小さな起動画面。UART の TAB/ENTER/Q で操作する。独自の5×7欧文書体による限定的な画面で、Swing、USB HID、本格的な入力方式は備えない。 */
public final class デスクトップ {
    static String 文字値一覧 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789+-.:";
    // 各字形は7行で、各行を16進数2桁で表す。プロジェクト独自の5×7書体。
    static String 形状一覧一覧 =
        "0E11111F111111" + "1E11111E11111E" + "0F10101010100F" + "1E11111111111E" +
        "1F10101E10101F" + "1F10101E101010" + "0F10101711110F" + "1111111F111111" +
        "0E04040404040E" + "0702020212120C" + "11121418141211" + "1010101010101F" +
        "111B1515111111" + "11191915131311" + "0E11111111110E" + "1E11111E101010" +
        "0E11111115120D" + "1E11111E141211" + "0F10100E01011E" + "1F040404040404" +
        "1111111111110E" + "11111111110A04" + "11111115151B11" + "11110A040A1111" +
        "11110A04040404" + "1F01020408101F" + "0E11131519110E" + "040C040404040E" +
        "0E11010204081F" + "1E01010601011E" + "02060A121F0202" + "1F10101E01011E" +
        "0E10101E11110E" + "1F010204080808" + "0E11110E11110E" + "0E11110F01010E" +
        "0004041F040400" + "0000001F000000" + "00000000000C0C" + "000C0C000C0C00";
    static int 桁値(int 文字値) { return 文字値 <= '9' ? 文字値 - '0' : 文字値 - 'A' + 10; }
    static void 文(int 水平位置, int 垂直位置, String 内容物値, int 色値) {
        for (int 文字値 = 0; 文字値 < 内容物値.length(); 文字値++) {
            int 発見結果値 = -1;
            for (int 候補 = 0; 候補 < 文字値一覧.length(); 候補++) if (文字値一覧.charAt(候補) == 内容物値.charAt(文字値)) 発見結果値 = 候補;
            if (発見結果値 < 0) continue;
            for (int 行番号値 = 0; 行番号値 < 7; 行番号値++) {
                int 位置 = 発見結果値 * 14 + 行番号値 * 2;
                int ビット値 = 桁値(形状一覧一覧.charAt(位置)) * 16 + 桁値(形状一覧一覧.charAt(位置 + 1));
                for (int 列値 = 0; 列値 < 5; 列値++) if ((ビット値 & (16 >> 列値)) != 0)
                    中核.矩形(水平位置 + 文字値 * 12 + 列値 * 2, 垂直位置 + 行番号値 * 2, 2, 2, 色値);
            }
        }
    }
    static void 塗装画面(int 選択状態値, String 状況値) {
        中核.矩形(0, 0, 基板.画面幅(), 基板.画面高さ(), 0x302018);
        中核.矩形(32, 24, 576, 432, 0xefe8e2);
        中核.矩形(32, 24, 576, 48, 0x905020);
        文(52, 40, "JKOROS PROGRAMS", 0xffffff);
        for (int 番号 = 0; 番号 < 5; 番号++) {
            中核.矩形(64, 112 + 番号 * 52, 512, 40, 番号 == 選択状態値 ? 0xd0a040 : 0xd8d0c8);
            文(84, 128 + 番号 * 52, 番号 == 0 ? "RUN C++ FILE PROGRAM" : 番号 == 1 ? "RUN UDP LOOPBACK" : 番号 == 2 ? "COMPILE AND RUN JAVA" : 番号 == 3 ? "RUN MICROPYTHON" : "OPEN TERMINAL", 0x201810);
        }
        文(68, 384, 状況値, 0x205020);
        文(52, 420, "TAB SELECT  ENTER RUN  Q EXIT", 0x302018);
    }
    public static void 命令実行() {
        if (基板.画面用意() == 0) { 端末入出力.書込("GUI unavailable\n"); return; }
        int 選択状態値 = 0;
        String 状況値 = "READY";
        boolean 前回行 = 命令解釈器.前回行;
        塗装画面(選択状態値, 状況値);
        端末入出力.書込("GUI READY: UART TAB selects, ENTER runs, Q exits\n");
        while (true) {
            int 入力値 = 基板.直列読取();
            if (入力値 < 0) { 基板.処理機実行権譲渡(); continue; }
            if (入力値 == 10 && 前回行) { 前回行 = false; continue; }
            前回行 = 入力値 == 13;
            if (入力値 >= '1' && 入力値 <= '5') { 選択状態値 = 入力値 - '1'; 入力値 = 13; }
            if (入力値 == 't' || 入力値 == 'T') { 命令解釈器.端末(false); return; }
            if (入力値 == 'q' || 入力値 == 'Q' || 入力値 == 27) break;
            if (入力値 == 9 || 入力値 == 'j') {
                選択状態値 = (選択状態値 + 1) % 5; 塗装画面(選択状態値, 状況値); 端末入出力.書込("GUI FOCUS "); 端末入出力.数(選択状態値); 端末入出力.文字(10);
            } else if (入力値 == 13 || 入力値 == 10) {
                if (選択状態値 == 4) { 命令解釈器.端末(false); return; }
                int 結果;
                if (選択状態値 < 2) 結果 = 基板.利用者プログラム起動処理(選択状態値 == 0 ? 0 : 9);
                else if (選択状態値 == 2) {
                    結果 = 命令解釈器.例起動処理(10, "Hello.java");
                    if (結果 == 0) 結果 = 命令解釈器.例起動処理(11, "Hello");
                } else 結果 = 命令解釈器.例起動処理(12, "hello.py");
                状況値 = 結果 != 0 ? "PROGRAM FAILED" : 選択状態値 == 0 ? "C++ FILE OK" : 選択状態値 == 1 ? "UDP LOOPBACK OK" : 選択状態値 == 2 ? "JAVA OK" : "MICROPYTHON OK";
                塗装画面(選択状態値, 状況値);
                端末入出力.書込("GUI ACTION "); 端末入出力.数(選択状態値); 端末入出力.書込(" RESULT "); 端末入出力.数(結果); 端末入出力.文字(10);
            }
        }
        中核.画面();
        端末入出力.書込("GUI EXIT\n");
    }
}
