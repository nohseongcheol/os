"""Two-set Hangul composition for the native VNC-to-UART input bridge.

The pending character is visible in the guest editor. Replacing it uses that
editor's UTF-8 Backspace, so commit before cursor motion, shortcuts or a click.
No host input-method daemon or third-party Python package is required.
"""

初期字母表 = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
中声字母表 = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
最終字母表 = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'
キー配置 = dict(zip('rRseEfaqQtTdwWczxvgkoiOjpuPhynbml',
                'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎㅏㅐㅑㅒㅓㅔㅕㅖㅗㅛㅜㅠㅡㅣ'))
合成語中声字母 = {('ㅗ','ㅏ'):'ㅘ',('ㅗ','ㅐ'):'ㅙ',('ㅗ','ㅣ'):'ㅚ',
          ('ㅜ','ㅓ'):'ㅝ',('ㅜ','ㅔ'):'ㅞ',('ㅜ','ㅣ'):'ㅟ',('ㅡ','ㅣ'):'ㅢ'}
合成語最終字母 = {('ㄱ','ㅅ'):'ㄳ',('ㄴ','ㅈ'):'ㄵ',('ㄴ','ㅎ'):'ㄶ',
          ('ㄹ','ㄱ'):'ㄺ',('ㄹ','ㅁ'):'ㄻ',('ㄹ','ㅂ'):'ㄼ',('ㄹ','ㅅ'):'ㄽ',
          ('ㄹ','ㅌ'):'ㄾ',('ㄹ','ㅍ'):'ㄿ',('ㄹ','ㅎ'):'ㅀ',('ㅂ','ㅅ'):'ㅄ'}
最終字母分割処理 = {値: 一対 for 一対,値 in 合成語最終字母.items()}


class ハングル合成:
    def __init__(自身値, 送信):
        自身値.送信 = 送信
        自身値.確定合成状態()

    def 確定合成状態(自身値):
        自身値.状況コード = ('','','')
        自身値.履歴 = []

    def 文(自身値):
        初期字母,中声字母,最終字母 = 自身値.状況コード
        if 初期字母 and 中声字母:
            return chr(0xac00 + (初期字母表.index(初期字母)*21 + 中声字母表.index(中声字母))*28
                       + (最終字母表.index(最終字母) if 最終字母 else 0))
        return 初期字母 or 中声字母

    def 後退消去(自身値):
        if not 自身値.履歴:
            return False
        自身値.状況コード = 自身値.履歴.pop()
        自身値.送信(b'\x7f' + 自身値.文().encode('utf-8'))
        return True

    def 供給キー(自身値, 押下済み値):
        文字データ = キー配置.get(押下済み値, キー配置.get(押下済み値.lower()))
        if 文字データ is None:
            return False
        前回項目 = 自身値.文()
        初期字母,中声字母,最終字母 = 自身値.状況コード
        履歴 = 自身値.履歴 + [自身値.状況コード]
        確定済み = ''
        if 文字データ in 初期字母表:
            if 初期字母 and 中声字母 and not 最終字母 and 文字データ in 最終字母表:
                最終字母 = 文字データ
            elif 最終字母 and (最終字母,文字データ) in 合成語最終字母:
                最終字母 = 合成語最終字母[最終字母,文字データ]
            else:
                確定済み = 前回項目
                初期字母,中声字母,最終字母 = 文字データ,'',''
                履歴 = [('','','')]
        elif 最終字母:
            左側面,右 = 最終字母分割処理.get(最終字母, ('',最終字母))
            自身値.状況コード = 初期字母,中声字母,左側面
            確定済み = 自身値.文()
            初期字母,中声字母,最終字母 = 右,文字データ,''
            履歴 = [('','',''),(右,'','')]
        elif 中声字母:
            if (中声字母,文字データ) in 合成語中声字母:
                中声字母 = 合成語中声字母[中声字母,文字データ]
            else:
                確定済み = 前回項目
                初期字母,中声字母,最終字母 = '',文字データ,''
                履歴 = [('','','')]
        else:
            中声字母 = 文字データ
        自身値.状況コード = 初期字母,中声字母,最終字母
        自身値.履歴 = 履歴
        自身値.送信((b'\x7f' if 前回項目 else b'') + (確定済み+自身値.文()).encode('utf-8'))
        return True
