/** engos POSIX 第1段階の呼出しを扱う Java 管理層。 */
public final class システム呼出 {
    public static final int 専用フラグ読取 = 0;
    public static final int 開始処理捜索 = 0;
    public static final int 現在捜索 = 1;
    public static final int 入口終端位置探索 = 2;

    private final ファイルシステム ファイルシステム;
    private final ページ管理器 ページ管理業務;
    private final 割当器 割当器;
    private final 実行形式ローダー ローダー = new 実行形式ローダー();
    private final 機器値 装置;
    private final 入力管理器 入力管理業務;

    public システム呼出(ファイルシステム ファイルシステム, ページ管理器 ページ管理業務, 割当器 割当器, 機器値 装置, 入力管理器 入力管理業務) {
        this.ファイルシステム = ファイルシステム;
        this.ページ管理業務 = ページ管理業務;
        this.割当器 = 割当器;
        this.装置 = 装置;
        this.入力管理業務 = 入力管理業務;
    }

    public int プロセス識別子(プロセス値 現在プロセス) {
        return 現在プロセス.識別子値();
    }

    public int 親プロセス識別子(プロセス値 現在プロセス) {
        return 現在プロセス.親識別子();
    }

    public int 開放(プロセス値 現在プロセス, String 名前, int フラグ値) {
        if (フラグ値 != 専用フラグ読取) {
            return -30;
        }
        return 現在プロセス.ファイル記述子().開放(名前);
    }

    public int 読取(プロセス値 現在プロセス, int 記述子入口, byte[] 宛先受取, int 容量) {
        if (記述子入口 == 0) {
            if (容量 <= 0 || 宛先受取.length == 0) {
                return 0;
            }
            入力イベント イベント = 入力管理業務.次回イベント();
            if (イベント == null || イベント.イベント種別() != 入力イベント.種別値.キー下方) {
                return -11;
            }
            宛先受取[0] = (byte) イベント.先頭位置値();
            return 1;
        }
        return 現在プロセス.ファイル記述子().読取(記述子入口, 宛先受取, 容量);
    }

    public int 書込(プロセス値 現在プロセス, int 記述子入口, byte[] データ, int 容量) {
        if (記述子入口 != 1 && 記述子入口 != 2) {
            return 現在プロセス.ファイル記述子().判定開放(記述子入口) ? -30 : -9;
        }
        if (容量 < 0 || 容量 > データ.length) {
            return -22;
        }
        装置.直列出力(new String(データ, 0, 容量, java.nio.charset.StandardCharsets.UTF_8));
        return 容量;
    }

    public int 閉鎖(プロセス値 現在プロセス, int 記述子入口) {
        return 現在プロセス.ファイル記述子().閉鎖(記述子入口);
    }

    public int 移動位置(プロセス値 現在プロセス, int 記述子入口, int 距離値, int 計画根) {
        return 現在プロセス.ファイル記述子().移動位置(記述子入口, 距離値, 計画根);
    }

    public int 複製記述子(プロセス値 現在プロセス, int 記述子入口) {
        return 現在プロセス.ファイル記述子().複製済み記述子(記述子入口, 0);
    }

    public int 複製記述子位置(プロセス値 現在プロセス, int 記述子入口, int 新規記述子) {
        return 現在プロセス.ファイル記述子().複製位置(記述子入口, 新規記述子);
    }

    public int 判定到達可能(String 名前, int メソッド方式) {
        ファイル情報 システム情報 = ファイルシステム.システム情報(名前);
        if (システム情報 == null) {
            return -2;
        }
        if ((メソッド方式 & 1) != 0 && (システム情報.形状種別() & 0111) == 0) {
            return -13;
        }
        if ((メソッド方式 & 2) != 0) {
            return -30;
        }
        return 0;
    }

    public int 切替作業一覧(String 名前) {
        return "/".equals(名前) ? 0 : -20;
    }

    public String 現在作業一覧(int 容量受取) {
        return 容量受取 >= 2 ? "/" : null;
    }

    public int 利用者識別子() { return 0; }
    public int 実効利用者識別子() { return 0; }
    public int 集合識別子() { return 0; }
    public int 実効集合識別子() { return 0; }

    public int ファイル同期化(プロセス値 現在プロセス, int 記述子入口) {
        return 現在プロセス.ファイル記述子().システム情報(記述子入口) == null ? -9 : 0;
    }

    public void 全体同期化() {
        // 現在のファイルシステムは読取り専用のため、排出するデータはない。
    }

    public boolean 判定端末(プロセス値 現在プロセス, int 記述子入口) {
        ファイル情報 システム情報 = 現在プロセス.ファイル記述子().システム情報(記述子入口);
        return システム情報 != null && (システム情報.形状種別() & 0170000) == 0020000;
    }

    public int ファイル制御(プロセス値 現在プロセス, int 記述子入口, int 命令, int 仮引数引数) {
        if (命令 == 0) {
            return 現在プロセス.ファイル記述子().複製済み記述子(記述子入口, 仮引数引数);
        }
        if (命令 == 1) {
            return 現在プロセス.ファイル記述子().有効側実行処理値閉鎖(記述子入口);
        }
        if (命令 == 2) {
            return 現在プロセス.ファイル記述子().閉鎖有効側実行処理設定(記述子入口, (仮引数引数 & 1) != 0);
        }
        if (命令 == 3) {
            return 現在プロセス.ファイル記述子().システム情報(記述子入口) == null ? -9 : 専用フラグ読取;
        }
        if (命令 == 4) {
            return 仮引数引数 == 専用フラグ読取 ? 0 : -30;
        }
        return -22;
    }

    public int 入口作成(String 名前, int 許可値) {
        return -30;
    }

    public ファイル情報 記述子情報(プロセス値 現在プロセス, int 記述子入口) {
        return 現在プロセス.ファイル記述子().システム情報(記述子入口);
    }

    public システム詳細一覧 システム詳細一覧() {
        return new システム詳細一覧("JJpnOS", "JJpnOS", "0.1", "Java managed kernel", "i386");
    }

    public ファイル情報 ファイル情報(String 名前) {
        return ファイルシステム.システム情報(名前);
    }

    public プロセス値 複製処理プロセス(プロセス値 親値) {
        return 割当器.複製処理値(親値);
    }

    public int 対象子待合(プロセス値 親値, int 子識別子, boolean 非該当閉塞) {
        return 割当器.対象子待合(親値, 子識別子, 非該当閉塞);
    }

    public int プログラム中断(プロセス値 現在プロセス, int 新規終端位置) {
        int 前回終端位置 = 現在プロセス.プログラム中断();
        if (新規終端位置 == 0) {
            return 前回終端位置;
        }
        if (新規終端位置 < 0x06000000 || 新規終端位置 > 0x07000000) {
            return -12;
        }
        int 先頭位置ページ = 前回終端位置 / ページ管理器.ページ容量;
        int 末尾ページ = (新規終端位置 + ページ管理器.ページ容量 - 1) / ページ管理器.ページ容量;
        if (新規終端位置 > 前回終端位置) {
            for (int 番号 = 先頭位置ページ; 番号 < 末尾ページ; 番号++) {
                int 番地 = 番号 * ページ管理器.ページ容量;
                try {
                    ページ管理業務.バイト値読取(現在プロセス.番地空間(), 番地);
                } catch (IllegalStateException エラー) {
                    ページ管理業務.対応表ページ(現在プロセス.番地空間(), 番地, true);
                }
            }
        }
        現在プロセス.プログラム中断設定(新規終端位置);
        return 新規終端位置;
    }

    public int プログラム中断増加(プロセス値 現在プロセス, int 増分総量) {
        int 前回終端位置 = 現在プロセス.プログラム中断();
        int 結果 = プログラム中断(現在プロセス, 前回終端位置 + 増分総量);
        return 結果 < 0 ? 結果 : 前回終端位置;
    }

    public int 命令実行(プロセス値 現在プロセス, byte[] 実行形式ファイル) {
        return 命令実行(現在プロセス, 実行形式ファイル, new String[0], new String[0]);
    }

    public int 命令実行(プロセス値 現在プロセス, byte[] 実行形式ファイル, String[] 仮引数引数, String[] 環境) {
        実行形式ローダー.イメージ イメージ値;
        try {
            イメージ値 = ローダー.検査項目(実行形式ファイル);
        } catch (IllegalArgumentException エラー) {
            return -8;
        }
        if (仮引数引数 == null || 環境 == null || 仮引数引数.length > 16 || 環境.length > 16) {
            return -7;
        }
        for (実行形式ローダー.区画値 区画値 : イメージ値.区画一覧一覧()) {
            if ((区画値.フラグ値() & 2) == 0 || 区画値.容量() == 0) {
                continue;
            }
            int 先頭位置ページ = 区画値.番地() / ページ管理器.ページ容量;
            int 末尾ページ = (区画値.番地() + 区画値.容量() + ページ管理器.ページ容量 - 1) / ページ管理器.ページ容量;
            for (int 番号 = 先頭位置ページ; 番号 < 末尾ページ; 番号++) {
                int 番地 = 番号 * ページ管理器.ページ容量;
                try {
                    ページ管理業務.バイト値読取(現在プロセス.番地空間(), 番地);
                    ページ管理業務.非公開範囲書込(現在プロセス.番地空間(), 番地, ページ管理器.ページ容量);
                } catch (IllegalStateException エラー) {
                    ページ管理業務.対応表ページ(現在プロセス.番地空間(), 番地, true);
                }
            }
            for (int 番号 = 0; 番号 < 区画値.容量(); 番号++) {
                byte 値 = 区画値.種別値() == 8 ? 0 : 実行形式ファイル[区画値.ファイル位置() + 番号];
                ページ管理業務.バイト値書込(現在プロセス.番地空間(), 区画値.番地() + 番号, 値);
            }
        }
        現在プロセス.実行状態文脈設定(イメージ値.番地開始処理(), 仮引数引数, 環境);
        現在プロセス.ファイル記述子().有効側実行処理閉鎖();
        return 0;
    }

    public void 脱出プログラム(プロセス値 現在プロセス, int 状況値) {
        現在プロセス.終了点プログラム(状況値);
    }
}
