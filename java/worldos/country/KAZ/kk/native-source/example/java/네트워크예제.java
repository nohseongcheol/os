import 한국어.자체.қосылым;
import 한국어.자체.실행인수;
import 한국어.자체.전문통로;
import 한국어.자체.문자;
import 한국어.자체.Шығысы;
import 한국어.자체.검사;
import 한국어.자체.кіріс_ағыны;
import 한국어.자체.енгізу_шығару_ерекшелік;

public class 네트워크예제 {
    public static void Орындау_2() throws енгізу_шығару_ерекшелік {
        // орналастыру: python3 Құралдар/예제되돌림.py --tcp-port 9000 --udp-port 9001
        қосылым Байланысу = қосылым.Ашу("10.0.2.2", 문자.талдау_бүтін_сан(실행인수.Мәтін(0)));
        try {
            Байланысу.ТАЙМ_АУТ(700);
            byte[] хабар = 문자.부호화("JAVA TCP kk\n");
            Байланысу.Шығысы().Жазу(хабар);
            кіріс_ағыны 입력 = Байланысу.입력();
            for (int 수 = 0; 수 < 문자.바이트수(хабар); 수++) {
                검사.참인지(입력.Оқу() == (хабар[수] & 255), "TCP жауап 불일치");
            }
        } finally { Байланысу.Жабу(); }
        전문통로 қатысушы = 전문통로.Ашу(0);
        try {
            қатысушы.ТАЙМ_АУТ(700);
            қатысушы.жіберу("10.0.2.2", 문자.талдау_бүтін_сан(실행인수.Мәтін(1)), "JAVA UDP kk");
            검사.참인지(문자.같음(қатысушы.받기(), "JAVA UDP kk"), "UDP жауап 불일치");
        } finally { қатысушы.Жабу(); }
        Шығысы.жазу_жол("JAVA 네트워크 тексеру: TCP UDP kk");
    }
}
