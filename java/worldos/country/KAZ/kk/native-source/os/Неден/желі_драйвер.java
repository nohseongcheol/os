/** PCI RTL8139 (10ec:8139), 단일 жіберу_мән_f993dacd 버퍼와 8KiB 수신 тұйық_мән. 인터럽트 대신 폴링한다. */
public final class желі_драйвер {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] құрылғы_мекенжай = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int Орны) {
        құрылғы_мән.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | Орны);
        return құрылғы_мән.입출력정수읽기(0xcfc);
    }

    static boolean Дайындау() {
        int 장치번호 = -1;
        for (int индекс = 0; индекс < 32; индекс++) {
            if (설정읽기(индекс, 0) == 0x813910ec) { 장치번호 = индекс; break; }
        }
        if (장치번호 < 0) return false;
        int әдепкі_мән = 설정읽기(장치번호, 0x10);
        if ((әдепкі_мән & 1) == 0 || (әдепкі_мән & 0xfffffffc) < 0x100 || (әдепкі_мән & 0xfffffffc) > 65535) return false;
        입출력기준주소 = әдепкі_мән & 0xfffc;
        int Команда = 설정읽기(장치번호, 4);
        құрылғы_мән.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        құрылғы_мән.입출력짧은수쓰기(0xcfc, Команда | 5); // I/O 및 bus master рұқсат_ету_мән, PCI күй_мән 비트는 건드리지 않음
        құрылғы_мән.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!Ысыру_мән()) { 입출력기준주소 = 0; return false; }
        for (int индекс = 0; индекс < 6; индекс++) құрылғы_мекенжай[индекс] = құрылғы_мән.입출력바이트읽기(입출력기준주소 + индекс);
        return true;
    }

    static boolean Ысыру_мән() {
        құрылғы_мән.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int Орындау_2 = құрылғы_мән.밀리초();
        while ((құрылғы_мән.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (құрылғы_мән.밀리초() - Орындау_2 > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        құрылғы_мән.입출력정수쓰기(입출력기준주소 + 0x30, құрылғы_мән.желі_Жад());
        for (int индекс = 0; индекс < 4; индекс++) құрылғы_мән.입출력정수쓰기(입출력기준주소 + 0x20 + индекс * 4, құрылғы_мән.желі_Жад() + 12288);
        құрылғы_мән.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        құрылғы_мән.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        құрылғы_мән.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        құрылғы_мән.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/тарату_мән, wrap 연속 сақтау_мән, 8KiB
        құрылғы_мән.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int жіберу(int[] деректер, int ұзындық_мән) {
        if (입출력기준주소 == 0) return -19;
        if (ұзындық_мән < 14 || ұзындық_мән > 1514) return -90;
        int күй_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int Орындау_2 = құрылғы_мән.밀리초();
        while ((құрылғы_мән.입출력정수읽기(күй_порт) & 0x2000) == 0)
            if (құрылғы_мән.밀리초() - Орындау_2 > 100) return -110;
        int Өлшемі = ұзындық_мән < 60 ? 60 : ұзындық_мән;
        for (int индекс = 0; индекс < Өлшемі; индекс++)
            құрылғы_мән.жазу_Жад(құрылғы_мән.желі_Жад() + 12288 + индекс, индекс < ұзындық_мән ? деректер[индекс] : 0);
        құрылғы_мән.입출력정수쓰기(күй_порт, Өлшемі | 0x00080000);
        Орындау_2 = құрылғы_мән.밀리초();
        while ((құрылғы_мән.입출력정수읽기(күй_порт) & 0xe0008000) == 0)
            if (құрылғы_мән.밀리초() - Орындау_2 > 100) return -110;
        if ((құрылғы_мән.입출력정수읽기(күй_порт) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return ұзындық_мән;
    }

    static int 받기(int[] деректер) {
        if (입출력기준주소 == 0) return 0;
        if ((құрылғы_мән.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!Ысыру_мән()) 입출력기준주소 = 0;
            return 0;
        }
        if ((құрылғы_мән.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = құрылғы_мән.желі_Жад() + 수신위치;
        int күй_мән = 실행관리.짧은수(머리), Өлшемі = 실행관리.짧은수(머리 + 2);
        if (Өлшемі == 0xfff0) return 0; // DMA 진행 중
        if (Өлшемі < 4 || Өлшемі > 1518) {
            오류수++;
            if (!Ысыру_мән()) 입출력기준주소 = 0;
            return 0;
        }
        int ұзындық_мән = Өлшемі - 4;
        if ((күй_мән & 1) != 0) {
            for (int индекс = 0; индекс < ұзындық_мән; индекс++) деректер[индекс] = құрылғы_мән.기억읽기(머리 + 4 + индекс);
            수신수++;
        } else { ұзындық_мән = 0; 오류수++; }
        수신위치 = (수신위치 + Өлшемі + 4 + 3) & ~3;
        수신위치 &= 8191;
        құрылғы_мән.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        құрылғы_мән.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return ұзындық_мән;
    }
}
