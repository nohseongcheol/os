public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int ұзындық_мән = 0;
    static boolean 앞줄복귀 = false;
    static boolean жол_толып_кету = false;

    static boolean Команда(String Аты) {
        if (ұзындық_мән < Аты.length()) return false;
        for (int индекс = 0; индекс < Аты.length(); индекс++)
            if (입력[индекс] != Аты.charAt(индекс)) return false;
        return ұзындық_мән == Аты.length() || 입력[Аты.length()] == ' ';
    }

    static void көрсету_анықтама() {
        Мәтін_Терминал.Жазу("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        Мәтін_Терминал.Жазу("apps | run NAME [ARGS] | net\n");
        Мәтін_Терминал.Жазу("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        Мәтін_Терминал.Жазу("sync (연결된 JKSTORE1 сақтау_мән 장치에 Файл 보존)\n");
    }

    static void Процесс_мән_енгізу() {
        if (ұзындық_мән == 0) return;
        if (Команда("help")) көрсету_анықтама();
        else if (Команда("sync")) {
            int НӘТИЖЕ = 파일보존.үндестіру();
            Мәтін_Терминал.Жазу("Sync: "); Мәтін_Терминал.수쓰기(НӘТИЖЕ); Мәтін_Терминал.문자(10);
        }
        else if (Команда("ls")) Жад_файлдық_жүйе.енгізу_Тізім();
        else if (Команда("edit")) Жад_файлдық_жүйе.Команда(입력, 4, ұзындық_мән, 0);
        else if (Команда("cat")) Жад_файлдық_жүйе.Команда(입력, 3, ұзындық_мән, 1);
        else if (Команда("rm")) Жад_файлдық_жүйе.Команда(입력, 2, ұзындық_мән, 2);
        else if (Команда("java") || Команда("javac")) {
            int НӘТИЖЕ = 실행관리.орындау_пәрмен(입력, 0, ұзындық_мән);
            Мәтін_Терминал.Жазу("Exit: "); Мәтін_Терминал.수쓰기(НӘТИЖЕ); Мәтін_Терминал.문자(10);
        }
        else if (Команда("apps")) 실행관리.енгізу_Тізім();
        else if (Команда("net")) желі_Бума.күй_мән();
        else if (Команда("run")) {
            int НӘТИЖЕ = 실행관리.орындау_пәрмен(입력, 3, ұзындық_мән);
            Мәтін_Терминал.Жазу("Exit: "); Мәтін_Терминал.수쓰기(НӘТИЖЕ); Мәтін_Терминал.Жазу("\n");
        } else if (Команда("info")) {
            Мәтін_Терминал.Жазу("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (Команда("mem")) {
            Мәтін_Терминал.Жазу("위쪽 Жад_мән мекенжай_аумақ(KiB): "); Мәтін_Терминал.수쓰기(Жад_аумақ.위쪽기억크기());
            Мәтін_Терминал.Жазу("\n배열 동적 Жад_мән мекенжай_аумақ(байт_мән): "); Мәтін_Терминал.수쓰기(құрылғы_мән.массив_пайдалану());
            Мәтін_Терминал.Жазу(" / 262144\n작업 мекенжай_аумақ бөлім_мән_366e0bfa: "); Мәтін_Терминал.수쓰기(Жад_аумақ.사용개수());
            Мәтін_Терминал.Жазу(" / 8 (각 4096바이트)\n");
        } else if (Команда("alloc")) {
            int индекс = Жад_аумақ.бекіту_Жад();
            Мәтін_Терминал.Жазу("бөлім_мән_366e0bfa индекс: "); Мәтін_Терминал.수쓰기(индекс); Мәтін_Терминал.Жазу("\n");
        } else if (Команда("free")) {
            if (ұзындық_мән == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                Мәтін_Терминал.Жазу(Жад_аумақ.қайтару_өлшем(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 бөлім_мән_366e0bfa\n");
            } else Мәтін_Терминал.Жазу("사용법: free 0..7\n");
        } else if (Команда("echo")) {
            for (int индекс = 5; индекс < ұзындық_мән; индекс++) Мәтін_Терминал.문자(입력[индекс]);
            Мәтін_Терминал.문자(10);
        } else if (Команда("clear")) Мәтін_Терминал.өшіру_енгізу();
        else if (Команда("test")) ядро.시험();
        else if (Команда("halt")) {
            Мәтін_Терминал.Жазу("HALTED\n");
            құрылғы_мән.정지();
        } else Мәтін_Терминал.Жазу("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int мән) {
        if (мән == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = мән == 13;
        if (мән == 10 || мән == 13) {
            Мәтін_Терминал.문자(10);
            if (Жад_файлдық_жүйе.편집중) Жад_файлдық_жүйе.Өңделетін_презентациялар_жол(입력, ұзындық_мән, жол_толып_кету);
            else Процесс_мән_енгізу();
            ұзындық_мән = 0;
            жол_толып_кету = false;
            Мәтін_Терминал.Жазу(Жад_файлдық_жүйе.편집중 ? "...> " : "jkoros> ");
        } else if (мән == 8 || мән == 127) {
            if (ұзындық_мән > 0) {
                ұзындық_мән--;
                Мәтін_Терминал.직렬바이트(8); Мәтін_Терминал.직렬바이트(32); Мәтін_Терминал.직렬바이트(8);
                Мәтін_Терминал.화면문자(8);
            }
        } else if (мән >= 32 && мән < 127 && ұзындық_мән < 입력.length) {
            입력[ұзындық_мән++] = мән;
            Мәтін_Терминал.문자(мән);
        } else if (мән >= 32 && мән < 127) жол_толып_кету = true;
    }

    static void Орындау_2() {
        көрсету_анықтама();
        Мәтін_Терминал.Жазу("READY\njkoros> ");
        while (true) {
            int мән = Мәтін_Терминал.직렬읽기();
            if (мән < 0) мән = пернетақта.Оқу();
            if (мән >= 0) 받아쓰기(мән);
            else { желі_Бума.тексеру(); құрылғы_мән.잠시양보(); }
        }
    }
}
