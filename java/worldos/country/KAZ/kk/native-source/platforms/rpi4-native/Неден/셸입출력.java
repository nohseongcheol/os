/** 파이프는 16 KiB씩 순서대로 실행한다. 프로세스/동시 파이프를 흉내 내지 않는다. */
public final class 셸입출력 {
    static int[] 입력자료 = new int[16384], 출력자료 = new int[16384];
    static int 입력길이, 입력위치, 출력길이, кіріс_файлы = -1, шығыс_файл = -1;
    static boolean 파이프입력, 파이프출력;
    static int қате_мән;
    static boolean рұқсат_ету_көзбе_көз_белсенді = true;
    public static int ақпараттық_жүйелер_көзбе_көз_белсенді() { return рұқсат_ету_көзбе_көз_белсенді && кіріс_файлы < 3 && шығыс_файл < 3 && !파이프입력 && !파이프출력 ? 1 : 0; }
    public static int Шығысы(int Арна_мән, int мән) {
        if (Арна_мән != 1) return 0;
        if (шығыс_файл >= 3) { int 처리값 = Жад_Файлдар.Жазу(шығыс_файл, мән); if (처리값 < 0) қате_мән = 처리값; return 1; }
        if (!파이프출력) return 0;
        if (출력길이 == 출력자료.length) қате_мән = -28;
        else 출력자료[출력길이++] = мән;
        return 1;
    }
    public static int 입력() {
        if (кіріс_файлы >= 3) { int 처리값 = Жад_Файлдар.Оқу(кіріс_файлы); return 처리값 == 256 ? -2 : 처리값; }
        if (파이프입력) return 입력위치 < 입력길이 ? 입력자료[입력위치++] : -2;
        return -3; // UART로 Алға_мән
    }
    static void Орындау_2(boolean аралық_тік_сызық, boolean 뒤파이프) {
        파이프입력 = аралық_тік_сызық; 파이프출력 = 뒤파이프;
        입력위치 = 0; 출력길이 = 0; кіріс_файлы = -1; шығыс_файл = -1; қате_мән = 0;
    }
    static void 끝() {
        Тақта.입출력전환(0);
        if (кіріс_файлы >= 3) Жад_Файлдар.Жабу(кіріс_файлы);
        if (шығыс_файл >= 3) Жад_Файлдар.Жабу(шығыс_файл);
        if (파이프출력) { 입력길이 = 출력길이; for (int тұйық_индекс = 0; тұйық_индекс < 출력길이; тұйық_индекс++) 입력자료[тұйық_индекс] = 출력자료[тұйық_индекс]; }
        кіріс_файлы = -1; шығыс_файл = -1; 파이프입력 = false; 파이프출력 = false;
    }
}
