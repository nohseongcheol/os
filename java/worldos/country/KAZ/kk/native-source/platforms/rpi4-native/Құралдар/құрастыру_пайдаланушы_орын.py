"""독립된 자체 ABI ELF64와 로더 қабылдамау_мән 시험 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from 파이썬빌드 import 파이썬만들기
from 자바라이브러리빌드 import 자바라이브러리만들기
from 시언어번역기빌드 import 시언어번역기만들기


def жасау_пайдаланушы_орын(түбір_жол, репозиторий_жол, 시언어번역기, 시플플번역기, 연결편집기, Мұрағат_құрал, конфигурация_фондық_интеллектуалдық_тасымалдау_қызметі, орындау_пәрмен):
    конфигурация_фондық_интеллектуалдық_тасымалдау_қызметі = [Параметрлер_мән for Параметрлер_мән in конфигурация_фондық_интеллектуалдық_тасымалдау_қызметі if Параметрлер_мән != '-mgeneral-regs-only']
    құрастыру_жол = түбір_жол / 'build'
    출력결과 = құрастыру_жол / 'user'
    출력결과.mkdir(exist_ok=True)
    원본자료 = түбір_жол / 'пайдаланушы'
    포직스경로 = репозиторий_жол / 'posix-kor/arm64-native'
    포함경로 = ['-I', 원본자료, '-I', 포직스경로 / '포함', '-I', 출력결과]
    for 번역기, 추가영역, Жол_2, Аты in [
            (시언어번역기, [], 원본자료 / 'Орындау_2.S', 'start.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'орындау_пәрмен.c', 'runtime.o'),
            (시언어번역기, ['-std=c11'], 포직스경로 / 'пайдаланушы_көпір.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '파일예제.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '통신예제.cpp', 'network.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / '보호시험.c', 'fault.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'өңдегіш.c', 'vi.o')]:
        орындау_пәрмен([번역기] + конфигурация_фондық_интеллектуалдық_тасымалдау_қызметі + 추가영역 + 포함경로 + ['-Wall', '-Wextra', '-Werror', '-c', Жол_2, '-o', 출력결과 / Аты])
    орындау_пәрмен([Мұрағат_құрал, 'rcs', құрастыру_жол / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for Аты in ('demo', 'fault', 'network', 'vi'):
        орындау_пәрмен([연결편집기, '-T', 원본자료 / 'Cілтеме_макет.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (Аты + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (Аты + '.o'), құрастыру_жол / 'libposix-kor-user.a'])
    자바라이브러리만들기(түбір_жол, орындау_пәрмен)
    # 기존 자체 Java 컴파일러/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(құрастыру_жол)) as 작업경로:
        оқу_жол = Path(작업경로)
        орындау_пәрмен(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', оқу_жол, '-sourcepath', оқу_жол, '-d', оқу_жол] +
            [деректер_лауазым for деректер_лауазым in sorted((репозиторий_жол / 'os/пайдаланушы/자바').glob('*.java')) if деректер_лауазым.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        орындау_пәрмен(['sh', репозиторий_жол / 'compiler/미리번역.sh', '--entry', 'құрал_енгізу.Орындау_2',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(оқу_жол.glob('*.class')))
    압축해제경로 = түбір_жол / 'vendor/uzlib'
    for Жол_2, Аты in [(출력결과 / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'жинау.c', 'jar.o')] + [(압축해제경로 / (Аты + '.c'), Аты + '.o') for Аты in ('tinflate', 'crc32', 'adler32')]:
        орындау_пәрмен([시언어번역기] + конфигурация_фондық_интеллектуалдық_тасымалдау_қызметі + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + 포함경로 + ['-c', Жол_2, '-o', 출력결과 / Аты])
    орындау_пәрмен([연결편집기, '-T', 원본자료 / 'Cілтеме_макет.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / Аты for Аты in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(түбір_жол, 시언어번역기, 연결편집기)
    시언어번역기만들기(түбір_жол, репозиторий_жол, 시언어번역기, 연결편집기, конфигурация_фондық_интеллектуалдық_тасымалдау_қызметі, орындау_пәрмен)
    유효함 = (출력결과 / 'demo.elf').read_bytes()
    бағдарлама_Тақырып_жылжыту = struct.unpack_from('<Q', 유효함, 32)[0]
    Тақырып_Тізім = [бағдарлама_Тақырып_жылжыту + 개수 * 56 for 개수 in range(struct.unpack_from('<H', 유효함, 56)[0])]
    적재구획 = [деректер_лауазым for деректер_лауазым in Тақырып_Тізім if struct.unpack_from('<I', 유효함, деректер_лауазым)[0] == 1]
    Мәтін, деректер = 적재구획[:2]
    пәрмен_мекенжай = struct.unpack_from('<Q', 유효함, Мәтін + 16)[0]
    деректер_мекенжай = struct.unpack_from('<Q', 유효함, деректер + 16)[0]
    호출규약 = 유효함.index(b'JKOROS\0')
    시험사례 = [('empty', b''), ('short', 유효함[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', пәрмен_мекенжай + 1), ('data-entry', 24, 'Q', деректер_мекенжай),
               ('outside-file', Мәтін + 32, 'Q', len(유효함) + 1), ('short-memory', Мәтін + 40, 'Q', 1),
               ('kernel-address', Мәтін + 16, 'Q', 0x80000), ('memory-overflow', Мәтін + 40, 'Q', 2**64 - 1),
               ('writable-code', Мәтін + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', Мәтін, 'I', 2),
               ('unaligned-load', Мәтін + 16, 'Q', пәрмен_мекенжай + 8),
               ('overlap', деректер + 16, 'Q', пәрмен_мекенжай)]
    for Аты, жылжыту_мән_450fc799, пішім_932e03c8, мән in 수정사항:
        바뀐자료 = bytearray(유효함); struct.pack_into('<' + пішім_932e03c8, 바뀐자료, жылжыту_мән_450fc799, мән)
        시험사례.append((Аты, bytes(바뀐자료)))
    탑재덩이들 = [(Аты.replace('-', '_'), 출력결과 / (Аты + '.elf')) for Аты in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for Іздеу_индекс, (Аты, жүктеме_деректер) in enumerate(시험사례):
        Жол_2 = 출력결과 / ('invalid-{}.elf'.format(Аты)); Жол_2.write_bytes(жүктеме_деректер)
        탑재덩이들.append(('invalid_{}'.format(Іздеу_индекс), Жол_2))
    жиын, Тақырып_мән = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for Аты, Жол_2 in 탑재덩이들:
        символ_мән = 'user_blob_' + Аты
        크기목록[Аты] = Жол_2.stat().st_size
        # 생성한 бір_рангілі_мән 경로만 넣어 프로젝트 경로의 공백/Цитата 영향을 피한다.
        жиын += ['.balign 16', '.global ' + символ_мән, символ_мән + ':', '.incbin "{}"'.format(Жол_2.relative_to(түбір_жол))]
        Тақырып_мән.append('extern const unsigned char {}[];'.format(символ_мән))
    жиын.append('.section .note.GNU-stack,"",%progbits')
    Тақырып_мән += ['static const бағдарлама 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    Тақырып_мән += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    Тақырып_мән += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    Тақырып_мән += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], әдіс_режим) for әдіс_режим in (0, 1)]
    Тақырып_мән += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    Тақырып_мән += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    Тақырып_мән += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    Тақырып_мән += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    Тақырып_мән += ['};', 'static const бағдарлама 잘못된실행항목들[] = {']
    Тақырып_мән += ['{user_blob_invalid_%d, %d, 0},' % (순번, len(жүктеме_деректер)) for 순번, (_, жүктеме_деректер) in enumerate(시험사례)]
    Тақырып_мән += ['};']
    (құрастыру_жол / 'programs.S').write_text('\n'.join(жиын) + '\n')
    (құрастыру_жол / 'programs.h').write_text('\n'.join(Тақырып_мән) + '\n')
    (출력결과 / 'invalid-cases.txt').write_text('\n'.join(Аты for Аты, _ in 시험사례) + '\n')
    орындау_пәрмен([시언어번역기] + конфигурация_фондық_интеллектуалдық_тасымалдау_қызметі + ['-c', құрастыру_жол / 'programs.S', '-o', құрастыру_жол / 'programs.o'])
