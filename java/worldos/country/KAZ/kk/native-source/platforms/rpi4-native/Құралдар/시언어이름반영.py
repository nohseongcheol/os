#!/usr/bin/env python3
"""мәлімдеме 고유번호와 UTF-8 байт_мән 위치로 자체 C 이름을 옮기는 일회성 이행 Құралдар.

сыртқы_мән 구조체의 멤버, жол_мән_6ca8363c, C 표준 функция_мән, 이식 규약은 보존한다.
입력은 өзгерту_мән 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

жоба_түбір = Path(__file__).resolve().parents[1]

def орындау_пәрмен():
    Талдау_мән = json.loads((жоба_түбір/'build/한국어화/시언어분석.json').read_text())
    if Талдау_мән['Қате']: raise SystemExit('Талдау_мән 오류를 먼저 해결해야 합니다.')
    аты_кесте = json.loads((жоба_түбір/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((жоба_түбір/'명명/규격이름.json').read_text()))
    мәлімдеме_кесте = Талдау_мән['мәлімдеме']
    바꿀선언 = {고유:аты_кесте[енгізу_мән['Аты']] for 고유,енгізу_мән in мәлімдеме_кесте.items()
                if енгізу_мән['Аты'] in аты_кесте and енгізу_мән['Аты'] not in 규격}
    қосылым_кесте = {енгізу_мән['Аты']:аты_кесте[енгізу_мән['Аты']] for енгізу_мән in мәлімдеме_кесте.values()
              if енгізу_мән.get('Байланысу')==4 and енгізу_мән['종류'] in (8,9)
              and енгізу_мән['Аты'] in аты_кесте and енгізу_мән['Аты'] not in 규격}
    # жасау AOT C·어셈블리·공개 SDK가 공유하는 바이너리 Байланысу 이름만 유지한다.
    머리 = ['/* 한국어 көз_дарақ 이름과 기존 компьютер Байланысу іс_мән. 자동 жасау: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(қосылым_кесте.items())]
    머리 += ['#endif','']
    (жоба_түбір/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Өзгерістер_Тізім = defaultdict(dict)
    for Файл,жылжыту_мән_450fc799,Аты,고유 in Талдау_мән['Анықтамалық']:
        if 고유 in 바꿀선언:
            Өзгерістер_Тізім[Файл][жылжыту_мән_450fc799] = (Аты,바꿀선언[고유])
    журнал_жол = ['Файл\t원래바이트위치\t이전이름\t한국어이름']
    елемеу_мән = []
    for Файл,өзгерту_мән in Өзгерістер_Тізім.items():
        Жол_2 = Path(Файл); 원본 = Жол_2.read_bytes(); деректер = 원본
        for жылжыту_мән_450fc799,(옛이름,새이름) in sorted(өзгерту_мән.items(),reverse=True):
            끝 = жылжыту_мән_450fc799+len(옛이름.encode())
            if 원본[жылжыту_мән_450fc799:끝] != 옛이름.encode():
                елемеу_мән.append((str(Жол_2.relative_to(жоба_түбір)),жылжыту_мән_450fc799,옛이름));continue
            деректер = деректер[:жылжыту_мән_450fc799]+새이름.encode()+деректер[끝:]
            журнал_жол.append('{}\t{}\t{}\t{}'.format(Жол_2.relative_to(жоба_түбір),жылжыту_мән_450fc799,옛이름,새이름))
        Жол_2.write_bytes(деректер)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макрос_мән = {енгізу_мән['Аты']:аты_кесте[енгізу_мән['Аты']] for енгізу_мән in мәлімдеме_кесте.values()
              if енгізу_мән['종류']==501 and енгізу_мән['Аты'] in аты_кесте and енгізу_мән['Аты'] not in 규격}
    for Жол_2 in sorted({Path(енгізу_мән['Файл']) for енгізу_мән in мәлімдеме_кесте.values()}):
        жол_Тізім = Жол_2.read_text().splitlines(True); 이어짐 = False
        for индекс,Жол in enumerate(жол_Тізім):
            전처리 = 이어짐 or bool(re.match(r'\s*#',Жол))
            이어짐 = 전처리 and Жол.rstrip().endswith('\\')
            if 전처리:
                Іздеу_кесте = аты_кесте if re.match(r'\s*#\s*define\b',Жол) or 이어짐 else макрос_мән
                жол_Тізім[индекс] = 낱말.sub(lambda 맞음: Іздеу_кесте.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],Жол)
        Жол_2.write_text(''.join(жол_Тізім))
    # 각 자체 Аудару_көз 단위에만 연결표를 넣는다. сыртқы_мән 배포본에는 전파하지 않는다.
    for Жол_2 in sorted({Path(енгізу_мән['Файл']) for енгізу_мән in мәлімдеме_кесте.values()}):
        if Жол_2.suffix not in ('.c','.cpp'):continue
        бір_рангілі_мән = '../' * len(Жол_2.relative_to(жоба_түбір).parts[:-1]) + '명명/기계연결이름.h'
        Жол_2.write_text('#include "'+бір_рангілі_мән+'"\n'+Жол_2.read_text())
    (жоба_түбір/'명명/시언어이름대응.tsv').write_text('\n'.join(журнал_жол)+'\n')
    (жоба_түбір/'build/한국어화/전처리참조.json').write_text(json.dumps(елемеу_мән,ensure_ascii=False,indent=2)+'\n')
    print('өзгерту_мән',len(журнал_жол)-1,'전처리 재검토',len(елемеу_мән),'компьютер Байланысу',len(қосылым_кесте))

if __name__=='__main__': орындау_пәрмен()
