/** 문자(文字), кодтау_мән(符號): UTF-8 바이트와 UTF-16 문자열의 Түрлендіру_мән. нормалдау_мән/조합 입력기는 별개다. */
public final class 문자 {
    public static int 바이트수(byte[] деректер) { return деректер.length; }
    private 문자() {}
    public static int ұзындық_мән(String Мәтін) { return Мәтін.length(); }
    public static boolean 같음(String алдыңғы_камера_мән, String АРТҚА_мән) { return алдыңғы_камера_мән == null ? АРТҚА_мән == null : алдыңғы_камера_мән.equals(АРТҚА_мән); }
    public static String қою_Мәтін(String алдыңғы_камера_мән, String АРТҚА_мән) { return алдыңғы_камера_мән.concat(АРТҚА_мән); }
    public static String кесу_мән(String Мәтін, int Орындау_2, int 끝) { return Мәтін.substring(Орындау_2, 끝); }
    public static int талдау_бүтін_сан(String Мәтін) { try { return Integer.parseInt(Мәтін); } catch (NumberFormatException Қате) { throw new 숫자형식예외("숫자의 형식이나 범위를 확인하십시오."); } }
    public static String жазу_бүтін_сан_мән(int 수) { return Integer.toString(수); }
    public static int 코드포인트수(String Мәтін) {
        int 수 = 0;
        for (int тұйық_индекс = 0; тұйық_индекс < Мәтін.length(); тұйық_индекс++, 수++) {
            int таңба_коды = Мәтін.charAt(тұйық_индекс);
            if (таңба_коды >= 0xd800 && таңба_коды <= 0xdbff && тұйық_индекс + 1 < Мәтін.length() && Мәтін.charAt(тұйық_индекс + 1) >= 0xdc00 && Мәтін.charAt(тұйық_индекс + 1) <= 0xdfff) тұйық_индекс++;
        }
        return 수;
    }
    public static byte[] 부호화(String Мәтін) {
        byte[] 임시 = new byte[Мәтін.length() * 3]; int 쓴수 = 0;
        for (int тұйық_индекс = 0; тұйық_индекс < Мәтін.length(); тұйық_индекс++) {
            int таңба_коды = Мәтін.charAt(тұйық_индекс);
            if (таңба_коды >= 0xd800 && таңба_коды <= 0xdbff && тұйық_индекс + 1 < Мәтін.length() && Мәтін.charAt(тұйық_индекс + 1) >= 0xdc00 && Мәтін.charAt(тұйық_индекс + 1) <= 0xdfff) таңба_коды = 0x10000 + ((таңба_коды - 0xd800) << 10) + Мәтін.charAt(++тұйық_индекс) - 0xdc00;
            else if (таңба_коды >= 0xd800 && таңба_коды <= 0xdfff) таңба_коды = '?';
            if (таңба_коды < 128) 임시[쓴수++] = (byte)таңба_коды;
            else if (таңба_коды < 2048) { 임시[쓴수++] = (byte)(192 | таңба_коды >> 6); 임시[쓴수++] = (byte)(128 | таңба_коды & 63); }
            else if (таңба_коды < 65536) { 임시[쓴수++] = (byte)(224 | таңба_коды >> 12); 임시[쓴수++] = (byte)(128 | таңба_коды >> 6 & 63); 임시[쓴수++] = (byte)(128 | таңба_коды & 63); }
            else { 임시[쓴수++] = (byte)(240 | таңба_коды >> 18); 임시[쓴수++] = (byte)(128 | таңба_коды >> 12 & 63); 임시[쓴수++] = (byte)(128 | таңба_коды >> 6 & 63); 임시[쓴수++] = (byte)(128 | таңба_коды & 63); }
        }
        byte[] НӘТИЖЕ = new byte[쓴수]; System.arraycopy(임시, 0, НӘТИЖЕ, 0, 쓴수); return НӘТИЖЕ;
    }
    /** 잘못된 UTF-8은 잘못된인수예외으로 거부한다. */
    public static String шифрді_шешу_деректер(byte[] байт_мән) {
        StringBuilder НӘТИЖЕ = new StringBuilder();
        for (int тұйық_индекс = 0; тұйық_индекс < байт_мән.length;) {
            int таңба_коды = байт_мән[тұйық_индекс++] & 255, 수 = таңба_коды < 128 ? 0 : таңба_коды >= 194 && таңба_коды < 224 ? 1 : таңба_коды >= 224 && таңба_коды < 240 ? 2 : таңба_коды >= 240 && таңба_коды <= 244 ? 3 : -1;
            if (수 < 0 || байт_мән.length - тұйық_индекс < 수) throw new дұрыс_емес_аргумент_ерекшелік("잘못된 UTF-8");
            int 최소 = 수 == 1 ? 128 : 수 == 2 ? 2048 : 수 == 3 ? 65536 : 0;
            if (수 > 0) таңба_коды &= (1 << (6 - 수)) - 1;
            for (int ішкі_лауазым = 0; ішкі_лауазым < 수; ішкі_лауазым++) { int АРТҚА_мән = байт_мән[тұйық_индекс++] & 255; if ((АРТҚА_мән & 192) != 128) throw new дұрыс_емес_аргумент_ерекшелік("잘못된 UTF-8"); таңба_коды = таңба_коды << 6 | АРТҚА_мән & 63; }
            if (таңба_коды < 최소 || таңба_коды > 0x10ffff || таңба_коды >= 0xd800 && таңба_коды <= 0xdfff) throw new дұрыс_емес_аргумент_ерекшелік("잘못된 UTF-8");
            if (таңба_коды < 65536) НӘТИЖЕ.append((char)таңба_коды);
            else { таңба_коды -= 65536; НӘТИЖЕ.append((char)(0xd800 | таңба_коды >> 10)); НӘТИЖЕ.append((char)(0xdc00 | таңба_коды & 1023)); }
        }
        return НӘТИЖЕ.toString();
    }
}
