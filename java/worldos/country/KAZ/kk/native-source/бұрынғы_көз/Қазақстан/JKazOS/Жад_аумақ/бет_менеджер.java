package Қазақстан.JKazOS.Жад_аумақ;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB бет_мән 연결과 Жазу 시 복사를 제공한다. */
public final class бет_менеджер {
    public static final int бет_өлшемі = 4096;

    private static final class бет_мән {
        private byte[] деректер = new byte[бет_өлшемі];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class мекенжай_орын {
        private final Map<Integer, бет_мән> бет_кесте = new HashMap<Integer, бет_мән>();
    }

    public мекенжай_орын 새주소공간() {
        return new мекенжай_орын();
    }

    public void карта_бет(мекенжай_орын мекенжай_аумақ, int виртуалды_мекенжай, boolean 쓰기가능) {
        int индекс = 쪽번호(виртуалды_мекенжай);
        бет_мән 새쪽 = new бет_мән();
        새쪽.쓰기가능 = 쓰기가능;
        мекенжай_аумақ.бет_кесте.put(Integer.valueOf(индекс), 새쪽);
    }

    public мекенжай_орын 쓰기시복사복제(мекенжай_орын 원본) {
        мекенжай_орын 복제본 = new мекенжай_орын();
        for (Map.Entry<Integer, бет_мән> енгізу_мән : 원본.бет_кесте.entrySet()) {
            бет_мән 공유쪽 = енгізу_мән.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.бет_кесте.put(енгізу_мән.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(мекенжай_орын мекенжай_аумақ, int виртуалды_мекенжай) {
        бет_мән мақсатты_мән = Табу_бет(мекенжай_аумақ, виртуалды_мекенжай);
        return мақсатты_мән.деректер[Math.floorMod(виртуалды_мекенжай, бет_өлшемі)];
    }

    public void жазу_байт_мән(мекенжай_орын мекенжай_аумақ, int виртуалды_мекенжай, byte мән) {
        int индекс = 쪽번호(виртуалды_мекенжай);
        бет_мән мақсатты_мән = Табу_бет(мекенжай_аумақ, виртуалды_мекенжай);
        if (!мақсатты_мән.쓰기가능) {
            if (!мақсатты_мән.쓰기시복사) {
                throw new IllegalStateException("Оқу 전용 쪽입니다.");
            }
            мақсатты_мән = жасау_Жеке_бет(мекенжай_аумақ, индекс, мақсатты_мән);
        }
        мақсатты_мән.деректер[Math.floorMod(виртуалды_мекенжай, бет_өлшемі)] = мән;
    }

    public void Жеке_ауқым_жазу(мекенжай_орын мекенжай_аумақ, int басы_мекенжай, int Өлшемі) {
        if (Өлшемі < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int тоқтату_мекенжай = Math.addExact(басы_мекенжай, Өлшемі);
        for (int мекенжай = басы_мекенжай; мекенжай < тоқтату_мекенжай; мекенжай = (쪽번호(мекенжай) + 1) * бет_өлшемі) {
            int индекс = 쪽번호(мекенжай);
            бет_мән мақсатты_мән = Табу_бет(мекенжай_аумақ, мекенжай);
            if (мақсатты_мән.쓰기시복사) {
                жасау_Жеке_бет(мекенжай_аумақ, индекс, мақсатты_мән);
            } else {
                мақсатты_мән.쓰기가능 = true;
            }
        }
    }

    public void ауқым_жазу(мекенжай_орын мекенжай_аумақ, int басы_мекенжай, byte[] деректер) {
        for (int индекс = 0; индекс < деректер.length; индекс++) {
            жазу_байт_мән(мекенжай_аумақ, басы_мекенжай + индекс, деректер[индекс]);
        }
    }

    private бет_мән жасау_Жеке_бет(мекенжай_орын мекенжай_аумақ, int индекс, бет_мән 공유쪽) {
        бет_мән Жеке_бет = new бет_мән();
        Жеке_бет.деректер = Arrays.copyOf(공유쪽.деректер, 공유쪽.деректер.length);
        Жеке_бет.쓰기가능 = true;
        Жеке_бет.쓰기시복사 = false;
        공유쪽.참조수--;
        мекенжай_аумақ.бет_кесте.put(Integer.valueOf(индекс), Жеке_бет);
        return Жеке_бет;
    }

    private бет_мән Табу_бет(мекенжай_орын мекенжай_аумақ, int мекенжай) {
        бет_мән мақсатты_мән = мекенжай_аумақ.бет_кесте.get(Integer.valueOf(쪽번호(мекенжай)));
        if (мақсатты_мән == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return мақсатты_мән;
    }

    private int 쪽번호(int мекенжай) {
        if (мекенжай < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return мекенжай / бет_өлшемі;
    }
}

