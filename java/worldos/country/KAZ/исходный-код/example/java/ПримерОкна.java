import русский.свой.Окно;
import русский.свой.Метка;
import русский.свой.текстовое_поле;
import русский.свой.кнопка;
import русский.свой.Событие_Очередь;
import русский.свой.текстовыйВывод;
import русский.свой.실행할일;
import русский.свой.동작받이;
import русский.свой.задача_уведомление;

/** свой 커널의 Swing Окно: русский входные_данные_ЗНАЧЕН → кнопка → файл_сведений_eb81d7d9 текст обновить. */
public class ПримерОкна implements 실행할일, 동작받이 {
    private Окно приветствие_окно;
    private текстовое_поле имя_Поле;
    private Метка приветствие;
    private int приветствие_СЧЁТ;

    public void открыть_окно() {
        приветствие_окно = new Окно("русский Swing", 460, 300);
        приветствие_окно.добавить_элемент(new Метка("Здравствуйте", 20, 20, 420, 28));
        имя_Поле = new текстовое_поле("русский", 20, 64, 420, 30);
        приветствие = new Метка("Здравствуйте", 20, 152, 420, 28);
        приветствие_окно.добавить_элемент(имя_Поле);
        приветствие_окно.добавить_элемент(new кнопка("인사하기", 20, 108, 180, 32, this));
        приветствие_окно.добавить_элемент(приветствие);
        приветствие_окно.добавить_элемент(new Метка("F9 / Shift+Space | X", 20, 204, 420, 28));
        приветствие_окно.выпуск_окно();
        текстовыйВывод.запись_линия("GUI 예제 Подготовить: ПримерОкна");
    }

    public void 인사하기() {
        приветствие_СЧЁТ++;
        приветствие.запись_SMS("Здравствуйте, " + имя_Поле.чтение_SMS() + "님! (" + приветствие_СЧЁТ + ")");
        текстовыйВывод.запись_линия("GUI приветствие_ae353e94: " + приветствие.чтение_SMS());
    }

    public void Выполнить() { открыть_окно(); }
    public void получить_задача(задача_уведомление уведомление) {
        текстовыйВывод.запись_линия("Действие уведомление: " + уведомление.명령글());
        인사하기();
    }
    public static void запустить() {
        Событие_Очередь.나중에실행(new ПримерОкна());
    }
}
