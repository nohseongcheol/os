    private static void тест_Память(Ядро ядро_ЗНАЧЕН) {
        Память_менеджер менеджер_ЗНАЧЕН = ядро_ЗНАЧЕН.Память_регион();
        int 첫주소 = менеджер_ЗНАЧЕН.정렬할당(100, 64);
        проверять((첫주소 & 63) == 0, "выровнять_ЗНАЧЕН выделить_Память");
        менеджер_ЗНАЧЕН.запись_байт_ЗНАЧЕН(첫주소, (byte) 0x5a);
        проверять(менеджер_ЗНАЧЕН.чтение_байт_ЗНАЧЕН(첫주소) == (byte) 0x5a, "물리 Память_регион 읽고 Запись");
        int 사용전 = менеджер_ЗНАЧЕН.사용크기();
        менеджер_ЗНАЧЕН.выпуск_Память_293182ec(첫주소);
        проверять(менеджер_ЗНАЧЕН.사용크기() < 사용전, "Память_регион выпуск_Память_293182ec");
    }

    private static void 쪽관리시험(Ядро ядро_ЗНАЧЕН) {
        страница_менеджер менеджер_ЗНАЧЕН = ядро_ЗНАЧЕН.쪽관리();
        страница_менеджер.диапазон_адресов родительский_место = менеджер_ЗНАЧЕН.새주소공간();
        менеджер_ЗНАЧЕН.MAP_страница(родительский_место, 0x1000, true);
        менеджер_ЗНАЧЕН.запись_байт_ЗНАЧЕН(родительский_место, 0x1010, (byte) 7);
        страница_менеджер.диапазон_адресов ребенок_место = менеджер_ЗНАЧЕН.клон_копирование_при_записи(родительский_место);
        менеджер_ЗНАЧЕН.запись_байт_ЗНАЧЕН(ребенок_место, 0x1010, (byte) 9);
        проверять(менеджер_ЗНАЧЕН.чтение_байт_ЗНАЧЕН(родительский_место, 0x1010) == 7, "Запись 시 экземпляр_ЗНАЧЕН родительский_ЗНАЧЕН 격리");
        проверять(менеджер_ЗНАЧЕН.чтение_байт_ЗНАЧЕН(ребенок_место, 0x1010) == 9, "Запись 시 экземпляр_ЗНАЧЕН ребенок_ЗНАЧЕН Запись");
    }

    private static void 파일과과정시험(Ядро ядро_ЗНАЧЕН) {
        byte[] контент_ЗНАЧЕН = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        ядро_ЗНАЧЕН.файловая_система().добавить_файл("испытания", контент_ЗНАЧЕН);
        Процесс_ЗНАЧЕН родительский_ЗНАЧЕН = ядро_ЗНАЧЕН.첫과정();
        системный_вызов 호출 = ядро_ЗНАЧЕН.системный_вызов();
        int дескриптор_ввод = 호출.Открыть(родительский_ЗНАЧЕН, "/испытания", системный_вызов.нередактируемый_флаг);
        проверять(дескриптор_ввод >= 3, "файл Открыть");

        byte[] получить_цель = new byte[контент_ЗНАЧЕН.length];
        проверять(호출.Чтение(родительский_ЗНАЧЕН, дескриптор_ввод, получить_цель, получить_цель.length) == контент_ЗНАЧЕН.length, "файл Чтение");
        проверять(Arrays.equals(контент_ЗНАЧЕН, получить_цель), "файл контент_ЗНАЧЕН");
        проверять(호출.переместить_позиция(родительский_ЗНАЧЕН, дескриптор_ввод, 0, системный_вызов.ПОИСК_Пуск) == 0, "файл позиция переместить_ЗНАЧЕН");

        int 복제서술자 = 호출.дубликат_дескриптор(родительский_ЗНАЧЕН, дескриптор_ввод);
        проверять(복제서술자 >= 0, "дескриптор_ввод клон_ЗНАЧЕН");
        Процесс_ЗНАЧЕН ребенок_ЗНАЧЕН = 호출.клон_Процесс(родительский_ЗНАЧЕН);
        проверять(ребенок_ЗНАЧЕН.идентификатор_ЗНАЧЕН() != родительский_ЗНАЧЕН.идентификатор_ЗНАЧЕН(), "Процесс_ЗНАЧЕН идентификатор_ЗНАЧЕН 분리");
        проверять(ребенок_ЗНАЧЕН.родительский_идентификатор() == родительский_ЗНАЧЕН.идентификатор_ЗНАЧЕН(), "родительский_ЗНАЧЕН Процесс_ЗНАЧЕН идентификатор_ЗНАЧЕН");
        проверять(호출.Закрыть(ребенок_ЗНАЧЕН, дескриптор_ввод) == 0 && родительский_ЗНАЧЕН.файл_дескриптор().ИТ_службы_открыть(дескриптор_ввод), "ребенок_ЗНАЧЕН Закрыть 격리");

        int Назад_элемент = 호출.увеличение_программа_останов(родительский_ЗНАЧЕН, 8192);
        проверять(Назад_элемент == 0x06000000, "программа_f5044b9b 끝 늘리기");
        проверять(родительский_ЗНАЧЕН.программа_останов() == 0x06002000, "программа_f5044b9b 끝 반영");
        проверять(ребенок_ЗНАЧЕН.программа_останов() == 0x06000000, "과정별 программа_f5044b9b 끝 격리");

        ребенок_ЗНАЧЕН.Выход_программа(7);
        проверять(호출.자식기다리기(родительский_ЗНАЧЕН, ребенок_ЗНАЧЕН.идентификатор_ЗНАЧЕН(), false) == (7 << 8), "ребенок_ЗНАЧЕН Выход_программа 기다리기");
        проверять(호출.접근가능("испытания", 1) == -13, "실행 Полномочие_ЗНАЧЕН отклонить_ЗНАЧЕН");
        проверять(호출.ИД_пользователя() == 0 && 호출.идентификатор_группы() == 0, "사용자와 무리 идентификатор_ЗНАЧЕН");
        проверять("/".equals(호출.текущий_список_задач(2)) && 호출.перейти_список_задач("/") == 0, "текущий_товар 작업 ввод_Список");
        проверять(호출.ИТ_службы_Терминал(родительский_ЗНАЧЕН, 1), "표준 текстовыйВывод 단말");
        проверять("JKazOS".equals(호출.система_Сведения().система_имя()), "операционная_система_ЗНАЧЕН msinfo32_exe");
    }

