#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 બાઇટ_મૂલ્ય 위치로 자체 C 이름을 옮기는 일회성 이행 ઉપકરણો.

외부 구조체의 멤버, સ્ટ્રિંગ_મૂલ્ય, C 표준 ફંક્શંસ_મૂલ્ય, 이식 규약은 보존한다.
입력은 પરિવર્તન_કરો_મૂલ્ય 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

પ્રોજેક્ટ_રૂટ = Path(__file__).resolve().parents[1]

def અમલ_કરો_આદેશ():
    분석 = json.loads((પ્રોજેક્ટ_રૂટ/'build/한국어화/시언어분석.json').read_text())
    if 분석['ભૂલ']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    નામ_કોષ્ટક = json.loads((પ્રોજેક્ટ_રૂટ/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((પ્રોજેક્ટ_રૂટ/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:નામ_કોષ્ટક[પ્રવેશ_મૂલ્ય['નામ']] for 고유,પ્રવેશ_મૂલ્ય in 선언표.items()
                if પ્રવેશ_મૂલ્ય['નામ'] in નામ_કોષ્ટક and પ્રવેશ_મૂલ્ય['નામ'] not in 규격}
    કનેક્શન_કોષ્ટક = {પ્રવેશ_મૂલ્ય['નામ']:નામ_કોષ્ટક[પ્રવેશ_મૂલ્ય['નામ']] for પ્રવેશ_મૂલ્ય in 선언표.values()
              if પ્રવેશ_મૂલ્ય.get('સંપર્ક_કરો')==4 and પ્રવેશ_મૂલ્ય['종류'] in (8,9)
              and પ્રવેશ_મૂલ્ય['નામ'] in નામ_કોષ્ટક and પ્રવેશ_મૂલ્ય['નામ'] not in 규격}
    # જનરેટ_કરો AOT C·어셈블리·공개 SDK가 공유하는 바이너리 સંપર્ક_કરો 이름만 유지한다.
    머리 = ['/* ગુજરાતી સ્રોત_ટ્રી 이름과 기존 મશીન સંપર્ક_કરો કામ_મૂલ્ય. 자동 જનરેટ_કરો: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(કનેક્શન_કોષ્ટક.items())]
    머리 += ['#endif','']
    (પ્રોજેક્ટ_રૂટ/'명명/기계연결이름.h').write_text('\n'.join(머리))
    પરિવર્તનો_સૂચી = defaultdict(dict)
    for ફાઈલ,ઑફસેટ_મૂલ્ય,નામ,고유 in 분석['સંદર્ભ']:
        if 고유 in 바꿀선언:
            પરિવર્તનો_સૂચી[ફાઈલ][ઑફસેટ_મૂલ્ય] = (નામ,바꿀선언[고유])
    લૉગ_પંક્તિ = ['ફાઈલ\t원래바이트위치\t이전이름\t한국어이름']
    અવગણો_મૂલ્ય = []
    for ફાઈલ,પરિવર્તન_કરો_મૂલ્ય in પરિવર્તનો_સૂચી.items():
        પથ = Path(ફાઈલ); 원본 = પથ.read_bytes(); ડેટા = 원본
        for ઑફસેટ_મૂલ્ય,(옛이름,새이름) in sorted(પરિવર્તન_કરો_મૂલ્ય.items(),reverse=True):
            끝 = ઑફસેટ_મૂલ્ય+len(옛이름.encode())
            if 원본[ઑફસેટ_મૂલ્ય:끝] != 옛이름.encode():
                અવગણો_મૂલ્ય.append((str(પથ.relative_to(પ્રોજેક્ટ_રૂટ)),ઑફસેટ_મૂલ્ય,옛이름));continue
            ડેટા = ડેટા[:ઑફસેટ_મૂલ્ય]+새이름.encode()+ડેટા[끝:]
            લૉગ_પંક્તિ.append('{}\t{}\t{}\t{}'.format(પથ.relative_to(પ્રોજેક્ટ_રૂટ),ઑફસેટ_મૂલ્ય,옛이름,새이름))
        પથ.write_bytes(ડેટા)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    મૅક્રો_મૂલ્ય = {પ્રવેશ_મૂલ્ય['નામ']:નામ_કોષ્ટક[પ્રવેશ_મૂલ્ય['નામ']] for પ્રવેશ_મૂલ્ય in 선언표.values()
              if પ્રવેશ_મૂલ્ય['종류']==501 and પ્રવેશ_મૂલ્ય['નામ'] in નામ_કોષ્ટક and પ્રવેશ_મૂલ્ય['નામ'] not in 규격}
    for પથ in sorted({Path(પ્રવેશ_મૂલ્ય['ફાઈલ']) for પ્રવેશ_મૂલ્ય in 선언표.values()}):
        લાઇન_સૂચી = પથ.read_text().splitlines(True); 이어짐 = False
        for અનુક્રમણિકા,લાઇન in enumerate(લાઇન_સૂચી):
            전처리 = 이어짐 or bool(re.match(r'\s*#',લાઇન))
            이어짐 = 전처리 and લાઇન.rstrip().endswith('\\')
            if 전처리:
                લુકઅપ_કોષ્ટક = નામ_કોષ્ટક if re.match(r'\s*#\s*define\b',લાઇન) or 이어짐 else મૅક્રો_મૂલ્ય
                લાઇન_સૂચી[અનુક્રમણિકા] = 낱말.sub(lambda 맞음: લુકઅપ_કોષ્ટક.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],લાઇન)
        પથ.write_text(''.join(લાઇન_સૂચી))
    # 각 자체 અનુવાદ_કરો_સ્રોત 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for પથ in sorted({Path(પ્રવેશ_મૂલ્ય['ફાઈલ']) for પ્રવેશ_મૂલ્ય in 선언표.values()}):
        if પથ.suffix not in ('.c','.cpp'):continue
        પીઅર_મૂલ્ય = '../' * len(પથ.relative_to(પ્રોજેક્ટ_રૂટ).parts[:-1]) + '명명/기계연결이름.h'
        પથ.write_text('#include "'+પીઅર_મૂલ્ય+'"\n'+પથ.read_text())
    (પ્રોજેક્ટ_રૂટ/'명명/시언어이름대응.tsv').write_text('\n'.join(લૉગ_પંક્તિ)+'\n')
    (પ્રોજેક્ટ_રૂટ/'build/한국어화/전처리참조.json').write_text(json.dumps(અવગણો_મૂલ્ય,ensure_ascii=False,indent=2)+'\n')
    print('પરિવર્તન_કરો_મૂલ્ય',len(લૉગ_પંક્તિ)-1,'전처리 재검토',len(અવગણો_મૂલ્ય),'મશીન સંપર્ક_કરો',len(કનેક્શન_કોષ્ટક))

if __name__=='__main__': અમલ_કરો_આદેશ()
