        ચકાસવું(બાળક_મૂલ્ય.ઓળખકર્તા_મૂલ્ય() != 부모.ઓળખકર્તા_મૂલ્ય(), "પ્રક્રિયા_મૂલ્ય ઓળખકર્તા_મૂલ્ય 분리");
        ચકાસવું(બાળક_મૂલ્ય.부모식별자() == 부모.ઓળખકર્તા_મૂલ્ય(), "부모 પ્રક્રિયા_મૂલ્ય ઓળખકર્તા_મૂલ્ય");
        ચકાસવું(호출.બંધ_કરો(બાળક_મૂલ્ય, 서술자) == 0 && 부모.파일서술자().ઇન્ટરમિટેંટ_બનાવો(서술자), "બાળક_મૂલ્ય બંધ_કરો 격리");

