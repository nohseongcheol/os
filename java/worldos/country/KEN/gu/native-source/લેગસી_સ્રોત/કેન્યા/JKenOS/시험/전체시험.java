        ચકાસવું(서술자 >= 3, "ફાઈલ ખોલો");

        byte[] 받을곳 = new byte[સામગ્રી_મૂલ્ય.length];
        ચકાસવું(호출.વાંચો(부모, 서술자, 받을곳, 받을곳.length) == સામગ્રી_મૂલ્ય.length, "ફાઈલ વાંચો");
        ચકાસવું(Arrays.equals(સામગ્રી_મૂલ્ય, 받을곳), "ફાઈલ સામગ્રી_મૂલ્ય");
