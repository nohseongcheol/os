        ચકાસવું(호출.자식기다리기(부모, બાળક_મૂલ્ય.ઓળખકર્તા_મૂલ્ય(), false) == (7 << 8), "બાળક_મૂલ્ય પ્રસ્થાન_એપ્લિકેશન 기다리기");
