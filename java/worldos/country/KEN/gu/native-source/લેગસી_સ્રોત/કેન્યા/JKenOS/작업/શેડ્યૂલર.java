package કેન્યા.JKenOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import કેન્યા.JKenOS.기억공간.પેજ_પ્રબંધક;
import કેન્યા.JKenOS.ફાઇલ_સિસ્ટમ.파일서술자표;

/** પ્રક્રિયા_મૂલ્ય 식별자와 라운드로빈 તૈયાર_કરો 대기열을 관리한다. */
public final class શેડ્યૂલર {
    private final પેજ_પ્રબંધક 쪽관리;
    private final Map<Integer, પ્રક્રિયા_મૂલ્ય> પ્રક્રિયા_સૂચી = new HashMap<Integer, પ્રક્રિયા_મૂલ્ય>();
    private final Queue<પ્રક્રિયા_મૂલ્ય> 준비대기열 = new ArrayDeque<પ્રક્રિયા_મૂલ્ય>();
    private int આગલું_ઓળખકર્તા = 1;

    public શેડ્યૂલર(પેજ_પ્રબંધક 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public પ્રક્રિયા_મૂલ્ય 첫과정(파일서술자표 파일서술자) {
        પ્રક્રિયા_મૂલ્ય 새과정 = new પ્રક્રિયા_મૂલ્ય(ફાળવો_ઓળખકર્તા(), 0, 쪽관리.새주소공간(), 파일서술자);
        પ્રક્રિયા_સૂચી.put(Integer.valueOf(새과정.ઓળખકર્તા_મૂલ્ય()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public પ્રક્રિયા_મૂલ્ય 복제(પ્રક્રિયા_મૂલ્ય 부모) {
        પ્રક્રિયા_મૂલ્ય બાળક_મૂલ્ય = new પ્રક્રિયા_મૂલ્ય(
                ફાળવો_ઓળખકર્તા(),
                부모.ઓળખકર્તા_મૂલ્ય(),
                쪽관리.쓰기시복사복제(부모.સરનામું_જગ્યા()),
                부모.파일서술자().복제());
        બાળક_મૂલ્ય.સેટ_એપ્લિકેશન_બ્રેક(부모.એપ્લિકેશન_બ્રેક());
        પ્રક્રિયા_સૂચી.put(Integer.valueOf(બાળક_મૂલ્ય.ઓળખકર્તા_મૂલ્ય()), બાળક_મૂલ્ય);
        준비대기열.offer(બાળક_મૂલ્ય);
        return બાળક_મૂલ્ય;
    }

    public પ્રક્રિયા_મૂલ્ય આગલું_પ્રક્રિયા() {
        int 검사수 = 준비대기열.size();
        for (int અનુક્રમણિકા = 0; અનુક્રમણિકા < 검사수; અનુક્રમણિકા++) {
            પ્રક્રિયા_મૂલ્ય આગલું_આઇટમ = 준비대기열.poll();
            if (આગલું_આઇટમ != null && (આગલું_આઇટમ.સ્થિતિ_મૂલ્ય_e10195a1() == પ્રક્રિયા_સ્થિતિ.તૈયાર_કરો || આગલું_આઇટમ.સ્થિતિ_મૂલ્ય_e10195a1() == પ્રક્રિયા_સ્થિતિ.અમલ_કરો_આદેશ)) {
                આગલું_આઇટમ.સેટ_સ્થિતિ(પ્રક્રિયા_સ્થિતિ.અમલ_કરો_આદેશ);
                준비대기열.offer(આગલું_આઇટમ);
                return આગલું_આઇટમ;
            }
        }
        return null;
    }

    public int 자식기다리기(પ્રક્રિયા_મૂલ્ય 부모, int બાળક_ઓળખકર્તા, boolean 기다리지않음) {
        for (પ્રક્રિયા_મૂલ્ય 후보 : પ્રક્રિયા_સૂચી.values()) {
            if (후보.부모식별자() != 부모.ઓળખકર્તા_મૂલ્ય()) {
                continue;
            }
            if (બાળક_ઓળખકર્તા > 0 && 후보.ઓળખકર્તા_મૂલ્ય() != બાળક_ઓળખકર્તા) {
                continue;
            }
            if (후보.સ્થિતિ_મૂલ્ય_e10195a1() == પ્રક્રિયા_સ્થિતિ.પ્રસ્થાન_એપ્લિકેશન) {
                int પરિમાણ = (후보.종료값() & 0xff) << 8;
                પ્રક્રિયા_સૂચી.remove(Integer.valueOf(후보.ઓળખકર્તા_મૂલ્ય()));
                return પરિમાણ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public પ્રક્રિયા_મૂલ્ય શોધો_પ્રક્રિયા(int ઓળખકર્તા_મૂલ્ય) {
        return પ્રક્રિયા_સૂચી.get(Integer.valueOf(ઓળખકર્તા_મૂલ્ય));
    }

    private int ફાળવો_ઓળખકર્તા() {
        return આગલું_ઓળખકર્તા++;
    }
}
