#include "통신규약.h"
static 인터넷통신주소 ਪਤਾ(unsigned ਪੋਰਟ_ਕੀਮਤ) {
    인터넷통신주소 ਕੀਮਤ = {}; ਕੀਮਤ.ਪਤਾ_ਪਰਿਵਾਰ = ਬੱਦਲ_ਪਰਿਵਾਰ;
    ਕੀਮਤ.접속번호 = 망차례짧은수(ਪੋਰਟ_ਕੀਮਤ); ਕੀਮਤ.ਇੰਟਰਨੈਟ_ਪਤਾ.ਪਤਾ_ਕੀਮਤ = ਨੈਟਵਰਕ_ਪੂਰਣ_ਅੰਕ(되돌림주소); return ਕੀਮਤ;
}
extern "C" int ਸੁਰੂ_ਉਪਭੋਗਤਾ_ਐਪਲੀਕੇਸ਼(int) {
    int 보내는곳 = 통신종단점만들기(ਬੱਦਲ_ਪਰਿਵਾਰ, 전문통신, 0);
    int 받는곳 = 통신종단점만들기(ਬੱਦਲ_ਪਰਿਵਾਰ, 전문통신, 전문전송규약);
    if (보내는곳 < 0 || 받는곳 < 0) return 1;
    인터넷통신주소 도착 = ਪਤਾ(7777), 출발 = ਪਤਾ(7778), 보낸주소 = {};
    통신주소길이형 ਪਤਾ_ਲੰਬਾਈ = sizeof(보낸주소);
    if (ਜ਼ਿਲਦਬੰਦੀ_ਪਤਾ(받는곳, (통신주소 *)&도착, sizeof(도착))) return 2;
    if (ਜ਼ਿਲਦਬੰਦੀ_ਪਤਾ(보내는곳, (통신주소 *)&도착, sizeof(도착)) != -1 || 오류번호 != 98) return 3;
    if (ਜ਼ਿਲਦਬੰਦੀ_ਪਤਾ(보내는곳, (통신주소 *)&출발, sizeof(출발))) return 4;
    static const char ਤਤਕਰਾ_ਕੀਮਤ[] = "한글 UDP loopback 😀";
    char 받은값[64] = {};
    if (자료전문보내기(보내는곳, ਤਤਕਰਾ_ਕੀਮਤ, sizeof(ਤਤਕਰਾ_ਕੀਮਤ), 0, (통신주소 *)&도착, sizeof(도착)) != sizeof(ਤਤਕਰਾ_ਕੀਮਤ)) return 5;
    if (자료전문받기(받는곳, (void *)ਤਤਕਰਾ_ਕੀਮਤ, sizeof(ਤਤਕਰਾ_ਕੀਮਤ), 0, 0, 0) != -1 || 오류번호 != 14) return 6;
    if (자료전문받기(받는곳, 받은값, sizeof(받은값), 0, (통신주소 *)&보낸주소, &ਪਤਾ_ਲੰਬਾਈ) != sizeof(ਤਤਕਰਾ_ਕੀਮਤ)) return 7;
    if (ਪਤਾ_ਲੰਬਾਈ != sizeof(보낸주소) || 장치차례짧은수(보낸주소.접속번호) != 7778 || ਤਜਵੀਜ_ਕ੍ਰਮ_ਪੂਰਣ_ਅੰਕ(보낸주소.ਇੰਟਰਨੈਟ_ਪਤਾ.ਪਤਾ_ਕੀਮਤ) != 되돌림주소) return 8;
    for (unsigned 순번 = 0; 순번 < sizeof(ਤਤਕਰਾ_ਕੀਮਤ); 순번++) if (받은값[순번] != ਤਤਕਰਾ_ਕੀਮਤ[순번]) return 9;
    if (자료전문받기(받는곳, 받은값, sizeof(받은값), 0, 0, 0) != -1 || 오류번호 != 11) return 10;
    if (자료전문보내기(받는곳, 받은값, sizeof(ਤਤਕਰਾ_ਕੀਮਤ), 0, (통신주소 *)&보낸주소, sizeof(보낸주소)) != sizeof(ਤਤਕਰਾ_ਕੀਮਤ)) return 11;
    if (자료전문받기(보내는곳, 받은값, 4, 0, 0, 0) != 4) return 12;
    if (자료전문받기(보내는곳, 받은값, 4, 0, 0, 0) != -1 || 오류번호 != 11) return 13;
    for (int 순번 = 0; 순번 < 4; 순번++) if (자료전문보내기(보내는곳, ਤਤਕਰਾ_ਕੀਮਤ, sizeof(ਤਤਕਰਾ_ਕੀਮਤ), 0, (통신주소 *)&도착, sizeof(도착)) != sizeof(ਤਤਕਰਾ_ਕੀਮਤ)) return 14;
    if (자료전문보내기(보내는곳, ਤਤਕਰਾ_ਕੀਮਤ, sizeof(ਤਤਕਰਾ_ਕੀਮਤ), 0, (통신주소 *)&도착, sizeof(도착)) != -1 || 오류번호 != 11) return 15;
    for (int 순번 = 0; 순번 < 4; 순번++) if (자료전문받기(받는곳, 받은값, sizeof(받은값), 0, 0, 0) != sizeof(ਤਤਕਰਾ_ਕੀਮਤ)) return 16;
    if (자료전문보내기(보내는곳, 0, 0, 0, (통신주소 *)&도착, sizeof(도착)) != 0 ||
        자료전문받기(받는곳, 0, 0, 0, 0, 0) != 0) return 21;
    도착.ਇੰਟਰਨੈਟ_ਪਤਾ.ਪਤਾ_ਕੀਮਤ = ਨੈਟਵਰਕ_ਪੂਰਣ_ਅੰਕ(0x08080808);
    if (자료전문보내기(보내는곳, ਤਤਕਰਾ_ਕੀਮਤ, sizeof(ਤਤਕਰਾ_ਕੀਮਤ), 0, (통신주소 *)&도착, sizeof(도착)) != -1 || 오류번호 != 101) return 17;
    if (통신종단점만들기(ਬੱਦਲ_ਪਰਿਵਾਰ, ਸਟ੍ਰੀਮ_ਨੈਟਵਰਕ, 전문전송규약) != -1 || 오류번호 != 93) return 18;
    ਪਤਾ_ਲੰਬਾਈ = sizeof(보낸주소);
    if (통신주소읽기(받는곳, (통신주소 *)&보낸주소, &ਪਤਾ_ਲੰਬਾਈ) || 장치차례짧은수(보낸주소.접속번호) != 7777) return 19;
    if (ਬੰਦ_ਕਰੋ_ਲਿਖਤ_ਪੱਤਰ(받는곳) || ਬੰਦ_ਕਰੋ_ਲਿਖਤ_ਪੱਤਰ(받는곳) != -1 || 오류번호 != 9) return 20;
    // 보내는곳은 열어 둔다: ਨਿਕਾਸ_ਐਪਲੀਕੇਸ਼ 시 프로세스별 socket 정리를 검사한다.
    static const char 완료[] = "EL0 UDP LOOPBACK PASS (external network unavailable)\n";
    ਲਿੱਖੋ_ਲਿਖਤ_ਪੱਤਰ_ਸਮੱਗਰੀ(1, 완료, sizeof(완료) - 1);
    return 0;
}
