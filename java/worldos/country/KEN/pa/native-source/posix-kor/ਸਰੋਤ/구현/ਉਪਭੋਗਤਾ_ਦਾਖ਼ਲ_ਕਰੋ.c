#include "호출경계.h"
extern int main(int 인수개수, char **ਦਲੀਲ_ਸੂਚੀ);
static char ਦਲੀਲ_ਮੈਮਰੀ[2048];
static char *ਦਲੀਲ_ਸੂਚੀ[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼ 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    ਦਲੀਲ_ਸੂਚੀ[0] = "jkoros-app";
    int ਸਥਿਤੀ = 0;
    for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 개수; ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
        const int *원본 = (const int *)jkoros_syscall(3, ਅਨੁਕ੍ਰਮਣਿਕਾ, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        ਦਲੀਲ_ਸੂਚੀ[ਅਨੁਕ੍ਰਮਣਿਕਾ + 1] = ਦਲੀਲ_ਮੈਮਰੀ + ਸਥਿਤੀ;
        for (int ਸਲੌਟ_ਦਾਖਲਾ = 0; ਸਲੌਟ_ਦਾਖਲਾ < 원본[0]; ਸਲੌਟ_ਦਾਖਲਾ++) {
            if (ਸਥਿਤੀ >= 2047) return 126;
            ਦਲੀਲ_ਮੈਮਰੀ[ਸਥਿਤੀ++] = 원본[ਸਲੌਟ_ਦਾਖਲਾ + 1];
        }
        ਦਲੀਲ_ਮੈਮਰੀ[ਸਥਿਤੀ++] = 0;
    }
    ਦਲੀਲ_ਸੂਚੀ[개수 + 1] = 0;
    return main(개수 + 1, ਦਲੀਲ_ਸੂਚੀ);
}
