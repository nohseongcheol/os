import 한국어.자체.туташуу;
import 한국어.자체.실행인수;
import 한국어.자체.전문통로;
import 한국어.자체.문자;
import 한국어.자체.Чыгыш;
import 한국어.자체.검사;
import 한국어.자체.입력흐름;
import 한국어.자체.입출력예외;

public class 네트워크예제 {
    public static void Жүргүзүү() throws 입출력예외 {
        // кабылдоо: python3 Куралдар/예제되돌림.py --tcp-port 9000 --udp-port 9001
        туташуу Туташуу = туташуу.Ачуу("10.0.2.2", 문자.талдоо_бүтүн_сан(실행인수.Текст(0)));
        try {
            Туташуу.대기시간(700);
            byte[] билдирүү = 문자.부호화("JAVA TCP ky\n");
            Туташуу.Чыгыш().Жазуу(билдирүү);
            입력흐름 입력 = Туташуу.입력();
            for (int 수 = 0; 수 < 문자.바이트수(билдирүү); 수++) {
                검사.참인지(입력.Окуу() == (билдирүү[수] & 255), "TCP жооп_берүү 불일치");
            }
        } finally { Туташуу.Жабуу(); }
        전문통로 종단 = 전문통로.Ачуу(0);
        try {
            종단.대기시간(700);
            종단.жөнөтүү("10.0.2.2", 문자.талдоо_бүтүн_сан(실행인수.Текст(1)), "JAVA UDP ky");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP ky"), "UDP жооп_берүү 불일치");
        } finally { 종단.Жабуу(); }
        Чыгыш.жазуу_сап("JAVA 네트워크 тууралыгын_аныктоо: TCP UDP ky");
    }
}
