/** PCI RTL8139 (10ec:8139), 단일 жөнөтүү_маани 버퍼와 8KiB 수신 цикл_маани. 인터럽트 대신 폴링한다. */
public final class Желе_драйвер {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] түзмөк_дарек = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int Турган_жери) {
        түзмөк_маани.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | Турган_жери);
        return түзмөк_маани.입출력정수읽기(0xcfc);
    }

    static boolean Даярдоо() {
        int 장치번호 = -1;
        for (int индекс = 0; индекс < 32; индекс++) {
            if (설정읽기(индекс, 0) == 0x813910ec) { 장치번호 = индекс; break; }
        }
        if (장치번호 < 0) return false;
        int жарыяланбаган_маани = 설정읽기(장치번호, 0x10);
        if ((жарыяланбаган_маани & 1) == 0 || (жарыяланбаган_маани & 0xfffffffc) < 0x100 || (жарыяланбаган_маани & 0xfffffffc) > 65535) return false;
        입출력기준주소 = жарыяланбаган_маани & 0xfffc;
        int Команда = 설정읽기(장치번호, 4);
        түзмөк_маани.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        түзмөк_маани.입출력짧은수쓰기(0xcfc, Команда | 5); // I/O 및 bus master Уруксат_берүү_маани, PCI абал_маани 비트는 건드리지 않음
        түзмөк_маани.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!нөлгө_келтирүү_маани()) { 입출력기준주소 = 0; return false; }
        for (int индекс = 0; индекс < 6; индекс++) түзмөк_дарек[индекс] = түзмөк_маани.입출력바이트읽기(입출력기준주소 + индекс);
        return true;
    }

    static boolean нөлгө_келтирүү_маани() {
        түзмөк_маани.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int Жүргүзүү = түзмөк_маани.밀리초();
        while ((түзмөк_маани.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (түзмөк_маани.밀리초() - Жүргүзүү > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        түзмөк_маани.입출력정수쓰기(입출력기준주소 + 0x30, түзмөк_маани.Желе_эс());
        for (int индекс = 0; индекс < 4; индекс++) түзмөк_маани.입출력정수쓰기(입출력기준주소 + 0x20 + индекс * 4, түзмөк_маани.Желе_эс() + 12288);
        түзмөк_маани.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        түзмөк_маани.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        түзмөк_маани.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        түзмөк_маани.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/방송, wrap 연속 сактагыч_маани, 8KiB
        түзмөк_маани.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int жөнөтүү(int[] берилмелер, int узундук_маани) {
        if (입출력기준주소 == 0) return -19;
        if (узундук_маани < 14 || узундук_маани > 1514) return -90;
        int абал_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int Жүргүзүү = түзмөк_маани.밀리초();
        while ((түзмөк_маани.입출력정수읽기(абал_порт) & 0x2000) == 0)
            if (түзмөк_маани.밀리초() - Жүргүзүү > 100) return -110;
        int Өлчөмү = узундук_маани < 60 ? 60 : узундук_маани;
        for (int индекс = 0; индекс < Өлчөмү; индекс++)
            түзмөк_маани.жазуу_эс(түзмөк_маани.Желе_эс() + 12288 + индекс, индекс < узундук_маани ? берилмелер[индекс] : 0);
        түзмөк_маани.입출력정수쓰기(абал_порт, Өлчөмү | 0x00080000);
        Жүргүзүү = түзмөк_маани.밀리초();
        while ((түзмөк_маани.입출력정수읽기(абал_порт) & 0xe0008000) == 0)
            if (түзмөк_маани.밀리초() - Жүргүзүү > 100) return -110;
        if ((түзмөк_маани.입출력정수읽기(абал_порт) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return узундук_маани;
    }

    static int 받기(int[] берилмелер) {
        if (입출력기준주소 == 0) return 0;
        if ((түзмөк_маани.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!нөлгө_келтирүү_маани()) 입출력기준주소 = 0;
            return 0;
        }
        if ((түзмөк_маани.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = түзмөк_маани.Желе_эс() + 수신위치;
        int абал_маани = 실행관리.짧은수(머리), Өлчөмү = 실행관리.짧은수(머리 + 2);
        if (Өлчөмү == 0xfff0) return 0; // DMA 진행 중
        if (Өлчөмү < 4 || Өлчөмү > 1518) {
            오류수++;
            if (!нөлгө_келтирүү_маани()) 입출력기준주소 = 0;
            return 0;
        }
        int узундук_маани = Өлчөмү - 4;
        if ((абал_маани & 1) != 0) {
            for (int индекс = 0; индекс < узундук_маани; индекс++) берилмелер[индекс] = түзмөк_маани.기억읽기(머리 + 4 + индекс);
            수신수++;
        } else { узундук_маани = 0; 오류수++; }
        수신위치 = (수신위치 + Өлчөмү + 4 + 3) & ~3;
        수신위치 &= 8191;
        түзмөк_маани.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        түзмөк_маани.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return узундук_маани;
    }
}
