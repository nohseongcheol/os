/** 최대 Өлчөмү/홀수 узундук_маани 데이터그램으로 актуалдуу_берилмелер RTL8139 수신 цикл_маани 순환을 시험한다. */
public final class Желе_цикл {
    public static int Жүргүзүү() {
        if (колдонуучу.인수개수() != 1) { колдонуучу.Жазуу("Usage: run stress PORT\n"); return 2; }
        String Текст = колдонуучу.인수(0);
        int порт_маани = 0;
        for (int индекс = 0; индекс < Текст.length(); индекс++) {
            if (Текст.charAt(индекс) < '0' || Текст.charAt(индекс) > '9' || порт_маани > 6553) return 2;
            порт_маани = порт_маани * 10 + Текст.charAt(индекс) - '0';
        }
        if (порт_маани < 1 || порт_маани > 65535) return 2;
        int тутка_маани = колдонуучу.ачуу_Желе(0);
        if (тутка_маани < 0) return 3;
        int[] берилмелер = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int узундук_маани = 1024 - (회차 & 1);
            for (int индекс = 0; индекс < узундук_маани; индекс++) берилмелер[индекс] = (индекс + 회차) & 255;
            if (колдонуучу.жөнөтүү_берилмелер(тутка_маани, 0x0a000202, порт_маани, берилмелер, узундук_маани) != узундук_маани) return 4;
            if (колдонуучу.자료받기(тутка_маани, берилмелер, 300) != узундук_маани) return 5;
            for (int индекс = 0; индекс < узундук_маани; индекс++) if (берилмелер[индекс] != ((индекс + 회차) & 255)) return 6;
        }
        колдонуучу.жабуу_Желе(тутка_маани);
        колдонуучу.Жазуу("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
