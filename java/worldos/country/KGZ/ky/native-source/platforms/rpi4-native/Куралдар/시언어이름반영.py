#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 байт_маани 위치로 자체 C 이름을 옮기는 일회성 이행 Куралдар.

외부 구조체의 멤버, сап_маани, C 표준 функция_маани, 이식 규약은 보존한다.
입력은 өзгөртүү_маани 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def аткаруу_буйрук():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['Ката']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    аты_жадыбал = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {ОКШОШТУКЖОК_маани:аты_жадыбал[киргизме_жазуу_маани['Аты']] for ОКШОШТУКЖОК_маани,киргизме_жазуу_маани in 선언표.items()
                if киргизме_жазуу_маани['Аты'] in аты_жадыбал and киргизме_жазуу_маани['Аты'] not in 규격}
    туташуу_жадыбал = {киргизме_жазуу_маани['Аты']:аты_жадыбал[киргизме_жазуу_маани['Аты']] for киргизме_жазуу_маани in 선언표.values()
              if киргизме_жазуу_маани.get('Туташуу')==4 and киргизме_жазуу_маани['종류'] in (8,9)
              and киргизме_жазуу_маани['Аты'] in аты_жадыбал and киргизме_жазуу_маани['Аты'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 Туташуу 이름만 유지한다.
    머리 = ['/* 한국어 башат_дарак 이름과 기존 машина Туташуу иш_маани. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(туташуу_жадыбал.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Өзгөртүүлөр_Тизме = defaultdict(dict)
    for Файл,Жылбышуу_маани,Аты,ОКШОШТУКЖОК_маани in 분석['Шилтемелер']:
        if ОКШОШТУКЖОК_маани in 바꿀선언:
            Өзгөртүүлөр_Тизме[Файл][Жылбышуу_маани] = (Аты,바꿀선언[ОКШОШТУКЖОК_маани])
    жазуу_катар = ['Файл\t원래바이트위치\t이전이름\t한국어이름']
    этибар_албоо_маани = []
    for Файл,өзгөртүү_маани in Өзгөртүүлөр_Тизме.items():
        ЖОЛ = Path(Файл); 원본 = ЖОЛ.read_bytes(); берилмелер = 원본
        for Жылбышуу_маани,(옛이름,새이름) in sorted(өзгөртүү_маани.items(),reverse=True):
            끝 = Жылбышуу_маани+len(옛이름.encode())
            if 원본[Жылбышуу_маани:끝] != 옛이름.encode():
                этибар_албоо_маани.append((str(ЖОЛ.relative_to(기준)),Жылбышуу_маани,옛이름));continue
            берилмелер = берилмелер[:Жылбышуу_маани]+새이름.encode()+берилмелер[끝:]
            жазуу_катар.append('{}\t{}\t{}\t{}'.format(ЖОЛ.relative_to(기준),Жылбышуу_маани,옛이름,새이름))
        ЖОЛ.write_bytes(берилмелер)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макро_маани = {киргизме_жазуу_маани['Аты']:аты_жадыбал[киргизме_жазуу_маани['Аты']] for киргизме_жазуу_маани in 선언표.values()
              if киргизме_жазуу_маани['종류']==501 and киргизме_жазуу_маани['Аты'] in аты_жадыбал and киргизме_жазуу_маани['Аты'] not in 규격}
    for ЖОЛ in sorted({Path(киргизме_жазуу_маани['Файл']) for киргизме_жазуу_маани in 선언표.values()}):
        сап_Тизме = ЖОЛ.read_text().splitlines(True); 이어짐 = False
        for индекс,сап in enumerate(сап_Тизме):
            전처리 = 이어짐 or bool(re.match(r'\s*#',сап))
            이어짐 = 전처리 and сап.rstrip().endswith('\\')
            if 전처리:
                표 = аты_жадыбал if re.match(r'\s*#\s*define\b',сап) or 이어짐 else макро_маани
                сап_Тизме[индекс] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],сап)
        ЖОЛ.write_text(''.join(сап_Тизме))
    # 각 자체 Которуу_башат 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ЖОЛ in sorted({Path(киргизме_жазуу_маани['Файл']) for киргизме_жазуу_маани in 선언표.values()}):
        if ЖОЛ.suffix not in ('.c','.cpp'):continue
        бирдей_маани = '../' * len(ЖОЛ.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        ЖОЛ.write_text('#include "'+бирдей_маани+'"\n'+ЖОЛ.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(жазуу_катар)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(этибар_албоо_маани,ensure_ascii=False,indent=2)+'\n')
    print('өзгөртүү_маани',len(жазуу_катар)-1,'전처리 재검토',len(этибар_албоо_маани),'машина Туташуу',len(туташуу_жадыбал))

if __name__=='__main__': аткаруу_буйрук()
