#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from иш_такта_көрүү import баскычтоп


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.СМС_буфер = ''
        def жөнөтүү(берилмелер):
            for символ_берилмелер_4d9f8719 in берилмелер.decode('utf-8'):
                if символ_берилмелер_4d9f8719 == '\x7f': 자신.СМС_буфер = 자신.СМС_буфер[:-1]
                else: 자신.СМС_буфер += символ_берилмелер_4d9f8719
        자신.баскычтоп_киргизме_жазуу = баскычтоп(жөнөтүү)

    def 글쇠누르기(자신, символ_маани):
        자신.баскычтоп_киргизме_жазуу.누름값(True, символ_маани)
        자신.баскычтоп_киргизме_жазуу.누름값(False, символ_маани)

    def түрү_категория(자신, 누름열):
        for 누름값 in 누름열: 자신.글쇠누르기(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.글쇠누르기(0xffc6); 자신.түрү_категория(누름열)
                자신.assertEqual(자신.СМС_буфер, 예상결과)

    def test_앞글자지우기(자신):
        자신.글쇠누르기(0xff31); 자신.түрү_категория('dlfr')
        자신.assertEqual(자신.СМС_буфер,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.글쇠누르기(0xff08); 자신.assertEqual(자신.СМС_буфер,예상결과)
        자신.түрү_категория('gksk'); 자신.assertEqual(자신.СМС_буфер,'하나')
        자신.글쇠누르기(0xff08); 자신.assertEqual(자신.СМС_буфер,'하ㄴ')

    def test_전환반복확정(자신):
        자신.түрү_категория('echo ')
        자신.баскычтоп_киргизме_жазуу.누름값(True,0xffe1)
        자신.баскычтоп_киргизме_жазуу.누름값(True,32); 자신.баскычтоп_киргизме_жазуу.누름값(True,32)
        자신.баскычтоп_киргизме_жазуу.누름값(False,32); 자신.баскычтоп_киргизме_жазуу.누름값(False,0xffe1)
        자신.assertTrue(자신.баскычтоп_киргизме_жазуу.한글여부)
        자신.түрү_категория('gksrmf'); 자신.글쇠누르기(0xff31); 자신.түрү_категория(' English')
        자신.assertEqual(자신.СМС_буфер,'echo 한글 English')
        자신.assertFalse(자신.баскычтоп_киргизме_жазуу.한글여부)
        자신.글쇠누르기(0xffc6); 자신.түрү_категория('rk'); 자신.글쇠누르기(0xff51)
        자신.түрү_категория('sk'); 자신.assertTrue(자신.СМС_буфер.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.글쇠누르기(0xffc6); 자신.түрү_категория('rk')
        자신.баскычтоп_киргизме_жазуу.алмашуу_буфери_маани='коюу_маани'.encode()
        자신.баскычтоп_киргизме_жазуу.누름값(True,0xffe3); 자신.баскычтоп_киргизме_жазуу.누름값(True,0xffe1)
        자신.글쇠누르기(ord('v'))
        자신.баскычтоп_киргизме_жазуу.누름값(False,0xffe1); 자신.баскычтоп_киргизме_жазуу.누름값(False,0xffe3)
        자신.글쇠누르기(0x0100d55c); 자신.түрү_категория('sk')
        자신.assertEqual(자신.СМС_буфер,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
