package Кыргызстан.JKgzOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB бет_маани 연결과 Жазуу 시 복사를 제공한다. */
public final class бет_башкаруучу {
    public static final int беттин_өлчөмү = 4096;

    private static final class бет_маани {
        private byte[] берилмелер = new byte[беттин_өлчөмү];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class дарек_АРАЛЫК {
        private final Map<Integer, бет_маани> бет_жадыбал = new HashMap<Integer, бет_маани>();
    }

    public дарек_АРАЛЫК 새주소공간() {
        return new дарек_АРАЛЫК();
    }

    public void картада_көрсөтүү_бет(дарек_АРАЛЫК 공간, int виртуалдык_дарек, boolean 쓰기가능) {
        int индекс = 쪽번호(виртуалдык_дарек);
        бет_маани 새쪽 = new бет_маани();
        새쪽.쓰기가능 = 쓰기가능;
        공간.бет_жадыбал.put(Integer.valueOf(индекс), 새쪽);
    }

    public дарек_АРАЛЫК 쓰기시복사복제(дарек_АРАЛЫК 원본) {
        дарек_АРАЛЫК 복제본 = new дарек_АРАЛЫК();
        for (Map.Entry<Integer, бет_маани> киргизме_жазуу_маани : 원본.бет_жадыбал.entrySet()) {
            бет_маани 공유쪽 = киргизме_жазуу_маани.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.бет_жадыбал.put(киргизме_жазуу_маани.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(дарек_АРАЛЫК 공간, int виртуалдык_дарек) {
        бет_маани максат = табуу_бет(공간, виртуалдык_дарек);
        return максат.берилмелер[Math.floorMod(виртуалдык_дарек, беттин_өлчөмү)];
    }

    public void жазуу_байт_маани(дарек_АРАЛЫК 공간, int виртуалдык_дарек, byte маани) {
        int индекс = 쪽번호(виртуалдык_дарек);
        бет_маани максат = табуу_бет(공간, виртуалдык_дарек);
        if (!максат.쓰기가능) {
            if (!максат.쓰기시복사) {
                throw new IllegalStateException("Окуу 전용 쪽입니다.");
            }
            максат = түзүү_жеке_бет(공간, индекс, максат);
        }
        максат.берилмелер[Math.floorMod(виртуалдык_дарек, беттин_өлчөмү)] = маани;
    }

    public void 범위개인쓰기(дарек_АРАЛЫК 공간, int Баштоо_дарек, int Өлчөмү) {
        if (Өлчөмү < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int аяктоо_дарек = Math.addExact(Баштоо_дарек, Өлчөмү);
        for (int дарек = Баштоо_дарек; дарек < аяктоо_дарек; дарек = (쪽번호(дарек) + 1) * беттин_өлчөмү) {
            int индекс = 쪽번호(дарек);
            бет_маани максат = табуу_бет(공간, дарек);
            if (максат.쓰기시복사) {
                түзүү_жеке_бет(공간, индекс, максат);
            } else {
                максат.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(дарек_АРАЛЫК 공간, int Баштоо_дарек, byte[] берилмелер) {
        for (int индекс = 0; индекс < берилмелер.length; индекс++) {
            жазуу_байт_маани(공간, Баштоо_дарек + индекс, берилмелер[индекс]);
        }
    }

    private бет_маани түзүү_жеке_бет(дарек_АРАЛЫК 공간, int индекс, бет_маани 공유쪽) {
        бет_маани жеке_бет = new бет_маани();
        жеке_бет.берилмелер = Arrays.copyOf(공유쪽.берилмелер, 공유쪽.берилмелер.length);
        жеке_бет.쓰기가능 = true;
        жеке_бет.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.бет_жадыбал.put(Integer.valueOf(индекс), жеке_бет);
        return жеке_бет;
    }

    private бет_маани табуу_бет(дарек_АРАЛЫК 공간, int дарек) {
        бет_маани максат = 공간.бет_жадыбал.get(Integer.valueOf(쪽번호(дарек)));
        if (максат == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return максат;
    }

    private int 쪽번호(int дарек) {
        if (дарек < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return дарек / беттин_өлчөмү;
    }
}

