import 한국어.자체.терезе;
import 한국어.자체.метка;
import 한국어.자체.текст_талаасы;
import 한국어.자체.баскыч;
import 한국어.자체.окуя_кезек;
import 한국어.자체.Чыгыш;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing терезе: Kirghiz 입력 → баскыч → readme_файл_eb81d7d9 Текст жаңылоо. */
public class 창예제 implements 실행할일, 동작받이 {
    private терезе 인사창;
    private текст_талаасы аты_талаа;
    private метка 인사말;
    private int 인사횟수;

    public void ачуу_терезе() {
        인사창 = new терезе("Kirghiz Swing", 460, 300);
        인사창.кошуу_элемент(new метка("Kirghiz", 20, 20, 420, 28));
        аты_талаа = new текст_талаасы("Kirghiz", 20, 64, 420, 30);
        인사말 = new метка("Kirghiz", 20, 152, 420, 28);
        인사창.кошуу_элемент(аты_талаа);
        인사창.кошуу_элемент(new баскыч("인사하기", 20, 108, 180, 32, this));
        인사창.кошуу_элемент(인사말);
        인사창.кошуу_элемент(new метка("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.көрсөтүү_терезе();
        Чыгыш.жазуу_сап("GUI 예제 Даярдоо: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.жазуу_СМС("Kirghiz, " + аты_талаа.글읽기() + "님! (" + 인사횟수 + ")");
        Чыгыш.жазуу_сап("GUI 인사: " + 인사말.글읽기());
    }

    public void аткаруу_маселе() { ачуу_терезе(); }
    public void 동작받기(동작알림 알림) {
        Чыгыш.жазуу_сап("Аракети 알림: " + 알림.буйрук_СМС());
        인사하기();
    }
    public static void Жүргүзүү() {
        окуя_кезек.나중에실행(new 창예제());
    }
}
