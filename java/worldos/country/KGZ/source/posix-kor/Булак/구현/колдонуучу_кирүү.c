#include "호출경계.h"
extern int main(int 인수개수, char **аргумент_Тизме);
static char аргумент_эс[2048];
static char *аргумент_Тизме[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 аткаруу_буйрук 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    аргумент_Тизме[0] = "jkoros-app";
    int Турган_жери = 0;
    for (int индекс = 0; индекс < 개수; индекс++) {
        const int *원본 = (const int *)jkoros_syscall(3, индекс, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        аргумент_Тизме[индекс + 1] = аргумент_эс + Турган_жери;
        for (int оюкча_киргизме_жазуу = 0; оюкча_киргизме_жазуу < 원본[0]; оюкча_киргизме_жазуу++) {
            if (Турган_жери >= 2047) return 126;
            аргумент_эс[Турган_жери++] = 원본[оюкча_киргизме_жазуу + 1];
        }
        аргумент_эс[Турган_жери++] = 0;
    }
    аргумент_Тизме[개수 + 1] = 0;
    return main(개수 + 1, аргумент_Тизме);
}
