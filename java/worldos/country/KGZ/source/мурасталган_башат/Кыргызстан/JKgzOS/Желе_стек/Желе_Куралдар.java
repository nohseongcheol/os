/** Ethernet/ARP/IPv4/ICMP/UDP 계층이 공유하는 байт_маани 순서와 검사합 도구다. */
public final class Желе_Куралдар {
    private Желе_Куралдар() {
    }

    public static int 큰순서짧은정수(byte[] берилмелер, int Турган_жери) {
        범위확인(берилмелер, Турган_жери, 2);
        return ((берилмелер[Турган_жери] & 0xff) << 8) | (берилмелер[Турган_жери + 1] & 0xff);
    }

    public static long 큰순서정수(byte[] берилмелер, int Турган_жери) {
        범위확인(берилмелер, Турган_жери, 4);
        return ((long) (берилмелер[Турган_жери] & 0xff) << 24)
                | ((long) (берилмелер[Турган_жери + 1] & 0xff) << 16)
                | ((long) (берилмелер[Турган_жери + 2] & 0xff) << 8)
                | (берилмелер[Турган_жери + 3] & 0xffL);
    }

    public static int 인터넷검사합(byte[] берилмелер, int Жүргүзүү, int узундук_маани) {
        범위확인(берилмелер, Жүргүзүү, узундук_маани);
        long 합 = 0;
        int 끝 = Жүргүзүү + узундук_маани;
        int Турган_жери = Жүргүзүү;
        while (Турган_жери + 1 < 끝) {
            합 += 큰순서짧은정수(берилмелер, Турган_жери);
            Турган_жери += 2;
        }
        if (Турган_жери < 끝) {
            합 += (берилмелер[Турган_жери] & 0xff) << 8;
        }
        while ((합 >>> 16) != 0) {
            합 = (합 & 0xffff) + (합 >>> 16);
        }
        return (int) (~합) & 0xffff;
    }

    public static boolean 이더넷틀인가(byte[] берилмелер) {
        return берилмелер != null && берилмелер.length >= 14;
    }

    public static int 이더넷상위규약(byte[] берилмелер) {
        if (!이더넷틀인가(берилмелер)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return 큰순서짧은정수(берилмелер, 12);
    }

    public static boolean 상호통신망규약사판인가(byte[] берилмелер, int Турган_жери) {
        if (берилмелер == null || Турган_жери < 0 || берилмелер.length - Турган_жери < 20) {
            return false;
        }
        int нуска_маани = (берилмелер[Турган_жери] >>> 4) & 0xf;
        int баш_аты_узундук = (берилмелер[Турган_жери] & 0xf) * 4;
        return нуска_маани == 4 && баш_аты_узундук >= 20 && берилмелер.length - Турган_жери >= баш_аты_узундук;
    }

    private static void 범위확인(byte[] берилмелер, int Жүргүзүү, int узундук_маани) {
        if (берилмелер == null || Жүргүзүү < 0 || узундук_маани < 0 || Жүргүзүү > берилмелер.length - узундук_маани) {
            throw new IllegalArgumentException("Желе_стек берилмелер 범위를 벗어났습니다.");
        }
    }
}

