package Кыргызстан.JKgzOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Кыргызстан.JKgzOS.기억공간.бет_башкаруучу;
import Кыргызстан.JKgzOS.файл_тутуму.파일서술자표;

/** Процесс_маани 식별자와 라운드로빈 Даярдоо 대기열을 관리한다. */
public final class 배정기 {
    private final бет_башкаруучу 쪽관리;
    private final Map<Integer, Процесс_маани> Жараян_Тизмеги = new HashMap<Integer, Процесс_маани>();
    private final Queue<Процесс_маани> 준비대기열 = new ArrayDeque<Процесс_маани>();
    private int 다음식별자 = 1;

    public 배정기(бет_башкаруучу 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public Процесс_маани 첫과정(파일서술자표 파일서술자) {
        Процесс_маани 새과정 = new Процесс_маани(энчилөө_аныктагыч(), 0, 쪽관리.새주소공간(), 파일서술자);
        Жараян_Тизмеги.put(Integer.valueOf(새과정.аныктагыч_маани()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public Процесс_маани 복제(Процесс_маани 부모) {
        Процесс_маани бала_маани = new Процесс_маани(
                энчилөө_аныктагыч(),
                부모.аныктагыч_маани(),
                쪽관리.쓰기시복사복제(부모.дарек_АРАЛЫК()),
                부모.파일서술자().복제());
        бала_маани.프로그램끝설정(부모.프로그램끝());
        Жараян_Тизмеги.put(Integer.valueOf(бала_маани.аныктагыч_маани()), бала_маани);
        준비대기열.offer(бала_маани);
        return бала_маани;
    }

    public Процесс_маани 다음과정() {
        int 검사수 = 준비대기열.size();
        for (int индекс = 0; индекс < 검사수; индекс++) {
            Процесс_маани 다음 = 준비대기열.poll();
            if (다음 != null && (다음.абал_маани() == Процесс_абал.Даярдоо || 다음.абал_маани() == Процесс_абал.аткаруу_буйрук)) {
                다음.топ_абал(Процесс_абал.аткаруу_буйрук);
                준비대기열.offer(다음);
                return 다음;
            }
        }
        return null;
    }

    public int 자식기다리기(Процесс_маани 부모, int бала_аныктагыч, boolean 기다리지않음) {
        for (Процесс_маани 후보 : Жараян_Тизмеги.values()) {
            if (후보.부모식별자() != 부모.аныктагыч_маани()) {
                continue;
            }
            if (бала_аныктагыч > 0 && 후보.аныктагыч_маани() != бала_аныктагыч) {
                continue;
            }
            if (후보.абал_маани() == Процесс_абал.Чыгуу_програм) {
                int 결과 = (후보.종료값() & 0xff) << 8;
                Жараян_Тизмеги.remove(Integer.valueOf(후보.аныктагыч_маани()));
                return 결과;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public Процесс_маани табуу_Процесс(int аныктагыч_маани) {
        return Жараян_Тизмеги.get(Integer.valueOf(аныктагыч_маани));
    }

    private int энчилөө_аныктагыч() {
        return 다음식별자++;
    }
}
