/** 부팅 ប្រព័ន្ធព័ត៌មាន 조회와 4KiB 고정 ដាក់ទំហំ 작업 ផ្នែក_តំលៃ លៃទុក_ការផ្ទុក/반환. 일반 물리 ទំព័រ_តំលៃ 관리자는 아니다. */
public final class 기억공간 {
    static int[] ផ្នែក_តំលៃ = new int[8192];
    static int[] 사용 = new int[8];

    static int ញែក_ចំនួនគត់(int អ៊ីម៉ែល) {
        return ឧបករណ៍_តំលៃ.기억읽기(អ៊ីម៉ែល) | (ឧបករណ៍_តំលៃ.기억읽기(អ៊ីម៉ែល + 1) << 8)
            | (ឧបករណ៍_តំលៃ.기억읽기(អ៊ីម៉ែល + 2) << 16) | (ឧបករណ៍_តំលៃ.기억읽기(អ៊ីម៉ែល + 3) << 24);
    }

    static int 위쪽기억크기() {
        int ប្រព័ន្ធព័ត៌មាន = ឧបករណ៍_តំលៃ.부팅정보();
        if (ឧបករណ៍_តំលៃ.부팅표식() != 0x2badb002 || ប្រព័ន្ធព័ត៌មាន == 0 || (ញែក_ចំនួនគត់(ប្រព័ន្ធព័ត៌មាន) & 1) == 0) return -1;
        return ញែក_ចំនួនគត់(ប្រព័ន្ធព័ត៌មាន + 8);
    }

    static int លៃទុក_ការផ្ទុក() {
        for (int សន្ទស្សន៏ = 0; សន្ទស្សន៏ < 사용.length; សន្ទស្សន៏++) {
            if (사용[សន្ទស្សន៏] == 0) {
                사용[សន្ទស្សន៏] = 1;
                for (int ចន្លោះប្រហោង_ការបញ្ចូល = 0; ចន្លោះប្រហោង_ការបញ្ចូល < 1024; ចន្លោះប្រហោង_ការបញ្ចូល++) ផ្នែក_តំលៃ[សន្ទស្សន៏ * 1024 + ចន្លោះប្រហោង_ការបញ្ចូល] = 0;
                return សន្ទស្សន៏;
            }
        }
        return -1;
    }

    static boolean 반환(int សន្ទស្សន៏) {
        if (សន្ទស្សន៏ < 0 || សន្ទស្សន៏ >= 사용.length || 사용[សន្ទស្សន៏] == 0) return false;
        사용[សន្ទស្សន៏] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int សន្ទស្សន៏ = 0; សន្ទស្សន៏ < 사용.length; សន្ទស្សន៏++) 개수 += 사용[សន្ទស្សន៏];
        return 개수;
    }
}
