#!/usr/bin/env python3
"""ការប្រកាស 고유번호와 UTF-8 បៃ_តំលៃ 위치로 자체 C 이름을 옮기는 일회성 이행 ឧបករណ៍.

외부 구조체의 멤버, សំនុំអក្សរ_តំលៃ, C 표준 អនុគមន៍_តំលៃ, 이식 규약은 보존한다.
입력은 កែប្រែ_តំលៃ 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

បញ្ចាំង_ឬស = Path(__file__).resolve().parents[1]

def អនុវត្ត_ពាក្យបញ្ជា():
    분석 = json.loads((បញ្ចាំង_ឬស/'build/한국어화/시언어분석.json').read_text())
    if 분석['កំហុស']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ឈ្មោះ_តារាង = json.loads((បញ្ចាំង_ឬស/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((បញ្ចាំង_ឬស/'명명/규격이름.json').read_text()))
    ការប្រកាស_តារាង = 분석['ការប្រកាស']
    바꿀선언 = {고유:ឈ្មោះ_តារាង[ការបញ្ចូល_តំលៃ['ឈ្មោះ']] for 고유,ការបញ្ចូល_តំលៃ in ការប្រកាស_តារាង.items()
                if ការបញ្ចូល_តំលៃ['ឈ្មោះ'] in ឈ្មោះ_តារាង and ការបញ្ចូល_តំលៃ['ឈ្មោះ'] not in 규격}
    ការភ្ជាប់_តារាង = {ការបញ្ចូល_តំលៃ['ឈ្មោះ']:ឈ្មោះ_តារាង[ការបញ្ចូល_តំលៃ['ឈ្មោះ']] for ការបញ្ចូល_តំលៃ in ការប្រកាស_តារាង.values()
              if ការបញ្ចូល_តំលៃ.get('ភ្ជាប់')==4 and ការបញ្ចូល_តំលៃ['종류'] in (8,9)
              and ការបញ្ចូល_តំលៃ['ឈ្មោះ'] in ឈ្មោះ_តារាង and ការបញ្ចូល_តំលៃ['ឈ្មោះ'] not in 규격}
    # បង្កើត AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ភ្ជាប់ 이름만 유지한다.
    머리 = ['/* 한국어 ប្រភព_មែកធាង 이름과 기존 ម៉ាស៊ីន ភ្ជាប់ ករណី_តំលៃ. 자동 បង្កើត: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(ការភ្ជាប់_តារាង.items())]
    머리 += ['#endif','']
    (បញ្ចាំង_ឬស/'명명/기계연결이름.h').write_text('\n'.join(머리))
    ការផ្លាស់ប្ដូរ_បញ្ជី = defaultdict(dict)
    for ឯកសារ,ការបែង_ភាគ_តំលៃ,ឈ្មោះ,고유 in 분석['យោង']:
        if 고유 in 바꿀선언:
            ការផ្លាស់ប្ដូរ_បញ្ជី[ឯកសារ][ការបែង_ភាគ_តំលៃ] = (ឈ្មោះ,바꿀선언[고유])
    កំណត់_ហេតុ_ថត = ['ឯកសារ\t원래바이트위치\t이전이름\t한국어이름']
    មិនអើពើ_តំលៃ = []
    for ឯកសារ,កែប្រែ_តំលៃ in ការផ្លាស់ប្ដូរ_បញ្ជី.items():
        ផ្លូវ = Path(ឯកសារ); 원본 = ផ្លូវ.read_bytes(); ទិន្នន័យ = 원본
        for ការបែង_ភាគ_តំលៃ,(옛이름,새이름) in sorted(កែប្រែ_តំលៃ.items(),reverse=True):
            끝 = ការបែង_ភាគ_តំលៃ+len(옛이름.encode())
            if 원본[ការបែង_ភាគ_តំលៃ:끝] != 옛이름.encode():
                មិនអើពើ_តំលៃ.append((str(ផ្លូវ.relative_to(បញ្ចាំង_ឬស)),ការបែង_ភាគ_តំលៃ,옛이름));continue
            ទិន្នន័យ = ទិន្នន័យ[:ការបែង_ភាគ_តំលៃ]+새이름.encode()+ទិន្នន័យ[끝:]
            កំណត់_ហេតុ_ថត.append('{}\t{}\t{}\t{}'.format(ផ្លូវ.relative_to(បញ្ចាំង_ឬស),ការបែង_ភាគ_តំលៃ,옛이름,새이름))
        ផ្លូវ.write_bytes(ទិន្នន័យ)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ម៉ាក្រូ_តំលៃ = {ការបញ្ចូល_តំលៃ['ឈ្មោះ']:ឈ្មោះ_តារាង[ការបញ្ចូល_តំលៃ['ឈ្មោះ']] for ការបញ្ចូល_តំលៃ in ការប្រកាស_តារាង.values()
              if ការបញ្ចូល_តំលៃ['종류']==501 and ការបញ្ចូល_តំលៃ['ឈ្មោះ'] in ឈ្មោះ_តារាង and ការបញ្ចូល_តំលៃ['ឈ្មោះ'] not in 규격}
    for ផ្លូវ in sorted({Path(ការបញ្ចូល_តំលៃ['ឯកសារ']) for ការបញ្ចូល_តំលៃ in ការប្រកាស_តារាង.values()}):
        បណ្ដាញ_បញ្ជី = ផ្លូវ.read_text().splitlines(True); 이어짐 = False
        for សន្ទស្សន៏,បន្ទាត់ in enumerate(បណ្ដាញ_បញ្ជី):
            전처리 = 이어짐 or bool(re.match(r'\s*#',បន្ទាត់))
            이어짐 = 전처리 and បន្ទាត់.rstrip().endswith('\\')
            if 전처리:
                រុករក_តារាង = ឈ្មោះ_តារាង if re.match(r'\s*#\s*define\b',បន្ទាត់) or 이어짐 else ម៉ាក្រូ_តំលៃ
                បណ្ដាញ_បញ្ជី[សន្ទស្សន៏] = 낱말.sub(lambda 맞음: រុករក_តារាង.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],បន្ទាត់)
        ផ្លូវ.write_text(''.join(បណ្ដាញ_បញ្ជី))
    # 각 자체 បកប្រែ_ប្រភព 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ផ្លូវ in sorted({Path(ការបញ្ចូល_តំលៃ['ឯកសារ']) for ការបញ្ចូល_តំលៃ in ការប្រកាស_តារាង.values()}):
        if ផ្លូវ.suffix not in ('.c','.cpp'):continue
        សិទ្ធស្មើ_តំលៃ = '../' * len(ផ្លូវ.relative_to(បញ្ចាំង_ឬស).parts[:-1]) + '명명/기계연결이름.h'
        ផ្លូវ.write_text('#include "'+សិទ្ធស្មើ_តំលៃ+'"\n'+ផ្លូវ.read_text())
    (បញ្ចាំង_ឬស/'명명/시언어이름대응.tsv').write_text('\n'.join(កំណត់_ហេតុ_ថត)+'\n')
    (បញ្ចាំង_ឬស/'build/한국어화/전처리참조.json').write_text(json.dumps(មិនអើពើ_តំលៃ,ensure_ascii=False,indent=2)+'\n')
    print('កែប្រែ_តំលៃ',len(កំណត់_ហេតុ_ថត)-1,'전처리 재검토',len(មិនអើពើ_តំលៃ),'ម៉ាស៊ីន ភ្ជាប់',len(ការភ្ជាប់_តារាង))

if __name__=='__main__': អនុវត្ត_ពាក្យបញ្ជា()
