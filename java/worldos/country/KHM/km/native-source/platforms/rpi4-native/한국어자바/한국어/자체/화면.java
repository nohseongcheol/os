package 한국어.자체;
/** 화면(畫面): 부팅 때 선택한 크기의 자체 ខឺណេល_តំលៃ RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int តំលៃ = ខឺណេល_តំលៃ.화면너비(); if (តំលៃ < 0) throw new ភាព_ការលើកលែង("프레임버퍼 없음"); return តំលៃ; }
    public static int 높이() { int តំលៃ = ខឺណេល_តំលៃ.화면높이(); if (តំលៃ < 0) throw new ភាព_ការលើកលែង("프레임버퍼 없음"); return តំលៃ; }
    public static void 사각형(int 가로, int បញ្ឈរ_កំណត់ទីតាំង, int 폭, int 높이, int 색) {
        if (가로 < 0 || បញ្ឈរ_កំណត់ទីតាំង < 0 || 폭 < 0 || 높이 < 0 || 가로 > 너비() || បញ្ឈរ_កំណត់ទីតាំង > 높이() || 폭 > 너비() - 가로 || 높이 > 높이() - បញ្ឈរ_កំណត់ទីតាំង) throw new មិនត្រឹមត្រូវ_អាគុយម៉ង់_ការលើកលែង("화면 មេឌៀខ្លីៗ");
        if (ខឺណេល_តំលៃ.사각형(가로, បញ្ឈរ_កំណត់ទីតាំង, 폭, 높이, 색) < 0) throw new ភាព_ការលើកលែង("프레임버퍼 없음");
    }
    public static void លុប_ការបញ្ចូល(int 색) { 사각형(0, 0, 너비(), 높이(), 색); }
    public static void 기다리기() { if (ខឺណេល_តំលៃ.그림대기() < 0) throw new ភាព_ការលើកលែង("អន្តរកម្ម 입력 필요"); }
}
