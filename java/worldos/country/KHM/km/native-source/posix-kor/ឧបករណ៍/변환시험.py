#!/usr/bin/env python3
"""ចងក្រង_ប្រព័ន្ធ 변환이 한국어 សំនុំអក្សរ_តំលៃ, 주석, 헤더 경로를 바꾸지 않는지 검사한다."""
from អង្គសម្គាល់_ការបំលែង import 변환

ប្រភព = '''#include <파일규약.h>
#include "통신규약.h"
// បើក_ឯកសារ 라는 주석
/* 자료이름 */
const char *ឯកសារ_ការបញ្ចូល_ឈ្មោះ = "한글 \\" សំនុំអក្សរ_តំលៃ";
char តួអក្សរ_តំលៃ = '가';
int 파일열기_횟수 = 1;
'''
លទ្ធផល = 변환(ប្រភព)
assert '#include <파일규약.h>' in លទ្ធផល
assert '#include "통신규약.h"' in លទ្ធផល
assert '// បើក_ឯកសារ 라는 주석' in លទ្ធផល
assert '/* 자료이름 */' in លទ្ធផល
assert '"한글 \\" សំនុំអក្សរ_តំលៃ"' in លទ្ធផល
assert "'가'" in លទ្ធផល
assert '\\ud30c\\uc77c\\uc774\\ub984' in លទ្ធផល
assert '파일열기_횟수' not in លទ្ធផល
assert 변환(លទ្ធផល) == លទ្ធផល
print('PASS: 한국어 អង្គសម្គាល់_តំលៃ 변환/សំនុំអក្សរ_តំលៃ·주석·ផ្លូវ 보존')
