package កម្ពុជា.JKhmOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import កម្ពុជា.JKhmOS.기억공간.ទំព័រ_អ្នកគ្រប់គ្រង;
import កម្ពុជា.JKhmOS.ឯកសារនៃប្រព័ន្ធ.파일서술자표;

/** ដំណើរការ_តំលៃ 식별자와 라운드로빈 រៀបចំ 대기열을 관리한다. */
public final class អ្នករៀបកាលវិភាគ {
    private final ទំព័រ_អ្នកគ្រប់គ្រង 쪽관리;
    private final Map<Integer, ដំណើរការ_តំលៃ> បញ្ជីដំណើរការ = new HashMap<Integer, ដំណើរការ_តំលៃ>();
    private final Queue<ដំណើរការ_តំលៃ> 준비대기열 = new ArrayDeque<ដំណើរការ_តំលៃ>();
    private int បន្ទាប់_អង្គសម្គាល់ = 1;

    public អ្នករៀបកាលវិភាគ(ទំព័រ_អ្នកគ្រប់គ្រង 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public ដំណើរការ_តំលៃ 첫과정(파일서술자표 파일서술자) {
        ដំណើរការ_តំលៃ 새과정 = new ដំណើរការ_តំលៃ(លៃទុក_អង្គសម្គាល់(), 0, 쪽관리.새주소공간(), 파일서술자);
        បញ្ជីដំណើរការ.put(Integer.valueOf(새과정.អង្គសម្គាល់_តំលៃ()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public ដំណើរការ_តំលៃ 복제(ដំណើរការ_តំលៃ 부모) {
        ដំណើរការ_តំលៃ កូន_តំលៃ = new ដំណើរការ_តំលៃ(
                លៃទុក_អង្គសម្គាល់(),
                부모.អង្គសម្គាល់_តំលៃ(),
                쪽관리.쓰기시복사복제(부모.អ៊ីម៉ែល_លំហ()),
                부모.파일서술자().복제());
        កូន_តំលៃ.프로그램끝설정(부모.프로그램끝());
        បញ្ជីដំណើរការ.put(Integer.valueOf(កូន_តំលៃ.អង្គសម្គាល់_តំលៃ()), កូន_តំលៃ);
        준비대기열.offer(កូន_តំលៃ);
        return កូន_តំលៃ;
    }

    public ដំណើរការ_តំលៃ បន្ទាប់_ដំណើរការ() {
        int 검사수 = 준비대기열.size();
        for (int សន្ទស្សន៏ = 0; សន្ទស្សន៏ < 검사수; សន្ទស្សន៏++) {
            ដំណើរការ_តំលៃ បន្ទាប់_ធាតុ = 준비대기열.poll();
            if (បន្ទាប់_ធាតុ != null && (បន្ទាប់_ធាតុ.ភាព_តំលៃ() == ដំណើរការ_ភាព.រៀបចំ || បន្ទាប់_ធាតុ.ភាព_តំលៃ() == ដំណើរការ_ភាព.អនុវត្ត_ពាក្យបញ្ជា)) {
                បន្ទាប់_ធាតុ.កំណត់_ភាព(ដំណើរការ_ភាព.អនុវត្ត_ពាក្យបញ្ជា);
                준비대기열.offer(បន្ទាប់_ធាតុ);
                return បន្ទាប់_ធាតុ;
            }
        }
        return null;
    }

    public int 자식기다리기(ដំណើរការ_តំលៃ 부모, int កូន_អង្គសម្គាល់, boolean 기다리지않음) {
        for (ដំណើរការ_តំលៃ 후보 : បញ្ជីដំណើរការ.values()) {
            if (후보.부모식별자() != 부모.អង្គសម្គាល់_តំលៃ()) {
                continue;
            }
            if (កូន_អង្គសម្គាល់ > 0 && 후보.អង្គសម្គាល់_តំលៃ() != កូន_អង្គសម្គាល់) {
                continue;
            }
            if (후보.ភាព_តំលៃ() == ដំណើរការ_ភាព.ចេញ_កម្មវិធី) {
                int ការវាស់វែង = (후보.ចេញ_កូដ() & 0xff) << 8;
                បញ្ជីដំណើរការ.remove(Integer.valueOf(후보.អង្គសម្គាល់_តំលៃ()));
                return ការវាស់វែង;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public ដំណើរការ_តំលៃ រក_ដំណើរការ(int អង្គសម្គាល់_តំលៃ) {
        return បញ្ជីដំណើរការ.get(Integer.valueOf(អង្គសម្គាល់_តំលៃ));
    }

    private int លៃទុក_អង្គសម្គាល់() {
        return បន្ទាប់_អង្គសម្គាល់++;
    }
}
