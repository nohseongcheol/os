/** 자체 커널의 Swing ວິນໂດ: lo 입력 → ປຸ່ມ → ຂໍ້ແນະນໍາການໃຊ້_eb81d7d9 ຂໍ້ຄວາມ ລຶ້ມຄືນໃຫມ່. */
public class 창예제 implements 실행할일, 동작받이 {
    private ວິນໂດ 인사창;
    private ຂໍ້ຄວາມ_ຊ່ອງຂໍ້ມູນ ຊື່_ຊ່ອງຂໍ້ມູນ;
    private ປ້າຍ 인사말;
    private int 인사횟수;

    public void ສ້າງ_ວິນໂດ() {
        인사창 = new ວິນໂດ("lo Swing", 460, 300);
        인사창.ເພີ່ມ_ອົງປະກອບ(new ປ້າຍ("ສະບາຍດີ", 20, 20, 420, 28));
        ຊື່_ຊ່ອງຂໍ້ມູນ = new ຂໍ້ຄວາມ_ຊ່ອງຂໍ້ມູນ("lo", 20, 64, 420, 30);
        인사말 = new ປ້າຍ("ສະບາຍດີ", 20, 152, 420, 28);
        인사창.ເພີ່ມ_ອົງປະກອບ(ຊື່_ຊ່ອງຂໍ້ມູນ);
        인사창.ເພີ່ມ_ອົງປະກອບ(new ປຸ່ມ("인사하기", 20, 108, 180, 32, this));
        인사창.ເພີ່ມ_ອົງປະກອບ(인사말);
        인사창.ເພີ່ມ_ອົງປະກອບ(new ປ້າຍ("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.ລາຍການ_ວິນໂດ();
        출력.ຂຽນ_ສາຍ("GUI 예제 ກະ_ກຽມ: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.ຂຽນ_ຂໍ້ຄວາມ("ສະບາຍດີ, " + ຊື່_ຊ່ອງຂໍ້ມູນ.글읽기() + "님! (" + 인사횟수 + ")");
        출력.ຂຽນ_ສາຍ("GUI 인사: " + 인사말.글읽기());
    }

    public void ປະ_ຕິ_ບັດ_ຫນ້າວຽກ() { ສ້າງ_ວິນໂດ(); }
    public void 동작받기(동작알림 알림) {
        출력.ຂຽນ_ສາຍ("ຄໍາສັ່ງ 알림: " + 알림.ຄໍາສັ່ງ_ຂໍ້ຄວາມ());
        인사하기();
    }
    public static void ແລ່ນ() {
        ງານ_ຄິວ.나중에실행(new 창예제());
    }
}
