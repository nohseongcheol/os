/** 부팅 ລະບົບ_ຂໍ້_ມູນ 조회와 4KiB 고정 ຂະ_ຫນາດ 작업 ຕອນ_ຄ່າ ຈັດສັນ_ບ່ອນເກັບຂໍ້ມູນ/반환. 일반 물리 ຫນ້າ_ຄ່າ 관리자는 아니다. */
public final class 기억공간 {
    static int[] ຕອນ_ຄ່າ = new int[8192];
    static int[] 사용 = new int[8];

    static int ການແຈກຄໍາສັບ_ຕົວເລກຈໍານວນເຕັມ(int ອີເມວ) {
        return ມືຖື_ຄ່າ.기억읽기(ອີເມວ) | (ມືຖື_ຄ່າ.기억읽기(ອີເມວ + 1) << 8)
            | (ມືຖື_ຄ່າ.기억읽기(ອີເມວ + 2) << 16) | (ມືຖື_ຄ່າ.기억읽기(ອີເມວ + 3) << 24);
    }

    static int 위쪽기억크기() {
        int ລະບົບ_ຂໍ້_ມູນ = ມືຖື_ຄ່າ.부팅정보();
        if (ມືຖື_ຄ່າ.부팅표식() != 0x2badb002 || ລະບົບ_ຂໍ້_ມູນ == 0 || (ການແຈກຄໍາສັບ_ຕົວເລກຈໍານວນເຕັມ(ລະບົບ_ຂໍ້_ມູນ) & 1) == 0) return -1;
        return ການແຈກຄໍາສັບ_ຕົວເລກຈໍານວນເຕັມ(ລະບົບ_ຂໍ້_ມູນ + 8);
    }

    static int ຈັດສັນ_ບ່ອນເກັບຂໍ້ມູນ() {
        for (int ດັດຊະນີ = 0; ດັດຊະນີ < 사용.length; ດັດຊະນີ++) {
            if (사용[ດັດຊະນີ] == 0) {
                사용[ດັດຊະນີ] = 1;
                for (int ຊ່ອງ_ເຂົ້າໃນ = 0; ຊ່ອງ_ເຂົ້າໃນ < 1024; ຊ່ອງ_ເຂົ້າໃນ++) ຕອນ_ຄ່າ[ດັດຊະນີ * 1024 + ຊ່ອງ_ເຂົ້າໃນ] = 0;
                return ດັດຊະນີ;
            }
        }
        return -1;
    }

    static boolean 반환(int ດັດຊະນີ) {
        if (ດັດຊະນີ < 0 || ດັດຊະນີ >= 사용.length || 사용[ດັດຊະນີ] == 0) return false;
        사용[ດັດຊະນີ] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int ດັດຊະນີ = 0; ດັດຊະນີ < 사용.length; ດັດຊະນີ++) 개수 += 사용[ດັດຊະນີ];
        return 개수;
    }
}
