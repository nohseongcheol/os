        확인(ເດັກ_ນ້ອຍ_ຄ່າ.부모식별자() == 부모.ຕົວ_ກໍາ_ນົດ_ຄ່າ(), "부모 ຂະ_ບວນ_ການ_ຄ່າ ຕົວ_ກໍາ_ນົດ_ຄ່າ");
        확인(호출.ປິດ(ເດັກ_ນ້ອຍ_ຄ່າ, 서술자) == 0 && 부모.파일서술자().ເທັກໂນໂລຢີຂໍ້ມູນຂ່າວສານ_ສ້າງ(서술자), "ເດັກ_ນ້ອຍ_ຄ່າ ປິດ 격리");

        int 이전끝 = 호출.프로그램끝늘리기(부모, 8192);
        확인(이전끝 == 0x06000000, "ແອັບ_f5044b9b 끝 늘리기");
        확인(부모.프로그램끝() == 0x06002000, "ແອັບ_f5044b9b 끝 반영");
        확인(ເດັກ_ນ້ອຍ_ຄ່າ.프로그램끝() == 0x06000000, "과정별 ແອັບ_f5044b9b 끝 격리");

        ເດັກ_ນ້ອຍ_ຄ່າ.ອອກ_ແອັບ(7);
        확인(호출.자식기다리기(부모, ເດັກ_ນ້ອຍ_ຄ່າ.ຕົວ_ກໍາ_ນົດ_ຄ່າ(), false) == (7 << 8), "ເດັກ_ນ້ອຍ_ຄ່າ ອອກ_ແອັບ 기다리기");
