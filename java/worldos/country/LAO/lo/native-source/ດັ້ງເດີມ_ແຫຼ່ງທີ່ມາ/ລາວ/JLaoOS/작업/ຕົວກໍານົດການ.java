package ລາວ.JLaoOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import ລາວ.JLaoOS.기억공간.쪽관리자;
import ລາວ.JLaoOS.ລະບົບຟາຍ.파일서술자표;

/** ຂະ_ບວນ_ການ_ຄ່າ 식별자와 라운드로빈 ກະ_ກຽມ 대기열을 관리한다. */
public final class ຕົວກໍານົດການ {
    private final 쪽관리자 쪽관리;
    private final Map<Integer, ຂະ_ບວນ_ການ_ຄ່າ> ລາຍ_ການ_ຂະ_ບວນ_ການ = new HashMap<Integer, ຂະ_ບວນ_ການ_ຄ່າ>();
    private final Queue<ຂະ_ບວນ_ການ_ຄ່າ> 준비대기열 = new ArrayDeque<ຂະ_ບວນ_ການ_ຄ່າ>();
    private int ຕໍ່ໄປ_ຕົວ_ກໍາ_ນົດ = 1;

    public ຕົວກໍານົດການ(쪽관리자 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public ຂະ_ບວນ_ການ_ຄ່າ 첫과정(파일서술자표 파일서술자) {
        ຂະ_ບວນ_ການ_ຄ່າ 새과정 = new ຂະ_ບວນ_ການ_ຄ່າ(ຈັດສັນ_ຕົວ_ກໍາ_ນົດ(), 0, 쪽관리.새주소공간(), 파일서술자);
        ລາຍ_ການ_ຂະ_ບວນ_ການ.put(Integer.valueOf(새과정.ຕົວ_ກໍາ_ນົດ_ຄ່າ()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public ຂະ_ບວນ_ການ_ຄ່າ 복제(ຂະ_ບວນ_ການ_ຄ່າ 부모) {
        ຂະ_ບວນ_ການ_ຄ່າ ເດັກ_ນ້ອຍ_ຄ່າ = new ຂະ_ບວນ_ການ_ຄ່າ(
                ຈັດສັນ_ຕົວ_ກໍາ_ນົດ(),
                부모.ຕົວ_ກໍາ_ນົດ_ຄ່າ(),
                쪽관리.쓰기시복사복제(부모.ອີເມວ_ພື້ນທີ່()),
                부모.파일서술자().복제());
        ເດັກ_ນ້ອຍ_ຄ່າ.프로그램끝설정(부모.프로그램끝());
        ລາຍ_ການ_ຂະ_ບວນ_ການ.put(Integer.valueOf(ເດັກ_ນ້ອຍ_ຄ່າ.ຕົວ_ກໍາ_ນົດ_ຄ່າ()), ເດັກ_ນ້ອຍ_ຄ່າ);
        준비대기열.offer(ເດັກ_ນ້ອຍ_ຄ່າ);
        return ເດັກ_ນ້ອຍ_ຄ່າ;
    }

    public ຂະ_ບວນ_ການ_ຄ່າ ຕໍ່ໄປ_ຂະ_ບວນ_ການ() {
        int 검사수 = 준비대기열.size();
        for (int ດັດຊະນີ = 0; ດັດຊະນີ < 검사수; ດັດຊະນີ++) {
            ຂະ_ບວນ_ການ_ຄ່າ ຕໍ່ໄປ_ລາຍການ = 준비대기열.poll();
            if (ຕໍ່ໄປ_ລາຍການ != null && (ຕໍ່ໄປ_ລາຍການ.ສະຖານະ_ຄ່າ() == ຂະ_ບວນ_ການ_ສະຖານະ.ກະ_ກຽມ || ຕໍ່ໄປ_ລາຍການ.ສະຖານະ_ຄ່າ() == ຂະ_ບວນ_ການ_ສະຖານະ.ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ)) {
                ຕໍ່ໄປ_ລາຍການ.ຊຸດ_ສະຖານະ(ຂະ_ບວນ_ການ_ສະຖານະ.ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ);
                준비대기열.offer(ຕໍ່ໄປ_ລາຍການ);
                return ຕໍ່ໄປ_ລາຍການ;
            }
        }
        return null;
    }

    public int 자식기다리기(ຂະ_ບວນ_ການ_ຄ່າ 부모, int ເດັກ_ນ້ອຍ_ຕົວ_ກໍາ_ນົດ, boolean 기다리지않음) {
        for (ຂະ_ບວນ_ການ_ຄ່າ 후보 : ລາຍ_ການ_ຂະ_ບວນ_ການ.values()) {
            if (후보.부모식별자() != 부모.ຕົວ_ກໍາ_ນົດ_ຄ່າ()) {
                continue;
            }
            if (ເດັກ_ນ້ອຍ_ຕົວ_ກໍາ_ນົດ > 0 && 후보.ຕົວ_ກໍາ_ນົດ_ຄ່າ() != ເດັກ_ນ້ອຍ_ຕົວ_ກໍາ_ນົດ) {
                continue;
            }
            if (후보.ສະຖານະ_ຄ່າ() == ຂະ_ບວນ_ການ_ສະຖານະ.ອອກ_ແອັບ) {
                int ມາດຕະການ = (후보.ອອກ_ລະຫັດ() & 0xff) << 8;
                ລາຍ_ການ_ຂະ_ບວນ_ການ.remove(Integer.valueOf(후보.ຕົວ_ກໍາ_ນົດ_ຄ່າ()));
                return ມາດຕະການ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public ຂະ_ບວນ_ການ_ຄ່າ ຊອກຫາ_ຂະ_ບວນ_ການ(int ຕົວ_ກໍາ_ນົດ_ຄ່າ) {
        return ລາຍ_ການ_ຂະ_ບວນ_ການ.get(Integer.valueOf(ຕົວ_ກໍາ_ນົດ_ຄ່າ));
    }

    private int ຈັດສັນ_ຕົວ_ກໍາ_ນົດ() {
        return ຕໍ່ໄປ_ຕົວ_ກໍາ_ນົດ++;
    }
}
