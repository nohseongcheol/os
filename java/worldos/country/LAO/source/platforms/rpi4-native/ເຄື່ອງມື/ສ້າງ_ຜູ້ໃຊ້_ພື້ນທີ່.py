    ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ([ການສໍາເນົາ_ເຄື່ອງມື, 'rcs', ສ້າງ_ທາງໂຄຈອນ / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for ຊື່ in ('demo', 'fault', 'network', 'vi'):
        ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ([연결편집기, '-T', 원본자료 / 'ລິ້ງ_ຮູບແບບ.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (ຊື່ + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (ຊື່ + '.o'), ສ້າງ_ທາງໂຄຈອນ / 'libposix-kor-user.a'])
    자바라이브러리만들기(ເລກຮາກ_ທາງໂຄຈອນ, ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ)
    # 기존 자체 Java 컴파일러/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(ສ້າງ_ທາງໂຄຈອນ)) as 작업경로:
        ປະເພດສິ່ງຂອງ_ທາງໂຄຈອນ = Path(작업경로)
        ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', ປະເພດສິ່ງຂອງ_ທາງໂຄຈອນ, '-sourcepath', ປະເພດສິ່ງຂອງ_ທາງໂຄຈອນ, '-d', ປະເພດສິ່ງຂອງ_ທາງໂຄຈອນ] +
            [ຂໍ້ມູນ_ຈັດຕໍາແຫນ່ງ for ຂໍ້ມູນ_ຈັດຕໍາແຫນ່ງ in sorted((ຣີໂພຊິທໍຣີ_ທາງໂຄຈອນ / 'os/ຜູ້ໃຊ້/자바').glob('*.java')) if ຂໍ້ມູນ_ຈັດຕໍາແຫນ່ງ.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ(['sh', ຣີໂພຊິທໍຣີ_ທາງໂຄຈອນ / 'compiler/미리번역.sh', '--entry', 'ເຄື່ອງມື_ເຂົ້າໃນ.ແລ່ນ',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(ປະເພດສິ່ງຂອງ_ທາງໂຄຈອນ.glob('*.class')))
    압축해제경로 = ເລກຮາກ_ທາງໂຄຈອນ / 'vendor/uzlib'
    for ທາງໂຄຈອນ, ຊື່ in [(출력결과 / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'ຊຸດ.c', 'jar.o')] + [(압축해제경로 / (ຊື່ + '.c'), ຊື່ + '.o') for ຊື່ in ('tinflate', 'crc32', 'adler32')]:
        ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ([시언어번역기] + ການຕັ້ງຄ່າເຊື່ອມຕໍ່_ບໍລິການໂອນຍ້າຍອັດສະລິຍະໃນພື້ນຫຼັງ + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + 포함경로 + ['-c', ທາງໂຄຈອນ, '-o', 출력결과 / ຊື່])
    ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ([연결편집기, '-T', 원본자료 / 'ລິ້ງ_ຮູບແບບ.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / ຊື່ for ຊື່ in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(ເລກຮາກ_ທາງໂຄຈອນ, 시언어번역기, 연결편집기)
    시언어번역기만들기(ເລກຮາກ_ທາງໂຄຈອນ, ຣີໂພຊິທໍຣີ_ທາງໂຄຈອນ, 시언어번역기, 연결편집기, ການຕັ້ງຄ່າເຊື່ອມຕໍ່_ບໍລິການໂອນຍ້າຍອັດສະລິຍະໃນພື້ນຫຼັງ, ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ)
    유효함 = (출력결과 / 'demo.elf').read_bytes()
    ແອັບ_ສ່ວນຫົວ_ອອບເຊັດ = struct.unpack_from('<Q', 유효함, 32)[0]
