    적재구획 = [ຂໍ້ມູນ_ຈັດຕໍາແຫນ່ງ for ຂໍ້ມູນ_ຈັດຕໍາແຫນ່ງ in ສ່ວນຫົວ_ລາຍຊື່ if struct.unpack_from('<I', 유효함, ຂໍ້ມູນ_ຈັດຕໍາແຫນ່ງ)[0] == 1]
    ຂໍ້ຄວາມ, ຂໍ້ມູນ = 적재구획[:2]
