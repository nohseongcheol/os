#!/usr/bin/env python3
"""ການປະກາດ 고유번호와 UTF-8 ໄບ_ຄ່າ 위치로 자체 C 이름을 옮기는 일회성 이행 ເຄື່ອງມື.

외부 구조체의 멤버, ສະຕຣິງ_ຄ່າ, C 표준 ຟັງ_ຄ໌_ຊັນ_ຄ່າ, 이식 규약은 보존한다.
입력은 ປ່ຽນ_ແປງ_ຄ່າ 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

ໂຄງ_ການ_ເລກຮາກ = Path(__file__).resolve().parents[1]

def ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ():
    분석 = json.loads((ໂຄງ_ການ_ເລກຮາກ/'build/한국어화/시언어분석.json').read_text())
    if 분석['ຂໍ້ຜິດພາດ']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ຊື່_ຕາຕະລາງ = json.loads((ໂຄງ_ການ_ເລກຮາກ/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((ໂຄງ_ການ_ເລກຮາກ/'명명/규격이름.json').read_text()))
    ການປະກາດ_ຕາຕະລາງ = 분석['ການປະກາດ']
    바꿀선언 = {고유:ຊື່_ຕາຕະລາງ[ເຂົ້າໃນ_ຄ່າ['ຊື່']] for 고유,ເຂົ້າໃນ_ຄ່າ in ການປະກາດ_ຕາຕະລາງ.items()
                if ເຂົ້າໃນ_ຄ່າ['ຊື່'] in ຊື່_ຕາຕະລາງ and ເຂົ້າໃນ_ຄ່າ['ຊື່'] not in 규격}
    ການເຊື່ອມຕໍ່_ຕາຕະລາງ = {ເຂົ້າໃນ_ຄ່າ['ຊື່']:ຊື່_ຕາຕະລາງ[ເຂົ້າໃນ_ຄ່າ['ຊື່']] for ເຂົ້າໃນ_ຄ່າ in ການປະກາດ_ຕາຕະລາງ.values()
              if ເຂົ້າໃນ_ຄ່າ.get('ເຊື່ອມຕໍ່')==4 and ເຂົ້າໃນ_ຄ່າ['종류'] in (8,9)
              and ເຂົ້າໃນ_ຄ່າ['ຊື່'] in ຊື່_ຕາຕະລາງ and ເຂົ້າໃນ_ຄ່າ['ຊື່'] not in 규격}
    # ສ້າງ_167eff27 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ເຊື່ອມຕໍ່ 이름만 유지한다.
    머리 = ['/* 한국어 ແຫຼ່ງທີ່ມາ_ຕົ້ນໄມ້ 이름과 기존 ເຄື່ອງຈັກ ເຊື່ອມຕໍ່ ສັນຍາ_ຄ່າ. 자동 ສ້າງ_167eff27: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(ການເຊື່ອມຕໍ່_ຕາຕະລາງ.items())]
    머리 += ['#endif','']
    (ໂຄງ_ການ_ເລກຮາກ/'명명/기계연결이름.h').write_text('\n'.join(머리))
    ການປ່ຽນແປງ_ລາຍຊື່ = defaultdict(dict)
    for ຟາຍ,ອອບເຊັດ_ຄ່າ,ຊື່,고유 in 분석['ການ_ອ້າງ_ອີງ']:
        if 고유 in 바꿀선언:
            ການປ່ຽນແປງ_ລາຍຊື່[ຟາຍ][ອອບເຊັດ_ຄ່າ] = (ຊື່,바꿀선언[고유])
    ບັນທຶກ_ແຖວ = ['ຟາຍ\t원래바이트위치\t이전이름\t한국어이름']
    ບໍ່ສົນໃຈ_ຄ່າ = []
    for ຟາຍ,ປ່ຽນ_ແປງ_ຄ່າ in ການປ່ຽນແປງ_ລາຍຊື່.items():
        ທາງໂຄຈອນ = Path(ຟາຍ); 원본 = ທາງໂຄຈອນ.read_bytes(); ຂໍ້ມູນ = 원본
        for ອອບເຊັດ_ຄ່າ,(옛이름,새이름) in sorted(ປ່ຽນ_ແປງ_ຄ່າ.items(),reverse=True):
            끝 = ອອບເຊັດ_ຄ່າ+len(옛이름.encode())
            if 원본[ອອບເຊັດ_ຄ່າ:끝] != 옛이름.encode():
                ບໍ່ສົນໃຈ_ຄ່າ.append((str(ທາງໂຄຈອນ.relative_to(ໂຄງ_ການ_ເລກຮາກ)),ອອບເຊັດ_ຄ່າ,옛이름));continue
            ຂໍ້ມູນ = ຂໍ້ມູນ[:ອອບເຊັດ_ຄ່າ]+새이름.encode()+ຂໍ້ມູນ[끝:]
            ບັນທຶກ_ແຖວ.append('{}\t{}\t{}\t{}'.format(ທາງໂຄຈອນ.relative_to(ໂຄງ_ການ_ເລກຮາກ),ອອບເຊັດ_ຄ່າ,옛이름,새이름))
        ທາງໂຄຈອນ.write_bytes(ຂໍ້ມູນ)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ມາກໂຄຣ_ຄ່າ = {ເຂົ້າໃນ_ຄ່າ['ຊື່']:ຊື່_ຕາຕະລາງ[ເຂົ້າໃນ_ຄ່າ['ຊື່']] for ເຂົ້າໃນ_ຄ່າ in ການປະກາດ_ຕາຕະລາງ.values()
              if ເຂົ້າໃນ_ຄ່າ['종류']==501 and ເຂົ້າໃນ_ຄ່າ['ຊື່'] in ຊື່_ຕາຕະລາງ and ເຂົ້າໃນ_ຄ່າ['ຊື່'] not in 규격}
    for ທາງໂຄຈອນ in sorted({Path(ເຂົ້າໃນ_ຄ່າ['ຟາຍ']) for ເຂົ້າໃນ_ຄ່າ in ການປະກາດ_ຕາຕະລາງ.values()}):
        ສາຍ_ລາຍຊື່ = ທາງໂຄຈອນ.read_text().splitlines(True); 이어짐 = False
        for ດັດຊະນີ,ສາຍ in enumerate(ສາຍ_ລາຍຊື່):
            전처리 = 이어짐 or bool(re.match(r'\s*#',ສາຍ))
            이어짐 = 전처리 and ສາຍ.rstrip().endswith('\\')
            if 전처리:
                ຄົ້ນຫາ_ຕາຕະລາງ = ຊື່_ຕາຕະລາງ if re.match(r'\s*#\s*define\b',ສາຍ) or 이어짐 else ມາກໂຄຣ_ຄ່າ
                ສາຍ_ລາຍຊື່[ດັດຊະນີ] = 낱말.sub(lambda 맞음: ຄົ້ນຫາ_ຕາຕະລາງ.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],ສາຍ)
        ທາງໂຄຈອນ.write_text(''.join(ສາຍ_ລາຍຊື່))
    # 각 자체 ແປພາສາ_ແຫຼ່ງທີ່ມາ 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ທາງໂຄຈອນ in sorted({Path(ເຂົ້າໃນ_ຄ່າ['ຟາຍ']) for ເຂົ້າໃນ_ຄ່າ in ການປະກາດ_ຕາຕະລາງ.values()}):
        if ທາງໂຄຈອນ.suffix not in ('.c','.cpp'):continue
        ລຸ້ນດຽວກັນ_ຄ່າ = '../' * len(ທາງໂຄຈອນ.relative_to(ໂຄງ_ການ_ເລກຮາກ).parts[:-1]) + '명명/기계연결이름.h'
        ທາງໂຄຈອນ.write_text('#include "'+ລຸ້ນດຽວກັນ_ຄ່າ+'"\n'+ທາງໂຄຈອນ.read_text())
    (ໂຄງ_ການ_ເລກຮາກ/'명명/시언어이름대응.tsv').write_text('\n'.join(ບັນທຶກ_ແຖວ)+'\n')
    (ໂຄງ_ການ_ເລກຮາກ/'build/한국어화/전처리참조.json').write_text(json.dumps(ບໍ່ສົນໃຈ_ຄ່າ,ensure_ascii=False,indent=2)+'\n')
    print('ປ່ຽນ_ແປງ_ຄ່າ',len(ບັນທຶກ_ແຖວ)-1,'전처리 재검토',len(ບໍ່ສົນໃຈ_ຄ່າ),'ເຄື່ອງຈັກ ເຊື່ອມຕໍ່',len(ການເຊື່ອມຕໍ່_ຕາຕະລາງ))

if __name__=='__main__': ປະ_ຕິ_ບັດ_ຄໍາສັ່ງ()
