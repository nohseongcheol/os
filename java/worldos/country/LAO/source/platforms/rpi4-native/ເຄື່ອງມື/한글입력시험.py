#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from ເດັສທັອບ_ເບິ່ງ import ແປ້ນພິມ


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ = ''
        def ສົ່ງ(ຂໍ້ມູນ):
            for ຕົວອັກສອນ_ຂໍ້ມູນ in ຂໍ້ມູນ.decode('utf-8'):
                if ຕົວອັກສອນ_ຂໍ້ມູນ == '\x7f': 자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ = 자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ[:-1]
                else: 자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ += ຕົວອັກສອນ_ຂໍ້ມູນ
        자신.ແປ້ນພິມ_ເຂົ້າໃນ = ແປ້ນພິມ(ສົ່ງ)

    def 글쇠누르기(자신, ສັນຍາລັກ_ຄ່າ):
        자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(True, ສັນຍາລັກ_ຄ່າ)
        자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(False, ສັນຍາລັກ_ຄ່າ)

    def ພິມ_ຫມວດ(자신, 누름열):
        for 누름값 in 누름열: 자신.글쇠누르기(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.글쇠누르기(0xffc6); 자신.ພິມ_ຫມວດ(누름열)
                자신.assertEqual(자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ, 예상결과)

    def test_앞글자지우기(자신):
        자신.글쇠누르기(0xff31); 자신.ພິມ_ຫມວດ('dlfr')
        자신.assertEqual(자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.글쇠누르기(0xff08); 자신.assertEqual(자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ,예상결과)
        자신.ພິມ_ຫມວດ('gksk'); 자신.assertEqual(자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ,'하나')
        자신.글쇠누르기(0xff08); 자신.assertEqual(자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ,'하ㄴ')

    def test_전환반복확정(자신):
        자신.ພິມ_ຫມວດ('echo ')
        자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(True,0xffe1)
        자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(True,32); 자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(True,32)
        자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(False,32); 자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(False,0xffe1)
        자신.assertTrue(자신.ແປ້ນພິມ_ເຂົ້າໃນ.한글여부)
        자신.ພິມ_ຫມວດ('gksrmf'); 자신.글쇠누르기(0xff31); 자신.ພິມ_ຫມວດ(' English')
        자신.assertEqual(자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ,'echo 한글 English')
        자신.assertFalse(자신.ແປ້ນພິມ_ເຂົ້າໃນ.한글여부)
        자신.글쇠누르기(0xffc6); 자신.ພິມ_ຫມວດ('rk'); 자신.글쇠누르기(0xff51)
        자신.ພິມ_ຫມວດ('sk'); 자신.assertTrue(자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.글쇠누르기(0xffc6); 자신.ພິມ_ຫມວດ('rk')
        자신.ແປ້ນພິມ_ເຂົ້າໃນ.ຄລິບບອດ_ຄ່າ='ວາງ_ຄ່າ'.encode()
        자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(True,0xffe3); 자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(True,0xffe1)
        자신.글쇠누르기(ord('v'))
        자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(False,0xffe1); 자신.ແປ້ນພິມ_ເຂົ້າໃນ.누름값(False,0xffe3)
        자신.글쇠누르기(0x0100d55c); 자신.ພິມ_ຫມວດ('sk')
        자신.assertEqual(자신.ຂໍ້ຄວາມ_ບ່ອນເກັບຊົ່ວຄາວ,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
