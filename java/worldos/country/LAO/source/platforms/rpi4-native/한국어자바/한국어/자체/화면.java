package 한국어.자체;
/** 화면(畫面): 부팅 때 선택한 크기의 자체 ແກນກາງ_ຄ່າ RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int ຄ່າ = ແກນກາງ_ຄ່າ.화면너비(); if (ຄ່າ < 0) throw new ສະຖານະ_ຂໍ້ຍົກເວັ້ນ("프레임버퍼 없음"); return ຄ່າ; }
    public static int 높이() { int ຄ່າ = ແກນກາງ_ຄ່າ.화면높이(); if (ຄ່າ < 0) throw new ສະຖານະ_ຂໍ້ຍົກເວັ້ນ("프레임버퍼 없음"); return ຄ່າ; }
    public static void 사각형(int 가로, int ລວງຕັ້ງ_ຈັດຕໍາແຫນ່ງ, int 폭, int 높이, int 색) {
        if (가로 < 0 || ລວງຕັ້ງ_ຈັດຕໍາແຫນ່ງ < 0 || 폭 < 0 || 높이 < 0 || 가로 > 너비() || ລວງຕັ້ງ_ຈັດຕໍາແຫນ່ງ > 높이() || 폭 > 너비() - 가로 || 높이 > 높이() - ລວງຕັ້ງ_ຈັດຕໍາແຫນ່ງ) throw new ໃຊ້ບໍ່ໄດ້_ຂໍ້ພິສູດ_ຂໍ້ຍົກເວັ້ນ("화면 ຄ_ລິບ");
        if (ແກນກາງ_ຄ່າ.사각형(가로, ລວງຕັ້ງ_ຈັດຕໍາແຫນ່ງ, 폭, 높이, 색) < 0) throw new ສະຖານະ_ຂໍ້ຍົກເວັ້ນ("프레임버퍼 없음");
    }
    public static void ລຶບ_ເຂົ້າໃນ(int 색) { 사각형(0, 0, 너비(), 높이(), 색); }
    public static void 기다리기() { if (ແກນກາງ_ຄ່າ.그림대기() < 0) throw new ສະຖານະ_ຂໍ້ຍົກເວັ້ນ("ແບບໂຕ້ຕອບ 입력 필요"); }
}
