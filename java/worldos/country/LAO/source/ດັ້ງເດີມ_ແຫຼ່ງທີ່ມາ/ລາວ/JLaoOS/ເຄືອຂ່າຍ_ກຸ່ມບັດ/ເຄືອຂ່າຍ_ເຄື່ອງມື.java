/** Ethernet/ARP/IPv4/ICMP/UDP 계층이 공유하는 ໄບ_ຄ່າ 순서와 검사합 도구다. */
public final class ເຄືອຂ່າຍ_ເຄື່ອງມື {
    private ເຄືອຂ່າຍ_ເຄື່ອງມື() {
    }

    public static int 큰순서짧은정수(byte[] ຂໍ້ມູນ, int ຈັດຕໍາແຫນ່ງ) {
        범위확인(ຂໍ້ມູນ, ຈັດຕໍາແຫນ່ງ, 2);
        return ((ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ] & 0xff) << 8) | (ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ + 1] & 0xff);
    }

    public static long 큰순서정수(byte[] ຂໍ້ມູນ, int ຈັດຕໍາແຫນ່ງ) {
        범위확인(ຂໍ້ມູນ, ຈັດຕໍາແຫນ່ງ, 4);
        return ((long) (ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ] & 0xff) << 24)
                | ((long) (ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ + 1] & 0xff) << 16)
                | ((long) (ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ + 2] & 0xff) << 8)
                | (ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ + 3] & 0xffL);
    }

    public static int 인터넷검사합(byte[] ຂໍ້ມູນ, int ແລ່ນ, int ຄວາມຍາວ_ຄ່າ) {
        범위확인(ຂໍ້ມູນ, ແລ່ນ, ຄວາມຍາວ_ຄ່າ);
        long 합 = 0;
        int 끝 = ແລ່ນ + ຄວາມຍາວ_ຄ່າ;
        int ຈັດຕໍາແຫນ່ງ = ແລ່ນ;
        while (ຈັດຕໍາແຫນ່ງ + 1 < 끝) {
            합 += 큰순서짧은정수(ຂໍ້ມູນ, ຈັດຕໍາແຫນ່ງ);
            ຈັດຕໍາແຫນ່ງ += 2;
        }
        if (ຈັດຕໍາແຫນ່ງ < 끝) {
            합 += (ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ] & 0xff) << 8;
        }
        while ((합 >>> 16) != 0) {
            합 = (합 & 0xffff) + (합 >>> 16);
        }
        return (int) (~합) & 0xffff;
    }

    public static boolean ເທັກໂນໂລຢີຂໍ້ມູນຂ່າວສານ_ການເຊື່ອມຕໍ່ແບບຜ່ານສາຍ_ກອບ(byte[] ຂໍ້ມູນ) {
        return ຂໍ້ມູນ != null && ຂໍ້ມູນ.length >= 14;
    }

    public static int 이더넷상위규약(byte[] ຂໍ້ມູນ) {
        if (!ເທັກໂນໂລຢີຂໍ້ມູນຂ່າວສານ_ການເຊື່ອມຕໍ່ແບບຜ່ານສາຍ_ກອບ(ຂໍ້ມູນ)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return 큰순서짧은정수(ຂໍ້ມູນ, 12);
    }

    public static boolean 상호통신망규약사판인가(byte[] ຂໍ້ມູນ, int ຈັດຕໍາແຫນ່ງ) {
        if (ຂໍ້ມູນ == null || ຈັດຕໍາແຫນ່ງ < 0 || ຂໍ້ມູນ.length - ຈັດຕໍາແຫນ່ງ < 20) {
            return false;
        }
        int 판 = (ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ] >>> 4) & 0xf;
        int ສ່ວນຫົວ_ຄວາມຍາວ = (ຂໍ້ມູນ[ຈັດຕໍາແຫນ່ງ] & 0xf) * 4;
        return 판 == 4 && ສ່ວນຫົວ_ຄວາມຍາວ >= 20 && ຂໍ້ມູນ.length - ຈັດຕໍາແຫນ່ງ >= ສ່ວນຫົວ_ຄວາມຍາວ;
    }

    private static void 범위확인(byte[] ຂໍ້ມູນ, int ແລ່ນ, int ຄວາມຍາວ_ຄ່າ) {
        if (ຂໍ້ມູນ == null || ແລ່ນ < 0 || ຄວາມຍາວ_ຄ່າ < 0 || ແລ່ນ > ຂໍ້ມູນ.length - ຄວາມຍາວ_ຄ່າ) {
            throw new IllegalArgumentException("ເຄືອຂ່າຍ_ກຸ່ມບັດ ຂໍ້ມູນ 범위를 벗어났습니다.");
        }
    }
}

