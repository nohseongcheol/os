#include "호출경계.h"
extern int main(int 인수개수, char **արգումենտ_Ցուցակ);
static char արգումենտ_Հիշողություն[2048];
static char *արգումենտ_Ցուցակ[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 կատարել_հրաման 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    արգումենտ_Ցուցակ[0] = "jkoros-app";
    int Դիրք = 0;
    for (int դասիչ = 0; դասիչ < 개수; դասիչ++) {
        const int *원본 = (const int *)jkoros_syscall(3, դասիչ, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        արգումենտ_Ցուցակ[դասիչ + 1] = արգումենտ_Հիշողություն + Դիրք;
        for (int փորակ_մուտքագրում = 0; փորակ_մուտքագրում < 원본[0]; փորակ_մուտքագրում++) {
            if (Դիրք >= 2047) return 126;
            արգումենտ_Հիշողություն[Դիրք++] = 원본[փորակ_մուտքագրում + 1];
        }
        արգումենտ_Հիշողություն[Դիրք++] = 0;
    }
    արգումենտ_Ցուցակ[개수 + 1] = 0;
    return main(개수 + 1, արգումենտ_Ցուցակ);
}
