#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 බයිටය_අගය 위치로 자체 C 이름을 옮기는 일회성 이행 මෙවලම්.

외부 구조체의 멤버, අනුලකුණු_වැල_අගය, C 표준 ශ්_රිතය_අගය, 이식 규약은 보존한다.
입력은 වෙනස්_කරන්න_අගය 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def ක්_රියාත්මක_කරන්න_විධානය():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['දෝෂය']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    නම_වගුව = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {අනන්_ය_අගය:නම_වගුව[පිවිසුම_අගය['නම']] for අනන්_ය_අගය,පිවිසුම_අගය in 선언표.items()
                if පිවිසුම_අගය['නම'] in නම_වගුව and පිවිසුම_අගය['නම'] not in 규격}
    සබැඳුම_වගුව = {පිවිසුම_අගය['නම']:නම_වගුව[පිවිසුම_අගය['නම']] for පිවිසුම_අගය in 선언표.values()
              if පිවිසුම_අගය.get('සම්බන්ද_වන්න')==4 and පිවිසුම_අගය['종류'] in (8,9)
              and පිවිසුම_අගය['නම'] in නම_වගුව and පිවිසුම_අගය['නම'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 සම්බන්ද_වන්න 이름만 유지한다.
    머리 = ['/* 한국어 මූලය_රුක 이름과 기존 යන්ත්_රය සම්බන්ද_වන්න කාරණය_අගය. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(සබැඳුම_වගුව.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    වෙනස්කම්_ලැයිස්තුව = defaultdict(dict)
    for ගොනු,ඕෆ්සෙට්_අගය,නම,අනන්_ය_අගය in 분석['පරිශීලනය']:
        if අනන්_ය_අගය in 바꿀선언:
            වෙනස්කම්_ලැයිස්තුව[ගොනු][ඕෆ්සෙට්_අගය] = (නම,바꿀선언[අනන්_ය_අගය])
    ලොගය_පේළිය = ['ගොනු\t원래바이트위치\t이전이름\t한국어이름']
    නොතකන්න_අගය = []
    for ගොනු,වෙනස්_කරන්න_අගය in වෙනස්කම්_ලැයිස්තුව.items():
        මාර්_ගය = Path(ගොනු); 원본 = මාර්_ගය.read_bytes(); දත්ත = 원본
        for ඕෆ්සෙට්_අගය,(옛이름,새이름) in sorted(වෙනස්_කරන්න_අගය.items(),reverse=True):
            끝 = ඕෆ්සෙට්_අගය+len(옛이름.encode())
            if 원본[ඕෆ්සෙට්_අගය:끝] != 옛이름.encode():
                නොතකන්න_අගය.append((str(මාර්_ගය.relative_to(기준)),ඕෆ්සෙට්_අගය,옛이름));continue
            දත්ත = දත්ත[:ඕෆ්සෙට්_අගය]+새이름.encode()+දත්ත[끝:]
            ලොගය_පේළිය.append('{}\t{}\t{}\t{}'.format(මාර්_ගය.relative_to(기준),ඕෆ්සෙට්_අගය,옛이름,새이름))
        මාර්_ගය.write_bytes(දත්ත)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    නියෝග_එකලස_අගය = {පිවිසුම_අගය['නම']:නම_වගුව[පිවිසුම_අගය['නම']] for පිවිසුම_අගය in 선언표.values()
              if පිවිසුම_අගය['종류']==501 and පිවිසුම_අගය['නම'] in නම_වගුව and පිවිසුම_අගය['නම'] not in 규격}
    for මාර්_ගය in sorted({Path(පිවිසුම_අගය['ගොනු']) for පිවිසුම_අගය in 선언표.values()}):
        පේළිය_ලැයිස්තුව = මාර්_ගය.read_text().splitlines(True); 이어짐 = False
        for සූචිය,පේළිය in enumerate(පේළිය_ලැයිස්තුව):
            전처리 = 이어짐 or bool(re.match(r'\s*#',පේළිය))
            이어짐 = 전처리 and පේළිය.rstrip().endswith('\\')
            if 전처리:
                표 = නම_වගුව if re.match(r'\s*#\s*define\b',පේළිය) or 이어짐 else නියෝග_එකලස_අගය
                පේළිය_ලැයිස්තුව[සූචිය] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],පේළිය)
        මාර්_ගය.write_text(''.join(පේළිය_ලැයිස්තුව))
    # 각 자체 පරිවර්තනය_මූලය 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for මාර්_ගය in sorted({Path(පිවිසුම_අගය['ගොනු']) for පිවිසුම_අගය in 선언표.values()}):
        if මාර්_ගය.suffix not in ('.c','.cpp'):continue
        සමානයා_අගය = '../' * len(මාර්_ගය.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        මාර්_ගය.write_text('#include "'+සමානයා_අගය+'"\n'+මාර්_ගය.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(ලොගය_පේළිය)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(නොතකන්න_අගය,ensure_ascii=False,indent=2)+'\n')
    print('වෙනස්_කරන්න_අගය',len(ලොගය_පේළිය)-1,'전처리 재검토',len(නොතකන්න_අගය),'යන්ත්_රය සම්බන්ද_වන්න',len(සබැඳුම_වගුව))

if __name__=='__main__': ක්_රියාත්මක_කරන්න_විධානය()
