        자신.assertTrue(자신.விசைப்பலகை_உள்ளீடு.한글여부)
        자신.வகை_வகை('gksrmf'); 자신.글쇠누르기(0xff31); 자신.வகை_வகை(' English')
        자신.assertEqual(자신.உரை_இடையகம்,'echo 한글 English')
        자신.assertFalse(자신.விசைப்பலகை_உள்ளீடு.한글여부)
        자신.글쇠누르기(0xffc6); 자신.வகை_வகை('rk'); 자신.글쇠누르기(0xff51)
        자신.வகை_வகை('sk'); 자신.assertTrue(자신.உரை_இடையகம்.endswith('가\x1b[D나'))

