from русский import системная_ошибка, 다시시도오류, открыть_датаграмма, получить_датаграмма, Close_сеть, чтение_файл, текстовыйВывод

участник = открыть_датаграмма(0)
try:
    try:
        получить_датаграмма(участник)
        raise AssertionError("비어 있는 датаграмма 대기에서 예외가 필요합니다.")
    except системная_ошибка as ошибка:
        assert ошибка.ИНДЕКС == 다시시도오류
        assert ошибка.описание == "операционная_система 작업에 실패했습니다."
        текстовыйВывод("русский датаграмма исключение проверять")
finally:
    Close_сеть(участник)
try:
    чтение_файл("/없는파일")
except системная_ошибка as ошибка:
    assert ошибка.ИНДЕКС == 2
    текстовыйВывод("русский файл исключение проверять")
else:
    raise AssertionError("файл 없음 예외가 필요합니다.")
