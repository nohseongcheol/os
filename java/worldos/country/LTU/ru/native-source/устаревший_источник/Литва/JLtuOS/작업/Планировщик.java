package Литва.JLtuOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Литва.JLtuOS.Память_регион.страница_менеджер;
import Литва.JLtuOS.файловая_система.файл_дескриптор_таблица;

/** Процесс_ЗНАЧЕН 식별자와 라운드로빈 Подготовить 대기열을 관리한다. */
public final class Планировщик {
    private final страница_менеджер 쪽관리;
    private final Map<Integer, Процесс_ЗНАЧЕН> Список_процессов = new HashMap<Integer, Процесс_ЗНАЧЕН>();
    private final Queue<Процесс_ЗНАЧЕН> 준비대기열 = new ArrayDeque<Процесс_ЗНАЧЕН>();
    private int Далее_идентификатор = 1;

    public Планировщик(страница_менеджер 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public Процесс_ЗНАЧЕН 첫과정(файл_дескриптор_таблица файл_дескриптор) {
        Процесс_ЗНАЧЕН 새과정 = new Процесс_ЗНАЧЕН(выделить_идентификатор(), 0, 쪽관리.새주소공간(), файл_дескриптор);
        Список_процессов.put(Integer.valueOf(새과정.идентификатор_ЗНАЧЕН()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public Процесс_ЗНАЧЕН клон_ЗНАЧЕН(Процесс_ЗНАЧЕН родительский_ЗНАЧЕН) {
        Процесс_ЗНАЧЕН ребенок_ЗНАЧЕН = new Процесс_ЗНАЧЕН(
                выделить_идентификатор(),
                родительский_ЗНАЧЕН.идентификатор_ЗНАЧЕН(),
                쪽관리.клон_копирование_при_записи(родительский_ЗНАЧЕН.диапазон_адресов()),
                родительский_ЗНАЧЕН.файл_дескриптор().клон_ЗНАЧЕН());
        ребенок_ЗНАЧЕН.сет_программа_останов(родительский_ЗНАЧЕН.программа_останов());
        Список_процессов.put(Integer.valueOf(ребенок_ЗНАЧЕН.идентификатор_ЗНАЧЕН()), ребенок_ЗНАЧЕН);
        준비대기열.offer(ребенок_ЗНАЧЕН);
        return ребенок_ЗНАЧЕН;
    }

    public Процесс_ЗНАЧЕН Далее_Процесс() {
        int чек_СЧЁТ = 준비대기열.size();
        for (int ИНДЕКС = 0; ИНДЕКС < чек_СЧЁТ; ИНДЕКС++) {
            Процесс_ЗНАЧЕН Далее_товар = 준비대기열.poll();
            if (Далее_товар != null && (Далее_товар.Состояние_ЗНАЧЕН() == Процесс_Состояние.Подготовить || Далее_товар.Состояние_ЗНАЧЕН() == Процесс_Состояние.실행)) {
                Далее_товар.сет_Состояние(Процесс_Состояние.실행);
                준비대기열.offer(Далее_товар);
                return Далее_товар;
            }
        }
        return null;
    }

    public int 자식기다리기(Процесс_ЗНАЧЕН родительский_ЗНАЧЕН, int ребенок_идентификатор, boolean 기다리지않음) {
        for (Процесс_ЗНАЧЕН соискатель : Список_процессов.values()) {
            if (соискатель.родительский_идентификатор() != родительский_ЗНАЧЕН.идентификатор_ЗНАЧЕН()) {
                continue;
            }
            if (ребенок_идентификатор > 0 && соискатель.идентификатор_ЗНАЧЕН() != ребенок_идентификатор) {
                continue;
            }
            if (соискатель.Состояние_ЗНАЧЕН() == Процесс_Состояние.Выход_программа) {
                int результат = (соискатель.код_выхода() & 0xff) << 8;
                Список_процессов.remove(Integer.valueOf(соискатель.идентификатор_ЗНАЧЕН()));
                return результат;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public Процесс_ЗНАЧЕН НАЙТИ_Процесс(int идентификатор_ЗНАЧЕН) {
        return Список_процессов.get(Integer.valueOf(идентификатор_ЗНАЧЕН));
    }

    private int выделить_идентификатор() {
        return Далее_идентификатор++;
    }
}
