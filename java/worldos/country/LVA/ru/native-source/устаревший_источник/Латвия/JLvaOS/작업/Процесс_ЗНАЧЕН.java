package Латвия.JLvaOS.작업;

import Латвия.JLvaOS.Память_регион.страница_менеджер;
import Латвия.JLvaOS.файловая_система.файл_дескриптор_таблица;

public final class Процесс_ЗНАЧЕН {
    private final int идентификатор_ЗНАЧЕН;
    private final int родительский_идентификатор;
    private final страница_менеджер.диапазон_адресов диапазон_адресов;
    private final файл_дескриптор_таблица файл_дескриптор;
    private Процесс_Состояние Состояние_ЗНАЧЕН = Процесс_Состояние.Подготовить;
    private int код_выхода;
    private int программа_останов = 0x06000000;
    private int выполнение_Пуск_АДРЕС;
    private String[] выполнение_аргумент = new String[0];
    private String[] среда_ЗНАЧЕН = new String[0];

    Процесс_ЗНАЧЕН(int идентификатор_ЗНАЧЕН, int родительский_идентификатор, страница_менеджер.диапазон_адресов диапазон_адресов, файл_дескриптор_таблица файл_дескриптор) {
        this.идентификатор_ЗНАЧЕН = идентификатор_ЗНАЧЕН;
        this.родительский_идентификатор = родительский_идентификатор;
        this.диапазон_адресов = диапазон_адресов;
        this.файл_дескриптор = файл_дескриптор;
    }

    public int идентификатор_ЗНАЧЕН() {
        return идентификатор_ЗНАЧЕН;
    }

    public int родительский_идентификатор() {
        return родительский_идентификатор;
    }

    public страница_менеджер.диапазон_адресов диапазон_адресов() {
        return диапазон_адресов;
    }

    public файл_дескриптор_таблица файл_дескриптор() {
        return файл_дескриптор;
    }

    public Процесс_Состояние Состояние_ЗНАЧЕН() {
        return Состояние_ЗНАЧЕН;
    }

    public void сет_Состояние(Процесс_Состояние 새상태) {
        Состояние_ЗНАЧЕН = 새상태;
    }

    public int код_выхода() {
        return код_выхода;
    }

    public void Выход_программа(int ЗНАЧЕН) {
        код_выхода = ЗНАЧЕН & 0xff;
        Состояние_ЗНАЧЕН = Процесс_Состояние.Выход_программа;
    }

    public int программа_останов() {
        return программа_останов;
    }

    public void сет_программа_останов(int 새끝) {
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            throw new IllegalArgumentException("программа_f5044b9b 끝 범위를 벗어났습니다.");
        }
        программа_останов = 새끝;
    }

    public void сет_контекст(int Пуск_АДРЕС, String[] параметр_аргумент, String[] среда) {
        выполнение_Пуск_АДРЕС = Пуск_АДРЕС;
        выполнение_аргумент = параметр_аргумент.clone();
        среда_ЗНАЧЕН = среда.clone();
    }

    public int выполнение_Пуск_АДРЕС() { return выполнение_Пуск_АДРЕС; }
    public String[] выполнение_аргумент() { return выполнение_аргумент.clone(); }
    public String[] среда_ЗНАЧЕН() { return среда_ЗНАЧЕН.clone(); }
}
