import java.util.Arrays;

/** 在 JVM 中调用实际的 Java 协议处理器，快速检查边界和损坏的输入。 */
public final class 数据包测试 {
    static int 重复状态个数 = 0;
    static void 验证(boolean 值) { if (!值) throw new AssertionError("case " + 重复状态个数); 重复状态个数++; }
    static int 校验和(int[] 值, int 运行, int 长度, int 初始状态) {
        int 总和值 = 初始状态;
        for (int 编号 = 0; 编号 < 长度; 编号++) 总和值 += 值[运行 + 编号] << ((编号 & 1) == 0 ? 8 : 0);
        总和值 = (总和值 & 65535) + (总和值 >>> 16);
        总和值 = (总和值 & 65535) + (总和值 >>> 16);
        return ~总和值 & 65535;
    }
    static void 准备(int 长度) {
        通信网络.清洁进程();
        验证(通信网络.打开(5000) == 3);
        int[] 帧索引 = 通信网络.输入帧;
        Arrays.fill(帧索引, 0);
        for (int 编号 = 0; 编号 < 6; 编号++) 帧索引[编号] = 网络设备驱动.设备地址[编号];
        通信网络.放入16(帧索引, 12, 0x0800);
        帧索引[14] = 0x45; 帧索引[22] = 64; 帧索引[23] = 17;
        通信网络.放入16(帧索引, 16, 28 + 长度);
        通信网络.放入32(帧索引, 26, 0x0a000202); 通信网络.放入32(帧索引, 30, 通信网络.自有对象地址);
        通信网络.放入16(帧索引, 34, 4321); 通信网络.放入16(帧索引, 36, 5000); 通信网络.放入16(帧索引, 38, 长度 + 8);
        for (int 编号 = 0; 编号 < 长度; 编号++) 帧索引[42 + 编号] = 编号 & 255;
        设定校验和(长度);
    }
    static void 设定校验和(int 长度) {
        int[] 帧索引 = 通信网络.输入帧;
        通信网络.放入16(帧索引, 24, 0); 通信网络.放入16(帧索引, 40, 0);
        通信网络.放入16(帧索引, 24, 校验和(帧索引, 14, 20, 0));
        int 初始状态 = 通信网络.伪头部校验和(通信网络.整数32(帧索引, 26), 通信网络.自有对象地址, 长度 + 8);
        int 总和值 = 校验和(帧索引, 34, 长度 + 8, 初始状态);
        通信网络.放入16(帧索引, 40, 总和值 == 0 ? 65535 : 总和值);
    }
    static void 拒绝值(int 长度) { 通信网络.进程帧(长度); 验证(通信网络.已接收长度[0] == -1); }
    public static void main(String[] 实参) {
        for (int 长度 : new int[]{0, 1, 2, 7, 1023, 1024}) {
            准备(长度); 通信网络.进程帧(长度 + 42);
            验证(通信网络.已接收长度[0] == 长度);
            验证(通信网络.已接收地址[0] == 0x0a000202 && 通信网络.已接收端口编号[0] == 4321);
            for (int 编号 = 0; 编号 < 长度; 编号++) 验证(通信网络.已接收数据[编号] == (编号 & 255));
        }
        for (int 长度 = 0; 长度 < 42; 长度++) { 准备(0); 拒绝值(长度); }
        准备(1025); 拒绝值(1067);
        准备(2); 通信网络.输入帧[24] ^= 1; 拒绝值(44);
        准备(2); 通信网络.输入帧[42] ^= 1; 拒绝值(44);
        准备(2); 通信网络.放入16(通信网络.输入帧, 38, 7); 拒绝值(44);
        准备(2); 通信网络.放入16(通信网络.输入帧, 38, 65535); 拒绝值(44);
        准备(2); 通信网络.输入帧[14] = 0x4f; 拒绝值(44);
        准备(2); 通信网络.输入帧[14] = 0x44; 拒绝值(44);
        准备(2); 通信网络.输入帧[20] = 0x20; 设定校验和(2); 拒绝值(44);
        准备(2); 通信网络.输入帧[21] = 1; 设定校验和(2); 拒绝值(44);
        准备(2); 通信网络.输入帧[33] = 99; 设定校验和(2); 拒绝值(44);
        准备(2); 通信网络.输入帧[0] ^= 1; 拒绝值(44);
        准备(2); 通信网络.输入帧[23] = 6; 设定校验和(2); 拒绝值(44);
        准备(2); 通信网络.放入16(通信网络.输入帧, 40, 0); 通信网络.进程帧(44); 验证(通信网络.已接收长度[0] == 2);
        int[] 结果 = new int[4];
        验证(通信网络.接收(3, 结果, 1, 0) == -90);
        验证(通信网络.接收(3, 结果, 4, 0) == -11);
        准备(2); 通信网络.进程帧(44); int 丢弃值 = 通信网络.已丢弃个数;
        通信网络.进程帧(44); 验证(通信网络.已丢弃个数 == 丢弃值 + 1);
        通信网络.清洁进程(); 验证(通信网络.打开(5000) == 3);
        验证(通信网络.打开(5000) == -98); 验证(通信网络.打开(0) == 4);
        验证(通信网络.打开(0) == 5); 验证(通信网络.打开(0) == 6); 验证(通信网络.打开(0) == -24);
        验证(通信网络.关闭(4) == 0); 验证(通信网络.关闭(4) == -9);
        通信网络.已找到地址 = 通信网络.网关值;
        验证(通信网络.发送(3, 通信网络.网关值, 4321, new int[]{1, 2, 3}, 3) == 3);
        int[] 拥有已发送 = 网络设备驱动.最近值;
        验证(校验和(拥有已发送, 14, 20, 0) == 0);
        验证(校验和(拥有已发送, 34, 11, 通信网络.伪头部校验和(通信网络.自有对象地址, 通信网络.网关值, 11)) == 0);
        验证(拥有已发送[42] == 1 && 拥有已发送[44] == 3);
        System.out.println("PACKET TEST PASS: " + 重复状态个数 + " assertions");
    }
}
