/** 驗證唯讀執行套件內的 ELF32，傳遞引數，每次執行一個使用者行程。 */
public final class 執行管理 {
    static final int 開始用戶程式 = 0x04000000;
    static final int 用戶結束 = 0x04400000;
    static final int 映像結束地址 = 0x04200000;
    static final int 實際參數開始 = 0x04300000;
    static int 實際參數個數 = 0;
    static int[] 實際參數地址 = new int[16];

    static boolean 裁剪(int 地址, int 長度) {
        return 地址 >= 開始用戶程式 && 地址 < 用戶結束 && 長度 >= 0 && 長度 <= 用戶結束 - 地址;
    }

    static int 數(int 地址) { return 記憶體空間.解析整數(地址); }
    static int 短整數值(int 地址) { return 設備.讀取記憶體(地址) | 設備.讀取記憶體(地址 + 1) << 8; }
    static void 寫入編號(int 地址, int 值) {
        for (int 編號 = 0; 編號 < 4; 編號++) 設備.寫入記憶體(地址 + 編號, 值 >>> (編號 * 8));
    }

    static int 組個數() {
        int 地址 = 設備.可執行文件捆綁();
        int 大小 = 設備.可執行文件捆綁大小();
        if (大小 < 8 || 數(地址) != 0x50414b4a) return 0;
        int 項目個數 = 數(地址 + 4);
        return 項目個數 >= 0 && 項目個數 <= 32 && 項目個數 <= (大小 - 8) / 24 ? 項目個數 : 0;
    }

    static void 條目列表() {
        for (int 編號 = 0; 編號 < 組個數(); 編號++) {
            int 條目值 = 設備.可執行文件捆綁() + 8 + 編號 * 24;
            for (int 字元值 = 0; 字元值 < 16 && 設備.讀取記憶體(條目值 + 字元值) != 0; 字元值++)
                字元終端.字元(設備.讀取記憶體(條目值 + 字元值));
            字元終端.寫入("\n");
        }
    }

    static int 查找條目(int[] 輸入值, int 運行, int 長度) {
        if (長度 <= 0 || 長度 >= 16) return 0;
        for (int 編號 = 0; 編號 < 組個數(); 編號++) {
            int 條目值 = 設備.可執行文件捆綁() + 8 + 編號 * 24;
            boolean 相等文本 = 設備.讀取記憶體(條目值 + 長度) == 0;
            for (int 字元值 = 0; 字元值 < 長度; 字元值++)
                if (輸入值[運行 + 字元值] != 設備.讀取記憶體(條目值 + 字元值)) 相等文本 = false;
            if (相等文本) return 條目值;
        }
        return 0;
    }

    static int 有效性校驗(int 檔案, int 長度) {
        if (長度 < 52 || 數(檔案) != 0x464c457f || 設備.讀取記憶體(檔案 + 4) != 1
            || 設備.讀取記憶體(檔案 + 5) != 1 || 設備.讀取記憶體(檔案 + 6) != 1
            || 短整數值(檔案 + 16) != 2 || 短整數值(檔案 + 18) != 3 || 數(檔案 + 20) != 1
            || 短整數值(檔案 + 40) != 52 || 短整數值(檔案 + 42) != 32) return -8;
        int 條目分值 = 數(檔案 + 24);
        int 表位置 = 數(檔案 + 28);
        int 項目個數 = 短整數值(檔案 + 44);
        if (項目個數 == 0 || 項目個數 > 16 || 表位置 < 52 || 表位置 > 長度 - 項目個數 * 32) return -8;
        boolean 是否可執行文件 = false;
        for (int 編號 = 0; 編號 < 項目個數; 編號++) {
            int 表 = 檔案 + 表位置 + 編號 * 32;
            int 種類值 = 數(表);
            if (種類值 == 2 || 種類值 == 3) return -8; // 不支援動態連結或直譯器。
            if (種類值 != 1) continue;
            int 位置 = 數(表 + 4), 地址 = 數(表 + 8), 檔案大小 = 數(表 + 16), 記憶體大小 = 數(表 + 20);
            int 對齊值 = 數(表 + 28);
            if (地址 < 開始用戶程式 || 地址 >= 映像結束地址 || 記憶體大小 < 0 || 記憶體大小 > 映像結束地址 - 地址
                || 檔案大小 < 0 || 檔案大小 > 記憶體大小 || 位置 < 0 || (檔案大小 > 0 && 位置 > 長度 - 檔案大小)
                || (對齊值 != 0 && (對齊值 < 0 || (對齊值 & (對齊值 - 1)) != 0
                    || ((地址 - 位置) & (對齊值 - 1)) != 0))) return -8;
            for (int 前端值 = 0; 前端值 < 編號; 前端值++) {
                int 上一個項目 = 檔案 + 表位置 + 前端值 * 32;
                if (數(上一個項目) == 1 && 記憶體大小 > 0 && 數(上一個項目 + 20) > 0
                    && 地址 < 數(上一個項目 + 8) + 數(上一個項目 + 20) && 數(上一個項目 + 8) < 地址 + 記憶體大小) return -8;
            }
            if ((數(表 + 24) & 1) != 0 && 條目分值 >= 地址 && 條目分值 - 地址 < 檔案大小) 是否可執行文件 = true;
        }
        return 是否可執行文件 ? 條目分值 : -8;
    }

    static int 執行命令(int[] 輸入值, int 運行, int 長度) {
        while (運行 < 長度 && 輸入值[運行] == ' ') 運行++;
        int 結尾 = 運行;
        while (結尾 < 長度 && 輸入值[結尾] != ' ') 結尾++;
        int 條目值 = 查找條目(輸入值, 運行, 結尾 - 運行);
        if (條目值 == 0) return -2;
        int 位置 = 數(條目值 + 16), 大小 = 數(條目值 + 20);
        if (位置 < 8 + 組個數() * 24 || 大小 < 52 || 位置 > 設備.可執行文件捆綁大小() - 大小) return -8;
        int 檔案 = 設備.可執行文件捆綁() + 位置;
        int 條目分值 = 有效性校驗(檔案, 大小);
        if (條目分值 < 0) return 條目分值;
        設備.用戶清空內容();
        int 表位置 = 數(檔案 + 28), 項目個數 = 短整數值(檔案 + 44);
        for (int 編號 = 0; 編號 < 項目個數; 編號++) {
            int 表 = 檔案 + 表位置 + 編號 * 32;
            if (數(表) != 1) continue;
            int 原始 = 檔案 + 數(表 + 4), 目的地址值 = 數(表 + 8), 檔案大小 = 數(表 + 16);
            for (int 位元組值 = 0; 位元組值 < 檔案大小; 位元組值++) 設備.寫入記憶體(目的地址值 + 位元組值, 設備.讀取記憶體(原始 + 位元組值));
        }
        實際參數個數 = 0;
        int 存儲值 = 實際參數開始;
        while (結尾 < 長度) {
            while (結尾 < 長度 && 輸入值[結尾] == ' ') 結尾++;
            if (結尾 == 長度) break;
            if (實際參數個數 == 實際參數地址.length) return -22;
            運行 = 結尾;
            while (結尾 < 長度 && 輸入值[結尾] != ' ') 結尾++;
            實際參數地址[實際參數個數++] = 存儲值;
            寫入編號(存儲值, 結尾 - 運行);
            for (int 字元值 = 運行; 字元值 < 結尾; 字元值++) 寫入編號(存儲值 + 4 + (字元值 - 運行) * 4, 輸入值[字元值]);
            存儲值 += 4 + (結尾 - 運行) * 4;
        }
        通信網絡.清潔程序();
        檔案描述子管理.開始程序();
        int 結果 = 設備.運行用戶程式(條目分值, 用戶結束 - 16);
        檔案描述子管理.清潔程序();
        通信網絡.清潔程序();
        return 結果;
    }
}
