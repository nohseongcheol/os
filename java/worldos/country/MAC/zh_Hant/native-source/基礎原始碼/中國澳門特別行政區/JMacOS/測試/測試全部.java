    private static void 測試記憶體(內核 內核值) {
        記憶體管理器 管理器值 = 內核值.記憶體空間();
        int 首位地址 = 管理器值.分配已對齊(100, 64);
        驗證((首位地址 & 63) == 0, "對齊值 分配存儲裝置");
        管理器值.寫入位元組值(首位地址, (byte) 0x5a);
        驗證(管理器值.讀取位元組值(首位地址) == (byte) 0x5a, "물리 記憶體空間 읽고 寫入");
        int 之前使用 = 管理器值.已使用大小();
        管理器值.釋放存儲裝置(首位地址);
        驗證(管理器值.已使用大小() < 之前使用, "記憶體空間 釋放存儲裝置");
    }

    private static void 測試頁管理工作(內核 內核值) {
        頁管理器 管理器值 = 內核值.頁管理工作();
        頁管理器.地址空間 父空間 = 管理器值.新建地址空間();
        管理器值.映射表頁(父空間, 0x1000, true);
        管理器值.寫入位元組值(父空間, 0x1010, (byte) 7);
        頁管理器.地址空間 子空間 = 管理器值.克隆複製啓用側寫入(父空間);
        管理器值.寫入位元組值(子空間, 0x1010, (byte) 9);
        驗證(管理器值.讀取位元組值(父空間, 0x1010) == 7, "寫入 시 複製值 父值 격리");
        驗證(管理器值.讀取位元組值(子空間, 0x1010) == 9, "寫入 시 複製值 子值 寫入");
    }

    private static void 測試檔案集與程序列(內核 內核值) {
        byte[] 內容值 = "안녕하세요".getBytes(StandardCharsets.UTF_8);
        內核值.檔案系統().追加檔案("測試", 內容值);
        程序值 父值 = 內核值.首位程序();
        系統呼叫 調用 = 內核值.系統呼叫();
        int 描述符條目 = 調用.打開(父值, "/測試", 系統呼叫.讀取僅用標誌);
        驗證(描述符條目 >= 3, "檔案 打開");

        byte[] 接收目的地址 = new byte[內容值.length];
        驗證(調用.讀取(父值, 描述符條目, 接收目的地址, 接收目的地址.length) == 內容值.length, "檔案 讀取");
        驗證(Arrays.equals(內容值, 接收目的地址), "檔案 內容值");
        驗證(調用.移動位置(父值, 描述符條目, 0, 系統呼叫.搜索開始) == 0, "檔案 位置 移動值");

        int 已克隆描述符 = 調用.複製副本描述符(父值, 描述符條目);
        驗證(已克隆描述符 >= 0, "描述符條目 克隆值");
        程序值 子值 = 調用.克隆程序(父值);
        驗證(子值.標識符值() != 父值.標識符值(), "程序值 標識符值 분리");
        驗證(子值.父標識符() == 父值.標識符值(), "父值 程序值 標識符值");
        驗證(調用.關閉(子值, 描述符條目) == 0 && 父值.檔案描述符().是否打開(描述符條目), "子值 關閉 격리");

        int 上一個結束 = 調用.增加程式跳出(父值, 8192);
        驗證(上一個結束 == 0x06000000, "程式 結尾 늘리기");
        驗證(父值.程式跳出() == 0x06002000, "程式 結尾 반영");
        驗證(子值.程式跳出() == 0x06000000, "과정별 程式 結尾 격리");

        子值.退出程式(7);
        驗證(調用.等待狀態用於子(父值, 子值.標識符值(), false) == (7 << 8), "子值 退出程式 等待");
        驗證(調用.是否可訪問("測試", 1) == -13, "執行命令 權限值 拒絕值");
        驗證(調用.用戶標識符() == 0 && 調用.組標識符() == 0, "사용자와 무리 標識符值");
        驗證("/".equals(調用.當前任務列表(2)) && 調用.切換任務列表("/") == 0, "當前項目 任務 條目列表");
        驗證(調用.是否終端(父值, 1), "표준 輸出 終端輸入輸出");
        驗證("JMacOS".equals(調用.系統詳情列().系統名稱()), "運行系統值 系統信息");
    }

    private static void 測試ELF(內核 內核值) {
        byte[] 資料 = new byte[92];
        資料[0] = 0x7f;
        資料[1] = 'E';
        資料[2] = 'L';
        資料[3] = 'F';
        資料[4] = 1;
        資料[5] = 1;
        寫入整數值(資料, 24, 0x04001000);
        寫入整數值(資料, 32, 52);
        寫入短整數整數(資料, 46, 40);
        寫入短整數整數(資料, 48, 1);
        寫入整數值(資料, 56, 8);
        寫入整數值(資料, 60, 2);
        寫入整數值(資料, 64, 0x04002000);
        寫入整數值(資料, 72, 64);

        可執行文件加載器.映像 映像值 = new 可執行文件加載器().檢查項(資料);
        驗證(映像值.開始地址() == 0x04001000, "ELF 運行 地址");
        驗證(映像值.區段列列表().size() == 1 && 映像值.區段列列表().get(0).種類值() == 8, "ELF 빈 資料 區段值");
        int 描述符條目 = 內核值.系統呼叫().打開(內核值.首位程序(), "測試", 系統呼叫.讀取僅用標誌);
        驗證(內核值.系統呼叫().檔案控制(內核值.首位程序(), 描述符條目, 2, 1) == 0, "執行命令 시 關閉 設置");
        驗證(內核值.系統呼叫().執行命令(內核值.首位程序(), 資料, new String[] {"測試", "값"}, new String[] {"語言=中文"}) == 0, "ELF 執行命令 映像值 적재");
        驗證(內核值.首位程序().執行狀態開始地址() == 0x04001000, "執行命令 運行 地址 반영");
        驗證(內核值.首位程序().執行狀態實際參數().length == 2 && 內核值.首位程序().環境值().length == 1, "執行命令 인자와 環境");
        驗證(!內核值.首位程序().檔案描述符().是否打開(描述符條目), "執行命令 시 描述符條目 關閉");
        驗證(內核值.頁管理工作().讀取位元組值(內核值.首位程序().地址空間(), 0x04002000) == 0, "빈 資料 區段值 零操作數 初始化");
    }

    private static void 測試輸入(內核 內核值) {
        內核值.輸入管理工作().鍵向下('가');
        內核值.輸入管理工作().鼠標移動量(3, -2);
        輸入事件 首位事件 = 內核值.輸入管理工作().下一事件();
        輸入事件 第二事件 = 內核值.輸入管理工作().下一事件();
        驗證(首位事件.事件種類() == 輸入事件.種類值.鍵向下, "자판 事件");
        驗證(第二事件.首位值() == 3 && 第二事件.第二值() == -2, "쥐 移動值 事件");
    }

