"""독립된 자체 ABI ELF64와 로더 отхвърлям_стойност_e3ecc00b 시험 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from 파이썬빌드 import 파이썬만들기
from 자바라이브러리빌드 import 자바라이브러리만들기
from 시언어번역기빌드 import 시언어번역기만들기


def Създаване_потребител_ИНТЕРВАЛ(корен_път, хранилище_път, 시언어번역기, 시플플번역기, 연결편집기, Архив_инструмент, конфигурация_Услуга_за_интелигентно_прехвърляне_във_фонов_режим, изпълнявам_команда):
    конфигурация_Услуга_за_интелигентно_прехвърляне_във_фонов_режим = [Настройки_стойност for Настройки_стойност in конфигурация_Услуга_за_интелигентно_прехвърляне_във_фонов_режим if Настройки_стойност != '-mgeneral-regs-only']
    компилация_път = корен_път / 'build'
    출력결과 = компилация_път / 'user'
    출력결과.mkdir(exist_ok=True)
    원본자료 = корен_път / 'потребител'
    포직스경로 = хранилище_път / 'posix-kor/arm64-native'
    включвам_път = ['-I', 원본자료, '-I', 포직스경로 / '포함', '-I', 출력결과]
    for компилатор_инструмент, 추가영역, ПЪТ, Име in [
            (시언어번역기, [], 원본자료 / 'Стартиране.S', 'start.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'изпълнявам_команда.c', 'runtime.o'),
            (시언어번역기, ['-std=c11'], 포직스경로 / 'потребител_мост.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '파일예제.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '통신예제.cpp', 'network.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / '보호시험.c', 'fault.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'Редактор.c', 'vi.o')]:
        изпълнявам_команда([компилатор_инструмент] + конфигурация_Услуга_за_интелигентно_прехвърляне_във_фонов_режим + 추가영역 + включвам_път + ['-Wall', '-Wextra', '-Werror', '-c', ПЪТ, '-o', 출력결과 / Име])
    изпълнявам_команда([Архив_инструмент, 'rcs', компилация_път / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for Име in ('demo', 'fault', 'network', 'vi'):
        изпълнявам_команда([연결편집기, '-T', 원본자료 / 'Връзка_схема.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (Име + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (Име + '.o'), компилация_път / 'libposix-kor-user.a'])
    자바라이브러리만들기(корен_път, изпълнявам_команда)
    # 기존 자체 Java компилатор/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(компилация_път)) as 작업경로:
        Клас_път = Path(작업경로)
        изпълнявам_команда(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', Клас_път, '-sourcepath', Клас_път, '-d', Клас_път] +
            [данни_позиция for данни_позиция in sorted((хранилище_път / 'os/потребител/자바').glob('*.java')) if данни_позиция.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        изпълнявам_команда(['sh', хранилище_път / 'compiler/미리번역.sh', '--entry', 'инструмент_запис.Стартиране',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(Клас_път.glob('*.class')))
    압축해제경로 = корен_път / 'vendor/uzlib'
    for ПЪТ, Име in [(출력결과 / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'пакет.c', 'jar.o')] + [(압축해제경로 / (Име + '.c'), Име + '.o') for Име in ('tinflate', 'crc32', 'adler32')]:
        изпълнявам_команда([시언어번역기] + конфигурация_Услуга_за_интелигентно_прехвърляне_във_фонов_режим + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + включвам_път + ['-c', ПЪТ, '-o', 출력결과 / Име])
    изпълнявам_команда([연결편집기, '-T', 원본자료 / 'Връзка_схема.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / Име for Име in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(корен_път, 시언어번역기, 연결편집기)
    시언어번역기만들기(корен_път, хранилище_път, 시언어번역기, 연결편집기, конфигурация_Услуга_за_интелигентно_прехвърляне_във_фонов_режим, изпълнявам_команда)
    유효함 = (출력결과 / 'demo.elf').read_bytes()
    програма_Заглавка_Изместване = struct.unpack_from('<Q', 유효함, 32)[0]
    Заглавка_Списък = [програма_Заглавка_Изместване + 개수 * 56 for 개수 in range(struct.unpack_from('<H', 유효함, 56)[0])]
    적재구획 = [данни_позиция for данни_позиция in Заглавка_Списък if struct.unpack_from('<I', 유효함, данни_позиция)[0] == 1]
    Текст, данни = 적재구획[:2]
    команда_адрес = struct.unpack_from('<Q', 유효함, Текст + 16)[0]
    данни_адрес = struct.unpack_from('<Q', 유효함, данни + 16)[0]
    호출규약 = 유효함.index(b'JKOROS\0')
    시험사례 = [('empty', b''), ('short', 유효함[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', команда_адрес + 1), ('data-entry', 24, 'Q', данни_адрес),
               ('outside-file', Текст + 32, 'Q', len(유효함) + 1), ('short-memory', Текст + 40, 'Q', 1),
               ('kernel-address', Текст + 16, 'Q', 0x80000), ('memory-overflow', Текст + 40, 'Q', 2**64 - 1),
               ('writable-code', Текст + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', Текст, 'I', 2),
               ('unaligned-load', Текст + 16, 'Q', команда_адрес + 8),
               ('overlap', данни + 16, 'Q', команда_адрес)]
    for Име, Изместване_стойност, формат_932e03c8, стойност in 수정사항:
        바뀐자료 = bytearray(유효함); struct.pack_into('<' + формат_932e03c8, 바뀐자료, Изместване_стойност, стойност)
        시험사례.append((Име, bytes(바뀐자료)))
    탑재덩이들 = [(Име.replace('-', '_'), 출력결과 / (Име + '.elf')) for Име in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for Търсене_индекс, (Име, полезен_обем_данни) in enumerate(시험사례):
        ПЪТ = 출력결과 / ('invalid-{}.elf'.format(Име)); ПЪТ.write_bytes(полезен_обем_данни)
        탑재덩이들.append(('invalid_{}'.format(Търсене_индекс), ПЪТ))
    блок_ec50080d, Заглавка_стойност = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for Име, ПЪТ in 탑재덩이들:
        символ_стойност = 'user_blob_' + Име
        크기목록[Име] = ПЪТ.stat().st_size
        # 생성한 крайно_устройство_стойност 경로만 넣어 프로젝트 경로의 공백/Цитат 영향을 피한다.
        блок_ec50080d += ['.balign 16', '.global ' + символ_стойност, символ_стойност + ':', '.incbin "{}"'.format(ПЪТ.relative_to(корен_път))]
        Заглавка_стойност.append('extern const unsigned char {}[];'.format(символ_стойност))
    блок_ec50080d.append('.section .note.GNU-stack,"",%progbits')
    Заглавка_стойност += ['static const програма 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    Заглавка_стойност += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    Заглавка_стойност += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    Заглавка_стойност += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], метод_режим) for метод_режим in (0, 1)]
    Заглавка_стойност += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    Заглавка_стойност += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    Заглавка_стойност += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    Заглавка_стойност += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    Заглавка_стойност += ['};', 'static const програма 잘못된실행항목들[] = {']
    Заглавка_стойност += ['{user_blob_invalid_%d, %d, 0},' % (순번, len(полезен_обем_данни)) for 순번, (_, полезен_обем_данни) in enumerate(시험사례)]
    Заглавка_стойност += ['};']
    (компилация_път / 'programs.S').write_text('\n'.join(блок_ec50080d) + '\n')
    (компилация_път / 'programs.h').write_text('\n'.join(Заглавка_стойност) + '\n')
    (출력결과 / 'invalid-cases.txt').write_text('\n'.join(Име for Име, _ in 시험사례) + '\n')
    изпълнявам_команда([시언어번역기] + конфигурация_Услуга_за_интелигентно_прехвърляне_във_фонов_режим + ['-c', компилация_път / 'programs.S', '-o', компилация_път / 'programs.o'])
