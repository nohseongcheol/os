package Молдова.JMdaOS.Памет_област;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB страница_стойност 연결과 Писане 시 복사를 제공한다. */
public final class 쪽관리자 {
    public static final int размер_на_страница = 4096;

    private static final class страница_стойност {
        private byte[] данни = new byte[размер_на_страница];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class адрес_ИНТЕРВАЛ {
        private final Map<Integer, страница_стойност> страница_таблица = new HashMap<Integer, страница_стойност>();
    }

    public адрес_ИНТЕРВАЛ 새주소공간() {
        return new адрес_ИНТЕРВАЛ();
    }

    public void нанасям_страница(адрес_ИНТЕРВАЛ адрес_област, int виртуален_адрес, boolean 쓰기가능) {
        int индекс = 쪽번호(виртуален_адрес);
        страница_стойност 새쪽 = new страница_стойност();
        새쪽.쓰기가능 = 쓰기가능;
        адрес_област.страница_таблица.put(Integer.valueOf(индекс), 새쪽);
    }

    public адрес_ИНТЕРВАЛ 쓰기시복사복제(адрес_ИНТЕРВАЛ 원본) {
        адрес_ИНТЕРВАЛ 복제본 = new адрес_ИНТЕРВАЛ();
        for (Map.Entry<Integer, страница_стойност> запис_стойност : 원본.страница_таблица.entrySet()) {
            страница_стойност 공유쪽 = запис_стойност.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.страница_таблица.put(запис_стойност.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(адрес_ИНТЕРВАЛ адрес_област, int виртуален_адрес) {
        страница_стойност цел = Търсене_страница(адрес_област, виртуален_адрес);
        return цел.данни[Math.floorMod(виртуален_адрес, размер_на_страница)];
    }

    public void записване_байт_стойност(адрес_ИНТЕРВАЛ адрес_област, int виртуален_адрес, byte стойност) {
        int индекс = 쪽번호(виртуален_адрес);
        страница_стойност цел = Търсене_страница(адрес_област, виртуален_адрес);
        if (!цел.쓰기가능) {
            if (!цел.쓰기시복사) {
                throw new IllegalStateException("Четене 전용 쪽입니다.");
            }
            цел = Създаване_частен_страница(адрес_област, индекс, цел);
        }
        цел.данни[Math.floorMod(виртуален_адрес, размер_на_страница)] = стойност;
    }

    public void частен_обхват_записване(адрес_ИНТЕРВАЛ адрес_област, int Старт_адрес, int Размер) {
        if (Размер < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int прекратяване_на_повикването_адрес = Math.addExact(Старт_адрес, Размер);
        for (int адрес = Старт_адрес; адрес < прекратяване_на_повикването_адрес; адрес = (쪽번호(адрес) + 1) * размер_на_страница) {
            int индекс = 쪽번호(адрес);
            страница_стойност цел = Търсене_страница(адрес_област, адрес);
            if (цел.쓰기시복사) {
                Създаване_частен_страница(адрес_област, индекс, цел);
            } else {
                цел.쓰기가능 = true;
            }
        }
    }

    public void обхват_записване(адрес_ИНТЕРВАЛ адрес_област, int Старт_адрес, byte[] данни) {
        for (int индекс = 0; индекс < данни.length; индекс++) {
            записване_байт_стойност(адрес_област, Старт_адрес + индекс, данни[индекс]);
        }
    }

    private страница_стойност Създаване_частен_страница(адрес_ИНТЕРВАЛ адрес_област, int индекс, страница_стойност 공유쪽) {
        страница_стойност частен_страница = new страница_стойност();
        частен_страница.данни = Arrays.copyOf(공유쪽.данни, 공유쪽.данни.length);
        частен_страница.쓰기가능 = true;
        частен_страница.쓰기시복사 = false;
        공유쪽.참조수--;
        адрес_област.страница_таблица.put(Integer.valueOf(индекс), частен_страница);
        return частен_страница;
    }

    private страница_стойност Търсене_страница(адрес_ИНТЕРВАЛ адрес_област, int адрес) {
        страница_стойност цел = адрес_област.страница_таблица.get(Integer.valueOf(쪽번호(адрес)));
        if (цел == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return цел;
    }

    private int 쪽번호(int адрес) {
        if (адрес < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return адрес / размер_на_страница;
    }
}

