package Молдова.JMdaOS.ядро;

import Молдова.JMdaOS.Памет_област.기억공간관리자;
import Молдова.JMdaOS.Памет_област.쪽관리자;
import Молдова.JMdaOS.입력.입력관리자;
import Молдова.JMdaOS.작업.Процес_стойност;
import Молдова.JMdaOS.작업.Планировчик;
import Молдова.JMdaOS.체계호출.체계호출;
import Молдова.JMdaOS.файлова_система.파일서술자표;
import Молдова.JMdaOS.файлова_система.файлова_система;

/** Java 관리 커널의 조립과 시작을 담당한다. */
public final class ядро {
    private final 하드웨어 устройство_стойност;
    private final 기억공간관리자 Памет_област = new 기억공간관리자(32 * 1024 * 1024);
    private final 쪽관리자 쪽관리 = new 쪽관리자();
    private final файлова_система файлова_система = new файлова_система();
    private final Планировчик Планировчик = new Планировчик(쪽관리);
    private final 입력관리자 입력관리 = new 입력관리자(256);
    private final Процес_стойност 첫과정;
    private final 체계호출 체계호출;

    public ядро(하드웨어 устройство_стойност) {
        this.устройство_стойност = устройство_стойност;
        첫과정 = Планировчик.첫과정(new 파일서술자표(файлова_система));
        체계호출 = new 체계호출(файлова_система, 쪽관리, Планировчик, устройство_стойност, 입력관리);
    }

    public void Стартиране() {
        устройство_стойност.직렬출력("=== JMdaOS 관리 ядро_стойност ===\n");
    }

    public void изпълнявам_стъпка() {
        устройство_стойност.중앙처리장치멈춤();
    }

    public 기억공간관리자 Памет_област() {
        return Памет_област;
    }

    public 쪽관리자 쪽관리() {
        return 쪽관리;
    }

    public файлова_система файлова_система() {
        return файлова_система;
    }

    public Планировчик Планировчик() {
        return Планировчик;
    }

    public 입력관리자 입력관리() {
        return 입력관리;
    }

    public Процес_стойност 첫과정() {
        return 첫과정;
    }

    public 체계호출 체계호출() {
        return 체계호출;
    }
}
