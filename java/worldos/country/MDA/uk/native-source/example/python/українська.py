class Система_помилка(OSError):
    def __init__(자신, індекс, 설명="операційна_система_ОС 작업에 실패했습니다."):
        super().__init__(індекс, 설명)
        자신.індекс = індекс
        자신.설명 = 설명

def 운영호출(функція_значення, *аргументи):
    try:
        return функція_значення(*аргументи)
    except OSError as ПОМИЛКА:
        індекс = ПОМИЛКА.args[0] if ПОМИЛКА.args else 0
        raise Система_помилка(індекс)

