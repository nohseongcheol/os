/** 디스크 Запис 없이 동작하는 작은 직렬/PS2 ІнтерпретаторКоманд. */
public final class ІнтерпретаторКоманд {
    static int[] 입력 = new int[128];
    static int 길이 = 0;
    static boolean 앞줄복귀 = false;
    static boolean рядок_надлишок = false;

    static boolean команда(String Назва) {
        if (길이 < Назва.length()) return false;
        for (int індекс = 0; індекс < Назва.length(); індекс++)
            if (입력[індекс] != Назва.charAt(індекс)) return false;
        return 길이 == Назва.length() || 입력[Назва.length()] == ' ';
    }

    static void показати_довідку() {
        Текст_Термінал.Запис("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        Текст_Термінал.Запис("apps | run NAME [ARGS] | net\n");
        Текст_Термінал.Запис("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        Текст_Термінал.Запис("sync (연결된 JKSTORE1 сховище_значення 장치에 файл 보존)\n");
    }

    static void процес_значення_запис() {
        if (길이 == 0) return;
        if (команда("help")) показати_довідку();
        else if (команда("sync")) {
            int результат = 파일보존.синхронізувати();
            Текст_Термінал.Запис("Sync: "); Текст_Термінал.수쓰기(результат); Текст_Термінал.문자(10);
        }
        else if (команда("ls")) Пам_ять_файлова_система.запис_список();
        else if (команда("edit")) Пам_ять_файлова_система.команда(입력, 4, 길이, 0);
        else if (команда("cat")) Пам_ять_файлова_система.команда(입력, 3, 길이, 1);
        else if (команда("rm")) Пам_ять_файлова_система.команда(입력, 2, 길이, 2);
        else if (команда("java") || команда("javac")) {
            int результат = 실행관리.Виконати_команда(입력, 0, 길이);
            Текст_Термінал.Запис("Exit: "); Текст_Термінал.수쓰기(результат); Текст_Термінал.문자(10);
        }
        else if (команда("apps")) 실행관리.запис_список();
        else if (команда("net")) мережа_Стіс.Стан_значення();
        else if (команда("run")) {
            int результат = 실행관리.Виконати_команда(입력, 3, 길이);
            Текст_Термінал.Запис("Exit: "); Текст_Термінал.수쓰기(результат); Текст_Термінал.Запис("\n");
        } else if (команда("info")) {
            Текст_Термінал.Запис("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (команда("mem")) {
            Текст_Термінал.Запис("위쪽 Пам_ять_значення адреса_область(KiB): "); Текст_Термінал.수쓰기(Пам_ять_область.위쪽기억크기());
            Текст_Термінал.Запис("\n배열 동적 Пам_ять_значення адреса_область(байт_значення): "); Текст_Термінал.수쓰기(пристрій_значення.배열사용량());
            Текст_Термінал.Запис(" / 262144\n작업 адреса_область розділ_значення_366e0bfa: "); Текст_Термінал.수쓰기(Пам_ять_область.사용개수());
            Текст_Термінал.Запис(" / 8 (각 4096바이트)\n");
        } else if (команда("alloc")) {
            int індекс = Пам_ять_область.виділяти_місце();
            Текст_Термінал.Запис("розділ_значення_366e0bfa індекс: "); Текст_Термінал.수쓰기(індекс); Текст_Термінал.Запис("\n");
        } else if (команда("free")) {
            if (길이 == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                Текст_Термінал.Запис(Пам_ять_область.повернути_КР(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 розділ_значення_366e0bfa\n");
            } else Текст_Термінал.Запис("사용법: free 0..7\n");
        } else if (команда("echo")) {
            for (int індекс = 5; індекс < 길이; індекс++) Текст_Термінал.문자(입력[індекс]);
            Текст_Термінал.문자(10);
        } else if (команда("clear")) Текст_Термінал.видаляти_запис();
        else if (команда("test")) Ядро.випробування();
        else if (команда("halt")) {
            Текст_Термінал.Запис("HALTED\n");
            пристрій_значення.정지();
        } else Текст_Термінал.Запис("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void приймати_і_записування(int значення) {
        if (значення == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = значення == 13;
        if (значення == 10 || значення == 13) {
            Текст_Термінал.문자(10);
            if (Пам_ять_файлова_система.편집중) Пам_ять_файлова_система.Відредаговані_рядок(입력, 길이, рядок_надлишок);
            else процес_значення_запис();
            길이 = 0;
            рядок_надлишок = false;
            Текст_Термінал.Запис(Пам_ять_файлова_система.편집중 ? "...> " : "jkoros> ");
        } else if (значення == 8 || значення == 127) {
            if (길이 > 0) {
                길이--;
                Текст_Термінал.직렬바이트(8); Текст_Термінал.직렬바이트(32); Текст_Термінал.직렬바이트(8);
                Текст_Термінал.화면문자(8);
            }
        } else if (значення >= 32 && значення < 127 && 길이 < 입력.length) {
            입력[길이++] = значення;
            Текст_Термінал.문자(значення);
        } else if (значення >= 32 && значення < 127) рядок_надлишок = true;
    }

    static void запустити() {
        показати_довідку();
        Текст_Термінал.Запис("READY\njkoros> ");
        while (true) {
            int значення = Текст_Термінал.직렬읽기();
            if (значення < 0) значення = клавіатура.Читання();
            if (значення >= 0) приймати_і_записування(значення);
            else { мережа_Стіс.перевіряти(); пристрій_значення.잠시양보(); }
        }
    }
}
