package українська.своє;
/** 화면(畫面): запуск_машини 때 선택한 크기의 своє ядро_значення RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int значення = ядро_значення.화면너비(); if (значення < 0) throw new Стан_виняток("프레임버퍼 없음"); return значення; }
    public static int 높이() { int значення = ядро_значення.화면높이(); if (значення < 0) throw new Стан_виняток("프레임버퍼 없음"); return значення; }
    public static void прямокутник(int 가로, int Вертикаль_посада, int 폭, int 높이, int 색) {
        if (가로 < 0 || Вертикаль_посада < 0 || 폭 < 0 || 높이 < 0 || 가로 > 너비() || Вертикаль_посада > 높이() || 폭 > 너비() - 가로 || 높이 > 높이() - Вертикаль_посада) throw new недійсний_аргумент_виняток("화면 кліп");
        if (ядро_значення.прямокутник(가로, Вертикаль_посада, 폭, 높이, 색) < 0) throw new Стан_виняток("프레임버퍼 없음");
    }
    public static void видаляти_запис(int 색) { прямокутник(0, 0, 너비(), 높이(), 색); }
    public static void 기다리기() { if (ядро_значення.그림대기() < 0) throw new Стан_виняток("대화형 입력 필요"); }
}
