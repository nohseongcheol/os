#!/usr/bin/env python3
"""збирання 변환이 українська рядок_значення, 주석, 헤더 경로를 바꾸지 않는지 검사한다."""
from ідентифікатор_перетворення import перетворити_значення

вихіднийКод = '''#include <파일규약.h>
#include "통신규약.h"
// відкрито_Файл 라는 주석
/* 자료이름 */
const char *Файл_запис_ім_я = "한글 \\" рядок_значення";
char символ_значення_068c2631 = '가';
int 파일열기_횟수 = 1;
'''
Вивід = перетворити_значення(вихіднийКод)
assert '#include <파일규약.h>' in Вивід
assert '#include "통신규약.h"' in Вивід
assert '// відкрито_Файл 라는 주석' in Вивід
assert '/* 자료이름 */' in Вивід
assert '"한글 \\" рядок_значення"' in Вивід
assert "'가'" in Вивід
assert '\\ud30c\\uc77c\\uc774\\ub984' in Вивід
assert '파일열기_횟수' not in Вивід
assert перетворити_значення(Вивід) == Вивід
print('PASS: українська ідентифікатор_значення перетворити_значення/рядок_значення·주석·шлях 보존')
