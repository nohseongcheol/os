package Молдова.JMdaOS.작업;

import Молдова.JMdaOS.Пам_ять_область.쪽관리자;
import Молдова.JMdaOS.файлова_система.파일서술자표;

public final class процес_значення {
    private final int ідентифікатор_значення;
    private final int батьківський_ідентифікатор;
    private final 쪽관리자.адреса_ПРОБІЛ адреса_ПРОБІЛ;
    private final 파일서술자표 파일서술자;
    private процес_Стан Стан_значення = процес_Стан.Готувати;
    private int Вийти_код;
    private int програма_перерва = 0x06000000;
    private int 실행시작주소;
    private String[] 실행인자 = new String[0];
    private String[] середовище_значення = new String[0];

    процес_значення(int ідентифікатор_значення, int батьківський_ідентифікатор, 쪽관리자.адреса_ПРОБІЛ адреса_ПРОБІЛ, 파일서술자표 파일서술자) {
        this.ідентифікатор_значення = ідентифікатор_значення;
        this.батьківський_ідентифікатор = батьківський_ідентифікатор;
        this.адреса_ПРОБІЛ = адреса_ПРОБІЛ;
        this.파일서술자 = 파일서술자;
    }

    public int ідентифікатор_значення() {
        return ідентифікатор_значення;
    }

    public int батьківський_ідентифікатор() {
        return батьківський_ідентифікатор;
    }

    public 쪽관리자.адреса_ПРОБІЛ адреса_ПРОБІЛ() {
        return адреса_ПРОБІЛ;
    }

    public 파일서술자표 파일서술자() {
        return 파일서술자;
    }

    public процес_Стан Стан_значення() {
        return Стан_значення;
    }

    public void група_Стан(процес_Стан 새상태) {
        Стан_значення = 새상태;
    }

    public int Вийти_код() {
        return Вийти_код;
    }

    public void Вийти_програма(int значення) {
        Вийти_код = значення & 0xff;
        Стан_значення = процес_Стан.Вийти_програма;
    }

    public int програма_перерва() {
        return програма_перерва;
    }

    public void група_програма_перерва(int 새끝) {
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            throw new IllegalArgumentException("програма_f5044b9b 끝 범위를 벗어났습니다.");
        }
        програма_перерва = 새끝;
    }

    public void 실행문맥설정(int ПУСК_адреса, String[] параметр_аргумент, String[] середовище) {
        실행시작주소 = ПУСК_адреса;
        실행인자 = параметр_аргумент.clone();
        середовище_значення = середовище.clone();
    }

    public int 실행시작주소() { return 실행시작주소; }
    public String[] 실행인자() { return 실행인자.clone(); }
    public String[] середовище_значення() { return середовище_значення.clone(); }
}
