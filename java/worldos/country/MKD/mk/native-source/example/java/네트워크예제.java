import Македонски.자체.врска;
import Македонски.자체.실행인수;
import Македонски.자체.전문통로;
import Македонски.자체.문자;
import Македонски.자체.출력;
import Македонски.자체.검사;
import Македонски.자체.입력흐름;
import Македонски.자체.В_И_исклучок;

public class 네트워크예제 {
    public static void Изврши_2() throws В_И_исклучок {
        // вдоми: python3 Алатки/예제되돌림.py --tcp-port 9000 --udp-port 9001
        врска Врзи_се = врска.Отвори("10.0.2.2", 문자.разложи_цел_број(실행인수.Текст(0)));
        try {
            Врзи_се.TIMEOUT(700);
            byte[] порака = 문자.부호화("JAVA TCP mk\n");
            Врзи_се.출력().Запиши(порака);
            입력흐름 입력 = Врзи_се.입력();
            for (int 수 = 0; 수 < 문자.бајт_COUNT(порака); 수++) {
                검사.참인지(입력.Читај() == (порака[수] & 255), "TCP одговори 불일치");
            }
        } finally { Врзи_се.Затвори(); }
        전문통로 종단 = 전문통로.Отвори(0);
        try {
            종단.TIMEOUT(700);
            종단.испрати("10.0.2.2", 문자.разложи_цел_број(실행인수.Текст(1)), "JAVA UDP mk");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP mk"), "UDP одговори 불일치");
        } finally { 종단.Затвори(); }
        출력.запиши_ред("JAVA 네트워크 провери: TCP UDP mk");
    }
}
