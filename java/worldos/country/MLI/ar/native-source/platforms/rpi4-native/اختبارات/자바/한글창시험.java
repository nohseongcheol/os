import العربية.ذاتي.نافذة;
import العربية.ذاتي.عنصر_شاشة;
import العربية.ذاتي.*;

public class 한글창시험 implements 실행할일, 동작받이 {
    نافذة 화면;
    تسمية 안내;
    حقل_نصي إدخال_قيمة;
    public void تنفيذ() {
        검사.참인지(حدث_يدرج.사건처리중인가(), "العربية 화면 작업 큐");
        화면 = new نافذة("العربية مكتبة نافذة", 400, 280);
        안내 = عنصر_شاشة.علامة_قيمة("한글로 Java 코딩", 20, 20, 340, 30);
        إدخال_قيمة = عنصر_شاشة.حقل_نصي("اسم", 20, 65, 340, 30);
        화면.يضيف_عنصر(안내);
        화면.يضيف_عنصر(إدخال_قيمة);
        화면.يضيف_عنصر(عنصر_شاشة.زر("인사하기", 20, 110, 180, 32, this));
        화면.عرض_نافذة();
        مخرجات.كتابة_خط("KOREAN SWING READY");
    }
    public void يستلم_إجراء(إجراء_إشعار حدث) {
        검사.참인지(حدث_يدرج.사건처리중인가(), "العربية إجراء 되부름");
        검사.참인지(حدث.فهرس() == 1001 && حدث.مصدر_الحدث() instanceof زر, "العربية حدث 객체와 نقطة_الأصل_قيمة");
        검사.참인지(!((Object)حدث.مصدر_الحدث() instanceof javax.swing.JButton), "표준 단추와 독립된 ينسق_قيمة");
        검사.참인지(!((Object)حدث instanceof java.awt.event.ActionEvent), "표준 사건과 독립된 ينسق_قيمة");
        안내.كتابة_نص("안녕하세요 " + إدخال_قيمة.يقرأ_نص());
        مخرجات.كتابة_خط("KOREAN SWING CLICK " + إدخال_قيمة.يقرأ_نص());
    }
    public static void main(String[] وسائط) {
        حدث_يدرج.나중에실행(new 한글창시험());
    }
}
