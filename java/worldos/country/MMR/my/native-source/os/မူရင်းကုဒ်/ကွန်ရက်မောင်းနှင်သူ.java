/** PCI RTL8139 (10ec:8139)၊ ပို့သိုလှောင်ရာတစ်ခုနှင့် 8 KiB လက်ခံကွင်း။ ကြားဖြတ်အစား လှည့်စစ်သည်။ */
public final class ကွန်ရက်မောင်းနှင်သူ {
    static int အဝင်အထွက်အခြေလိပ်စာ = 0;
    static int နေရာလက်ခံရယူ = 0, ထုတ်ပို့နေရာကွက် = 0;
    static int[] ကိရိယာလိပ်စာ = new int[6];
    static int ထုတ်ပို့အရေအတွက် = 0, အရေအတွက်လက်ခံရယူ = 0, အမှားအရေအတွက် = 0;

    static int သတ်မှတ်ချက်ဖတ်(int ကိရိယာကိန်း, int နေရာ) {
        ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ရေး(0xcf8, 0x80000000 | (ကိရိယာကိန်း << 11) | နေရာ);
        return ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ဖတ်(0xcfc);
    }

    static boolean ပြင်ဆင်() {
        int ကိရိယာကိန်း = -1;
        for (int နံပါတ် = 0; နံပါတ် < 32; နံပါတ်++) {
            if (သတ်မှတ်ချက်ဖတ်(နံပါတ်, 0) == 0x813910ec) { ကိရိယာကိန်း = နံပါတ်; break; }
        }
        if (ကိရိယာကိန်း < 0) return false;
        int မူလသတ်မှတ်တန်ဖိုး = သတ်မှတ်ချက်ဖတ်(ကိရိယာကိန်း, 0x10);
        if ((မူလသတ်မှတ်တန်ဖိုး & 1) == 0 || (မူလသတ်မှတ်တန်ဖိုး & 0xfffffffc) < 0x100 || (မူလသတ်မှတ်တန်ဖိုး & 0xfffffffc) > 65535) return false;
        အဝင်အထွက်အခြေလိပ်စာ = မူလသတ်မှတ်တန်ဖိုး & 0xfffc;
        int အမိန့် = သတ်မှတ်ချက်ဖတ်(ကိရိယာကိန်း, 4);
        ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ရေး(0xcf8, 0x80000004 | (ကိရိယာကိန်း << 11));
        ကိရိယာ.အဝင်အထွက်တိုရေး(0xcfc, အမိန့် | 5); // I/O နှင့် bus master ကို ခွင့်ပြုပြီး PCI အခြေအနေဘစ်များကို မပြောင်းပါ။
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x52, 0);
        if (!တန်ဖိုးပြန်သတ်မှတ်()) { အဝင်အထွက်အခြေလိပ်စာ = 0; return false; }
        for (int နံပါတ် = 0; နံပါတ် < 6; နံပါတ်++) ကိရိယာလိပ်စာ[နံပါတ်] = ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(အဝင်အထွက်အခြေလိပ်စာ + နံပါတ်);
        return true;
    }

    static boolean တန်ဖိုးပြန်သတ်မှတ်() {
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x37, 0x10);
        int လုပ်ဆောင် = ကိရိယာ.မီလီစက္ကန့်();
        while ((ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(အဝင်အထွက်အခြေလိပ်စာ + 0x37) & 0x10) != 0)
            if (ကိရိယာ.မီလီစက္ကန့်() - လုပ်ဆောင် > 100) return false;
        နေရာလက်ခံရယူ = 0; ထုတ်ပို့နေရာကွက် = 0;
        ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x30, ကိရိယာ.ကွန်ရက်မှတ်ဉာဏ်());
        for (int နံပါတ် = 0; နံပါတ် < 4; နံပါတ်++) ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x20 + နံပါတ် * 4, ကိရိယာ.ကွန်ရက်မှတ်ဉာဏ်() + 12288);
        ကိရိယာ.အဝင်အထွက်တိုရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x3c, 0);
        ကိရိယာ.အဝင်အထွက်တိုရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x3e, 0xffff);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x37, 0x0c);
        ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x44, 0x0000e78a); // မိမိလိပ်စာနှင့် အများသို့ပို့၊ ကွင်းပတ်ဆက်သိုလှောင်မှု၊ 8 KiB။
        ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x40, 0x03000600);
        return true;
    }

    static int ပို့(int[] ဒေတာ, int အလျား) {
        if (အဝင်အထွက်အခြေလိပ်စာ == 0) return -19;
        if (အလျား < 14 || အလျား > 1514) return -90;
        int လက်ရှိအခြေအနေဆက်သွယ်ပေါက် = အဝင်အထွက်အခြေလိပ်စာ + 0x10 + ထုတ်ပို့နေရာကွက် * 4;
        int လုပ်ဆောင် = ကိရိယာ.မီလီစက္ကန့်();
        while ((ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ဖတ်(လက်ရှိအခြေအနေဆက်သွယ်ပေါက်) & 0x2000) == 0)
            if (ကိရိယာ.မီလီစက္ကန့်() - လုပ်ဆောင် > 100) return -110;
        int အရွယ် = အလျား < 60 ? 60 : အလျား;
        for (int နံပါတ် = 0; နံပါတ် < အရွယ်; နံပါတ်++)
            ကိရိယာ.မှတ်ဉာဏ်ရေး(ကိရိယာ.ကွန်ရက်မှတ်ဉာဏ်() + 12288 + နံပါတ်, နံပါတ် < အလျား ? ဒေတာ[နံပါတ်] : 0);
        ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ရေး(လက်ရှိအခြေအနေဆက်သွယ်ပေါက်, အရွယ် | 0x00080000);
        လုပ်ဆောင် = ကိရိယာ.မီလီစက္ကန့်();
        while ((ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ဖတ်(လက်ရှိအခြေအနေဆက်သွယ်ပေါက်) & 0xe0008000) == 0)
            if (ကိရိယာ.မီလီစက္ကန့်() - လုပ်ဆောင် > 100) return -110;
        if ((ကိရိယာ.အဝင်အထွက်ကိန်းပြည့်ဖတ်(လက်ရှိအခြေအနေဆက်သွယ်ပေါက်) & 0x8000) == 0) { အမှားအရေအတွက်++; return -5; }
        ထုတ်ပို့နေရာကွက် = (ထုတ်ပို့နေရာကွက် + 1) & 3;
        ထုတ်ပို့အရေအတွက်++;
        return အလျား;
    }

    static int လက်ခံ(int[] ဒေတာ) {
        if (အဝင်အထွက်အခြေလိပ်စာ == 0) return 0;
        if ((ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(အဝင်အထွက်အခြေလိပ်စာ + 0x3e) & 0x50) != 0) {
            အမှားအရေအတွက်++;
            if (!တန်ဖိုးပြန်သတ်မှတ်()) အဝင်အထွက်အခြေလိပ်စာ = 0;
            return 0;
        }
        if ((ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(အဝင်အထွက်အခြေလိပ်စာ + 0x37) & 1) != 0) return 0;
        int ဦးခေါင်းတန်ဖိုး = ကိရိယာ.ကွန်ရက်မှတ်ဉာဏ်() + နေရာလက်ခံရယူ;
        int အခြေအနေတန်ဖိုး = လုပ်ဆောင်မှုစီမံ.တိုတန်ဖိုး(ဦးခေါင်းတန်ဖိုး), အရွယ် = လုပ်ဆောင်မှုစီမံ.တိုတန်ဖိုး(ဦးခေါင်းတန်ဖိုး + 2);
        if (အရွယ် == 0xfff0) return 0; // DMA လုပ်ဆောင်နေသည်။
        if (အရွယ် < 4 || အရွယ် > 1518) {
            အမှားအရေအတွက်++;
            if (!တန်ဖိုးပြန်သတ်မှတ်()) အဝင်အထွက်အခြေလိပ်စာ = 0;
            return 0;
        }
        int အလျား = အရွယ် - 4;
        if ((အခြေအနေတန်ဖိုး & 1) != 0) {
            for (int နံပါတ် = 0; နံပါတ် < အလျား; နံပါတ်++) ဒေတာ[နံပါတ်] = ကိရိယာ.မှတ်ဉာဏ်ဖတ်(ဦးခေါင်းတန်ဖိုး + 4 + နံပါတ်);
            အရေအတွက်လက်ခံရယူ++;
        } else { အလျား = 0; အမှားအရေအတွက်++; }
        နေရာလက်ခံရယူ = (နေရာလက်ခံရယူ + အရွယ် + 4 + 3) & ~3;
        နေရာလက်ခံရယူ &= 8191;
        ကိရိယာ.အဝင်အထွက်တိုရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x38, (နေရာလက်ခံရယူ - 16) & 65535);
        ကိရိယာ.အဝင်အထွက်တိုရေး(အဝင်အထွက်အခြေလိပ်စာ + 0x3e, 0x000f);
        return အလျား;
    }
}
