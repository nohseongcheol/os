/** int 0x80 တံခါးပေါက်မှ ခေါ်သည်။ သုံးစွဲသူညွှန်ကိန်းနှင့် အရှည်အားလုံးကို ဝင်ရောက်မီ စစ်ဆေးသည်။ */
public final class စနစ်ခေါ်ဆိုမှု {
    static int[] ယာယီကြားခံ = new int[1024];

    static int အခင်းအကျင်းအလျား(int လိပ်စာ) {
        if (!လုပ်ဆောင်မှုစီမံ.ဖြတ်နယ်ပယ်(လိပ်စာ, 4)) return -14;
        int အလျား = လုပ်ဆောင်မှုစီမံ.ကိန်းတန်ဖိုး(လိပ်စာ);
        if (အလျား < 0 || အလျား > (လုပ်ဆောင်မှုစီမံ.သုံးစွဲသူအဆုံး - လိပ်စာ - 4) / 4) return -14;
        return အလျား;
    }

    public static int လုပ်ငန်းစဉ်တန်ဖိုးအချက်(int နံပါတ်, int ပထမတွက်ချက်ခံ, int ဒုတိယတွက်ချက်ခံ, int တတိယအော်ပရန်း, int စတုတ္ထအော်ပရန်း, int ပဉ္စမအော်ပရန်း) {
        if (နံပါတ် == 30) return ဖိုင်အညွှန်းစီမံ.ဖိုင်ဖွင့်(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း);
        if (နံပါတ် == 31) return ဖိုင်အညွှန်းစီမံ.ဖိုင်ဖတ်(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း);
        if (နံပါတ် == 32) return ဖိုင်အညွှန်းစီမံ.ဖိုင်ရေး(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း);
        if (နံပါတ် == 33) return ဖိုင်အညွှန်းစီမံ.ဖိုင်ပိတ်(ပထမတွက်ချက်ခံ);
        if (နံပါတ် == 34) return ဖိုင်အညွှန်းစီမံ.ဖိုင်နေရာရွှေ့(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း);
        if (နံပါတ် == 35) return ဖိုင်အညွှန်းစီမံ.မိတ္တူအညွှန်း(ပထမတွက်ချက်ခံ, 0, false, 0);
        if (နံပါတ် == 36) return ဖိုင်အညွှန်းစီမံ.မိတ္တူအညွှန်း(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, true, 0);
        if (နံပါတ် == 37) return ဖိုင်အညွှန်းစီမံ.ဖိုင်လက်ရှိအခြေအနေဖတ်(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ);
        if (နံပါတ် == 38) return ဖိုင်အညွှန်းစီမံ.ဖိုင်အချက်အမည်ဖယ်ရှား(ပထမတွက်ချက်ခံ);
        if (နံပါတ် == 39) return ဖိုင်အညွှန်းစီမံ.ဖိုင်အလျားသတ်မှတ်(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ);
        if (နံပါတ် == 40) return ဖိုင်အညွှန်းစီမံ.ထိန်းချုပ်အညွှန်း(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း);
        if (နံပါတ် == 41) return ဖိုင်အညွှန်းစီမံ.အဆုံးမှတ်ဖန်တီး(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း);
        if (နံပါတ် == 42) return ဖိုင်အညွှန်းစီမံ.လိပ်စာချည်နှောင်(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း);
        if (နံပါတ် == 43) return ဖိုင်အညွှန်းစီမံ.ဒေတာစာဒေတာပို့(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း, စတုတ္ထအော်ပရန်း, ပဉ္စမအော်ပရန်း);
        if (နံပါတ် == 44) return ဖိုင်အညွှန်းစီမံ.ဒေတာစာဒေတာလက်ခံရယူ(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း, စတုတ္ထအော်ပရန်း, ပဉ္စမအော်ပရန်း);
        if (နံပါတ် == 45) return ဖိုင်အညွှန်းစီမံ.ကွန်ရက်ပေါက်လိပ်စာဖတ်(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း);
        if (နံပါတ် == 46) return ဖိုင်အညွှန်းစီမံ.လက်ခံရယူအချိန်လွန်သတ်မှတ်(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ);
        if (နံပါတ် == 47) {
            int အညွှန်းတန်ဖိုး = ဖိုင်အညွှန်းစီမံ.အညွှန်းရှာ(ပထမတွက်ချက်ခံ);
            if (အညွှန်းတန်ဖိုး < 0) return -9;
            if (ဖိုင်အညွှန်းစီမံ.အမျိုးအစားတန်ဖိုး[အညွှန်းတန်ဖိုး] != 2) return -22;
            return ဖိုင်ထိန်းသိမ်းမှု.တစ်ပြေးညီလုပ်();
        }
        if (နံပါတ် == 1) {
            int အလျား = အခင်းအကျင်းအလျား(ပထမတွက်ချက်ခံ);
            if (အလျား < 0) return အလျား;
            if (အလျား > 4096) return -90;
            for (int အက္ခရာတန်ဖိုး = 0; အက္ခရာတန်ဖိုး < အလျား; အက္ခရာတန်ဖိုး++) စာသားစက်.အက္ခရာ(လုပ်ဆောင်မှုစီမံ.ကိန်းတန်ဖိုး(ပထမတွက်ချက်ခံ + 4 + အက္ခရာတန်ဖိုး * 4) & 65535);
            return အလျား;
        }
        if (နံပါတ် == 2) return လုပ်ဆောင်မှုစီမံ.ပေးအချက်အရေအတွက်;
        if (နံပါတ် == 3) return ပထမတွက်ချက်ခံ >= 0 && ပထမတွက်ချက်ခံ < လုပ်ဆောင်မှုစီမံ.ပေးအချက်အရေအတွက် ? လုပ်ဆောင်မှုစီမံ.ပေးအချက်လိပ်စာ[ပထမတွက်ချက်ခံ] : 0;
        if (နံပါတ် == 10) return ကွန်ရက်အလွှာစု.ဖွင့်(ပထမတွက်ချက်ခံ);
        if (နံပါတ် == 11) {
            int အလျား = အခင်းအကျင်းအလျား(စတုတ္ထအော်ပရန်း);
            if (အလျား < 0) return အလျား;
            if (ပဉ္စမအော်ပရန်း < 0 || ပဉ္စမအော်ပရန်း > အလျား || ပဉ္စမအော်ပရန်း > 1024) return -90;
            for (int နေရာ = 0; နေရာ < ပဉ္စမအော်ပရန်း; နေရာ++) ယာယီကြားခံ[နေရာ] = လုပ်ဆောင်မှုစီမံ.ကိန်းတန်ဖိုး(စတုတ္ထအော်ပရန်း + 4 + နေရာ * 4) & 255;
            return ကွန်ရက်အလွှာစု.ပို့(ပထမတွက်ချက်ခံ, ဒုတိယတွက်ချက်ခံ, တတိယအော်ပရန်း, ယာယီကြားခံ, ပဉ္စမအော်ပရန်း);
        }
        if (နံပါတ် == 12) {
            int အလျား = အခင်းအကျင်းအလျား(ဒုတိယတွက်ချက်ခံ);
            if (အလျား < 0) return အလျား;
            if (တတိယအော်ပရန်း < 0 || တတိယအော်ပရန်း > 2000) return -22;
            int ရလဒ် = ကွန်ရက်အလွှာစု.လက်ခံ(ပထမတွက်ချက်ခံ, ယာယီကြားခံ, အလျား < 1024 ? အလျား : 1024, တတိယအော်ပရန်း);
            if (ရလဒ် >= 0) for (int နေရာ = 0; နေရာ < ရလဒ်; နေရာ++) လုပ်ဆောင်မှုစီမံ.ကိန်းထုတ်(ဒုတိယတွက်ချက်ခံ + 4 + နေရာ * 4, ယာယီကြားခံ[နေရာ]);
            return ရလဒ်;
        }
        if (နံပါတ် == 13) return ကွန်ရက်အလွှာစု.ပိတ်(ပထမတွက်ချက်ခံ);
        if (နံပါတ် == 14) return ကွန်ရက်အလွှာစု.မိမိပိုင်လိပ်စာ;
        if (နံပါတ် == 15) return ကွန်ရက်အလွှာစု.တစ်ဖက်လိပ်စာ(ပထမတွက်ချက်ခံ);
        if (နံပါတ် == 16) return ကွန်ရက်အလွှာစု.တစ်ဖက်ဆက်သွယ်ပေါက်အမှတ်(ပထမတွက်ချက်ခံ);
        if (နံပါတ် == 22) {
            if (ပထမတွက်ချက်ခံ < 0 || ပထမတွက်ချက်ခံ > 65535) return -22;
            စာသားစက်.အက္ခရာ(ပထမတွက်ချက်ခံ); return 1;
        }
        if (နံပါတ် == 20 || နံပါတ် == 21) {
            int အမည်အရွယ် = အခင်းအကျင်းအလျား(ပထမတွက်ချက်ခံ), ဒေတာအရွယ် = အခင်းအကျင်းအလျား(ဒုတိယတွက်ချက်ခံ);
            if (အမည်အရွယ် < 0 || ဒေတာအရွယ် < 0) return -14;
            if (အမည်အရွယ် < 1 || အမည်အရွယ် > 64) return -22;
            int အလျား = 0;
            while (အလျား < အမည်အရွယ် && လုပ်ဆောင်မှုစီမံ.ကိန်းတန်ဖိုး(ပထမတွက်ချက်ခံ + 4 + အလျား * 4) != 0) {
                မှတ်ဉာဏ်ဖိုင်စနစ်.အမည်[အလျား] = လုပ်ဆောင်မှုစီမံ.ကိန်းတန်ဖိုး(ပထမတွက်ချက်ခံ + 4 + အလျား * 4);
                အလျား++;
            }
            if (!မှတ်ဉာဏ်ဖိုင်စနစ်.အမည်စစ်(မှတ်ဉာဏ်ဖိုင်စနစ်.အမည်, အလျား)) return -22;
            if (နံပါတ် == 20) {
                int ဖိုင် = မှတ်ဉာဏ်ဖိုင်စနစ်.အချက်ရှာ(မှတ်ဉာဏ်ဖိုင်စနစ်.အမည်, အလျား);
                if (ဖိုင် < 0) return ဖိုင်;
                int အရွယ် = မှတ်ဉာဏ်ဖိုင်စနစ်.အရွယ်စာရင်း[ဖိုင်];
                if (အရွယ် > ဒေတာအရွယ်) return -90;
                int လိပ်စာ = ကိရိယာ.ဖိုင်မှတ်ဉာဏ်() + ဖိုင် * မှတ်ဉာဏ်ဖိုင်စနစ်.အများဆုံးအရွယ်;
                for (int ကိန်းတန်ဖိုး = 0; ကိန်းတန်ဖိုး < အရွယ်; ကိန်းတန်ဖိုး++) လုပ်ဆောင်မှုစီမံ.ကိန်းထုတ်(ဒုတိယတွက်ချက်ခံ + 4 + ကိန်းတန်ဖိုး * 4, ကိရိယာ.မှတ်ဉာဏ်ဖတ်(လိပ်စာ + ကိန်းတန်ဖိုး));
                return အရွယ်;
            }
            if (တတိယအော်ပရန်း < 0 || တတိယအော်ပရန်း > ဒေတာအရွယ်) return -22;
            if (တတိယအော်ပရန်း > မှတ်ဉာဏ်ဖိုင်စနစ်.အများဆုံးအရွယ်) return -90;
            for (int ကိန်းတန်ဖိုး = 0; ကိန်းတန်ဖိုး < တတိယအော်ပရန်း; ကိန်းတန်ဖိုး++) မှတ်ဉာဏ်ဖိုင်စနစ်.တည်းဖြတ်တန်ဖိုး[ကိန်းတန်ဖိုး] = လုပ်ဆောင်မှုစီမံ.ကိန်းတန်ဖိုး(ဒုတိယတွက်ချက်ခံ + 4 + ကိန်းတန်ဖိုး * 4) & 255;
            return မှတ်ဉာဏ်ဖိုင်စနစ်.သိုလှောင်တန်ဖိုး(မှတ်ဉာဏ်ဖိုင်စနစ်.အမည်, အလျား, မှတ်ဉာဏ်ဖိုင်စနစ်.တည်းဖြတ်တန်ဖိုး, တတိယအော်ပရန်း);
        }
        return -38;
    }
}
