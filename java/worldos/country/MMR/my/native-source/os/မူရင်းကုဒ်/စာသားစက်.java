/** COM1 စီးရီးအထွက်နှင့် VGA 80x25 စာသားမျက်နှာပြင်။ ဟန်ဂုကို စီးရီးအဆုံးသုံးမျက်နှာပြင်သို့ UTF-8 ဖြင့် ထုတ်သည်။ */
public final class စာသားစက် {
    static int နေရာကွက်အချက် = 0;
    static int အရောင်တန်ဖိုး = 7;

    static void ပြင်ဆင်() {
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3f9, 0);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3fb, 0x80);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3f8, 1);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3f9, 0);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3fb, 3);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3fa, 0xc7);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3fc, 0x0b);
        အချက်ဖျက်();
    }

    static void အစဉ်ဆက်ဘိုက်(int တန်ဖိုး) {
        int အကြိမ်အရေအတွက် = 100000;
        while ((ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(0x3fd) & 0x20) == 0 && အကြိမ်အရေအတွက် > 0) အကြိမ်အရေအတွက်--;
        if (အကြိမ်အရေအတွက် > 0) ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3f8, တန်ဖိုး);
    }

    static void အချက်ဖျက်() {
        for (int နံပါတ် = 0; နံပါတ် < 2000; နံပါတ်++) {
            ကိရိယာ.မှတ်ဉာဏ်ရေး(0xb8000 + နံပါတ် * 2, 32);
            ကိရိယာ.မှတ်ဉာဏ်ရေး(0xb8001 + နံပါတ် * 2, အရောင်တန်ဖိုး);
        }
        နေရာကွက်အချက် = 0;
        စာညွှန်းတန်ဖိုး();
    }

    static void စာညွှန်းတန်ဖိုး() {
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3d4, 14);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3d5, နေရာကွက်အချက် >> 8);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3d4, 15);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3d5, နေရာကွက်အချက် & 255);
    }

    static void မျက်နှာပြင်အက္ခရာ(int တန်ဖိုး) {
        if (တန်ဖိုး == 13) return;
        if (တန်ဖိုး == 10) {
            နေရာကွက်အချက် = (နေရာကွက်အချက် / 80 + 1) * 80;
        } else if (တန်ဖိုး == 8) {
            if (နေရာကွက်အချက် > 0) {
                နေရာကွက်အချက်--;
                ကိရိယာ.မှတ်ဉာဏ်ရေး(0xb8000 + နေရာကွက်အချက် * 2, 32);
            }
        } else {
            ကိရိယာ.မှတ်ဉာဏ်ရေး(0xb8000 + နေရာကွက်အချက် * 2, တန်ဖိုး < 128 ? တန်ဖိုး : '?');
            ကိရိယာ.မှတ်ဉာဏ်ရေး(0xb8001 + နေရာကွက်အချက် * 2, အရောင်တန်ဖိုး);
            နေရာကွက်အချက်++;
        }
        if (နေရာကွက်အချက် >= 2000) {
            for (int နံပါတ် = 0; နံပါတ် < 3840; နံပါတ်++)
                ကိရိယာ.မှတ်ဉာဏ်ရေး(0xb8000 + နံပါတ်, ကိရိယာ.မှတ်ဉာဏ်ဖတ်(0xb80a0 + နံပါတ်));
            for (int နံပါတ် = 1920; နံပါတ် < 2000; နံပါတ်++) {
                ကိရိယာ.မှတ်ဉာဏ်ရေး(0xb8000 + နံပါတ် * 2, 32);
                ကိရိယာ.မှတ်ဉာဏ်ရေး(0xb8001 + နံပါတ် * 2, အရောင်တန်ဖိုး);
            }
            နေရာကွက်အချက် = 1920;
        }
        စာညွှန်းတန်ဖိုး();
    }

    static void အက္ခရာ(int တန်ဖိုး) {
        if (တန်ဖိုး < 128) {
            if (တန်ဖိုး == 10) အစဉ်ဆက်ဘိုက်(13);
            အစဉ်ဆက်ဘိုက်(တန်ဖိုး);
        } else if (တန်ဖိုး < 2048) {
            အစဉ်ဆက်ဘိုက်(0xc0 | (တန်ဖိုး >> 6));
            အစဉ်ဆက်ဘိုက်(0x80 | (တန်ဖိုး & 63));
        } else {
            အစဉ်ဆက်ဘိုက်(0xe0 | (တန်ဖိုး >> 12));
            အစဉ်ဆက်ဘိုက်(0x80 | ((တန်ဖိုး >> 6) & 63));
            အစဉ်ဆက်ဘိုက်(0x80 | (တန်ဖိုး & 63));
        }
        မျက်နှာပြင်အက္ခရာ(တန်ဖိုး);
    }

    static void ရေး(String အကြောင်းအရာတန်ဖိုး) {
        for (int နံပါတ် = 0; နံပါတ် < အကြောင်းအရာတန်ဖိုး.length(); နံပါတ်++) အက္ခရာ(အကြောင်းအရာတန်ဖိုး.charAt(နံပါတ်));
    }

    static void ကိန်းထုတ်(int တန်ဖိုး) {
        // အပေါင်းသို့ မပြောင်းသဖြင့် Integer.MIN_VALUE ကိုလည်း လုံခြုံစွာ ကိုင်တွယ်နိုင်သည်။
        if (တန်ဖိုး < 0) အက္ခရာ('-');
        else တန်ဖိုး = -တန်ဖိုး;
        int နေရာအညွှန်းကိန်း = 1000000000;
        boolean လုပ်ဆောင် = false;
        while (နေရာအညွှန်းကိန်း > 0) {
            int ဂဏန်းတန်ဖိုး = -(တန်ဖိုး / နေရာအညွှန်းကိန်း);
            if (ဂဏန်းတန်ဖိုး != 0 || လုပ်ဆောင် || နေရာအညွှန်းကိန်း == 1) {
                အက္ခရာ('0' + ဂဏန်းတန်ဖိုး);
                လုပ်ဆောင် = true;
            }
            တန်ဖိုး %= နေရာအညွှန်းကိန်း;
            နေရာအညွှန်းကိန်း /= 10;
        }
    }

    static int အစဉ်ဆက်ဖတ်() {
        if ((ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(0x3fd) & 1) != 0) return ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(0x3f8);
        return -1;
    }
}
