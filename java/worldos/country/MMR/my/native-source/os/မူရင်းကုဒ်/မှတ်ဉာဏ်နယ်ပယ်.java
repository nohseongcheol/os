/** စက်နှိုးသတင်း မေးမြန်းမှုနှင့် 4 KiB ပုံသေအလုပ်နယ် ခွဲဝေပြန်လွှတ်မှု။ အထွေထွေ ရုပ်ပိုင်းစာမျက်နှာစီမံသူ မဟုတ်ပါ။ */
public final class မှတ်ဉာဏ်နယ်ပယ် {
    static int[] ကဏ္ဍတန်ဖိုး = new int[8192];
    static int[] သုံးစွဲမှု = new int[8];

    static int ကိန်းပြည့်သဒ္ဒါခွဲခြမ်း(int လိပ်စာ) {
        return ကိရိယာ.မှတ်ဉာဏ်ဖတ်(လိပ်စာ) | (ကိရိယာ.မှတ်ဉာဏ်ဖတ်(လိပ်စာ + 1) << 8)
            | (ကိရိယာ.မှတ်ဉာဏ်ဖတ်(လိပ်စာ + 2) << 16) | (ကိရိယာ.မှတ်ဉာဏ်ဖတ်(လိပ်စာ + 3) << 24);
    }

    static int အပေါ်မှတ်ဉာဏ်အရွယ်() {
        int စနစ်သတင်းအချက်အလက် = ကိရိယာ.စက်တင်အချက်အလက်();
        if (ကိရိယာ.စက်နှိုးအမှတ်အသား() != 0x2badb002 || စနစ်သတင်းအချက်အလက် == 0 || (ကိန်းပြည့်သဒ္ဒါခွဲခြမ်း(စနစ်သတင်းအချက်အလက်) & 1) == 0) return -1;
        return ကိန်းပြည့်သဒ္ဒါခွဲခြမ်း(စနစ်သတင်းအချက်အလက် + 8);
    }

    static int သိုလှောင်ရာခွဲဝေ() {
        for (int နံပါတ် = 0; နံပါတ် < သုံးစွဲမှု.length; နံပါတ်++) {
            if (သုံးစွဲမှု[နံပါတ်] == 0) {
                သုံးစွဲမှု[နံပါတ်] = 1;
                for (int နေရာကွက်အချက် = 0; နေရာကွက်အချက် < 1024; နေရာကွက်အချက်++) ကဏ္ဍတန်ဖိုး[နံပါတ် * 1024 + နေရာကွက်အချက်] = 0;
                return နံပါတ်;
            }
        }
        return -1;
    }

    static boolean ပြန်ပေးရလဒ်(int နံပါတ်) {
        if (နံပါတ် < 0 || နံပါတ် >= သုံးစွဲမှု.length || သုံးစွဲမှု[နံပါတ်] == 0) return false;
        သုံးစွဲမှု[နံပါတ်] = 0;
        return true;
    }

    static int သုံးထားအချက်အရေအတွက်() {
        int အရေအတွက် = 0;
        for (int နံပါတ် = 0; နံပါတ် < သုံးစွဲမှု.length; နံပါတ်++) အရေအတွက် += သုံးစွဲမှု[နံပါတ်];
        return အရေအတွက်;
    }
}
