/** ပထမ IDE ကိရိယာ၏ 512 ဘိုက် ယုတ္တိကဏ္ဍ။ ဤအလွှာသည် ပုံစံချခြင်း သို့မဟုတ် အခြားကိရိယာ ဖျက်ခြင်း မပြုပါ။ */
public final class သိုလှောင်ကိရိယာဆက် {
    static boolean ဖြစ်သောရနိုင် = false;
    static int[] ကဏ္ဍဒေတာ = new int[512];
    static void ခဏတာစောင့်() {
        for (int နံပါတ် = 0; နံပါတ် < 4; နံပါတ်++) ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(0x3f6);
    }
    static int အသင့်ဖြစ်သည်အထိစောင့်(boolean ဒေတာလိုအပ်) {
        int လုပ်ဆောင် = ကိရိယာ.မီလီစက္ကန့်();
        while (ကိရိယာ.မီလီစက္ကန့်() - လုပ်ဆောင် < 500) {
            int အခြေအနေတန်ဖိုး = ကိရိယာ.အဝင်အထွက်ဘိုက်ဖတ်(0x1f7);
            if (အခြေအနေတန်ဖိုး == 0 || အခြေအနေတန်ဖိုး == 255) return -19;
            if ((အခြေအနေတန်ဖိုး & 128) == 0) {
                if ((အခြေအနေတန်ဖိုး & 33) != 0) return -5;
                if (!ဒေတာလိုအပ် || (အခြေအနေတန်ဖိုး & 8) != 0) return 0;
            }
            ကိရိယာ.ခဏအလှည့်ပေး();
        }
        return -110;
    }
    static int တောင်းဆိုချက်(int ကဏ္ဍတန်ဖိုး, int အမိန့်) {
        if (ကဏ္ဍတန်ဖိုး < 0 || ကဏ္ဍတန်ဖိုး >= 2048) return -22;
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x3f6, 2); // လှည့်စစ်သည်။ IDE IRQ ကို မသုံးပါ။
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x1f6, 0xe0); ခဏတာစောင့်();
        int ရလဒ် = အသင့်ဖြစ်သည်အထိစောင့်(false);
        if (ရလဒ် < 0) return ရလဒ်;
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x1f2, 1);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x1f3, ကဏ္ဍတန်ဖိုး & 255);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x1f4, (ကဏ္ဍတန်ဖိုး >>> 8) & 255);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x1f5, 0);
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x1f7, အမိန့်); ခဏတာစောင့်();
        return အသင့်ဖြစ်သည်အထိစောင့်(true);
    }
    static int ဖတ်(int ကဏ္ဍတန်ဖိုး) {
        int ရလဒ် = တောင်းဆိုချက်(ကဏ္ဍတန်ဖိုး, 0x20);
        if (ရလဒ် < 0) return ရလဒ်;
        for (int နံပါတ် = 0; နံပါတ် < 256; နံပါတ်++) {
            int တန်ဖိုး = ကိရိယာ.အဝင်အထွက်တိုဖတ်(0x1f0);
            ကဏ္ဍဒေတာ[နံပါတ် * 2] = တန်ဖိုး & 255; ကဏ္ဍဒေတာ[နံပါတ် * 2 + 1] = တန်ဖိုး >>> 8;
        }
        ခဏတာစောင့်(); return အသင့်ဖြစ်သည်အထိစောင့်(false);
    }
    static int ရေး(int ကဏ္ဍတန်ဖိုး) {
        if (!ဖြစ်သောရနိုင် || ကဏ္ဍတန်ဖိုး < 1 || ကဏ္ဍတန်ဖိုး > 518) return -19;
        int ရလဒ် = တောင်းဆိုချက်(ကဏ္ဍတန်ဖိုး, 0x30);
        if (ရလဒ် < 0) return ရလဒ်;
        for (int နံပါတ် = 0; နံပါတ် < 256; နံပါတ်++)
            ကိရိယာ.အဝင်အထွက်တိုရေး(0x1f0, ကဏ္ဍဒေတာ[နံပါတ် * 2] | ကဏ္ဍဒေတာ[နံပါတ် * 2 + 1] << 8);
        ခဏတာစောင့်(); return အသင့်ဖြစ်သည်အထိစောင့်(false);
    }
    static int ကြားခံရှင်းအထွက်() {
        if (!ဖြစ်သောရနိုင်) return -19;
        ကိရိယာ.အဝင်အထွက်ဘိုက်ရေး(0x1f7, 0xe7); ခဏတာစောင့်();
        return အသင့်ဖြစ်သည်အထိစောင့်(false);
    }
    static int ကိန်းပြည့်သဒ္ဒါခွဲခြမ်း(int နေရာ) {
        return ကဏ္ဍဒေတာ[နေရာ] | ကဏ္ဍဒေတာ[နေရာ + 1] << 8 | ကဏ္ဍဒေတာ[နေရာ + 2] << 16 | ကဏ္ဍဒေတာ[နေရာ + 3] << 24;
    }
    static void ကိန်းပြည့်တန်ဖိုးရေး(int နေရာ, int တန်ဖိုး) {
        for (int နံပါတ် = 0; နံပါတ် < 4; နံပါတ်++) ကဏ္ဍဒေတာ[နေရာ + နံပါတ်] = (တန်ဖိုး >>> (နံပါတ် * 8)) & 255;
    }
}
