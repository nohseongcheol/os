/** ဒစ်ပေါ် မရေးဘဲ လုပ်ဆောင်သော သေးငယ်သည့် စီးရီးနှင့် PS/2 အမိန့်အဓိပ္ပာယ်ဖော်စက်။ */
public final class အမိန့်အဓိပ္ပာယ်ဖော် {
    static int[] ဝင်ဒေတာ = new int[128];
    static int အလျား = 0;
    static boolean ရှေ့စာကြောင်းပြန် = false;
    static boolean စာကြောင်းလျှံကျ = false;

    static boolean အမိန့်(String အမည်) {
        if (အလျား < အမည်.length()) return false;
        for (int နံပါတ် = 0; နံပါတ် < အမည်.length(); နံပါတ်++)
            if (ဝင်ဒေတာ[နံပါတ်] != အမည်.charAt(နံပါတ်)) return false;
        return အလျား == အမည်.length() || ဝင်ဒေတာ[အမည်.length()] == ' ';
    }

    static void အကူအညီပြသ() {
        စာသားစက်.ရေး("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        စာသားစက်.ရေး("apps | run NAME [ARGS] | net\n");
        စာသားစက်.ရေး("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        စာသားစက်.ရေး("sync (연결된 JKSTORE1 သိုလှောင်တန်ဖိုး 장치에 ဖိုင် 보존)\n");
    }

    static void လုပ်ငန်းစဉ်တန်ဖိုးအချက်() {
        if (အလျား == 0) return;
        if (အမိန့်("help")) အကူအညီပြသ();
        else if (အမိန့်("sync")) {
            int ရလဒ် = ဖိုင်ထိန်းသိမ်းမှု.တစ်ပြေးညီလုပ်();
            စာသားစက်.ရေး("Sync: "); စာသားစက်.ကိန်းထုတ်(ရလဒ်); စာသားစက်.အက္ခရာ(10);
        }
        else if (အမိန့်("ls")) မှတ်ဉာဏ်ဖိုင်စနစ်.အချက်စာရင်း();
        else if (အမိန့်("edit")) မှတ်ဉာဏ်ဖိုင်စနစ်.အမိန့်(ဝင်ဒေတာ, 4, အလျား, 0);
        else if (အမိန့်("cat")) မှတ်ဉာဏ်ဖိုင်စနစ်.အမိန့်(ဝင်ဒေတာ, 3, အလျား, 1);
        else if (အမိန့်("rm")) မှတ်ဉာဏ်ဖိုင်စနစ်.အမိန့်(ဝင်ဒေတာ, 2, အလျား, 2);
        else if (အမိန့်("java") || အမိန့်("javac")) {
            int ရလဒ် = လုပ်ဆောင်မှုစီမံ.စက်မောင်း(ဝင်ဒေတာ, 0, အလျား);
            စာသားစက်.ရေး("Exit: "); စာသားစက်.ကိန်းထုတ်(ရလဒ်); စာသားစက်.အက္ခရာ(10);
        }
        else if (အမိန့်("apps")) လုပ်ဆောင်မှုစီမံ.အချက်စာရင်း();
        else if (အမိန့်("net")) ကွန်ရက်အလွှာစု.အခြေအနေတန်ဖိုး();
        else if (အမိန့်("run")) {
            int ရလဒ် = လုပ်ဆောင်မှုစီမံ.စက်မောင်း(ဝင်ဒေတာ, 3, အလျား);
            စာသားစက်.ရေး("Exit: "); စာသားစက်.ကိန်းထုတ်(ရလဒ်); စာသားစက်.ရေး("\n");
        } else if (အမိန့်("info")) {
            စာသားစက်.ရေး("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (အမိန့်("mem")) {
            စာသားစက်.ရေး("အပေါ်ဘက် မှတ်ဉာဏ် သတ်မှတ်လိပ်စာနယ်(KiB): "); စာသားစက်.ကိန်းထုတ်(မှတ်ဉာဏ်နယ်ပယ်.အပေါ်မှတ်ဉာဏ်အရွယ်());
            စာသားစက်.ရေး("\n배열 동적 မှတ်ဉာဏ် သတ်မှတ်လိပ်စာနယ်(ဘိုက်တန်ဖိုး): "); စာသားစက်.ကိန်းထုတ်(ကိရိယာ.အခင်းအကျင်းအသုံးပြုပုံ());
            စာသားစက်.ရေး(" / 262144\n작업 သတ်မှတ်လိပ်စာနယ် ကဏ္ဍတန်ဖိုး: "); စာသားစက်.ကိန်းထုတ်(မှတ်ဉာဏ်နယ်ပယ်.သုံးထားအချက်အရေအတွက်());
            စာသားစက်.ရေး(" / 8 (각 4096바이트)\n");
        } else if (အမိန့်("alloc")) {
            int နံပါတ် = မှတ်ဉာဏ်နယ်ပယ်.သိုလှောင်ရာခွဲဝေ();
            စာသားစက်.ရေး("ကဏ္ဍတန်ဖိုး နံပါတ်: "); စာသားစက်.ကိန်းထုတ်(နံပါတ်); စာသားစက်.ရေး("\n");
        } else if (အမိန့်("free")) {
            if (အလျား == 6 && ဝင်ဒေတာ[4] == ' ' && ဝင်ဒေတာ[5] >= '0' && ဝင်ဒေတာ[5] <= '7') {
                စာသားစက်.ရေး(မှတ်ဉာဏ်နယ်ပယ်.ပြန်ပေးရလဒ်(ဝင်ဒေတာ[5] - '0') ? "반환됨\n" : "할당되지 않은 ကဏ္ဍတန်ဖိုး\n");
            } else စာသားစက်.ရေး("사용법: free 0..7\n");
        } else if (အမိန့်("echo")) {
            for (int နံပါတ် = 5; နံပါတ် < အလျား; နံပါတ်++) စာသားစက်.အက္ခရာ(ဝင်ဒေတာ[နံပါတ်]);
            စာသားစက်.အက္ခရာ(10);
        } else if (အမိန့်("clear")) စာသားစက်.အချက်ဖျက်();
        else if (အမိန့်("test")) အူတိုင်.စမ်းသပ်မှု();
        else if (အမိန့်("halt")) {
            စာသားစက်.ရေး("HALTED\n");
            ကိရိယာ.လုပ်ဆောင်မှုရပ်();
        } else စာသားစက်.ရေး("알 ကိန်းတန်ဖိုး 없는 명령입니다. help를 입력하세요.\n");
    }

    static void နှင့်ရေးလက်ခံ(int တန်ဖိုး) {
        if (တန်ဖိုး == 10 && ရှေ့စာကြောင်းပြန်) { ရှေ့စာကြောင်းပြန် = false; return; }
        ရှေ့စာကြောင်းပြန် = တန်ဖိုး == 13;
        if (တန်ဖိုး == 10 || တန်ဖိုး == 13) {
            စာသားစက်.အက္ခရာ(10);
            if (မှတ်ဉာဏ်ဖိုင်စနစ်.ပြင်ဆင်နေသလား) မှတ်ဉာဏ်ဖိုင်စနစ်.ပြင်ထားစာကြောင်း(ဝင်ဒေတာ, အလျား, စာကြောင်းလျှံကျ);
            else လုပ်ငန်းစဉ်တန်ဖိုးအချက်();
            အလျား = 0;
            စာကြောင်းလျှံကျ = false;
            စာသားစက်.ရေး(မှတ်ဉာဏ်ဖိုင်စနစ်.ပြင်ဆင်နေသလား ? "...> " : "jkoros> ");
        } else if (တန်ဖိုး == 8 || တန်ဖိုး == 127) {
            if (အလျား > 0) {
                အလျား--;
                စာသားစက်.အစဉ်ဆက်ဘိုက်(8); စာသားစက်.အစဉ်ဆက်ဘိုက်(32); စာသားစက်.အစဉ်ဆက်ဘိုက်(8);
                စာသားစက်.မျက်နှာပြင်အက္ခရာ(8);
            }
        } else if (တန်ဖိုး >= 32 && တန်ဖိုး < 127 && အလျား < ဝင်ဒေတာ.length) {
            ဝင်ဒေတာ[အလျား++] = တန်ဖိုး;
            စာသားစက်.အက္ခရာ(တန်ဖိုး);
        } else if (တန်ဖိုး >= 32 && တန်ဖိုး < 127) စာကြောင်းလျှံကျ = true;
    }

    static void လုပ်ဆောင်() {
        အကူအညီပြသ();
        စာသားစက်.ရေး("READY\njkoros> ");
        while (true) {
            int တန်ဖိုး = စာသားစက်.အစဉ်ဆက်ဖတ်();
            if (တန်ဖိုး < 0) တန်ဖိုး = လက်ကွက်.ဖတ်();
            if (တန်ဖိုး >= 0) နှင့်ရေးလက်ခံ(တန်ဖိုး);
            else { ကွန်ရက်အလွှာစု.အတည်ပြု(); ကိရိယာ.ခဏအလှည့်ပေး(); }
        }
    }
}
