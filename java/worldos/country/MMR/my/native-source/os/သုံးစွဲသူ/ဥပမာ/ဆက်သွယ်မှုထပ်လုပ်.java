/** အများဆုံးအရွယ်နှင့် မကိန်းအရှည် ဒေတာစာများဖြင့် RTL8139 လက်ခံကွင်း ပတ်လည်လည်မှုကို အမှန်စမ်းသပ်သည်။ */
public final class ဆက်သွယ်မှုထပ်လုပ် {
    public static int လုပ်ဆောင်() {
        if (သုံးစွဲသူ.ပေးအချက်များအရေအတွက်() != 1) { သုံးစွဲသူ.ရေး("Usage: run stress PORT\n"); return 2; }
        String စာသား = သုံးစွဲသူ.အချက်များ(0);
        int ဆက်သွယ်ပေါက်တန်ဖိုး = 0;
        for (int နံပါတ် = 0; နံပါတ် < စာသား.length(); နံပါတ်++) {
            if (စာသား.charAt(နံပါတ်) < '0' || စာသား.charAt(နံပါတ်) > '9' || ဆက်သွယ်ပေါက်တန်ဖိုး > 6553) return 2;
            ဆက်သွယ်ပေါက်တန်ဖိုး = ဆက်သွယ်ပေါက်တန်ဖိုး * 10 + စာသား.charAt(နံပါတ်) - '0';
        }
        if (ဆက်သွယ်ပေါက်တန်ဖိုး < 1 || ဆက်သွယ်ပေါက်တန်ဖိုး > 65535) return 2;
        int ကိုင်တွယ်ရာတန်ဖိုး = သုံးစွဲသူ.ကွန်ရက်ဖွင့်(0);
        if (ကိုင်တွယ်ရာတန်ဖိုး < 0) return 3;
        int[] ဒေတာ = new int[1024];
        for (int အလှည့်အစဉ် = 0; အလှည့်အစဉ် < 24; အလှည့်အစဉ်++) {
            int အလျား = 1024 - (အလှည့်အစဉ် & 1);
            for (int နံပါတ် = 0; နံပါတ် < အလျား; နံပါတ်++) ဒေတာ[နံပါတ်] = (နံပါတ် + အလှည့်အစဉ်) & 255;
            if (သုံးစွဲသူ.ဒေတာပို့(ကိုင်တွယ်ရာတန်ဖိုး, 0x0a000202, ဆက်သွယ်ပေါက်တန်ဖိုး, ဒေတာ, အလျား) != အလျား) return 4;
            if (သုံးစွဲသူ.ဒေတာလက်ခံရယူ(ကိုင်တွယ်ရာတန်ဖိုး, ဒေတာ, 300) != အလျား) return 5;
            for (int နံပါတ် = 0; နံပါတ် < အလျား; နံပါတ်++) if (ဒေတာ[နံပါတ်] != ((နံပါတ် + အလှည့်အစဉ်) & 255)) return 6;
        }
        သုံးစွဲသူ.ကွန်ရက်ပိတ်(ကိုင်တွယ်ရာတန်ဖိုး);
        သုံးစွဲသူ.ရေး("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
