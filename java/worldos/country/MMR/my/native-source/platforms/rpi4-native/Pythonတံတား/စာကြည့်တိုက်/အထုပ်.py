"""ကိုယ်ပိုင် 커널용 제한형 pip. PyPI의 작은 순수 Python 소스를 အိမ်ရှင် 중계로 설치한다."""
import sys
import json
import hashlib
import gc
import jkoros as စက်စနစ်

목록경로 = "/lib/.pip.json"


def 지문(ဒေတာ):
    return "".join("%02x" % တန်ဖိုး for တန်ဖိုး in hashlib.sha256(ဒေတာ).digest())


def စာရင်းဖတ်():
    if စက်စနစ်.path_kind(목록경로) == 0:
        return {}
    return json.loads(စက်စနစ်.read(목록경로).decode("utf-8"))


def မှတ်တမ်းရေး(လမ်း, ဒေတာ):
    if စက်စနစ်.write(လမ်း, ဒေတာ) != len(ဒေတာ):
        raise OSError(28)


def လမ်းကြောင်းစစ်(လမ်း):
    if not isinstance(လမ်း, str) or not လမ်း.endswith(".py"):
        raise ValueError("Python 소스만 설치할 ကိန်းတန်ဖိုး 있습니다.")
    if any(အစိတ်အပိုင်းတန်ဖိုး in ("", ".", "..") or အစိတ်အပိုင်းတန်ဖိုး.startswith(".") for အစိတ်အပိုင်းတန်ဖိုး in လမ်း.split("/")):
        raise ValueError("허용하지 않는 အထုပ် လမ်း")
    if "\\" in လမ်း or any(ord(အက္ခရာတန်ဖိုး) < 32 or ord(အက္ခရာတန်ဖိုး) == 127 for အက္ခရာတန်ဖိုး in လမ်း):
        raise ValueError("잘못된 လမ်း အက္ခရာ")
    ရလဒ် = "/lib/" + လမ်း
    if len(ရလဒ်.encode("utf-8")) > 63 or လမ်း in ("မြန်မာ.py", "အထုပ်.py"):
        raise ValueError("အထုပ် 경로가 너무 길거나 မူလသတ်မှတ်တန်ဖိုး 라이브러리와 겹칩니다.")
    return ရလဒ်


class စီးကြောင်းလက်ခံရယူ:
    def __init__(자신, ဆုံးမှတ်):
        자신.ဆုံးမှတ် = ဆုံးမှတ်
        자신.ကျန်ရှိဒေတာ = b""
        자신.လုပ်ဆောင် = စက်စနစ်.ticks_ms()

    def 정확히읽기(자신, အလျား):
        ဒေတာ = bytearray()
        while len(ဒေတာ) < အလျား:
            if စက်စနစ်.ticks_ms() - 자신.လုပ်ဆောင် > 90000:
                raise ValueError("အထုပ် 중계 အကြောင်းပြန်ချက် အချိန်တန်ဖိုး 초과")
            if not 자신.ကျန်ရှိဒေတာ:
                try:
                    자신.ကျန်ရှိဒေတာ = စက်စနစ်.tcp_read(자신.ဆုံးမှတ်, 512)
                except OSError as အမှား:
                    if အမှား.args[0] != 11:
                        raise
                    စက်စနစ်.sleep_ms(10)
                    continue
                if not 자신.ကျန်ရှိဒေတာ:
                    raise ValueError("အထုပ် 전송이 중간에 끝났습니다.")
            အရေအတွက် = min(အလျား - len(ဒေတာ), len(자신.ကျန်ရှိဒေတာ))
            ဒေတာ.extend(자신.ကျန်ရှိဒေတာ[:အရေအတွက်])
            자신.ကျန်ရှိဒေတာ = 자신.ကျန်ရှိဒေတာ[အရေအတွက်:]
            စက်စနစ်.sleep_ms(0)
        return bytes(ဒေတာ)


def ဆွဲယူ(တောင်းဆိုချက်, ဆက်သွယ်ပေါက်ကိန်း):
    if len(တောင်းဆိုချက်) > 96 or any(အက္ခရာတန်ဖိုး not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-=" for အက္ခရာတန်ဖိုး in တောင်းဆိုချက်):
        raise ValueError("사용법: pip install အမည် 또는 အမည်==버전")
    ဆုံးမှတ် = စက်စနစ်.tcp_open()
    try:
        လုပ်ဆောင် = စက်စနစ်.ticks_ms()
        while True:
            try:
                စက်စနစ်.tcp_connect(ဆုံးမှတ်, "10.0.2.2", ဆက်သွယ်ပေါက်ကိန်း)
                break
            except OSError as အမှား:
                if အမှား.args[0] not in (11, 115) or စက်စနစ်.ticks_ms() - လုပ်ဆောင် > 5000:
                    raise ValueError("အထုပ် 중계 ချိတ်ဆက် မအောင်မြင်မှု: 호스트에서 --network --pip로 실행하십시오.")
                စက်စနစ်.sleep_ms(10)
        ဒေတာ = (တောင်းဆိုချက် + "\n").encode()
        while ဒေတာ:
            try:
                အရေအတွက် = စက်စနစ်.tcp_write(ဆုံးမှတ်, ဒေတာ)
                if not အရေအတွက်:
                    raise ValueError("အထုပ် တောင်းဆိုချက် လွှဲပြောင်းတန်ဖိုး မအောင်မြင်မှု")
                ဒေတာ = ဒေတာ[အရေအတွက်:]
            except OSError as အမှား:
                if အမှား.args[0] != 11:
                    raise
                စက်စနစ်.sleep_ms(10)
                if စက်စနစ်.ticks_ms() - လုပ်ဆောင် > 10000:
                    raise ValueError("အထုပ် တောင်းဆိုချက် လွှဲပြောင်းတန်ဖိုး အချိန်တန်ဖိုး 초과")
        စီးကြောင်းတန်ဖိုး = စီးကြောင်းလက်ခံရယူ(ဆုံးမှတ်)
        ဦးခေါင်းတန်ဖိုး = စီးကြောင်းတန်ဖိုး.정확히읽기(8)
        if ဦးခေါင်းတန်ဖိုး[:4] != b"JKP1":
            raise ValueError("အထုပ် လွှဲပြောင်းတန်ဖိုး သဘောတူစည်းမျဉ်းတန်ဖိုး 불일치")
        အလျား = (ဦးခေါင်းတန်ဖိုး[4] << 24) | (ဦးခေါင်းတန်ဖိုး[5] << 16) | (ဦးခေါင်းတန်ဖိုး[6] << 8) | ဦးခေါင်းတန်ဖိုး[7]
        if အလျား > 8192:
            raise ValueError("အထုပ် 명세가 너무 큽니다.")
        သတ်မှတ်စံ = json.loads(စီးကြောင်းတန်ဖိုး.정확히읽기(အလျား).decode())
        if "error" in သတ်မှတ်စံ:
            raise ValueError(သတ်မှတ်စံ["error"])
        if not 1 <= len(သတ်မှတ်စံ["files"]) <= 16:
            raise ValueError("꾸러미당 မူရင်းကုဒ်အပင်ဖွဲ့စည်းပုံ 파일은 1~16개여야 합니다.")
        if sum(အချက်တန်ဖိုး["size"] for အချက်တန်ဖိုး in သတ်မှတ်စံ["files"]) > 65536:
            raise ValueError("အထုပ် မူရင်းကုဒ်အပင်ဖွဲ့စည်းပုံ 합계는 64 KiB 이하여야 합니다.")
        ဖိုင်အချက်များ = {}
        for အချက်တန်ဖိုး in သတ်မှတ်စံ["files"]:
            လမ်း = လမ်းကြောင်းစစ်(အချက်တန်ဖိုး["path"])
            if လမ်း in ဖိုင်အချက်များ or not 0 <= အချက်တန်ဖိုး["size"] <= 16384:
                raise ValueError("중복 လမ်း 또는 ဖိုင် အရွယ် 초과")
            ဒေတာ = စီးကြောင်းတန်ဖိုး.정확히읽기(အချက်တန်ဖိုး["size"])
            if 지문(ဒေတာ) != အချက်တန်ဖိုး["sha256"]:
                raise ValueError("အထုပ် ဖိုင် SHA-256 불일치")
            # 실행하지 않고 လက်ရှိအချက်အလက်တစ်ခု MicroPython의 문법으로 먼저 검사한다.
            compile(ဒေတာ.decode("utf-8"), လမ်း, "exec")
            ဖိုင်အချက်များ[လမ်း] = ဒေတာ
            gc.collect()
        return သတ်မှတ်စံ, ဖိုင်အချက်များ
    finally:
        စက်စနစ်.udp_close(ဆုံးမှတ်)


def တန်ဖိုးတပ်ဆင်(တောင်းဆိုချက်, ဆက်သွယ်ပေါက်ကိန်း):
    print("အထုပ် ဆွဲယူ:", တောင်းဆိုချက်)
    သတ်မှတ်စံ, ဖိုင်အချက်များ = ဆွဲယူ(တောင်းဆိုချက်, ဆက်သွယ်ပေါက်ကိန်း)
    အချက်စာရင်း = စာရင်းဖတ်()
    အမည် = သတ်မှတ်စံ["name"]
    if အမည် in အချက်စာရင်း:
        if အချက်စာရင်း[အမည်]["version"] == သတ်မှတ်စံ["version"]:
            for လမ်း, 지문값 in အချက်စာရင်း[အမည်]["files"].items():
                if စက်စနစ်.path_kind(လမ်း) != 1 or 지문(စက်စနစ်.read(လမ်း)) != 지문값:
                    raise ValueError("설치된 အထုပ် 파일이 달라졌습니다: " + လမ်း)
            print("이미 설치됨:", အမည်, သတ်မှတ်စံ["version"])
            return
        raise ValueError("다른 버전이 있습니다. pip uninstall로 제거한 နောက်တန်ဖိုး 설치하십시오.")
    for လမ်း in ဖိုင်အချက်များ:
        if စက်စနစ်.path_kind(လမ်း):
            raise ValueError("기존 파일을 덮어쓰지 않습니다: " + လမ်း)
    အချက်စာရင်း[အမည်] = {"version": သတ်မှတ်စံ["version"], "files": {လမ်း: 지문(ဒေတာ) for လမ်း, ဒေတာ in ဖိုင်အချက်များ.items()}}
    အသစ်စာရင်း = json.dumps(အချက်စာရင်း).encode()
    if len(အသစ်စာရင်း) > 16384:
        raise ValueError("အထုပ် အချက်စာရင်း အရွယ် 초과")
    ယခင်စာရင်း = စက်စနစ်.read(목록경로) if စက်စနစ်.path_kind(목록경로) else None
    만든파일 = []
    만든폴더 = []
    try:
        for လမ်း, ဒေတာ in ဖိုင်အချက်များ.items():
            အစိတ်အပိုင်းများ = လမ်း.split("/")
            for ကိန်းတန်ဖိုး in range(2, len(အစိတ်အပိုင်းများ)):
                ဖိုင်တွဲတန်ဖိုး = "/".join(အစိတ်အပိုင်းများ[:ကိန်းတန်ဖိုး])
                အမျိုးအစားတန်ဖိုး = စက်စနစ်.path_kind(ဖိုင်တွဲတန်ဖိုး)
                if အမျိုးအစားတန်ဖိုး == 0:
                    စက်စနစ်.mkdir(ဖိုင်တွဲတန်ဖိုး)
                    만든폴더.append(ဖိုင်တွဲတန်ဖိုး)
                elif အမျိုးအစားတန်ဖိုး != 2:
                    raise ValueError("ဖိုင်တွဲတန်ဖိုး 경로에 파일이 있습니다: " + ဖိုင်တွဲတန်ဖိုး)
            만든파일.append(လမ်း)
            မှတ်တမ်းရေး(လမ်း, ဒေတာ)
        မှတ်တမ်းရေး(목록경로, အသစ်စာရင်း)
    except Exception:
        for လမ်း in 만든파일:
            if စက်စနစ်.path_kind(လမ်း):
                စက်စနစ်.remove(လမ်း)
        for ဖိုင်တွဲတန်ဖိုး in reversed(만든폴더):
            စက်စနစ်.rmdir(ဖိုင်တွဲတန်ဖိုး)
        if ယခင်စာရင်း is not None:
            မှတ်တမ်းရေး(목록경로, ယခင်စာရင်း)
        elif စက်စနစ်.path_kind(목록경로):
            စက်စနစ်.remove(목록경로)
        raise
    print("တန်ဖိုးတပ်ဆင် ဖြစ်သောအပြည့်အစုံ:", အမည်, သတ်မှတ်စံ["version"], "→ /lib (RAM)")


def အချက်ဖယ်ရှား(အမည်):
    အချက်စာရင်း = စာရင်းဖတ်()
    if အမည် not in အချက်စာရင်း:
        raise ValueError("설치되지 않은 꾸러미입니다: " + အမည်)
    for လမ်း, 지문값 in အချက်စာရင်း[အမည်]["files"].items():
        if စက်စနစ်.path_kind(လမ်း) != 1 or 지문(စက်စနစ်.read(လမ်း)) != 지문값:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + လမ်း)
    for လမ်း in အချက်စာရင်း[အမည်]["files"]:
        စက်စနစ်.remove(လမ်း)
    del အချက်စာရင်း[အမည်]
    မှတ်တမ်းရေး(목록경로, json.dumps(အချက်စာရင်း).encode())
    print("အချက်ဖယ်ရှား ဖြစ်သောအပြည့်အစုံ:", အမည်)


def လုပ်ဆောင်(အချက်များ):
    ဆက်သွယ်ပေါက်ကိန်း = 8027
    if len(အချက်များ) >= 2 and အချက်များ[-2] == "--port":
        ဆက်သွယ်ပေါက်ကိန်း = int(အချက်များ[-1])
        အချက်များ = အချက်များ[:-2]
    if အချက်များ == ["list"]:
        for အမည်, စနစ်သတင်းအချက်အလက် in စာရင်းဖတ်().items():
            print(အမည်, စနစ်သတင်းအချက်အလက်["version"])
    elif len(အချက်များ) == 2 and အချက်များ[0] == "install":
        တန်ဖိုးတပ်ဆင်(အချက်များ[1], ဆက်သွယ်ပေါက်ကိန်း)
    elif len(အချက်များ) == 2 and အချက်များ[0] == "uninstall":
        အချက်ဖယ်ရှား(အချက်များ[1])
    elif not အချက်များ or အချက်များ in (["--help"], ["--version"]):
        print("jkoros pip 1 / MicroPython မူရင်းကုဒ်အပင်ဖွဲ့စည်းပုံ 설치기 (PyPA pip 전체가 아님)")
        print("pip install အမည်[==버전] [--port 8027] | pip list | pip uninstall အမည်")
        print("အိမ်ရှင်: ကိရိယာစု/စက်မောင်း.py --network --pip; /lib는 재부팅 때 사라지는 RAM입니다.")
    else:
        raise ValueError("pip --help로 사용법을 확인하십시오.")


if __name__ == "__main__":
    try:
        လုပ်ဆောင်(sys.argv[1:])
    except Exception as အမှား:
        print("အထုပ် အမှား:", အမှား)
        sys.exit(1)
