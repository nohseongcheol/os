#!/usr/bin/env python3
"""ကိုယ်ပိုင် Java ဒေသတွင်းနယ်ပယ်ကန့်သတ် 이름을 바꾼다. အက္ခရာစဉ်·주석·ပြင်ပတန်ဖိုး 멤버 이름은 보존한다."""
import json
import re
from pathlib import Path

စီမံကိန်းအမြစ် = Path(__file__).resolve().parents[1]
ချိတ်ဆက်ပုံတန်ဖိုး = json.loads((စီမံကိန်းအမြစ် / '명명/Javaအမည်များ.json').read_text())
အပိုင်းကိန်းဖော်ပြချက် = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[\w$]+|[^\w\s]', re.UNICODE)
မှတ်တမ်းမှတ်တမ်းတစ်ခု = []
for ဖိုင်တွဲတန်ဖိုး in ('မူရင်းကုဒ်', 'သုံးစွဲသူ/Java', 'မြန်မာJava'):
    for လမ်း in sorted((စီမံကိန်းအမြစ် / ဖိုင်တွဲတန်ဖိုး).rglob('*.java')):
        မူရင်းကုဒ် = လမ်း.read_text()
        토막들 = list(အပိုင်းကိန်းဖော်ပြချက်.finditer(မူရင်းကုဒ်))
        사용이름 = {토막.group() for 토막 in 토막들 if re.search('[ပထမတွက်ချက်ခံ-힣]', 토막.group())}
        ဖိုင်ချိတ်ဆက်ပုံ = {}
        for ယခင်အချက်အလက်တစ်ခု, 이후 in ချိတ်ဆက်ပုံတန်ဖိုး.items():
            # A pre-existing Korean binding must never be shadowed by renaming.
            အသစ်အမည် = 이후
            while အသစ်အမည် in 사용이름: အသစ်အမည် = 'ဒေသတွင်းနယ်ပယ်ကန့်သတ်' + အသစ်အမည်
            ဖိုင်ချိတ်ဆက်ပုံ[ယခင်အချက်အလက်တစ်ခု] = အသစ်အမည်
        수정 = []
        이전토막 = ''
        for 토막 in 토막들:
            ဝေါဟာရ = 토막.group()
            if ဝေါဟာရ.startswith(('//', '/*', '"', "'")): continue
            if ဝေါဟာရ in ဖိုင်ချိတ်ဆက်ပုံ and 이전토막 != '.':
                수정.append((토막.start(), 토막.end(), ဖိုင်ချိတ်ဆက်ပုံ[ဝေါဟာရ]))
                မှတ်တမ်းမှတ်တမ်းတစ်ခု.append((str(လမ်း.relative_to(စီမံကိန်းအမြစ်)), ဝေါဟာရ, ဖိုင်ချိတ်ဆက်ပုံ[ဝေါဟာရ]))
            이전토막 = ဝေါဟာရ
        for လုပ်ဆောင်, အဆုံး, အသစ်အမည် in reversed(수정): မူရင်းကုဒ် = မူရင်းကုဒ်[:လုပ်ဆောင်] + အသစ်အမည် + မူရင်းကုဒ်[အဆုံး:]
        if 수정: လမ်း.write_text(မူရင်းကုဒ်)
(စီမံကိန်းအမြစ် / '명명/Javaအမည်ချိတ်ဆက်ပုံ.tsv').write_text('ဖိုင်\t이전\t이후\n' + ''.join('\t'.join(အချက်တန်ဖိုး)+'\n' for အချက်တန်ဖိုး in sorted(set(မှတ်တမ်းမှတ်တမ်းတစ်ခု))))
print('Java အမည် ကိုးကားချက် တန်ဖိုးပြောင်း:', len(မှတ်တမ်းမှတ်တမ်းတစ်ခု))
