"""Two-set Hangul composition for the native VNC-to-UART input bridge.

The pending character is visible in the guest editor. Replacing it uses that
editor's UTF-8 Backspace, so commit before cursor motion, shortcuts or a click.
No host input-method daemon or third-party Python package is required.
"""

첫소리목록 = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
가운뎃소리목록 = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
끝소리목록 = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'
သော့နေရာချပုံ = dict(zip('rRseEfaqQtTdwWczxvgkoiOjpuPhynbml',
                'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎㅏㅐㅑㅒㅓㅔㅕㅖㅗㅛㅜㅠㅡㅣ'))
겹가운뎃소리 = {('ㅗ','ㅏ'):'ㅘ',('ㅗ','ㅐ'):'ㅙ',('ㅗ','ㅣ'):'ㅚ',
          ('ㅜ','ㅓ'):'ㅝ',('ㅜ','ㅔ'):'ㅞ',('ㅜ','ㅣ'):'ㅟ',('ㅡ','ㅣ'):'ㅢ'}
겹끝소리 = {('ㄱ','ㅅ'):'ㄳ',('ㄴ','ㅈ'):'ㄵ',('ㄴ','ㅎ'):'ㄶ',
          ('ㄹ','ㄱ'):'ㄺ',('ㄹ','ㅁ'):'ㄻ',('ㄹ','ㅂ'):'ㄼ',('ㄹ','ㅅ'):'ㄽ',
          ('ㄹ','ㅌ'):'ㄾ',('ㄹ','ㅍ'):'ㄿ',('ㄹ','ㅎ'):'ㅀ',('ㅂ','ㅅ'):'ㅄ'}
끝소리가르기 = {တန်ဖိုး: 한쌍 for 한쌍,တန်ဖိုး in 겹끝소리.items()}


class ဟန်ဂုဖွဲ့စပ်:
    def __init__(자신, ပို့):
        자신.ပို့ = ပို့
        자신.조합확정()

    def 조합확정(자신):
        자신.အခြေအနေကုဒ် = ('','','')
        자신.မှတ်တမ်းဟောင်း = []

    def စာသား(자신):
        첫소리,가운뎃소리,끝소리 = 자신.အခြေအနေကုဒ်
        if 첫소리 and 가운뎃소리:
            return chr(0xac00 + (첫소리목록.index(첫소리)*21 + 가운뎃소리목록.index(가운뎃소리))*28
                       + (끝소리목록.index(끝소리) if 끝소리 else 0))
        return 첫소리 or 가운뎃소리

    def 앞글자지우기(자신):
        if not 자신.မှတ်တမ်းဟောင်း:
            return False
        자신.အခြေအနေကုဒ် = 자신.မှတ်တမ်းဟောင်း.pop()
        자신.ပို့(b'\x7f' + 자신.စာသား().encode('utf-8'))
        return True

    def 글쇠넣기(자신, 누름값):
        အက္ခရာဒေတာ = သော့နေရာချပုံ.get(누름값, သော့နေရာချပုံ.get(누름값.lower()))
        if အက္ခရာဒေတာ is None:
            return False
        ယခင်အချက်အလက်တစ်ခု = 자신.စာသား()
        첫소리,가운뎃소리,끝소리 = 자신.အခြေအနေကုဒ်
        မှတ်တမ်းဟောင်း = 자신.မှတ်တမ်းဟောင်း + [자신.အခြေအနေကုဒ်]
        확정글 = ''
        if အက္ခရာဒေတာ in 첫소리목록:
            if 첫소리 and 가운뎃소리 and not 끝소리 and အက္ခရာဒေတာ in 끝소리목록:
                끝소리 = အက္ခရာဒေတာ
            elif 끝소리 and (끝소리,အက္ခရာဒေတာ) in 겹끝소리:
                끝소리 = 겹끝소리[끝소리,အက္ခရာဒေတာ]
            else:
                확정글 = ယခင်အချက်အလက်တစ်ခု
                첫소리,가운뎃소리,끝소리 = အက္ခရာဒေတာ,'',''
                မှတ်တမ်းဟောင်း = [('','','')]
        elif 끝소리:
            ဘယ်ဘက်,ညာ = 끝소리가르기.get(끝소리, ('',끝소리))
            자신.အခြေအနေကုဒ် = 첫소리,가운뎃소리,ဘယ်ဘက်
            확정글 = 자신.စာသား()
            첫소리,가운뎃소리,끝소리 = ညာ,အက္ခရာဒေတာ,''
            မှတ်တမ်းဟောင်း = [('','',''),(ညာ,'','')]
        elif 가운뎃소리:
            if (가운뎃소리,အက္ခရာဒေတာ) in 겹가운뎃소리:
                가운뎃소리 = 겹가운뎃소리[가운뎃소리,အက္ခရာဒေတာ]
            else:
                확정글 = ယခင်အချက်အလက်တစ်ခု
                첫소리,가운뎃소리,끝소리 = '',အက္ခရာဒေတာ,''
                မှတ်တမ်းဟောင်း = [('','','')]
        else:
            가운뎃소리 = အက္ခရာဒေတာ
        자신.အခြေအနေကုဒ် = 첫소리,가운뎃소리,끝소리
        자신.မှတ်တမ်းဟောင်း = မှတ်တမ်းဟောင်း
        자신.ပို့((b'\x7f' if ယခင်အချက်အလက်တစ်ခု else b'') + (확정글+자신.စာသား()).encode('utf-8'))
        return True
