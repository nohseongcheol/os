#include "ခေါ်နယ်နိမိတ်.h"
extern int main(int ပေးအချက်များအရေအတွက်, char **ပေးအချက်စာရင်း);
static char ပေးအချက်မှတ်ဉာဏ်[2048];
static char *ပေးအချက်စာရင်း[18];
int jkoros_main(void) {
    int အရေအတွက် = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (အရေအတွက် < 0 || အရေအတွက် > 16) return 126;
    /* လက်ရှိအချက်အလက်တစ်ခု 커널의 argv는 စက်မောင်း 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    ပေးအချက်စာရင်း[0] = "jkoros-app";
    int နေရာ = 0;
    for (int နံပါတ် = 0; နံပါတ် < အရေအတွက်; နံပါတ်++) {
        const int *မူရင်း = (const int *)jkoros_syscall(3, နံပါတ်, 0, 0, 0, 0);
        if (!မူရင်း || မူရင်း[0] < 0 || မူရင်း[0] > 127) return 126;
        ပေးအချက်စာရင်း[နံပါတ် + 1] = ပေးအချက်မှတ်ဉာဏ် + နေရာ;
        for (int နေရာကွက်အချက် = 0; နေရာကွက်အချက် < မူရင်း[0]; နေရာကွက်အချက်++) {
            if (နေရာ >= 2047) return 126;
            ပေးအချက်မှတ်ဉာဏ်[နေရာ++] = မူရင်း[နေရာကွက်အချက် + 1];
        }
        ပေးအချက်မှတ်ဉာဏ်[နေရာ++] = 0;
    }
    ပေးအချက်စာရင်း[အရေအတွက် + 1] = 0;
    return main(အရေအတွက် + 1, ပေးအချက်စာရင်း);
}
