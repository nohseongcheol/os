package မြန်မာနိုင်ငံ.JMmrOS.ကွန်ရက်အလွှာစု;

/** Ethernet/ARP/IPv4/ICMP/UDP အလွှာများ မျှဝေသော ဘိုက်အစဉ်နှင့် စစ်ဆေးပေါင်း ကိရိယာများ။ */
public final class ကွန်ရက်ကိရိယာ {
    private ကွန်ရက်ကိရိယာ() {
    }

    public static int အမြင့်ဘိုက်ရှေ့ကိန်းတို(byte[] ဒေတာ, int နေရာ) {
        အပိုင်းအခြားစစ်(ဒေတာ, နေရာ, 2);
        return ((ဒေတာ[နေရာ] & 0xff) << 8) | (ဒေတာ[နေရာ + 1] & 0xff);
    }

    public static long အမြင့်ဘိုက်ရှေ့ကိန်းပြည့်(byte[] ဒေတာ, int နေရာ) {
        အပိုင်းအခြားစစ်(ဒေတာ, နေရာ, 4);
        return ((long) (ဒေတာ[နေရာ] & 0xff) << 24)
                | ((long) (ဒေတာ[နေရာ + 1] & 0xff) << 16)
                | ((long) (ဒေတာ[နေရာ + 2] & 0xff) << 8)
                | (ဒေတာ[နေရာ + 3] & 0xffL);
    }

    public static int အင်တာနက်စစ်ပေါင်း(byte[] ဒေတာ, int လုပ်ဆောင်, int အလျား) {
        အပိုင်းအခြားစစ်(ဒေတာ, လုပ်ဆောင်, အလျား);
        long စုစုပေါင်းတန်ဖိုး = 0;
        int အဆုံး = လုပ်ဆောင် + အလျား;
        int နေရာ = လုပ်ဆောင်;
        while (နေရာ + 1 < အဆုံး) {
            စုစုပေါင်းတန်ဖိုး += အမြင့်ဘိုက်ရှေ့ကိန်းတို(ဒေတာ, နေရာ);
            နေရာ += 2;
        }
        if (နေရာ < အဆုံး) {
            စုစုပေါင်းတန်ဖိုး += (ဒေတာ[နေရာ] & 0xff) << 8;
        }
        while ((စုစုပေါင်းတန်ဖိုး >>> 16) != 0) {
            စုစုပေါင်းတန်ဖိုး = (စုစုပေါင်းတန်ဖိုး & 0xffff) + (စုစုပေါင်းတန်ဖိုး >>> 16);
        }
        return (int) (~စုစုပေါင်းတန်ဖိုး) & 0xffff;
    }

    public static boolean Ethernetဘောင်ဖြစ်သလား(byte[] ဒေတာ) {
        return ဒေတာ != null && ဒေတာ.length >= 14;
    }

    public static int Ethernetအပေါ်စည်းမျဉ်း(byte[] ဒေတာ) {
        if (!Ethernetဘောင်ဖြစ်သလား(ဒေတာ)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return အမြင့်ဘိုက်ရှေ့ကိန်းတို(ဒေတာ, 12);
    }

    public static boolean IPv4စည်းမျဉ်းဖြစ်သလား(byte[] ဒေတာ, int နေရာ) {
        if (ဒေတာ == null || နေရာ < 0 || ဒေတာ.length - နေရာ < 20) {
            return false;
        }
        int ထုတ်ဝေမှုတန်ဖိုး = (ဒေတာ[နေရာ] >>> 4) & 0xf;
        int ခေါင်းစီးအလျား = (ဒေတာ[နေရာ] & 0xf) * 4;
        return ထုတ်ဝေမှုတန်ဖိုး == 4 && ခေါင်းစီးအလျား >= 20 && ဒေတာ.length - နေရာ >= ခေါင်းစီးအလျား;
    }

    private static void အပိုင်းအခြားစစ်(byte[] ဒေတာ, int လုပ်ဆောင်, int အလျား) {
        if (ဒေတာ == null || လုပ်ဆောင် < 0 || အလျား < 0 || လုပ်ဆောင် > ဒေတာ.length - အလျား) {
            throw new IllegalArgumentException("ကွန်ရက်အလွှာစု ဒေတာ 범위를 벗어났습니다.");
        }
    }
}

