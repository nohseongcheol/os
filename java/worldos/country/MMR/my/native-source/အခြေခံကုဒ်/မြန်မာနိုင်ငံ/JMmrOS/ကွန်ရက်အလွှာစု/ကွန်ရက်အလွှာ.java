package မြန်မာနိုင်ငံ.JMmrOS.ကွန်ရက်အလွှာစု;

import java.util.HashMap;
import java.util.Map;

/** Ethernet၊ ARP၊ IPv4၊ ICMP၊ UDP နှင့် TCP လက်ခံဖြန့်ဝေမှုကို တစ်နေရာတည်းတွင် စီမံသည်။ */
public final class ကွန်ရက်အလွှာ {
    @FunctionalInterface
    public interface ဒေတာကိုင်တွယ်သူ {
        void လုပ်ငန်းစဉ်တန်ဖိုးအချက်(byte[] ဒေတာ, int လုပ်ဆောင်, int အလျား);
    }

    private final Map<Integer, ဒေတာကိုင်တွယ်သူ> Ethernetကိုင်တွယ်သူ = new HashMap<Integer, ဒေတာကိုင်တွယ်သူ>();
    private final Map<Integer, ဒေတာကိုင်တွယ်သူ> အင်တာနက်ဆက်သွယ်စည်းမျဉ်းကိုင်တွယ်သူ = new HashMap<Integer, ဒေတာကိုင်တွယ်သူ>();
    private final Map<Integer, ဒေတာကိုင်တွယ်သူ> သုံးစွဲသူဒေတာယူနစ်ကိုင်တွယ်သူ = new HashMap<Integer, ဒေတာကိုင်တွယ်သူ>();
    private final Map<Integer, ဒေတာကိုင်တွယ်သူ> ပို့ဆောင်ထိန်းကိုင်တွယ်သူ = new HashMap<Integer, ဒေတာကိုင်တွယ်သူ>();

    public void Ethernetစာရင်းသွင်း(int အမျိုးအစားတန်ဖိုး, ဒေတာကိုင်တွယ်သူ ကိုင်တွယ်သူ) {
        Ethernetကိုင်တွယ်သူ.put(Integer.valueOf(အမျိုးအစားတန်ဖိုး & 0xffff), ကိုင်တွယ်သူ);
    }

    public void အင်တာနက်စည်းမျဉ်းစာရင်းသွင်း(int သဘောတူစည်းမျဉ်းတန်ဖိုး, ဒေတာကိုင်တွယ်သူ ကိုင်တွယ်သူ) {
        အင်တာနက်ဆက်သွယ်စည်းမျဉ်းကိုင်တွယ်သူ.put(Integer.valueOf(သဘောတူစည်းမျဉ်းတန်ဖိုး & 0xff), ကိုင်တွယ်သူ);
    }

    public void UDPစာရင်းသွင်း(int စက်ပစ္စည်းဆက်သွယ်ပေါက်, ဒေတာကိုင်တွယ်သူ ကိုင်တွယ်သူ) {
        သုံးစွဲသူဒေတာယူနစ်ကိုင်တွယ်သူ.put(Integer.valueOf(စက်ပစ္စည်းဆက်သွယ်ပေါက် & 0xffff), ကိုင်တွယ်သူ);
    }

    public void TCPစာရင်းသွင်း(int စက်ပစ္စည်းဆက်သွယ်ပေါက်, ဒေတာကိုင်တွယ်သူ ကိုင်တွယ်သူ) {
        ပို့ဆောင်ထိန်းကိုင်တွယ်သူ.put(Integer.valueOf(စက်ပစ္စည်းဆက်သွယ်ပေါက် & 0xffff), ကိုင်တွယ်သူ);
    }

    public boolean Ethernetလက်ခံ(byte[] ဘောင်အညွှန်းကိန်း) {
        if (!ကွန်ရက်ကိရိယာ.Ethernetဘောင်ဖြစ်သလား(ဘောင်အညွှန်းကိန်း)) {
            return false;
        }
        int အမျိုးအစားတန်ဖိုး = ကွန်ရက်ကိရိယာ.Ethernetအပေါ်စည်းမျဉ်း(ဘောင်အညွှန်းကိန်း);
        ဒေတာကိုင်တွယ်သူ တိုက်ရိုက်ကိုင်တွယ်သူ = Ethernetကိုင်တွယ်သူ.get(Integer.valueOf(အမျိုးအစားတန်ဖိုး));
        if (တိုက်ရိုက်ကိုင်တွယ်သူ != null) {
            တိုက်ရိုက်ကိုင်တွယ်သူ.လုပ်ငန်းစဉ်တန်ဖိုးအချက်(ဘောင်အညွှန်းကိန်း, 14, ဘောင်အညွှန်းကိန်း.length - 14);
            return true;
        }
        return အမျိုးအစားတန်ဖိုး == 0x0800 && အင်တာနက်ဒေတာထုပ်လက်ခံရယူ(ဘောင်အညွှန်းကိန်း, 14);
    }

    private boolean အင်တာနက်ဒေတာထုပ်လက်ခံရယူ(byte[] ဒေတာ, int လုပ်ဆောင်) {
        if (!ကွန်ရက်ကိရိယာ.IPv4စည်းမျဉ်းဖြစ်သလား(ဒေတာ, လုပ်ဆောင်)) {
            return false;
        }
        int ခေါင်းစီးအလျား = (ဒေတာ[လုပ်ဆောင်] & 0x0f) * 4;
        int အကုန်စုစုပေါင်းအလျား = ကွန်ရက်ကိရိယာ.အမြင့်ဘိုက်ရှေ့ကိန်းတို(ဒေတာ, လုပ်ဆောင် + 2);
        if (အကုန်စုစုပေါင်းအလျား < ခေါင်းစီးအလျား || လုပ်ဆောင် + အကုန်စုစုပေါင်းအလျား > ဒေတာ.length) {
            return false;
        }
        int သဘောတူစည်းမျဉ်းတန်ဖိုး = ဒေတာ[လုပ်ဆောင် + 9] & 0xff;
        int အကြောင်းအရာအစ = လုပ်ဆောင် + ခေါင်းစီးအလျား;
        int အကြောင်းအရာအလျား = အကုန်စုစုပေါင်းအလျား - ခေါင်းစီးအလျား;
        ဒေတာကိုင်တွယ်သူ တိုက်ရိုက်ကိုင်တွယ်သူ = အင်တာနက်ဆက်သွယ်စည်းမျဉ်းကိုင်တွယ်သူ.get(Integer.valueOf(သဘောတူစည်းမျဉ်းတန်ဖိုး));
        if (တိုက်ရိုက်ကိုင်တွယ်သူ != null) {
            တိုက်ရိုက်ကိုင်တွယ်သူ.လုပ်ငန်းစဉ်တန်ဖိုးအချက်(ဒေတာ, အကြောင်းအရာအစ, အကြောင်းအရာအလျား);
            return true;
        }
        if (အကြောင်းအရာအလျား < 4) {
            return false;
        }
        int ဦးတည်ရာဆက်သွယ်ပေါက်ကိန်း = ကွန်ရက်ကိရိယာ.အမြင့်ဘိုက်ရှေ့ကိန်းတို(ဒေတာ, အကြောင်းအရာအစ + 2);
        Map<Integer, ဒေတာကိုင်တွယ်သူ> ဆက်သွယ်ပေါက်ဇယား = သဘောတူစည်းမျဉ်းတန်ဖိုး == 17 ? သုံးစွဲသူဒေတာယူနစ်ကိုင်တွယ်သူ : သဘောတူစည်းမျဉ်းတန်ဖိုး == 6 ? ပို့ဆောင်ထိန်းကိုင်တွယ်သူ : null;
        if (ဆက်သွယ်ပေါက်ဇယား == null) {
            return false;
        }
        ဒေတာကိုင်တွယ်သူ ဆက်သွယ်ပေါက်ကိုင်တွယ်သူ = ဆက်သွယ်ပေါက်ဇယား.get(Integer.valueOf(ဦးတည်ရာဆက်သွယ်ပေါက်ကိန်း));
        if (ဆက်သွယ်ပေါက်ကိုင်တွယ်သူ == null) {
            return false;
        }
        ဆက်သွယ်ပေါက်ကိုင်တွယ်သူ.လုပ်ငန်းစဉ်တန်ဖိုးအချက်(ဒေတာ, အကြောင်းအရာအစ, အကြောင်းအရာအလျား);
        return true;
    }
}

