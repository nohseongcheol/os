package မြန်မာနိုင်ငံ.JMmrOS.မှတ်ဉာဏ်နယ်ပယ်;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB စာမျက်နှာချိတ်ဆက်မှုနှင့် ရေးချိန်ကူးယူမှုကို ပံ့ပိုးသည်။ */
public final class စာမျက်နှာစီမံသူ {
    public static final int စာမျက်နှာအရွယ် = 4096;

    private static final class စာမျက်နှာတန်ဖိုး {
        private byte[] ဒေတာ = new byte[စာမျက်နှာအရွယ်];
        private int ကိုးကားချက်အရေအတွက် = 1;
        private boolean နိုင်ရေး = true;
        private boolean ရေးချိန်ကူး;
    }

    public static final class လိပ်စာနယ်ပယ် {
        private final Map<Integer, စာမျက်နှာတန်ဖိုး> စာမျက်နှာဇယား = new HashMap<Integer, စာမျက်နှာတန်ဖိုး>();
    }

    public လိပ်စာနယ်ပယ် အသစ်လိပ်စာနေရာလပ်() {
        return new လိပ်စာနယ်ပယ်();
    }

    public void စာမျက်နှာချိတ်(လိပ်စာနယ်ပယ် သတ်မှတ်လိပ်စာနယ်, int အတုလိပ်စာ, boolean နိုင်ရေး) {
        int နံပါတ် = စာမျက်နှာကိန်း(အတုလိပ်စာ);
        စာမျက်နှာတန်ဖိုး အသစ်စာမျက်နှာ = new စာမျက်နှာတန်ဖိုး();
        အသစ်စာမျက်နှာ.နိုင်ရေး = နိုင်ရေး;
        သတ်မှတ်လိပ်စာနယ်.စာမျက်နှာဇယား.put(Integer.valueOf(နံပါတ်), အသစ်စာမျက်နှာ);
    }

    public လိပ်စာနယ်ပယ် ရေးချိန်ကူးပွား(လိပ်စာနယ်ပယ် မူရင်း) {
        လိပ်စာနယ်ပယ် ပွားမိတ္တူ = new လိပ်စာနယ်ပယ်();
        for (Map.Entry<Integer, စာမျက်နှာတန်ဖိုး> အချက်တန်ဖိုး : မူရင်း.စာမျက်နှာဇယား.entrySet()) {
            စာမျက်နှာတန်ဖိုး မျှဝေသုံးစာမျက်နှာ = အချက်တန်ဖိုး.getValue();
            မျှဝေသုံးစာမျက်နှာ.ကိုးကားချက်အရေအတွက်++;
            if (မျှဝေသုံးစာမျက်နှာ.နိုင်ရေး) {
                မျှဝေသုံးစာမျက်နှာ.နိုင်ရေး = false;
                မျှဝေသုံးစာမျက်နှာ.ရေးချိန်ကူး = true;
            }
            ပွားမိတ္တူ.စာမျက်နှာဇယား.put(အချက်တန်ဖိုး.getKey(), မျှဝေသုံးစာမျက်နှာ);
        }
        return ပွားမိတ္တူ;
    }

    public byte ဘိုက်တန်ဖိုးဖတ်(လိပ်စာနယ်ပယ် သတ်မှတ်လိပ်စာနယ်, int အတုလိပ်စာ) {
        စာမျက်နှာတန်ဖိုး ဦးတည်ချက်တန်ဖိုး = စာမျက်နှာရှာ(သတ်မှတ်လိပ်စာနယ်, အတုလိပ်စာ);
        return ဦးတည်ချက်တန်ဖိုး.ဒေတာ[Math.floorMod(အတုလိပ်စာ, စာမျက်နှာအရွယ်)];
    }

    public void ဘိုက်တန်ဖိုးရေး(လိပ်စာနယ်ပယ် သတ်မှတ်လိပ်စာနယ်, int အတုလိပ်စာ, byte တန်ဖိုး) {
        int နံပါတ် = စာမျက်နှာကိန်း(အတုလိပ်စာ);
        စာမျက်နှာတန်ဖိုး ဦးတည်ချက်တန်ဖိုး = စာမျက်နှာရှာ(သတ်မှတ်လိပ်စာနယ်, အတုလိပ်စာ);
        if (!ဦးတည်ချက်တန်ဖိုး.နိုင်ရေး) {
            if (!ဦးတည်ချက်တန်ဖိုး.ရေးချိန်ကူး) {
                throw new IllegalStateException("ဖတ် 전용 쪽입니다.");
            }
            ဦးတည်ချက်တန်ဖိုး = သီးသန့်စာမျက်နှာဖန်တီး(သတ်မှတ်လိပ်စာနယ်, နံပါတ်, ဦးတည်ချက်တန်ဖိုး);
        }
        ဦးတည်ချက်တန်ဖိုး.ဒေတာ[Math.floorMod(အတုလိပ်စာ, စာမျက်နှာအရွယ်)] = တန်ဖိုး;
    }

    public void သီးသန့်အပိုင်းအခြားရေး(လိပ်စာနယ်ပယ် သတ်မှတ်လိပ်စာနယ်, int စတင်လိပ်စာ, int အရွယ်) {
        if (အရွယ် < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int အဆုံးလိပ်စာ = Math.addExact(စတင်လိပ်စာ, အရွယ်);
        for (int လိပ်စာ = စတင်လိပ်စာ; လိပ်စာ < အဆုံးလိပ်စာ; လိပ်စာ = (စာမျက်နှာကိန်း(လိပ်စာ) + 1) * စာမျက်နှာအရွယ်) {
            int နံပါတ် = စာမျက်နှာကိန်း(လိပ်စာ);
            စာမျက်နှာတန်ဖိုး ဦးတည်ချက်တန်ဖိုး = စာမျက်နှာရှာ(သတ်မှတ်လိပ်စာနယ်, လိပ်စာ);
            if (ဦးတည်ချက်တန်ဖိုး.ရေးချိန်ကူး) {
                သီးသန့်စာမျက်နှာဖန်တီး(သတ်မှတ်လိပ်စာနယ်, နံပါတ်, ဦးတည်ချက်တန်ဖိုး);
            } else {
                ဦးတည်ချက်တန်ဖိုး.နိုင်ရေး = true;
            }
        }
    }

    public void အပိုင်းအခြားရေး(လိပ်စာနယ်ပယ် သတ်မှတ်လိပ်စာနယ်, int စတင်လိပ်စာ, byte[] ဒေတာ) {
        for (int နံပါတ် = 0; နံပါတ် < ဒေတာ.length; နံပါတ်++) {
            ဘိုက်တန်ဖိုးရေး(သတ်မှတ်လိပ်စာနယ်, စတင်လိပ်စာ + နံပါတ်, ဒေတာ[နံပါတ်]);
        }
    }

    private စာမျက်နှာတန်ဖိုး သီးသန့်စာမျက်နှာဖန်တီး(လိပ်စာနယ်ပယ် သတ်မှတ်လိပ်စာနယ်, int နံပါတ်, စာမျက်နှာတန်ဖိုး မျှဝေသုံးစာမျက်နှာ) {
        စာမျက်နှာတန်ဖိုး သီးသန့်စာမျက်နှာ = new စာမျက်နှာတန်ဖိုး();
        သီးသန့်စာမျက်နှာ.ဒေတာ = Arrays.copyOf(မျှဝေသုံးစာမျက်နှာ.ဒေတာ, မျှဝေသုံးစာမျက်နှာ.ဒေတာ.length);
        သီးသန့်စာမျက်နှာ.နိုင်ရေး = true;
        သီးသန့်စာမျက်နှာ.ရေးချိန်ကူး = false;
        မျှဝေသုံးစာမျက်နှာ.ကိုးကားချက်အရေအတွက်--;
        သတ်မှတ်လိပ်စာနယ်.စာမျက်နှာဇယား.put(Integer.valueOf(နံပါတ်), သီးသန့်စာမျက်နှာ);
        return သီးသန့်စာမျက်နှာ;
    }

    private စာမျက်နှာတန်ဖိုး စာမျက်နှာရှာ(လိပ်စာနယ်ပယ် သတ်မှတ်လိပ်စာနယ်, int လိပ်စာ) {
        စာမျက်နှာတန်ဖိုး ဦးတည်ချက်တန်ဖိုး = သတ်မှတ်လိပ်စာနယ်.စာမျက်နှာဇယား.get(Integer.valueOf(စာမျက်နှာကိန်း(လိပ်စာ)));
        if (ဦးတည်ချက်တန်ဖိုး == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return ဦးတည်ချက်တန်ဖိုး;
    }

    private int စာမျက်နှာကိန်း(int လိပ်စာ) {
        if (လိပ်စာ < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return လိပ်စာ / စာမျက်နှာအရွယ်;
    }
}

