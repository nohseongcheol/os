package မြန်မာနိုင်ငံ.JMmrOS.ဝင်ဒေတာ;

public final class အဝင်ဖြစ်ရပ် {
    public enum အမျိုးအစားတန်ဖိုး {
        သော့အောက်,
        သော့အပေါ်,
        မောက်စ်ရွှေ့,
        မောက်စ်ခလုတ်နှိပ်,
        မောက်စ်ခလုတ်လွှတ်
    }

    private final အမျိုးအစားတန်ဖိုး ဖြစ်ရပ်အမျိုးအစား;
    private final int ပထမတန်ဖိုး;
    private final int ဒုတိယတန်ဖိုး;

    public အဝင်ဖြစ်ရပ်(အမျိုးအစားတန်ဖိုး ဖြစ်ရပ်အမျိုးအစား, int ပထမတန်ဖိုး, int ဒုတိယတန်ဖိုး) {
        this.ဖြစ်ရပ်အမျိုးအစား = ဖြစ်ရပ်အမျိုးအစား;
        this.ပထမတန်ဖိုး = ပထမတန်ဖိုး;
        this.ဒုတိယတန်ဖိုး = ဒုတိယတန်ဖိုး;
    }

    public အမျိုးအစားတန်ဖိုး ဖြစ်ရပ်အမျိုးအစား() {
        return ဖြစ်ရပ်အမျိုးအစား;
    }

    public int ပထမတန်ဖိုး() {
        return ပထမတန်ဖိုး;
    }

    public int ဒုတိယတန်ဖိုး() {
        return ဒုတိယတန်ဖိုး;
    }
}

