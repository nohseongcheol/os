package မြန်မာနိုင်ငံ.JMmrOS.အညွှန်း;

/** x86 အလုပ်ပြောင်းချိန် အထူးခွင့်စုပုံနေရာ ပံ့ပိုးသော TSS စီမံဖော်ပြချက်။ */
public final class အလုပ်အခြေအနေအပိုင်း {
    private int ထပ်ဆင့်အစုသုညအတုံး;
    private int ထပ်ဆင့်အစုသုညလိပ်စာ;
    private int အဝင်အထွက်ခွင့်ပြုချက်ဇယားနေရာ = 104;

    public void အထူးခွင့်စုပုံနေရာသတ်မှတ်(int အစိတ်အပိုင်း, int လိပ်စာ) {
        ထပ်ဆင့်အစုသုညအတုံး = အစိတ်အပိုင်း;
        ထပ်ဆင့်အစုသုညလိပ်စာ = လိပ်စာ;
    }

    public int ထပ်ဆင့်အစုသုညအတုံး() { return ထပ်ဆင့်အစုသုညအတုံး; }
    public int ထပ်ဆင့်အစုသုညလိပ်စာ() { return ထပ်ဆင့်အစုသုညလိပ်စာ; }
    public int အဝင်အထွက်ခွင့်ပြုချက်ဇယားနေရာ() { return အဝင်အထွက်ခွင့်ပြုချက်ဇယားနေရာ; }
}

