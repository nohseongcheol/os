package မြန်မာနိုင်ငံ.JMmrOS.အူတိုင်;

import မြန်မာနိုင်ငံ.JMmrOS.မှတ်ဉာဏ်နယ်ပယ်.မှတ်ဉာဏ်စီမံသူ;
import မြန်မာနိုင်ငံ.JMmrOS.မှတ်ဉာဏ်နယ်ပယ်.စာမျက်နှာစီမံသူ;
import မြန်မာနိုင်ငံ.JMmrOS.ဝင်ဒေတာ.အဝင်စီမံသူ;
import မြန်မာနိုင်ငံ.JMmrOS.အလုပ်.လုပ်ငန်းစဉ်;
import မြန်မာနိုင်ငံ.JMmrOS.အလုပ်.အလှည့်ခွဲဝေသူ;
import မြန်မာနိုင်ငံ.JMmrOS.စနစ်ခေါ်ဆိုမှု.စနစ်ခေါ်ဆိုမှု;
import မြန်မာနိုင်ငံ.JMmrOS.ဖိုင်စနစ်.ဖိုင်အညွှန်းဇယား;
import မြန်မာနိုင်ငံ.JMmrOS.ဖိုင်စနစ်.ဖိုင်စနစ်;

/** Java စီမံအူတိုင် စုစည်းမှုနှင့် စတင်မှုကို တာဝန်ယူသည်။ */
public final class အူတိုင် {
    private final စက်ပစ္စည်း ကိရိယာ;
    private final မှတ်ဉာဏ်စီမံသူ မှတ်ဉာဏ်နယ်ပယ် = new မှတ်ဉာဏ်စီမံသူ(32 * 1024 * 1024);
    private final စာမျက်နှာစီမံသူ စာမျက်နှာစီမံမှု = new စာမျက်နှာစီမံသူ();
    private final ဖိုင်စနစ် ဖိုင်စနစ် = new ဖိုင်စနစ်();
    private final အလှည့်ခွဲဝေသူ အလှည့်ခွဲဝေသူ = new အလှည့်ခွဲဝေသူ(စာမျက်နှာစီမံမှု);
    private final အဝင်စီမံသူ အဝင်စီမံမှု = new အဝင်စီမံသူ(256);
    private final လုပ်ငန်းစဉ် ပထမလုပ်ငန်းစဉ်;
    private final စနစ်ခေါ်ဆိုမှု စနစ်ခေါ်ဆိုမှု;

    public အူတိုင်(စက်ပစ္စည်း ကိရိယာ) {
        this.ကိရိယာ = ကိရိယာ;
        ပထမလုပ်ငန်းစဉ် = အလှည့်ခွဲဝေသူ.ပထမလုပ်ငန်းစဉ်(new ဖိုင်အညွှန်းဇယား(ဖိုင်စနစ်));
        စနစ်ခေါ်ဆိုမှု = new စနစ်ခေါ်ဆိုမှု(ဖိုင်စနစ်, စာမျက်နှာစီမံမှု, အလှည့်ခွဲဝေသူ, ကိရိယာ, အဝင်စီမံမှု);
    }

    public void လုပ်ဆောင်() {
        ကိရိယာ.အစဉ်ဆက်အထွက်("=== JMmrOS 관리 အူတိုင်တန်ဖိုး ===\n");
    }

    public void ခြေလှမ်းလုပ်ဆောင်() {
        ကိရိယာ.CPUရပ်();
    }

    public မှတ်ဉာဏ်စီမံသူ မှတ်ဉာဏ်နယ်ပယ်() {
        return မှတ်ဉာဏ်နယ်ပယ်;
    }

    public စာမျက်နှာစီမံသူ စာမျက်နှာစီမံမှု() {
        return စာမျက်နှာစီမံမှု;
    }

    public ဖိုင်စနစ် ဖိုင်စနစ်() {
        return ဖိုင်စနစ်;
    }

    public အလှည့်ခွဲဝေသူ အလှည့်ခွဲဝေသူ() {
        return အလှည့်ခွဲဝေသူ;
    }

    public အဝင်စီမံသူ အဝင်စီမံမှု() {
        return အဝင်စီမံမှု;
    }

    public လုပ်ငန်းစဉ် ပထမလုပ်ငန်းစဉ်() {
        return ပထမလုပ်ငန်းစဉ်;
    }

    public စနစ်ခေါ်ဆိုမှု စနစ်ခေါ်ဆိုမှု() {
        return စနစ်ခေါ်ဆိုမှု;
    }
}
