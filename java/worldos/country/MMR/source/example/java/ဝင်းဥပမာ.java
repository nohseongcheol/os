import မြန်မာ.ကိုယ်ပိုင်.ဝင်း;
import မြန်မာ.ကိုယ်ပိုင်.အညွှန်းစာ;
import မြန်မာ.ကိုယ်ပိုင်.စာသားအကွက်;
import မြန်မာ.ကိုယ်ပိုင်.ခလုတ်;
import မြန်မာ.ကိုယ်ပိုင်.ဖြစ်ရပ်တန်းစီရာ;
import မြန်မာ.ကိုယ်ပိုင်.အထွက်;
import မြန်မာ.ကိုယ်ပိုင်.လုပ်ဆောင်ရန်အလုပ်;
import မြန်မာ.ကိုယ်ပိုင်.လှုပ်ရှားမှုလက်ခံသူ;
import မြန်မာ.ကိုယ်ပိုင်.လှုပ်ရှားမှုအသိပေးချက်;

/** ကိုယ်ပိုင် အူတိုင်၏ Swing ဝင်း။ စာသားထည့်သွင်းခြင်း၊ ခလုတ်နှိပ်ခြင်းနှင့် လမ်းညွှန်စာ ပြန်လည်မွမ်းမံခြင်း။ */
public class ဝင်းဥပမာ implements လုပ်ဆောင်ရန်အလုပ်, လှုပ်ရှားမှုလက်ခံသူ {
    private ဝင်း နှုတ်ဆက်စကားဝင်း;
    private စာသားအကွက် အမည်အကွက်;
    private အညွှန်းစာ နှုတ်ဆက်စကား;
    private int နှုတ်ဆက်စကားအရေအတွက်;

    public void ဝင်းဖွင့်() {
        နှုတ်ဆက်စကားဝင်း = new ဝင်း("Burmese Swing", 460, 300);
        နှုတ်ဆက်စကားဝင်း.ထည့်သွင်း(new အညွှန်းစာ("မင်္ဂလာပါ", 20, 20, 420, 28));
        အမည်အကွက် = new စာသားအကွက်("Burmese", 20, 64, 420, 30);
        နှုတ်ဆက်စကား = new အညွှန်းစာ("မင်္ဂလာပါ", 20, 152, 420, 28);
        နှုတ်ဆက်စကားဝင်း.ထည့်သွင်း(အမည်အကွက်);
        နှုတ်ဆက်စကားဝင်း.ထည့်သွင်း(new ခလုတ်("နှုတ်ဆက်လုပ်ဆောင်", 20, 108, 180, 32, this));
        နှုတ်ဆက်စကားဝင်း.ထည့်သွင်း(နှုတ်ဆက်စကား);
        နှုတ်ဆက်စကားဝင်း.ထည့်သွင်း(new အညွှန်းစာ("F9 / Shift+Space | X", 20, 204, 420, 28));
        နှုတ်ဆက်စကားဝင်း.ပြသ();
        အထွက်.စာကြောင်းထုတ်("GUI ဥပမာ ပြင်ဆင်: ဝင်းဥပမာ");
    }

    public void နှုတ်ဆက်လုပ်ဆောင်() {
        နှုတ်ဆက်စကားအရေအတွက်++;
        နှုတ်ဆက်စကား.စာသားရေး("မင်္ဂလာပါ, " + အမည်အကွက်.စာသားဖတ်() + "님! (" + နှုတ်ဆက်စကားအရေအတွက် + ")");
        အထွက်.စာကြောင်းထုတ်("GUI နှုတ်ဆက်: " + နှုတ်ဆက်စကား.စာသားဖတ်());
    }

    public void အလုပ်လုပ်ဆောင်() { ဝင်းဖွင့်(); }
    public void လုပ်ဆောင်ချက်လက်ခံရယူ(လှုပ်ရှားမှုအသိပေးချက် အသိပေးချက်) {
        အထွက်.စာကြောင်းထုတ်("လှုပ်ရှားမှု အသိပေးချက်: " + အသိပေးချက်.အမိန့်စာသား());
        နှုတ်ဆက်လုပ်ဆောင်();
    }
    public static void လုပ်ဆောင်() {
        ဖြစ်ရပ်တန်းစီရာ.နောက်မှလုပ်ဆောင်(new ဝင်းဥပမာ());
    }
}
