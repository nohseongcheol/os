/** ဧည့်ကိရိယာများ၏ ဘုံအထွက်နှင့် ASCII ဖိုင်အမည် ကိုင်တွယ်မှု။ */
public final class Javaကိရိယာ {
    /** UTF-8 ဘိုက်အခင်းကို တူညီသော အခင်းအတွင်း UTF-16 ယူနစ်များသို့ ပြောင်းသည်။ မမှန်သော အဝင်ကို ငြင်းပယ်သည်။ */
    static int မူရင်းကုဒ်ကုဒ်ဖြည်(int[] ဒေတာ, int အလျား) {
        int ဖတ် = 0, ရေး = 0;
        if (အလျား >= 3 && ဒေတာ[0] == 239 && ဒေတာ[1] == 187 && ဒေတာ[2] == 191) ဖတ် = 3;
        while (ဖတ် < အလျား) {
            int တန်ဖိုး = ဒေတာ[ဖတ်++], ကိန်းတန်ဖိုး = 0, အနည်းဆုံးတန်ဖိုး = 0;
            if (တန်ဖိုး >= 194 && တန်ဖိုး <= 223) { ကိန်းတန်ဖိုး = 1; အနည်းဆုံးတန်ဖိုး = 128; တန်ဖိုး &= 31; }
            else if (တန်ဖိုး >= 224 && တန်ဖိုး <= 239) { ကိန်းတန်ဖိုး = 2; အနည်းဆုံးတန်ဖိုး = 2048; တန်ဖိုး &= 15; }
            else if (တန်ဖိုး >= 240 && တန်ဖိုး <= 244) { ကိန်းတန်ဖိုး = 3; အနည်းဆုံးတန်ဖိုး = 65536; တန်ဖိုး &= 7; }
            else if (တန်ဖိုး >= 128 || တန်ဖိုး < 0) return -1;
            if (ကိန်းတန်ဖိုး > အလျား - ဖတ်) return -1;
            for (int i = 0; i < ကိန်းတန်ဖိုး; i++) {
                int နောက်တစ်ခုအချက်အလက်တစ်ခု = ဒေတာ[ဖတ်++]; if ((နောက်တစ်ခုအချက်အလက်တစ်ခု & 192) != 128) return -1;
                တန်ဖိုး = (တန်ဖိုး << 6) | (နောက်တစ်ခုအချက်အလက်တစ်ခု & 63);
            }
            if (တန်ဖိုး < အနည်းဆုံးတန်ဖိုး || တန်ဖိုး > 0x10ffff || (တန်ဖိုး >= 0xd800 && တန်ဖိုး <= 0xdfff)) return -1;
            if (တန်ဖိုး >= 65536) { တန်ဖိုး -= 65536; ဒေတာ[ရေး++] = 0xd800 | (တန်ဖိုး >> 10); ဒေတာ[ရေး++] = 0xdc00 | (တန်ဖိုး & 1023); }
            else ဒေတာ[ရေး++] = တန်ဖိုး;
        }
        return ရေး;
    }
    static void ကိန်းထုတ်(int တန်ဖိုး) {
        if (တန်ဖိုး < 0) သုံးစွဲသူ.အက္ခရာတန်ဖိုးရေး('-'); else တန်ဖိုး = -တန်ဖိုး;
        int နေရာအညွှန်းကိန်း = 1000000000;
        boolean လုပ်ဆောင် = false;
        while (နေရာအညွှန်းကိန်း != 0) {
            int ကိန်းတန်ဖိုး = -(တန်ဖိုး / နေရာအညွှန်းကိန်း);
            if (ကိန်းတန်ဖိုး != 0 || လုပ်ဆောင် || နေရာအညွှန်းကိန်း == 1) { သုံးစွဲသူ.အက္ခရာတန်ဖိုးရေး('0' + ကိန်းတန်ဖိုး); လုပ်ဆောင် = true; }
            တန်ဖိုး %= နေရာအညွှန်းကိန်း; နေရာအညွှန်းကိန်း /= 10;
        }
    }
    static int အမည်(int[] ဦးတည်ရာတန်ဖိုး, String မူရင်း) {
        if (မူရင်း.length() >= ဦးတည်ရာတန်ဖိုး.length) return -1;
        for (int ကိန်းတန်ဖိုး = 0; ကိန်းတန်ဖိုး < ဦးတည်ရာတန်ဖိုး.length; ကိန်းတန်ဖိုး++) ဦးတည်ရာတန်ဖိုး[ကိန်းတန်ဖိုး] = ကိန်းတန်ဖိုး < မူရင်း.length() ? မူရင်း.charAt(ကိန်းတန်ဖိုး) : 0;
        return မူရင်း.length();
    }
    static boolean ညီစာသား(String ပထမတွက်ချက်ခံ, String ဒုတိယတွက်ချက်ခံ) {
        if (ပထမတွက်ချက်ခံ.length() != ဒုတိယတွက်ချက်ခံ.length()) return false;
        for (int ကိန်းတန်ဖိုး = 0; ကိန်းတန်ဖိုး < ပထမတွက်ချက်ခံ.length(); ကိန်းတန်ဖိုး++) if (ပထမတွက်ချက်ခံ.charAt(ကိန်းတန်ဖိုး) != ဒုတိယတွက်ချက်ခံ.charAt(ကိန်းတန်ဖိုး)) return false;
        return true;
    }
}
