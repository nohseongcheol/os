        if hasattr(အကောင်အထည်ဖော်မှု, လက်ရှိအချက်အလက်တစ်ခု): globals()[ယခင်အချက်အလက်တစ်ခု] = getattr(အကောင်အထည်ဖော်မှု, လက်ရှိအချက်အလက်တစ်ခု)
