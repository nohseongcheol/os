if __name__ == '__main__':
    import runpy as ပရိုဂရမ်စက်နှိုးကိရိယာ
    ပရိုဂရမ်စက်နှိုးကိရိယာ.run_module('စီးကြောင်းစမ်းသပ်', run_name='__main__', alter_sys=True)
