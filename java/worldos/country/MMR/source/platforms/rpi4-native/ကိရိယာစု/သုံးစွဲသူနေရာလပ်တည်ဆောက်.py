"""독립된 ကိုယ်ပိုင် ABI ELF64와 로더 တန်ဖိုးငြင်းပယ် စမ်းသပ်မှု 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from Pythonတည်ဆောက် import Pythonဖန်တီး
from Javaစာကြည့်တိုက်တည်ဆောက် import Javaစာကြည့်တိုက်ဖန်တီး
from Cဘာသာပြန်စက်တည်ဆောက် import Cဘာသာပြန်စက်ဖန်တီး


def သုံးစွဲသူနေရာလပ်ဖန်တီး(အမြစ်လမ်းကြောင်း, 저장소경로, Cဘာသာပြန်စက်, 시플플번역기, ချိတ်ဆက်စက်ကိရိယာတစ်ခု, မော်ကွန်းကိရိယာတစ်ခု, ပြင်ဆင်မှုဘစ်များ, စက်မောင်း):
    ပြင်ဆင်မှုဘစ်များ = [သတ်မှတ်ချက်တန်ဖိုး for သတ်မှတ်ချက်တန်ဖိုး in ပြင်ဆင်မှုဘစ်များ if သတ်မှတ်ချက်တန်ဖိုး != '-mgeneral-regs-only']
    လမ်းကြောင်းတည်ဆောက် = အမြစ်လမ်းကြောင်း / 'build'
    출력결과 = လမ်းကြောင်းတည်ဆောက် / 'user'
    출력결과.mkdir(exist_ok=True)
    မူရင်းဒေတာ = အမြစ်လမ်းကြောင်း / 'သုံးစွဲသူ'
    POSIX = 저장소경로 / 'posix-kor/arm64-native'
    ပါဝင်စေလမ်းကြောင်း = ['-I', မူရင်းဒေတာ, '-I', POSIX / 'ခေါင်းစီးဖိုင်', '-I', 출력결과]
    for ဘာသာပြန်စက်ကိရိယာတစ်ခု, 추가영역, လမ်း, အမည် in [
            (Cဘာသာပြန်စက်, [], မူရင်းဒေတာ / 'လုပ်ဆောင်.S', 'start.o'),
            (Cဘာသာပြန်စက်, ['-std=c11'], မူရင်းဒေတာ / 'စက်မောင်း.c', 'runtime.o'),
            (Cဘာသာပြန်စက်, ['-std=c11'], POSIX / 'သုံးစွဲသူတံတား.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], မူရင်းဒေတာ / 'ဖိုင်ဥပမာ.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], မူရင်းဒေတာ / 'ဆက်သွယ်မှုဥပမာ.cpp', 'network.o'),
            (Cဘာသာပြန်စက်, ['-std=c11'], မူရင်းဒေတာ / 'ကာကွယ်မှုစမ်းသပ်.c', 'fault.o'),
            (Cဘာသာပြန်စက်, ['-std=c11'], မူရင်းဒေတာ / 'တည်းဖြတ်စက်.c', 'vi.o')]:
        စက်မောင်း([ဘာသာပြန်စက်ကိရိယာတစ်ခု] + ပြင်ဆင်မှုဘစ်များ + 추가영역 + ပါဝင်စေလမ်းကြောင်း + ['-Wall', '-Wextra', '-Werror', '-c', လမ်း, '-o', 출력결과 / အမည်])
    စက်မောင်း([မော်ကွန်းကိရိယာတစ်ခု, 'rcs', လမ်းကြောင်းတည်ဆောက် / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for အမည် in ('demo', 'fault', 'network', 'vi'):
        စက်မောင်း([ချိတ်ဆက်စက်ကိရိယာတစ်ခု, '-T', မူရင်းဒေတာ / 'နေရာချထားပုံ.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (အမည် + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (အမည် + '.o'), လမ်းကြောင်းတည်ဆောက် / 'libposix-kor-user.a'])
    Javaစာကြည့်တိုက်ဖန်တီး(အမြစ်လမ်းကြောင်း, စက်မောင်း)
    # 기존 ကိုယ်ပိုင် Java ဘာသာပြန်စက်/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(လမ်းကြောင်းတည်ဆောက်)) as လုပ်ဆောင်လမ်း:
        အတန်းလမ်းကြောင်း = Path(လုပ်ဆောင်လမ်း)
        စက်မောင်း(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', အတန်းလမ်းကြောင်း, '-sourcepath', အတန်းလမ်းကြောင်း, '-d', အတန်းလမ်းကြောင်း] +
            [ဒေတာနေရာ for ဒေတာနေရာ in sorted((저장소경로 / 'os/သုံးစွဲသူ/Java').glob('*.java')) if ဒေတာနေရာ.name != 'Javaစက်တု.java'] + sorted((မူရင်းဒေတာ / 'Java').glob('*.java')))
        စက်မောင်း(['sh', 저장소경로 / 'compiler/미리번역.sh', '--entry', 'ကိရိယာတစ်ခုအချက်.လုပ်ဆောင်',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(အတန်းလမ်းကြောင်း.glob('*.class')))
    압축해제경로 = အမြစ်လမ်းကြောင်း / 'vendor/uzlib'
    for လမ်း, အမည် in [(출력결과 / 'java-tools.c', 'java-tools.o'), (မူရင်းဒေတာ / 'Javaတံတား.c', 'java-link.o'),
                       (မူရင်းဒေတာ / 'အထုပ်.c', 'jar.o')] + [(압축해제경로 / (အမည် + '.c'), အမည် + '.o') for အမည် in ('tinflate', 'crc32', 'adler32')]:
        စက်မောင်း([Cဘာသာပြန်စက်] + ပြင်ဆင်မှုဘစ်များ + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + ပါဝင်စေလမ်းကြောင်း + ['-c', လမ်း, '-o', 출력결과 / အမည်])
    စက်မောင်း([ချိတ်ဆက်စက်ကိရိယာတစ်ခု, '-T', မူရင်းဒေတာ / 'နေရာချထားပုံ.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / အမည် for အမည် in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    Pythonဖန်တီး(အမြစ်လမ်းကြောင်း, Cဘာသာပြန်စက်, ချိတ်ဆက်စက်ကိရိယာတစ်ခု)
    Cဘာသာပြန်စက်ဖန်တီး(အမြစ်လမ်းကြောင်း, 저장소경로, Cဘာသာပြန်စက်, ချိတ်ဆက်စက်ကိရိယာတစ်ခု, ပြင်ဆင်မှုဘစ်များ, စက်မောင်း)
    မှန်ကန် = (출력결과 / 'demo.elf').read_bytes()
    ပရိုဂရမ်ခေါင်းစီးအရွေ့ = struct.unpack_from('<Q', မှန်ကန်, 32)[0]
    ခေါင်းစီးစာရင်း = [ပရိုဂရမ်ခေါင်းစီးအရွေ့ + အရေအတွက် * 56 for အရေအတွက် in range(struct.unpack_from('<H', မှန်ကန်, 56)[0])]
    적재구획 = [ဒေတာနေရာ for ဒေတာနေရာ in ခေါင်းစီးစာရင်း if struct.unpack_from('<I', မှန်ကန်, ဒေတာနေရာ)[0] == 1]
    စာသား, ဒေတာ = 적재구획[:2]
    အမိန့်လိပ်စာ = struct.unpack_from('<Q', မှန်ကန်, စာသား + 16)[0]
    ဒေတာလိပ်စာ = struct.unpack_from('<Q', မှန်ကန်, ဒေတာ + 16)[0]
    호출규약 = မှန်ကန်.index(b'JKOROS\0')
    ကိစ္စစမ်းသပ် = [('empty', b''), ('short', မှန်ကန်[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', အမိန့်လိပ်စာ + 1), ('data-entry', 24, 'Q', ဒေတာလိပ်စာ),
               ('outside-file', စာသား + 32, 'Q', len(မှန်ကန်) + 1), ('short-memory', စာသား + 40, 'Q', 1),
               ('kernel-address', စာသား + 16, 'Q', 0x80000), ('memory-overflow', စာသား + 40, 'Q', 2**64 - 1),
               ('writable-code', စာသား + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', စာသား, 'I', 2),
               ('unaligned-load', စာသား + 16, 'Q', အမိန့်လိပ်စာ + 8),
               ('overlap', ဒေတာ + 16, 'Q', အမိန့်လိပ်စာ)]
    for အမည်, အရွေ့တန်ဖိုး, ဒေတာပုံစံ, တန်ဖိုး in 수정사항:
        바뀐자료 = bytearray(မှန်ကန်); struct.pack_into('<' + ဒေတာပုံစံ, 바뀐자료, အရွေ့တန်ဖိုး, တန်ဖိုး)
        ကိစ္စစမ်းသပ်.append((အမည်, bytes(바뀐자료)))
    탑재덩이들 = [(အမည်.replace('-', '_'), 출력결과 / (အမည် + '.elf')) for အမည် in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for ရှာကြည့်အညွှန်းကိန်း, (အမည်, 내용자료) in enumerate(ကိစ္စစမ်းသပ်):
        လမ်း = 출력결과 / ('invalid-{}.elf'.format(အမည်)); လမ်း.write_bytes(내용자료)
        탑재덩이들.append(('invalid_{}'.format(ရှာကြည့်အညွှန်းကိန်း), လမ်း))
    အက်ဆမ်ဘလီဒေတာ, ခေါင်းစီးတန်ဖိုး = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for အမည်, လမ်း in 탑재덩이들:
        သင်္ကေတတန်ဖိုး = 'user_blob_' + အမည်
        크기목록[အမည်] = လမ်း.stat().st_size
        # 생성한 တစ်ဖက်တန်ဖိုး 경로만 넣어 프로젝트 경로의 공백/ကိုးကားအမှတ် 영향을 피한다.
        အက်ဆမ်ဘလီဒေတာ += ['.balign 16', '.global ' + သင်္ကေတတန်ဖိုး, သင်္ကေတတန်ဖိုး + ':', '.incbin "{}"'.format(လမ်း.relative_to(အမြစ်လမ်းကြောင်း))]
        ခေါင်းစီးတန်ဖိုး.append('extern const unsigned char {}[];'.format(သင်္ကေတတန်ဖိုး))
    အက်ဆမ်ဘလီဒေတာ.append('.section .note.GNU-stack,"",%progbits')
    ခေါင်းစီးတန်ဖိုး += ['static const လုပ်ဆောင်မည့်အချက် 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    ခေါင်းစီးတန်ဖိုး += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    ခေါင်းစီးတန်ဖိုး += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    ခေါင်းစီးတန်ဖိုး += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], နည်းလမ်းနည်းစနစ်) for နည်းလမ်းနည်းစနစ် in (0, 1)]
    ခေါင်းစီးတန်ဖိုး += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    ခေါင်းစီးတန်ဖိုး += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    ခေါင်းစီးတန်ဖိုး += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    ခေါင်းစီးတန်ဖိုး += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    ခေါင်းစီးတန်ဖိုး += ['};', 'static const လုပ်ဆောင်မည့်အချက် 잘못된실행항목들[] = {']
    ခေါင်းစီးတန်ဖိုး += ['{user_blob_invalid_%d, %d, 0},' % (အစဉ်အမှတ်, len(내용자료)) for အစဉ်အမှတ်, (_, 내용자료) in enumerate(ကိစ္စစမ်းသပ်)]
    ခေါင်းစီးတန်ဖိုး += ['};']
    (လမ်းကြောင်းတည်ဆောက် / 'programs.S').write_text('\n'.join(အက်ဆမ်ဘလီဒေတာ) + '\n')
    (လမ်းကြောင်းတည်ဆောက် / 'programs.h').write_text('\n'.join(ခေါင်းစီးတန်ဖိုး) + '\n')
    (출력결과 / 'invalid-cases.txt').write_text('\n'.join(အမည် for အမည်, _ in ကိစ္စစမ်းသပ်) + '\n')
    စက်မောင်း([Cဘာသာပြန်စက်] + ပြင်ဆင်မှုဘစ်များ + ['-c', လမ်းကြောင်းတည်ဆောက် / 'programs.S', '-o', လမ်းကြောင်းတည်ဆောက် / 'programs.o'])
