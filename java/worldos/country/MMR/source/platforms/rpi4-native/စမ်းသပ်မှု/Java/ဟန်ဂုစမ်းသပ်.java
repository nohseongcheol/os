import မြန်မာ.ကိုယ်ပိုင်.အက္ခရာ;
import မြန်မာ.ကိုယ်ပိုင်.ဖိုင်;
import မြန်မာ.ကိုယ်ပိုင်.အချက်စာရင်း;
import မြန်မာ.ကိုယ်ပိုင်.အဘိဓာန်;
import မြန်မာ.ကိုယ်ပိုင်.အထွက်;
public class ဟန်ဂုစမ်းသပ် {
    public static void main(String[] a) throws Exception {
        String နှုတ်ဆက် = "안녕하세요 · 日本語 · العربية · 😀";
        အထွက်.စာကြောင်းထုတ်(အက္ခရာ.လျှို့ဝှက်ကုဒ်ဖြည်(အက္ခရာ.ကုဒ်သွင်း(နှုတ်ဆက်))); အထွက်.ကိန်းထုတ်(အက္ခရာ.ကုဒ်အမှတ်တစ်ခုအရေအတွက်("한글😀"));
        ဖိုင်.ရေး("한글자료.txt", နှုတ်ဆက်); အထွက်.စာကြောင်းထုတ်(ဖိုင်.ဖတ်("한글자료.txt"));
        အချက်စာရင်း အမည်များစာရင်း = new အချက်စာရင်း(); အမည်များစာရင်း.တန်ဖိုးများထည့်("가람"); အမည်များစာရင်း.တန်ဖိုးများထည့်("누리"); အထွက်.စာကြောင်းထုတ်(အမည်များစာရင်း.ဖတ်(1));
        အဘိဓာန် အဓိပ္ပာယ် = new အဘိဓာန်(); အဓိပ္ပာယ်.တန်ဖိုးထား("가람", "강"); System.gc(); အထွက်.စာကြောင်းထုတ်(အဓိပ္ပာယ်.အချက်ရှာ("가람"));
        try { အက္ခရာ.လျှို့ဝှက်ကုဒ်ဖြည်(new byte[] {(byte)0xc0, (byte)0xaf}); } catch (IllegalArgumentException e) { အထွက်.စာကြောင်းထုတ်("UTF-8 အမှား တန်ဖိုးငြင်းပယ်"); }
        အထွက်.စာကြောင်းထုတ်("မြန်မာ စာကြည့်တိုက် ဖြစ်သောအပြည့်အစုံ");
    }
}
