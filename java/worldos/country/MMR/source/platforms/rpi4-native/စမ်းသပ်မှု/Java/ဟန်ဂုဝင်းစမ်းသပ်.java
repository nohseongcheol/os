import မြန်မာ.ကိုယ်ပိုင်.ဝင်း;
import မြန်မာ.ကိုယ်ပိုင်.မြင်ကွင်းအစိတ်အပိုင်း;
import မြန်မာ.ကိုယ်ပိုင်.*;

public class ဟန်ဂုဝင်းစမ်းသပ် implements လုပ်ဆောင်ရန်အလုပ်, လှုပ်ရှားမှုလက်ခံသူ {
    ဝင်း မျက်နှာပြင်;
    အညွှန်းစာ လမ်းညွှန်;
    စာသားအကွက် ဝင်ဒေတာ;
    public void အလုပ်လုပ်ဆောင်() {
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(ဖြစ်ရပ်တန်းစီရာ.ဖြစ်ရပ်ဖြန့်ဝေနေသလား(), "မြန်မာ မျက်နှာပြင် အလုပ် 큐");
        မျက်နှာပြင် = new ဝင်း("မြန်မာ စာကြည့်တိုက် ဝင်း", 400, 280);
        လမ်းညွှန် = မြင်ကွင်းအစိတ်အပိုင်း.တံဆိပ်တန်ဖိုး("한글로 Java 코딩", 20, 20, 340, 30);
        ဝင်ဒေတာ = မြင်ကွင်းအစိတ်အပိုင်း.စာသားအကွက်("အမည်", 20, 65, 340, 30);
        မျက်နှာပြင်.ထည့်သွင်း(လမ်းညွှန်);
        မျက်နှာပြင်.ထည့်သွင်း(ဝင်ဒေတာ);
        မျက်နှာပြင်.ထည့်သွင်း(မြင်ကွင်းအစိတ်အပိုင်း.ခလုတ်("နှုတ်ဆက်လုပ်ဆောင်", 20, 110, 180, 32, this));
        မျက်နှာပြင်.ပြသ();
        အထွက်.စာကြောင်းထုတ်("KOREAN SWING READY");
    }
    public void လုပ်ဆောင်ချက်လက်ခံရယူ(လှုပ်ရှားမှုအသိပေးချက် ဖြစ်ရပ်) {
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(ဖြစ်ရပ်တန်းစီရာ.ဖြစ်ရပ်ဖြန့်ဝေနေသလား(), "မြန်မာ လှုပ်ရှားမှု 되부름");
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(ဖြစ်ရပ်.နံပါတ်() == 1001 && ဖြစ်ရပ်.ဖြစ်ရပ်မူရင်းကုဒ်() instanceof ခလုတ်, "မြန်မာ ဖြစ်ရပ် 객체와 출처");
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(!((Object)ဖြစ်ရပ်.ဖြစ်ရပ်မူရင်းကုဒ်() instanceof javax.swing.JButton), "표준 단추와 독립된 ပုံစံတန်ဖိုး");
        စစ်ဆေးချက်.မှန်ကြောင်းစစ်(!((Object)ဖြစ်ရပ် instanceof java.awt.event.ActionEvent), "표준 사건과 독립된 ပုံစံတန်ဖိုး");
        လမ်းညွှန်.စာသားရေး("안녕하세요 " + ဝင်ဒေတာ.စာသားဖတ်());
        အထွက်.စာကြောင်းထုတ်("KOREAN SWING CLICK " + ဝင်ဒေတာ.စာသားဖတ်());
    }
    public static void main(String[] အချက်များ) {
        ဖြစ်ရပ်တန်းစီရာ.နောက်မှလုပ်ဆောင်(new ဟန်ဂုဝင်းစမ်းသပ်());
    }
}
