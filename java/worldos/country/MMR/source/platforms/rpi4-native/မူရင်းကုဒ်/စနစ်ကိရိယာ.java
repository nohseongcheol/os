            အဆုံးသုံးစက်.အက္ခရာ(' ');အဆုံးသုံးစက်.ကိန်းတန်ဖိုး(ဆားကစ်ပြား.ကွန်ရက်အခြေအနေ(15,နံပါတ်));အဆုံးသုံးစက်.အက္ခရာ(10);
