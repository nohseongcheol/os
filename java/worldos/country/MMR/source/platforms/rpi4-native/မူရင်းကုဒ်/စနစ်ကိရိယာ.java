            လိပ်စာရေး(ဆားကစ်ပြား.ကွန်ရက်အခြေအနေ(12,နံပါတ်));အဆုံးသုံးစက်.အက္ခရာ(':');အဆုံးသုံးစက်.ကိန်းတန်ဖိုး(ဆားကစ်ပြား.ကွန်ရက်အခြေအနေ(13,နံပါတ်));အဆုံးသုံးစက်.အက္ခရာ(' ');
