    static boolean စားတန်ဖိုးများ(int အရွယ်) {
        int နေရာ = 0, အဆုံး = 0; သင်္ကေတစကားလုံးအရေအတွက် = 0;
        while (နေရာ < အရွယ်) {
            while (နေရာ < အရွယ် && (စာကြောင်း[နေရာ] == 32 || စာကြောင်း[နေရာ] == 9)) နေရာ++;
            if (နေရာ == အရွယ်) break;
            if (သင်္ကေတစကားလုံးအရေအတွက် == 16) { အဆုံးသုံးစက်.ရေး("အမိန့် တန်ဖိုးသဒ္ဒါခွဲခြမ်း: 인수가 너무 많습니다\n"); return false; }
            စမှတ်[သင်္ကေတစကားလုံးအရေအတွက်] = အဆုံး; int ကိုးကားတန်ဖိုး = 0;
            while (နေရာ < အရွယ်) {
                int တန်ဖိုး = စာကြောင်း[နေရာ++];
                if (ကိုးကားတန်ဖိုး == 0 && (တန်ဖိုး == 32 || တန်ဖိုး == 9)) break;
                if (တန်ဖိုး == ကိုးကားတန်ဖိုး) { ကိုးကားတန်ဖိုး = 0; continue; }
                if (ကိုးကားတန်ဖိုး == 0 && (တန်ဖိုး == 39 || တန်ဖိုး == 34)) { ကိုးကားတန်ဖိုး = တန်ဖိုး; continue; }
                သင်္ကေတစကားလုံးတန်ဖိုး[အဆုံး++] = တန်ဖိုး;
            }
            if (ကိုးကားတန်ဖိုး != 0) { အဆုံးသုံးစက်.ရေး("အမိန့် တန်ဖိုးသဒ္ဒါခွဲခြမ်း: 따옴표가 닫히지 않았습니다\n"); return false; }
            အလျား[သင်္ကေတစကားလုံးအရေအတွက်] = အဆုံး - စမှတ်[သင်္ကေတစကားလုံးအရေအတွက်]; သင်္ကေတစကားလုံးအရေအတွက်++;
        }
        return true;
    }
    static boolean ညီစာသား(int နံပါတ်, String စကားလုံးစာသား) {
        if (နံပါတ် >= သင်္ကေတစကားလုံးအရေအတွက်) return false;
        int နေရာအညွှန်းကိန်း=0;
        for (int အစဉ်အမှတ်=0; အစဉ်အမှတ်<စကားလုံးစာသား.length(); အစဉ်အမှတ်++) {
            int အက္ခရာကုဒ်=စကားလုံးစာသား.charAt(အစဉ်အမှတ်);
            if (အက္ခရာကုဒ်>=0xd800 && အက္ခရာကုဒ်<=0xdbff && အစဉ်အမှတ်+1<စကားလုံးစာသား.length()) အက္ခရာကုဒ်=0x10000+((အက္ခရာကုဒ်-0xd800)<<10)+စကားလုံးစာသား.charAt(++အစဉ်အမှတ်)-0xdc00;
            int ဘိုက်အရေအတွက်=အက္ခရာကုဒ်<128?1:အက္ခရာကုဒ်<2048?2:အက္ခရာကုဒ်<65536?3:4;
            for (int အစဉ်လိုက်တန်ဖိုး=ဘိုက်အရေအတွက်-1; အစဉ်လိုက်တန်ဖိုး>=0; အစဉ်လိုက်တန်ဖိုး--) {
                int တန်ဖိုး=ဘိုက်အရေအတွက်==1?အက္ခရာကုဒ်:အစဉ်လိုက်တန်ဖိုး==ဘိုက်အရေအတွက်-1?(ဘိုက်အရေအတွက်==2?0xc0:ဘိုက်အရေအတွက်==3?0xe0:0xf0)|(အက္ခရာကုဒ်>>(6*အစဉ်လိုက်တန်ဖိုး)):0x80|((အက္ခရာကုဒ်>>(6*အစဉ်လိုက်တန်ဖိုး))&63);
                if (နေရာအညွှန်းကိန်း>=အလျား[နံပါတ်] || သင်္ကေတစကားလုံးတန်ဖိုး[စမှတ်[နံပါတ်]+နေရာအညွှန်းကိန်း++]!=တန်ဖိုး) return false;
            }
        }
        return နေရာအညွှန်းကိန်း==အလျား[နံပါတ်];
    }
    static int လမ်း(int နံပါတ်) {
        if (နံပါတ် >= သင်္ကေတစကားလုံးအရေအတွက်) return -22;
        int ရလဒ် = မှတ်ဉာဏ်ဖိုင်.လမ်းကြောင်းစတင်(အလျား[နံပါတ်]); if (ရလဒ် < 0) return ရလဒ်;
        for (int ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း = 0; ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း < အလျား[နံပါတ်]; ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း++) {
            ရလဒ် = မှတ်ဉာဏ်ဖိုင်.လမ်းကြောင်းဘိုက်(ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း, သင်္ကေတစကားလုံးတန်ဖိုး[စမှတ်[နံပါတ်] + ထပ်ခါလည်ပတ်မှုအညွှန်းကိန်း]); if (ရလဒ် < 0) return ရလဒ်;
        }
        return 0;
    }
