    static int ဆယ့်ခြောက်လီတန်ဖိုး(int တန်ဖိုး) {
        if (တန်ဖိုး >= '0' && တန်ဖိုး <= '9') return တန်ဖိုး - '0';
        if (တန်ဖိုး >= 'a' && တန်ဖိုး <= 'f') return တန်ဖိုး - 'a' + 10;
        if (တန်ဖိုး >= 'A' && တန်ဖိုး <= 'F') return တန်ဖိုး - 'A' + 10;
        return -1;
    }
