        "0004041F040400" + "0000001F000000" + "00000000000C0C" + "000C0C000C0C00";
    static int ဂဏန်းတန်ဖိုး(int အက္ခရာတန်ဖိုး) { return အက္ခရာတန်ဖိုး <= '9' ? အက္ခရာတန်ဖိုး - '0' : အက္ခရာတန်ဖိုး - 'A' + 10; }
    static void စာသား(int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ, String အကြောင်းအရာတန်ဖိုး, int အရောင်တန်ဖိုး) {
        for (int အက္ခရာတန်ဖိုး = 0; အက္ခရာတန်ဖိုး < အကြောင်းအရာတန်ဖိုး.length(); အက္ခရာတန်ဖိုး++) {
            int တွေ့တန်ဖိုး = -1;
            for (int အဆိုပြုချက် = 0; အဆိုပြုချက် < အက္ခရာတန်ဖိုးများ.length(); အဆိုပြုချက်++) if (အက္ခရာတန်ဖိုးများ.charAt(အဆိုပြုချက်) == အကြောင်းအရာတန်ဖိုး.charAt(အက္ခရာတန်ဖိုး)) တွေ့တန်ဖိုး = အဆိုပြုချက်;
            if (တွေ့တန်ဖိုး < 0) continue;
            for (int အတန်းလိုက်တန်ဖိုး = 0; အတန်းလိုက်တန်ဖိုး < 7; အတန်းလိုက်တန်ဖိုး++) {
                int နေရာ = တွေ့တန်ဖိုး * 14 + အတန်းလိုက်တန်ဖိုး * 2;
                int ဘစ်တန်ဖိုး = ဂဏန်းတန်ဖိုး(ပုံသဏ္ဌာန်များ.charAt(နေရာ)) * 16 + ဂဏန်းတန်ဖိုး(ပုံသဏ္ဌာန်များ.charAt(နေရာ + 1));
                for (int ကော်လံတန်ဖိုး = 0; ကော်လံတန်ဖိုး < 5; ကော်လံတန်ဖိုး++) if ((ဘစ်တန်ဖိုး & (16 >> ကော်လံတန်ဖိုး)) != 0)
                    အူတိုင်.စတုဂံ(အလျားတည်နေရာ + အက္ခရာတန်ဖိုး * 12 + ကော်လံတန်ဖိုး * 2, ဒေါင်လိုက်တည်နေရာ + အတန်းလိုက်တန်ဖိုး * 2, 2, 2, အရောင်တန်ဖိုး);
            }
        }
    }
    static void မျက်နှာပြင်ဆေးခြယ်(int ရွေးချယ်မှုတန်ဖိုး, String အခြေအနေတန်ဖိုး) {
        အူတိုင်.စတုဂံ(0, 0, ဆားကစ်ပြား.မျက်နှာပြင်အနံ(), ဆားကစ်ပြား.မျက်နှာပြင်အမြင့်(), 0x302018);
        အူတိုင်.စတုဂံ(32, 24, 576, 432, 0xefe8e2);
        အူတိုင်.စတုဂံ(32, 24, 576, 48, 0x905020);
        စာသား(52, 40, "JKOROS PROGRAMS", 0xffffff);
        for (int နံပါတ် = 0; နံပါတ် < 5; နံပါတ်++) {
            အူတိုင်.စတုဂံ(64, 112 + နံပါတ် * 52, 512, 40, နံပါတ် == ရွေးချယ်မှုတန်ဖိုး ? 0xd0a040 : 0xd8d0c8);
            စာသား(84, 128 + နံပါတ် * 52, နံပါတ် == 0 ? "RUN C++ FILE PROGRAM" : နံပါတ် == 1 ? "RUN UDP LOOPBACK" : နံပါတ် == 2 ? "COMPILE AND RUN JAVA" : နံပါတ် == 3 ? "RUN MICROPYTHON" : "OPEN TERMINAL", 0x201810);
        }
        စာသား(68, 384, အခြေအနေတန်ဖိုး, 0x205020);
        စာသား(52, 420, "TAB SELECT  ENTER RUN  Q EXIT", 0x302018);
    }
    public static void စက်မောင်း() {
        if (ဆားကစ်ပြား.မျက်နှာပြင်ပြင်ဆင်() == 0) { အဆုံးသုံးစက်.ရေး("GUI unavailable\n"); return; }
        int ရွေးချယ်မှုတန်ဖိုး = 0;
        String အခြေအနေတန်ဖိုး = "READY";
        boolean ယခင်စာကြောင်း = အမိန့်အဓိပ္ပာယ်ဖော်.ယခင်စာကြောင်း;
        မျက်နှာပြင်ဆေးခြယ်(ရွေးချယ်မှုတန်ဖိုး, အခြေအနေတန်ဖိုး);
        အဆုံးသုံးစက်.ရေး("GUI READY: UART TAB selects, ENTER runs, Q exits\n");
        while (true) {
            int ဝင်ဒေတာ = ဆားကစ်ပြား.အစဉ်ဆက်ဖတ်();
            if (ဝင်ဒေတာ < 0) { ဆားကစ်ပြား.တွက်ချက်စက်အလှည့်ပေး(); continue; }
            if (ဝင်ဒေတာ == 10 && ယခင်စာကြောင်း) { ယခင်စာကြောင်း = false; continue; }
            ယခင်စာကြောင်း = ဝင်ဒေတာ == 13;
            if (ဝင်ဒေတာ >= '1' && ဝင်ဒေတာ <= '5') { ရွေးချယ်မှုတန်ဖိုး = ဝင်ဒေတာ - '1'; ဝင်ဒေတာ = 13; }
            if (ဝင်ဒေတာ == 't' || ဝင်ဒေတာ == 'T') { အမိန့်အဓိပ္ပာယ်ဖော်.အဆုံးသုံးမျက်နှာပြင်(false); return; }
            if (ဝင်ဒေတာ == 'q' || ဝင်ဒေတာ == 'Q' || ဝင်ဒေတာ == 27) break;
            if (ဝင်ဒေတာ == 9 || ဝင်ဒေတာ == 'j') {
                ရွေးချယ်မှုတန်ဖိုး = (ရွေးချယ်မှုတန်ဖိုး + 1) % 5; မျက်နှာပြင်ဆေးခြယ်(ရွေးချယ်မှုတန်ဖိုး, အခြေအနေတန်ဖိုး); အဆုံးသုံးစက်.ရေး("GUI FOCUS "); အဆုံးသုံးစက်.ကိန်းတန်ဖိုး(ရွေးချယ်မှုတန်ဖိုး); အဆုံးသုံးစက်.အက္ခရာ(10);
            } else if (ဝင်ဒေတာ == 13 || ဝင်ဒေတာ == 10) {
                if (ရွေးချယ်မှုတန်ဖိုး == 4) { အမိန့်အဓိပ္ပာယ်ဖော်.အဆုံးသုံးမျက်နှာပြင်(false); return; }
                int ရလဒ်;
                if (ရွေးချယ်မှုတန်ဖိုး < 2) ရလဒ် = ဆားကစ်ပြား.သုံးစွဲသူပရိုဂရမ်စက်မောင်း(ရွေးချယ်မှုတန်ဖိုး == 0 ? 0 : 9);
                else if (ရွေးချယ်မှုတန်ဖိုး == 2) {
                    ရလဒ် = အမိန့်အဓိပ္ပာယ်ဖော်.ဥပမာစက်မောင်း(10, "Hello.java");
                    if (ရလဒ် == 0) ရလဒ် = အမိန့်အဓိပ္ပာယ်ဖော်.ဥပမာစက်မောင်း(11, "Hello");
                } else ရလဒ် = အမိန့်အဓိပ္ပာယ်ဖော်.ဥပမာစက်မောင်း(12, "hello.py");
                အခြေအနေတန်ဖိုး = ရလဒ် != 0 ? "PROGRAM FAILED" : ရွေးချယ်မှုတန်ဖိုး == 0 ? "C++ FILE OK" : ရွေးချယ်မှုတန်ဖိုး == 1 ? "UDP LOOPBACK OK" : ရွေးချယ်မှုတန်ဖိုး == 2 ? "JAVA OK" : "MICROPYTHON OK";
                မျက်နှာပြင်ဆေးခြယ်(ရွေးချယ်မှုတန်ဖိုး, အခြေအနေတန်ဖိုး);
                အဆုံးသုံးစက်.ရေး("GUI ACTION "); အဆုံးသုံးစက်.ကိန်းတန်ဖိုး(ရွေးချယ်မှုတန်ဖိုး); အဆုံးသုံးစက်.ရေး(" RESULT "); အဆုံးသုံးစက်.ကိန်းတန်ဖိုး(ရလဒ်); အဆုံးသုံးစက်.အက္ခရာ(10);
            }
        }
        အူတိုင်.မျက်နှာပြင်();
        အဆုံးသုံးစက်.ရေး("GUI EXIT\n");
    }
