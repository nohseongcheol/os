package မြန်မာနိုင်ငံ.JMmrOS.ကြားဖြတ်မှု;

import java.util.Arrays;

/** IDT ၏ Java စီမံဘက် ကိုင်တွယ်သူမှတ်ပုံတင်မှုနှင့် ဖြန့်ဝေမှုကို တာဝန်ယူသည်။ */
public final class ကြားဖြတ်စီမံသူ {
    private final ကြားဖြတ်ကိုင်တွယ်သူ[] ကိုင်တွယ်သူစာရင်း = new ကြားဖြတ်ကိုင်တွယ်သူ[256];
    private boolean အလုပ်လုပ်နေ;

    public void ကိုင်တွယ်သူစာရင်းသွင်း(int နံပါတ်, ကြားဖြတ်ကိုင်တွယ်သူ ကိုင်တွယ်သူ) {
        ကိန်းအတည်ပြု(နံပါတ်);
        ကိုင်တွယ်သူစာရင်း[နံပါတ်] = ကိုင်တွယ်သူ;
    }

    public void သိုလှောင်ရာလွှတ်ပေး(int နံပါတ်) {
        ကိန်းအတည်ပြု(နံပါတ်);
        ကိုင်တွယ်သူစာရင်း[နံပါတ်] = null;
    }

    public int တန်ဖိုးဖြန့်ဝေ(int နံပါတ်, int သိမ်းပြီးထပ်ဆင့်အစုလိပ်စာ) {
        ကိန်းအတည်ပြု(နံပါတ်);
        if (!အလုပ်လုပ်နေ) {
            return သိမ်းပြီးထပ်ဆင့်အစုလိပ်စာ;
        }
        ကြားဖြတ်ကိုင်တွယ်သူ ကိုင်တွယ်သူ = ကိုင်တွယ်သူစာရင်း[နံပါတ်];
        return ကိုင်တွယ်သူ == null ? သိမ်းပြီးထပ်ဆင့်အစုလိပ်စာ : ကိုင်တွယ်သူ.လုပ်ငန်းစဉ်တန်ဖိုးအချက်(သိမ်းပြီးထပ်ဆင့်အစုလိပ်စာ);
    }

    public void ဖွင့်သုံး() {
        အလုပ်လုပ်နေ = true;
    }

    public void ပိတ်ထား() {
        အလုပ်လုပ်နေ = false;
    }

    public boolean ဖြစ်သောအလုပ်လုပ်နေ() {
        return အလုပ်လုပ်နေ;
    }

    public void အားလုံးလွှတ်ပေး() {
        Arrays.fill(ကိုင်တွယ်သူစာရင်း, null);
    }

    private void ကိန်းအတည်ပြု(int နံပါတ်) {
        if (နံပါတ် < 0 || နံပါတ် >= ကိုင်တွယ်သူစာရင်း.length) {
            throw new IllegalArgumentException("ကြားဖြတ်မှု 번호가 올바르지 않습니다.");
        }
    }
}

