package မြန်မာနိုင်ငံ.JMmrOS.ဖိုင်စနစ်;

import java.util.HashMap;
import java.util.Map;

/** လုပ်ငန်းစဉ်တစ်ခုစီ၏ သီးခြားအညွှန်းများနှင့် မျှဝေနိုင်သော ဖွင့်ဖိုင်ဖော်ပြချက်များကို ထိန်းထားသည်။ */
public final class ဖိုင်အညွှန်းဇယား {
    private static final int အများဆုံးအညွှန်း = 32;

    private static final class အညွှန်း {
        private final ဖိုင်စနစ်.ဖွင့်ထားဖိုင် ဖွင့်ထားဖိုင်;
        private boolean လုပ်ဆောင်ချိန်ပိတ်;

        အညွှန်း(ဖိုင်စနစ်.ဖွင့်ထားဖိုင် ဖွင့်ထားဖိုင်) {
            this.ဖွင့်ထားဖိုင် = ဖွင့်ထားဖိုင်;
        }
    }

    private final ဖိုင်စနစ် ဖိုင်စနစ်;
    private final Map<Integer, အညွှန်း> အညွှန်းများ = new HashMap<Integer, အညွှန်း>();

    public ဖိုင်အညွှန်းဇယား(ဖိုင်စနစ် ဖိုင်စနစ်) {
        this.ဖိုင်စနစ် = ဖိုင်စနစ်;
    }

    public int ဖွင့်(String အမည်) {
        ဖိုင်စနစ်.ဖွင့်ထားဖိုင် ဖွင့်ထားဖိုင် = ဖိုင်စနစ်.ဖွင့်(အမည်);
        if (ဖွင့်ထားဖိုင် == null) {
            return -2;
        }
        int နံပါတ် = အလွတ်အညွှန်းကိန်း(3);
        if (နံပါတ် < 0) {
            return -24;
        }
        အညွှန်းများ.put(Integer.valueOf(နံပါတ်), new အညွှန်း(ဖွင့်ထားဖိုင်));
        return နံပါတ်;
    }

    public int ဖတ်(int နံပါတ်, byte[] ဦးတည်ရာလက်ခံရယူ, int အရွယ်) {
        အညွှန်း အချက်တန်ဖိုး = အညွှန်းများ.get(Integer.valueOf(နံပါတ်));
        if (အချက်တန်ဖိုး == null) {
            return -9;
        }
        if (အရွယ် < 0 || အရွယ် > ဦးတည်ရာလက်ခံရယူ.length) {
            return -22;
        }
        int လက်ကျန်ဒေတာ = အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.ဒေတာ.length - အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.နေရာ;
        int အရွယ်ဖတ် = Math.min(အရွယ်, Math.max(လက်ကျန်ဒေတာ, 0));
        System.arraycopy(အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.ဒေတာ, အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.နေရာ, ဦးတည်ရာလက်ခံရယူ, 0, အရွယ်ဖတ်);
        အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.နေရာ += အရွယ်ဖတ်;
        return အရွယ်ဖတ်;
    }

    public int ရွှေ့နေရာ(int နံပါတ်, int အကွာအဝေး, int စီမံကိန်းအမြစ်) {
        အညွှန်း အချက်တန်ဖိုး = အညွှန်းများ.get(Integer.valueOf(နံပါတ်));
        if (အချက်တန်ဖိုး == null) {
            return -9;
        }
        int နောက်ခံတန်ဖိုး;
        if (စီမံကိန်းအမြစ် == 0) {
            နောက်ခံတန်ဖိုး = 0;
        } else if (စီမံကိန်းအမြစ် == 1) {
            နောက်ခံတန်ဖိုး = အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.နေရာ;
        } else if (စီမံကိန်းအမြစ် == 2) {
            နောက်ခံတန်ဖိုး = အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.ဒေတာ.length;
        } else {
            return -22;
        }
        int အသစ်နေရာ = နောက်ခံတန်ဖိုး + အကွာအဝေး;
        if (အသစ်နေရာ < 0) {
            return -22;
        }
        အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.နေရာ = အသစ်နေရာ;
        return အသစ်နေရာ;
    }

    public int ပိတ်(int နံပါတ်) {
        အညွှန်း အချက်တန်ဖိုး = အညွှန်းများ.remove(Integer.valueOf(နံပါတ်));
        if (အချက်တန်ဖိုး == null) {
            return -9;
        }
        အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.ကိုးကားချက်အရေအတွက်--;
        return 0;
    }

    public int ပွားအညွှန်း(int နံပါတ်, int အနည်းဆုံးကိန်း) {
        အညွှန်း အချက်တန်ဖိုး = အညွှန်းများ.get(Integer.valueOf(နံပါတ်));
        if (အချက်တန်ဖိုး == null) {
            return -9;
        }
        int အသစ်ကိန်း = အလွတ်အညွှန်းကိန်း(အနည်းဆုံးကိန်း);
        if (အသစ်ကိန်း < 0) {
            return -24;
        }
        အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.ကိုးကားချက်အရေအတွက်++;
        အညွှန်းများ.put(Integer.valueOf(အသစ်ကိန်း), new အညွှန်း(အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်));
        return အသစ်ကိန်း;
    }

    public int သတ်မှတ်နေရာပွား(int နံပါတ်, int အသစ်ကိန်း) {
        if (နံပါတ် == အသစ်ကိန်း) {
            return အညွှန်းများ.containsKey(Integer.valueOf(နံပါတ်)) ? နံပါတ် : -9;
        }
        if (အသစ်ကိန်း < 0 || အသစ်ကိန်း >= အများဆုံးအညွှန်း) {
            return -9;
        }
        အညွှန်း မူရင်း = အညွှန်းများ.get(Integer.valueOf(နံပါတ်));
        if (မူရင်း == null) {
            return -9;
        }
        if (အညွှန်းများ.containsKey(Integer.valueOf(အသစ်ကိန်း))) {
            ပိတ်(အသစ်ကိန်း);
        }
        မူရင်း.ဖွင့်ထားဖိုင်.ကိုးကားချက်အရေအတွက်++;
        အညွှန်းများ.put(Integer.valueOf(အသစ်ကိန်း), new အညွှန်း(မူရင်း.ဖွင့်ထားဖိုင်));
        return အသစ်ကိန်း;
    }

    public int လုပ်ဆောင်ချိန်ပိတ်သတ်မှတ်(int နံပါတ်, boolean တန်ဖိုး) {
        အညွှန်း အချက်တန်ဖိုး = အညွှန်းများ.get(Integer.valueOf(နံပါတ်));
        if (အချက်တန်ဖိုး == null) {
            return -9;
        }
        အချက်တန်ဖိုး.လုပ်ဆောင်ချိန်ပိတ် = တန်ဖိုး;
        return 0;
    }

    public int လုပ်ဆောင်ချိန်ပိတ်တန်ဖိုး(int နံပါတ်) {
        အညွှန်း အချက်တန်ဖိုး = အညွှန်းများ.get(Integer.valueOf(နံပါတ်));
        if (အချက်တန်ဖိုး == null) {
            return -9;
        }
        return အချက်တန်ဖိုး.လုပ်ဆောင်ချိန်ပိတ် ? 1 : 0;
    }

    public ဖိုင်အချက်အလက် စနစ်သတင်းအချက်အလက်(int နံပါတ်) {
        if (နံပါတ် >= 0 && နံပါတ် <= 2) {
            return new ဖိုင်အချက်အလက်(0, 0020666);
        }
        အညွှန်း အချက်တန်ဖိုး = အညွှန်းများ.get(Integer.valueOf(နံပါတ်));
        if (အချက်တန်ဖိုး == null) {
            return null;
        }
        return new ဖိုင်အချက်အလက်(အချက်တန်ဖိုး.ဖွင့်ထားဖိုင်.ဒေတာ.length, 0100444);
    }

    public void လုပ်ဆောင်ချိန်ပိတ်() {
        Integer[] ကိန်းစာရင်း = အညွှန်းများ.keySet().toArray(new Integer[0]);
        for (Integer နံပါတ် : ကိန်းစာရင်း) {
            အညွှန်း အချက်တန်ဖိုး = အညွှန်းများ.get(နံပါတ်);
            if (အချက်တန်ဖိုး != null && အချက်တန်ဖိုး.လုပ်ဆောင်ချိန်ပိတ်) {
                ပိတ်(နံပါတ်.intValue());
            }
        }
    }

    public boolean ဖြစ်သောဖွင့်(int နံပါတ်) {
        return အညွှန်းများ.containsKey(Integer.valueOf(နံပါတ်));
    }

    public ဖိုင်အညွှန်းဇယား ပုံတူပွားတန်ဖိုး() {
        ဖိုင်အညွှန်းဇယား ရလဒ် = new ဖိုင်အညွှန်းဇယား(ဖိုင်စနစ်);
        for (Map.Entry<Integer, အညွှန်း> အချက်တန်ဖိုး : အညွှန်းများ.entrySet()) {
            အချက်တန်ဖိုး.getValue().ဖွင့်ထားဖိုင်.ကိုးကားချက်အရေအတွက်++;
            အညွှန်း အသစ်အညွှန်း = new အညွှန်း(အချက်တန်ဖိုး.getValue().ဖွင့်ထားဖိုင်);
            အသစ်အညွှန်း.လုပ်ဆောင်ချိန်ပိတ် = အချက်တန်ဖိုး.getValue().လုပ်ဆောင်ချိန်ပိတ်;
            ရလဒ်.အညွှန်းများ.put(အချက်တန်ဖိုး.getKey(), အသစ်အညွှန်း);
        }
        return ရလဒ်;
    }

    private int အလွတ်အညွှန်းကိန်း(int အနည်းဆုံးကိန်း) {
        for (int နံပါတ် = Math.max(0, အနည်းဆုံးကိန်း); နံပါတ် < အများဆုံးအညွှန်း; နံပါတ်++) {
            if (!အညွှန်းများ.containsKey(Integer.valueOf(နံပါတ်))) {
                return နံပါတ်;
            }
        }
        return -1;
    }
}
