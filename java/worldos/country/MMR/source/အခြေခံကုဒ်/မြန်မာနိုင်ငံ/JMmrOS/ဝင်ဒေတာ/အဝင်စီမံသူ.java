package မြန်မာနိုင်ငံ.JMmrOS.ဝင်ဒေတာ;

import java.util.ArrayDeque;
import java.util.Queue;

/** ကြားဖြတ်မှုနှင့် စီမံကုဒ်အကြား အဝင်ဖြစ်ရပ်များကို လုံခြုံစွာ ပို့သည်။ */
public final class အဝင်စီမံသူ {
    private final Queue<အဝင်ဖြစ်ရပ်> ဖြစ်ရပ်များ = new ArrayDeque<အဝင်ဖြစ်ရပ်>();
    private final int အများဆုံးဖြစ်ရပ်အရေအတွက်;
    private int ပယ်ဖြစ်ရပ်အရေအတွက်;

    public အဝင်စီမံသူ(int အများဆုံးဖြစ်ရပ်အရေအတွက်) {
        if (အများဆုံးဖြစ်ရပ်အရေအတွက် <= 0) {
            throw new IllegalArgumentException("ဖြစ်ရပ် 수가 올바르지 않습니다.");
        }
        this.အများဆုံးဖြစ်ရပ်အရေအတွက် = အများဆုံးဖြစ်ရပ်အရေအတွက်;
    }

    public synchronized void သော့အောက်(int သော့ဒေတာ) {
        တန်ဖိုးထား(new အဝင်ဖြစ်ရပ်(အဝင်ဖြစ်ရပ်.အမျိုးအစားတန်ဖိုး.သော့အောက်, သော့ဒေတာ & 0xff, 0));
    }

    public synchronized void သော့အပေါ်(int သော့ဒေတာ) {
        တန်ဖိုးထား(new အဝင်ဖြစ်ရပ်(အဝင်ဖြစ်ရပ်.အမျိုးအစားတန်ဖိုး.သော့အပေါ်, သော့ဒေတာ & 0xff, 0));
    }

    public synchronized void မောက်စ်ရွှေ့(int အလျားတည်နေရာ, int ဒေါင်လိုက်တည်နေရာ) {
        တန်ဖိုးထား(new အဝင်ဖြစ်ရပ်(အဝင်ဖြစ်ရပ်.အမျိုးအစားတန်ဖိုး.မောက်စ်ရွှေ့, အလျားတည်နေရာ, ဒေါင်လိုက်တည်နေရာ));
    }

    public synchronized အဝင်ဖြစ်ရပ် နောက်တစ်ခုဖြစ်ရပ်() {
        return ဖြစ်ရပ်များ.poll();
    }

    public synchronized int ပယ်ဖြစ်ရပ်အရေအတွက်() {
        return ပယ်ဖြစ်ရပ်အရေအတွက်;
    }

    private void တန်ဖိုးထား(အဝင်ဖြစ်ရပ် ဖြစ်ရပ်) {
        if (ဖြစ်ရပ်များ.size() == အများဆုံးဖြစ်ရပ်အရေအတွက်) {
            ဖြစ်ရပ်များ.poll();
            ပယ်ဖြစ်ရပ်အရေအတွက်++;
        }
        ဖြစ်ရပ်များ.offer(ဖြစ်ရပ်);
    }
}

