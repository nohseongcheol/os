package မြန်မာနိုင်ငံ.JMmrOS.အလုပ်;

import မြန်မာနိုင်ငံ.JMmrOS.မှတ်ဉာဏ်နယ်ပယ်.စာမျက်နှာစီမံသူ;
import မြန်မာနိုင်ငံ.JMmrOS.ဖိုင်စနစ်.ဖိုင်အညွှန်းဇယား;

public final class လုပ်ငန်းစဉ် {
    private final int သတ်မှတ်နံပါတ်တန်ဖိုး;
    private final int မိဘသတ်မှတ်နံပါတ်;
    private final စာမျက်နှာစီမံသူ.လိပ်စာနယ်ပယ် လိပ်စာနယ်ပယ်;
    private final ဖိုင်အညွှန်းဇယား ဖိုင်အညွှန်း;
    private လုပ်ငန်းစဉ်အခြေအနေ အခြေအနေတန်ဖိုး = လုပ်ငန်းစဉ်အခြေအနေ.ပြင်ဆင်;
    private int ထွက်ကုဒ်;
    private int ပရိုဂရမ်ဖြတ် = 0x06000000;
    private int လုပ်ဆောင်မှုစတင်လိပ်စာ;
    private String[] လုပ်ဆောင်မှုပေးအချက် = new String[0];
    private String[] ဝန်းကျင်တန်ဖိုး = new String[0];

    လုပ်ငန်းစဉ်(int သတ်မှတ်နံပါတ်တန်ဖိုး, int မိဘသတ်မှတ်နံပါတ်, စာမျက်နှာစီမံသူ.လိပ်စာနယ်ပယ် လိပ်စာနယ်ပယ်, ဖိုင်အညွှန်းဇယား ဖိုင်အညွှန်း) {
        this.သတ်မှတ်နံပါတ်တန်ဖိုး = သတ်မှတ်နံပါတ်တန်ဖိုး;
        this.မိဘသတ်မှတ်နံပါတ် = မိဘသတ်မှတ်နံပါတ်;
        this.လိပ်စာနယ်ပယ် = လိပ်စာနယ်ပယ်;
        this.ဖိုင်အညွှန်း = ဖိုင်အညွှန်း;
    }

    public int သတ်မှတ်နံပါတ်တန်ဖိုး() {
        return သတ်မှတ်နံပါတ်တန်ဖိုး;
    }

    public int မိဘသတ်မှတ်နံပါတ်() {
        return မိဘသတ်မှတ်နံပါတ်;
    }

    public စာမျက်နှာစီမံသူ.လိပ်စာနယ်ပယ် လိပ်စာနယ်ပယ်() {
        return လိပ်စာနယ်ပယ်;
    }

    public ဖိုင်အညွှန်းဇယား ဖိုင်အညွှန်း() {
        return ဖိုင်အညွှန်း;
    }

    public လုပ်ငန်းစဉ်အခြေအနေ အခြေအနေတန်ဖိုး() {
        return အခြေအနေတန်ဖိုး;
    }

    public void အခြေအနေသတ်မှတ်(လုပ်ငန်းစဉ်အခြေအနေ အသစ်အခြေအနေ) {
        အခြေအနေတန်ဖိုး = အသစ်အခြေအနေ;
    }

    public int ထွက်ကုဒ်() {
        return ထွက်ကုဒ်;
    }

    public void ထွက်ပရိုဂရမ်(int တန်ဖိုး) {
        ထွက်ကုဒ် = တန်ဖိုး & 0xff;
        အခြေအနေတန်ဖိုး = လုပ်ငန်းစဉ်အခြေအနေ.ထွက်ပရိုဂရမ်;
    }

    public int ပရိုဂရမ်ဖြတ်() {
        return ပရိုဂရမ်ဖြတ်;
    }

    public void ပရိုဂရမ်ဖြတ်သတ်မှတ်(int အသစ်အဆုံး) {
        if (အသစ်အဆုံး < 0x06000000 || အသစ်အဆုံး > 0x07000000) {
            throw new IllegalArgumentException("ပရိုဂရမ် အဆုံး 범위를 벗어났습니다.");
        }
        ပရိုဂရမ်ဖြတ် = အသစ်အဆုံး;
    }

    public void လုပ်ဆောင်မှုပတ်ဝန်းကျင်အဓိပ္ပာယ်သတ်မှတ်(int စတင်လိပ်စာ, String[] သတ်မှတ်အချက်ပေးအချက်, String[] ဝန်းကျင်) {
        လုပ်ဆောင်မှုစတင်လိပ်စာ = စတင်လိပ်စာ;
        လုပ်ဆောင်မှုပေးအချက် = သတ်မှတ်အချက်ပေးအချက်.clone();
        ဝန်းကျင်တန်ဖိုး = ဝန်းကျင်.clone();
    }

    public int လုပ်ဆောင်မှုစတင်လိပ်စာ() { return လုပ်ဆောင်မှုစတင်လိပ်စာ; }
    public String[] လုပ်ဆောင်မှုပေးအချက်() { return လုပ်ဆောင်မှုပေးအချက်.clone(); }
    public String[] ဝန်းကျင်တန်ဖိုး() { return ဝန်းကျင်တန်ဖိုး.clone(); }
}
