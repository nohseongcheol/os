import Монгол.자체.холболт;
import Монгол.자체.실행인수;
import Монгол.자체.전문통로;
import Монгол.자체.문자;
import Монгол.자체.출력;
import Монгол.자체.검사;
import Монгол.자체.입력흐름;
import Монгол.자체.입출력예외;

public class 네트워크예제 {
    public static void Ажиллуулах() throws 입출력예외 {
        // хост: python3 Хэрэгслүүд/예제되돌림.py --tcp-port 9000 --udp-port 9001
        холболт Холбох = холболт.Нээх("10.0.2.2", 문자.задлан_ялгал_хийх_бүхэл_тоо(실행인수.Бичвэр(0)));
        try {
            Холбох.대기시간(700);
            byte[] мэдээлэл = 문자.부호화("JAVA TCP mn\n");
            Холбох.출력().Бичих(мэдээлэл);
            입력흐름 입력 = Холбох.입력();
            for (int 수 = 0; 수 < 문자.바이트수(мэдээлэл); 수++) {
                검사.참인지(입력.Унших() == (мэдээлэл[수] & 255), "TCP хариулах 불일치");
            }
        } finally { Холбох.Хаах(); }
        전문통로 종단 = 전문통로.Нээх(0);
        try {
            종단.대기시간(700);
            종단.илгээх("10.0.2.2", 문자.задлан_ялгал_хийх_бүхэл_тоо(실행인수.Бичвэр(1)), "JAVA UDP mn");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP mn"), "UDP хариулах 불일치");
        } finally { 종단.Хаах(); }
        출력.бичих_мөр("JAVA 네트워크 шалгах: TCP UDP mn");
    }
}
