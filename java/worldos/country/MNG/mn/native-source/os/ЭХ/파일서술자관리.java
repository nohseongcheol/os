        if (지정) { if (нээх_барих[새서술자] != 0) хаах_файл(새서술자); }
        else { 새서술자 = 빈서술자(새서술자); if (새서술자 < 0) return 새서술자; }
        нээх_барих[새서술자] = 기술 + 1; 서술자설정[새서술자] = Тохиргоо; 참조수[기술]++;
