    public int Гүйцэтгэх_команд(үйл_явц_утга 현재과정, byte[] 실행파일, String[] 인자, String[] 환경) {
        실행파일적재기.зураг зураг_утга;
        try {
            зураг_утга = 적재기.검사(실행파일);
        } catch (IllegalArgumentException Алдаа) {
            return -8;
        }
        if (인자 == null || 환경 == null || 인자.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.хэсэг_утга хэсэг_утга : зураг_утга.구역들()) {
            if ((хэсэг_утга.дарцаг_утга() & 2) == 0 || хэсэг_утга.Хэмжээ() == 0) {
                continue;
            }
            int 첫쪽 = хэсэг_утга.хаяг() / хуудас_менежер.хуудасны_хэмжээ;
            int 끝쪽 = (хэсэг_утга.хаяг() + хэсэг_утга.Хэмжээ() + хуудас_менежер.хуудасны_хэмжээ - 1) / хуудас_менежер.хуудасны_хэмжээ;
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int хаяг = индекс * хуудас_менежер.хуудасны_хэмжээ;
                try {
                    쪽관리.바이트읽기(현재과정.хаяг_орон_зай(), хаяг);
                    쪽관리.범위개인쓰기(현재과정.хаяг_орон_зай(), хаяг, хуудас_менежер.хуудасны_хэмжээ);
                } catch (IllegalStateException Алдаа) {
                    쪽관리.газрын_зураг_дээр_олох_хуудас(현재과정.хаяг_орон_зай(), хаяг, true);
                }
            }
            for (int индекс = 0; индекс < хэсэг_утга.Хэмжээ(); индекс++) {
                byte утга = хэсэг_утга.종류() == 8 ? 0 : 실행파일[хэсэг_утга.파일위치() + индекс];
                쪽관리.бичих_байт_утга(현재과정.хаяг_орон_зай(), хэсэг_утга.хаяг() + индекс, утга);
            }
        }
        현재과정.실행문맥설정(зураг_утга.Эхлэл_хаяг(), 인자, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

