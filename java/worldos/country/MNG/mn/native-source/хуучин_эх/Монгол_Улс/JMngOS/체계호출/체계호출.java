    public int 프로그램끝(үйл_явц_утга 현재과정, int 새끝) {
        int 이전끝 = 현재과정.프로그램끝();
        if (새끝 == 0) {
            return 이전끝;
        }
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            return -12;
        }
        int 첫쪽 = 이전끝 / хуудас_менежер.хуудасны_хэмжээ;
        int 끝쪽 = (새끝 + хуудас_менежер.хуудасны_хэмжээ - 1) / хуудас_менежер.хуудасны_хэмжээ;
        if (새끝 > 이전끝) {
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int хаяг = индекс * хуудас_менежер.хуудасны_хэмжээ;
                try {
                    쪽관리.바이트읽기(현재과정.хаяг_орон_зай(), хаяг);
                } catch (IllegalStateException Алдаа) {
                    쪽관리.газрын_зураг_дээр_олох_хуудас(현재과정.хаяг_орон_зай(), хаяг, true);
                }
            }
        }
        현재과정.프로그램끝설정(새끝);
        return 새끝;
    }

    public int 프로그램끝늘리기(үйл_явц_утга 현재과정, int 증가량) {
        int 이전끝 = 현재과정.프로그램끝();
        int 결과 = 프로그램끝(현재과정, 이전끝 + 증가량);
        return 결과 < 0 ? 결과 : 이전끝;
    }

