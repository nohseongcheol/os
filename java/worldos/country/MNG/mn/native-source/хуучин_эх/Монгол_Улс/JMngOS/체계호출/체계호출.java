    public int файл_хяналт(үйл_явц_утга 현재과정, int 서술자, int Тушаал, int 인자) {
        if (Тушаал == 0) {
            return 현재과정.파일서술자().복제서술자(서술자, 인자);
        }
        if (Тушаал == 1) {
            return 현재과정.파일서술자().실행시닫기값(서술자);
        }
        if (Тушаал == 2) {
            return 현재과정.파일서술자().실행시닫기설정(서술자, (인자 & 1) != 0);
        }
        if (Тушаал == 3) {
            return 현재과정.파일서술자().системийн_мэдээлэл(서술자) == null ? -9 : зөвхөн_унших_дарцаг;
        }
        if (Тушаал == 4) {
            return 인자 == зөвхөн_унших_дарцаг ? 0 : -30;
        }
        return -22;
    }

