import 한국어.자체.цонх;
import 한국어.자체.Тэмдэг;
import 한국어.자체.бичвэрийн_талбар;
import 한국어.자체.товч;
import 한국어.자체.үйлдэл_дараалал;
import 한국어.자체.출력;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing цонх: Монгол 입력 → товч → заавал_унших_eb81d7d9 Бичвэр сэргээх. */
public class 창예제 implements 실행할일, 동작받이 {
    private цонх 인사창;
    private бичвэрийн_талбар нэр_талбар;
    private Тэмдэг 인사말;
    private int 인사횟수;

    public void нээх_цонх() {
        인사창 = new цонх("Монгол Swing", 460, 300);
        인사창.нэмэх_элемент(new Тэмдэг("Монгол", 20, 20, 420, 28));
        нэр_талбар = new бичвэрийн_талбар("Монгол", 20, 64, 420, 30);
        인사말 = new Тэмдэг("Монгол", 20, 152, 420, 28);
        인사창.нэмэх_элемент(нэр_талбар);
        인사창.нэмэх_элемент(new товч("인사하기", 20, 108, 180, 32, this));
        인사창.нэмэх_элемент(인사말);
        인사창.нэмэх_элемент(new Тэмдэг("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.үзүүлэх_цонх();
        출력.бичих_мөр("GUI 예제 Бэлтгэх: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.бичих_Бичвэр("Монгол, " + нэр_талбар.글읽기() + "님! (" + 인사횟수 + ")");
        출력.бичих_мөр("GUI 인사: " + 인사말.글읽기());
    }

    public void Гүйцэтгэх_даалгавар() { нээх_цонх(); }
    public void 동작받기(동작알림 알림) {
        출력.бичих_мөр("Үйлдэл 알림: " + 알림.команд_Бичвэр());
        인사하기();
    }
    public static void Ажиллуулах() {
        үйлдэл_дараалал.나중에실행(new 창예제());
    }
}
