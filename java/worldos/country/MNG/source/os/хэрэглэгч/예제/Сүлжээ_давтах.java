/** 최대 Хэмжээ/홀수 урт_утга 데이터그램으로 бодит_өгөгдөл RTL8139 수신 давтах_утга 순환을 시험한다. */
public final class Сүлжээ_давтах {
    public static int Ажиллуулах() {
        if (хэрэглэгч.인수개수() != 1) { хэрэглэгч.Бичих("Usage: run stress PORT\n"); return 2; }
        String Бичвэр = хэрэглэгч.인수(0);
        int порт_утга = 0;
        for (int индекс = 0; индекс < Бичвэр.length(); индекс++) {
            if (Бичвэр.charAt(индекс) < '0' || Бичвэр.charAt(индекс) > '9' || порт_утга > 6553) return 2;
            порт_утга = порт_утга * 10 + Бичвэр.charAt(индекс) - '0';
        }
        if (порт_утга < 1 || порт_утга > 65535) return 2;
        int барих_утга = хэрэглэгч.нээх_Сүлжээ(0);
        if (барих_утга < 0) return 3;
        int[] өгөгдөл = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int урт_утга = 1024 - (회차 & 1);
            for (int индекс = 0; индекс < урт_утга; индекс++) өгөгдөл[индекс] = (индекс + 회차) & 255;
            if (хэрэглэгч.илгээх_өгөгдөл(барих_утга, 0x0a000202, порт_утга, өгөгдөл, урт_утга) != урт_утга) return 4;
            if (хэрэглэгч.자료받기(барих_утга, өгөгдөл, 300) != урт_утга) return 5;
            for (int индекс = 0; индекс < урт_утга; индекс++) if (өгөгдөл[индекс] != ((индекс + 회차) & 255)) return 6;
        }
        хэрэглэгч.хаах_Сүлжээ(барих_утга);
        хэрэглэгч.Бичих("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
