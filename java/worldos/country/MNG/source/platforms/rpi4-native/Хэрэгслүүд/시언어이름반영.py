#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 байт_утга 위치로 자체 C 이름을 옮기는 일회성 이행 Хэрэгслүүд.

외부 구조체의 멤버, мөр_утга_6ca8363c, C 표준 ФУНКЦ_утга, 이식 규약은 보존한다.
입력은 өөрчлөх_утга 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def Гүйцэтгэх_команд():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['Алдаа']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    нэр_хүснэгт = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {ЦОР_ГАНЦ_утга:нэр_хүснэгт[оролт_утга['Нэр']] for ЦОР_ГАНЦ_утга,оролт_утга in 선언표.items()
                if оролт_утга['Нэр'] in нэр_хүснэгт and оролт_утга['Нэр'] not in 규격}
    холболт_хүснэгт = {оролт_утга['Нэр']:нэр_хүснэгт[оролт_утга['Нэр']] for оролт_утга in 선언표.values()
              if оролт_утга.get('Холбох')==4 and оролт_утга['종류'] in (8,9)
              and оролт_утга['Нэр'] in нэр_хүснэгт and оролт_утга['Нэр'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 Холбох 이름만 유지한다.
    머리 = ['/* 한국어 эх_мод 이름과 기존 компьютер Холбох нөхцөл_байдал_утга. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(холболт_хүснэгт.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Өөрчлөлтүүд_Жагсаалт = defaultdict(dict)
    for Файл,Оффсет_утга,Нэр,ЦОР_ГАНЦ_утга in 분석['Толь_лавлах']:
        if ЦОР_ГАНЦ_утга in 바꿀선언:
            Өөрчлөлтүүд_Жагсаалт[Файл][Оффсет_утга] = (Нэр,바꿀선언[ЦОР_ГАНЦ_утга])
    бичих_мөр_6e8b375a = ['Файл\t원래바이트위치\t이전이름\t한국어이름']
    үл_ойшоох_утга = []
    for Файл,өөрчлөх_утга in Өөрчлөлтүүд_Жагсаалт.items():
        ЗАМ = Path(Файл); 원본 = ЗАМ.read_bytes(); өгөгдөл = 원본
        for Оффсет_утга,(옛이름,새이름) in sorted(өөрчлөх_утга.items(),reverse=True):
            끝 = Оффсет_утга+len(옛이름.encode())
            if 원본[Оффсет_утга:끝] != 옛이름.encode():
                үл_ойшоох_утга.append((str(ЗАМ.relative_to(기준)),Оффсет_утга,옛이름));continue
            өгөгдөл = өгөгдөл[:Оффсет_утга]+새이름.encode()+өгөгдөл[끝:]
            бичих_мөр_6e8b375a.append('{}\t{}\t{}\t{}'.format(ЗАМ.relative_to(기준),Оффсет_утга,옛이름,새이름))
        ЗАМ.write_bytes(өгөгдөл)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макро_утга = {оролт_утга['Нэр']:нэр_хүснэгт[оролт_утга['Нэр']] for оролт_утга in 선언표.values()
              if оролт_утга['종류']==501 and оролт_утга['Нэр'] in нэр_хүснэгт and оролт_утга['Нэр'] not in 규격}
    for ЗАМ in sorted({Path(оролт_утга['Файл']) for оролт_утга in 선언표.values()}):
        мөр_Жагсаалт = ЗАМ.read_text().splitlines(True); 이어짐 = False
        for индекс,Шугам in enumerate(мөр_Жагсаалт):
            전처리 = 이어짐 or bool(re.match(r'\s*#',Шугам))
            이어짐 = 전처리 and Шугам.rstrip().endswith('\\')
            if 전처리:
                표 = нэр_хүснэгт if re.match(r'\s*#\s*define\b',Шугам) or 이어짐 else макро_утга
                мөр_Жагсаалт[индекс] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],Шугам)
        ЗАМ.write_text(''.join(мөр_Жагсаалт))
    # 각 자체 Орчуулах_эх 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ЗАМ in sorted({Path(оролт_утга['Файл']) for оролт_утга in 선언표.values()}):
        if ЗАМ.suffix not in ('.c','.cpp'):continue
        ижил_түвшин_утга = '../' * len(ЗАМ.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        ЗАМ.write_text('#include "'+ижил_түвшин_утга+'"\n'+ЗАМ.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(бичих_мөр_6e8b375a)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(үл_ойшоох_утга,ensure_ascii=False,indent=2)+'\n')
    print('өөрчлөх_утга',len(бичих_мөр_6e8b375a)-1,'전처리 재검토',len(үл_ойшоох_утга),'компьютер Холбох',len(холболт_хүснэгт))

if __name__=='__main__': Гүйцэтгэх_команд()
