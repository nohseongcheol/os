package Монгол.JMngOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB хуудас_утга 연결과 Бичих 시 복사를 제공한다. */
public final class хуудас_менежер {
    public static final int хуудасны_хэмжээ = 4096;

    private static final class хуудас_утга {
        private byte[] өгөгдөл = new byte[хуудасны_хэмжээ];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class хаяг_орон_зай {
        private final Map<Integer, хуудас_утга> хуудас_хүснэгт = new HashMap<Integer, хуудас_утга>();
    }

    public хаяг_орон_зай 새주소공간() {
        return new хаяг_орон_зай();
    }

    public void газрын_зураг_дээр_олох_хуудас(хаяг_орон_зай 공간, int виртуал_хаяг, boolean 쓰기가능) {
        int индекс = 쪽번호(виртуал_хаяг);
        хуудас_утга 새쪽 = new хуудас_утга();
        새쪽.쓰기가능 = 쓰기가능;
        공간.хуудас_хүснэгт.put(Integer.valueOf(индекс), 새쪽);
    }

    public хаяг_орон_зай 쓰기시복사복제(хаяг_орон_зай 원본) {
        хаяг_орон_зай 복제본 = new хаяг_орон_зай();
        for (Map.Entry<Integer, хуудас_утга> оролт_утга : 원본.хуудас_хүснэгт.entrySet()) {
            хуудас_утга 공유쪽 = оролт_утга.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.хуудас_хүснэгт.put(оролт_утга.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(хаяг_орон_зай 공간, int виртуал_хаяг) {
        хуудас_утга зорилго = хайх_хуудас(공간, виртуал_хаяг);
        return зорилго.өгөгдөл[Math.floorMod(виртуал_хаяг, хуудасны_хэмжээ)];
    }

    public void бичих_байт_утга(хаяг_орон_зай 공간, int виртуал_хаяг, byte утга) {
        int индекс = 쪽번호(виртуал_хаяг);
        хуудас_утга зорилго = хайх_хуудас(공간, виртуал_хаяг);
        if (!зорилго.쓰기가능) {
            if (!зорилго.쓰기시복사) {
                throw new IllegalStateException("Унших 전용 쪽입니다.");
            }
            зорилго = үүсгэх_хувийн_хуудас(공간, индекс, зорилго);
        }
        зорилго.өгөгдөл[Math.floorMod(виртуал_хаяг, хуудасны_хэмжээ)] = утга;
    }

    public void 범위개인쓰기(хаяг_орон_зай 공간, int Эхлэл_хаяг, int Хэмжээ) {
        if (Хэмжээ < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int дуусгах_хаяг = Math.addExact(Эхлэл_хаяг, Хэмжээ);
        for (int хаяг = Эхлэл_хаяг; хаяг < дуусгах_хаяг; хаяг = (쪽번호(хаяг) + 1) * хуудасны_хэмжээ) {
            int индекс = 쪽번호(хаяг);
            хуудас_утга зорилго = хайх_хуудас(공간, хаяг);
            if (зорилго.쓰기시복사) {
                үүсгэх_хувийн_хуудас(공간, индекс, зорилго);
            } else {
                зорилго.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(хаяг_орон_зай 공간, int Эхлэл_хаяг, byte[] өгөгдөл) {
        for (int индекс = 0; индекс < өгөгдөл.length; индекс++) {
            бичих_байт_утга(공간, Эхлэл_хаяг + индекс, өгөгдөл[индекс]);
        }
    }

    private хуудас_утга үүсгэх_хувийн_хуудас(хаяг_орон_зай 공간, int индекс, хуудас_утга 공유쪽) {
        хуудас_утга хувийн_хуудас = new хуудас_утга();
        хувийн_хуудас.өгөгдөл = Arrays.copyOf(공유쪽.өгөгдөл, 공유쪽.өгөгдөл.length);
        хувийн_хуудас.쓰기가능 = true;
        хувийн_хуудас.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.хуудас_хүснэгт.put(Integer.valueOf(индекс), хувийн_хуудас);
        return хувийн_хуудас;
    }

    private хуудас_утга хайх_хуудас(хаяг_орон_зай 공간, int хаяг) {
        хуудас_утга зорилго = 공간.хуудас_хүснэгт.get(Integer.valueOf(쪽번호(хаяг)));
        if (зорилго == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return зорилго;
    }

    private int 쪽번호(int хаяг) {
        if (хаяг < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return хаяг / хуудасны_хэмжээ;
    }
}

