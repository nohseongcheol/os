/** 会话期间保留 8 个文件；源码编辑或编译失败时保留原文件。 */
public final class 主存文件系统 {
    static final int 最大大小 = 16384;
    static int[] 名称列列表 = new int[8 * 64];
    static int[] 大小列表 = new int[8];
    static int[] 打开个数 = new int[8], 权限授权列 = new int[8];
    static int[] 名称 = new int[64];
    static int[] 编辑值 = new int[最大大小];
    static boolean 是否编辑中 = false;
    static boolean 溢出值 = false;
    static int 编辑大小 = 0;

    static boolean 检查名称(int[] 字符值, int 长度) {
        if (长度 < 1 || 长度 > 63) return false;
        for (int 数 = 0; 数 < 长度; 数++) {
            int 值 = 字符值[数];
            if (!(值 >= 'a' && 值 <= 'z') && !(值 >= 'A' && 值 <= 'Z')
                && !(值 >= '0' && 值 <= '9') && 值 != '_' && 值 != '-' && 值 != '.') return false;
        }
        return 字符值[0] != '.';
    }

    static int 查找条目(int[] 字符值, int 长度) {
        if (!检查名称(字符值, 长度)) return -22;
        for (int 数 = 0; 数 < 8; 数++) {
            boolean 相等文本 = 名称列列表[数 * 64 + 长度] == 0;
            for (int 槽条目 = 0; 槽条目 < 长度; 槽条目++) if (名称列列表[数 * 64 + 槽条目] != 字符值[槽条目]) 相等文本 = false;
            if (相等文本) return 数;
        }
        return -2;
    }

    static int 存储值(int[] 字符值, int 长度, int[] 数据, int 大小) {
        if (!检查名称(字符值, 长度) || 大小 < 0 || 大小 > 数据.length) return -22;
        if (大小 > 最大大小) return -90;
        int 编号 = 查找条目(字符值, 长度);
        if (编号 == -2) {
            for (int 数 = 0; 数 < 8 && 编号 < 0; 数++) if (名称列列表[数 * 64] == 0 && 打开个数[数] == 0) 编号 = 数;
            if (编号 >= 0) 权限授权列[编号] = 438;
        }
        if (编号 < 0) return -28;
        int 地址 = 设备.文件内存() + 编号 * 最大大小;
        for (int 数 = 0; 数 < 大小; 数++) 设备.写入内存(地址 + 数, 数据[数]);
        for (int 数 = 0; 数 < 64; 数++) 名称列列表[编号 * 64 + 数] = 数 < 长度 ? 字符值[数] : 0;
        大小列表[编号] = 大小;
        return 大小;
    }

    static void 条目列表() {
        for (int 数 = 0; 数 < 8; 数++) if (名称列列表[数 * 64] != 0) {
            for (int 槽条目 = 0; 槽条目 < 64 && 名称列列表[数 * 64 + 槽条目] != 0; 槽条目++) 字符终端.字符(名称列列表[数 * 64 + 槽条目]);
            字符终端.写入("  "); 字符终端.写入编号(大小列表[数]); 字符终端.写入("字节值\n");
        }
        字符终端.写入(存储设备连接.是否可用 ? "文件 8칸, 파일당 16384바이트; sync로 存储值 장치에 보존\n"
            : "临时值 文件 8칸, 파일당 16384바이트; 重试值 시작하면 사라짐\n");
    }

    static void 命令(int[] 输入值, int 运行, int 长度, int 动作) {
        while (运行 < 长度 && 输入值[运行] == ' ') 运行++;
        int 结尾 = 长度;
        while (结尾 > 运行 && 输入值[结尾 - 1] == ' ') 结尾--;
        int 数 = 结尾 - 运行;
        if (数 < 1 || 数 > 63) { 字符终端.写入("올바르지 않은 文件 名称\n"); return; }
        for (int 槽条目 = 0; 槽条目 < 64; 槽条目++) 名称[槽条目] = 槽条目 < 数 ? 输入值[运行 + 槽条目] : 0;
        int 编号 = 查找条目(名称, 数);
        if (编号 == -22) { 字符终端.写入("올바르지 않은 文件 名称\n"); return; }
        if (动作 == 0) {
            是否编辑中 = true; 编辑大小 = 0; 溢出值 = false;
            字符终端.写入("원문을 입력하세요. .save는 보존, .cancel은 취소합니다.\n");
        } else if (编号 < 0) 字符终端.写入("파일을 찾을 数 없습니다\n");
        else if (动作 == 1) {
            int 地址 = 设备.文件内存() + 编号 * 最大大小;
            for (int 槽条目 = 0; 槽条目 < 大小列表[编号]; 槽条目++) 字符终端.字符(设备.读取内存(地址 + 槽条目));
            字符终端.字符(10);
        } else { 名称列列表[编号 * 64] = 0; 大小列表[编号] = 0; 字符终端.写入("파일을 지웠습니다\n"); }
    }

    static boolean 是否精确(int[] 输入值, int 长度, String 短语值) {
        if (长度 != 短语值.length()) return false;
        for (int 槽条目 = 0; 槽条目 < 长度; 槽条目++) if (输入值[槽条目] != 短语值.charAt(槽条目)) return false;
        return true;
    }

    static void 已编辑行(int[] 输入值, int 长度, boolean 行溢出) {
        if (是否精确(输入值, 长度, ".cancel")) {
            是否编辑中 = false; 字符终端.写入("취소했습니다. 원래 파일은 그대로입니다\n");
        } else if (是否精确(输入值, 长度, ".save")) {
            是否编辑中 = false;
            if (溢出值) { 字符终端.写入("입력이 너무 깁니다. 원래 파일은 그대로입니다\n"); return; }
            int 数 = 0;
            while (数 < 64 && 名称[数] != 0) 数++;
            int 结果 = 存储值(名称, 数, 编辑值, 编辑大小);
            字符终端.写入(结果 >= 0 ? "보존한 字节值 数: " : "보존 失败值: ");
            字符终端.写入编号(结果); 字符终端.字符(10);
        } else if (行溢出 || 长度 + 1 > 最大大小 - 编辑大小) 溢出值 = true;
        else {
            for (int 数 = 0; 数 < 长度; 数++) 编辑值[编辑大小++] = 输入值[数];
            编辑值[编辑大小++] = 10;
        }
    }

    static void 用例(String 文件, String 内容值) {
        for (int 数 = 0; 数 < 64; 数++) 名称[数] = 数 < 文件.length() ? 文件.charAt(数) : 0;
        for (int 数 = 0; 数 < 内容值.length(); 数++) 编辑值[数] = 内容值.charAt(数);
        存储值(名称, 文件.length(), 编辑值, 内容值.length());
    }

    static void 准备() {
        用例("Hello.java", "public class Hello {\n public static void main(String[] args) {\n  System.out.println(\"Hello from jkoros JVM!\");\n  int sum = 0;\n  for (int i = 1; i <= 10; i++) { sum = sum + i; }\n  System.out.println(sum);\n }\n}\n");
        int 组值 = 设备.Java文件捆绑(), 大小 = 设备.Java文件捆绑大小();
        if (大小 < 8 || 执行管理.数(组值) != 0x464a4b4a) { 字符终端.写入("올바르지 않은 Java 文件 组值\n"); return; }
        int 项目个数 = 执行管理.数(组值 + 4);
        if (项目个数 < 0 || 项目个数 > 8 || 项目个数 > (大小 - 8) / 72) { 字符终端.写入("올바르지 않은 Java 文件 条目列表\n"); return; }
        for (int 数 = 0; 数 < 项目个数; 数++) {
            int 条目值 = 组值 + 8 + 数 * 72, 长度 = 0;
            for (int 槽条目 = 0; 槽条目 < 64; 槽条目++) 名称[槽条目] = 设备.读取内存(条目值 + 槽条目);
            while (长度 < 64 && 名称[长度] != 0) 长度++;
            int 位置 = 执行管理.数(条目值 + 64), 文件大小 = 执行管理.数(条目值 + 68);
            if (!检查名称(名称, 长度) || 文件大小 < 0 || 文件大小 > 最大大小 || 位置 < 8 + 项目个数 * 72 || 位置 > 大小 - 文件大小) {
                字符终端.写入("올바르지 않은 Java 文件 条目值\n"); return;
            }
            for (int 槽条目 = 0; 槽条目 < 文件大小; 槽条目++) 编辑值[槽条目] = 设备.读取内存(组值 + 位置 + 槽条目);
            if (存储值(名称, 长度, 编辑值, 文件大小) < 0) { 字符终端.写入("Java 파일을 가져오지 못했습니다\n"); return; }
        }
    }
}
