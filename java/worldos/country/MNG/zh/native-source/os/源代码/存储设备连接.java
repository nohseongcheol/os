/** 第一个 IDE 设备的 512 字节逻辑扇区；此层不格式化或擦除任意设备。 */
public final class 存储设备连接 {
    static boolean 是否可用 = false;
    static int[] 区段数据 = new int[512];
    static void 等待状态短暂地() {
        for (int 编号 = 0; 编号 < 4; 编号++) 设备.读取输入输出字节(0x3f6);
    }
    static int 等待状态直到就绪(boolean 数据必需) {
        int 运行 = 设备.毫秒();
        while (设备.毫秒() - 运行 < 500) {
            int 状态值 = 设备.读取输入输出字节(0x1f7);
            if (状态值 == 0 || 状态值 == 255) return -19;
            if ((状态值 & 128) == 0) {
                if ((状态值 & 33) != 0) return -5;
                if (!数据必需 || (状态值 & 8) != 0) return 0;
            }
            设备.挂起短暂地();
        }
        return -110;
    }
    static int 申请(int 区段值, int 命令) {
        if (区段值 < 0 || 区段值 >= 2048) return -22;
        设备.写入输入输出字节(0x3f6, 2); // 采用轮询，不使用 IDE IRQ。
        设备.写入输入输出字节(0x1f6, 0xe0); 等待状态短暂地();
        int 结果 = 等待状态直到就绪(false);
        if (结果 < 0) return 结果;
        设备.写入输入输出字节(0x1f2, 1);
        设备.写入输入输出字节(0x1f3, 区段值 & 255);
        设备.写入输入输出字节(0x1f4, (区段值 >>> 8) & 255);
        设备.写入输入输出字节(0x1f5, 0);
        设备.写入输入输出字节(0x1f7, 命令); 等待状态短暂地();
        return 等待状态直到就绪(true);
    }
    static int 读取(int 区段值) {
        int 结果 = 申请(区段值, 0x20);
        if (结果 < 0) return 结果;
        for (int 编号 = 0; 编号 < 256; 编号++) {
            int 值 = 设备.读取输入输出短整数(0x1f0);
            区段数据[编号 * 2] = 值 & 255; 区段数据[编号 * 2 + 1] = 值 >>> 8;
        }
        等待状态短暂地(); return 等待状态直到就绪(false);
    }
    static int 写入(int 区段值) {
        if (!是否可用 || 区段值 < 1 || 区段值 > 518) return -19;
        int 结果 = 申请(区段值, 0x30);
        if (结果 < 0) return 结果;
        for (int 编号 = 0; 编号 < 256; 编号++)
            设备.写入输入输出短整数(0x1f0, 区段数据[编号 * 2] | 区段数据[编号 * 2 + 1] << 8);
        等待状态短暂地(); return 等待状态直到就绪(false);
    }
    static int 冲刷输出() {
        if (!是否可用) return -19;
        设备.写入输入输出字节(0x1f7, 0xe7); 等待状态短暂地();
        return 等待状态直到就绪(false);
    }
    static int 解析整数(int 位置) {
        return 区段数据[位置] | 区段数据[位置 + 1] << 8 | 区段数据[位置 + 2] << 16 | 区段数据[位置 + 3] << 24;
    }
    static void 写入整数值(int 位置, int 值) {
        for (int 编号 = 0; 编号 < 4; 编号++) 区段数据[位置 + 编号] = (值 >>> (编号 * 8)) & 255;
    }
}
