/** 验证只读执行包内的 ELF32，传递参数，每次运行一个用户进程。 */
public final class 执行管理 {
    static final int 开始用户程序 = 0x04000000;
    static final int 用户结束 = 0x04400000;
    static final int 映像结束地址 = 0x04200000;
    static final int 参数开始 = 0x04300000;
    static int 参数个数 = 0;
    static int[] 参数地址 = new int[16];

    static boolean 裁剪(int 地址, int 长度) {
        return 地址 >= 开始用户程序 && 地址 < 用户结束 && 长度 >= 0 && 长度 <= 用户结束 - 地址;
    }

    static int 数(int 地址) { return 内存空间.解析整数(地址); }
    static int 短整数值(int 地址) { return 设备.读取内存(地址) | 设备.读取内存(地址 + 1) << 8; }
    static void 写入编号(int 地址, int 值) {
        for (int 编号 = 0; 编号 < 4; 编号++) 设备.写入内存(地址 + 编号, 值 >>> (编号 * 8));
    }

    static int 组个数() {
        int 地址 = 设备.可执行文件捆绑();
        int 大小 = 设备.可执行文件捆绑大小();
        if (大小 < 8 || 数(地址) != 0x50414b4a) return 0;
        int 项目个数 = 数(地址 + 4);
        return 项目个数 >= 0 && 项目个数 <= 32 && 项目个数 <= (大小 - 8) / 24 ? 项目个数 : 0;
    }

    static void 条目列表() {
        for (int 编号 = 0; 编号 < 组个数(); 编号++) {
            int 条目值 = 设备.可执行文件捆绑() + 8 + 编号 * 24;
            for (int 字符值 = 0; 字符值 < 16 && 设备.读取内存(条目值 + 字符值) != 0; 字符值++)
                字符终端.字符(设备.读取内存(条目值 + 字符值));
            字符终端.写入("\n");
        }
    }

    static int 查找条目(int[] 输入值, int 运行, int 长度) {
        if (长度 <= 0 || 长度 >= 16) return 0;
        for (int 编号 = 0; 编号 < 组个数(); 编号++) {
            int 条目值 = 设备.可执行文件捆绑() + 8 + 编号 * 24;
            boolean 相等文本 = 设备.读取内存(条目值 + 长度) == 0;
            for (int 字符值 = 0; 字符值 < 长度; 字符值++)
                if (输入值[运行 + 字符值] != 设备.读取内存(条目值 + 字符值)) 相等文本 = false;
            if (相等文本) return 条目值;
        }
        return 0;
    }

    static int 有效性校验(int 文件, int 长度) {
        if (长度 < 52 || 数(文件) != 0x464c457f || 设备.读取内存(文件 + 4) != 1
            || 设备.读取内存(文件 + 5) != 1 || 设备.读取内存(文件 + 6) != 1
            || 短整数值(文件 + 16) != 2 || 短整数值(文件 + 18) != 3 || 数(文件 + 20) != 1
            || 短整数值(文件 + 40) != 52 || 短整数值(文件 + 42) != 32) return -8;
        int 条目分值 = 数(文件 + 24);
        int 表位置 = 数(文件 + 28);
        int 项目个数 = 短整数值(文件 + 44);
        if (项目个数 == 0 || 项目个数 > 16 || 表位置 < 52 || 表位置 > 长度 - 项目个数 * 32) return -8;
        boolean 是否可执行文件 = false;
        for (int 编号 = 0; 编号 < 项目个数; 编号++) {
            int 表 = 文件 + 表位置 + 编号 * 32;
            int 种类值 = 数(表);
            if (种类值 == 2 || 种类值 == 3) return -8; // 不支持动态链接或解释器。
            if (种类值 != 1) continue;
            int 位置 = 数(表 + 4), 地址 = 数(表 + 8), 文件大小 = 数(表 + 16), 内存大小 = 数(表 + 20);
            int 对齐值 = 数(表 + 28);
            if (地址 < 开始用户程序 || 地址 >= 映像结束地址 || 内存大小 < 0 || 内存大小 > 映像结束地址 - 地址
                || 文件大小 < 0 || 文件大小 > 内存大小 || 位置 < 0 || (文件大小 > 0 && 位置 > 长度 - 文件大小)
                || (对齐值 != 0 && (对齐值 < 0 || (对齐值 & (对齐值 - 1)) != 0
                    || ((地址 - 位置) & (对齐值 - 1)) != 0))) return -8;
            for (int 前端值 = 0; 前端值 < 编号; 前端值++) {
                int 上一个项目 = 文件 + 表位置 + 前端值 * 32;
                if (数(上一个项目) == 1 && 内存大小 > 0 && 数(上一个项目 + 20) > 0
                    && 地址 < 数(上一个项目 + 8) + 数(上一个项目 + 20) && 数(上一个项目 + 8) < 地址 + 内存大小) return -8;
            }
            if ((数(表 + 24) & 1) != 0 && 条目分值 >= 地址 && 条目分值 - 地址 < 文件大小) 是否可执行文件 = true;
        }
        return 是否可执行文件 ? 条目分值 : -8;
    }

    static int 执行命令(int[] 输入值, int 运行, int 长度) {
        while (运行 < 长度 && 输入值[运行] == ' ') 运行++;
        int 结尾 = 运行;
        while (结尾 < 长度 && 输入值[结尾] != ' ') 结尾++;
        int 条目值 = 查找条目(输入值, 运行, 结尾 - 运行);
        if (条目值 == 0) return -2;
        int 位置 = 数(条目值 + 16), 大小 = 数(条目值 + 20);
        if (位置 < 8 + 组个数() * 24 || 大小 < 52 || 位置 > 设备.可执行文件捆绑大小() - 大小) return -8;
        int 文件 = 设备.可执行文件捆绑() + 位置;
        int 条目分值 = 有效性校验(文件, 大小);
        if (条目分值 < 0) return 条目分值;
        设备.用户清空内容();
        int 表位置 = 数(文件 + 28), 项目个数 = 短整数值(文件 + 44);
        for (int 编号 = 0; 编号 < 项目个数; 编号++) {
            int 表 = 文件 + 表位置 + 编号 * 32;
            if (数(表) != 1) continue;
            int 原始 = 文件 + 数(表 + 4), 目的地址值 = 数(表 + 8), 文件大小 = 数(表 + 16);
            for (int 字节值 = 0; 字节值 < 文件大小; 字节值++) 设备.写入内存(目的地址值 + 字节值, 设备.读取内存(原始 + 字节值));
        }
        参数个数 = 0;
        int 存储值 = 参数开始;
        while (结尾 < 长度) {
            while (结尾 < 长度 && 输入值[结尾] == ' ') 结尾++;
            if (结尾 == 长度) break;
            if (参数个数 == 参数地址.length) return -22;
            运行 = 结尾;
            while (结尾 < 长度 && 输入值[结尾] != ' ') 结尾++;
            参数地址[参数个数++] = 存储值;
            写入编号(存储值, 结尾 - 运行);
            for (int 字符值 = 运行; 字符值 < 结尾; 字符值++) 写入编号(存储值 + 4 + (字符值 - 运行) * 4, 输入值[字符值]);
            存储值 += 4 + (结尾 - 运行) * 4;
        }
        通信网络.清洁进程();
        文件描述符管理.开始进程();
        int 结果 = 设备.运行用户程序(条目分值, 用户结束 - 16);
        文件描述符管理.清洁进程();
        通信网络.清洁进程();
        return 结果;
    }
}
