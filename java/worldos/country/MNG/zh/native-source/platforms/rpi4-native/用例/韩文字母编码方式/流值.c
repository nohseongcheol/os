#include "网络ABI.h"

int 开始用户程序(int 实参) {
    (void)实参;
    struct 互联网套接字地址 地址 = {0};
    地址.地址族 = 互联网族;
    地址.端口编号 = 网络短整数(9260);
    地址.互联网地址.地址值 = 网络整数(环回地址);
    int 服务器值 = 创建端点(互联网族, 流网络, 流传输协议);
    if (服务器值 < 0 || 绑定地址(服务器值, (struct 套接字地址 *)&地址, sizeof(地址)) < 0 ||
        等待状态用于网络连接状态(服务器值, 4) < 0) return 1;
    if (接受网络连接状态(服务器值, 0, 0) != -1 || 错误编号 != 11) return 2;
    int 客户机值 = 创建端点(互联网族, 流网络, 流传输协议);
    if (客户机值 < 0 || 连接网络(客户机值, (struct 套接字地址 *)&地址, sizeof(地址)) < 0) return 3;
    int 连接 = 接受网络连接状态(服务器值, 0, 0);
    if (连接 < 0) return 4;
    unsigned char 项目目标侧发送[1500], 已接收项目[1500];
    for (int 数 = 0; 数 < 1500; 数++) 项目目标侧发送[数] = (unsigned char)数;
    int 已发送个数 = 0;
    while (已发送个数 < 1024) {
        int 长度 = 写入文件数据(客户机值, 项目目标侧发送 + 已发送个数, sizeof(项目目标侧发送) - 已发送个数);
        if (长度 <= 0) return 5;
        已发送个数 += 长度;
    }
    if (写入文件数据(客户机值, 项目目标侧发送, 1) != -1 || 错误编号 != 11) return 6;
    /* 상대가 닫아도 이미 도착한 자료를 构建全部 읽은 后端值 EOF가 된다. */
    关闭文件(客户机值);
    int 已接收个数 = 0;
    while (已接收个数 < 已发送个数) {
        int 长度 = 读取文件数据(连接, 已接收项目 + 已接收个数, sizeof(已接收项目) - 已接收个数);
        if (长度 <= 0) return 7;
        已接收个数 += 长度;
    }
    for (int 数 = 0; 数 < 已接收个数; 数++) if (已接收项目[数] != 项目目标侧发送[数]) return 8;
    if (读取文件数据(连接, 已接收项目, 1) != 0) return 9;
    if (写入文件数据(连接, 项目目标侧发送, 1) != -1 || 错误编号 != 32) return 10;
    关闭文件(连接); 关闭文件(服务器值);
    const char 结果[] = "C posix-kor 연결형 通信 PASS\n";
    写入文件数据(1, 结果, sizeof(结果) - 1);
    return 0;
}
