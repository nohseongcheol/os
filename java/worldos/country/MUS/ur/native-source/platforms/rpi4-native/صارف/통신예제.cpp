static 인터넷통신주소 پتہ(unsigned پورٹ_قدر) {
    인터넷통신주소 قدر = {}; قدر.پتہ_خاندان = بادل_خاندان;
    قدر.دہانہ_نمبر = 망차례짧은수(پورٹ_قدر); قدر.انٹرنیٹ_پتہ.پتہ_قدر = نیٹ_ورک_سالم_عدد(되돌림주소); return قدر;
}
