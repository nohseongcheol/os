#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 بائٹ_قدر 위치로 اپنا C 이름을 옮기는 일회성 이행 ٹولز.

외부 구조체의 멤버, سلک_قدر, C 표준 فعل_قدر, 이식 규약은 보존한다.
입력은 تبدیل_کریں_قدر 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

عکس_ڈالنا_روٹ = Path(__file__).resolve().parents[1]

def نفاذ_کریں_حکم():
    분석 = json.loads((عکس_ڈالنا_روٹ/'build/한국어화/시언어분석.json').read_text())
    if 분석['غلطی']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    نام_جدول = json.loads((عکس_ڈالنا_روٹ/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((عکس_ڈالنا_روٹ/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:نام_جدول[اندراج_قدر['نام']] for 고유,اندراج_قدر in 선언표.items()
                if اندراج_قدر['نام'] in نام_جدول and اندراج_قدر['نام'] not in 규격}
    رابطہ_جدول = {اندراج_قدر['نام']:نام_جدول[اندراج_قدر['نام']] for اندراج_قدر in 선언표.values()
              if اندراج_قدر.get('متصل_ہوں')==4 and اندراج_قدر['종류'] in (8,9)
              and اندراج_قدر['نام'] in نام_جدول and اندراج_قدر['نام'] not in 규격}
    # تخلیق_کرنا AOT C·어셈블리·공개 SDK가 공유하는 바이너리 متصل_ہوں 이름만 유지한다.
    머리 = ['/* اردو ماخذ_شجر 이름과 기존 مشین متصل_ہوں جاب_قدر. 자동 تخلیق_کرنا: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(رابطہ_جدول.items())]
    머리 += ['#endif','']
    (عکس_ڈالنا_روٹ/'명명/기계연결이름.h').write_text('\n'.join(머리))
    تبدیلیاں_فہرست = defaultdict(dict)
    for فائل_کا_نام,آفسٹ_قدر,نام,고유 in 분석['حوالہ_جات']:
        if 고유 in 바꿀선언:
            تبدیلیاں_فہرست[فائل_کا_نام][آفسٹ_قدر] = (نام,바꿀선언[고유])
    لاگ_صف = ['فائل_کا_نام\t원래바이트위치\t이전이름\t한국어이름']
    نظر_انداز_کریں_قدر = []
    for فائل_کا_نام,تبدیل_کریں_قدر in تبدیلیاں_فہرست.items():
        راستہ_2 = Path(فائل_کا_نام); 원본 = راستہ_2.read_bytes(); کوائف = 원본
        for آفسٹ_قدر,(옛이름,새이름) in sorted(تبدیل_کریں_قدر.items(),reverse=True):
            끝 = آفسٹ_قدر+len(옛이름.encode())
            if 원본[آفسٹ_قدر:끝] != 옛이름.encode():
                نظر_انداز_کریں_قدر.append((str(راستہ_2.relative_to(عکس_ڈالنا_روٹ)),آفسٹ_قدر,옛이름));continue
            کوائف = کوائف[:آفسٹ_قدر]+새이름.encode()+کوائف[끝:]
            لاگ_صف.append('{}\t{}\t{}\t{}'.format(راستہ_2.relative_to(عکس_ڈالنا_روٹ),آفسٹ_قدر,옛이름,새이름))
        راستہ_2.write_bytes(کوائف)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    میکرو_قدر = {اندراج_قدر['نام']:نام_جدول[اندراج_قدر['نام']] for اندراج_قدر in 선언표.values()
              if اندراج_قدر['종류']==501 and اندراج_قدر['نام'] in نام_جدول and اندراج_قدر['نام'] not in 규격}
    for راستہ_2 in sorted({Path(اندراج_قدر['فائل_کا_نام']) for اندراج_قدر in 선언표.values()}):
        لائن_فہرست = راستہ_2.read_text().splitlines(True); 이어짐 = False
        for اشاریہ,اندراج_کی_سطر in enumerate(لائن_فہرست):
            전처리 = 이어짐 or bool(re.match(r'\s*#',اندراج_کی_سطر))
            이어짐 = 전처리 and اندراج_کی_سطر.rstrip().endswith('\\')
            if 전처리:
                لُک_اپ_جدول = نام_جدول if re.match(r'\s*#\s*define\b',اندراج_کی_سطر) or 이어짐 else میکرو_قدر
                لائن_فہرست[اشاریہ] = 낱말.sub(lambda 맞음: لُک_اپ_جدول.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],اندراج_کی_سطر)
        راستہ_2.write_text(''.join(لائن_فہرست))
    # 각 اپنا ترجمہ_ماخذ 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for راستہ_2 in sorted({Path(اندراج_قدر['فائل_کا_نام']) for اندراج_قدر in 선언표.values()}):
        if راستہ_2.suffix not in ('.c','.cpp'):continue
        ساتھی_قدر = '../' * len(راستہ_2.relative_to(عکس_ڈالنا_روٹ).parts[:-1]) + '명명/기계연결이름.h'
        راستہ_2.write_text('#include "'+ساتھی_قدر+'"\n'+راستہ_2.read_text())
    (عکس_ڈالنا_روٹ/'명명/시언어이름대응.tsv').write_text('\n'.join(لاگ_صف)+'\n')
    (عکس_ڈالنا_روٹ/'build/한국어화/전처리참조.json').write_text(json.dumps(نظر_انداز_کریں_قدر,ensure_ascii=False,indent=2)+'\n')
    print('تبدیل_کریں_قدر',len(لاگ_صف)-1,'전처리 재검토',len(نظر_انداز_کریں_قدر),'مشین متصل_ہوں',len(رابطہ_جدول))

if __name__=='__main__': نفاذ_کریں_حکم()
