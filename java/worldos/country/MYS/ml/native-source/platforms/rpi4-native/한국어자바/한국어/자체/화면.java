package 한국어.자체;
/** 화면(畫面): 부팅 때 선택한 크기의 자체 കെര്_ണല്_മൂല്യം RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int മൂല്യം = കെര്_ണല്_മൂല്യം.화면너비(); if (മൂല്യം < 0) throw new അവസ്ഥ_ഒഴിവാക്കൽ("프레임버퍼 없음"); return മൂല്യം; }
    public static int 높이() { int മൂല്യം = കെര്_ണല്_മൂല്യം.화면높이(); if (മൂല്യം < 0) throw new അവസ്ഥ_ഒഴിവാക്കൽ("프레임버퍼 없음"); return മൂല്യം; }
    public static void 사각형(int 가로, int ലംബം_പദവി, int 폭, int 높이, int 색) {
        if (가로 < 0 || ലംബം_പദവി < 0 || 폭 < 0 || 높이 < 0 || 가로 > 너비() || ലംബം_പദവി > 높이() || 폭 > 너비() - 가로 || 높이 > 높이() - ലംബം_പദവി) throw new അസാധുവായ_ആര്_ഗ്യുമെന്_റ്_ഒഴിവാക്കൽ("화면 ക്ലിപ്പ്");
        if (കെര്_ണല്_മൂല്യം.사각형(가로, ലംബം_പദവി, 폭, 높이, 색) < 0) throw new അവസ്ഥ_ഒഴിവാക്കൽ("프레임버퍼 없음");
    }
    public static void മായ്ക്കുക_എന്_ട്രി(int 색) { 사각형(0, 0, 너비(), 높이(), 색); }
    public static void 기다리기() { if (കെര്_ണല്_മൂല്യം.그림대기() < 0) throw new അവസ്ഥ_ഒഴിവാക്കൽ("ഇടപെടാനുതകുന്ന 입력 필요"); }
}
