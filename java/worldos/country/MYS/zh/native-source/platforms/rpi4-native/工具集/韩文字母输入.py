"""Two-set Hangul composition for the native VNC-to-UART input bridge.

The pending character is visible in the guest editor. Replacing it uses that
editor's UTF-8 Backspace, so commit before cursor motion, shortcuts or a click.
No host input-method daemon or third-party Python package is required.
"""

初始字母构件表 = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
中声字母构件表 = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
最终字母构件表 = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'
键导航 = dict(zip('rRseEfaqQtTdwWczxvgkoiOjpuPhynbml',
                'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎㅏㅐㅑㅒㅓㅔㅕㅖㅗㅛㅜㅠㅡㅣ'))
复合中声字母构件 = {('ㅗ','ㅏ'):'ㅘ',('ㅗ','ㅐ'):'ㅙ',('ㅗ','ㅣ'):'ㅚ',
          ('ㅜ','ㅓ'):'ㅝ',('ㅜ','ㅔ'):'ㅞ',('ㅜ','ㅣ'):'ㅟ',('ㅡ','ㅣ'):'ㅢ'}
复合最终字母构件 = {('ㄱ','ㅅ'):'ㄳ',('ㄴ','ㅈ'):'ㄵ',('ㄴ','ㅎ'):'ㄶ',
          ('ㄹ','ㄱ'):'ㄺ',('ㄹ','ㅁ'):'ㄻ',('ㄹ','ㅂ'):'ㄼ',('ㄹ','ㅅ'):'ㄽ',
          ('ㄹ','ㅌ'):'ㄾ',('ㄹ','ㅍ'):'ㄿ',('ㄹ','ㅎ'):'ㅀ',('ㅂ','ㅅ'):'ㅄ'}
分割最终字母构件 = {值: 一一对 for 一一对,值 in 复合最终字母构件.items()}


class 合成韩文字母:
    def __init__(自身值, 发送):
        自身值.发送 = 发送
        自身值.提交合成状态()

    def 提交合成状态(自身值):
        自身值.状态代码 = ('','','')
        自身值.历史记录 = []

    def 文本(自身值):
        初始字母构件,中声字母构件,最终字母构件 = 自身值.状态代码
        if 初始字母构件 and 中声字母构件:
            return chr(0xac00 + (初始字母构件表.index(初始字母构件)*21 + 中声字母构件表.index(中声字母构件))*28
                       + (最终字母构件表.index(最终字母构件) if 最终字母构件 else 0))
        return 初始字母构件 or 中声字母构件

    def 退格(自身值):
        if not 自身值.历史记录:
            return False
        自身值.状态代码 = 自身值.历史记录.pop()
        自身值.发送(b'\x7f' + 自身值.文本().encode('utf-8'))
        return True

    def 供给键(自身值, 已按下值):
        字符数据 = 键导航.get(已按下值, 键导航.get(已按下值.lower()))
        if 字符数据 is None:
            return False
        上一个项目 = 自身值.文本()
        初始字母构件,中声字母构件,最终字母构件 = 自身值.状态代码
        历史记录 = 自身值.历史记录 + [自身值.状态代码]
        已提交 = ''
        if 字符数据 in 初始字母构件表:
            if 初始字母构件 and 中声字母构件 and not 最终字母构件 and 字符数据 in 最终字母构件表:
                最终字母构件 = 字符数据
            elif 最终字母构件 and (最终字母构件,字符数据) in 复合最终字母构件:
                最终字母构件 = 复合最终字母构件[最终字母构件,字符数据]
            else:
                已提交 = 上一个项目
                初始字母构件,中声字母构件,最终字母构件 = 字符数据,'',''
                历史记录 = [('','','')]
        elif 最终字母构件:
            左侧,右 = 分割最终字母构件.get(最终字母构件, ('',最终字母构件))
            自身值.状态代码 = 初始字母构件,中声字母构件,左侧
            已提交 = 自身值.文本()
            初始字母构件,中声字母构件,最终字母构件 = 右,字符数据,''
            历史记录 = [('','',''),(右,'','')]
        elif 中声字母构件:
            if (中声字母构件,字符数据) in 复合中声字母构件:
                中声字母构件 = 复合中声字母构件[中声字母构件,字符数据]
            else:
                已提交 = 上一个项目
                初始字母构件,中声字母构件,最终字母构件 = '',字符数据,''
                历史记录 = [('','','')]
        else:
            中声字母构件 = 字符数据
        自身值.状态代码 = 初始字母构件,中声字母构件,最终字母构件
        自身值.历史记录 = 历史记录
        自身值.发送((b'\x7f' if 上一个项目 else b'') + (已提交+自身值.文本()).encode('utf-8'))
        return True
