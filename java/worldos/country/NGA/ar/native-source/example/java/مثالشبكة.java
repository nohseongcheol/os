import العربية.ذاتي.صديق;
import العربية.ذاتي.실행인수;
import العربية.ذاتي.مخطط_بيانات_قناة;
import العربية.ذاتي.문자;
import العربية.ذاتي.مخرجات;
import العربية.ذاتي.검사;
import العربية.ذاتي.تدفق_المدخلات;
import العربية.ذاتي.إدخال_إخراج_استثناء;

public class مثالشبكة {
    public static void تشغيل() throws إدخال_إخراج_استثناء {
        // مضيف: python3 أدوات/예제되돌림.py --tcp-port 9000 --udp-port 9001
        صديق اتصال = صديق.فتح("10.0.2.2", 문자.يوزّع_عدد_صحيح(실행인수.نص(0)));
        try {
            اتصال.대기시간(700);
            byte[] رسالة = 문자.يرمّز("JAVA TCP ar\n");
            اتصال.مخرجات().كتابة(رسالة);
            تدفق_المدخلات إدخال_قيمة = اتصال.إدخال_قيمة();
            for (int رقم = 0; رقم < 문자.바이트수(رسالة); رقم++) {
                검사.참인지(إدخال_قيمة.قراءة() == (رسالة[رقم] & 255), "TCP رد 불일치");
            }
        } finally { اتصال.إغلاق(); }
        مخطط_بيانات_قناة المشارك = مخطط_بيانات_قناة.فتح(0);
        try {
            المشارك.대기시간(700);
            المشارك.يرسل("10.0.2.2", 문자.يوزّع_عدد_صحيح(실행인수.نص(1)), "JAVA UDP ar");
            검사.참인지(문자.같음(المشارك.يستلم(), "JAVA UDP ar"), "UDP رد 불일치");
        } finally { المشارك.إغلاق(); }
        مخرجات.كتابة_خط("JAVA 네트워크 يتحقق: TCP UDP ar");
    }
}
