/** পড়া 전용 কার্যকর_করুন_আদেশ 묶음의 ELF32 বৈধ_করুন, আর্গুমেন্ট_তালিকা ফরোয়ার্ড_মান, 한 번에 한 ব্যবহারকারী প্রসেসর_মান কার্যকর_করুন_আদেশ. */
public final class 실행관리 {
    static final int শুরু_ব্যবহারকারী_অ্যাপ = 0x04000000;
    static final int ব্যবহারকারী_শেষ_করা = 0x04400000;
    static final int ছবি_শেষ_করা_ইমেইল = 0x04200000;
    static final int যুক্তি_শুরু = 0x04300000;
    static int 인수수 = 0;
    static int[] যুক্তি_ইমেইল = new int[16];

    static boolean ক্লিপ(int ইমেইল, int দৈর্ঘ্য_মান) {
        return ইমেইল >= শুরু_ব্যবহারকারী_অ্যাপ && ইমেইল < ব্যবহারকারী_শেষ_করা && দৈর্ঘ্য_মান >= 0 && দৈর্ঘ্য_মান <= ব্যবহারকারী_শেষ_করা - ইমেইল;
    }

    static int 수(int ইমেইল) { return 기억공간.বিভাজন_করা_পূর্ণসংখ্যা(ইমেইল); }
    static int 짧은수(int ইমেইল) { return ডিভাইস_মান.기억읽기(ইমেইল) | ডিভাইস_মান.기억읽기(ইমেইল + 1) << 8; }
    static void 수쓰기(int ইমেইল, int মান) {
        for (int সূচি = 0; সূচি < 4; সূচি++) ডিভাইস_মান.লেখা_মেমরি(ইমেইল + সূচি, মান >>> (সূচি * 8));
    }

    static int 묶음개수() {
        int ইমেইল = ডিভাইস_মান.실행묶음();
        int আকার = ডিভাইস_মান.실행묶음크기();
        if (আকার < 8 || 수(ইমেইল) != 0x50414b4a) return 0;
        int 개수 = 수(ইমেইল + 4);
        return 개수 >= 0 && 개수 <= 32 && 개수 <= (আকার - 8) / 24 ? 개수 : 0;
    }

    static void ভুক্তি_তালিকা() {
        for (int সূচি = 0; সূচি < 묶음개수(); সূচি++) {
            int ভুক্তি_মান = ডিভাইস_মান.실행묶음() + 8 + সূচি * 24;
            for (int অক্ষর_মান = 0; অক্ষর_মান < 16 && ডিভাইস_মান.기억읽기(ভুক্তি_মান + অক্ষর_মান) != 0; অক্ষর_মান++)
                পাঠ_টার্মিনাল.문자(ডিভাইস_মান.기억읽기(ভুক্তি_মান + অক্ষর_মান));
            পাঠ_টার্মিনাল.লেখা("\n");
        }
    }

    static int খোঁজা_ভুক্তি(int[] 입력, int চালনা, int দৈর্ঘ্য_মান) {
        if (দৈর্ঘ্য_মান <= 0 || দৈর্ঘ্য_মান >= 16) return 0;
        for (int সূচি = 0; সূচি < 묶음개수(); সূচি++) {
            int ভুক্তি_মান = ডিভাইস_মান.실행묶음() + 8 + সূচি * 24;
            boolean 같음 = ডিভাইস_মান.기억읽기(ভুক্তি_মান + দৈর্ঘ্য_মান) == 0;
            for (int অক্ষর_মান = 0; অক্ষর_মান < দৈর্ঘ্য_মান; অক্ষর_মান++)
                if (입력[চালনা + অক্ষর_মান] != ডিভাইস_মান.기억읽기(ভুক্তি_মান + অক্ষর_মান)) 같음 = false;
            if (같음) return ভুক্তি_মান;
        }
        return 0;
    }

    static int বৈধ_করুন(int নথির_নাম, int দৈর্ঘ্য_মান) {
        if (দৈর্ঘ্য_মান < 52 || 수(নথির_নাম) != 0x464c457f || ডিভাইস_মান.기억읽기(নথির_নাম + 4) != 1
            || ডিভাইস_মান.기억읽기(নথির_নাম + 5) != 1 || ডিভাইস_মান.기억읽기(নথির_নাম + 6) != 1
            || 짧은수(নথির_নাম + 16) != 2 || 짧은수(নথির_নাম + 18) != 3 || 수(নথির_নাম + 20) != 1
            || 짧은수(নথির_নাম + 40) != 52 || 짧은수(নথির_নাম + 42) != 32) return -8;
        int ভুক্তি_বিন্দু_মান = 수(নথির_নাম + 24);
        int সারণি_পদ = 수(নথির_নাম + 28);
        int 개수 = 짧은수(নথির_নাম + 44);
        if (개수 == 0 || 개수 > 16 || সারণি_পদ < 52 || সারণি_পদ > দৈর্ঘ্য_মান - 개수 * 32) return -8;
        boolean 실행가능 = false;
        for (int সূচি = 0; সূচি < 개수; সূচি++) {
            int লুকআপ_সারণি = নথির_নাম + সারণি_পদ + সূচি * 32;
            int 종류 = 수(লুকআপ_সারণি);
            if (종류 == 2 || 종류 == 3) return -8; // 동적 সংযোগ_স্থাপনা/পার্সার_48ee4b1b 미지원
            if (종류 != 1) continue;
            int অবস্থান = 수(লুকআপ_সারণি + 4), ইমেইল = 수(লুকআপ_সারণি + 8), ফাইল_আয়তন = 수(লুকআপ_সারণি + 16), মেমরি_আয়তন = 수(লুকআপ_সারণি + 20);
            int সারিকরণ_করা_মান = 수(লুকআপ_সারণি + 28);
            if (ইমেইল < শুরু_ব্যবহারকারী_অ্যাপ || ইমেইল >= ছবি_শেষ_করা_ইমেইল || মেমরি_আয়তন < 0 || মেমরি_আয়তন > ছবি_শেষ_করা_ইমেইল - ইমেইল
                || ফাইল_আয়তন < 0 || ফাইল_আয়তন > মেমরি_আয়তন || অবস্থান < 0 || (ফাইল_আয়তন > 0 && অবস্থান > দৈর্ঘ্য_মান - ফাইল_আয়তন)
                || (সারিকরণ_করা_মান != 0 && (সারিকরণ_করা_মান < 0 || (সারিকরণ_করা_মান & (সারিকরণ_করা_মান - 1)) != 0
                    || ((ইমেইল - অবস্থান) & (সারিকরণ_করা_মান - 1)) != 0))) return -8;
            for (int সম্মুখ_মান = 0; সম্মুখ_মান < সূচি; সম্মুখ_মান++) {
                int 이전 = নথির_নাম + সারণি_পদ + সম্মুখ_মান * 32;
                if (수(이전) == 1 && মেমরি_আয়তন > 0 && 수(이전 + 20) > 0
                    && ইমেইল < 수(이전 + 8) + 수(이전 + 20) && 수(이전 + 8) < ইমেইল + মেমরি_আয়তন) return -8;
            }
            if ((수(লুকআপ_সারণি + 24) & 1) != 0 && ভুক্তি_বিন্দু_মান >= ইমেইল && ভুক্তি_বিন্দু_মান - ইমেইল < ফাইল_আয়তন) 실행가능 = true;
        }
        return 실행가능 ? ভুক্তি_বিন্দু_মান : -8;
    }

    static int কার্যকর_করুন_আদেশ(int[] 입력, int চালনা, int দৈর্ঘ্য_মান) {
        while (চালনা < দৈর্ঘ্য_মান && 입력[চালনা] == ' ') চালনা++;
        int 끝 = চালনা;
        while (끝 < দৈর্ঘ্য_মান && 입력[끝] != ' ') 끝++;
        int ভুক্তি_মান = খোঁজা_ভুক্তি(입력, চালনা, 끝 - চালনা);
        if (ভুক্তি_মান == 0) return -2;
        int অবস্থান = 수(ভুক্তি_মান + 16), আকার = 수(ভুক্তি_মান + 20);
        if (অবস্থান < 8 + 묶음개수() * 24 || আকার < 52 || অবস্থান > ডিভাইস_মান.실행묶음크기() - আকার) return -8;
        int নথির_নাম = ডিভাইস_মান.실행묶음() + অবস্থান;
        int ভুক্তি_বিন্দু_মান = বৈধ_করুন(নথির_নাম, আকার);
        if (ভুক্তি_বিন্দু_মান < 0) return ভুক্তি_বিন্দু_মান;
        ডিভাইস_মান.ব্যবহারকারী_মুছে_দিন_সূচী();
        int সারণি_পদ = 수(নথির_নাম + 28), 개수 = 짧은수(নথির_নাম + 44);
        for (int সূচি = 0; সূচি < 개수; সূচি++) {
            int লুকআপ_সারণি = নথির_নাম + সারণি_পদ + সূচি * 32;
            if (수(লুকআপ_সারণি) != 1) continue;
            int 원본 = নথির_নাম + 수(লুকআপ_সারণি + 4), গন্তব্য_মান = 수(লুকআপ_সারণি + 8), ফাইল_আয়তন = 수(লুকআপ_সারণি + 16);
            for (int বাইট_মান = 0; বাইট_মান < ফাইল_আয়তন; বাইট_মান++) ডিভাইস_মান.লেখা_মেমরি(গন্তব্য_মান + বাইট_মান, ডিভাইস_মান.기억읽기(원본 + বাইট_মান));
        }
        인수수 = 0;
        int ভাণ্ডার_মান = যুক্তি_শুরু;
        while (끝 < দৈর্ঘ্য_মান) {
            while (끝 < দৈর্ঘ্য_মান && 입력[끝] == ' ') 끝++;
            if (끝 == দৈর্ঘ্য_মান) break;
            if (인수수 == যুক্তি_ইমেইল.length) return -22;
            চালনা = 끝;
            while (끝 < দৈর্ঘ্য_মান && 입력[끝] != ' ') 끝++;
            যুক্তি_ইমেইল[인수수++] = ভাণ্ডার_মান;
            수쓰기(ভাণ্ডার_মান, 끝 - চালনা);
            for (int অক্ষর_মান = চালনা; অক্ষর_মান < 끝; অক্ষর_মান++) 수쓰기(ভাণ্ডার_মান + 4 + (অক্ষর_মান - চালনা) * 4, 입력[অক্ষর_মান]);
            ভাণ্ডার_মান += 4 + (끝 - চালনা) * 4;
        }
        নেটওয়ার্ক_গাদা.পরিষ্কার_করুন_প্রসেসর();
        파일서술자관리.শুরু_প্রসেসর();
        int পরিমাপ = ডিভাইস_মান.রান_ব্যবহারকারী_অ্যাপ(ভুক্তি_বিন্দু_মান, ব্যবহারকারী_শেষ_করা - 16);
        파일서술자관리.পরিষ্কার_করুন_প্রসেসর();
        নেটওয়ার্ক_গাদা.পরিষ্কার_করুন_প্রসেসর();
        return পরিমাপ;
    }
}
