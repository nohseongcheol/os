#include "호출경계.h"
extern int main(int 인수개수, char **যুক্তি_তালিকা);
static char যুক্তি_মেমরি[2048];
static char *যুক্তি_তালিকা[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 কার্যকর_করুন_আদেশ 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    যুক্তি_তালিকা[0] = "jkoros-app";
    int অবস্থান = 0;
    for (int সূচি = 0; সূচি < 개수; সূচি++) {
        const int *원본 = (const int *)jkoros_syscall(3, সূচি, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        যুক্তি_তালিকা[সূচি + 1] = যুক্তি_মেমরি + অবস্থান;
        for (int স্লট_ভুক্তি = 0; স্লট_ভুক্তি < 원본[0]; স্লট_ভুক্তি++) {
            if (অবস্থান >= 2047) return 126;
            যুক্তি_মেমরি[অবস্থান++] = 원본[স্লট_ভুক্তি + 1];
        }
        যুক্তি_মেমরি[অবস্থান++] = 0;
    }
    যুক্তি_তালিকা[개수 + 1] = 0;
    return main(개수 + 1, যুক্তি_তালিকা);
}
