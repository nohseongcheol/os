#!/usr/bin/env python3
"""গঠন_সিস্টেম 변환이 বাংলা স্ট্রিং_মান, 주석, 헤더 경로를 바꾸지 않는지 검사한다."""
from 식별자변환 import 변환

উৎস_নথি = '''#include <파일규약.h>
#include "통신규약.h"
// খোলা_ফাইল 라는 주석
/* 자료이름 */
const char *ফাইল_ভুক্তি_নাম = "한글 \\" স্ট্রিং_মান";
char অক্ষর_মান = '가';
int 파일열기_횟수 = 1;
'''
নির্গম = 변환(উৎস_নথি)
assert '#include <파일규약.h>' in নির্গম
assert '#include "통신규약.h"' in নির্গম
assert '// খোলা_ফাইল 라는 주석' in নির্গম
assert '/* 자료이름 */' in নির্গম
assert '"한글 \\" স্ট্রিং_মান"' in নির্গম
assert "'가'" in নির্গম
assert '\\ud30c\\uc77c\\uc774\\ub984' in নির্গম
assert '파일열기_횟수' not in নির্গম
assert 변환(নির্গম) == নির্গম
print('PASS: বাংলা সনাক্তকারী_মান 변환/স্ট্রিং_মান·주석·পথ_2 보존')
