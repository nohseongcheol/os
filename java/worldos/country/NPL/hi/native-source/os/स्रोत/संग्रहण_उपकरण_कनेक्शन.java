/** 첫 IDE 장치의 512바이트 논리 खंड_मान. 이 계층은 포맷을 만들거나 임의 장치를 지우지 않는다. */
public final class संग्रहण_उपकरण_कनेक्शन {
    static boolean सूचना_प्रौद्योगिकी_उपलब्ध = false;
    static int[] खंड_डेटा = new int[512];
    static void 잠깐기다리기() {
        for (int इंडेक्स = 0; इंडेक्स < 4; इंडेक्स++) उपकरण_मान.입출력바이트읽기(0x3f6);
    }
    static int 준비기다리기(boolean 자료필요) {
        int चलाएँ = उपकरण_मान.밀리초();
        while (उपकरण_मान.밀리초() - चलाएँ < 500) {
            int अवस्था_मान = उपकरण_मान.입출력바이트읽기(0x1f7);
            if (अवस्था_मान == 0 || अवस्था_मान == 255) return -19;
            if ((अवस्था_मान & 128) == 0) {
                if ((अवस्था_मान & 33) != 0) return -5;
                if (!자료필요 || (अवस्था_मान & 8) != 0) return 0;
            }
            उपकरण_मान.잠시양보();
        }
        return -110;
    }
    static int अनुरोध(int खंड_मान, int आदेश) {
        if (खंड_मान < 0 || खंड_मान >= 2048) return -22;
        उपकरण_मान.입출력바이트쓰기(0x3f6, 2); // polling; IDE IRQ 사용 안 함
        उपकरण_मान.입출력바이트쓰기(0x1f6, 0xe0); 잠깐기다리기();
        int परिणाम = 준비기다리기(false);
        if (परिणाम < 0) return परिणाम;
        उपकरण_मान.입출력바이트쓰기(0x1f2, 1);
        उपकरण_मान.입출력바이트쓰기(0x1f3, खंड_मान & 255);
        उपकरण_मान.입출력바이트쓰기(0x1f4, (खंड_मान >>> 8) & 255);
        उपकरण_मान.입출력바이트쓰기(0x1f5, 0);
        उपकरण_मान.입출력바이트쓰기(0x1f7, आदेश); 잠깐기다리기();
        return 준비기다리기(true);
    }
    static int पढ़ें(int खंड_मान) {
        int परिणाम = अनुरोध(खंड_मान, 0x20);
        if (परिणाम < 0) return परिणाम;
        for (int इंडेक्स = 0; इंडेक्स < 256; इंडेक्स++) {
            int मान = उपकरण_मान.입출력짧은수읽기(0x1f0);
            खंड_डेटा[इंडेक्स * 2] = मान & 255; खंड_डेटा[इंडेक्स * 2 + 1] = मान >>> 8;
        }
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int लिखें(int खंड_मान) {
        if (!सूचना_प्रौद्योगिकी_उपलब्ध || खंड_मान < 1 || खंड_मान > 518) return -19;
        int परिणाम = अनुरोध(खंड_मान, 0x30);
        if (परिणाम < 0) return परिणाम;
        for (int इंडेक्स = 0; इंडेक्स < 256; इंडेक्स++)
            उपकरण_मान.입출력짧은수쓰기(0x1f0, खंड_डेटा[इंडेक्स * 2] | खंड_डेटा[इंडेक्स * 2 + 1] << 8);
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int 밀어쓰기() {
        if (!सूचना_प्रौद्योगिकी_उपलब्ध) return -19;
        उपकरण_मान.입출력바이트쓰기(0x1f7, 0xe7); 잠깐기다리기();
        return 준비기다리기(false);
    }
    static int पार्स_करें_पूर्णांक(int स्थान) {
        return खंड_डेटा[स्थान] | खंड_डेटा[स्थान + 1] << 8 | खंड_डेटा[स्थान + 2] << 16 | खंड_डेटा[स्थान + 3] << 24;
    }
    static void लिखना_पूर्णांक_मान(int स्थान, int मान) {
        for (int इंडेक्स = 0; इंडेक्स < 4; इंडेक्स++) खंड_डेटा[स्थान + इंडेक्स] = (मान >>> (इंडेक्स * 8)) & 255;
    }
}
