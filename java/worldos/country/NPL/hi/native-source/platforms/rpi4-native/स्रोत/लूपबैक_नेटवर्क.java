/** 첫 네트워크 लेयर_मान: 단일 कर्नेल_मान 안의 IPv4/UDP 루프백 हस्तांतरण_मान.
 * बाहरी_मान IP는 ENETUNREACH. Ethernet/IP 패킷 드라이버를 대신한다고 표시하지 않는다.
 * समाप्त_करें_अंक 8개, 끝점당 स्वतंत्रसंदेश 4개, 전문당 512바이트. 모든 호출은 비차단이다.
 */
public final class लूपबैक_नेटवर्क {
    static int[] 사용 = new int[8];
    static int[] पोर्ट_मान = new int[8];
    static int[] पता = new int[8];
    static int[] सामने_मान = new int[8];
    static int[] 개수 = new int[8];
    static int[] 받은창구 = new int[8];
    static int[] 길이 = new int[32];
    static int[] 보낸창구 = new int[32];
    static int[] आँकड़े = new int[32 * 512];
    static int[] आगे_मान = new int[512];
    static int अगला_एंडपॉइंट = 49152;
    static int सत्यापित_करें(int इंडेक्स) { return इंडेक्स >= 32 && इंडेक्स < 40 && 사용[इंडेक्स - 32] != 0 ? इंडेक्स - 32 : -1; }
    static boolean 겹침(int इंडेक्स) {
        for (int 칸 = 0; 칸 < 8; 칸++) if (사용[칸] != 0 && पोर्ट_मान[칸] == इंडेक्स) return true;
        return false;
    }
    static int 임시창구() {
        for (int 시도 = 0; 시도 < 16; 시도++) {
            int 후보 = अगला_एंडपॉइंट++;
            if (अगला_एंडपॉइंट > 65535) अगला_एंडपॉइंट = 49152;
            if (!겹침(후보)) return 후보;
        }
        return -98;
    }
    public static int बनाएँ_एन्ट्री(int क्षेत्र_मान, int 종류, int मामला_मान) {
        if (क्षेत्र_मान != 2) return -97;
        if (종류 != 2 || (मामला_मान != 0 && मामला_मान != 17)) return -93;
        for (int 칸 = 0; 칸 < 8; 칸++) if (사용[칸] == 0) {
            사용[칸] = 1; पोर्ट_मान[칸] = 0; पता[칸] = 0; सामने_मान[칸] = 0; 개수[칸] = 0; 받은창구[칸] = 0;
            return 칸 + 32;
        }
        return -24;
    }
    public static int बाइंड_करें_एंडपॉइंट(int इंडेक्स, int नेटवर्क_पता, int एंडपॉइंट_पोर्ट_संख्या) {
        int 칸 = सत्यापित_करें(इंडेक्स);
        if (칸 < 0) return -9;
        if (नेटवर्क_पता != 0 && नेटवर्क_पता != 0x7f000001) return -99;
        if (पोर्ट_मान[칸] != 0 || एंडपॉइंट_पोर्ट_संख्या < 0 || एंडपॉइंट_पोर्ट_संख्या > 65535) return -22;
        if (एंडपॉइंट_पोर्ट_संख्या == 0) एंडपॉइंट_पोर्ट_संख्या = 임시창구();
        if (एंडपॉइंट_पोर्ट_संख्या < 0) return एंडपॉइंट_पोर्ट_संख्या;
        if (겹침(एंडपॉइंट_पोर्ट_संख्या)) return -98;
        पोर्ट_मान[칸] = एंडपॉइंट_पोर्ट_संख्या; पता[칸] = नेटवर्क_पता; return 0;
    }
    public static int 자료넣기(int इंडेक्स, int मान) {
        if (इंडेक्स < 0 || इंडेक्स >= 512) return -22;
        आगे_मान[इंडेक्स] = मान & 255; return 0;
    }
    public static int पढें_डेटा(int इंडेक्स) { return इंडेक्स >= 0 && इंडेक्स < 512 ? आगे_मान[इंडेक्स] : -22; }
    public static int भेजें(int इंडेक्स, int नेटवर्क_पता, int एंडपॉइंट_पोर्ट_संख्या, int आकार) {
        int 칸 = सत्यापित_करें(इंडेक्स);
        if (칸 < 0) return -9;
        if (नेटवर्क_पता != 0x7f000001) return -101;
        if (एंडपॉइंट_पोर्ट_संख्या < 1 || एंडपॉइंट_पोर्ट_संख्या > 65535) return -22;
        if (आकार < 0 || आकार > 512) return -90;
        if (पोर्ट_मान[칸] == 0) {
            int परिणाम = बाइंड_करें_एंडपॉइंट(इंडेक्स, 0x7f000001, 0);
            if (परिणाम < 0) return परिणाम;
        }
        int गंतव्य_मान = -1;
        for (int 후보 = 0; 후보 < 8; 후보++) if (사용[후보] != 0 && पोर्ट_मान[후보] == एंडपॉइंट_पोर्ट_संख्या) गंतव्य_मान = 후보;
        if (गंतव्य_मान < 0) return -111;
        if (개수[गंतव्य_मान] == 4) return -11;
        int पद_इंडेक्स = गंतव्य_मान * 4 + (सामने_मान[गंतव्य_मान] + 개수[गंतव्य_मान]) % 4;
        for (int बाइट_मान = 0; बाइट_मान < आकार; बाइट_मान++) आँकड़े[पद_इंडेक्स * 512 + बाइट_मान] = आगे_मान[बाइट_मान];
        길이[पद_इंडेक्स] = आकार; 보낸창구[पद_इंडेक्स] = पोर्ट_मान[칸]; 개수[गंतव्य_मान]++;
        return आकार;
    }
    public static int 받기(int इंडेक्स, int क्षमता_मान) {
        int 칸 = सत्यापित_करें(इंडेक्स);
        if (칸 < 0) return -9;
        if (क्षमता_मान < 0 || क्षमता_मान > 512) return -22;
        if (개수[칸] == 0) return -11;
        int पद_इंडेक्स = 칸 * 4 + सामने_मान[칸];
        int आकार = 길이[पद_इंडेक्स] < क्षमता_मान ? 길이[पद_इंडेक्स] : क्षमता_मान;
        for (int बाइट_मान = 0; बाइट_मान < आकार; बाइट_मान++) आगे_मान[बाइट_मान] = आँकड़े[पद_इंडेक्स * 512 + बाइट_मान];
        받은창구[칸] = 보낸창구[पद_इंडेक्स]; सामने_मान[칸] = (सामने_मान[칸] + 1) % 4; 개수[칸]--;
        return आकार;
    }
    public static int पढें_एंडपॉइंट_पोर्ट(int इंडेक्स) { int 칸 = सत्यापित_करें(इंडेक्स); return 칸 < 0 ? -9 : पोर्ट_मान[칸]; }
    public static int पढें_पता(int इंडेक्स) { int 칸 = सत्यापित_करें(इंडेक्स); return 칸 < 0 ? -9 : पता[칸]; }
    public static int प्रेषक_एंडपॉइंट(int इंडेक्स) { int 칸 = सत्यापित_करें(इंडेक्स); return 칸 < 0 ? -9 : 받은창구[칸]; }
    public static int बंदकरें(int इंडेक्स) {
        int 칸 = सत्यापित_करें(इंडेक्स); if (칸 < 0) return -9;
        사용[칸] = 0; 개수[칸] = 0; पोर्ट_मान[칸] = 0; return 0;
    }
}
