class प्रणाली_त्रुटि(OSError):
    def __init__(자신, अनुक्रमणिका, 설명="सञ्चालनप्रणाली 작업에 실패했습니다."):
        super().__init__(अनुक्रमणिका, 설명)
        자신.अनुक्रमणिका = अनुक्रमणिका
        자신.설명 = 설명

def 운영호출(प्रकार्य_मान, *तर्क):
    try:
        return प्रकार्य_मान(*तर्क)
    except OSError as त्रुटि:
        अनुक्रमणिका = त्रुटि.args[0] if त्रुटि.args else 0
        raise प्रणाली_त्रुटि(अनुक्रमणिका)

