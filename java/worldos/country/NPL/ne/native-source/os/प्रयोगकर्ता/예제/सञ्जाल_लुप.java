/** 최대 आकार/홀수 लम्बाइ_मान 데이터그램으로 वास्तविक_लगत RTL8139 수신 लुप_मान 순환을 시험한다. */
public final class सञ्जाल_लुप {
    public static int चलाउनुहोस्() {
        if (प्रयोगकर्ता.인수개수() != 1) { प्रयोगकर्ता.लेख्नुहोस्("Usage: run stress PORT\n"); return 2; }
        String पाठ = प्रयोगकर्ता.तर्क(0);
        int पोर्ट_मान = 0;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < पाठ.length(); अनुक्रमणिका++) {
            if (पाठ.charAt(अनुक्रमणिका) < '0' || पाठ.charAt(अनुक्रमणिका) > '9' || पोर्ट_मान > 6553) return 2;
            पोर्ट_मान = पोर्ट_मान * 10 + पाठ.charAt(अनुक्रमणिका) - '0';
        }
        if (पोर्ट_मान < 1 || पोर्ट_मान > 65535) return 2;
        int ह्यान्डल_मान = प्रयोगकर्ता.सिर्जना_सञ्जाल(0);
        if (ह्यान्डल_मान < 0) return 3;
        int[] लगत = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int लम्बाइ_मान = 1024 - (회차 & 1);
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < लम्बाइ_मान; अनुक्रमणिका++) लगत[अनुक्रमणिका] = (अनुक्रमणिका + 회차) & 255;
            if (प्रयोगकर्ता.पठाउनुहोस्_लगत(ह्यान्डल_मान, 0x0a000202, पोर्ट_मान, लगत, लम्बाइ_मान) != लम्बाइ_मान) return 4;
            if (प्रयोगकर्ता.자료받기(ह्यान्डल_मान, लगत, 300) != लम्बाइ_मान) return 5;
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < लम्बाइ_मान; अनुक्रमणिका++) if (लगत[अनुक्रमणिका] != ((अनुक्रमणिका + 회차) & 255)) return 6;
        }
        प्रयोगकर्ता.बन्द_गर्नुहोस्_सञ्जाल(ह्यान्डल_मान);
        प्रयोगकर्ता.लेख्नुहोस्("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
