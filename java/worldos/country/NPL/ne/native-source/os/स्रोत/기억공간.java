/** 부팅 प्रणाली_जानकारी 조회와 4KiB 고정 आकार 작업 सेक्सन_मान निर्धारण_गर्नुहोस्_भण्डारण/반환. 일반 물리 पृष्ठ_मान 관리자는 아니다. */
public final class 기억공간 {
    static int[] सेक्सन_मान = new int[8192];
    static int[] 사용 = new int[8];

    static int पदच्छेद_गर्नुहोस्_पूर्ण_सङ्ख्या(int ठेगाना) {
        return मोबाइल_मान.기억읽기(ठेगाना) | (मोबाइल_मान.기억읽기(ठेगाना + 1) << 8)
            | (मोबाइल_मान.기억읽기(ठेगाना + 2) << 16) | (मोबाइल_मान.기억읽기(ठेगाना + 3) << 24);
    }

    static int 위쪽기억크기() {
        int प्रणाली_जानकारी = मोबाइल_मान.부팅정보();
        if (मोबाइल_मान.부팅표식() != 0x2badb002 || प्रणाली_जानकारी == 0 || (पदच्छेद_गर्नुहोस्_पूर्ण_सङ्ख्या(प्रणाली_जानकारी) & 1) == 0) return -1;
        return पदच्छेद_गर्नुहोस्_पूर्ण_सङ्ख्या(प्रणाली_जानकारी + 8);
    }

    static int निर्धारण_गर्नुहोस्_भण्डारण() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 사용.length; अनुक्रमणिका++) {
            if (사용[अनुक्रमणिका] == 0) {
                사용[अनुक्रमणिका] = 1;
                for (int स्लट_प्रविष्टि = 0; स्लट_प्रविष्टि < 1024; स्लट_प्रविष्टि++) सेक्सन_मान[अनुक्रमणिका * 1024 + स्लट_प्रविष्टि] = 0;
                return अनुक्रमणिका;
            }
        }
        return -1;
    }

    static boolean 반환(int अनुक्रमणिका) {
        if (अनुक्रमणिका < 0 || अनुक्रमणिका >= 사용.length || 사용[अनुक्रमणिका] == 0) return false;
        사용[अनुक्रमणिका] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 사용.length; अनुक्रमणिका++) 개수 += 사용[अनुक्रमणिका];
        return 개수;
    }
}
