/** 디스크 लेख्नुहोस् 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int लम्बाइ_मान = 0;
    static boolean 앞줄복귀 = false;
    static boolean रेखा_ओभरफ्लो = false;

    static boolean आदेश(String नाम) {
        if (लम्बाइ_मान < नाम.length()) return false;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < नाम.length(); अनुक्रमणिका++)
            if (입력[अनुक्रमणिका] != नाम.charAt(अनुक्रमणिका)) return false;
        return लम्बाइ_मान == नाम.length() || 입력[नाम.length()] == ' ';
    }

    static void शो_मद्दत() {
        पाठ_टर्मिनल.लेख्नुहोस्("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        पाठ_टर्मिनल.लेख्नुहोस्("apps | run NAME [ARGS] | net\n");
        पाठ_टर्मिनल.लेख्नुहोस्("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        पाठ_टर्मिनल.लेख्नुहोस्("sync (연결된 JKSTORE1 भण्डार_गर्नुहोस्_मान 장치에 फाइल 보존)\n");
    }

    static void प्रक्रिया_मान_प्रविष्टि() {
        if (लम्बाइ_मान == 0) return;
        if (आदेश("help")) शो_मद्दत();
        else if (आदेश("sync")) {
            int मापन = 파일보존.समक्रमित();
            पाठ_टर्मिनल.लेख्नुहोस्("Sync: "); पाठ_टर्मिनल.수쓰기(मापन); पाठ_टर्मिनल.문자(10);
        }
        else if (आदेश("ls")) मेमोरी_फाइल_प्रणाली.प्रविष्टि_सूची();
        else if (आदेश("edit")) मेमोरी_फाइल_प्रणाली.आदेश(입력, 4, लम्बाइ_मान, 0);
        else if (आदेश("cat")) मेमोरी_फाइल_प्रणाली.आदेश(입력, 3, लम्बाइ_मान, 1);
        else if (आदेश("rm")) मेमोरी_फाइल_प्रणाली.आदेश(입력, 2, लम्बाइ_मान, 2);
        else if (आदेश("java") || आदेश("javac")) {
            int मापन = 실행관리.कार्यान्वयन_गर्नुहोस्_आदेश(입력, 0, लम्बाइ_मान);
            पाठ_टर्मिनल.लेख्नुहोस्("Exit: "); पाठ_टर्मिनल.수쓰기(मापन); पाठ_टर्मिनल.문자(10);
        }
        else if (आदेश("apps")) 실행관리.प्रविष्टि_सूची();
        else if (आदेश("net")) सञ्जाल_चाङ.स्थिति_मान();
        else if (आदेश("run")) {
            int मापन = 실행관리.कार्यान्वयन_गर्नुहोस्_आदेश(입력, 3, लम्बाइ_मान);
            पाठ_टर्मिनल.लेख्नुहोस्("Exit: "); पाठ_टर्मिनल.수쓰기(मापन); पाठ_टर्मिनल.लेख्नुहोस्("\n");
        } else if (आदेश("info")) {
            पाठ_टर्मिनल.लेख्नुहोस्("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (आदेश("mem")) {
            पाठ_टर्मिनल.लेख्नुहोस्("위쪽 मेमोरी_मान 공간(KiB): "); पाठ_टर्मिनल.수쓰기(기억공간.위쪽기억크기());
            पाठ_टर्मिनल.लेख्नुहोस्("\n배열 동적 मेमोरी_मान 공간(बाइट_मान): "); पाठ_टर्मिनल.수쓰기(मोबाइल_मान.विन्यास_प्रयोग());
            पाठ_टर्मिनल.लेख्नुहोस्(" / 262144\n작업 공간 सेक्सन_मान: "); पाठ_टर्मिनल.수쓰기(기억공간.사용개수());
            पाठ_टर्मिनल.लेख्नुहोस्(" / 8 (각 4096바이트)\n");
        } else if (आदेश("alloc")) {
            int अनुक्रमणिका = 기억공간.निर्धारण_गर्नुहोस्_भण्डारण();
            पाठ_टर्मिनल.लेख्नुहोस्("सेक्सन_मान अनुक्रमणिका: "); पाठ_टर्मिनल.수쓰기(अनुक्रमणिका); पाठ_टर्मिनल.लेख्नुहोस्("\n");
        } else if (आदेश("free")) {
            if (लम्बाइ_मान == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                पाठ_टर्मिनल.लेख्नुहोस्(기억공간.반환(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 सेक्सन_मान\n");
            } else पाठ_टर्मिनल.लेख्नुहोस्("사용법: free 0..7\n");
        } else if (आदेश("echo")) {
            for (int अनुक्रमणिका = 5; अनुक्रमणिका < लम्बाइ_मान; अनुक्रमणिका++) पाठ_टर्मिनल.문자(입력[अनुक्रमणिका]);
            पाठ_टर्मिनल.문자(10);
        } else if (आदेश("clear")) पाठ_टर्मिनल.지우기();
        else if (आदेश("test")) कर्णेल.시험();
        else if (आदेश("halt")) {
            पाठ_टर्मिनल.लेख्नुहोस्("HALTED\n");
            मोबाइल_मान.정지();
        } else पाठ_टर्मिनल.लेख्नुहोस्("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int मान) {
        if (मान == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = मान == 13;
        if (मान == 10 || मान == 13) {
            पाठ_टर्मिनल.문자(10);
            if (मेमोरी_फाइल_प्रणाली.편집중) मेमोरी_फाइल_प्रणाली.편집줄(입력, लम्बाइ_मान, रेखा_ओभरफ्लो);
            else प्रक्रिया_मान_प्रविष्टि();
            लम्बाइ_मान = 0;
            रेखा_ओभरफ्लो = false;
            पाठ_टर्मिनल.लेख्नुहोस्(मेमोरी_फाइल_प्रणाली.편집중 ? "...> " : "jkoros> ");
        } else if (मान == 8 || मान == 127) {
            if (लम्बाइ_मान > 0) {
                लम्बाइ_मान--;
                पाठ_टर्मिनल.직렬바이트(8); पाठ_टर्मिनल.직렬바이트(32); पाठ_टर्मिनल.직렬바이트(8);
                पाठ_टर्मिनल.화면문자(8);
            }
        } else if (मान >= 32 && मान < 127 && लम्बाइ_मान < 입력.length) {
            입력[लम्बाइ_मान++] = मान;
            पाठ_टर्मिनल.문자(मान);
        } else if (मान >= 32 && मान < 127) रेखा_ओभरफ्लो = true;
    }

    static void चलाउनुहोस्() {
        शो_मद्दत();
        पाठ_टर्मिनल.लेख्नुहोस्("READY\njkoros> ");
        while (true) {
            int मान = पाठ_टर्मिनल.직렬읽기();
            if (मान < 0) मान = कुञ्जीपाटी.पढनुहोस्();
            if (मान >= 0) 받아쓰기(मान);
            else { सञ्जाल_चाङ.रुजू_गर्नुहोस्(); मोबाइल_मान.잠시양보(); }
        }
    }
}
