    static final int 서술자한도 = 32;
    static final int पढ्न_लेख्_न_झन्डा = 2, सिर्जना_प्रविष्टि = 64, 독점생성 = 128, खाली_गर्नुहोस्_टिओसी = 512;
    static final int 이어쓰기 = 1024, 기다리지않기 = 2048, 실행시닫기 = 524288;
    static int[] सिर्जना_ह्यान्डल = new int[서술자한도], 서술자설정 = new int[서술자한도];
    static int[] 종류 = new int[서술자한도], लक्ष्य = new int[서술자한도];
    static int[] फाइल_राख्नुहोस् = new int[서술자한도], सिर्जना_सेटिङहरू = new int[서술자한도], 참조수 = new int[서술자한도];
    static int[] सञ्जाल_ह्यान्डल = new int[서술자한도], 수신대기밀리초 = new int[서술자한도];
    static int[] बाटो_नाम = new int[64], ट्रान्सफर_लगत = new int[1024];

    static int 기술찾기(int 파일서술자) {
        if (파일서술자 < 0 || 파일서술자 >= 서술자한도) return -9;
        return सिर्जना_ह्यान्डल[파일서술자] - 1;
    }
    static int 빈서술자(int चलाउनुहोस्) {
        for (int अनुक्रमणिका = चलाउनुहोस्; अनुक्रमणिका < 서술자한도; अनुक्रमणिका++) if (सिर्जना_ह्यान्डल[अनुक्रमणिका] == 0) return अनुक्रमणिका;
        return -24;
    }
    static int रिक्त_ह्यान्डल() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 서술자한도; अनुक्रमणिका++) if (참조수[अनुक्रमणिका] == 0) return अनुक्रमणिका;
        return -24;
    }
    static int जडान(int 서술자, int 기술, int 파일종류, int फाइल_लक्ष्य, int सेटिङ) {
        सिर्जना_ह्यान्डल[서술자] = 기술 + 1; 서술자설정[서술자] = (सेटिङ & 실행시닫기) != 0 ? 1 : 0;
        종류[기술] = 파일종류; लक्ष्य[기술] = फाइल_लक्ष्य; 참조수[기술] = 1;
        सिर्जना_सेटिङहरू[기술] = सेटिङ & (3 | 이어쓰기 | 기다리지않기); फाइल_राख्नुहोस्[기술] = 0;
        सञ्जाल_ह्यान्डल[기술] = 0; 수신대기밀리초[기술] = 0;
        return 서술자;
    }
    static void सुरु_प्रक्रिया() {
        स्पष्ट_प्रक्रिया();
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 3; अनुक्रमणिका++) जडान(अनुक्रमणिका, अनुक्रमणिका, 1, अनुक्रमणिका, अनुक्रमणिका == 0 ? 0 : 1);
    }
    static void स्पष्ट_प्रक्रिया() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 서술자한도; अनुक्रमणिका++) if (सिर्जना_ह्यान्डल[अनुक्रमणिका] != 0) बन्द_गर्नुहोस्_फाइल(अनुक्रमणिका);
    }
    static int बन्द_गर्नुहोस्_फाइल(int 서술자) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0) return -9;
        सिर्जना_ह्यान्डल[서술자] = 0; 서술자설정[서술자] = 0;
        참조수[기술]--;
        if (참조수[기술] == 0) {
            if (종류[기술] == 2) मेमोरी_फाइल_प्रणाली.열림수[लक्ष्य[기술]]--;
            if (종류[기술] == 3 && सञ्जाल_ह्यान्डल[기술] != 0) सञ्जाल_चाङ.बन्दगर्नुहोस्(सञ्जाल_ह्यान्डल[기술]);
            종류[기술] = 0;
        }
        return 0;
    }
    // C 경로는 NUL 끝 बाइट_मान 문자열이다. 루트의 한 이름만 지원한다.
    static int 경로읽기(int ठेगाना) {
        if (!실행관리.क्लिप(ठेगाना, 1)) return -14;
        int स्थिति = मोबाइल_मान.기억읽기(ठेगाना) == '/' ? 1 : 0;
        for (int लम्बाइ_मान = 0; लम्बाइ_मान < 64; लम्बाइ_मान++) {
            if (!실행관리.क्लिप(ठेगाना + स्थिति + लम्बाइ_मान, 1)) return -14;
            int मान = मोबाइल_मान.기억읽기(ठेगाना + स्थिति + लम्बाइ_मान);
            बाटो_नाम[लम्बाइ_मान] = मान;
            if (मान == 0) return लम्बाइ_मान == 0 ? -2 : (मेमोरी_फाइल_प्रणाली.चेक_नाम(बाटो_नाम, लम्बाइ_मान) ? लम्बाइ_मान : -22);
            if (मान == '/') return -20;
        }
        return -36;
    }
    static int सिर्जना_फाइल(int नाम_ठेगाना, int सेटिङ, int 허가) {
        int लम्बाइ_मान = 경로읽기(नाम_ठेगाना);
        if (लम्बाइ_मान < 0) return लम्बाइ_मान;
        if ((सेटिङ & ~(3 | सिर्जना_प्रविष्टि | 독점생성 | खाली_गर्नुहोस्_टिओसी | 이어쓰기 | 기다리지않기 | 실행시닫기)) != 0) return -95;
        if ((सेटिङ & 3) == 3 || ((सेटिङ & खाली_गर्नुहोस्_टिओसी) != 0 && (सेटिङ & 3) == 0)) return -22;
        int फाइल = मेमोरी_फाइल_प्रणाली.खोज_गर्नुहोस्_प्रविष्टि(बाटो_नाम, लम्बाइ_मान);
        if (फाइल >= 0 && (सेटिङ & (सिर्जना_प्रविष्टि | 독점생성)) == (सिर्जना_प्रविष्टि | 독점생성)) return -17;
        if (फाइल == -2 && (सेटिङ & सिर्जना_प्रविष्टि) == 0) return -2;
        int 서술자 = 빈서술자(0), 기술 = रिक्त_ह्यान्डल();
        if (서술자 < 0 || 기술 < 0) return -24;
        if (फाइल == -2) {
            int मापन = मेमोरी_फाइल_प्रणाली.भण्डार_गर्नुहोस्_मान(बाटो_नाम, लम्बाइ_मान, बाटो_नाम, 0);
            if (मापन < 0) return मापन;
            फाइल = मेमोरी_फाइल_प्रणाली.खोज_गर्नुहोस्_प्रविष्टि(बाटो_नाम, लम्बाइ_मान);
            मेमोरी_फाइल_प्रणाली.허가들[फाइल] = 허가 & 511;
        }
        if (फाइल < 0) return फाइल;
        if ((सेटिङ & खाली_गर्नुहोस्_टिओसी) != 0) मेमोरी_फाइल_प्रणाली.साइज_सूची[फाइल] = 0;
        मेमोरी_फाइल_प्रणाली.열림수[फाइल]++;
        return जडान(서술자, 기술, 2, फाइल, सेटिङ);
    }
    static int 파일읽기(int 서술자, int लगत_ठेगाना, int लम्बाइ_मान) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0 || (सिर्जना_सेटिङहरू[기술] & 3) == 1) return -9;
        if (लम्बाइ_मान < 0) return -22;
        if (लम्बाइ_मान == 0) return 0;
        if (!실행관리.क्लिप(लगत_ठेगाना, लम्बाइ_मान)) return -14;
        if (종류[기술] == 3) return 자료전문받기(서술자, लगत_ठेगाना, लम्बाइ_मान, 0, 0);
        if (종류[기술] == 1) {
            int 받은수 = 0;
            while (받은수 < लम्बाइ_मान) {
                int मान = पाठ_टर्मिनल.직렬읽기();
                if (मान < 0) मान = कुञ्जीपाटी.पढनुहोस्();
                if (मान < 0) {
                    if (받은수 > 0) return 받은수;
                    if ((सिर्जना_सेटिङहरू[기술] & 기다리지않기) != 0) return -11;
                    if (मोबाइल_मान.사용자남은밀리초() <= 10) return -11;
                    सञ्जाल_चाङ.रुजू_गर्नुहोस्(); मोबाइल_मान.잠시양보();
                } else {
                    मोबाइल_मान.लेख्नुहोस्_मेमोरी(लगत_ठेगाना + 받은수, मान); 받은수++;
                }
            }
            return 받은수;
        }
        int फाइल = लक्ष्य[기술], स्थिति = फाइल_राख्नुहोस्[기술];
        if (स्थिति >= मेमोरी_फाइल_प्रणाली.साइज_सूची[फाइल]) return 0;
        if (लम्बाइ_मान > मेमोरी_फाइल_प्रणाली.साइज_सूची[फाइल] - स्थिति) लम्बाइ_मान = मेमोरी_फाइल_प्रणाली.साइज_सूची[फाइल] - स्थिति;
        int 원본주소 = मोबाइल_मान.फाइल_मेमोरी() + फाइल * मेमोरी_फाइल_प्रणाली.최대크기 + स्थिति;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < लम्बाइ_मान; अनुक्रमणिका++) मोबाइल_मान.लेख्नुहोस्_मेमोरी(लगत_ठेगाना + अनुक्रमणिका, मोबाइल_मान.기억읽기(원본주소 + अनुक्रमणिका));
        फाइल_राख्नुहोस्[기술] += लम्बाइ_मान;
        return लम्बाइ_मान;
    }
    static int लेख्नुहोस्_फाइल(int 서술자, int लगत_ठेगाना, int लम्बाइ_मान) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0 || (सिर्जना_सेटिङहरू[기술] & 3) == 0) return -9;
        if (लम्बाइ_मान < 0) return -22;
        if (लम्बाइ_मान == 0) return 0;
        if (!실행관리.क्लिप(लगत_ठेगाना, लम्बाइ_मान)) return -14;
        if (종류[기술] == 3) return -89; // 연결하지 않은 자료전문 종단점에는 गन्तव्य_मान 주소가 필요하다.
        if (종류[기술] == 1) {
            if (लम्बाइ_मान > 16384) लम्बाइ_मान = 16384;
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < लम्बाइ_मान; अनुक्रमणिका++) {
                int मान = मोबाइल_मान.기억읽기(लगत_ठेगाना + अनुक्रमणिका);
                पाठ_टर्मिनल.직렬바이트(मान); पाठ_टर्मिनल.화면문자(मान);
            }
            return लम्बाइ_मान;
        }
        int फाइल = लक्ष्य[기술], आकार = मेमोरी_फाइल_प्रणाली.साइज_सूची[फाइल];
        int स्थिति = (सिर्जना_सेटिङहरू[기술] & 이어쓰기) != 0 ? आकार : फाइल_राख्नुहोस्[기술];
        if (स्थिति >= मेमोरी_फाइल_प्रणाली.최대크기) return -27;
        if (लम्बाइ_मान > मेमोरी_फाइल_प्रणाली.최대크기 - स्थिति) लम्बाइ_मान = मेमोरी_फाइल_प्रणाली.최대크기 - स्थिति;
        int गन्तव्य_ठेगाना = मोबाइल_मान.फाइल_मेमोरी() + फाइल * मेमोरी_फाइल_प्रणाली.최대크기;
        for (int अनुक्रमणिका = आकार; अनुक्रमणिका < स्थिति; अनुक्रमणिका++) मोबाइल_मान.लेख्नुहोस्_मेमोरी(गन्तव्य_ठेगाना + अनुक्रमणिका, 0);
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < लम्बाइ_मान; अनुक्रमणिका++) मोबाइल_मान.लेख्नुहोस्_मेमोरी(गन्तव्य_ठेगाना + स्थिति + अनुक्रमणिका, मोबाइल_मान.기억읽기(लगत_ठेगाना + अनुक्रमणिका));
        फाइल_राख्नुहोस्[기술] = स्थिति + लम्बाइ_मान;
        if (स्थिति + लम्बाइ_मान > आकार) मेमोरी_फाइल_प्रणाली.साइज_सूची[फाइल] = स्थिति + लम्बाइ_मान;
        return लम्बाइ_मान;
    }
    static int खोज्नुहोस्_फाइल(int 서술자, int अफसेट_मान, int परियोजना_रूट) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0) return -9;
        if (종류[기술] != 2) return -29;
        if (परियोजना_रूट < 0 || परियोजना_रूट > 2) return -22;
        int वालपेपर_मान = परियोजना_रूट == 0 ? 0 : (परियोजना_रूट == 1 ? फाइल_राख्नुहोस्[기술] : मेमोरी_फाइल_प्रणाली.साइज_सूची[लक्ष्य[기술]]);
        if (अफसेट_मान > 0 && वालपेपर_मान > 2147483647 - अफसेट_मान) return -75;
        if (अफसेट_मान < 0 && अफसेट_मान < -वालपेपर_मान) return -22;
        फाइल_राख्नुहोस्[기술] = वालपेपर_मान + अफसेट_मान;
        return फाइल_राख्नुहोस्[기술];
    }
    static int 서술자복제(int 서술자, int 새서술자, boolean 지정, int सेटिङ) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0) return -9;
        if (새서술자 < 0 || 새서술자 >= 서술자한도) return 지정 ? -9 : -22;
        if (지정 && 서술자 == 새서술자) return 새서술자;
        if (지정) { if (सिर्जना_ह्यान्डल[새서술자] != 0) बन्द_गर्नुहोस्_फाइल(새서술자); }
        else { 새서술자 = 빈서술자(새서술자); if (새서술자 < 0) return 새서술자; }
        सिर्जना_ह्यान्डल[새서술자] = 기술 + 1; 서술자설정[새서술자] = सेटिङ; 참조수[기술]++;
        return 새서술자;
    }
