#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from डेस्कटप_दृश्य import कुञ्जीपाटी


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.पाठ_बफर = ''
        def पठाउनुहोस्(लगत):
            for वर्ण_लगत in लगत.decode('utf-8'):
                if वर्ण_लगत == '\x7f': 자신.पाठ_बफर = 자신.पाठ_बफर[:-1]
                else: 자신.पाठ_बफर += वर्ण_लगत
        자신.कुञ्जीपाटी_प्रविष्टि = कुञ्जीपाटी(पठाउनुहोस्)

    def 글쇠누르기(자신, चिन्ह_मान):
        자신.कुञ्जीपाटी_प्रविष्टि.누름값(True, चिन्ह_मान)
        자신.कुञ्जीपाटी_प्रविष्टि.누름값(False, चिन्ह_मान)

    def प्रकार_कोटि(자신, 누름열):
        for 누름값 in 누름열: 자신.글쇠누르기(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.글쇠누르기(0xffc6); 자신.प्रकार_कोटि(누름열)
                자신.assertEqual(자신.पाठ_बफर, 예상결과)

    def test_앞글자지우기(자신):
        자신.글쇠누르기(0xff31); 자신.प्रकार_कोटि('dlfr')
        자신.assertEqual(자신.पाठ_बफर,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.글쇠누르기(0xff08); 자신.assertEqual(자신.पाठ_बफर,예상결과)
        자신.प्रकार_कोटि('gksk'); 자신.assertEqual(자신.पाठ_बफर,'하나')
        자신.글쇠누르기(0xff08); 자신.assertEqual(자신.पाठ_बफर,'하ㄴ')

    def test_전환반복확정(자신):
        자신.प्रकार_कोटि('echo ')
        자신.कुञ्जीपाटी_प्रविष्टि.누름값(True,0xffe1)
        자신.कुञ्जीपाटी_प्रविष्टि.누름값(True,32); 자신.कुञ्जीपाटी_प्रविष्टि.누름값(True,32)
        자신.कुञ्जीपाटी_प्रविष्टि.누름값(False,32); 자신.कुञ्जीपाटी_प्रविष्टि.누름값(False,0xffe1)
        자신.assertTrue(자신.कुञ्जीपाटी_प्रविष्टि.한글여부)
        자신.प्रकार_कोटि('gksrmf'); 자신.글쇠누르기(0xff31); 자신.प्रकार_कोटि(' English')
        자신.assertEqual(자신.पाठ_बफर,'echo 한글 English')
        자신.assertFalse(자신.कुञ्जीपाटी_प्रविष्टि.한글여부)
        자신.글쇠누르기(0xffc6); 자신.प्रकार_कोटि('rk'); 자신.글쇠누르기(0xff51)
        자신.प्रकार_कोटि('sk'); 자신.assertTrue(자신.पाठ_बफर.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.글쇠누르기(0xffc6); 자신.प्रकार_कोटि('rk')
        자신.कुञ्जीपाटी_प्रविष्टि.क्लिपबोर्ड_मान='टाँस्नुहोस्_मान'.encode()
        자신.कुञ्जीपाटी_प्रविष्टि.누름값(True,0xffe3); 자신.कुञ्जीपाटी_प्रविष्टि.누름값(True,0xffe1)
        자신.글쇠누르기(ord('v'))
        자신.कुञ्जीपाटी_प्रविष्टि.누름값(False,0xffe1); 자신.कुञ्जीपाटी_प्रविष्टि.누름값(False,0xffe3)
        자신.글쇠누르기(0x0100d55c); 자신.प्रकार_कोटि('sk')
        자신.assertEqual(자신.पाठ_बफर,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
