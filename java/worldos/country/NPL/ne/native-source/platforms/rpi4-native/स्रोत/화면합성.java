/** 화면 टुक्राउने_मान·띠 합성·पोइन्टर 밑그림을 관리한다. वास्तविक_लगत 화면 मेमोरी_लगत 접근은 보드가 담당한다. */
public final class 화면합성 {
    static int 너비, 높이, 합성중, 왼경계, 위경계, 오른경계, 아래경계;
    static int 포인터가로, 포인터세로, पोइन्टर_आकार;
    static int 기록아래낱말, 기록위낱말;
    static int[] 완성그림 = new int[32 * 1920];
    static int[] पोइन्टर_वालपेपर = new int[21 * 21];
    static int[] 잘린범위 = new int[4];
    public static void तयार_गर्नुहोस्(int 폭, int लम्बाइ_मान) {
        너비 = 폭; 높이 = लम्बाइ_मान; 합성중 = 0; पोइन्टर_आकार = 0;
        기록아래낱말 = 0; 기록위낱말 = 0;
    }
    public static int 너비얻기() { return 너비; }
    public static int 높이얻기() { return 높이; }
    public static int 기록아래얻기() { return 기록아래낱말; }
    public static int 기록위얻기() { return 기록위낱말; }
    public static int क्लिप_मान(int 순번) { return 잘린범위[순번]; }
    static int 양의길이더하기(int सुरु_मान, int लम्बाइ_मान) {
        if (सुरु_मान > 2147483647 - लम्बाइ_मान) return 2147483647;
        return सुरु_मान + लम्बाइ_मान;
    }
    public static int क्लिप(int 가로, int ठाडो_राख्नुहोस्, int 폭, int लम्बाइ_मान) {
        if (너비 == 0 || 폭 <= 0 || लम्बाइ_मान <= 0) return 0;
        int 오른쪽 = 양의길이더하기(가로, 폭), 아래쪽 = 양의길이더하기(ठाडो_राख्नुहोस्, लम्बाइ_मान);
        int 왼쪽 = 합성중 != 0 ? 왼경계 : 0, 위쪽 = 합성중 != 0 ? 위경계 : 0;
        int 최대가로 = 합성중 != 0 ? 오른경계 : 너비, 최대세로 = 합성중 != 0 ? 아래경계 : 높이;
        if (가로 < 왼쪽) 가로 = 왼쪽;
        if (ठाडो_राख्नुहोस् < 위쪽) ठाडो_राख्नुहोस् = 위쪽;
        if (오른쪽 > 최대가로) 오른쪽 = 최대가로;
        if (아래쪽 > 최대세로) 아래쪽 = 최대세로;
        if (오른쪽 <= 가로 || 아래쪽 <= ठाडो_राख्नुहोस्) return 0;
        잘린범위[0] = 가로; 잘린범위[1] = ठाडो_राख्नुहोस्;
        잘린범위[2] = 오른쪽 - 가로; 잘린범위[3] = 아래쪽 - ठाडो_राख्नुहोस्;
        return 1;
    }
    public static int चलाउनुहोस्(int 가로, int ठाडो_राख्नुहोस्, int 폭, int लम्बाइ_मान) {
        if (합성중 != 0 || लम्बाइ_मान > 32 || क्लिप(가로, ठाडो_राख्नुहोस्, 폭, लम्बाइ_मान) == 0) return 0;
        왼경계 = 잘린범위[0]; 위경계 = 잘린범위[1];
        오른경계 = 왼경계 + 잘린범위[2]; 아래경계 = 위경계 + 잘린범위[3];
        합성중 = 1; return 1;
    }
    static boolean पोइन्टर_बिट(int 가로, int ठाडो_राख्नुहोस्, int आकार_मान) {
        if (आकार_मान == 1) return 가로 >= 0 && 가로 <= ठाडो_राख्नुहोस् / 2 && ठाडो_राख्नुहोस् < 16;
        if (आकार_मान == 3) 가로 = 20 - 가로;
        int 차이 = 가로 - ठाडो_राख्नुहोस्; if (차이 < 0) 차이 = -차이;
        return (차이 <= 1 && 가로 >= 3 && 가로 <= 17) ||
            (가로 >= 2 && 가로 <= 8 && ठाडो_राख्नुहोस् >= 2 && ठाडो_राख्नुहोस् <= 8 && (가로 <= 3 || ठाडो_राख्नुहोस् <= 3)) ||
            (가로 >= 12 && 가로 <= 18 && ठाडो_राख्नुहोस् >= 12 && ठाडो_राख्नुहोस् <= 18 && (가로 >= 17 || ठाडो_राख्नुहोस् >= 17));
    }
    static int पोइन्टर_पेल(int 가로, int ठाडो_राख्नुहोस्) {
        if (पोइन्टर_बिट(가로, ठाडो_राख्नुहोस्, पोइन्टर_आकार)) return 2;
        for (int रेखा = -1; रेखा <= 1; रेखा++) for (int स्लट_प्रविष्टि = -1; स्लट_प्रविष्टि <= 1; स्लट_प्रविष्टि++)
            if (पोइन्टर_बिट(가로 + स्लट_प्रविष्टि, ठाडो_राख्नुहोस् + रेखा, पोइन्टर_आकार)) return 1;
        return 0;
    }
    static void प्रदर्शन_पेल(int 가로, int ठाडो_राख्नुहोस्, int 색) {
        int स्लट_प्रविष्टि = 가로 - 포인터가로, रेखा = ठाडो_राख्नुहोस् - 포인터세로;
        if (पोइन्टर_आकार != 0 && स्लट_प्रविष्टि >= 0 && रेखा >= 0 && स्लट_प्रविष्टि < 21 && रेखा < 21) {
            पोइन्टर_वालपेपर[रेखा * 21 + स्लट_प्रविष्टि] = 색;
            int अंक_मान = पोइन्टर_पेल(स्लट_प्रविष्टि, रेखा); if (अंक_मान != 0) 색 = अंक_मान == 2 ? 0xffffff : 0x101010;
        }
        if (बोर्ड.표시화소읽기(가로, ठाडो_राख्नुहोस्) != 색) {
            बोर्ड.लेख्नुहोस्_प्रदर्शन_पेल(가로, ठाडो_राख्नुहोस्, 색);
            기록아래낱말++; if (기록아래낱말 == 0) 기록위낱말++;
        }
    }
    public static void समाप्त() {
        if (합성중 == 0) return;
        for (int रेखा = 위경계; रेखा < 아래경계; रेखा++) for (int स्लट_प्रविष्टि = 왼경계; स्लट_प्रविष्टि < 오른경계; स्लट_प्रविष्टि++)
            प्रदर्शन_पेल(स्लट_प्रविष्टि, रेखा, 완성그림[(रेखा - 위경계) * 1920 + स्लट_प्रविष्टि]);
        합성중 = 0;
    }
    public static int पेल(int 가로, int ठाडो_राख्नुहोस्, int 색) {
        if (가로 < 0 || ठाडो_राख्नुहोस् < 0 || 가로 >= 너비 || ठाडो_राख्नुहोस् >= 높이) return 0;
        if (합성중 != 0) {
            if (가로 >= 왼경계 && 가로 < 오른경계 && ठाडो_राख्नुहोस् >= 위경계 && ठाडो_राख्नुहोस् < 아래경계)
                완성그림[(ठाडो_राख्नुहोस् - 위경계) * 1920 + 가로] = 색;
        } else प्रदर्शन_पेल(가로, ठाडो_राख्नुहोस्, 색);
        return 0;
    }
    public static void 사각그림(int 가로, int ठाडो_राख्नुहोस्, int 폭, int लम्बाइ_मान, int 색) {
        if (क्लिप(가로, ठाडो_राख्नुहोस्, 폭, लम्बाइ_मान) == 0) return;
        가로 = 잘린범위[0]; ठाडो_राख्नुहोस् = 잘린범위[1]; 폭 = 잘린범위[2]; लम्बाइ_मान = 잘린범위[3];
        for (int रेखा = ठाडो_राख्नुहोस्; रेखा < ठाडो_राख्नुहोस् + लम्बाइ_मान; रेखा++) for (int स्लट_प्रविष्टि = 가로; स्लट_प्रविष्टि < 가로 + 폭; स्लट_प्रविष्टि++) {
            if (합성중 != 0) 완성그림[(रेखा - 위경계) * 1920 + स्लट_प्रविष्टि] = 색;
            else प्रदर्शन_पेल(स्लट_प्रविष्टि, रेखा, 색);
        }
    }
    public static void पोइन्टर(int 가로, int ठाडो_राख्नुहोस्, int आकार_मान) {
        if (너비 == 0) return;
        int 새가로 = 가로 - (आकार_मान >= 2 ? 10 : 0), 새세로 = ठाडो_राख्नुहोस् - (आकार_मान >= 2 ? 10 : 0);
        if (पोइन्टर_आकार == आकार_मान && 포인터가로 == 새가로 && 포인터세로 == 새세로) return;
        if (पोइन्टर_आकार != 0) for (int रेखा = 0; रेखा < 21; रेखा++) for (int स्लट_प्रविष्टि = 0; स्लट_प्रविष्टि < 21; स्लट_प्रविष्टि++) {
            int 가 = 포인터가로 + स्लट_प्रविष्टि, 세 = 포인터세로 + रेखा;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) बोर्ड.लेख्नुहोस्_प्रदर्शन_पेल(가, 세, पोइन्टर_वालपेपर[रेखा * 21 + स्लट_प्रविष्टि]);
        }
        पोइन्टर_आकार = आकार_मान; 포인터가로 = 새가로; 포인터세로 = 새세로;
        if (आकार_मान != 0) for (int रेखा = 0; रेखा < 21; रेखा++) for (int स्लट_प्रविष्टि = 0; स्लट_प्रविष्टि < 21; स्लट_प्रविष्टि++) {
            int 가 = 포인터가로 + स्लट_प्रविष्टि, 세 = 포인터세로 + रेखा;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) {
                पोइन्टर_वालपेपर[रेखा * 21 + स्लट_प्रविष्टि] = बोर्ड.표시화소읽기(가, 세);
                int अंक_मान = पोइन्टर_पेल(स्लट_प्रविष्टि, रेखा); if (अंक_मान != 0) बोर्ड.लेख्नुहोस्_प्रदर्शन_पेल(가, 세, अंक_मान == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
