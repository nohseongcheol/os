#include "호출경계.h"
extern int main(int 인수개수, char **तर्क_सूची);
static char तर्क_मेमोरी[2048];
static char *तर्क_सूची[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 कार्यान्वयन_गर्नुहोस्_आदेश 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    तर्क_सूची[0] = "jkoros-app";
    int स्थिति = 0;
    for (int अनुक्रमणिका = 0; अनुक्रमणिका < 개수; अनुक्रमणिका++) {
        const int *원본 = (const int *)jkoros_syscall(3, अनुक्रमणिका, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        तर्क_सूची[अनुक्रमणिका + 1] = तर्क_मेमोरी + स्थिति;
        for (int स्लट_प्रविष्टि = 0; स्लट_प्रविष्टि < 원본[0]; स्लट_प्रविष्टि++) {
            if (स्थिति >= 2047) return 126;
            तर्क_मेमोरी[स्थिति++] = 원본[स्लट_प्रविष्टि + 1];
        }
        तर्क_मेमोरी[स्थिति++] = 0;
    }
    तर्क_सूची[개수 + 1] = 0;
    return main(개수 + 1, तर्क_सूची);
}
