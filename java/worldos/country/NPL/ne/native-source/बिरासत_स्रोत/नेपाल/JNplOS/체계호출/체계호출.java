    public int कार्यान्वयन_गर्नुहोस्_आदेश(प्रक्रिया_मान 현재과정, byte[] 실행파일, String[] 인자, String[] 환경) {
        실행파일적재기.छवि छवि_मान;
        try {
            छवि_मान = 적재기.검사(실행파일);
        } catch (IllegalArgumentException त्रुटि) {
            return -8;
        }
        if (인자 == null || 환경 == null || 인자.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.सेक्सन_मान सेक्सन_मान : छवि_मान.구역들()) {
            if ((सेक्सन_मान.झन्डा_मान() & 2) == 0 || सेक्सन_मान.आकार() == 0) {
                continue;
            }
            int 첫쪽 = सेक्सन_मान.ठेगाना() / पृष्ठ_प्रबन्धक.पृष्ठ_साइज;
            int 끝쪽 = (सेक्सन_मान.ठेगाना() + सेक्सन_मान.आकार() + पृष्ठ_प्रबन्धक.पृष्ठ_साइज - 1) / पृष्ठ_प्रबन्धक.पृष्ठ_साइज;
            for (int अनुक्रमणिका = 첫쪽; अनुक्रमणिका < 끝쪽; अनुक्रमणिका++) {
                int ठेगाना = अनुक्रमणिका * पृष्ठ_प्रबन्धक.पृष्ठ_साइज;
                try {
                    쪽관리.바이트읽기(현재과정.ठेगाना_स्थान(), ठेगाना);
                    쪽관리.범위개인쓰기(현재과정.ठेगाना_स्थान(), ठेगाना, पृष्ठ_प्रबन्धक.पृष्ठ_साइज);
                } catch (IllegalStateException त्रुटि) {
                    쪽관리.मानचित्र_पृष्ठ(현재과정.ठेगाना_स्थान(), ठेगाना, true);
                }
            }
            for (int अनुक्रमणिका = 0; अनुक्रमणिका < सेक्सन_मान.आकार(); अनुक्रमणिका++) {
                byte मान = सेक्सन_मान.종류() == 8 ? 0 : 실행파일[सेक्सन_मान.फाइल_राख्नुहोस्() + अनुक्रमणिका];
                쪽관리.लेख्नुहोस्_बाइट_मान(현재과정.ठेगाना_स्थान(), सेक्सन_मान.ठेगाना() + अनुक्रमणिका, मान);
            }
        }
        현재과정.실행문맥설정(छवि_मान.सुरु_ठेगाना(), 인자, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

