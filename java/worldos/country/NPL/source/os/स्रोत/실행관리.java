/** पढनुहोस् 전용 कार्यान्वयन_गर्नुहोस्_आदेश 묶음의 ELF32 वैध_गर्नुहोस्, तर्क फरवार्ड_मान, 한 번에 한 प्रयोगकर्ता प्रक्रिया_मान कार्यान्वयन_गर्नुहोस्_आदेश. */
public final class 실행관리 {
    static final int सुरु_प्रयोगकर्ता_अनुप्रयोग = 0x04000000;
    static final int प्रयोगकर्ता_समाप्त_गर्नुहोस् = 0x04400000;
    static final int छवि_समाप्त_गर्नुहोस्_ठेगाना = 0x04200000;
    static final int तर्क_सुरु = 0x04300000;
    static int 인수수 = 0;
    static int[] तर्क_ठेगाना = new int[16];

    static boolean क्लिप(int ठेगाना, int लम्बाइ_मान) {
        return ठेगाना >= सुरु_प्रयोगकर्ता_अनुप्रयोग && ठेगाना < प्रयोगकर्ता_समाप्त_गर्नुहोस् && लम्बाइ_मान >= 0 && लम्बाइ_मान <= प्रयोगकर्ता_समाप्त_गर्नुहोस् - ठेगाना;
    }

    static int 수(int ठेगाना) { return 기억공간.पदच्छेद_गर्नुहोस्_पूर्ण_सङ्ख्या(ठेगाना); }
    static int 짧은수(int ठेगाना) { return मोबाइल_मान.기억읽기(ठेगाना) | मोबाइल_मान.기억읽기(ठेगाना + 1) << 8; }
    static void 수쓰기(int ठेगाना, int मान) {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 4; अनुक्रमणिका++) मोबाइल_मान.लेख्नुहोस्_मेमोरी(ठेगाना + अनुक्रमणिका, मान >>> (अनुक्रमणिका * 8));
    }

    static int 묶음개수() {
        int ठेगाना = मोबाइल_मान.실행묶음();
        int आकार = मोबाइल_मान.실행묶음크기();
        if (आकार < 8 || 수(ठेगाना) != 0x50414b4a) return 0;
        int 개수 = 수(ठेगाना + 4);
        return 개수 >= 0 && 개수 <= 32 && 개수 <= (आकार - 8) / 24 ? 개수 : 0;
    }

    static void प्रविष्टि_सूची() {
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 묶음개수(); अनुक्रमणिका++) {
            int प्रविष्टि_मान = मोबाइल_मान.실행묶음() + 8 + अनुक्रमणिका * 24;
            for (int वर्ण_मान = 0; वर्ण_मान < 16 && मोबाइल_मान.기억읽기(प्रविष्टि_मान + वर्ण_मान) != 0; वर्ण_मान++)
                पाठ_टर्मिनल.문자(मोबाइल_मान.기억읽기(प्रविष्टि_मान + वर्ण_मान));
            पाठ_टर्मिनल.लेख्नुहोस्("\n");
        }
    }

    static int खोज_गर्नुहोस्_प्रविष्टि(int[] 입력, int चलाउनुहोस्, int लम्बाइ_मान) {
        if (लम्बाइ_मान <= 0 || लम्बाइ_मान >= 16) return 0;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 묶음개수(); अनुक्रमणिका++) {
            int प्रविष्टि_मान = मोबाइल_मान.실행묶음() + 8 + अनुक्रमणिका * 24;
            boolean 같음 = मोबाइल_मान.기억읽기(प्रविष्टि_मान + लम्बाइ_मान) == 0;
            for (int वर्ण_मान = 0; वर्ण_मान < लम्बाइ_मान; वर्ण_मान++)
                if (입력[चलाउनुहोस् + वर्ण_मान] != मोबाइल_मान.기억읽기(प्रविष्टि_मान + वर्ण_मान)) 같음 = false;
            if (같음) return प्रविष्टि_मान;
        }
        return 0;
    }

    static int वैध_गर्नुहोस्(int फाइल, int लम्बाइ_मान) {
        if (लम्बाइ_मान < 52 || 수(फाइल) != 0x464c457f || मोबाइल_मान.기억읽기(फाइल + 4) != 1
            || मोबाइल_मान.기억읽기(फाइल + 5) != 1 || मोबाइल_मान.기억읽기(फाइल + 6) != 1
            || 짧은수(फाइल + 16) != 2 || 짧은수(फाइल + 18) != 3 || 수(फाइल + 20) != 1
            || 짧은수(फाइल + 40) != 52 || 짧은수(फाइल + 42) != 32) return -8;
        int प्रविष्टि_अंक_मान = 수(फाइल + 24);
        int तालिका_राख्नुहोस् = 수(फाइल + 28);
        int 개수 = 짧은수(फाइल + 44);
        if (개수 == 0 || 개수 > 16 || तालिका_राख्नुहोस् < 52 || तालिका_राख्नुहोस् > लम्बाइ_मान - 개수 * 32) return -8;
        boolean 실행가능 = false;
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 개수; अनुक्रमणिका++) {
            int विवरण_हेर्ने_सुविधा_तालिका = फाइल + तालिका_राख्नुहोस् + अनुक्रमणिका * 32;
            int 종류 = 수(विवरण_हेर्ने_सुविधा_तालिका);
            if (종류 == 2 || 종류 == 3) return -8; // 동적 जडान/해석기 미지원
            if (종류 != 1) continue;
            int स्थिति = 수(विवरण_हेर्ने_सुविधा_तालिका + 4), ठेगाना = 수(विवरण_हेर्ने_सुविधा_तालिका + 8), फाइल_साइज = 수(विवरण_हेर्ने_सुविधा_तालिका + 16), मेमोरी_साइज = 수(विवरण_हेर्ने_सुविधा_तालिका + 20);
            int पङ्_क्तिबद्ध_गर्नुहोस्_मान = 수(विवरण_हेर्ने_सुविधा_तालिका + 28);
            if (ठेगाना < सुरु_प्रयोगकर्ता_अनुप्रयोग || ठेगाना >= छवि_समाप्त_गर्नुहोस्_ठेगाना || मेमोरी_साइज < 0 || मेमोरी_साइज > छवि_समाप्त_गर्नुहोस्_ठेगाना - ठेगाना
                || फाइल_साइज < 0 || फाइल_साइज > मेमोरी_साइज || स्थिति < 0 || (फाइल_साइज > 0 && स्थिति > लम्बाइ_मान - फाइल_साइज)
                || (पङ्_क्तिबद्ध_गर्नुहोस्_मान != 0 && (पङ्_क्तिबद्ध_गर्नुहोस्_मान < 0 || (पङ्_क्तिबद्ध_गर्नुहोस्_मान & (पङ्_क्तिबद्ध_गर्नुहोस्_मान - 1)) != 0
                    || ((ठेगाना - स्थिति) & (पङ्_क्तिबद्ध_गर्नुहोस्_मान - 1)) != 0))) return -8;
            for (int 앞 = 0; 앞 < अनुक्रमणिका; 앞++) {
                int 이전 = फाइल + तालिका_राख्नुहोस् + 앞 * 32;
                if (수(이전) == 1 && मेमोरी_साइज > 0 && 수(이전 + 20) > 0
                    && ठेगाना < 수(이전 + 8) + 수(이전 + 20) && 수(이전 + 8) < ठेगाना + मेमोरी_साइज) return -8;
            }
            if ((수(विवरण_हेर्ने_सुविधा_तालिका + 24) & 1) != 0 && प्रविष्टि_अंक_मान >= ठेगाना && प्रविष्टि_अंक_मान - ठेगाना < फाइल_साइज) 실행가능 = true;
        }
        return 실행가능 ? प्रविष्टि_अंक_मान : -8;
    }

    static int कार्यान्वयन_गर्नुहोस्_आदेश(int[] 입력, int चलाउनुहोस्, int लम्बाइ_मान) {
        while (चलाउनुहोस् < लम्बाइ_मान && 입력[चलाउनुहोस्] == ' ') चलाउनुहोस्++;
        int 끝 = चलाउनुहोस्;
        while (끝 < लम्बाइ_मान && 입력[끝] != ' ') 끝++;
        int प्रविष्टि_मान = खोज_गर्नुहोस्_प्रविष्टि(입력, चलाउनुहोस्, 끝 - चलाउनुहोस्);
        if (प्रविष्टि_मान == 0) return -2;
        int स्थिति = 수(प्रविष्टि_मान + 16), आकार = 수(प्रविष्टि_मान + 20);
        if (स्थिति < 8 + 묶음개수() * 24 || आकार < 52 || स्थिति > मोबाइल_मान.실행묶음크기() - आकार) return -8;
        int फाइल = मोबाइल_मान.실행묶음() + स्थिति;
        int प्रविष्टि_अंक_मान = वैध_गर्नुहोस्(फाइल, आकार);
        if (प्रविष्टि_अंक_मान < 0) return प्रविष्टि_अंक_मान;
        मोबाइल_मान.प्रयोगकर्ता_खाली_गर्नुहोस्_टिओसी();
        int तालिका_राख्नुहोस् = 수(फाइल + 28), 개수 = 짧은수(फाइल + 44);
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 개수; अनुक्रमणिका++) {
            int विवरण_हेर्ने_सुविधा_तालिका = फाइल + तालिका_राख्नुहोस् + अनुक्रमणिका * 32;
            if (수(विवरण_हेर्ने_सुविधा_तालिका) != 1) continue;
            int 원본 = फाइल + 수(विवरण_हेर्ने_सुविधा_तालिका + 4), गन्तव्य_मान = 수(विवरण_हेर्ने_सुविधा_तालिका + 8), फाइल_साइज = 수(विवरण_हेर्ने_सुविधा_तालिका + 16);
            for (int बाइट_मान = 0; बाइट_मान < फाइल_साइज; बाइट_मान++) मोबाइल_मान.लेख्नुहोस्_मेमोरी(गन्तव्य_मान + बाइट_मान, मोबाइल_मान.기억읽기(원본 + बाइट_मान));
        }
        인수수 = 0;
        int भण्डार_गर्नुहोस्_मान = तर्क_सुरु;
        while (끝 < लम्बाइ_मान) {
            while (끝 < लम्बाइ_मान && 입력[끝] == ' ') 끝++;
            if (끝 == लम्बाइ_मान) break;
            if (인수수 == तर्क_ठेगाना.length) return -22;
            चलाउनुहोस् = 끝;
            while (끝 < लम्बाइ_मान && 입력[끝] != ' ') 끝++;
            तर्क_ठेगाना[인수수++] = भण्डार_गर्नुहोस्_मान;
            수쓰기(भण्डार_गर्नुहोस्_मान, 끝 - चलाउनुहोस्);
            for (int वर्ण_मान = चलाउनुहोस्; वर्ण_मान < 끝; वर्ण_मान++) 수쓰기(भण्डार_गर्नुहोस्_मान + 4 + (वर्ण_मान - चलाउनुहोस्) * 4, 입력[वर्ण_मान]);
            भण्डार_गर्नुहोस्_मान += 4 + (끝 - चलाउनुहोस्) * 4;
        }
        सञ्जाल_चाङ.स्पष्ट_प्रक्रिया();
        파일서술자관리.सुरु_प्रक्रिया();
        int मापन = मोबाइल_मान.चलाउनुहोस्_प्रयोगकर्ता_अनुप्रयोग(प्रविष्टि_अंक_मान, प्रयोगकर्ता_समाप्त_गर्नुहोस् - 16);
        파일서술자관리.स्पष्ट_प्रक्रिया();
        सञ्जाल_चाङ.स्पष्ट_प्रक्रिया();
        return मापन;
    }
}
