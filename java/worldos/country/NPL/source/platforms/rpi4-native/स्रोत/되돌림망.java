/** 첫 네트워크 तह_मान: 단일 कर्णेल_मान 안의 IPv4/UDP 루프백 ट्रान्सफर_मान.
 * 외부 IP는 ENETUNREACH. Ethernet/IP 패킷 드라이버를 대신한다고 표시하지 않는다.
 * समाप्त_गर्नुहोस्_अंक 8개, 끝점당 전문 4개, 전문당 512바이트. 모든 호출은 비차단이다.
 */
public final class 되돌림망 {
    static int[] 사용 = new int[8];
    static int[] पोर्ट_मान = new int[8];
    static int[] ठेगाना = new int[8];
    static int[] 앞 = new int[8];
    static int[] 개수 = new int[8];
    static int[] 받은창구 = new int[8];
    static int[] लम्बाइ_मान = new int[32];
    static int[] 보낸창구 = new int[32];
    static int[] लगत = new int[32 * 512];
    static int[] फरवार्ड_मान = new int[512];
    static int 다음창구 = 49152;
    static int रुजू_गर्नुहोस्(int अनुक्रमणिका) { return अनुक्रमणिका >= 32 && अनुक्रमणिका < 40 && 사용[अनुक्रमणिका - 32] != 0 ? अनुक्रमणिका - 32 : -1; }
    static boolean 겹침(int अनुक्रमणिका) {
        for (int स्लट_प्रविष्टि = 0; स्लट_प्रविष्टि < 8; स्लट_प्रविष्टि++) if (사용[स्लट_प्रविष्टि] != 0 && पोर्ट_मान[स्लट_प्रविष्टि] == अनुक्रमणिका) return true;
        return false;
    }
    static int 임시창구() {
        for (int 시도 = 0; 시도 < 16; 시도++) {
            int 후보 = 다음창구++;
            if (다음창구 > 65535) 다음창구 = 49152;
            if (!겹침(후보)) return 후보;
        }
        return -98;
    }
    public static int सिर्जना_प्रविष्टि(int 영역, int 종류, int केस_मान) {
        if (영역 != 2) return -97;
        if (종류 != 2 || (केस_मान != 0 && केस_मान != 17)) return -93;
        for (int स्लट_प्रविष्टि = 0; स्लट_प्रविष्टि < 8; स्लट_प्रविष्टि++) if (사용[स्लट_प्रविष्टि] == 0) {
            사용[स्लट_प्रविष्टि] = 1; पोर्ट_मान[स्लट_प्रविष्टि] = 0; ठेगाना[स्लट_प्रविष्टि] = 0; 앞[स्लट_प्रविष्टि] = 0; 개수[स्लट_प्रविष्टि] = 0; 받은창구[स्लट_प्रविष्टि] = 0;
            return स्लट_प्रविष्टि + 32;
        }
        return -24;
    }
    public static int 묶기(int अनुक्रमणिका, int सञ्जाल_ठेगाना, int 창구번호) {
        int स्लट_प्रविष्टि = रुजू_गर्नुहोस्(अनुक्रमणिका);
        if (स्लट_प्रविष्टि < 0) return -9;
        if (सञ्जाल_ठेगाना != 0 && सञ्जाल_ठेगाना != 0x7f000001) return -99;
        if (पोर्ट_मान[स्लट_प्रविष्टि] != 0 || 창구번호 < 0 || 창구번호 > 65535) return -22;
        if (창구번호 == 0) 창구번호 = 임시창구();
        if (창구번호 < 0) return 창구번호;
        if (겹침(창구번호)) return -98;
        पोर्ट_मान[स्लट_प्रविष्टि] = 창구번호; ठेगाना[स्लट_प्रविष्टि] = सञ्जाल_ठेगाना; return 0;
    }
    public static int 자료넣기(int अनुक्रमणिका, int मान) {
        if (अनुक्रमणिका < 0 || अनुक्रमणिका >= 512) return -22;
        फरवार्ड_मान[अनुक्रमणिका] = मान & 255; return 0;
    }
    public static int 자료읽기(int अनुक्रमणिका) { return अनुक्रमणिका >= 0 && अनुक्रमणिका < 512 ? फरवार्ड_मान[अनुक्रमणिका] : -22; }
    public static int पठाउनुहोस्(int अनुक्रमणिका, int सञ्जाल_ठेगाना, int 창구번호, int आकार) {
        int स्लट_प्रविष्टि = रुजू_गर्नुहोस्(अनुक्रमणिका);
        if (स्लट_प्रविष्टि < 0) return -9;
        if (सञ्जाल_ठेगाना != 0x7f000001) return -101;
        if (창구번호 < 1 || 창구번호 > 65535) return -22;
        if (आकार < 0 || आकार > 512) return -90;
        if (पोर्ट_मान[स्लट_प्रविष्टि] == 0) {
            int मापन = 묶기(अनुक्रमणिका, 0x7f000001, 0);
            if (मापन < 0) return मापन;
        }
        int गन्तव्य_मान = -1;
        for (int 후보 = 0; 후보 < 8; 후보++) if (사용[후보] != 0 && पोर्ट_मान[후보] == 창구번호) गन्तव्य_मान = 후보;
        if (गन्तव्य_मान < 0) return -111;
        if (개수[गन्तव्य_मान] == 4) return -11;
        int राख्नुहोस्_अनुक्रमणिका = गन्तव्य_मान * 4 + (앞[गन्तव्य_मान] + 개수[गन्तव्य_मान]) % 4;
        for (int बाइट_मान = 0; बाइट_मान < आकार; बाइट_मान++) लगत[राख्नुहोस्_अनुक्रमणिका * 512 + बाइट_मान] = फरवार्ड_मान[बाइट_मान];
        लम्बाइ_मान[राख्नुहोस्_अनुक्रमणिका] = आकार; 보낸창구[राख्नुहोस्_अनुक्रमणिका] = पोर्ट_मान[स्लट_प्रविष्टि]; 개수[गन्तव्य_मान]++;
        return आकार;
    }
    public static int 받기(int अनुक्रमणिका, int 용량) {
        int स्लट_प्रविष्टि = रुजू_गर्नुहोस्(अनुक्रमणिका);
        if (स्लट_प्रविष्टि < 0) return -9;
        if (용량 < 0 || 용량 > 512) return -22;
        if (개수[स्लट_प्रविष्टि] == 0) return -11;
        int राख्नुहोस्_अनुक्रमणिका = स्लट_प्रविष्टि * 4 + 앞[स्लट_प्रविष्टि];
        int आकार = लम्बाइ_मान[राख्नुहोस्_अनुक्रमणिका] < 용량 ? लम्बाइ_मान[राख्नुहोस्_अनुक्रमणिका] : 용량;
        for (int बाइट_मान = 0; बाइट_मान < आकार; बाइट_मान++) फरवार्ड_मान[बाइट_मान] = लगत[राख्नुहोस्_अनुक्रमणिका * 512 + बाइट_मान];
        받은창구[स्लट_प्रविष्टि] = 보낸창구[राख्नुहोस्_अनुक्रमणिका]; 앞[स्लट_प्रविष्टि] = (앞[स्लट_प्रविष्टि] + 1) % 4; 개수[स्लट_प्रविष्टि]--;
        return आकार;
    }
    public static int 창구읽기(int अनुक्रमणिका) { int स्लट_प्रविष्टि = रुजू_गर्नुहोस्(अनुक्रमणिका); return स्लट_प्रविष्टि < 0 ? -9 : पोर्ट_मान[स्लट_प्रविष्टि]; }
    public static int 주소읽기(int अनुक्रमणिका) { int स्लट_प्रविष्टि = रुजू_गर्नुहोस्(अनुक्रमणिका); return स्लट_प्रविष्टि < 0 ? -9 : ठेगाना[स्लट_प्रविष्टि]; }
    public static int 보낸곳(int अनुक्रमणिका) { int स्लट_प्रविष्टि = रुजू_गर्नुहोस्(अनुक्रमणिका); return स्लट_प्रविष्टि < 0 ? -9 : 받은창구[स्लट_प्रविष्टि]; }
    public static int बन्दगर्नुहोस्(int अनुक्रमणिका) {
        int स्लट_प्रविष्टि = रुजू_गर्नुहोस्(अनुक्रमणिका); if (स्लट_प्रविष्टि < 0) return -9;
        사용[स्लट_प्रविष्टि] = 0; 개수[स्लट_प्रविष्टि] = 0; पोर्ट_मान[स्लट_प्रविष्टि] = 0; return 0;
    }
}
