/** 문자(文字), एनकोडिङ_मान(符號): UTF-8 바이트와 UTF-16 문자열의 변환. सामान्यकरण_गर्नुहोस्_मान/조합 입력기는 별개다. */
public final class 문자 {
    public static int 바이트수(byte[] लगत) { return लगत.length; }
    private 문자() {}
    public static int लम्बाइ_मान(String पाठ) { return पाठ.length(); }
    public static boolean 같음(String 앞, String पछाडि_मान) { return 앞 == null ? पछाडि_मान == null : 앞.equals(पछाडि_मान); }
    public static String टाँस्नुहोस्_पाठ(String 앞, String पछाडि_मान) { return 앞.concat(पछाडि_मान); }
    public static String टुक्राउने_मान(String पाठ, int चलाउनुहोस्, int 끝) { return पाठ.substring(चलाउनुहोस्, 끝); }
    public static int पदच्छेद_गर्नुहोस्_पूर्ण_सङ्ख्या(String पाठ) { try { return Integer.parseInt(पाठ); } catch (NumberFormatException त्रुटि) { throw new 숫자형식예외("숫자의 형식이나 범위를 확인하십시오."); } }
    public static String लेख्नुहोस्_पूर्ण_सङ्ख्या_मान(int 수) { return Integer.toString(수); }
    public static int 코드포인트수(String पाठ) {
        int 수 = 0;
        for (int लुप_अनुक्रमणिका = 0; लुप_अनुक्रमणिका < पाठ.length(); लुप_अनुक्रमणिका++, 수++) {
            int वर्ण_सङ्केत = पाठ.charAt(लुप_अनुक्रमणिका);
            if (वर्ण_सङ्केत >= 0xd800 && वर्ण_सङ्केत <= 0xdbff && लुप_अनुक्रमणिका + 1 < पाठ.length() && पाठ.charAt(लुप_अनुक्रमणिका + 1) >= 0xdc00 && पाठ.charAt(लुप_अनुक्रमणिका + 1) <= 0xdfff) लुप_अनुक्रमणिका++;
        }
        return 수;
    }
    public static byte[] 부호화(String पाठ) {
        byte[] 임시 = new byte[पाठ.length() * 3]; int 쓴수 = 0;
        for (int लुप_अनुक्रमणिका = 0; लुप_अनुक्रमणिका < पाठ.length(); लुप_अनुक्रमणिका++) {
            int वर्ण_सङ्केत = पाठ.charAt(लुप_अनुक्रमणिका);
            if (वर्ण_सङ्केत >= 0xd800 && वर्ण_सङ्केत <= 0xdbff && लुप_अनुक्रमणिका + 1 < पाठ.length() && पाठ.charAt(लुप_अनुक्रमणिका + 1) >= 0xdc00 && पाठ.charAt(लुप_अनुक्रमणिका + 1) <= 0xdfff) वर्ण_सङ्केत = 0x10000 + ((वर्ण_सङ्केत - 0xd800) << 10) + पाठ.charAt(++लुप_अनुक्रमणिका) - 0xdc00;
            else if (वर्ण_सङ्केत >= 0xd800 && वर्ण_सङ्केत <= 0xdfff) वर्ण_सङ्केत = '?';
            if (वर्ण_सङ्केत < 128) 임시[쓴수++] = (byte)वर्ण_सङ्केत;
            else if (वर्ण_सङ्केत < 2048) { 임시[쓴수++] = (byte)(192 | वर्ण_सङ्केत >> 6); 임시[쓴수++] = (byte)(128 | वर्ण_सङ्केत & 63); }
            else if (वर्ण_सङ्केत < 65536) { 임시[쓴수++] = (byte)(224 | वर्ण_सङ्केत >> 12); 임시[쓴수++] = (byte)(128 | वर्ण_सङ्केत >> 6 & 63); 임시[쓴수++] = (byte)(128 | वर्ण_सङ्केत & 63); }
            else { 임시[쓴수++] = (byte)(240 | वर्ण_सङ्केत >> 18); 임시[쓴수++] = (byte)(128 | वर्ण_सङ्केत >> 12 & 63); 임시[쓴수++] = (byte)(128 | वर्ण_सङ्केत >> 6 & 63); 임시[쓴수++] = (byte)(128 | वर्ण_सङ्केत & 63); }
        }
        byte[] मापन = new byte[쓴수]; System.arraycopy(임시, 0, मापन, 0, 쓴수); return मापन;
    }
    /** 잘못된 UTF-8은 잘못된인수예외으로 거부한다. */
    public static String गुप्तलेखन_उल्टाउनुहोस्_लगत(byte[] बाइट_मान) {
        StringBuilder मापन = new StringBuilder();
        for (int लुप_अनुक्रमणिका = 0; लुप_अनुक्रमणिका < बाइट_मान.length;) {
            int वर्ण_सङ्केत = बाइट_मान[लुप_अनुक्रमणिका++] & 255, 수 = वर्ण_सङ्केत < 128 ? 0 : वर्ण_सङ्केत >= 194 && वर्ण_सङ्केत < 224 ? 1 : वर्ण_सङ्केत >= 224 && वर्ण_सङ्केत < 240 ? 2 : वर्ण_सङ्केत >= 240 && वर्ण_सङ्केत <= 244 ? 3 : -1;
            if (수 < 0 || बाइट_मान.length - लुप_अनुक्रमणिका < 수) throw new 잘못된인수예외("잘못된 UTF-8");
            int 최소 = 수 == 1 ? 128 : 수 == 2 ? 2048 : 수 == 3 ? 65536 : 0;
            if (수 > 0) वर्ण_सङ्केत &= (1 << (6 - 수)) - 1;
            for (int भित्री_जोड्नी_राख्नुहोस् = 0; भित्री_जोड्नी_राख्नुहोस् < 수; भित्री_जोड्नी_राख्नुहोस्++) { int पछाडि_मान = बाइट_मान[लुप_अनुक्रमणिका++] & 255; if ((पछाडि_मान & 192) != 128) throw new 잘못된인수예외("잘못된 UTF-8"); वर्ण_सङ्केत = वर्ण_सङ्केत << 6 | पछाडि_मान & 63; }
            if (वर्ण_सङ्केत < 최소 || वर्ण_सङ्केत > 0x10ffff || वर्ण_सङ्केत >= 0xd800 && वर्ण_सङ्केत <= 0xdfff) throw new 잘못된인수예외("잘못된 UTF-8");
            if (वर्ण_सङ्केत < 65536) मापन.append((char)वर्ण_सङ्केत);
            else { वर्ण_सङ्केत -= 65536; मापन.append((char)(0xd800 | वर्ण_सङ्केत >> 10)); मापन.append((char)(0xdc00 | वर्ण_सङ्केत & 1023)); }
        }
        return मापन.toString();
    }
}
