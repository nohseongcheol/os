package नेपाल.JNplOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import नेपाल.JNplOS.기억공간.पृष्ठ_प्रबन्धक;
import नेपाल.JNplOS.फाइल_प्रणाली.파일서술자표;

/** प्रक्रिया_मान 식별자와 라운드로빈 तयार_गर्नुहोस् 대기열을 관리한다. */
public final class निर्धारक {
    private final पृष्ठ_प्रबन्धक 쪽관리;
    private final Map<Integer, प्रक्रिया_मान> प्रक्रिया_सूची = new HashMap<Integer, प्रक्रिया_मान>();
    private final Queue<प्रक्रिया_मान> 준비대기열 = new ArrayDeque<प्रक्रिया_मान>();
    private int अर्को_परिचायक = 1;

    public निर्धारक(पृष्ठ_प्रबन्धक 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public प्रक्रिया_मान 첫과정(파일서술자표 파일서술자) {
        प्रक्रिया_मान 새과정 = new प्रक्रिया_मान(निर्धारण_गर्नुहोस्_परिचायक(), 0, 쪽관리.새주소공간(), 파일서술자);
        प्रक्रिया_सूची.put(Integer.valueOf(새과정.परिचायक_मान()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public प्रक्रिया_मान 복제(प्रक्रिया_मान 부모) {
        प्रक्रिया_मान बच्चा_मान = new प्रक्रिया_मान(
                निर्धारण_गर्नुहोस्_परिचायक(),
                부모.परिचायक_मान(),
                쪽관리.쓰기시복사복제(부모.ठेगाना_स्थान()),
                부모.파일서술자().복제());
        बच्चा_मान.프로그램끝설정(부모.프로그램끝());
        प्रक्रिया_सूची.put(Integer.valueOf(बच्चा_मान.परिचायक_मान()), बच्चा_मान);
        준비대기열.offer(बच्चा_मान);
        return बच्चा_मान;
    }

    public प्रक्रिया_मान अर्को_प्रक्रिया() {
        int 검사수 = 준비대기열.size();
        for (int अनुक्रमणिका = 0; अनुक्रमणिका < 검사수; अनुक्रमणिका++) {
            प्रक्रिया_मान अर्को_वस्तु = 준비대기열.poll();
            if (अर्को_वस्तु != null && (अर्को_वस्तु.स्थिति_मान() == प्रक्रिया_स्थिति.तयार_गर्नुहोस् || अर्को_वस्तु.स्थिति_मान() == प्रक्रिया_स्थिति.कार्यान्वयन_गर्नुहोस्_आदेश)) {
                अर्को_वस्तु.सेट_स्थिति(प्रक्रिया_स्थिति.कार्यान्वयन_गर्नुहोस्_आदेश);
                준비대기열.offer(अर्को_वस्तु);
                return अर्को_वस्तु;
            }
        }
        return null;
    }

    public int 자식기다리기(प्रक्रिया_मान 부모, int बच्चा_परिचायक, boolean 기다리지않음) {
        for (प्रक्रिया_मान 후보 : प्रक्रिया_सूची.values()) {
            if (후보.부모식별자() != 부모.परिचायक_मान()) {
                continue;
            }
            if (बच्चा_परिचायक > 0 && 후보.परिचायक_मान() != बच्चा_परिचायक) {
                continue;
            }
            if (후보.स्थिति_मान() == प्रक्रिया_स्थिति.बाहिर_जानुहोस्_अनुप्रयोग) {
                int मापन = (후보.종료값() & 0xff) << 8;
                प्रक्रिया_सूची.remove(Integer.valueOf(후보.परिचायक_मान()));
                return मापन;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public प्रक्रिया_मान खोज_गर्नुहोस्_प्रक्रिया(int परिचायक_मान) {
        return प्रक्रिया_सूची.get(Integer.valueOf(परिचायक_मान));
    }

    private int निर्धारण_गर्नुहोस्_परिचायक() {
        return अर्को_परिचायक++;
    }
}
