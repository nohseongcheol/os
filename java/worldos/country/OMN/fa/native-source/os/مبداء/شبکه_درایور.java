/** PCI RTL8139 (10ec:8139), 단일 ارسال_مقدار 버퍼와 8KiB 수신 حلقه_مقدار. 인터럽트 대신 폴링한다. */
public final class شبکه_درایور {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] دستگاه_آدرس_856320c2 = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int مرتب_کردن) {
        دستگاه_مقدار.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | مرتب_کردن);
        return دستگاه_مقدار.입출력정수읽기(0xcfc);
    }

    static boolean آماده_کردن() {
        int 장치번호 = -1;
        for (int فهرست = 0; فهرست < 32; فهرست++) {
            if (설정읽기(فهرست, 0) == 0x813910ec) { 장치번호 = فهرست; break; }
        }
        if (장치번호 < 0) return false;
        int مقدار_پیش_فرض = 설정읽기(장치번호, 0x10);
        if ((مقدار_پیش_فرض & 1) == 0 || (مقدار_پیش_فرض & 0xfffffffc) < 0x100 || (مقدار_پیش_فرض & 0xfffffffc) > 65535) return false;
        입출력기준주소 = مقدار_پیش_فرض & 0xfffc;
        int فرمان = 설정읽기(장치번호, 4);
        دستگاه_مقدار.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        دستگاه_مقدار.입출력짧은수쓰기(0xcfc, فرمان | 5); // I/O 및 bus master اجازه_مقدار, PCI وضعیت_مقدار 비트는 건드리지 않음
        دستگاه_مقدار.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!بازنشانی_مقدار()) { 입출력기준주소 = 0; return false; }
        for (int فهرست = 0; فهرست < 6; فهرست++) دستگاه_آدرس_856320c2[فهرست] = دستگاه_مقدار.입출력바이트읽기(입출력기준주소 + فهرست);
        return true;
    }

    static boolean بازنشانی_مقدار() {
        دستگاه_مقدار.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int اجرا_2 = دستگاه_مقدار.밀리초();
        while ((دستگاه_مقدار.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (دستگاه_مقدار.밀리초() - اجرا_2 > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        دستگاه_مقدار.입출력정수쓰기(입출력기준주소 + 0x30, دستگاه_مقدار.شبکه_حافظه());
        for (int فهرست = 0; فهرست < 4; فهرست++) دستگاه_مقدار.입출력정수쓰기(입출력기준주소 + 0x20 + فهرست * 4, دستگاه_مقدار.شبکه_حافظه() + 12288);
        دستگاه_مقدار.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        دستگاه_مقدار.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        دستگاه_مقدار.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        دستگاه_مقدار.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/پخش_مقدار, wrap 연속 ذخیره_مقدار, 8KiB
        دستگاه_مقدار.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int ارسال(int[] داده_ها, int طول_مقدار) {
        if (입출력기준주소 == 0) return -19;
        if (طول_مقدار < 14 || طول_مقدار > 1514) return -90;
        int وضعیت_تبدیل = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int اجرا_2 = دستگاه_مقدار.밀리초();
        while ((دستگاه_مقدار.입출력정수읽기(وضعیت_تبدیل) & 0x2000) == 0)
            if (دستگاه_مقدار.밀리초() - اجرا_2 > 100) return -110;
        int اندازه = طول_مقدار < 60 ? 60 : طول_مقدار;
        for (int فهرست = 0; فهرست < اندازه; فهرست++)
            دستگاه_مقدار.نوشتن_حافظه(دستگاه_مقدار.شبکه_حافظه() + 12288 + فهرست, فهرست < طول_مقدار ? داده_ها[فهرست] : 0);
        دستگاه_مقدار.입출력정수쓰기(وضعیت_تبدیل, اندازه | 0x00080000);
        اجرا_2 = دستگاه_مقدار.밀리초();
        while ((دستگاه_مقدار.입출력정수읽기(وضعیت_تبدیل) & 0xe0008000) == 0)
            if (دستگاه_مقدار.밀리초() - اجرا_2 > 100) return -110;
        if ((دستگاه_مقدار.입출력정수읽기(وضعیت_تبدیل) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return طول_مقدار;
    }

    static int 받기(int[] داده_ها) {
        if (입출력기준주소 == 0) return 0;
        if ((دستگاه_مقدار.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!بازنشانی_مقدار()) 입출력기준주소 = 0;
            return 0;
        }
        if ((دستگاه_مقدار.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = دستگاه_مقدار.شبکه_حافظه() + 수신위치;
        int وضعیت_مقدار = 실행관리.짧은수(머리), اندازه = 실행관리.짧은수(머리 + 2);
        if (اندازه == 0xfff0) return 0; // DMA 진행 중
        if (اندازه < 4 || اندازه > 1518) {
            오류수++;
            if (!بازنشانی_مقدار()) 입출력기준주소 = 0;
            return 0;
        }
        int طول_مقدار = اندازه - 4;
        if ((وضعیت_مقدار & 1) != 0) {
            for (int فهرست = 0; فهرست < طول_مقدار; فهرست++) داده_ها[فهرست] = دستگاه_مقدار.기억읽기(머리 + 4 + فهرست);
            수신수++;
        } else { طول_مقدار = 0; 오류수++; }
        수신위치 = (수신위치 + اندازه + 4 + 3) & ~3;
        수신위치 &= 8191;
        دستگاه_مقدار.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        دستگاه_مقدار.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return طول_مقدار;
    }
}
