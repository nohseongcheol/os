#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from رایانه_نما import صفحه_کلید


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.متن_حافظه_میانی = ''
        def ارسال(داده_ها):
            for نویسه_داده_ها in داده_ها.decode('utf-8'):
                if نویسه_داده_ها == '\x7f': 자신.متن_حافظه_میانی = 자신.متن_حافظه_میانی[:-1]
                else: 자신.متن_حافظه_میانی += نویسه_داده_ها
        자신.صفحه_کلید_ورودی = صفحه_کلید(ارسال)

    def فشار_دادن_کلید(자신, نماد_مقدار):
        자신.صفحه_کلید_ورودی.누름값(True, نماد_مقدار)
        자신.صفحه_کلید_ورودی.누름값(False, نماد_مقدار)

    def تایپ_کردن_دسته(자신, 누름열):
        for 누름값 in 누름열: 자신.فشار_دادن_کلید(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.فشار_دادن_کلید(0xffc6); 자신.تایپ_کردن_دسته(누름열)
                자신.assertEqual(자신.متن_حافظه_میانی, 예상결과)

    def test_앞글자지우기(자신):
        자신.فشار_دادن_کلید(0xff31); 자신.تایپ_کردن_دسته('dlfr')
        자신.assertEqual(자신.متن_حافظه_میانی,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.فشار_دادن_کلید(0xff08); 자신.assertEqual(자신.متن_حافظه_میانی,예상결과)
        자신.تایپ_کردن_دسته('gksk'); 자신.assertEqual(자신.متن_حافظه_میانی,'하나')
        자신.فشار_دادن_کلید(0xff08); 자신.assertEqual(자신.متن_حافظه_میانی,'하ㄴ')

    def test_전환반복확정(자신):
        자신.تایپ_کردن_دسته('echo ')
        자신.صفحه_کلید_ورودی.누름값(True,0xffe1)
        자신.صفحه_کلید_ورودی.누름값(True,32); 자신.صفحه_کلید_ورودی.누름값(True,32)
        자신.صفحه_کلید_ورودی.누름값(False,32); 자신.صفحه_کلید_ورودی.누름값(False,0xffe1)
        자신.assertTrue(자신.صفحه_کلید_ورودی.한글여부)
        자신.تایپ_کردن_دسته('gksrmf'); 자신.فشار_دادن_کلید(0xff31); 자신.تایپ_کردن_دسته(' English')
        자신.assertEqual(자신.متن_حافظه_میانی,'echo 한글 English')
        자신.assertFalse(자신.صفحه_کلید_ورودی.한글여부)
        자신.فشار_دادن_کلید(0xffc6); 자신.تایپ_کردن_دسته('rk'); 자신.فشار_دادن_کلید(0xff51)
        자신.تایپ_کردن_دسته('sk'); 자신.assertTrue(자신.متن_حافظه_میانی.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.فشار_دادن_کلید(0xffc6); 자신.تایپ_کردن_دسته('rk')
        자신.صفحه_کلید_ورودی.کلیپ_بورد_مقدار='جای_گذاری_مقدار'.encode()
        자신.صفحه_کلید_ورودی.누름값(True,0xffe3); 자신.صفحه_کلید_ورودی.누름값(True,0xffe1)
        자신.فشار_دادن_کلید(ord('v'))
        자신.صفحه_کلید_ورودی.누름값(False,0xffe1); 자신.صفحه_کلید_ورودی.누름값(False,0xffe3)
        자신.فشار_دادن_کلید(0x0100d55c); 자신.تایپ_کردن_دسته('sk')
        자신.assertEqual(자신.متن_حافظه_میانی,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
