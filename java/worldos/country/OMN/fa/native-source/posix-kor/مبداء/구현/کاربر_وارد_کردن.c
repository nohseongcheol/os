#include "호출경계.h"
extern int main(int 인수개수, char **آرگومان_لیست);
static char آرگومان_حافظه[2048];
static char *آرگومان_لیست[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 اجرا_فرمان 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    آرگومان_لیست[0] = "jkoros-app";
    int مرتب_کردن = 0;
    for (int فهرست = 0; فهرست < 개수; فهرست++) {
        const int *원본 = (const int *)jkoros_syscall(3, فهرست, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        آرگومان_لیست[فهرست + 1] = آرگومان_حافظه + مرتب_کردن;
        for (int شکاف_ورودی = 0; شکاف_ورودی < 원본[0]; شکاف_ورودی++) {
            if (مرتب_کردن >= 2047) return 126;
            آرگومان_حافظه[مرتب_کردن++] = 원본[شکاف_ورودی + 1];
        }
        آرگومان_حافظه[مرتب_کردن++] = 0;
    }
    آرگومان_لیست[개수 + 1] = 0;
    return main(개수 + 1, آرگومان_لیست);
}
