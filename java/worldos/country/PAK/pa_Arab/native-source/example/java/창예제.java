import 한국어.자체.کھڑکی;
import 한국어.자체.پرچی;
import 한국어.자체.متن_قطعہ;
import 한국어.자체.بٹن;
import 한국어.자체.واقعہ_قطار;
import 한국어.자체.출력;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing کھڑکی: pa_Arab 입력 → بٹن → فائل_مینوں_پڑھو_eb81d7d9 متن پھر_تازہ_کرو. */
public class 창예제 implements 실행할일, 동작받이 {
    private کھڑکی 인사창;
    private متن_قطعہ ناں_قطعہ;
    private پرچی 인사말;
    private int 인사횟수;

    public void بنڑاؤ_کھڑکی() {
        인사창 = new کھڑکی("pa_Arab Swing", 460, 300);
        인사창.اضافہ_کرو_عنصر(new پرچی("pa_Arab", 20, 20, 420, 28));
        ناں_قطعہ = new متن_قطعہ("pa_Arab", 20, 64, 420, 30);
        인사말 = new پرچی("pa_Arab", 20, 152, 420, 28);
        인사창.اضافہ_کرو_عنصر(ناں_قطعہ);
        인사창.اضافہ_کرو_عنصر(new بٹن("인사하기", 20, 108, 180, 32, this));
        인사창.اضافہ_کرو_عنصر(인사말);
        인사창.اضافہ_کرو_عنصر(new پرچی("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.نمایش_کرو_کھڑکی();
        출력.لکھو_لائن("GUI 예제 تیاری_کرو: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.لکھو_متن("pa_Arab, " + ناں_قطعہ.글읽기() + "님! (" + 인사횟수 + ")");
        출력.لکھو_لائن("GUI 인사: " + 인사말.글읽기());
    }

    public void نفاذ_کرو_ٹاسک() { بنڑاؤ_کھڑکی(); }
    public void 동작받기(동작알림 알림) {
        출력.لکھو_لائن("کم 알림: " + 알림.حکم_متن());
        인사하기();
    }
    public static void چلاؤ() {
        واقعہ_قطار.나중에실행(new 창예제());
    }
}
