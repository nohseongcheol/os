/** 최대 سائز/홀수 لمبائی_قدر 데이터그램으로 اصلی_کوائف RTL8139 수신 لوپ_قدر 순환을 시험한다. */
public final class نیٹ_ورک_لوپ {
    public static int چلاؤ() {
        if (صارف.인수개수() != 1) { صارف.لکھو("Usage: run stress PORT\n"); return 2; }
        String متن = صارف.인수(0);
        int دہانہ_قدر = 0;
        for (int اشاریہ = 0; اشاریہ < متن.length(); اشاریہ++) {
            if (متن.charAt(اشاریہ) < '0' || متن.charAt(اشاریہ) > '9' || دہانہ_قدر > 6553) return 2;
            دہانہ_قدر = دہانہ_قدر * 10 + متن.charAt(اشاریہ) - '0';
        }
        if (دہانہ_قدر < 1 || دہانہ_قدر > 65535) return 2;
        int نبٹنا_قدر = صارف.بنڑاؤ_نیٹ_ورک(0);
        if (نبٹنا_قدر < 0) return 3;
        int[] کوائف = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int لمبائی_قدر = 1024 - (회차 & 1);
            for (int اشاریہ = 0; اشاریہ < لمبائی_قدر; اشاریہ++) کوائف[اشاریہ] = (اشاریہ + 회차) & 255;
            if (صارف.بھیجو_کوائف(نبٹنا_قدر, 0x0a000202, دہانہ_قدر, کوائف, لمبائی_قدر) != لمبائی_قدر) return 4;
            if (صارف.자료받기(نبٹنا_قدر, کوائف, 300) != لمبائی_قدر) return 5;
            for (int اشاریہ = 0; اشاریہ < لمبائی_قدر; اشاریہ++) if (کوائف[اشاریہ] != ((اشاریہ + 회차) & 255)) return 6;
        }
        صارف.بند_کرو_نیٹ_ورک(نبٹنا_قدر);
        صارف.لکھو("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
