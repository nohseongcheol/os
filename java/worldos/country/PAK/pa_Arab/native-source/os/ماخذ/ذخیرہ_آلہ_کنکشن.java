/** 첫 IDE 장치의 512바이트 논리 سیکشن_قدر. 이 계층은 포맷을 만들거나 임의 장치를 지우지 않는다. */
public final class ذخیرہ_آلہ_کنکشن {
    static boolean 사용가능 = false;
    static int[] سیکشن_کوائف = new int[512];
    static void 잠깐기다리기() {
        for (int اشاریہ = 0; اشاریہ < 4; اشاریہ++) آلہ_قدر.입출력바이트읽기(0x3f6);
    }
    static int 준비기다리기(boolean 자료필요) {
        int چلاؤ = آلہ_قدر.밀리초();
        while (آلہ_قدر.밀리초() - چلاؤ < 500) {
            int حالت_قدر = آلہ_قدر.입출력바이트읽기(0x1f7);
            if (حالت_قدر == 0 || حالت_قدر == 255) return -19;
            if ((حالت_قدر & 128) == 0) {
                if ((حالت_قدر & 33) != 0) return -5;
                if (!자료필요 || (حالت_قدر & 8) != 0) return 0;
            }
            آلہ_قدر.잠시양보();
        }
        return -110;
    }
    static int 요청(int سیکشن_قدر, int حکم) {
        if (سیکشن_قدر < 0 || سیکشن_قدر >= 2048) return -22;
        آلہ_قدر.입출력바이트쓰기(0x3f6, 2); // polling; IDE IRQ 사용 안 함
        آلہ_قدر.입출력바이트쓰기(0x1f6, 0xe0); 잠깐기다리기();
        int 결과 = 준비기다리기(false);
        if (결과 < 0) return 결과;
        آلہ_قدر.입출력바이트쓰기(0x1f2, 1);
        آلہ_قدر.입출력바이트쓰기(0x1f3, سیکشن_قدر & 255);
        آلہ_قدر.입출력바이트쓰기(0x1f4, (سیکشن_قدر >>> 8) & 255);
        آلہ_قدر.입출력바이트쓰기(0x1f5, 0);
        آلہ_قدر.입출력바이트쓰기(0x1f7, حکم); 잠깐기다리기();
        return 준비기다리기(true);
    }
    static int 읽기(int سیکشن_قدر) {
        int 결과 = 요청(سیکشن_قدر, 0x20);
        if (결과 < 0) return 결과;
        for (int اشاریہ = 0; اشاریہ < 256; اشاریہ++) {
            int قدر = آلہ_قدر.입출력짧은수읽기(0x1f0);
            سیکشن_کوائف[اشاریہ * 2] = قدر & 255; سیکشن_کوائف[اشاریہ * 2 + 1] = قدر >>> 8;
        }
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int لکھو(int سیکشن_قدر) {
        if (!사용가능 || سیکشن_قدر < 1 || سیکشن_قدر > 518) return -19;
        int 결과 = 요청(سیکشن_قدر, 0x30);
        if (결과 < 0) return 결과;
        for (int اشاریہ = 0; اشاریہ < 256; اشاریہ++)
            آلہ_قدر.입출력짧은수쓰기(0x1f0, سیکشن_کوائف[اشاریہ * 2] | سیکشن_کوائف[اشاریہ * 2 + 1] << 8);
        잠깐기다리기(); return 준비기다리기(false);
    }
    static int 밀어쓰기() {
        if (!사용가능) return -19;
        آلہ_قدر.입출력바이트쓰기(0x1f7, 0xe7); 잠깐기다리기();
        return 준비기다리기(false);
    }
    static int 정수읽기(int 위치) {
        return سیکشن_کوائف[위치] | سیکشن_کوائف[위치 + 1] << 8 | سیکشن_کوائف[위치 + 2] << 16 | سیکشن_کوائف[위치 + 3] << 24;
    }
    static void لکھو_عدد_قدر(int 위치, int قدر) {
        for (int اشاریہ = 0; اشاریہ < 4; اشاریہ++) سیکشن_کوائف[위치 + اشاریہ] = (قدر >>> (اشاریہ * 8)) & 255;
    }
}
