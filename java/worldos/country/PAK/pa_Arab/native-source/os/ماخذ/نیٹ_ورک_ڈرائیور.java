/** PCI RTL8139 (10ec:8139), 단일 بھیجو_قدر 버퍼와 8KiB 수신 لوپ_قدر. 인터럽트 대신 폴링한다. */
public final class نیٹ_ورک_ڈرائیور {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] آلہ_پتا = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int 위치) {
        آلہ_قدر.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | 위치);
        return آلہ_قدر.입출력정수읽기(0xcfc);
    }

    static boolean تیاری_کرو() {
        int 장치번호 = -1;
        for (int اشاریہ = 0; اشاریہ < 32; اشاریہ++) {
            if (설정읽기(اشاریہ, 0) == 0x813910ec) { 장치번호 = اشاریہ; break; }
        }
        if (장치번호 < 0) return false;
        int طےشدہ_قدر = 설정읽기(장치번호, 0x10);
        if ((طےشدہ_قدر & 1) == 0 || (طےشدہ_قدر & 0xfffffffc) < 0x100 || (طےشدہ_قدر & 0xfffffffc) > 65535) return false;
        입출력기준주소 = طےشدہ_قدر & 0xfffc;
        int حکم = 설정읽기(장치번호, 4);
        آلہ_قدر.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        آلہ_قدر.입출력짧은수쓰기(0xcfc, حکم | 5); // I/O 및 bus master اجازت_قدر_688200c4, PCI حالت_قدر 비트는 건드리지 않음
        آلہ_قدر.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!فیر_سیٹ_کرو_قدر()) { 입출력기준주소 = 0; return false; }
        for (int اشاریہ = 0; اشاریہ < 6; اشاریہ++) آلہ_پتا[اشاریہ] = آلہ_قدر.입출력바이트읽기(입출력기준주소 + اشاریہ);
        return true;
    }

    static boolean فیر_سیٹ_کرو_قدر() {
        آلہ_قدر.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int چلاؤ = آلہ_قدر.밀리초();
        while ((آلہ_قدر.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (آلہ_قدر.밀리초() - چلاؤ > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        آلہ_قدر.입출력정수쓰기(입출력기준주소 + 0x30, آلہ_قدر.نیٹ_ورک_میموری());
        for (int اشاریہ = 0; اشاریہ < 4; اشاریہ++) آلہ_قدر.입출력정수쓰기(입출력기준주소 + 0x20 + اشاریہ * 4, آلہ_قدر.نیٹ_ورک_میموری() + 12288);
        آلہ_قدر.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        آلہ_قدر.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        آلہ_قدر.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        آلہ_قدر.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/نشر_کرو_قدر, wrap 연속 ذخیرہ_کرو_قدر, 8KiB
        آلہ_قدر.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int بھیجو(int[] کوائف, int لمبائی_قدر) {
        if (입출력기준주소 == 0) return -19;
        if (لمبائی_قدر < 14 || لمبائی_قدر > 1514) return -90;
        int حالت_دہانہ = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int چلاؤ = آلہ_قدر.밀리초();
        while ((آلہ_قدر.입출력정수읽기(حالت_دہانہ) & 0x2000) == 0)
            if (آلہ_قدر.밀리초() - چلاؤ > 100) return -110;
        int سائز = لمبائی_قدر < 60 ? 60 : لمبائی_قدر;
        for (int اشاریہ = 0; اشاریہ < سائز; اشاریہ++)
            آلہ_قدر.لکھو_میموری(آلہ_قدر.نیٹ_ورک_میموری() + 12288 + اشاریہ, اشاریہ < لمبائی_قدر ? کوائف[اشاریہ] : 0);
        آلہ_قدر.입출력정수쓰기(حالت_دہانہ, سائز | 0x00080000);
        چلاؤ = آلہ_قدر.밀리초();
        while ((آلہ_قدر.입출력정수읽기(حالت_دہانہ) & 0xe0008000) == 0)
            if (آلہ_قدر.밀리초() - چلاؤ > 100) return -110;
        if ((آلہ_قدر.입출력정수읽기(حالت_دہانہ) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return لمبائی_قدر;
    }

    static int 받기(int[] کوائف) {
        if (입출력기준주소 == 0) return 0;
        if ((آلہ_قدر.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!فیر_سیٹ_کرو_قدر()) 입출력기준주소 = 0;
            return 0;
        }
        if ((آلہ_قدر.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = آلہ_قدر.نیٹ_ورک_میموری() + 수신위치;
        int حالت_قدر = 실행관리.짧은수(머리), سائز = 실행관리.짧은수(머리 + 2);
        if (سائز == 0xfff0) return 0; // DMA 진행 중
        if (سائز < 4 || سائز > 1518) {
            오류수++;
            if (!فیر_سیٹ_کرو_قدر()) 입출력기준주소 = 0;
            return 0;
        }
        int لمبائی_قدر = سائز - 4;
        if ((حالت_قدر & 1) != 0) {
            for (int اشاریہ = 0; اشاریہ < لمبائی_قدر; اشاریہ++) کوائف[اشاریہ] = آلہ_قدر.기억읽기(머리 + 4 + اشاریہ);
            수신수++;
        } else { لمبائی_قدر = 0; 오류수++; }
        수신위치 = (수신위치 + سائز + 4 + 3) & ~3;
        수신위치 &= 8191;
        آلہ_قدر.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        آلہ_قدر.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return لمبائی_قدر;
    }
}
