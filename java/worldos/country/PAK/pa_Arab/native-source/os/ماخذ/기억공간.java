/** 부팅 سسٹم_دی_معلومات 조회와 4KiB 고정 سائز 작업 سیکشن_قدر مختص_کرو_ذخیرہ/반환. 일반 물리 صفحہ_قدر 관리자는 아니다. */
public final class 기억공간 {
    static int[] سیکشن_قدر = new int[8192];
    static int[] 사용 = new int[8];

    static int 정수읽기(int پتا) {
        return آلہ_قدر.기억읽기(پتا) | (آلہ_قدر.기억읽기(پتا + 1) << 8)
            | (آلہ_قدر.기억읽기(پتا + 2) << 16) | (آلہ_قدر.기억읽기(پتا + 3) << 24);
    }

    static int 위쪽기억크기() {
        int سسٹم_دی_معلومات = آلہ_قدر.부팅정보();
        if (آلہ_قدر.부팅표식() != 0x2badb002 || سسٹم_دی_معلومات == 0 || (정수읽기(سسٹم_دی_معلومات) & 1) == 0) return -1;
        return 정수읽기(سسٹم_دی_معلومات + 8);
    }

    static int مختص_کرو_ذخیرہ() {
        for (int اشاریہ = 0; اشاریہ < 사용.length; اشاریہ++) {
            if (사용[اشاریہ] == 0) {
                사용[اشاریہ] = 1;
                for (int سلاٹ_داخلہ = 0; سلاٹ_داخلہ < 1024; سلاٹ_داخلہ++) سیکشن_قدر[اشاریہ * 1024 + سلاٹ_داخلہ] = 0;
                return اشاریہ;
            }
        }
        return -1;
    }

    static boolean 반환(int اشاریہ) {
        if (اشاریہ < 0 || اشاریہ >= 사용.length || 사용[اشاریہ] == 0) return false;
        사용[اشاریہ] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int اشاریہ = 0; اشاریہ < 사용.length; اشاریہ++) 개수 += 사용[اشاریہ];
        return 개수;
    }
}
