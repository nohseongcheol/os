/** 디스크 لکھو 없이 동작하는 작은 직렬/PS2 명령해석기. */
public final class 명령해석기 {
    static int[] 입력 = new int[128];
    static int لمبائی_قدر = 0;
    static boolean 앞줄복귀 = false;
    static boolean لائن_اوور_فلو = false;

    static boolean حکم(String ناں) {
        if (لمبائی_قدر < ناں.length()) return false;
        for (int اشاریہ = 0; اشاریہ < ناں.length(); اشاریہ++)
            if (입력[اشاریہ] != ناں.charAt(اشاریہ)) return false;
        return لمبائی_قدر == ناں.length() || 입력[ناں.length()] == ' ';
    }

    static void نمایش_کرو_مدد() {
        문자단말.لکھو("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        문자단말.لکھو("apps | run NAME [ARGS] | net\n");
        문자단말.لکھو("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        문자단말.لکھو("sync (연결된 JKSTORE1 ذخیرہ_کرو_قدر 장치에 فائل 보존)\n");
    }

    static void عمل_قدر_داخلہ() {
        if (لمبائی_قدر == 0) return;
        if (حکم("help")) نمایش_کرو_مدد();
        else if (حکم("sync")) {
            int 결과 = 파일보존.ہم_آہنگ_کرنا();
            문자단말.لکھو("Sync: "); 문자단말.수쓰기(결과); 문자단말.문자(10);
        }
        else if (حکم("ls")) میموری_فائل_سسٹم.داخلہ_فرست();
        else if (حکم("edit")) میموری_فائل_سسٹم.حکم(입력, 4, لمبائی_قدر, 0);
        else if (حکم("cat")) میموری_فائل_سسٹم.حکم(입력, 3, لمبائی_قدر, 1);
        else if (حکم("rm")) میموری_فائل_سسٹم.حکم(입력, 2, لمبائی_قدر, 2);
        else if (حکم("java") || حکم("javac")) {
            int 결과 = 실행관리.نفاذ_کرو_حکم(입력, 0, لمبائی_قدر);
            문자단말.لکھو("Exit: "); 문자단말.수쓰기(결과); 문자단말.문자(10);
        }
        else if (حکم("apps")) 실행관리.داخلہ_فرست();
        else if (حکم("net")) نیٹ_ورک_گٹھا.حالت_قدر();
        else if (حکم("run")) {
            int 결과 = 실행관리.نفاذ_کرو_حکم(입력, 3, لمبائی_قدر);
            문자단말.لکھو("Exit: "); 문자단말.수쓰기(결과); 문자단말.لکھو("\n");
        } else if (حکم("info")) {
            문자단말.لکھو("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (حکم("mem")) {
            문자단말.لکھو("위쪽 میموری_قدر 공간(KiB): "); 문자단말.수쓰기(기억공간.위쪽기억크기());
            문자단말.لکھو("\n배열 동적 میموری_قدر 공간(بائٹ_قدر): "); 문자단말.수쓰기(آلہ_قدر.배열사용량());
            문자단말.لکھو(" / 262144\n작업 공간 سیکشن_قدر: "); 문자단말.수쓰기(기억공간.사용개수());
            문자단말.لکھو(" / 8 (각 4096바이트)\n");
        } else if (حکم("alloc")) {
            int اشاریہ = 기억공간.مختص_کرو_ذخیرہ();
            문자단말.لکھو("سیکشن_قدر اشاریہ: "); 문자단말.수쓰기(اشاریہ); 문자단말.لکھو("\n");
        } else if (حکم("free")) {
            if (لمبائی_قدر == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                문자단말.لکھو(기억공간.반환(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 سیکشن_قدر\n");
            } else 문자단말.لکھو("사용법: free 0..7\n");
        } else if (حکم("echo")) {
            for (int اشاریہ = 5; اشاریہ < لمبائی_قدر; اشاریہ++) 문자단말.문자(입력[اشاریہ]);
            문자단말.문자(10);
        } else if (حکم("clear")) 문자단말.지우기();
        else if (حکم("test")) کرنل.시험();
        else if (حکم("halt")) {
            문자단말.لکھو("HALTED\n");
            آلہ_قدر.정지();
        } else 문자단말.لکھو("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int قدر) {
        if (قدر == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = قدر == 13;
        if (قدر == 10 || قدر == 13) {
            문자단말.문자(10);
            if (میموری_فائل_سسٹم.편집중) میموری_فائل_سسٹم.편집줄(입력, لمبائی_قدر, لائن_اوور_فلو);
            else عمل_قدر_داخلہ();
            لمبائی_قدر = 0;
            لائن_اوور_فلو = false;
            문자단말.لکھو(میموری_فائل_سسٹم.편집중 ? "...> " : "jkoros> ");
        } else if (قدر == 8 || قدر == 127) {
            if (لمبائی_قدر > 0) {
                لمبائی_قدر--;
                문자단말.직렬바이트(8); 문자단말.직렬바이트(32); 문자단말.직렬바이트(8);
                문자단말.화면문자(8);
            }
        } else if (قدر >= 32 && قدر < 127 && لمبائی_قدر < 입력.length) {
            입력[لمبائی_قدر++] = قدر;
            문자단말.문자(قدر);
        } else if (قدر >= 32 && قدر < 127) لائن_اوور_فلو = true;
    }

    static void چلاؤ() {
        نمایش_کرو_مدد();
        문자단말.لکھو("READY\njkoros> ");
        while (true) {
            int قدر = 문자단말.직렬읽기();
            if (قدر < 0) قدر = کلیدی_بورڈ.읽기();
            if (قدر >= 0) 받아쓰기(قدر);
            else { نیٹ_ورک_گٹھا.تصدیق_کرو(); آلہ_قدر.잠시양보(); }
        }
    }
}
