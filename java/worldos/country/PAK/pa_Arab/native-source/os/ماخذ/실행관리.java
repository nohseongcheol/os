/** 읽기 전용 نفاذ_کرو_حکم 묶음의 ELF32 تریخ_دے_مطابق_کرو, 인수 آگے_قدر, 한 번에 한 صارف عمل_قدر نفاذ_کرو_حکم. */
public final class 실행관리 {
    static final int مکھ_صارف_ایپ = 0x04000000;
    static final int صارف_ختم_کرو = 0x04400000;
    static final int نقش_ختم_کرو_پتا = 0x04200000;
    static final int دلیل_مکھ = 0x04300000;
    static int 인수수 = 0;
    static int[] دلیل_پتا = new int[16];

    static boolean تراشہ(int پتا, int لمبائی_قدر) {
        return پتا >= مکھ_صارف_ایپ && پتا < صارف_ختم_کرو && لمبائی_قدر >= 0 && لمبائی_قدر <= صارف_ختم_کرو - پتا;
    }

    static int 수(int پتا) { return 기억공간.정수읽기(پتا); }
    static int 짧은수(int پتا) { return آلہ_قدر.기억읽기(پتا) | آلہ_قدر.기억읽기(پتا + 1) << 8; }
    static void 수쓰기(int پتا, int قدر) {
        for (int اشاریہ = 0; اشاریہ < 4; اشاریہ++) آلہ_قدر.لکھو_میموری(پتا + اشاریہ, قدر >>> (اشاریہ * 8));
    }

    static int 묶음개수() {
        int پتا = آلہ_قدر.실행묶음();
        int سائز = آلہ_قدر.실행묶음크기();
        if (سائز < 8 || 수(پتا) != 0x50414b4a) return 0;
        int 개수 = 수(پتا + 4);
        return 개수 >= 0 && 개수 <= 32 && 개수 <= (سائز - 8) / 24 ? 개수 : 0;
    }

    static void داخلہ_فرست() {
        for (int اشاریہ = 0; اشاریہ < 묶음개수(); اشاریہ++) {
            int داخلہ_قدر = آلہ_قدر.실행묶음() + 8 + اشاریہ * 24;
            for (int کریکٹر_قدر = 0; کریکٹر_قدر < 16 && آلہ_قدر.기억읽기(داخلہ_قدر + کریکٹر_قدر) != 0; کریکٹر_قدر++)
                문자단말.문자(آلہ_قدر.기억읽기(داخلہ_قدر + کریکٹر_قدر));
            문자단말.لکھو("\n");
        }
    }

    static int ڈھونڈو_داخلہ(int[] 입력, int چلاؤ, int لمبائی_قدر) {
        if (لمبائی_قدر <= 0 || لمبائی_قدر >= 16) return 0;
        for (int اشاریہ = 0; اشاریہ < 묶음개수(); اشاریہ++) {
            int داخلہ_قدر = آلہ_قدر.실행묶음() + 8 + اشاریہ * 24;
            boolean 같음 = آلہ_قدر.기억읽기(داخلہ_قدر + لمبائی_قدر) == 0;
            for (int کریکٹر_قدر = 0; کریکٹر_قدر < لمبائی_قدر; کریکٹر_قدر++)
                if (입력[چلاؤ + کریکٹر_قدر] != آلہ_قدر.기억읽기(داخلہ_قدر + کریکٹر_قدر)) 같음 = false;
            if (같음) return داخلہ_قدر;
        }
        return 0;
    }

    static int تریخ_دے_مطابق_کرو(int فائل, int لمبائی_قدر) {
        if (لمبائی_قدر < 52 || 수(فائل) != 0x464c457f || آلہ_قدر.기억읽기(فائل + 4) != 1
            || آلہ_قدر.기억읽기(فائل + 5) != 1 || آلہ_قدر.기억읽기(فائل + 6) != 1
            || 짧은수(فائل + 16) != 2 || 짧은수(فائل + 18) != 3 || 수(فائل + 20) != 1
            || 짧은수(فائل + 40) != 52 || 짧은수(فائل + 42) != 32) return -8;
        int داخلہ_مقام_قدر = 수(فائل + 24);
        int 표위치 = 수(فائل + 28);
        int 개수 = 짧은수(فائل + 44);
        if (개수 == 0 || 개수 > 16 || 표위치 < 52 || 표위치 > لمبائی_قدر - 개수 * 32) return -8;
        boolean 실행가능 = false;
        for (int اشاریہ = 0; اشاریہ < 개수; اشاریہ++) {
            int 표 = فائل + 표위치 + اشاریہ * 32;
            int 종류 = 수(표);
            if (종류 == 2 || 종류 == 3) return -8; // 동적 جڑو/해석기 미지원
            if (종류 != 1) continue;
            int 위치 = 수(표 + 4), پتا = 수(표 + 8), فائل_سائز = 수(표 + 16), میموری_سائز = 수(표 + 20);
            int سیدھا_قدر = 수(표 + 28);
            if (پتا < مکھ_صارف_ایپ || پتا >= نقش_ختم_کرو_پتا || میموری_سائز < 0 || میموری_سائز > نقش_ختم_کرو_پتا - پتا
                || فائل_سائز < 0 || فائل_سائز > میموری_سائز || 위치 < 0 || (فائل_سائز > 0 && 위치 > لمبائی_قدر - فائل_سائز)
                || (سیدھا_قدر != 0 && (سیدھا_قدر < 0 || (سیدھا_قدر & (سیدھا_قدر - 1)) != 0
                    || ((پتا - 위치) & (سیدھا_قدر - 1)) != 0))) return -8;
            for (int 앞 = 0; 앞 < اشاریہ; 앞++) {
                int 이전 = فائل + 표위치 + 앞 * 32;
                if (수(이전) == 1 && میموری_سائز > 0 && 수(이전 + 20) > 0
                    && پتا < 수(이전 + 8) + 수(이전 + 20) && 수(이전 + 8) < پتا + میموری_سائز) return -8;
            }
            if ((수(표 + 24) & 1) != 0 && داخلہ_مقام_قدر >= پتا && داخلہ_مقام_قدر - پتا < فائل_سائز) 실행가능 = true;
        }
        return 실행가능 ? داخلہ_مقام_قدر : -8;
    }

    static int نفاذ_کرو_حکم(int[] 입력, int چلاؤ, int لمبائی_قدر) {
        while (چلاؤ < لمبائی_قدر && 입력[چلاؤ] == ' ') چلاؤ++;
        int 끝 = چلاؤ;
        while (끝 < لمبائی_قدر && 입력[끝] != ' ') 끝++;
        int داخلہ_قدر = ڈھونڈو_داخلہ(입력, چلاؤ, 끝 - چلاؤ);
        if (داخلہ_قدر == 0) return -2;
        int 위치 = 수(داخلہ_قدر + 16), سائز = 수(داخلہ_قدر + 20);
        if (위치 < 8 + 묶음개수() * 24 || سائز < 52 || 위치 > آلہ_قدر.실행묶음크기() - سائز) return -8;
        int فائل = آلہ_قدر.실행묶음() + 위치;
        int داخلہ_مقام_قدر = تریخ_دے_مطابق_کرو(فائل, سائز);
        if (داخلہ_مقام_قدر < 0) return داخلہ_مقام_قدر;
        آلہ_قدر.صارف_صاف_کرو_مواد();
        int 표위치 = 수(فائل + 28), 개수 = 짧은수(فائل + 44);
        for (int اشاریہ = 0; اشاریہ < 개수; اشاریہ++) {
            int 표 = فائل + 표위치 + اشاریہ * 32;
            if (수(표) != 1) continue;
            int 원본 = فائل + 수(표 + 4), منزل_مقصود_قدر = 수(표 + 8), فائل_سائز = 수(표 + 16);
            for (int بائٹ_قدر = 0; بائٹ_قدر < فائل_سائز; بائٹ_قدر++) آلہ_قدر.لکھو_میموری(منزل_مقصود_قدر + بائٹ_قدر, آلہ_قدر.기억읽기(원본 + بائٹ_قدر));
        }
        인수수 = 0;
        int ذخیرہ_کرو_قدر = دلیل_مکھ;
        while (끝 < لمبائی_قدر) {
            while (끝 < لمبائی_قدر && 입력[끝] == ' ') 끝++;
            if (끝 == لمبائی_قدر) break;
            if (인수수 == دلیل_پتا.length) return -22;
            چلاؤ = 끝;
            while (끝 < لمبائی_قدر && 입력[끝] != ' ') 끝++;
            دلیل_پتا[인수수++] = ذخیرہ_کرو_قدر;
            수쓰기(ذخیرہ_کرو_قدر, 끝 - چلاؤ);
            for (int کریکٹر_قدر = چلاؤ; کریکٹر_قدر < 끝; کریکٹر_قدر++) 수쓰기(ذخیرہ_کرو_قدر + 4 + (کریکٹر_قدر - چلاؤ) * 4, 입력[کریکٹر_قدر]);
            ذخیرہ_کرو_قدر += 4 + (끝 - چلاؤ) * 4;
        }
        نیٹ_ورک_گٹھا.과정정리();
        파일서술자관리.مکھ_عمل();
        int 결과 = آلہ_قدر.چلاؤ_صارف_ایپ(داخلہ_مقام_قدر, صارف_ختم_کرو - 16);
        파일서술자관리.과정정리();
        نیٹ_ورک_گٹھا.과정정리();
        return 결과;
    }
}
