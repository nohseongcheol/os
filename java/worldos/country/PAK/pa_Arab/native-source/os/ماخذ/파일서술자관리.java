        int 위치 = (بنڑاؤ_سیٹنگاں[기술] & 이어쓰기) != 0 ? سائز : 파일위치[기술];
        if (위치 >= میموری_فائل_سسٹم.최대크기) return -27;
        if (لمبائی_قدر > میموری_فائل_سسٹم.최대크기 - 위치) لمبائی_قدر = میموری_فائل_سسٹم.최대크기 - 위치;
        int منزل_مقصود_پتا = آلہ_قدر.فائل_میموری() + فائل * میموری_فائل_سسٹم.최대크기;
        for (int اشاریہ = سائز; اشاریہ < 위치; اشاریہ++) آلہ_قدر.لکھو_میموری(منزل_مقصود_پتا + اشاریہ, 0);
        for (int اشاریہ = 0; اشاریہ < لمبائی_قدر; اشاریہ++) آلہ_قدر.لکھو_میموری(منزل_مقصود_پتا + 위치 + اشاریہ, آلہ_قدر.기억읽기(کوائف_پتا + اشاریہ));
        파일위치[기술] = 위치 + لمبائی_قدر;
        if (위치 + لمبائی_قدر > سائز) میموری_فائل_سسٹم.سائز_فرست[فائل] = 위치 + لمبائی_قدر;
