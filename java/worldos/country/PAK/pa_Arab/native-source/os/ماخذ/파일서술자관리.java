            int قدر = 0;
            if (اشاریہ == 0) قدر = 2;
            if (اشاریہ == 2) قدر = 접속번호 >>> 8;
            if (اشاریہ == 3) قدر = 접속번호;
            if (اشاریہ >= 4 && اشاریہ < 8) قدر = نیٹ_ورک_پتا >>> (56 - اشاریہ * 8);
