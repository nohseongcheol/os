#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 بائٹ_قدر 위치로 자체 C 이름을 옮기는 일회성 이행 اوزار.

외부 구조체의 멤버, سٹرنگ_قدر, C 표준 فعل_قدر, 이식 규약은 보존한다.
입력은 تبدیل_کرو_قدر 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def نفاذ_کرو_حکم():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['نقص']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ناں_جدول = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:ناں_جدول[داخلہ_قدر['ناں']] for 고유,داخلہ_قدر in 선언표.items()
                if داخلہ_قدر['ناں'] in ناں_جدول and داخلہ_قدر['ناں'] not in 규격}
    کنکشن_جدول = {داخلہ_قدر['ناں']:ناں_جدول[داخلہ_قدر['ناں']] for داخلہ_قدر in 선언표.values()
              if داخلہ_قدر.get('جڑو')==4 and داخلہ_قدر['종류'] in (8,9)
              and داخلہ_قدر['ناں'] in ناں_جدول and داخلہ_قدر['ناں'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 جڑو 이름만 유지한다.
    머리 = ['/* 한국어 ماخذ_شجرہ 이름과 기존 مشین جڑو حالت_قدر_102996da. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(کنکشن_جدول.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    تبدیلیاں_فرست = defaultdict(dict)
    for فائل,آف_سیٹ_قدر,ناں,고유 in 분석['حوالہ']:
        if 고유 in 바꿀선언:
            تبدیلیاں_فرست[فائل][آف_سیٹ_قدر] = (ناں,바꿀선언[고유])
    لاگ_صف = ['فائل\t원래바이트위치\t이전이름\t한국어이름']
    نظر_انداز_کرو_قدر = []
    for فائل,تبدیل_کرو_قدر in تبدیلیاں_فرست.items():
        راہ = Path(فائل); 원본 = راہ.read_bytes(); کوائف = 원본
        for آف_سیٹ_قدر,(옛이름,새이름) in sorted(تبدیل_کرو_قدر.items(),reverse=True):
            끝 = آف_سیٹ_قدر+len(옛이름.encode())
            if 원본[آف_سیٹ_قدر:끝] != 옛이름.encode():
                نظر_انداز_کرو_قدر.append((str(راہ.relative_to(기준)),آف_سیٹ_قدر,옛이름));continue
            کوائف = کوائف[:آف_سیٹ_قدر]+새이름.encode()+کوائف[끝:]
            لاگ_صف.append('{}\t{}\t{}\t{}'.format(راہ.relative_to(기준),آف_سیٹ_قدر,옛이름,새이름))
        راہ.write_bytes(کوائف)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    میکرو_قدر = {داخلہ_قدر['ناں']:ناں_جدول[داخلہ_قدر['ناں']] for داخلہ_قدر in 선언표.values()
              if داخلہ_قدر['종류']==501 and داخلہ_قدر['ناں'] in ناں_جدول and داخلہ_قدر['ناں'] not in 규격}
    for راہ in sorted({Path(داخلہ_قدر['فائل']) for داخلہ_قدر in 선언표.values()}):
        لائن_فرست = راہ.read_text().splitlines(True); 이어짐 = False
        for اشاریہ,لائن in enumerate(لائن_فرست):
            전처리 = 이어짐 or bool(re.match(r'\s*#',لائن))
            이어짐 = 전처리 and لائن.rstrip().endswith('\\')
            if 전처리:
                표 = ناں_جدول if re.match(r'\s*#\s*define\b',لائن) or 이어짐 else میکرو_قدر
                لائن_فرست[اشاریہ] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],لائن)
        راہ.write_text(''.join(لائن_فرست))
    # 각 자체 ترجمہ_کرو_ماخذ 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for راہ in sorted({Path(داخلہ_قدر['فائل']) for داخلہ_قدر in 선언표.values()}):
        if راہ.suffix not in ('.c','.cpp'):continue
        ہم_سر_قدر = '../' * len(راہ.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        راہ.write_text('#include "'+ہم_سر_قدر+'"\n'+راہ.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(لاگ_صف)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(نظر_انداز_کرو_قدر,ensure_ascii=False,indent=2)+'\n')
    print('تبدیل_کرو_قدر',len(لاگ_صف)-1,'전처리 재검토',len(نظر_انداز_کرو_قدر),'مشین جڑو',len(کنکشن_جدول))

if __name__=='__main__': نفاذ_کرو_حکم()
