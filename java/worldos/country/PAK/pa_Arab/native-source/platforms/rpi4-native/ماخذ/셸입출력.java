/** 파이프는 16 KiB씩 순서대로 실행한다. 프로세스/동시 파이프를 흉내 내지 않는다. */
public final class 셸입출력 {
    static int[] 입력자료 = new int[16384], 출력자료 = new int[16384];
    static int 입력길이, 입력위치, 출력길이, 입력파일 = -1, آؤٹ_پٹ_فایل = -1;
    static boolean 파이프입력, 파이프출력;
    static int ناکامی_قدر;
    static boolean اجازت_متعامل = true;
    public static int 대화가능() { return اجازت_متعامل && 입력파일 < 3 && آؤٹ_پٹ_فایل < 3 && !파이프입력 && !파이프출력 ? 1 : 0; }
    public static int 출력(int چینل_قدر, int قدر) {
        if (چینل_قدر != 1) return 0;
        if (آؤٹ_پٹ_فایل >= 3) { int 처리값 = میموری_فائلاں.لکھو(آؤٹ_پٹ_فایل, قدر); if (처리값 < 0) ناکامی_قدر = 처리값; return 1; }
        if (!파이프출력) return 0;
        if (출력길이 == 출력자료.length) ناکامی_قدر = -28;
        else 출력자료[출력길이++] = قدر;
        return 1;
    }
    public static int 입력() {
        if (입력파일 >= 3) { int 처리값 = میموری_فائلاں.읽기(입력파일); return 처리값 == 256 ? -2 : 처리값; }
        if (파이프입력) return 입력위치 < 입력길이 ? 입력자료[입력위치++] : -2;
        return -3; // UART로 آگے_قدر
    }
    static void چلاؤ(boolean 앞파이프, boolean 뒤파이프) {
        파이프입력 = 앞파이프; 파이프출력 = 뒤파이프;
        입력위치 = 0; 출력길이 = 0; 입력파일 = -1; آؤٹ_پٹ_فایل = -1; ناکامی_قدر = 0;
    }
    static void 끝() {
        보드.입출력전환(0);
        if (입력파일 >= 3) میموری_فائلاں.بند_کرو(입력파일);
        if (آؤٹ_پٹ_فایل >= 3) میموری_فائلاں.بند_کرو(آؤٹ_پٹ_فایل);
        if (파이프출력) { 입력길이 = 출력길이; for (int لوپ_اشاریہ = 0; لوپ_اشاریہ < 출력길이; لوپ_اشاریہ++) 입력자료[لوپ_اشاریہ] = 출력자료[لوپ_اشاریہ]; }
        입력파일 = -1; آؤٹ_پٹ_فایل = -1; 파이프입력 = false; 파이프출력 = false;
    }
}
