package 한국어.자체;
/** 한국어 화면 구성요소를 만드는 편의 فعل_قدر. */
public final class ویجٹ {
    private ویجٹ() {}
    public static void 나중에실행(실행할일 ٹاسک_کم) { واقعہ_قطار.나중에실행(ٹاسک_کم); }
    public static پرچی ٹیگ_قدر(String متن, int 가로, int 세로, int 폭, int 높이) {
        return new پرچی(متن, 가로, 세로, 폭, 높이);
    }
    public static بٹن بٹن(String متن, int 가로, int 세로, int 폭, int 높이, 동작받이 받이) {
        return new بٹن(متن, 가로, 세로, 폭, 높이, 받이);
    }
    public static متن_قطعہ متن_قطعہ(String متن, int 가로, int 세로, int 폭, int 높이) {
        return new متن_قطعہ(متن, 가로, 세로, 폭, 높이);
    }
}
