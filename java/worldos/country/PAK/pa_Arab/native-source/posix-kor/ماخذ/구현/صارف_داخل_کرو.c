#include "호출경계.h"
extern int main(int 인수개수, char **دلیل_فرست);
static char دلیل_میموری[2048];
static char *دلیل_فرست[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 نفاذ_کرو_حکم 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    دلیل_فرست[0] = "jkoros-app";
    int 위치 = 0;
    for (int اشاریہ = 0; اشاریہ < 개수; اشاریہ++) {
        const int *원본 = (const int *)jkoros_syscall(3, اشاریہ, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        دلیل_فرست[اشاریہ + 1] = دلیل_میموری + 위치;
        for (int سلاٹ_داخلہ = 0; سلاٹ_داخلہ < 원본[0]; سلاٹ_داخلہ++) {
            if (위치 >= 2047) return 126;
            دلیل_میموری[위치++] = 원본[سلاٹ_داخلہ + 1];
        }
        دلیل_میموری[위치++] = 0;
    }
    دلیل_فرست[개수 + 1] = 0;
    return main(개수 + 1, دلیل_فرست);
}
