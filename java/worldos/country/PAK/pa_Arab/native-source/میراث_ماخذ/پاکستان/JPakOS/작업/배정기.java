package پاکستان.JPakOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import پاکستان.JPakOS.기억공간.صفحہ_مینیجر;
import پاکستان.JPakOS.فائل_سسٹم.파일서술자표;

/** عمل_قدر 식별자와 라운드로빈 تیاری_کرو 대기열을 관리한다. */
public final class 배정기 {
    private final صفحہ_مینیجر 쪽관리;
    private final Map<Integer, عمل_قدر> طریقیاں_دی_فرست = new HashMap<Integer, عمل_قدر>();
    private final Queue<عمل_قدر> 준비대기열 = new ArrayDeque<عمل_قدر>();
    private int 다음식별자 = 1;

    public 배정기(صفحہ_مینیجر 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public عمل_قدر 첫과정(파일서술자표 파일서술자) {
        عمل_قدر 새과정 = new عمل_قدر(مختص_کرو_شناخت_کرنڑ_آلا(), 0, 쪽관리.새주소공간(), 파일서술자);
        طریقیاں_دی_فرست.put(Integer.valueOf(새과정.شناخت_کرنڑ_آلا_قدر()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public عمل_قدر 복제(عمل_قدر 부모) {
        عمل_قدر بچہ_قدر = new عمل_قدر(
                مختص_کرو_شناخت_کرنڑ_آلا(),
                부모.شناخت_کرنڑ_آلا_قدر(),
                쪽관리.쓰기시복사복제(부모.پتا_جگہ()),
                부모.파일서술자().복제());
        بچہ_قدر.프로그램끝설정(부모.프로그램끝());
        طریقیاں_دی_فرست.put(Integer.valueOf(بچہ_قدر.شناخت_کرنڑ_آلا_قدر()), بچہ_قدر);
        준비대기열.offer(بچہ_قدر);
        return بچہ_قدر;
    }

    public عمل_قدر 다음과정() {
        int 검사수 = 준비대기열.size();
        for (int اشاریہ = 0; اشاریہ < 검사수; اشاریہ++) {
            عمل_قدر 다음 = 준비대기열.poll();
            if (다음 != null && (다음.حالت_قدر() == عمل_حالت.تیاری_کرو || 다음.حالت_قدر() == عمل_حالت.نفاذ_کرو_حکم)) {
                다음.سیٹ_حالت(عمل_حالت.نفاذ_کرو_حکم);
                준비대기열.offer(다음);
                return 다음;
            }
        }
        return null;
    }

    public int 자식기다리기(عمل_قدر 부모, int بچہ_شناخت_کرنڑ_آلا, boolean 기다리지않음) {
        for (عمل_قدر 후보 : طریقیاں_دی_فرست.values()) {
            if (후보.부모식별자() != 부모.شناخت_کرنڑ_آلا_قدر()) {
                continue;
            }
            if (بچہ_شناخت_کرنڑ_آلا > 0 && 후보.شناخت_کرنڑ_آلا_قدر() != بچہ_شناخت_کرنڑ_آلا) {
                continue;
            }
            if (후보.حالت_قدر() == عمل_حالت.خارج_کرو_ایپ) {
                int 결과 = (후보.종료값() & 0xff) << 8;
                طریقیاں_دی_فرست.remove(Integer.valueOf(후보.شناخت_کرنڑ_آلا_قدر()));
                return 결과;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public عمل_قدر ڈھونڈو_عمل(int شناخت_کرنڑ_آلا_قدر) {
        return طریقیاں_دی_فرست.get(Integer.valueOf(شناخت_کرنڑ_آلا_قدر));
    }

    private int مختص_کرو_شناخت_کرنڑ_آلا() {
        return 다음식별자++;
    }
}
