    public int 접근가능(String ناں, int طریقہ_موڈ) {
        فائل_معلومات سسٹم_دی_معلومات = فائل_سسٹم.سسٹم_دی_معلومات(ناں);
        if (سسٹم_دی_معلومات == null) {
            return -2;
        }
        if ((طریقہ_موڈ & 1) != 0 && (سسٹم_دی_معلومات.형태() & 0111) == 0) {
            return -13;
        }
        if ((طریقہ_موڈ & 2) != 0) {
            return -30;
        }
        return 0;
    }

