    public int 읽기(عمل_قدر 현재과정, int 서술자, byte[] 받을곳, int سائز) {
        if (서술자 == 0) {
            if (سائز <= 0 || 받을곳.length == 0) {
                return 0;
            }
            입력사건 واقعہ = 입력관리.다음사건();
            if (واقعہ == null || واقعہ.사건종류() != 입력사건.종류.키누름) {
                return -11;
            }
            받을곳[0] = (byte) واقعہ.첫째값();
            return 1;
        }
        return 현재과정.파일서술자().읽기(서술자, 받을곳, سائز);
    }

    public int لکھو(عمل_قدر 현재과정, int 서술자, byte[] کوائف, int سائز) {
        if (서술자 != 1 && 서술자 != 2) {
            return 현재과정.파일서술자().열려있음(서술자) ? -30 : -9;
        }
        if (سائز < 0 || سائز > کوائف.length) {
            return -22;
        }
        آلہ_قدر.직렬출력(new String(کوائف, 0, سائز, java.nio.charset.StandardCharsets.UTF_8));
        return سائز;
    }

