    public int نفاذ_کرو_حکم(عمل_قدر 현재과정, byte[] 실행파일, String[] 인자, String[] 환경) {
        실행파일적재기.نقش نقش_قدر;
        try {
            نقش_قدر = 적재기.검사(실행파일);
        } catch (IllegalArgumentException نقص) {
            return -8;
        }
        if (인자 == null || 환경 == null || 인자.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.سیکشن_قدر سیکشن_قدر : نقش_قدر.구역들()) {
            if ((سیکشن_قدر.جھنڈا_قدر() & 2) == 0 || سیکشن_قدر.سائز() == 0) {
                continue;
            }
            int 첫쪽 = سیکشن_قدر.پتا() / صفحہ_مینیجر.ورقے_دا_ناپ;
            int 끝쪽 = (سیکشن_قدر.پتا() + سیکشن_قدر.سائز() + صفحہ_مینیجر.ورقے_دا_ناپ - 1) / صفحہ_مینیجر.ورقے_دا_ناپ;
            for (int اشاریہ = 첫쪽; اشاریہ < 끝쪽; اشاریہ++) {
                int پتا = اشاریہ * صفحہ_مینیجر.ورقے_دا_ناپ;
                try {
                    쪽관리.바이트읽기(현재과정.پتا_جگہ(), پتا);
                    쪽관리.범위개인쓰기(현재과정.پتا_جگہ(), پتا, صفحہ_مینیجر.ورقے_دا_ناپ);
                } catch (IllegalStateException نقص) {
                    쪽관리.نقشہ_صفحہ(현재과정.پتا_جگہ(), پتا, true);
                }
            }
            for (int اشاریہ = 0; اشاریہ < سیکشن_قدر.سائز(); اشاریہ++) {
                byte قدر = سیکشن_قدر.종류() == 8 ? 0 : 실행파일[سیکشن_قدر.파일위치() + اشاریہ];
                쪽관리.لکھو_بائٹ_قدر(현재과정.پتا_جگہ(), سیکشن_قدر.پتا() + اشاریہ, قدر);
            }
        }
        현재과정.실행문맥설정(نقش_قدر.مکھ_پتا(), 인자, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

