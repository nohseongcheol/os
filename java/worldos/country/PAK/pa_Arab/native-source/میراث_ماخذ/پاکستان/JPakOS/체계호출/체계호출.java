    public boolean 단말인가(عمل_قدر 현재과정, int 서술자) {
        فائل_معلومات سسٹم_دی_معلومات = 현재과정.파일서술자().سسٹم_دی_معلومات(서술자);
        return سسٹم_دی_معلومات != null && (سسٹم_دی_معلومات.형태() & 0170000) == 0020000;
    }

    public int فائل_کنٹرول(عمل_قدر 현재과정, int 서술자, int حکم, int 인자) {
        if (حکم == 0) {
            return 현재과정.파일서술자().복제서술자(서술자, 인자);
        }
        if (حکم == 1) {
            return 현재과정.파일서술자().실행시닫기값(서술자);
        }
        if (حکم == 2) {
            return 현재과정.파일서술자().실행시닫기설정(서술자, (인자 & 1) != 0);
        }
        if (حکم == 3) {
            return 현재과정.파일서술자().سسٹم_دی_معلومات(서술자) == null ? -9 : صرف_مطالعہ_جھنڈا;
        }
        if (حکم == 4) {
            return 인자 == صرف_مطالعہ_جھنڈا ? 0 : -30;
        }
        return -22;
    }

