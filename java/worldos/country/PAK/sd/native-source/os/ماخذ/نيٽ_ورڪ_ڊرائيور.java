/** PCI RTL8139 (10ec:8139), 단일 اي_ميل_قدر 버퍼와 8KiB 수신 لوپ_قدر. 인터럽트 대신 폴링한다. */
public final class نيٽ_ورڪ_ڊرائيور {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] آلو_پتو = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int 위치) {
        آلو_قدر.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | 위치);
        return آلو_قدر.입출력정수읽기(0xcfc);
    }

    static boolean تياري_ڪريو() {
        int 장치번호 = -1;
        for (int ابتدائي = 0; ابتدائي < 32; ابتدائي++) {
            if (설정읽기(ابتدائي, 0) == 0x813910ec) { 장치번호 = ابتدائي; break; }
        }
        if (장치번호 < 0) return false;
        int طئي_ٿيل_ملهه = 설정읽기(장치번호, 0x10);
        if ((طئي_ٿيل_ملهه & 1) == 0 || (طئي_ٿيل_ملهه & 0xfffffffc) < 0x100 || (طئي_ٿيل_ملهه & 0xfffffffc) > 65535) return false;
        입출력기준주소 = طئي_ٿيل_ملهه & 0xfffc;
        int حڪم = 설정읽기(장치번호, 4);
        آلو_قدر.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        آلو_قدر.입출력짧은수쓰기(0xcfc, حڪم | 5); // I/O 및 bus master اجازت_ڏيو_قدر, PCI حالت_قدر 비트는 건드리지 않음
        آلو_قدر.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!ٻيهر_سيٽ_ڪريو_قدر()) { 입출력기준주소 = 0; return false; }
        for (int ابتدائي = 0; ابتدائي < 6; ابتدائي++) آلو_پتو[ابتدائي] = آلو_قدر.입출력바이트읽기(입출력기준주소 + ابتدائي);
        return true;
    }

    static boolean ٻيهر_سيٽ_ڪريو_قدر() {
        آلو_قدر.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int هلائڻ = آلو_قدر.밀리초();
        while ((آلو_قدر.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (آلو_قدر.밀리초() - هلائڻ > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        آلو_قدر.입출력정수쓰기(입출력기준주소 + 0x30, آلو_قدر.نيٽ_ورڪ_ميموري());
        for (int ابتدائي = 0; ابتدائي < 4; ابتدائي++) آلو_قدر.입출력정수쓰기(입출력기준주소 + 0x20 + ابتدائي * 4, آلو_قدر.نيٽ_ورڪ_ميموري() + 12288);
        آلو_قدر.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        آلو_قدر.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        آلو_قدر.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        آلو_قدر.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/방송, wrap 연속 روڪيو_قدر, 8KiB
        آلو_قدر.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int اي_ميل(int[] ڪوائف, int لمبائي_قدر) {
        if (입출력기준주소 == 0) return -19;
        if (لمبائي_قدر < 14 || لمبائي_قدر > 1514) return -90;
        int حالت_پورٽ = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int هلائڻ = آلو_قدر.밀리초();
        while ((آلو_قدر.입출력정수읽기(حالت_پورٽ) & 0x2000) == 0)
            if (آلو_قدر.밀리초() - هلائڻ > 100) return -110;
        int سائيز = لمبائي_قدر < 60 ? 60 : لمبائي_قدر;
        for (int ابتدائي = 0; ابتدائي < سائيز; ابتدائي++)
            آلو_قدر.لکو_ميموري(آلو_قدر.نيٽ_ورڪ_ميموري() + 12288 + ابتدائي, ابتدائي < لمبائي_قدر ? ڪوائف[ابتدائي] : 0);
        آلو_قدر.입출력정수쓰기(حالت_پورٽ, سائيز | 0x00080000);
        هلائڻ = آلو_قدر.밀리초();
        while ((آلو_قدر.입출력정수읽기(حالت_پورٽ) & 0xe0008000) == 0)
            if (آلو_قدر.밀리초() - هلائڻ > 100) return -110;
        if ((آلو_قدر.입출력정수읽기(حالت_پورٽ) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return لمبائي_قدر;
    }

    static int 받기(int[] ڪوائف) {
        if (입출력기준주소 == 0) return 0;
        if ((آلو_قدر.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!ٻيهر_سيٽ_ڪريو_قدر()) 입출력기준주소 = 0;
            return 0;
        }
        if ((آلو_قدر.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = آلو_قدر.نيٽ_ورڪ_ميموري() + 수신위치;
        int حالت_قدر = 실행관리.짧은수(머리), سائيز = 실행관리.짧은수(머리 + 2);
        if (سائيز == 0xfff0) return 0; // DMA 진행 중
        if (سائيز < 4 || سائيز > 1518) {
            오류수++;
            if (!ٻيهر_سيٽ_ڪريو_قدر()) 입출력기준주소 = 0;
            return 0;
        }
        int لمبائي_قدر = سائيز - 4;
        if ((حالت_قدر & 1) != 0) {
            for (int ابتدائي = 0; ابتدائي < لمبائي_قدر; ابتدائي++) ڪوائف[ابتدائي] = آلو_قدر.기억읽기(머리 + 4 + ابتدائي);
            수신수++;
        } else { لمبائي_قدر = 0; 오류수++; }
        수신위치 = (수신위치 + سائيز + 4 + 3) & ~3;
        수신위치 &= 8191;
        آلو_قدر.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        آلو_قدر.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return لمبائي_قدر;
    }
}
