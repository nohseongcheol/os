/** 부팅 سسٽم_معلومات 조회와 4KiB 고정 سائيز 작업 سيڪشن_قدر مختص_ڪريو_ذخيرو/반환. 일반 물리 صفحو_قدر 관리자는 아니다. */
public final class 기억공간 {
    static int[] سيڪشن_قدر = new int[8192];
    static int[] 사용 = new int[8];

    static int 정수읽기(int پتو) {
        return آلو_قدر.기억읽기(پتو) | (آلو_قدر.기억읽기(پتو + 1) << 8)
            | (آلو_قدر.기억읽기(پتو + 2) << 16) | (آلو_قدر.기억읽기(پتو + 3) << 24);
    }

    static int 위쪽기억크기() {
        int سسٽم_معلومات = آلو_قدر.부팅정보();
        if (آلو_قدر.부팅표식() != 0x2badb002 || سسٽم_معلومات == 0 || (정수읽기(سسٽم_معلومات) & 1) == 0) return -1;
        return 정수읽기(سسٽم_معلومات + 8);
    }

    static int مختص_ڪريو_ذخيرو() {
        for (int ابتدائي = 0; ابتدائي < 사용.length; ابتدائي++) {
            if (사용[ابتدائي] == 0) {
                사용[ابتدائي] = 1;
                for (int سوراخ_داخلا = 0; سوراخ_داخلا < 1024; سوراخ_داخلا++) سيڪشن_قدر[ابتدائي * 1024 + سوراخ_داخلا] = 0;
                return ابتدائي;
            }
        }
        return -1;
    }

    static boolean 반환(int ابتدائي) {
        if (ابتدائي < 0 || ابتدائي >= 사용.length || 사용[ابتدائي] == 0) return false;
        사용[ابتدائي] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int ابتدائي = 0; ابتدائي < 사용.length; ابتدائي++) 개수 += 사용[ابتدائي];
        return 개수;
    }
}
