#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 بائٽ_قدر 위치로 자체 C 이름을 옮기는 일회성 이행 اوزار.

외부 구조체의 멤버, اسٽرنگ_قدر, C 표준 فعل_قدر, 이식 규약은 보존한다.
입력은 تبديل_ڪريو_قدر 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def تعميل_ڪرڻ_حڪم():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['نقص']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    نالو_جدول = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {منفرد_قدر:نالو_جدول[داخلا_قدر['نالو']] for منفرد_قدر,داخلا_قدر in 선언표.items()
                if داخلا_قدر['نالو'] in نالو_جدول and داخلا_قدر['نالو'] not in 규격}
    ڪنيڪشن_جدول = {داخلا_قدر['نالو']:نالو_جدول[داخلا_قدر['نالو']] for داخلا_قدر in 선언표.values()
              if داخلا_قدر.get('ڪنيڪٽ')==4 and داخلا_قدر['종류'] in (8,9)
              and داخلا_قدر['نالو'] in نالو_جدول and داخلا_قدر['نالو'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ڪنيڪٽ 이름만 유지한다.
    머리 = ['/* 한국어 ماخذ_شجرو 이름과 기존 مشين ڪنيڪٽ حالت_قدر_102996da. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(ڪنيڪشن_جدول.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    تبديليون_فهرست = defaultdict(dict)
    for فائل,آف_سيٽ_قدر,نالو,منفرد_قدر in 분석['حوالو']:
        if منفرد_قدر in 바꿀선언:
            تبديليون_فهرست[فائل][آف_سيٽ_قدر] = (نالو,바꿀선언[منفرد_قدر])
    لاگ_صف = ['فائل\t원래바이트위치\t이전이름\t한국어이름']
    نظرانداز_ڪريو_قدر = []
    for فائل,تبديل_ڪريو_قدر in تبديليون_فهرست.items():
        راههه = Path(فائل); 원본 = راههه.read_bytes(); ڪوائف = 원본
        for آف_سيٽ_قدر,(옛이름,새이름) in sorted(تبديل_ڪريو_قدر.items(),reverse=True):
            끝 = آف_سيٽ_قدر+len(옛이름.encode())
            if 원본[آف_سيٽ_قدر:끝] != 옛이름.encode():
                نظرانداز_ڪريو_قدر.append((str(راههه.relative_to(기준)),آف_سيٽ_قدر,옛이름));continue
            ڪوائف = ڪوائف[:آف_سيٽ_قدر]+새이름.encode()+ڪوائف[끝:]
            لاگ_صف.append('{}\t{}\t{}\t{}'.format(راههه.relative_to(기준),آف_سيٽ_قدر,옛이름,새이름))
        راههه.write_bytes(ڪوائف)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ميڪرو_قدر = {داخلا_قدر['نالو']:نالو_جدول[داخلا_قدر['نالو']] for داخلا_قدر in 선언표.values()
              if داخلا_قدر['종류']==501 and داخلا_قدر['نالو'] in نالو_جدول and داخلا_قدر['نالو'] not in 규격}
    for راههه in sorted({Path(داخلا_قدر['فائل']) for داخلا_قدر in 선언표.values()}):
        لڪير_فهرست = راههه.read_text().splitlines(True); 이어짐 = False
        for ابتدائي,لڪير in enumerate(لڪير_فهرست):
            전처리 = 이어짐 or bool(re.match(r'\s*#',لڪير))
            이어짐 = 전처리 and لڪير.rstrip().endswith('\\')
            if 전처리:
                표 = نالو_جدول if re.match(r'\s*#\s*define\b',لڪير) or 이어짐 else ميڪرو_قدر
                لڪير_فهرست[ابتدائي] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],لڪير)
        راههه.write_text(''.join(لڪير_فهرست))
    # 각 자체 ترجمو_ماخذ 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for راههه in sorted({Path(داخلا_قدر['فائل']) for داخلا_قدر in 선언표.values()}):
        if راههه.suffix not in ('.c','.cpp'):continue
        همعصر_قدر = '../' * len(راههه.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        راههه.write_text('#include "'+همعصر_قدر+'"\n'+راههه.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(لاگ_صف)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(نظرانداز_ڪريو_قدر,ensure_ascii=False,indent=2)+'\n')
    print('تبديل_ڪريو_قدر',len(لاگ_صف)-1,'전처리 재검토',len(نظرانداز_ڪريو_قدر),'مشين ڪنيڪٽ',len(ڪنيڪشن_جدول))

if __name__=='__main__': تعميل_ڪرڻ_حڪم()
