import اردو.اپنا.ونڈو;
import اردو.اپنا.سرنامہ;
import اردو.اپنا.متن_فیلڈ;
import اردو.اپنا.بٹن;
import اردو.اپنا.ایونٹ_قطار;
import اردو.اپنا.اخراج_کا_مقام;
import اردو.اپنا.실행할일;
import اردو.اپنا.동작받이;
import اردو.اپنا.동작알림;

/** اپنا 커널의 Swing ونڈو: Urdu 입력 → بٹن → مجھے_پڑھیں_eb81d7d9 متن تازہ_کریں. */
public class کھڑکیمثال implements 실행할일, 동작받이 {
    private ونڈو 인사창;
    private متن_فیلڈ نام_قطعہ;
    private سرنامہ 인사말;
    private int 인사횟수;

    public void بنائیں_دریچہ() {
        인사창 = new ونڈو("Urdu Swing", 460, 300);
        인사창.شامل_کریں_عنصر(new سرنامہ("سلام", 20, 20, 420, 28));
        نام_قطعہ = new متن_فیلڈ("Urdu", 20, 64, 420, 30);
        인사말 = new سرنامہ("سلام", 20, 152, 420, 28);
        인사창.شامل_کریں_عنصر(نام_قطعہ);
        인사창.شامل_کریں_عنصر(new بٹن("인사하기", 20, 108, 180, 32, this));
        인사창.شامل_کریں_عنصر(인사말);
        인사창.شامل_کریں_عنصر(new سرنامہ("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.دکھانا_دریچہ();
        اخراج_کا_مقام.لکھیں_لائن("GUI 예제 تیار_کریں: کھڑکیمثال");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.لکھیں_متن("سلام, " + نام_قطعہ.글읽기() + "님! (" + 인사횟수 + ")");
        اخراج_کا_مقام.لکھیں_لائن("GUI 인사: " + 인사말.글읽기());
    }

    public void اطلاق() { بنائیں_دریچہ(); }
    public void 동작받기(동작알림 알림) {
        اخراج_کا_مقام.لکھیں_لائن("عمل 알림: " + 알림.حکم_متن());
        인사하기();
    }
    public static void چلائیں() {
        ایونٹ_قطار.나중에실행(new کھڑکیمثال());
    }
}
