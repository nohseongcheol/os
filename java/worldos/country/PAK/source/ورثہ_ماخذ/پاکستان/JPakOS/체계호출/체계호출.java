    public boolean معلومات_ٹیکنالوجی_ٹرمینل(عمل_قدر 현재과정, int 서술자) {
        فائل_معلومات نظام_کی_معلومات = 현재과정.파일서술자().نظام_کی_معلومات(서술자);
        return نظام_کی_معلومات != null && (نظام_کی_معلومات.형태() & 0170000) == 0020000;
    }

    public int فائل_کنٹرول(عمل_قدر 현재과정, int 서술자, int حکم, int پیرا_میٹر_دلائل) {
        if (حکم == 0) {
            return 현재과정.파일서술자().복제서술자(서술자, پیرا_میٹر_دلائل);
        }
        if (حکم == 1) {
            return 현재과정.파일서술자().실행시닫기값(서술자);
        }
        if (حکم == 2) {
            return 현재과정.파일서술자().실행시닫기설정(서술자, (پیرا_میٹر_دلائل & 1) != 0);
        }
        if (حکم == 3) {
            return 현재과정.파일서술자().نظام_کی_معلومات(서술자) == null ? -9 : فقط_مطالعہ_پرچم;
        }
        if (حکم == 4) {
            return پیرا_میٹر_دلائل == فقط_مطالعہ_پرچم ? 0 : -30;
        }
        return -22;
    }

