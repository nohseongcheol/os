    public int نفاذ_کریں_حکم(عمل_قدر 현재과정, byte[] 실행파일, String[] پیرا_میٹر_دلائل, String[] 환경) {
        실행파일적재기.نقش نقش_قدر;
        try {
            نقش_قدر = 적재기.검사(실행파일);
        } catch (IllegalArgumentException غلطی) {
            return -8;
        }
        if (پیرا_میٹر_دلائل == null || 환경 == null || پیرا_میٹر_دلائل.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.صیغہ_قدر صیغہ_قدر : نقش_قدر.구역들()) {
            if ((صیغہ_قدر.پرچم_قدر() & 2) == 0 || صیغہ_قدر.حجم() == 0) {
                continue;
            }
            int 첫쪽 = صیغہ_قدر.پتہ() / صفحہ_مینیجر.صفحہ_سائز;
            int 끝쪽 = (صیغہ_قدر.پتہ() + صیغہ_قدر.حجم() + صفحہ_مینیجر.صفحہ_سائز - 1) / صفحہ_مینیجر.صفحہ_سائز;
            for (int اشاریہ = 첫쪽; اشاریہ < 끝쪽; اشاریہ++) {
                int پتہ = اشاریہ * صفحہ_مینیجر.صفحہ_سائز;
                try {
                    쪽관리.바이트읽기(현재과정.پتہ_اسپیس(), پتہ);
                    쪽관리.범위개인쓰기(현재과정.پتہ_اسپیس(), پتہ, صفحہ_مینیجر.صفحہ_سائز);
                } catch (IllegalStateException غلطی) {
                    쪽관리.میپ_صفحہ(현재과정.پتہ_اسپیس(), پتہ, true);
                }
            }
            for (int اشاریہ = 0; اشاریہ < صیغہ_قدر.حجم(); اشاریہ++) {
                byte قدر = صیغہ_قدر.종류() == 8 ? 0 : 실행파일[صیغہ_قدر.فائل_پوزیشن_ٹھیک_کریں() + اشاریہ];
                쪽관리.لکھیں_بائٹ_قدر(현재과정.پتہ_اسپیس(), صیغہ_قدر.پتہ() + اشاریہ, قدر);
            }
        }
        현재과정.실행문맥설정(نقش_قدر.ابتدا_پتہ(), پیرا_میٹر_دلائل, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

