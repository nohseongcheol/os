package پاکستان.JPakOS.화면;

import java.util.Arrays;

/** VGA 문자 방식과 같은 80x25 문자 화면 모형이다. */
public final class کریکٹر_ڈسپلے {
    public static final int 너비 = 80;
    public static final int 높이 = 25;
    private final char[] 문자들 = new char[너비 * 높이];
    private int 가로;
    private int عمودی_پوزیشن_ٹھیک_کریں;

    public کریکٹر_ڈسپلے() {
        지우기();
    }

    public void اخراج_کا_مقام(String مشمول_قدر) {
        for (int اشاریہ = 0; اشاریہ < مشمول_قدر.length(); اشاریہ++) {
            char 문자 = مشمول_قدر.charAt(اشاریہ);
            if (문자 == '\n') {
                가로 = 0;
                عمودی_پوزیشن_ٹھیک_کریں++;
            } else {
                문자출력(가로++, عمودی_پوزیشن_ٹھیک_کریں, 문자);
            }
            if (가로 >= 너비) {
                가로 = 0;
                عمودی_پوزیشن_ٹھیک_کریں++;
            }
            if (عمودی_پوزیشن_ٹھیک_کریں >= 높이) {
                위로밀기();
            }
        }
    }

    public char 문자(int 가로, int عمودی_پوزیشن_ٹھیک_کریں) {
        تصدیق_کریں_پوزیشن_ٹھیک_کریں(가로, عمودی_پوزیشن_ٹھیک_کریں);
        return 문자들[عمودی_پوزیشن_ٹھیک_کریں * 너비 + 가로];
    }

    public void 지우기() {
        Arrays.fill(문자들, ' ');
        가로 = 0;
        عمودی_پوزیشن_ٹھیک_کریں = 0;
    }

    private void 문자출력(int 가로, int عمودی_پوزیشن_ٹھیک_کریں, char 문자) {
        تصدیق_کریں_پوزیشن_ٹھیک_کریں(가로, عمودی_پوزیشن_ٹھیک_کریں);
        문자들[عمودی_پوزیشن_ٹھیک_کریں * 너비 + 가로] = 문자;
    }

    private void 위로밀기() {
        System.arraycopy(문자들, 너비, 문자들, 0, 너비 * (높이 - 1));
        Arrays.fill(문자들, 너비 * (높이 - 1), 문자들.length, ' ');
        عمودی_پوزیشن_ٹھیک_کریں = 높이 - 1;
    }

    private void تصدیق_کریں_پوزیشن_ٹھیک_کریں(int 가로, int عمودی_پوزیشن_ٹھیک_کریں) {
        if (가로 < 0 || 가로 >= 너비 || عمودی_پوزیشن_ٹھیک_کریں < 0 || عمودی_پوزیشن_ٹھیک_کریں >= 높이) {
            throw new IllegalArgumentException("화면 위치가 올바르지 않습니다.");
        }
    }
}

