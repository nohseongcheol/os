        if (새서술자 < 0 || 새서술자 >= 서술자한도) return تفویض_کریں_قدر ? -9 : -22;
        if (تفویض_کریں_قدر && 서술자 == 새서술자) return 새서술자;
        if (تفویض_کریں_قدر) { if (بنائیں_ہینڈل[새서술자] != 0) بند_فائل(새서술자); }
        else { 새서술자 = 빈서술자(새서술자); if (새서술자 < 0) return 새서술자; }
        بنائیں_ہینڈل[새서술자] = 기술 + 1; 서술자설정[새서술자] = ترتیبات; 참조수[기술]++;
