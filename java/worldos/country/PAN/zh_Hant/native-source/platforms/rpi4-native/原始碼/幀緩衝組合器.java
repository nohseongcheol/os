/** 管理裁切、帶狀區域合成與指標下方背景；實際畫面記憶體存取由板級程式負責。 */
public final class 幀緩衝組合器 {
    static int 寬度值, 高度值, 是否組合中, 左邊界位置值, 上位側邊界位置, 右邊界位置值, 下位側邊界位置值;
    static int 指針橫座標, 指針Y_按鈕, 指針形狀;
    static int 計數器低位, 計數器高位;
    static int[] 已合成像素列 = new int[32 * 1920];
    static int[] 指針背景 = new int[21 * 21];
    static int[] 已裁剪邊界 = new int[4];
    public static void 準備(int 寬度跨度, int 長度) {
        寬度值 = 寬度跨度; 高度值 = 長度; 是否組合中 = 0; 指針形狀 = 0;
        計數器低位 = 0; 計數器高位 = 0;
    }
    public static int 獲取寬度() { return 寬度值; }
    public static int 獲取高度() { return 高度值; }
    public static int 獲取計數器低位() { return 計數器低位; }
    public static int 獲取計數器高位() { return 計數器高位; }
    public static int 裁剪值(int 序數索引) { return 已裁剪邊界[序數索引]; }
    static int 添加正數長度(int 開始值, int 長度) {
        if (開始值 > 2147483647 - 長度) return 2147483647;
        return 開始值 + 長度;
    }
    public static int 裁剪(int 水平位置, int 垂直位置, int 寬度跨度, int 長度) {
        if (寬度值 == 0 || 寬度跨度 <= 0 || 長度 <= 0) return 0;
        int 右 = 添加正數長度(水平位置, 寬度跨度), 下位側側 = 添加正數長度(垂直位置, 長度);
        int 左側 = 是否組合中 != 0 ? 左邊界位置值 : 0, 上位側側 = 是否組合中 != 0 ? 上位側邊界位置 : 0;
        int 最大水平位置 = 是否組合中 != 0 ? 右邊界位置值 : 寬度值, 最大垂直位置 = 是否組合中 != 0 ? 下位側邊界位置值 : 高度值;
        if (水平位置 < 左側) 水平位置 = 左側;
        if (垂直位置 < 上位側側) 垂直位置 = 上位側側;
        if (右 > 最大水平位置) 右 = 最大水平位置;
        if (下位側側 > 最大垂直位置) 下位側側 = 最大垂直位置;
        if (右 <= 水平位置 || 下位側側 <= 垂直位置) return 0;
        已裁剪邊界[0] = 水平位置; 已裁剪邊界[1] = 垂直位置;
        已裁剪邊界[2] = 右 - 水平位置; 已裁剪邊界[3] = 下位側側 - 垂直位置;
        return 1;
    }
    public static int 運行(int 水平位置, int 垂直位置, int 寬度跨度, int 長度) {
        if (是否組合中 != 0 || 長度 > 32 || 裁剪(水平位置, 垂直位置, 寬度跨度, 長度) == 0) return 0;
        左邊界位置值 = 已裁剪邊界[0]; 上位側邊界位置 = 已裁剪邊界[1];
        右邊界位置值 = 左邊界位置值 + 已裁剪邊界[2]; 下位側邊界位置值 = 上位側邊界位置 + 已裁剪邊界[3];
        是否組合中 = 1; return 1;
    }
    static boolean 指針位元(int 水平位置, int 垂直位置, int 形狀值) {
        if (形狀值 == 1) return 水平位置 >= 0 && 水平位置 <= 垂直位置 / 2 && 垂直位置 < 16;
        if (形狀值 == 3) 水平位置 = 20 - 水平位置;
        int 差異值 = 水平位置 - 垂直位置; if (差異值 < 0) 差異值 = -差異值;
        return (差異值 <= 1 && 水平位置 >= 3 && 水平位置 <= 17) ||
            (水平位置 >= 2 && 水平位置 <= 8 && 垂直位置 >= 2 && 垂直位置 <= 8 && (水平位置 <= 3 || 垂直位置 <= 3)) ||
            (水平位置 >= 12 && 水平位置 <= 18 && 垂直位置 >= 12 && 垂直位置 <= 18 && (水平位置 >= 17 || 垂直位置 >= 17));
    }
    static int 指針像素(int 水平位置, int 垂直位置) {
        if (指針位元(水平位置, 垂直位置, 指針形狀)) return 2;
        for (int 行 = -1; 行 <= 1; 行++) for (int 槽條目 = -1; 槽條目 <= 1; 槽條目++)
            if (指針位元(水平位置 + 槽條目, 垂直位置 + 行, 指針形狀)) return 1;
        return 0;
    }
    static void 顯示操作像素(int 水平位置, int 垂直位置, int 顏色值) {
        int 槽條目 = 水平位置 - 指針橫座標, 行 = 垂直位置 - 指針Y_按鈕;
        if (指針形狀 != 0 && 槽條目 >= 0 && 行 >= 0 && 槽條目 < 21 && 行 < 21) {
            指針背景[行 * 21 + 槽條目] = 顏色值;
            int 分值 = 指針像素(槽條目, 行); if (分值 != 0) 顏色值 = 分值 == 2 ? 0xffffff : 0x101010;
        }
        if (板.讀取顯示操作像素(水平位置, 垂直位置) != 顏色值) {
            板.寫入顯示操作像素(水平位置, 垂直位置, 顏色值);
            計數器低位++; if (計數器低位 == 0) 計數器高位++;
        }
    }
    public static void 結束操作() {
        if (是否組合中 == 0) return;
        for (int 行 = 上位側邊界位置; 行 < 下位側邊界位置值; 行++) for (int 槽條目 = 左邊界位置值; 槽條目 < 右邊界位置值; 槽條目++)
            顯示操作像素(槽條目, 行, 已合成像素列[(行 - 上位側邊界位置) * 1920 + 槽條目]);
        是否組合中 = 0;
    }
    public static int 像素(int 水平位置, int 垂直位置, int 顏色值) {
        if (水平位置 < 0 || 垂直位置 < 0 || 水平位置 >= 寬度值 || 垂直位置 >= 高度值) return 0;
        if (是否組合中 != 0) {
            if (水平位置 >= 左邊界位置值 && 水平位置 < 右邊界位置值 && 垂直位置 >= 上位側邊界位置 && 垂直位置 < 下位側邊界位置值)
                已合成像素列[(垂直位置 - 上位側邊界位置) * 1920 + 水平位置] = 顏色值;
        } else 顯示操作像素(水平位置, 垂直位置, 顏色值);
        return 0;
    }
    public static void 矩形填充(int 水平位置, int 垂直位置, int 寬度跨度, int 長度, int 顏色值) {
        if (裁剪(水平位置, 垂直位置, 寬度跨度, 長度) == 0) return;
        水平位置 = 已裁剪邊界[0]; 垂直位置 = 已裁剪邊界[1]; 寬度跨度 = 已裁剪邊界[2]; 長度 = 已裁剪邊界[3];
        for (int 行 = 垂直位置; 行 < 垂直位置 + 長度; 行++) for (int 槽條目 = 水平位置; 槽條目 < 水平位置 + 寬度跨度; 槽條目++) {
            if (是否組合中 != 0) 已合成像素列[(行 - 上位側邊界位置) * 1920 + 槽條目] = 顏色值;
            else 顯示操作像素(槽條目, 行, 顏色值);
        }
    }
    public static void 指針(int 水平位置, int 垂直位置, int 形狀值) {
        if (寬度值 == 0) return;
        int 新建水平位置 = 水平位置 - (形狀值 >= 2 ? 10 : 0), 新建垂直位置 = 垂直位置 - (形狀值 >= 2 ? 10 : 0);
        if (指針形狀 == 形狀值 && 指針橫座標 == 新建水平位置 && 指針Y_按鈕 == 新建垂直位置) return;
        if (指針形狀 != 0) for (int 行 = 0; 行 < 21; 行++) for (int 槽條目 = 0; 槽條目 < 21; 槽條目++) {
            int 首位操作數 = 指針橫座標 + 槽條目, 三值 = 指針Y_按鈕 + 行;
            if (首位操作數 >= 0 && 三值 >= 0 && 首位操作數 < 寬度值 && 三值 < 高度值) 板.寫入顯示操作像素(首位操作數, 三值, 指針背景[行 * 21 + 槽條目]);
        }
        指針形狀 = 形狀值; 指針橫座標 = 新建水平位置; 指針Y_按鈕 = 新建垂直位置;
        if (形狀值 != 0) for (int 行 = 0; 行 < 21; 行++) for (int 槽條目 = 0; 槽條目 < 21; 槽條目++) {
            int 首位操作數 = 指針橫座標 + 槽條目, 三值 = 指針Y_按鈕 + 行;
            if (首位操作數 >= 0 && 三值 >= 0 && 首位操作數 < 寬度值 && 三值 < 高度值) {
                指針背景[行 * 21 + 槽條目] = 板.讀取顯示操作像素(首位操作數, 三值);
                int 分值 = 指針像素(槽條目, 行); if (分值 != 0) 板.寫入顯示操作像素(首位操作數, 三值, 分值 == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
