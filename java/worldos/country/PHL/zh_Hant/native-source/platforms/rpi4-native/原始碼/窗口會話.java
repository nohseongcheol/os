/** 四個終端機的 shell 狀態；共用檔案儲存，路徑、變數、歷史與輸入各自獨立。 */
public final class 窗口會話 {
    static int[] 保留值 = new int[4 * 30000], 準備 = new int[4];
    static int 當前項目, 位置;
    static boolean 讀取繼續狀態;
    static void 陣列值(int[] 資料, boolean 存儲值) {
        for (int 循環索引 = 0; 循環索引 < 資料.length; 循環索引++) { if (存儲值) 保留值[位置++] = 資料[循環索引]; else 資料[循環索引] = 保留值[位置++]; }
    }
    static int 值(int 資料值, boolean 曾經已存儲) { if (曾經已存儲) { 保留值[位置++] = 資料值; return 資料值; } return 保留值[位置++]; }
    static void 尋道位置(int 已保留槽, boolean 曾經已存儲) {
        位置 = 已保留槽 * 30000;
        陣列值(記憶體檔案集.當前項目, 曾經已存儲); 記憶體檔案集.當前長度 = 值(記憶體檔案集.當前長度, 曾經已存儲);
        陣列值(命令殼語法.變量名稱, 曾經已存儲); 陣列值(命令殼語法.變量資料, 曾經已存儲); 陣列值(命令殼語法.名稱長度, 曾經已存儲); 陣列值(命令殼語法.值長度, 曾經已存儲);
        命令殼語法.狀態值 = 值(命令殼語法.狀態值, 曾經已存儲);
        陣列值(行編輯器.日誌記錄, 曾經已存儲); 陣列值(行編輯器.日誌長度, 曾經已存儲); 陣列值(行編輯器.存儲值, 曾經已存儲); 陣列值(命令解釋器.行, 曾經已存儲);
        行編輯器.日誌個數 = 值(行編輯器.日誌個數, 曾經已存儲); 行編輯器.日誌記錄結束 = 值(行編輯器.日誌記錄結束, 曾經已存儲);
        行編輯器.搜索值 = 值(行編輯器.搜索值, 曾經已存儲); 行編輯器.已存儲長度 = 值(行編輯器.已存儲長度, 曾經已存儲);
        行編輯器.大小 = 值(行編輯器.大小, 曾經已存儲); 行編輯器.光標值 = 值(行編輯器.光標值, 曾經已存儲); 行編輯器.開始窗口 = 值(行編輯器.開始窗口, 曾經已存儲);
        準備[已保留槽] = 1;
    }
    static void 程序值條目() {
        int 事件編號 = 板.終端(12); if (事件編號 == 0) return;
        尋道位置(當前項目, true);
        for (int 循環索引 = 0; 循環索引 < 4; 循環索引++) {
            if ((事件編號 & (1 << (8 + 循環索引))) != 0) { 板.控制用戶程式(32 + 循環索引); 準備[循環索引] = 0; }
            if ((事件編號 & (1 << (4 + 循環索引))) != 0 && 循環索引 != 當前項目) 準備[循環索引] = 0;
        }
        int 下一位置 = (事件編號 & 15) - 1; if (下一位置 < 0) 下一位置 = 0;
        if (準備[下一位置] == 0) for (int 循環索引 = 0; 循環索引 < 30000; 循環索引++) 保留值[下一位置 * 30000 + 循環索引] = 0;
        當前項目 = 下一位置; 尋道位置(當前項目, false); 板.終端(100 + 當前項目); 讀取繼續狀態 = true;
        終端輸入輸出.寫入("\nTERMINAL FOCUS "); 終端輸入輸出.數(當前項目 + 1); 終端輸入輸出.字元(10);
    }
    static boolean 恢復執行執行狀態() {
        if (板.控制用戶程式(16 + 當前項目) == 0) return false;
        命令殼輸入輸出.允許交互式 = true; 命令殼輸入輸出.運行(false, false); 板.切換輸入輸出(1);
        int 已處理值 = 板.控制用戶程式(當前項目); 命令殼輸入輸出.結尾();
        if (已處理值 != -1005) { 讀取繼續狀態 = false; 命令殼語法.狀態值 = 已處理值 < 0 ? 126 : 已處理值; 終端輸入輸出.寫入("exit "); 終端輸入輸出.數(已處理值); 終端輸入輸出.字元(10); 板.終端(3); }
        return true;
    }
}
