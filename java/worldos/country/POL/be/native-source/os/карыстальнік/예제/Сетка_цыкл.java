/** 최대 Памер/홀수 даўжыня_значэнне 데이터그램으로 фактычны_дадзеныя RTL8139 수신 цыкл_значэнне 순환을 시험한다. */
public final class Сетка_цыкл {
    public static int Выканаць() {
        if (карыстальнік.인수개수() != 1) { карыстальнік.Запіс("Usage: run stress PORT\n"); return 2; }
        String Тэкст = карыстальнік.인수(0);
        int порт_значэнне = 0;
        for (int індэкс = 0; індэкс < Тэкст.length(); індэкс++) {
            if (Тэкст.charAt(індэкс) < '0' || Тэкст.charAt(індэкс) > '9' || порт_значэнне > 6553) return 2;
            порт_значэнне = порт_значэнне * 10 + Тэкст.charAt(індэкс) - '0';
        }
        if (порт_значэнне < 1 || порт_значэнне > 65535) return 2;
        int маркер_значэнне = карыстальнік.адкрыць_Сетка(0);
        if (маркер_значэнне < 0) return 3;
        int[] дадзеныя = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int даўжыня_значэнне = 1024 - (회차 & 1);
            for (int індэкс = 0; індэкс < даўжыня_значэнне; індэкс++) дадзеныя[індэкс] = (індэкс + 회차) & 255;
            if (карыстальнік.адправіць_дадзеныя(маркер_значэнне, 0x0a000202, порт_значэнне, дадзеныя, даўжыня_значэнне) != даўжыня_значэнне) return 4;
            if (карыстальнік.자료받기(маркер_значэнне, дадзеныя, 300) != даўжыня_значэнне) return 5;
            for (int індэкс = 0; індэкс < даўжыня_значэнне; індэкс++) if (дадзеныя[індэкс] != ((індэкс + 회차) & 255)) return 6;
        }
        карыстальнік.закрыць_Сетка(маркер_значэнне);
        карыстальнік.Запіс("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
