package Польшча.JPolOS.Сетка_Стэк;

/** Ethernet/ARP/IPv4/ICMP/UDP 계층이 공유하는 байт_значэнне 순서와 кантрольная_сума 도구다. */
public final class Сетка_Інструменты {
    private Сетка_Інструменты() {
    }

    public static int 큰순서짧은정수(byte[] дадзеныя, int Пазіцыя) {
        범위확인(дадзеныя, Пазіцыя, 2);
        return ((дадзеныя[Пазіцыя] & 0xff) << 8) | (дадзеныя[Пазіцыя + 1] & 0xff);
    }

    public static long 큰순서정수(byte[] дадзеныя, int Пазіцыя) {
        범위확인(дадзеныя, Пазіцыя, 4);
        return ((long) (дадзеныя[Пазіцыя] & 0xff) << 24)
                | ((long) (дадзеныя[Пазіцыя + 1] & 0xff) << 16)
                | ((long) (дадзеныя[Пазіцыя + 2] & 0xff) << 8)
                | (дадзеныя[Пазіцыя + 3] & 0xffL);
    }

    public static int воблака_кантрольная_сума(byte[] дадзеныя, int Выканаць, int даўжыня_значэнне) {
        범위확인(дадзеныя, Выканаць, даўжыня_значэнне);
        long 합 = 0;
        int 끝 = Выканаць + даўжыня_значэнне;
        int Пазіцыя = Выканаць;
        while (Пазіцыя + 1 < 끝) {
            합 += 큰순서짧은정수(дадзеныя, Пазіцыя);
            Пазіцыя += 2;
        }
        if (Пазіцыя < 끝) {
            합 += (дадзеныя[Пазіцыя] & 0xff) << 8;
        }
        while ((합 >>> 16) != 0) {
            합 = (합 & 0xffff) + (합 >>> 16);
        }
        return (int) (~합) & 0xffff;
    }

    public static boolean 이더넷틀인가(byte[] дадзеныя) {
        return дадзеныя != null && дадзеныя.length >= 14;
    }

    public static int 이더넷상위규약(byte[] дадзеныя) {
        if (!이더넷틀인가(дадзеныя)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return 큰순서짧은정수(дадзеныя, 12);
    }

    public static boolean 상호통신망규약사판인가(byte[] дадзеныя, int Пазіцыя) {
        if (дадзеныя == null || Пазіцыя < 0 || дадзеныя.length - Пазіцыя < 20) {
            return false;
        }
        int версія_значэнне = (дадзеныя[Пазіцыя] >>> 4) & 0xf;
        int Загаловак_даўжыня = (дадзеныя[Пазіцыя] & 0xf) * 4;
        return версія_значэнне == 4 && Загаловак_даўжыня >= 20 && дадзеныя.length - Пазіцыя >= Загаловак_даўжыня;
    }

    private static void 범위확인(byte[] дадзеныя, int Выканаць, int даўжыня_значэнне) {
        if (дадзеныя == null || Выканаць < 0 || даўжыня_значэнне < 0 || Выканаць > дадзеныя.length - даўжыня_значэнне) {
            throw new IllegalArgumentException("Сетка_Стэк дадзеныя 범위를 벗어났습니다.");
        }
    }
}

