package Польшча.JPolOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB старонка_значэнне 연결과 Запіс 시 복사를 제공한다. */
public final class старонка_менеджар {
    public static final int памер_старонкі = 4096;

    private static final class старонка_значэнне {
        private byte[] дадзеныя = new byte[памер_старонкі];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class адрас_ПРАБЕЛ {
        private final Map<Integer, старонка_значэнне> старонка_табліца = new HashMap<Integer, старонка_значэнне>();
    }

    public адрас_ПРАБЕЛ 새주소공간() {
        return new адрас_ПРАБЕЛ();
    }

    public void супастаўляць_старонка(адрас_ПРАБЕЛ 공간, int віртуальны_адрас, boolean 쓰기가능) {
        int індэкс = 쪽번호(віртуальны_адрас);
        старонка_значэнне 새쪽 = new старонка_значэнне();
        새쪽.쓰기가능 = 쓰기가능;
        공간.старонка_табліца.put(Integer.valueOf(індэкс), 새쪽);
    }

    public адрас_ПРАБЕЛ 쓰기시복사복제(адрас_ПРАБЕЛ 원본) {
        адрас_ПРАБЕЛ 복제본 = new адрас_ПРАБЕЛ();
        for (Map.Entry<Integer, старонка_значэнне> увядзенне_значэнне : 원본.старонка_табліца.entrySet()) {
            старонка_значэнне 공유쪽 = увядзенне_значэнне.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.старонка_табліца.put(увядзенне_значэнне.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(адрас_ПРАБЕЛ 공간, int віртуальны_адрас) {
        старонка_значэнне мэтавы_паказчык = выявіць_старонка(공간, віртуальны_адрас);
        return мэтавы_паказчык.дадзеныя[Math.floorMod(віртуальны_адрас, памер_старонкі)];
    }

    public void напісаць_байт_значэнне(адрас_ПРАБЕЛ 공간, int віртуальны_адрас, byte значэнне) {
        int індэкс = 쪽번호(віртуальны_адрас);
        старонка_значэнне мэтавы_паказчык = выявіць_старонка(공간, віртуальны_адрас);
        if (!мэтавы_паказчык.쓰기가능) {
            if (!мэтавы_паказчык.쓰기시복사) {
                throw new IllegalStateException("Чытанне 전용 쪽입니다.");
            }
            мэтавы_паказчык = стварыць_прыватны_старонка(공간, індэкс, мэтавы_паказчык);
        }
        мэтавы_паказчык.дадзеныя[Math.floorMod(віртуальны_адрас, памер_старонкі)] = значэнне;
    }

    public void 범위개인쓰기(адрас_ПРАБЕЛ 공간, int Пуск_адрас, int Памер) {
        if (Памер < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int скончыць_адрас = Math.addExact(Пуск_адрас, Памер);
        for (int адрас = Пуск_адрас; адрас < скончыць_адрас; адрас = (쪽번호(адрас) + 1) * памер_старонкі) {
            int індэкс = 쪽번호(адрас);
            старонка_значэнне мэтавы_паказчык = выявіць_старонка(공간, адрас);
            if (мэтавы_паказчык.쓰기시복사) {
                стварыць_прыватны_старонка(공간, індэкс, мэтавы_паказчык);
            } else {
                мэтавы_паказчык.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(адрас_ПРАБЕЛ 공간, int Пуск_адрас, byte[] дадзеныя) {
        for (int індэкс = 0; індэкс < дадзеныя.length; індэкс++) {
            напісаць_байт_значэнне(공간, Пуск_адрас + індэкс, дадзеныя[індэкс]);
        }
    }

    private старонка_значэнне стварыць_прыватны_старонка(адрас_ПРАБЕЛ 공간, int індэкс, старонка_значэнне 공유쪽) {
        старонка_значэнне прыватны_старонка = new старонка_значэнне();
        прыватны_старонка.дадзеныя = Arrays.copyOf(공유쪽.дадзеныя, 공유쪽.дадзеныя.length);
        прыватны_старонка.쓰기가능 = true;
        прыватны_старонка.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.старонка_табліца.put(Integer.valueOf(індэкс), прыватны_старонка);
        return прыватны_старонка;
    }

    private старонка_значэнне выявіць_старонка(адрас_ПРАБЕЛ 공간, int адрас) {
        старонка_значэнне мэтавы_паказчык = 공간.старонка_табліца.get(Integer.valueOf(쪽번호(адрас)));
        if (мэтавы_паказчык == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return мэтавы_паказчык;
    }

    private int 쪽번호(int адрас) {
        if (адрас < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return адрас / памер_старонкі;
    }
}

