package Польшча.JPolOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Польшча.JPolOS.기억공간.старонка_менеджар;
import Польшча.JPolOS.файлавая_сістэма.파일서술자표;

/** Працэс_значэнне 식별자와 라운드로빈 Падрыхтаваць 대기열을 관리한다. */
public final class 배정기 {
    private final старонка_менеджар 쪽관리;
    private final Map<Integer, Працэс_значэнне> Спіс_працэсаў = new HashMap<Integer, Працэс_значэнне>();
    private final Queue<Працэс_значэнне> 준비대기열 = new ArrayDeque<Працэс_значэнне>();
    private int 다음식별자 = 1;

    public 배정기(старонка_менеджар 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public Працэс_значэнне 첫과정(파일서술자표 파일서술자) {
        Працэс_значэнне 새과정 = new Працэс_значэнне(вылучыць_ідэнтыфікатар(), 0, 쪽관리.새주소공간(), 파일서술자);
        Спіс_працэсаў.put(Integer.valueOf(새과정.ідэнтыфікатар_значэнне()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public Працэс_значэнне 복제(Працэс_значэнне 부모) {
        Працэс_значэнне дзіця_значэнне = new Працэс_значэнне(
                вылучыць_ідэнтыфікатар(),
                부모.ідэнтыфікатар_значэнне(),
                쪽관리.쓰기시복사복제(부모.адрас_ПРАБЕЛ()),
                부모.파일서술자().복제());
        дзіця_значэнне.프로그램끝설정(부모.프로그램끝());
        Спіс_працэсаў.put(Integer.valueOf(дзіця_значэнне.ідэнтыфікатар_значэнне()), дзіця_значэнне);
        준비대기열.offer(дзіця_значэнне);
        return дзіця_значэнне;
    }

    public Працэс_значэнне 다음과정() {
        int 검사수 = 준비대기열.size();
        for (int індэкс = 0; індэкс < 검사수; індэкс++) {
            Працэс_значэнне 다음 = 준비대기열.poll();
            if (다음 != null && (다음.стан_значэнне() == Працэс_стан.Падрыхтаваць || 다음.стан_значэнне() == Працэс_стан.выканаць_каманда)) {
                다음.набор_стан(Працэс_стан.выканаць_каманда);
                준비대기열.offer(다음);
                return 다음;
            }
        }
        return null;
    }

    public int 자식기다리기(Працэс_значэнне 부모, int дзіця_ідэнтыфікатар, boolean 기다리지않음) {
        for (Працэс_значэнне 후보 : Спіс_працэсаў.values()) {
            if (후보.부모식별자() != 부모.ідэнтыфікатар_значэнне()) {
                continue;
            }
            if (дзіця_ідэнтыфікатар > 0 && 후보.ідэнтыфікатар_значэнне() != дзіця_ідэнтыфікатар) {
                continue;
            }
            if (후보.стан_значэнне() == Працэс_стан.Выхад_праграма) {
                int 결과 = (후보.Выхад_код() & 0xff) << 8;
                Спіс_працэсаў.remove(Integer.valueOf(후보.ідэнтыфікатар_значэнне()));
                return 결과;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public Працэс_значэнне выявіць_Працэс(int ідэнтыфікатар_значэнне) {
        return Спіс_працэсаў.get(Integer.valueOf(ідэнтыфікатар_значэнне));
    }

    private int вылучыць_ідэнтыфікатар() {
        return 다음식별자++;
    }
}
