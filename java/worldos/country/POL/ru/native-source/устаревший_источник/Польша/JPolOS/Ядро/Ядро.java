package Польша.JPolOS.Ядро;

import Польша.JPolOS.Память_регион.Память_менеджер;
import Польша.JPolOS.Память_регион.страница_менеджер;
import Польша.JPolOS.входные_данные_ЗНАЧЕН.входные_данные_менеджер;
import Польша.JPolOS.작업.Процесс_ЗНАЧЕН;
import Польша.JPolOS.작업.Планировщик;
import Польша.JPolOS.системный_вызов.системный_вызов;
import Польша.JPolOS.файловая_система.файл_дескриптор_таблица;
import Польша.JPolOS.файловая_система.файловая_система;

/** Java 관리 커널의 조립과 시작을 담당한다. */
public final class Ядро {
    private final аппаратный_ЗНАЧЕН устройство_ЗНАЧЕН;
    private final Память_менеджер Память_регион = new Память_менеджер(32 * 1024 * 1024);
    private final страница_менеджер 쪽관리 = new страница_менеджер();
    private final файловая_система файловая_система = new файловая_система();
    private final Планировщик Планировщик = new Планировщик(쪽관리);
    private final входные_данные_менеджер 입력관리 = new входные_данные_менеджер(256);
    private final Процесс_ЗНАЧЕН 첫과정;
    private final системный_вызов системный_вызов;

    public Ядро(аппаратный_ЗНАЧЕН устройство_ЗНАЧЕН) {
        this.устройство_ЗНАЧЕН = устройство_ЗНАЧЕН;
        첫과정 = Планировщик.첫과정(new файл_дескриптор_таблица(файловая_система));
        системный_вызов = new системный_вызов(файловая_система, 쪽관리, Планировщик, устройство_ЗНАЧЕН, 입력관리);
    }

    public void запустить() {
        устройство_ЗНАЧЕН.직렬출력("=== JPolOS 관리 ядро_ЗНАЧЕН ===\n");
    }

    public void Выполнить_шаг() {
        устройство_ЗНАЧЕН.중앙처리장치멈춤();
    }

    public Память_менеджер Память_регион() {
        return Память_регион;
    }

    public страница_менеджер 쪽관리() {
        return 쪽관리;
    }

    public файловая_система файловая_система() {
        return файловая_система;
    }

    public Планировщик Планировщик() {
        return Планировщик;
    }

    public входные_данные_менеджер 입력관리() {
        return 입력관리;
    }

    public Процесс_ЗНАЧЕН 첫과정() {
        return 첫과정;
    }

    public системный_вызов системный_вызов() {
        return системный_вызов;
    }
}
