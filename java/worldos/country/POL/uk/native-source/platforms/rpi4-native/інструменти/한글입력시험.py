#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from настільний_Вигляд import клавіатура


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.Текст_буфер = ''
        def надсилати(дані):
            for символьні_дані in дані.decode('utf-8'):
                if символьні_дані == '\x7f': 자신.Текст_буфер = 자신.Текст_буфер[:-1]
                else: 자신.Текст_буфер += символьні_дані
        자신.клавіатура_запис = клавіатура(надсилати)

    def натиснути_Ключ(자신, символ_значення):
        자신.клавіатура_запис.누름값(True, символ_значення)
        자신.клавіатура_запис.누름값(False, символ_значення)

    def Тип_область(자신, 누름열):
        for 누름값 in 누름열: 자신.натиснути_Ключ(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.натиснути_Ключ(0xffc6); 자신.Тип_область(누름열)
                자신.assertEqual(자신.Текст_буфер, 예상결과)

    def test_앞글자지우기(자신):
        자신.натиснути_Ключ(0xff31); 자신.Тип_область('dlfr')
        자신.assertEqual(자신.Текст_буфер,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.натиснути_Ключ(0xff08); 자신.assertEqual(자신.Текст_буфер,예상결과)
        자신.Тип_область('gksk'); 자신.assertEqual(자신.Текст_буфер,'하나')
        자신.натиснути_Ключ(0xff08); 자신.assertEqual(자신.Текст_буфер,'하ㄴ')

    def test_전환반복확정(자신):
        자신.Тип_область('echo ')
        자신.клавіатура_запис.누름값(True,0xffe1)
        자신.клавіатура_запис.누름값(True,32); 자신.клавіатура_запис.누름값(True,32)
        자신.клавіатура_запис.누름값(False,32); 자신.клавіатура_запис.누름값(False,0xffe1)
        자신.assertTrue(자신.клавіатура_запис.한글여부)
        자신.Тип_область('gksrmf'); 자신.натиснути_Ключ(0xff31); 자신.Тип_область(' English')
        자신.assertEqual(자신.Текст_буфер,'echo 한글 English')
        자신.assertFalse(자신.клавіатура_запис.한글여부)
        자신.натиснути_Ключ(0xffc6); 자신.Тип_область('rk'); 자신.натиснути_Ключ(0xff51)
        자신.Тип_область('sk'); 자신.assertTrue(자신.Текст_буфер.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.натиснути_Ключ(0xffc6); 자신.Тип_область('rk')
        자신.клавіатура_запис.буфер_обміну_значення='вставляти_значення'.encode()
        자신.клавіатура_запис.누름값(True,0xffe3); 자신.клавіатура_запис.누름값(True,0xffe1)
        자신.натиснути_Ключ(ord('v'))
        자신.клавіатура_запис.누름값(False,0xffe1); 자신.клавіатура_запис.누름값(False,0xffe3)
        자신.натиснути_Ключ(0x0100d55c); 자신.Тип_область('sk')
        자신.assertEqual(자신.Текст_буфер,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
