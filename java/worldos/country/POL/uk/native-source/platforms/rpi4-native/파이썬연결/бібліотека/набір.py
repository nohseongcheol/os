import jkoros as операційна_система_ОС

список_шлях = "/lib/.pip.json"


def 지문(дані):
    return "".join("%02x" % значення for значення in hashlib.sha256(дані).digest())


def 목록읽기():
    if операційна_система_ОС.path_kind(список_шлях) == 0:
        return {}
    return json.loads(операційна_система_ОС.read(список_шлях).decode("utf-8"))


def записування_журнал(шлях, дані):
    if операційна_система_ОС.write(шлях, дані) != len(дані):
        raise OSError(28)


def перевіряти_шлях(шлях):
    if not isinstance(шлях, str) or not шлях.endswith(".py"):
        raise ValueError("Python 소스만 설치할 수 있습니다.")
    if any(부분 in ("", ".", "..") or 부분.startswith(".") for 부분 in шлях.split("/")):
        raise ValueError("허용하지 않는 набір шлях")
    if "\\" in шлях or any(ord(символ_значення_068c2631) < 32 or ord(символ_значення_068c2631) == 127 for символ_значення_068c2631 in шлях):
        raise ValueError("잘못된 шлях 문자")
    результат = "/lib/" + шлях
    if len(результат.encode("utf-8")) > 63 or шлях in ("українська.py", "набір.py"):
        raise ValueError("набір 경로가 너무 길거나 стандартне_значення 라이브러리와 겹칩니다.")
    return результат


class отримувати_потік:
    def __init__(자신, учасник):
        자신.учасник = учасник
        자신.남은자료 = b""
        자신.запустити = операційна_система_ОС.ticks_ms()

    def 정확히읽기(자신, 길이):
        дані = bytearray()
        while len(дані) < 길이:
            if операційна_система_ОС.ticks_ms() - 자신.запустити > 90000:
                raise ValueError("набір 중계 відповідь час_значення 초과")
            if not 자신.남은자료:
                try:
                    자신.남은자료 = операційна_система_ОС.tcp_read(자신.учасник, 512)
                except OSError as ПОМИЛКА:
                    if ПОМИЛКА.args[0] != 11:
                        raise
                    операційна_система_ОС.sleep_ms(10)
                    continue
                if not 자신.남은자료:
                    raise ValueError("набір 전송이 중간에 끝났습니다.")
            개수 = min(길이 - len(дані), len(자신.남은자료))
            дані.extend(자신.남은자료[:개수])
            자신.남은자료 = 자신.남은자료[개수:]
            операційна_система_ОС.sleep_ms(0)
        return bytes(дані)


def завантажити(запит, номер_порту):
    if len(запит) > 96 or any(символ_значення_068c2631 not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-=" for символ_значення_068c2631 in запит):
        raise ValueError("사용법: pip install Назва 또는 Назва==버전")
    учасник = операційна_система_ОС.tcp_open()
    try:
        запустити = операційна_система_ОС.ticks_ms()
        while True:
            try:
                операційна_система_ОС.tcp_connect(учасник, "10.0.2.2", номер_порту)
                break
            except OSError as ПОМИЛКА:
                if ПОМИЛКА.args[0] not in (11, 115) or операційна_система_ОС.ticks_ms() - запустити > 5000:
                    raise ValueError("набір 중계 З_єднання неполадка_значення: 호스트에서 --network --pip로 실행하십시오.")
                операційна_система_ОС.sleep_ms(10)
        дані = (запит + "\n").encode()
        while дані:
            try:
                개수 = операційна_система_ОС.tcp_write(учасник, дані)
                if not 개수:
                    raise ValueError("набір запит передача_значення неполадка_значення")
                дані = дані[개수:]
            except OSError as ПОМИЛКА:
                if ПОМИЛКА.args[0] != 11:
                    raise
                операційна_система_ОС.sleep_ms(10)
                if операційна_система_ОС.ticks_ms() - запустити > 10000:
                    raise ValueError("набір запит передача_значення час_значення 초과")
        потік_значення = отримувати_потік(учасник)
        머리 = потік_значення.정확히읽기(8)
        if 머리[:4] != b"JKP1":
            raise ValueError("набір передача_значення контракт_значення 불일치")
        길이 = (머리[4] << 24) | (머리[5] << 16) | (머리[6] << 8) | 머리[7]
        if 길이 > 8192:
            raise ValueError("набір 명세가 너무 큽니다.")
        명세 = json.loads(потік_значення.정확히읽기(길이).decode())
        if "error" in 명세:
            raise ValueError(명세["error"])
        if not 1 <= len(명세["files"]) <= 16:
            raise ValueError("꾸러미당 джерело_дерево 파일은 1~16개여야 합니다.")
        if sum(запис_значення_962f286b["size"] for запис_значення_962f286b in 명세["files"]) > 65536:
            raise ValueError("набір джерело_дерево 합계는 64 KiB 이하여야 합니다.")
        파일들 = {}
        for запис_значення_962f286b in 명세["files"]:
            шлях = перевіряти_шлях(запис_значення_962f286b["path"])
            if шлях in 파일들 or not 0 <= запис_значення_962f286b["size"] <= 16384:
                raise ValueError("중복 шлях 또는 файл Розмір 초과")
            дані = потік_значення.정확히읽기(запис_значення_962f286b["size"])
            if 지문(дані) != запис_значення_962f286b["sha256"]:
                raise ValueError("набір файл SHA-256 불일치")
            # 실행하지 않고 чинний_елемент MicroPython의 문법으로 먼저 검사한다.
            compile(дані.decode("utf-8"), шлях, "exec")
            파일들[шлях] = дані
            gc.collect()
        return 명세, 파일들
    finally:
        операційна_система_ОС.udp_close(учасник)


def інсталювати_значення(запит, номер_порту):
    print("набір завантажити:", запит)
    명세, 파일들 = завантажити(запит, номер_порту)
    запис_список = 목록읽기()
    Назва = 명세["name"]
    if Назва in запис_список:
        if запис_список[Назва]["version"] == 명세["version"]:
            for шлях, 지문값 in запис_список[Назва]["files"].items():
                if операційна_система_ОС.path_kind(шлях) != 1 or 지문(операційна_система_ОС.read(шлях)) != 지문값:
                    raise ValueError("설치된 набір 파일이 달라졌습니다: " + шлях)
            print("이미 설치됨:", Назва, 명세["version"])
            return
        raise ValueError("다른 버전이 있습니다. pip uninstall로 제거한 НАЗАД_значення 설치하십시오.")
    for шлях in 파일들:
        if операційна_система_ОС.path_kind(шлях):
            raise ValueError("기존 파일을 덮어쓰지 않습니다: " + шлях)
    запис_список[Назва] = {"version": 명세["version"], "files": {шлях: 지문(дані) for шлях, дані in 파일들.items()}}
    새목록 = json.dumps(запис_список).encode()
    if len(새목록) > 16384:
        raise ValueError("набір запис_список Розмір 초과")
    이전목록 = операційна_система_ОС.read(список_шлях) if операційна_система_ОС.path_kind(список_шлях) else None
    만든파일 = []
    만든폴더 = []
    try:
        for шлях, дані in 파일들.items():
            부분들 = шлях.split("/")
            for 수 in range(2, len(부분들)):
                Каталог_значення = "/".join(부분들[:수])
                종류 = операційна_система_ОС.path_kind(Каталог_значення)
                if 종류 == 0:
                    операційна_система_ОС.mkdir(Каталог_значення)
                    만든폴더.append(Каталог_значення)
                elif 종류 != 2:
                    raise ValueError("Каталог_значення 경로에 파일이 있습니다: " + Каталог_значення)
            만든파일.append(шлях)
            записування_журнал(шлях, дані)
        записування_журнал(список_шлях, 새목록)
    except Exception:
        for шлях in 만든파일:
            if операційна_система_ОС.path_kind(шлях):
                операційна_система_ОС.remove(шлях)
        for Каталог_значення in reversed(만든폴더):
            операційна_система_ОС.rmdir(Каталог_значення)
        if 이전목록 is not None:
            записування_журнал(список_шлях, 이전목록)
        elif операційна_система_ОС.path_kind(список_шлях):
            операційна_система_ОС.remove(список_шлях)
        raise
    print("інсталювати_значення 완료:", Назва, 명세["version"], "→ /lib (RAM)")


def вилучати_запис(Назва):
    запис_список = 목록읽기()
    if Назва not in запис_список:
        raise ValueError("설치되지 않은 꾸러미입니다: " + Назва)
    for шлях, 지문값 in запис_список[Назва]["files"].items():
        if операційна_система_ОС.path_kind(шлях) != 1 or 지문(операційна_система_ОС.read(шлях)) != 지문값:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + шлях)
    for шлях in запис_список[Назва]["files"]:
        операційна_система_ОС.remove(шлях)
    del запис_список[Назва]
    записування_журнал(список_шлях, json.dumps(запис_список).encode())
    print("вилучати_запис 완료:", Назва)


def запустити(аргументи):
    номер_порту = 8027
    if len(аргументи) >= 2 and аргументи[-2] == "--port":
        номер_порту = int(аргументи[-1])
        аргументи = аргументи[:-2]
    if аргументи == ["list"]:
        for Назва, Відомості_про_систему in 목록읽기().items():
            print(Назва, Відомості_про_систему["version"])
    elif len(аргументи) == 2 and аргументи[0] == "install":
        інсталювати_значення(аргументи[1], номер_порту)
    elif len(аргументи) == 2 and аргументи[0] == "uninstall":
        вилучати_запис(аргументи[1])
    elif not аргументи or аргументи in (["--help"], ["--version"]):
        print("jkoros pip 1 / MicroPython джерело_дерево 설치기 (PyPA pip 전체가 아님)")
        print("pip install Назва[==버전] [--port 8027] | pip list | pip uninstall Назва")
        print("хост: інструменти/Виконати_команда.py --network --pip; /lib는 재부팅 때 사라지는 RAM입니다.")
    else:
        raise ValueError("pip --help로 사용법을 확인하십시오.")


