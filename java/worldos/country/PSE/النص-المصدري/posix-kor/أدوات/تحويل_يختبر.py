#!/usr/bin/env python3
"""بنية_نظام 변환이 العربية سلسلة_قيمة, 주석, 헤더 경로를 바꾸지 않는지 검사한다."""
from معرف_تحويل import تحويل_قيمة

مصدر = '''#include <파일규약.h>
#include "통신규약.h"
// فتح_ملف 라는 주석
/* 자료이름 */
const char *ملف_إدخال_اسم = "한글 \\" سلسلة_قيمة";
char حرف_قيمة = '가';
int 파일열기_횟수 = 1;
'''
مخرجات = تحويل_قيمة(مصدر)
assert '#include <파일규약.h>' in مخرجات
assert '#include "통신규약.h"' in مخرجات
assert '// فتح_ملف 라는 주석' in مخرجات
assert '/* 자료이름 */' in مخرجات
assert '"한글 \\" سلسلة_قيمة"' in مخرجات
assert "'가'" in مخرجات
assert '\\ud30c\\uc77c\\uc774\\ub984' in مخرجات
assert '파일열기_횟수' not in مخرجات
assert تحويل_قيمة(مخرجات) == مخرجات
print('PASS: العربية معرف_قيمة تحويل_قيمة/سلسلة_قيمة·주석·مسار 보존')
