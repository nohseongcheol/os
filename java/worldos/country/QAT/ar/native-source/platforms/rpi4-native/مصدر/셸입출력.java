/** 파이프는 16 KiB씩 순서대로 실행한다. 프로세스/동시 파이프를 흉내 내지 않는다. */
public final class 셸입출력 {
    static int[] إدخال_بيانات = new int[16384], الناتج_بيانات = new int[16384];
    static int 입력길이, إدخال_منصب, 출력길이, ملف_إدخال = -1, ملف_الإخراج = -1;
    static boolean خط_عمودي_إدخال, خط_عمودي_الناتج;
    static int فشل_قيمة;
    static boolean يسمح_تفاعلي = true;
    public static int أنظمة_المعلومات_تفاعلي() { return يسمح_تفاعلي && ملف_إدخال < 3 && ملف_الإخراج < 3 && !خط_عمودي_إدخال && !خط_عمودي_الناتج ? 1 : 0; }
    public static int مخرجات(int قناة_قيمة, int قيمة) {
        if (قناة_قيمة != 1) return 0;
        if (ملف_الإخراج >= 3) { int 처리값 = ذاكرة_الملفات.كتابة(ملف_الإخراج, قيمة); if (처리값 < 0) فشل_قيمة = 처리값; return 1; }
        if (!خط_عمودي_الناتج) return 0;
        if (출력길이 == الناتج_بيانات.length) فشل_قيمة = -28;
        else الناتج_بيانات[출력길이++] = قيمة;
        return 1;
    }
    public static int إدخال_قيمة() {
        if (ملف_إدخال >= 3) { int 처리값 = ذاكرة_الملفات.قراءة(ملف_إدخال); return 처리값 == 256 ? -2 : 처리값; }
        if (خط_عمودي_إدخال) return إدخال_منصب < 입력길이 ? إدخال_بيانات[إدخال_منصب++] : -2;
        return -3; // UART로 تحويل_قيمة_24592b8a
    }
    static void تشغيل(boolean بادئة_خط_عمودي, boolean لاحق_خط_عمودي) {
        خط_عمودي_إدخال = بادئة_خط_عمودي; خط_عمودي_الناتج = لاحق_خط_عمودي;
        إدخال_منصب = 0; 출력길이 = 0; ملف_إدخال = -1; ملف_الإخراج = -1; فشل_قيمة = 0;
    }
    static void 끝() {
        لوحة.입출력전환(0);
        if (ملف_إدخال >= 3) ذاكرة_الملفات.إغلاق(ملف_إدخال);
        if (ملف_الإخراج >= 3) ذاكرة_الملفات.إغلاق(ملف_الإخراج);
        if (خط_عمودي_الناتج) { 입력길이 = 출력길이; for (int يكرر_فهرس = 0; يكرر_فهرس < 출력길이; يكرر_فهرس++) إدخال_بيانات[يكرر_فهرس] = الناتج_بيانات[يكرر_فهرس]; }
        ملف_إدخال = -1; ملف_الإخراج = -1; خط_عمودي_إدخال = false; خط_عمودي_الناتج = false;
    }
}
