/** 최대 اندازه/홀수 طول_مقدار 데이터그램으로 واقعی_داده_ها RTL8139 수신 حلقه_مقدار 순환을 시험한다. */
public final class شبکه_حلقه {
    public static int اجرا_2() {
        if (کاربر.인수개수() != 1) { کاربر.نوشتن("Usage: run stress PORT\n"); return 2; }
        String متن = کاربر.نشانوندها(0);
        int تبدیل_مقدار = 0;
        for (int فهرست = 0; فهرست < متن.length(); فهرست++) {
            if (متن.charAt(فهرست) < '0' || متن.charAt(فهرست) > '9' || تبدیل_مقدار > 6553) return 2;
            تبدیل_مقدار = تبدیل_مقدار * 10 + متن.charAt(فهرست) - '0';
        }
        if (تبدیل_مقدار < 1 || تبدیل_مقدار > 65535) return 2;
        int دستگیره_مقدار = کاربر.ایجاد_شبکه(0);
        if (دستگیره_مقدار < 0) return 3;
        int[] داده_ها = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int طول_مقدار = 1024 - (회차 & 1);
            for (int فهرست = 0; فهرست < طول_مقدار; فهرست++) داده_ها[فهرست] = (فهرست + 회차) & 255;
            if (کاربر.ارسال_داده_ها(دستگیره_مقدار, 0x0a000202, تبدیل_مقدار, داده_ها, طول_مقدار) != طول_مقدار) return 4;
            if (کاربر.자료받기(دستگیره_مقدار, داده_ها, 300) != طول_مقدار) return 5;
            for (int فهرست = 0; فهرست < طول_مقدار; فهرست++) if (داده_ها[فهرست] != ((فهرست + 회차) & 255)) return 6;
        }
        کاربر.بستن_شبکه(دستگیره_مقدار);
        کاربر.نوشتن("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
