package قطر.JQatOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import قطر.JQatOS.기억공간.صفحه_مدیر;
import قطر.JQatOS.سیستم_پرونده.파일서술자표;

/** فرآیند_مقدار 식별자와 라운드로빈 آماده_کردن 대기열을 관리한다. */
public final class زمان_بند {
    private final صفحه_مدیر 쪽관리;
    private final Map<Integer, فرآیند_مقدار> لیست_پردازش = new HashMap<Integer, فرآیند_مقدار>();
    private final Queue<فرآیند_مقدار> 준비대기열 = new ArrayDeque<فرآیند_مقدار>();
    private int بعدی_شناسه = 1;

    public زمان_بند(صفحه_مدیر 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public فرآیند_مقدار 첫과정(파일서술자표 파일서술자) {
        فرآیند_مقدار 새과정 = new فرآیند_مقدار(اختصاص_دادن_شناسه(), 0, 쪽관리.새주소공간(), 파일서술자);
        لیست_پردازش.put(Integer.valueOf(새과정.شناسه_مقدار()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public فرآیند_مقدار 복제(فرآیند_مقدار 부모) {
        فرآیند_مقدار فرزند_مقدار = new فرآیند_مقدار(
                اختصاص_دادن_شناسه(),
                부모.شناسه_مقدار(),
                쪽관리.쓰기시복사복제(부모.آدرس_فضا()),
                부모.파일서술자().복제());
        فرزند_مقدار.프로그램끝설정(부모.프로그램끝());
        لیست_پردازش.put(Integer.valueOf(فرزند_مقدار.شناسه_مقدار()), فرزند_مقدار);
        준비대기열.offer(فرزند_مقدار);
        return فرزند_مقدار;
    }

    public فرآیند_مقدار بعدی_فرآیند() {
        int 검사수 = 준비대기열.size();
        for (int فهرست = 0; فهرست < 검사수; فهرست++) {
            فرآیند_مقدار بعدی_مورد = 준비대기열.poll();
            if (بعدی_مورد != null && (بعدی_مورد.وضعیت_مقدار() == فرآیند_وضعیت.آماده_کردن || بعدی_مورد.وضعیت_مقدار() == فرآیند_وضعیت.اجرا_فرمان)) {
                بعدی_مورد.مجموعه_وضعیت(فرآیند_وضعیت.اجرا_فرمان);
                준비대기열.offer(بعدی_مورد);
                return بعدی_مورد;
            }
        }
        return null;
    }

    public int 자식기다리기(فرآیند_مقدار 부모, int فرزند_شناسه, boolean 기다리지않음) {
        for (فرآیند_مقدار 후보 : لیست_پردازش.values()) {
            if (후보.부모식별자() != 부모.شناسه_مقدار()) {
                continue;
            }
            if (فرزند_شناسه > 0 && 후보.شناسه_مقدار() != فرزند_شناسه) {
                continue;
            }
            if (후보.وضعیت_مقدار() == فرآیند_وضعیت.خروج_برنامه) {
                int سنجش = (후보.خروج_کد() & 0xff) << 8;
                لیست_پردازش.remove(Integer.valueOf(후보.شناسه_مقدار()));
                return سنجش;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public فرآیند_مقدار کشف_فرآیند(int شناسه_مقدار) {
        return لیست_پردازش.get(Integer.valueOf(شناسه_مقدار));
    }

    private int اختصاص_دادن_شناسه() {
        return بعدی_شناسه++;
    }
}
