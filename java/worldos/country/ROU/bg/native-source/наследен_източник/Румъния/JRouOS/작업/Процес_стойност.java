package Румъния.JRouOS.작업;

import Румъния.JRouOS.Памет_област.쪽관리자;
import Румъния.JRouOS.файлова_система.파일서술자표;

public final class Процес_стойност {
    private final int Идентификатор_стойност;
    private final int родител_Идентификатор;
    private final 쪽관리자.адрес_ИНТЕРВАЛ адрес_ИНТЕРВАЛ;
    private final 파일서술자표 파일서술자;
    private Процес_Състояние Състояние_стойност = Процес_Състояние.Подготвяне;
    private int Изход_код;
    private int програма_почивка = 0x06000000;
    private int 실행시작주소;
    private String[] 실행인자 = new String[0];
    private String[] 환경값 = new String[0];

    Процес_стойност(int Идентификатор_стойност, int родител_Идентификатор, 쪽관리자.адрес_ИНТЕРВАЛ адрес_ИНТЕРВАЛ, 파일서술자표 파일서술자) {
        this.Идентификатор_стойност = Идентификатор_стойност;
        this.родител_Идентификатор = родител_Идентификатор;
        this.адрес_ИНТЕРВАЛ = адрес_ИНТЕРВАЛ;
        this.파일서술자 = 파일서술자;
    }

    public int Идентификатор_стойност() {
        return Идентификатор_стойност;
    }

    public int родител_Идентификатор() {
        return родител_Идентификатор;
    }

    public 쪽관리자.адрес_ИНТЕРВАЛ адрес_ИНТЕРВАЛ() {
        return адрес_ИНТЕРВАЛ;
    }

    public 파일서술자표 파일서술자() {
        return 파일서술자;
    }

    public Процес_Състояние Състояние_стойност() {
        return Състояние_стойност;
    }

    public void набор_Състояние(Процес_Състояние 새상태) {
        Състояние_стойност = 새상태;
    }

    public int Изход_код() {
        return Изход_код;
    }

    public void Изход_програма(int стойност) {
        Изход_код = стойност & 0xff;
        Състояние_стойност = Процес_Състояние.Изход_програма;
    }

    public int програма_почивка() {
        return програма_почивка;
    }

    public void набор_програма_почивка(int 새끝) {
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            throw new IllegalArgumentException("програма_f5044b9b 끝 범위를 벗어났습니다.");
        }
        програма_почивка = 새끝;
    }

    public void 실행문맥설정(int Старт_адрес, String[] параметър_аргумент, String[] 환경) {
        실행시작주소 = Старт_адрес;
        실행인자 = параметър_аргумент.clone();
        환경값 = 환경.clone();
    }

    public int 실행시작주소() { return 실행시작주소; }
    public String[] 실행인자() { return 실행인자.clone(); }
    public String[] 환경값() { return 환경값.clone(); }
}
