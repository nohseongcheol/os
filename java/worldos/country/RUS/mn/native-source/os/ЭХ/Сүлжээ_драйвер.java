/** PCI RTL8139 (10ec:8139), 단일 илгээх_утга 버퍼와 8KiB 수신 давтах_утга. 인터럽트 대신 폴링한다. */
public final class Сүлжээ_драйвер {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] гар_утас_хаяг = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int 위치) {
        гар_утас_утга.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | 위치);
        return гар_утас_утга.입출력정수읽기(0xcfc);
    }

    static boolean Бэлтгэх() {
        int 장치번호 = -1;
        for (int индекс = 0; индекс < 32; индекс++) {
            if (설정읽기(индекс, 0) == 0x813910ec) { 장치번호 = индекс; break; }
        }
        if (장치번호 < 0) return false;
        int өгөгдмөл_утга = 설정읽기(장치번호, 0x10);
        if ((өгөгдмөл_утга & 1) == 0 || (өгөгдмөл_утга & 0xfffffffc) < 0x100 || (өгөгдмөл_утга & 0xfffffffc) > 65535) return false;
        입출력기준주소 = өгөгдмөл_утга & 0xfffc;
        int Тушаал = 설정읽기(장치번호, 4);
        гар_утас_утга.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        гар_утас_утга.입출력짧은수쓰기(0xcfc, Тушаал | 5); // I/O 및 bus master Зөвшөөрөх_утга, PCI төлөв_утга 비트는 건드리지 않음
        гар_утас_утга.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!Тэглэх_утга()) { 입출력기준주소 = 0; return false; }
        for (int индекс = 0; индекс < 6; индекс++) гар_утас_хаяг[индекс] = гар_утас_утга.입출력바이트읽기(입출력기준주소 + индекс);
        return true;
    }

    static boolean Тэглэх_утга() {
        гар_утас_утга.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int Ажиллуулах = гар_утас_утга.밀리초();
        while ((гар_утас_утга.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (гар_утас_утга.밀리초() - Ажиллуулах > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        гар_утас_утга.입출력정수쓰기(입출력기준주소 + 0x30, гар_утас_утга.Сүлжээ_санах_ой());
        for (int индекс = 0; индекс < 4; индекс++) гар_утас_утга.입출력정수쓰기(입출력기준주소 + 0x20 + индекс * 4, гар_утас_утга.Сүлжээ_санах_ой() + 12288);
        гар_утас_утга.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        гар_утас_утга.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        гар_утас_утга.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        гар_утас_утга.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/방송, wrap 연속 хадгалах_утга, 8KiB
        гар_утас_утга.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int илгээх(int[] өгөгдөл, int урт_утга) {
        if (입출력기준주소 == 0) return -19;
        if (урт_утга < 14 || урт_утга > 1514) return -90;
        int төлөв_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int Ажиллуулах = гар_утас_утга.밀리초();
        while ((гар_утас_утга.입출력정수읽기(төлөв_порт) & 0x2000) == 0)
            if (гар_утас_утга.밀리초() - Ажиллуулах > 100) return -110;
        int Хэмжээ = урт_утга < 60 ? 60 : урт_утга;
        for (int индекс = 0; индекс < Хэмжээ; индекс++)
            гар_утас_утга.бичих_санах_ой(гар_утас_утга.Сүлжээ_санах_ой() + 12288 + индекс, индекс < урт_утга ? өгөгдөл[индекс] : 0);
        гар_утас_утга.입출력정수쓰기(төлөв_порт, Хэмжээ | 0x00080000);
        Ажиллуулах = гар_утас_утга.밀리초();
        while ((гар_утас_утга.입출력정수읽기(төлөв_порт) & 0xe0008000) == 0)
            if (гар_утас_утга.밀리초() - Ажиллуулах > 100) return -110;
        if ((гар_утас_утга.입출력정수읽기(төлөв_порт) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return урт_утга;
    }

    static int 받기(int[] өгөгдөл) {
        if (입출력기준주소 == 0) return 0;
        if ((гар_утас_утга.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!Тэглэх_утга()) 입출력기준주소 = 0;
            return 0;
        }
        if ((гар_утас_утга.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = гар_утас_утга.Сүлжээ_санах_ой() + 수신위치;
        int төлөв_утга = 실행관리.짧은수(머리), Хэмжээ = 실행관리.짧은수(머리 + 2);
        if (Хэмжээ == 0xfff0) return 0; // DMA 진행 중
        if (Хэмжээ < 4 || Хэмжээ > 1518) {
            오류수++;
            if (!Тэглэх_утга()) 입출력기준주소 = 0;
            return 0;
        }
        int урт_утга = Хэмжээ - 4;
        if ((төлөв_утга & 1) != 0) {
            for (int индекс = 0; индекс < урт_утга; индекс++) өгөгдөл[индекс] = гар_утас_утга.기억읽기(머리 + 4 + индекс);
            수신수++;
        } else { урт_утга = 0; 오류수++; }
        수신위치 = (수신위치 + Хэмжээ + 4 + 3) & ~3;
        수신위치 &= 8191;
        гар_утас_утга.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        гар_утас_утга.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return урт_утга;
    }
}
