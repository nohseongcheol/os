/** 부팅 системийн_мэдээлэл 조회와 4KiB 고정 Хэмжээ 작업 хэсэг_утга хуваарилах_Санах_ой/반환. 일반 물리 хуудас_утга 관리자는 아니다. */
public final class 기억공간 {
    static int[] хэсэг_утга = new int[8192];
    static int[] 사용 = new int[8];

    static int задлан_ялгал_хийх_бүхэл_тоо(int хаяг) {
        return гар_утас_утга.기억읽기(хаяг) | (гар_утас_утга.기억읽기(хаяг + 1) << 8)
            | (гар_утас_утга.기억읽기(хаяг + 2) << 16) | (гар_утас_утга.기억읽기(хаяг + 3) << 24);
    }

    static int 위쪽기억크기() {
        int системийн_мэдээлэл = гар_утас_утга.부팅정보();
        if (гар_утас_утга.부팅표식() != 0x2badb002 || системийн_мэдээлэл == 0 || (задлан_ялгал_хийх_бүхэл_тоо(системийн_мэдээлэл) & 1) == 0) return -1;
        return задлан_ялгал_хийх_бүхэл_тоо(системийн_мэдээлэл + 8);
    }

    static int хуваарилах_Санах_ой() {
        for (int индекс = 0; индекс < 사용.length; индекс++) {
            if (사용[индекс] == 0) {
                사용[индекс] = 1;
                for (int зай_оролт = 0; зай_оролт < 1024; зай_оролт++) хэсэг_утга[индекс * 1024 + зай_оролт] = 0;
                return индекс;
            }
        }
        return -1;
    }

    static boolean 반환(int индекс) {
        if (индекс < 0 || индекс >= 사용.length || 사용[индекс] == 0) return false;
        사용[индекс] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int индекс = 0; индекс < 사용.length; индекс++) 개수 += 사용[индекс];
        return 개수;
    }
}
