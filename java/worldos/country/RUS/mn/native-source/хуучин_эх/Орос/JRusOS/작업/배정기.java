package Орос.JRusOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Орос.JRusOS.기억공간.хуудас_менежер;
import Орос.JRusOS.файлын_систем.파일서술자표;

/** үйл_явц_утга 식별자와 라운드로빈 Бэлтгэх 대기열을 관리한다. */
public final class 배정기 {
    private final хуудас_менежер 쪽관리;
    private final Map<Integer, үйл_явц_утга> Үйл_явцын_жагсаалт = new HashMap<Integer, үйл_явц_утга>();
    private final Queue<үйл_явц_утга> 준비대기열 = new ArrayDeque<үйл_явц_утга>();
    private int 다음식별자 = 1;

    public 배정기(хуудас_менежер 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public үйл_явц_утга 첫과정(파일서술자표 파일서술자) {
        үйл_явц_утга 새과정 = new үйл_явц_утга(хуваарилах_танигч(), 0, 쪽관리.새주소공간(), 파일서술자);
        Үйл_явцын_жагсаалт.put(Integer.valueOf(새과정.танигч_утга()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public үйл_явц_утга 복제(үйл_явц_утга 부모) {
        үйл_явц_утга хүүхэд_утга = new үйл_явц_утга(
                хуваарилах_танигч(),
                부모.танигч_утга(),
                쪽관리.쓰기시복사복제(부모.хаяг_орон_зай()),
                부모.파일서술자().복제());
        хүүхэд_утга.프로그램끝설정(부모.프로그램끝());
        Үйл_явцын_жагсаалт.put(Integer.valueOf(хүүхэд_утга.танигч_утга()), хүүхэд_утга);
        준비대기열.offer(хүүхэд_утга);
        return хүүхэд_утга;
    }

    public үйл_явц_утга 다음과정() {
        int 검사수 = 준비대기열.size();
        for (int индекс = 0; индекс < 검사수; индекс++) {
            үйл_явц_утга 다음 = 준비대기열.poll();
            if (다음 != null && (다음.төлөв_утга() == үйл_явц_төлөв.Бэлтгэх || 다음.төлөв_утга() == үйл_явц_төлөв.Гүйцэтгэх_команд)) {
                다음.багц_төлөв(үйл_явц_төлөв.Гүйцэтгэх_команд);
                준비대기열.offer(다음);
                return 다음;
            }
        }
        return null;
    }

    public int 자식기다리기(үйл_явц_утга 부모, int хүүхэд_танигч, boolean 기다리지않음) {
        for (үйл_явц_утга 후보 : Үйл_явцын_жагсаалт.values()) {
            if (후보.부모식별자() != 부모.танигч_утга()) {
                continue;
            }
            if (хүүхэд_танигч > 0 && 후보.танигч_утга() != хүүхэд_танигч) {
                continue;
            }
            if (후보.төлөв_утга() == үйл_явц_төлөв.Гарах_програм) {
                int 결과 = (후보.종료값() & 0xff) << 8;
                Үйл_явцын_жагсаалт.remove(Integer.valueOf(후보.танигч_утга()));
                return 결과;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public үйл_явц_утга хайх_үйл_явц(int танигч_утга) {
        return Үйл_явцын_жагсаалт.get(Integer.valueOf(танигч_утга));
    }

    private int хуваарилах_танигч() {
        return 다음식별자++;
    }
}
