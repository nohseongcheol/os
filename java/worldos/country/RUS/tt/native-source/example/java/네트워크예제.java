import Татарча.자체.тоташу;
import Татарча.자체.실행인수;
import Татарча.자체.전문통로;
import Татарча.자체.문자;
import Татарча.자체.출력;
import Татарча.자체.검사;
import Татарча.자체.입력흐름;
import Татарча.자체.입출력예외;

public class 네트워크예제 {
    public static void эшләтү() throws 입출력예외 {
        // хост: python3 Кораллар/예제되돌림.py --tcp-port 9000 --udp-port 9001
        тоташу ялгау = тоташу.ачу("10.0.2.2", 문자.бүлү_бөтен_сан(실행인수.Mäten(0)));
        try {
            ялгау.КӨТҮВАКЫТЫЧЫГУ(700);
            byte[] хәбәр = 문자.부호화("JAVA TCP tt\n");
            ялгау.출력().язу(хәбәр);
            입력흐름 입력 = ялгау.입력();
            for (int 수 = 0; 수 < 문자.байт_COUNT(хәбәр); 수++) {
                검사.참인지(입력.읽기() == (хәбәр[수] & 255), "TCP җавап_бирү 불일치");
            }
        } finally { ялгау.Yap(); }
        전문통로 종단 = 전문통로.ачу(0);
        try {
            종단.КӨТҮВАКЫТЫЧЫГУ(700);
            종단.җибәрү("10.0.2.2", 문자.бүлү_бөтен_сан(실행인수.Mäten(1)), "JAVA UDP tt");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP tt"), "UDP җавап_бирү 불일치");
        } finally { 종단.Yap(); }
        출력.язу_юл("JAVA 네트워크 раслау: TCP UDP tt");
    }
}
