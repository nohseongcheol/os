import Татарча.자체.тәрәз;
import Татарча.자체.тамга;
import Татарча.자체.текст_кыры;
import Татарча.자체.төймә;
import Татарча.자체.вакыйга_чират;
import Татарча.자체.출력;
import Татарча.자체.실행할일;
import Татарча.자체.동작받이;
import Татарча.자체.동작알림;

/** 자체 커널의 Swing тәрәз: tt 입력 → төймә → Белешмә_файлы_eb81d7d9 Mäten яңарту. */
public class 창예제 implements 실행할일, 동작받이 {
    private тәрәз 인사창;
    private текст_кыры исем_кыр;
    private тамга 인사말;
    private int 인사횟수;

    public void ачу_тәрәз() {
        인사창 = new тәрәз("tt Swing", 460, 300);
        인사창.өстәү_элемент(new тамга("tt", 20, 20, 420, 28));
        исем_кыр = new текст_кыры("tt", 20, 64, 420, 30);
        인사말 = new тамга("tt", 20, 152, 420, 28);
        인사창.өстәү_элемент(исем_кыр);
        인사창.өстәү_элемент(new төймә("인사하기", 20, 108, 180, 32, this));
        인사창.өстәү_элемент(인사말);
        인사창.өстәү_элемент(new тамга("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.күрсәтү_тәрәз();
        출력.язу_юл("GUI 예제 Әзерләү: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.язу_СМС("tt, " + исем_кыр.글읽기() + "님! (" + 인사횟수 + ")");
        출력.язу_юл("GUI 인사: " + 인사말.글읽기());
    }

    public void Башкару() { ачу_тәрәз(); }
    public void 동작받기(동작알림 알림) {
        출력.язу_юл("Гамәл 알림: " + 알림.команда_СМС());
        인사하기();
    }
    public static void эшләтү() {
        вакыйга_чират.나중에실행(new 창예제());
    }
}
