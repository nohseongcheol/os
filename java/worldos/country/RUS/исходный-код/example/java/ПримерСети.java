import русский.свой.контакт;
import русский.свой.실행인수;
import русский.свой.датаграмма_канал;
import русский.свой.문자;
import русский.свой.текстовыйВывод;
import русский.свой.검사;
import русский.свой.входной_поток;
import русский.свой.входные_данные_выход_исключение;

public class ПримерСети {
    public static void запустить() throws входные_данные_выход_исключение {
        // узел: python3 инструменты/예제되돌림.py --tcp-port 9000 --udp-port 9001
        контакт Подключить = контакт.Открыть("10.0.2.2", 문자.анализировать_целое_число(실행인수.текст(0)));
        try {
            Подключить.ТАЙМАУТ(700);
            byte[] письмо = 문자.кодировать("JAVA TCP русский\n");
            Подключить.текстовыйВывод().Запись(письмо);
            входной_поток входные_данные_ЗНАЧЕН = Подключить.входные_данные_ЗНАЧЕН();
            for (int 수 = 0; 수 < 문자.байт_СЧЁТ(письмо); 수++) {
                검사.참인지(входные_данные_ЗНАЧЕН.Чтение() == (письмо[수] & 255), "TCP ответ 불일치");
            }
        } finally { Подключить.Закрыть(); }
        датаграмма_канал участник = датаграмма_канал.Открыть(0);
        try {
            участник.ТАЙМАУТ(700);
            участник.написать("10.0.2.2", 문자.анализировать_целое_число(실행인수.текст(1)), "JAVA UDP русский");
            검사.참인지(문자.같음(участник.получить(), "JAVA UDP русский"), "UDP ответ 불일치");
        } finally { участник.Закрыть(); }
        текстовыйВывод.запись_линия("JAVA 네트워크 проверять: TCP UDP русский");
    }
}
