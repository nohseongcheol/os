package العربية.ذاتي;
/** 화면(畫面): إقلاع_الآلة 때 선택한 크기의 ذاتي نواة_قيمة RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int قيمة = نواة_قيمة.화면너비(); if (قيمة < 0) throw new حالة_استثناء("프레임버퍼 없음"); return قيمة; }
    public static int ارتفاع_قيمة() { int قيمة = نواة_قيمة.화면높이(); if (قيمة < 0) throw new حالة_استثناء("프레임버퍼 없음"); return قيمة; }
    public static void مستطيل(int 가로, int عمودي_منصب, int 폭, int ارتفاع_قيمة, int 색) {
        if (가로 < 0 || عمودي_منصب < 0 || 폭 < 0 || ارتفاع_قيمة < 0 || 가로 > 너비() || عمودي_منصب > ارتفاع_قيمة() || 폭 > 너비() - 가로 || ارتفاع_قيمة > ارتفاع_قيمة() - عمودي_منصب) throw new غير_صالح_وسيطة_استثناء("화면 يقص");
        if (نواة_قيمة.مستطيل(가로, عمودي_منصب, 폭, ارتفاع_قيمة, 색) < 0) throw new حالة_استثناء("프레임버퍼 없음");
    }
    public static void مسح_إدخال(int 색) { مستطيل(0, 0, 너비(), ارتفاع_قيمة(), 색); }
    public static void 기다리기() { if (نواة_قيمة.그림대기() < 0) throw new حالة_استثناء("تفاعلي إدخال_قيمة 필요"); }
}
