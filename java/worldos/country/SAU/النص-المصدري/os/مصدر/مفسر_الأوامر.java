/** 디스크 كتابة 없이 동작하는 작은 직렬/PS2 مفسر_الأوامر. */
public final class مفسر_الأوامر {
    static int[] إدخال_قيمة = new int[128];
    static int 길이 = 0;
    static boolean 앞줄복귀 = false;
    static boolean خط_تجاوز = false;

    static boolean أمر(String اسم) {
        if (길이 < اسم.length()) return false;
        for (int فهرس = 0; فهرس < اسم.length(); فهرس++)
            if (إدخال_قيمة[فهرس] != اسم.charAt(فهرس)) return false;
        return 길이 == اسم.length() || إدخال_قيمة[اسم.length()] == ' ';
    }

    static void عرض_المساعدة() {
        نص_الوحدة_الطرفية.كتابة("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        نص_الوحدة_الطرفية.كتابة("apps | run NAME [ARGS] | net\n");
        نص_الوحدة_الطرفية.كتابة("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        نص_الوحدة_الطرفية.كتابة("sync (연결된 JKSTORE1 مخزن_قيمة 장치에 ملف 보존)\n");
    }

    static void عملية_قيمة_إدخال() {
        if (길이 == 0) return;
        if (أمر("help")) عرض_المساعدة();
        else if (أمر("sync")) {
            int نتيجة = 파일보존.تزامن();
            نص_الوحدة_الطرفية.كتابة("Sync: "); نص_الوحدة_الطرفية.كتابة_رقم(نتيجة); نص_الوحدة_الطرفية.문자(10);
        }
        else if (أمر("ls")) ذاكرة_نظام_الملفات.إدخال_قائمة_f07b3200();
        else if (أمر("edit")) ذاكرة_نظام_الملفات.أمر(إدخال_قيمة, 4, 길이, 0);
        else if (أمر("cat")) ذاكرة_نظام_الملفات.أمر(إدخال_قيمة, 3, 길이, 1);
        else if (أمر("rm")) ذاكرة_نظام_الملفات.أمر(إدخال_قيمة, 2, 길이, 2);
        else if (أمر("java") || أمر("javac")) {
            int نتيجة = 실행관리.ينفذ_أمر(إدخال_قيمة, 0, 길이);
            نص_الوحدة_الطرفية.كتابة("Exit: "); نص_الوحدة_الطرفية.كتابة_رقم(نتيجة); نص_الوحدة_الطرفية.문자(10);
        }
        else if (أمر("apps")) 실행관리.إدخال_قائمة_f07b3200();
        else if (أمر("net")) شبكة_رمز.حالة_قيمة();
        else if (أمر("run")) {
            int نتيجة = 실행관리.ينفذ_أمر(إدخال_قيمة, 3, 길이);
            نص_الوحدة_الطرفية.كتابة("Exit: "); نص_الوحدة_الطرفية.كتابة_رقم(نتيجة); نص_الوحدة_الطرفية.كتابة("\n");
        } else if (أمر("info")) {
            نص_الوحدة_الطرفية.كتابة("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (أمر("mem")) {
            نص_الوحدة_الطرفية.كتابة("위쪽 ذاكرة_قيمة عنوان_منطقة(KiB): "); نص_الوحدة_الطرفية.كتابة_رقم(ذاكرة_منطقة.위쪽기억크기());
            نص_الوحدة_الطرفية.كتابة("\n배열 동적 ذاكرة_قيمة عنوان_منطقة(بايت_قيمة): "); نص_الوحدة_الطرفية.كتابة_رقم(جهاز_قيمة.배열사용량());
            نص_الوحدة_الطرفية.كتابة(" / 262144\n작업 عنوان_منطقة قسم_قيمة_366e0bfa: "); نص_الوحدة_الطرفية.كتابة_رقم(ذاكرة_منطقة.사용개수());
            نص_الوحدة_الطرفية.كتابة(" / 8 (각 4096바이트)\n");
        } else if (أمر("alloc")) {
            int فهرس = ذاكرة_منطقة.يخصص_تخزين();
            نص_الوحدة_الطرفية.كتابة("قسم_قيمة_366e0bfa فهرس: "); نص_الوحدة_الطرفية.كتابة_رقم(فهرس); نص_الوحدة_الطرفية.كتابة("\n");
        } else if (أمر("free")) {
            if (길이 == 6 && إدخال_قيمة[4] == ' ' && إدخال_قيمة[5] >= '0' && إدخال_قيمة[5] <= '7') {
                نص_الوحدة_الطرفية.كتابة(ذاكرة_منطقة.إرجاع_مقياس(إدخال_قيمة[5] - '0') ? "반환됨\n" : "할당되지 않은 قسم_قيمة_366e0bfa\n");
            } else نص_الوحدة_الطرفية.كتابة("사용법: free 0..7\n");
        } else if (أمر("echo")) {
            for (int فهرس = 5; فهرس < 길이; فهرس++) نص_الوحدة_الطرفية.문자(إدخال_قيمة[فهرس]);
            نص_الوحدة_الطرفية.문자(10);
        } else if (أمر("clear")) نص_الوحدة_الطرفية.مسح_إدخال();
        else if (أمر("test")) نواة.اختبارات();
        else if (أمر("halt")) {
            نص_الوحدة_الطرفية.كتابة("HALTED\n");
            جهاز_قيمة.정지();
        } else نص_الوحدة_الطرفية.كتابة("알 رقم 없는 명령입니다. help를 입력하세요.\n");
    }

    static void قبول_و_كتابة(int قيمة) {
        if (قيمة == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = قيمة == 13;
        if (قيمة == 10 || قيمة == 13) {
            نص_الوحدة_الطرفية.문자(10);
            if (ذاكرة_نظام_الملفات.편집중) ذاكرة_نظام_الملفات.الملفات_المحررة_خط(إدخال_قيمة, 길이, خط_تجاوز);
            else عملية_قيمة_إدخال();
            길이 = 0;
            خط_تجاوز = false;
            نص_الوحدة_الطرفية.كتابة(ذاكرة_نظام_الملفات.편집중 ? "...> " : "jkoros> ");
        } else if (قيمة == 8 || قيمة == 127) {
            if (길이 > 0) {
                길이--;
                نص_الوحدة_الطرفية.직렬바이트(8); نص_الوحدة_الطرفية.직렬바이트(32); نص_الوحدة_الطرفية.직렬바이트(8);
                نص_الوحدة_الطرفية.화면문자(8);
            }
        } else if (قيمة >= 32 && قيمة < 127 && 길이 < إدخال_قيمة.length) {
            إدخال_قيمة[길이++] = قيمة;
            نص_الوحدة_الطرفية.문자(قيمة);
        } else if (قيمة >= 32 && قيمة < 127) خط_تجاوز = true;
    }

    static void تشغيل() {
        عرض_المساعدة();
        نص_الوحدة_الطرفية.كتابة("READY\njkoros> ");
        while (true) {
            int قيمة = نص_الوحدة_الطرفية.직렬읽기();
            if (قيمة < 0) قيمة = لوحة_المفاتيح.قراءة();
            if (قيمة >= 0) قبول_و_كتابة(قيمة);
            else { شبكة_رمز.يتحقق(); جهاز_قيمة.잠시양보(); }
        }
    }
}
