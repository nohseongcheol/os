#!/usr/bin/env python3
"""പ്രസ്താവം 고유번호와 UTF-8 బైట్_മൂല്യം 위치로 자체 C 이름을 옮기는 일회성 이행 ഉപകരണങ്ങൾ.

외부 구조체의 멤버, സ്ട്രിംഗ്_മൂല്യം, C 표준 കാര്യപ്രവര്_ത്തനം_മൂല്യം, 이식 규약은 보존한다.
입력은 മാറ്റികൊടുക്കുക_മൂല്യം 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം = Path(__file__).resolve().parents[1]

def നടപ്പാക്കുക_കമാന്_ഡ്():
    분석 = json.loads((പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം/'build/한국어화/시언어분석.json').read_text())
    if 분석['പിശക്']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    നാ_മം_పట్టిక = json.loads((പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം/'명명/규격이름.json').read_text()))
    പ്രസ്താവം_పట్టిక = 분석['പ്രസ്താവം']
    바꿀선언 = {고유:നാ_മം_పట్టిక[എന്_ട്രി_മൂല്യം['പേരു്']] for 고유,എന്_ട്രി_മൂല്യം in പ്രസ്താവം_పట్టిక.items()
                if എന്_ട്രി_മൂല്യം['പേരു്'] in നാ_മം_పట్టిక and എന്_ട്രി_മൂല്യം['പേരു്'] not in 규격}
    കണക്ഷൻ_పట్టిక = {എന്_ട്രി_മൂല്യം['പേരു്']:നാ_മം_పట్టిక[എന്_ട്രി_മൂല്യം['പേരു്']] for എന്_ട്രി_മൂല്യം in പ്രസ്താവം_పట్టిక.values()
              if എന്_ട്രി_മൂല്യം.get('കണക്ടു്_ചെയ്യുക')==4 and എന്_ട്രി_മൂല്യം['종류'] in (8,9)
              and എന്_ട്രി_മൂല്യം['പേരു്'] in നാ_മം_పట్టిక and എന്_ട്രി_മൂല്യം['പേരു്'] not in 규격}
    # സൃഷ്_ടിക്കുക AOT C·어셈블리·공개 SDK가 공유하는 바이너리 കണക്ടു്_ചെയ്യുക 이름만 유지한다.
    머리 = ['/* 한국어 ഉറവിടം_ശാഖി 이름과 기존 മെഷീൻ കണക്ടു്_ചെയ്യുക കേസ്_മൂല്യം. 자동 സൃഷ്_ടിക്കുക: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(കണക്ഷൻ_పట్టిక.items())]
    머리 += ['#endif','']
    (പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം/'명명/기계연결이름.h').write_text('\n'.join(머리))
    മാറ്റങ്ങൾ_ലിസ്റ്റ് = defaultdict(dict)
    for ഫയല്,ഓഫ്_സെറ്റ്_മൂല്യം,പേരു്,고유 in 분석['റഫറൻസ്']:
        if 고유 in 바꿀선언:
            മാറ്റങ്ങൾ_ലിസ്റ്റ്[ഫയല്][ഓഫ്_സെറ്റ്_മൂല്യം] = (പേരു്,바꿀선언[고유])
    ലോഗ്_രേഖ = ['ഫയല്\t원래바이트위치\t이전이름\t한국어이름']
    അവഗണിക്കുക_മൂല്യം = []
    for ഫയല്,മാറ്റികൊടുക്കുക_മൂല്യം in മാറ്റങ്ങൾ_ലിസ്റ്റ്.items():
        വഴി = Path(ഫയല്); 원본 = വഴി.read_bytes(); ഡാറ്റാ = 원본
        for ഓഫ്_സെറ്റ്_മൂല്യം,(옛이름,새이름) in sorted(മാറ്റികൊടുക്കുക_മൂല്യം.items(),reverse=True):
            끝 = ഓഫ്_സെറ്റ്_മൂല്യം+len(옛이름.encode())
            if 원본[ഓഫ്_സെറ്റ്_മൂല്യം:끝] != 옛이름.encode():
                അവഗണിക്കുക_മൂല്യം.append((str(വഴി.relative_to(പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം)),ഓഫ്_സെറ്റ്_മൂല്യം,옛이름));continue
            ഡാറ്റാ = ഡാറ്റാ[:ഓഫ്_സെറ്റ്_മൂല്യം]+새이름.encode()+ഡാറ്റാ[끝:]
            ലോഗ്_രേഖ.append('{}\t{}\t{}\t{}'.format(വഴി.relative_to(പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം),ഓഫ്_സെറ്റ്_മൂല്യം,옛이름,새이름))
        വഴി.write_bytes(ഡാറ്റാ)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    മാക്രോ_മൂല്യം = {എന്_ട്രി_മൂല്യം['പേരു്']:നാ_മം_పట్టిక[എന്_ട്രി_മൂല്യം['പേരു്']] for എന്_ട്രി_മൂല്യം in പ്രസ്താവം_పట్టిక.values()
              if എന്_ട്രി_മൂല്യം['종류']==501 and എന്_ട്രി_മൂല്യം['പേരു്'] in നാ_മം_పట్టిక and എന്_ട്രി_മൂല്യം['പേരു്'] not in 규격}
    for വഴി in sorted({Path(എന്_ട്രി_മൂല്യം['ഫയല്']) for എന്_ട്രി_മൂല്യം in പ്രസ്താവം_పట్టిక.values()}):
        ലൈൻ_ലിസ്റ്റ് = വഴി.read_text().splitlines(True); 이어짐 = False
        for സൂചിക,ലൈൻ in enumerate(ലൈൻ_ലിസ്റ്റ്):
            전처리 = 이어짐 or bool(re.match(r'\s*#',ലൈൻ))
            이어짐 = 전처리 and ലൈൻ.rstrip().endswith('\\')
            if 전처리:
                തിരഞ്ഞു_നോക്കൽ_పట్టిక = നാ_മം_పట్టిక if re.match(r'\s*#\s*define\b',ലൈൻ) or 이어짐 else മാക്രോ_മൂല്യം
                ലൈൻ_ലിസ്റ്റ്[സൂചിക] = 낱말.sub(lambda 맞음: തിരഞ്ഞു_നോക്കൽ_పట్టిక.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],ലൈൻ)
        വഴി.write_text(''.join(ലൈൻ_ലിസ്റ്റ്))
    # 각 자체 വിവർത്തനം_ചെയ്യുക_ഉറവിടം 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for വഴി in sorted({Path(എന്_ട്രി_മൂല്യം['ഫയല്']) for എന്_ട്രി_മൂല്യം in പ്രസ്താവം_పట్టిక.values()}):
        if വഴി.suffix not in ('.c','.cpp'):continue
        പീര്_മൂല്യം = '../' * len(വഴി.relative_to(പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം).parts[:-1]) + '명명/기계연결이름.h'
        വഴി.write_text('#include "'+പീര്_മൂല്യം+'"\n'+വഴി.read_text())
    (പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം/'명명/시언어이름대응.tsv').write_text('\n'.join(ലോഗ്_രേഖ)+'\n')
    (പ്രൊജക്റ്റ്_ചെയ്യുക_വർഗ്ഗമൂലം/'build/한국어화/전처리참조.json').write_text(json.dumps(അവഗണിക്കുക_മൂല്യം,ensure_ascii=False,indent=2)+'\n')
    print('മാറ്റികൊടുക്കുക_മൂല്യം',len(ലോഗ്_രേഖ)-1,'전처리 재검토',len(അവഗണിക്കുക_മൂല്യം),'മെഷീൻ കണക്ടു്_ചെയ്യുക',len(കണക്ഷൻ_పట్టిక))

if __name__=='__main__': നടപ്പാക്കുക_കമാന്_ഡ്()
