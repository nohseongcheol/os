"""자체 커널의 ਫਾਇਲ·통신·화면 호출과 ਪੰਜਾਬੀ 예외. 표준 이름은 이 연결부에서만 쓴다."""
import jkoros as ਸਿਸਟਮ_ਚਲਾਉਣਾ
import sys as ਸਾਧਾਰਨ_ਭਾਸ਼ਾ_ਰਨਟਾਈਮ

def ਆਉਟਪੁੱਟ(*ਕੀਮਤ, ਵਿਭਾਜਕ=" ", 끝="\n", **기존인수):
    # 기존 print의 sep/end 인수도 연결부에서 호환한다.
    if "sep" not in 기존인수: 기존인수["sep"] = ਵਿਭਾਜਕ
    if "end" not in 기존인수: 기존인수["end"] = 끝
    print(*ਕੀਮਤ, **기존인수)

ਪੂਰਣ_ਅੰਕ = int
명령인수 = ਸਾਧਾਰਨ_ਭਾਸ਼ਾ_ਰਨਟਾਈਮ.argv
다시시도오류 = 11

class ਪਰਬੰਧ_ਗਲਤ(OSError):
    def __init__(자신, ਅਨੁਕ੍ਰਮਣਿਕਾ, 설명="ਸਿਸਟਮ_ਚਲਾਉਣਾ 작업에 실패했습니다."):
        super().__init__(ਅਨੁਕ੍ਰਮਣਿਕਾ, 설명)
        자신.ਅਨੁਕ੍ਰਮਣਿਕਾ = ਅਨੁਕ੍ਰਮਣਿਕਾ
        자신.설명 = 설명

def 운영호출(ਫੰਗਸ਼ਨ_ਕੀਮਤ, *ਆਰਗੂਮੈਂਟ):
    try:
        return ਫੰਗਸ਼ਨ_ਕੀਮਤ(*ਆਰਗੂਮੈਂਟ)
    except OSError as ਗਲਤੀ:
        ਅਨੁਕ੍ਰਮਣਿਕਾ = ਗਲਤੀ.args[0] if ਗਲਤੀ.args else 0
        raise ਪਰਬੰਧ_ਗਲਤ(ਅਨੁਕ੍ਰਮਣਿਕਾ)

def 글부호화(ਟੈਕਸਟ):
    return ਟੈਕਸਟ.encode("utf-8")

def 글해독(ਸਮੱਗਰੀ):
    return ਸਮੱਗਰੀ.decode("utf-8")

def 파일읽기(ਨਾਂ):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.read, ਨਾਂ)

def ਲਿੱਖੋ_ਲਿਖਤ_ਪੱਤਰ(ਨਾਂ, ਸਮੱਗਰੀ):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.write, ਨਾਂ, ਸਮੱਗਰੀ)

def ਹਟਾਉਣਾ_ਲਿਖਤ_ਪੱਤਰ(ਨਾਂ):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.remove, ਨਾਂ)

def 전문통신열기(접속번호):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.udp_open, 접속번호)

def 전문보내기(종단, 접속번호, ਸਮੱਗਰੀ):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.udp_send, 종단, 접속번호, ਸਮੱਗਰੀ)

def 바깥전문보내기(종단, ਪਤਾ, 접속번호, ਸਮੱਗਰੀ):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.udp_sendto, 종단, ਪਤਾ, 접속번호, ਸਮੱਗਰੀ)

def 전문받기(종단):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.udp_recv, 종단)

def ਬੰਦ_ਕਰੋ_ਨੈਟਵਰਕ(종단):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.udp_close, 종단)

def 네모그리기(*ਆਰਗੂਮੈਂਟ):
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.rect, *ਆਰਗੂਮੈਂਟ)

def 화면크기():
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.screen_size)

def 그림기다리기():
    return 운영호출(ਸਿਸਟਮ_ਚਲਾਉਣਾ.wait_key)

