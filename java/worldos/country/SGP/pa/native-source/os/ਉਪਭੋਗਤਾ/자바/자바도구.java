/** 게스트 ਸਾਧਨ 공통 ਆਉਟਪੁੱਟ 및 ASCII ਫਾਇਲ ਨਾਂ ਕਾਰਵਾਈ_ਕੀਮਤ_ਦਾਖਲਾ. */
public final class 자바도구 {
    /** UTF-8 ਬਾਈਟ_ਕੀਮਤ 배열을 같은 배열의 UTF-16 단위로 바꾼다. 잘못된 입력은 거부. */
    static int 원문해독(int[] ਸਮੱਗਰੀ, int ਲੰਬਾਈ_ਕੀਮਤ) {
        int ਪੜ੍ਹਨ = 0, ਲਿਖਣ = 0;
        if (ਲੰਬਾਈ_ਕੀਮਤ >= 3 && ਸਮੱਗਰੀ[0] == 239 && ਸਮੱਗਰੀ[1] == 187 && ਸਮੱਗਰੀ[2] == 191) ਪੜ੍ਹਨ = 3;
        while (ਪੜ੍ਹਨ < ਲੰਬਾਈ_ਕੀਮਤ) {
            int ਕੀਮਤ = ਸਮੱਗਰੀ[ਪੜ੍ਹਨ++], 수 = 0, 최소 = 0;
            if (ਕੀਮਤ >= 194 && ਕੀਮਤ <= 223) { 수 = 1; 최소 = 128; ਕੀਮਤ &= 31; }
            else if (ਕੀਮਤ >= 224 && ਕੀਮਤ <= 239) { 수 = 2; 최소 = 2048; ਕੀਮਤ &= 15; }
            else if (ਕੀਮਤ >= 240 && ਕੀਮਤ <= 244) { 수 = 3; 최소 = 65536; ਕੀਮਤ &= 7; }
            else if (ਕੀਮਤ >= 128 || ਕੀਮਤ < 0) return -1;
            if (수 > ਲੰਬਾਈ_ਕੀਮਤ - ਪੜ੍ਹਨ) return -1;
            for (int i = 0; i < 수; i++) {
                int ਅਗਲਾ_ਆਇਟਮ = ਸਮੱਗਰੀ[ਪੜ੍ਹਨ++]; if ((ਅਗਲਾ_ਆਇਟਮ & 192) != 128) return -1;
                ਕੀਮਤ = (ਕੀਮਤ << 6) | (ਅਗਲਾ_ਆਇਟਮ & 63);
            }
            if (ਕੀਮਤ < 최소 || ਕੀਮਤ > 0x10ffff || (ਕੀਮਤ >= 0xd800 && ਕੀਮਤ <= 0xdfff)) return -1;
            if (ਕੀਮਤ >= 65536) { ਕੀਮਤ -= 65536; ਸਮੱਗਰੀ[ਲਿਖਣ++] = 0xd800 | (ਕੀਮਤ >> 10); ਸਮੱਗਰੀ[ਲਿਖਣ++] = 0xdc00 | (ਕੀਮਤ & 1023); }
            else ਸਮੱਗਰੀ[ਲਿਖਣ++] = ਕੀਮਤ;
        }
        return ਲਿਖਣ;
    }
    static void 수쓰기(int ਕੀਮਤ) {
        if (ਕੀਮਤ < 0) ਉਪਭੋਗਤਾ.ਲਿੱਖੋ_ਵਰਣ_ਕੀਮਤ('-'); else ਕੀਮਤ = -ਕੀਮਤ;
        int ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ = 1000000000;
        boolean ਚਲਾਓ_2 = false;
        while (ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ != 0) {
            int 수 = -(ਕੀਮਤ / ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ);
            if (수 != 0 || ਚਲਾਓ_2 || ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ == 1) { ਉਪਭੋਗਤਾ.ਲਿੱਖੋ_ਵਰਣ_ਕੀਮਤ('0' + 수); ਚਲਾਓ_2 = true; }
            ਕੀਮਤ %= ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ; ਸਥਿਤੀ_ਬਦਲੋ_ਅਨੁਕ੍ਰਮਣਿਕਾ /= 10;
        }
    }
    static int ਨਾਂ(int[] ਮੰਜਿਲ_ਕੀਮਤ, String 원본) {
        if (원본.length() >= ਮੰਜਿਲ_ਕੀਮਤ.length) return -1;
        for (int 수 = 0; 수 < ਮੰਜਿਲ_ਕੀਮਤ.length; 수++) ਮੰਜਿਲ_ਕੀਮਤ[수] = 수 < 원본.length() ? 원본.charAt(수) : 0;
        return 원본.length();
    }
    static boolean 같음(String 가, String 나) {
        if (가.length() != 나.length()) return false;
        for (int 수 = 0; 수 < 가.length(); 수++) if (가.charAt(수) != 나.charAt(수)) return false;
        return true;
    }
}
