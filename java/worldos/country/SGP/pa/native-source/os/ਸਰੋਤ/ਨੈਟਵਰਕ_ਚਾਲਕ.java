/** PCI RTL8139 (10ec:8139), 단일 ਈਮੇਲ_ਕੀਮਤ 버퍼와 8KiB 수신 ਲੂਪ_ਕੀਮਤ. 인터럽트 대신 폴링한다. */
public final class ਨੈਟਵਰਕ_ਚਾਲਕ {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] ਤਜਵੀਜ_ਪਤਾ = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int ਸਥਿਤੀ) {
        ਤਜਵੀਜ_ਕੀਮਤ.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | ਸਥਿਤੀ);
        return ਤਜਵੀਜ_ਕੀਮਤ.입출력정수읽기(0xcfc);
    }

    static boolean ਤਿਆਰ_ਕਰੋ() {
        int 장치번호 = -1;
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 32; ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
            if (설정읽기(ਅਨੁਕ੍ਰਮਣਿਕਾ, 0) == 0x813910ec) { 장치번호 = ਅਨੁਕ੍ਰਮਣਿਕਾ; break; }
        }
        if (장치번호 < 0) return false;
        int ਡਿਫੌਲਟ_ਵੈਲਯੂ = 설정읽기(장치번호, 0x10);
        if ((ਡਿਫੌਲਟ_ਵੈਲਯੂ & 1) == 0 || (ਡਿਫੌਲਟ_ਵੈਲਯੂ & 0xfffffffc) < 0x100 || (ਡਿਫੌਲਟ_ਵੈਲਯੂ & 0xfffffffc) > 65535) return false;
        입출력기준주소 = ਡਿਫੌਲਟ_ਵੈਲਯੂ & 0xfffc;
        int ਕਮਾਂਡ = 설정읽기(장치번호, 4);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        ਤਜਵੀਜ_ਕੀਮਤ.입출력짧은수쓰기(0xcfc, ਕਮਾਂਡ | 5); // I/O 및 bus master ਇਜਾਜ਼ਤ_ਦਿਉ_ਕੀਮਤ, PCI ਸਥਿਤੀ_ਕੀਮਤ 비트는 건드리지 않음
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!ਰੀਸੈਟ_ਕੀਮਤ()) { 입출력기준주소 = 0; return false; }
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 6; ਅਨੁਕ੍ਰਮਣਿਕਾ++) ਤਜਵੀਜ_ਪਤਾ[ਅਨੁਕ੍ਰਮਣਿਕਾ] = ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트읽기(입출력기준주소 + ਅਨੁਕ੍ਰਮਣਿਕਾ);
        return true;
    }

    static boolean ਰੀਸੈਟ_ਕੀਮਤ() {
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int ਚਲਾਓ_2 = ਤਜਵੀਜ_ਕੀਮਤ.밀리초();
        while ((ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (ਤਜਵੀਜ_ਕੀਮਤ.밀리초() - ਚਲਾਓ_2 > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        ਤਜਵੀਜ_ਕੀਮਤ.입출력정수쓰기(입출력기준주소 + 0x30, ਤਜਵੀਜ_ਕੀਮਤ.ਨੈਟਵਰਕ_ਮੈਮਰੀ());
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < 4; ਅਨੁਕ੍ਰਮਣਿਕਾ++) ਤਜਵੀਜ_ਕੀਮਤ.입출력정수쓰기(입출력기준주소 + 0x20 + ਅਨੁਕ੍ਰਮਣਿਕਾ * 4, ਤਜਵੀਜ_ਕੀਮਤ.ਨੈਟਵਰਕ_ਮੈਮਰੀ() + 12288);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/ਬਰੌਡਕਾਸਟ_ਕੀਮਤ, wrap 연속 ਸੰਭਾਲੋ_ਕੀਮਤ, 8KiB
        ਤਜਵੀਜ_ਕੀਮਤ.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int ਈਮੇਲ(int[] ਸਮੱਗਰੀ, int ਲੰਬਾਈ_ਕੀਮਤ) {
        if (입출력기준주소 == 0) return -19;
        if (ਲੰਬਾਈ_ਕੀਮਤ < 14 || ਲੰਬਾਈ_ਕੀਮਤ > 1514) return -90;
        int ਸਥਿਤੀ_ਪੋਰਟ = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int ਚਲਾਓ_2 = ਤਜਵੀਜ_ਕੀਮਤ.밀리초();
        while ((ਤਜਵੀਜ_ਕੀਮਤ.입출력정수읽기(ਸਥਿਤੀ_ਪੋਰਟ) & 0x2000) == 0)
            if (ਤਜਵੀਜ_ਕੀਮਤ.밀리초() - ਚਲਾਓ_2 > 100) return -110;
        int ਆਕਾਰ = ਲੰਬਾਈ_ਕੀਮਤ < 60 ? 60 : ਲੰਬਾਈ_ਕੀਮਤ;
        for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < ਆਕਾਰ; ਅਨੁਕ੍ਰਮਣਿਕਾ++)
            ਤਜਵੀਜ_ਕੀਮਤ.ਲਿੱਖੋ_ਮੈਮਰੀ(ਤਜਵੀਜ_ਕੀਮਤ.ਨੈਟਵਰਕ_ਮੈਮਰੀ() + 12288 + ਅਨੁਕ੍ਰਮਣਿਕਾ, ਅਨੁਕ੍ਰਮਣਿਕਾ < ਲੰਬਾਈ_ਕੀਮਤ ? ਸਮੱਗਰੀ[ਅਨੁਕ੍ਰਮਣਿਕਾ] : 0);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력정수쓰기(ਸਥਿਤੀ_ਪੋਰਟ, ਆਕਾਰ | 0x00080000);
        ਚਲਾਓ_2 = ਤਜਵੀਜ_ਕੀਮਤ.밀리초();
        while ((ਤਜਵੀਜ_ਕੀਮਤ.입출력정수읽기(ਸਥਿਤੀ_ਪੋਰਟ) & 0xe0008000) == 0)
            if (ਤਜਵੀਜ_ਕੀਮਤ.밀리초() - ਚਲਾਓ_2 > 100) return -110;
        if ((ਤਜਵੀਜ_ਕੀਮਤ.입출력정수읽기(ਸਥਿਤੀ_ਪੋਰਟ) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return ਲੰਬਾਈ_ਕੀਮਤ;
    }

    static int 받기(int[] ਸਮੱਗਰੀ) {
        if (입출력기준주소 == 0) return 0;
        if ((ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!ਰੀਸੈਟ_ਕੀਮਤ()) 입출력기준주소 = 0;
            return 0;
        }
        if ((ਤਜਵੀਜ_ਕੀਮਤ.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = ਤਜਵੀਜ_ਕੀਮਤ.ਨੈਟਵਰਕ_ਮੈਮਰੀ() + 수신위치;
        int ਸਥਿਤੀ_ਕੀਮਤ = 실행관리.짧은수(머리), ਆਕਾਰ = 실행관리.짧은수(머리 + 2);
        if (ਆਕਾਰ == 0xfff0) return 0; // DMA 진행 중
        if (ਆਕਾਰ < 4 || ਆਕਾਰ > 1518) {
            오류수++;
            if (!ਰੀਸੈਟ_ਕੀਮਤ()) 입출력기준주소 = 0;
            return 0;
        }
        int ਲੰਬਾਈ_ਕੀਮਤ = ਆਕਾਰ - 4;
        if ((ਸਥਿਤੀ_ਕੀਮਤ & 1) != 0) {
            for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < ਲੰਬਾਈ_ਕੀਮਤ; ਅਨੁਕ੍ਰਮਣਿਕਾ++) ਸਮੱਗਰੀ[ਅਨੁਕ੍ਰਮਣਿਕਾ] = ਤਜਵੀਜ_ਕੀਮਤ.기억읽기(머리 + 4 + ਅਨੁਕ੍ਰਮਣਿਕਾ);
            수신수++;
        } else { ਲੰਬਾਈ_ਕੀਮਤ = 0; 오류수++; }
        수신위치 = (수신위치 + ਆਕਾਰ + 4 + 3) & ~3;
        수신위치 &= 8191;
        ਤਜਵੀਜ_ਕੀਮਤ.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        ਤਜਵੀਜ_ਕੀਮਤ.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return ਲੰਬਾਈ_ਕੀਮਤ;
    }
}
