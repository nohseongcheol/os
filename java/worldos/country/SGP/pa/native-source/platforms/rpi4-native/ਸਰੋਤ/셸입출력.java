/** 파이프는 16 KiB씩 순서대로 실행한다. 프로세스/동시 파이프를 흉내 내지 않는다. */
public final class 셸입출력 {
    static int[] 입력자료 = new int[16384], 출력자료 = new int[16384];
    static int 입력길이, 입력위치, 출력길이, 입력파일 = -1, ਆਉਟਪੁਟ_ਫਾਈਲ = -1;
    static boolean 파이프입력, 파이프출력;
    static int ਅਸਫਲ_ਕੀਮਤ;
    static boolean ਇਜਾਜ਼ਤ_ਦਿਉ_ਪਰਸਪਰਸਕ੍ਰਿਆਸ਼ੀਲ = true;
    public static int 대화가능() { return ਇਜਾਜ਼ਤ_ਦਿਉ_ਪਰਸਪਰਸਕ੍ਰਿਆਸ਼ੀਲ && 입력파일 < 3 && ਆਉਟਪੁਟ_ਫਾਈਲ < 3 && !파이프입력 && !파이프출력 ? 1 : 0; }
    public static int ਆਉਟਪੁੱਟ(int ਚੈਨਲ_ਕੀਮਤ, int ਕੀਮਤ) {
        if (ਚੈਨਲ_ਕੀਮਤ != 1) return 0;
        if (ਆਉਟਪੁਟ_ਫਾਈਲ >= 3) { int 처리값 = ਮੈਮਰੀ_ਫ਼ਾਈਲਾਂ.ਲਿਖਣ(ਆਉਟਪੁਟ_ਫਾਈਲ, ਕੀਮਤ); if (처리값 < 0) ਅਸਫਲ_ਕੀਮਤ = 처리값; return 1; }
        if (!파이프출력) return 0;
        if (출력길이 == 출력자료.length) ਅਸਫਲ_ਕੀਮਤ = -28;
        else 출력자료[출력길이++] = ਕੀਮਤ;
        return 1;
    }
    public static int 입력() {
        if (입력파일 >= 3) { int 처리값 = ਮੈਮਰੀ_ਫ਼ਾਈਲਾਂ.ਪੜ੍ਹਨ(입력파일); return 처리값 == 256 ? -2 : 처리값; }
        if (파이프입력) return 입력위치 < 입력길이 ? 입력자료[입력위치++] : -2;
        return -3; // UART로 ਫਾਰਵਰਡ_ਕੀਮਤ
    }
    static void ਚਲਾਓ_2(boolean ਲੀਡਿੰਗ_ਪਾਈਪ, boolean 뒤파이프) {
        파이프입력 = ਲੀਡਿੰਗ_ਪਾਈਪ; 파이프출력 = 뒤파이프;
        입력위치 = 0; 출력길이 = 0; 입력파일 = -1; ਆਉਟਪੁਟ_ਫਾਈਲ = -1; ਅਸਫਲ_ਕੀਮਤ = 0;
    }
    static void 끝() {
        ਬੋਰਡ.입출력전환(0);
        if (입력파일 >= 3) ਮੈਮਰੀ_ਫ਼ਾਈਲਾਂ.ਬੰਦ_ਕਰੋ(입력파일);
        if (ਆਉਟਪੁਟ_ਫਾਈਲ >= 3) ਮੈਮਰੀ_ਫ਼ਾਈਲਾਂ.ਬੰਦ_ਕਰੋ(ਆਉਟਪੁਟ_ਫਾਈਲ);
        if (파이프출력) { 입력길이 = 출력길이; for (int ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ < 출력길이; ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ++) 입력자료[ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ] = 출력자료[ਲੂਪ_ਅਨੁਕ੍ਰਮਣਿਕਾ]; }
        입력파일 = -1; ਆਉਟਪੁਟ_ਫਾਈਲ = -1; 파이프입력 = false; 파이프출력 = false;
    }
}
