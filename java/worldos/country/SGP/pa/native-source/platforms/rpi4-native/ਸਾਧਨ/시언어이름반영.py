#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 ਬਾਈਟ_ਕੀਮਤ 위치로 자체 C 이름을 옮기는 일회성 이행 ਸਾਧਨ.

외부 구조체의 멤버, ਨਿਰਭਰ_ਰਹਿਣ_ਵਾਲਾ_ਕੀਮਤ, C 표준 ਫੰਗਸ਼ਨ_ਕੀਮਤ, 이식 규약은 보존한다.
입력은 ਬਦਲੋ_ਕੀਮਤ 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

ਪ੍ਰੋਜੈਕਟ_ਰੂਟ = Path(__file__).resolve().parents[1]

def ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼():
    분석 = json.loads((ਪ੍ਰੋਜੈਕਟ_ਰੂਟ/'build/한국어화/시언어분석.json').read_text())
    if 분석['ਗਲਤੀ']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ਨਾਮ_ਤਾਲਿਕਾ = json.loads((ਪ੍ਰੋਜੈਕਟ_ਰੂਟ/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((ਪ੍ਰੋਜੈਕਟ_ਰੂਟ/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:ਨਾਮ_ਤਾਲਿਕਾ[ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ']] for 고유,ਦਾਖਲਾ_ਕੀਮਤ in 선언표.items()
                if ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ'] in ਨਾਮ_ਤਾਲਿਕਾ and ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ'] not in 규격}
    ਸਬੰਧ_ਤਾਲਿਕਾ = {ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ']:ਨਾਮ_ਤਾਲਿਕਾ[ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ']] for ਦਾਖਲਾ_ਕੀਮਤ in 선언표.values()
              if ਦਾਖਲਾ_ਕੀਮਤ.get('ਕੁਨੈਕਸ਼ਨ_ਕਰੋ')==4 and ਦਾਖਲਾ_ਕੀਮਤ['종류'] in (8,9)
              and ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ'] in ਨਾਮ_ਤਾਲਿਕਾ and ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ'] not in 규격}
    # ਜਨਰੇਟ_ਕਰੋ AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ਕੁਨੈਕਸ਼ਨ_ਕਰੋ 이름만 유지한다.
    머리 = ['/* ਪੰਜਾਬੀ ਸਰੋਤ_ਟ੍ਰੀ 이름과 기존 ਮਸ਼ੀਨ ਕੁਨੈਕਸ਼ਨ_ਕਰੋ ਕੰਮ_ਕੀਮਤ. 자동 ਜਨਰੇਟ_ਕਰੋ: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(ਸਬੰਧ_ਤਾਲਿਕਾ.items())]
    머리 += ['#endif','']
    (ਪ੍ਰੋਜੈਕਟ_ਰੂਟ/'명명/기계연결이름.h').write_text('\n'.join(머리))
    ਬਦਲਾਅ_ਸੂਚੀ = defaultdict(dict)
    for ਫਾਇਲ,ਔਫਸੈਟ_ਕੀਮਤ,ਨਾਂ,고유 in 분석['ਸੰਦਰਭ']:
        if 고유 in 바꿀선언:
            ਬਦਲਾਅ_ਸੂਚੀ[ਫਾਇਲ][ਔਫਸੈਟ_ਕੀਮਤ] = (ਨਾਂ,바꿀선언[고유])
    ਲੌਗ_ਕਤਾਰ = ['ਫਾਇਲ\t원래바이트위치\t이전이름\t한국어이름']
    ਅਣਡਿੱਠ_ਕਰੋ_ਕੀਮਤ = []
    for ਫਾਇਲ,ਬਦਲੋ_ਕੀਮਤ in ਬਦਲਾਅ_ਸੂਚੀ.items():
        ਮਾਰਗ = Path(ਫਾਇਲ); 원본 = ਮਾਰਗ.read_bytes(); ਸਮੱਗਰੀ = 원본
        for ਔਫਸੈਟ_ਕੀਮਤ,(옛이름,새이름) in sorted(ਬਦਲੋ_ਕੀਮਤ.items(),reverse=True):
            끝 = ਔਫਸੈਟ_ਕੀਮਤ+len(옛이름.encode())
            if 원본[ਔਫਸੈਟ_ਕੀਮਤ:끝] != 옛이름.encode():
                ਅਣਡਿੱਠ_ਕਰੋ_ਕੀਮਤ.append((str(ਮਾਰਗ.relative_to(ਪ੍ਰੋਜੈਕਟ_ਰੂਟ)),ਔਫਸੈਟ_ਕੀਮਤ,옛이름));continue
            ਸਮੱਗਰੀ = ਸਮੱਗਰੀ[:ਔਫਸੈਟ_ਕੀਮਤ]+새이름.encode()+ਸਮੱਗਰੀ[끝:]
            ਲੌਗ_ਕਤਾਰ.append('{}\t{}\t{}\t{}'.format(ਮਾਰਗ.relative_to(ਪ੍ਰੋਜੈਕਟ_ਰੂਟ),ਔਫਸੈਟ_ਕੀਮਤ,옛이름,새이름))
        ਮਾਰਗ.write_bytes(ਸਮੱਗਰੀ)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ਮੈਕ੍ਰੋ_ਕੀਮਤ = {ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ']:ਨਾਮ_ਤਾਲਿਕਾ[ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ']] for ਦਾਖਲਾ_ਕੀਮਤ in 선언표.values()
              if ਦਾਖਲਾ_ਕੀਮਤ['종류']==501 and ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ'] in ਨਾਮ_ਤਾਲਿਕਾ and ਦਾਖਲਾ_ਕੀਮਤ['ਨਾਂ'] not in 규격}
    for ਮਾਰਗ in sorted({Path(ਦਾਖਲਾ_ਕੀਮਤ['ਫਾਇਲ']) for ਦਾਖਲਾ_ਕੀਮਤ in 선언표.values()}):
        ਕਤਾਰ_ਸੂਚੀ = ਮਾਰਗ.read_text().splitlines(True); 이어짐 = False
        for ਅਨੁਕ੍ਰਮਣਿਕਾ,ਲਾਈਨ in enumerate(ਕਤਾਰ_ਸੂਚੀ):
            전처리 = 이어짐 or bool(re.match(r'\s*#',ਲਾਈਨ))
            이어짐 = 전처리 and ਲਾਈਨ.rstrip().endswith('\\')
            if 전처리:
                ਲੱਭਣਾ_ਤਾਲਿਕਾ = ਨਾਮ_ਤਾਲਿਕਾ if re.match(r'\s*#\s*define\b',ਲਾਈਨ) or 이어짐 else ਮੈਕ੍ਰੋ_ਕੀਮਤ
                ਕਤਾਰ_ਸੂਚੀ[ਅਨੁਕ੍ਰਮਣਿਕਾ] = 낱말.sub(lambda 맞음: ਲੱਭਣਾ_ਤਾਲਿਕਾ.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],ਲਾਈਨ)
        ਮਾਰਗ.write_text(''.join(ਕਤਾਰ_ਸੂਚੀ))
    # 각 자체 ਅਨੁਵਾਦ_ਸਰੋਤ 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ਮਾਰਗ in sorted({Path(ਦਾਖਲਾ_ਕੀਮਤ['ਫਾਇਲ']) for ਦਾਖਲਾ_ਕੀਮਤ in 선언표.values()}):
        if ਮਾਰਗ.suffix not in ('.c','.cpp'):continue
        ਪਿਅਰ_ਕੀਮਤ = '../' * len(ਮਾਰਗ.relative_to(ਪ੍ਰੋਜੈਕਟ_ਰੂਟ).parts[:-1]) + '명명/기계연결이름.h'
        ਮਾਰਗ.write_text('#include "'+ਪਿਅਰ_ਕੀਮਤ+'"\n'+ਮਾਰਗ.read_text())
    (ਪ੍ਰੋਜੈਕਟ_ਰੂਟ/'명명/시언어이름대응.tsv').write_text('\n'.join(ਲੌਗ_ਕਤਾਰ)+'\n')
    (ਪ੍ਰੋਜੈਕਟ_ਰੂਟ/'build/한국어화/전처리참조.json').write_text(json.dumps(ਅਣਡਿੱਠ_ਕਰੋ_ਕੀਮਤ,ensure_ascii=False,indent=2)+'\n')
    print('ਬਦਲੋ_ਕੀਮਤ',len(ਲੌਗ_ਕਤਾਰ)-1,'전처리 재검토',len(ਅਣਡਿੱਠ_ਕਰੋ_ਕੀਮਤ),'ਮਸ਼ੀਨ ਕੁਨੈਕਸ਼ਨ_ਕਰੋ',len(ਸਬੰਧ_ਤਾਲਿਕਾ))

if __name__=='__main__': ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼()
