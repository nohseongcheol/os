    public int ਲਿਖਤ_ਪੱਤਰ_ਨਿਯੰਤਰਣ(ਕਾਰਵਾਈ_ਕੀਮਤ 현재과정, int 서술자, int ਕਮਾਂਡ, int 인자) {
        if (ਕਮਾਂਡ == 0) {
            return 현재과정.파일서술자().복제서술자(서술자, 인자);
        }
        if (ਕਮਾਂਡ == 1) {
            return 현재과정.파일서술자().실행시닫기값(서술자);
        }
        if (ਕਮਾਂਡ == 2) {
            return 현재과정.파일서술자().실행시닫기설정(서술자, (인자 & 1) != 0);
        }
        if (ਕਮਾਂਡ == 3) {
            return 현재과정.파일서술자().ਸਿਸਟਮ_ਜਾਣਕਾਰੀ(서술자) == null ? -9 : ਸਿਰਫ਼_ਪੜ੍ਹੋ_ਨਿਸ਼ਾਨ;
        }
        if (ਕਮਾਂਡ == 4) {
            return 인자 == ਸਿਰਫ਼_ਪੜ੍ਹੋ_ਨਿਸ਼ਾਨ ? 0 : -30;
        }
        return -22;
    }

