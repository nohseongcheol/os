    public int 프로그램끝(ਕਾਰਵਾਈ_ਕੀਮਤ 현재과정, int 새끝) {
        int 이전끝 = 현재과정.프로그램끝();
        if (새끝 == 0) {
            return 이전끝;
        }
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            return -12;
        }
        int 첫쪽 = 이전끝 / ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ;
        int 끝쪽 = (새끝 + ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ - 1) / ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ;
        if (새끝 > 이전끝) {
            for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 첫쪽; ਅਨੁਕ੍ਰਮਣਿਕਾ < 끝쪽; ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
                int ਪਤਾ = ਅਨੁਕ੍ਰਮਣਿਕਾ * ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ;
                try {
                    쪽관리.바이트읽기(현재과정.ਪਤਾ_ਥਾਂ(), ਪਤਾ);
                } catch (IllegalStateException ਗਲਤੀ) {
                    쪽관리.ਮੈਪ_ਪੰਨਾ(현재과정.ਪਤਾ_ਥਾਂ(), ਪਤਾ, true);
                }
            }
        }
        현재과정.프로그램끝설정(새끝);
        return 새끝;
    }

    public int 프로그램끝늘리기(ਕਾਰਵਾਈ_ਕੀਮਤ 현재과정, int 증가량) {
        int 이전끝 = 현재과정.프로그램끝();
        int ਮਾਪ = 프로그램끝(현재과정, 이전끝 + 증가량);
        return ਮਾਪ < 0 ? ਮਾਪ : 이전끝;
    }

