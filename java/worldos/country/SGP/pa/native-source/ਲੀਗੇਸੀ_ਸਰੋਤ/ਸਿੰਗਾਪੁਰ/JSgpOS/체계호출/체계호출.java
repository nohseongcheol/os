    public int ਪੜ੍ਹਨ(ਕਾਰਵਾਈ_ਕੀਮਤ 현재과정, int 서술자, byte[] 받을곳, int ਆਕਾਰ) {
        if (서술자 == 0) {
            if (ਆਕਾਰ <= 0 || 받을곳.length == 0) {
                return 0;
            }
            입력사건 ਇਵੈਂਟ = 입력관리.ਅਗਲਾ_ਇਵੈਂਟ();
            if (ਇਵੈਂਟ == null || ਇਵੈਂਟ.사건종류() != 입력사건.종류.키누름) {
                return -11;
            }
            받을곳[0] = (byte) ਇਵੈਂਟ.첫째값();
            return 1;
        }
        return 현재과정.파일서술자().ਪੜ੍ਹਨ(서술자, 받을곳, ਆਕਾਰ);
    }

    public int ਲਿਖਣ(ਕਾਰਵਾਈ_ਕੀਮਤ 현재과정, int 서술자, byte[] ਸਮੱਗਰੀ, int ਆਕਾਰ) {
        if (서술자 != 1 && 서술자 != 2) {
            return 현재과정.파일서술자().열려있음(서술자) ? -30 : -9;
        }
        if (ਆਕਾਰ < 0 || ਆਕਾਰ > ਸਮੱਗਰੀ.length) {
            return -22;
        }
        ਤਜਵੀਜ_ਕੀਮਤ.직렬출력(new String(ਸਮੱਗਰੀ, 0, ਆਕਾਰ, java.nio.charset.StandardCharsets.UTF_8));
        return ਆਕਾਰ;
    }

