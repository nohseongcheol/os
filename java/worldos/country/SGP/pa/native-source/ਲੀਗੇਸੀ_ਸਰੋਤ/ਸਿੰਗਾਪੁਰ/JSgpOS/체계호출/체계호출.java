    public int 접근가능(String ਨਾਂ, int ਮੈਥਡ_ਮੋਡ) {
        ਲਿਖਤ_ਪੱਤਰ_ਜਾਣਕਾਰੀ ਸਿਸਟਮ_ਜਾਣਕਾਰੀ = ਫਾਈਲ_ਸਿਸਟਮ.ਸਿਸਟਮ_ਜਾਣਕਾਰੀ(ਨਾਂ);
        if (ਸਿਸਟਮ_ਜਾਣਕਾਰੀ == null) {
            return -2;
        }
        if ((ਮੈਥਡ_ਮੋਡ & 1) != 0 && (ਸਿਸਟਮ_ਜਾਣਕਾਰੀ.형태() & 0111) == 0) {
            return -13;
        }
        if ((ਮੈਥਡ_ਮੋਡ & 2) != 0) {
            return -30;
        }
        return 0;
    }

