    public int ਅਮਲ_ਕਰੋ_ਆਦੇਸ਼(ਕਾਰਵਾਈ_ਕੀਮਤ 현재과정, byte[] 실행파일, String[] 인자, String[] 환경) {
        실행파일적재기.ਤਸਵੀਰ ਤਸਵੀਰ_ਕੀਮਤ;
        try {
            ਤਸਵੀਰ_ਕੀਮਤ = 적재기.검사(실행파일);
        } catch (IllegalArgumentException ਗਲਤੀ) {
            return -8;
        }
        if (인자 == null || 환경 == null || 인자.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.ਵਿਭਾਗ_ਕੀਮਤ ਵਿਭਾਗ_ਕੀਮਤ : ਤਸਵੀਰ_ਕੀਮਤ.구역들()) {
            if ((ਵਿਭਾਗ_ਕੀਮਤ.ਨਿਸ਼ਾਨ_ਕੀਮਤ() & 2) == 0 || ਵਿਭਾਗ_ਕੀਮਤ.ਆਕਾਰ() == 0) {
                continue;
            }
            int 첫쪽 = ਵਿਭਾਗ_ਕੀਮਤ.ਪਤਾ() / ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ;
            int 끝쪽 = (ਵਿਭਾਗ_ਕੀਮਤ.ਪਤਾ() + ਵਿਭਾਗ_ਕੀਮਤ.ਆਕਾਰ() + ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ - 1) / ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ;
            for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 첫쪽; ਅਨੁਕ੍ਰਮਣਿਕਾ < 끝쪽; ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
                int ਪਤਾ = ਅਨੁਕ੍ਰਮਣਿਕਾ * ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ;
                try {
                    쪽관리.바이트읽기(현재과정.ਪਤਾ_ਥਾਂ(), ਪਤਾ);
                    쪽관리.범위개인쓰기(현재과정.ਪਤਾ_ਥਾਂ(), ਪਤਾ, ਪੰਨਾ_ਪ੍ਰਬੰਧਕ.ਪੰਨਾ_ਆਕਾਰ);
                } catch (IllegalStateException ਗਲਤੀ) {
                    쪽관리.ਮੈਪ_ਪੰਨਾ(현재과정.ਪਤਾ_ਥਾਂ(), ਪਤਾ, true);
                }
            }
            for (int ਅਨੁਕ੍ਰਮਣਿਕਾ = 0; ਅਨੁਕ੍ਰਮਣਿਕਾ < ਵਿਭਾਗ_ਕੀਮਤ.ਆਕਾਰ(); ਅਨੁਕ੍ਰਮਣਿਕਾ++) {
                byte ਕੀਮਤ = ਵਿਭਾਗ_ਕੀਮਤ.종류() == 8 ? 0 : 실행파일[ਵਿਭਾਗ_ਕੀਮਤ.ਲਿਖਤ_ਪੱਤਰ_ਸਥਿਤੀ_ਬਦਲੋ() + ਅਨੁਕ੍ਰਮਣਿਕਾ];
                쪽관리.ਲਿੱਖੋ_ਬਾਈਟ_ਕੀਮਤ(현재과정.ਪਤਾ_ਥਾਂ(), ਵਿਭਾਗ_ਕੀਮਤ.ਪਤਾ() + ਅਨੁਕ੍ਰਮਣਿਕਾ, ਕੀਮਤ);
            }
        }
        현재과정.실행문맥설정(ਤਸਵੀਰ_ਕੀਮਤ.ਸੁਰੂ_ਪਤਾ(), 인자, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

