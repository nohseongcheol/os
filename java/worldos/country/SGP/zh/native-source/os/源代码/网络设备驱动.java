/** PCI RTL8139（10ec:8139），一个发送缓冲区和 8 KiB 接收环；使用轮询而非中断。 */
public final class 网络设备驱动 {
    static int 输入输出基底地址 = 0;
    static int 接收位置 = 0, 传输槽 = 0;
    static int[] 设备地址 = new int[6];
    static int 传输个数 = 0, 接收个数 = 0, 错误个数 = 0;

    static int 读取设置(int 设备编号, int 位置) {
        设备.写入输入输出整数(0xcf8, 0x80000000 | (设备编号 << 11) | 位置);
        return 设备.读取输入输出整数(0xcfc);
    }

    static boolean 准备() {
        int 设备编号 = -1;
        for (int 编号 = 0; 编号 < 32; 编号++) {
            if (读取设置(编号, 0) == 0x813910ec) { 设备编号 = 编号; break; }
        }
        if (设备编号 < 0) return false;
        int 默认值 = 读取设置(设备编号, 0x10);
        if ((默认值 & 1) == 0 || (默认值 & 0xfffffffc) < 0x100 || (默认值 & 0xfffffffc) > 65535) return false;
        输入输出基底地址 = 默认值 & 0xfffc;
        int 命令 = 读取设置(设备编号, 4);
        设备.写入输入输出整数(0xcf8, 0x80000004 | (设备编号 << 11));
        设备.写入输入输出短整数(0xcfc, 命令 | 5); // 启用 I/O 和总线主控，不改动 PCI 状态位。
        设备.写入输入输出字节(输入输出基底地址 + 0x52, 0);
        if (!重置值()) { 输入输出基底地址 = 0; return false; }
        for (int 编号 = 0; 编号 < 6; 编号++) 设备地址[编号] = 设备.读取输入输出字节(输入输出基底地址 + 编号);
        return true;
    }

    static boolean 重置值() {
        设备.写入输入输出字节(输入输出基底地址 + 0x37, 0x10);
        int 运行 = 设备.毫秒();
        while ((设备.读取输入输出字节(输入输出基底地址 + 0x37) & 0x10) != 0)
            if (设备.毫秒() - 运行 > 100) return false;
        接收位置 = 0; 传输槽 = 0;
        设备.写入输入输出整数(输入输出基底地址 + 0x30, 设备.网络内存());
        for (int 编号 = 0; 编号 < 4; 编号++) 设备.写入输入输出整数(输入输出基底地址 + 0x20 + 编号 * 4, 设备.网络内存() + 12288);
        设备.写入输入输出短整数(输入输出基底地址 + 0x3c, 0);
        设备.写入输入输出短整数(输入输出基底地址 + 0x3e, 0xffff);
        设备.写入输入输出字节(输入输出基底地址 + 0x37, 0x0c);
        设备.写入输入输出整数(输入输出基底地址 + 0x44, 0x0000e78a); // 接收本机地址和广播；回绕时连续存储，容量 8 KiB。
        设备.写入输入输出整数(输入输出基底地址 + 0x40, 0x03000600);
        return true;
    }

    static int 发送(int[] 数据, int 长度) {
        if (输入输出基底地址 == 0) return -19;
        if (长度 < 14 || 长度 > 1514) return -90;
        int 运行状态端口 = 输入输出基底地址 + 0x10 + 传输槽 * 4;
        int 运行 = 设备.毫秒();
        while ((设备.读取输入输出整数(运行状态端口) & 0x2000) == 0)
            if (设备.毫秒() - 运行 > 100) return -110;
        int 大小 = 长度 < 60 ? 60 : 长度;
        for (int 编号 = 0; 编号 < 大小; 编号++)
            设备.写入内存(设备.网络内存() + 12288 + 编号, 编号 < 长度 ? 数据[编号] : 0);
        设备.写入输入输出整数(运行状态端口, 大小 | 0x00080000);
        运行 = 设备.毫秒();
        while ((设备.读取输入输出整数(运行状态端口) & 0xe0008000) == 0)
            if (设备.毫秒() - 运行 > 100) return -110;
        if ((设备.读取输入输出整数(运行状态端口) & 0x8000) == 0) { 错误个数++; return -5; }
        传输槽 = (传输槽 + 1) & 3;
        传输个数++;
        return 长度;
    }

    static int 接收(int[] 数据) {
        if (输入输出基底地址 == 0) return 0;
        if ((设备.读取输入输出字节(输入输出基底地址 + 0x3e) & 0x50) != 0) {
            错误个数++;
            if (!重置值()) 输入输出基底地址 = 0;
            return 0;
        }
        if ((设备.读取输入输出字节(输入输出基底地址 + 0x37) & 1) != 0) return 0;
        int 头值 = 设备.网络内存() + 接收位置;
        int 状态值 = 执行管理.短整数值(头值), 大小 = 执行管理.短整数值(头值 + 2);
        if (大小 == 0xfff0) return 0; // DMA 正在进行。
        if (大小 < 4 || 大小 > 1518) {
            错误个数++;
            if (!重置值()) 输入输出基底地址 = 0;
            return 0;
        }
        int 长度 = 大小 - 4;
        if ((状态值 & 1) != 0) {
            for (int 编号 = 0; 编号 < 长度; 编号++) 数据[编号] = 设备.读取内存(头值 + 4 + 编号);
            接收个数++;
        } else { 长度 = 0; 错误个数++; }
        接收位置 = (接收位置 + 大小 + 4 + 3) & ~3;
        接收位置 &= 8191;
        设备.写入输入输出短整数(输入输出基底地址 + 0x38, (接收位置 - 16) & 65535);
        设备.写入输入输出短整数(输入输出基底地址 + 0x3e, 0x000f);
        return 长度;
    }
}
