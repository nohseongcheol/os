/** 静态 IPv4/ARP/UDP；最多保存四个通信端口，每个端口一个数据报。 */
public final class 通信网络 {
    static final int 自有对象地址 = 0xc0a80064; /* ip.conf:IP */
    static final int 网络掩码 = 0xffffff00; /* ip.conf:NETMASK */
    static final int 网关值 = 0xc0a80001; /* ip.conf:GATEWAY */
    static int[] 输入帧 = new int[1536], 输出帧 = new int[1536];
    static int[] 端口列 = new int[4], 已接收长度 = new int[4], 已接收地址 = new int[4], 已接收端口编号 = new int[4];
    static int[] 已接收数据 = new int[4096], 已找到设备 = new int[6];
    static int 地址目标侧查找 = 0, 已找到地址 = 0, 标识符值 = 0, 已丢弃个数 = 0;

    static int 整数16(int[] 帧索引, int 位置) { return (帧索引[位置] << 8) | 帧索引[位置 + 1]; }
    static int 整数32(int[] 帧索引, int 位置) { return (整数16(帧索引, 位置) << 16) | 整数16(帧索引, 位置 + 2); }
    static void 放入16(int[] 帧索引, int 位置, int 值) { 帧索引[位置] = (值 >>> 8) & 255; 帧索引[位置 + 1] = 值 & 255; }
    static void 放入32(int[] 帧索引, int 位置, int 值) { 放入16(帧索引, 位置, 值 >>> 16); 放入16(帧索引, 位置 + 2, 值); }
    static int 总和值(int[] 帧索引, int 运行, int 长度, int 值) {
        for (int 编号 = 0; 编号 < 长度; 编号 += 2)
            值 += (帧索引[运行 + 编号] << 8) | (编号 + 1 < 长度 ? 帧索引[运行 + 编号 + 1] : 0);
        while ((值 >>> 16) != 0) 值 = (值 & 65535) + (值 >>> 16);
        return 值;
    }
    static int 伪头部校验和(int 出发值, int 到达值, int 长度) {
        return (出发值 >>> 16) + (出发值 & 65535) + (到达值 >>> 16) + (到达值 & 65535) + 17 + 长度;
    }

    static void 清洁进程() {
        for (int 编号 = 0; 编号 < 4; 编号++) {
            端口列[编号] = 0; 已接收长度[编号] = -1; 已接收地址[编号] = 0; 已接收端口编号[编号] = 0;
        }
        for (int 编号 = 0; 编号 < 64; 编号++) if (网络设备驱动.接收(输入帧) == 0) break;
    }
    static int 编号(int 句柄值) { return 句柄值 >= 3 && 句柄值 < 7 && 端口列[句柄值 - 3] != 0 ? 句柄值 - 3 : -1; }
    static int 打开(int 端口编号) {
        if (网络设备驱动.输入输出基底地址 == 0) return -19;
        if (端口编号 < 0 || 端口编号 > 65535) return -22;
        if (端口编号 != 0) for (int 编号 = 0; 编号 < 4; 编号++) if (端口列[编号] == 端口编号) return -98;
        for (int 编号 = 0; 编号 < 4; 编号++) if (端口列[编号] == 0) {
            if (端口编号 == 0) {
                端口编号 = 49152;
                boolean 重叠区列 = true;
                while (重叠区列) {
                    重叠区列 = false;
                    for (int 前端值 = 0; 前端值 < 4; 前端值++) if (端口列[前端值] == 端口编号) 重叠区列 = true;
                    if (重叠区列) 端口编号++;
                }
            }
            端口列[编号] = 端口编号; 已接收长度[编号] = -1;
            return 编号 + 3;
        }
        return -24;
    }
    static int 关闭(int 句柄值) {
        int 槽条目 = 编号(句柄值);
        if (槽条目 < 0) return -9;
        端口列[槽条目] = 0; 已接收长度[槽条目] = -1;
        return 0;
    }
    static int 对端地址(int 句柄值) { int 槽条目 = 编号(句柄值); return 槽条目 < 0 ? -9 : 已接收地址[槽条目]; }
    static int 对端端口编号(int 句柄值) { int 槽条目 = 编号(句柄值); return 槽条目 < 0 ? -9 : 已接收端口编号[槽条目]; }

    static void 外层头部(int 种类值, boolean 广播值) {
        for (int 编号 = 0; 编号 < 6; 编号++) {
            输出帧[编号] = 广播值 ? 255 : 已找到设备[编号];
            输出帧[6 + 编号] = 网络设备驱动.设备地址[编号];
        }
        放入16(输出帧, 12, 种类值);
    }
    static void 申请地址(int 目的地址值) {
        外层头部(0x0806, true);
        放入16(输出帧, 14, 1); 放入16(输出帧, 16, 0x0800);
        输出帧[18] = 6; 输出帧[19] = 4; 放入16(输出帧, 20, 1);
        for (int 编号 = 0; 编号 < 6; 编号++) {
            输出帧[22 + 编号] = 网络设备驱动.设备地址[编号]; 输出帧[32 + 编号] = 0;
        }
        放入32(输出帧, 28, 自有对象地址); 放入32(输出帧, 38, 目的地址值);
        网络设备驱动.发送(输出帧, 42);
    }
    static void 进程地址(int 长度) {
        if (长度 < 42 || 整数16(输入帧, 14) != 1 || 整数16(输入帧, 16) != 0x0800
            || 输入帧[18] != 6 || 输入帧[19] != 4 || 整数32(输入帧, 38) != 自有对象地址) { 已丢弃个数++; return; }
        int 种类值 = 整数16(输入帧, 20), 对端值 = 整数32(输入帧, 28);
        if (种类值 == 2 && 对端值 == 地址目标侧查找) {
            for (int 编号 = 0; 编号 < 6; 编号++) {
                if (输入帧[6 + 编号] != 输入帧[22 + 编号] || 输入帧[32 + 编号] != 网络设备驱动.设备地址[编号]) return;
            }
            for (int 编号 = 0; 编号 < 6; 编号++) 已找到设备[编号] = 输入帧[22 + 编号];
            已找到地址 = 对端值;
        } else if (种类值 == 1) {
            外层头部(0x0806, false);
            放入16(输出帧, 14, 1); 放入16(输出帧, 16, 0x0800);
            输出帧[18] = 6; 输出帧[19] = 4; 放入16(输出帧, 20, 2);
            for (int 编号 = 0; 编号 < 6; 编号++) {
                输出帧[编号] = 输入帧[22 + 编号]; 输出帧[32 + 编号] = 输入帧[22 + 编号];
                输出帧[22 + 编号] = 网络设备驱动.设备地址[编号];
            }
            放入32(输出帧, 28, 自有对象地址); 放入32(输出帧, 38, 对端值);
            网络设备驱动.发送(输出帧, 42);
        }
    }

    static void 进程帧(int 长度) {
        if (长度 < 14 || 长度 > 输入帧.length) { 已丢弃个数++; return; }
        boolean 自身引用 = true, 广播值 = true;
        for (int 编号 = 0; 编号 < 6; 编号++) {
            if (输入帧[编号] != 网络设备驱动.设备地址[编号]) 自身引用 = false;
            if (输入帧[编号] != 255) 广播值 = false;
        }
        if (!自身引用 && !广播值) return;
        if (整数16(输入帧, 12) == 0x0806) { 进程地址(长度); return; }
        if (整数16(输入帧, 12) != 0x0800) return;
        if (长度 < 34 || (输入帧[14] >>> 4) != 4) { 已丢弃个数++; return; }
        int 头部长度 = (输入帧[14] & 15) * 4, 总计长度 = 整数16(输入帧, 16);
        if (头部长度 < 20 || 头部长度 > 60 || 总计长度 < 头部长度 + 8 || 总计长度 > 长度 - 14
            || (整数16(输入帧, 20) & 0x3fff) != 0 || 输入帧[23] != 17
            || 整数32(输入帧, 30) != 自有对象地址 || 总和值(输入帧, 14, 头部长度, 0) != 65535) { 已丢弃个数++; return; }
        int 运行 = 14 + 头部长度, 数据长度 = 整数16(输入帧, 运行 + 4);
        if (数据长度 < 8 || 数据长度 != 总计长度 - 头部长度 || 数据长度 > 1032) { 已丢弃个数++; return; }
        int 出发值 = 整数32(输入帧, 26);
        if (整数16(输入帧, 运行 + 6) != 0 && 总和值(输入帧, 运行, 数据长度, 伪头部校验和(出发值, 自有对象地址, 数据长度)) != 65535) {
            已丢弃个数++; return;
        }
        int 目的地址值 = 整数16(输入帧, 运行 + 2);
        for (int 槽条目 = 0; 槽条目 < 4; 槽条目++) if (端口列[槽条目] != 0 && 端口列[槽条目] == 目的地址值) {
            if (已接收长度[槽条目] >= 0) { 已丢弃个数++; return; }
            已接收长度[槽条目] = 数据长度 - 8; 已接收地址[槽条目] = 出发值; 已接收端口编号[槽条目] = 整数16(输入帧, 运行);
            for (int 编号 = 0; 编号 < 数据长度 - 8; 编号++) 已接收数据[槽条目 * 1024 + 编号] = 输入帧[运行 + 8 + 编号];
            return;
        }
    }

    static void 验证() {
        for (int 编号 = 0; 编号 < 16; 编号++) {
            int 长度 = 网络设备驱动.接收(输入帧);
            if (长度 == 0) return;
            进程帧(长度);
        }
    }
    static int 查找地址(int 地址) {
        if (地址 == 0 || 地址 == -1 || (地址 >>> 28) >= 14 || (地址 >>> 24) == 127 || 地址 == 自有对象地址) return -101;
        int 下一项目 = (地址 & 网络掩码) == (自有对象地址 & 网络掩码) ? 地址 : 网关值;
        if (下一项目 == 已找到地址) return 0;
        地址目标侧查找 = 下一项目;
        int 运行 = 设备.毫秒(), 下一申请 = 运行;
        while (设备.毫秒() - 运行 < 1000) {
            if (设备.毫秒() - 下一申请 >= 0) { 申请地址(下一项目); 下一申请 += 300; }
            验证();
            if (已找到地址 == 下一项目) return 0;
            设备.挂起短暂地();
        }
        return -110;
    }
    static int 发送(int 句柄值, int 地址, int 端口编号, int[] 数据, int 长度) {
        int 槽条目 = 编号(句柄值);
        if (槽条目 < 0) return -9;
        if (网络设备驱动.输入输出基底地址 == 0) return -19;
        if (端口编号 < 1 || 端口编号 > 65535 || 长度 < 0 || 长度 > 1024) return -22;
        int 结果 = 查找地址(地址);
        if (结果 < 0) return 结果;
        外层头部(0x0800, false);
        输出帧[14] = 0x45; 输出帧[15] = 0; 放入16(输出帧, 16, 28 + 长度);
        放入16(输出帧, 18, 标识符值++); 放入16(输出帧, 20, 0x4000);
        输出帧[22] = 64; 输出帧[23] = 17; 放入16(输出帧, 24, 0);
        放入32(输出帧, 26, 自有对象地址); 放入32(输出帧, 30, 地址);
        放入16(输出帧, 24, ~总和值(输出帧, 14, 20, 0));
        放入16(输出帧, 34, 端口列[槽条目]); 放入16(输出帧, 36, 端口编号);
        放入16(输出帧, 38, 长度 + 8); 放入16(输出帧, 40, 0);
        for (int 编号 = 0; 编号 < 长度; 编号++) 输出帧[42 + 编号] = 数据[编号] & 255;
        int 校验和 = (~总和值(输出帧, 34, 长度 + 8, 伪头部校验和(自有对象地址, 地址, 长度 + 8))) & 65535;
        放入16(输出帧, 40, 校验和 == 0 ? 65535 : 校验和);
        结果 = 网络设备驱动.发送(输出帧, 长度 + 42);
        return 结果 < 0 ? 结果 : 长度;
    }
    static int 接收(int 句柄值, int[] 数据, int 容量值, int 限制值) {
        int 槽条目 = 编号(句柄值);
        if (槽条目 < 0) return -9;
        int 运行 = 设备.毫秒();
        while (true) {
            验证();
            int 长度 = 已接收长度[槽条目];
            if (长度 >= 0) {
                已接收长度[槽条目] = -1;
                if (长度 > 容量值) return -90;
                for (int 编号 = 0; 编号 < 长度; 编号++) 数据[编号] = 已接收数据[槽条目 * 1024 + 编号];
                return 长度;
            }
            if (限制值 == 0) return -11;
            if (设备.毫秒() - 运行 >= 限制值) return -110;
            设备.挂起短暂地();
        }
    }
    static void 状态值() {
        字符终端.写入(网络设备驱动.输入输出基底地址 == 0 ? "NET unavailable (RTL8139 required)\n" : "NET RTL8139 192.168.0.100/24 gateway 192.168.0.1 UDP\n");
        字符终端.写入("TX: "); 字符终端.写入编号(网络设备驱动.传输个数);
        字符终端.写入(" RX: "); 字符终端.写入编号(网络设备驱动.接收个数);
        字符终端.写入(" DROP: "); 字符终端.写入编号(已丢弃个数);
        字符终端.写入("\n");
    }
}
