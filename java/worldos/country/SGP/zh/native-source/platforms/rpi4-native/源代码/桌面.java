/** 帧缓冲上的小型启动界面，通过 UART 的 TAB/ENTER/Q 操作。采用自定义 5×7 拉丁字体，界面功能有限，不提供 Swing、USB HID 或完整输入法。 */
public final class 桌面 {
    static String 字符值列 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789+-.:";
    // 每个字形 7 行，每行用两位十六进制数表示；这是项目自定义的 5×7 字体。
    static String 形状列列表 =
        "0E11111F111111" + "1E11111E11111E" + "0F10101010100F" + "1E11111111111E" +
        "1F10101E10101F" + "1F10101E101010" + "0F10101711110F" + "1111111F111111" +
        "0E04040404040E" + "0702020212120C" + "11121418141211" + "1010101010101F" +
        "111B1515111111" + "11191915131311" + "0E11111111110E" + "1E11111E101010" +
        "0E11111115120D" + "1E11111E141211" + "0F10100E01011E" + "1F040404040404" +
        "1111111111110E" + "11111111110A04" + "11111115151B11" + "11110A040A1111" +
        "11110A04040404" + "1F01020408101F" + "0E11131519110E" + "040C040404040E" +
        "0E11010204081F" + "1E01010601011E" + "02060A121F0202" + "1F10101E01011E" +
        "0E10101E11110E" + "1F010204080808" + "0E11110E11110E" + "0E11110F01010E" +
        "0004041F040400" + "0000001F000000" + "00000000000C0C" + "000C0C000C0C00";
    static int 数字值(int 字符值) { return 字符值 <= '9' ? 字符值 - '0' : 字符值 - 'A' + 10; }
    static void 文本(int 水平位置, int 垂直位置, String 内容值, int 颜色值) {
        for (int 字符值 = 0; 字符值 < 内容值.length(); 字符值++) {
            int 已找到值 = -1;
            for (int 候选 = 0; 候选 < 字符值列.length(); 候选++) if (字符值列.charAt(候选) == 内容值.charAt(字符值)) 已找到值 = 候选;
            if (已找到值 < 0) continue;
            for (int 行值 = 0; 行值 < 7; 行值++) {
                int 位置 = 已找到值 * 14 + 行值 * 2;
                int 位值 = 数字值(形状列列表.charAt(位置)) * 16 + 数字值(形状列列表.charAt(位置 + 1));
                for (int 列值 = 0; 列值 < 5; 列值++) if ((位值 & (16 >> 列值)) != 0)
                    内核.矩形(水平位置 + 字符值 * 12 + 列值 * 2, 垂直位置 + 行值 * 2, 2, 2, 颜色值);
            }
        }
    }
    static void 画图屏幕(int 选中状态值, String 状态值) {
        内核.矩形(0, 0, 板.屏幕宽度(), 板.屏幕高度(), 0x302018);
        内核.矩形(32, 24, 576, 432, 0xefe8e2);
        内核.矩形(32, 24, 576, 48, 0x905020);
        文本(52, 40, "JKOROS PROGRAMS", 0xffffff);
        for (int 编号 = 0; 编号 < 5; 编号++) {
            内核.矩形(64, 112 + 编号 * 52, 512, 40, 编号 == 选中状态值 ? 0xd0a040 : 0xd8d0c8);
            文本(84, 128 + 编号 * 52, 编号 == 0 ? "RUN C++ FILE PROGRAM" : 编号 == 1 ? "RUN UDP LOOPBACK" : 编号 == 2 ? "COMPILE AND RUN JAVA" : 编号 == 3 ? "RUN MICROPYTHON" : "OPEN TERMINAL", 0x201810);
        }
        文本(68, 384, 状态值, 0x205020);
        文本(52, 420, "TAB SELECT  ENTER RUN  Q EXIT", 0x302018);
    }
    public static void 执行命令() {
        if (板.准备屏幕() == 0) { 终端输入输出.写入("GUI unavailable\n"); return; }
        int 选中状态值 = 0;
        String 状态值 = "READY";
        boolean 上一个行 = 命令解释器.上一个行;
        画图屏幕(选中状态值, 状态值);
        终端输入输出.写入("GUI READY: UART TAB selects, ENTER runs, Q exits\n");
        while (true) {
            int 输入值 = 板.读取串行();
            if (输入值 < 0) { 板.挂起处理器(); continue; }
            if (输入值 == 10 && 上一个行) { 上一个行 = false; continue; }
            上一个行 = 输入值 == 13;
            if (输入值 >= '1' && 输入值 <= '5') { 选中状态值 = 输入值 - '1'; 输入值 = 13; }
            if (输入值 == 't' || 输入值 == 'T') { 命令解释器.终端(false); return; }
            if (输入值 == 'q' || 输入值 == 'Q' || 输入值 == 27) break;
            if (输入值 == 9 || 输入值 == 'j') {
                选中状态值 = (选中状态值 + 1) % 5; 画图屏幕(选中状态值, 状态值); 终端输入输出.写入("GUI FOCUS "); 终端输入输出.数(选中状态值); 终端输入输出.字符(10);
            } else if (输入值 == 13 || 输入值 == 10) {
                if (选中状态值 == 4) { 命令解释器.终端(false); return; }
                int 结果;
                if (选中状态值 < 2) 结果 = 板.运行用户程序(选中状态值 == 0 ? 0 : 9);
                else if (选中状态值 == 2) {
                    结果 = 命令解释器.运行示例(10, "Hello.java");
                    if (结果 == 0) 结果 = 命令解释器.运行示例(11, "Hello");
                } else 结果 = 命令解释器.运行示例(12, "hello.py");
                状态值 = 结果 != 0 ? "PROGRAM FAILED" : 选中状态值 == 0 ? "C++ FILE OK" : 选中状态值 == 1 ? "UDP LOOPBACK OK" : 选中状态值 == 2 ? "JAVA OK" : "MICROPYTHON OK";
                画图屏幕(选中状态值, 状态值);
                终端输入输出.写入("GUI ACTION "); 终端输入输出.数(选中状态值); 终端输入输出.写入(" RESULT "); 终端输入输出.数(结果); 终端输入输出.字符(10);
            }
        }
        内核.屏幕();
        终端输入输出.写入("GUI EXIT\n");
    }
}
