/** 四个终端的 shell 状态；共享文件存储，路径、变量、历史和输入各自独立。 */
public final class 窗口会话 {
    static int[] 保留值 = new int[4 * 30000], 准备 = new int[4];
    static int 当前项目, 位置;
    static boolean 读取继续状态;
    static void 数组值(int[] 数据, boolean 存储值) {
        for (int 循环索引 = 0; 循环索引 < 数据.length; 循环索引++) { if (存储值) 保留值[位置++] = 数据[循环索引]; else 数据[循环索引] = 保留值[位置++]; }
    }
    static int 值(int 数据值, boolean 曾经已存储) { if (曾经已存储) { 保留值[位置++] = 数据值; return 数据值; } return 保留值[位置++]; }
    static void 寻道位置(int 已保留槽, boolean 曾经已存储) {
        位置 = 已保留槽 * 30000;
        数组值(内存文件集.当前项目, 曾经已存储); 内存文件集.当前长度 = 值(内存文件集.当前长度, 曾经已存储);
        数组值(命令壳语法.变量名称, 曾经已存储); 数组值(命令壳语法.变量数据, 曾经已存储); 数组值(命令壳语法.名称长度, 曾经已存储); 数组值(命令壳语法.值长度, 曾经已存储);
        命令壳语法.状态值 = 值(命令壳语法.状态值, 曾经已存储);
        数组值(行编辑器.日志记录, 曾经已存储); 数组值(行编辑器.日志长度, 曾经已存储); 数组值(行编辑器.存储值, 曾经已存储); 数组值(命令解释器.行, 曾经已存储);
        行编辑器.日志个数 = 值(行编辑器.日志个数, 曾经已存储); 行编辑器.日志记录结束 = 值(行编辑器.日志记录结束, 曾经已存储);
        行编辑器.搜索值 = 值(行编辑器.搜索值, 曾经已存储); 行编辑器.已存储长度 = 值(行编辑器.已存储长度, 曾经已存储);
        行编辑器.大小 = 值(行编辑器.大小, 曾经已存储); 行编辑器.光标值 = 值(行编辑器.光标值, 曾经已存储); 行编辑器.开始窗口 = 值(行编辑器.开始窗口, 曾经已存储);
        准备[已保留槽] = 1;
    }
    static void 进程值条目() {
        int 事件编号 = 板.终端(12); if (事件编号 == 0) return;
        寻道位置(当前项目, true);
        for (int 循环索引 = 0; 循环索引 < 4; 循环索引++) {
            if ((事件编号 & (1 << (8 + 循环索引))) != 0) { 板.控制用户程序(32 + 循环索引); 准备[循环索引] = 0; }
            if ((事件编号 & (1 << (4 + 循环索引))) != 0 && 循环索引 != 当前项目) 准备[循环索引] = 0;
        }
        int 下一位置 = (事件编号 & 15) - 1; if (下一位置 < 0) 下一位置 = 0;
        if (准备[下一位置] == 0) for (int 循环索引 = 0; 循环索引 < 30000; 循环索引++) 保留值[下一位置 * 30000 + 循环索引] = 0;
        当前项目 = 下一位置; 寻道位置(当前项目, false); 板.终端(100 + 当前项目); 读取继续状态 = true;
        终端输入输出.写入("\nTERMINAL FOCUS "); 终端输入输出.数(当前项目 + 1); 终端输入输出.字符(10);
    }
    static boolean 恢复执行执行状态() {
        if (板.控制用户程序(16 + 当前项目) == 0) return false;
        命令壳输入输出.允许交互式 = true; 命令壳输入输出.运行(false, false); 板.切换输入输出(1);
        int 已处理值 = 板.控制用户程序(当前项目); 命令壳输入输出.结尾();
        if (已处理值 != -1005) { 读取继续状态 = false; 命令壳语法.状态值 = 已处理值 < 0 ? 126 : 已处理值; 终端输入输出.写入("exit "); 终端输入输出.数(已处理值); 终端输入输出.字符(10); 板.终端(3); }
        return true;
    }
}
