import 한국어.자체.веза;
import 한국어.자체.실행인수;
import 한국어.자체.전문통로;
import 한국어.자체.문자;
import 한국어.자체.Излаз;
import 한국어.자체.검사;
import 한국어.자체.입력흐름;
import 한국어.자체.У_И_изузетак;

public class 네트워크예제 {
    public static void Покрени() throws У_И_изузетак {
        // хост: python3 Алатке/예제되돌림.py --tcp-port 9000 --udp-port 9001
        веза Повежи_се = веза.Отвори("10.0.2.2", 문자.рашчланити_цијели_број(실행인수.Текст(0)));
        try {
            Повежи_се.대기시간(700);
            byte[] порука = 문자.부호화("JAVA TCP српски\n");
            Повежи_се.Излаз().Пише(порука);
            입력흐름 입력 = Повежи_се.입력();
            for (int 수 = 0; 수 < 문자.바이트수(порука); 수++) {
                검사.참인지(입력.Чита() == (порука[수] & 255), "TCP одговор 불일치");
            }
        } finally { Повежи_се.Затворен(); }
        전문통로 крајња_тачка = 전문통로.Отвори(0);
        try {
            крајња_тачка.대기시간(700);
            крајња_тачка.послати("10.0.2.2", 문자.рашчланити_цијели_број(실행인수.Текст(1)), "JAVA UDP српски");
            검사.참인지(문자.같음(крајња_тачка.받기(), "JAVA UDP српски"), "UDP одговор 불일치");
        } finally { крајња_тачка.Затворен(); }
        Излаз.писати_редак("JAVA 네트워크 потврдити: TCP UDP српски");
    }
}
