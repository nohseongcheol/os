/** 자체 커널의 Swing Прозор: српски 입력 → дугме → Прочитај_ме_eb81d7d9 Текст освежити. */
public class 창예제 implements 실행할일, 동작받이 {
    private Прозор 인사창;
    private текстуално_поље име_поље;
    private Натпис 인사말;
    private int 인사횟수;

    public void креирати_прозор() {
        인사창 = new Прозор("српски Swing", 460, 300);
        인사창.додати_елемент(new Натпис("српски", 20, 20, 420, 28));
        име_поље = new текстуално_поље("српски", 20, 64, 420, 30);
        인사말 = new Натпис("српски", 20, 152, 420, 28);
        인사창.додати_елемент(име_поље);
        인사창.додати_елемент(new дугме("인사하기", 20, 108, 180, 32, this));
        인사창.додати_елемент(인사말);
        인사창.додати_елемент(new Натпис("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.емисија_прозор();
        Излаз.писати_редак("GUI 예제 Припремити: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.писати_Текст("српски, " + име_поље.글읽기() + "님! (" + 인사횟수 + ")");
        Излаз.писати_редак("GUI 인사: " + 인사말.글읽기());
    }

    public void Изврши() { креирати_прозор(); }
    public void 동작받기(동작알림 알림) {
        Излаз.писати_редак("радња 알림: " + 알림.команда_Текст());
        인사하기();
    }
    public static void Покрени() {
        догађај_редослед.나중에실행(new 창예제());
    }
}
