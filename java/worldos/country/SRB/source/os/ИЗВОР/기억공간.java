/** 부팅 Информације_о_систему 조회와 4KiB 고정 Величина 작업 одељак_вриједност доделити_похрана/вратити_мера. 일반 물리 страница_вриједност 관리자는 아니다. */
public final class 기억공간 {
    static int[] одељак_вриједност = new int[8192];
    static int[] 사용 = new int[8];

    static int рашчланити_цијели_број(int адреса) {
        return уређај_вриједност.기억읽기(адреса) | (уређај_вриједност.기억읽기(адреса + 1) << 8)
            | (уређај_вриједност.기억읽기(адреса + 2) << 16) | (уређај_вриједност.기억읽기(адреса + 3) << 24);
    }

    static int 위쪽기억크기() {
        int Информације_о_систему = уређај_вриједност.부팅정보();
        if (уређај_вриједност.부팅표식() != 0x2badb002 || Информације_о_систему == 0 || (рашчланити_цијели_број(Информације_о_систему) & 1) == 0) return -1;
        return рашчланити_цијели_број(Информације_о_систему + 8);
    }

    static int доделити_похрана() {
        for (int индекс = 0; индекс < 사용.length; индекс++) {
            if (사용[индекс] == 0) {
                사용[индекс] = 1;
                for (int простор_за_унос_унос = 0; простор_за_унос_унос < 1024; простор_за_унос_унос++) одељак_вриједност[индекс * 1024 + простор_за_унос_унос] = 0;
                return индекс;
            }
        }
        return -1;
    }

    static boolean вратити_мера(int индекс) {
        if (индекс < 0 || индекс >= 사용.length || 사용[индекс] == 0) return false;
        사용[индекс] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int индекс = 0; индекс < 사용.length; индекс++) 개수 += 사용[индекс];
        return 개수;
    }
}
