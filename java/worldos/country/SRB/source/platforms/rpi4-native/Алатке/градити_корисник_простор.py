"""독립된 자체 ABI ELF64와 로더 одбацити_вриједност_e3ecc00b 시험 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from 파이썬빌드 import 파이썬만들기
from 자바라이브러리빌드 import 자바라이브러리만들기
from 시언어번역기빌드 import 시언어번역기만들기


def Направи_корисник_простор(корен_пут, депо_пут, 시언어번역기, 시플플번역기, 연결편집기, Архива_алат, конфигурација_Услуга_интелигентног_преноса_у_позадини, Изврши_команда):
    конфигурација_Услуга_интелигентног_преноса_у_позадини = [Поставке_вриједност for Поставке_вриједност in конфигурација_Услуга_интелигентног_преноса_у_позадини if Поставке_вриједност != '-mgeneral-regs-only']
    градити_пут = корен_пут / 'build'
    출력결과 = градити_пут / 'user'
    출력결과.mkdir(exist_ok=True)
    원본자료 = корен_пут / 'корисник'
    포직스경로 = депо_пут / 'posix-kor/arm64-native'
    포함경로 = ['-I', 원본자료, '-I', 포직스경로 / '포함', '-I', 출력결과]
    for 번역기, 추가영역, ПУТАЊА, Назив in [
            (시언어번역기, [], 원본자료 / 'Покрени.S', 'start.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'Изврши_команда.c', 'runtime.o'),
            (시언어번역기, ['-std=c11'], 포직스경로 / 'корисник_мост.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '파일예제.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '통신예제.cpp', 'network.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / '보호시험.c', 'fault.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'уредник.c', 'vi.o')]:
        Изврши_команда([번역기] + конфигурација_Услуга_интелигентног_преноса_у_позадини + 추가영역 + 포함경로 + ['-Wall', '-Wextra', '-Werror', '-c', ПУТАЊА, '-o', 출력결과 / Назив])
    Изврши_команда([Архива_алат, 'rcs', градити_пут / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for Назив in ('demo', 'fault', 'network', 'vi'):
        Изврши_команда([연결편집기, '-T', 원본자료 / 'Веза_изглед.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (Назив + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (Назив + '.o'), градити_пут / 'libposix-kor-user.a'])
    자바라이브러리만들기(корен_пут, Изврши_команда)
    # 기존 자체 Java 컴파일러/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(градити_пут)) as 작업경로:
        класа_пут = Path(작업경로)
        Изврши_команда(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', класа_пут, '-sourcepath', класа_пут, '-d', класа_пут] +
            [подаци_позиција for подаци_позиција in sorted((депо_пут / 'os/корисник/자바').glob('*.java')) if подаци_позиција.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        Изврши_команда(['sh', депо_пут / 'compiler/미리번역.sh', '--entry', 'алат_унос.Покрени',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(класа_пут.glob('*.class')))
    압축해제경로 = корен_пут / 'vendor/uzlib'
    for ПУТАЊА, Назив in [(출력결과 / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'пакет.c', 'jar.o')] + [(압축해제경로 / (Назив + '.c'), Назив + '.o') for Назив in ('tinflate', 'crc32', 'adler32')]:
        Изврши_команда([시언어번역기] + конфигурација_Услуга_интелигентног_преноса_у_позадини + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + 포함경로 + ['-c', ПУТАЊА, '-o', 출력결과 / Назив])
    Изврши_команда([연결편집기, '-T', 원본자료 / 'Веза_изглед.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / Назив for Назив in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(корен_пут, 시언어번역기, 연결편집기)
    시언어번역기만들기(корен_пут, депо_пут, 시언어번역기, 연결편집기, конфигурација_Услуга_интелигентног_преноса_у_позадини, Изврши_команда)
    유효함 = (출력결과 / 'demo.elf').read_bytes()
    програм_Заглавље_Помак = struct.unpack_from('<Q', 유효함, 32)[0]
    Заглавље_Листа = [програм_Заглавље_Помак + 개수 * 56 for 개수 in range(struct.unpack_from('<H', 유효함, 56)[0])]
    적재구획 = [подаци_позиција for подаци_позиција in Заглавље_Листа if struct.unpack_from('<I', 유효함, подаци_позиција)[0] == 1]
    Текст, подаци = 적재구획[:2]
    команда_адреса = struct.unpack_from('<Q', 유효함, Текст + 16)[0]
    подаци_адреса = struct.unpack_from('<Q', 유효함, подаци + 16)[0]
    호출규약 = 유효함.index(b'JKOROS\0')
    시험사례 = [('empty', b''), ('short', 유효함[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', команда_адреса + 1), ('data-entry', 24, 'Q', подаци_адреса),
               ('outside-file', Текст + 32, 'Q', len(유효함) + 1), ('short-memory', Текст + 40, 'Q', 1),
               ('kernel-address', Текст + 16, 'Q', 0x80000), ('memory-overflow', Текст + 40, 'Q', 2**64 - 1),
               ('writable-code', Текст + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', Текст, 'I', 2),
               ('unaligned-load', Текст + 16, 'Q', команда_адреса + 8),
               ('overlap', подаци + 16, 'Q', команда_адреса)]
    for Назив, Помак_вриједност, формат_932e03c8, вриједност in 수정사항:
        바뀐자료 = bytearray(유효함); struct.pack_into('<' + формат_932e03c8, 바뀐자료, Помак_вриједност, вриједност)
        시험사례.append((Назив, bytes(바뀐자료)))
    탑재덩이들 = [(Назив.replace('-', '_'), 출력결과 / (Назив + '.elf')) for Назив in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for Претрага_индекс, (Назив, корисни_подаци_подаци) in enumerate(시험사례):
        ПУТАЊА = 출력결과 / ('invalid-{}.elf'.format(Назив)); ПУТАЊА.write_bytes(корисни_подаци_подаци)
        탑재덩이들.append(('invalid_{}'.format(Претрага_индекс), ПУТАЊА))
    склоп, Заглавље_вриједност = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for Назив, ПУТАЊА in 탑재덩이들:
        симбол_вриједност = 'user_blob_' + Назив
        크기목록[Назив] = ПУТАЊА.stat().st_size
        # 생성한 상대 경로만 넣어 프로젝트 경로의 공백/Цитат 영향을 피한다.
        склоп += ['.balign 16', '.global ' + симбол_вриједност, симбол_вриједност + ':', '.incbin "{}"'.format(ПУТАЊА.relative_to(корен_пут))]
        Заглавље_вриједност.append('extern const unsigned char {}[];'.format(симбол_вриједност))
    склоп.append('.section .note.GNU-stack,"",%progbits')
    Заглавље_вриједност += ['static const програм 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    Заглавље_вриједност += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    Заглавље_вриједност += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    Заглавље_вриједност += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], метода_мод) for метода_мод in (0, 1)]
    Заглавље_вриједност += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    Заглавље_вриједност += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    Заглавље_вриједност += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    Заглавље_вриједност += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    Заглавље_вриједност += ['};', 'static const програм 잘못된실행항목들[] = {']
    Заглавље_вриједност += ['{user_blob_invalid_%d, %d, 0},' % (순번, len(корисни_подаци_подаци)) for 순번, (_, корисни_подаци_подаци) in enumerate(시험사례)]
    Заглавље_вриједност += ['};']
    (градити_пут / 'programs.S').write_text('\n'.join(склоп) + '\n')
    (градити_пут / 'programs.h').write_text('\n'.join(Заглавље_вриједност) + '\n')
    (출력결과 / 'invalid-cases.txt').write_text('\n'.join(Назив for Назив, _ in 시험사례) + '\n')
    Изврши_команда([시언어번역기] + конфигурација_Услуга_интелигентног_преноса_у_позадини + ['-c', градити_пут / 'programs.S', '-o', градити_пут / 'programs.o'])
