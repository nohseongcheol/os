#!/usr/bin/env python3
"""декларација 고유번호와 UTF-8 бајт_вриједност 위치로 자체 C 이름을 옮기는 일회성 이행 Алатке.

екстерни_вриједност 구조체의 멤버, ниска_вриједност, C 표준 функција_вриједност, 이식 규약은 보존한다.
입력은 промијенити_вриједност 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

пројектовати_корен = Path(__file__).resolve().parents[1]

def Изврши_команда():
    Анализа_вриједност = json.loads((пројектовати_корен/'build/한국어화/시언어분석.json').read_text())
    if Анализа_вриједност['ГРЕШКА']: raise SystemExit('Анализа_вриједност 오류를 먼저 해결해야 합니다.')
    име_табела = json.loads((пројектовати_корен/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((пројектовати_корен/'명명/규격이름.json').read_text()))
    декларација_табела = Анализа_вриједност['декларација']
    바꿀선언 = {고유:име_табела[унос_вриједност['Назив']] for 고유,унос_вриједност in декларација_табела.items()
                if унос_вриједност['Назив'] in име_табела and унос_вриједност['Назив'] not in 규격}
    веза_табела = {унос_вриједност['Назив']:име_табела[унос_вриједност['Назив']] for унос_вриједност in декларација_табела.values()
              if унос_вриједност.get('Повежи_се')==4 and унос_вриједност['종류'] in (8,9)
              and унос_вриједност['Назив'] in име_табела and унос_вриједност['Назив'] not in 규격}
    # генерисати AOT C·어셈블리·공개 SDK가 공유하는 바이너리 Повежи_се 이름만 유지한다.
    머리 = ['/* 한국어 извор_стабло 이름과 기존 рачунар Повежи_се случај_вриједност. 자동 генерисати: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(веза_табела.items())]
    머리 += ['#endif','']
    (пројектовати_корен/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Промене_Листа = defaultdict(dict)
    for Датотека,Помак_вриједност,Назив,고유 in Анализа_вриједност['Литература']:
        if 고유 in 바꿀선언:
            Промене_Листа[Датотека][Помак_вриједност] = (Назив,바꿀선언[고유])
    евиденција_ред = ['Датотека\t원래바이트위치\t이전이름\t한국어이름']
    занемарити_вриједност = []
    for Датотека,промијенити_вриједност in Промене_Листа.items():
        ПУТАЊА = Path(Датотека); 원본 = ПУТАЊА.read_bytes(); подаци = 원본
        for Помак_вриједност,(옛이름,새이름) in sorted(промијенити_вриједност.items(),reverse=True):
            끝 = Помак_вриједност+len(옛이름.encode())
            if 원본[Помак_вриједност:끝] != 옛이름.encode():
                занемарити_вриједност.append((str(ПУТАЊА.relative_to(пројектовати_корен)),Помак_вриједност,옛이름));continue
            подаци = подаци[:Помак_вриједност]+새이름.encode()+подаци[끝:]
            евиденција_ред.append('{}\t{}\t{}\t{}'.format(ПУТАЊА.relative_to(пројектовати_корен),Помак_вриједност,옛이름,새이름))
        ПУТАЊА.write_bytes(подаци)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макро_вриједност = {унос_вриједност['Назив']:име_табела[унос_вриједност['Назив']] for унос_вриједност in декларација_табела.values()
              if унос_вриједност['종류']==501 and унос_вриједност['Назив'] in име_табела and унос_вриједност['Назив'] not in 규격}
    for ПУТАЊА in sorted({Path(унос_вриједност['Датотека']) for унос_вриједност in декларација_табела.values()}):
        редак_Листа = ПУТАЊА.read_text().splitlines(True); 이어짐 = False
        for индекс,Ред in enumerate(редак_Листа):
            전처리 = 이어짐 or bool(re.match(r'\s*#',Ред))
            이어짐 = 전처리 and Ред.rstrip().endswith('\\')
            if 전처리:
                Претрага_табела = име_табела if re.match(r'\s*#\s*define\b',Ред) or 이어짐 else макро_вриједност
                редак_Листа[индекс] = 낱말.sub(lambda 맞음: Претрага_табела.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],Ред)
        ПУТАЊА.write_text(''.join(редак_Листа))
    # 각 자체 превести_извор 단위에만 연결표를 넣는다. екстерни_вриједност 배포본에는 전파하지 않는다.
    for ПУТАЊА in sorted({Path(унос_вриједност['Датотека']) for унос_вриједност in декларација_табела.values()}):
        if ПУТАЊА.suffix not in ('.c','.cpp'):continue
        상대 = '../' * len(ПУТАЊА.relative_to(пројектовати_корен).parts[:-1]) + '명명/기계연결이름.h'
        ПУТАЊА.write_text('#include "'+상대+'"\n'+ПУТАЊА.read_text())
    (пројектовати_корен/'명명/시언어이름대응.tsv').write_text('\n'.join(евиденција_ред)+'\n')
    (пројектовати_корен/'build/한국어화/전처리참조.json').write_text(json.dumps(занемарити_вриједност,ensure_ascii=False,indent=2)+'\n')
    print('промијенити_вриједност',len(евиденција_ред)-1,'전처리 재검토',len(занемарити_вриједност),'рачунар Повежи_се',len(веза_табела))

if __name__=='__main__': Изврши_команда()
