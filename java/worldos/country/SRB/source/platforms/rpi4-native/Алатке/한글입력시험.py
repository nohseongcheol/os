#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from десктоп_Приказ import тастатура


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.Текст_бафер = ''
        def послати(подаци):
            for знак_подаци in подаци.decode('utf-8'):
                if знак_подаци == '\x7f': 자신.Текст_бафер = 자신.Текст_бафер[:-1]
                else: 자신.Текст_бафер += знак_подаци
        자신.тастатура_унос = тастатура(послати)

    def отиснути_Кључ(자신, симбол_вриједност):
        자신.тастатура_унос.누름값(True, симбол_вриједност)
        자신.тастатура_унос.누름값(False, симбол_вриједност)

    def тип_област(자신, 누름열):
        for 누름값 in 누름열: 자신.отиснути_Кључ(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.отиснути_Кључ(0xffc6); 자신.тип_област(누름열)
                자신.assertEqual(자신.Текст_бафер, 예상결과)

    def test_앞글자지우기(자신):
        자신.отиснути_Кључ(0xff31); 자신.тип_област('dlfr')
        자신.assertEqual(자신.Текст_бафер,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.отиснути_Кључ(0xff08); 자신.assertEqual(자신.Текст_бафер,예상결과)
        자신.тип_област('gksk'); 자신.assertEqual(자신.Текст_бафер,'하나')
        자신.отиснути_Кључ(0xff08); 자신.assertEqual(자신.Текст_бафер,'하ㄴ')

    def test_전환반복확정(자신):
        자신.тип_област('echo ')
        자신.тастатура_унос.누름값(True,0xffe1)
        자신.тастатура_унос.누름값(True,32); 자신.тастатура_унос.누름값(True,32)
        자신.тастатура_унос.누름값(False,32); 자신.тастатура_унос.누름값(False,0xffe1)
        자신.assertTrue(자신.тастатура_унос.한글여부)
        자신.тип_област('gksrmf'); 자신.отиснути_Кључ(0xff31); 자신.тип_област(' English')
        자신.assertEqual(자신.Текст_бафер,'echo 한글 English')
        자신.assertFalse(자신.тастатура_унос.한글여부)
        자신.отиснути_Кључ(0xffc6); 자신.тип_област('rk'); 자신.отиснути_Кључ(0xff51)
        자신.тип_област('sk'); 자신.assertTrue(자신.Текст_бафер.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.отиснути_Кључ(0xffc6); 자신.тип_област('rk')
        자신.тастатура_унос.међуспремник_вриједност='залијепити_вриједност'.encode()
        자신.тастатура_унос.누름값(True,0xffe3); 자신.тастатура_унос.누름값(True,0xffe1)
        자신.отиснути_Кључ(ord('v'))
        자신.тастатура_унос.누름값(False,0xffe1); 자신.тастатура_унос.누름값(False,0xffe3)
        자신.отиснути_Кључ(0x0100d55c); 자신.тип_област('sk')
        자신.assertEqual(자신.Текст_бафер,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
