"""자체 커널용 제한형 pip. PyPI의 작은 순수 Python 소스를 хост 중계로 설치한다."""
import sys
import json
import hashlib
import gc
import jkoros as оперативни_систем

Листа_пут = "/lib/.pip.json"


def 지문(подаци):
    return "".join("%02x" % вриједност for вриједност in hashlib.sha256(подаци).digest())


def 목록읽기():
    if оперативни_систем.path_kind(Листа_пут) == 0:
        return {}
    return json.loads(оперативни_систем.read(Листа_пут).decode("utf-8"))


def писати_евиденција(ПУТАЊА, подаци):
    if оперативни_систем.write(ПУТАЊА, подаци) != len(подаци):
        raise OSError(28)


def чек_пут(ПУТАЊА):
    if not isinstance(ПУТАЊА, str) or not ПУТАЊА.endswith(".py"):
        raise ValueError("Python 소스만 설치할 수 있습니다.")
    if any(부분 in ("", ".", "..") or 부분.startswith(".") for 부분 in ПУТАЊА.split("/")):
        raise ValueError("허용하지 않는 пакет ПУТАЊА")
    if "\\" in ПУТАЊА or any(ord(знак_вриједност) < 32 or ord(знак_вриједност) == 127 for знак_вриједност in ПУТАЊА):
        raise ValueError("잘못된 ПУТАЊА 문자")
    ИСХОД = "/lib/" + ПУТАЊА
    if len(ИСХОД.encode("utf-8")) > 63 or ПУТАЊА in ("한국어.py", "пакет.py"):
        raise ValueError("пакет 경로가 너무 길거나 задана_вриједност 라이브러리와 겹칩니다.")
    return ИСХОД


class 수신흐름:
    def __init__(자신, крајња_тачка):
        자신.крајња_тачка = крајња_тачка
        자신.남은자료 = b""
        자신.Покрени = оперативни_систем.ticks_ms()

    def 정확히읽기(자신, дужина_вриједност):
        подаци = bytearray()
        while len(подаци) < дужина_вриједност:
            if оперативни_систем.ticks_ms() - 자신.Покрени > 90000:
                raise ValueError("пакет 중계 одговор време_вриједност 초과")
            if not 자신.남은자료:
                try:
                    자신.남은자료 = оперативни_систем.tcp_read(자신.крајња_тачка, 512)
                except OSError as ГРЕШКА:
                    if ГРЕШКА.args[0] != 11:
                        raise
                    оперативни_систем.sleep_ms(10)
                    continue
                if not 자신.남은자료:
                    raise ValueError("пакет 전송이 중간에 끝났습니다.")
            개수 = min(дужина_вриједност - len(подаци), len(자신.남은자료))
            подаци.extend(자신.남은자료[:개수])
            자신.남은자료 = 자신.남은자료[개수:]
            оперативни_систем.sleep_ms(0)
        return bytes(подаци)


def преузми(захтев, број_порта):
    if len(захтев) > 96 or any(знак_вриједност not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-=" for знак_вриједност in захтев):
        raise ValueError("사용법: pip install Назив 또는 Назив==버전")
    крајња_тачка = оперативни_систем.tcp_open()
    try:
        Покрени = оперативни_систем.ticks_ms()
        while True:
            try:
                оперативни_систем.tcp_connect(крајња_тачка, "10.0.2.2", број_порта)
                break
            except OSError as ГРЕШКА:
                if ГРЕШКА.args[0] not in (11, 115) or оперативни_систем.ticks_ms() - Покрени > 5000:
                    raise ValueError("пакет 중계 Повежи_се неуспјех_вриједност: 호스트에서 --network --pip로 실행하십시오.")
                оперативни_систем.sleep_ms(10)
        подаци = (захтев + "\n").encode()
        while подаци:
            try:
                개수 = оперативни_систем.tcp_write(крајња_тачка, подаци)
                if not 개수:
                    raise ValueError("пакет захтев пренос_вриједност неуспјех_вриједност")
                подаци = подаци[개수:]
            except OSError as ГРЕШКА:
                if ГРЕШКА.args[0] != 11:
                    raise
                оперативни_систем.sleep_ms(10)
                if оперативни_систем.ticks_ms() - Покрени > 10000:
                    raise ValueError("пакет захтев пренос_вриједност време_вриједност 초과")
        ток_вриједност = 수신흐름(крајња_тачка)
        머리 = ток_вриједност.정확히읽기(8)
        if 머리[:4] != b"JKP1":
            raise ValueError("пакет пренос_вриједност случај_вриједност 불일치")
        дужина_вриједност = (머리[4] << 24) | (머리[5] << 16) | (머리[6] << 8) | 머리[7]
        if дужина_вриједност > 8192:
            raise ValueError("пакет 명세가 너무 큽니다.")
        명세 = json.loads(ток_вриједност.정확히읽기(дужина_вриједност).decode())
        if "error" in 명세:
            raise ValueError(명세["error"])
        if not 1 <= len(명세["files"]) <= 16:
            raise ValueError("꾸러미당 извор_стабло 파일은 1~16개여야 합니다.")
        if sum(унос_вриједност["size"] for унос_вриједност in 명세["files"]) > 65536:
            raise ValueError("пакет извор_стабло 합계는 64 KiB 이하여야 합니다.")
        파일들 = {}
        for унос_вриједност in 명세["files"]:
            ПУТАЊА = чек_пут(унос_вриједност["path"])
            if ПУТАЊА in 파일들 or not 0 <= унос_вриједност["size"] <= 16384:
                raise ValueError("중복 ПУТАЊА 또는 Датотека Величина 초과")
            подаци = ток_вриједност.정확히읽기(унос_вриједност["size"])
            if 지문(подаци) != унос_вриједност["sha256"]:
                raise ValueError("пакет Датотека SHA-256 불일치")
            # 실행하지 않고 актуелно_ставка MicroPython의 문법으로 먼저 검사한다.
            compile(подаци.decode("utf-8"), ПУТАЊА, "exec")
            파일들[ПУТАЊА] = подаци
            gc.collect()
        return 명세, 파일들
    finally:
        оперативни_систем.udp_close(крајња_тачка)


def инсталирај_вриједност(захтев, број_порта):
    print("пакет преузми:", захтев)
    명세, 파일들 = преузми(захтев, број_порта)
    унос_Листа = 목록읽기()
    Назив = 명세["name"]
    if Назив in унос_Листа:
        if унос_Листа[Назив]["version"] == 명세["version"]:
            for ПУТАЊА, 지문값 in унос_Листа[Назив]["files"].items():
                if оперативни_систем.path_kind(ПУТАЊА) != 1 or 지문(оперативни_систем.read(ПУТАЊА)) != 지문값:
                    raise ValueError("설치된 пакет 파일이 달라졌습니다: " + ПУТАЊА)
            print("이미 설치됨:", Назив, 명세["version"])
            return
        raise ValueError("다른 버전이 있습니다. pip uninstall로 제거한 НАЗАД_вриједност 설치하십시오.")
    for ПУТАЊА in 파일들:
        if оперативни_систем.path_kind(ПУТАЊА):
            raise ValueError("기존 파일을 덮어쓰지 않습니다: " + ПУТАЊА)
    унос_Листа[Назив] = {"version": 명세["version"], "files": {ПУТАЊА: 지문(подаци) for ПУТАЊА, подаци in 파일들.items()}}
    새목록 = json.dumps(унос_Листа).encode()
    if len(새목록) > 16384:
        raise ValueError("пакет унос_Листа Величина 초과")
    이전목록 = оперативни_систем.read(Листа_пут) if оперативни_систем.path_kind(Листа_пут) else None
    만든파일 = []
    만든폴더 = []
    try:
        for ПУТАЊА, подаци in 파일들.items():
            부분들 = ПУТАЊА.split("/")
            for 수 in range(2, len(부분들)):
                именик_вриједност = "/".join(부분들[:수])
                종류 = оперативни_систем.path_kind(именик_вриједност)
                if 종류 == 0:
                    оперативни_систем.mkdir(именик_вриједност)
                    만든폴더.append(именик_вриједност)
                elif 종류 != 2:
                    raise ValueError("именик_вриједност 경로에 파일이 있습니다: " + именик_вриједност)
            만든파일.append(ПУТАЊА)
            писати_евиденција(ПУТАЊА, подаци)
        писати_евиденција(Листа_пут, 새목록)
    except Exception:
        for ПУТАЊА in 만든파일:
            if оперативни_систем.path_kind(ПУТАЊА):
                оперативни_систем.remove(ПУТАЊА)
        for именик_вриједност in reversed(만든폴더):
            оперативни_систем.rmdir(именик_вриједност)
        if 이전목록 is not None:
            писати_евиденција(Листа_пут, 이전목록)
        elif оперативни_систем.path_kind(Листа_пут):
            оперативни_систем.remove(Листа_пут)
        raise
    print("инсталирај_вриједност 완료:", Назив, 명세["version"], "→ /lib (RAM)")


def уклонити_унос(Назив):
    унос_Листа = 목록읽기()
    if Назив not in унос_Листа:
        raise ValueError("설치되지 않은 꾸러미입니다: " + Назив)
    for ПУТАЊА, 지문값 in унос_Листа[Назив]["files"].items():
        if оперативни_систем.path_kind(ПУТАЊА) != 1 or 지문(оперативни_систем.read(ПУТАЊА)) != 지문값:
            raise ValueError("사용자가 바꾼 파일을 보존합니다: " + ПУТАЊА)
    for ПУТАЊА in унос_Листа[Назив]["files"]:
        оперативни_систем.remove(ПУТАЊА)
    del унос_Листа[Назив]
    писати_евиденција(Листа_пут, json.dumps(унос_Листа).encode())
    print("уклонити_унос 완료:", Назив)


def Покрени(Аргументи):
    број_порта = 8027
    if len(Аргументи) >= 2 and Аргументи[-2] == "--port":
        број_порта = int(Аргументи[-1])
        Аргументи = Аргументи[:-2]
    if Аргументи == ["list"]:
        for Назив, Информације_о_систему in 목록읽기().items():
            print(Назив, Информације_о_систему["version"])
    elif len(Аргументи) == 2 and Аргументи[0] == "install":
        инсталирај_вриједност(Аргументи[1], број_порта)
    elif len(Аргументи) == 2 and Аргументи[0] == "uninstall":
        уклонити_унос(Аргументи[1])
    elif not Аргументи or Аргументи in (["--help"], ["--version"]):
        print("jkoros pip 1 / MicroPython извор_стабло 설치기 (PyPA pip 전체가 아님)")
        print("pip install Назив[==버전] [--port 8027] | pip list | pip uninstall Назив")
        print("хост: Алатке/Изврши_команда.py --network --pip; /lib는 재부팅 때 사라지는 RAM입니다.")
    else:
        raise ValueError("pip --help로 사용법을 확인하십시오.")


if __name__ == "__main__":
    try:
        Покрени(sys.argv[1:])
    except Exception as ГРЕШКА:
        print("пакет ГРЕШКА:", ГРЕШКА)
        sys.exit(1)
