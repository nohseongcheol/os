public final class 화면 {
    private 화면() {}
    public static int 너비() { int вриједност = језгро_вриједност.화면너비(); if (вриједност < 0) throw new стање_изузетак("프레임버퍼 없음"); return вриједност; }
    public static int 높이() { int вриједност = језгро_вриједност.화면높이(); if (вриједност < 0) throw new стање_изузетак("프레임버퍼 없음"); return вриједност; }
    public static void 사각형(int 가로, int вертикала_позиција, int 폭, int 높이, int 색) {
        if (가로 < 0 || вертикала_позиција < 0 || 폭 < 0 || 높이 < 0 || 가로 > 너비() || вертикала_позиција > 높이() || 폭 > 너비() - 가로 || 높이 > 높이() - вертикала_позиција) throw new неважеће_аргумент_изузетак("화면 клип");
        if (језгро_вриједност.사각형(가로, вертикала_позиција, 폭, 높이, 색) < 0) throw new стање_изузетак("프레임버퍼 없음");
    }
    public static void 지우기(int 색) { 사각형(0, 0, 너비(), 높이(), 색); }
    public static void 기다리기() { if (језгро_вриједност.그림대기() < 0) throw new стање_изузетак("интерактивно 입력 필요"); }
}
