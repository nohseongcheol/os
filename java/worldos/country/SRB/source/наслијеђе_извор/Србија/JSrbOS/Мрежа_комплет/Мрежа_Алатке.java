/** Ethernet/ARP/IPv4/ICMP/UDP 계층이 공유하는 бајт_вриједност 순서와 контролни_збир 도구다. */
public final class Мрежа_Алатке {
    private Мрежа_Алатке() {
    }

    public static int 큰순서짧은정수(byte[] подаци, int Положај) {
        чек_опсег(подаци, Положај, 2);
        return ((подаци[Положај] & 0xff) << 8) | (подаци[Положај + 1] & 0xff);
    }

    public static long 큰순서정수(byte[] подаци, int Положај) {
        чек_опсег(подаци, Положај, 4);
        return ((long) (подаци[Положај] & 0xff) << 24)
                | ((long) (подаци[Положај + 1] & 0xff) << 16)
                | ((long) (подаци[Положај + 2] & 0xff) << 8)
                | (подаци[Положај + 3] & 0xffL);
    }

    public static int облак_контролни_збир(byte[] подаци, int Покрени, int дужина_вриједност) {
        чек_опсег(подаци, Покрени, дужина_вриједност);
        long 합 = 0;
        int 끝 = Покрени + дужина_вриједност;
        int Положај = Покрени;
        while (Положај + 1 < 끝) {
            합 += 큰순서짧은정수(подаци, Положај);
            Положај += 2;
        }
        if (Положај < 끝) {
            합 += (подаци[Положај] & 0xff) << 8;
        }
        while ((합 >>> 16) != 0) {
            합 = (합 & 0xffff) + (합 >>> 16);
        }
        return (int) (~합) & 0xffff;
    }

    public static boolean 이더넷틀인가(byte[] подаци) {
        return подаци != null && подаци.length >= 14;
    }

    public static int 이더넷상위규약(byte[] подаци) {
        if (!이더넷틀인가(подаци)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return 큰순서짧은정수(подаци, 12);
    }

    public static boolean 상호통신망규약사판인가(byte[] подаци, int Положај) {
        if (подаци == null || Положај < 0 || подаци.length - Положај < 20) {
            return false;
        }
        int верзија_вриједност = (подаци[Положај] >>> 4) & 0xf;
        int Заглавље_дужина = (подаци[Положај] & 0xf) * 4;
        return верзија_вриједност == 4 && Заглавље_дужина >= 20 && подаци.length - Положај >= Заглавље_дужина;
    }

    private static void чек_опсег(byte[] подаци, int Покрени, int дужина_вриједност) {
        if (подаци == null || Покрени < 0 || дужина_вриједност < 0 || Покрени > подаци.length - дужина_вриједност) {
            throw new IllegalArgumentException("Мрежа_комплет подаци 범위를 벗어났습니다.");
        }
    }
}

