package Србија.JSrbOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB страница_вриједност 연결과 Пише 시 복사를 제공한다. */
public final class страница_менаџер {
    public static final int величина_странице = 4096;

    private static final class страница_вриједност {
        private byte[] подаци = new byte[величина_странице];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class адреса_простор {
        private final Map<Integer, страница_вриједност> страница_табела = new HashMap<Integer, страница_вриједност>();
    }

    public адреса_простор 새주소공간() {
        return new адреса_простор();
    }

    public void мапирати_страница(адреса_простор 공간, int виртуелно_адреса, boolean 쓰기가능) {
        int индекс = 쪽번호(виртуелно_адреса);
        страница_вриједност 새쪽 = new страница_вриједност();
        새쪽.쓰기가능 = 쓰기가능;
        공간.страница_табела.put(Integer.valueOf(индекс), 새쪽);
    }

    public адреса_простор 쓰기시복사복제(адреса_простор 원본) {
        адреса_простор 복제본 = new адреса_простор();
        for (Map.Entry<Integer, страница_вриједност> унос_вриједност : 원본.страница_табела.entrySet()) {
            страница_вриједност 공유쪽 = унос_вриједност.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.страница_табела.put(унос_вриједност.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(адреса_простор 공간, int виртуелно_адреса) {
        страница_вриједност циљ = наћи_страница(공간, виртуелно_адреса);
        return циљ.подаци[Math.floorMod(виртуелно_адреса, величина_странице)];
    }

    public void писати_бајт_вриједност(адреса_простор 공간, int виртуелно_адреса, byte вриједност) {
        int индекс = 쪽번호(виртуелно_адреса);
        страница_вриједност циљ = наћи_страница(공간, виртуелно_адреса);
        if (!циљ.쓰기가능) {
            if (!циљ.쓰기시복사) {
                throw new IllegalStateException("Чита 전용 쪽입니다.");
            }
            циљ = Направи_приватан_страница(공간, индекс, циљ);
        }
        циљ.подаци[Math.floorMod(виртуелно_адреса, величина_странице)] = вриједност;
    }

    public void приватан_опсег_писати(адреса_простор 공간, int почетна_адреса, int Величина) {
        if (Величина < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int завршити_адреса = Math.addExact(почетна_адреса, Величина);
        for (int адреса = почетна_адреса; адреса < завршити_адреса; адреса = (쪽번호(адреса) + 1) * величина_странице) {
            int индекс = 쪽번호(адреса);
            страница_вриједност циљ = наћи_страница(공간, адреса);
            if (циљ.쓰기시복사) {
                Направи_приватан_страница(공간, индекс, циљ);
            } else {
                циљ.쓰기가능 = true;
            }
        }
    }

    public void опсег_писати(адреса_простор 공간, int почетна_адреса, byte[] подаци) {
        for (int индекс = 0; индекс < подаци.length; индекс++) {
            писати_бајт_вриједност(공간, почетна_адреса + индекс, подаци[индекс]);
        }
    }

    private страница_вриједност Направи_приватан_страница(адреса_простор 공간, int индекс, страница_вриједност 공유쪽) {
        страница_вриједност приватан_страница = new страница_вриједност();
        приватан_страница.подаци = Arrays.copyOf(공유쪽.подаци, 공유쪽.подаци.length);
        приватан_страница.쓰기가능 = true;
        приватан_страница.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.страница_табела.put(Integer.valueOf(индекс), приватан_страница);
        return приватан_страница;
    }

    private страница_вриједност наћи_страница(адреса_простор 공간, int адреса) {
        страница_вриједност циљ = 공간.страница_табела.get(Integer.valueOf(쪽번호(адреса)));
        if (циљ == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return циљ;
    }

    private int 쪽번호(int адреса) {
        if (адреса < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return адреса / величина_странице;
    }
}

