package Србија.JSrbOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Србија.JSrbOS.기억공간.страница_менаџер;
import Србија.JSrbOS.фајл_систем.파일서술자표;

/** Процес_вриједност 식별자와 라운드로빈 Припремити 대기열을 관리한다. */
public final class Планер {
    private final страница_менаџер 쪽관리;
    private final Map<Integer, Процес_вриједност> Листа_процеса = new HashMap<Integer, Процес_вриједност>();
    private final Queue<Процес_вриједност> 준비대기열 = new ArrayDeque<Процес_вриједност>();
    private int Даље_идентификатор = 1;

    public Планер(страница_менаџер 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public Процес_вриједност 첫과정(파일서술자표 파일서술자) {
        Процес_вриједност 새과정 = new Процес_вриједност(доделити_идентификатор(), 0, 쪽관리.새주소공간(), 파일서술자);
        Листа_процеса.put(Integer.valueOf(새과정.идентификатор_вриједност()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public Процес_вриједност клон_вриједност(Процес_вриједност родитељ_вриједност) {
        Процес_вриједност дете_вриједност = new Процес_вриједност(
                доделити_идентификатор(),
                родитељ_вриједност.идентификатор_вриједност(),
                쪽관리.쓰기시복사복제(родитељ_вриједност.адреса_простор()),
                родитељ_вриједност.파일서술자().клон_вриједност());
        дете_вриједност.скуп_програм_пауза(родитељ_вриједност.програм_пауза());
        Листа_процеса.put(Integer.valueOf(дете_вриједност.идентификатор_вриједност()), дете_вриједност);
        준비대기열.offer(дете_вриједност);
        return дете_вриједност;
    }

    public Процес_вриједност Даље_Процес() {
        int 검사수 = 준비대기열.size();
        for (int индекс = 0; индекс < 검사수; индекс++) {
            Процес_вриједност Даље_ставка = 준비대기열.poll();
            if (Даље_ставка != null && (Даље_ставка.стање_вриједност() == Процес_стање.Припремити || Даље_ставка.стање_вриједност() == Процес_стање.Изврши_команда)) {
                Даље_ставка.скуп_стање(Процес_стање.Изврши_команда);
                준비대기열.offer(Даље_ставка);
                return Даље_ставка;
            }
        }
        return null;
    }

    public int 자식기다리기(Процес_вриједност родитељ_вриједност, int дете_идентификатор, boolean 기다리지않음) {
        for (Процес_вриједност 후보 : Листа_процеса.values()) {
            if (후보.родитељ_идентификатор() != родитељ_вриједност.идентификатор_вриједност()) {
                continue;
            }
            if (дете_идентификатор > 0 && 후보.идентификатор_вриједност() != дете_идентификатор) {
                continue;
            }
            if (후보.стање_вриједност() == Процес_стање.Излаз_програм) {
                int ИСХОД = (후보.Излаз_шифра() & 0xff) << 8;
                Листа_процеса.remove(Integer.valueOf(후보.идентификатор_вриједност()));
                return ИСХОД;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public Процес_вриједност наћи_Процес(int идентификатор_вриједност) {
        return Листа_процеса.get(Integer.valueOf(идентификатор_вриједност));
    }

    private int доделити_идентификатор() {
        return Даље_идентификатор++;
    }
}
