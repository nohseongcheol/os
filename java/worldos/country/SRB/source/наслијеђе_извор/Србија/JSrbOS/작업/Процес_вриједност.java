package Србија.JSrbOS.작업;

import Србија.JSrbOS.기억공간.страница_менаџер;
import Србија.JSrbOS.фајл_систем.파일서술자표;

public final class Процес_вриједност {
    private final int идентификатор_вриједност;
    private final int родитељ_идентификатор;
    private final страница_менаџер.адреса_простор адреса_простор;
    private final 파일서술자표 파일서술자;
    private Процес_стање стање_вриједност = Процес_стање.Припремити;
    private int Излаз_шифра;
    private int програм_пауза = 0x06000000;
    private int 실행시작주소;
    private String[] 실행인자 = new String[0];
    private String[] радно_окружење_вриједност = new String[0];

    Процес_вриједност(int идентификатор_вриједност, int родитељ_идентификатор, страница_менаџер.адреса_простор адреса_простор, 파일서술자표 파일서술자) {
        this.идентификатор_вриједност = идентификатор_вриједност;
        this.родитељ_идентификатор = родитељ_идентификатор;
        this.адреса_простор = адреса_простор;
        this.파일서술자 = 파일서술자;
    }

    public int идентификатор_вриједност() {
        return идентификатор_вриједност;
    }

    public int родитељ_идентификатор() {
        return родитељ_идентификатор;
    }

    public страница_менаџер.адреса_простор адреса_простор() {
        return адреса_простор;
    }

    public 파일서술자표 파일서술자() {
        return 파일서술자;
    }

    public Процес_стање стање_вриједност() {
        return стање_вриједност;
    }

    public void скуп_стање(Процес_стање 새상태) {
        стање_вриједност = 새상태;
    }

    public int Излаз_шифра() {
        return Излаз_шифра;
    }

    public void Излаз_програм(int вриједност) {
        Излаз_шифра = вриједност & 0xff;
        стање_вриједност = Процес_стање.Излаз_програм;
    }

    public int програм_пауза() {
        return програм_пауза;
    }

    public void скуп_програм_пауза(int 새끝) {
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            throw new IllegalArgumentException("програм_f5044b9b 끝 범위를 벗어났습니다.");
        }
        програм_пауза = 새끝;
    }

    public void 실행문맥설정(int почетна_адреса, String[] параметар_аргумент, String[] радно_окружење) {
        실행시작주소 = почетна_адреса;
        실행인자 = параметар_аргумент.clone();
        радно_окружење_вриједност = радно_окружење.clone();
    }

    public int 실행시작주소() { return 실행시작주소; }
    public String[] 실행인자() { return 실행인자.clone(); }
    public String[] радно_окружење_вриједност() { return радно_окружење_вриједност.clone(); }
}
