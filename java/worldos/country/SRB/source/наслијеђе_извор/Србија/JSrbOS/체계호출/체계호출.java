    public int Изврши_команда(Процес_вриједност актуелно_Процес, byte[] 실행파일, String[] параметар_аргумент, String[] радно_окружење) {
        실행파일적재기.слика слика_вриједност;
        try {
            слика_вриједност = 적재기.검사(실행파일);
        } catch (IllegalArgumentException ГРЕШКА) {
            return -8;
        }
        if (параметар_аргумент == null || радно_окружење == null || параметар_аргумент.length > 16 || радно_окружење.length > 16) {
            return -7;
        }
        for (실행파일적재기.одељак_вриједност одељак_вриједност : слика_вриједност.구역들()) {
            if ((одељак_вриједност.заставица_вриједност() & 2) == 0 || одељак_вриједност.Величина() == 0) {
                continue;
            }
            int 첫쪽 = одељак_вриједност.адреса() / страница_менаџер.величина_странице;
            int 끝쪽 = (одељак_вриједност.адреса() + одељак_вриједност.Величина() + страница_менаџер.величина_странице - 1) / страница_менаџер.величина_странице;
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int адреса = индекс * страница_менаџер.величина_странице;
                try {
                    쪽관리.바이트읽기(актуелно_Процес.адреса_простор(), адреса);
                    쪽관리.приватан_опсег_писати(актуелно_Процес.адреса_простор(), адреса, страница_менаџер.величина_странице);
                } catch (IllegalStateException ГРЕШКА) {
                    쪽관리.мапирати_страница(актуелно_Процес.адреса_простор(), адреса, true);
                }
            }
            for (int индекс = 0; индекс < одељак_вриједност.Величина(); индекс++) {
                byte вриједност = одељак_вриједност.종류() == 8 ? 0 : 실행파일[одељак_вриједност.фајл_позиција() + индекс];
                쪽관리.писати_бајт_вриједност(актуелно_Процес.адреса_простор(), одељак_вриједност.адреса() + индекс, вриједност);
            }
        }
        актуелно_Процес.실행문맥설정(слика_вриједност.почетна_адреса(), параметар_аргумент, радно_окружење);
        актуелно_Процес.파일서술자().실행시닫기();
        return 0;
    }

