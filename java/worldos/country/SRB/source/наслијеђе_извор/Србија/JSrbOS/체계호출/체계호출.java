    public int програм_пауза(Процес_вриједност актуелно_Процес, int 새끝) {
        int 이전끝 = актуелно_Процес.програм_пауза();
        if (새끝 == 0) {
            return 이전끝;
        }
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            return -12;
        }
        int 첫쪽 = 이전끝 / страница_менаџер.величина_странице;
        int 끝쪽 = (새끝 + страница_менаџер.величина_странице - 1) / страница_менаџер.величина_странице;
        if (새끝 > 이전끝) {
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int адреса = индекс * страница_менаџер.величина_странице;
                try {
                    쪽관리.바이트읽기(актуелно_Процес.адреса_простор(), адреса);
                } catch (IllegalStateException ГРЕШКА) {
                    쪽관리.мапирати_страница(актуелно_Процес.адреса_простор(), адреса, true);
                }
            }
        }
        актуелно_Процес.скуп_програм_пауза(새끝);
        return 새끝;
    }

    public int 프로그램끝늘리기(Процес_вриједност актуелно_Процес, int 증가량) {
        int 이전끝 = актуелно_Процес.програм_пауза();
        int ИСХОД = програм_пауза(актуелно_Процес, 이전끝 + 증가량);
        return ИСХОД < 0 ? ИСХОД : 이전끝;
    }

