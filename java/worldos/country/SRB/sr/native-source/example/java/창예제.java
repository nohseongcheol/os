import 한국어.자체.Прозор;
import 한국어.자체.Натпис;
import 한국어.자체.입력칸;
import 한국어.자체.дугме;
import 한국어.자체.화면일정;
import 한국어.자체.Излаз;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing Прозор: sr 입력 → дугме → 안내 Текст 갱신. */
public class 창예제 implements 실행할일, 동작받이 {
    private Прозор 인사창;
    private 입력칸 이름입력;
    private Натпис 인사말;
    private int 인사횟수;

    public void 창열기() {
        인사창 = new Прозор("sr Swing", 460, 300);
        인사창.담기(new Натпис("sr", 20, 20, 420, 28));
        이름입력 = new 입력칸("sr", 20, 64, 420, 30);
        인사말 = new Натпис("sr", 20, 152, 420, 28);
        인사창.담기(이름입력);
        인사창.담기(new дугме("인사하기", 20, 108, 180, 32, this));
        인사창.담기(인사말);
        인사창.담기(new Натпис("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.보이기();
        Излаз.줄쓰기("GUI 예제 준비: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.글쓰기("sr, " + 이름입력.글읽기() + "님! (" + 인사횟수 + ")");
        Излаз.줄쓰기("GUI 인사: " + 인사말.글읽기());
    }

    public void Изврши() { 창열기(); }
    public void 동작받기(동작알림 알림) {
        Излаз.줄쓰기("радња 알림: " + 알림.명령글());
        인사하기();
    }
    public static void Покрени() {
        화면일정.나중에실행(new 창예제());
    }
}
