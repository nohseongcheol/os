/** 게스트 інструменти 공통 Вивід 및 ASCII файл Назва процес_значення_запис. */
public final class 자바도구 {
    /** UTF-8 байт_значення 배열을 같은 배열의 UTF-16 단위로 바꾼다. 잘못된 입력은 відхилити_значення. */
    static int 원문해독(int[] дані, int 길이) {
        int Читання = 0, Запис = 0;
        if (길이 >= 3 && дані[0] == 239 && дані[1] == 187 && дані[2] == 191) Читання = 3;
        while (Читання < 길이) {
            int значення = дані[Читання++], 수 = 0, 최소 = 0;
            if (значення >= 194 && значення <= 223) { 수 = 1; 최소 = 128; значення &= 31; }
            else if (значення >= 224 && значення <= 239) { 수 = 2; 최소 = 2048; значення &= 15; }
            else if (значення >= 240 && значення <= 244) { 수 = 3; 최소 = 65536; значення &= 7; }
            else if (значення >= 128 || значення < 0) return -1;
            if (수 > 길이 - Читання) return -1;
            for (int i = 0; i < 수; i++) {
                int Далі_елемент = дані[Читання++]; if ((Далі_елемент & 192) != 128) return -1;
                значення = (значення << 6) | (Далі_елемент & 63);
            }
            if (значення < 최소 || значення > 0x10ffff || (значення >= 0xd800 && значення <= 0xdfff)) return -1;
            if (значення >= 65536) { значення -= 65536; дані[Запис++] = 0xd800 | (значення >> 10); дані[Запис++] = 0xdc00 | (значення & 1023); }
            else дані[Запис++] = значення;
        }
        return Запис;
    }
    static void 수쓰기(int значення) {
        if (значення < 0) простір_користувача.записування_символ_значення('-'); else значення = -значення;
        int індекс_розташування = 1000000000;
        boolean запустити = false;
        while (індекс_розташування != 0) {
            int 수 = -(значення / індекс_розташування);
            if (수 != 0 || запустити || індекс_розташування == 1) { простір_користувача.записування_символ_значення('0' + 수); запустити = true; }
            значення %= індекс_розташування; індекс_розташування /= 10;
        }
    }
    static int Назва(int[] місце_значення, String 원본) {
        if (원본.length() >= місце_значення.length) return -1;
        for (int 수 = 0; 수 < місце_значення.length; 수++) місце_значення[수] = 수 < 원본.length() ? 원본.charAt(수) : 0;
        return 원본.length();
    }
    static boolean 같음(String 가, String 나) {
        if (가.length() != 나.length()) return false;
        for (int 수 = 0; 수 < 가.length(); 수++) if (가.charAt(수) != 나.charAt(수)) return false;
        return true;
    }
}
