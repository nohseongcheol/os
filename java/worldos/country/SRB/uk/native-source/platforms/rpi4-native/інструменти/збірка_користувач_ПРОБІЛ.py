"""독립된 своє ABI ELF64와 로더 відхилити_значення випробування 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from 파이썬빌드 import 파이썬만들기
from 자바라이브러리빌드 import 자바라이브러리만들기
from 시언어번역기빌드 import 시언어번역기만들기


def Створення_користувач_ПРОБІЛ(корінь_шлях, репозиторій_шлях, 시언어번역기, 시플플번역기, 연결편집기, Архів_інструмент, конфігурація_служба_фонового_передавання_файлів, Виконати_команда):
    конфігурація_служба_фонового_передавання_файлів = [Настройки_значення for Настройки_значення in конфігурація_служба_фонового_передавання_файлів if Настройки_значення != '-mgeneral-regs-only']
    збірка_шлях = корінь_шлях / 'build'
    출력결과 = збірка_шлях / 'user'
    출력결과.mkdir(exist_ok=True)
    원본자료 = корінь_шлях / 'простір_користувача'
    포직스경로 = репозиторій_шлях / 'posix-kor/arm64-native'
    містити_шлях = ['-I', 원본자료, '-I', 포직스경로 / 'оголошення', '-I', 출력결과]
    for компілятор_інструмент, 추가영역, шлях, Назва in [
            (시언어번역기, [], 원본자료 / 'запустити.S', 'start.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'Виконати_команда.c', 'runtime.o'),
            (시언어번역기, ['-std=c11'], 포직스경로 / 'користувач_міст.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / 'ПрикладФайлу.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '통신예제.cpp', 'network.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / '보호시험.c', 'fault.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'Редактор.c', 'vi.o')]:
        Виконати_команда([компілятор_інструмент] + конфігурація_служба_фонового_передавання_файлів + 추가영역 + містити_шлях + ['-Wall', '-Wextra', '-Werror', '-c', шлях, '-o', 출력결과 / Назва])
    Виконати_команда([Архів_інструмент, 'rcs', збірка_шлях / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for Назва in ('demo', 'fault', 'network', 'vi'):
        Виконати_команда([연결편집기, '-T', 원본자료 / 'схема_компонування.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (Назва + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (Назва + '.o'), збірка_шлях / 'libposix-kor-user.a'])
    자바라이브러리만들기(корінь_шлях, Виконати_команда)
    # 기존 своє Java компілятор/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(збірка_шлях)) as 작업경로:
        Клас_шлях = Path(작업경로)
        Виконати_команда(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', Клас_шлях, '-sourcepath', Клас_шлях, '-d', Клас_шлях] +
            [дані_посада for дані_посада in sorted((репозиторій_шлях / 'os/простір_користувача/자바').glob('*.java')) if дані_посада.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        Виконати_команда(['sh', репозиторій_шлях / 'compiler/미리번역.sh', '--entry', 'інструмент_запис.запустити',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(Клас_шлях.glob('*.class')))
    압축해제경로 = корінь_шлях / 'vendor/uzlib'
    for шлях, Назва in [(출력결과 / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'набір.c', 'jar.o')] + [(압축해제경로 / (Назва + '.c'), Назва + '.o') for Назва in ('tinflate', 'crc32', 'adler32')]:
        Виконати_команда([시언어번역기] + конфігурація_служба_фонового_передавання_файлів + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + містити_шлях + ['-c', шлях, '-o', 출력결과 / Назва])
    Виконати_команда([연결편집기, '-T', 원본자료 / 'схема_компонування.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / Назва for Назва in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(корінь_шлях, 시언어번역기, 연결편집기)
    시언어번역기만들기(корінь_шлях, репозиторій_шлях, 시언어번역기, 연결편집기, конфігурація_служба_фонового_передавання_файлів, Виконати_команда)
    유효함 = (출력결과 / 'demo.elf').read_bytes()
    програма_Заголовок_Зміщена_копія = struct.unpack_from('<Q', 유효함, 32)[0]
    Заголовок_список = [програма_Заголовок_Зміщена_копія + 개수 * 56 for 개수 in range(struct.unpack_from('<H', 유효함, 56)[0])]
    적재구획 = [дані_посада for дані_посада in Заголовок_список if struct.unpack_from('<I', 유효함, дані_посада)[0] == 1]
    текст, дані = 적재구획[:2]
    команда_адреса = struct.unpack_from('<Q', 유효함, текст + 16)[0]
    дані_адреса = struct.unpack_from('<Q', 유효함, дані + 16)[0]
    호출규약 = 유효함.index(b'JKOROS\0')
    시험사례 = [('empty', b''), ('short', 유효함[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', команда_адреса + 1), ('data-entry', 24, 'Q', дані_адреса),
               ('outside-file', текст + 32, 'Q', len(유효함) + 1), ('short-memory', текст + 40, 'Q', 1),
               ('kernel-address', текст + 16, 'Q', 0x80000), ('memory-overflow', текст + 40, 'Q', 2**64 - 1),
               ('writable-code', текст + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', текст, 'I', 2),
               ('unaligned-load', текст + 16, 'Q', команда_адреса + 8),
               ('overlap', дані + 16, 'Q', команда_адреса)]
    for Назва, Зміщена_копія_значення, формат_932e03c8, значення in 수정사항:
        바뀐자료 = bytearray(유효함); struct.pack_into('<' + формат_932e03c8, 바뀐자료, Зміщена_копія_значення, значення)
        시험사례.append((Назва, bytes(바뀐자료)))
    탑재덩이들 = [(Назва.replace('-', '_'), 출력결과 / (Назва + '.elf')) for Назва in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for Інформування_індекс, (Назва, вміст_пакета_дані) in enumerate(시험사례):
        шлях = 출력결과 / ('invalid-{}.elf'.format(Назва)); шлях.write_bytes(вміст_пакета_дані)
        탑재덩이들.append(('invalid_{}'.format(Інформування_індекс), шлях))
    збірка, Заголовок_значення = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for Назва, шлях in 탑재덩이들:
        символ_значення = 'user_blob_' + Назва
        크기목록[Назва] = шлях.stat().st_size
        # 생성한 точка_значення 경로만 넣어 프로젝트 경로의 공백/Цитування 영향을 피한다.
        збірка += ['.balign 16', '.global ' + символ_значення, символ_значення + ':', '.incbin "{}"'.format(шлях.relative_to(корінь_шлях))]
        Заголовок_значення.append('extern const unsigned char {}[];'.format(символ_значення))
    збірка.append('.section .note.GNU-stack,"",%progbits')
    Заголовок_значення += ['static const програма 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    Заголовок_значення += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    Заголовок_значення += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    Заголовок_значення += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], метод_режим) for метод_режим in (0, 1)]
    Заголовок_значення += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    Заголовок_значення += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    Заголовок_значення += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    Заголовок_значення += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    Заголовок_значення += ['};', 'static const програма 잘못된실행항목들[] = {']
    Заголовок_значення += ['{user_blob_invalid_%d, %d, 0},' % (순번, len(вміст_пакета_дані)) for 순번, (_, вміст_пакета_дані) in enumerate(시험사례)]
    Заголовок_значення += ['};']
    (збірка_шлях / 'programs.S').write_text('\n'.join(збірка) + '\n')
    (збірка_шлях / 'programs.h').write_text('\n'.join(Заголовок_значення) + '\n')
    (출력결과 / 'invalid-cases.txt').write_text('\n'.join(Назва for Назва, _ in 시험사례) + '\n')
    Виконати_команда([시언어번역기] + конфігурація_служба_фонового_передавання_файлів + ['-c', збірка_шлях / 'programs.S', '-o', збірка_шлях / 'programs.o'])
