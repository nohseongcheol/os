#!/usr/bin/env python3
"""оголошення_4f4f026b 고유번호와 UTF-8 байт_значення 위치로 своє C 이름을 옮기는 일회성 이행 інструменти.

зовнішній_значення 구조체의 멤버, рядок_значення, C 표준 функція_значення, 이식 규약은 보존한다.
입력은 змінювати_значення 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

Дії_корінь = Path(__file__).resolve().parents[1]

def Виконати_команда():
    Аналіз_значення = json.loads((Дії_корінь/'build/한국어화/시언어분석.json').read_text())
    if Аналіз_значення['ПОМИЛКА']: raise SystemExit('Аналіз_значення 오류를 먼저 해결해야 합니다.')
    ім_я_таблиця = json.loads((Дії_корінь/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((Дії_корінь/'명명/규격이름.json').read_text()))
    оголошення_таблиця = Аналіз_значення['оголошення_4f4f026b']
    바꿀선언 = {고유:ім_я_таблиця[запис_значення_962f286b['Назва']] for 고유,запис_значення_962f286b in оголошення_таблиця.items()
                if запис_значення_962f286b['Назва'] in ім_я_таблиця and запис_значення_962f286b['Назва'] not in 규격}
    зв_язок_таблиця = {запис_значення_962f286b['Назва']:ім_я_таблиця[запис_значення_962f286b['Назва']] for запис_значення_962f286b in оголошення_таблиця.values()
              if запис_значення_962f286b.get('З_єднання')==4 and запис_значення_962f286b['종류'] in (8,9)
              and запис_значення_962f286b['Назва'] in ім_я_таблиця and запис_значення_962f286b['Назва'] not in 규격}
    # генерувати AOT C·어셈블리·공개 SDK가 공유하는 바이너리 З_єднання 이름만 유지한다.
    머리 = ['/* українська джерело_дерево 이름과 기존 комп_ютер З_єднання контракт_значення. 자동 генерувати: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(зв_язок_таблиця.items())]
    머리 += ['#endif','']
    (Дії_корінь/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Зміни_список = defaultdict(dict)
    for файл,Зміщена_копія_значення,Назва,고유 in Аналіз_значення['довідка']:
        if 고유 in 바꿀선언:
            Зміни_список[файл][Зміщена_копія_значення] = (Назва,바꿀선언[고유])
    журнал_запис = ['файл\t원래바이트위치\t이전이름\t한국어이름']
    пропустити_значення = []
    for файл,змінювати_значення in Зміни_список.items():
        шлях = Path(файл); 원본 = шлях.read_bytes(); дані = 원본
        for Зміщена_копія_значення,(옛이름,새이름) in sorted(змінювати_значення.items(),reverse=True):
            끝 = Зміщена_копія_значення+len(옛이름.encode())
            if 원본[Зміщена_копія_значення:끝] != 옛이름.encode():
                пропустити_значення.append((str(шлях.relative_to(Дії_корінь)),Зміщена_копія_значення,옛이름));continue
            дані = дані[:Зміщена_копія_значення]+새이름.encode()+дані[끝:]
            журнал_запис.append('{}\t{}\t{}\t{}'.format(шлях.relative_to(Дії_корінь),Зміщена_копія_значення,옛이름,새이름))
        шлях.write_bytes(дані)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макрос_значення = {запис_значення_962f286b['Назва']:ім_я_таблиця[запис_значення_962f286b['Назва']] for запис_значення_962f286b in оголошення_таблиця.values()
              if запис_значення_962f286b['종류']==501 and запис_значення_962f286b['Назва'] in ім_я_таблиця and запис_значення_962f286b['Назва'] not in 규격}
    for шлях in sorted({Path(запис_значення_962f286b['файл']) for запис_значення_962f286b in оголошення_таблиця.values()}):
        рядок_список = шлях.read_text().splitlines(True); 이어짐 = False
        for індекс,рядок_введення in enumerate(рядок_список):
            전처리 = 이어짐 or bool(re.match(r'\s*#',рядок_введення))
            이어짐 = 전처리 and рядок_введення.rstrip().endswith('\\')
            if 전처리:
                таблиця_підстановки = ім_я_таблиця if re.match(r'\s*#\s*define\b',рядок_введення) or 이어짐 else макрос_значення
                рядок_список[індекс] = 낱말.sub(lambda 맞음: таблиця_підстановки.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],рядок_введення)
        шлях.write_text(''.join(рядок_список))
    # 각 своє Перекласти_джерело 단위에만 연결표를 넣는다. зовнішній_значення 배포본에는 전파하지 않는다.
    for шлях in sorted({Path(запис_значення_962f286b['файл']) for запис_значення_962f286b in оголошення_таблиця.values()}):
        if шлях.suffix not in ('.c','.cpp'):continue
        точка_значення = '../' * len(шлях.relative_to(Дії_корінь).parts[:-1]) + '명명/기계연결이름.h'
        шлях.write_text('#include "'+точка_значення+'"\n'+шлях.read_text())
    (Дії_корінь/'명명/시언어이름대응.tsv').write_text('\n'.join(журнал_запис)+'\n')
    (Дії_корінь/'build/한국어화/전처리참조.json').write_text(json.dumps(пропустити_значення,ensure_ascii=False,indent=2)+'\n')
    print('змінювати_значення',len(журнал_запис)-1,'전처리 재검토',len(пропустити_значення),'комп_ютер З_єднання',len(зв_язок_таблиця))

if __name__=='__main__': Виконати_команда()
