package Сербія.JSrbOS.Ядро;

import Сербія.JSrbOS.Пам_ять_область.기억공간관리자;
import Сербія.JSrbOS.Пам_ять_область.쪽관리자;
import Сербія.JSrbOS.입력.입력관리자;
import Сербія.JSrbOS.작업.процес_значення;
import Сербія.JSrbOS.작업.планувальник;
import Сербія.JSrbOS.системний_виклик.системний_виклик;
import Сербія.JSrbOS.файлова_система.파일서술자표;
import Сербія.JSrbOS.файлова_система.файлова_система;

/** Java 관리 커널의 조립과 시작을 담당한다. */
public final class Ядро {
    private final обладнання_значення пристрій_значення;
    private final 기억공간관리자 Пам_ять_область = new 기억공간관리자(32 * 1024 * 1024);
    private final 쪽관리자 쪽관리 = new 쪽관리자();
    private final файлова_система файлова_система = new файлова_система();
    private final планувальник планувальник = new планувальник(쪽관리);
    private final 입력관리자 입력관리 = new 입력관리자(256);
    private final процес_значення 첫과정;
    private final системний_виклик системний_виклик;

    public Ядро(обладнання_значення пристрій_значення) {
        this.пристрій_значення = пристрій_значення;
        첫과정 = планувальник.첫과정(new 파일서술자표(файлова_система));
        системний_виклик = new системний_виклик(файлова_система, 쪽관리, планувальник, пристрій_значення, 입력관리);
    }

    public void запустити() {
        пристрій_значення.직렬출력("=== JSrbOS 관리 ядро_значення ===\n");
    }

    public void Виконати_крок() {
        пристрій_значення.중앙처리장치멈춤();
    }

    public 기억공간관리자 Пам_ять_область() {
        return Пам_ять_область;
    }

    public 쪽관리자 쪽관리() {
        return 쪽관리;
    }

    public файлова_система файлова_система() {
        return файлова_система;
    }

    public планувальник планувальник() {
        return планувальник;
    }

    public 입력관리자 입력관리() {
        return 입력관리;
    }

    public процес_значення 첫과정() {
        return 첫과정;
    }

    public системний_виклик системний_виклик() {
        return системний_виклик;
    }
}
