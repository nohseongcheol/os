    public int програма_перерва(процес_значення чинний_процес, int 새끝) {
        int 이전끝 = чинний_процес.програма_перерва();
        if (새끝 == 0) {
            return 이전끝;
        }
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            return -12;
        }
        int 첫쪽 = 이전끝 / 쪽관리자.розмір_сторінки;
        int 끝쪽 = (새끝 + 쪽관리자.розмір_сторінки - 1) / 쪽관리자.розмір_сторінки;
        if (새끝 > 이전끝) {
            for (int індекс = 첫쪽; індекс < 끝쪽; індекс++) {
                int Адреса = індекс * 쪽관리자.розмір_сторінки;
                try {
                    쪽관리.바이트읽기(чинний_процес.адреса_ПРОБІЛ(), Адреса);
                } catch (IllegalStateException ПОМИЛКА) {
                    쪽관리.карта_сторінка(чинний_процес.адреса_ПРОБІЛ(), Адреса, true);
                }
            }
        }
        чинний_процес.група_програма_перерва(새끝);
        return 새끝;
    }

    public int 프로그램끝늘리기(процес_значення чинний_процес, int крок_приросту_сума) {
        int 이전끝 = чинний_процес.програма_перерва();
        int результат = програма_перерва(чинний_процес, 이전끝 + крок_приросту_сума);
        return результат < 0 ? результат : 이전끝;
    }

