    public boolean ІТ_відділ_Термінал(процес_значення чинний_процес, int 서술자) {
        Файл_відомості Відомості_про_систему = чинний_процес.파일서술자().Відомості_про_систему(서술자);
        return Відомості_про_систему != null && (Відомості_про_систему.형태() & 0170000) == 0020000;
    }

    public int керування_файлом(процес_значення чинний_процес, int 서술자, int команда, int параметр_аргумент) {
        if (команда == 0) {
            return чинний_процес.파일서술자().복제서술자(서술자, параметр_аргумент);
        }
        if (команда == 1) {
            return чинний_процес.파일서술자().실행시닫기값(서술자);
        }
        if (команда == 2) {
            return чинний_процес.파일서술자().실행시닫기설정(서술자, (параметр_аргумент & 1) != 0);
        }
        if (команда == 3) {
            return чинний_процес.파일서술자().Відомості_про_систему(서술자) == null ? -9 : лише_для_читання_позначка;
        }
        if (команда == 4) {
            return параметр_аргумент == лише_для_читання_позначка ? 0 : -30;
        }
        return -22;
    }

