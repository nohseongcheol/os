    public int Виконати_команда(процес_значення чинний_процес, byte[] 실행파일, String[] параметр_аргумент, String[] середовище) {
        실행파일적재기.фото фото_значення;
        try {
            фото_значення = завантажувач.검사(실행파일);
        } catch (IllegalArgumentException ПОМИЛКА) {
            return -8;
        }
        if (параметр_аргумент == null || середовище == null || параметр_аргумент.length > 16 || середовище.length > 16) {
            return -7;
        }
        for (실행파일적재기.розділ_значення_366e0bfa розділ_значення_366e0bfa : фото_значення.구역들()) {
            if ((розділ_значення_366e0bfa.позначка_значення() & 2) == 0 || розділ_значення_366e0bfa.Розмір() == 0) {
                continue;
            }
            int 첫쪽 = розділ_значення_366e0bfa.Адреса() / 쪽관리자.розмір_сторінки;
            int 끝쪽 = (розділ_значення_366e0bfa.Адреса() + розділ_значення_366e0bfa.Розмір() + 쪽관리자.розмір_сторінки - 1) / 쪽관리자.розмір_сторінки;
            for (int індекс = 첫쪽; індекс < 끝쪽; індекс++) {
                int Адреса = індекс * 쪽관리자.розмір_сторінки;
                try {
                    쪽관리.바이트읽기(чинний_процес.адреса_ПРОБІЛ(), Адреса);
                    쪽관리.Приховано_діапазон_записування(чинний_процес.адреса_ПРОБІЛ(), Адреса, 쪽관리자.розмір_сторінки);
                } catch (IllegalStateException ПОМИЛКА) {
                    쪽관리.карта_сторінка(чинний_процес.адреса_ПРОБІЛ(), Адреса, true);
                }
            }
            for (int індекс = 0; індекс < розділ_значення_366e0bfa.Розмір(); індекс++) {
                byte значення = розділ_значення_366e0bfa.종류() == 8 ? 0 : 실행파일[розділ_значення_366e0bfa.Файл_посада() + індекс];
                쪽관리.записування_байт_значення(чинний_процес.адреса_ПРОБІЛ(), розділ_значення_366e0bfa.Адреса() + індекс, значення);
            }
        }
        чинний_процес.실행문맥설정(фото_значення.ПУСК_адреса(), параметр_аргумент, середовище);
        чинний_процес.파일서술자().실행시닫기();
        return 0;
    }

