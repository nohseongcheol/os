package Сербія.JSrbOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Сербія.JSrbOS.Пам_ять_область.쪽관리자;
import Сербія.JSrbOS.файлова_система.파일서술자표;

/** процес_значення 식별자와 라운드로빈 Готувати 대기열을 관리한다. */
public final class планувальник {
    private final 쪽관리자 쪽관리;
    private final Map<Integer, процес_значення> список_процесу = new HashMap<Integer, процес_значення>();
    private final Queue<процес_значення> 준비대기열 = new ArrayDeque<процес_значення>();
    private int Далі_ідентифікатор = 1;

    public планувальник(쪽관리자 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public процес_значення 첫과정(파일서술자표 파일서술자) {
        процес_значення 새과정 = new процес_значення(виділяти_ідентифікатор(), 0, 쪽관리.새주소공간(), 파일서술자);
        список_процесу.put(Integer.valueOf(새과정.ідентифікатор_значення()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public процес_значення клонувати_значення(процес_значення батьківський_значення) {
        процес_значення дитина_значення = new процес_значення(
                виділяти_ідентифікатор(),
                батьківський_значення.ідентифікатор_значення(),
                쪽관리.쓰기시복사복제(батьківський_значення.адреса_ПРОБІЛ()),
                батьківський_значення.파일서술자().клонувати_значення());
        дитина_значення.група_програма_перерва(батьківський_значення.програма_перерва());
        список_процесу.put(Integer.valueOf(дитина_значення.ідентифікатор_значення()), дитина_значення);
        준비대기열.offer(дитина_значення);
        return дитина_значення;
    }

    public процес_значення Далі_процес() {
        int 검사수 = 준비대기열.size();
        for (int індекс = 0; індекс < 검사수; індекс++) {
            процес_значення Далі_елемент = 준비대기열.poll();
            if (Далі_елемент != null && (Далі_елемент.Стан_значення() == процес_Стан.Готувати || Далі_елемент.Стан_значення() == процес_Стан.Виконати_команда)) {
                Далі_елемент.група_Стан(процес_Стан.Виконати_команда);
                준비대기열.offer(Далі_елемент);
                return Далі_елемент;
            }
        }
        return null;
    }

    public int 자식기다리기(процес_значення батьківський_значення, int дитина_ідентифікатор, boolean 기다리지않음) {
        for (процес_значення кандидат : список_процесу.values()) {
            if (кандидат.батьківський_ідентифікатор() != батьківський_значення.ідентифікатор_значення()) {
                continue;
            }
            if (дитина_ідентифікатор > 0 && кандидат.ідентифікатор_значення() != дитина_ідентифікатор) {
                continue;
            }
            if (кандидат.Стан_значення() == процес_Стан.Вийти_програма) {
                int результат = (кандидат.Вийти_код() & 0xff) << 8;
                список_процесу.remove(Integer.valueOf(кандидат.ідентифікатор_значення()));
                return результат;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public процес_значення Знайти_процес(int ідентифікатор_значення) {
        return список_процесу.get(Integer.valueOf(ідентифікатор_значення));
    }

    private int виділяти_ідентифікатор() {
        return Далі_ідентифікатор++;
    }
}
