import Português.자바.문자;

/** 다른 언어가 표준 출력으로 결과를 받을 número 있는 작은 Java ponto_de_entrada. */
public final class 문자명령 {
    public static void main(String[] argumentos) {
        if (argumentos.length != 1) {
            System.err.println("사용법: 문자명령 cadeia_VALOR");
            System.exit(2);
        }
        System.out.println(문자.ponto_de_código_CONT_NÚM(argumentos[0]));
    }
}
