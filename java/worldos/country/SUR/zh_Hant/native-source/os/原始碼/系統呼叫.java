/** 由 int 0x80 閘呼叫；存取前檢查所有使用者指標與長度。 */
public final class 系統呼叫 {
    static int[] 臨時緩衝區 = new int[1024];

    static int 陣列長度(int 地址) {
        if (!執行管理.裁剪(地址, 4)) return -14;
        int 長度 = 執行管理.數(地址);
        if (長度 < 0 || 長度 > (執行管理.用戶結束 - 地址 - 4) / 4) return -14;
        return 長度;
    }

    public static int 程序值條目(int 編號, int 首位操作數, int 第二操作數, int 第三操作數, int 第四操作數, int 第五操作數) {
        if (編號 == 30) return 檔案描述子管理.打開檔案(首位操作數, 第二操作數, 第三操作數);
        if (編號 == 31) return 檔案描述子管理.讀取檔案(首位操作數, 第二操作數, 第三操作數);
        if (編號 == 32) return 檔案描述子管理.寫入檔案(首位操作數, 第二操作數, 第三操作數);
        if (編號 == 33) return 檔案描述子管理.關閉檔案(首位操作數);
        if (編號 == 34) return 檔案描述子管理.尋道檔案(首位操作數, 第二操作數, 第三操作數);
        if (編號 == 35) return 檔案描述子管理.複製副本描述符(首位操作數, 0, false, 0);
        if (編號 == 36) return 檔案描述子管理.複製副本描述符(首位操作數, 第二操作數, true, 0);
        if (編號 == 37) return 檔案描述子管理.讀取檔案運行狀態(首位操作數, 第二操作數);
        if (編號 == 38) return 檔案描述子管理.移除檔案條目名稱(首位操作數);
        if (編號 == 39) return 檔案描述子管理.設定檔案長度(首位操作數, 第二操作數);
        if (編號 == 40) return 檔案描述子管理.控制描述符(首位操作數, 第二操作數, 第三操作數);
        if (編號 == 41) return 檔案描述子管理.創建端點(首位操作數, 第二操作數, 第三操作數);
        if (編號 == 42) return 檔案描述子管理.綁定地址(首位操作數, 第二操作數, 第三操作數);
        if (編號 == 43) return 檔案描述子管理.發送數據報資料(首位操作數, 第二操作數, 第三操作數, 第四操作數, 第五操作數);
        if (編號 == 44) return 檔案描述子管理.接收數據報資料(首位操作數, 第二操作數, 第三操作數, 第四操作數, 第五操作數);
        if (編號 == 45) return 檔案描述子管理.讀取通訊端地址(首位操作數, 第二操作數, 第三操作數);
        if (編號 == 46) return 檔案描述子管理.設定接收超時(首位操作數, 第二操作數);
        if (編號 == 47) {
            int 描述符值 = 檔案描述子管理.查找描述符(首位操作數);
            if (描述符值 < 0) return -9;
            if (檔案描述子管理.種類值[描述符值] != 2) return -22;
            return 檔案持久化.同步化();
        }
        if (編號 == 1) {
            int 長度 = 陣列長度(首位操作數);
            if (長度 < 0) return 長度;
            if (長度 > 4096) return -90;
            for (int 字元值 = 0; 字元值 < 長度; 字元值++) 字元終端.字元(執行管理.數(首位操作數 + 4 + 字元值 * 4) & 65535);
            return 長度;
        }
        if (編號 == 2) return 執行管理.實際參數個數;
        if (編號 == 3) return 首位操作數 >= 0 && 首位操作數 < 執行管理.實際參數個數 ? 執行管理.實際參數地址[首位操作數] : 0;
        if (編號 == 10) return 通信網絡.打開(首位操作數);
        if (編號 == 11) {
            int 長度 = 陣列長度(第四操作數);
            if (長度 < 0) return 長度;
            if (第五操作數 < 0 || 第五操作數 > 長度 || 第五操作數 > 1024) return -90;
            for (int 位置 = 0; 位置 < 第五操作數; 位置++) 臨時緩衝區[位置] = 執行管理.數(第四操作數 + 4 + 位置 * 4) & 255;
            return 通信網絡.發送(首位操作數, 第二操作數, 第三操作數, 臨時緩衝區, 第五操作數);
        }
        if (編號 == 12) {
            int 長度 = 陣列長度(第二操作數);
            if (長度 < 0) return 長度;
            if (第三操作數 < 0 || 第三操作數 > 2000) return -22;
            int 結果 = 通信網絡.接收(首位操作數, 臨時緩衝區, 長度 < 1024 ? 長度 : 1024, 第三操作數);
            if (結果 >= 0) for (int 位置 = 0; 位置 < 結果; 位置++) 執行管理.寫入編號(第二操作數 + 4 + 位置 * 4, 臨時緩衝區[位置]);
            return 結果;
        }
        if (編號 == 13) return 通信網絡.關閉(首位操作數);
        if (編號 == 14) return 通信網絡.自有對象地址;
        if (編號 == 15) return 通信網絡.對端地址(首位操作數);
        if (編號 == 16) return 通信網絡.對端埠編號(首位操作數);
        if (編號 == 22) {
            if (首位操作數 < 0 || 首位操作數 > 65535) return -22;
            字元終端.字元(首位操作數); return 1;
        }
        if (編號 == 20 || 編號 == 21) {
            int 名稱大小 = 陣列長度(首位操作數), 資料大小 = 陣列長度(第二操作數);
            if (名稱大小 < 0 || 資料大小 < 0) return -14;
            if (名稱大小 < 1 || 名稱大小 > 64) return -22;
            int 長度 = 0;
            while (長度 < 名稱大小 && 執行管理.數(首位操作數 + 4 + 長度 * 4) != 0) {
                主記憶體檔案系統.名稱[長度] = 執行管理.數(首位操作數 + 4 + 長度 * 4);
                長度++;
            }
            if (!主記憶體檔案系統.檢查名稱(主記憶體檔案系統.名稱, 長度)) return -22;
            if (編號 == 20) {
                int 檔案 = 主記憶體檔案系統.查找條目(主記憶體檔案系統.名稱, 長度);
                if (檔案 < 0) return 檔案;
                int 大小 = 主記憶體檔案系統.大小列表[檔案];
                if (大小 > 資料大小) return -90;
                int 地址 = 設備.檔案記憶體() + 檔案 * 主記憶體檔案系統.最大大小;
                for (int 數 = 0; 數 < 大小; 數++) 執行管理.寫入編號(第二操作數 + 4 + 數 * 4, 設備.讀取記憶體(地址 + 數));
                return 大小;
            }
            if (第三操作數 < 0 || 第三操作數 > 資料大小) return -22;
            if (第三操作數 > 主記憶體檔案系統.最大大小) return -90;
            for (int 數 = 0; 數 < 第三操作數; 數++) 主記憶體檔案系統.編輯值[數] = 執行管理.數(第二操作數 + 4 + 數 * 4) & 255;
            return 主記憶體檔案系統.存儲值(主記憶體檔案系統.名稱, 長度, 主記憶體檔案系統.編輯值, 第三操作數);
        }
        return -38;
    }
}
