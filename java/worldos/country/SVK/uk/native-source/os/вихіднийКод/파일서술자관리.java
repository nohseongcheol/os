    static int надсилати_дейтаграма_дані(int 서술자, int дані_адреса, int 길이, int Налаштування, int 요청주소) {
        int 기술 = 종단점기술(서술자);
        if (기술 < 0) return 기술;
        if (Налаштування != 0) return -95;
        if (길이 < 0 || 길이 > 1024) return -90;
        if (길이 != 0 && !실행관리.кліп(дані_адреса, 길이)) return -14;
        if (!실행관리.кліп(요청주소, 8)) return -14;
        int Адреса = 실행관리.수(요청주소);
        int результат = перевіряти_адреса(Адреса, 실행관리.수(요청주소 + 4));
        if (результат < 0) return результат;
        int номер_порту = пристрій_значення.기억읽기(Адреса + 2) << 8 | пристрій_значення.기억읽기(Адреса + 3);
        if (номер_порту == 0) return -22;
        результат = Авто_зв_язувати(기술);
        if (результат < 0) return результат;
        for (int індекс = 0; індекс < 길이; індекс++) передача_дані[індекс] = пристрій_значення.기억읽기(дані_адреса + індекс);
        return мережа_Стіс.надсилати(мережа_маркер[기술], адреса_32(Адреса + 4), номер_порту, передача_дані, 길이);
    }
    static void записування_адреса(int Адреса, int 길이, int ідентифікатор_мережі, int номер_порту) {
        for (int індекс = 0; індекс < 길이 && індекс < 16; індекс++) {
            int значення = 0;
            if (індекс == 0) значення = 2;
            if (індекс == 2) значення = номер_порту >>> 8;
            if (індекс == 3) значення = номер_порту;
            if (індекс >= 4 && індекс < 8) значення = ідентифікатор_мережі >>> (56 - індекс * 8);
            пристрій_значення.записування_Пам_ять(Адреса + індекс, значення & 255);
        }
    }
    static int отримувати_дейтаграма_дані(int 서술자, int дані_адреса, int 길이, int Налаштування, int 요청주소) {
        int 기술 = 종단점기술(서술자);
        if (기술 < 0) return 기술;
        if ((Налаштування & ~64) != 0) return -95;
        if (길이 < 0) return -22;
        if (길이 != 0 && !실행관리.кліп(дані_адреса, 길이)) return -14;
        int Адреса = 0, 주소길이주소 = 0, 주소길이 = 0;
        if (요청주소 != 0) {
            if (!실행관리.кліп(요청주소, 8)) return -14;
            Адреса = 실행관리.수(요청주소); 주소길이주소 = 실행관리.수(요청주소 + 4);
            if (Адреса != 0) {
                if (!실행관리.кліп(주소길이주소, 4)) return -14;
                주소길이 = 실행관리.수(주소길이주소);
                if (주소길이 < 0) return -22;
                if (!실행관리.кліп(Адреса, 주소길이 < 16 ? 주소길이 : 16)) return -14;
            }
        }
        int результат = Авто_зв_язувати(기술);
        if (результат < 0) return результат;
        int запустити = пристрій_значення.밀리초();
        while (true) {
            результат = мережа_Стіс.отримувати(мережа_маркер[기술], передача_дані, 1024, 0);
            if (результат != -11) break;
            if ((Налаштування & 64) != 0 || (відкрито_Настройки[기술] & 기다리지않기) != 0) return -11;
            if (수신대기밀리초[기술] > 0 && пристрій_значення.밀리초() - запустити >= 수신대기밀리초[기술]) return -11;
            if (пристрій_значення.사용자남은밀리초() <= 10) return -11;
            пристрій_значення.잠시양보();
        }
        if (результат < 0) return результат;
        if (результат > 길이) результат = 길이;
        for (int індекс = 0; індекс < результат; індекс++) пристрій_значення.записування_Пам_ять(дані_адреса + індекс, передача_дані[індекс]);
        if (Адреса != 0) {
            записування_адреса(Адреса, 주소길이, мережа_Стіс.точка_адреса(мережа_маркер[기술]), мережа_Стіс.точка_номер_порту(мережа_маркер[기술]));
            실행관리.수쓰기(주소길이주소, 16);
        }
        return результат;
    }
