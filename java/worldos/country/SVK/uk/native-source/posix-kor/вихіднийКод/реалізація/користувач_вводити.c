#include "호출경계.h"
extern int main(int 인수개수, char **аргумент_список);
static char аргумент_Пам_ять[2048];
static char *аргумент_список[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* чинний_елемент 커널의 argv는 Виконати_команда 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    аргумент_список[0] = "jkoros-app";
    int позиція = 0;
    for (int індекс = 0; індекс < 개수; індекс++) {
        const int *원본 = (const int *)jkoros_syscall(3, індекс, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        аргумент_список[індекс + 1] = аргумент_Пам_ять + позиція;
        for (int 칸 = 0; 칸 < 원본[0]; 칸++) {
            if (позиція >= 2047) return 126;
            аргумент_Пам_ять[позиція++] = 원본[칸 + 1];
        }
        аргумент_Пам_ять[позиція++] = 0;
    }
    аргумент_список[개수 + 1] = 0;
    return main(개수 + 1, аргумент_список);
}
