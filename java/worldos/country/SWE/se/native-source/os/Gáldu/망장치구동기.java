/** PCI RTL8139 (10ec:8139), 단일 송신 버퍼와 8KiB 수신 고리. 인터럽트 대신 폴링한다. */
public final class 망장치구동기 {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] 장치주소 = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int 위치) {
        장치.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | 위치);
        return 장치.입출력정수읽기(0xcfc);
    }

    static boolean 준비() {
        int 장치번호 = -1;
        for (int 번호 = 0; 번호 < 32; 번호++) {
            if (설정읽기(번호, 0) == 0x813910ec) { 장치번호 = 번호; break; }
        }
        if (장치번호 < 0) return false;
        int 기본 = 설정읽기(장치번호, 0x10);
        if ((기본 & 1) == 0 || (기본 & 0xfffffffc) < 0x100 || (기본 & 0xfffffffc) > 65535) return false;
        입출력기준주소 = 기본 & 0xfffc;
        int Gohččun = 설정읽기(장치번호, 4);
        장치.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        장치.입출력짧은수쓰기(0xcfc, Gohččun | 5); // I/O 및 bus master 허용, PCI 상태 비트는 건드리지 않음
        장치.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!재설정()) { 입출력기준주소 = 0; return false; }
        for (int 번호 = 0; 번호 < 6; 번호++) 장치주소[번호] = 장치.입출력바이트읽기(입출력기준주소 + 번호);
        return true;
    }

    static boolean 재설정() {
        장치.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int 시작 = 장치.밀리초();
        while ((장치.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (장치.밀리초() - 시작 > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        장치.입출력정수쓰기(입출력기준주소 + 0x30, 장치.통신기억());
        for (int 번호 = 0; 번호 < 4; 번호++) 장치.입출력정수쓰기(입출력기준주소 + 0x20 + 번호 * 4, 장치.통신기억() + 12288);
        장치.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        장치.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        장치.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        장치.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/방송, wrap 연속 저장, 8KiB
        장치.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int 보내기(int[] 자료, int 길이) {
        if (입출력기준주소 == 0) return -19;
        if (길이 < 14 || 길이 > 1514) return -90;
        int 상태포트 = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int 시작 = 장치.밀리초();
        while ((장치.입출력정수읽기(상태포트) & 0x2000) == 0)
            if (장치.밀리초() - 시작 > 100) return -110;
        int 크기 = 길이 < 60 ? 60 : 길이;
        for (int 번호 = 0; 번호 < 크기; 번호++)
            장치.기억쓰기(장치.통신기억() + 12288 + 번호, 번호 < 길이 ? 자료[번호] : 0);
        장치.입출력정수쓰기(상태포트, 크기 | 0x00080000);
        시작 = 장치.밀리초();
        while ((장치.입출력정수읽기(상태포트) & 0xe0008000) == 0)
            if (장치.밀리초() - 시작 > 100) return -110;
        if ((장치.입출력정수읽기(상태포트) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return 길이;
    }

    static int 받기(int[] 자료) {
        if (입출력기준주소 == 0) return 0;
        if ((장치.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!재설정()) 입출력기준주소 = 0;
            return 0;
        }
        if ((장치.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = 장치.통신기억() + 수신위치;
        int 상태 = 실행관리.짧은수(머리), 크기 = 실행관리.짧은수(머리 + 2);
        if (크기 == 0xfff0) return 0; // DMA 진행 중
        if (크기 < 4 || 크기 > 1518) {
            오류수++;
            if (!재설정()) 입출력기준주소 = 0;
            return 0;
        }
        int 길이 = 크기 - 4;
        if ((상태 & 1) != 0) {
            for (int 번호 = 0; 번호 < 길이; 번호++) 자료[번호] = 장치.기억읽기(머리 + 4 + 번호);
            수신수++;
        } else { 길이 = 0; 오류수++; }
        수신위치 = (수신위치 + 크기 + 4 + 3) & ~3;
        수신위치 &= 8191;
        장치.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        장치.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return 길이;
    }
}
