        for (int رقم = 0; رقم < حجم; رقم++) جهاز_قيمة.كتابة_ذاكرة(عنوان + رقم, بيانات[رقم]);
        for (int رقم = 0; رقم < 64; رقم++) 이름들[فهرس * 64 + رقم] = رقم < 길이 ? حرف_قيمة[رقم] : 0;
        يغير_الحجم_قائمة[فهرس] = حجم;
