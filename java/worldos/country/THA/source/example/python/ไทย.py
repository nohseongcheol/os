"""เอง 커널의 แฟ้ม·통신·화면 호출과 ไทย ข้อยกเว้น. 표준 이름은 이 연결부에서만 쓴다."""
import jkoros as ระบบปฏิบัติการ
import sys as รันไทม์

def ข้อความออก(*ค่า, แถบคั่น=" ", 끝="\n", **기존인수):
    # 기존 print의 sep/end 인수도 연결부에서 호환한다.
    if "sep" not in 기존인수: 기존인수["sep"] = แถบคั่น
    if "end" not in 기존인수: 기존인수["end"] = 끝
    print(*ค่า, **기존인수)

จํานวนเต็ม = int
명령인수 = รันไทม์.argv
다시시도오류 = 11

class ระบบ_ข้อผิดพลาด(OSError):
    def __init__(자신, ดัชนี, 설명="ระบบปฏิบัติการ 작업에 실패했습니다."):
        super().__init__(ดัชนี, 설명)
        자신.ดัชนี = ดัชนี
        자신.설명 = 설명

def 운영호출(ฟังก์ชัน_ค่า, *อาร์กิวเมนต์):
    try:
        return ฟังก์ชัน_ค่า(*อาร์กิวเมนต์)
    except OSError as ข้อผิดพลาด:
        ดัชนี = ข้อผิดพลาด.args[0] if ข้อผิดพลาด.args else 0
        raise ระบบ_ข้อผิดพลาด(ดัชนี)

def เข้ารหัส_ข้อความ(ข้อความ):
    return ข้อความ.encode("utf-8")

def 글해독(ข้อมูล):
    return ข้อมูล.decode("utf-8")

def 파일읽기(ชื่อ):
    return 운영호출(ระบบปฏิบัติการ.read, ชื่อ)

def 파일쓰기(ชื่อ, ข้อมูล):
    return 운영호출(ระบบปฏิบัติการ.write, ชื่อ, ข้อมูล)

def นําออก_แฟ้ม(ชื่อ):
    return 운영호출(ระบบปฏิบัติการ.remove, ชื่อ)

def เปิด_เดตาแกรม(หมายเลขพอร์ต):
    return 운영호출(ระบบปฏิบัติการ.udp_open, หมายเลขพอร์ต)

def ส่ง_เดตาแกรม(ปลายทาง, หมายเลขพอร์ต, ข้อมูล):
    return 운영호출(ระบบปฏิบัติการ.udp_send, ปลายทาง, หมายเลขพอร์ต, ข้อมูล)

def ส่ง_ภายนอก_เดตาแกรม(ปลายทาง, อีเมล, หมายเลขพอร์ต, ข้อมูล):
    return 운영호출(ระบบปฏิบัติการ.udp_sendto, ปลายทาง, อีเมล, หมายเลขพอร์ต, ข้อมูล)

def รับ_เดตาแกรม(ปลายทาง):
    return 운영호출(ระบบปฏิบัติการ.udp_recv, ปลายทาง)

def ปิด_เครือข่าย(ปลายทาง):
    return 운영호출(ระบบปฏิบัติการ.udp_close, ปลายทาง)

def วาด_สี่เหลี่ยมผืนผ้า(*อาร์กิวเมนต์):
    return 운영호출(ระบบปฏิบัติการ.rect, *อาร์กิวเมนต์)

def 화면크기():
    return 운영호출(ระบบปฏิบัติการ.screen_size)

def 그림기다리기():
    return 운영호출(ระบบปฏิบัติการ.wait_key)

밀리초 = ระบบปฏิบัติการ.ticks_ms
