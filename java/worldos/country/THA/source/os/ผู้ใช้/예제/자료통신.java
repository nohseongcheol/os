public final class 자료통신 {
    static int ตัวเลข_ค่า(String ข้อความ) {
        if (ข้อความ == null || ข้อความ.length() == 0) return -1;
        int ผลลัพธ์ = 0;
        for (int ดัชนี = 0; ดัชนี < ข้อความ.length(); ดัชนี++) {
            int ค่า = ข้อความ.charAt(ดัชนี) - '0';
            if (ค่า < 0 || ค่า > 9 || ผลลัพธ์ > 6553) return -1;
            ผลลัพธ์ = ผลลัพธ์ * 10 + ค่า;
            if (ผลลัพธ์ > 65535) return -1;
        }
        return ผลลัพธ์;
    }
    static int อีเมล(String ข้อความ) {
        if (ข้อความ == null) return 0;
        int ค่า = 0, ผลลัพธ์ = 0, 부분 = 0, 자릿수 = 0;
        for (int ดัชนี = 0; ดัชนี <= ข้อความ.length(); ดัชนี++) {
            int 문자 = ดัชนี == ข้อความ.length() ? '.' : ข้อความ.charAt(ดัชนี);
            if (문자 == '.') {
                if (자릿수 == 0 || 부분 == 4) return 0;
                ผลลัพธ์ = (ผลลัพธ์ << 8) | ค่า; 부분++; ค่า = 0; 자릿수 = 0;
            } else {
                if (문자 < '0' || 문자 > '9') return 0;
                ค่า = ค่า * 10 + 문자 - '0';
                if (++자릿수 > 3 || ค่า > 255) return 0;
            }
        }
        return 부분 == 4 ? ผลลัพธ์ : 0;
    }
    public static int เรียกใช้งาน() {
        if (ผู้ใช้.인수개수() != 3) { ผู้ใช้.เขียน("Usage: run udp IP PORT TEXT\n"); return 2; }
        int อีเมล = อีเมล(ผู้ใช้.อาร์กิวเมนต์(0)), แปลง_ค่า = ตัวเลข_ค่า(ผู้ใช้.อาร์กิวเมนต์(1));
        String เนื้อหา_ค่า = ผู้ใช้.อาร์กิวเมนต์(2);
        if (อีเมล == 0 || แปลง_ค่า < 1 || เนื้อหา_ค่า.length() > 1024) { ผู้ใช้.เขียน("Bad destination\n"); return 2; }
        int จุดจับ_ค่า = ผู้ใช้.เปิด_เครือข่าย(0);
        if (จุดจับ_ค่า < 0) { ผู้ใช้.เขียน("UDP OPEN FAILED (network unavailable)\n"); return 3; }
        int[] ข้อมูล = new int[1024];
        for (int ดัชนี = 0; ดัชนี < เนื้อหา_ค่า.length(); ดัชนี++) ข้อมูล[ดัชนี] = เนื้อหา_ค่า.charAt(ดัชนี);
        if (ผู้ใช้.ส่ง_ข้อมูล(จุดจับ_ค่า, อีเมล, แปลง_ค่า, ข้อมูล, เนื้อหา_ค่า.length()) < 0) {
            ผู้ใช้.เขียน("UDP SEND FAILED\n"); ผู้ใช้.ปิด_เครือข่าย(จุดจับ_ค่า); return 4;
        }
        ผู้ใช้.เขียน("UDP SENT\n");
        int 받은길이 = ผู้ใช้.รับ_ข้อมูล(จุดจับ_ค่า, ข้อมูล, 1500);
        boolean 같음 = 받은길이 == เนื้อหา_ค่า.length() && ผู้ใช้.보낸주소(จุดจับ_ค่า) == อีเมล && ผู้ใช้.보낸창구(จุดจับ_ค่า) == แปลง_ค่า;
        if (같음) for (int ดัชนี = 0; ดัชนี < 받은길이; ดัชนี++) if (ข้อมูล[ดัชนี] != เนื้อหา_ค่า.charAt(ดัชนี)) 같음 = false;
        ผู้ใช้.ปิด_เครือข่าย(จุดจับ_ค่า);
        if (받은길이 < 0) { ผู้ใช้.เขียน("UDP RECEIVE TIMEOUT/ERROR\n"); return 5; }
        ผู้ใช้.เขียน(같음 ? "UDP ECHO PASS\n" : "UDP REPLY MISMATCH\n");
        return 같음 ? 0 : 6;
    }
}
