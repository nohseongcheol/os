/** int 0x80 게이트가 호출한다. 모든 ผู้ใช้ ตัวชี้/길이는 เข้าถึง_รายการ 전에 검사한다. */
public final class 체계호출 {
    static int[] 임시자료 = new int[1024];

    static int 배열길이(int อีเมล) {
        if (!실행관리.คลิป(อีเมล, 4)) return -14;
        int 길이 = 실행관리.หมายเลข(อีเมล);
        if (길이 < 0 || 길이 > (실행관리.ผู้ใช้_สิ้นสุดการโทร - อีเมล - 4) / 4) return -14;
        return 길이;
    }

    public static int กระบวนการ_ค่า_รายการ(int ดัชนี, int 가, int 나, int 다, int 라, int 마) {
        if (ดัชนี == 30) return 파일서술자관리.เปิด_แฟ้ม(가, 나, 다);
        if (ดัชนี == 31) return 파일서술자관리.파일읽기(가, 나, 다);
        if (ดัชนี == 32) return 파일서술자관리.파일쓰기(가, 나, 다);
        if (ดัชนี == 33) return 파일서술자관리.ปิด_แฟ้ม(가);
        if (ดัชนี == 34) return 파일서술자관리.กรอ_แฟ้ม(가, 나, 다);
        if (ดัชนี == 35) return 파일서술자관리.서술자복제(가, 0, false, 0);
        if (ดัชนี == 36) return 파일서술자관리.서술자복제(가, 나, true, 0);
        if (ดัชนี == 37) return 파일서술자관리.파일상태읽기(가, 나);
        if (ดัชนี == 38) return 파일서술자관리.นําออก_แฟ้ม_รายการ_ชื่อ(가);
        if (ดัชนี == 39) return 파일서술자관리.파일길이정하기(가, 나);
        if (ดัชนี == 40) return 파일서술자관리.서술자제어(가, 나, 다);
        if (ดัชนี == 41) return 파일서술자관리.เปิด_ปลายทาง(가, 나, 다);
        if (ดัชนี == 42) return 파일서술자관리.ผูก_อีเมล(가, 나, 다);
        if (ดัชนี == 43) return 파일서술자관리.ส่ง_เดตาแกรม_ข้อมูล(가, 나, 다, 라, 마);
        if (ดัชนี == 44) return 파일서술자관리.รับ_เดตาแกรม_ข้อมูล(가, 나, 다, 라, 마);
        if (ดัชนี == 45) return 파일서술자관리.통신주소읽기(가, 나, 다);
        if (ดัชนี == 46) return 파일서술자관리.수신대기정하기(가, 나);
        if (ดัชนี == 47) {
            int 기술 = 파일서술자관리.기술찾기(가);
            if (기술 < 0) return -9;
            if (파일서술자관리.종류[기술] != 2) return -22;
            return 파일보존.ซิงค์();
        }
        if (ดัชนี == 1) {
            int 길이 = 배열길이(가);
            if (길이 < 0) return 길이;
            if (길이 > 4096) return -90;
            for (int อักขระ_ค่า = 0; อักขระ_ค่า < 길이; อักขระ_ค่า++) ข้อความ_เทอร์มินัล.문자(실행관리.หมายเลข(가 + 4 + อักขระ_ค่า * 4) & 65535);
            return 길이;
        }
        if (ดัชนี == 2) return 실행관리.인수수;
        if (ดัชนี == 3) return 가 >= 0 && 가 < 실행관리.인수수 ? 실행관리.อาร์กิวเมนต์_อีเมล[가] : 0;
        if (ดัชนี == 10) return เครือข่าย_สแตก.เปิด(가);
        if (ดัชนี == 11) {
            int 길이 = 배열길이(라);
            if (길이 < 0) return 길이;
            if (마 < 0 || 마 > 길이 || 마 > 1024) return -90;
            for (int ตําแหน่ง = 0; ตําแหน่ง < 마; ตําแหน่ง++) 임시자료[ตําแหน่ง] = 실행관리.หมายเลข(라 + 4 + ตําแหน่ง * 4) & 255;
            return เครือข่าย_สแตก.ส่ง(가, 나, 다, 임시자료, 마);
        }
        if (ดัชนี == 12) {
            int 길이 = 배열길이(나);
            if (길이 < 0) return 길이;
            if (다 < 0 || 다 > 2000) return -22;
            int ผลลัพธ์ = เครือข่าย_สแตก.รับ(가, 임시자료, 길이 < 1024 ? 길이 : 1024, 다);
            if (ผลลัพธ์ >= 0) for (int ตําแหน่ง = 0; ตําแหน่ง < ผลลัพธ์; ตําแหน่ง++) 실행관리.수쓰기(나 + 4 + ตําแหน่ง * 4, 임시자료[ตําแหน่ง]);
            return ผลลัพธ์;
        }
        if (ดัชนี == 13) return เครือข่าย_สแตก.ปิด(가);
        if (ดัชนี == 14) return เครือข่าย_สแตก.내주소;
        if (ดัชนี == 15) return เครือข่าย_สแตก.ชั้น_อีเมล(가);
        if (ดัชนี == 16) return เครือข่าย_สแตก.ชั้น_หมายเลขพอร์ต(가);
        if (ดัชนี == 22) {
            if (가 < 0 || 가 > 65535) return -22;
            ข้อความ_เทอร์มินัล.문자(가); return 1;
        }
        if (ดัชนี == 20 || ดัชนี == 21) {
            int ชื่อ_ขนาด = 배열길이(가), ข้อมูล_ขนาด = 배열길이(나);
            if (ชื่อ_ขนาด < 0 || ข้อมูล_ขนาด < 0) return -14;
            if (ชื่อ_ขนาด < 1 || ชื่อ_ขนาด > 64) return -22;
            int 길이 = 0;
            while (길이 < ชื่อ_ขนาด && 실행관리.หมายเลข(가 + 4 + 길이 * 4) != 0) {
                ความจํา_ระบบแฟ้ม.ชื่อ[길이] = 실행관리.หมายเลข(가 + 4 + 길이 * 4);
                길이++;
            }
            if (!ความจํา_ระบบแฟ้ม.เช็ค_ชื่อ(ความจํา_ระบบแฟ้ม.ชื่อ, 길이)) return -22;
            if (ดัชนี == 20) {
                int แฟ้ม = ความจํา_ระบบแฟ้ม.ค้นพบ_รายการ(ความจํา_ระบบแฟ้ม.ชื่อ, 길이);
                if (แฟ้ม < 0) return แฟ้ม;
                int ขนาด = ความจํา_ระบบแฟ้ม.ขนาด_รายการ[แฟ้ม];
                if (ขนาด > ข้อมูล_ขนาด) return -90;
                int อีเมล = อุปกรณ์_ค่า.แฟ้ม_ความจํา() + แฟ้ม * ความจํา_ระบบแฟ้ม.최대크기;
                for (int หมายเลข = 0; หมายเลข < ขนาด; หมายเลข++) 실행관리.수쓰기(나 + 4 + หมายเลข * 4, อุปกรณ์_ค่า.기억읽기(อีเมล + หมายเลข));
                return ขนาด;
            }
            if (다 < 0 || 다 > ข้อมูล_ขนาด) return -22;
            if (다 > ความจํา_ระบบแฟ้ม.최대크기) return -90;
            for (int หมายเลข = 0; หมายเลข < 다; หมายเลข++) ความจํา_ระบบแฟ้ม.แก้ไข_ค่า[หมายเลข] = 실행관리.หมายเลข(나 + 4 + หมายเลข * 4) & 255;
            return ความจํา_ระบบแฟ้ม.เก็บ_ค่า(ความจํา_ระบบแฟ้ม.ชื่อ, 길이, ความจํา_ระบบแฟ้ม.แก้ไข_ค่า, 다);
        }
        return -38;
    }
}
