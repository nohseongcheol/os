#include "호출경계.h"
extern int main(int 인수개수, char **อาร์กิวเมนต์_รายการ);
static char อาร์กิวเมนต์_ความจํา[2048];
static char *อาร์กิวเมนต์_รายการ[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* ปัจจุบัน_รายการ 커널의 argv는 ดําเนินการ_คําสั่ง 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    อาร์กิวเมนต์_รายการ[0] = "jkoros-app";
    int ตําแหน่ง = 0;
    for (int ดัชนี = 0; ดัชนี < 개수; ดัชนี++) {
        const int *원본 = (const int *)jkoros_syscall(3, ดัชนี, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        อาร์กิวเมนต์_รายการ[ดัชนี + 1] = อาร์กิวเมนต์_ความจํา + ตําแหน่ง;
        for (int 칸 = 0; 칸 < 원본[0]; 칸++) {
            if (ตําแหน่ง >= 2047) return 126;
            อาร์กิวเมนต์_ความจํา[ตําแหน่ง++] = 원본[칸 + 1];
        }
        อาร์กิวเมนต์_ความจํา[ตําแหน่ง++] = 0;
    }
    อาร์กิวเมนต์_รายการ[개수 + 1] = 0;
    return main(개수 + 1, อาร์กิวเมนต์_รายการ);
}
