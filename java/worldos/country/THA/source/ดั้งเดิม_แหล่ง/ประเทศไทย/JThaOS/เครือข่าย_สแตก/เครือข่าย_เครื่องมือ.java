package ประเทศไทย.JThaOS.เครือข่าย_สแตก;

/** Ethernet/ARP/IPv4/ICMP/UDP 계층이 공유하는 ไบต์_ค่า 순서와 검사합 도구다. */
public final class เครือข่าย_เครื่องมือ {
    private เครือข่าย_เครื่องมือ() {
    }

    public static int 큰순서짧은정수(byte[] ข้อมูล, int ตําแหน่ง) {
        เช็ค_ช่วง(ข้อมูล, ตําแหน่ง, 2);
        return ((ข้อมูล[ตําแหน่ง] & 0xff) << 8) | (ข้อมูล[ตําแหน่ง + 1] & 0xff);
    }

    public static long บิ๊กเอนเดียน_จํานวนเต็ม(byte[] ข้อมูล, int ตําแหน่ง) {
        เช็ค_ช่วง(ข้อมูล, ตําแหน่ง, 4);
        return ((long) (ข้อมูล[ตําแหน่ง] & 0xff) << 24)
                | ((long) (ข้อมูล[ตําแหน่ง + 1] & 0xff) << 16)
                | ((long) (ข้อมูล[ตําแหน่ง + 2] & 0xff) << 8)
                | (ข้อมูล[ตําแหน่ง + 3] & 0xffL);
    }

    public static int 인터넷검사합(byte[] ข้อมูล, int เรียกใช้งาน, int 길이) {
        เช็ค_ช่วง(ข้อมูล, เรียกใช้งาน, 길이);
        long 합 = 0;
        int 끝 = เรียกใช้งาน + 길이;
        int ตําแหน่ง = เรียกใช้งาน;
        while (ตําแหน่ง + 1 < 끝) {
            합 += 큰순서짧은정수(ข้อมูล, ตําแหน่ง);
            ตําแหน่ง += 2;
        }
        if (ตําแหน่ง < 끝) {
            합 += (ข้อมูล[ตําแหน่ง] & 0xff) << 8;
        }
        while ((합 >>> 16) != 0) {
            합 = (합 & 0xffff) + (합 >>> 16);
        }
        return (int) (~합) & 0xffff;
    }

    public static boolean เทคโนโลยีสารสนเทศ_อีเทอร์เน็ต_กรอบ(byte[] ข้อมูล) {
        return ข้อมูล != null && ข้อมูล.length >= 14;
    }

    public static int 이더넷상위규약(byte[] ข้อมูล) {
        if (!เทคโนโลยีสารสนเทศ_อีเทอร์เน็ต_กรอบ(ข้อมูล)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return 큰순서짧은정수(ข้อมูล, 12);
    }

    public static boolean เทคโนโลยีสารสนเทศ_วัคซีนป้องกันโปลิโอ_4_โพรโทคอล(byte[] ข้อมูล, int ตําแหน่ง) {
        if (ข้อมูล == null || ตําแหน่ง < 0 || ข้อมูล.length - ตําแหน่ง < 20) {
            return false;
        }
        int รุ่น_ค่า = (ข้อมูล[ตําแหน่ง] >>> 4) & 0xf;
        int 머리길이 = (ข้อมูล[ตําแหน่ง] & 0xf) * 4;
        return รุ่น_ค่า == 4 && 머리길이 >= 20 && ข้อมูล.length - ตําแหน่ง >= 머리길이;
    }

    private static void เช็ค_ช่วง(byte[] ข้อมูล, int เรียกใช้งาน, int 길이) {
        if (ข้อมูล == null || เรียกใช้งาน < 0 || 길이 < 0 || เรียกใช้งาน > ข้อมูล.length - 길이) {
            throw new IllegalArgumentException("เครือข่าย_สแตก ข้อมูล 범위를 벗어났습니다.");
        }
    }
}

