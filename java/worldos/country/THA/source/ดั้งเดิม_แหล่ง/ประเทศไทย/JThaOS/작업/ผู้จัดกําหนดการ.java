package ประเทศไทย.JThaOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import ประเทศไทย.JThaOS.ความจํา_ขอบเขต.เพจ_ผู้จัดการ;
import ประเทศไทย.JThaOS.ระบบแฟ้ม.파일서술자표;

/** กระบวนการ_ค่า 식별자와 라운드로빈 จัดเตรียม 대기열을 관리한다. */
public final class ผู้จัดกําหนดการ {
    private final เพจ_ผู้จัดการ 쪽관리;
    private final Map<Integer, กระบวนการ_ค่า> รายการกระบวนการ = new HashMap<Integer, กระบวนการ_ค่า>();
    private final Queue<กระบวนการ_ค่า> 준비대기열 = new ArrayDeque<กระบวนการ_ค่า>();
    private int ถัดไป_ตัวระบุ = 1;

    public ผู้จัดกําหนดการ(เพจ_ผู้จัดการ 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public กระบวนการ_ค่า 첫과정(파일서술자표 파일서술자) {
        กระบวนการ_ค่า 새과정 = new กระบวนการ_ค่า(จัดสรร_ตัวระบุ(), 0, 쪽관리.새주소공간(), 파일서술자);
        รายการกระบวนการ.put(Integer.valueOf(새과정.ตัวระบุ_ค่า()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public กระบวนการ_ค่า ลอกแบบ_ค่า(กระบวนการ_ค่า แม่_ค่า) {
        กระบวนการ_ค่า ลูก_ค่า = new กระบวนการ_ค่า(
                จัดสรร_ตัวระบุ(),
                แม่_ค่า.ตัวระบุ_ค่า(),
                쪽관리.쓰기시복사복제(แม่_ค่า.อีเมล_สเปซ()),
                แม่_ค่า.파일서술자().ลอกแบบ_ค่า());
        ลูก_ค่า.ชุด_แอป_เวลาพัก(แม่_ค่า.แอป_เวลาพัก());
        รายการกระบวนการ.put(Integer.valueOf(ลูก_ค่า.ตัวระบุ_ค่า()), ลูก_ค่า);
        준비대기열.offer(ลูก_ค่า);
        return ลูก_ค่า;
    }

    public กระบวนการ_ค่า ถัดไป_กระบวนการ() {
        int 검사수 = 준비대기열.size();
        for (int ดัชนี = 0; ดัชนี < 검사수; ดัชนี++) {
            กระบวนการ_ค่า ถัดไป_รายการ = 준비대기열.poll();
            if (ถัดไป_รายการ != null && (ถัดไป_รายการ.สถานะ_ค่า() == กระบวนการ_สถานะ.จัดเตรียม || ถัดไป_รายการ.สถานะ_ค่า() == กระบวนการ_สถานะ.ดําเนินการ_คําสั่ง)) {
                ถัดไป_รายการ.ชุด_สถานะ(กระบวนการ_สถานะ.ดําเนินการ_คําสั่ง);
                준비대기열.offer(ถัดไป_รายการ);
                return ถัดไป_รายการ;
            }
        }
        return null;
    }

    public int 자식기다리기(กระบวนการ_ค่า แม่_ค่า, int ลูก_ตัวระบุ, boolean 기다리지않음) {
        for (กระบวนการ_ค่า 후보 : รายการกระบวนการ.values()) {
            if (후보.แม่_ตัวระบุ() != แม่_ค่า.ตัวระบุ_ค่า()) {
                continue;
            }
            if (ลูก_ตัวระบุ > 0 && 후보.ตัวระบุ_ค่า() != ลูก_ตัวระบุ) {
                continue;
            }
            if (후보.สถานะ_ค่า() == กระบวนการ_สถานะ.ออก_แอป) {
                int ผลลัพธ์ = (후보.ออก_รหัส() & 0xff) << 8;
                รายการกระบวนการ.remove(Integer.valueOf(후보.ตัวระบุ_ค่า()));
                return ผลลัพธ์;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public กระบวนการ_ค่า ค้นพบ_กระบวนการ(int ตัวระบุ_ค่า) {
        return รายการกระบวนการ.get(Integer.valueOf(ตัวระบุ_ค่า));
    }

    private int จัดสรร_ตัวระบุ() {
        return ถัดไป_ตัวระบุ++;
    }
}
