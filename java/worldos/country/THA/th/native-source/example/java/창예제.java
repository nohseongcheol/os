import ไทย.เอง.หน้าต่าง;
import ไทย.เอง.ฉลาก;
import ไทย.เอง.เขตข้อมูลข้อความ;
import ไทย.เอง.ปุ่ม;
import ไทย.เอง.กิจกรรม_คิว;
import ไทย.เอง.ข้อความออก;
import ไทย.เอง.실행할일;
import ไทย.เอง.동작받이;
import ไทย.เอง.แอคชัน_ข้อสังเกต;

/** เอง 커널의 Swing หน้าต่าง: th 입력 → ปุ่ม → 안내 ข้อความ รีเฟรช. */
public class 창예제 implements 실행할일, 동작받이 {
    private หน้าต่าง 인사창;
    private เขตข้อมูลข้อความ ชื่อ_เขตข้อมูล;
    private ฉลาก 인사말;
    private int 인사횟수;

    public void เปิด_หน้าต่าง() {
        인사창 = new หน้าต่าง("th Swing", 460, 300);
        인사창.เพิ่ม_องค์ประกอบ(new ฉลาก("สวัสดี", 20, 20, 420, 28));
        ชื่อ_เขตข้อมูล = new เขตข้อมูลข้อความ("th", 20, 64, 420, 30);
        인사말 = new ฉลาก("สวัสดี", 20, 152, 420, 28);
        인사창.เพิ่ม_องค์ประกอบ(ชื่อ_เขตข้อมูล);
        인사창.เพิ่ม_องค์ประกอบ(new ปุ่ม("인사하기", 20, 108, 180, 32, this));
        인사창.เพิ่ม_องค์ประกอบ(인사말);
        인사창.เพิ่ม_องค์ประกอบ(new ฉลาก("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.แสดง_หน้าต่าง();
        ข้อความออก.줄쓰기("GUI 예제 จัดเตรียม: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.글쓰기("สวัสดี, " + ชื่อ_เขตข้อมูล.글읽기() + "님! (" + 인사횟수 + ")");
        ข้อความออก.줄쓰기("GUI 인사: " + 인사말.글읽기());
    }

    public void เรียกทํางาน() { เปิด_หน้าต่าง(); }
    public void รับ_แอคชัน(แอคชัน_ข้อสังเกต ข้อสังเกต) {
        ข้อความออก.줄쓰기("การกระทํา ข้อสังเกต: " + ข้อสังเกต.คําสั่ง_ข้อความ());
        인사하기();
    }
    public static void เรียกใช้งาน() {
        กิจกรรม_คิว.나중에실행(new 창예제());
    }
}
