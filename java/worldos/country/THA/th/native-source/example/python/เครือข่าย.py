from ไทย import ข้อความออก, เปิด_เดตาแกรม, ส่ง_ภายนอก_เดตาแกรม, รับ_เดตาแกรม, ปิด_เครือข่าย, 밀리초
from ไทย import ระบบ_ข้อผิดพลาด, 다시시도오류, เข้ารหัส_ข้อความ, 명령인수, จํานวนเต็ม
ปลายทาง = เปิด_เดตาแกรม(0)
try:
    เดตาแกรม = เข้ารหัส_ข้อความ("PYTHON UDP th")
    ส่ง_ภายนอก_เดตาแกรม(ปลายทาง, "10.0.2.2", จํานวนเต็ม(명령인수[1]), เดตาแกรม)
    เรียกใช้งาน = 밀리초()
    while True:
        try:
            ตอบกลับ, แปลง_ค่า = รับ_เดตาแกรม(ปลายทาง)
            break
        except ระบบ_ข้อผิดพลาด as ข้อผิดพลาด:
            if ข้อผิดพลาด.ดัชนี != 다시시도오류 or 밀리초() - เรียกใช้งาน >= 700:
                raise
    assert ตอบกลับ == เดตาแกรม
    ข้อความออก("PYTHON 네트워크 ยืนยัน: UDP th")
finally:
    ปิด_เครือข่าย(ปลายทาง)
