/** 최대 ขนาด/홀수 길이 데이터그램으로 ค่าจริง_ข้อมูล RTL8139 รับ_ค่า วน_ค่า 순환을 시험한다. */
public final class เครือข่าย_วน {
    public static int เรียกใช้งาน() {
        if (ผู้ใช้.인수개수() != 1) { ผู้ใช้.เขียน("Usage: run stress PORT\n"); return 2; }
        String ข้อความ = ผู้ใช้.อาร์กิวเมนต์(0);
        int แปลง_ค่า = 0;
        for (int ดัชนี = 0; ดัชนี < ข้อความ.length(); ดัชนี++) {
            if (ข้อความ.charAt(ดัชนี) < '0' || ข้อความ.charAt(ดัชนี) > '9' || แปลง_ค่า > 6553) return 2;
            แปลง_ค่า = แปลง_ค่า * 10 + ข้อความ.charAt(ดัชนี) - '0';
        }
        if (แปลง_ค่า < 1 || แปลง_ค่า > 65535) return 2;
        int จุดจับ_ค่า = ผู้ใช้.เปิด_เครือข่าย(0);
        if (จุดจับ_ค่า < 0) return 3;
        int[] ข้อมูล = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int 길이 = 1024 - (회차 & 1);
            for (int ดัชนี = 0; ดัชนี < 길이; ดัชนี++) ข้อมูล[ดัชนี] = (ดัชนี + 회차) & 255;
            if (ผู้ใช้.ส่ง_ข้อมูล(จุดจับ_ค่า, 0x0a000202, แปลง_ค่า, ข้อมูล, 길이) != 길이) return 4;
            if (ผู้ใช้.รับ_ข้อมูล(จุดจับ_ค่า, ข้อมูล, 300) != 길이) return 5;
            for (int ดัชนี = 0; ดัชนี < 길이; ดัชนี++) if (ข้อมูล[ดัชนี] != ((ดัชนี + 회차) & 255)) return 6;
        }
        ผู้ใช้.ปิด_เครือข่าย(จุดจับ_ค่า);
        ผู้ใช้.เขียน("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
