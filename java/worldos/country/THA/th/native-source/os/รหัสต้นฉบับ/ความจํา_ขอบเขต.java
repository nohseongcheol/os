/** 부팅 ข้อมูลระบบ 조회와 4KiB 고정 ขนาด 작업 ส่วน_ค่า จัดสรร_ที่เก็บ/ส่งคืน_เมตริก. 일반 물리 เพจ_ค่า 관리자는 아니다. */
public final class ความจํา_ขอบเขต {
    static int[] ส่วน_ค่า = new int[8192];
    static int[] ใช้_ค่า = new int[8];

    static int แยกวิเคราะห์_จํานวนเต็ม(int อีเมล) {
        return อุปกรณ์_ค่า.기억읽기(อีเมล) | (อุปกรณ์_ค่า.기억읽기(อีเมล + 1) << 8)
            | (อุปกรณ์_ค่า.기억읽기(อีเมล + 2) << 16) | (อุปกรณ์_ค่า.기억읽기(อีเมล + 3) << 24);
    }

    static int 위쪽기억크기() {
        int ข้อมูลระบบ = อุปกรณ์_ค่า.부팅정보();
        if (อุปกรณ์_ค่า.부팅표식() != 0x2badb002 || ข้อมูลระบบ == 0 || (แยกวิเคราะห์_จํานวนเต็ม(ข้อมูลระบบ) & 1) == 0) return -1;
        return แยกวิเคราะห์_จํานวนเต็ม(ข้อมูลระบบ + 8);
    }

    static int จัดสรร_ที่เก็บ() {
        for (int ดัชนี = 0; ดัชนี < ใช้_ค่า.length; ดัชนี++) {
            if (ใช้_ค่า[ดัชนี] == 0) {
                ใช้_ค่า[ดัชนี] = 1;
                for (int 칸 = 0; 칸 < 1024; 칸++) ส่วน_ค่า[ดัชนี * 1024 + 칸] = 0;
                return ดัชนี;
            }
        }
        return -1;
    }

    static boolean ส่งคืน_เมตริก(int ดัชนี) {
        if (ดัชนี < 0 || ดัชนี >= ใช้_ค่า.length || ใช้_ค่า[ดัชนี] == 0) return false;
        ใช้_ค่า[ดัชนี] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int ดัชนี = 0; ดัชนี < ใช้_ค่า.length; ดัชนี++) 개수 += ใช้_ค่า[ดัชนี];
        return 개수;
    }
}
