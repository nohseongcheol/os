/** 디스크 เขียน 없이 동작하는 작은 직렬/PS2 ตัวแปลคําสั่ง. */
public final class ตัวแปลคําสั่ง {
    static int[] 입력 = new int[128];
    static int 길이 = 0;
    static boolean 앞줄복귀 = false;
    static boolean สาย_ยาวเกิน = false;

    static boolean คําสั่ง(String ชื่อ) {
        if (길이 < ชื่อ.length()) return false;
        for (int ดัชนี = 0; ดัชนี < ชื่อ.length(); ดัชนี++)
            if (입력[ดัชนี] != ชื่อ.charAt(ดัชนี)) return false;
        return 길이 == ชื่อ.length() || 입력[ชื่อ.length()] == ' ';
    }

    static void แสดง_ความช่วยเหลือ() {
        ข้อความ_เทอร์มินัล.เขียน("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        ข้อความ_เทอร์มินัล.เขียน("apps | run NAME [ARGS] | net\n");
        ข้อความ_เทอร์มินัล.เขียน("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        ข้อความ_เทอร์มินัล.เขียน("sync (연결된 JKSTORE1 เก็บ_ค่า 장치에 แฟ้ม 보존)\n");
    }

    static void กระบวนการ_ค่า_รายการ() {
        if (길이 == 0) return;
        if (คําสั่ง("help")) แสดง_ความช่วยเหลือ();
        else if (คําสั่ง("sync")) {
            int ผลลัพธ์ = 파일보존.ซิงค์();
            ข้อความ_เทอร์มินัล.เขียน("Sync: "); ข้อความ_เทอร์มินัล.수쓰기(ผลลัพธ์); ข้อความ_เทอร์มินัล.문자(10);
        }
        else if (คําสั่ง("ls")) ความจํา_ระบบแฟ้ม.รายการ_รายการ();
        else if (คําสั่ง("edit")) ความจํา_ระบบแฟ้ม.คําสั่ง(입력, 4, 길이, 0);
        else if (คําสั่ง("cat")) ความจํา_ระบบแฟ้ม.คําสั่ง(입력, 3, 길이, 1);
        else if (คําสั่ง("rm")) ความจํา_ระบบแฟ้ม.คําสั่ง(입력, 2, 길이, 2);
        else if (คําสั่ง("java") || คําสั่ง("javac")) {
            int ผลลัพธ์ = 실행관리.ดําเนินการ_คําสั่ง(입력, 0, 길이);
            ข้อความ_เทอร์มินัล.เขียน("Exit: "); ข้อความ_เทอร์มินัล.수쓰기(ผลลัพธ์); ข้อความ_เทอร์มินัล.문자(10);
        }
        else if (คําสั่ง("apps")) 실행관리.รายการ_รายการ();
        else if (คําสั่ง("net")) เครือข่าย_สแตก.สถานะ_ค่า();
        else if (คําสั่ง("run")) {
            int ผลลัพธ์ = 실행관리.ดําเนินการ_คําสั่ง(입력, 3, 길이);
            ข้อความ_เทอร์มินัล.เขียน("Exit: "); ข้อความ_เทอร์มินัล.수쓰기(ผลลัพธ์); ข้อความ_เทอร์มินัล.เขียน("\n");
        } else if (คําสั่ง("info")) {
            ข้อความ_เทอร์มินัล.เขียน("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (คําสั่ง("mem")) {
            ข้อความ_เทอร์มินัล.เขียน("위쪽 ความจํา_ค่า อีเมล_ขอบเขต(KiB): "); ข้อความ_เทอร์มินัล.수쓰기(ความจํา_ขอบเขต.위쪽기억크기());
            ข้อความ_เทอร์มินัล.เขียน("\n배열 동적 ความจํา_ค่า อีเมล_ขอบเขต(ไบต์_ค่า): "); ข้อความ_เทอร์มินัล.수쓰기(อุปกรณ์_ค่า.อาร์เรย์_การใช้());
            ข้อความ_เทอร์มินัล.เขียน(" / 262144\n작업 อีเมล_ขอบเขต ส่วน_ค่า: "); ข้อความ_เทอร์มินัล.수쓰기(ความจํา_ขอบเขต.사용개수());
            ข้อความ_เทอร์มินัล.เขียน(" / 8 (각 4096바이트)\n");
        } else if (คําสั่ง("alloc")) {
            int ดัชนี = ความจํา_ขอบเขต.จัดสรร_ที่เก็บ();
            ข้อความ_เทอร์มินัล.เขียน("ส่วน_ค่า ดัชนี: "); ข้อความ_เทอร์มินัล.수쓰기(ดัชนี); ข้อความ_เทอร์มินัล.เขียน("\n");
        } else if (คําสั่ง("free")) {
            if (길이 == 6 && 입력[4] == ' ' && 입력[5] >= '0' && 입력[5] <= '7') {
                ข้อความ_เทอร์มินัล.เขียน(ความจํา_ขอบเขต.ส่งคืน_เมตริก(입력[5] - '0') ? "반환됨\n" : "할당되지 않은 ส่วน_ค่า\n");
            } else ข้อความ_เทอร์มินัล.เขียน("사용법: free 0..7\n");
        } else if (คําสั่ง("echo")) {
            for (int ดัชนี = 5; ดัชนี < 길이; ดัชนี++) ข้อความ_เทอร์มินัล.문자(입력[ดัชนี]);
            ข้อความ_เทอร์มินัล.문자(10);
        } else if (คําสั่ง("clear")) ข้อความ_เทอร์มินัล.ลบ_รายการ();
        else if (คําสั่ง("test")) แก่นระบบ.시험();
        else if (คําสั่ง("halt")) {
            ข้อความ_เทอร์มินัล.เขียน("HALTED\n");
            อุปกรณ์_ค่า.정지();
        } else ข้อความ_เทอร์มินัล.เขียน("알 หมายเลข 없는 명령입니다. help를 입력하세요.\n");
    }

    static void 받아쓰기(int ค่า) {
        if (ค่า == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = ค่า == 13;
        if (ค่า == 10 || ค่า == 13) {
            ข้อความ_เทอร์มินัล.문자(10);
            if (ความจํา_ระบบแฟ้ม.편집중) ความจํา_ระบบแฟ้ม.แก้ไขแล้ว_สาย(입력, 길이, สาย_ยาวเกิน);
            else กระบวนการ_ค่า_รายการ();
            길이 = 0;
            สาย_ยาวเกิน = false;
            ข้อความ_เทอร์มินัล.เขียน(ความจํา_ระบบแฟ้ม.편집중 ? "...> " : "jkoros> ");
        } else if (ค่า == 8 || ค่า == 127) {
            if (길이 > 0) {
                길이--;
                ข้อความ_เทอร์มินัล.직렬바이트(8); ข้อความ_เทอร์มินัล.직렬바이트(32); ข้อความ_เทอร์มินัล.직렬바이트(8);
                ข้อความ_เทอร์มินัล.화면문자(8);
            }
        } else if (ค่า >= 32 && ค่า < 127 && 길이 < 입력.length) {
            입력[길이++] = ค่า;
            ข้อความ_เทอร์มินัล.문자(ค่า);
        } else if (ค่า >= 32 && ค่า < 127) สาย_ยาวเกิน = true;
    }

    static void เรียกใช้งาน() {
        แสดง_ความช่วยเหลือ();
        ข้อความ_เทอร์มินัล.เขียน("READY\njkoros> ");
        while (true) {
            int ค่า = ข้อความ_เทอร์มินัล.직렬읽기();
            if (ค่า < 0) ค่า = คีย์บอร์ด.อ่าน();
            if (ค่า >= 0) 받아쓰기(ค่า);
            else { เครือข่าย_สแตก.ยืนยัน(); อุปกรณ์_ค่า.잠시양보(); }
        }
    }
}
