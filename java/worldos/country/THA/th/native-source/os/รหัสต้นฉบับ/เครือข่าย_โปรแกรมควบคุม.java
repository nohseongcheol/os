/** PCI RTL8139 (10ec:8139), 단일 ส่ง_ค่า 버퍼와 8KiB รับ_ค่า วน_ค่า. 인터럽트 대신 폴링한다. */
public final class เครือข่าย_โปรแกรมควบคุม {
    static int 입출력기준주소 = 0;
    static int รับ_ตําแหน่ง = 0, 송신칸 = 0;
    static int[] อุปกรณ์_อีเมล = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int อุปกรณ์_หมายเลข, int ตําแหน่ง) {
        อุปกรณ์_ค่า.입출력정수쓰기(0xcf8, 0x80000000 | (อุปกรณ์_หมายเลข << 11) | ตําแหน่ง);
        return อุปกรณ์_ค่า.입출력정수읽기(0xcfc);
    }

    static boolean จัดเตรียม() {
        int อุปกรณ์_หมายเลข = -1;
        for (int ดัชนี = 0; ดัชนี < 32; ดัชนี++) {
            if (설정읽기(ดัชนี, 0) == 0x813910ec) { อุปกรณ์_หมายเลข = ดัชนี; break; }
        }
        if (อุปกรณ์_หมายเลข < 0) return false;
        int ค่าเริ่มต้น = 설정읽기(อุปกรณ์_หมายเลข, 0x10);
        if ((ค่าเริ่มต้น & 1) == 0 || (ค่าเริ่มต้น & 0xfffffffc) < 0x100 || (ค่าเริ่มต้น & 0xfffffffc) > 65535) return false;
        입출력기준주소 = ค่าเริ่มต้น & 0xfffc;
        int คําสั่ง = 설정읽기(อุปกรณ์_หมายเลข, 4);
        อุปกรณ์_ค่า.입출력정수쓰기(0xcf8, 0x80000004 | (อุปกรณ์_หมายเลข << 11));
        อุปกรณ์_ค่า.입출력짧은수쓰기(0xcfc, คําสั่ง | 5); // I/O 및 bus master อนุญาต_ค่า, PCI สถานะ_ค่า 비트는 건드리지 않음
        อุปกรณ์_ค่า.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!รีเซ็ต_ค่า()) { 입출력기준주소 = 0; return false; }
        for (int ดัชนี = 0; ดัชนี < 6; ดัชนี++) อุปกรณ์_อีเมล[ดัชนี] = อุปกรณ์_ค่า.입출력바이트읽기(입출력기준주소 + ดัชนี);
        return true;
    }

    static boolean รีเซ็ต_ค่า() {
        อุปกรณ์_ค่า.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int เรียกใช้งาน = อุปกรณ์_ค่า.밀리초();
        while ((อุปกรณ์_ค่า.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (อุปกรณ์_ค่า.밀리초() - เรียกใช้งาน > 100) return false;
        รับ_ตําแหน่ง = 0; 송신칸 = 0;
        อุปกรณ์_ค่า.입출력정수쓰기(입출력기준주소 + 0x30, อุปกรณ์_ค่า.เครือข่าย_ความจํา());
        for (int ดัชนี = 0; ดัชนี < 4; ดัชนี++) อุปกรณ์_ค่า.입출력정수쓰기(입출력기준주소 + 0x20 + ดัชนี * 4, อุปกรณ์_ค่า.เครือข่าย_ความจํา() + 12288);
        อุปกรณ์_ค่า.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        อุปกรณ์_ค่า.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        อุปกรณ์_ค่า.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        อุปกรณ์_ค่า.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/ออกอากาศ_ค่า, wrap 연속 เก็บ_ค่า, 8KiB
        อุปกรณ์_ค่า.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int ส่ง(int[] ข้อมูล, int 길이) {
        if (입출력기준주소 == 0) return -19;
        if (길이 < 14 || 길이 > 1514) return -90;
        int สถานะ_แปลง = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int เรียกใช้งาน = อุปกรณ์_ค่า.밀리초();
        while ((อุปกรณ์_ค่า.입출력정수읽기(สถานะ_แปลง) & 0x2000) == 0)
            if (อุปกรณ์_ค่า.밀리초() - เรียกใช้งาน > 100) return -110;
        int ขนาด = 길이 < 60 ? 60 : 길이;
        for (int ดัชนี = 0; ดัชนี < ขนาด; ดัชนี++)
            อุปกรณ์_ค่า.기억쓰기(อุปกรณ์_ค่า.เครือข่าย_ความจํา() + 12288 + ดัชนี, ดัชนี < 길이 ? ข้อมูล[ดัชนี] : 0);
        อุปกรณ์_ค่า.입출력정수쓰기(สถานะ_แปลง, ขนาด | 0x00080000);
        เรียกใช้งาน = อุปกรณ์_ค่า.밀리초();
        while ((อุปกรณ์_ค่า.입출력정수읽기(สถานะ_แปลง) & 0xe0008000) == 0)
            if (อุปกรณ์_ค่า.밀리초() - เรียกใช้งาน > 100) return -110;
        if ((อุปกรณ์_ค่า.입출력정수읽기(สถานะ_แปลง) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return 길이;
    }

    static int รับ(int[] ข้อมูล) {
        if (입출력기준주소 == 0) return 0;
        if ((อุปกรณ์_ค่า.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!รีเซ็ต_ค่า()) 입출력기준주소 = 0;
            return 0;
        }
        if ((อุปกรณ์_ค่า.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = อุปกรณ์_ค่า.เครือข่าย_ความจํา() + รับ_ตําแหน่ง;
        int สถานะ_ค่า = 실행관리.짧은수(머리), ขนาด = 실행관리.짧은수(머리 + 2);
        if (ขนาด == 0xfff0) return 0; // DMA 진행 중
        if (ขนาด < 4 || ขนาด > 1518) {
            오류수++;
            if (!รีเซ็ต_ค่า()) 입출력기준주소 = 0;
            return 0;
        }
        int 길이 = ขนาด - 4;
        if ((สถานะ_ค่า & 1) != 0) {
            for (int ดัชนี = 0; ดัชนี < 길이; ดัชนี++) ข้อมูล[ดัชนี] = อุปกรณ์_ค่า.기억읽기(머리 + 4 + ดัชนี);
            수신수++;
        } else { 길이 = 0; 오류수++; }
        รับ_ตําแหน่ง = (รับ_ตําแหน่ง + ขนาด + 4 + 3) & ~3;
        รับ_ตําแหน่ง &= 8191;
        อุปกรณ์_ค่า.입출력짧은수쓰기(입출력기준주소 + 0x38, (รับ_ตําแหน่ง - 16) & 65535);
        อุปกรณ์_ค่า.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return 길이;
    }
}
