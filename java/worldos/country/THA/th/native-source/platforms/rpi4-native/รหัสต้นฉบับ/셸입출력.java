/** 파이프는 16 KiB씩 순서대로 실행한다. 프로세스/동시 파이프를 흉내 내지 않는다. */
public final class 셸입출력 {
    static int[] 입력자료 = new int[16384], ผลผลิต_ข้อมูล = new int[16384];
    static int 입력길이, 입력위치, 출력길이, ไฟล์อินพุท = -1, ไฟล์ผลลัพธ์ = -1;
    static boolean 파이프입력, ไปป์_ผลผลิต;
    static int ความล้มเหลว_ค่า;
    static boolean 대화허용 = true;
    public static int 대화가능() { return 대화허용 && ไฟล์อินพุท < 3 && ไฟล์ผลลัพธ์ < 3 && !파이프입력 && !ไปป์_ผลผลิต ? 1 : 0; }
    public static int ข้อความออก(int ช่อง_ค่า, int ค่า) {
        if (ช่อง_ค่า != 1) return 0;
        if (ไฟล์ผลลัพธ์ >= 3) { int 처리값 = แฟ้มในหน่วยความจํา.เขียน(ไฟล์ผลลัพธ์, ค่า); if (처리값 < 0) ความล้มเหลว_ค่า = 처리값; return 1; }
        if (!ไปป์_ผลผลิต) return 0;
        if (출력길이 == ผลผลิต_ข้อมูล.length) ความล้มเหลว_ค่า = -28;
        else ผลผลิต_ข้อมูล[출력길이++] = ค่า;
        return 1;
    }
    public static int 입력() {
        if (ไฟล์อินพุท >= 3) { int 처리값 = แฟ้มในหน่วยความจํา.อ่าน(ไฟล์อินพุท); return 처리값 == 256 ? -2 : 처리값; }
        if (파이프입력) return 입력위치 < 입력길이 ? 입력자료[입력위치++] : -2;
        return -3; // UART로 ส่งต่อ_ค่า_24592b8a
    }
    static void เรียกใช้งาน(boolean ด้านหน้า_ไปป์, boolean 뒤파이프) {
        파이프입력 = ด้านหน้า_ไปป์; ไปป์_ผลผลิต = 뒤파이프;
        입력위치 = 0; 출력길이 = 0; ไฟล์อินพุท = -1; ไฟล์ผลลัพธ์ = -1; ความล้มเหลว_ค่า = 0;
    }
    static void 끝() {
        บอร์ด.입출력전환(0);
        if (ไฟล์อินพุท >= 3) แฟ้มในหน่วยความจํา.ปิด(ไฟล์อินพุท);
        if (ไฟล์ผลลัพธ์ >= 3) แฟ้มในหน่วยความจํา.ปิด(ไฟล์ผลลัพธ์);
        if (ไปป์_ผลผลิต) { 입력길이 = 출력길이; for (int วน_ดัชนี = 0; วน_ดัชนี < 출력길이; วน_ดัชนี++) 입력자료[วน_ดัชนี] = ผลผลิต_ข้อมูล[วน_ดัชนี]; }
        ไฟล์อินพุท = -1; ไฟล์ผลลัพธ์ = -1; 파이프입력 = false; ไปป์_ผลผลิต = false;
    }
}
