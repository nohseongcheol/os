/** 화면 ตัด_ค่า·띠 합성·ตัวชี้ 밑그림을 관리한다. ค่าจริง_ข้อมูล 화면 ความจํา_ข้อมูล 접근은 보드가 담당한다. */
public final class 화면합성 {
    static int 너비, 높이, 합성중, 왼경계, 위경계, 오른경계, 아래경계;
    static int ตัวชี้_ปุ่ม_X, ตัวชี้_ปุ่ม_Y, ตัวชี้_รูปร่าง;
    static int 기록아래낱말, 기록위낱말;
    static int[] 완성그림 = new int[32 * 1920];
    static int[] ตัวชี้_พื้นหลัง = new int[21 * 21];
    static int[] 잘린범위 = new int[4];
    public static void จัดเตรียม(int 폭, int 길이) {
        너비 = 폭; 높이 = 길이; 합성중 = 0; ตัวชี้_รูปร่าง = 0;
        기록아래낱말 = 0; 기록위낱말 = 0;
    }
    public static int 너비얻기() { return 너비; }
    public static int 높이얻기() { return 높이; }
    public static int 기록아래얻기() { return 기록아래낱말; }
    public static int 기록위얻기() { return 기록위낱말; }
    public static int คลิป_ค่า(int 순번) { return 잘린범위[순번]; }
    static int 양의길이더하기(int เริ่ม_ค่า, int 길이) {
        if (เริ่ม_ค่า > 2147483647 - 길이) return 2147483647;
        return เริ่ม_ค่า + 길이;
    }
    public static int คลิป(int 가로, int แนวตั้ง_ตําแหน่ง, int 폭, int 길이) {
        if (너비 == 0 || 폭 <= 0 || 길이 <= 0) return 0;
        int สิทธิ์ = 양의길이더하기(가로, 폭), 아래쪽 = 양의길이더하기(แนวตั้ง_ตําแหน่ง, 길이);
        int 왼쪽 = 합성중 != 0 ? 왼경계 : 0, 위쪽 = 합성중 != 0 ? 위경계 : 0;
        int 최대가로 = 합성중 != 0 ? 오른경계 : 너비, 최대세로 = 합성중 != 0 ? 아래경계 : 높이;
        if (가로 < 왼쪽) 가로 = 왼쪽;
        if (แนวตั้ง_ตําแหน่ง < 위쪽) แนวตั้ง_ตําแหน่ง = 위쪽;
        if (สิทธิ์ > 최대가로) สิทธิ์ = 최대가로;
        if (아래쪽 > 최대세로) 아래쪽 = 최대세로;
        if (สิทธิ์ <= 가로 || 아래쪽 <= แนวตั้ง_ตําแหน่ง) return 0;
        잘린범위[0] = 가로; 잘린범위[1] = แนวตั้ง_ตําแหน่ง;
        잘린범위[2] = สิทธิ์ - 가로; 잘린범위[3] = 아래쪽 - แนวตั้ง_ตําแหน่ง;
        return 1;
    }
    public static int เรียกใช้งาน(int 가로, int แนวตั้ง_ตําแหน่ง, int 폭, int 길이) {
        if (합성중 != 0 || 길이 > 32 || คลิป(가로, แนวตั้ง_ตําแหน่ง, 폭, 길이) == 0) return 0;
        왼경계 = 잘린범위[0]; 위경계 = 잘린범위[1];
        오른경계 = 왼경계 + 잘린범위[2]; 아래경계 = 위경계 + 잘린범위[3];
        합성중 = 1; return 1;
    }
    static boolean ตัวชี้_บิต(int 가로, int แนวตั้ง_ตําแหน่ง, int รูปร่าง_ค่า) {
        if (รูปร่าง_ค่า == 1) return 가로 >= 0 && 가로 <= แนวตั้ง_ตําแหน่ง / 2 && แนวตั้ง_ตําแหน่ง < 16;
        if (รูปร่าง_ค่า == 3) 가로 = 20 - 가로;
        int 차이 = 가로 - แนวตั้ง_ตําแหน่ง; if (차이 < 0) 차이 = -차이;
        return (차이 <= 1 && 가로 >= 3 && 가로 <= 17) ||
            (가로 >= 2 && 가로 <= 8 && แนวตั้ง_ตําแหน่ง >= 2 && แนวตั้ง_ตําแหน่ง <= 8 && (가로 <= 3 || แนวตั้ง_ตําแหน่ง <= 3)) ||
            (가로 >= 12 && 가로 <= 18 && แนวตั้ง_ตําแหน่ง >= 12 && แนวตั้ง_ตําแหน่ง <= 18 && (가로 >= 17 || แนวตั้ง_ตําแหน่ง >= 17));
    }
    static int ตัวชี้_พิกเซล(int 가로, int แนวตั้ง_ตําแหน่ง) {
        if (ตัวชี้_บิต(가로, แนวตั้ง_ตําแหน่ง, ตัวชี้_รูปร่าง)) return 2;
        for (int บรรทัด = -1; บรรทัด <= 1; บรรทัด++) for (int 칸 = -1; 칸 <= 1; 칸++)
            if (ตัวชี้_บิต(가로 + 칸, แนวตั้ง_ตําแหน่ง + บรรทัด, ตัวชี้_รูปร่าง)) return 1;
        return 0;
    }
    static void แสดง_พิกเซล(int 가로, int แนวตั้ง_ตําแหน่ง, int 색) {
        int 칸 = 가로 - ตัวชี้_ปุ่ม_X, บรรทัด = แนวตั้ง_ตําแหน่ง - ตัวชี้_ปุ่ม_Y;
        if (ตัวชี้_รูปร่าง != 0 && 칸 >= 0 && บรรทัด >= 0 && 칸 < 21 && บรรทัด < 21) {
            ตัวชี้_พื้นหลัง[บรรทัด * 21 + 칸] = 색;
            int ชี้_ค่า = ตัวชี้_พิกเซล(칸, บรรทัด); if (ชี้_ค่า != 0) 색 = ชี้_ค่า == 2 ? 0xffffff : 0x101010;
        }
        if (บอร์ด.표시화소읽기(가로, แนวตั้ง_ตําแหน่ง) != 색) {
            บอร์ด.표시화소쓰기(가로, แนวตั้ง_ตําแหน่ง, 색);
            기록아래낱말++; if (기록아래낱말 == 0) 기록위낱말++;
        }
    }
    public static void เสร็จสิ้น() {
        if (합성중 == 0) return;
        for (int บรรทัด = 위경계; บรรทัด < 아래경계; บรรทัด++) for (int 칸 = 왼경계; 칸 < 오른경계; 칸++)
            แสดง_พิกเซล(칸, บรรทัด, 완성그림[(บรรทัด - 위경계) * 1920 + 칸]);
        합성중 = 0;
    }
    public static int พิกเซล(int 가로, int แนวตั้ง_ตําแหน่ง, int 색) {
        if (가로 < 0 || แนวตั้ง_ตําแหน่ง < 0 || 가로 >= 너비 || แนวตั้ง_ตําแหน่ง >= 높이) return 0;
        if (합성중 != 0) {
            if (가로 >= 왼경계 && 가로 < 오른경계 && แนวตั้ง_ตําแหน่ง >= 위경계 && แนวตั้ง_ตําแหน่ง < 아래경계)
                완성그림[(แนวตั้ง_ตําแหน่ง - 위경계) * 1920 + 가로] = 색;
        } else แสดง_พิกเซล(가로, แนวตั้ง_ตําแหน่ง, 색);
        return 0;
    }
    public static void สี่เหลี่ยมผืนผ้า_เติม(int 가로, int แนวตั้ง_ตําแหน่ง, int 폭, int 길이, int 색) {
        if (คลิป(가로, แนวตั้ง_ตําแหน่ง, 폭, 길이) == 0) return;
        가로 = 잘린범위[0]; แนวตั้ง_ตําแหน่ง = 잘린범위[1]; 폭 = 잘린범위[2]; 길이 = 잘린범위[3];
        for (int บรรทัด = แนวตั้ง_ตําแหน่ง; บรรทัด < แนวตั้ง_ตําแหน่ง + 길이; บรรทัด++) for (int 칸 = 가로; 칸 < 가로 + 폭; 칸++) {
            if (합성중 != 0) 완성그림[(บรรทัด - 위경계) * 1920 + 칸] = 색;
            else แสดง_พิกเซล(칸, บรรทัด, 색);
        }
    }
    public static void ตัวชี้(int 가로, int แนวตั้ง_ตําแหน่ง, int รูปร่าง_ค่า) {
        if (너비 == 0) return;
        int 새가로 = 가로 - (รูปร่าง_ค่า >= 2 ? 10 : 0), 새세로 = แนวตั้ง_ตําแหน่ง - (รูปร่าง_ค่า >= 2 ? 10 : 0);
        if (ตัวชี้_รูปร่าง == รูปร่าง_ค่า && ตัวชี้_ปุ่ม_X == 새가로 && ตัวชี้_ปุ่ม_Y == 새세로) return;
        if (ตัวชี้_รูปร่าง != 0) for (int บรรทัด = 0; บรรทัด < 21; บรรทัด++) for (int 칸 = 0; 칸 < 21; 칸++) {
            int 가 = ตัวชี้_ปุ่ม_X + 칸, 세 = ตัวชี้_ปุ่ม_Y + บรรทัด;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) บอร์ด.표시화소쓰기(가, 세, ตัวชี้_พื้นหลัง[บรรทัด * 21 + 칸]);
        }
        ตัวชี้_รูปร่าง = รูปร่าง_ค่า; ตัวชี้_ปุ่ม_X = 새가로; ตัวชี้_ปุ่ม_Y = 새세로;
        if (รูปร่าง_ค่า != 0) for (int บรรทัด = 0; บรรทัด < 21; บรรทัด++) for (int 칸 = 0; 칸 < 21; 칸++) {
            int 가 = ตัวชี้_ปุ่ม_X + 칸, 세 = ตัวชี้_ปุ่ม_Y + บรรทัด;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) {
                ตัวชี้_พื้นหลัง[บรรทัด * 21 + 칸] = บอร์ด.표시화소읽기(가, 세);
                int ชี้_ค่า = ตัวชี้_พิกเซล(칸, บรรทัด); if (ชี้_ค่า != 0) บอร์ด.표시화소쓰기(가, 세, ชี้_ค่า == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
