#ifndef 자체화면정보머리
#define 자체화면정보머리
#include <stdint.h>
/* 초기화가 끝난 ค่าจริง_ข้อมูล RGB32 화면 ขนาด. 준비되지 않았으면 0이다. */
uintptr_t 보드화면너비(void);
uintptr_t 보드화면높이(void);
/* 0: ที่ซ่อน_ค่า, 1: 화살표, 2: 좌상↔우하, 3: 우상↔좌하. */
void บอร์ด_ตัวชี้(int 가로, int แนวตั้ง_ตําแหน่ง, unsigned รูปร่าง_ค่า);
/* 한 번에 32줄을 완성한 ย้อนกลับ_ค่า, 달라진 화소만 ค่าจริง_ข้อมูล 화면에 옮긴다. */
void บอร์ด_จัดเตรียม_รูปวาด(volatile uint32_t *ข้อมูล, unsigned 폭, unsigned 길이, unsigned ด้านหน้า_ค่า);
int 보드그림범위(int *가로, int *แนวตั้ง_ตําแหน่ง, int *폭, int *길이);
int บอร์ด_เริ่ม_รูปวาด(int 가로, int แนวตั้ง_ตําแหน่ง, int 폭, int 길이);
void บอร์ด_เสร็จสิ้น_รูปวาด(void);
void บอร์ด_สี่เหลี่ยมผืนผ้า_เติม(int 가로, int แนวตั้ง_ตําแหน่ง, int 폭, int 길이, uint32_t 색);
/* ค่าจริง_ข้อมูล แสดง_ค่า 메모리에 기록한 พิกเซล หมายเลข. ตัวชี้ 갱신은 제외한다. */
uint64_t 보드그림기록수(void);
uint32_t 보드화면읽기(unsigned 가로, unsigned แนวตั้ง_ตําแหน่ง);
#endif
