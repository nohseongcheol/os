"""독립된 เอง ABI ELF64와 로더 ปฏิเสธ_ค่า 시험 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from 파이썬빌드 import 파이썬만들기
from 자바라이브러리빌드 import 자바라이브러리만들기
from 시언어번역기빌드 import 시언어번역기만들기


def เปิด_ผู้ใช้_สเปซ(ราก_พาธ, ที่เก็บ_พาธ, 시언어번역기, 시플플번역기, ตัวเชื่อมโยง_เครื่องมือ, เก็บถาวร_เครื่องมือ, 설정비트, ดําเนินการ_คําสั่ง):
    설정비트 = [การตั้งค่า_ค่า for การตั้งค่า_ค่า in 설정비트 if การตั้งค่า_ค่า != '-mgeneral-regs-only']
    รุ่น_พาธ = ราก_พาธ / 'build'
    ผลผลิต = รุ่น_พาธ / 'user'
    ผลผลิต.mkdir(exist_ok=True)
    원본자료 = ราก_พาธ / 'ผู้ใช้'
    포직스경로 = ที่เก็บ_พาธ / 'posix-kor/arm64-native'
    รวม_พาธ = ['-I', 원본자료, '-I', 포직스경로 / '포함', '-I', ผลผลิต]
    for คอมไพเลอร์_เครื่องมือ, 추가영역, เส้นทาง, ชื่อ in [
            (시언어번역기, [], 원본자료 / 'เรียกใช้งาน.S', 'start.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'ดําเนินการ_คําสั่ง.c', 'runtime.o'),
            (시언어번역기, ['-std=c11'], 포직스경로 / 'ผู้ใช้_บริดจ์.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '파일예제.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '통신예제.cpp', 'network.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'การป้องกัน_การทดสอบ.c', 'fault.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'ตัวแก้ไข.c', 'vi.o')]:
        ดําเนินการ_คําสั่ง([คอมไพเลอร์_เครื่องมือ] + 설정비트 + 추가영역 + รวม_พาธ + ['-Wall', '-Wextra', '-Werror', '-c', เส้นทาง, '-o', ผลผลิต / ชื่อ])
    ดําเนินการ_คําสั่ง([เก็บถาวร_เครื่องมือ, 'rcs', รุ่น_พาธ / 'libposix-kor-user.a', ผลผลิต / 'posix.o'])
    for ชื่อ in ('demo', 'fault', 'network', 'vi'):
        ดําเนินการ_คําสั่ง([ตัวเชื่อมโยง_เครื่องมือ, '-T', 원본자료 / 'ลิงก์_การนําทาง.ld', '-z', 'max-page-size=4096', '-o', ผลผลิต / (ชื่อ + '.elf'),
             ผลผลิต / 'start.o', ผลผลิต / 'runtime.o', ผลผลิต / (ชื่อ + '.o'), รุ่น_พาธ / 'libposix-kor-user.a'])
    자바라이브러리만들기(ราก_พาธ, ดําเนินการ_คําสั่ง)
    # 기존 เอง Java คอมไพเลอร์/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(รุ่น_พาธ)) as 작업경로:
        คลาส_พาธ = Path(작업경로)
        ดําเนินการ_คําสั่ง(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', คลาส_พาธ, '-sourcepath', คลาส_พาธ, '-d', คลาส_พาธ] +
            [ข้อมูล_ตําแหน่ง for ข้อมูล_ตําแหน่ง in sorted((ที่เก็บ_พาธ / 'os/ผู้ใช้/자바').glob('*.java')) if ข้อมูล_ตําแหน่ง.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        ดําเนินการ_คําสั่ง(['sh', ที่เก็บ_พาธ / 'compiler/미리번역.sh', '--entry', 'เครื่องมือ_รายการ.เรียกใช้งาน',
             '--profile', 'user', '--heap-words', '1048576', '-o', ผลผลิต / 'java-tools.c'] + sorted(คลาส_พาธ.glob('*.class')))
    압축해제경로 = ราก_พาธ / 'vendor/uzlib'
    for เส้นทาง, ชื่อ in [(ผลผลิต / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'รวม.c', 'jar.o')] + [(압축해제경로 / (ชื่อ + '.c'), ชื่อ + '.o') for ชื่อ in ('tinflate', 'crc32', 'adler32')]:
        ดําเนินการ_คําสั่ง([시언어번역기] + 설정비트 + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + รวม_พาธ + ['-c', เส้นทาง, '-o', ผลผลิต / ชื่อ])
    ดําเนินการ_คําสั่ง([ตัวเชื่อมโยง_เครื่องมือ, '-T', 원본자료 / 'ลิงก์_การนําทาง.ld', '-z', 'max-page-size=4096', '-o', ผลผลิต / 'java-tools.elf'] +
        [ผลผลิต / ชื่อ for ชื่อ in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(ราก_พาธ, 시언어번역기, ตัวเชื่อมโยง_เครื่องมือ)
    시언어번역기만들기(ราก_พาธ, ที่เก็บ_พาธ, 시언어번역기, ตัวเชื่อมโยง_เครื่องมือ, 설정비트, ดําเนินการ_คําสั่ง)
    ถูกต้อง = (ผลผลิต / 'demo.elf').read_bytes()
    แอป_ส่วนหัว_ออฟเซต = struct.unpack_from('<Q', ถูกต้อง, 32)[0]
    ส่วนหัว_รายการ = [แอป_ส่วนหัว_ออฟเซต + 개수 * 56 for 개수 in range(struct.unpack_from('<H', ถูกต้อง, 56)[0])]
    적재구획 = [ข้อมูล_ตําแหน่ง for ข้อมูล_ตําแหน่ง in ส่วนหัว_รายการ if struct.unpack_from('<I', ถูกต้อง, ข้อมูล_ตําแหน่ง)[0] == 1]
    ข้อความ, ข้อมูล = 적재구획[:2]
    คําสั่ง_อีเมล = struct.unpack_from('<Q', ถูกต้อง, ข้อความ + 16)[0]
    ข้อมูล_อีเมล = struct.unpack_from('<Q', ถูกต้อง, ข้อมูล + 16)[0]
    호출규약 = ถูกต้อง.index(b'JKOROS\0')
    กรณีทดสอบ = [('empty', b''), ('short', ถูกต้อง[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', คําสั่ง_อีเมล + 1), ('data-entry', 24, 'Q', ข้อมูล_อีเมล),
               ('outside-file', ข้อความ + 32, 'Q', len(ถูกต้อง) + 1), ('short-memory', ข้อความ + 40, 'Q', 1),
               ('kernel-address', ข้อความ + 16, 'Q', 0x80000), ('memory-overflow', ข้อความ + 40, 'Q', 2**64 - 1),
               ('writable-code', ข้อความ + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', ข้อความ, 'I', 2),
               ('unaligned-load', ข้อความ + 16, 'Q', คําสั่ง_อีเมล + 8),
               ('overlap', ข้อมูล + 16, 'Q', คําสั่ง_อีเมล)]
    for ชื่อ, ออฟเซต_ค่า, รูปแบบ_932e03c8, ค่า in 수정사항:
        바뀐자료 = bytearray(ถูกต้อง); struct.pack_into('<' + รูปแบบ_932e03c8, 바뀐자료, ออฟเซต_ค่า, ค่า)
        กรณีทดสอบ.append((ชื่อ, bytes(바뀐자료)))
    탑재덩이들 = [(ชื่อ.replace('-', '_'), ผลผลิต / (ชื่อ + '.elf')) for ชื่อ in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for การค้นหา_ดัชนี, (ชื่อ, ส่วนข้อมูล_ข้อมูล) in enumerate(กรณีทดสอบ):
        เส้นทาง = ผลผลิต / ('invalid-{}.elf'.format(ชื่อ)); เส้นทาง.write_bytes(ส่วนข้อมูล_ข้อมูล)
        탑재덩이들.append(('invalid_{}'.format(การค้นหา_ดัชนี), เส้นทาง))
    แอสเซมบลี, ส่วนหัว_ค่า = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for ชื่อ, เส้นทาง in 탑재덩이들:
        สัญลักษณ์_ค่า = 'user_blob_' + ชื่อ
        크기목록[ชื่อ] = เส้นทาง.stat().st_size
        # 생성한 ชั้น_ค่า 경로만 넣어 프로젝트 경로의 공백/ยกคําพูด 영향을 피한다.
        แอสเซมบลี += ['.balign 16', '.global ' + สัญลักษณ์_ค่า, สัญลักษณ์_ค่า + ':', '.incbin "{}"'.format(เส้นทาง.relative_to(ราก_พาธ))]
        ส่วนหัว_ค่า.append('extern const unsigned char {}[];'.format(สัญลักษณ์_ค่า))
    แอสเซมบลี.append('.section .note.GNU-stack,"",%progbits')
    ส่วนหัว_ค่า += ['static const แอป 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    ส่วนหัว_ค่า += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    ส่วนหัว_ค่า += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    ส่วนหัว_ค่า += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], เมธอด_โหมด) for เมธอด_โหมด in (0, 1)]
    ส่วนหัว_ค่า += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    ส่วนหัว_ค่า += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    ส่วนหัว_ค่า += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    ส่วนหัว_ค่า += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    ส่วนหัว_ค่า += ['};', 'static const แอป 잘못된실행항목들[] = {']
    ส่วนหัว_ค่า += ['{user_blob_invalid_%d, %d, 0},' % (순번, len(ส่วนข้อมูล_ข้อมูล)) for 순번, (_, ส่วนข้อมูล_ข้อมูล) in enumerate(กรณีทดสอบ)]
    ส่วนหัว_ค่า += ['};']
    (รุ่น_พาธ / 'programs.S').write_text('\n'.join(แอสเซมบลี) + '\n')
    (รุ่น_พาธ / 'programs.h').write_text('\n'.join(ส่วนหัว_ค่า) + '\n')
    (ผลผลิต / 'invalid-cases.txt').write_text('\n'.join(ชื่อ for ชื่อ, _ in กรณีทดสอบ) + '\n')
    ดําเนินการ_คําสั่ง([시언어번역기] + 설정비트 + ['-c', รุ่น_พาธ / 'programs.S', '-o', รุ่น_พาธ / 'programs.o'])
