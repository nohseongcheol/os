#!/usr/bin/env python3
"""การประกาศ 고유번호와 UTF-8 ไบต์_ค่า 위치로 เอง C 이름을 옮기는 일회성 이행 เครื่องมือ.

ภายนอก_ค่า 구조체의 멤버, สตริง_ค่า, C 표준 ฟังก์ชัน_ค่า, 이식 규약은 보존한다.
입력은 เปลี่ยนแปลง_ค่า 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

แสดง_ราก = Path(__file__).resolve().parents[1]

def ดําเนินการ_คําสั่ง():
    วิเคราะห์_ค่า = json.loads((แสดง_ราก/'build/한국어화/시언어분석.json').read_text())
    if วิเคราะห์_ค่า['ข้อผิดพลาด']: raise SystemExit('วิเคราะห์_ค่า 오류를 먼저 해결해야 합니다.')
    ชื่อ_ตาราง = json.loads((แสดง_ราก/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((แสดง_ราก/'명명/규격이름.json').read_text()))
    การประกาศ_ตาราง = วิเคราะห์_ค่า['การประกาศ']
    바꿀선언 = {고유:ชื่อ_ตาราง[รายการ_ค่า['ชื่อ']] for 고유,รายการ_ค่า in การประกาศ_ตาราง.items()
                if รายการ_ค่า['ชื่อ'] in ชื่อ_ตาราง and รายการ_ค่า['ชื่อ'] not in 규격}
    เพื่อน_ตาราง = {รายการ_ค่า['ชื่อ']:ชื่อ_ตาราง[รายการ_ค่า['ชื่อ']] for รายการ_ค่า in การประกาศ_ตาราง.values()
              if รายการ_ค่า.get('เชื่อมต่อ')==4 and รายการ_ค่า['종류'] in (8,9)
              and รายการ_ค่า['ชื่อ'] in ชื่อ_ตาราง and รายการ_ค่า['ชื่อ'] not in 규격}
    # สร้าง_167eff27 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 เชื่อมต่อ 이름만 유지한다.
    머리 = ['/* ไทย แหล่ง_ทรี 이름과 기존 เครื่อง เชื่อมต่อ มูลค่าตามสัญญา. 자동 สร้าง_167eff27: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(เพื่อน_ตาราง.items())]
    머리 += ['#endif','']
    (แสดง_ราก/'명명/기계연결이름.h').write_text('\n'.join(머리))
    การเปลี่ยนแปลง_รายการ = defaultdict(dict)
    for แฟ้ม,ออฟเซต_ค่า,ชื่อ,고유 in วิเคราะห์_ค่า['อ้างอิง']:
        if 고유 in 바꿀선언:
            การเปลี่ยนแปลง_รายการ[แฟ้ม][ออฟเซต_ค่า] = (ชื่อ,바꿀선언[고유])
    บันทึก_สถิติ = ['แฟ้ม\t원래바이트위치\t이전이름\t한국어이름']
    ละเว้น_ค่า = []
    for แฟ้ม,เปลี่ยนแปลง_ค่า in การเปลี่ยนแปลง_รายการ.items():
        เส้นทาง = Path(แฟ้ม); 원본 = เส้นทาง.read_bytes(); ข้อมูล = 원본
        for ออฟเซต_ค่า,(옛이름,새이름) in sorted(เปลี่ยนแปลง_ค่า.items(),reverse=True):
            끝 = ออฟเซต_ค่า+len(옛이름.encode())
            if 원본[ออฟเซต_ค่า:끝] != 옛이름.encode():
                ละเว้น_ค่า.append((str(เส้นทาง.relative_to(แสดง_ราก)),ออฟเซต_ค่า,옛이름));continue
            ข้อมูล = ข้อมูล[:ออฟเซต_ค่า]+새이름.encode()+ข้อมูล[끝:]
            บันทึก_สถิติ.append('{}\t{}\t{}\t{}'.format(เส้นทาง.relative_to(แสดง_ราก),ออฟเซต_ค่า,옛이름,새이름))
        เส้นทาง.write_bytes(ข้อมูล)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    แมโคร_ค่า = {รายการ_ค่า['ชื่อ']:ชื่อ_ตาราง[รายการ_ค่า['ชื่อ']] for รายการ_ค่า in การประกาศ_ตาราง.values()
              if รายการ_ค่า['종류']==501 and รายการ_ค่า['ชื่อ'] in ชื่อ_ตาราง and รายการ_ค่า['ชื่อ'] not in 규격}
    for เส้นทาง in sorted({Path(รายการ_ค่า['แฟ้ม']) for รายการ_ค่า in การประกาศ_ตาราง.values()}):
        สาย_รายการ = เส้นทาง.read_text().splitlines(True); 이어짐 = False
        for ดัชนี,บรรทัด in enumerate(สาย_รายการ):
            전처리 = 이어짐 or bool(re.match(r'\s*#',บรรทัด))
            이어짐 = 전처리 and บรรทัด.rstrip().endswith('\\')
            if 전처리:
                การค้นหา_ตาราง = ชื่อ_ตาราง if re.match(r'\s*#\s*define\b',บรรทัด) or 이어짐 else แมโคร_ค่า
                สาย_รายการ[ดัชนี] = 낱말.sub(lambda 맞음: การค้นหา_ตาราง.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],บรรทัด)
        เส้นทาง.write_text(''.join(สาย_รายการ))
    # 각 เอง แปล_แหล่ง 단위에만 연결표를 넣는다. ภายนอก_ค่า 배포본에는 전파하지 않는다.
    for เส้นทาง in sorted({Path(รายการ_ค่า['แฟ้ม']) for รายการ_ค่า in การประกาศ_ตาราง.values()}):
        if เส้นทาง.suffix not in ('.c','.cpp'):continue
        ชั้น_ค่า = '../' * len(เส้นทาง.relative_to(แสดง_ราก).parts[:-1]) + '명명/기계연결이름.h'
        เส้นทาง.write_text('#include "'+ชั้น_ค่า+'"\n'+เส้นทาง.read_text())
    (แสดง_ราก/'명명/시언어이름대응.tsv').write_text('\n'.join(บันทึก_สถิติ)+'\n')
    (แสดง_ราก/'build/한국어화/전처리참조.json').write_text(json.dumps(ละเว้น_ค่า,ensure_ascii=False,indent=2)+'\n')
    print('เปลี่ยนแปลง_ค่า',len(บันทึก_สถิติ)-1,'전처리 재검토',len(ละเว้น_ค่า),'เครื่อง เชื่อมต่อ',len(เพื่อน_ตาราง))

if __name__=='__main__': ดําเนินการ_คําสั่ง()
