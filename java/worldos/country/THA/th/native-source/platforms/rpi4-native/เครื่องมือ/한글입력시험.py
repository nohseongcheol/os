#!/usr/bin/env python3
"""Composition/shortcut tests independent of a host input method."""
import unittest
from เดสก์ท็อป_ดู import คีย์บอร์ด


class 한글입력시험(unittest.TestCase):
    def setUp(자신):
        자신.ข้อความ_บัฟเฟอร์ = ''
        def ส่ง(ข้อมูล):
            for ข้อมูลอักขระ in ข้อมูล.decode('utf-8'):
                if ข้อมูลอักขระ == '\x7f': 자신.ข้อความ_บัฟเฟอร์ = 자신.ข้อความ_บัฟเฟอร์[:-1]
                else: 자신.ข้อความ_บัฟเฟอร์ += ข้อมูลอักขระ
        자신.คีย์บอร์ด_รายการ = คีย์บอร์ด(ส่ง)

    def กด_คีย์(자신, สัญลักษณ์_ค่า):
        자신.คีย์บอร์ด_รายการ.누름값(True, สัญลักษณ์_ค่า)
        자신.คีย์บอร์ด_รายการ.누름값(False, สัญลักษณ์_ค่า)

    def ชนิด_ประเภท(자신, 누름열):
        for 누름값 in 누름열: 자신.กด_คีย์(ord(누름값))

    def test_낱말(자신):
        for 누름열,예상결과 in [('gksrmf','한글'),('dkssudgktpdy','안녕하세요'),
                ('rhk','과'),('rhos','괜'),('dml','의'),('rkqt','값'),
                ('rkqtk','갑사'),('dkswdk','앉아'),('qkfrk','발가'),
                ('RkRnd','까꿍'),('Wkfqdk','짧아'),('dkflfkddms','아리랑은')]:
            with 자신.subTest(누름열=누름열):
                자신.setUp(); 자신.กด_คีย์(0xffc6); 자신.ชนิด_ประเภท(누름열)
                자신.assertEqual(자신.ข้อความ_บัฟเฟอร์, 예상결과)

    def test_앞글자지우기(자신):
        자신.กด_คีย์(0xff31); 자신.ชนิด_ประเภท('dlfr')
        자신.assertEqual(자신.ข้อความ_บัฟเฟอร์,'읽')
        for 예상결과 in ('일','이','ㅇ',''):
            자신.กด_คีย์(0xff08); 자신.assertEqual(자신.ข้อความ_บัฟเฟอร์,예상결과)
        자신.ชนิด_ประเภท('gksk'); 자신.assertEqual(자신.ข้อความ_บัฟเฟอร์,'하나')
        자신.กด_คีย์(0xff08); 자신.assertEqual(자신.ข้อความ_บัฟเฟอร์,'하ㄴ')

    def test_전환반복확정(자신):
        자신.ชนิด_ประเภท('echo ')
        자신.คีย์บอร์ด_รายการ.누름값(True,0xffe1)
        자신.คีย์บอร์ด_รายการ.누름값(True,32); 자신.คีย์บอร์ด_รายการ.누름값(True,32)
        자신.คีย์บอร์ด_รายการ.누름값(False,32); 자신.คีย์บอร์ด_รายการ.누름값(False,0xffe1)
        자신.assertTrue(자신.คีย์บอร์ด_รายการ.한글여부)
        자신.ชนิด_ประเภท('gksrmf'); 자신.กด_คีย์(0xff31); 자신.ชนิด_ประเภท(' English')
        자신.assertEqual(자신.ข้อความ_บัฟเฟอร์,'echo 한글 English')
        자신.assertFalse(자신.คีย์บอร์ด_รายการ.한글여부)
        자신.กด_คีย์(0xffc6); 자신.ชนิด_ประเภท('rk'); 자신.กด_คีย์(0xff51)
        자신.ชนิด_ประเภท('sk'); 자신.assertTrue(자신.ข้อความ_บัฟเฟอร์.endswith('가\x1b[D나'))

    def test_붙이기유니코드(자신):
        자신.กด_คีย์(0xffc6); 자신.ชนิด_ประเภท('rk')
        자신.คีย์บอร์ด_รายการ.คลิปบอร์ด_ค่า='วาง_ค่า'.encode()
        자신.คีย์บอร์ด_รายการ.누름값(True,0xffe3); 자신.คีย์บอร์ด_รายการ.누름값(True,0xffe1)
        자신.กด_คีย์(ord('v'))
        자신.คีย์บอร์ด_รายการ.누름값(False,0xffe1); 자신.คีย์บอร์ด_รายการ.누름값(False,0xffe3)
        자신.กด_คีย์(0x0100d55c); 자신.ชนิด_ประเภท('sk')
        자신.assertEqual(자신.ข้อความ_บัฟเฟอร์,'가붙여넣기한나')


if __name__ == '__main__': unittest.main()
