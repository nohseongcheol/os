/** 문자(文字), การเข้ารหัส_ค่า(符號): UTF-8 바이트와 UTF-16 문자열의 แปลง_ค่า_4633b7f3. นอร์มัลไลซ์_ค่า/องค์ประกอบ_ค่า_40acfcb7 입력기는 별개다. */
public final class 문자 {
    public static int 바이트수(byte[] ข้อมูล) { return ข้อมูล.length; }
    private 문자() {}
    public static int 길이(String ข้อความ) { return ข้อความ.length(); }
    public static boolean 같음(String กล้องหน้า_ค่า, String ย้อนกลับ_ค่า) { return กล้องหน้า_ค่า == null ? ย้อนกลับ_ค่า == null : กล้องหน้า_ค่า.equals(ย้อนกลับ_ค่า); }
    public static String วาง_ข้อความ(String กล้องหน้า_ค่า, String ย้อนกลับ_ค่า) { return กล้องหน้า_ค่า.concat(ย้อนกลับ_ค่า); }
    public static String ตัด_ค่า(String ข้อความ, int เรียกใช้งาน, int 끝) { return ข้อความ.substring(เรียกใช้งาน, 끝); }
    public static int แยกวิเคราะห์_จํานวนเต็ม(String ข้อความ) { try { return Integer.parseInt(ข้อความ); } catch (NumberFormatException ข้อผิดพลาด) { throw new หมายเลข_รูปแบบ_ความล้มเหลว("숫자의 형식이나 범위를 확인하십시오."); } }
    public static String 정수쓰기(int หมายเลข) { return Integer.toString(หมายเลข); }
    public static int 코드포인트수(String ข้อความ) {
        int หมายเลข = 0;
        for (int วน_ดัชนี = 0; วน_ดัชนี < ข้อความ.length(); วน_ดัชนี++, หมายเลข++) {
            int รหัสอักขระ = ข้อความ.charAt(วน_ดัชนี);
            if (รหัสอักขระ >= 0xd800 && รหัสอักขระ <= 0xdbff && วน_ดัชนี + 1 < ข้อความ.length() && ข้อความ.charAt(วน_ดัชนี + 1) >= 0xdc00 && ข้อความ.charAt(วน_ดัชนี + 1) <= 0xdfff) วน_ดัชนี++;
        }
        return หมายเลข;
    }
    public static byte[] เข้ารหัส(String ข้อความ) {
        byte[] 임시 = new byte[ข้อความ.length() * 3]; int 쓴수 = 0;
        for (int วน_ดัชนี = 0; วน_ดัชนี < ข้อความ.length(); วน_ดัชนี++) {
            int รหัสอักขระ = ข้อความ.charAt(วน_ดัชนี);
            if (รหัสอักขระ >= 0xd800 && รหัสอักขระ <= 0xdbff && วน_ดัชนี + 1 < ข้อความ.length() && ข้อความ.charAt(วน_ดัชนี + 1) >= 0xdc00 && ข้อความ.charAt(วน_ดัชนี + 1) <= 0xdfff) รหัสอักขระ = 0x10000 + ((รหัสอักขระ - 0xd800) << 10) + ข้อความ.charAt(++วน_ดัชนี) - 0xdc00;
            else if (รหัสอักขระ >= 0xd800 && รหัสอักขระ <= 0xdfff) รหัสอักขระ = '?';
            if (รหัสอักขระ < 128) 임시[쓴수++] = (byte)รหัสอักขระ;
            else if (รหัสอักขระ < 2048) { 임시[쓴수++] = (byte)(192 | รหัสอักขระ >> 6); 임시[쓴수++] = (byte)(128 | รหัสอักขระ & 63); }
            else if (รหัสอักขระ < 65536) { 임시[쓴수++] = (byte)(224 | รหัสอักขระ >> 12); 임시[쓴수++] = (byte)(128 | รหัสอักขระ >> 6 & 63); 임시[쓴수++] = (byte)(128 | รหัสอักขระ & 63); }
            else { 임시[쓴수++] = (byte)(240 | รหัสอักขระ >> 18); 임시[쓴수++] = (byte)(128 | รหัสอักขระ >> 12 & 63); 임시[쓴수++] = (byte)(128 | รหัสอักขระ >> 6 & 63); 임시[쓴수++] = (byte)(128 | รหัสอักขระ & 63); }
        }
        byte[] ผลลัพธ์ = new byte[쓴수]; System.arraycopy(임시, 0, ผลลัพธ์, 0, 쓴수); return ผลลัพธ์;
    }
    /** 잘못된 UTF-8은 잘못된인수예외으로 거부한다. */
    public static String ถอดรหัสลับ_ข้อมูล(byte[] ไบต์_ค่า) {
        StringBuilder ผลลัพธ์ = new StringBuilder();
        for (int วน_ดัชนี = 0; วน_ดัชนี < ไบต์_ค่า.length;) {
            int รหัสอักขระ = ไบต์_ค่า[วน_ดัชนี++] & 255, หมายเลข = รหัสอักขระ < 128 ? 0 : รหัสอักขระ >= 194 && รหัสอักขระ < 224 ? 1 : รหัสอักขระ >= 224 && รหัสอักขระ < 240 ? 2 : รหัสอักขระ >= 240 && รหัสอักขระ <= 244 ? 3 : -1;
            if (หมายเลข < 0 || ไบต์_ค่า.length - วน_ดัชนี < หมายเลข) throw new ไม่ถูกต้อง_อาร์กิวเมนต์_ข้อยกเว้น("잘못된 UTF-8");
            int 최소 = หมายเลข == 1 ? 128 : หมายเลข == 2 ? 2048 : หมายเลข == 3 ? 65536 : 0;
            if (หมายเลข > 0) รหัสอักขระ &= (1 << (6 - หมายเลข)) - 1;
            for (int ภายใน_ตําแหน่ง = 0; ภายใน_ตําแหน่ง < หมายเลข; ภายใน_ตําแหน่ง++) { int ย้อนกลับ_ค่า = ไบต์_ค่า[วน_ดัชนี++] & 255; if ((ย้อนกลับ_ค่า & 192) != 128) throw new ไม่ถูกต้อง_อาร์กิวเมนต์_ข้อยกเว้น("잘못된 UTF-8"); รหัสอักขระ = รหัสอักขระ << 6 | ย้อนกลับ_ค่า & 63; }
            if (รหัสอักขระ < 최소 || รหัสอักขระ > 0x10ffff || รหัสอักขระ >= 0xd800 && รหัสอักขระ <= 0xdfff) throw new ไม่ถูกต้อง_อาร์กิวเมนต์_ข้อยกเว้น("잘못된 UTF-8");
            if (รหัสอักขระ < 65536) ผลลัพธ์.append((char)รหัสอักขระ);
            else { รหัสอักขระ -= 65536; ผลลัพธ์.append((char)(0xd800 | รหัสอักขระ >> 10)); ผลลัพธ์.append((char)(0xdc00 | รหัสอักขระ & 1023)); }
        }
        return ผลลัพธ์.toString();
    }
}
