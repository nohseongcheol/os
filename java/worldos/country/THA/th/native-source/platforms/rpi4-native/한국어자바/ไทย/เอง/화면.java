package ไทย.เอง;
/** 화면(畫面): 부팅 때 선택한 크기의 เอง เคอร์เนล_ค่า RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int ค่า = เคอร์เนล_ค่า.화면너비(); if (ค่า < 0) throw new สถานะ_ข้อยกเว้น("프레임버퍼 없음"); return ค่า; }
    public static int 높이() { int ค่า = เคอร์เนล_ค่า.화면높이(); if (ค่า < 0) throw new สถานะ_ข้อยกเว้น("프레임버퍼 없음"); return ค่า; }
    public static void สี่เหลี่ยมผืนผ้า(int 가로, int แนวตั้ง_ตําแหน่ง, int 폭, int 높이, int 색) {
        if (가로 < 0 || แนวตั้ง_ตําแหน่ง < 0 || 폭 < 0 || 높이 < 0 || 가로 > 너비() || แนวตั้ง_ตําแหน่ง > 높이() || 폭 > 너비() - 가로 || 높이 > 높이() - แนวตั้ง_ตําแหน่ง) throw new ไม่ถูกต้อง_อาร์กิวเมนต์_ข้อยกเว้น("화면 คลิป");
        if (เคอร์เนล_ค่า.สี่เหลี่ยมผืนผ้า(가로, แนวตั้ง_ตําแหน่ง, 폭, 높이, 색) < 0) throw new สถานะ_ข้อยกเว้น("프레임버퍼 없음");
    }
    public static void ลบ_รายการ(int 색) { สี่เหลี่ยมผืนผ้า(0, 0, 너비(), 높이(), 색); }
    public static void 기다리기() { if (เคอร์เนล_ค่า.그림대기() < 0) throw new สถานะ_ข้อยกเว้น("대화형 입력 필요"); }
}
