package ประเทศไทย.JThaOS.ความจํา_ขอบเขต;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB เพจ_ค่า 연결과 เขียน 시 복사를 제공한다. */
public final class เพจ_ผู้จัดการ {
    public static final int ขนาดหน้ากระดาษ = 4096;

    private static final class เพจ_ค่า {
        private byte[] ข้อมูล = new byte[ขนาดหน้ากระดาษ];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class อีเมล_สเปซ {
        private final Map<Integer, เพจ_ค่า> เพจ_ตาราง = new HashMap<Integer, เพจ_ค่า>();
    }

    public อีเมล_สเปซ 새주소공간() {
        return new อีเมล_สเปซ();
    }

    public void แมป_เพจ(อีเมล_สเปซ อีเมล_ขอบเขต, int เลขที่อยู่เสมือน, boolean 쓰기가능) {
        int ดัชนี = เพจ_หมายเลข(เลขที่อยู่เสมือน);
        เพจ_ค่า 새쪽 = new เพจ_ค่า();
        새쪽.쓰기가능 = 쓰기가능;
        อีเมล_ขอบเขต.เพจ_ตาราง.put(Integer.valueOf(ดัชนี), 새쪽);
    }

    public อีเมล_สเปซ 쓰기시복사복제(อีเมล_สเปซ 원본) {
        อีเมล_สเปซ 복제본 = new อีเมล_สเปซ();
        for (Map.Entry<Integer, เพจ_ค่า> รายการ_ค่า : 원본.เพจ_ตาราง.entrySet()) {
            เพจ_ค่า 공유쪽 = รายการ_ค่า.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.เพจ_ตาราง.put(รายการ_ค่า.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(อีเมล_สเปซ อีเมล_ขอบเขต, int เลขที่อยู่เสมือน) {
        เพจ_ค่า เป้าหมาย = ค้นพบ_เพจ(อีเมล_ขอบเขต, เลขที่อยู่เสมือน);
        return เป้าหมาย.ข้อมูล[Math.floorMod(เลขที่อยู่เสมือน, ขนาดหน้ากระดาษ)];
    }

    public void 바이트쓰기(อีเมล_สเปซ อีเมล_ขอบเขต, int เลขที่อยู่เสมือน, byte ค่า) {
        int ดัชนี = เพจ_หมายเลข(เลขที่อยู่เสมือน);
        เพจ_ค่า เป้าหมาย = ค้นพบ_เพจ(อีเมล_ขอบเขต, เลขที่อยู่เสมือน);
        if (!เป้าหมาย.쓰기가능) {
            if (!เป้าหมาย.쓰기시복사) {
                throw new IllegalStateException("อ่าน 전용 쪽입니다.");
            }
            เป้าหมาย = เปิด_ส่วนตัว_เพจ(อีเมล_ขอบเขต, ดัชนี, เป้าหมาย);
        }
        เป้าหมาย.ข้อมูล[Math.floorMod(เลขที่อยู่เสมือน, ขนาดหน้ากระดาษ)] = ค่า;
    }

    public void 범위개인쓰기(อีเมล_สเปซ อีเมล_ขอบเขต, int เริ่ม_อีเมล, int ขนาด) {
        if (ขนาด < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int สิ้นสุดการโทร_อีเมล = Math.addExact(เริ่ม_อีเมล, ขนาด);
        for (int อีเมล = เริ่ม_อีเมล; อีเมล < สิ้นสุดการโทร_อีเมล; อีเมล = (เพจ_หมายเลข(อีเมล) + 1) * ขนาดหน้ากระดาษ) {
            int ดัชนี = เพจ_หมายเลข(อีเมล);
            เพจ_ค่า เป้าหมาย = ค้นพบ_เพจ(อีเมล_ขอบเขต, อีเมล);
            if (เป้าหมาย.쓰기시복사) {
                เปิด_ส่วนตัว_เพจ(อีเมล_ขอบเขต, ดัชนี, เป้าหมาย);
            } else {
                เป้าหมาย.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(อีเมล_สเปซ อีเมล_ขอบเขต, int เริ่ม_อีเมล, byte[] ข้อมูล) {
        for (int ดัชนี = 0; ดัชนี < ข้อมูล.length; ดัชนี++) {
            바이트쓰기(อีเมล_ขอบเขต, เริ่ม_อีเมล + ดัชนี, ข้อมูล[ดัชนี]);
        }
    }

    private เพจ_ค่า เปิด_ส่วนตัว_เพจ(อีเมล_สเปซ อีเมล_ขอบเขต, int ดัชนี, เพจ_ค่า 공유쪽) {
        เพจ_ค่า ส่วนตัว_เพจ = new เพจ_ค่า();
        ส่วนตัว_เพจ.ข้อมูล = Arrays.copyOf(공유쪽.ข้อมูล, 공유쪽.ข้อมูล.length);
        ส่วนตัว_เพจ.쓰기가능 = true;
        ส่วนตัว_เพจ.쓰기시복사 = false;
        공유쪽.참조수--;
        อีเมล_ขอบเขต.เพจ_ตาราง.put(Integer.valueOf(ดัชนี), ส่วนตัว_เพจ);
        return ส่วนตัว_เพจ;
    }

    private เพจ_ค่า ค้นพบ_เพจ(อีเมล_สเปซ อีเมล_ขอบเขต, int อีเมล) {
        เพจ_ค่า เป้าหมาย = อีเมล_ขอบเขต.เพจ_ตาราง.get(Integer.valueOf(เพจ_หมายเลข(อีเมล)));
        if (เป้าหมาย == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return เป้าหมาย;
    }

    private int เพจ_หมายเลข(int อีเมล) {
        if (อีเมล < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return อีเมล / ขนาดหน้ากระดาษ;
    }
}

