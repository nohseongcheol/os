package ประเทศไทย.JThaOS.แก่นระบบ;

import ประเทศไทย.JThaOS.ความจํา_ขอบเขต.ความจํา_ผู้จัดการ;
import ประเทศไทย.JThaOS.ความจํา_ขอบเขต.เพจ_ผู้จัดการ;
import ประเทศไทย.JThaOS.입력.입력관리자;
import ประเทศไทย.JThaOS.작업.กระบวนการ_ค่า;
import ประเทศไทย.JThaOS.작업.ผู้จัดกําหนดการ;
import ประเทศไทย.JThaOS.체계호출.체계호출;
import ประเทศไทย.JThaOS.ระบบแฟ้ม.파일서술자표;
import ประเทศไทย.JThaOS.ระบบแฟ้ม.ระบบแฟ้ม;

/** Java 관리 커널의 조립과 시작을 담당한다. */
public final class แก่นระบบ {
    private final ฮาร์ดแวร์_ค่า อุปกรณ์_ค่า;
    private final ความจํา_ผู้จัดการ ความจํา_ขอบเขต = new ความจํา_ผู้จัดการ(32 * 1024 * 1024);
    private final เพจ_ผู้จัดการ 쪽관리 = new เพจ_ผู้จัดการ();
    private final ระบบแฟ้ม ระบบแฟ้ม = new ระบบแฟ้ม();
    private final ผู้จัดกําหนดการ ผู้จัดกําหนดการ = new ผู้จัดกําหนดการ(쪽관리);
    private final 입력관리자 입력관리 = new 입력관리자(256);
    private final กระบวนการ_ค่า 첫과정;
    private final 체계호출 체계호출;

    public แก่นระบบ(ฮาร์ดแวร์_ค่า อุปกรณ์_ค่า) {
        this.อุปกรณ์_ค่า = อุปกรณ์_ค่า;
        첫과정 = ผู้จัดกําหนดการ.첫과정(new 파일서술자표(ระบบแฟ้ม));
        체계호출 = new 체계호출(ระบบแฟ้ม, 쪽관리, ผู้จัดกําหนดการ, อุปกรณ์_ค่า, 입력관리);
    }

    public void เรียกใช้งาน() {
        อุปกรณ์_ค่า.직렬출력("=== JThaOS 관리 เคอร์เนล_ค่า ===\n");
    }

    public void ดําเนินการ_ขั้นตอน() {
        อุปกรณ์_ค่า.중앙처리장치멈춤();
    }

    public ความจํา_ผู้จัดการ ความจํา_ขอบเขต() {
        return ความจํา_ขอบเขต;
    }

    public เพจ_ผู้จัดการ 쪽관리() {
        return 쪽관리;
    }

    public ระบบแฟ้ม ระบบแฟ้ม() {
        return ระบบแฟ้ม;
    }

    public ผู้จัดกําหนดการ ผู้จัดกําหนดการ() {
        return ผู้จัดกําหนดการ;
    }

    public 입력관리자 입력관리() {
        return 입력관리;
    }

    public กระบวนการ_ค่า 첫과정() {
        return 첫과정;
    }

    public 체계호출 체계호출() {
        return 체계호출;
    }
}
