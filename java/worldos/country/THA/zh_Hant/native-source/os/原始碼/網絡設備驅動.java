/** PCI RTL8139（10ec:8139），一個傳送緩衝區與 8 KiB 接收環；使用輪詢而非中斷。 */
public final class 網絡設備驅動 {
    static int 輸入輸出基底地址 = 0;
    static int 接收位置 = 0, 傳輸槽 = 0;
    static int[] 設備地址 = new int[6];
    static int 傳輸個數 = 0, 接收個數 = 0, 錯誤個數 = 0;

    static int 讀取設置(int 設備編號, int 位置) {
        設備.寫入輸入輸出整數(0xcf8, 0x80000000 | (設備編號 << 11) | 位置);
        return 設備.讀取輸入輸出整數(0xcfc);
    }

    static boolean 準備() {
        int 設備編號 = -1;
        for (int 編號 = 0; 編號 < 32; 編號++) {
            if (讀取設置(編號, 0) == 0x813910ec) { 設備編號 = 編號; break; }
        }
        if (設備編號 < 0) return false;
        int 默認值 = 讀取設置(設備編號, 0x10);
        if ((默認值 & 1) == 0 || (默認值 & 0xfffffffc) < 0x100 || (默認值 & 0xfffffffc) > 65535) return false;
        輸入輸出基底地址 = 默認值 & 0xfffc;
        int 命令 = 讀取設置(設備編號, 4);
        設備.寫入輸入輸出整數(0xcf8, 0x80000004 | (設備編號 << 11));
        設備.寫入輸入輸出短整數(0xcfc, 命令 | 5); // 啟用 I/O 與匯流排主控，不變更 PCI 狀態位元。
        設備.寫入輸入輸出位元組(輸入輸出基底地址 + 0x52, 0);
        if (!重置值()) { 輸入輸出基底地址 = 0; return false; }
        for (int 編號 = 0; 編號 < 6; 編號++) 設備地址[編號] = 設備.讀取輸入輸出位元組(輸入輸出基底地址 + 編號);
        return true;
    }

    static boolean 重置值() {
        設備.寫入輸入輸出位元組(輸入輸出基底地址 + 0x37, 0x10);
        int 運行 = 設備.毫秒();
        while ((設備.讀取輸入輸出位元組(輸入輸出基底地址 + 0x37) & 0x10) != 0)
            if (設備.毫秒() - 運行 > 100) return false;
        接收位置 = 0; 傳輸槽 = 0;
        設備.寫入輸入輸出整數(輸入輸出基底地址 + 0x30, 設備.網路記憶體());
        for (int 編號 = 0; 編號 < 4; 編號++) 設備.寫入輸入輸出整數(輸入輸出基底地址 + 0x20 + 編號 * 4, 設備.網路記憶體() + 12288);
        設備.寫入輸入輸出短整數(輸入輸出基底地址 + 0x3c, 0);
        設備.寫入輸入輸出短整數(輸入輸出基底地址 + 0x3e, 0xffff);
        設備.寫入輸入輸出位元組(輸入輸出基底地址 + 0x37, 0x0c);
        設備.寫入輸入輸出整數(輸入輸出基底地址 + 0x44, 0x0000e78a); // 接收本機位址與廣播；繞回時連續儲存，容量 8 KiB。
        設備.寫入輸入輸出整數(輸入輸出基底地址 + 0x40, 0x03000600);
        return true;
    }

    static int 發送(int[] 資料, int 長度) {
        if (輸入輸出基底地址 == 0) return -19;
        if (長度 < 14 || 長度 > 1514) return -90;
        int 運行狀態埠 = 輸入輸出基底地址 + 0x10 + 傳輸槽 * 4;
        int 運行 = 設備.毫秒();
        while ((設備.讀取輸入輸出整數(運行狀態埠) & 0x2000) == 0)
            if (設備.毫秒() - 運行 > 100) return -110;
        int 大小 = 長度 < 60 ? 60 : 長度;
        for (int 編號 = 0; 編號 < 大小; 編號++)
            設備.寫入記憶體(設備.網路記憶體() + 12288 + 編號, 編號 < 長度 ? 資料[編號] : 0);
        設備.寫入輸入輸出整數(運行狀態埠, 大小 | 0x00080000);
        運行 = 設備.毫秒();
        while ((設備.讀取輸入輸出整數(運行狀態埠) & 0xe0008000) == 0)
            if (設備.毫秒() - 運行 > 100) return -110;
        if ((設備.讀取輸入輸出整數(運行狀態埠) & 0x8000) == 0) { 錯誤個數++; return -5; }
        傳輸槽 = (傳輸槽 + 1) & 3;
        傳輸個數++;
        return 長度;
    }

    static int 接收(int[] 資料) {
        if (輸入輸出基底地址 == 0) return 0;
        if ((設備.讀取輸入輸出位元組(輸入輸出基底地址 + 0x3e) & 0x50) != 0) {
            錯誤個數++;
            if (!重置值()) 輸入輸出基底地址 = 0;
            return 0;
        }
        if ((設備.讀取輸入輸出位元組(輸入輸出基底地址 + 0x37) & 1) != 0) return 0;
        int 頭值 = 設備.網路記憶體() + 接收位置;
        int 狀態值 = 執行管理.短整數值(頭值), 大小 = 執行管理.短整數值(頭值 + 2);
        if (大小 == 0xfff0) return 0; // DMA 正在進行。
        if (大小 < 4 || 大小 > 1518) {
            錯誤個數++;
            if (!重置值()) 輸入輸出基底地址 = 0;
            return 0;
        }
        int 長度 = 大小 - 4;
        if ((狀態值 & 1) != 0) {
            for (int 編號 = 0; 編號 < 長度; 編號++) 資料[編號] = 設備.讀取記憶體(頭值 + 4 + 編號);
            接收個數++;
        } else { 長度 = 0; 錯誤個數++; }
        接收位置 = (接收位置 + 大小 + 4 + 3) & ~3;
        接收位置 &= 8191;
        設備.寫入輸入輸出短整數(輸入輸出基底地址 + 0x38, (接收位置 - 16) & 65535);
        設備.寫入輸入輸出短整數(輸入輸出基底地址 + 0x3e, 0x000f);
        return 長度;
    }
}
