#include "網路ABI.h"

int 開始用戶程式(int 實參) {
    (void)實參;
    struct 互聯網通訊端地址 地址 = {0};
    地址.地址族 = 互聯網族;
    地址.埠編號 = 網路短整數(9260);
    地址.互聯網地址.地址值 = 網路整數(環回地址);
    int 服務器值 = 創建端點(互聯網族, 流網路, 流傳輸通訊協定);
    if (服務器值 < 0 || 綁定地址(服務器值, (struct 通訊端地址 *)&地址, sizeof(地址)) < 0 ||
        等待狀態用於網路連接狀態(服務器值, 4) < 0) return 1;
    if (接受網路連接狀態(服務器值, 0, 0) != -1 || 錯誤編號 != 11) return 2;
    int 客戶機值 = 創建端點(互聯網族, 流網路, 流傳輸通訊協定);
    if (客戶機值 < 0 || 連接網路(客戶機值, (struct 通訊端地址 *)&地址, sizeof(地址)) < 0) return 3;
    int 連接 = 接受網路連接狀態(服務器值, 0, 0);
    if (連接 < 0) return 4;
    unsigned char 項目目標側發送[1500], 已接收項目[1500];
    for (int 數 = 0; 數 < 1500; 數++) 項目目標側發送[數] = (unsigned char)數;
    int 已發送個數 = 0;
    while (已發送個數 < 1024) {
        int 長度 = 寫入檔案資料(客戶機值, 項目目標側發送 + 已發送個數, sizeof(項目目標側發送) - 已發送個數);
        if (長度 <= 0) return 5;
        已發送個數 += 長度;
    }
    if (寫入檔案資料(客戶機值, 項目目標側發送, 1) != -1 || 錯誤編號 != 11) return 6;
    /* 상대가 닫아도 이미 도착한 자료를 構建全部 읽은 後端值 EOF가 된다. */
    關閉檔案(客戶機值);
    int 已接收個數 = 0;
    while (已接收個數 < 已發送個數) {
        int 長度 = 讀取檔案資料(連接, 已接收項目 + 已接收個數, sizeof(已接收項目) - 已接收個數);
        if (長度 <= 0) return 7;
        已接收個數 += 長度;
    }
    for (int 數 = 0; 數 < 已接收個數; 數++) if (已接收項目[數] != 項目目標側發送[數]) return 8;
    if (讀取檔案資料(連接, 已接收項目, 1) != 0) return 9;
    if (寫入檔案資料(連接, 項目目標側發送, 1) != -1 || 錯誤編號 != 32) return 10;
    關閉檔案(連接); 關閉檔案(服務器值);
    const char 結果[] = "C posix-kor 연결형 通信 PASS\n";
    寫入檔案資料(1, 結果, sizeof(結果) - 1);
    return 0;
}
