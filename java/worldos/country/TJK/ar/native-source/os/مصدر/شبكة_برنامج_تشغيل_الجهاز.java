/** PCI RTL8139 (10ec:8139), 단일 يرسل_قيمة 버퍼와 8KiB يستلم_قيمة يكرر_قيمة. 인터럽트 대신 폴링한다. */
public final class شبكة_برنامج_تشغيل_الجهاز {
    static int 입출력기준주소 = 0;
    static int يستلم_منصب = 0, 송신칸 = 0;
    static int[] جهاز_عنوان = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int يقرأ_إعدادات(int جهاز_رقم, int موضع) {
        جهاز_قيمة.입출력정수쓰기(0xcf8, 0x80000000 | (جهاز_رقم << 11) | موضع);
        return جهاز_قيمة.입출력정수읽기(0xcfc);
    }

    static boolean إعداد() {
        int جهاز_رقم = -1;
        for (int فهرس = 0; فهرس < 32; فهرس++) {
            if (يقرأ_إعدادات(فهرس, 0) == 0x813910ec) { جهاز_رقم = فهرس; break; }
        }
        if (جهاز_رقم < 0) return false;
        int قيمة_افتراضية = يقرأ_إعدادات(جهاز_رقم, 0x10);
        if ((قيمة_افتراضية & 1) == 0 || (قيمة_افتراضية & 0xfffffffc) < 0x100 || (قيمة_افتراضية & 0xfffffffc) > 65535) return false;
        입출력기준주소 = قيمة_افتراضية & 0xfffc;
        int أمر = يقرأ_إعدادات(جهاز_رقم, 4);
        جهاز_قيمة.입출력정수쓰기(0xcf8, 0x80000004 | (جهاز_رقم << 11));
        جهاز_قيمة.입출력짧은수쓰기(0xcfc, أمر | 5); // I/O 및 bus master يسمح_قيمة, PCI حالة_قيمة 비트는 건드리지 않음
        جهاز_قيمة.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!إعادة_ضبط_قيمة()) { 입출력기준주소 = 0; return false; }
        for (int فهرس = 0; فهرس < 6; فهرس++) جهاز_عنوان[فهرس] = جهاز_قيمة.입출력바이트읽기(입출력기준주소 + فهرس);
        return true;
    }

    static boolean إعادة_ضبط_قيمة() {
        جهاز_قيمة.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int تشغيل = جهاز_قيمة.밀리초();
        while ((جهاز_قيمة.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (جهاز_قيمة.밀리초() - تشغيل > 100) return false;
        يستلم_منصب = 0; 송신칸 = 0;
        جهاز_قيمة.입출력정수쓰기(입출력기준주소 + 0x30, جهاز_قيمة.شبكة_ذاكرة());
        for (int فهرس = 0; فهرس < 4; فهرس++) جهاز_قيمة.입출력정수쓰기(입출력기준주소 + 0x20 + فهرس * 4, جهاز_قيمة.شبكة_ذاكرة() + 12288);
        جهاز_قيمة.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        جهاز_قيمة.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        جهاز_قيمة.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        جهاز_قيمة.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/بث_قيمة_3df56558, wrap 연속 مخزن_قيمة, 8KiB
        جهاز_قيمة.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int يرسل(int[] بيانات, int 길이) {
        if (입출력기준주소 == 0) return -19;
        if (길이 < 14 || 길이 > 1514) return -90;
        int توفر_منفذ = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int تشغيل = جهاز_قيمة.밀리초();
        while ((جهاز_قيمة.입출력정수읽기(توفر_منفذ) & 0x2000) == 0)
            if (جهاز_قيمة.밀리초() - تشغيل > 100) return -110;
        int حجم = 길이 < 60 ? 60 : 길이;
        for (int فهرس = 0; فهرس < حجم; فهرس++)
            جهاز_قيمة.كتابة_ذاكرة(جهاز_قيمة.شبكة_ذاكرة() + 12288 + فهرس, فهرس < 길이 ? بيانات[فهرس] : 0);
        جهاز_قيمة.입출력정수쓰기(توفر_منفذ, حجم | 0x00080000);
        تشغيل = جهاز_قيمة.밀리초();
        while ((جهاز_قيمة.입출력정수읽기(توفر_منفذ) & 0xe0008000) == 0)
            if (جهاز_قيمة.밀리초() - تشغيل > 100) return -110;
        if ((جهاز_قيمة.입출력정수읽기(توفر_منفذ) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return 길이;
    }

    static int يستلم(int[] بيانات) {
        if (입출력기준주소 == 0) return 0;
        if ((جهاز_قيمة.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!إعادة_ضبط_قيمة()) 입출력기준주소 = 0;
            return 0;
        }
        if ((جهاز_قيمة.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int رأس_قيمة = جهاز_قيمة.شبكة_ذاكرة() + يستلم_منصب;
        int حالة_قيمة = 실행관리.짧은수(رأس_قيمة), حجم = 실행관리.짧은수(رأس_قيمة + 2);
        if (حجم == 0xfff0) return 0; // DMA 진행 중
        if (حجم < 4 || حجم > 1518) {
            오류수++;
            if (!إعادة_ضبط_قيمة()) 입출력기준주소 = 0;
            return 0;
        }
        int 길이 = حجم - 4;
        if ((حالة_قيمة & 1) != 0) {
            for (int فهرس = 0; فهرس < 길이; فهرس++) بيانات[فهرس] = جهاز_قيمة.يقرأ_ذاكرة(رأس_قيمة + 4 + فهرس);
            수신수++;
        } else { 길이 = 0; 오류수++; }
        يستلم_منصب = (يستلم_منصب + حجم + 4 + 3) & ~3;
        يستلم_منصب &= 8191;
        جهاز_قيمة.입출력짧은수쓰기(입출력기준주소 + 0x38, (يستلم_منصب - 16) & 65535);
        جهاز_قيمة.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return 길이;
    }
}
