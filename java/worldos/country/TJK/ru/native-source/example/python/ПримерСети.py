from русский import текстовыйВывод, открыть_датаграмма, написать_внешний_датаграмма, получить_датаграмма, Close_сеть, 밀리초
from русский import системная_ошибка, 다시시도오류, кодировать_SMS, 명령인수, целое_число
участник = открыть_датаграмма(0)
try:
    датаграмма = кодировать_SMS("PYTHON UDP ru")
    написать_внешний_датаграмма(участник, "10.0.2.2", целое_число(명령인수[1]), датаграмма)
    запустить = 밀리초()
    while True:
        try:
            ответ, порт_ЗНАЧЕН = получить_датаграмма(участник)
            break
        except системная_ошибка as ошибка:
            if ошибка.ИНДЕКС != 다시시도오류 or 밀리초() - запустить >= 700:
                raise
    assert ответ == датаграмма
    текстовыйВывод("PYTHON 네트워크 проверять: UDP ru")
finally:
    Close_сеть(участник)
