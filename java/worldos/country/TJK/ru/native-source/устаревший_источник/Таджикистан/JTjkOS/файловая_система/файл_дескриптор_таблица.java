package Таджикистан.JTjkOS.файловая_система;

import java.util.HashMap;
import java.util.Map;

/** 과정마다 독립적인 서술자와 공유 가능한 열린 файл 설명을 유지한다. */
public final class файл_дескриптор_таблица {
    private static final int 최대서술자 = 32;

    private static final class дескриптор_ввод {
        private final файловая_система.열린파일 열린파일;
        private boolean 실행시닫기;

        дескриптор_ввод(файловая_система.열린파일 열린파일) {
            this.열린파일 = 열린파일;
        }
    }

    private final файловая_система файловая_система;
    private final Map<Integer, дескриптор_ввод> 서술자들 = new HashMap<Integer, дескриптор_ввод>();

    public файл_дескриптор_таблица(файловая_система файловая_система) {
        this.файловая_система = файловая_система;
    }

    public int Открыть(String Название) {
        файловая_система.열린파일 열린파일 = файловая_система.Открыть(Название);
        if (열린파일 == null) {
            return -2;
        }
        int ИНДЕКС = пустой_ИНДЕКС(3);
        if (ИНДЕКС < 0) {
            return -24;
        }
        서술자들.put(Integer.valueOf(ИНДЕКС), new дескриптор_ввод(열린파일));
        return ИНДЕКС;
    }

    public int Чтение(int ИНДЕКС, byte[] получить_цель, int Размер) {
        дескриптор_ввод ввод_ЗНАЧЕН = 서술자들.get(Integer.valueOf(ИНДЕКС));
        if (ввод_ЗНАЧЕН == null) {
            return -9;
        }
        if (Размер < 0 || Размер > получить_цель.length) {
            return -22;
        }
        int 남음 = ввод_ЗНАЧЕН.열린파일.данные.length - ввод_ЗНАЧЕН.열린파일.позиция;
        int чтение_изменить_размер = Math.min(Размер, Math.max(남음, 0));
        System.arraycopy(ввод_ЗНАЧЕН.열린파일.данные, ввод_ЗНАЧЕН.열린파일.позиция, получить_цель, 0, чтение_изменить_размер);
        ввод_ЗНАЧЕН.열린파일.позиция += чтение_изменить_размер;
        return чтение_изменить_размер;
    }

    public int переместить_позиция(int ИНДЕКС, int 거리, int задача_корень) {
        дескриптор_ввод ввод_ЗНАЧЕН = 서술자들.get(Integer.valueOf(ИНДЕКС));
        if (ввод_ЗНАЧЕН == null) {
            return -9;
        }
        int фон_ЗНАЧЕН;
        if (задача_корень == 0) {
            фон_ЗНАЧЕН = 0;
        } else if (задача_корень == 1) {
            фон_ЗНАЧЕН = ввод_ЗНАЧЕН.열린파일.позиция;
        } else if (задача_корень == 2) {
            фон_ЗНАЧЕН = ввод_ЗНАЧЕН.열린파일.данные.length;
        } else {
            return -22;
        }
        int 새위치 = фон_ЗНАЧЕН + 거리;
        if (새위치 < 0) {
            return -22;
        }
        ввод_ЗНАЧЕН.열린파일.позиция = 새위치;
        return 새위치;
    }

    public int Закрыть(int ИНДЕКС) {
        дескриптор_ввод ввод_ЗНАЧЕН = 서술자들.remove(Integer.valueOf(ИНДЕКС));
        if (ввод_ЗНАЧЕН == null) {
            return -9;
        }
        ввод_ЗНАЧЕН.열린파일.ссылка_СЧЁТ--;
        return 0;
    }

    public int 복제서술자(int ИНДЕКС, int 최소번호) {
        дескриптор_ввод ввод_ЗНАЧЕН = 서술자들.get(Integer.valueOf(ИНДЕКС));
        if (ввод_ЗНАЧЕН == null) {
            return -9;
        }
        int новый_номер = пустой_ИНДЕКС(최소번호);
        if (новый_номер < 0) {
            return -24;
        }
        ввод_ЗНАЧЕН.열린파일.ссылка_СЧЁТ++;
        서술자들.put(Integer.valueOf(новый_номер), new дескриптор_ввод(ввод_ЗНАЧЕН.열린파일));
        return новый_номер;
    }

    public int 지정복제(int ИНДЕКС, int новый_номер) {
        if (ИНДЕКС == новый_номер) {
            return 서술자들.containsKey(Integer.valueOf(ИНДЕКС)) ? ИНДЕКС : -9;
        }
        if (новый_номер < 0 || новый_номер >= 최대서술자) {
            return -9;
        }
        дескриптор_ввод 원본 = 서술자들.get(Integer.valueOf(ИНДЕКС));
        if (원본 == null) {
            return -9;
        }
        if (서술자들.containsKey(Integer.valueOf(новый_номер))) {
            Закрыть(новый_номер);
        }
        원본.열린파일.ссылка_СЧЁТ++;
        서술자들.put(Integer.valueOf(новый_номер), new дескриптор_ввод(원본.열린파일));
        return новый_номер;
    }

    public int 실행시닫기설정(int ИНДЕКС, boolean ЗНАЧЕН) {
        дескриптор_ввод ввод_ЗНАЧЕН = 서술자들.get(Integer.valueOf(ИНДЕКС));
        if (ввод_ЗНАЧЕН == null) {
            return -9;
        }
        ввод_ЗНАЧЕН.실행시닫기 = ЗНАЧЕН;
        return 0;
    }

    public int 실행시닫기값(int ИНДЕКС) {
        дескриптор_ввод ввод_ЗНАЧЕН = 서술자들.get(Integer.valueOf(ИНДЕКС));
        if (ввод_ЗНАЧЕН == null) {
            return -9;
        }
        return ввод_ЗНАЧЕН.실행시닫기 ? 1 : 0;
    }

    public файл_сведения msinfo32_exe(int ИНДЕКС) {
        if (ИНДЕКС >= 0 && ИНДЕКС <= 2) {
            return new файл_сведения(0, 0020666);
        }
        дескриптор_ввод ввод_ЗНАЧЕН = 서술자들.get(Integer.valueOf(ИНДЕКС));
        if (ввод_ЗНАЧЕН == null) {
            return null;
        }
        return new файл_сведения(ввод_ЗНАЧЕН.열린파일.данные.length, 0100444);
    }

    public void 실행시닫기() {
        Integer[] 번호들 = 서술자들.keySet().toArray(new Integer[0]);
        for (Integer ИНДЕКС : 번호들) {
            дескриптор_ввод ввод_ЗНАЧЕН = 서술자들.get(ИНДЕКС);
            if (ввод_ЗНАЧЕН != null && ввод_ЗНАЧЕН.실행시닫기) {
                Закрыть(ИНДЕКС.intValue());
            }
        }
    }

    public boolean ИТ_службы_открыть(int ИНДЕКС) {
        return 서술자들.containsKey(Integer.valueOf(ИНДЕКС));
    }

    public файл_дескриптор_таблица клон_ЗНАЧЕН() {
        файл_дескриптор_таблица результат = new файл_дескриптор_таблица(файловая_система);
        for (Map.Entry<Integer, дескриптор_ввод> ввод_ЗНАЧЕН : 서술자들.entrySet()) {
            ввод_ЗНАЧЕН.getValue().열린파일.ссылка_СЧЁТ++;
            дескриптор_ввод 새서술자 = new дескриптор_ввод(ввод_ЗНАЧЕН.getValue().열린파일);
            새서술자.실행시닫기 = ввод_ЗНАЧЕН.getValue().실행시닫기;
            результат.서술자들.put(ввод_ЗНАЧЕН.getKey(), 새서술자);
        }
        return результат;
    }

    private int пустой_ИНДЕКС(int 최소번호) {
        for (int ИНДЕКС = Math.max(0, 최소번호); ИНДЕКС < 최대서술자; ИНДЕКС++) {
            if (!서술자들.containsKey(Integer.valueOf(ИНДЕКС))) {
                return ИНДЕКС;
            }
        }
        return -1;
    }
}
