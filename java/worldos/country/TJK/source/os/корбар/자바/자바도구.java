/** 게스트 Абзорҳо 공통 출력 및 ASCII Файл Ном Раванд_қимат_ворида. */
public final class 자바도구 {
    /** UTF-8 байт_қимат 배열을 같은 배열의 UTF-16 단위로 바꾼다. 잘못된 입력은 거부. */
    static int 원문해독(int[] иттилоот, int дарозӣ_қимат) {
        int Хондан = 0, Навиштан = 0;
        if (дарозӣ_қимат >= 3 && иттилоот[0] == 239 && иттилоот[1] == 187 && иттилоот[2] == 191) Хондан = 3;
        while (Хондан < дарозӣ_қимат) {
            int қимат = иттилоот[Хондан++], 수 = 0, 최소 = 0;
            if (қимат >= 194 && қимат <= 223) { 수 = 1; 최소 = 128; қимат &= 31; }
            else if (қимат >= 224 && қимат <= 239) { 수 = 2; 최소 = 2048; қимат &= 15; }
            else if (қимат >= 240 && қимат <= 244) { 수 = 3; 최소 = 65536; қимат &= 7; }
            else if (қимат >= 128 || қимат < 0) return -1;
            if (수 > дарозӣ_қимат - Хондан) return -1;
            for (int i = 0; i < 수; i++) {
                int 다음 = иттилоот[Хондан++]; if ((다음 & 192) != 128) return -1;
                қимат = (қимат << 6) | (다음 & 63);
            }
            if (қимат < 최소 || қимат > 0x10ffff || (қимат >= 0xd800 && қимат <= 0xdfff)) return -1;
            if (қимат >= 65536) { қимат -= 65536; иттилоот[Навиштан++] = 0xd800 | (қимат >> 10); иттилоот[Навиштан++] = 0xdc00 | (қимат & 1023); }
            else иттилоот[Навиштан++] = қимат;
        }
        return Навиштан;
    }
    static void 수쓰기(int қимат) {
        if (қимат < 0) корбар.навиштан_аломат_қимат('-'); else қимат = -қимат;
        int 자리 = 1000000000;
        boolean порча = false;
        while (자리 != 0) {
            int 수 = -(қимат / 자리);
            if (수 != 0 || порча || 자리 == 1) { корбар.навиштан_аломат_қимат('0' + 수); порча = true; }
            қимат %= 자리; 자리 /= 10;
        }
    }
    static int Ном(int[] ҷои_таъинот_қимат, String 원본) {
        if (원본.length() >= ҷои_таъинот_қимат.length) return -1;
        for (int 수 = 0; 수 < ҷои_таъинот_қимат.length; 수++) ҷои_таъинот_қимат[수] = 수 < 원본.length() ? 원본.charAt(수) : 0;
        return 원본.length();
    }
    static boolean 같음(String 가, String 나) {
        if (가.length() != 나.length()) return false;
        for (int 수 = 0; 수 < 가.length(); 수++) if (가.charAt(수) != 나.charAt(수)) return false;
        return true;
    }
}
