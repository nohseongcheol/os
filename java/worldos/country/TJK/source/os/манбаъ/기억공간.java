/** 부팅 Маълумоти_система 조회와 4KiB 고정 андоза_кардан 작업 қисмат_қимат татбиқ_кардан_Захирагоҳ/반환. 일반 물리 саҳифа_қимат 관리자는 아니다. */
public final class 기억공간 {
    static int[] қисмат_қимат = new int[8192];
    static int[] 사용 = new int[8];

    static int 정수읽기(int суроға) {
        return мобилӣ_қимат.기억읽기(суроға) | (мобилӣ_қимат.기억읽기(суроға + 1) << 8)
            | (мобилӣ_қимат.기억읽기(суроға + 2) << 16) | (мобилӣ_қимат.기억읽기(суроға + 3) << 24);
    }

    static int 위쪽기억크기() {
        int Маълумоти_система = мобилӣ_қимат.부팅정보();
        if (мобилӣ_қимат.부팅표식() != 0x2badb002 || Маълумоти_система == 0 || (정수읽기(Маълумоти_система) & 1) == 0) return -1;
        return 정수읽기(Маълумоти_система + 8);
    }

    static int татбиқ_кардан_Захирагоҳ() {
        for (int индекс = 0; индекс < 사용.length; индекс++) {
            if (사용[индекс] == 0) {
                사용[индекс] = 1;
                for (int ковокӣ_ворида = 0; ковокӣ_ворида < 1024; ковокӣ_ворида++) қисмат_қимат[индекс * 1024 + ковокӣ_ворида] = 0;
                return индекс;
            }
        }
        return -1;
    }

    static boolean 반환(int индекс) {
        if (индекс < 0 || индекс >= 사용.length || 사용[индекс] == 0) return false;
        사용[индекс] = 0;
        return true;
    }

    static int 사용개수() {
        int 개수 = 0;
        for (int индекс = 0; индекс < 사용.length; индекс++) 개수 += 사용[индекс];
        return 개수;
    }
}
