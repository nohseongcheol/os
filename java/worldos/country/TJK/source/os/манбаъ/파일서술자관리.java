    static int 기술찾기(int 파일서술자) {
        if (파일서술자 < 0 || 파일서술자 >= 서술자한도) return -9;
        return кушодан_дастак[파일서술자] - 1;
    }
    static int 빈서술자(int порча) {
        for (int индекс = порча; индекс < 서술자한도; индекс++) if (кушодан_дастак[индекс] == 0) return индекс;
        return -24;
    }
    static int холӣ_дастак() {
        for (int индекс = 0; индекс < 서술자한도; индекс++) if (참조수[индекс] == 0) return индекс;
        return -24;
    }
    static int ПАЙВАСТ(int 서술자, int 기술, int 파일종류, int файл_ҳадаф, int Танзимот) {
        кушодан_дастак[서술자] = 기술 + 1; 서술자설정[서술자] = (Танзимот & 실행시닫기) != 0 ? 1 : 0;
        종류[기술] = 파일종류; ҳадаф[기술] = файл_ҳадаф; 참조수[기술] = 1;
        кушодан_Танзимот[기술] = Танзимот & (3 | 이어쓰기 | 기다리지않기); 파일위치[기술] = 0;
        Шабака_дастак[기술] = 0; 수신대기밀리초[기술] = 0;
        return 서술자;
    }
    static void Оғоз_Раванд() {
        과정정리();
        for (int индекс = 0; индекс < 3; индекс++) ПАЙВАСТ(индекс, индекс, 1, индекс, индекс == 0 ? 0 : 1);
    }
    static void 과정정리() {
        for (int индекс = 0; индекс < 서술자한도; индекс++) if (кушодан_дастак[индекс] != 0) пӯшидан_файл(индекс);
    }
    static int пӯшидан_файл(int 서술자) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0) return -9;
        кушодан_дастак[서술자] = 0; 서술자설정[서술자] = 0;
        참조수[기술]--;
        if (참조수[기술] == 0) {
            if (종류[기술] == 2) ҳофиза_системаи_файлӣ.열림수[ҳадаф[기술]]--;
            if (종류[기술] == 3 && Шабака_дастак[기술] != 0) Шабака_ҷамъ.Пӯшидан(Шабака_дастак[기술]);
            종류[기술] = 0;
        }
        return 0;
    }
    // C 경로는 NUL 끝 байт_қимат 문자열이다. 루트의 한 이름만 지원한다.
    static int 경로읽기(int суроға) {
        if (!실행관리.клип(суроға, 1)) return -14;
        int 위치 = мобилӣ_қимат.기억읽기(суроға) == '/' ? 1 : 0;
        for (int дарозӣ_қимат = 0; дарозӣ_қимат < 64; дарозӣ_қимат++) {
            if (!실행관리.клип(суроға + 위치 + дарозӣ_қимат, 1)) return -14;
            int қимат = мобилӣ_қимат.기억읽기(суроға + 위치 + дарозӣ_қимат);
            масир_ном[дарозӣ_қимат] = қимат;
            if (қимат == 0) return дарозӣ_қимат == 0 ? -2 : (ҳофиза_системаи_файлӣ.санҷиш_ном(масир_ном, дарозӣ_қимат) ? дарозӣ_қимат : -22);
            if (қимат == '/') return -20;
        }
        return -36;
    }
    static int кушодан_файл(int ном_суроға, int Танзимот, int 허가) {
        int дарозӣ_қимат = 경로읽기(ном_суроға);
        if (дарозӣ_қимат < 0) return дарозӣ_қимат;
        if ((Танзимот & ~(3 | эҷод_кардан_ворида | 독점생성 | пок_кардан_Мундариҷа | 이어쓰기 | 기다리지않기 | 실행시닫기)) != 0) return -95;
        if ((Танзимот & 3) == 3 || ((Танзимот & пок_кардан_Мундариҷа) != 0 && (Танзимот & 3) == 0)) return -22;
        int Файл = ҳофиза_системаи_файлӣ.ёфтан_ворида(масир_ном, дарозӣ_қимат);
        if (Файл >= 0 && (Танзимот & (эҷод_кардан_ворида | 독점생성)) == (эҷод_кардан_ворида | 독점생성)) return -17;
        if (Файл == -2 && (Танзимот & эҷод_кардан_ворида) == 0) return -2;
        int 서술자 = 빈서술자(0), 기술 = холӣ_дастак();
        if (서술자 < 0 || 기술 < 0) return -24;
        if (Файл == -2) {
            int 결과 = ҳофиза_системаи_файлӣ.ҳифз_кардан_қимат(масир_ном, дарозӣ_қимат, масир_ном, 0);
            if (결과 < 0) return 결과;
            Файл = ҳофиза_системаи_файлӣ.ёфтан_ворида(масир_ном, дарозӣ_қимат);
            ҳофиза_системаи_файлӣ.허가들[Файл] = 허가 & 511;
        }
        if (Файл < 0) return Файл;
        if ((Танзимот & пок_кардан_Мундариҷа) != 0) ҳофиза_системаи_файлӣ.андоза_кардан_Рӯйхат[Файл] = 0;
        ҳофиза_системаи_файлӣ.열림수[Файл]++;
        return ПАЙВАСТ(서술자, 기술, 2, Файл, Танзимот);
    }
    static int 파일읽기(int 서술자, int иттилоот_суроға, int дарозӣ_қимат) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0 || (кушодан_Танзимот[기술] & 3) == 1) return -9;
        if (дарозӣ_қимат < 0) return -22;
        if (дарозӣ_қимат == 0) return 0;
        if (!실행관리.клип(иттилоот_суроға, дарозӣ_қимат)) return -14;
        if (종류[기술] == 3) return 자료전문받기(서술자, иттилоот_суроға, дарозӣ_қимат, 0, 0);
        if (종류[기술] == 1) {
            int 받은수 = 0;
            while (받은수 < дарозӣ_қимат) {
                int қимат = 문자단말.직렬읽기();
                if (қимат < 0) қимат = клавиатура.Хондан();
                if (қимат < 0) {
                    if (받은수 > 0) return 받은수;
                    if ((кушодан_Танзимот[기술] & 기다리지않기) != 0) return -11;
                    if (мобилӣ_қимат.사용자남은밀리초() <= 10) return -11;
                    Шабака_ҷамъ.тасдиқ_кардан(); мобилӣ_қимат.잠시양보();
                } else {
                    мобилӣ_қимат.навиштан_ҳофиза(иттилоот_суроға + 받은수, қимат); 받은수++;
                }
            }
            return 받은수;
        }
        int Файл = ҳадаф[기술], 위치 = 파일위치[기술];
        if (위치 >= ҳофиза_системаи_файлӣ.андоза_кардан_Рӯйхат[Файл]) return 0;
        if (дарозӣ_қимат > ҳофиза_системаи_файлӣ.андоза_кардан_Рӯйхат[Файл] - 위치) дарозӣ_қимат = ҳофиза_системаи_файлӣ.андоза_кардан_Рӯйхат[Файл] - 위치;
        int 원본주소 = мобилӣ_қимат.файл_ҳофиза() + Файл * ҳофиза_системаи_файлӣ.최대크기 + 위치;
        for (int индекс = 0; индекс < дарозӣ_қимат; индекс++) мобилӣ_қимат.навиштан_ҳофиза(иттилоот_суроға + индекс, мобилӣ_қимат.기억읽기(원본주소 + индекс));
        파일위치[기술] += дарозӣ_қимат;
        return дарозӣ_қимат;
    }
    static int навиштан_файл(int 서술자, int иттилоот_суроға, int дарозӣ_қимат) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0 || (кушодан_Танзимот[기술] & 3) == 0) return -9;
        if (дарозӣ_қимат < 0) return -22;
        if (дарозӣ_қимат == 0) return 0;
        if (!실행관리.клип(иттилоот_суроға, дарозӣ_қимат)) return -14;
        if (종류[기술] == 3) return -89; // 연결하지 않은 자료전문 종단점에는 ҷои_таъинот_қимат 주소가 필요하다.
        if (종류[기술] == 1) {
            if (дарозӣ_қимат > 16384) дарозӣ_қимат = 16384;
            for (int индекс = 0; индекс < дарозӣ_қимат; индекс++) {
                int қимат = мобилӣ_қимат.기억읽기(иттилоот_суроға + индекс);
                문자단말.직렬바이트(қимат); 문자단말.화면문자(қимат);
            }
            return дарозӣ_қимат;
        }
        int Файл = ҳадаф[기술], андоза_кардан = ҳофиза_системаи_файлӣ.андоза_кардан_Рӯйхат[Файл];
        int 위치 = (кушодан_Танзимот[기술] & 이어쓰기) != 0 ? андоза_кардан : 파일위치[기술];
        if (위치 >= ҳофиза_системаи_файлӣ.최대크기) return -27;
        if (дарозӣ_қимат > ҳофиза_системаи_файлӣ.최대크기 - 위치) дарозӣ_қимат = ҳофиза_системаи_файлӣ.최대크기 - 위치;
        int ҷои_таъинот_суроға = мобилӣ_қимат.файл_ҳофиза() + Файл * ҳофиза_системаи_файлӣ.최대크기;
        for (int индекс = андоза_кардан; индекс < 위치; индекс++) мобилӣ_қимат.навиштан_ҳофиза(ҷои_таъинот_суроға + индекс, 0);
        for (int индекс = 0; индекс < дарозӣ_қимат; индекс++) мобилӣ_қимат.навиштан_ҳофиза(ҷои_таъинот_суроға + 위치 + индекс, мобилӣ_қимат.기억읽기(иттилоот_суроға + индекс));
        파일위치[기술] = 위치 + дарозӣ_қимат;
        if (위치 + дарозӣ_қимат > андоза_кардан) ҳофиза_системаи_файлӣ.андоза_кардан_Рӯйхат[Файл] = 위치 + дарозӣ_қимат;
        return дарозӣ_қимат;
    }
    static int ҷустан_файл(int 서술자, int Интиқолшавӣ_қимат, int 기준) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0) return -9;
        if (종류[기술] != 2) return -29;
        if (기준 < 0 || 기준 > 2) return -22;
        int Пасзамина_қимат = 기준 == 0 ? 0 : (기준 == 1 ? 파일위치[기술] : ҳофиза_системаи_файлӣ.андоза_кардан_Рӯйхат[ҳадаф[기술]]);
        if (Интиқолшавӣ_қимат > 0 && Пасзамина_қимат > 2147483647 - Интиқолшавӣ_қимат) return -75;
        if (Интиқолшавӣ_қимат < 0 && Интиқолшавӣ_қимат < -Пасзамина_қимат) return -22;
        파일위치[기술] = Пасзамина_қимат + Интиқолшавӣ_қимат;
        return 파일위치[기술];
    }
    static int 서술자복제(int 서술자, int 새서술자, boolean 지정, int Танзимот) {
        int 기술 = 기술찾기(서술자);
        if (기술 < 0) return -9;
        if (새서술자 < 0 || 새서술자 >= 서술자한도) return 지정 ? -9 : -22;
        if (지정 && 서술자 == 새서술자) return 새서술자;
        if (지정) { if (кушодан_дастак[새서술자] != 0) пӯшидан_файл(새서술자); }
        else { 새서술자 = 빈서술자(새서술자); if (새서술자 < 0) return 새서술자; }
        кушодан_дастак[새서술자] = 기술 + 1; 서술자설정[새서술자] = Танзимот; 참조수[기술]++;
        return 새서술자;
    }
