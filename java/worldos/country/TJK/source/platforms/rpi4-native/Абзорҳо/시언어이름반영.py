#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 байт_қимат 위치로 자체 C 이름을 옮기는 일회성 이행 Абзорҳо.

외부 구조체의 멤버, сатр_қимат_6ca8363c, C 표준 функсия_қимат, 이식 규약은 보존한다.
입력은 тағйир_додан_қимат 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def иҷро_кардан_фармон():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['Хато']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ном_ҷадвал = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:ном_ҷадвал[ворида_қимат['Ном']] for 고유,ворида_қимат in 선언표.items()
                if ворида_қимат['Ном'] in ном_ҷадвал and ворида_қимат['Ном'] not in 규격}
    пайваст_ҷадвал = {ворида_қимат['Ном']:ном_ҷадвал[ворида_қимат['Ном']] for ворида_қимат in 선언표.values()
              if ворида_қимат.get('ПАЙВАСТ')==4 and ворида_қимат['종류'] in (8,9)
              and ворида_қимат['Ном'] in ном_ҷадвал and ворида_қимат['Ном'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ПАЙВАСТ 이름만 유지한다.
    머리 = ['/* 한국어 манбаъ_дарахт 이름과 기존 компютер ПАЙВАСТ кор_қимат. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(пайваст_ҷадвал.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    Тағйирот_Рӯйхат = defaultdict(dict)
    for Файл,Интиқолшавӣ_қимат,Ном,고유 in 분석['Маълумотнома']:
        if 고유 in 바꿀선언:
            Тағйирот_Рӯйхат[Файл][Интиқолшавӣ_қимат] = (Ном,바꿀선언[고유])
    сабт_кардан_сабт = ['Файл\t원래바이트위치\t이전이름\t한국어이름']
    нодида_гирифтан_қимат = []
    for Файл,тағйир_додан_қимат in Тағйирот_Рӯйхат.items():
        масир = Path(Файл); 원본 = масир.read_bytes(); иттилоот = 원본
        for Интиқолшавӣ_қимат,(옛이름,새이름) in sorted(тағйир_додан_қимат.items(),reverse=True):
            끝 = Интиқолшавӣ_қимат+len(옛이름.encode())
            if 원본[Интиқолшавӣ_қимат:끝] != 옛이름.encode():
                нодида_гирифтан_қимат.append((str(масир.relative_to(기준)),Интиқолшавӣ_қимат,옛이름));continue
            иттилоот = иттилоот[:Интиқолшавӣ_қимат]+새이름.encode()+иттилоот[끝:]
            сабт_кардан_сабт.append('{}\t{}\t{}\t{}'.format(масир.relative_to(기준),Интиқолшавӣ_қимат,옛이름,새이름))
        масир.write_bytes(иттилоот)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    макро_қимат = {ворида_қимат['Ном']:ном_ҷадвал[ворида_қимат['Ном']] for ворида_қимат in 선언표.values()
              if ворида_қимат['종류']==501 and ворида_қимат['Ном'] in ном_ҷадвал and ворида_қимат['Ном'] not in 규격}
    for масир in sorted({Path(ворида_қимат['Файл']) for ворида_қимат in 선언표.values()}):
        хат_Рӯйхат = масир.read_text().splitlines(True); 이어짐 = False
        for индекс,хат in enumerate(хат_Рӯйхат):
            전처리 = 이어짐 or bool(re.match(r'\s*#',хат))
            이어짐 = 전처리 and хат.rstrip().endswith('\\')
            if 전처리:
                표 = ном_ҷадвал if re.match(r'\s*#\s*define\b',хат) or 이어짐 else макро_қимат
                хат_Рӯйхат[индекс] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],хат)
        масир.write_text(''.join(хат_Рӯйхат))
    # 각 자체 Тарҷума_манбаъ 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for масир in sorted({Path(ворида_қимат['Файл']) for ворида_қимат in 선언표.values()}):
        if масир.suffix not in ('.c','.cpp'):continue
        ҳамсон_қимат = '../' * len(масир.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        масир.write_text('#include "'+ҳамсон_қимат+'"\n'+масир.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(сабт_кардан_сабт)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(нодида_гирифтан_қимат,ensure_ascii=False,indent=2)+'\n')
    print('тағйир_додан_қимат',len(сабт_кардан_сабт)-1,'전처리 재검토',len(нодида_гирифтан_қимат),'компютер ПАЙВАСТ',len(пайваст_ҷадвал))

if __name__=='__main__': иҷро_кардан_фармон()
