/** 파이프는 16 KiB씩 순서대로 실행한다. 프로세스/동시 파이프를 흉내 내지 않는다. */
public final class 셸입출력 {
    static int[] 입력자료 = new int[16384], 출력자료 = new int[16384];
    static int 입력길이, 입력위치, 출력길이, 입력파일 = -1, файли_натиҷа = -1;
    static boolean 파이프입력, 파이프출력;
    static int нокомӣ_қимат;
    static boolean Иҷозат_интерактивӣ = true;
    public static int 대화가능() { return Иҷозат_интерактивӣ && 입력파일 < 3 && файли_натиҷа < 3 && !파이프입력 && !파이프출력 ? 1 : 0; }
    public static int 출력(int канал_қимат, int қимат) {
        if (канал_қимат != 1) return 0;
        if (файли_натиҷа >= 3) { int 처리값 = ҳофиза_Файлҳо.Навиштан(файли_натиҷа, қимат); if (처리값 < 0) нокомӣ_қимат = 처리값; return 1; }
        if (!파이프출력) return 0;
        if (출력길이 == 출력자료.length) нокомӣ_қимат = -28;
        else 출력자료[출력길이++] = қимат;
        return 1;
    }
    public static int 입력() {
        if (입력파일 >= 3) { int 처리값 = ҳофиза_Файлҳо.Хондан(입력파일); return 처리값 == 256 ? -2 : 처리값; }
        if (파이프입력) return 입력위치 < 입력길이 ? 입력자료[입력위치++] : -2;
        return -3; // UART로 бозфиристодан_қимат
    }
    static void порча(boolean 앞파이프, boolean 뒤파이프) {
        파이프입력 = 앞파이프; 파이프출력 = 뒤파이프;
        입력위치 = 0; 출력길이 = 0; 입력파일 = -1; файли_натиҷа = -1; нокомӣ_қимат = 0;
    }
    static void 끝() {
        보드.입출력전환(0);
        if (입력파일 >= 3) ҳофиза_Файлҳо.Пӯшидан(입력파일);
        if (файли_натиҷа >= 3) ҳофиза_Файлҳо.Пӯшидан(файли_натиҷа);
        if (파이프출력) { 입력길이 = 출력길이; for (int ҳалқа_индекс = 0; ҳалқа_индекс < 출력길이; ҳалқа_индекс++) 입력자료[ҳалқа_индекс] = 출력자료[ҳалқа_индекс]; }
        입력파일 = -1; файли_натиҷа = -1; 파이프입력 = false; 파이프출력 = false;
    }
}
