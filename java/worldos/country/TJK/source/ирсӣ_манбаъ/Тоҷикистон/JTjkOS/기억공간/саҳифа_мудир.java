package Тоҷикистон.JTjkOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB саҳифа_қимат 연결과 Навиштан 시 복사를 제공한다. */
public final class саҳифа_мудир {
    public static final int андозаи_саҳифа = 4096;

    private static final class саҳифа_қимат {
        private byte[] иттилоот = new byte[андозаи_саҳифа];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class суроға_фазо {
        private final Map<Integer, саҳифа_қимат> саҳифа_ҷадвал = new HashMap<Integer, саҳифа_қимат>();
    }

    public суроға_фазо 새주소공간() {
        return new суроға_фазо();
    }

    public void нишона_гузоштан_саҳифа(суроға_фазо 공간, int виртуалӣ_суроға, boolean 쓰기가능) {
        int индекс = 쪽번호(виртуалӣ_суроға);
        саҳифа_қимат 새쪽 = new саҳифа_қимат();
        새쪽.쓰기가능 = 쓰기가능;
        공간.саҳифа_ҷадвал.put(Integer.valueOf(индекс), 새쪽);
    }

    public суроға_фазо 쓰기시복사복제(суроға_фазо 원본) {
        суроға_фазо 복제본 = new суроға_фазо();
        for (Map.Entry<Integer, саҳифа_қимат> ворида_қимат : 원본.саҳифа_ҷадвал.entrySet()) {
            саҳифа_қимат 공유쪽 = ворида_қимат.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.саҳифа_ҷадвал.put(ворида_қимат.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(суроға_фазо 공간, int виртуалӣ_суроға) {
        саҳифа_қимат ҳадаф = ёфтан_саҳифа(공간, виртуалӣ_суроға);
        return ҳадаф.иттилоот[Math.floorMod(виртуалӣ_суроға, андозаи_саҳифа)];
    }

    public void навиштан_байт_қимат(суроға_фазо 공간, int виртуалӣ_суроға, byte қимат) {
        int индекс = 쪽번호(виртуалӣ_суроға);
        саҳифа_қимат ҳадаф = ёфтан_саҳифа(공간, виртуалӣ_суроға);
        if (!ҳадаф.쓰기가능) {
            if (!ҳадаф.쓰기시복사) {
                throw new IllegalStateException("Хондан 전용 쪽입니다.");
            }
            ҳадаф = эҷод_кардан_махфӣ_саҳифа(공간, индекс, ҳадаф);
        }
        ҳадаф.иттилоот[Math.floorMod(виртуалӣ_суроға, андозаи_саҳифа)] = қимат;
    }

    public void 범위개인쓰기(суроға_фазо 공간, int Оғоз_суроға, int андоза_кардан) {
        if (андоза_кардан < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int анҷом_додан_суроға = Math.addExact(Оғоз_суроға, андоза_кардан);
        for (int суроға = Оғоз_суроға; суроға < анҷом_додан_суроға; суроға = (쪽번호(суроға) + 1) * андозаи_саҳифа) {
            int индекс = 쪽번호(суроға);
            саҳифа_қимат ҳадаф = ёфтан_саҳифа(공간, суроға);
            if (ҳадаф.쓰기시복사) {
                эҷод_кардан_махфӣ_саҳифа(공간, индекс, ҳадаф);
            } else {
                ҳадаф.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(суроға_фазо 공간, int Оғоз_суроға, byte[] иттилоот) {
        for (int индекс = 0; индекс < иттилоот.length; индекс++) {
            навиштан_байт_қимат(공간, Оғоз_суроға + индекс, иттилоот[индекс]);
        }
    }

    private саҳифа_қимат эҷод_кардан_махфӣ_саҳифа(суроға_фазо 공간, int индекс, саҳифа_қимат 공유쪽) {
        саҳифа_қимат махфӣ_саҳифа = new саҳифа_қимат();
        махфӣ_саҳифа.иттилоот = Arrays.copyOf(공유쪽.иттилоот, 공유쪽.иттилоот.length);
        махфӣ_саҳифа.쓰기가능 = true;
        махфӣ_саҳифа.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.саҳифа_ҷадвал.put(Integer.valueOf(индекс), махфӣ_саҳифа);
        return махфӣ_саҳифа;
    }

    private саҳифа_қимат ёфтан_саҳифа(суроға_фазо 공간, int суроға) {
        саҳифа_қимат ҳадаф = 공간.саҳифа_ҷадвал.get(Integer.valueOf(쪽번호(суроға)));
        if (ҳадаф == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return ҳадаф;
    }

    private int 쪽번호(int суроға) {
        if (суроға < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return суроға / андозаи_саҳифа;
    }
}

