    public int файл_идоракунӣ(Раванд_қимат 현재과정, int 서술자, int фармон, int 인자) {
        if (фармон == 0) {
            return 현재과정.파일서술자().복제서술자(서술자, 인자);
        }
        if (фармон == 1) {
            return 현재과정.파일서술자().실행시닫기값(서술자);
        }
        if (фармон == 2) {
            return 현재과정.파일서술자().실행시닫기설정(서술자, (인자 & 1) != 0);
        }
        if (фармон == 3) {
            return 현재과정.파일서술자().Маълумоти_система(서술자) == null ? -9 : танҳо_барои_хондан_байрақ;
        }
        if (фармон == 4) {
            return 인자 == танҳо_барои_хондан_байрақ ? 0 : -30;
        }
        return -22;
    }

