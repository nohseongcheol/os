    public int иҷро_кардан_фармон(Раванд_қимат 현재과정, byte[] 실행파일, String[] 인자, String[] 환경) {
        실행파일적재기.расм расм_қимат;
        try {
            расм_қимат = 적재기.검사(실행파일);
        } catch (IllegalArgumentException Хато) {
            return -8;
        }
        if (인자 == null || 환경 == null || 인자.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.қисмат_қимат қисмат_қимат : расм_қимат.구역들()) {
            if ((қисмат_қимат.байрақ_қимат() & 2) == 0 || қисмат_қимат.андоза_кардан() == 0) {
                continue;
            }
            int 첫쪽 = қисмат_қимат.суроға() / саҳифа_мудир.андозаи_саҳифа;
            int 끝쪽 = (қисмат_қимат.суроға() + қисмат_қимат.андоза_кардан() + саҳифа_мудир.андозаи_саҳифа - 1) / саҳифа_мудир.андозаи_саҳифа;
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int суроға = индекс * саҳифа_мудир.андозаи_саҳифа;
                try {
                    쪽관리.바이트읽기(현재과정.суроға_фазо(), суроға);
                    쪽관리.범위개인쓰기(현재과정.суроға_фазо(), суроға, саҳифа_мудир.андозаи_саҳифа);
                } catch (IllegalStateException Хато) {
                    쪽관리.нишона_гузоштан_саҳифа(현재과정.суроға_фазо(), суроға, true);
                }
            }
            for (int индекс = 0; индекс < қисмат_қимат.андоза_кардан(); индекс++) {
                byte қимат = қисмат_қимат.종류() == 8 ? 0 : 실행파일[қисмат_қимат.파일위치() + индекс];
                쪽관리.навиштан_байт_қимат(현재과정.суроға_фазо(), қисмат_қимат.суроға() + индекс, қимат);
            }
        }
        현재과정.실행문맥설정(расм_қимат.Оғоз_суроға(), 인자, 환경);
        현재과정.파일서술자().실행시닫기();
        return 0;
    }

