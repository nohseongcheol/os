import 한국어.자체.равзана;
import 한국어.자체.барчасп;
import 한국어.자체.Матн_майдон;
import 한국어.자체.тугма;
import 한국어.자체.рӯйдод_навбат;
import 한국어.자체.출력;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing равзана: tg 입력 → тугма → файли_тафсилот_eb81d7d9 Матн навсозӣ. */
public class 창예제 implements 실행할일, 동작받이 {
    private равзана 인사창;
    private Матн_майдон ном_майдон;
    private барчасп 인사말;
    private int 인사횟수;

    public void кушодан_равзана() {
        인사창 = new равзана("tg Swing", 460, 300);
        인사창.илова_кардан_унсур(new барчасп("tg", 20, 20, 420, 28));
        ном_майдон = new Матн_майдон("tg", 20, 64, 420, 30);
        인사말 = new барчасп("tg", 20, 152, 420, 28);
        인사창.илова_кардан_унсур(ном_майдон);
        인사창.илова_кардан_унсур(new тугма("인사하기", 20, 108, 180, 32, this));
        인사창.илова_кардан_унсур(인사말);
        인사창.илова_кардан_унсур(new барчасп("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.намоиш_додан_равзана();
        출력.навиштан_хат("GUI 예제 Омода_кардан: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.навиштан_Матн("tg, " + ном_майдон.글읽기() + "님! (" + 인사횟수 + ")");
        출력.навиштан_хат("GUI 인사: " + 인사말.글읽기());
    }

    public void Иҷро_кардан() { кушодан_равзана(); }
    public void 동작받기(동작알림 알림) {
        출력.навиштан_хат("Амал 알림: " + 알림.фармон_Матн());
        인사하기();
    }
    public static void порча() {
        рӯйдод_навбат.나중에실행(new 창예제());
    }
}
