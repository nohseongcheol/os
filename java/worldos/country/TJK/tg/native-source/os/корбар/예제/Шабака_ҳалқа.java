/** 최대 андоза_кардан/홀수 дарозӣ_қимат 데이터그램으로 воқеӣ_иттилоот RTL8139 수신 ҳалқа_қимат 순환을 시험한다. */
public final class Шабака_ҳалқа {
    public static int порча() {
        if (корбар.인수개수() != 1) { корбар.Навиштан("Usage: run stress PORT\n"); return 2; }
        String Матн = корбар.인수(0);
        int порт_қимат = 0;
        for (int индекс = 0; индекс < Матн.length(); индекс++) {
            if (Матн.charAt(индекс) < '0' || Матн.charAt(индекс) > '9' || порт_қимат > 6553) return 2;
            порт_қимат = порт_қимат * 10 + Матн.charAt(индекс) - '0';
        }
        if (порт_қимат < 1 || порт_қимат > 65535) return 2;
        int дастак_қимат = корбар.кушодан_Шабака(0);
        if (дастак_қимат < 0) return 3;
        int[] иттилоот = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int дарозӣ_қимат = 1024 - (회차 & 1);
            for (int индекс = 0; индекс < дарозӣ_қимат; индекс++) иттилоот[индекс] = (индекс + 회차) & 255;
            if (корбар.фиристодан_иттилоот(дастак_қимат, 0x0a000202, порт_қимат, иттилоот, дарозӣ_қимат) != дарозӣ_қимат) return 4;
            if (корбар.자료받기(дастак_қимат, иттилоот, 300) != дарозӣ_қимат) return 5;
            for (int индекс = 0; индекс < дарозӣ_қимат; индекс++) if (иттилоот[индекс] != ((индекс + 회차) & 255)) return 6;
        }
        корбар.пӯшидан_Шабака(дастак_қимат);
        корбар.Навиштан("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
