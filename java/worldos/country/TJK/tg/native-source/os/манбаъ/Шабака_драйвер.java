/** PCI RTL8139 (10ec:8139), 단일 фиристодан_қимат 버퍼와 8KiB 수신 ҳалқа_қимат. 인터럽트 대신 폴링한다. */
public final class Шабака_драйвер {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] мобилӣ_суроға = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int 위치) {
        мобилӣ_қимат.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | 위치);
        return мобилӣ_қимат.입출력정수읽기(0xcfc);
    }

    static boolean Омода_кардан() {
        int 장치번호 = -1;
        for (int индекс = 0; индекс < 32; индекс++) {
            if (설정읽기(индекс, 0) == 0x813910ec) { 장치번호 = индекс; break; }
        }
        if (장치번호 < 0) return false;
        int қимати_пешфарз = 설정읽기(장치번호, 0x10);
        if ((қимати_пешфарз & 1) == 0 || (қимати_пешфарз & 0xfffffffc) < 0x100 || (қимати_пешфарз & 0xfffffffc) > 65535) return false;
        입출력기준주소 = қимати_пешфарз & 0xfffc;
        int фармон = 설정읽기(장치번호, 4);
        мобилӣ_қимат.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        мобилӣ_қимат.입출력짧은수쓰기(0xcfc, фармон | 5); // I/O 및 bus master Иҷозат_қимат, PCI вазъият_қимат 비트는 건드리지 않음
        мобилӣ_қимат.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!танзими_дубора_қимат()) { 입출력기준주소 = 0; return false; }
        for (int индекс = 0; индекс < 6; индекс++) мобилӣ_суроға[индекс] = мобилӣ_қимат.입출력바이트읽기(입출력기준주소 + индекс);
        return true;
    }

    static boolean танзими_дубора_қимат() {
        мобилӣ_қимат.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int порча = мобилӣ_қимат.밀리초();
        while ((мобилӣ_қимат.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (мобилӣ_қимат.밀리초() - порча > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        мобилӣ_қимат.입출력정수쓰기(입출력기준주소 + 0x30, мобилӣ_қимат.Шабака_ҳофиза());
        for (int индекс = 0; индекс < 4; индекс++) мобилӣ_қимат.입출력정수쓰기(입출력기준주소 + 0x20 + индекс * 4, мобилӣ_қимат.Шабака_ҳофиза() + 12288);
        мобилӣ_қимат.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        мобилӣ_қимат.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        мобилӣ_қимат.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        мобилӣ_қимат.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/пахш_қимат, wrap 연속 ҳифз_кардан_қимат, 8KiB
        мобилӣ_қимат.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int фиристодан(int[] иттилоот, int дарозӣ_қимат) {
        if (입출력기준주소 == 0) return -19;
        if (дарозӣ_қимат < 14 || дарозӣ_қимат > 1514) return -90;
        int вазъият_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int порча = мобилӣ_қимат.밀리초();
        while ((мобилӣ_қимат.입출력정수읽기(вазъият_порт) & 0x2000) == 0)
            if (мобилӣ_қимат.밀리초() - порча > 100) return -110;
        int андоза_кардан = дарозӣ_қимат < 60 ? 60 : дарозӣ_қимат;
        for (int индекс = 0; индекс < андоза_кардан; индекс++)
            мобилӣ_қимат.навиштан_ҳофиза(мобилӣ_қимат.Шабака_ҳофиза() + 12288 + индекс, индекс < дарозӣ_қимат ? иттилоот[индекс] : 0);
        мобилӣ_қимат.입출력정수쓰기(вазъият_порт, андоза_кардан | 0x00080000);
        порча = мобилӣ_қимат.밀리초();
        while ((мобилӣ_қимат.입출력정수읽기(вазъият_порт) & 0xe0008000) == 0)
            if (мобилӣ_қимат.밀리초() - порча > 100) return -110;
        if ((мобилӣ_қимат.입출력정수읽기(вазъият_порт) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return дарозӣ_қимат;
    }

    static int 받기(int[] иттилоот) {
        if (입출력기준주소 == 0) return 0;
        if ((мобилӣ_қимат.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!танзими_дубора_қимат()) 입출력기준주소 = 0;
            return 0;
        }
        if ((мобилӣ_қимат.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = мобилӣ_қимат.Шабака_ҳофиза() + 수신위치;
        int вазъият_қимат = 실행관리.짧은수(머리), андоза_кардан = 실행관리.짧은수(머리 + 2);
        if (андоза_кардан == 0xfff0) return 0; // DMA 진행 중
        if (андоза_кардан < 4 || андоза_кардан > 1518) {
            오류수++;
            if (!танзими_дубора_қимат()) 입출력기준주소 = 0;
            return 0;
        }
        int дарозӣ_қимат = андоза_кардан - 4;
        if ((вазъият_қимат & 1) != 0) {
            for (int индекс = 0; индекс < дарозӣ_қимат; индекс++) иттилоот[индекс] = мобилӣ_қимат.기억읽기(머리 + 4 + индекс);
            수신수++;
        } else { дарозӣ_қимат = 0; 오류수++; }
        수신위치 = (수신위치 + андоза_кардан + 4 + 3) & ~3;
        수신위치 &= 8191;
        мобилӣ_қимат.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        мобилӣ_қимат.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return дарозӣ_қимат;
    }
}
