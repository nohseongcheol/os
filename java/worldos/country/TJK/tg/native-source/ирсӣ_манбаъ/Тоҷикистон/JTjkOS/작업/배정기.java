package Тоҷикистон.JTjkOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Тоҷикистон.JTjkOS.기억공간.саҳифа_мудир;
import Тоҷикистон.JTjkOS.системаи_файлӣ.파일서술자표;

/** Раванд_қимат 식별자와 라운드로빈 Омода_кардан 대기열을 관리한다. */
public final class 배정기 {
    private final саҳифа_мудир 쪽관리;
    private final Map<Integer, Раванд_қимат> Рӯйхати_равандҳо = new HashMap<Integer, Раванд_қимат>();
    private final Queue<Раванд_қимат> 준비대기열 = new ArrayDeque<Раванд_қимат>();
    private int 다음식별자 = 1;

    public 배정기(саҳифа_мудир 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public Раванд_қимат 첫과정(파일서술자표 파일서술자) {
        Раванд_қимат 새과정 = new Раванд_қимат(татбиқ_кардан_идентификатор(), 0, 쪽관리.새주소공간(), 파일서술자);
        Рӯйхати_равандҳо.put(Integer.valueOf(새과정.идентификатор_қимат()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public Раванд_қимат 복제(Раванд_қимат 부모) {
        Раванд_қимат кӯдак_қимат = new Раванд_қимат(
                татбиқ_кардан_идентификатор(),
                부모.идентификатор_қимат(),
                쪽관리.쓰기시복사복제(부모.суроға_фазо()),
                부모.파일서술자().복제());
        кӯдак_қимат.프로그램끝설정(부모.프로그램끝());
        Рӯйхати_равандҳо.put(Integer.valueOf(кӯдак_қимат.идентификатор_қимат()), кӯдак_қимат);
        준비대기열.offer(кӯдак_қимат);
        return кӯдак_қимат;
    }

    public Раванд_қимат 다음과정() {
        int 검사수 = 준비대기열.size();
        for (int индекс = 0; индекс < 검사수; индекс++) {
            Раванд_қимат 다음 = 준비대기열.poll();
            if (다음 != null && (다음.вазъият_қимат() == Раванд_вазъият.Омода_кардан || 다음.вазъият_қимат() == Раванд_вазъият.иҷро_кардан_фармон)) {
                다음.маҷмуъ_вазъият(Раванд_вазъият.иҷро_кардан_фармон);
                준비대기열.offer(다음);
                return 다음;
            }
        }
        return null;
    }

    public int 자식기다리기(Раванд_қимат 부모, int кӯдак_идентификатор, boolean 기다리지않음) {
        for (Раванд_қимат 후보 : Рӯйхати_равандҳо.values()) {
            if (후보.부모식별자() != 부모.идентификатор_қимат()) {
                continue;
            }
            if (кӯдак_идентификатор > 0 && 후보.идентификатор_қимат() != кӯдак_идентификатор) {
                continue;
            }
            if (후보.вазъият_қимат() == Раванд_вазъият.Баромад_барнома) {
                int 결과 = (후보.종료값() & 0xff) << 8;
                Рӯйхати_равандҳо.remove(Integer.valueOf(후보.идентификатор_қимат()));
                return 결과;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public Раванд_қимат ёфтан_Раванд(int идентификатор_қимат) {
        return Рӯйхати_равандҳо.get(Integer.valueOf(идентификатор_қимат));
    }

    private int татбиқ_кардан_идентификатор() {
        return 다음식별자++;
    }
}
