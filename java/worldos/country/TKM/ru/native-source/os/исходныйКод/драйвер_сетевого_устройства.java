/** PCI RTL8139 (10ec:8139), 단일 написать_ЗНАЧЕН 버퍼와 8KiB получить_ЗНАЧЕН Loop_ЗНАЧЕН. 인터럽트 대신 폴링한다. */
public final class драйвер_сетевого_устройства {
    static int 입출력기준주소 = 0;
    static int получить_позиция = 0, 송신칸 = 0;
    static int[] устройство_АДРЕС = new int[6];
    static int 송신수 = 0, получить_СЧЁТ = 0, ошибка_СЧЁТ = 0;

    static int чтение_Настройки(int 장치번호, int позиция) {
        устройство_ЗНАЧЕН.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | позиция);
        return устройство_ЗНАЧЕН.입출력정수읽기(0xcfc);
    }

    static boolean Подготовить() {
        int 장치번호 = -1;
        for (int ИНДЕКС = 0; ИНДЕКС < 32; ИНДЕКС++) {
            if (чтение_Настройки(ИНДЕКС, 0) == 0x813910ec) { 장치번호 = ИНДЕКС; break; }
        }
        if (장치번호 < 0) return false;
        int значение_по_умолчанию = чтение_Настройки(장치번호, 0x10);
        if ((значение_по_умолчанию & 1) == 0 || (значение_по_умолчанию & 0xfffffffc) < 0x100 || (значение_по_умолчанию & 0xfffffffc) > 65535) return false;
        입출력기준주소 = значение_по_умолчанию & 0xfffc;
        int команда = чтение_Настройки(장치번호, 4);
        устройство_ЗНАЧЕН.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        устройство_ЗНАЧЕН.입출력짧은수쓰기(0xcfc, команда | 5); // I/O 및 bus master разрешить_ЗНАЧЕН, PCI Состояние_ЗНАЧЕН 비트는 건드리지 않음
        устройство_ЗНАЧЕН.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!сбросить_ЗНАЧЕН()) { 입출력기준주소 = 0; return false; }
        for (int ИНДЕКС = 0; ИНДЕКС < 6; ИНДЕКС++) устройство_АДРЕС[ИНДЕКС] = устройство_ЗНАЧЕН.입출력바이트읽기(입출력기준주소 + ИНДЕКС);
        return true;
    }

    static boolean сбросить_ЗНАЧЕН() {
        устройство_ЗНАЧЕН.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int запустить = устройство_ЗНАЧЕН.밀리초();
        while ((устройство_ЗНАЧЕН.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (устройство_ЗНАЧЕН.밀리초() - запустить > 100) return false;
        получить_позиция = 0; 송신칸 = 0;
        устройство_ЗНАЧЕН.입출력정수쓰기(입출력기준주소 + 0x30, устройство_ЗНАЧЕН.сеть_Память());
        for (int ИНДЕКС = 0; ИНДЕКС < 4; ИНДЕКС++) устройство_ЗНАЧЕН.입출력정수쓰기(입출력기준주소 + 0x20 + ИНДЕКС * 4, устройство_ЗНАЧЕН.сеть_Память() + 12288);
        устройство_ЗНАЧЕН.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        устройство_ЗНАЧЕН.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        устройство_ЗНАЧЕН.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        устройство_ЗНАЧЕН.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/вещать_ЗНАЧЕН, wrap 연속 Store_ЗНАЧЕН, 8KiB
        устройство_ЗНАЧЕН.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int написать(int[] данные, int длина_ЗНАЧЕН) {
        if (입출력기준주소 == 0) return -19;
        if (длина_ЗНАЧЕН < 14 || длина_ЗНАЧЕН > 1514) return -90;
        int статус_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int запустить = устройство_ЗНАЧЕН.밀리초();
        while ((устройство_ЗНАЧЕН.입출력정수읽기(статус_порт) & 0x2000) == 0)
            if (устройство_ЗНАЧЕН.밀리초() - запустить > 100) return -110;
        int Размер = длина_ЗНАЧЕН < 60 ? 60 : длина_ЗНАЧЕН;
        for (int ИНДЕКС = 0; ИНДЕКС < Размер; ИНДЕКС++)
            устройство_ЗНАЧЕН.запись_Память(устройство_ЗНАЧЕН.сеть_Память() + 12288 + ИНДЕКС, ИНДЕКС < длина_ЗНАЧЕН ? данные[ИНДЕКС] : 0);
        устройство_ЗНАЧЕН.입출력정수쓰기(статус_порт, Размер | 0x00080000);
        запустить = устройство_ЗНАЧЕН.밀리초();
        while ((устройство_ЗНАЧЕН.입출력정수읽기(статус_порт) & 0xe0008000) == 0)
            if (устройство_ЗНАЧЕН.밀리초() - запустить > 100) return -110;
        if ((устройство_ЗНАЧЕН.입출력정수읽기(статус_порт) & 0x8000) == 0) { ошибка_СЧЁТ++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return длина_ЗНАЧЕН;
    }

    static int получить(int[] данные) {
        if (입출력기준주소 == 0) return 0;
        if ((устройство_ЗНАЧЕН.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            ошибка_СЧЁТ++;
            if (!сбросить_ЗНАЧЕН()) 입출력기준주소 = 0;
            return 0;
        }
        if ((устройство_ЗНАЧЕН.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int HEAD_ЗНАЧЕН = устройство_ЗНАЧЕН.сеть_Память() + получить_позиция;
        int Состояние_ЗНАЧЕН = выполнение_менеджер.짧은수(HEAD_ЗНАЧЕН), Размер = выполнение_менеджер.짧은수(HEAD_ЗНАЧЕН + 2);
        if (Размер == 0xfff0) return 0; // DMA 진행 중
        if (Размер < 4 || Размер > 1518) {
            ошибка_СЧЁТ++;
            if (!сбросить_ЗНАЧЕН()) 입출력기준주소 = 0;
            return 0;
        }
        int длина_ЗНАЧЕН = Размер - 4;
        if ((Состояние_ЗНАЧЕН & 1) != 0) {
            for (int ИНДЕКС = 0; ИНДЕКС < длина_ЗНАЧЕН; ИНДЕКС++) данные[ИНДЕКС] = устройство_ЗНАЧЕН.чтение_Память(HEAD_ЗНАЧЕН + 4 + ИНДЕКС);
            получить_СЧЁТ++;
        } else { длина_ЗНАЧЕН = 0; ошибка_СЧЁТ++; }
        получить_позиция = (получить_позиция + Размер + 4 + 3) & ~3;
        получить_позиция &= 8191;
        устройство_ЗНАЧЕН.입출력짧은수쓰기(입출력기준주소 + 0x38, (получить_позиция - 16) & 65535);
        устройство_ЗНАЧЕН.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return длина_ЗНАЧЕН;
    }
}
