#include "호출경계.h"
extern int main(int 인수개수, char **وسيطة_قائمة);
static char وسيطة_ذاكرة[2048];
static char *وسيطة_قائمة[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* حديث_عنصر 커널의 argv는 ينفذ_أمر 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    وسيطة_قائمة[0] = "jkoros-app";
    int موضع = 0;
    for (int فهرس = 0; فهرس < 개수; فهرس++) {
        const int *원본 = (const int *)jkoros_syscall(3, فهرس, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        وسيطة_قائمة[فهرس + 1] = وسيطة_ذاكرة + موضع;
        for (int فتحة_إدخال = 0; فتحة_إدخال < 원본[0]; فتحة_إدخال++) {
            if (موضع >= 2047) return 126;
            وسيطة_ذاكرة[موضع++] = 원본[فتحة_إدخال + 1];
        }
        وسيطة_ذاكرة[موضع++] = 0;
    }
    وسيطة_قائمة[개수 + 1] = 0;
    return main(개수 + 1, وسيطة_قائمة);
}
