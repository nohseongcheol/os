/** PCI RTL8139 (10ec:8139), 단일 изпращам_стойност 버퍼와 8KiB получавам_стойност_cef4d8ab цикъл_стойност. 인터럽트 대신 폴링한다. */
public final class мрежа_драйвер {
    static int 입출력기준주소 = 0;
    static int получавам_позиция = 0, 송신칸 = 0;
    static int[] устройство_адрес = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int Позиция) {
        устройство_стойност.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | Позиция);
        return устройство_стойност.입출력정수읽기(0xcfc);
    }

    static boolean Подготвяне() {
        int 장치번호 = -1;
        for (int индекс = 0; индекс < 32; индекс++) {
            if (설정읽기(индекс, 0) == 0x813910ec) { 장치번호 = индекс; break; }
        }
        if (장치번호 < 0) return false;
        int стойност_по_подразбиране = 설정읽기(장치번호, 0x10);
        if ((стойност_по_подразбиране & 1) == 0 || (стойност_по_подразбиране & 0xfffffffc) < 0x100 || (стойност_по_подразбиране & 0xfffffffc) > 65535) return false;
        입출력기준주소 = стойност_по_подразбиране & 0xfffc;
        int Команда = 설정읽기(장치번호, 4);
        устройство_стойност.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        устройство_стойност.입출력짧은수쓰기(0xcfc, Команда | 5); // I/O 및 bus master позволявам_стойност, PCI Състояние_стойност 비트는 건드리지 않음
        устройство_стойност.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!нулирам_стойност()) { 입출력기준주소 = 0; return false; }
        for (int индекс = 0; индекс < 6; индекс++) устройство_адрес[индекс] = устройство_стойност.입출력바이트읽기(입출력기준주소 + индекс);
        return true;
    }

    static boolean нулирам_стойност() {
        устройство_стойност.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int Стартиране = устройство_стойност.밀리초();
        while ((устройство_стойност.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (устройство_стойност.밀리초() - Стартиране > 100) return false;
        получавам_позиция = 0; 송신칸 = 0;
        устройство_стойност.입출력정수쓰기(입출력기준주소 + 0x30, устройство_стойност.мрежа_Памет());
        for (int индекс = 0; индекс < 4; индекс++) устройство_стойност.입출력정수쓰기(입출력기준주소 + 0x20 + индекс * 4, устройство_стойност.мрежа_Памет() + 12288);
        устройство_стойност.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        устройство_стойност.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        устройство_стойност.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        устройство_стойност.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/излъчвам_стойност, wrap 연속 хранилище_стойност, 8KiB
        устройство_стойност.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int изпращам(int[] данни, int 길이) {
        if (입출력기준주소 == 0) return -19;
        if (길이 < 14 || 길이 > 1514) return -90;
        int статус_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int Стартиране = устройство_стойност.밀리초();
        while ((устройство_стойност.입출력정수읽기(статус_порт) & 0x2000) == 0)
            if (устройство_стойност.밀리초() - Стартиране > 100) return -110;
        int Размер = 길이 < 60 ? 60 : 길이;
        for (int индекс = 0; индекс < Размер; индекс++)
            устройство_стойност.записване_Памет(устройство_стойност.мрежа_Памет() + 12288 + индекс, индекс < 길이 ? данни[индекс] : 0);
        устройство_стойност.입출력정수쓰기(статус_порт, Размер | 0x00080000);
        Стартиране = устройство_стойност.밀리초();
        while ((устройство_стойност.입출력정수읽기(статус_порт) & 0xe0008000) == 0)
            if (устройство_стойност.밀리초() - Стартиране > 100) return -110;
        if ((устройство_стойност.입출력정수읽기(статус_порт) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return 길이;
    }

    static int получавам(int[] данни) {
        if (입출력기준주소 == 0) return 0;
        if ((устройство_стойност.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!нулирам_стойност()) 입출력기준주소 = 0;
            return 0;
        }
        if ((устройство_стойност.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = устройство_стойност.мрежа_Памет() + получавам_позиция;
        int Състояние_стойност = 실행관리.짧은수(머리), Размер = 실행관리.짧은수(머리 + 2);
        if (Размер == 0xfff0) return 0; // DMA 진행 중
        if (Размер < 4 || Размер > 1518) {
            오류수++;
            if (!нулирам_стойност()) 입출력기준주소 = 0;
            return 0;
        }
        int 길이 = Размер - 4;
        if ((Състояние_стойност & 1) != 0) {
            for (int индекс = 0; индекс < 길이; индекс++) данни[индекс] = устройство_стойност.기억읽기(머리 + 4 + индекс);
            수신수++;
        } else { 길이 = 0; 오류수++; }
        получавам_позиция = (получавам_позиция + Размер + 4 + 3) & ~3;
        получавам_позиция &= 8191;
        устройство_стойност.입출력짧은수쓰기(입출력기준주소 + 0x38, (получавам_позиция - 16) & 65535);
        устройство_стойност.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return 길이;
    }
}
