/** 게스트 Инструменти 공통 Изход 및 ASCII Файл Име Процес_стойност_запис. */
public final class 자바도구 {
    /** UTF-8 байт_стойност 배열을 같은 배열의 UTF-16 단위로 바꾼다. 잘못된 입력은 отхвърлям_стойност_e3ecc00b. */
    static int 원문해독(int[] данни, int 길이) {
        int Четене = 0, Писане = 0;
        if (길이 >= 3 && данни[0] == 239 && данни[1] == 187 && данни[2] == 191) Четене = 3;
        while (Четене < 길이) {
            int стойност = данни[Четене++], 수 = 0, 최소 = 0;
            if (стойност >= 194 && стойност <= 223) { 수 = 1; 최소 = 128; стойност &= 31; }
            else if (стойност >= 224 && стойност <= 239) { 수 = 2; 최소 = 2048; стойност &= 15; }
            else if (стойност >= 240 && стойност <= 244) { 수 = 3; 최소 = 65536; стойност &= 7; }
            else if (стойност >= 128 || стойност < 0) return -1;
            if (수 > 길이 - Четене) return -1;
            for (int i = 0; i < 수; i++) {
                int Следваща_артикул = данни[Четене++]; if ((Следваща_артикул & 192) != 128) return -1;
                стойност = (стойност << 6) | (Следваща_артикул & 63);
            }
            if (стойност < 최소 || стойност > 0x10ffff || (стойност >= 0xd800 && стойност <= 0xdfff)) return -1;
            if (стойност >= 65536) { стойност -= 65536; данни[Писане++] = 0xd800 | (стойност >> 10); данни[Писане++] = 0xdc00 | (стойност & 1023); }
            else данни[Писане++] = стойност;
        }
        return Писане;
    }
    static void 수쓰기(int стойност) {
        if (стойност < 0) потребител.записване_знак_стойност('-'); else стойност = -стойност;
        int позиционен_указател = 1000000000;
        boolean Стартиране = false;
        while (позиционен_указател != 0) {
            int 수 = -(стойност / позиционен_указател);
            if (수 != 0 || Стартиране || позиционен_указател == 1) { потребител.записване_знак_стойност('0' + 수); Стартиране = true; }
            стойност %= позиционен_указател; позиционен_указател /= 10;
        }
    }
    static int Име(int[] местоназначение_стойност, String 원본) {
        if (원본.length() >= местоназначение_стойност.length) return -1;
        for (int 수 = 0; 수 < местоназначение_стойност.length; 수++) местоназначение_стойност[수] = 수 < 원본.length() ? 원본.charAt(수) : 0;
        return 원본.length();
    }
    static boolean 같음(String 가, String 나) {
        if (가.length() != 나.length()) return false;
        for (int 수 = 0; 수 < 가.length(); 수++) if (가.charAt(수) != 나.charAt(수)) return false;
        return true;
    }
}
