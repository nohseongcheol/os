#!/usr/bin/env python3
"""자체 Java локален_Обхват 이름을 바꾼다. низ_стойност·주석·външен_стойност 멤버 이름은 보존한다."""
import json
import re
from pathlib import Path

проект_корен = Path(__file__).resolve().parents[1]
съпоставяне_стойност = json.loads((проект_корен / '명명/자바이름.json').read_text())
блок_израз = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[\w$]+|[^\w\s]', re.UNICODE)
регистрирам_запис = []
for указател_стойност in ('ИЗТОЧНИК', 'потребител/자바', '한국어자바'):
    for ПЪТ in sorted((проект_корен / указател_стойност).rglob('*.java')):
        ИЗТОЧНИК = ПЪТ.read_text()
        토막들 = list(блок_израз.finditer(ИЗТОЧНИК))
        사용이름 = {блок_запис.group() for блок_запис in 토막들 if re.search('[가-힣]', блок_запис.group())}
        съпоставяне_на_файлове = {}
        for 이전, 이후 in съпоставяне_стойност.items():
            # A pre-existing Korean binding must never be shadowed by renaming.
            새이름 = 이후
            while 새이름 in 사용이름: 새이름 = 'локален_Обхват' + 새이름
            съпоставяне_на_файлове[이전] = 새이름
        수정 = []
        이전토막 = ''
        for блок_запис in 토막들:
            낱말 = блок_запис.group()
            if 낱말.startswith(('//', '/*', '"', "'")): continue
            if 낱말 in съпоставяне_на_файлове and 이전토막 != '.':
                수정.append((блок_запис.start(), блок_запис.end(), съпоставяне_на_файлове[낱말]))
                регистрирам_запис.append((str(ПЪТ.relative_to(проект_корен)), 낱말, съпоставяне_на_файлове[낱말]))
            이전토막 = 낱말
        for Стартиране, 끝, 새이름 in reversed(수정): ИЗТОЧНИК = ИЗТОЧНИК[:Стартиране] + 새이름 + ИЗТОЧНИК[끝:]
        if 수정: ПЪТ.write_text(ИЗТОЧНИК)
(проект_корен / '명명/자바이름대응.tsv').write_text('Файл\t이전\t이후\n' + ''.join('\t'.join(запис_стойност)+'\n' for запис_стойност in sorted(set(регистрирам_запис))))
print('Java Име препратка променям_стойност:', len(регистрирам_запис))
