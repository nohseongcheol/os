package Турция.JTurOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Турция.JTurOS.Памет_област.쪽관리자;
import Турция.JTurOS.файлова_система.파일서술자표;

/** Процес_стойност 식별자와 라운드로빈 Подготвяне 대기열을 관리한다. */
public final class Планировчик {
    private final 쪽관리자 쪽관리;
    private final Map<Integer, Процес_стойност> Обработване_на_списъка = new HashMap<Integer, Процес_стойност>();
    private final Queue<Процес_стойност> 준비대기열 = new ArrayDeque<Процес_стойност>();
    private int Следваща_Идентификатор = 1;

    public Планировчик(쪽관리자 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public Процес_стойност 첫과정(파일서술자표 파일서술자) {
        Процес_стойност 새과정 = new Процес_стойност(заделям_Идентификатор(), 0, 쪽관리.새주소공간(), 파일서술자);
        Обработване_на_списъка.put(Integer.valueOf(새과정.Идентификатор_стойност()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public Процес_стойност клонирам_стойност(Процес_стойност родител_стойност) {
        Процес_стойност дете_стойност = new Процес_стойност(
                заделям_Идентификатор(),
                родител_стойност.Идентификатор_стойност(),
                쪽관리.쓰기시복사복제(родител_стойност.адрес_ИНТЕРВАЛ()),
                родител_стойност.파일서술자().клонирам_стойност());
        дете_стойност.набор_програма_почивка(родител_стойност.програма_почивка());
        Обработване_на_списъка.put(Integer.valueOf(дете_стойност.Идентификатор_стойност()), дете_стойност);
        준비대기열.offer(дете_стойност);
        return дете_стойност;
    }

    public Процес_стойност Следваща_Процес() {
        int 검사수 = 준비대기열.size();
        for (int индекс = 0; индекс < 검사수; индекс++) {
            Процес_стойност Следваща_артикул = 준비대기열.poll();
            if (Следваща_артикул != null && (Следваща_артикул.Състояние_стойност() == Процес_Състояние.Подготвяне || Следваща_артикул.Състояние_стойност() == Процес_Състояние.изпълнявам_команда)) {
                Следваща_артикул.набор_Състояние(Процес_Състояние.изпълнявам_команда);
                준비대기열.offer(Следваща_артикул);
                return Следваща_артикул;
            }
        }
        return null;
    }

    public int 자식기다리기(Процес_стойност родител_стойност, int дете_Идентификатор, boolean 기다리지않음) {
        for (Процес_стойност 후보 : Обработване_на_списъка.values()) {
            if (후보.родител_Идентификатор() != родител_стойност.Идентификатор_стойност()) {
                continue;
            }
            if (дете_Идентификатор > 0 && 후보.Идентификатор_стойност() != дете_Идентификатор) {
                continue;
            }
            if (후보.Състояние_стойност() == Процес_Състояние.Изход_програма) {
                int РЕЗУЛТАТ = (후보.Изход_код() & 0xff) << 8;
                Обработване_на_списъка.remove(Integer.valueOf(후보.Идентификатор_стойност()));
                return РЕЗУЛТАТ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public Процес_стойност Търсене_Процес(int Идентификатор_стойност) {
        return Обработване_на_списъка.get(Integer.valueOf(Идентификатор_стойност));
    }

    private int заделям_Идентификатор() {
        return Следваща_Идентификатор++;
    }
}
