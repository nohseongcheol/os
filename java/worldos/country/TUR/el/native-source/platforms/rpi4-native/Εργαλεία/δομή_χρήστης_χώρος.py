"""독립된 ίδιο ABI ELF64와 로더 απορρίπτω_τιμή 시험 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from 파이썬빌드 import 파이썬만들기
from 자바라이브러리빌드 import 자바라이브러리만들기
from δομή_Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης import ανοίγω_Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης


def ανοίγω_χρήστης_χώρος(ρίζα_διαδρομή, αποθετήριο_διαδρομή, Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης, 시플플번역기, πρόγραμμα_σύνδεσης_εργαλείο, Αρχειοθήκη_εργαλείο, ρυθμίσεις_Υπηρεσία_έξυπνης_μεταφοράς_στο_παρασκήνιο, εκτελώ_εντολή):
    ρυθμίσεις_Υπηρεσία_έξυπνης_μεταφοράς_στο_παρασκήνιο = [Ρυθμίσεις_τιμή for Ρυθμίσεις_τιμή in ρυθμίσεις_Υπηρεσία_έξυπνης_μεταφοράς_στο_παρασκήνιο if Ρυθμίσεις_τιμή != '-mgeneral-regs-only']
    δομή_διαδρομή = ρίζα_διαδρομή / 'build'
    출력결과 = δομή_διαδρομή / 'user'
    출력결과.mkdir(exist_ok=True)
    원본자료 = ρίζα_διαδρομή / 'χρήστης'
    포직스경로 = αποθετήριο_διαδρομή / 'posix-kor/arm64-native'
    περιλαμβάνω_διαδρομή = ['-I', 원본자료, '-I', 포직스경로 / '포함', '-I', 출력결과]
    for πρόγραμμα_μεταγλώττισης_εργαλείο, 추가영역, ΔΙΑΔΡΟΜΗ, Όνομα in [
            (Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης, [], 원본자료 / 'Εκτέλεση_2.S', 'start.o'),
            (Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης, ['-std=c11'], 원본자료 / 'εκτελώ_εντολή.c', 'runtime.o'),
            (Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης, ['-std=c11'], 포직스경로 / 'χρήστης_γέφυρα.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / 'ΠαράδειγμαΑρχείου.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '통신예제.cpp', 'network.o'),
            (Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης, ['-std=c11'], 원본자료 / 'Προστασία_δοκιμή.c', 'fault.o'),
            (Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης, ['-std=c11'], 원본자료 / 'Βοηθός_γραφής.c', 'vi.o')]:
        εκτελώ_εντολή([πρόγραμμα_μεταγλώττισης_εργαλείο] + ρυθμίσεις_Υπηρεσία_έξυπνης_μεταφοράς_στο_παρασκήνιο + 추가영역 + περιλαμβάνω_διαδρομή + ['-Wall', '-Wextra', '-Werror', '-c', ΔΙΑΔΡΟΜΗ, '-o', 출력결과 / Όνομα])
    εκτελώ_εντολή([Αρχειοθήκη_εργαλείο, 'rcs', δομή_διαδρομή / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for Όνομα in ('demo', 'fault', 'network', 'vi'):
        εκτελώ_εντολή([πρόγραμμα_σύνδεσης_εργαλείο, '-T', 원본자료 / 'συνδέω_Διάταξη.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (Όνομα + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (Όνομα + '.o'), δομή_διαδρομή / 'libposix-kor-user.a'])
    자바라이브러리만들기(ρίζα_διαδρομή, εκτελώ_εντολή)
    # 기존 ίδιο Java πρόγραμμα_μεταγλώττισης/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(δομή_διαδρομή)) as 작업경로:
        Τάξη_διαδρομή = Path(작업경로)
        εκτελώ_εντολή(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', Τάξη_διαδρομή, '-sourcepath', Τάξη_διαδρομή, '-d', Τάξη_διαδρομή] +
            [δεδομένα_θέση for δεδομένα_θέση in sorted((αποθετήριο_διαδρομή / 'os/χρήστης/자바').glob('*.java')) if δεδομένα_θέση.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        εκτελώ_εντολή(['sh', αποθετήριο_διαδρομή / 'compiler/미리번역.sh', '--entry', 'εργαλείο_καταχώρηση.Εκτέλεση_2',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(Τάξη_διαδρομή.glob('*.class')))
    압축해제경로 = ρίζα_διαδρομή / 'vendor/uzlib'
    for ΔΙΑΔΡΟΜΗ, Όνομα in [(출력결과 / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'πακέτο.c', 'jar.o')] + [(압축해제경로 / (Όνομα + '.c'), Όνομα + '.o') for Όνομα in ('tinflate', 'crc32', 'adler32')]:
        εκτελώ_εντολή([Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης] + ρυθμίσεις_Υπηρεσία_έξυπνης_μεταφοράς_στο_παρασκήνιο + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + περιλαμβάνω_διαδρομή + ['-c', ΔΙΑΔΡΟΜΗ, '-o', 출력결과 / Όνομα])
    εκτελώ_εντολή([πρόγραμμα_σύνδεσης_εργαλείο, '-T', 원본자료 / 'συνδέω_Διάταξη.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / Όνομα for Όνομα in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(ρίζα_διαδρομή, Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης, πρόγραμμα_σύνδεσης_εργαλείο)
    ανοίγω_Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης(ρίζα_διαδρομή, αποθετήριο_διαδρομή, Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης, πρόγραμμα_σύνδεσης_εργαλείο, ρυθμίσεις_Υπηρεσία_έξυπνης_μεταφοράς_στο_παρασκήνιο, εκτελώ_εντολή)
    έγγυρος = (출력결과 / 'demo.elf').read_bytes()
    εφαρμογή_κεφαλίδα_Υπέρθεση = struct.unpack_from('<Q', έγγυρος, 32)[0]
    κεφαλίδα_Λίστα = [εφαρμογή_κεφαλίδα_Υπέρθεση + 개수 * 56 for 개수 in range(struct.unpack_from('<H', έγγυρος, 56)[0])]
    적재구획 = [δεδομένα_θέση for δεδομένα_θέση in κεφαλίδα_Λίστα if struct.unpack_from('<I', έγγυρος, δεδομένα_θέση)[0] == 1]
    Κείμενο, δεδομένα = 적재구획[:2]
    εντολή_διεύθυνση = struct.unpack_from('<Q', έγγυρος, Κείμενο + 16)[0]
    δεδομένα_διεύθυνση = struct.unpack_from('<Q', έγγυρος, δεδομένα + 16)[0]
    호출규약 = έγγυρος.index(b'JKOROS\0')
    υπόθεση_δοκιμής = [('empty', b''), ('short', έγγυρος[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', εντολή_διεύθυνση + 1), ('data-entry', 24, 'Q', δεδομένα_διεύθυνση),
               ('outside-file', Κείμενο + 32, 'Q', len(έγγυρος) + 1), ('short-memory', Κείμενο + 40, 'Q', 1),
               ('kernel-address', Κείμενο + 16, 'Q', 0x80000), ('memory-overflow', Κείμενο + 40, 'Q', 2**64 - 1),
               ('writable-code', Κείμενο + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', Κείμενο, 'I', 2),
               ('unaligned-load', Κείμενο + 16, 'Q', εντολή_διεύθυνση + 8),
               ('overlap', δεδομένα + 16, 'Q', εντολή_διεύθυνση)]
    for Όνομα, Υπέρθεση_τιμή, μορφή_932e03c8, τιμή in 수정사항:
        바뀐자료 = bytearray(έγγυρος); struct.pack_into('<' + μορφή_932e03c8, 바뀐자료, Υπέρθεση_τιμή, τιμή)
        υπόθεση_δοκιμής.append((Όνομα, bytes(바뀐자료)))
    탑재덩이들 = [(Όνομα.replace('-', '_'), 출력결과 / (Όνομα + '.elf')) for Όνομα in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for Αναζήτηση_Ευρετήριο, (Όνομα, ωφέλιμο_φορτίο_δεδομένα) in enumerate(υπόθεση_δοκιμής):
        ΔΙΑΔΡΟΜΗ = 출력결과 / ('invalid-{}.elf'.format(Όνομα)); ΔΙΑΔΡΟΜΗ.write_bytes(ωφέλιμο_φορτίο_δεδομένα)
        탑재덩이들.append(('invalid_{}'.format(Αναζήτηση_Ευρετήριο), ΔΙΑΔΡΟΜΗ))
    συγκρότηση, κεφαλίδα_τιμή = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for Όνομα, ΔΙΑΔΡΟΜΗ in 탑재덩이들:
        σύμβολο_τιμή = 'user_blob_' + Όνομα
        크기목록[Όνομα] = ΔΙΑΔΡΟΜΗ.stat().st_size
        # 생성한 ομότιμος_τιμή 경로만 넣어 프로젝트 경로의 공백/προσφορά 영향을 피한다.
        συγκρότηση += ['.balign 16', '.global ' + σύμβολο_τιμή, σύμβολο_τιμή + ':', '.incbin "{}"'.format(ΔΙΑΔΡΟΜΗ.relative_to(ρίζα_διαδρομή))]
        κεφαλίδα_τιμή.append('extern const unsigned char {}[];'.format(σύμβολο_τιμή))
    συγκρότηση.append('.section .note.GNU-stack,"",%progbits')
    κεφαλίδα_τιμή += ['static const εφαρμογή 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    κεφαλίδα_τιμή += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    κεφαλίδα_τιμή += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    κεφαλίδα_τιμή += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], μέθοδος_λειτουργία) for μέθοδος_λειτουργία in (0, 1)]
    κεφαλίδα_τιμή += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    κεφαλίδα_τιμή += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    κεφαλίδα_τιμή += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    κεφαλίδα_τιμή += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    κεφαλίδα_τιμή += ['};', 'static const εφαρμογή 잘못된실행항목들[] = {']
    κεφαλίδα_τιμή += ['{user_blob_invalid_%d, %d, 0},' % (순번, len(ωφέλιμο_φορτίο_δεδομένα)) for 순번, (_, ωφέλιμο_φορτίο_δεδομένα) in enumerate(υπόθεση_δοκιμής)]
    κεφαλίδα_τιμή += ['};']
    (δομή_διαδρομή / 'programs.S').write_text('\n'.join(συγκρότηση) + '\n')
    (δομή_διαδρομή / 'programs.h').write_text('\n'.join(κεφαλίδα_τιμή) + '\n')
    (출력결과 / 'invalid-cases.txt').write_text('\n'.join(Όνομα for Όνομα, _ in υπόθεση_δοκιμής) + '\n')
    εκτελώ_εντολή([Ταχυδρομικός_κώδικας_πρόγραμμα_μεταγλώττισης] + ρυθμίσεις_Υπηρεσία_έξυπνης_μεταφοράς_στο_παρασκήνιο + ['-c', δομή_διαδρομή / 'programs.S', '-o', δομή_διαδρομή / 'programs.o'])
