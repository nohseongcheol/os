            χρήση_τιμή[υποδοχή_καταχώρηση] = 1; θύρα_τιμή[υποδοχή_καταχώρηση] = 0; διεύθυνση[υποδοχή_καταχώρηση] = 0; μπροστινή_τιμή[υποδοχή_καταχώρηση] = 0; 개수[υποδοχή_καταχώρηση] = 0; 받은창구[υποδοχή_καταχώρηση] = 0;
