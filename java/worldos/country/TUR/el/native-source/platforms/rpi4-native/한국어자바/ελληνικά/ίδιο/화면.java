package ελληνικά.ίδιο;
/** 화면(畫面): 부팅 때 선택한 크기의 ίδιο πυρήνας_τιμή RGB32 프레임버퍼. */
public final class 화면 {
    private 화면() {}
    public static int 너비() { int τιμή = πυρήνας_τιμή.화면너비(); if (τιμή < 0) throw new Κατάσταση_εξαίρεση("프레임버퍼 없음"); return τιμή; }
    public static int ύψος_τιμή() { int τιμή = πυρήνας_τιμή.화면높이(); if (τιμή < 0) throw new Κατάσταση_εξαίρεση("프레임버퍼 없음"); return τιμή; }
    public static void ορθογώνιο(int 가로, int τομέας_θέση, int 폭, int ύψος_τιμή, int 색) {
        if (가로 < 0 || τομέας_θέση < 0 || 폭 < 0 || ύψος_τιμή < 0 || 가로 > 너비() || τομέας_θέση > ύψος_τιμή() || 폭 > 너비() - 가로 || ύψος_τιμή > ύψος_τιμή() - τομέας_θέση) throw new άκυρος_όρισμα_εξαίρεση("화면 απόσπασμα");
        if (πυρήνας_τιμή.ορθογώνιο(가로, τομέας_θέση, 폭, ύψος_τιμή, 색) < 0) throw new Κατάσταση_εξαίρεση("프레임버퍼 없음");
    }
    public static void διαγράφω_καταχώρηση(int 색) { ορθογώνιο(0, 0, 너비(), ύψος_τιμή(), 색); }
    public static void 기다리기() { if (πυρήνας_τιμή.그림대기() < 0) throw new Κατάσταση_εξαίρεση("αλληλεπιδραστικός είσοδος_τιμή 필요"); }
}
