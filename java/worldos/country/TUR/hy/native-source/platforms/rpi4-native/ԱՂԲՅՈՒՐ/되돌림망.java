    static int[] Առաջ_արժեք = new int[512];
    static int 다음창구 = 49152;
    static int հաստատել(int դասիչ) { return դասիչ >= 32 && դասիչ < 40 && 사용[դասիչ - 32] != 0 ? դասիչ - 32 : -1; }
