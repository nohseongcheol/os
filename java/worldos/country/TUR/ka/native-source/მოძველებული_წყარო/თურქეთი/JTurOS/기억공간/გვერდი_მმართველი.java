package თურქეთი.JTurOS.기억공간;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB გვერდი_მნიშვნელობა 연결과 ჩაწერა 시 복사를 제공한다. */
public final class გვერდი_მმართველი {
    public static final int გვერდის_ზომა = 4096;

    private static final class გვერდი_მნიშვნელობა {
        private byte[] მონაცემები = new byte[გვერდის_ზომა];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class მისამართი_სივრცე {
        private final Map<Integer, გვერდი_მნიშვნელობა> გვერდი_ცხრილი = new HashMap<Integer, გვერდი_მნიშვნელობა>();
    }

    public მისამართი_სივრცე 새주소공간() {
        return new მისამართი_სივრცე();
    }

    public void რუკის_შედგენა_გვერდი(მისამართი_სივრცე 공간, int ვირტუალური_მისამართი, boolean 쓰기가능) {
        int ინდექსი = 쪽번호(ვირტუალური_მისამართი);
        გვერდი_მნიშვნელობა 새쪽 = new გვერდი_მნიშვნელობა();
        새쪽.쓰기가능 = 쓰기가능;
        공간.გვერდი_ცხრილი.put(Integer.valueOf(ინდექსი), 새쪽);
    }

    public მისამართი_სივრცე 쓰기시복사복제(მისამართი_სივრცე 원본) {
        მისამართი_სივრცე 복제본 = new მისამართი_სივრცე();
        for (Map.Entry<Integer, გვერდი_მნიშვნელობა> შენატანი_მნიშვნელობა : 원본.გვერდი_ცხრილი.entrySet()) {
            გვერდი_მნიშვნელობა 공유쪽 = შენატანი_მნიშვნელობა.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.გვერდი_ცხრილი.put(შენატანი_მნიშვნელობა.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(მისამართი_სივრცე 공간, int ვირტუალური_მისამართი) {
        გვერდი_მნიშვნელობა მიზანი = ძებნა_გვერდი(공간, ვირტუალური_მისამართი);
        return მიზანი.მონაცემები[Math.floorMod(ვირტუალური_მისამართი, გვერდის_ზომა)];
    }

    public void ჩაწერა_ბაიტი_მნიშვნელობა(მისამართი_სივრცე 공간, int ვირტუალური_მისამართი, byte მნიშვნელობა) {
        int ინდექსი = 쪽번호(ვირტუალური_მისამართი);
        გვერდი_მნიშვნელობა მიზანი = ძებნა_გვერდი(공간, ვირტუალური_მისამართი);
        if (!მიზანი.쓰기가능) {
            if (!მიზანი.쓰기시복사) {
                throw new IllegalStateException("კითხვა 전용 쪽입니다.");
            }
            მიზანი = შექმნა_პირადი_გვერდი(공간, ინდექსი, მიზანი);
        }
        მიზანი.მონაცემები[Math.floorMod(ვირტუალური_მისამართი, გვერდის_ზომა)] = მნიშვნელობა;
    }

    public void 범위개인쓰기(მისამართი_სივრცე 공간, int დაწყება_მისამართი, int ზომა) {
        if (ზომა < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int დასასრული_მისამართი = Math.addExact(დაწყება_მისამართი, ზომა);
        for (int მისამართი = დაწყება_მისამართი; მისამართი < დასასრული_მისამართი; მისამართი = (쪽번호(მისამართი) + 1) * გვერდის_ზომა) {
            int ინდექსი = 쪽번호(მისამართი);
            გვერდი_მნიშვნელობა მიზანი = ძებნა_გვერდი(공간, მისამართი);
            if (მიზანი.쓰기시복사) {
                შექმნა_პირადი_გვერდი(공간, ინდექსი, მიზანი);
            } else {
                მიზანი.쓰기가능 = true;
            }
        }
    }

    public void 범위쓰기(მისამართი_სივრცე 공간, int დაწყება_მისამართი, byte[] მონაცემები) {
        for (int ინდექსი = 0; ინდექსი < მონაცემები.length; ინდექსი++) {
            ჩაწერა_ბაიტი_მნიშვნელობა(공간, დაწყება_მისამართი + ინდექსი, მონაცემები[ინდექსი]);
        }
    }

    private გვერდი_მნიშვნელობა შექმნა_პირადი_გვერდი(მისამართი_სივრცე 공간, int ინდექსი, გვერდი_მნიშვნელობა 공유쪽) {
        გვერდი_მნიშვნელობა პირადი_გვერდი = new გვერდი_მნიშვნელობა();
        პირადი_გვერდი.მონაცემები = Arrays.copyOf(공유쪽.მონაცემები, 공유쪽.მონაცემები.length);
        პირადი_გვერდი.쓰기가능 = true;
        პირადი_გვერდი.쓰기시복사 = false;
        공유쪽.참조수--;
        공간.გვერდი_ცხრილი.put(Integer.valueOf(ინდექსი), პირადი_გვერდი);
        return პირადი_გვერდი;
    }

    private გვერდი_მნიშვნელობა ძებნა_გვერდი(მისამართი_სივრცე 공간, int მისამართი) {
        გვერდი_მნიშვნელობა მიზანი = 공간.გვერდი_ცხრილი.get(Integer.valueOf(쪽번호(მისამართი)));
        if (მიზანი == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return მიზანი;
    }

    private int 쪽번호(int მისამართი) {
        if (მისამართი < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return მისამართი / გვერდის_ზომა;
    }
}

