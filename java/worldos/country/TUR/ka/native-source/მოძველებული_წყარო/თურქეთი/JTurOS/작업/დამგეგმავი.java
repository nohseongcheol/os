package თურქეთი.JTurOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import თურქეთი.JTurOS.기억공간.გვერდი_მმართველი;
import თურქეთი.JTurOS.ფაილური_სისტემა.파일서술자표;

/** პროცესი_მნიშვნელობა 식별자와 라운드로빈 მომზადება 대기열을 관리한다. */
public final class დამგეგმავი {
    private final გვერდი_მმართველი 쪽관리;
    private final Map<Integer, პროცესი_მნიშვნელობა> პროცესის_სია = new HashMap<Integer, პროცესი_მნიშვნელობა>();
    private final Queue<პროცესი_მნიშვნელობა> 준비대기열 = new ArrayDeque<პროცესი_მნიშვნელობა>();
    private int შემდეგი_იდენტიფიკატორი = 1;

    public დამგეგმავი(გვერდი_მმართველი 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public პროცესი_მნიშვნელობა 첫과정(파일서술자표 파일서술자) {
        პროცესი_მნიშვნელობა 새과정 = new პროცესი_მნიშვნელობა(გამოყოფა_იდენტიფიკატორი(), 0, 쪽관리.새주소공간(), 파일서술자);
        პროცესის_სია.put(Integer.valueOf(새과정.იდენტიფიკატორი_მნიშვნელობა()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public პროცესი_მნიშვნელობა 복제(პროცესი_მნიშვნელობა 부모) {
        პროცესი_მნიშვნელობა ბავშვი_მნიშვნელობა = new პროცესი_მნიშვნელობა(
                გამოყოფა_იდენტიფიკატორი(),
                부모.იდენტიფიკატორი_მნიშვნელობა(),
                쪽관리.쓰기시복사복제(부모.მისამართი_სივრცე()),
                부모.파일서술자().복제());
        ბავშვი_მნიშვნელობა.프로그램끝설정(부모.프로그램끝());
        პროცესის_სია.put(Integer.valueOf(ბავშვი_მნიშვნელობა.იდენტიფიკატორი_მნიშვნელობა()), ბავშვი_მნიშვნელობა);
        준비대기열.offer(ბავშვი_მნიშვნელობა);
        return ბავშვი_მნიშვნელობა;
    }

    public პროცესი_მნიშვნელობა შემდეგი_პროცესი() {
        int 검사수 = 준비대기열.size();
        for (int ინდექსი = 0; ინდექსი < 검사수; ინდექსი++) {
            პროცესი_მნიშვნელობა შემდეგი_ელემენტი = 준비대기열.poll();
            if (შემდეგი_ელემენტი != null && (შემდეგი_ელემენტი.სტატუსი_მნიშვნელობა() == პროცესი_სტატუსი.მომზადება || შემდეგი_ელემენტი.სტატუსი_მნიშვნელობა() == პროცესი_სტატუსი.შესრულება_ბრძანება)) {
                შემდეგი_ელემენტი.ნაკრები_სტატუსი(პროცესი_სტატუსი.შესრულება_ბრძანება);
                준비대기열.offer(შემდეგი_ელემენტი);
                return შემდეგი_ელემენტი;
            }
        }
        return null;
    }

    public int 자식기다리기(პროცესი_მნიშვნელობა 부모, int ბავშვი_იდენტიფიკატორი, boolean 기다리지않음) {
        for (პროცესი_მნიშვნელობა 후보 : პროცესის_სია.values()) {
            if (후보.부모식별자() != 부모.იდენტიფიკატორი_მნიშვნელობა()) {
                continue;
            }
            if (ბავშვი_იდენტიფიკატორი > 0 && 후보.იდენტიფიკატორი_მნიშვნელობა() != ბავშვი_იდენტიფიკატორი) {
                continue;
            }
            if (후보.სტატუსი_მნიშვნელობა() == პროცესი_სტატუსი.გასვლა_აპი) {
                int გაზომვა = (후보.გასვლა_კოდექსი() & 0xff) << 8;
                პროცესის_სია.remove(Integer.valueOf(후보.იდენტიფიკატორი_მნიშვნელობა()));
                return გაზომვა;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public პროცესი_მნიშვნელობა ძებნა_პროცესი(int იდენტიფიკატორი_მნიშვნელობა) {
        return პროცესის_სია.get(Integer.valueOf(იდენტიფიკატორი_მნიშვნელობა));
    }

    private int გამოყოფა_იდენტიფიკატორი() {
        return შემდეგი_იდენტიფიკატორი++;
    }
}
