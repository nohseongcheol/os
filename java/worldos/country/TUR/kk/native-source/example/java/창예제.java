import 한국어.자체.Терезе;
import 한국어.자체.Белгі;
import 한국어.자체.мәтіндік_өріс;
import 한국어.자체.батырма;
import 한국어.자체.оқиға_кезек;
import 한국어.자체.Шығысы;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing Терезе: kk 입력 → батырма → readme_файлы_eb81d7d9 Мәтін жаңарту. */
public class 창예제 implements 실행할일, 동작받이 {
    private Терезе 인사창;
    private мәтіндік_өріс аты_өріс;
    private Белгі 인사말;
    private int 인사횟수;

    public void ашу_терезе() {
        인사창 = new Терезе("kk Swing", 460, 300);
        인사창.Қосу_элемент(new Белгі("kk", 20, 20, 420, 28));
        аты_өріс = new мәтіндік_өріс("kk", 20, 64, 420, 30);
        인사말 = new Белгі("kk", 20, 152, 420, 28);
        인사창.Қосу_элемент(аты_өріс);
        인사창.Қосу_элемент(new батырма("인사하기", 20, 108, 180, 32, this));
        인사창.Қосу_элемент(인사말);
        인사창.Қосу_элемент(new Белгі("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.көрсету_терезе();
        Шығысы.жазу_жол("GUI 예제 Дайындау: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.жазу_Мәтін("kk, " + аты_өріс.글읽기() + "님! (" + 인사횟수 + ")");
        Шығысы.жазу_жол("GUI 인사: " + 인사말.글읽기());
    }

    public void Орындау() { ашу_терезе(); }
    public void 동작받기(동작알림 알림) {
        Шығысы.жазу_жол("Әрекет 알림: " + 알림.пәрмен_Мәтін());
        인사하기();
    }
    public static void Орындау_2() {
        оқиға_кезек.나중에실행(new 창예제());
    }
}
