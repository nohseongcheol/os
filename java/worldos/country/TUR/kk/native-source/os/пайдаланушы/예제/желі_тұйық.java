/** 최대 Өлшемі/홀수 ұзындық_мән 데이터그램으로 нақты_деректер RTL8139 수신 тұйық_мән 순환을 시험한다. */
public final class желі_тұйық {
    public static int Орындау_2() {
        if (пайдаланушы.인수개수() != 1) { пайдаланушы.Жазу("Usage: run stress PORT\n"); return 2; }
        String Мәтін = пайдаланушы.Аргументтер(0);
        int порт_мән = 0;
        for (int индекс = 0; индекс < Мәтін.length(); индекс++) {
            if (Мәтін.charAt(индекс) < '0' || Мәтін.charAt(индекс) > '9' || порт_мән > 6553) return 2;
            порт_мән = порт_мән * 10 + Мәтін.charAt(индекс) - '0';
        }
        if (порт_мән < 1 || порт_мән > 65535) return 2;
        int дескриптор_мән = пайдаланушы.ашу_желі(0);
        if (дескриптор_мән < 0) return 3;
        int[] деректер = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int ұзындық_мән = 1024 - (회차 & 1);
            for (int индекс = 0; индекс < ұзындық_мән; индекс++) деректер[индекс] = (индекс + 회차) & 255;
            if (пайдаланушы.жіберу_деректер(дескриптор_мән, 0x0a000202, порт_мән, деректер, ұзындық_мән) != ұзындық_мән) return 4;
            if (пайдаланушы.자료받기(дескриптор_мән, деректер, 300) != ұзындық_мән) return 5;
            for (int индекс = 0; индекс < ұзындық_мән; индекс++) if (деректер[индекс] != ((индекс + 회차) & 255)) return 6;
        }
        пайдаланушы.Жабу_желі(дескриптор_мән);
        пайдаланушы.Жазу("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
