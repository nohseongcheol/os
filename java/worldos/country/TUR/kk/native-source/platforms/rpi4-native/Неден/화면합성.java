/** 화면 кесу_мән·띠 합성·меңзер 밑그림을 관리한다. нақты_деректер 화면 Жад_деректер 접근은 보드가 담당한다. */
public final class 화면합성 {
    static int 너비, 높이, 합성중, 왼경계, 위경계, 오른경계, 아래경계;
    static int меңзер_X_түймешігі, меңзер_Y_түймешігі, меңзер_пішін;
    static int 기록아래낱말, 기록위낱말;
    static int[] 완성그림 = new int[32 * 1920];
    static int[] меңзер_Фон = new int[21 * 21];
    static int[] 잘린범위 = new int[4];
    public static void Дайындау(int 폭, int ұзындық_мән) {
        너비 = 폭; 높이 = ұзындық_мән; 합성중 = 0; меңзер_пішін = 0;
        기록아래낱말 = 0; 기록위낱말 = 0;
    }
    public static int 너비얻기() { return 너비; }
    public static int 높이얻기() { return 높이; }
    public static int 기록아래얻기() { return 기록아래낱말; }
    public static int 기록위얻기() { return 기록위낱말; }
    public static int клип_мән(int 순번) { return 잘린범위[순번]; }
    static int 양의길이더하기(int басы_мән, int ұзындық_мән) {
        if (басы_мән > 2147483647 - ұзындық_мән) return 2147483647;
        return басы_мән + ұзындық_мән;
    }
    public static int клип(int 가로, int Тік_лауазым, int 폭, int ұзындық_мән) {
        if (너비 == 0 || 폭 <= 0 || ұзындық_мән <= 0) return 0;
        int 오른쪽 = 양의길이더하기(가로, 폭), 아래쪽 = 양의길이더하기(Тік_лауазым, ұзындық_мән);
        int 왼쪽 = 합성중 != 0 ? 왼경계 : 0, 위쪽 = 합성중 != 0 ? 위경계 : 0;
        int 최대가로 = 합성중 != 0 ? 오른경계 : 너비, 최대세로 = 합성중 != 0 ? 아래경계 : 높이;
        if (가로 < 왼쪽) 가로 = 왼쪽;
        if (Тік_лауазым < 위쪽) Тік_лауазым = 위쪽;
        if (오른쪽 > 최대가로) 오른쪽 = 최대가로;
        if (아래쪽 > 최대세로) 아래쪽 = 최대세로;
        if (오른쪽 <= 가로 || 아래쪽 <= Тік_лауазым) return 0;
        잘린범위[0] = 가로; 잘린범위[1] = Тік_лауазым;
        잘린범위[2] = 오른쪽 - 가로; 잘린범위[3] = 아래쪽 - Тік_лауазым;
        return 1;
    }
    public static int Орындау_2(int 가로, int Тік_лауазым, int 폭, int ұзындық_мән) {
        if (합성중 != 0 || ұзындық_мән > 32 || клип(가로, Тік_лауазым, 폭, ұзындық_мән) == 0) return 0;
        왼경계 = 잘린범위[0]; 위경계 = 잘린범위[1];
        오른경계 = 왼경계 + 잘린범위[2]; 아래경계 = 위경계 + 잘린범위[3];
        합성중 = 1; return 1;
    }
    static boolean меңзер_бит(int 가로, int Тік_лауазым, int пішін_мән) {
        if (пішін_мән == 1) return 가로 >= 0 && 가로 <= Тік_лауазым / 2 && Тік_лауазым < 16;
        if (пішін_мән == 3) 가로 = 20 - 가로;
        int 차이 = 가로 - Тік_лауазым; if (차이 < 0) 차이 = -차이;
        return (차이 <= 1 && 가로 >= 3 && 가로 <= 17) ||
            (가로 >= 2 && 가로 <= 8 && Тік_лауазым >= 2 && Тік_лауазым <= 8 && (가로 <= 3 || Тік_лауазым <= 3)) ||
            (가로 >= 12 && 가로 <= 18 && Тік_лауазым >= 12 && Тік_лауазым <= 18 && (가로 >= 17 || Тік_лауазым >= 17));
    }
    static int меңзер_нүкте(int 가로, int Тік_лауазым) {
        if (меңзер_бит(가로, Тік_лауазым, меңзер_пішін)) return 2;
        for (int Жол = -1; Жол <= 1; Жол++) for (int 칸 = -1; 칸 <= 1; 칸++)
            if (меңзер_бит(가로 + 칸, Тік_лауазым + Жол, меңзер_пішін)) return 1;
        return 0;
    }
    static void дисплей_нүкте(int 가로, int Тік_лауазым, int 색) {
        int 칸 = 가로 - меңзер_X_түймешігі, Жол = Тік_лауазым - меңзер_Y_түймешігі;
        if (меңзер_пішін != 0 && 칸 >= 0 && Жол >= 0 && 칸 < 21 && Жол < 21) {
            меңзер_Фон[Жол * 21 + 칸] = 색;
            int ұпай_мән = меңзер_нүкте(칸, Жол); if (ұпай_мән != 0) 색 = ұпай_мән == 2 ? 0xffffff : 0x101010;
        }
        if (Тақта.표시화소읽기(가로, Тік_лауазым) != 색) {
            Тақта.жазу_дисплей_нүкте(가로, Тік_лауазым, 색);
            기록아래낱말++; if (기록아래낱말 == 0) 기록위낱말++;
        }
    }
    public static void соңы() {
        if (합성중 == 0) return;
        for (int Жол = 위경계; Жол < 아래경계; Жол++) for (int 칸 = 왼경계; 칸 < 오른경계; 칸++)
            дисплей_нүкте(칸, Жол, 완성그림[(Жол - 위경계) * 1920 + 칸]);
        합성중 = 0;
    }
    public static int нүкте(int 가로, int Тік_лауазым, int 색) {
        if (가로 < 0 || Тік_лауазым < 0 || 가로 >= 너비 || Тік_лауазым >= 높이) return 0;
        if (합성중 != 0) {
            if (가로 >= 왼경계 && 가로 < 오른경계 && Тік_лауазым >= 위경계 && Тік_лауазым < 아래경계)
                완성그림[(Тік_лауазым - 위경계) * 1920 + 가로] = 색;
        } else дисплей_нүкте(가로, Тік_лауазым, 색);
        return 0;
    }
    public static void тік_төртбұрыш_бояу(int 가로, int Тік_лауазым, int 폭, int ұзындық_мән, int 색) {
        if (клип(가로, Тік_лауазым, 폭, ұзындық_мән) == 0) return;
        가로 = 잘린범위[0]; Тік_лауазым = 잘린범위[1]; 폭 = 잘린범위[2]; ұзындық_мән = 잘린범위[3];
        for (int Жол = Тік_лауазым; Жол < Тік_лауазым + ұзындық_мән; Жол++) for (int 칸 = 가로; 칸 < 가로 + 폭; 칸++) {
            if (합성중 != 0) 완성그림[(Жол - 위경계) * 1920 + 칸] = 색;
            else дисплей_нүкте(칸, Жол, 색);
        }
    }
    public static void меңзер(int 가로, int Тік_лауазым, int пішін_мән) {
        if (너비 == 0) return;
        int 새가로 = 가로 - (пішін_мән >= 2 ? 10 : 0), 새세로 = Тік_лауазым - (пішін_мән >= 2 ? 10 : 0);
        if (меңзер_пішін == пішін_мән && меңзер_X_түймешігі == 새가로 && меңзер_Y_түймешігі == 새세로) return;
        if (меңзер_пішін != 0) for (int Жол = 0; Жол < 21; Жол++) for (int 칸 = 0; 칸 < 21; 칸++) {
            int 가 = меңзер_X_түймешігі + 칸, 세 = меңзер_Y_түймешігі + Жол;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) Тақта.жазу_дисплей_нүкте(가, 세, меңзер_Фон[Жол * 21 + 칸]);
        }
        меңзер_пішін = пішін_мән; меңзер_X_түймешігі = 새가로; меңзер_Y_түймешігі = 새세로;
        if (пішін_мән != 0) for (int Жол = 0; Жол < 21; Жол++) for (int 칸 = 0; 칸 < 21; 칸++) {
            int 가 = меңзер_X_түймешігі + 칸, 세 = меңзер_Y_түймешігі + Жол;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) {
                меңзер_Фон[Жол * 21 + 칸] = Тақта.표시화소읽기(가, 세);
                int ұпай_мән = меңзер_нүкте(칸, Жол); if (ұпай_мән != 0) Тақта.жазу_дисплей_нүкте(가, 세, ұпай_мән == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
