#include "호출경계.h"
extern int main(int 인수개수, char **аргумент_Тізім);
static char аргумент_Жад[2048];
static char *аргумент_Тізім[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* ток_элемент 커널의 argv는 орындау_пәрмен 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    аргумент_Тізім[0] = "jkoros-app";
    int Орны = 0;
    for (int индекс = 0; индекс < 개수; индекс++) {
        const int *원본 = (const int *)jkoros_syscall(3, индекс, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        аргумент_Тізім[индекс + 1] = аргумент_Жад + Орны;
        for (int 칸 = 0; 칸 < 원본[0]; 칸++) {
            if (Орны >= 2047) return 126;
            аргумент_Жад[Орны++] = 원본[칸 + 1];
        }
        аргумент_Жад[Орны++] = 0;
    }
    аргумент_Тізім[개수 + 1] = 0;
    return main(개수 + 1, аргумент_Тізім);
}
