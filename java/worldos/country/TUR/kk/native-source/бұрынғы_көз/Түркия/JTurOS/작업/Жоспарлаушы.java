package Түркия.JTurOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import Түркия.JTurOS.Жад_аумақ.бет_менеджер;
import Түркия.JTurOS.файлдық_жүйе.파일서술자표;

/** Процесс_мән 식별자와 라운드로빈 Дайындау 대기열을 관리한다. */
public final class Жоспарлаушы {
    private final бет_менеджер 쪽관리;
    private final Map<Integer, Процесс_мән> Процестер_тізімі = new HashMap<Integer, Процесс_мән>();
    private final Queue<Процесс_мән> 준비대기열 = new ArrayDeque<Процесс_мән>();
    private int Келесі_идентификатор = 1;

    public Жоспарлаушы(бет_менеджер 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public Процесс_мән 첫과정(파일서술자표 파일서술자) {
        Процесс_мән 새과정 = new Процесс_мән(бекіту_идентификатор(), 0, 쪽관리.새주소공간(), 파일서술자);
        Процестер_тізімі.put(Integer.valueOf(새과정.идентификатор_мән()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public Процесс_мән клон_мән(Процесс_мән басты_мән) {
        Процесс_мән еншілес_элемент_мән = new Процесс_мән(
                бекіту_идентификатор(),
                басты_мән.идентификатор_мән(),
                쪽관리.쓰기시복사복제(басты_мән.мекенжай_орын()),
                басты_мән.파일서술자().клон_мән());
        еншілес_элемент_мән.жинақ_бағдарлама_үзу(басты_мән.бағдарлама_үзу());
        Процестер_тізімі.put(Integer.valueOf(еншілес_элемент_мән.идентификатор_мән()), еншілес_элемент_мән);
        준비대기열.offer(еншілес_элемент_мән);
        return еншілес_элемент_мән;
    }

    public Процесс_мән Келесі_Процесс() {
        int 검사수 = 준비대기열.size();
        for (int индекс = 0; индекс < 검사수; индекс++) {
            Процесс_мән Келесі_элемент = 준비대기열.poll();
            if (Келесі_элемент != null && (Келесі_элемент.күй_мән() == Процесс_күй.Дайындау || Келесі_элемент.күй_мән() == Процесс_күй.орындау_пәрмен)) {
                Келесі_элемент.жинақ_күй(Процесс_күй.орындау_пәрмен);
                준비대기열.offer(Келесі_элемент);
                return Келесі_элемент;
            }
        }
        return null;
    }

    public int 자식기다리기(Процесс_мән басты_мән, int еншілес_элемент_идентификатор, boolean 기다리지않음) {
        for (Процесс_мән 후보 : Процестер_тізімі.values()) {
            if (후보.басты_идентификатор() != басты_мән.идентификатор_мән()) {
                continue;
            }
            if (еншілес_элемент_идентификатор > 0 && 후보.идентификатор_мән() != еншілес_элемент_идентификатор) {
                continue;
            }
            if (후보.күй_мән() == Процесс_күй.Шығу_бағдарлама) {
                int НӘТИЖЕ = (후보.Шығу_код() & 0xff) << 8;
                Процестер_тізімі.remove(Integer.valueOf(후보.идентификатор_мән()));
                return НӘТИЖЕ;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public Процесс_мән Табу_Процесс(int идентификатор_мән) {
        return Процестер_тізімі.get(Integer.valueOf(идентификатор_мән));
    }

    private int бекіту_идентификатор() {
        return Келесі_идентификатор++;
    }
}
