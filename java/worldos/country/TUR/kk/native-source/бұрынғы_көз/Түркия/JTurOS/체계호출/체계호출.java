    public int 접근가능(String Аты, int әдіс_режим) {
        файл_ақпарат Жүйелік_ақпарат = файлдық_жүйе.Жүйелік_ақпарат(Аты);
        if (Жүйелік_ақпарат == null) {
            return -2;
        }
        if ((әдіс_режим & 1) != 0 && (Жүйелік_ақпарат.형태() & 0111) == 0) {
            return -13;
        }
        if ((әдіс_режим & 2) != 0) {
            return -30;
        }
        return 0;
    }

