    public int файл_Басқару(Процесс_мән ток_Процесс, int 서술자, int Команда, int параметр_аргумент) {
        if (Команда == 0) {
            return ток_Процесс.파일서술자().복제서술자(서술자, параметр_аргумент);
        }
        if (Команда == 1) {
            return ток_Процесс.파일서술자().실행시닫기값(서술자);
        }
        if (Команда == 2) {
            return ток_Процесс.파일서술자().실행시닫기설정(서술자, (параметр_аргумент & 1) != 0);
        }
        if (Команда == 3) {
            return ток_Процесс.파일서술자().Жүйелік_ақпарат(서술자) == null ? -9 : тек_оқу_үшін_жалауша;
        }
        if (Команда == 4) {
            return параметр_аргумент == тек_оқу_үшін_жалауша ? 0 : -30;
        }
        return -22;
    }

