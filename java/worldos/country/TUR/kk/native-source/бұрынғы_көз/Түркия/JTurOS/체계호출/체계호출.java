    public int Оқу(Процесс_мән ток_Процесс, int 서술자, byte[] 받을곳, int Өлшемі) {
        if (서술자 == 0) {
            if (Өлшемі <= 0 || 받을곳.length == 0) {
                return 0;
            }
            입력사건 Оқиға = 입력관리.Келесі_оқиға();
            if (Оқиға == null || Оқиға.оқиға_түрі() != 입력사건.종류.Кілт_ажыратылған) {
                return -11;
            }
            받을곳[0] = (byte) Оқиға.첫째값();
            return 1;
        }
        return ток_Процесс.파일서술자().Оқу(서술자, 받을곳, Өлшемі);
    }

    public int Жазу(Процесс_мән ток_Процесс, int 서술자, byte[] деректер, int Өлшемі) {
        if (서술자 != 1 && 서술자 != 2) {
            return ток_Процесс.파일서술자().ақпараттық_жүйелер_ашу(서술자) ? -30 : -9;
        }
        if (Өлшемі < 0 || Өлшемі > деректер.length) {
            return -22;
        }
        құрылғы_мән.직렬출력(new String(деректер, 0, Өлшемі, java.nio.charset.StandardCharsets.UTF_8));
        return Өлшемі;
    }

