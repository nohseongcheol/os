    public int орындау_пәрмен(Процесс_мән ток_Процесс, byte[] 실행파일, String[] параметр_аргумент, String[] 환경) {
        실행파일적재기.сурет сурет_мән;
        try {
            сурет_мән = 적재기.검사(실행파일);
        } catch (IllegalArgumentException Қате) {
            return -8;
        }
        if (параметр_аргумент == null || 환경 == null || параметр_аргумент.length > 16 || 환경.length > 16) {
            return -7;
        }
        for (실행파일적재기.бөлім_мән_366e0bfa бөлім_мән_366e0bfa : сурет_мән.구역들()) {
            if ((бөлім_мән_366e0bfa.жалауша_мән() & 2) == 0 || бөлім_мән_366e0bfa.Өлшемі() == 0) {
                continue;
            }
            int 첫쪽 = бөлім_мән_366e0bfa.мекенжай() / бет_менеджер.бет_өлшемі;
            int 끝쪽 = (бөлім_мән_366e0bfa.мекенжай() + бөлім_мән_366e0bfa.Өлшемі() + бет_менеджер.бет_өлшемі - 1) / бет_менеджер.бет_өлшемі;
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int мекенжай = индекс * бет_менеджер.бет_өлшемі;
                try {
                    쪽관리.바이트읽기(ток_Процесс.мекенжай_орын(), мекенжай);
                    쪽관리.Жеке_ауқым_жазу(ток_Процесс.мекенжай_орын(), мекенжай, бет_менеджер.бет_өлшемі);
                } catch (IllegalStateException Қате) {
                    쪽관리.карта_бет(ток_Процесс.мекенжай_орын(), мекенжай, true);
                }
            }
            for (int индекс = 0; индекс < бөлім_мән_366e0bfa.Өлшемі(); индекс++) {
                byte мән = бөлім_мән_366e0bfa.종류() == 8 ? 0 : 실행파일[бөлім_мән_366e0bfa.файл_лауазым() + индекс];
                쪽관리.жазу_байт_мән(ток_Процесс.мекенжай_орын(), бөлім_мән_366e0bfa.мекенжай() + индекс, мән);
            }
        }
        ток_Процесс.실행문맥설정(сурет_мән.басы_мекенжай(), параметр_аргумент, 환경);
        ток_Процесс.파일서술자().실행시닫기();
        return 0;
    }

