    public int бағдарлама_үзу(Процесс_мән ток_Процесс, int 새끝) {
        int 이전끝 = ток_Процесс.бағдарлама_үзу();
        if (새끝 == 0) {
            return 이전끝;
        }
        if (새끝 < 0x06000000 || 새끝 > 0x07000000) {
            return -12;
        }
        int 첫쪽 = 이전끝 / бет_менеджер.бет_өлшемі;
        int 끝쪽 = (새끝 + бет_менеджер.бет_өлшемі - 1) / бет_менеджер.бет_өлшемі;
        if (새끝 > 이전끝) {
            for (int индекс = 첫쪽; индекс < 끝쪽; индекс++) {
                int мекенжай = индекс * бет_менеджер.бет_өлшемі;
                try {
                    쪽관리.바이트읽기(ток_Процесс.мекенжай_орын(), мекенжай);
                } catch (IllegalStateException Қате) {
                    쪽관리.карта_бет(ток_Процесс.мекенжай_орын(), мекенжай, true);
                }
            }
        }
        ток_Процесс.жинақ_бағдарлама_үзу(새끝);
        return 새끝;
    }

    public int 프로그램끝늘리기(Процесс_мән ток_Процесс, int өсім_қадамы_көлем) {
        int 이전끝 = ток_Процесс.бағдарлама_үзу();
        int НӘТИЖЕ = бағдарлама_үзу(ток_Процесс, 이전끝 + өсім_қадамы_көлем);
        return НӘТИЖЕ < 0 ? НӘТИЖЕ : 이전끝;
    }

