import 中文.內建.*;

/** 在 OpenJDK 與自製 JVM 上執行相同位元組碼的通訊契約測試。 */
public class 測試韓語聯網 {
    public static void main(String[] 實參) throws 輸入輸出異常 {
        接收埠 埠值 = 連接狀態傳輸.打開接收者(0);
        連接通道 客戶機值 = 連接狀態傳輸.打開("127.0.0.1", 埠值.埠編號());
        連接通道 所有者標識符 = 埠值.接收();
        客戶機值.超時(200); 所有者標識符.超時(200);
        檢查項.確認真值(客戶機值.已連接() && !客戶機值.是否已關閉(), "連接 狀態值");
        檢查項.確認真值(所有者標識符.埠編號() == 客戶機值.局部埠編號(), "對端值 埠編號");
        檢查項.確認真值(客戶機值.埠編號() == 所有者標識符.局部埠編號(), "局部作用域 埠編號");
        輸入流 輸入值 = 所有者標識符.輸入值(); 輸出流 輸出頁 = 客戶機值.輸出();
        byte[] 消息 = 字元.編碼("한글 流值");
        輸出頁.寫入(消息, 0, 消息.length); 輸出頁.發射值();
        byte[] 已接收文本 = new byte[消息.length];
        int 讀取個數 = 0;
        while (讀取個數 < 已接收文本.length) {
            int 附加讀取 = 輸入值.讀取(已接收文本, 讀取個數, 已接收文本.length - 讀取個數);
            檢查項.確認真值(附加讀取 > 0, "예상하지 않은 檔案 結尾"); 讀取個數 += 附加讀取;
        }
        檢查項.確認真值(字元.相等文本(字元.解密資料(已接收文本), "한글 流值"), "子部分值 읽기와 寫入");
        輸出頁.寫入(new byte[] {17, 18});
        byte[] 讀取短整數 = new byte[2];
        int 首位讀取 = 輸入值.讀取(讀取短整數);
        檢查項.確認真值(首位讀取 > 0 && 讀取短整數[0] == 17, "陣列值 讀取");
        if (首位讀取 == 1) 讀取短整數[1] = (byte)輸入值.讀取();
        檢查項.確認真值(讀取短整數[1] == 18, "餘數值 讀取");
        所有者標識符.輸出().寫入(255);
        檢查項.確認真值(客戶機值.輸入值().讀取() == 255, "編碼狀態值 없는 한 位元組值");
        輸出頁.關閉();
        檢查項.確認真值(客戶機值.是否已關閉() && 輸入值.讀取() == -1, "닫기와 檔案 結尾");
        輸入值.關閉(); 檢查項.確認真值(所有者標識符.是否已關閉(), "輸入值 流值 關閉");
        客戶機值.關閉(); 所有者標識符.關閉();
        埠值.超時(15);
        boolean 執行狀態超時 = false;
        try { 埠值.接收(); } catch (等待狀態超時異常 預期錯誤) { 執行狀態超時 = true; }
        檢查項.確認真值(執行狀態超時, "接收值 超時");
        埠值.關閉(); 檢查項.確認真值(埠值.是否已關閉(), "接收埠 關閉");
        數據報信道 接收者端點 = 數據報信道.打開(0), 發送中端點 = 數據報信道.打開(0);
        接收者端點.超時(200);
        發送中端點.發送("127.0.0.1", 接收者端點.埠編號(), "數據報 한글");
        檢查項.確認真值(字元.相等文本(接收者端點.接收(), "數據報 한글"), "數據報 송수신");
        發送中端點.關閉(); 接收者端點.關閉();
        檢查項.確認真值(發送中端點.是否已關閉() && 接收者端點.是否已關閉(), "數據報 關閉");
        輸出.寫入行("中文 通信 驗證: 連接 數據報 流值 執行狀態超時 關閉");
    }
}
