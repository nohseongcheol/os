/** PCI RTL8139 (10ec:8139), 단일 भेजें_मान 버퍼와 8KiB 수신 लूप_मान. 인터럽트 대신 폴링한다. */
public final class नेटवर्क_डिवाइस_ड्राइवर {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] उपकरण_पता = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int पढें_सेटिंग(int 장치번호, int स्थान) {
        उपकरण_मान.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | स्थान);
        return उपकरण_मान.입출력정수읽기(0xcfc);
    }

    static boolean 준비() {
        int 장치번호 = -1;
        for (int इंडेक्स = 0; इंडेक्स < 32; इंडेक्स++) {
            if (पढें_सेटिंग(इंडेक्स, 0) == 0x813910ec) { 장치번호 = इंडेक्स; break; }
        }
        if (장치번호 < 0) return false;
        int डिफ़ॉल्ट_मान = पढें_सेटिंग(장치번호, 0x10);
        if ((डिफ़ॉल्ट_मान & 1) == 0 || (डिफ़ॉल्ट_मान & 0xfffffffc) < 0x100 || (डिफ़ॉल्ट_मान & 0xfffffffc) > 65535) return false;
        입출력기준주소 = डिफ़ॉल्ट_मान & 0xfffc;
        int आदेश = पढें_सेटिंग(장치번호, 4);
        उपकरण_मान.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        उपकरण_मान.입출력짧은수쓰기(0xcfc, आदेश | 5); // I/O 및 bus master अनुमति_दें_मान, PCI अवस्था_मान 비트는 건드리지 않음
        उपकरण_मान.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!रीसेट_करें_मान()) { 입출력기준주소 = 0; return false; }
        for (int इंडेक्स = 0; इंडेक्स < 6; इंडेक्स++) उपकरण_पता[इंडेक्स] = उपकरण_मान.입출력바이트읽기(입출력기준주소 + इंडेक्स);
        return true;
    }

    static boolean रीसेट_करें_मान() {
        उपकरण_मान.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int चलाएँ = उपकरण_मान.밀리초();
        while ((उपकरण_मान.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (उपकरण_मान.밀리초() - चलाएँ > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        उपकरण_मान.입출력정수쓰기(입출력기준주소 + 0x30, उपकरण_मान.नेटवर्क_मेमोरी());
        for (int इंडेक्स = 0; इंडेक्स < 4; इंडेक्स++) उपकरण_मान.입출력정수쓰기(입출력기준주소 + 0x20 + इंडेक्स * 4, उपकरण_मान.नेटवर्क_मेमोरी() + 12288);
        उपकरण_मान.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        उपकरण_मान.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        उपकरण_मान.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        उपकरण_मान.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/प्रसारण_मान, wrap 연속 स्टोर_मान, 8KiB
        उपकरण_मान.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int भेजें(int[] आँकड़े, int 길이) {
        if (입출력기준주소 == 0) return -19;
        if (길이 < 14 || 길이 > 1514) return -90;
        int स्थिति_पोर्ट = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int चलाएँ = उपकरण_मान.밀리초();
        while ((उपकरण_मान.입출력정수읽기(स्थिति_पोर्ट) & 0x2000) == 0)
            if (उपकरण_मान.밀리초() - चलाएँ > 100) return -110;
        int आकार = 길이 < 60 ? 60 : 길이;
        for (int इंडेक्स = 0; इंडेक्स < आकार; इंडेक्स++)
            उपकरण_मान.लिखना_मेमोरी(उपकरण_मान.नेटवर्क_मेमोरी() + 12288 + इंडेक्स, इंडेक्स < 길이 ? आँकड़े[इंडेक्स] : 0);
        उपकरण_मान.입출력정수쓰기(स्थिति_पोर्ट, आकार | 0x00080000);
        चलाएँ = उपकरण_मान.밀리초();
        while ((उपकरण_मान.입출력정수읽기(स्थिति_पोर्ट) & 0xe0008000) == 0)
            if (उपकरण_मान.밀리초() - चलाएँ > 100) return -110;
        if ((उपकरण_मान.입출력정수읽기(स्थिति_पोर्ट) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return 길이;
    }

    static int 받기(int[] आँकड़े) {
        if (입출력기준주소 == 0) return 0;
        if ((उपकरण_मान.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!रीसेट_करें_मान()) 입출력기준주소 = 0;
            return 0;
        }
        if ((उपकरण_मान.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = उपकरण_मान.नेटवर्क_मेमोरी() + 수신위치;
        int अवस्था_मान = 실행관리.짧은수(머리), आकार = 실행관리.짧은수(머리 + 2);
        if (आकार == 0xfff0) return 0; // DMA 진행 중
        if (आकार < 4 || आकार > 1518) {
            오류수++;
            if (!रीसेट_करें_मान()) 입출력기준주소 = 0;
            return 0;
        }
        int 길이 = आकार - 4;
        if ((अवस्था_मान & 1) != 0) {
            for (int इंडेक्स = 0; इंडेक्स < 길이; इंडेक्स++) आँकड़े[इंडेक्स] = उपकरण_मान.पढें_मेमोरी(머리 + 4 + इंडेक्स);
            수신수++;
        } else { 길이 = 0; 오류수++; }
        수신위치 = (수신위치 + आकार + 4 + 3) & ~3;
        수신위치 &= 8191;
        उपकरण_मान.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        उपकरण_मान.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return 길이;
    }
}
