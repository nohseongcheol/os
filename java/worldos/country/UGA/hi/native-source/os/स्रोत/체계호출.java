/** int 0x80 게이트가 호출한다. 모든 उपयोगकर्ता सूचक/길이는 पहुँच_एन्ट्री 전에 검사한다. */
public final class 체계호출 {
    static int[] 임시자료 = new int[1024];

    static int 배열길이(int पता) {
        if (!실행관리.क्लिप(पता, 4)) return -14;
        int 길이 = 실행관리.수(पता);
        if (길이 < 0 || 길이 > (실행관리.उपयोगकर्ता_समाप्त_करें - पता - 4) / 4) return -14;
        return 길이;
    }

    public static int प्रक्रिया_मान_एन्ट्री(int इंडेक्स, int 가, int 나, int 다, int 라, int 마) {
        if (इंडेक्स == 30) return 파일서술자관리.जारी_फ़ाइल(가, 나, 다);
        if (इंडेक्स == 31) return 파일서술자관리.पढें_फ़ाइल(가, 나, 다);
        if (इंडेक्स == 32) return 파일서술자관리.लिखना_फ़ाइल(가, 나, 다);
        if (इंडेक्स == 33) return 파일서술자관리.बंद_फ़ाइल(가);
        if (इंडेक्स == 34) return 파일서술자관리.खोजें_फ़ाइल(가, 나, 다);
        if (इंडेक्स == 35) return 파일서술자관리.서술자복제(가, 0, false, 0);
        if (इंडेक्स == 36) return 파일서술자관리.서술자복제(가, 나, true, 0);
        if (इंडेक्स == 37) return 파일서술자관리.पढें_फ़ाइल_स्थिति(가, 나);
        if (इंडेक्स == 38) return 파일서술자관리.निकालें_फ़ाइल_एन्ट्री_नाम(가);
        if (इंडेक्स == 39) return 파일서술자관리.파일길이정하기(가, 나);
        if (इंडेक्स == 40) return 파일서술자관리.서술자제어(가, 나, 다);
        if (इंडेक्स == 41) return 파일서술자관리.बनाएँ_एंडपॉइंट(가, 나, 다);
        if (इंडेक्स == 42) return 파일서술자관리.बाइंड_करें_पता(가, 나, 다);
        if (इंडेक्स == 43) return 파일서술자관리.자료전문보내기(가, 나, 다, 라, 마);
        if (इंडेक्स == 44) return 파일서술자관리.자료전문받기(가, 나, 다, 라, 마);
        if (इंडेक्स == 45) return 파일서술자관리.पढें_सॉकेट_पता(가, 나, 다);
        if (इंडेक्स == 46) return 파일서술자관리.수신대기정하기(가, 나);
        if (इंडेक्स == 47) {
            int 기술 = 파일서술자관리.기술찾기(가);
            if (기술 < 0) return -9;
            if (파일서술자관리.종류[기술] != 2) return -22;
            return 파일보존.सिंक्रनाइज़_करें();
        }
        if (इंडेक्स == 1) {
            int 길이 = 배열길이(가);
            if (길이 < 0) return 길이;
            if (길이 > 4096) return -90;
            for (int कैरेक्टर_मान = 0; कैरेक्टर_मान < 길이; कैरेक्टर_मान++) पाठ_टर्मिनल.문자(실행관리.수(가 + 4 + कैरेक्टर_मान * 4) & 65535);
            return 길이;
        }
        if (इंडेक्स == 2) return 실행관리.인수수;
        if (इंडेक्स == 3) return 가 >= 0 && 가 < 실행관리.인수수 ? 실행관리.तर्क_पता[가] : 0;
        if (इंडेक्स == 10) return नेटवर्क_स्टैक.खोलें(가);
        if (इंडेक्स == 11) {
            int 길이 = 배열길이(라);
            if (길이 < 0) return 길이;
            if (마 < 0 || 마 > 길이 || 마 > 1024) return -90;
            for (int स्थान = 0; स्थान < 마; स्थान++) 임시자료[स्थान] = 실행관리.수(라 + 4 + स्थान * 4) & 255;
            return नेटवर्क_स्टैक.भेजें(가, 나, 다, 임시자료, 마);
        }
        if (इंडेक्स == 12) {
            int 길이 = 배열길이(나);
            if (길이 < 0) return 길이;
            if (다 < 0 || 다 > 2000) return -22;
            int परिणाम = नेटवर्क_स्टैक.받기(가, 임시자료, 길이 < 1024 ? 길이 : 1024, 다);
            if (परिणाम >= 0) for (int स्थान = 0; स्थान < परिणाम; स्थान++) 실행관리.수쓰기(나 + 4 + स्थान * 4, 임시자료[स्थान]);
            return परिणाम;
        }
        if (इंडेक्स == 13) return नेटवर्क_स्टैक.बंदकरें(가);
        if (इंडेक्स == 14) return नेटवर्क_स्टैक.내주소;
        if (इंडेक्स == 15) return नेटवर्क_स्टैक.पीअर_पता(가);
        if (इंडेक्स == 16) return नेटवर्क_स्टैक.पीअर_पोर्ट_संख्या(가);
        if (इंडेक्स == 22) {
            if (가 < 0 || 가 > 65535) return -22;
            पाठ_टर्मिनल.문자(가); return 1;
        }
        if (इंडेक्स == 20 || इंडेक्स == 21) {
            int नाम_आकार = 배열길이(가), डेटा_आकार = 배열길이(나);
            if (नाम_आकार < 0 || डेटा_आकार < 0) return -14;
            if (नाम_आकार < 1 || नाम_आकार > 64) return -22;
            int 길이 = 0;
            while (길이 < नाम_आकार && 실행관리.수(가 + 4 + 길이 * 4) != 0) {
                मेमोरी_फ़ाइल_सिस्टम.नाम[길이] = 실행관리.수(가 + 4 + 길이 * 4);
                길이++;
            }
            if (!मेमोरी_फ़ाइल_सिस्टम.जाँचें_नाम(मेमोरी_फ़ाइल_सिस्टम.नाम, 길이)) return -22;
            if (इंडेक्स == 20) {
                int संचिका = मेमोरी_फ़ाइल_सिस्टम.खोजें_एन्ट्री(मेमोरी_फ़ाइल_सिस्टम.नाम, 길이);
                if (संचिका < 0) return संचिका;
                int आकार = मेमोरी_फ़ाइल_सिस्टम.आकार_सूची[संचिका];
                if (आकार > डेटा_आकार) return -90;
                int पता = उपकरण_मान.फ़ाइल_मेमोरी() + संचिका * मेमोरी_फ़ाइल_सिस्टम.최대크기;
                for (int 수 = 0; 수 < आकार; 수++) 실행관리.수쓰기(나 + 4 + 수 * 4, उपकरण_मान.पढें_मेमोरी(पता + 수));
                return आकार;
            }
            if (다 < 0 || 다 > डेटा_आकार) return -22;
            if (다 > मेमोरी_फ़ाइल_सिस्टम.최대크기) return -90;
            for (int 수 = 0; 수 < 다; 수++) मेमोरी_फ़ाइल_सिस्टम.संपादन_मान[수] = 실행관리.수(나 + 4 + 수 * 4) & 255;
            return मेमोरी_फ़ाइल_सिस्टम.स्टोर_मान(मेमोरी_फ़ाइल_सिस्टम.नाम, 길이, मेमोरी_फ़ाइल_सिस्टम.संपादन_मान, 다);
        }
        return -38;
    }
}
