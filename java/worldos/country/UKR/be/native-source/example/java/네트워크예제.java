import 한국어.자체.кантакт;
import 한국어.자체.실행인수;
import 한국어.자체.전문통로;
import 한국어.자체.문자;
import 한국어.자체.Выхад;
import 한국어.자체.검사;
import 한국어.자체.입력흐름;
import 한국어.자체.увод_вывад_выключэнне;

public class 네트워크예제 {
    public static void Выканаць() throws увод_вывад_выключэнне {
        // вузел: python3 Інструменты/예제되돌림.py --tcp-port 9000 --udp-port 9001
        кантакт Злучыцца = кантакт.Адкрыць("10.0.2.2", 문자.정수읽기(실행인수.Тэкст(0)));
        try {
            Злучыцца.대기시간(700);
            byte[] ліст = 문자.부호화("JAVA TCP be\n");
            Злучыцца.Выхад().Запіс(ліст);
            입력흐름 입력 = Злучыцца.입력();
            for (int 수 = 0; 수 < 문자.바이트수(ліст); 수++) {
                검사.참인지(입력.Чытанне() == (ліст[수] & 255), "TCP адказаць 불일치");
            }
        } finally { Злучыцца.Закрыць(); }
        전문통로 종단 = 전문통로.Адкрыць(0);
        try {
            종단.대기시간(700);
            종단.адправіць("10.0.2.2", 문자.정수읽기(실행인수.Тэкст(1)), "JAVA UDP be");
            검사.참인지(문자.같음(종단.받기(), "JAVA UDP be"), "UDP адказаць 불일치");
        } finally { 종단.Закрыць(); }
        Выхад.напісаць_лінія("JAVA 네트워크 праверыць: TCP UDP be");
    }
}
