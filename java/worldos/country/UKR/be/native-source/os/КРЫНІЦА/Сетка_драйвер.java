/** PCI RTL8139 (10ec:8139), 단일 адправіць_значэнне 버퍼와 8KiB 수신 цыкл_значэнне. 인터럽트 대신 폴링한다. */
public final class Сетка_драйвер {
    static int 입출력기준주소 = 0;
    static int 수신위치 = 0, 송신칸 = 0;
    static int[] прылада_адрас = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int Пазіцыя) {
        прылада_значэнне.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | Пазіцыя);
        return прылада_значэнне.입출력정수읽기(0xcfc);
    }

    static boolean Падрыхтаваць() {
        int 장치번호 = -1;
        for (int індэкс = 0; індэкс < 32; індэкс++) {
            if (설정읽기(індэкс, 0) == 0x813910ec) { 장치번호 = індэкс; break; }
        }
        if (장치번호 < 0) return false;
        int значэнне_па_змаўчанні = 설정읽기(장치번호, 0x10);
        if ((значэнне_па_змаўчанні & 1) == 0 || (значэнне_па_змаўчанні & 0xfffffffc) < 0x100 || (значэнне_па_змаўчанні & 0xfffffffc) > 65535) return false;
        입출력기준주소 = значэнне_па_змаўчанні & 0xfffc;
        int Загад = 설정읽기(장치번호, 4);
        прылада_значэнне.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        прылада_значэнне.입출력짧은수쓰기(0xcfc, Загад | 5); // I/O 및 bus master Дазволіць_значэнне, PCI стан_значэнне 비트는 건드리지 않음
        прылада_значэнне.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!скінуць_значэнне()) { 입출력기준주소 = 0; return false; }
        for (int індэкс = 0; індэкс < 6; індэкс++) прылада_адрас[індэкс] = прылада_значэнне.입출력바이트읽기(입출력기준주소 + індэкс);
        return true;
    }

    static boolean скінуць_значэнне() {
        прылада_значэнне.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int Выканаць = прылада_значэнне.밀리초();
        while ((прылада_значэнне.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (прылада_значэнне.밀리초() - Выканаць > 100) return false;
        수신위치 = 0; 송신칸 = 0;
        прылада_значэнне.입출력정수쓰기(입출력기준주소 + 0x30, прылада_значэнне.Сетка_памяць());
        for (int індэкс = 0; індэкс < 4; індэкс++) прылада_значэнне.입출력정수쓰기(입출력기준주소 + 0x20 + індэкс * 4, прылада_значэнне.Сетка_памяць() + 12288);
        прылада_значэнне.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        прылада_значэнне.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        прылада_значэнне.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        прылада_значэнне.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/трансляцыя_значэнне, wrap 연속 сховішча_значэнне, 8KiB
        прылада_значэнне.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int адправіць(int[] дадзеныя, int даўжыня_значэнне) {
        if (입출력기준주소 == 0) return -19;
        if (даўжыня_значэнне < 14 || даўжыня_значэнне > 1514) return -90;
        int стан_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int Выканаць = прылада_значэнне.밀리초();
        while ((прылада_значэнне.입출력정수읽기(стан_порт) & 0x2000) == 0)
            if (прылада_значэнне.밀리초() - Выканаць > 100) return -110;
        int Памер = даўжыня_значэнне < 60 ? 60 : даўжыня_значэнне;
        for (int індэкс = 0; індэкс < Памер; індэкс++)
            прылада_значэнне.напісаць_памяць(прылада_значэнне.Сетка_памяць() + 12288 + індэкс, індэкс < даўжыня_значэнне ? дадзеныя[індэкс] : 0);
        прылада_значэнне.입출력정수쓰기(стан_порт, Памер | 0x00080000);
        Выканаць = прылада_значэнне.밀리초();
        while ((прылада_значэнне.입출력정수읽기(стан_порт) & 0xe0008000) == 0)
            if (прылада_значэнне.밀리초() - Выканаць > 100) return -110;
        if ((прылада_значэнне.입출력정수읽기(стан_порт) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return даўжыня_значэнне;
    }

    static int 받기(int[] дадзеныя) {
        if (입출력기준주소 == 0) return 0;
        if ((прылада_значэнне.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!скінуць_значэнне()) 입출력기준주소 = 0;
            return 0;
        }
        if ((прылада_значэнне.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = прылада_значэнне.Сетка_памяць() + 수신위치;
        int стан_значэнне = 실행관리.짧은수(머리), Памер = 실행관리.짧은수(머리 + 2);
        if (Памер == 0xfff0) return 0; // DMA 진행 중
        if (Памер < 4 || Памер > 1518) {
            오류수++;
            if (!скінуць_значэнне()) 입출력기준주소 = 0;
            return 0;
        }
        int даўжыня_значэнне = Памер - 4;
        if ((стан_значэнне & 1) != 0) {
            for (int індэкс = 0; індэкс < даўжыня_значэнне; індэкс++) дадзеныя[індэкс] = прылада_значэнне.기억읽기(머리 + 4 + індэкс);
            수신수++;
        } else { даўжыня_значэнне = 0; 오류수++; }
        수신위치 = (수신위치 + Памер + 4 + 3) & ~3;
        수신위치 &= 8191;
        прылада_значэнне.입출력짧은수쓰기(입출력기준주소 + 0x38, (수신위치 - 16) & 65535);
        прылада_значэнне.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return даўжыня_значэнне;
    }
}
