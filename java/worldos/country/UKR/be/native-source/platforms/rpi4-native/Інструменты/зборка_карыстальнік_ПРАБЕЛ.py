"""독립된 자체 ABI ELF64와 로더 адхіліць_значэнне 시험 자료를 만든다."""
import struct
import tempfile
from pathlib import Path
from 파이썬빌드 import 파이썬만들기
from 자바라이브러리빌드 import 자바라이브러리만들기
from 시언어번역기빌드 import 시언어번역기만들기


def стварыць_карыстальнік_ПРАБЕЛ(기준경로, рэпазіторый_шлях, 시언어번역기, 시플플번역기, 연결편집기, Архіў_інструмент, канфігурацыя_Служба_інтэлектуальнай_фонавай_перадачы_файлаў, выканаць_каманда):
    канфігурацыя_Служба_інтэлектуальнай_фонавай_перадачы_файлаў = [Налады_значэнне for Налады_значэнне in канфігурацыя_Служба_інтэлектуальнай_фонавай_перадачы_файлаў if Налады_значэнне != '-mgeneral-regs-only']
    зборка_шлях = 기준경로 / 'build'
    출력결과 = зборка_шлях / 'user'
    출력결과.mkdir(exist_ok=True)
    원본자료 = 기준경로 / 'карыстальнік'
    포직스경로 = рэпазіторый_шлях / 'posix-kor/arm64-native'
    포함경로 = ['-I', 원본자료, '-I', 포직스경로 / '포함', '-I', 출력결과]
    for 번역기, 추가영역, ШЛЯХ, Назва in [
            (시언어번역기, [], 원본자료 / 'Выканаць.S', 'start.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'выканаць_каманда.c', 'runtime.o'),
            (시언어번역기, ['-std=c11'], 포직스경로 / 'карыстальнік_мост.c', 'posix.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '파일예제.cpp', 'demo.o'),
            (시플플번역기, ['-std=c++11', '-fno-exceptions', '-fno-rtti'], 원본자료 / '통신예제.cpp', 'network.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / '보호시험.c', 'fault.o'),
            (시언어번역기, ['-std=c11'], 원본자료 / 'Рэдактар.c', 'vi.o')]:
        выканаць_каманда([번역기] + канфігурацыя_Служба_інтэлектуальнай_фонавай_перадачы_файлаў + 추가영역 + 포함경로 + ['-Wall', '-Wextra', '-Werror', '-c', ШЛЯХ, '-o', 출력결과 / Назва])
    выканаць_каманда([Архіў_інструмент, 'rcs', зборка_шлях / 'libposix-kor-user.a', 출력결과 / 'posix.o'])
    for Назва in ('demo', 'fault', 'network', 'vi'):
        выканаць_каманда([연결편집기, '-T', 원본자료 / 'сувязь_Макет.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / (Назва + '.elf'),
             출력결과 / 'start.o', 출력결과 / 'runtime.o', 출력결과 / (Назва + '.o'), зборка_шлях / 'libposix-kor-user.a'])
    자바라이브러리만들기(기준경로, выканаць_каманда)
    # 기존 자체 Java 컴파일러/JVM을 별도의 EL0 ELF로 재사용한다.
    with tempfile.TemporaryDirectory(prefix='java-tools-', dir=str(зборка_шлях)) as 작업경로:
        клас_шлях = Path(작업경로)
        выканаць_каманда(['javac', '--release', '8', '-encoding', 'UTF-8', '-proc:none',
             '-classpath', клас_шлях, '-sourcepath', клас_шлях, '-d', клас_шлях] +
            [자료위치 for 자료위치 in sorted((рэпазіторый_шлях / 'os/карыстальнік/자바').glob('*.java')) if 자료위치.name != '자바가상기계.java'] + sorted((원본자료 / '자바').glob('*.java')))
        выканаць_каманда(['sh', рэпазіторый_шлях / 'compiler/미리번역.sh', '--entry', 'інструмент_увядзенне.Выканаць',
             '--profile', 'user', '--heap-words', '1048576', '-o', 출력결과 / 'java-tools.c'] + sorted(клас_шлях.glob('*.class')))
    압축해제경로 = 기준경로 / 'vendor/uzlib'
    for ШЛЯХ, Назва in [(출력결과 / 'java-tools.c', 'java-tools.o'), (원본자료 / '자바연결.c', 'java-link.o'),
                       (원본자료 / 'пакет.c', 'jar.o')] + [(압축해제경로 / (Назва + '.c'), Назва + '.o') for Назва in ('tinflate', 'crc32', 'adler32')]:
        выканаць_каманда([시언어번역기] + канфігурацыя_Служба_інтэлектуальнай_фонавай_перадачы_файлаў + ['-std=c11', '-DUZLIB_CONF_PARANOID_CHECKS=1', '-I', 압축해제경로] + 포함경로 + ['-c', ШЛЯХ, '-o', 출력결과 / Назва])
    выканаць_каманда([연결편집기, '-T', 원본자료 / 'сувязь_Макет.ld', '-z', 'max-page-size=4096', '-o', 출력결과 / 'java-tools.elf'] +
        [출력결과 / Назва for Назва in ('start.o', 'runtime.o', 'java-tools.o', 'java-link.o', 'jar.o', 'tinflate.o', 'crc32.o', 'adler32.o')])
    파이썬만들기(기준경로, 시언어번역기, 연결편집기)
    시언어번역기만들기(기준경로, рэпазіторый_шлях, 시언어번역기, 연결편집기, канфігурацыя_Служба_інтэлектуальнай_фонавай_перадачы_файлаў, выканаць_каманда)
    유효함 = (출력결과 / 'demo.elf').read_bytes()
    праграма_Загаловак_Зрух = struct.unpack_from('<Q', 유효함, 32)[0]
    Загаловак_Спіс = [праграма_Загаловак_Зрух + 개수 * 56 for 개수 in range(struct.unpack_from('<H', 유효함, 56)[0])]
    적재구획 = [자료위치 for 자료위치 in Загаловак_Спіс if struct.unpack_from('<I', 유효함, 자료위치)[0] == 1]
    Тэкст, дадзеныя = 적재구획[:2]
    каманда_адрас = struct.unpack_from('<Q', 유효함, Тэкст + 16)[0]
    дадзеныя_адрас = struct.unpack_from('<Q', 유효함, дадзеныя + 16)[0]
    호출규약 = 유효함.index(b'JKOROS\0')
    시험사례 = [('empty', b''), ('short', 유효함[:63])]
    수정사항 = [('magic', 0, 'B', 0), ('elf32', 4, 'B', 1), ('endian', 5, 'B', 2),
               ('machine', 18, 'H', 62), ('shared', 16, 'H', 3),
               ('phoff-overflow', 32, 'Q', 2**64 - 8), ('phnum', 56, 'H', 17), ('phsize', 54, 'H', 57),
               ('unaligned-entry', 24, 'Q', каманда_адрас + 1), ('data-entry', 24, 'Q', дадзеныя_адрас),
               ('outside-file', Тэкст + 32, 'Q', len(유효함) + 1), ('short-memory', Тэкст + 40, 'Q', 1),
               ('kernel-address', Тэкст + 16, 'Q', 0x80000), ('memory-overflow', Тэкст + 40, 'Q', 2**64 - 1),
               ('writable-code', Тэкст + 4, 'I', 7), ('missing-abi', 호출규약, 'B', ord('X')),
               ('wrong-abi', 호출규약 + 8, 'I', 2), ('dynamic', Тэкст, 'I', 2),
               ('unaligned-load', Тэкст + 16, 'Q', каманда_адрас + 8),
               ('overlap', дадзеныя + 16, 'Q', каманда_адрас)]
    for Назва, Зрух_значэнне, фармат_932e03c8, значэнне in 수정사항:
        바뀐자료 = bytearray(유효함); struct.pack_into('<' + фармат_932e03c8, 바뀐자료, Зрух_значэнне, значэнне)
        시험사례.append((Назва, bytes(바뀐자료)))
    탑재덩이들 = [(Назва.replace('-', '_'), 출력결과 / (Назва + '.elf')) for Назва in ('demo', 'fault', 'network', 'java-tools', 'python', 'vi', 'cc')]
    for 색인, (Назва, карыснае_змесціва_дадзеныя) in enumerate(시험사례):
        ШЛЯХ = 출력결과 / ('invalid-{}.elf'.format(Назва)); ШЛЯХ.write_bytes(карыснае_змесціва_дадзеныя)
        탑재덩이들.append(('invalid_{}'.format(색인), ШЛЯХ))
    어셈블리자료, Загаловак_значэнне = ['.section .rodata.user,"a"'], []
    크기목록 = {}
    for Назва, ШЛЯХ in 탑재덩이들:
        сімвал_значэнне = 'user_blob_' + Назва
        크기목록[Назва] = ШЛЯХ.stat().st_size
        # 생성한 аднарангавы_значэнне 경로만 넣어 프로젝트 경로의 공백/따옴표 영향을 피한다.
        어셈블리자료 += ['.balign 16', '.global ' + сімвал_значэнне, сімвал_значэнне + ':', '.incbin "{}"'.format(ШЛЯХ.relative_to(기준경로))]
        Загаловак_значэнне.append('extern const unsigned char {}[];'.format(сімвал_значэнне))
    어셈블리자료.append('.section .note.GNU-stack,"",%progbits')
    Загаловак_значэнне += ['static const праграма 실행항목들[] = {', '{user_blob_demo, %d, 0},' % 크기목록['demo']]
    Загаловак_значэнне += ['{user_blob_fault, %d, %d},' % (크기목록['fault'], 전달값) for 전달값 in range(8)]
    Загаловак_значэнне += ['{user_blob_network, %d, 0},' % 크기목록['network']]
    Загаловак_значэнне += ['{user_blob_java_tools, %d, %d},' % (크기목록['java_tools'], спосаб_рэжым) for спосаб_рэжым in (0, 1)]
    Загаловак_значэнне += ['{user_blob_python, %d, 0},' % 크기목록['python'], '{user_blob_vi, %d, 0},' % 크기목록['vi']]
    Загаловак_значэнне += ['{user_blob_java_tools, %d, 2},' % 크기목록['java_tools']]
    Загаловак_значэнне += ['{user_blob_cc, %d, 0},' % 크기목록['cc']]
    Загаловак_значэнне += ['{user_blob_cc, %d, 1},' % 크기목록['cc']]
    Загаловак_значэнне += ['};', 'static const праграма 잘못된실행항목들[] = {']
    Загаловак_значэнне += ['{user_blob_invalid_%d, %d, 0},' % (순번, len(карыснае_змесціва_дадзеныя)) for 순번, (_, карыснае_змесціва_дадзеныя) in enumerate(시험사례)]
    Загаловак_значэнне += ['};']
    (зборка_шлях / 'programs.S').write_text('\n'.join(어셈블리자료) + '\n')
    (зборка_шлях / 'programs.h').write_text('\n'.join(Загаловак_значэнне) + '\n')
    (출력결과 / 'invalid-cases.txt').write_text('\n'.join(Назва for Назва, _ in 시험사례) + '\n')
    выканаць_каманда([시언어번역기] + канфігурацыя_Служба_інтэлектуальнай_фонавай_перадачы_файлаў + ['-c', зборка_шлях / 'programs.S', '-o', зборка_шлях / 'programs.o'])
