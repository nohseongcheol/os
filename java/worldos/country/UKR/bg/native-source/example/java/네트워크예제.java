import Български.자체.검사;
import Български.자체.входен_поток;
import Български.자체.В_И_изключение;

public class 네트워크예제 {
    public static void Стартиране() throws В_И_изключение {
        // хост: python3 Инструменти/예제되돌림.py --tcp-port 9000 --udp-port 9001
        връзка Свързване = връзка.Отваряне("10.0.2.2", 문자.анализирам_цяло_число(실행인수.Текст(0)));
        try {
            Свързване.време_на_изчакване(700);
            byte[] имейл = 문자.кодирам("JAVA TCP bg\n");
            Свързване.Изход().Писане(имейл);
            входен_поток 입력 = Свързване.입력();
            for (int 수 = 0; 수 < 문자.바이트수(имейл); 수++) {
                검사.참인지(입력.Четене() == (имейл[수] & 255), "TCP отговор 불일치");
            }
        } finally { Свързване.Затворен(); }
        дейтаграма_Канал участник = дейтаграма_Канал.Отваряне(0);
        try {
            участник.време_на_изчакване(700);
            участник.изпращам("10.0.2.2", 문자.анализирам_цяло_число(실행인수.Текст(1)), "JAVA UDP bg");
            검사.참인지(문자.같음(участник.получавам(), "JAVA UDP bg"), "UDP отговор 불일치");
        } finally { участник.Затворен(); }
        Изход.записване_ред("JAVA 네트워크 проверявам: TCP UDP bg");
    }
}
