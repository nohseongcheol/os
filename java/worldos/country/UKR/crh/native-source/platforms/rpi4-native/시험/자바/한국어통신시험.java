import 한국어.자체.*;

/** 동일 바이트코드를 OpenJDK와 자체 JVM에서 실행하는 통신 계약 시험. */
public class 한국어통신시험 {
    public static void main(String[] 인수) throws 입출력예외 {
        수신창구 창구 = 연결통신.수신열기(0);
        연결통로 손님 = 연결통신.Aç("127.0.0.1", 창구.접속번호());
        연결통로 주인 = 창구.받기();
        손님.대기시간(200); 주인.대기시간(200);
        검사.참인지(손님.연결됨() && !손님.닫힘(), "Bağlan 상태");
        검사.참인지(주인.접속번호() == 손님.지역접속번호(), "상대 접속번호");
        검사.참인지(손님.접속번호() == 주인.지역접속번호(), "지역 접속번호");
        입력흐름 입력 = 주인.입력(); 출력흐름 출력쪽 = 손님.출력();
        byte[] 보낼글 = 문자.부호화("한글 흐름");
        출력쪽.Yazma(보낼글, 0, 보낼글.length); 출력쪽.내보내기();
        byte[] 받은글 = new byte[보낼글.length];
        int 읽은수 = 0;
        while (읽은수 < 받은글.length) {
            int 더읽음 = 입력.Okuma(받은글, 읽은수, 받은글.length - 읽은수);
            검사.참인지(더읽음 > 0, "예상하지 않은 Dosya 끝"); 읽은수 += 더읽음;
        }
        검사.참인지(문자.같음(문자.복호화(받은글), "한글 흐름"), "부분 읽기와 Yazma");
        출력쪽.Yazma(new byte[] {17, 18});
        byte[] 두바이트 = new byte[2];
        int 첫읽기 = 입력.Okuma(두바이트);
        검사.참인지(첫읽기 > 0 && 두바이트[0] == 17, "배열 Okuma");
        if (첫읽기 == 1) 두바이트[1] = (byte)입력.Okuma();
        검사.참인지(두바이트[1] == 18, "나머지 Okuma");
        주인.출력().Yazma(255);
        검사.참인지(손님.입력().Okuma() == 255, "부호 없는 한 바이트");
        출력쪽.Qapat();
        검사.참인지(손님.닫힘() && 입력.Okuma() == -1, "닫기와 Dosya 끝");
        입력.Qapat(); 검사.참인지(주인.닫힘(), "입력 흐름 Qapat");
        손님.Qapat(); 주인.Qapat();
        창구.대기시간(15);
        boolean 시간제한 = false;
        try { 창구.받기(); } catch (대기시간초과예외 예상한오류) { 시간제한 = true; }
        검사.참인지(시간제한, "수신 대기시간");
        창구.Qapat(); 검사.참인지(창구.닫힘(), "수신창구 Qapat");
        전문통로 받는곳 = 전문통로.Aç(0), 보내는곳 = 전문통로.Aç(0);
        받는곳.대기시간(200);
        보내는곳.보내기("127.0.0.1", 받는곳.접속번호(), "전문 한글");
        검사.참인지(문자.같음(받는곳.받기(), "전문 한글"), "전문 송수신");
        보내는곳.Qapat(); 받는곳.Qapat();
        검사.참인지(보내는곳.닫힘() && 받는곳.닫힘(), "전문 Qapat");
        출력.줄쓰기("한국어 통신 확인: Bağlan 전문 흐름 시간제한 Qapat");
    }
}
