/** PCI RTL8139 (10ec:8139), 단일 στέλνω_τιμή 버퍼와 8KiB λαμβάνω_τιμή_cef4d8ab βρόχος_τιμή. 인터럽트 대신 폴링한다. */
public final class δίκτυο_πρόγραμμα_οδήγησης {
    static int 입출력기준주소 = 0;
    static int λαμβάνω_θέση = 0, 송신칸 = 0;
    static int[] συσκευή_διεύθυνση = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int Θέση) {
        συσκευή_τιμή.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | Θέση);
        return συσκευή_τιμή.입출력정수읽기(0xcfc);
    }

    static boolean Προετοίμασε() {
        int 장치번호 = -1;
        for (int Ευρετήριο = 0; Ευρετήριο < 32; Ευρετήριο++) {
            if (설정읽기(Ευρετήριο, 0) == 0x813910ec) { 장치번호 = Ευρετήριο; break; }
        }
        if (장치번호 < 0) return false;
        int προεπιλεγμένη_τιμή = 설정읽기(장치번호, 0x10);
        if ((προεπιλεγμένη_τιμή & 1) == 0 || (προεπιλεγμένη_τιμή & 0xfffffffc) < 0x100 || (προεπιλεγμένη_τιμή & 0xfffffffc) > 65535) return false;
        입출력기준주소 = προεπιλεγμένη_τιμή & 0xfffc;
        int Εντολή = 설정읽기(장치번호, 4);
        συσκευή_τιμή.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        συσκευή_τιμή.입출력짧은수쓰기(0xcfc, Εντολή | 5); // I/O 및 bus master Αποδοχή_τιμή, PCI Κατάσταση_τιμή 비트는 건드리지 않음
        συσκευή_τιμή.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!επαναφέρω_τιμή()) { 입출력기준주소 = 0; return false; }
        for (int Ευρετήριο = 0; Ευρετήριο < 6; Ευρετήριο++) συσκευή_διεύθυνση[Ευρετήριο] = συσκευή_τιμή.입출력바이트읽기(입출력기준주소 + Ευρετήριο);
        return true;
    }

    static boolean επαναφέρω_τιμή() {
        συσκευή_τιμή.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int Εκτέλεση_2 = συσκευή_τιμή.밀리초();
        while ((συσκευή_τιμή.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (συσκευή_τιμή.밀리초() - Εκτέλεση_2 > 100) return false;
        λαμβάνω_θέση = 0; 송신칸 = 0;
        συσκευή_τιμή.입출력정수쓰기(입출력기준주소 + 0x30, συσκευή_τιμή.δίκτυο_Μνήμη());
        for (int Ευρετήριο = 0; Ευρετήριο < 4; Ευρετήριο++) συσκευή_τιμή.입출력정수쓰기(입출력기준주소 + 0x20 + Ευρετήριο * 4, συσκευή_τιμή.δίκτυο_Μνήμη() + 12288);
        συσκευή_τιμή.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        συσκευή_τιμή.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        συσκευή_τιμή.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        συσκευή_τιμή.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/εκπομπή_τιμή, wrap 연속 αποθηκεύω_τιμή, 8KiB
        συσκευή_τιμή.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int στέλνω(int[] δεδομένα, int διάρκεια_τιμή) {
        if (입출력기준주소 == 0) return -19;
        if (διάρκεια_τιμή < 14 || διάρκεια_τιμή > 1514) return -90;
        int κατάσταση_θύρα = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int Εκτέλεση_2 = συσκευή_τιμή.밀리초();
        while ((συσκευή_τιμή.입출력정수읽기(κατάσταση_θύρα) & 0x2000) == 0)
            if (συσκευή_τιμή.밀리초() - Εκτέλεση_2 > 100) return -110;
        int Μέγεθος = διάρκεια_τιμή < 60 ? 60 : διάρκεια_τιμή;
        for (int Ευρετήριο = 0; Ευρετήριο < Μέγεθος; Ευρετήριο++)
            συσκευή_τιμή.εγγράφω_Μνήμη(συσκευή_τιμή.δίκτυο_Μνήμη() + 12288 + Ευρετήριο, Ευρετήριο < διάρκεια_τιμή ? δεδομένα[Ευρετήριο] : 0);
        συσκευή_τιμή.입출력정수쓰기(κατάσταση_θύρα, Μέγεθος | 0x00080000);
        Εκτέλεση_2 = συσκευή_τιμή.밀리초();
        while ((συσκευή_τιμή.입출력정수읽기(κατάσταση_θύρα) & 0xe0008000) == 0)
            if (συσκευή_τιμή.밀리초() - Εκτέλεση_2 > 100) return -110;
        if ((συσκευή_τιμή.입출력정수읽기(κατάσταση_θύρα) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return διάρκεια_τιμή;
    }

    static int λαμβάνω(int[] δεδομένα) {
        if (입출력기준주소 == 0) return 0;
        if ((συσκευή_τιμή.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!επαναφέρω_τιμή()) 입출력기준주소 = 0;
            return 0;
        }
        if ((συσκευή_τιμή.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = συσκευή_τιμή.δίκτυο_Μνήμη() + λαμβάνω_θέση;
        int Κατάσταση_τιμή = εκτέλεση_Υπεύθυνος.짧은수(머리), Μέγεθος = εκτέλεση_Υπεύθυνος.짧은수(머리 + 2);
        if (Μέγεθος == 0xfff0) return 0; // DMA 진행 중
        if (Μέγεθος < 4 || Μέγεθος > 1518) {
            오류수++;
            if (!επαναφέρω_τιμή()) 입출력기준주소 = 0;
            return 0;
        }
        int διάρκεια_τιμή = Μέγεθος - 4;
        if ((Κατάσταση_τιμή & 1) != 0) {
            for (int Ευρετήριο = 0; Ευρετήριο < διάρκεια_τιμή; Ευρετήριο++) δεδομένα[Ευρετήριο] = συσκευή_τιμή.기억읽기(머리 + 4 + Ευρετήριο);
            수신수++;
        } else { διάρκεια_τιμή = 0; 오류수++; }
        λαμβάνω_θέση = (λαμβάνω_θέση + Μέγεθος + 4 + 3) & ~3;
        λαμβάνω_θέση &= 8191;
        συσκευή_τιμή.입출력짧은수쓰기(입출력기준주소 + 0x38, (λαμβάνω_θέση - 16) & 65535);
        συσκευή_τιμή.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return διάρκεια_τιμή;
    }
}
