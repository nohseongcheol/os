class системная_ошибка(OSError):
    def __init__(자신, ИНДЕКС, описание="операционная_система 작업에 실패했습니다."):
        super().__init__(ИНДЕКС, описание)
        자신.ИНДЕКС = ИНДЕКС
        자신.описание = описание

def 운영호출(ФУНКЦИЯ_ЗНАЧЕН, *аргументы):
    try:
        return ФУНКЦИЯ_ЗНАЧЕН(*аргументы)
    except OSError as ошибка:
        ИНДЕКС = ошибка.args[0] if ошибка.args else 0
        raise системная_ошибка(ИНДЕКС)

