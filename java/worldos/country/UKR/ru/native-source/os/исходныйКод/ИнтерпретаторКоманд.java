/** 디스크 Запись 없이 동작하는 작은 직렬/PS2 ИнтерпретаторКоманд. */
public final class ИнтерпретаторКоманд {
    static int[] входные_данные_ЗНАЧЕН = new int[128];
    static int длина_ЗНАЧЕН = 0;
    static boolean 앞줄복귀 = false;
    static boolean линия_переполнение = false;

    static boolean команда(String Название) {
        if (длина_ЗНАЧЕН < Название.length()) return false;
        for (int ИНДЕКС = 0; ИНДЕКС < Название.length(); ИНДЕКС++)
            if (входные_данные_ЗНАЧЕН[ИНДЕКС] != Название.charAt(ИНДЕКС)) return false;
        return длина_ЗНАЧЕН == Название.length() || входные_данные_ЗНАЧЕН[Название.length()] == ' ';
    }

    static void показать_справку() {
        SMS_Терминал.Запись("help | info | mem | alloc | free N | echo TEXT | clear | test | halt\n");
        SMS_Терминал.Запись("apps | run NAME [ARGS] | net\n");
        SMS_Терминал.Запись("ls | cat FILE | edit FILE | rm FILE | javac FILE.java | java CLASS [ARGS]\n");
        SMS_Терминал.Запись("sync (연결된 JKSTORE1 Store_ЗНАЧЕН 장치에 файл 보존)\n");
    }

    static void Процесс_ЗНАЧЕН_ввод() {
        if (длина_ЗНАЧЕН == 0) return;
        if (команда("help")) показать_справку();
        else if (команда("sync")) {
            int результат = 파일보존.синхронизировать();
            SMS_Терминал.Запись("Sync: "); SMS_Терминал.수쓰기(результат); SMS_Терминал.문자(10);
        }
        else if (команда("ls")) Память_файловая_система.ввод_Список();
        else if (команда("edit")) Память_файловая_система.команда(входные_данные_ЗНАЧЕН, 4, длина_ЗНАЧЕН, 0);
        else if (команда("cat")) Память_файловая_система.команда(входные_данные_ЗНАЧЕН, 3, длина_ЗНАЧЕН, 1);
        else if (команда("rm")) Память_файловая_система.команда(входные_данные_ЗНАЧЕН, 2, длина_ЗНАЧЕН, 2);
        else if (команда("java") || команда("javac")) {
            int результат = выполнение_менеджер.실행(входные_данные_ЗНАЧЕН, 0, длина_ЗНАЧЕН);
            SMS_Терминал.Запись("Exit: "); SMS_Терминал.수쓰기(результат); SMS_Терминал.문자(10);
        }
        else if (команда("apps")) выполнение_менеджер.ввод_Список();
        else if (команда("net")) сеть_стек.Состояние_ЗНАЧЕН();
        else if (команда("run")) {
            int результат = выполнение_менеджер.실행(входные_данные_ЗНАЧЕН, 3, длина_ЗНАЧЕН);
            SMS_Терминал.Запись("Exit: "); SMS_Терминал.수쓰기(результат); SMS_Терминал.Запись("\n");
        } else if (команда("info")) {
            SMS_Терминал.Запись("JKOROS: Java AOT / x86 32-bit / embedded subset JVM / polling kernel\n");
        } else if (команда("mem")) {
            SMS_Терминал.Запись("위쪽 Память_ЗНАЧЕН АДРЕС_регион(KiB): "); SMS_Терминал.수쓰기(Память_регион.ПРОПИСН_Память_изменить_размер());
            SMS_Терминал.Запись("\n배열 동적 Память_ЗНАЧЕН АДРЕС_регион(байт_ЗНАЧЕН): "); SMS_Терминал.수쓰기(устройство_ЗНАЧЕН.МАССИВ_потребление());
            SMS_Терминал.Запись(" / 262144\n작업 АДРЕС_регион раздел_ЗНАЧЕН_366e0bfa: "); SMS_Терминал.수쓰기(Память_регион.사용개수());
            SMS_Терминал.Запись(" / 8 (각 4096바이트)\n");
        } else if (команда("alloc")) {
            int ИНДЕКС = Память_регион.выделить_Память();
            SMS_Терминал.Запись("раздел_ЗНАЧЕН_366e0bfa ИНДЕКС: "); SMS_Терминал.수쓰기(ИНДЕКС); SMS_Терминал.Запись("\n");
        } else if (команда("free")) {
            if (длина_ЗНАЧЕН == 6 && входные_данные_ЗНАЧЕН[4] == ' ' && входные_данные_ЗНАЧЕН[5] >= '0' && входные_данные_ЗНАЧЕН[5] <= '7') {
                SMS_Терминал.Запись(Память_регион.Возврат_KR(входные_данные_ЗНАЧЕН[5] - '0') ? "반환됨\n" : "할당되지 않은 раздел_ЗНАЧЕН_366e0bfa\n");
            } else SMS_Терминал.Запись("사용법: free 0..7\n");
        } else if (команда("echo")) {
            for (int ИНДЕКС = 5; ИНДЕКС < длина_ЗНАЧЕН; ИНДЕКС++) SMS_Терминал.문자(входные_данные_ЗНАЧЕН[ИНДЕКС]);
            SMS_Терминал.문자(10);
        } else if (команда("clear")) SMS_Терминал.удалить_ввод_c8dbc399();
        else if (команда("test")) Ядро.испытания();
        else if (команда("halt")) {
            SMS_Терминал.Запись("HALTED\n");
            устройство_ЗНАЧЕН.정지();
        } else SMS_Терминал.Запись("알 수 없는 명령입니다. help를 입력하세요.\n");
    }

    static void принять_И_запись(int ЗНАЧЕН) {
        if (ЗНАЧЕН == 10 && 앞줄복귀) { 앞줄복귀 = false; return; }
        앞줄복귀 = ЗНАЧЕН == 13;
        if (ЗНАЧЕН == 10 || ЗНАЧЕН == 13) {
            SMS_Терминал.문자(10);
            if (Память_файловая_система.편집중) Память_файловая_система.Доступно_для_редактирования_линия(входные_данные_ЗНАЧЕН, длина_ЗНАЧЕН, линия_переполнение);
            else Процесс_ЗНАЧЕН_ввод();
            длина_ЗНАЧЕН = 0;
            линия_переполнение = false;
            SMS_Терминал.Запись(Память_файловая_система.편집중 ? "...> " : "jkoros> ");
        } else if (ЗНАЧЕН == 8 || ЗНАЧЕН == 127) {
            if (длина_ЗНАЧЕН > 0) {
                длина_ЗНАЧЕН--;
                SMS_Терминал.직렬바이트(8); SMS_Терминал.직렬바이트(32); SMS_Терминал.직렬바이트(8);
                SMS_Терминал.экран_знак(8);
            }
        } else if (ЗНАЧЕН >= 32 && ЗНАЧЕН < 127 && длина_ЗНАЧЕН < входные_данные_ЗНАЧЕН.length) {
            входные_данные_ЗНАЧЕН[длина_ЗНАЧЕН++] = ЗНАЧЕН;
            SMS_Терминал.문자(ЗНАЧЕН);
        } else if (ЗНАЧЕН >= 32 && ЗНАЧЕН < 127) линия_переполнение = true;
    }

    static void запустить() {
        показать_справку();
        SMS_Терминал.Запись("READY\njkoros> ");
        while (true) {
            int ЗНАЧЕН = SMS_Терминал.직렬읽기();
            if (ЗНАЧЕН < 0) ЗНАЧЕН = клавиатура.Чтение();
            if (ЗНАЧЕН >= 0) принять_И_запись(ЗНАЧЕН);
            else { сеть_стек.проверять(); устройство_ЗНАЧЕН.잠시양보(); }
        }
    }
}
