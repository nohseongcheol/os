/** 최대 Размер/홀수 длина_ЗНАЧЕН 데이터그램으로 фактический_данные RTL8139 получить_ЗНАЧЕН Loop_ЗНАЧЕН 순환을 시험한다. */
public final class сеть_Loop {
    public static int запустить() {
        if (пространство_пользователя.인수개수() != 1) { пространство_пользователя.Запись("Usage: run stress PORT\n"); return 2; }
        String текст = пространство_пользователя.аргументы(0);
        int порт_ЗНАЧЕН = 0;
        for (int ИНДЕКС = 0; ИНДЕКС < текст.length(); ИНДЕКС++) {
            if (текст.charAt(ИНДЕКС) < '0' || текст.charAt(ИНДЕКС) > '9' || порт_ЗНАЧЕН > 6553) return 2;
            порт_ЗНАЧЕН = порт_ЗНАЧЕН * 10 + текст.charAt(ИНДЕКС) - '0';
        }
        if (порт_ЗНАЧЕН < 1 || порт_ЗНАЧЕН > 65535) return 2;
        int маркер_ЗНАЧЕН = пространство_пользователя.открыть_сеть(0);
        if (маркер_ЗНАЧЕН < 0) return 3;
        int[] данные = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int длина_ЗНАЧЕН = 1024 - (회차 & 1);
            for (int ИНДЕКС = 0; ИНДЕКС < длина_ЗНАЧЕН; ИНДЕКС++) данные[ИНДЕКС] = (ИНДЕКС + 회차) & 255;
            if (пространство_пользователя.написать_данные(маркер_ЗНАЧЕН, 0x0a000202, порт_ЗНАЧЕН, данные, длина_ЗНАЧЕН) != длина_ЗНАЧЕН) return 4;
            if (пространство_пользователя.получить_данные(маркер_ЗНАЧЕН, данные, 300) != длина_ЗНАЧЕН) return 5;
            for (int ИНДЕКС = 0; ИНДЕКС < длина_ЗНАЧЕН; ИНДЕКС++) if (данные[ИНДЕКС] != ((ИНДЕКС + 회차) & 255)) return 6;
        }
        пространство_пользователя.Close_сеть(маркер_ЗНАЧЕН);
        пространство_пользователя.Запись("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
