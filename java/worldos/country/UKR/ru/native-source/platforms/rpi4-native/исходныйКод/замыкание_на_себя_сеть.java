/** 첫 네트워크 слой_ЗНАЧЕН: 단일 ядро_ЗНАЧЕН 안의 IPv4/UDP 루프백 передать_ЗНАЧЕН_630ba093.
 * внешний_ЗНАЧЕН IP는 ENETUNREACH. Ethernet/IP 패킷 드라이버를 대신한다고 표시하지 않는다.
 * элемент_p 8개, 끝점당 датаграмма 4개, 전문당 512바이트. 모든 호출은 비차단이다.
 */
public final class замыкание_на_себя_сеть {
    static int[] использовать_ЗНАЧЕН = new int[8];
    static int[] порт_ЗНАЧЕН = new int[8];
    static int[] АДРЕС = new int[8];
    static int[] лицевая_камера_ЗНАЧЕН = new int[8];
    static int[] товар_СЧЁТ = new int[8];
    static int[] ПОЛУЧЕНО_порт = new int[8];
    static int[] длина_ЗНАЧЕН = new int[32];
    static int[] 보낸창구 = new int[32];
    static int[] данные = new int[32 * 512];
    static int[] вперед_ЗНАЧЕН = new int[512];
    static int Далее_участник = 49152;
    static int проверять(int ИНДЕКС) { return ИНДЕКС >= 32 && ИНДЕКС < 40 && использовать_ЗНАЧЕН[ИНДЕКС - 32] != 0 ? ИНДЕКС - 32 : -1; }
    static boolean 겹침(int ИНДЕКС) {
        for (int слот_ввод = 0; слот_ввод < 8; слот_ввод++) if (использовать_ЗНАЧЕН[слот_ввод] != 0 && порт_ЗНАЧЕН[слот_ввод] == ИНДЕКС) return true;
        return false;
    }
    static int 임시창구() {
        for (int 시도 = 0; 시도 < 16; 시도++) {
            int соискатель = Далее_участник++;
            if (Далее_участник > 65535) Далее_участник = 49152;
            if (!겹침(соискатель)) return соискатель;
        }
        return -98;
    }
    public static int Create_ввод(int регион_ЗНАЧЕН, int Вид_ЗНАЧЕН, int сумма_контракта) {
        if (регион_ЗНАЧЕН != 2) return -97;
        if (Вид_ЗНАЧЕН != 2 || (сумма_контракта != 0 && сумма_контракта != 17)) return -93;
        for (int слот_ввод = 0; слот_ввод < 8; слот_ввод++) if (использовать_ЗНАЧЕН[слот_ввод] == 0) {
            использовать_ЗНАЧЕН[слот_ввод] = 1; порт_ЗНАЧЕН[слот_ввод] = 0; АДРЕС[слот_ввод] = 0; лицевая_камера_ЗНАЧЕН[слот_ввод] = 0; товар_СЧЁТ[слот_ввод] = 0; ПОЛУЧЕНО_порт[слот_ввод] = 0;
            return слот_ввод + 32;
        }
        return -24;
    }
    public static int BIND_участник(int ИНДЕКС, int идентификатор_сети, int участник_номер_порта) {
        int слот_ввод = проверять(ИНДЕКС);
        if (слот_ввод < 0) return -9;
        if (идентификатор_сети != 0 && идентификатор_сети != 0x7f000001) return -99;
        if (порт_ЗНАЧЕН[слот_ввод] != 0 || участник_номер_порта < 0 || участник_номер_порта > 65535) return -22;
        if (участник_номер_порта == 0) участник_номер_порта = 임시창구();
        if (участник_номер_порта < 0) return участник_номер_порта;
        if (겹침(участник_номер_порта)) return -98;
        порт_ЗНАЧЕН[слот_ввод] = участник_номер_порта; АДРЕС[слот_ввод] = идентификатор_сети; return 0;
    }
    public static int 자료넣기(int ИНДЕКС, int ЗНАЧЕН) {
        if (ИНДЕКС < 0 || ИНДЕКС >= 512) return -22;
        вперед_ЗНАЧЕН[ИНДЕКС] = ЗНАЧЕН & 255; return 0;
    }
    public static int чтение_данные(int ИНДЕКС) { return ИНДЕКС >= 0 && ИНДЕКС < 512 ? вперед_ЗНАЧЕН[ИНДЕКС] : -22; }
    public static int написать(int ИНДЕКС, int идентификатор_сети, int участник_номер_порта, int Размер) {
        int слот_ввод = проверять(ИНДЕКС);
        if (слот_ввод < 0) return -9;
        if (идентификатор_сети != 0x7f000001) return -101;
        if (участник_номер_порта < 1 || участник_номер_порта > 65535) return -22;
        if (Размер < 0 || Размер > 512) return -90;
        if (порт_ЗНАЧЕН[слот_ввод] == 0) {
            int результат = BIND_участник(ИНДЕКС, 0x7f000001, 0);
            if (результат < 0) return результат;
        }
        int цель_ЗНАЧЕН = -1;
        for (int соискатель = 0; соискатель < 8; соискатель++) if (использовать_ЗНАЧЕН[соискатель] != 0 && порт_ЗНАЧЕН[соискатель] == участник_номер_порта) цель_ЗНАЧЕН = соискатель;
        if (цель_ЗНАЧЕН < 0) return -111;
        if (товар_СЧЁТ[цель_ЗНАЧЕН] == 4) return -11;
        int позиция_ИНДЕКС = цель_ЗНАЧЕН * 4 + (лицевая_камера_ЗНАЧЕН[цель_ЗНАЧЕН] + товар_СЧЁТ[цель_ЗНАЧЕН]) % 4;
        for (int байт_ЗНАЧЕН = 0; байт_ЗНАЧЕН < Размер; байт_ЗНАЧЕН++) данные[позиция_ИНДЕКС * 512 + байт_ЗНАЧЕН] = вперед_ЗНАЧЕН[байт_ЗНАЧЕН];
        длина_ЗНАЧЕН[позиция_ИНДЕКС] = Размер; 보낸창구[позиция_ИНДЕКС] = порт_ЗНАЧЕН[слот_ввод]; товар_СЧЁТ[цель_ЗНАЧЕН]++;
        return Размер;
    }
    public static int получить(int ИНДЕКС, int емкость_ЗНАЧЕН) {
        int слот_ввод = проверять(ИНДЕКС);
        if (слот_ввод < 0) return -9;
        if (емкость_ЗНАЧЕН < 0 || емкость_ЗНАЧЕН > 512) return -22;
        if (товар_СЧЁТ[слот_ввод] == 0) return -11;
        int позиция_ИНДЕКС = слот_ввод * 4 + лицевая_камера_ЗНАЧЕН[слот_ввод];
        int Размер = длина_ЗНАЧЕН[позиция_ИНДЕКС] < емкость_ЗНАЧЕН ? длина_ЗНАЧЕН[позиция_ИНДЕКС] : емкость_ЗНАЧЕН;
        for (int байт_ЗНАЧЕН = 0; байт_ЗНАЧЕН < Размер; байт_ЗНАЧЕН++) вперед_ЗНАЧЕН[байт_ЗНАЧЕН] = данные[позиция_ИНДЕКС * 512 + байт_ЗНАЧЕН];
        ПОЛУЧЕНО_порт[слот_ввод] = 보낸창구[позиция_ИНДЕКС]; лицевая_камера_ЗНАЧЕН[слот_ввод] = (лицевая_камера_ЗНАЧЕН[слот_ввод] + 1) % 4; товар_СЧЁТ[слот_ввод]--;
        return Размер;
    }
    public static int чтение_участник_порт(int ИНДЕКС) { int слот_ввод = проверять(ИНДЕКС); return слот_ввод < 0 ? -9 : порт_ЗНАЧЕН[слот_ввод]; }
    public static int чтение_АДРЕС(int ИНДЕКС) { int слот_ввод = проверять(ИНДЕКС); return слот_ввод < 0 ? -9 : АДРЕС[слот_ввод]; }
    public static int отправитель_участник(int ИНДЕКС) { int слот_ввод = проверять(ИНДЕКС); return слот_ввод < 0 ? -9 : ПОЛУЧЕНО_порт[слот_ввод]; }
    public static int Закрыть(int ИНДЕКС) {
        int слот_ввод = проверять(ИНДЕКС); if (слот_ввод < 0) return -9;
        использовать_ЗНАЧЕН[слот_ввод] = 0; товар_СЧЁТ[слот_ввод] = 0; порт_ЗНАЧЕН[слот_ввод] = 0; return 0;
    }
}
