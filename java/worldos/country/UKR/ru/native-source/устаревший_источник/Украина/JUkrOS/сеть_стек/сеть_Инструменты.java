package Украина.JUkrOS.сеть_стек;

/** Ethernet/ARP/IPv4/ICMP/UDP 계층이 공유하는 байт_ЗНАЧЕН 순서와 контрольная_сумма 도구다. */
public final class сеть_Инструменты {
    private сеть_Инструменты() {
    }

    public static int 큰순서짧은정수(byte[] данные, int позиция) {
        чек_диапазон(данные, позиция, 2);
        return ((данные[позиция] & 0xff) << 8) | (данные[позиция + 1] & 0xff);
    }

    public static long обратный_порядок_байтов_целое_число(byte[] данные, int позиция) {
        чек_диапазон(данные, позиция, 4);
        return ((long) (данные[позиция] & 0xff) << 24)
                | ((long) (данные[позиция + 1] & 0xff) << 16)
                | ((long) (данные[позиция + 2] & 0xff) << 8)
                | (данные[позиция + 3] & 0xffL);
    }

    public static int облако_контрольная_сумма(byte[] данные, int запустить, int длина_ЗНАЧЕН) {
        чек_диапазон(данные, запустить, длина_ЗНАЧЕН);
        long SUM_ЗНАЧЕН = 0;
        int 끝 = запустить + длина_ЗНАЧЕН;
        int позиция = запустить;
        while (позиция + 1 < 끝) {
            SUM_ЗНАЧЕН += 큰순서짧은정수(данные, позиция);
            позиция += 2;
        }
        if (позиция < 끝) {
            SUM_ЗНАЧЕН += (данные[позиция] & 0xff) << 8;
        }
        while ((SUM_ЗНАЧЕН >>> 16) != 0) {
            SUM_ЗНАЧЕН = (SUM_ЗНАЧЕН & 0xffff) + (SUM_ЗНАЧЕН >>> 16);
        }
        return (int) (~SUM_ЗНАЧЕН) & 0xffff;
    }

    public static boolean ИТ_службы_Ethernet_кадр(byte[] данные) {
        return данные != null && данные.length >= 14;
    }

    public static int Ethernet_ПРОПИСН_протокол(byte[] данные) {
        if (!ИТ_службы_Ethernet_кадр(данные)) {
            throw new IllegalArgumentException("이더넷 틀이 너무 짧습니다.");
        }
        return 큰순서짧은정수(данные, 12);
    }

    public static boolean ИТ_службы_вакцина_полиовируса_4_протокол(byte[] данные, int позиция) {
        if (данные == null || позиция < 0 || данные.length - позиция < 20) {
            return false;
        }
        int версия_ЗНАЧЕН_65c6ecdc = (данные[позиция] >>> 4) & 0xf;
        int Заголовок_длина = (данные[позиция] & 0xf) * 4;
        return версия_ЗНАЧЕН_65c6ecdc == 4 && Заголовок_длина >= 20 && данные.length - позиция >= Заголовок_длина;
    }

    private static void чек_диапазон(byte[] данные, int запустить, int длина_ЗНАЧЕН) {
        if (данные == null || запустить < 0 || длина_ЗНАЧЕН < 0 || запустить > данные.length - длина_ЗНАЧЕН) {
            throw new IllegalArgumentException("сеть_стек данные 범위를 벗어났습니다.");
        }
    }
}

