import українська.своє.Вікно;
import українська.своє.Мітка;
import українська.своє.текстове_поле;
import українська.своє.кнопка;
import українська.своє.подія_черга;
import українська.своє.Вивід;
import українська.своє.실행할일;
import українська.своє.동작받이;
import українська.своє.Дія_повідомлення;

/** своє 커널의 Swing Вікно: українська 입력 → кнопка → файл_Readme_eb81d7d9 текст оновлювати. */
public class ПрикладВікна implements 실행할일, 동작받이 {
    private Вікно 인사창;
    private текстове_поле ім_я_поле;
    private Мітка 인사말;
    private int 인사횟수;

    public void відкрито_вікно() {
        인사창 = new Вікно("українська Swing", 460, 300);
        인사창.Додати_елемент(new Мітка("Вітаю", 20, 20, 420, 28));
        ім_я_поле = new текстове_поле("українська", 20, 64, 420, 30);
        인사말 = new Мітка("Вітаю", 20, 152, 420, 28);
        인사창.Додати_елемент(ім_я_поле);
        인사창.Додати_елемент(new кнопка("인사하기", 20, 108, 180, 32, this));
        인사창.Додати_елемент(인사말);
        인사창.Додати_елемент(new Мітка("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.показувати_вікно();
        Вивід.записування_рядок("GUI 예제 Готувати: ПрикладВікна");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.записування_Текст("Вітаю, " + ім_я_поле.글읽기() + "님! (" + 인사횟수 + ")");
        Вивід.записування_рядок("GUI 인사: " + 인사말.글읽기());
    }

    public void Виконати() { відкрито_вікно(); }
    public void отримувати_Дія(Дія_повідомлення повідомлення_12ddd6ca) {
        Вивід.записування_рядок("Дія повідомлення_12ddd6ca: " + повідомлення_12ddd6ca.команда_Текст());
        인사하기();
    }
    public static void запустити() {
        подія_черга.나중에실행(new ПрикладВікна());
    }
}
