import українська.своє.зв_язок;
import українська.своє.실행인수;
import українська.своє.дейтаграма_Канал;
import українська.своє.문자;
import українська.своє.Вивід;
import українська.своє.검사;
import українська.своє.вхідний_потік;
import українська.своє.ввід_вивід_виняток;

public class ПрикладМережі {
    public static void запустити() throws ввід_вивід_виняток {
        // хост: python3 інструменти/예제되돌림.py --tcp-port 9000 --udp-port 9001
        зв_язок З_єднання = зв_язок.Відкрити("10.0.2.2", 문자.аналізувати_ціле_число(실행인수.текст(0)));
        try {
            З_єднання.대기시간(700);
            byte[] повідомлення = 문자.кодувати("JAVA TCP українська\n");
            З_єднання.Вивід().Запис(повідомлення);
            вхідний_потік 입력 = З_єднання.입력();
            for (int 수 = 0; 수 < 문자.바이트수(повідомлення); 수++) {
                검사.참인지(입력.Читання() == (повідомлення[수] & 255), "TCP відповідь 불일치");
            }
        } finally { З_єднання.Закрити(); }
        дейтаграма_Канал учасник = дейтаграма_Канал.Відкрити(0);
        try {
            учасник.대기시간(700);
            учасник.надсилати("10.0.2.2", 문자.аналізувати_ціле_число(실행인수.текст(1)), "JAVA UDP українська");
            검사.참인지(문자.같음(учасник.отримувати(), "JAVA UDP українська"), "UDP відповідь 불일치");
        } finally { учасник.Закрити(); }
        Вивід.записування_рядок("JAVA 네트워크 перевіряти: TCP UDP українська");
    }
}
