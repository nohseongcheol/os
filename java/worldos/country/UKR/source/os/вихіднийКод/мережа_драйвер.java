/** PCI RTL8139 (10ec:8139), 단일 надсилати_значення 버퍼와 8KiB отримувати_значення_cef4d8ab цикл_значення_201e2521. 인터럽트 대신 폴링한다. */
public final class мережа_драйвер {
    static int 입출력기준주소 = 0;
    static int отримувати_посада = 0, 송신칸 = 0;
    static int[] пристрій_адреса = new int[6];
    static int 송신수 = 0, 수신수 = 0, 오류수 = 0;

    static int 설정읽기(int 장치번호, int позиція) {
        пристрій_значення.입출력정수쓰기(0xcf8, 0x80000000 | (장치번호 << 11) | позиція);
        return пристрій_значення.입출력정수읽기(0xcfc);
    }

    static boolean Готувати() {
        int 장치번호 = -1;
        for (int індекс = 0; індекс < 32; індекс++) {
            if (설정읽기(індекс, 0) == 0x813910ec) { 장치번호 = індекс; break; }
        }
        if (장치번호 < 0) return false;
        int стандартне_значення = 설정읽기(장치번호, 0x10);
        if ((стандартне_значення & 1) == 0 || (стандартне_значення & 0xfffffffc) < 0x100 || (стандартне_значення & 0xfffffffc) > 65535) return false;
        입출력기준주소 = стандартне_значення & 0xfffc;
        int команда = 설정읽기(장치번호, 4);
        пристрій_значення.입출력정수쓰기(0xcf8, 0x80000004 | (장치번호 << 11));
        пристрій_значення.입출력짧은수쓰기(0xcfc, команда | 5); // I/O 및 bus master Дозволити_значення, PCI Стан_значення 비트는 건드리지 않음
        пристрій_значення.입출력바이트쓰기(입출력기준주소 + 0x52, 0);
        if (!скидати_значення()) { 입출력기준주소 = 0; return false; }
        for (int індекс = 0; індекс < 6; індекс++) пристрій_адреса[індекс] = пристрій_значення.입출력바이트읽기(입출력기준주소 + індекс);
        return true;
    }

    static boolean скидати_значення() {
        пристрій_значення.입출력바이트쓰기(입출력기준주소 + 0x37, 0x10);
        int запустити = пристрій_значення.밀리초();
        while ((пристрій_значення.입출력바이트읽기(입출력기준주소 + 0x37) & 0x10) != 0)
            if (пристрій_значення.밀리초() - запустити > 100) return false;
        отримувати_посада = 0; 송신칸 = 0;
        пристрій_значення.입출력정수쓰기(입출력기준주소 + 0x30, пристрій_значення.мережа_Пам_ять());
        for (int індекс = 0; індекс < 4; індекс++) пристрій_значення.입출력정수쓰기(입출력기준주소 + 0x20 + індекс * 4, пристрій_значення.мережа_Пам_ять() + 12288);
        пристрій_значення.입출력짧은수쓰기(입출력기준주소 + 0x3c, 0);
        пристрій_значення.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0xffff);
        пристрій_значення.입출력바이트쓰기(입출력기준주소 + 0x37, 0x0c);
        пристрій_значення.입출력정수쓰기(입출력기준주소 + 0x44, 0x0000e78a); // 자기주소/передавати_значення_3df56558, wrap 연속 сховище_значення, 8KiB
        пристрій_значення.입출력정수쓰기(입출력기준주소 + 0x40, 0x03000600);
        return true;
    }

    static int надсилати(int[] дані, int 길이) {
        if (입출력기준주소 == 0) return -19;
        if (길이 < 14 || 길이 > 1514) return -90;
        int стан_порт = 입출력기준주소 + 0x10 + 송신칸 * 4;
        int запустити = пристрій_значення.밀리초();
        while ((пристрій_значення.입출력정수읽기(стан_порт) & 0x2000) == 0)
            if (пристрій_значення.밀리초() - запустити > 100) return -110;
        int Розмір = 길이 < 60 ? 60 : 길이;
        for (int індекс = 0; індекс < Розмір; індекс++)
            пристрій_значення.записування_Пам_ять(пристрій_значення.мережа_Пам_ять() + 12288 + індекс, індекс < 길이 ? дані[індекс] : 0);
        пристрій_значення.입출력정수쓰기(стан_порт, Розмір | 0x00080000);
        запустити = пристрій_значення.밀리초();
        while ((пристрій_значення.입출력정수읽기(стан_порт) & 0xe0008000) == 0)
            if (пристрій_значення.밀리초() - запустити > 100) return -110;
        if ((пристрій_значення.입출력정수읽기(стан_порт) & 0x8000) == 0) { 오류수++; return -5; }
        송신칸 = (송신칸 + 1) & 3;
        송신수++;
        return 길이;
    }

    static int отримувати(int[] дані) {
        if (입출력기준주소 == 0) return 0;
        if ((пристрій_значення.입출력바이트읽기(입출력기준주소 + 0x3e) & 0x50) != 0) {
            오류수++;
            if (!скидати_значення()) 입출력기준주소 = 0;
            return 0;
        }
        if ((пристрій_значення.입출력바이트읽기(입출력기준주소 + 0x37) & 1) != 0) return 0;
        int 머리 = пристрій_значення.мережа_Пам_ять() + отримувати_посада;
        int Стан_значення = 실행관리.짧은수(머리), Розмір = 실행관리.짧은수(머리 + 2);
        if (Розмір == 0xfff0) return 0; // DMA 진행 중
        if (Розмір < 4 || Розмір > 1518) {
            오류수++;
            if (!скидати_значення()) 입출력기준주소 = 0;
            return 0;
        }
        int 길이 = Розмір - 4;
        if ((Стан_значення & 1) != 0) {
            for (int індекс = 0; індекс < 길이; індекс++) дані[індекс] = пристрій_значення.기억읽기(머리 + 4 + індекс);
            수신수++;
        } else { 길이 = 0; 오류수++; }
        отримувати_посада = (отримувати_посада + Розмір + 4 + 3) & ~3;
        отримувати_посада &= 8191;
        пристрій_значення.입출력짧은수쓰기(입출력기준주소 + 0x38, (отримувати_посада - 16) & 65535);
        пристрій_значення.입출력짧은수쓰기(입출력기준주소 + 0x3e, 0x000f);
        return 길이;
    }
}
