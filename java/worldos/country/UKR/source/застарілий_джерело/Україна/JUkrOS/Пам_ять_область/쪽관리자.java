package Україна.JUkrOS.Пам_ять_область;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB сторінка_значення 연결과 Запис 시 복사를 제공한다. */
public final class 쪽관리자 {
    public static final int розмір_сторінки = 4096;

    private static final class сторінка_значення {
        private byte[] дані = new byte[розмір_сторінки];
        private int 참조수 = 1;
        private boolean 쓰기가능 = true;
        private boolean 쓰기시복사;
    }

    public static final class адреса_ПРОБІЛ {
        private final Map<Integer, сторінка_значення> сторінка_таблиця = new HashMap<Integer, сторінка_значення>();
    }

    public адреса_ПРОБІЛ 새주소공간() {
        return new адреса_ПРОБІЛ();
    }

    public void карта_сторінка(адреса_ПРОБІЛ адреса_область, int віртуальна_адреса, boolean 쓰기가능) {
        int індекс = 쪽번호(віртуальна_адреса);
        сторінка_значення 새쪽 = new сторінка_значення();
        새쪽.쓰기가능 = 쓰기가능;
        адреса_область.сторінка_таблиця.put(Integer.valueOf(індекс), 새쪽);
    }

    public адреса_ПРОБІЛ 쓰기시복사복제(адреса_ПРОБІЛ 원본) {
        адреса_ПРОБІЛ 복제본 = new адреса_ПРОБІЛ();
        for (Map.Entry<Integer, сторінка_значення> запис_значення_962f286b : 원본.сторінка_таблиця.entrySet()) {
            сторінка_значення 공유쪽 = запис_значення_962f286b.getValue();
            공유쪽.참조수++;
            if (공유쪽.쓰기가능) {
                공유쪽.쓰기가능 = false;
                공유쪽.쓰기시복사 = true;
            }
            복제본.сторінка_таблиця.put(запис_значення_962f286b.getKey(), 공유쪽);
        }
        return 복제본;
    }

    public byte 바이트읽기(адреса_ПРОБІЛ адреса_область, int віртуальна_адреса) {
        сторінка_значення мета = Знайти_сторінка(адреса_область, віртуальна_адреса);
        return мета.дані[Math.floorMod(віртуальна_адреса, розмір_сторінки)];
    }

    public void записування_байт_значення(адреса_ПРОБІЛ адреса_область, int віртуальна_адреса, byte значення) {
        int індекс = 쪽번호(віртуальна_адреса);
        сторінка_значення мета = Знайти_сторінка(адреса_область, віртуальна_адреса);
        if (!мета.쓰기가능) {
            if (!мета.쓰기시복사) {
                throw new IllegalStateException("Читання 전용 쪽입니다.");
            }
            мета = Створення_Приховано_сторінка(адреса_область, індекс, мета);
        }
        мета.дані[Math.floorMod(віртуальна_адреса, розмір_сторінки)] = значення;
    }

    public void Приховано_діапазон_записування(адреса_ПРОБІЛ адреса_область, int ПУСК_адреса, int Розмір) {
        if (Розмір < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int завершити_виклик_адреса = Math.addExact(ПУСК_адреса, Розмір);
        for (int Адреса = ПУСК_адреса; Адреса < завершити_виклик_адреса; Адреса = (쪽번호(Адреса) + 1) * розмір_сторінки) {
            int індекс = 쪽번호(Адреса);
            сторінка_значення мета = Знайти_сторінка(адреса_область, Адреса);
            if (мета.쓰기시복사) {
                Створення_Приховано_сторінка(адреса_область, індекс, мета);
            } else {
                мета.쓰기가능 = true;
            }
        }
    }

    public void діапазон_записування(адреса_ПРОБІЛ адреса_область, int ПУСК_адреса, byte[] дані) {
        for (int індекс = 0; індекс < дані.length; індекс++) {
            записування_байт_значення(адреса_область, ПУСК_адреса + індекс, дані[індекс]);
        }
    }

    private сторінка_значення Створення_Приховано_сторінка(адреса_ПРОБІЛ адреса_область, int індекс, сторінка_значення 공유쪽) {
        сторінка_значення Приховано_сторінка = new сторінка_значення();
        Приховано_сторінка.дані = Arrays.copyOf(공유쪽.дані, 공유쪽.дані.length);
        Приховано_сторінка.쓰기가능 = true;
        Приховано_сторінка.쓰기시복사 = false;
        공유쪽.참조수--;
        адреса_область.сторінка_таблиця.put(Integer.valueOf(індекс), Приховано_сторінка);
        return Приховано_сторінка;
    }

    private сторінка_значення Знайти_сторінка(адреса_ПРОБІЛ адреса_область, int Адреса) {
        сторінка_значення мета = адреса_область.сторінка_таблиця.get(Integer.valueOf(쪽번호(Адреса)));
        if (мета == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return мета;
    }

    private int 쪽번호(int Адреса) {
        if (Адреса < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return Адреса / розмір_сторінки;
    }
}

