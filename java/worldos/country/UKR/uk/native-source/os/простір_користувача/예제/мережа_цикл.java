/** 최대 Розмір/홀수 길이 데이터그램으로 фактично_дані RTL8139 отримувати_значення_cef4d8ab цикл_значення_201e2521 순환을 시험한다. */
public final class мережа_цикл {
    public static int запустити() {
        if (простір_користувача.인수개수() != 1) { простір_користувача.Запис("Usage: run stress PORT\n"); return 2; }
        String текст = простір_користувача.аргументи(0);
        int порт_значення = 0;
        for (int індекс = 0; індекс < текст.length(); індекс++) {
            if (текст.charAt(індекс) < '0' || текст.charAt(індекс) > '9' || порт_значення > 6553) return 2;
            порт_значення = порт_значення * 10 + текст.charAt(індекс) - '0';
        }
        if (порт_значення < 1 || порт_значення > 65535) return 2;
        int маркер_значення = простір_користувача.відкрито_мережа(0);
        if (маркер_значення < 0) return 3;
        int[] дані = new int[1024];
        for (int 회차 = 0; 회차 < 24; 회차++) {
            int 길이 = 1024 - (회차 & 1);
            for (int індекс = 0; індекс < 길이; індекс++) дані[індекс] = (індекс + 회차) & 255;
            if (простір_користувача.надсилати_дані(маркер_значення, 0x0a000202, порт_значення, дані, 길이) != 길이) return 4;
            if (простір_користувача.отримувати_дані(маркер_значення, дані, 300) != 길이) return 5;
            for (int індекс = 0; індекс < 길이; індекс++) if (дані[індекс] != ((індекс + 회차) & 255)) return 6;
        }
        простір_користувача.Закрити_мережа(маркер_значення);
        простір_користувача.Запис("UDP STRESS PASS: 24 full/odd datagrams\n");
        return 0;
    }
}
