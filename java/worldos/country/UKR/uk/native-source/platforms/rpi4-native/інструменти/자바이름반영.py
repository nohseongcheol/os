#!/usr/bin/env python3
"""своє Java місцевий_масштаб 이름을 바꾼다. рядок_значення·주석·зовнішній_значення 멤버 이름은 보존한다."""
import json
import re
from pathlib import Path

Дії_корінь = Path(__file__).resolve().parents[1]
зіставлення_значення = json.loads((Дії_корінь / '명명/자바이름.json').read_text())
блок_вираз = re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[\w$]+|[^\w\s]', re.UNICODE)
журнал_запис = []
for Каталог_значення in ('вихіднийКод', 'простір_користувача/자바', '한국어자바'):
    for шлях in sorted((Дії_корінь / Каталог_значення).rglob('*.java')):
        вихіднийКод = шлях.read_text()
        토막들 = list(блок_вираз.finditer(вихіднийКод))
        사용이름 = {блок_запис.group() for блок_запис in 토막들 if re.search('[가-힣]', блок_запис.group())}
        зіставлення_вмісту_файлу = {}
        for 이전, 이후 in зіставлення_значення.items():
            # A pre-existing Korean binding must never be shadowed by renaming.
            새이름 = 이후
            while 새이름 in 사용이름: 새이름 = 'місцевий_масштаб' + 새이름
            зіставлення_вмісту_файлу[이전] = 새이름
        수정 = []
        이전토막 = ''
        for блок_запис in 토막들:
            낱말 = блок_запис.group()
            if 낱말.startswith(('//', '/*', '"', "'")): continue
            if 낱말 in зіставлення_вмісту_файлу and 이전토막 != '.':
                수정.append((блок_запис.start(), блок_запис.end(), зіставлення_вмісту_файлу[낱말]))
                журнал_запис.append((str(шлях.relative_to(Дії_корінь)), 낱말, зіставлення_вмісту_файлу[낱말]))
            이전토막 = 낱말
        for запустити, 끝, 새이름 in reversed(수정): вихіднийКод = вихіднийКод[:запустити] + 새이름 + вихіднийКод[끝:]
        if 수정: шлях.write_text(вихіднийКод)
(Дії_корінь / '명명/자바이름대응.tsv').write_text('файл\t이전\t이후\n' + ''.join('\t'.join(запис_значення_962f286b)+'\n' for запис_значення_962f286b in sorted(set(журнал_запис))))
print('Java Назва довідка змінювати_значення:', len(журнал_запис))
