import 한국어.자체.ᏦᎳᏂ;
import 한국어.자체.ᏗᎦᏯᎸᏗ;
import 한국어.자체.ᎠᎪᎵᏰᏗ_ᏠᎨᏏ;
import 한국어.자체.ᎠᏐᏅᏍᏙᏗ;
import 한국어.자체.ᎢᏳᎵᏍᏔᏂᏓᏍᏗᎢ_ᎠᏍᏓᏅᏅ;
import 한국어.자체.출력;
import 한국어.자체.실행할일;
import 한국어.자체.동작받이;
import 한국어.자체.동작알림;

/** 자체 커널의 Swing ᏦᎳᏂ: chr 입력 → ᎠᏐᏅᏍᏙᏗ → ᏍᎩᎪᎵᏯ_eb81d7d9 ᎠᎪᎵᏰᏗ ᎯᏤᎲᏍᏓ. */
public class 창예제 implements 실행할일, 동작받이 {
    private ᏦᎳᏂ 인사창;
    private ᎠᎪᎵᏰᏗ_ᏠᎨᏏ ᏚᏙᎥᎢ_ᏠᎨᏏ;
    private ᏗᎦᏯᎸᏗ 인사말;
    private int 인사횟수;

    public void ᎯᏍᏚᎢ_ᏦᎳᏂ() {
        인사창 = new ᏦᎳᏂ("chr Swing", 460, 300);
        인사창.ᎧᏁᏉᏍᏗ_ᏑᏓᎴᎩ(new ᏗᎦᏯᎸᏗ("chr", 20, 20, 420, 28));
        ᏚᏙᎥᎢ_ᏠᎨᏏ = new ᎠᎪᎵᏰᏗ_ᏠᎨᏏ("chr", 20, 64, 420, 30);
        인사말 = new ᏗᎦᏯᎸᏗ("chr", 20, 152, 420, 28);
        인사창.ᎧᏁᏉᏍᏗ_ᏑᏓᎴᎩ(ᏚᏙᎥᎢ_ᏠᎨᏏ);
        인사창.ᎧᏁᏉᏍᏗ_ᏑᏓᎴᎩ(new ᎠᏐᏅᏍᏙᏗ("인사하기", 20, 108, 180, 32, this));
        인사창.ᎧᏁᏉᏍᏗ_ᏑᏓᎴᎩ(인사말);
        인사창.ᎧᏁᏉᏍᏗ_ᏑᏓᎴᎩ(new ᏗᎦᏯᎸᏗ("F9 / Shift+Space | X", 20, 204, 420, 28));
        인사창.ᏍᎩᎪᏩᏛᏓ_ᏦᎳᏂ();
        출력.ᎪᏪᎶᏗ_ᏚᏓᏅᏅᎢ("GUI 예제 ᎭᏛᏅᎢᏍᏓ: 창예제");
    }

    public void 인사하기() {
        인사횟수++;
        인사말.ᎪᏪᎶᏗ_ᎠᎪᎵᏰᏗ("chr, " + ᏚᏙᎥᎢ_ᏠᎨᏏ.글읽기() + "님! (" + 인사횟수 + ")");
        출력.ᎪᏪᎶᏗ_ᏚᏓᏅᏅᎢ("GUI 인사: " + 인사말.글읽기());
    }

    public void ᎠᎴᏅᏗᏱ_ᏯᏛᏁᏗ() { ᎯᏍᏚᎢ_ᏦᎳᏂ(); }
    public void 동작받기(동작알림 알림) {
        출력.ᎪᏪᎶᏗ_ᏚᏓᏅᏅᎢ("ᎠᏛᏁᎵᏓ 알림: " + 알림.ᎤᏁᏤᎸᎩ_ᎠᎪᎵᏰᏗ());
        인사하기();
    }
    public static void ᎠᎢᏎᏍᏗ() {
        ᎢᏳᎵᏍᏔᏂᏓᏍᏗᎢ_ᎠᏍᏓᏅᏅ.나중에실행(new 창예제());
    }
}
