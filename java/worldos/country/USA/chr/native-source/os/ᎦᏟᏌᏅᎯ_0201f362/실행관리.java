                if (수(이전) == 1 && ᎠᏅᏓᏗᏍᏙ_ᎢᎩᏓ > 0 && 수(이전 + 20) > 0
                    && ᎪᏪᎵ_ᏫᏗᎦᏅᏗ < 수(이전 + 8) + 수(이전 + 20) && 수(이전 + 8) < ᎪᏪᎵ_ᏫᏗᎦᏅᏗ + ᎠᏅᏓᏗᏍᏙ_ᎢᎩᏓ) return -8;
