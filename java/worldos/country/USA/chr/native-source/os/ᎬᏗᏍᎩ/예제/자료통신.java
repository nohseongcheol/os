public final class 자료통신 {
    static int 숫자(String ᎠᎪᎵᏰᏗ) {
        if (ᎠᎪᎵᏰᏗ == null || ᎠᎪᎵᏰᏗ.length() == 0) return -1;
        int 결과 = 0;
        for (int ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ = 0; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ < ᎠᎪᎵᏰᏗ.length(); ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ++) {
            int ᏧᎬᏩᎶᏗᏯ = ᎠᎪᎵᏰᏗ.charAt(ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ) - '0';
            if (ᏧᎬᏩᎶᏗᏯ < 0 || ᏧᎬᏩᎶᏗᏯ > 9 || 결과 > 6553) return -1;
            결과 = 결과 * 10 + ᏧᎬᏩᎶᏗᏯ;
            if (결과 > 65535) return -1;
        }
        return 결과;
    }
    static int ᎪᏪᎵ_ᏫᏗᎦᏅᏗ(String ᎠᎪᎵᏰᏗ) {
        if (ᎠᎪᎵᏰᏗ == null) return 0;
        int ᏧᎬᏩᎶᏗᏯ = 0, 결과 = 0, 부분 = 0, 자릿수 = 0;
        for (int ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ = 0; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ <= ᎠᎪᎵᏰᏗ.length(); ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ++) {
            int 문자 = ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ == ᎠᎪᎵᏰᏗ.length() ? '.' : ᎠᎪᎵᏰᏗ.charAt(ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ);
            if (문자 == '.') {
                if (자릿수 == 0 || 부분 == 4) return 0;
                결과 = (결과 << 8) | ᏧᎬᏩᎶᏗᏯ; 부분++; ᏧᎬᏩᎶᏗᏯ = 0; 자릿수 = 0;
            } else {
                if (문자 < '0' || 문자 > '9') return 0;
                ᏧᎬᏩᎶᏗᏯ = ᏧᎬᏩᎶᏗᏯ * 10 + 문자 - '0';
                if (++자릿수 > 3 || ᏧᎬᏩᎶᏗᏯ > 255) return 0;
            }
        }
        return 부분 == 4 ? 결과 : 0;
    }
    public static int ᎠᎢᏎᏍᏗ() {
        if (ᎬᏗᏍᎩ.인수개수() != 3) { ᎬᏗᏍᎩ.ᎪᏪᎶᏗ("Usage: run udp IP PORT TEXT\n"); return 2; }
        int ᎪᏪᎵ_ᏫᏗᎦᏅᏗ = ᎪᏪᎵ_ᏫᏗᎦᏅᏗ(ᎬᏗᏍᎩ.인수(0)), ᎫᏓᎸᏗ_ᏧᎬᏩᎶᏗᏯ = 숫자(ᎬᏗᏍᎩ.인수(1));
        String ᎦᎸᏛᎢ_ᏧᎬᏩᎶᏗᏯ = ᎬᏗᏍᎩ.인수(2);
        if (ᎪᏪᎵ_ᏫᏗᎦᏅᏗ == 0 || ᎫᏓᎸᏗ_ᏧᎬᏩᎶᏗᏯ < 1 || ᎦᎸᏛᎢ_ᏧᎬᏩᎶᏗᏯ.length() > 1024) { ᎬᏗᏍᎩ.ᎪᏪᎶᏗ("Bad destination\n"); return 2; }
        int ᎫᎭᏢ_ᏧᎬᏩᎶᏗᏯ = ᎬᏗᏍᎩ.ᎯᏍᏚᎢ_ᏧᎾᏚᏓᎵ(0);
        if (ᎫᎭᏢ_ᏧᎬᏩᎶᏗᏯ < 0) { ᎬᏗᏍᎩ.ᎪᏪᎶᏗ("UDP OPEN FAILED (network unavailable)\n"); return 3; }
        int[] ᎦᏟᏌᏅᎯ = new int[1024];
        for (int ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ = 0; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ < ᎦᎸᏛᎢ_ᏧᎬᏩᎶᏗᏯ.length(); ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ++) ᎦᏟᏌᏅᎯ[ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ] = ᎦᎸᏛᎢ_ᏧᎬᏩᎶᏗᏯ.charAt(ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ);
        if (ᎬᏗᏍᎩ.ᏫᎦᏅᏗ_ᎦᏟᏌᏅᎯ(ᎫᎭᏢ_ᏧᎬᏩᎶᏗᏯ, ᎪᏪᎵ_ᏫᏗᎦᏅᏗ, ᎫᏓᎸᏗ_ᏧᎬᏩᎶᏗᏯ, ᎦᏟᏌᏅᎯ, ᎦᎸᏛᎢ_ᏧᎬᏩᎶᏗᏯ.length()) < 0) {
            ᎬᏗᏍᎩ.ᎪᏪᎶᏗ("UDP SEND FAILED\n"); ᎬᏗᏍᎩ.ᎯᏍᏚᎲᎦ_ᏧᎾᏚᏓᎵ(ᎫᎭᏢ_ᏧᎬᏩᎶᏗᏯ); return 4;
        }
        ᎬᏗᏍᎩ.ᎪᏪᎶᏗ("UDP SENT\n");
        int 받은길이 = ᎬᏗᏍᎩ.자료받기(ᎫᎭᏢ_ᏧᎬᏩᎶᏗᏯ, ᎦᏟᏌᏅᎯ, 1500);
        boolean 같음 = 받은길이 == ᎦᎸᏛᎢ_ᏧᎬᏩᎶᏗᏯ.length() && ᎬᏗᏍᎩ.보낸주소(ᎫᎭᏢ_ᏧᎬᏩᎶᏗᏯ) == ᎪᏪᎵ_ᏫᏗᎦᏅᏗ && ᎬᏗᏍᎩ.보낸창구(ᎫᎭᏢ_ᏧᎬᏩᎶᏗᏯ) == ᎫᏓᎸᏗ_ᏧᎬᏩᎶᏗᏯ;
        if (같음) for (int ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ = 0; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ < 받은길이; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ++) if (ᎦᏟᏌᏅᎯ[ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ] != ᎦᎸᏛᎢ_ᏧᎬᏩᎶᏗᏯ.charAt(ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ)) 같음 = false;
        ᎬᏗᏍᎩ.ᎯᏍᏚᎲᎦ_ᏧᎾᏚᏓᎵ(ᎫᎭᏢ_ᏧᎬᏩᎶᏗᏯ);
        if (받은길이 < 0) { ᎬᏗᏍᎩ.ᎪᏪᎶᏗ("UDP RECEIVE TIMEOUT/ERROR\n"); return 5; }
        ᎬᏗᏍᎩ.ᎪᏪᎶᏗ(같음 ? "UDP ECHO PASS\n" : "UDP REPLY MISMATCH\n");
        return 같음 ? 0 : 6;
    }
}
