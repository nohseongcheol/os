/** 게스트 도구 공통 출력 및 ASCII ᎠᏍᏆᏂᎪᏙᏗ ᏚᏙᎥᎢ ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ_Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ. */
public final class 자바도구 {
    /** UTF-8 byte_ᏧᎬᏩᎶᏗᏯ 배열을 같은 배열의 UTF-16 단위로 바꾼다. 잘못된 입력은 거부. */
    static int 원문해독(int[] ᎦᏟᏌᏅᎯ, int ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) {
        int 읽기 = 0, ᎪᏪᎶᏗ = 0;
        if (ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ >= 3 && ᎦᏟᏌᏅᎯ[0] == 239 && ᎦᏟᏌᏅᎯ[1] == 187 && ᎦᏟᏌᏅᎯ[2] == 191) 읽기 = 3;
        while (읽기 < ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) {
            int ᏧᎬᏩᎶᏗᏯ = ᎦᏟᏌᏅᎯ[읽기++], 수 = 0, 최소 = 0;
            if (ᏧᎬᏩᎶᏗᏯ >= 194 && ᏧᎬᏩᎶᏗᏯ <= 223) { 수 = 1; 최소 = 128; ᏧᎬᏩᎶᏗᏯ &= 31; }
            else if (ᏧᎬᏩᎶᏗᏯ >= 224 && ᏧᎬᏩᎶᏗᏯ <= 239) { 수 = 2; 최소 = 2048; ᏧᎬᏩᎶᏗᏯ &= 15; }
            else if (ᏧᎬᏩᎶᏗᏯ >= 240 && ᏧᎬᏩᎶᏗᏯ <= 244) { 수 = 3; 최소 = 65536; ᏧᎬᏩᎶᏗᏯ &= 7; }
            else if (ᏧᎬᏩᎶᏗᏯ >= 128 || ᏧᎬᏩᎶᏗᏯ < 0) return -1;
            if (수 > ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ - 읽기) return -1;
            for (int i = 0; i < 수; i++) {
                int 다음 = ᎦᏟᏌᏅᎯ[읽기++]; if ((다음 & 192) != 128) return -1;
                ᏧᎬᏩᎶᏗᏯ = (ᏧᎬᏩᎶᏗᏯ << 6) | (다음 & 63);
            }
            if (ᏧᎬᏩᎶᏗᏯ < 최소 || ᏧᎬᏩᎶᏗᏯ > 0x10ffff || (ᏧᎬᏩᎶᏗᏯ >= 0xd800 && ᏧᎬᏩᎶᏗᏯ <= 0xdfff)) return -1;
            if (ᏧᎬᏩᎶᏗᏯ >= 65536) { ᏧᎬᏩᎶᏗᏯ -= 65536; ᎦᏟᏌᏅᎯ[ᎪᏪᎶᏗ++] = 0xd800 | (ᏧᎬᏩᎶᏗᏯ >> 10); ᎦᏟᏌᏅᎯ[ᎪᏪᎶᏗ++] = 0xdc00 | (ᏧᎬᏩᎶᏗᏯ & 1023); }
            else ᎦᏟᏌᏅᎯ[ᎪᏪᎶᏗ++] = ᏧᎬᏩᎶᏗᏯ;
        }
        return ᎪᏪᎶᏗ;
    }
    static void 수쓰기(int ᏧᎬᏩᎶᏗᏯ) {
        if (ᏧᎬᏩᎶᏗᏯ < 0) ᎬᏗᏍᎩ.ᎪᏪᎶᏗ_ᎪᏪᎸ_ᏧᎬᏩᎶᏗᏯ('-'); else ᏧᎬᏩᎶᏗᏯ = -ᏧᎬᏩᎶᏗᏯ;
        int 자리 = 1000000000;
        boolean ᎠᎢᏎᏍᏗ = false;
        while (자리 != 0) {
            int 수 = -(ᏧᎬᏩᎶᏗᏯ / 자리);
            if (수 != 0 || ᎠᎢᏎᏍᏗ || 자리 == 1) { ᎬᏗᏍᎩ.ᎪᏪᎶᏗ_ᎪᏪᎸ_ᏧᎬᏩᎶᏗᏯ('0' + 수); ᎠᎢᏎᏍᏗ = true; }
            ᏧᎬᏩᎶᏗᏯ %= 자리; 자리 /= 10;
        }
    }
    static int ᏚᏙᎥᎢ(int[] ᏮᎦᏛᎢ_ᏧᎬᏩᎶᏗᏯ, String 원본) {
        if (원본.length() >= ᏮᎦᏛᎢ_ᏧᎬᏩᎶᏗᏯ.length) return -1;
        for (int 수 = 0; 수 < ᏮᎦᏛᎢ_ᏧᎬᏩᎶᏗᏯ.length; 수++) ᏮᎦᏛᎢ_ᏧᎬᏩᎶᏗᏯ[수] = 수 < 원본.length() ? 원본.charAt(수) : 0;
        return 원본.length();
    }
    static boolean 같음(String 가, String 나) {
        if (가.length() != 나.length()) return false;
        for (int 수 = 0; 수 < 가.length(); 수++) if (가.charAt(수) != 나.charAt(수)) return false;
        return true;
    }
}
