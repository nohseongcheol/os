/** 화면 ᎯᎦᎳ_ᏧᎬᏩᎶᏗᏯ·띠 합성·ᎠᏎᎯᎯ 밑그림을 관리한다. ᎤᏙᎯᏳ_ᎾᏍᎩ_ᎨᏒ_ᎦᏟᏌᏅᎯ 화면 ᎠᏅᏓᏗᏍᏙ_ᎦᏟᏌᏅᎯ 접근은 보드가 담당한다. */
public final class 화면합성 {
    static int 너비, 높이, 합성중, 왼경계, 위경계, 오른경계, 아래경계;
    static int 포인터가로, 포인터세로, ᎠᏎᎯᎯ_ᎤᏙᏢᏒᎢ;
    static int 기록아래낱말, 기록위낱말;
    static int[] 완성그림 = new int[32 * 1920];
    static int[] ᎠᏎᎯᎯ_ᎠᏍᏆᏚᎸ_ᎦᏯᎸᏗ = new int[21 * 21];
    static int[] 잘린범위 = new int[4];
    public static void ᎭᏛᏅᎢᏍᏓ(int 폭, int ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) {
        너비 = 폭; 높이 = ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ; 합성중 = 0; ᎠᏎᎯᎯ_ᎤᏙᏢᏒᎢ = 0;
        기록아래낱말 = 0; 기록위낱말 = 0;
    }
    public static int 너비얻기() { return 너비; }
    public static int 높이얻기() { return 높이; }
    public static int 기록아래얻기() { return 기록아래낱말; }
    public static int 기록위얻기() { return 기록위낱말; }
    public static int ᎠᎬᎭᎸᏓ_ᏗᏓᏴᎳᏛᏙᏗ_ᏧᎬᏩᎶᏗᏯ(int 순번) { return 잘린범위[순번]; }
    static int 양의길이더하기(int ᎭᏂᎩᏍᏓ_ᏧᎬᏩᎶᏗᏯ, int ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) {
        if (ᎭᏂᎩᏍᏓ_ᏧᎬᏩᎶᏗᏯ > 2147483647 - ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) return 2147483647;
        return ᎭᏂᎩᏍᏓ_ᏧᎬᏩᎶᏗᏯ + ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ;
    }
    public static int ᎠᎬᎭᎸᏓ_ᏗᏓᏴᎳᏛᏙᏗ(int 가로, int 세로, int 폭, int ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) {
        if (너비 == 0 || 폭 <= 0 || ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ <= 0) return 0;
        int 오른쪽 = 양의길이더하기(가로, 폭), 아래쪽 = 양의길이더하기(세로, ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ);
        int 왼쪽 = 합성중 != 0 ? 왼경계 : 0, 위쪽 = 합성중 != 0 ? 위경계 : 0;
        int 최대가로 = 합성중 != 0 ? 오른경계 : 너비, 최대세로 = 합성중 != 0 ? 아래경계 : 높이;
        if (가로 < 왼쪽) 가로 = 왼쪽;
        if (세로 < 위쪽) 세로 = 위쪽;
        if (오른쪽 > 최대가로) 오른쪽 = 최대가로;
        if (아래쪽 > 최대세로) 아래쪽 = 최대세로;
        if (오른쪽 <= 가로 || 아래쪽 <= 세로) return 0;
        잘린범위[0] = 가로; 잘린범위[1] = 세로;
        잘린범위[2] = 오른쪽 - 가로; 잘린범위[3] = 아래쪽 - 세로;
        return 1;
    }
    public static int ᎠᎢᏎᏍᏗ(int 가로, int 세로, int 폭, int ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) {
        if (합성중 != 0 || ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ > 32 || ᎠᎬᎭᎸᏓ_ᏗᏓᏴᎳᏛᏙᏗ(가로, 세로, 폭, ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) == 0) return 0;
        왼경계 = 잘린범위[0]; 위경계 = 잘린범위[1];
        오른경계 = 왼경계 + 잘린범위[2]; 아래경계 = 위경계 + 잘린범위[3];
        합성중 = 1; return 1;
    }
    static boolean ᎠᏎᎯᎯ_bit(int 가로, int 세로, int ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ) {
        if (ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ == 1) return 가로 >= 0 && 가로 <= 세로 / 2 && 세로 < 16;
        if (ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ == 3) 가로 = 20 - 가로;
        int 차이 = 가로 - 세로; if (차이 < 0) 차이 = -차이;
        return (차이 <= 1 && 가로 >= 3 && 가로 <= 17) ||
            (가로 >= 2 && 가로 <= 8 && 세로 >= 2 && 세로 <= 8 && (가로 <= 3 || 세로 <= 3)) ||
            (가로 >= 12 && 가로 <= 18 && 세로 >= 12 && 세로 <= 18 && (가로 >= 17 || 세로 >= 17));
    }
    static int ᎠᏎᎯᎯ_pel(int 가로, int 세로) {
        if (ᎠᏎᎯᎯ_bit(가로, 세로, ᎠᏎᎯᎯ_ᎤᏙᏢᏒᎢ)) return 2;
        for (int ᏚᏓᏅᏅᎢ = -1; ᏚᏓᏅᏅᎢ <= 1; ᏚᏓᏅᏅᎢ++) for (int 칸 = -1; 칸 <= 1; 칸++)
            if (ᎠᏎᎯᎯ_bit(가로 + 칸, 세로 + ᏚᏓᏅᏅᎢ, ᎠᏎᎯᎯ_ᎤᏙᏢᏒᎢ)) return 1;
        return 0;
    }
    static void ᎬᏂᎨᏒ_ᏅᎦ_pel(int 가로, int 세로, int 색) {
        int 칸 = 가로 - 포인터가로, ᏚᏓᏅᏅᎢ = 세로 - 포인터세로;
        if (ᎠᏎᎯᎯ_ᎤᏙᏢᏒᎢ != 0 && 칸 >= 0 && ᏚᏓᏅᏅᎢ >= 0 && 칸 < 21 && ᏚᏓᏅᏅᎢ < 21) {
            ᎠᏎᎯᎯ_ᎠᏍᏆᏚᎸ_ᎦᏯᎸᏗ[ᏚᏓᏅᏅᎢ * 21 + 칸] = 색;
            int ᎤᏓᏓᏟ_ᏧᎬᏩᎶᏗᏯ = ᎠᏎᎯᎯ_pel(칸, ᏚᏓᏅᏅᎢ); if (ᎤᏓᏓᏟ_ᏧᎬᏩᎶᏗᏯ != 0) 색 = ᎤᏓᏓᏟ_ᏧᎬᏩᎶᏗᏯ == 2 ? 0xffffff : 0x101010;
        }
        if (보드.표시화소읽기(가로, 세로) != 색) {
            보드.ᎪᏪᎶᏗ_ᎬᏂᎨᏒ_ᏅᎦ_pel(가로, 세로, 색);
            기록아래낱말++; if (기록아래낱말 == 0) 기록위낱말++;
        }
    }
    public static void ᎯᏍᏆᏓ() {
        if (합성중 == 0) return;
        for (int ᏚᏓᏅᏅᎢ = 위경계; ᏚᏓᏅᏅᎢ < 아래경계; ᏚᏓᏅᏅᎢ++) for (int 칸 = 왼경계; 칸 < 오른경계; 칸++)
            ᎬᏂᎨᏒ_ᏅᎦ_pel(칸, ᏚᏓᏅᏅᎢ, 완성그림[(ᏚᏓᏅᏅᎢ - 위경계) * 1920 + 칸]);
        합성중 = 0;
    }
    public static int pel(int 가로, int 세로, int 색) {
        if (가로 < 0 || 세로 < 0 || 가로 >= 너비 || 세로 >= 높이) return 0;
        if (합성중 != 0) {
            if (가로 >= 왼경계 && 가로 < 오른경계 && 세로 >= 위경계 && 세로 < 아래경계)
                완성그림[(세로 - 위경계) * 1920 + 가로] = 색;
        } else ᎬᏂᎨᏒ_ᏅᎦ_pel(가로, 세로, 색);
        return 0;
    }
    public static void 사각그림(int 가로, int 세로, int 폭, int ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ, int 색) {
        if (ᎠᎬᎭᎸᏓ_ᏗᏓᏴᎳᏛᏙᏗ(가로, 세로, 폭, ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ) == 0) return;
        가로 = 잘린범위[0]; 세로 = 잘린범위[1]; 폭 = 잘린범위[2]; ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ = 잘린범위[3];
        for (int ᏚᏓᏅᏅᎢ = 세로; ᏚᏓᏅᏅᎢ < 세로 + ᏱᎦᏅᎯᏓ_ᏧᎬᏩᎶᏗᏯ; ᏚᏓᏅᏅᎢ++) for (int 칸 = 가로; 칸 < 가로 + 폭; 칸++) {
            if (합성중 != 0) 완성그림[(ᏚᏓᏅᏅᎢ - 위경계) * 1920 + 칸] = 색;
            else ᎬᏂᎨᏒ_ᏅᎦ_pel(칸, ᏚᏓᏅᏅᎢ, 색);
        }
    }
    public static void ᎠᏎᎯᎯ(int 가로, int 세로, int ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ) {
        if (너비 == 0) return;
        int 새가로 = 가로 - (ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ >= 2 ? 10 : 0), 새세로 = 세로 - (ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ >= 2 ? 10 : 0);
        if (ᎠᏎᎯᎯ_ᎤᏙᏢᏒᎢ == ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ && 포인터가로 == 새가로 && 포인터세로 == 새세로) return;
        if (ᎠᏎᎯᎯ_ᎤᏙᏢᏒᎢ != 0) for (int ᏚᏓᏅᏅᎢ = 0; ᏚᏓᏅᏅᎢ < 21; ᏚᏓᏅᏅᎢ++) for (int 칸 = 0; 칸 < 21; 칸++) {
            int 가 = 포인터가로 + 칸, 세 = 포인터세로 + ᏚᏓᏅᏅᎢ;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) 보드.ᎪᏪᎶᏗ_ᎬᏂᎨᏒ_ᏅᎦ_pel(가, 세, ᎠᏎᎯᎯ_ᎠᏍᏆᏚᎸ_ᎦᏯᎸᏗ[ᏚᏓᏅᏅᎢ * 21 + 칸]);
        }
        ᎠᏎᎯᎯ_ᎤᏙᏢᏒᎢ = ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ; 포인터가로 = 새가로; 포인터세로 = 새세로;
        if (ᎤᏙᏢᏒᎢ_ᏧᎬᏩᎶᏗᏯ != 0) for (int ᏚᏓᏅᏅᎢ = 0; ᏚᏓᏅᏅᎢ < 21; ᏚᏓᏅᏅᎢ++) for (int 칸 = 0; 칸 < 21; 칸++) {
            int 가 = 포인터가로 + 칸, 세 = 포인터세로 + ᏚᏓᏅᏅᎢ;
            if (가 >= 0 && 세 >= 0 && 가 < 너비 && 세 < 높이) {
                ᎠᏎᎯᎯ_ᎠᏍᏆᏚᎸ_ᎦᏯᎸᏗ[ᏚᏓᏅᏅᎢ * 21 + 칸] = 보드.표시화소읽기(가, 세);
                int ᎤᏓᏓᏟ_ᏧᎬᏩᎶᏗᏯ = ᎠᏎᎯᎯ_pel(칸, ᏚᏓᏅᏅᎢ); if (ᎤᏓᏓᏟ_ᏧᎬᏩᎶᏗᏯ != 0) 보드.ᎪᏪᎶᏗ_ᎬᏂᎨᏒ_ᏅᎦ_pel(가, 세, ᎤᏓᏓᏟ_ᏧᎬᏩᎶᏗᏯ == 2 ? 0xffffff : 0x101010);
            }
        }
    }
}
