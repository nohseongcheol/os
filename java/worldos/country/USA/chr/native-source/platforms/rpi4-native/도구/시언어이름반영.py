#!/usr/bin/env python3
"""선언 고유번호와 UTF-8 byte_ᏧᎬᏩᎶᏗᏯ 위치로 자체 C 이름을 옮기는 일회성 이행 도구.

외부 구조체의 멤버, ᎠᏍᏘ_ᏧᎬᏩᎶᏗᏯ, C 표준 ᏧᎸᏫᏍᏓᏁᏗᏱ_ᏧᎬᏩᎶᏗᏯ, 이식 규약은 보존한다.
입력은 ᎯᏁᏟᏴᎾ_ᏧᎬᏩᎶᏗᏯ 전 소스에 대한 시언어이름분석.py 결과여야 한다.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

기준 = Path(__file__).resolve().parents[1]

def ᎠᎴᏅᏗᏱ_ᎤᏁᏤᎸᎩ():
    분석 = json.loads((기준/'build/한국어화/시언어분석.json').read_text())
    if 분석['ᎦᎵᏓᏍᏔᏅ']: raise SystemExit('분석 오류를 먼저 해결해야 합니다.')
    ᏚᏙᎥᎢ_ᏧᎾᎶᎢᏓ = json.loads((기준/'명명/시언어이름.json').read_text())
    규격 = set(json.loads((기준/'명명/규격이름.json').read_text()))
    선언표 = 분석['선언']
    바꿀선언 = {고유:ᏚᏙᎥᎢ_ᏧᎾᎶᎢᏓ[Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ']] for 고유,Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ in 선언표.items()
                if Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ'] in ᏚᏙᎥᎢ_ᏧᎾᎶᎢᏓ and Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ'] not in 규격}
    ᎫᏓᎸᎢ_ᏧᎾᎶᎢᏓ = {Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ']:ᏚᏙᎥᎢ_ᏧᎾᎶᎢᏓ[Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ']] for Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ in 선언표.values()
              if Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ.get('ᎫᏓᎳ')==4 and Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['종류'] in (8,9)
              and Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ'] in ᏚᏙᎥᎢ_ᏧᎾᎶᎢᏓ and Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ'] not in 규격}
    # 생성 AOT C·어셈블리·공개 SDK가 공유하는 바이너리 ᎫᏓᎳ 이름만 유지한다.
    머리 = ['/* 한국어 ᎦᏟᏌᏅᎯ_ᏡᎬ 이름과 기존 기계 ᎫᏓᎳ ᎢᏳᎵᏍᏔᏅᎢ_ᏧᎬᏩᎶᏗᏯ. 자동 생성: 명명/시언어이름.json */',
           '#ifndef 자체기계연결이름머리', '#define 자체기계연결이름머리']
    머리 += ['#define '+새이름+' '+옛이름 for 옛이름,새이름 in sorted(ᎫᏓᎸᎢ_ᏧᎾᎶᎢᏓ.items())]
    머리 += ['#endif','']
    (기준/'명명/기계연결이름.h').write_text('\n'.join(머리))
    변경들 = defaultdict(dict)
    for ᎠᏍᏆᏂᎪᏙᏗ,변위,ᏚᏙᎥᎢ,고유 in 분석['참조']:
        if 고유 in 바꿀선언:
            변경들[ᎠᏍᏆᏂᎪᏙᏗ][변위] = (ᏚᏙᎥᎢ,바꿀선언[고유])
    ᎸᏛᏁᎸ_ᎪᏪᎳᏅᎢ_ᎤᏓᏅᏅ = ['ᎠᏍᏆᏂᎪᏙᏗ\t원래바이트위치\t이전이름\t한국어이름']
    ᏞᏍᏗ_ᏥᎭᎦᏎᏍᏔᏂ_ᏧᎬᏩᎶᏗᏯ = []
    for ᎠᏍᏆᏂᎪᏙᏗ,ᎯᏁᏟᏴᎾ_ᏧᎬᏩᎶᏗᏯ in 변경들.items():
        ᎠᏍᏓᏩᏛᏍᏗ = Path(ᎠᏍᏆᏂᎪᏙᏗ); 원본 = ᎠᏍᏓᏩᏛᏍᏗ.read_bytes(); ᎦᏟᏌᏅᎯ = 원본
        for 변위,(옛이름,새이름) in sorted(ᎯᏁᏟᏴᎾ_ᏧᎬᏩᎶᏗᏯ.items(),reverse=True):
            끝 = 변위+len(옛이름.encode())
            if 원본[변위:끝] != 옛이름.encode():
                ᏞᏍᏗ_ᏥᎭᎦᏎᏍᏔᏂ_ᏧᎬᏩᎶᏗᏯ.append((str(ᎠᏍᏓᏩᏛᏍᏗ.relative_to(기준)),변위,옛이름));continue
            ᎦᏟᏌᏅᎯ = ᎦᏟᏌᏅᎯ[:변위]+새이름.encode()+ᎦᏟᏌᏅᎯ[끝:]
            ᎸᏛᏁᎸ_ᎪᏪᎳᏅᎢ_ᎤᏓᏅᏅ.append('{}\t{}\t{}\t{}'.format(ᎠᏍᏓᏩᏛᏍᏗ.relative_to(기준),변위,옛이름,새이름))
        ᎠᏍᏓᏩᏛᏍᏗ.write_bytes(ᎦᏟᏌᏅᎯ)
    # 전처리 매개변수는 AST의 선언으로 나타나지 않는다. 전처리 줄만 보완한다.
    낱말 = re.compile(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\b[A-Za-z_]\w*\b')
    ᏍᏆᎳ_ᏱᏗᎬᏁᎸ_ᏧᎬᏩᎶᏗᏯ = {Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ']:ᏚᏙᎥᎢ_ᏧᎾᎶᎢᏓ[Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ']] for Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ in 선언표.values()
              if Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['종류']==501 and Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ'] in ᏚᏙᎥᎢ_ᏧᎾᎶᎢᏓ and Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᏚᏙᎥᎢ'] not in 규격}
    for ᎠᏍᏓᏩᏛᏍᏗ in sorted({Path(Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᎠᏍᏆᏂᎪᏙᏗ']) for Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ in 선언표.values()}):
        ᏚᏓᏅᏅᎢ_ᏕᎦᏅᏅᏛ = ᎠᏍᏓᏩᏛᏍᏗ.read_text().splitlines(True); 이어짐 = False
        for ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ,ᏚᏓᏅᏅᎢ in enumerate(ᏚᏓᏅᏅᎢ_ᏕᎦᏅᏅᏛ):
            전처리 = 이어짐 or bool(re.match(r'\s*#',ᏚᏓᏅᏅᎢ))
            이어짐 = 전처리 and ᏚᏓᏅᏅᎢ.rstrip().endswith('\\')
            if 전처리:
                표 = ᏚᏙᎥᎢ_ᏧᎾᎶᎢᏓ if re.match(r'\s*#\s*define\b',ᏚᏓᏅᏅᎢ) or 이어짐 else ᏍᏆᎳ_ᏱᏗᎬᏁᎸ_ᏧᎬᏩᎶᏗᏯ
                ᏚᏓᏅᏅᎢ_ᏕᎦᏅᏅᏛ[ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ] = 낱말.sub(lambda 맞음: 표.get(맞음[0],맞음[0]) if 맞음[0] not in 규격 else 맞음[0],ᏚᏓᏅᏅᎢ)
        ᎠᏍᏓᏩᏛᏍᏗ.write_text(''.join(ᏚᏓᏅᏅᎢ_ᏕᎦᏅᏅᏛ))
    # 각 자체 번역 단위에만 연결표를 넣는다. 외부 배포본에는 전파하지 않는다.
    for ᎠᏍᏓᏩᏛᏍᏗ in sorted({Path(Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ['ᎠᏍᏆᏂᎪᏙᏗ']) for Ꭵ_ᎧᏁᏉᎢᏍᏙᏗ_ᏧᎬᏩᎶᏗᏯ in 선언표.values()}):
        if ᎠᏍᏓᏩᏛᏍᏗ.suffix not in ('.c','.cpp'):continue
        ᏱᎦᏲᎩᎾᏛᏂ_ᏧᎬᏩᎶᏗᏯ = '../' * len(ᎠᏍᏓᏩᏛᏍᏗ.relative_to(기준).parts[:-1]) + '명명/기계연결이름.h'
        ᎠᏍᏓᏩᏛᏍᏗ.write_text('#include "'+ᏱᎦᏲᎩᎾᏛᏂ_ᏧᎬᏩᎶᏗᏯ+'"\n'+ᎠᏍᏓᏩᏛᏍᏗ.read_text())
    (기준/'명명/시언어이름대응.tsv').write_text('\n'.join(ᎸᏛᏁᎸ_ᎪᏪᎳᏅᎢ_ᎤᏓᏅᏅ)+'\n')
    (기준/'build/한국어화/전처리참조.json').write_text(json.dumps(ᏞᏍᏗ_ᏥᎭᎦᏎᏍᏔᏂ_ᏧᎬᏩᎶᏗᏯ,ensure_ascii=False,indent=2)+'\n')
    print('ᎯᏁᏟᏴᎾ_ᏧᎬᏩᎶᏗᏯ',len(ᎸᏛᏁᎸ_ᎪᏪᎳᏅᎢ_ᎤᏓᏅᏅ)-1,'전처리 재검토',len(ᏞᏍᏗ_ᏥᎭᎦᏎᏍᏔᏂ_ᏧᎬᏩᎶᏗᏯ),'기계 ᎫᏓᎳ',len(ᎫᏓᎸᎢ_ᏧᎾᎶᎢᏓ))

if __name__=='__main__': ᎠᎴᏅᏗᏱ_ᎤᏁᏤᎸᎩ()
