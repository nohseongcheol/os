#include "호출경계.h"
extern int main(int 인수개수, char **ᏗᏓᎦᏘᎸᏍᏗ_ᏕᎦᏅᏅᏛ);
static char ᏗᏓᎦᏘᎸᏍᏗ_ᎠᏅᏓᏗᏍᏙ[2048];
static char *ᏗᏓᎦᏘᎸᏍᏗ_ᏕᎦᏅᏅᏛ[18];
int jkoros_main(void) {
    int 개수 = jkoros_syscall(2, 0, 0, 0, 0, 0);
    if (개수 < 0 || 개수 > 16) return 126;
    /* 현재 커널의 argv는 ᎠᎴᏅᏗᏱ_ᎤᏁᏤᎸᎩ 이름을 제외한다. C argv[0]은 고정 식별 이름이다. */
    ᏗᏓᎦᏘᎸᏍᏗ_ᏕᎦᏅᏅᏛ[0] = "jkoros-app";
    int 위치 = 0;
    for (int ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ = 0; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ < 개수; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ++) {
        const int *원본 = (const int *)jkoros_syscall(3, ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ, 0, 0, 0, 0);
        if (!원본 || 원본[0] < 0 || 원본[0] > 127) return 126;
        ᏗᏓᎦᏘᎸᏍᏗ_ᏕᎦᏅᏅᏛ[ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ + 1] = ᏗᏓᎦᏘᎸᏍᏗ_ᎠᏅᏓᏗᏍᏙ + 위치;
        for (int 칸 = 0; 칸 < 원본[0]; 칸++) {
            if (위치 >= 2047) return 126;
            ᏗᏓᎦᏘᎸᏍᏗ_ᎠᏅᏓᏗᏍᏙ[위치++] = 원본[칸 + 1];
        }
        ᏗᏓᎦᏘᎸᏍᏗ_ᎠᏅᏓᏗᏍᏙ[위치++] = 0;
    }
    ᏗᏓᎦᏘᎸᏍᏗ_ᏕᎦᏅᏅᏛ[개수 + 1] = 0;
    return main(개수 + 1, ᏗᏓᎦᏘᎸᏍᏗ_ᏕᎦᏅᏅᏛ);
}
