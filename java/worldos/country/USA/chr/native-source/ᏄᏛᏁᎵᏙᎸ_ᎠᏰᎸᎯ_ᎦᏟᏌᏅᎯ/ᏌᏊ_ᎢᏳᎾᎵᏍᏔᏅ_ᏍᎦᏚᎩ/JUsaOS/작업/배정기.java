package ᏌᏊ_ᎢᏳᎾᎵᏍᏔᏅ_ᏍᎦᏚᎩ.JUsaOS.작업;

import java.util.ArrayDeque;
import java.util.HashMap;
import java.util.Map;
import java.util.Queue;
import ᏌᏊ_ᎢᏳᎾᎵᏍᏔᏅ_ᏍᎦᏚᎩ.JUsaOS.기억공간.ᎤᎦᏅᏓᏛᎢ_ᏗᎫᎪᏔᏂᏙᎯ;
import ᏌᏊ_ᎢᏳᎾᎵᏍᏔᏅ_ᏍᎦᏚᎩ.JUsaOS.ᎠᏍᏆᏂᎪᏙᏗ_ᏄᏍᏗᏓᏅᎢ.파일서술자표;

/** ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 식별자와 라운드로빈 ᎭᏛᏅᎢᏍᏓ 대기열을 관리한다. */
public final class 배정기 {
    private final ᎤᎦᏅᏓᏛᎢ_ᏗᎫᎪᏔᏂᏙᎯ 쪽관리;
    private final Map<Integer, ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ> ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏕᎦᏅᏅᏛ = new HashMap<Integer, ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ>();
    private final Queue<ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ> 준비대기열 = new ArrayDeque<ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ>();
    private int 다음식별자 = 1;

    public 배정기(ᎤᎦᏅᏓᏛᎢ_ᏗᎫᎪᏔᏂᏙᎯ 쪽관리) {
        this.쪽관리 = 쪽관리;
    }

    public ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 첫과정(파일서술자표 파일서술자) {
        ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 새과정 = new ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ(식별자할당(), 0, 쪽관리.새주소공간(), 파일서술자);
        ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏕᎦᏅᏅᏛ.put(Integer.valueOf(새과정.ᎠᏓᏙᎵᎩ_ᏧᎬᏩᎶᏗᏯ()), 새과정);
        준비대기열.offer(새과정);
        return 새과정;
    }

    public ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 복제(ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 부모) {
        ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 자식 = new ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ(
                식별자할당(),
                부모.ᎠᏓᏙᎵᎩ_ᏧᎬᏩᎶᏗᏯ(),
                쪽관리.쓰기시복사복제(부모.ᎪᏪᎵ_ᏫᏗᎦᏅᏗ_SPACE()),
                부모.파일서술자().복제());
        자식.프로그램끝설정(부모.프로그램끝());
        ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏕᎦᏅᏅᏛ.put(Integer.valueOf(자식.ᎠᏓᏙᎵᎩ_ᏧᎬᏩᎶᏗᏯ()), 자식);
        준비대기열.offer(자식);
        return 자식;
    }

    public ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 다음과정() {
        int 검사수 = 준비대기열.size();
        for (int ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ = 0; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ < 검사수; ᏂᎬᎿᏅ_ᎠᏓᏎᎮᎯ++) {
            ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 다음 = 준비대기열.poll();
            if (다음 != null && (다음.ᏄᏍᏗᏓᏅ_ᏧᎬᏩᎶᏗᏯ() == ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏄᏍᏗᏓᏅ.ᎭᏛᏅᎢᏍᏓ || 다음.ᏄᏍᏗᏓᏅ_ᏧᎬᏩᎶᏗᏯ() == ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏄᏍᏗᏓᏅ.ᎠᎴᏅᏗᏱ_ᎤᏁᏤᎸᎩ)) {
                다음.ᎦᎪᏗ_ᏄᏍᏗᏓᏅ(ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏄᏍᏗᏓᏅ.ᎠᎴᏅᏗᏱ_ᎤᏁᏤᎸᎩ);
                준비대기열.offer(다음);
                return 다음;
            }
        }
        return null;
    }

    public int 자식기다리기(ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 부모, int 자식식별자, boolean 기다리지않음) {
        for (ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ 후보 : ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏕᎦᏅᏅᏛ.values()) {
            if (후보.부모식별자() != 부모.ᎠᏓᏙᎵᎩ_ᏧᎬᏩᎶᏗᏯ()) {
                continue;
            }
            if (자식식별자 > 0 && 후보.ᎠᏓᏙᎵᎩ_ᏧᎬᏩᎶᏗᏯ() != 자식식별자) {
                continue;
            }
            if (후보.ᏄᏍᏗᏓᏅ_ᏧᎬᏩᎶᏗᏯ() == ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏄᏍᏗᏓᏅ.ᎦᏅᎪᎢᏍᏗ_ᎬᏙᏗ) {
                int 결과 = (후보.종료값() & 0xff) << 8;
                ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏕᎦᏅᏅᏛ.remove(Integer.valueOf(후보.ᎠᏓᏙᎵᎩ_ᏧᎬᏩᎶᏗᏯ()));
                return 결과;
            }
            return 기다리지않음 ? 0 : -11;
        }
        return -10;
    }

    public ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏧᎬᏩᎶᏗᏯ ᎯᏩᏔ_ᎢᏯᏛᏁᎵᏓᏍᏗ(int ᎠᏓᏙᎵᎩ_ᏧᎬᏩᎶᏗᏯ) {
        return ᎢᏯᏛᏁᎵᏓᏍᏗ_ᏕᎦᏅᏅᏛ.get(Integer.valueOf(ᎠᏓᏙᎵᎩ_ᏧᎬᏩᎶᏗᏯ));
    }

    private int 식별자할당() {
        return 다음식별자++;
    }
}
