package Узбекистан.JUzbOS.Память_регион;

import java.util.Arrays;
import java.util.HashMap;
import java.util.Map;

/** 4 KiB страница_ЗНАЧЕН 연결과 Запись 시 복사를 제공한다. */
public final class страница_менеджер {
    public static final int размер_страницы = 4096;

    private static final class страница_ЗНАЧЕН {
        private byte[] данные = new byte[размер_страницы];
        private int ссылка_СЧЁТ = 1;
        private boolean 쓰기가능 = true;
        private boolean копирование_при_записи;
    }

    public static final class диапазон_адресов {
        private final Map<Integer, страница_ЗНАЧЕН> страница_таблица = new HashMap<Integer, страница_ЗНАЧЕН>();
    }

    public диапазон_адресов 새주소공간() {
        return new диапазон_адресов();
    }

    public void MAP_страница(диапазон_адресов АДРЕС_регион, int виртуальный_адрес, boolean 쓰기가능) {
        int ИНДЕКС = 쪽번호(виртуальный_адрес);
        страница_ЗНАЧЕН 새쪽 = new страница_ЗНАЧЕН();
        새쪽.쓰기가능 = 쓰기가능;
        АДРЕС_регион.страница_таблица.put(Integer.valueOf(ИНДЕКС), 새쪽);
    }

    public диапазон_адресов клон_копирование_при_записи(диапазон_адресов 원본) {
        диапазон_адресов 복제본 = new диапазон_адресов();
        for (Map.Entry<Integer, страница_ЗНАЧЕН> ввод_ЗНАЧЕН : 원본.страница_таблица.entrySet()) {
            страница_ЗНАЧЕН Общий_страница = ввод_ЗНАЧЕН.getValue();
            Общий_страница.ссылка_СЧЁТ++;
            if (Общий_страница.쓰기가능) {
                Общий_страница.쓰기가능 = false;
                Общий_страница.копирование_при_записи = true;
            }
            복제본.страница_таблица.put(ввод_ЗНАЧЕН.getKey(), Общий_страница);
        }
        return 복제본;
    }

    public byte чтение_байт_ЗНАЧЕН(диапазон_адресов АДРЕС_регион, int виртуальный_адрес) {
        страница_ЗНАЧЕН целевое_значение = НАЙТИ_страница(АДРЕС_регион, виртуальный_адрес);
        return целевое_значение.данные[Math.floorMod(виртуальный_адрес, размер_страницы)];
    }

    public void запись_байт_ЗНАЧЕН(диапазон_адресов АДРЕС_регион, int виртуальный_адрес, byte ЗНАЧЕН) {
        int ИНДЕКС = 쪽번호(виртуальный_адрес);
        страница_ЗНАЧЕН целевое_значение = НАЙТИ_страница(АДРЕС_регион, виртуальный_адрес);
        if (!целевое_значение.쓰기가능) {
            if (!целевое_значение.копирование_при_записи) {
                throw new IllegalStateException("Чтение 전용 쪽입니다.");
            }
            целевое_значение = Create_частный_страница(АДРЕС_регион, ИНДЕКС, целевое_значение);
        }
        целевое_значение.данные[Math.floorMod(виртуальный_адрес, размер_страницы)] = ЗНАЧЕН;
    }

    public void частный_диапазон_запись(диапазон_адресов АДРЕС_регион, int Пуск_АДРЕС, int Размер) {
        if (Размер < 0) {
            throw new IllegalArgumentException("크기가 음수입니다.");
        }
        int конечный_адрес = Math.addExact(Пуск_АДРЕС, Размер);
        for (int АДРЕС = Пуск_АДРЕС; АДРЕС < конечный_адрес; АДРЕС = (쪽번호(АДРЕС) + 1) * размер_страницы) {
            int ИНДЕКС = 쪽번호(АДРЕС);
            страница_ЗНАЧЕН целевое_значение = НАЙТИ_страница(АДРЕС_регион, АДРЕС);
            if (целевое_значение.копирование_при_записи) {
                Create_частный_страница(АДРЕС_регион, ИНДЕКС, целевое_значение);
            } else {
                целевое_значение.쓰기가능 = true;
            }
        }
    }

    public void диапазон_запись(диапазон_адресов АДРЕС_регион, int Пуск_АДРЕС, byte[] данные) {
        for (int ИНДЕКС = 0; ИНДЕКС < данные.length; ИНДЕКС++) {
            запись_байт_ЗНАЧЕН(АДРЕС_регион, Пуск_АДРЕС + ИНДЕКС, данные[ИНДЕКС]);
        }
    }

    private страница_ЗНАЧЕН Create_частный_страница(диапазон_адресов АДРЕС_регион, int ИНДЕКС, страница_ЗНАЧЕН Общий_страница) {
        страница_ЗНАЧЕН частный_страница = new страница_ЗНАЧЕН();
        частный_страница.данные = Arrays.copyOf(Общий_страница.данные, Общий_страница.данные.length);
        частный_страница.쓰기가능 = true;
        частный_страница.копирование_при_записи = false;
        Общий_страница.ссылка_СЧЁТ--;
        АДРЕС_регион.страница_таблица.put(Integer.valueOf(ИНДЕКС), частный_страница);
        return частный_страница;
    }

    private страница_ЗНАЧЕН НАЙТИ_страница(диапазон_адресов АДРЕС_регион, int АДРЕС) {
        страница_ЗНАЧЕН целевое_значение = АДРЕС_регион.страница_таблица.get(Integer.valueOf(쪽번호(АДРЕС)));
        if (целевое_значение == null) {
            throw new IllegalStateException("연결되지 않은 가상 주소입니다.");
        }
        return целевое_значение;
    }

    private int 쪽번호(int АДРЕС) {
        if (АДРЕС < 0) {
            throw new IllegalArgumentException("주소가 음수입니다.");
        }
        return АДРЕС / размер_страницы;
    }
}

