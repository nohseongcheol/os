/** 採用總和檢查碼及雙副本的小型專用儲存格式，只在 fsync/sync 時持久保存。 */
public final class 檔案持久化 {
    static int 當前已保留複製 = -1, 代次編號 = 0;
    static int[] 檔案表 = new int[1024];
    static int 哈希位元組列(int 值, int 資料) { return (值 ^ 資料) * 16777619; }
    static void 清空資料() {
        for (int 編號 = 0; 編號 < 512; 編號++) 存儲設備連接.區段資料[編號] = 0;
    }
    static int 表整數(int 位置) {
        return 檔案表[位置] | 檔案表[位置 + 1] << 8 | 檔案表[位置 + 2] << 16 | 檔案表[位置 + 3] << 24;
    }
    static void 寫入表整數(int 位置, int 值) {
        for (int 編號 = 0; 編號 < 4; 編號++) 檔案表[位置 + 編號] = (值 >>> (編號 * 8)) & 255;
    }
    static boolean 檢查表() {
        for (int 檔案 = 0; 檔案 < 8; 檔案++) {
            int 長度 = 0;
            for (int 槽條目 = 0; 槽條目 < 64; 槽條目++) 主記憶體檔案系統.名稱[槽條目] = 檔案表[檔案 * 72 + 槽條目];
            while (長度 < 64 && 主記憶體檔案系統.名稱[長度] != 0) 長度++;
            if (長度 == 0) continue;
            if (!主記憶體檔案系統.檢查名稱(主記憶體檔案系統.名稱, 長度)
                || 表整數(檔案 * 72 + 64) < 0 || 表整數(檔案 * 72 + 64) > 16384) return false;
            for (int 前端值 = 0; 前端值 < 檔案; 前端值++) {
                boolean 相等文本 = 檔案表[前端值 * 72 + 長度] == 0;
                for (int 槽條目 = 0; 槽條目 < 長度; 槽條目++) if (檔案表[前端值 * 72 + 槽條目] != 主記憶體檔案系統.名稱[槽條目]) 相等文本 = false;
                if (相等文本) return false;
            }
        }
        return true;
    }
    static int 檢查已保留複製(int 已保留複製) {
        int 開始區段 = 1 + 已保留複製 * 259;
        if (存儲設備連接.讀取(開始區段) < 0 || 存儲設備連接.解析整數(0) != 0x4a4b534e) return -1;
        int 代次值 = 存儲設備連接.解析整數(4), 校驗和 = 存儲設備連接.解析整數(8);
        if (代次值 < 1 || 存儲設備連接.解析整數(12) != (代次值 ^ 校驗和 ^ 0x4a4b534e)) return -1;
        int 哈希檔案 = 0x811c9dc5;
        for (int 區段值 = 0; 區段值 < 258; 區段值++) {
            if (存儲設備連接.讀取(開始區段 + 1 + 區段值) < 0) return -1;
            for (int 槽條目 = 0; 槽條目 < 512; 槽條目++) {
                int 值 = 存儲設備連接.區段資料[槽條目];
                哈希檔案 = 哈希位元組列(哈希檔案, 值);
                if (區段值 < 2) 檔案表[區段值 * 512 + 槽條目] = 值;
            }
        }
        return 哈希檔案 == 校驗和 && 檢查表() ? 代次值 : -1;
    }
    static int 加載(int 已保留複製) {
        int 開始區段 = 1 + 已保留複製 * 259;
        for (int 區段值 = 0; 區段值 < 2; 區段值++) {
            if (存儲設備連接.讀取(開始區段 + 1 + 區段值) < 0) return -5;
            for (int 槽條目 = 0; 槽條目 < 512; 槽條目++) 檔案表[區段值 * 512 + 槽條目] = 存儲設備連接.區段資料[槽條目];
        }
        for (int 檔案 = 0; 檔案 < 8; 檔案++) {
            for (int 槽條目 = 0; 槽條目 < 64; 槽條目++) 主記憶體檔案系統.名稱列列表[檔案 * 64 + 槽條目] = 檔案表[檔案 * 72 + 槽條目];
            主記憶體檔案系統.大小列表[檔案] = 檔案表[檔案 * 72] == 0 ? 0 : 表整數(檔案 * 72 + 64);
            主記憶體檔案系統.權限授權列[檔案] = 表整數(檔案 * 72 + 68) & 511;
            for (int 區段值 = 0; 區段值 < 32; 區段值++) {
                if (存儲設備連接.讀取(開始區段 + 3 + 檔案 * 32 + 區段值) < 0) return -5;
                int 地址 = 設備.檔案記憶體() + 檔案 * 16384 + 區段值 * 512;
                for (int 槽條目 = 0; 槽條目 < 512; 槽條目++) 設備.寫入記憶體(地址 + 槽條目, 存儲設備連接.區段資料[槽條目]);
            }
        }
        return 0;
    }
    static void 準備() {
        if (存儲設備連接.讀取(0) < 0 || 存儲設備連接.解析整數(0) != 0x54534b4a
            || 存儲設備連接.解析整數(4) != 0x3145524f || 存儲設備連接.解析整數(8) != 2048
            || 存儲設備連接.解析整數(12) != 0x3153464a) {
            字元終端.寫入("STORE RAM only (no JKSTORE1 disk)\n"); return;
        }
        存儲設備連接.是否可用 = true;
        int 首位序數 = 檢查已保留複製(0), 第二序數 = 檢查已保留複製(1);
        if (首位序數 < 0 && 第二序數 < 0) { 字元終端.寫入("STORE ready; no valid snapshot\n"); return; }
        當前已保留複製 = 首位序數 >= 第二序數 ? 0 : 1; 代次編號 = 首位序數 >= 第二序數 ? 首位序數 : 第二序數;
        if (加載(當前已保留複製) < 0) {
            字元終端.寫入("STORE read failed; halted to preserve files\n"); 設備.停機執行狀態();
        }
        字元終端.寫入("STORE restored generation "); 字元終端.寫入編號(代次編號); 字元終端.字元(10);
    }
    static int 同步化() {
        if (!存儲設備連接.是否可用) return -19;
        if (代次編號 == 2147483647) return -75;
        int 下一項目 = 當前已保留複製 == 0 ? 1 : 0, 開始區段 = 1 + 下一項目 * 259;
        // 寫入新本文前，先使舊 commit 失效並清空裝置快取。
        清空資料();
        if (存儲設備連接.寫入(開始區段) < 0 || 存儲設備連接.沖刷輸出() < 0) return -5;
        for (int 槽條目 = 0; 槽條目 < 1024; 槽條目++) 檔案表[槽條目] = 0;
        for (int 檔案 = 0; 檔案 < 8; 檔案++) if (主記憶體檔案系統.名稱列列表[檔案 * 64] != 0) {
            for (int 槽條目 = 0; 槽條目 < 64; 槽條目++) 檔案表[檔案 * 72 + 槽條目] = 主記憶體檔案系統.名稱列列表[檔案 * 64 + 槽條目];
            寫入表整數(檔案 * 72 + 64, 主記憶體檔案系統.大小列表[檔案]);
            寫入表整數(檔案 * 72 + 68, 主記憶體檔案系統.權限授權列[檔案]);
        }
        int 哈希檔案 = 0x811c9dc5;
        for (int 區段值 = 0; 區段值 < 258; 區段值++) {
            for (int 槽條目 = 0; 槽條目 < 512; 槽條目++) {
                int 值 = 0;
                if (區段值 < 2) 值 = 檔案表[區段值 * 512 + 槽條目];
                else {
                    int 檔案 = (區段值 - 2) / 32, 位置 = (區段值 - 2) % 32 * 512 + 槽條目;
                    if (檔案表[檔案 * 72] != 0 && 位置 < 主記憶體檔案系統.大小列表[檔案])
                        值 = 設備.讀取記憶體(設備.檔案記憶體() + 檔案 * 16384 + 位置);
                }
                存儲設備連接.區段資料[槽條目] = 值; 哈希檔案 = 哈希位元組列(哈希檔案, 值);
            }
            if (存儲設備連接.寫入(開始區段 + 1 + 區段值) < 0) return -5;
        }
        if (存儲設備連接.沖刷輸出() < 0) return -5;
        清空資料(); 存儲設備連接.寫入整數值(0, 0x4a4b534e);
        存儲設備連接.寫入整數值(4, 代次編號 + 1); 存儲設備連接.寫入整數值(8, 哈希檔案);
        存儲設備連接.寫入整數值(12, (代次編號 + 1) ^ 哈希檔案 ^ 0x4a4b534e);
        if (存儲設備連接.寫入(開始區段) < 0 || 存儲設備連接.沖刷輸出() < 0) return -5;
        當前已保留複製 = 下一項目; 代次編號++;
        return 0;
    }
}
