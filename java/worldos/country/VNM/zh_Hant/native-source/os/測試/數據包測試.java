import java.util.Arrays;

/** 在 JVM 中呼叫實際的 Java 協定處理器，快速檢查邊界與損壞的輸入。 */
public final class 數據包測試 {
    static int 重複狀態個數 = 0;
    static void 驗證(boolean 值) { if (!值) throw new AssertionError("case " + 重複狀態個數); 重複狀態個數++; }
    static int 校驗和(int[] 值, int 運行, int 長度, int 初始狀態) {
        int 總和值 = 初始狀態;
        for (int 編號 = 0; 編號 < 長度; 編號++) 總和值 += 值[運行 + 編號] << ((編號 & 1) == 0 ? 8 : 0);
        總和值 = (總和值 & 65535) + (總和值 >>> 16);
        總和值 = (總和值 & 65535) + (總和值 >>> 16);
        return ~總和值 & 65535;
    }
    static void 準備(int 長度) {
        通信網絡.清潔程序();
        驗證(通信網絡.打開(5000) == 3);
        int[] 幀索引 = 通信網絡.輸入幀;
        Arrays.fill(幀索引, 0);
        for (int 編號 = 0; 編號 < 6; 編號++) 幀索引[編號] = 網絡設備驅動.設備地址[編號];
        通信網絡.放入16(幀索引, 12, 0x0800);
        幀索引[14] = 0x45; 幀索引[22] = 64; 幀索引[23] = 17;
        通信網絡.放入16(幀索引, 16, 28 + 長度);
        通信網絡.放入32(幀索引, 26, 0x0a000202); 通信網絡.放入32(幀索引, 30, 通信網絡.自有對象地址);
        通信網絡.放入16(幀索引, 34, 4321); 通信網絡.放入16(幀索引, 36, 5000); 通信網絡.放入16(幀索引, 38, 長度 + 8);
        for (int 編號 = 0; 編號 < 長度; 編號++) 幀索引[42 + 編號] = 編號 & 255;
        設定校驗和(長度);
    }
    static void 設定校驗和(int 長度) {
        int[] 幀索引 = 通信網絡.輸入幀;
        通信網絡.放入16(幀索引, 24, 0); 通信網絡.放入16(幀索引, 40, 0);
        通信網絡.放入16(幀索引, 24, 校驗和(幀索引, 14, 20, 0));
        int 初始狀態 = 通信網絡.僞標頭校驗和(通信網絡.整數32(幀索引, 26), 通信網絡.自有對象地址, 長度 + 8);
        int 總和值 = 校驗和(幀索引, 34, 長度 + 8, 初始狀態);
        通信網絡.放入16(幀索引, 40, 總和值 == 0 ? 65535 : 總和值);
    }
    static void 拒絕值(int 長度) { 通信網絡.程序幀(長度); 驗證(通信網絡.已接收長度[0] == -1); }
    public static void main(String[] 實參) {
        for (int 長度 : new int[]{0, 1, 2, 7, 1023, 1024}) {
            準備(長度); 通信網絡.程序幀(長度 + 42);
            驗證(通信網絡.已接收長度[0] == 長度);
            驗證(通信網絡.已接收地址[0] == 0x0a000202 && 通信網絡.已接收埠編號[0] == 4321);
            for (int 編號 = 0; 編號 < 長度; 編號++) 驗證(通信網絡.已接收資料[編號] == (編號 & 255));
        }
        for (int 長度 = 0; 長度 < 42; 長度++) { 準備(0); 拒絕值(長度); }
        準備(1025); 拒絕值(1067);
        準備(2); 通信網絡.輸入幀[24] ^= 1; 拒絕值(44);
        準備(2); 通信網絡.輸入幀[42] ^= 1; 拒絕值(44);
        準備(2); 通信網絡.放入16(通信網絡.輸入幀, 38, 7); 拒絕值(44);
        準備(2); 通信網絡.放入16(通信網絡.輸入幀, 38, 65535); 拒絕值(44);
        準備(2); 通信網絡.輸入幀[14] = 0x4f; 拒絕值(44);
        準備(2); 通信網絡.輸入幀[14] = 0x44; 拒絕值(44);
        準備(2); 通信網絡.輸入幀[20] = 0x20; 設定校驗和(2); 拒絕值(44);
        準備(2); 通信網絡.輸入幀[21] = 1; 設定校驗和(2); 拒絕值(44);
        準備(2); 通信網絡.輸入幀[33] = 99; 設定校驗和(2); 拒絕值(44);
        準備(2); 通信網絡.輸入幀[0] ^= 1; 拒絕值(44);
        準備(2); 通信網絡.輸入幀[23] = 6; 設定校驗和(2); 拒絕值(44);
        準備(2); 通信網絡.放入16(通信網絡.輸入幀, 40, 0); 通信網絡.程序幀(44); 驗證(通信網絡.已接收長度[0] == 2);
        int[] 結果 = new int[4];
        驗證(通信網絡.接收(3, 結果, 1, 0) == -90);
        驗證(通信網絡.接收(3, 結果, 4, 0) == -11);
        準備(2); 通信網絡.程序幀(44); int 丟棄值 = 通信網絡.已丟棄個數;
        通信網絡.程序幀(44); 驗證(通信網絡.已丟棄個數 == 丟棄值 + 1);
        通信網絡.清潔程序(); 驗證(通信網絡.打開(5000) == 3);
        驗證(通信網絡.打開(5000) == -98); 驗證(通信網絡.打開(0) == 4);
        驗證(通信網絡.打開(0) == 5); 驗證(通信網絡.打開(0) == 6); 驗證(通信網絡.打開(0) == -24);
        驗證(通信網絡.關閉(4) == 0); 驗證(通信網絡.關閉(4) == -9);
        通信網絡.已找到地址 = 通信網絡.網關值;
        驗證(通信網絡.發送(3, 通信網絡.網關值, 4321, new int[]{1, 2, 3}, 3) == 3);
        int[] 擁有已發送 = 網絡設備驅動.最近值;
        驗證(校驗和(擁有已發送, 14, 20, 0) == 0);
        驗證(校驗和(擁有已發送, 34, 11, 通信網絡.僞標頭校驗和(通信網絡.自有對象地址, 通信網絡.網關值, 11)) == 0);
        驗證(擁有已發送[42] == 1 && 擁有已發送[44] == 3);
        System.out.println("PACKET TEST PASS: " + 重複狀態個數 + " assertions");
    }
}
