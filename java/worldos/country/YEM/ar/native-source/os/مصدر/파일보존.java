    static int 현재보존본 = -1, جيل_رقم = 0;
    static int[] ملف_جدول = new int[1024];
    static int 바이트해시(int قيمة, int بيانات) { return (قيمة ^ بيانات) * 16777619; }
    static void مسح_بيانات() {
        for (int فهرس = 0; فهرس < 512; فهرس++) جهاز_تخزين_صديق.قسم_بيانات[فهرس] = 0;
    }
    static int جدول_عدد_صحيح(int موضع) {
        return ملف_جدول[موضع] | ملف_جدول[موضع + 1] << 8 | ملف_جدول[موضع + 2] << 16 | ملف_جدول[موضع + 3] << 24;
    }
    static void كتابة_جدول_عدد_صحيح(int موضع, int قيمة) {
        for (int فهرس = 0; فهرس < 4; فهرس++) ملف_جدول[موضع + فهرس] = (قيمة >>> (فهرس * 8)) & 255;
    }
    static boolean شيك_جدول() {
        for (int ملف = 0; ملف < 8; ملف++) {
            int 길이 = 0;
            for (int فتحة_إدخال = 0; فتحة_إدخال < 64; فتحة_إدخال++) ذاكرة_نظام_الملفات.اسم[فتحة_إدخال] = ملف_جدول[ملف * 72 + فتحة_إدخال];
            while (길이 < 64 && ذاكرة_نظام_الملفات.اسم[길이] != 0) 길이++;
            if (길이 == 0) continue;
            if (!ذاكرة_نظام_الملفات.شيك_اسم(ذاكرة_نظام_الملفات.اسم, 길이)
                || جدول_عدد_صحيح(ملف * 72 + 64) < 0 || جدول_عدد_صحيح(ملف * 72 + 64) > 16384) return false;
            for (int الكاميرا_الأمامية_قيمة = 0; الكاميرا_الأمامية_قيمة < ملف; الكاميرا_الأمامية_قيمة++) {
                boolean 같음 = ملف_جدول[الكاميرا_الأمامية_قيمة * 72 + 길이] == 0;
                for (int فتحة_إدخال = 0; فتحة_إدخال < 길이; فتحة_إدخال++) if (ملف_جدول[الكاميرا_الأمامية_قيمة * 72 + فتحة_إدخال] != ذاكرة_نظام_الملفات.اسم[فتحة_إدخال]) 같음 = false;
                if (같음) return false;
            }
        }
        return true;
    }
    static int 보존본검사(int 보존본) {
        int بدء_قسم = 1 + 보존본 * 259;
        if (جهاز_تخزين_صديق.قراءة(بدء_قسم) < 0 || جهاز_تخزين_صديق.يوزّع_عدد_صحيح(0) != 0x4a4b534e) return -1;
        int جيل_قيمة = جهاز_تخزين_صديق.يوزّع_عدد_صحيح(4), مجموع_اختباري = جهاز_تخزين_صديق.يوزّع_عدد_صحيح(8);
        if (جيل_قيمة < 1 || جهاز_تخزين_صديق.يوزّع_عدد_صحيح(12) != (جيل_قيمة ^ مجموع_اختباري ^ 0x4a4b534e)) return -1;
        int تجزئة_ملف = 0x811c9dc5;
        for (int قسم_قيمة_366e0bfa = 0; قسم_قيمة_366e0bfa < 258; قسم_قيمة_366e0bfa++) {
            if (جهاز_تخزين_صديق.قراءة(بدء_قسم + 1 + قسم_قيمة_366e0bfa) < 0) return -1;
            for (int فتحة_إدخال = 0; فتحة_إدخال < 512; فتحة_إدخال++) {
                int قيمة = جهاز_تخزين_صديق.قسم_بيانات[فتحة_إدخال];
                تجزئة_ملف = 바이트해시(تجزئة_ملف, قيمة);
                if (قسم_قيمة_366e0bfa < 2) ملف_جدول[قسم_قيمة_366e0bfa * 512 + فتحة_إدخال] = قيمة;
            }
        }
        return تجزئة_ملف == مجموع_اختباري && شيك_جدول() ? جيل_قيمة : -1;
    }
    static int تحميل(int 보존본) {
        int بدء_قسم = 1 + 보존본 * 259;
        for (int قسم_قيمة_366e0bfa = 0; قسم_قيمة_366e0bfa < 2; قسم_قيمة_366e0bfa++) {
            if (جهاز_تخزين_صديق.قراءة(بدء_قسم + 1 + قسم_قيمة_366e0bfa) < 0) return -5;
            for (int فتحة_إدخال = 0; فتحة_إدخال < 512; فتحة_إدخال++) ملف_جدول[قسم_قيمة_366e0bfa * 512 + فتحة_إدخال] = جهاز_تخزين_صديق.قسم_بيانات[فتحة_إدخال];
        }
        for (int ملف = 0; ملف < 8; ملف++) {
            for (int فتحة_إدخال = 0; فتحة_إدخال < 64; فتحة_إدخال++) ذاكرة_نظام_الملفات.이름들[ملف * 64 + فتحة_إدخال] = ملف_جدول[ملف * 72 + فتحة_إدخال];
            ذاكرة_نظام_الملفات.يغير_الحجم_قائمة[ملف] = ملف_جدول[ملف * 72] == 0 ? 0 : جدول_عدد_صحيح(ملف * 72 + 64);
            ذاكرة_نظام_الملفات.허가들[ملف] = جدول_عدد_صحيح(ملف * 72 + 68) & 511;
            for (int قسم_قيمة_366e0bfa = 0; قسم_قيمة_366e0bfa < 32; قسم_قيمة_366e0bfa++) {
                if (جهاز_تخزين_صديق.قراءة(بدء_قسم + 3 + ملف * 32 + قسم_قيمة_366e0bfa) < 0) return -5;
                int عنوان = جهاز_قيمة.ملف_ذاكرة() + ملف * 16384 + قسم_قيمة_366e0bfa * 512;
                for (int فتحة_إدخال = 0; فتحة_إدخال < 512; فتحة_إدخال++) جهاز_قيمة.كتابة_ذاكرة(عنوان + فتحة_إدخال, جهاز_تخزين_صديق.قسم_بيانات[فتحة_إدخال]);
            }
        }
        return 0;
    }
    static void إعداد() {
        if (جهاز_تخزين_صديق.قراءة(0) < 0 || جهاز_تخزين_صديق.يوزّع_عدد_صحيح(0) != 0x54534b4a
            || جهاز_تخزين_صديق.يوزّع_عدد_صحيح(4) != 0x3145524f || جهاز_تخزين_صديق.يوزّع_عدد_صحيح(8) != 2048
            || جهاز_تخزين_صديق.يوزّع_عدد_صحيح(12) != 0x3153464a) {
            نص_الوحدة_الطرفية.كتابة("STORE RAM only (no JKSTORE1 disk)\n"); return;
        }
        جهاز_تخزين_صديق.أنظمة_المعلومات_نشِط = true;
        int 첫째 = 보존본검사(0), 둘째 = 보존본검사(1);
        if (첫째 < 0 && 둘째 < 0) { نص_الوحدة_الطرفية.كتابة("STORE ready; no valid snapshot\n"); return; }
        현재보존본 = 첫째 >= 둘째 ? 0 : 1; جيل_رقم = 첫째 >= 둘째 ? 첫째 : 둘째;
        if (تحميل(현재보존본) < 0) {
            نص_الوحدة_الطرفية.كتابة("STORE read failed; halted to preserve files\n"); جهاز_قيمة.정지();
        }
        نص_الوحدة_الطرفية.كتابة("STORE restored generation "); نص_الوحدة_الطرفية.كتابة_رقم(جيل_رقم); نص_الوحدة_الطرفية.문자(10);
    }
    static int تزامن() {
        if (!جهاز_تخزين_صديق.أنظمة_المعلومات_نشِط) return -19;
        if (جيل_رقم == 2147483647) return -75;
        int التالي_عنصر = 현재보존본 == 0 ? 1 : 0, بدء_قسم = 1 + التالي_عنصر * 259;
        // 새 본문보다 먼저 이전 commit을 무효화하고 جهاز_قيمة 캐시를 비운다.
        مسح_بيانات();
        if (جهاز_تخزين_صديق.كتابة(بدء_قسم) < 0 || جهاز_تخزين_صديق.محاذاة_الناتج() < 0) return -5;
        for (int فتحة_إدخال = 0; فتحة_إدخال < 1024; فتحة_إدخال++) ملف_جدول[فتحة_إدخال] = 0;
        for (int ملف = 0; ملف < 8; ملف++) if (ذاكرة_نظام_الملفات.이름들[ملف * 64] != 0) {
            for (int فتحة_إدخال = 0; فتحة_إدخال < 64; فتحة_إدخال++) ملف_جدول[ملف * 72 + فتحة_إدخال] = ذاكرة_نظام_الملفات.이름들[ملف * 64 + فتحة_إدخال];
            كتابة_جدول_عدد_صحيح(ملف * 72 + 64, ذاكرة_نظام_الملفات.يغير_الحجم_قائمة[ملف]);
            كتابة_جدول_عدد_صحيح(ملف * 72 + 68, ذاكرة_نظام_الملفات.허가들[ملف]);
        }
        int تجزئة_ملف = 0x811c9dc5;
        for (int قسم_قيمة_366e0bfa = 0; قسم_قيمة_366e0bfa < 258; قسم_قيمة_366e0bfa++) {
            for (int فتحة_إدخال = 0; فتحة_إدخال < 512; فتحة_إدخال++) {
                int قيمة = 0;
                if (قسم_قيمة_366e0bfa < 2) قيمة = ملف_جدول[قسم_قيمة_366e0bfa * 512 + فتحة_إدخال];
                else {
                    int ملف = (قسم_قيمة_366e0bfa - 2) / 32, موضع = (قسم_قيمة_366e0bfa - 2) % 32 * 512 + فتحة_إدخال;
                    if (ملف_جدول[ملف * 72] != 0 && موضع < ذاكرة_نظام_الملفات.يغير_الحجم_قائمة[ملف])
                        قيمة = جهاز_قيمة.يقرأ_ذاكرة(جهاز_قيمة.ملف_ذاكرة() + ملف * 16384 + موضع);
                }
                جهاز_تخزين_صديق.قسم_بيانات[فتحة_إدخال] = قيمة; تجزئة_ملف = 바이트해시(تجزئة_ملف, قيمة);
            }
            if (جهاز_تخزين_صديق.كتابة(بدء_قسم + 1 + قسم_قيمة_366e0bfa) < 0) return -5;
        }
        if (جهاز_تخزين_صديق.محاذاة_الناتج() < 0) return -5;
        مسح_بيانات(); جهاز_تخزين_صديق.كتابة_عدد_صحيح_قيمة(0, 0x4a4b534e);
        جهاز_تخزين_صديق.كتابة_عدد_صحيح_قيمة(4, جيل_رقم + 1); جهاز_تخزين_صديق.كتابة_عدد_صحيح_قيمة(8, تجزئة_ملف);
        جهاز_تخزين_صديق.كتابة_عدد_صحيح_قيمة(12, (جيل_رقم + 1) ^ تجزئة_ملف ^ 0x4a4b534e);
        if (جهاز_تخزين_صديق.كتابة(بدء_قسم) < 0 || جهاز_تخزين_صديق.محاذاة_الناتج() < 0) return -5;
        현재보존본 = التالي_عنصر; جيل_رقم++;
        return 0;
    }
