"""निज 커널의 संचिका·통신·화면 호출과 हिंदी अपवाद. 표준 이름은 이 연결부에서만 쓴다."""
import jkoros as ऑपरेटिंग_सिस्टम
import sys as कॉमन_लैंग्वेज_रनटाइम

def निर्गम(*मान, विभाजक=" ", 끝="\n", **기존인수):
    # 기존 print의 sep/end 인수도 연결부에서 호환한다.
    if "sep" not in 기존인수: 기존인수["sep"] = विभाजक
    if "end" not in 기존인수: 기존인수["end"] = 끝
    print(*मान, **기존인수)

पूर्णांक = int
명령인수 = कॉमन_लैंग्वेज_रनटाइम.argv
다시시도오류 = 11

class सिस्टम_त्रुटि(OSError):
    def __init__(자신, इंडेक्स, 설명="ऑपरेटिंग_सिस्टम 작업에 실패했습니다."):
        super().__init__(इंडेक्स, 설명)
        자신.इंडेक्स = इंडेक्स
        자신.설명 = 설명

def 운영호출(फ़ंक्_शन_मान, *तर्क):
    try:
        return फ़ंक्_शन_मान(*तर्क)
    except OSError as त्रुटि:
        इंडेक्स = त्रुटि.args[0] if त्रुटि.args else 0
        raise सिस्टम_त्रुटि(इंडेक्स)

def 글부호화(पाठ):
    return पाठ.encode("utf-8")

def 글해독(आँकड़े):
    return आँकड़े.decode("utf-8")

def पढें_फ़ाइल(नाम):
    return 운영호출(ऑपरेटिंग_सिस्टम.read, नाम)

