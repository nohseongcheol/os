func (셀프 *T콘솔) M출력(매개값 ...interface{}) {
	var 엑스 uint16 = 1000
	var 와이 uint16 = 1000
	var 값 interface{}

	for 아이, 피 := range 매개값 {
		switch 아이 {
		case 0:
			피에이알에이엠, _ := 피.(interface{})
			값 = 피에이알에이엠
		case 1:
			switch 피.(type) {
			case uint16:
				피에이알에이엠, _ := 피.(uint16)
				엑스 = 피에이알에이엠
			case int:
				피에이알에이엠, _ := 피.(int)
				엑스 = uint16(피에이알에이엠)
			}
		case 2:
			switch 피.(type) {
			case uint16:
				피에이알에이엠, _ := 피.(uint16)
				와이 = 피에이알에이엠
			case int:
				피에이알에이엠, _ := 피.(int)
				와이 = uint16(피에이알에이엠)
			}
		}
	}

	셀프.M출력XY(값, 엑스, 와이)

}
func (셀프 *T콘솔) M출력XY(임시 interface{}, 엑스 uint16, 와이 uint16) {

	switch 임시.(type) {
	case string:
		자료, _ := 임시.(string)
		셀프.M출력BytesXY(([]byte)(자료), 엑스, 와이)
	case uint8:
		자료, _ := 임시.(uint8)
		셀프.MHex출력XY(자료, 엑스, 와이)
	case uint16:
		자료, _ := 임시.(uint16)
		셀프.MUint16출력XY(자료, 엑스, 와이)
	case uint32:
		자료, _ := 임시.(uint32)
		셀프.MUint32출력XY(자료, 엑스, 와이)
	case uint64:
		자료, _ := 임시.(uint64)
		셀프.MUint64출력XY(자료, 엑스, 와이)
	default:
		자료, _ := 임시.([]byte)
		셀프.M출력BytesXY(자료, 엑스, 와이)
	}

}
func (셀프 *T콘솔) M출력BytesXY(비유에프 []byte, 엑스 uint16, 와이 uint16) {

	if 엑스 <= 999 {
		셀프.엑스포스 = 엑스
	}
	if 와이 <= 999 {
		셀프.와이포스 = 와이
	}

	에이티티알 := uint16(0x0F)
	엘아이엠아이티 := len(비유에프)
	if 엘아이엠아이티 > 4096 {
		엘아이엠아이티 = 4096
	}
	for 아이 := 0; 아이 < 엘아이엠아이티; 아이++ {
		시리얼엘오지바이트(비유에프[아이])
		switch 비유에프[아이] {
		case '\n':
			셀프.와이포스++
			셀프.엑스포스 = 0
		default:
			*(*uint16)(Pointer(에프비피에이치와이에스에이디디알 + uintptr((80*셀프.와이포스+셀프.엑스포스)*2))) = 에이티티알<<8 | uint16(비유에프[아이])
			셀프.엑스포스++
		}

		if 셀프.엑스포스 >= 80 {
			셀프.와이포스++
			셀프.엑스포스 = 0
		}

		if 셀프.와이포스 >= 25 {
			for 셀프.와이포스 = 0; 셀프.와이포스 < 25; 셀프.와이포스++ {
				for 셀프.엑스포스 = 0; 셀프.엑스포스 < 80; 셀프.엑스포스++ {
					*(*uint16)(Pointer(에프비피에이치와이에스에이디디알 + uintptr((80*셀프.와이포스+셀프.엑스포스)*2))) = 에이티티알<<8 | ' '
				}
			}
			셀프.엑스포스 = 0
			셀프.와이포스 = 0
		}

	}

}
