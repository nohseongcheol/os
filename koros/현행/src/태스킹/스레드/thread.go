package T스레드_티에이치알이에이디

import . "unsafe"
import . "reflect"
import . "gdt"
import . "콘솔"
import . "멀티태스킹"
import 엠이엠 "메모리매니저"
import . "버추얼메모리"

const (
	B비엘오시케이이디	= 1
	R알이에이디와이	= 2
	S에스티오피피이디	= 3
	S에스티에이알티이디	= 4
)

const T스레드스택사이즈 = 32 * 1024

type T스레드 struct {
	C시피유에스티에이티이			*T티시피유에스티에이티이
	S스택				uint32
	U유저스택_유에스이알에스티에이시케이		uint32
	U유저스택사이즈_유에스이알에스티에이시케이에스아이지이	uint32
	P피아이디				uint32
	P페어런트피아이디			uint32

	P페이지디아이알엔트리	uint32

	T스레드에스티에이티이		uint8
	B비엘오시케이이디에스티에이티이	uint8

	티아이엠이디이엘티에이	uint32

	T티엘에스에스이지엠이엔티에스	[G지디티이엔티알아이이에스]T조각설명자
	F에프피유오에프에프에스이티	uintptr
	F에프피유버퍼		[512 + 16]byte
	I아이에스커널		bool
}

func (셀프 *T스레드) N엔이더블유() {
}

type T스레드에이치이엘피이알 struct {
	엠이엠 *엠이엠.T메모리매니저
}

var 콘솔_이름 = T콘솔{}

func (셀프 *T스레드에이치이엘피이알) I이닛(엠이엠 *엠이엠.T메모리매니저) {
	셀프.엠이엠 = 엠이엠
	콘솔_이름.M출력XY(([]byte)("thread:"), 1, 14)
}
func (셀프 *T스레드에이치이엘피이알) C시알이에이티이에프알오엠펑션(이엔티알와이피오아이엔티 func(), P페이지디아이알엔트리 uint32, 아이에스커널 bool) T스레드 {
	알이에스유엘티 := T스레드{}

	알이에스유엘티.S스택 = uint32(uintptr(셀프.엠이엠.M엠에이엘엘오시(T스레드스택사이즈)))
	if 알이에스유엘티.S스택 == 0 {
		return 알이에스유엘티
	}
	콘솔_이름.M출력(([]byte)("[mem:"))
	콘솔_이름.MUint32출력(알이에스유엘티.S스택)

	알이에스유엘티.C시피유에스티에이티이 = (*T티시피유에스티에이티이)(Pointer(uintptr(알이에스유엘티.S스택) + T스레드스택사이즈 - Sizeof(T티시피유에스티에이티이{})))
	알이에스유엘티.C시피유에스티에이티이.E이에스피 = 알이에스유엘티.S스택 + T스레드스택사이즈
	알이에스유엘티.C시피유에스티에이티이.E이비피 = 알이에스유엘티.C시피유에스티에이티이.E이에스피
	알이에스유엘티.C시피유에스티에이티이.E이아이피 = uint32(ValueOf(이엔티알와이피오아이엔티).Pointer())
	알이에스유엘티.U유저스택_유에스이알에스티에이시케이 = U유저스택
	알이에스유엘티.U유저스택사이즈_유에스이알에스티에이시케이에스아이지이 = U유저스택사이즈
	알이에스유엘티.P피아이디 = 0
	알이에스유엘티.P페어런트피아이디 = 0
	알이에스유엘티.P페이지디아이알엔트리 = P페이지디아이알엔트리
	콘솔_이름.M출력((([]byte)("cpu")))

	콘솔_이름.MUint32출력(uint32(uintptr(Pointer(알이에스유엘티.C시피유에스티에이티이))))

	콘솔_이름.M출력((([]byte)(":")))
	콘솔_이름.MUint32출력(알이에스유엘티.C시피유에스티에이티이.E이아이피)

	콘솔_이름.M출력("]")
	if 아이에스커널 == true {
		알이에스유엘티.C시피유에스티에이티이.C시에스 = S에스이지커널시오디이
		알이에스유엘티.C시피유에스티에이티이.D디에스 = S에스이지커널데이터
		알이에스유엘티.C시피유에스티에이티이.E이에스 = S에스이지커널데이터
		알이에스유엘티.C시피유에스티에이티이.F에프에스 = S에스이지커널데이터
		알이에스유엘티.C시피유에스티에이티이.G지에스 = S에스이지커널지에스
		알이에스유엘티.C시피유에스티에이티이.S에스에스 = S에스이지커널데이터
		알이에스유엘티.T스레드에스티에이티이 = R알이에이디와이
		알이에스유엘티.C시피유에스티에이티이.E이에프엘에이지에스 = 0x202
	} else {
		알이에스유엘티.C시피유에스티에이티이.C시에스 = S에스이지유저시오디이
		알이에스유엘티.C시피유에스티에이티이.D디에스 = S에스이지유저데이터
		알이에스유엘티.C시피유에스티에이티이.E이에스 = S에스이지유저데이터
		알이에스유엘티.C시피유에스티에이티이.F에프에스 = S에스이지유저데이터
		알이에스유엘티.C시피유에스티에이티이.G지에스 = S에스이지유저지에스
		알이에스유엘티.C시피유에스티에이티이.S에스에스 = S에스이지유저데이터
		알이에스유엘티.T스레드에스티에이티이 = S에스티에이알티이디
		알이에스유엘티.C시피유에스티에이티이.E이에프엘에이지에스 = 0x222
	}
	알이에스유엘티.I아이에스커널 = 아이에스커널
	알이에스유엘티.F에프피유오에프에프에스이티 = 0xffffffff

	return 알이에스유엘티
}

func (셀프 *T스레드에이치이엘피이알) C시알이에이티이피티알에프알오엠펑션(이엔티알와이피오아이엔티 func(), P페이지디아이알엔트리 uint32, 아이에스커널 bool) *T스레드 {
	알이에스유엘티 := (*T스레드)(셀프.엠이엠.M엠에이엘엘오시(uint32(Sizeof(T스레드{}))))
	if 알이에스유엘티 == nil {
		return nil
	}
	*알이에스유엘티 = 셀프.C시알이에이티이에프알오엠펑션(이엔티알와이피오아이엔티, P페이지디아이알엔트리, 아이에스커널)
	if 알이에스유엘티.C시피유에스티에이티이 == nil {
		셀프.엠이엠.F프리(Pointer(알이에스유엘티))
		return nil
	}
	return 알이에스유엘티
}
