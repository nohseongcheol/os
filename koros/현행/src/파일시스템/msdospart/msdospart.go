type T피에이알티아이티아이오엔테이블엔트리 struct {
	비오오티에이비엘이	uint8

	에스티에이알티에이치이에이디		uint8
	에스티에이알티에스이시티오알		uint8
	에스티에이알티시와이엘아이엔디이알	uint16

	P피에이알티아이티아이오엔아이디	uint8

	이엔디에이치이에이디	uint8
	이엔디에스이시티오알	uint8
	이엔디시와이엘아이엔디이알	uint16

	S에스티에이알티엘비에이	uint32
	렝스		uint32
}

func (셀프 *T피에이알티아이티아이오엔테이블엔트리) I이닛(데이터 [16]byte) {
	셀프.비오오티에이비엘이 = 데이터[0]

	셀프.에스티에이알티에이치이에이디 = 데이터[1]
	셀프.에스티에이알티에스이시티오알 = (데이터[2] >> 2)
	셀프.에스티에이알티시와이엘아이엔디이알 = U유아이엔티16알(uint16(데이터[2]&0x03) | uint16(데이터[3]))

	셀프.P피에이알티아이티아이오엔아이디 = 데이터[4]

	셀프.이엔디에이치이에이디 = 데이터[5]
	셀프.이엔디에스이시티오알 = (데이터[6] >> 2)
	셀프.이엔디시와이엘아이엔디이알 = U유아이엔티16알(uint16(데이터[6]&0x03) | uint16(데이터[7]))

	var 비유에프1 [4]byte
	copy(비유에프1[:4], 데이터[8:12])
	셀프.S에스티에이알티엘비에이 = U유아이엔티32알(A어레이티오유아이엔티32(비유에프1))

	var 비유에프2 [4]byte
	copy(비유에프2[:4], 데이터[12:16])
	셀프.렝스 = U유아이엔티32알(A어레이티오유아이엔티32(비유에프2))
}

type T엠에이에스티이알비오오티알이시오알디 struct {
	비오오티엘오에이디이알	[440]byte
	에스아이지엔에이티유알이	uint32
	유엔유에스이디		uint16

	P피알아이엠에이알와이피에이알티아이티아이오엔	[4]T피에이알티아이티아이오엔테이블엔트리

	엠에이지아이시엔유엠비이알	uint16
}
type T티엠에스디오에스피에이알티아이티아이오엔테이블 struct {
	M엠비알 T엠에이에스티이알비오오티알이시오알디
}

func (셀프 *T티엠에스디오에스피에이알티아이티아이오엔테이블) R리드피에이알티아이티아이오엔에스(에이치디 *T에이디브이에이엔시이디티이시에이치엔오엘오지와이에이티티에이시에이치엠이엔티) {

	콘솔_이름 := T콘솔{}
	콘솔_이름.M출력(([]byte)("Reading MBR"))

	var 피에이알티아이티아이오엔비와이티이에스 [512]byte
	var 버퍼 = 피에이알티아이티아이오엔비와이티이에스[:]
	에이치디.R리드28(0, &버퍼, 512)

	셀프.M엠비알 = T엠에이에스티이알비오오티알이시오알디{}
	var 아이 int = 0
	for ; 아이 < 440; 아이++ {
		셀프.M엠비알.비오오티엘오에이디이알[아이] = 피에이알티아이티아이오엔비와이티이에스[아이]
	}

	var 비유에프1 [4]byte
	copy(비유에프1[:4], 피에이알티아이티아이오엔비와이티이에스[아이:아이+4])
	셀프.M엠비알.에스아이지엔에이티유알이 = U유아이엔티32알(A어레이티오유아이엔티32(비유에프1))
	아이 += 4

	var 비유에프2 [2]byte
	copy(비유에프2[:2], 피에이알티아이티아이오엔비와이티이에스[아이:아이+2])
	셀프.M엠비알.유엔유에스이디 = U유아이엔티16알(A어레이티오유아이엔티16(비유에프2))
	아이 += 2

	var 비유에프3 [16]byte
	copy(비유에프3[:16], 피에이알티아이티아이오엔비와이티이에스[아이:아이+16])
	셀프.M엠비알.P피알아이엠에이알와이피에이알티아이티아이오엔[0].I이닛(비유에프3)
	아이 += 16

	copy(비유에프3[:16], 피에이알티아이티아이오엔비와이티이에스[아이:아이+16])
	셀프.M엠비알.P피알아이엠에이알와이피에이알티아이티아이오엔[1].I이닛(비유에프3)
	아이 += 16

	copy(비유에프3[:16], 피에이알티아이티아이오엔비와이티이에스[아이:아이+16])
	셀프.M엠비알.P피알아이엠에이알와이피에이알티아이티아이오엔[2].I이닛(비유에프3)
	아이 += 16

	copy(비유에프3[:16], 피에이알티아이티아이오엔비와이티이에스[아이:아이+16])
	셀프.M엠비알.P피알아이엠에이알와이피에이알티아이티아이오엔[3].I이닛(비유에프3)
	아이 += 16

	var 비유에프6 [2]byte
	copy(비유에프6[:2], 피에이알티아이티아이오엔비와이티이에스[아이:아이+2])
	셀프.M엠비알.엠에이지아이시엔유엠비이알 = U유아이엔티16알(A어레이티오유아이엔티16(비유에프6))

	if 셀프.M엠비알.엠에이지아이시엔유엠비이알 != 0xAA55 {
		콘솔_이름.M출력(([]byte)("illegal MBR"))
		return
	}

	for 아이 := 0; 아이 < 4; 아이++ {

		if 셀프.M엠비알.P피알아이엠에이알와이피에이알티아이티아이오엔[아이].P피에이알티아이티아이오엔아이디 == 0x00 {
			continue
		}

	}
}
